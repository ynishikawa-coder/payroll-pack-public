# -*- coding: utf-8 -*-
"""配る・見回り（docs/設計/寄せる道具.md §2・§4）。

配る＝新しい直しを事務所の全社に当てる見通し（中は 当てる.見通す を全社で回すだけ）。
見回り＝期限の来た物・旧_／99_／02_ の物・前の版のままの会社・消してよい直しを並べ、
事務所ごとに 1 枚の「消す問い」を作る。道具は何も消さない（消すのはオーナーの OK の後に殻）。
"""
import datetime as dt
import re

import 当てる


def 配る(会社たち: list[dict], 型: dict, 直したち: list[dict], 今日: dt.date | None = None) -> dict:
    今の版 = 当てる.型を読む(型)["版"]
    行たち, 結果たち = [], []
    for c in 会社たち:
        r = 当てる.見通す(c, 型, 直したち, 今日)
        r["消す問い"] += 置き場を見る(c, 今日 or dt.date.today(), "")
        r["人が見る物"] = 当てる.人が見る物(r)
        結果たち.append(r)
        行たち.append({
            "会社": r["会社"], "今の版": r["前の版"], "当てる直し": r["当てた直し"],
            "変わるタブ": len(r["変わるタブ"]),
            "変わる列の数": sum(1 for s in r["書く手順"] if s["する"] == "値を書く"),
            "寄せられない物": len(r["寄せられない物"]), "足りない値": len(r["足りない値"]),
            "当てるか": "当てる" if not r["寄せられない物"] and r["当てた直し"] else ("済" if not r["当てた直し"] else "残す（答えを集める）"),
        })
    # 前の版のまま残る会社を頭に（黙って残さない）
    行たち.sort(key=lambda x: (x["当てるか"] != "残す（答えを集める）", x["今の版"]))
    版たち = [x["今の版"] if x["当てるか"] != "当てる" else 今の版 for x in 行たち]
    return {"今の版": 今の版, "見通し": 行たち, "結果": 結果たち,
            "消してよい直し": 消してよい直し(版たち, 直したち),
            "人が見る物": 見通しの一枚(今の版, 行たち, 消してよい直し(版たち, 直したち))}


def 消してよい直し(版たち: list[int], 直したち: list[dict]) -> list[int]:
    """全社の型の版が N 以上なら直し N は消してよい（両方の事務所でそろってから消す＝§2.3）。"""
    if not 版たち:
        return []
    低い = min(版たち)
    return [d["版"] for d in 直したち if d["版"] <= 低い]


def 見通しの一枚(今の版, 行たち, 消せる) -> str:
    L = [f"# 配りの見通し（今の版 {今の版}）", "", "| 会社 | 今の版 | 当てる直し | 変わるタブ | 変わる列の数 | 寄せられない物 | 足りない値 | 当てるか |", "|---|---|---|---|---|---|---|---|"]
    L += [f"| {x['会社']} | {x['今の版']} | {','.join(map(str, x['当てる直し'])) or '—'} | {x['変わるタブ']} | {x['変わる列の数']} | {x['寄せられない物']} | {x['足りない値']} | {x['当てるか']} |" for x in 行たち]
    L += ["", f"消してよい直し（この事務所の分）: {', '.join(map(str, 消せる)) or 'なし'}（もう片方の事務所でもそろってから消す）"]
    return "\n".join(L)


# ---------------------------------------------------------------- 見回り

期限の名 = re.compile(r"(?:^|/)(?:消す_)?(\d{4}-?\d{2}-?\d{2})_")


def 名の期限(名: str):
    m = 期限の名.search(名)
    if not m:
        return None
    s = m.group(1).replace("-", "")
    try:
        return dt.date(int(s[:4]), int(s[4:6]), int(s[6:8]))
    except ValueError:
        return None


def 置き場を見る(会社: dict, 今日: dt.date, 窓: str) -> list[dict]:
    """置き場の一覧（名だけ）から、消す問いへ並べる物を拾う。"""
    out = []
    for p in 会社.get("置き場", []):
        名 = p.rstrip("/").split("/")[-1]
        親 = p.rstrip("/").rsplit("/", 1)[0] if "/" in p.rstrip("/") else ""
        期限 = 名の期限(p)
        行 = None
        頭 = p.split("/")[0]
        直の子 = p.rstrip("/").count("/") == 1
        if 頭.startswith("99_") and 直の子:
            if 期限 is None:
                行 = ("期限が無い", "", "期限を付ける（置いた日の翌月末）か、原本なら原本の置き場へ移す（中を見た窓が決める）")
            elif 期限 <= 今日:
                行 = ("期限が来た", 期限.isoformat(), "消す")
        elif 頭 == "02_初回の書類" and 直の子:
            ok = 会社.get("初回の確認の OK の日")
            if ok and dt.date.fromisoformat(ok) <= 今日:
                行 = ("初回の確認の OK の後", ok, "原本は最初の月の 01_原本/ へ 書類_ を付けて移す・残りは 90_履歴/ へ消す日を付けて移す")
            else:
                行 = ("立ち上げの置き場", ok or "", "初回の確認の OK の日を管理表に書く（その日が期限）")
        elif p.startswith("90_履歴/") and 名.startswith("消す_") and 期限 and 期限 <= 今日:
            行 = ("消す日が過ぎた", 期限.isoformat(), "消す")
        elif 名.startswith("旧_") or "コピー" in 名 or "（1）" in 名:
            行 = ("旧_・写しの名", "", "その会社の寄せで今のタブ・file と照らしてから消す")
        elif (頭.startswith("80_答え") and p.rstrip("/") == 頭) or 名.startswith("照合_"):
            行 = ("答え（開発の間だけ）", "", "事務所の根から外す（答えは開発の手元・確かめと仮.md）")
        if 行:
            out.append({"会社": 会社["会社"], "物": 名, "置き場": 親 or "（組の根）", "中を見た窓": 窓,
                        "中身はどこに在るか": 行[0], "期限": 行[1], "推奨": 行[2],
                        "消す手順": [{"する": "file を消す", "名": p}] if 行[2] == "消す" else []})
    return out


def 見回り(会社たち: list[dict], 直したち: list[dict], 今の版: int, 今日: dt.date | None = None,
         窓: str = "", 寄せの消す問い: list[dict] | None = None, 前の答え: dict | None = None) -> dict:
    """事務所ごとに 1 枚の消す問いを作る。答えの無かった行は次の回にもう一度並ぶ（前の答えに無い行は全部並べる）。"""
    今日 = 今日 or dt.date.today()
    前の答え = 前の答え or {}
    行たち = []
    for c in 会社たち:
        行たち += 置き場を見る(c, 今日, 窓)
        if c.get("シート"):
            記 = 当てる.記録()
            当てる.旧のタブを照らす(当てる.物(c), 記)
            for x in 記.消す問い:
                行たち.append({"会社": c["会社"], "中を見た窓": 窓, "期限": "", **x})
            for x in 記.寄せられない:
                行たち.append({"会社": c["会社"], "物": x["所"], "置き場": x["所"], "中を見た窓": 窓,
                            "中身はどこに在るか": "どこにも無い値が在る", "期限": "", "推奨": "残す（寄せで行き先を答える）", "消す手順": []})
    for x in 寄せの消す問い or []:
        行たち.append({"中を見た窓": 窓, "期限": "", **x})
    for x in 行たち:
        x["鍵"] = f"{x['会社']}/{x['置き場']}/{x['物']}"
    # 「残す」と答えた行は新しい期限まで並べない
    残す = {k: v for k, v in 前の答え.items() if str(v).startswith("残す:")}
    行たち = [x for x in 行たち if not (x["鍵"] in 残す and dt.date.fromisoformat(残す[x["鍵"]][3:].strip()) > 今日)]
    前の版のまま = [{"会社": c["会社"], "型の版": int(c.get("型の版", 0) or 0)} for c in 会社たち if int(c.get("型の版", 0) or 0) < 今の版]
    消せる = 消してよい直し([int(c.get("型の版", 0) or 0) for c in 会社たち], 直したち)
    return {"消す問い": 行たち, "前の版のままの会社": 前の版のまま, "消してよい直し": 消せる,
            "人が見る物": 消す問いの一枚(行たち, 前の版のまま, 消せる)}


def 消す問いの一枚(行たち, 前の版のまま, 消せる) -> str:
    """オーナーへ 1 回で聞く 1 枚（置き場は事務所の Drive の確認ページの置き場・会社の名が入るので repo に出さない）。"""
    L = ["# 消す問い", "", "答え方: 「推奨どおり全部」か、行ごとに 消す／原本へ移す／残す:<新しい期限 YYYY-MM-DD>。答えの無い行は次の回にもう一度並ぶ。", "",
         "| 会社 | 物 | 置き場 | 中を見た窓 | 中身はどこに在るか | 期限 | 推奨 |", "|---|---|---|---|---|---|---|"]
    L += [f"| {x['会社']} | {x['物']} | {x['置き場']} | {x['中を見た窓']} | {x['中身はどこに在るか']} | {x['期限']} | {x['推奨']} |" for x in 行たち]
    if 前の版のまま:
        L += ["", "前の版のままの会社: " + "・".join(f"{x['会社']}（版 {x['型の版']}）" for x in 前の版のまま)]
    L += ["", f"消してよい直し（この事務所の分）: {', '.join(map(str, 消せる)) or 'なし'}"]
    return "\n".join(L)
