def 名の期限(名: str):
    m = 期限の名.search(名)
    if not m:
        return None
    s = m.group(1).replace("-", "")
    try:
        return dt.date(int(s[:4]), int(s[4:6]), int(s[6:8]))
    except ValueError:
        return None


def 寄せの写しか(名: str, 会社: dict) -> bool:
    """9_履歴/消す_<日>_<元の名> の <元の名> が、その会社の今の file（シート・md・置き場の file）の名を / → _ にした物か
    ＝寄せ・配りの写し（当てる.手順を作る の file を写す・md を 9_履歴 へ移す の名）。"""
    r = 確認の口.消す名を読む(名)
