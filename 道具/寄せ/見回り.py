    名の会社 = 会社.get("会社", "")
    組 = 会社.get("組") or 名の会社   # 組で束ねた会社は殻が 組 を渡す（1 社の会社は組＝会社）

    def 挙げる(項目: int, 所: str, 訳: str):
        out.append({"会社": 名の会社, "項目": 項目, "何": 置き場の検査の項目[項目], "所": 所, "訳": 訳, "赤": 項目 != 4})

    for p in 会社.get("置き場", []):
        部分 = [x for x in p.rstrip("/").split("/") if x]
        if not 部分:
            continue
        名 = 部分[-1]
        頭 = 部分[0]
        if 頭 == 事務所の名:
            if len(部分) >= 2 and 部分[1] not in 事務所の物 and not 確認事項の名か(部分[1], "事務所", len(部分) == 2 and not p.endswith("/")):
                挙げる(1, "/".join(部分[:2]), f"{事務所の名} に木（{'・'.join(事務所の物)}・確認事項_事務所_<支給月>_v<版>.html）に無い名「{部分[1]}」")
        elif 頭 not in 会社の根の名 and not 台帳の名.fullmatch(頭):
            挙げる(1, 頭, f"会社の根に木（{'・'.join(会社の根の名)}・{_台帳}）に無い名「{頭}」")
        elif 頭 == 確認事項の名 and len(部分) >= 2 and not 確認事項の名か(部分[1], 組, len(部分) == 2 and not p.endswith("/")):
            挙げる(1, "/".join(部分[:2]), f"{確認事項の名} に組「{組}」の確認事項の名（確認事項_{組}_<YYYY.MM支給（M月分）>_v<版>.html）でない物「{部分[1]}」")
