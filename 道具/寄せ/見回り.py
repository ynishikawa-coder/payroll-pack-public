推奨どおり = "推奨どおり"
答えの語 = ("消す", "原本へ移す:", "残す:")


def 答えを当てる(行たち: list[dict], 答え: dict, 今日: dt.date) -> dict:
    """オーナーの答え（{"全部": "推奨どおり"} か {鍵: 消す｜原本へ移す:<置き場>｜残す:<YYYY-MM-DD>}）を、今の 消す問い
    （同じ回に 見回り が今の Drive から作った行）に当て、殻が当てる手順を返す。全部か無し: 1 つでも誤りが在れば手順は空。

    拒む: 今の消す問いに無い鍵（前の回の答え＝読み直して聞き直す）・消す手順の無い行（作り直す・中身がどこにも無い 等）への 消す・
    file でない行への 原本へ移す・期限の無いか今日より後でない 残す・知らない答え。答えの無い行は 答えの無い行 に返す
    （次の消す問いにもう一度並ぶ＝黙って消さず黙って残さない）。"""
    行 = {x["鍵"]: x for x in 行たち}
    誤り, 手順, 残す, 済 = [], {}, {}, set()
    全部 = 答え.get("全部")
    if 全部 is not None and 全部 != 推奨どおり:
        誤り.append(f"全部: 答えは「{推奨どおり}」だけ（受けた物: {全部!r}）")
    for k, v in 答え.items():
        if k == "全部":
            continue
        v = str(v).strip()
        x = 行.get(k)
        if x is None:
            誤り.append(f"{k}: 今の消す問いに無い行＝読み直して聞き直す（前の回の答えを当てない）")
            continue
        if v == "消す":
            if not x.get("消す手順"):
                誤り.append(f"{k}: 消す手順の無い行（推奨 {x.get('推奨')}）は 消す と答えられない")
                continue
            手順.setdefault(x["会社"], []).extend(x["消す手順"])
        elif v.startswith("原本へ移す:"):
            先 = v[len("原本へ移す:"):].strip().strip("/")
            if not 先 or [s.get("する") for s in x.get("消す手順") or []] != ["file を消す"]:
                誤り.append(f"{k}: 原本へ移す は file の行だけ・先の置き場を書く（原本へ移す:<置き場>）")
                continue
            元 = x["消す手順"][0]["名"]
            手順.setdefault(x["会社"], []).append({"する": "file を移す", "前": 元, "後": f"{先}/{元.rstrip('/').split('/')[-1]}"})
        elif v.startswith("残す:"):
            try:
                日 = dt.date.fromisoformat(v[3:].strip())
            except ValueError:
                日 = None
            if 日 is None or 日 <= 今日:
                誤り.append(f"{k}: 残す は今日より後の新しい期限を持つ（残す:YYYY-MM-DD・受けた物 {v!r}）")
                continue
            残す[k] = f"残す:{日.isoformat()}"
        else:
            誤り.append(f"{k}: 知らない答え {v!r}（消す・原本へ移す:<置き場>・残す:<YYYY-MM-DD> のどれか）")
            continue
        済.add(k)
    if 全部 == 推奨どおり:
        for k, x in 行.items():
            if k in 済:
                continue
            if x.get("推奨") == "消す" and x.get("消す手順"):
                手順.setdefault(x["会社"], []).extend(x["消す手順"])
                済.add(k)
    if 誤り:
        return {"誤り": 誤り, "手順": {}, "残す": {}, "答えの無い行": sorted(行)}
    return {"誤り": [], "手順": 手順, "残す": 残す, "答えの無い行": sorted(k for k in 行 if k not in 済)}


def 置き場の検査の一枚(検査) -> str:
    L = ["# 置き場の検査（Drive の型 §2 の 6 つ。4 は知らせ）", "", "| 会社 | 項目 | 所 | 訳 |", "|---|---|---|---|"]
    L += [f"| {x['会社']} | {x['項目']} {x['何']} | {x['所']} | {x['訳']} |" for x in 検査]
    return "\n".join(L)


def 書き方を見る(会社: dict) -> list[dict]:
    """型の書き方（支給月 YYYY.MM支給・日付 YYYY-MM-DD・時刻 h:mm・月の置き場の名 YYYY.MM支給（M月分））からずれた値（赤で知らせる・直さない）。

    照らす書き方は台帳を書く口（月次/台帳の形.py の 書き方のずれ）と同じ 1 か所。直すのは人か寄せ（値を黙って書き換えない）。"""
    形 = 当てる.台帳の形()
    out = []
    for f, tabs in (会社.get("シート") or {}).items():
        if not (f.startswith(当てる.マスタの名) or f.startswith("台帳")):
            continue
        for t, rows in tabs.items():
            if not rows:
                continue
            h = [str(x) for x in rows[0]]
            for n, r in enumerate(rows[1:], 2):
                for x in 形.書き方のずれ(t, h, ["" if v is None else str(v) for v in r]):
                    out.append({"会社": 会社["会社"], "所": f"{f}/{t}/{n}行目", "ずれ": x})
    for p in 会社.get("置き場", []):
        部分 = p.rstrip("/").split("/")
        if len(部分) >= 2 and 部分[0] == 月ごとの名:
            if 支給月の字.置き場の字を読む(部分[1]) is None:
                out.append({"会社": 会社["会社"], "所": "/".join(部分[:2]), "ずれ": f"月の置き場の名「{部分[1]}」（YYYY.MM支給（M月分））"})
    return list({(x["所"], x["ずれ"]): x for x in out}.values())


def 書き方のずれの一枚(ずれ) -> str:
    L = ["# 赤: 書き方のずれ（型の列の意味の書き方に合わない値）", "", "| 会社 | 所 | ずれ |", "|---|---|---|"]
    L += [f"| {x['会社']} | {x['所']} | {x['ずれ']} |" for x in ずれ]
    return "\n".join(L)


def 消す問いの一枚(行たち, 前の版のまま, 消せる, 寄せ中=()) -> str:
    """オーナーへ 1 回で聞く 1 枚（置き場は事務所の Drive の確認ページの置き場・会社の名が入るので repo に出さない）。"""
