def 会社の印(管理表: list, 会社: str) -> dict:
    """管理表「会社」（今の値）からその会社の 寄せ中・理由・最後に配った日 を読む（管理表/管理表.py の読む口だけ）。
    行の無い会社・選べない値・日付でない値は 管理表の口.拒む で止める（黙って寄せ中でない・配った日が空と読まない）。"""
    印 = 管理表の口.寄せの印({"今の値": 管理表, "会社": 会社})
    return {**印, "配った日": 管理表の口.配った日({"今の値": 管理表, "会社": 会社})}


def 配る(会社たち: list[dict], 型: dict, 直したち: list[dict], 今日: dt.date | None = None, *, 管理表: list) -> dict:
    """§2.2 の 4（見通し・書かない）と §2.3（配り残しを頭に・消してよい直し）。当てるのは 1 社ずつ殻の 寄せる 口（§1.5 の 5〜7）。
    管理表＝管理表「会社」の今の値（必ず渡す）。寄せ中の会社は当てずに「寄せ中」と並べる（寄せる口で寄せ直す）。"""
    今の版 = 当てる.型を読む(型)["版"]
    今日 = 今日 or dt.date.today()
    行たち, 結果たち = [], []
    for c in 会社たち:
        印 = 会社の印(管理表, c["会社"])
        r = 当てる.見通す(c, 型, 直したち, 今日)
        r["消す問い"] += 置き場を見る(c, 今日, "", 印=印)
        r["人が見る物"] = 当てる.人が見る物(r)
        結果たち.append(r)
        当てるか = "当てる" if not r["寄せられない物"] and r["当てた直し"] else ("済" if not r["当てた直し"] else 残す)
        if 印["寄せ中"]:
            当てるか = f"寄せ中（{印['理由'] or '寄せの最中'}）＝寄せる口で寄せ直す"
        行たち.append({
            "会社": r["会社"], "今の版": r["前の版"], "当てる直し": r["当てた直し"],
            "変わるタブ": len(r["変わるタブ"]),
            "変わる列の数": sum(1 for s in r["書く手順"] if s["する"] == "値を書く"),
            "寄せられない物": len(r["寄せられない物"]), "足りない値": len(r["足りない値"]),
            "当てるか": 当てるか,
        })
    # 前の版のまま残る会社（答えを集める・寄せ中）を頭に（黙って残さない）
    行たち.sort(key=lambda x: (x["当てるか"] in ("当てる", "済"), x["今の版"]))
    版たち = [x["今の版"] if x["当てるか"] != "当てる" else 今の版 for x in 行たち]
    return {"今の版": 今の版, "見通し": 行たち, "結果": 結果たち,
            "消してよい直し": 消してよい直し(版たち, 直したち),
            "人が見る物": 見通しの一枚(今の版, 行たち, 消してよい直し(版たち, 直したち))}


def 消してよい直し(版たち: list[int], 直したち: list[dict]) -> list[int]:
    """全社の型の版が N 以上なら直し N は消してよい（両方の事務所でそろってから消す＝§2.3）。"""
    if not 版たち:
        return []
    低い = min(版たち)
    return [d["版"] for d in 直したち if d["版"] <= 低い]


def 見通しの一枚(今の版, 行たち, 消せる) -> str:
    L = [f"# 配りの見通し（今の版 {今の版}）", "", "| 会社 | 今の版 | 当てる直し | 変わるタブ | 変わる列の数 | 寄せられない物 | 足りない値 | 当てるか |", "|---|---|---|---|---|---|---|---|"]
    L += [f"| {x['会社']} | {x['今の版']} | {','.join(map(str, x['当てる直し'])) or '—'} | {x['変わるタブ']} | {x['変わる列の数']} | {x['寄せられない物']} | {x['足りない値']} | {x['当てるか']} |" for x in 行たち]
    L += ["", f"消してよい直し（この事務所の分）: {', '.join(map(str, 消せる)) or 'なし'}（もう片方の事務所でもそろってから消す）"]
    return "\n".join(L)


