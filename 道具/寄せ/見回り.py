"""配る・見回り（docs/設計/寄せる道具.md §2・§4）。

配る＝新しい直しを事務所の全社に当てる見通し（中は 当てる.見通す を全社で回すだけ）。
見回り＝期限の来た物・旧_／99_／02_ の物・前の版のままの会社・消してよい直しを並べ、
事務所ごとに 1 枚の「消す問い」を作る。道具は何も消さない（消すのはオーナーの OK の後に殻）。
"""
import datetime as dt
import re

import 当てる
import 直し as 直しの形
from 芯 import 字  # 字のそろえ方の正本（当てる が パックの根を sys.path に置く）

月の置き場の名 = re.compile(r"(\d{4})\.(\d{2})支給（(\d{1,2})月分）")


def 配る(会社たち: list[dict], 型: dict, 直したち: list[dict], 今日: dt.date | None = None) -> dict:
    今の版 = 当てる.型を読む(型)["版"]
    行たち, 結果たち = [], []
    for c in 会社たち:
        r = 当てる.見通す(c, 型, 直したち, 今日)
        r["消す問い"] += 置き場を見る(c, 今日 or dt.date.today(), "")
        r["人が見る物"] = 当てる.人が見る物(r)
        結果たち.append(r)
        行たち.append({
            "会社": r["会社"], "今の版": r["前の版"], "当てる直し": r["当てた直し"],
            "変わるタブ": len(r["変わるタブ"]),
            "変わる列の数": sum(1 for s in r["書く手順"] if s["する"] == "値を書く"),
            "寄せられない物": len(r["寄せられない物"]), "足りない値": len(r["足りない値"]),
            "当てるか": "当てる" if not r["寄せられない物"] and r["当てた直し"] else ("済" if not r["当てた直し"] else "残す（答えを集める）"),
        })
    # 前の版のまま残る会社を頭に（黙って残さない）
    行たち.sort(key=lambda x: (x["当てるか"] != "残す（答えを集める）", x["今の版"]))
    版たち = [x["今の版"] if x["当てるか"] != "当てる" else 今の版 for x in 行たち]
    return {"今の版": 今の版, "見通し": 行たち, "結果": 結果たち,
            "消してよい直し": 消してよい直し(版たち, 直したち),
            "人が見る物": 見通しの一枚(今の版, 行たち, 消してよい直し(版たち, 直したち))}


def 消してよい直し(版たち: list[int], 直したち: list[dict]) -> list[int]:
    """全社の型の版が N 以上なら直し N は消してよい（両方の事務所でそろってから消す＝§2.3）。"""
    if not 版たち:
        return []
    低い = min(版たち)
    return [d["版"] for d in 直したち if d["版"] <= 低い]


def 見通しの一枚(今の版, 行たち, 消せる) -> str:
    L = [f"# 配りの見通し（今の版 {今の版}）", "", "| 会社 | 今の版 | 当てる直し | 変わるタブ | 変わる列の数 | 寄せられない物 | 足りない値 | 当てるか |", "|---|---|---|---|---|---|---|---|"]
    L += [f"| {x['会社']} | {x['今の版']} | {','.join(map(str, x['当てる直し'])) or '—'} | {x['変わるタブ']} | {x['変わる列の数']} | {x['寄せられない物']} | {x['足りない値']} | {x['当てるか']} |" for x in 行たち]
    L += ["", f"消してよい直し（この事務所の分）: {', '.join(map(str, 消せる)) or 'なし'}（もう片方の事務所でもそろってから消す）"]
    return "\n".join(L)


# ---------------------------------------------------------------- 見回り

期限の名 = re.compile(r"(?:^|/)(?:消す_)?(\d{4}-?\d{2}-?\d{2})_")


def 名の期限(名: str):
    m = 期限の名.search(名)
    if not m:
        return None
    s = m.group(1).replace("-", "")
    try:
        return dt.date(int(s[:4]), int(s[4:6]), int(s[6:8]))
    except ValueError:
        return None


def 置き場を見る(会社: dict, 今日: dt.date, 窓: str, 止め: list | None = None) -> list[dict]:
    """置き場の一覧（名だけ）から、消す問いへ並べる物を拾う。

    止め＝直しの「前の置き場を止める」の (前の名, 今の名, 版)。前の形の置き場の名の物は消さずに 作り直す と並べる
    （Drive の型 §10＝前の形の Drive は寄せずに作り直す。寄せる も同じ名で止まる）。"""
    out = []
    for p in 会社.get("置き場", []):
        名 = p.rstrip("/").split("/")[-1]
        親 = p.rstrip("/").rsplit("/", 1)[0] if "/" in p.rstrip("/") else ""
        期限 = 名の期限(p)
        行 = None
        前の名 = next((前 for 前, _, _ in (止め or []) if 直しの形.前の名か(p, 前)), None)
        if 前の名:
            行 = ("前の形の置き場", "", f"消さずに残し、会社の Drive を新しい形で作り直す（前の名「{前の名}」・Drive の型 §10）")
        elif p.startswith("9_履歴/") and 名.startswith("消す_") and 期限 and 期限 <= 今日:
            行 = ("消す日が過ぎた", 期限.isoformat(), "消す")
        elif 写しの名か(名):
            行 = ("旧_・写しの名", "", "その会社の寄せで今のタブ・file と照らしてから消す")
        elif (頭 := p.split("/")[0]).startswith("80_答え") and p.rstrip("/") == 頭 or 名.startswith("照合_"):
            行 = ("答え（開発の間だけ）", "", "事務所の根から外す（答えは開発の手元・確かめと仮.md）")
        if 行:
            out.append({"会社": 会社["会社"], "物": 名, "置き場": 親 or "（組の根）", "中を見た窓": 窓,
                        "中身はどこに在るか": 行[0], "期限": 行[1], "推奨": 行[2],
                        "消す手順": [{"する": "file を消す", "名": p}] if 行[2] == "消す" else []})
    return out


# 旧_・写しの名（Drive の型 §2 の検査の 3）。消す問い（置き場を見る）と置き場の検査が同じ並びで照らす＝ここ 1 か所。
# 字は 芯/字.py でそろえてから照らす: 全角の「（1）」も Drive が付ける半角の「(1)」も、「コピー」も英語の「Copy of …」（大小を問わず頭）も当たる。
写しの頭 = ("旧_", "Copy of")
写しの語 = ("コピー", "(1)")


def 写しの名か(名: str) -> bool:
    """名が 旧_ の物か、Drive が作った写しの名（コピー・（1）・Copy of）か。"""
    return 字.頭が(名, 写しの頭) or 字.含む(名, 写しの語)


# 会社の根の木（docs/設計/Drive の型.md §2「会社の根」）。置き場の検査の 1・2 が照らす名（型.json は置き場の木を持たない＝ここ 1 か所）
会社の根の名 = ("1_決まり", "2_マスタ", "3_月ごと", "8_確認事項", "9_履歴")
台帳の名 = re.compile(r"台帳_\d{4}")
月のフォルダの名 = ("1_届いた物", "2_出す物")
# 事務所の根の 00_事務所（Drive の型 §2「事務所の根」。殻が会社の置き場に並べて渡す時もある）
事務所の名 = "00_事務所"
事務所の物 = ("事務所のルール.md", "事務所の設定", "管理表", "質問と回答", "9_履歴")
事務所の確認事項 = re.compile(r"確認事項_事務所_.+\.html")
決まりの4つ = ("給与のルール.md", "作業のルール.md", "人のルール.md", "質問と回答")
AIの作業の物 = re.compile(r"\.(?:py|json|ipynb|pyc)$|引き継ぎ")
置き場の検査の項目 = {1: "木に無い名", 2: "1_決まり/ に 4 つ以外の物", 3: "旧_・コピー・（1） の名", 4: "消す日が過ぎた（知らせ）",
               5: "AI の作業の物", 6: "シートのタブ・見出しが型と違う・列 会社 が無いか空"}


def 置き場の検査(会社: dict, 今日: dt.date, 型: dict | None = None) -> list[dict]:
    """置き場の検査（Drive の型 §2「照らす検査の要件」の 6 つ）を 1 つの口で当てる → [{会社, 項目, 何, 所, 訳, 赤}]。
    項目 4（消す日が過ぎた）は知らせ（赤＝False）。6 は 型（型.json を開いた物）を渡した時だけシートの見出しを型と照らし、
    列 会社 の無いタブ・会社 の空な行は型が無くても見る。置き場は 会社["置き場"]（組の根からの名・フォルダは / で終わる）。"""
    out = []
    名の会社 = 会社.get("会社", "")

    def 挙げる(項目: int, 所: str, 訳: str):
        out.append({"会社": 名の会社, "項目": 項目, "何": 置き場の検査の項目[項目], "所": 所, "訳": 訳, "赤": 項目 != 4})

    for p in 会社.get("置き場", []):
        部分 = [x for x in p.rstrip("/").split("/") if x]
        if not 部分:
            continue
        名 = 部分[-1]
        頭 = 部分[0]
        if 頭 == 事務所の名:
            if len(部分) >= 2 and 部分[1] not in 事務所の物 and not 事務所の確認事項.fullmatch(部分[1]):
                挙げる(1, "/".join(部分[:2]), f"00_事務所 に木（{'・'.join(事務所の物)}・確認事項_事務所_…）に無い名「{部分[1]}」")
        elif 頭 not in 会社の根の名 and not 台帳の名.fullmatch(頭):
            挙げる(1, 頭, f"会社の根に木（{'・'.join(会社の根の名)}・台帳_<支給年>）に無い名「{頭}」")
        elif 頭 == "3_月ごと" and len(部分) >= 3 and 部分[2] not in 月のフォルダの名:
            挙げる(1, "/".join(部分[:3]), f"月のフォルダに {'・'.join(月のフォルダの名)} のほかの名「{部分[2]}」")
        if 頭 == "1_決まり" and len(部分) >= 2 and (部分[1] not in 決まりの4つ or len(部分) > 2 or p.endswith("/")):
            挙げる(2, "/".join(部分[:2]), f"1_決まり/ に {'・'.join(決まりの4つ)} のほかの物「{部分[1]}」")
        if any(写しの名か(x) for x in 部分):
            挙げる(3, p, f"名に 旧_・コピー・（1） を持つ物「{名}」")
        期限 = 名の期限(p)
        if 頭 == "9_履歴" and 名.startswith("消す_") and 期限 and 期限 <= 今日:
            挙げる(4, p, f"消す日 {期限.isoformat()} が過ぎた")
        if AIの作業の物.search(名):
            挙げる(5, p, f"AI の作業の物「{名}」は Drive に置かない（窓の作業場へ）")
    型のファイル = 当てる.型を読む(型)["ファイル"] if 型 else {}
    for f, tabs in (会社.get("シート") or {}).items():
        K = 型のファイル.get(f, 型のファイル.get(台帳の名.sub("台帳_<支給年>", f)) if 台帳の名.fullmatch(f) else None)
        for t, rows in tabs.items():
            if t.startswith("旧_") or not rows:
                continue
            h = [str(x).strip() for x in rows[0]]
            会社が要る = not f.startswith(事務所の名 + "/")   # 事務所の設定のタブは型が列「会社」を持たない物がある
            if K is not None:
                if t not in K:
                    挙げる(6, f"{f}/{t}", "型に無いタブ")
                    continue
                want = [c["名"] for c in K[t]]
                会社が要る = "会社" in want
                if h[:len(want)] != want or any(x for x in h[len(want):]):
                    挙げる(6, f"{f}/{t}", f"見出しが型と違う（型: {'・'.join(want)}／シート: {'・'.join(x for x in h if x)}）")
            if not 会社が要る:
                continue
            if "会社" not in h:
                挙げる(6, f"{f}/{t}", "列 会社 が無い")
                continue
            i = h.index("会社")
            空 = [n for n, r in enumerate(rows[1:], 2)
                 if any(str(v or "").strip() for v in r) and not str(r[i] if i < len(r) else "").strip()]
            if 空:
                挙げる(6, f"{f}/{t}", f"列 会社 が空の行（{'・'.join(map(str, 空[:5]))}{' ほか' if len(空) > 5 else ''} 行目）")
    return out


def 見回り(会社たち: list[dict], 直したち: list[dict], 今の版: int, 今日: dt.date | None = None,
         窓: str = "", 寄せの消す問い: list[dict] | None = None, 前の答え: dict | None = None, 型: dict | None = None) -> dict:
    """事務所ごとに 1 枚の消す問いを作る。答えの無かった行は次の回にもう一度並ぶ（前の答えに無い行は全部並べる）。
    置き場の検査（§2 の 6 つ）を会社ごとに当て、`置き場の検査` に返す（項目 4 のほかが 1 つでもあれば 赤）。"""
    今日 = 今日 or dt.date.today()
    前の答え = 前の答え or {}
    行たち = []
    for c in 会社たち:
        行たち += 置き場を見る(c, 今日, 窓, 直しの形.前の置き場(直したち))
        if c.get("シート"):
            記 = 当てる.記録()
            当てる.旧のタブを照らす(当てる.物(c), 記)
            for x in 記.消す問い:
                行たち.append({"会社": c["会社"], "中を見た窓": 窓, "期限": "", **x})
            for x in 記.寄せられない:
                行たち.append({"会社": c["会社"], "物": x["所"], "置き場": x["所"], "中を見た窓": 窓,
                            "中身はどこに在るか": "どこにも無い値が在る", "期限": "", "推奨": "残す（寄せで行き先を答える）", "消す手順": []})
    for x in 寄せの消す問い or []:
        行たち.append({"中を見た窓": 窓, "期限": "", **x})
    for x in 行たち:
        x["鍵"] = f"{x['会社']}/{x['置き場']}/{x['物']}"
    # 「残す」と答えた行は新しい期限まで並べない
    残す = {k: v for k, v in 前の答え.items() if str(v).startswith("残す:")}
    行たち = [x for x in 行たち if not (x["鍵"] in 残す and dt.date.fromisoformat(残す[x["鍵"]][3:].strip()) > 今日)]
    ずれ = [x for c in 会社たち for x in 書き方を見る(c)]
    検査 = [x for c in 会社たち for x in 置き場の検査(c, 今日, 型)]
    前の版のまま = [{"会社": c["会社"], "型の版": int(c.get("型の版", 0) or 0)} for c in 会社たち if int(c.get("型の版", 0) or 0) < 今の版]
    消せる = 消してよい直し([int(c.get("型の版", 0) or 0) for c in 会社たち], 直したち)
    人が見る物 = 消す問いの一枚(行たち, 前の版のまま, 消せる)
    if ずれ:
        人が見る物 += "\n\n" + 書き方のずれの一枚(ずれ)
    if 検査:
        人が見る物 += "\n\n" + 置き場の検査の一枚(検査)
    return {"消す問い": 行たち, "前の版のままの会社": 前の版のまま, "消してよい直し": 消せる, "書き方のずれ": ずれ,
            "置き場の検査": 検査, "赤": bool(ずれ) or any(x["赤"] for x in 検査), "人が見る物": 人が見る物}


def 置き場の検査の一枚(検査) -> str:
    L = ["# 置き場の検査（Drive の型 §2 の 6 つ。4 は知らせ）", "", "| 会社 | 項目 | 所 | 訳 |", "|---|---|---|---|"]
    L += [f"| {x['会社']} | {x['項目']} {x['何']} | {x['所']} | {x['訳']} |" for x in 検査]
    return "\n".join(L)


def 書き方を見る(会社: dict) -> list[dict]:
    """型の書き方（支給月 YYYY.MM支給・日付 YYYY-MM-DD・時刻 h:mm・月の置き場の名 YYYY.MM支給（M月分））からずれた値（赤で知らせる・直さない）。

    照らす書き方は台帳を書く口（月次/台帳の形.py の 書き方のずれ）と同じ 1 か所。直すのは人か寄せ（値を黙って書き換えない）。"""
    形 = 当てる.台帳の形()
    out = []
    for f, tabs in (会社.get("シート") or {}).items():
        if not (f.startswith("2_マスタ") or f.startswith("台帳")):
            continue
        for t, rows in tabs.items():
            if not rows:
                continue
            h = [str(x) for x in rows[0]]
            for n, r in enumerate(rows[1:], 2):
                for x in 形.書き方のずれ(t, h, ["" if v is None else str(v) for v in r]):
                    out.append({"会社": 会社["会社"], "所": f"{f}/{t}/{n}行目", "ずれ": x})
    for p in 会社.get("置き場", []):
        部分 = p.rstrip("/").split("/")
        if len(部分) >= 2 and 部分[0] == "3_月ごと":
            m = 月の置き場の名.fullmatch(部分[1])
            if not m or not 1 <= int(m.group(3)) <= 12:
                out.append({"会社": 会社["会社"], "所": "/".join(部分[:2]), "ずれ": f"月の置き場の名「{部分[1]}」（YYYY.MM支給（M月分））"})
    return list({(x["所"], x["ずれ"]): x for x in out}.values())


def 書き方のずれの一枚(ずれ) -> str:
    L = ["# 赤: 書き方のずれ（型の列の意味の書き方に合わない値）", "", "| 会社 | 所 | ずれ |", "|---|---|---|"]
    L += [f"| {x['会社']} | {x['所']} | {x['ずれ']} |" for x in ずれ]
    return "\n".join(L)


def 消す問いの一枚(行たち, 前の版のまま, 消せる) -> str:
    """オーナーへ 1 回で聞く 1 枚（置き場は事務所の Drive の確認ページの置き場・会社の名が入るので repo に出さない）。"""
    L = ["# 消す問い", "", "答え方: 「推奨どおり全部」か、行ごとに 消す／原本へ移す／残す:<新しい期限 YYYY-MM-DD>。答えの無い行は次の回にもう一度並ぶ。", "",
         "| 会社 | 物 | 置き場 | 中を見た窓 | 中身はどこに在るか | 期限 | 推奨 |", "|---|---|---|---|---|---|---|"]
    L += [f"| {x['会社']} | {x['物']} | {x['置き場']} | {x['中を見た窓']} | {x['中身はどこに在るか']} | {x['期限']} | {x['推奨']} |" for x in 行たち]
    if 前の版のまま:
        L += ["", "前の版のままの会社: " + "・".join(f"{x['会社']}（版 {x['型の版']}）" for x in 前の版のまま)]
    L += ["", f"消してよい直し（この事務所の分）: {', '.join(map(str, 消せる)) or 'なし'}"]
    return "\n".join(L)
