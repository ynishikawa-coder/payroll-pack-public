# -*- coding: utf-8 -*-
"""前の道具の 勤務の長さの丸め（分）を `時間.打刻の丸めの単位` へ黙って移さない（型の版を上げない読み）。

前の道具の 勤務の長さの丸め（分）は、日の実働を単位で **切り捨て** た
（委託の日当と時給を選ぶ実働も、委託の時給の実働も、この丸めの後）。今の `時間.打刻の丸めの単位` は区間を **長くする向き** だけの丸め＝別の意味の値。
直し 3（出た版・中身は変えない）はこの列を `時間.打刻の丸めの単位` へ名を変えて移すため、そのまま書くと額が変わる
（作り物: 委託だけの人・10:22〜13:59・15 → 打刻の丸めで 3:45／前の道具 3:30）。

決め: 前の道具の委託の丸めは「休憩を引いた後の日の実働を N 分単位で切り捨て」で意味が決まっている＝事務所には聞かない。
ただし `時間.打刻の丸めの単位` は今の型でも正しい項目（事務所が雇用の人のために書ける）＝**出所の分かる値だけ** 移す。

直しの鎖の後に、どの版の会社にも毎回当てる:
- 出所が前の道具と分かる値＝寄せの入力（Drive に今在る値）の勤務の型に前の列 `勤務の長さの丸め（分）` が在り、その回の直し 3 が 打刻の丸めの単位 へ移した値:
  - 打刻の丸めの単位 を空にする（前の道具の切り捨てを長くする向きの丸めに使わない）。
  - 委託の人（`人.区分` 委託・委託の併用）が居て `委託.実働の丸め` が無ければ、会社の行 `委託.実働の丸め`＝`N分切捨て`（N＝0 は `丸めない`）を書く。
    委託の人が居なければ書かない（持たない＝捨てた（直しの持たない））。
  - 雇用の人が居れば知らせ 1 つ: 前の道具は雇用の人の日の実働も切り捨てた＝写さない（24 条）＝前の明細と額が変わる。
  - 分の数でない値・型ごとに違う N は問い 1 つ。
- 出所の分からない値（版 3 以上の会社の 打刻の丸めの単位。前の寄せが移した値か、事務所が今の型で書いた値か見分けられない）:
  黙って変えない。委託の人が居て `委託.実働の丸め` が無い会社だけ問い 1 つ（委託の人の額が変わるため）。委託の人が居なければ何もしない。
- 答え: `前の道具の丸め`（その値 N を N分切捨て へ）・`値:<単位と向き>`・`丸めない` → `委託.実働の丸め` へ書き 打刻の丸めの単位 を空に／
  `打刻の丸めのまま` → 打刻の丸めの単位 は残し `委託.実働の丸め`＝丸めない。
- 一度移した後（前の列も 打刻の丸めの単位 の値も無い・または `委託.実働の丸め` が在る）は何もしない＝何度当てても同じ。
"""
import re

import 当てる as 当

マスタ = "03_マスタ"
打刻 = "時間.打刻の丸めの単位"
項目 = "委託.実働の丸め"
鍵 = f"{マスタ}/勤務の型/{項目}"
丸めない = "丸めない"
打刻のまま = "打刻の丸めのまま"
前の道具 = "前の道具の丸め"
前の列 = "勤務の長さの丸め（分）"
委託の区分 = ("委託", "委託の併用")
_字 = re.compile(r"^(\d+)分(切捨て|切上げ|四捨五入)$")


def 字をそろえる(v) -> str:
    """芯/計算/形.語をそろえる と同じそろえ（切り捨て→切捨て・空白と区切りを落とす）。"""
    s = str(v or "").strip()
    for a, b in (("切り捨て", "切捨て"), ("切り上げ", "切上げ"), (" ", ""), ("　", ""), ("・", ""), ("、", "")):
        s = s.replace(a, b)
    return s.translate(str.maketrans("０１２３４５６７８９", "0123456789"))


def 値を読む(v) -> str | None:
    """答えの値 → 書く字（`15分切捨て`・丸めない）。読めなければ None。"""
    s = 字をそろえる(v)
    if s in (丸めない, "しない", "無し"):
        return 丸めない
    m = _字.match(s)
    if not m or int(m.group(1)) <= 0:
        return None
    return f"{int(m.group(1))}分{m.group(2)}"


def 前の分(v) -> int | None:
    """前の道具の 勤務の長さの丸め（分）の値（`15`・`15分`・全角）→ 分の数。読めなければ None。"""
    m = re.fullmatch(r"(\d+)(分)?", 字をそろえる(v))
    return int(m.group(1)) if m else None


def _値(rows, r, 名) -> str:
    i = 当.列の番号(rows, 名)
    return "" if i is None else str(rows[r][i]).strip()


def _区分たち(o) -> list[str]:
    rows = o.シート.get(マスタ, {}).get("社員")
    if not rows or 当.列の番号(rows, "人.区分") is None:
        return []
    return [_値(rows, r, "人.区分") for r in range(1, len(rows)) if any(not 当.空か(v) for v in rows[r])]


def _前の値(前) -> dict:
    """寄せの入力の勤務の型の前の列 勤務の長さの丸め（分）→ {型の名: 値}（値の在る行だけ）。列が無ければ {}。"""
    rows = (前.シート.get(マスタ, {}).get("勤務の型") if 前 is not None else None) or []
    if not rows or 当.列の番号(rows, 前の列) is None:
        return {}
    return {_値(rows, r, "型の名"): _値(rows, r, 前の列) for r in range(1, len(rows)) if _値(rows, r, 前の列)}


def 当てる(o, 記, 前=None):
    型rows = o.シート.get(マスタ, {}).get("勤務の型")
    if not 型rows or 当.列の番号(型rows, 打刻) is None:
        return
    i = 当.列の番号(型rows, 打刻)
    在る = [r for r in range(1, len(型rows)) if not 当.空か(型rows[r][i])]
    if not 在る:
        return
    前の値 = _前の値(前)
    分かる = [r for r in 在る if 前の値.get(_値(型rows, r, "型の名")) == str(型rows[r][i]).strip()]
    区分 = _区分たち(o)
    委託が居る = any(k in 委託の区分 for k in 区分)
    雇用が居る = any(k != "委託" and k != "役員" for k in 区分)
    会社rows = o.シート.get(マスタ, {}).get("会社")
    書ける = bool(会社rows) and all(当.列の番号(会社rows, c) is not None for c in ("項目", "今の値"))
    既に = 書ける and any(_値(会社rows, r, "項目") == 項目 and _値(会社rows, r, "会社") in ("", o.会社) and _値(会社rows, r, "今の値")
                       for r in range(1, len(会社rows)))
    where = f"{マスタ}/勤務の型"
    対象 = 分かる if 分かる else ([] if 既に or not 委託が居る else 在る)
    if not 対象:
        return
    並び = "・".join(f"{_値(型rows, r, '型の名') or f'{r + 1} 行目'}={型rows[r][i]}" for r in 対象)
    ans = str(o.人の答え.get(鍵, "")).strip()
    Ns = {前の分(型rows[r][i]) for r in 対象}
    N = next(iter(Ns)) if len(Ns) == 1 and None not in Ns else None
    書く, 誰 = None, f"人の答え「{ans}」"
    if ans.startswith("値:"):
        書く = 値を読む(ans[2:])
    elif ans in (丸めない, 打刻のまま):
        書く = 丸めない
    elif ans == 前の道具 or (not ans and 分かる):
        if N is not None:
            書く = f"{N}分切捨て" if N else 丸めない
            誰 = "前の道具の 勤務の長さの丸め（休憩を引いた後の日の実働を切り捨て）"
    if 書く is None or (委託が居る and not 既に and not 書ける):
        if 分かる:
            中身 = (f"前の道具の 勤務の長さの丸め（分）＝休憩を引いた後の日の実働の切り捨て の値 {並び}。"
                  f"分の数でないか、型ごとに違う（{項目} は会社の段の 1 つの値）")
        else:
            中身 = (f"{打刻}（区間を長くする向きの丸め）の値 {並び} の出所が分からない: 前の寄せが前の道具の 勤務の長さの丸め（分）"
                  f"＝休憩を引いた後の日の実働の切り捨て を移した値か、事務所が今の型で書いた打刻の丸めか。委託の人の額が変わる"
                  f"（例 10:22〜13:59・15 → 打刻の丸め 3:45／前の道具 3:30）")
        記.出せない(鍵, "読めない値" if 分かる else "出所の分からない値", where, 中身,
                  [前の道具, 打刻のまま, "値:<単位と向き（例 15分切捨て）>", 丸めない],
                  f"{前の道具}＝その値 N を {項目}＝N分切捨て へ・値:／丸めない も {項目} へ（どれも {打刻} を空に）"
                  f"／{打刻のまま}＝{打刻} を残し {項目}＝丸めない" + (f"。答え「{ans}」は読めない" if ans else ""))
        return
    if ans != 打刻のまま:
        for r in 対象:
            型rows[r][i] = ""
        記.当てた.append((0, 0, "値を移す", f"{where}/{打刻}"))
    if 委託が居る and not 既に:
        if ans != 打刻のまま:
            記.数["他の所へ移した" if 書く != 丸めない else "捨てた（人の答え）"] += len(対象)
        new = [""] * len(会社rows[0])
        for c, w in (("会社", o.会社), ("項目", 項目), ("今の値", 書く)):
            if 当.列の番号(会社rows, c) is not None:
                new[当.列の番号(会社rows, c)] = w
        会社rows.append(new)
        記.数["足した"] += sum(1 for v in new if not 当.空か(v))
        記.知らせ.append(f"{where}: {打刻} の {並び} を {誰} として {マスタ}/会社 の {項目}＝{書く} へ"
                        + ("（打刻の丸めは残す）" if ans == 打刻のまま else "（打刻の丸めは空に）"))
    elif ans != 打刻のまま:
        なぜ = ("前の道具の 勤務の長さの丸め＝日の実働の切り捨て（打刻の丸めと意味が違う・"
              + (f"{項目} は在る" if 既に else f"委託の人が居ない＝{項目} へも書かない") + "）")
        記.数["捨てた（直しの持たない）" if not ans else "捨てた（人の答え）"] += len(対象)
        記.持たない.append((f"{where}/{打刻}", len(対象), なぜ))
        記.知らせ.append(f"{where}: {打刻} の {並び} は{なぜ}＝空にした")
    if 分かる and 雇用が居る and ans != 打刻のまま:
        記.知らせ.append(f"{where}: 前の道具は 勤務の長さの丸め（{並び}）で雇用の人の日の実働も切り捨てていた。"
                        "雇用の人の実働を短くする丸めは写さない（24 条の全額払い）＝前の明細と額が変わる")
