# -*- coding: utf-8 -*-
"""事務所の 質問と回答（タブ 質問）1 枚を、事務所が渡す「前の形の読み替え」と型の作りで今の型へ寄せる（docs/設計/寄せる道具.md §1.3）。

なぜ在るか（2026-11-19）: 事務所全体の問い（`00_事務所/質問と回答`）は会社の型の版の鎖（`寄せる`）に乗らない表で、前の道具の
形（列の欠け・型に無い列・並び・前の形の問いの番号 `QYYYY.MM-NN`）のまま残ると、前の答えを照らす口（`確認ページ/前の答え.py`）が
「照らせない」で止まり、事務所全体の問いの確認ページを出せない。

型: 会社の 質問と回答 と同じ 1 つの型（列・並び。`初期設定/型.json` の 質問と回答「事務所」＝置き場 00_事務所・列「会社」は 事務所。
読むのは `型の口.事務所の質問と回答` の 1 か所）。寄せる道は 2 段:
  1. 事務所の読み替え（`列の名を変える`・`値の語を読み替える`・`列を足す`・`列の並びをそろえる`）: 前の語 → 今の語の中身は事務所の
     Drive の寄せの記録に置き、殻が渡す（パックは持たない＝`入れてよい物.md` ⟦鍵:給与計算/移行だけの物はパックに入れない⟧）。
  2. 型の作り（パックが型から当てる・どの事務所にも同じ）: 型の列で無い物を空で足す（列「会社」は値の在る行に 事務所）→ 型の並びに
     そろえる。当てるのは直しと同じ `当てる.当てる操作` の 1 か所。寄せた後は前の答えの照らしと同じ読みで確かめる。

止める物（書く手順を出さない・寄せられない物に出す。何も消さない）:
  - 1 行目が見出しでない表（上に URL などの行がある・読み替えの後も 問いの番号・質問・回答 の見出しが無い）＝見出しを推し量らない
    （型の作りを当てる前に見る＝見出しの無い列へ 問いの番号 を足して黙って通さない）
  - 型に無い列（値の在る列も空の列も）＝行き先を推し量らない（事務所の読み替えで型の列へ名を変える・どの事務所にも要る列なら型へ足す PR）
  - 列「会社」に 事務所 でない字（会社の問いが事務所の表に混ざった）
  - 読み替えの後も今の形 `Q<支給年月 6 桁>-<順>` でない問いの番号・聞き直しの番号（読み替えに無い前の形）
  - 読み替えた番号が、別の問いの今の形の番号と同じになる（ぶつかり＝答え済みの問いを取り違える）
  - 閉じた一覧の外の操作・ほかのファイルやタブへの操作・値の保ちが合わない
道具は Drive を開かない。殻が get_values の形の表と読み替えを渡し、返る書く手順（値を書く 1 手・書き方 RAW）を当てる。

  python3 道具/寄せ/呼び口.py 質問と回答 --表 <質問の get_values の JSON> --読み替え <操作の並びの JSON> [--ファイル 00_事務所/質問と回答]
終わりの値: 0＝書ける（書く手順 0 なら既に今の形）／1＝寄せられない物が在る（書く手順は空）。
"""
from __future__ import annotations

import copy
import importlib.util
from pathlib import Path

import 当てる
import 直し as 直しの形

_根 = Path(__file__).resolve().parents[2]
_s = importlib.util.spec_from_file_location("寄せ_前の答え", _根 / "確認ページ" / "前の答え.py")
前の答え = importlib.util.module_from_spec(_s)
_s.loader.exec_module(前の答え)

_型 = 当てる.型の口.事務所の質問と回答()
タブ = _型["タブ"]
既定のファイル = _型["ファイル"]
事務所 = _型["会社"]
型の見出し = _型["見出し"]
使える操作 = ("列の名を変える", "値の語を読み替える", "列を足す", "列の並びをそろえる")
if 前の答え.タブ != タブ:
    raise ValueError(f"前の答えの照らしのタブ {前の答え.タブ!r} と型のタブ {タブ!r} が違う")


def _値の数(rows) -> int:
    """見出しの外の空でない値の数（足した見出しは数えない）。"""
    return sum(1 for r in rows[1:] for v in r if not 当てる.空か(v))


def _番号の列(rows) -> int | None:
    return 当てる.列の番号(rows, "問いの番号") if rows else None


def 型の作り(ファイル: str = 既定のファイル) -> list[dict]:
    """型の列を足す（会社＝事務所・ほかは空）→ 型の並びにそろえる。どの事務所にも同じ（前の語を持たない）。"""
    return ([{"する": "列を足す", "ファイル": ファイル, "タブ": タブ, "見出し": c, "値": "<会社>" if c == "会社" else ""}
             for c in 型の見出し]
            + [{"する": "列の並びをそろえる", "ファイル": ファイル, "タブ": タブ}])


def 寄せる(values, 読み替え, ファイル: str = 既定のファイル) -> dict:
    """values（タブ 質問の get_values・1 行目が見出し）に 読み替え（操作の並び）と型の作りを当てる。
    返す物: 寄せた後の値・書く手順・戻す手順・当てた・寄せられない物・知らせ。寄せられない物が在れば書く手順と戻す手順は空。"""
    出せない: list[dict] = []
    if isinstance(values, dict):
        values = values.get("values", [])
    if not isinstance(values, list) or not all(isinstance(r, list) for r in values):
        raise ValueError("質問と回答の表は get_values の形（行の並び）")
    if not isinstance(読み替え, list) or not all(isinstance(op, dict) for op in 読み替え):
        raise ValueError("読み替えは操作の並び（[{\"する\": …}, …]）")
    誤り = 直しの形.形を確かめる({"版": 1, "前の版": 0, "なぜ": "質問と回答の前の形の読み替え", "操作": 読み替え}, "読み替え")
    for i, op in enumerate(読み替え, 1):
        if op.get("する") not in 使える操作:
            誤り.append(f"読み替え 操作{i}: 質問と回答の読み替えは {'・'.join(使える操作)} だけ（「{op.get('する')}」）")
        if op.get("ファイル") != ファイル or op.get("タブ") != タブ:
            誤り.append(f"読み替え 操作{i}: ファイル「{ファイル}」・タブ「{タブ}」への操作だけ（{op.get('ファイル')}/{op.get('タブ')}）")
    if 誤り:
        raise 直しの形.直しの誤り("\n".join(誤り))

    前 = 当てる.そろえる(values)
    o = 当てる.物({"会社": 事務所, "シート": {ファイル: {タブ: copy.deepcopy(前)}}})
    記 = 当てる.記録()
    K = {"ファイル": {ファイル: {タブ: [{"名": c} for c in 型の見出し]}}}
    for 番, op in enumerate(読み替え, 1):
        当てる.当てる操作(o, op, K, 記, 0, 番, {})
    where = f"{ファイル}/{タブ}"

    訳 = 前の答え.見出しの訳(o.シート[ファイル][タブ])
    if 訳:   # 見出しを推し量らない（1 行目が URL の行・見出しが欠けた表は人が直す）。型の作りは当てない
        出せない.append({"鍵": f"{where}/見出し", "種類": "形の合わない値", "所": where, "中身": f"質問と回答の{訳}",
                      "選べる答え": ["1 行目を型の見出しにしてからもう一度（人）"], "手がかり": ""})
    else:
        for 番, op in enumerate(型の作り(ファイル), len(読み替え) + 1):
            当てる.当てる操作(o, op, K, 記, 0, 番, {})
        後 = o.シート[ファイル][タブ]
        外 = [c for c in 後[0] if c not in 型の見出し]
        for c in 外:   # 型に無い列は消さず、行き先を推し量らない
            k = 後[0].index(c)
            n = sum(1 for r in 後[1:] if not 当てる.空か(r[k]))
            出せない.append({"鍵": f"{where}/列:{c}", "種類": "行き先の無い列", "所": where,
                          "中身": f"型に無い列「{c}」（値 {n} 個）",
                          "選べる答え": ["読み替えに 列の名を変える（前＝この列・後＝型の列）を足してもう一度（事務所の寄せの記録）",
                                       "型へ足す（どの事務所にも要る列の時だけ・型の PR）"], "手がかり": ""})
        if not 外 and 後[0] != 型の見出し:
            出せない.append({"鍵": f"{where}/並び", "種類": "直しの誤り", "所": where, "中身": "列が型と違う（型の作りが当たらない）",
                          "選べる答え": ["道具を直す（PR）"], "手がかり": ""})
        ki = 当てる.列の番号(後, "会社")
        他 = sorted({str(r[ki]).strip() for r in 後[1:] if ki is not None and str(r[ki]).strip() not in ("", 事務所)})
        if 他:
            出せない.append({"鍵": f"{where}/会社", "種類": "形の合わない値", "所": where,
                          "中身": f"列「会社」に {事務所} でない字: {'・'.join(他[:5])}（事務所の表は事務所全体の問いだけ）",
                          "選べる答え": ["会社の問いはその会社の 1_決まり/質問と回答 へ移してからもう一度（人）"], "手がかり": ""})
        行たち = 前の答え.行にする(後)
        悪い = 前の答え.読めない番号(行たち)
        if 悪い:
            出せない.append({"鍵": f"{where}/問いの番号", "種類": "形の合わない値", "所": where,
                          "中身": f"今の形（Q<支給年月 6 桁>-<順>）でない番号が残る: {'・'.join(悪い[:5])}"
                                f"{f' ほか {len(悪い) - 5} 件' if len(悪い) > 5 else ''}",
                          "選べる答え": ["読み替えに前の語 → 今の語を足してもう一度（事務所の寄せの記録）"], "手がかり": ""})
        # 読み替えで作った番号が、読み替える前から在った別の行の今の形の番号と同じ＝別の問いを 1 つに数える
        i, j = _番号の列(前), _番号の列(後)
        if i is not None and j is not None and len(前) == len(後):
            元の今の形 = {str(r[i]).strip() for r in 前[1:] if 前の答え.番号の形.fullmatch(str(r[i]).strip())}
            ぶつかる = sorted({str(b[j]).strip() for a, b in zip(前[1:], 後[1:])
                            if str(a[i]).strip() != str(b[j]).strip() and str(b[j]).strip() in 元の今の形})
            if ぶつかる:
                出せない.append({"鍵": f"{where}/問いの番号/ぶつかり", "種類": "ぶつかり", "所": where,
                              "中身": f"読み替えた番号が、前から在る今の形の番号と同じ: {'・'.join(ぶつかる[:5])}",
                              "選べる答え": ["前の形の問いに別の順を振る読み替えにする（事務所の寄せの記録）"], "手がかり": ""})
    後 = o.シート[ファイル][タブ]
    if _値の数(前) + 記.数["足した"] != _値の数(後):
        出せない.append({"鍵": f"{where}/値の保ち", "種類": "直しの誤り", "所": where,
                      "中身": f"空でない値の数が合わない（前 {_値の数(前)}・足した {記.数['足した']}・後 {_値の数(後)}）",
                      "選べる答え": ["読み替えを直す"], "手がかり": ""})

    当てた = [{"操作の番号": 番, "する": する, "所": 所} for _, 番, する, 所 in 記.当てた]
    書く, 戻す = [], []
    if not 出せない and 後 != 前:
        h, w = 当てる.大きさ(前, 後)
        範囲 = f"A1:{当てる.列の字(w)}{h}"
        書く = [{"する": "値を書く", "ファイル": ファイル, "タブ": タブ, "範囲": 範囲, "値": 当てる.敷く(後, h, w), "書き方": 当てる.字のまま}]
        戻す = [{"する": "値を書く", "ファイル": ファイル, "タブ": タブ, "範囲": 範囲, "値": 当てる.敷く(前, h, w), "書き方": 当てる.字のまま}]
    出せない = list(記.寄せられない) + 出せない
    知らせ = list(記.知らせ)
    if not 出せない and not 書く:
        知らせ.append(f"{where} は既に今の形（書く手順 0）")
    return {"寄せた後の値": 前 if 出せない else 後, "書く手順": 書く, "戻す手順": 戻す, "当てた": 当てた,
            "寄せられない物": 出せない, "知らせ": 知らせ}
