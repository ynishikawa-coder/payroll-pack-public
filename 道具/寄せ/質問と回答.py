def _番号の読み替え(読み替え) -> list[tuple[str, str, str]]:
    """読み替えのうち、問いの番号の列（後の 列の名を変える で 問いの番号 になる列も）への 値の語を読み替える → (前, 後, 合わせ) の並び。"""
    out = []
    for k, op in enumerate(読み替え):
        if op.get("する") != "値の語を読み替える" or "md" in op:
            continue
        名 = op.get("列")
        for later in 読み替え[k + 1:]:
            if later.get("する") == "列の名を変える" and later.get("前") == 名:
                名 = later.get("後")
        if 名 == "問いの番号":
            out.append((str(op["前"]), str(op["後"]), op.get("合わせ", "全体")))
    return out


def 字の中の番号を読み替える(字: str, 番号の読み替え) -> str:
    """番号の字 1 つ（自分を指す書き方から切り出した物）を、問いの番号の列と同じ読み替えで今の形へ（番号の切れ目でだけ当てる・順に当てる）。"""
    for 前, 後, 合わせ in 番号の読み替え:
        頭 = r"(?<![0-9A-Za-z])" + re.escape(前)
        if 合わせ == "全体":
            字 = re.sub(頭 + r"(?![0-9])", lambda m: 後, 字)
        elif 合わせ == "頭":
            字 = re.sub(頭 + r"(?=[0-9])", lambda m: 後, 字)
        else:   # 頭で全体: 頭が合う番号を丸ごと替える
            字 = re.sub(頭 + r"[0-9.\-/]*(?<=[0-9])|" + 頭 + r"(?![0-9])", lambda m: 後, 字)
    return 字


def _自分を指す番号(rows):
    """(行, 列の番号, 列の名, 当たり) を、この表の問いを指す書き方の当たりごとに。"""
    for c, 形 in 自分を指す書き方.items():
        k = 当てる.列の番号(rows, c) if rows else None
        if k is None:
            continue
        for r in range(1, len(rows)):
            for m in 形.finditer(str(rows[r][k])):
                yield r, k, c, m


def _字の中の番号をそろえる(rows, 番号の読み替え, 記, 番: int, where: str) -> None:
    替える: dict[tuple[int, int], list] = {}
    for r, k, c, m in _自分を指す番号(rows):
        w = 字の中の番号を読み替える(m.group(m.lastindex), 番号の読み替え)
        if w != m.group(m.lastindex):
            替える.setdefault((r, k), []).append((m.span(m.lastindex), w))
    for (r, k), xs in 替える.items():
        v = str(rows[r][k])
        for (a, b), w in sorted(xs, reverse=True):   # 後ろから差し替える（前の位置がずれない）
            v = v[:a] + w + v[b:]
        rows[r][k] = v
        記.当てた.append((0, 番, "字の中の問いの番号を読み替える", f"{where}/{rows[0][k]}/{当てる.行の名(rows, r)}"))


def 字の中の前の番号(rows) -> list[str]:
    """この表の問いを指す書き方（出し直し→・聞き直し:）の番号のうち、今の形でない物（前の形 Q2026.11-05 など）。"""
