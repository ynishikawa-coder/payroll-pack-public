"""直しの形（docs/設計/寄せる道具.md §1.2）。

直し＝型の版 N−1 の形を版 N の形へ持ち上げる操作の並び。1 つの直しは `直し/直し_NNNN.json` の 1 file。
操作は下の「操作の一覧」に在る物だけ（閉じた一覧）。足す時は設計書（寄せる道具.md §1.2）を直してから。
この file は直しを読み、形を確かめ、版の鎖（1, 2, …, N）を並べるだけ。当てるのは 当てる.py。
"""
import json
import os
import re

置き場 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "直し")

# する → (要る鍵, 任意の鍵)。どの操作も「前の形を確かめ、当たっていれば飛ばす」（当てる.py）。
操作の一覧 = {
    "タブを足す": ({"ファイル", "タブ"}, set()),
    "タブの名を変える": ({"ファイル", "前", "後"}, set()),
    # 値: "" ＝空／{"既定": x} ＝型の既定値／"<会社>" ＝入力の会社の呼び名（事務所の設定「会社の一覧」の字）
    # 条件: {"列": c, "より前": "YYYY-MM-DD"} ＝その列の日がこの日より前の行の空だけを埋める（寄せる道具.md §3「欄より前」）
    "列を足す": ({"ファイル", "タブ", "見出し", "値"}, {"条件"}),
    "列の名を変える": ({"ファイル", "タブ", "前", "後"}, set()),
    "列の並びをそろえる": ({"ファイル", "タブ"}, set()),
    # 合わせ: "全体"（既定）／"頭"（値の頭の語だけを替え、後ろは残す＝出所の語）／"頭で全体"（頭が合う値を丸ごと替える）。md: 値の代わりに md の本文の字を替える
    # 問いを起こす: true なら替えた所を「足りない値」に出す（確かめと仮.md の「過去の支給と一致」→仮）
    "値の語を読み替える": ({"前", "後"}, {"ファイル", "タブ", "列", "合わせ", "md", "問いを起こす"}),
    # 行: {"列": "値"} か {"列": {"頭": "…"}} ＝縦のタブ（項目の行）で、その行を md へ移して行を消す
    "列を md の見出しへ移す": ({"ファイル", "タブ", "列", "md", "見出し"}, {"行"}),
    # 先: {"タブ", "鍵": [...], "列", "足す行"?: {...}} ＝鍵で行を合わせて移す（足す行があれば縦の行を足す）
    #     "持たない" ＝型が持たないと決めた（門① の型）。値は捨てた数に数え、人が見る物に件数を出す
    "列を畳む": ({"ファイル", "タブ", "列", "先"}, {"行", "なぜ"}),
    "md の見出しの名を変える": ({"md", "前", "後"}, set()),
    "md の見出しを足す": ({"md", "見出し"}, {"後に"}),
    "file を置き場へ移す": ({"前", "後"}, set()),
    # 値の形を今の型の形へそろえる（当てる.py の 形の一覧）。行: 縦のタブの行の条件。読み: {前の語: 今の語}（形＝読み）。
    # 時間の値の項目: 形＝欄の名 の行に時間の値が在れば、その行の 項目 をこの名へ変える（値は会社の段の定数）
    # 先の列: 読んだ値を同じ行の別の列へ書く（元の列はそのまま＝後の操作が md へ移す）。読めない値は問いに残す（黙って通さない）
    "値をそろえる": ({"ファイル", "タブ", "列", "形"}, {"行", "読み", "先の列", "なぜ", "時間の値の項目"}),
    # 会社の行の前の語（例 給与の形＝委託）を、同じ会社の社員の列（例 人.区分）へ移す。人の値の在る人は人が勝つ（段の決まり）
    # 列の行き（任意）: 社員の列の前の語も移す {"列": c, "値": v}（その列を空にして 先の列 へ）
    "人の列へ移す": ({"ファイル", "行", "値", "先の列"}, {"人の値の列", "列の行き"}),
}

直しの鍵 = {"版", "前の版", "なぜ", "部品", "操作"}


class 直しの誤り(ValueError):
    pass


def 形を確かめる(直し: dict, 名: str = "直し") -> list[str]:
    """直し 1 つの形の誤りを並べる（空なら正しい）。"""
    誤り = []
    足りない = 直しの鍵 - set(直し) - {"部品"}
    if 足りない:
        誤り.append(f"{名}: 鍵が無い {sorted(足りない)}")
    余り = set(直し) - 直しの鍵 - {"手がかり", "説明", "当たる"}  # 当たる: "全ての事務所"（骨の自己検査 tests/test_骨.py「4」が見る）
    if 余り:
        誤り.append(f"{名}: 知らない鍵 {sorted(余り)}")
    if isinstance(直し.get("版"), int) and 直し.get("前の版") != 直し["版"] - 1:
        誤り.append(f"{名}: 前の版は 版−1（{直し.get('前の版')}）")
    for i, op in enumerate(直し.get("操作", [])):
        する = op.get("する")
        if する not in 操作の一覧:
            誤り.append(f"{名} 操作{i + 1}: 閉じた一覧に無い「{する}」")
            continue
        要る, 任意 = 操作の一覧[する]
        無い = 要る - set(op)
        知らない = set(op) - 要る - 任意 - {"する"}
        if 無い:
            誤り.append(f"{名} 操作{i + 1}「{する}」: 鍵が無い {sorted(無い)}")
        if 知らない:
            誤り.append(f"{名} 操作{i + 1}「{する}」: 知らない鍵 {sorted(知らない)}")
        if する == "列を畳む" and op.get("先") != "持たない":
            先 = op.get("先")
            if not isinstance(先, dict) or not {"タブ", "鍵", "列"} <= set(先):
                誤り.append(f"{名} 操作{i + 1}「列を畳む」: 先は \"持たない\" か {{タブ・鍵・列}}（移す先が決まっている時だけ）")
            elif "行" in op:
                誤り.append(f"{名} 操作{i + 1}「列を畳む」: 行を選ぶのは 先＝\"持たない\" の時だけ（行の他の値が消えるため）")
        if する == "値をそろえる" and op.get("形") not in ("支給月", "読み", "都道府県", "休憩の長さ", "欄の名"):
            誤り.append(f"{名} 操作{i + 1}「値をそろえる」: 形は 支給月・読み・都道府県・休憩の長さ・欄の名")
        if する == "値をそろえる" and "時間の値の項目" in op and not (op.get("形") == "欄の名" and "項目" in (op.get("行") or {})):
            誤り.append(f"{名} 操作{i + 1}「値をそろえる」: 時間の値の項目 は 形＝欄の名 と 行 の 項目 と一緒に（縦のタブの行の項目を変える）")
        if する == "値をそろえる" and op.get("形") == "読み" and not isinstance(op.get("読み"), dict):
            誤り.append(f"{名} 操作{i + 1}「値をそろえる」: 形＝読み には 読み（{{前: 今}}）が要る")
        if する == "値の語を読み替える" and op.get("合わせ", "全体") not in ("全体", "頭", "頭で全体"):
            誤り.append(f"{名} 操作{i + 1}「値の語を読み替える」: 合わせは 全体・頭・頭で全体")
        if する == "値の語を読み替える" and not ("md" in op or {"ファイル", "タブ", "列"} <= set(op)):
            誤り.append(f"{名} 操作{i + 1}「値の語を読み替える」: ファイル・タブ・列 か md が要る")
    return 誤り


def 読む(dir_: str = 置き場) -> list[dict]:
    """直しを版の順に並べて返す。形の誤り・鎖の切れ目があれば 直しの誤り。"""
    直したち = []
    if not os.path.isdir(dir_):
        return 直したち
    for f in sorted(os.listdir(dir_)):
        if not re.fullmatch(r"直し_\d{4}\.json", f):
            continue
        with open(os.path.join(dir_, f), encoding="utf-8") as fh:
            d = json.load(fh)
        誤り = 形を確かめる(d, f)
        if 誤り:
            raise 直しの誤り("\n".join(誤り))
        if int(f[3:7]) != d["版"]:
            raise 直しの誤り(f"{f}: file の名の番号と版（{d['版']}）が違う")
        直したち.append(d)
    return 鎖を確かめる(直したち)


def 鎖を確かめる(直したち: list[dict]) -> list[dict]:
    """版が切れ目なく続くか（消した古い直しの後から始まってよい）。"""
    直したち = sorted(直したち, key=lambda d: d["版"])
    for a, b in zip(直したち, 直したち[1:]):
        if b["版"] != a["版"] + 1:
            raise 直しの誤り(f"版 {a['版']} の次が {b['版']}（切れ目）")
    return 直したち


def 当てる直し(直したち: list[dict], 会社の版: int, 部品: list[str]) -> list[dict]:
    """会社の版より後の直しのうち、共通か会社が選んだ部品の物を版の順に返す。"""
    if 直したち and 会社の版 < 直したち[0]["版"] - 1:
        raise 直しの誤り(f"会社の版 {会社の版} を持ち上げる直し（版 {会社の版 + 1}）はもう消した。雛形から作り直すか、消した直しを戻す")
    return [d for d in 直したち if d["版"] > 会社の版 and d.get("部品", "共通") in ["共通", *部品]]
