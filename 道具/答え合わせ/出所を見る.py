def _読み込む(名: str, path: Path):
    if 名 in sys.modules:
        return sys.modules[名]
    s = importlib.util.spec_from_file_location(名, path)
    m = importlib.util.module_from_spec(s)
    sys.modules[名] = m
    s.loader.exec_module(m)
    return m


_根 = Path(__file__).resolve().parents[2]
# 質問と回答の 3 タブ（問い・答え・振り分け）の読みの正本は 初期設定/質問と回答.py、答えの値の読みの正本は 確認ページ/前の答え.py
