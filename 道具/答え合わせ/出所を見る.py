# 答えの資料の名の当て方・答えの行の出所の読み・過去の結果の照らしの正本は 月次/例の確かめ.py（月次の 確かめた人 の過去の結果と
# 同じ 1 つ。写さずに呼ぶ）
_名 = _例の確かめ.答えの資料の名
_答えの出所 = _例の確かめ.答えの出所


_番号の区切り = re.compile(r"[、・,，;；\s]+")
# 問いの鍵（`質問と回答.鍵を振る` の振る `Q<数>`）。前の受付の形 `Q<6 桁>-<数>` も 1 つの鍵に読む＝表に無ければ 問いが無い で止める
_鍵の字 = r"(?<![A-Za-z0-9])Q\d+(?:-\d+)?(?![A-Za-z0-9])"
_番号の形 = re.compile(_鍵の字)
# `［出所］X`（前の形）と `［出所: X・適用 …］`（初期設定/README.md「md の書き方」の形）の両方を読む
_出所の行 = re.compile(r"[［\[]出所(?:[］\]]\s*[:：]?|\s*[:：])\s*([^］\]［\[]+)")
# 適用の時期の注（`適用 2026.08支給〜`・`適用2026.10`・`適用 2026.10〜2026.12支給`）だけを抜く。後ろに続く字は書類の名に残す
_月の字 = r"\d{4}\s*[./年-]\s*\d{1,2}\s*(?:月\s*)?(?:支給|分)?"
_適用の注 = re.compile(rf"適用\s*{_月の字}(?:\s*[〜~]\s*(?:{_月の字})?)?")
_訳の問い = re.compile(r"問い[:：]\s*([^\s、,，;；・／/（(]+)")


def 出所の行たち(md: dict | None = None, 台帳: dict | None = None, 会社: str | None = None) -> list[dict]:
    """決まりの MD の `［出所］<書類の名・問いの番号を 、・ で>` の行と、台帳（確定した勤怠・確定した勤怠の区間）の 直した訳 の
    `問い:<番号>` → 変更の記録と同じ形の行（{会社, 項目, NO, 書類の名, 問いの番号, 確かめ, 新しい値, 所}）。
    md: {md の名: 字}。台帳: {タブの名: 行（列名の dict の並びか、1 行目が見出しの 2 次元の並び）}。
    MD の出所は確かめ＝空（書類か問いの番号を見る）・台帳の答えは確かめ＝確認済（答えの無い問いで確定にしない）。"""
    out = []
    for 名, 字 in (md or {}).items():
        見出し = ""
        for n, 行 in enumerate(str(字 or "").splitlines(), 1):
            h = re.match(r"^#+\s*(.+?)\s*$", 行)
            if h:
                見出し = h.group(1)
                continue
            ms = list(_出所の行.finditer(行))
            if not ms:
                continue
            # 最初の［出所 から行の終わりまでの字（前の読みの範囲）も注を抜く前の字に入れる＝区切りの読み方で答えの名を落としても止める側へ
            # （過去の結果の照らしの字だけは抜く＝照らしで確かめる側。問いの番号の形は抜かない＝番号を含む答えの名も当てる）
            # 抜くのは各［出所の中で読んで 見る が照らす過去の結果の字だけ（尾を読み直さない＝照らす物と抜く物をずらさない）
            尾 = unicodedata.normalize("NFKC", 行[ms[0].start():])
            頭 = len(out)
            for j, m in enumerate(ms):
                中 = unicodedata.normalize("NFKC", m.group(1)).strip("（）() ")
                過去, _ = _例の確かめ.過去の結果を読む(中)   # 形の外れは 見る が同じ読みで返す（ここでは字を残す）
                for x in 過去:
                    中 = 中.replace(x["字"], " ")
                    尾 = 尾.replace(x["字"], " ", 1)
                書類, 番号, 元 = [x["字"] for x in 過去], [], []
                if _例の確かめ.過去の結果の印 in 中:   # 形に読めない過去の結果の字は書類に残して 見る で止める
                    書類.append(中.strip())
                    中 = ""
                # 、, で分けた片ごとに、問いの番号と適用の時期の注を抜いた残りを書類の名にする（書類の名の中の ・ では分けない＝
                # `8・9・10月分の支給控除一覧表` を答えの資料に当てる）。問いの番号を含む括弧の注（`（Q… の出し直し）`）だけは書類にしない
                for w in re.split(r"[、,，;；]", 中):
                    番号 += _番号の形.findall(w)
                    w = re.sub(rf"（[^（）]*{_鍵の字}[^（）]*）|\([^()]*{_鍵の字}[^()]*\)", "", w)   # 鍵の注の括弧だけ
                    元.append(w.strip(" ・"))   # 注を抜く前の字（抜き方の誤りで答えの名を消しても止める側へ）
                    w = _適用の注.sub("", _番号の形.sub("", w))
                    w = re.sub(r"・{2,}", "・", w).strip(" ・")
                    if w:
                        書類.append(w)
                out.append({"会社": 会社 or "", "項目": f"{名}#{見出し}", "NO": "", "書類の名": "、".join(書類),
                            "問いの番号": "、".join(dict.fromkeys(番号)), "確かめ": "", "新しい値": 行.strip(),
                            "所": f"{名} {n} 行目", "注を抜く前": [w for w in 元 if w]})
            out[頭]["注を抜く前"].append(尾)
    for タブ in ("確定した勤怠", "確定した勤怠の区間"):
        rows = (台帳 or {}).get(タブ) or []
        if rows and isinstance(rows[0], (list, tuple)):
            h = [str(x).strip() for x in rows[0]]
            rows = [dict(zip(h, r)) for r in rows[1:]]
        for n, r in enumerate(rows, 2):
            if 会社 is not None and _字(r.get("会社")) not in ("", 会社):
                continue
            番号 = _訳の問い.findall(_字(r.get("直した訳")))
            if 番号:
                out.append({"会社": _字(r.get("会社")), "項目": f"台帳/{タブ}", "NO": _字(r.get("NO")), "書類の名": "",
                            "問いの番号": "、".join(番号), "確かめ": "確認済", "新しい値": _字(r.get("直した訳")),
                            "所": f"台帳/{タブ} {n} 行目（{_字(r.get('日付'))}）"})
    return out


def _字(v) -> str:
    return str(v or "").strip()


def _表(x):
    """質問と回答 → 表（`質問と回答.読む` の戻りの表・タブの名 → 格子 の dict・空＝無し）。前の 1 枚の表の行の並びは止める。"""
    if isinstance(x, dict):
        return _質問と回答.読む(x)
    return _質問と回答.表で受ける(list(x) if isinstance(x, (list, tuple)) else x)


def _答えたち(*表たち) -> dict[str, str]:
    """表たち（後ろの表が勝つ）→ {問いの鍵: 答えの値}。問いの在る鍵だけ。答えは鍵ごとに一番下の行が正（送り直しは新しい行）。
    答えの無い問いは値 ""。値の読みは `前の答え.答えの芯`、結論の決まらない答え（不明・確認中 など）も "" にする。"""
    out: dict[str, str] = {}
    for t in 表たち:
        下 = {}
        for a in t.答えたち:
            下[a.鍵] = a.回答
        for q in t.問いたち:
            行 = {"回答": 下.get(q.鍵, "")}
            out[q.鍵] = "" if _前の答え.決まり切らない(行) else _前の答え.答えの芯(行)
    return out


_含みの短さ = 4   # 中に含むかで当てる答えの名の短さの下限（`縦` のような 1 字の名をほかの名の中に当てない）


def _答えの名を含むか(書類: str, 答え) -> bool:
    """書類の名が答えの資料の名（拡張子を除く）と同じか、それを中に含むか。止める側（`過去の結果が書類`）だけの見分け
    （含むかで当てるのは、答えの file を出所にした行を広く止めるため。過去の結果の資料の名を通す照らしには使わない）。"""
    幹 = _例の確かめ.資料の幹(書類)
    全 = _例の確かめ.字のそろえ.そろえる(書類, 大小も=False)   # 道の区切り（/・#）で切らない字でも当てる
    名たち = {_例の確かめ.資料の幹(x) for x in 答え}
    return any(h and any(a and (h == a or len(a) >= _含みの短さ and a in h) for a in 名たち) for h in (幹, 全))


def 答えの資料(答えの行) -> set[str]:
    """照らした答えの縦（行か dict）→ 答えの file の名の集まり。"""
    out = set()
    for r in 答えの行 or ():
        出所 = r.get("出所") if isinstance(r, dict) else getattr(r, "出所", "")
        if _名(出所):
            out.add(_名(出所))
    return out


def _照らしの一致(照らし) -> set[tuple[str, str, str, str]] | None:
    """照らしの結果（照合の段の 照らした物・その 字の形 の dict・差の表の 2 次元の並び〔1 行目が見出し〕）→
    差 0 の (支給月, 会社, NO, 項目) の集まり。None は渡していない。"""
    if 照らし is None:
        return None
    表 = getattr(照らし, "差の表", None)
    if 表 is None:
        表 = 照らし.get("差の表") if isinstance(照らし, dict) else 照らし
    return _例の確かめ.照らしの一致(表 or ())   # 差の表の読みの正本は 月次/例の確かめ（月次の 過去の結果 の照らしと同じ 1 つ）


def _過去の結果を照らす(字, 会社: str, 一致, 答えの出所) -> tuple[list[str], str]:
    """書類の名か出所の字 → (訳たち, 過去の結果の字を抜いた残り)。形の正本 `過去の結果を読む` で読み、照らしの結果で 1 つずつ確かめる。"""
    s = unicodedata.normalize("NFKC", _字(字))
    過去, 止め = _例の確かめ.過去の結果を読む(s)
    for x in 過去:
        s = s.replace(x["字"], " ")
    if 止め:
        return ["過去の結果の形が読めない"], s.replace(_例の確かめ.過去の結果の印, " ")
    if not 過去:
        return [], s
    if 一致 is None or 答えの出所 is None:
        return ["過去の結果を確かめられない"], s
    訳 = [f"過去の結果と{何}" if 何 == "一致していない" else f"過去の結果の{何}"
         for x in 過去 for 何, _, _, _ in _例の確かめ.過去の結果の外れ(x, 会社, 一致, 答えの出所)]
    return list(dict.fromkeys(訳)), s


def 見る(変更の記録, 答えの資料たち, 質問と回答=(), 会社: str | None = None, *, 事務所の質問と回答=(),
       md: dict | None = None, 台帳: dict | None = None, 照らし=None, 答えの行=None, 例=None) -> 見た物:
    """変更の記録の行 → 出所の外れ。答えの資料たち: 答えの file の名（`答えの資料` の返す物か名の並び）。
    質問と回答: その会社の質問と回答（表か タブの名 → 格子 の dict。問いの鍵を出所にした行があれば要る・無ければ止める）。
    会社: 渡せばその会社の行だけ見る。事務所の質問と回答: 00_事務所 の質問と回答（同じ形。会社の表に無い鍵を引く）。md・台帳: `出所の行たち` へ渡し、
    出た行を変更の記録の後ろに足して同じに見る（行の番号は変更の記録の続き・`所` に MD の行・台帳の行を書く）。
    照らし: 照合の段の照らしの結果（`照らした物`・差.json の dict・差の表）。答えの行: 照らした答えの行（読む の出す行）。
    この 2 つは過去の結果の照らしを出所にした行・例があれば要る（無ければ止める）。例: 例の行（月次/例の確かめ の
    `MDから例を読む` の返す物）。md の中の給与のルールの例の表も読み、確かめた人 の過去の結果の照らしを同じに見る。"""
    一致, 出所の表 = _照らしの一致(照らし), _答えの出所(答えの行)
    答え = {_名(x) for x in 答えの資料たち if _名(x)}
    会社の表, 事務所の表 = _表(質問と回答), _表(事務所の質問と回答)
    今の答え = _答えたち(事務所の表, 会社の表)   # 同じ鍵は会社の表が勝つ
    質問と回答 = bool(会社の表.問いたち or 事務所の表.問いたち)
    行たち = list(変更の記録 or ()) + 出所の行たち(md, 台帳, 会社)
    外れ, 見た = [], 0
    for i, r in enumerate(行たち, start=1):
        if 会社 is not None and _字(r.get("会社")) not in ("", 会社):
            continue
        if _字(r.get("確かめ")) == "記録だけ":
            continue
        見た += 1
        書類, 番号 = _字(r.get("書類の名")), _字(r.get("問いの番号"))
        基 = {"行の番号": i, "NO": _字(r.get("NO")), "項目": _字(r.get("項目")), "書類の名": 書類, "問いの番号": 番号,
              "字": _字(r.get("新しい値")), **({"所": r["所"]} if r.get("所") else {})}
        訳たち, 残り = _過去の結果を照らす(書類, _字(r.get("会社")) or 会社 or "", 一致, 出所の表)
        過去を書いた = 残り != unicodedata.normalize("NFKC", 書類)
        書類たち = [w for w in re.split(r"[、,]", 残り) if w.strip(" ・")]
        if any(_答えの名を含むか(w, 答え) for w in 書類たち + list(r.get("注を抜く前") or ())):
            訳たち.append("過去の結果が書類")   # 照らしの形で書かずに答えの file を出所にした（人×項目の一致を指していない）
        番号たち = [w for w in _番号の区切り.split(unicodedata.normalize("NFKC", 番号)) if w]
        if 番号たち and not 質問と回答:   # 問いが在るか・答えが来たか・見当が何からかを見る材料が無い＝進まない
            訳たち.append("問いを確かめられない")
        for no in 番号たち if 質問と回答 else ():
            if no not in 今の答え:
                訳たち.append("問いが無い")
            elif _答えの無い答え.fullmatch(今の答え[no]) and _字(r.get("確かめ")) == "確認済":
                訳たち.append("答えの無い問いが出所")
        訳たち = list(dict.fromkeys(訳たち))
        if not 書類たち and not 番号 and not 過去を書いた:
            訳たち.append("出所が無い")
        外れ += [dict(基, 訳=w) for w in 訳たち]
    # 例の 確かめた人 の過去の結果の照らし（出所の種類の形は 月次/例の確かめ が見る。ここは一致だけを見る）
    例たち = list(例 or ())
    for 名, 字 in (md or {}).items():
        例たち += _例の確かめ.MDから例を読む(字, 会社 or "_")   # 会社が空でない＝例の誤りを投げない（読めない表は 書けない の行）
    for e in 例たち:
        e会社 = _字(e.get("会社"))
        if 会社 is not None and e会社 not in ("", "_", 会社):
            continue
        人 = _字(e.get("確かめた人"))
        if _例の確かめ.過去の結果の印 not in unicodedata.normalize("NFKC", 人):
            continue
        見た += 1
        e会社 = 会社 or ("" if e会社 == "_" else e会社)
        訳たち = (_過去の結果を照らす(人, e会社, 一致, 出所の表)[0] if e会社 else ["過去の結果を確かめられない"])  # 会社が無い＝引けない
        外れ += [{"行の番号": "", "NO": "", "項目": f"例 {_字(e.get('例の番号'))}（{_例の確かめ.例の所(e)}）", "書類の名": 人,
                  "問いの番号": "", "字": 人, "所": "例の 確かめた人", "訳": w} for w in 訳たち]
    return 見た物(外れ=tuple(外れ), 見た行の数=見た, 止める=bool(外れ))
