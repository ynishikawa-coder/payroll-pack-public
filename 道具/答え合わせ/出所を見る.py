"""出所を見る（確かめと仮.md §1「確かめ方」）。初期設定の照らしの終わりに、マスタの値の出所に過去の結果（答え）が 0 かを見る。

初期設定の照らしは本番の 0 段の手順。照らしを終えて毎月の計算へ進む前に、マスタ「変更の記録」の各行の出所
（書類の名・問いの番号）が 原本・決まりの MD・質問と回答・**過去の結果の照らし**（人×項目で一致した事）のどれかで、
照らしで確かめていない過去の結果を出所とする値が 0 であることを見る。1 つでもあれば止める（`止める` が真）＝毎月へ進まない。

過去の結果の照らし（2026-11-19 オーナーの決定: 過去の資料で埋め切り、本当に分からない物だけ聞く）: 書類の名（MD の［出所］・例の
確かめた人 の出所も同じ）に過去の結果の照らしを書いた値は、渡した照らしの結果（`照らし`＝照合の段の差の表）でその支給月・会社・
人×項目の差が 0 で、答えの行（`答えの行`）のその人×項目の出所の file の名と書いた資料の名が字まで同じ時だけ通す。
文法と書き方の正本は 月次/例の確かめ.py の表 `出所の種類たち`（書き方は `過去の結果の書き方`。読みは `過去の結果を読む`・照らしは
`過去の結果の外れ`＝月次と同じ 1 つを呼び、写さない）。過去の結果を照らすのは道具だけ（芯は答えを見ない）。

止める行（どれも `外れ` に 1 行ずつ返す・黙って捨てない）:
- `過去の結果が書類`: 書類の名が照らした答えの file（答えの行の出所の file か、渡した答えの資料の名）。
- `答えの無い問いが出所`: 確かめ＝確認済 の値の問い（質問と回答の 1_問い の鍵）に、まだ答えが無い（2_答え に行が無い・空・分からない・
  結論が決まらない＝答えでなく見当で決めた値）。見当で置いた値（確かめ＝仮）は止めない＝仮が残る人は出口へ出ない決まりが守る。
- `出所が無い`: 書類の名も問いの番号も空（確かめ＝記録だけ の行は見ない）。
- `問いが無い`: 問いの番号の欄の鍵が質問と回答の 1_問い に無い。
- `問いを確かめられない`: 問いの番号を出所にした行があるのに、質問と回答を渡していない（材料が無い時は止める）。
- `過去の結果の形が読めない`: `過去の結果` の語があるのに表の文法に全体で当たらない（欠け・字の混ざり・区切りの変種）。
- `過去の結果を確かめられない`: 過去の結果の照らしを出所にした行があるのに、照らしの結果（か答えの行）を渡していない。
- `過去の結果と一致していない`: 書いた人×項目が照らしの差の表に無いか、差が 0 でない。
- `過去の結果の資料が違う`: 書いた資料の名が、その人×項目の答えの行の出所の file の名と字まで同じでない（含む・頭が では当てない）。
- `過去の結果の答えの行が食い違う`: その人×項目の答えの行が 2 つ以上在り、出所の資料が食い違う（どの資料の一致かを決めない）。
- 例（`例`・md の給与のルールの例の表）の 確かめた人 に書いた過去の結果の照らしも同じに見る（`例 <番号>` の行で返す）。

読み方:
- `過去の結果が書類` は止める側の見分けなので、書類の名が答えの資料の名（拡張子を除き 芯/字 の そろえる でそろえた字）と同じか、
  その字を中に含めば当てる（`（逆算）8〜10 月分の支給控除一覧表` は答えの資料 `8〜10月分の支給控除一覧表.pdf` に当たる）。
  通す側（過去の結果の資料の名）は含むかで当てない（`過去の結果の外れ` の字まで同じの照らし）。
- 問いの番号の欄（列の名は前のまま・中身は問いの鍵 `Q<数>`）は 、・, で並べてよい（1 つずつ引く）。会社の質問と回答に無い鍵は、
  渡せば事務所の質問と回答（00_事務所）から引く（同じ鍵は会社の表が勝つ）。質問と回答は 3 タブの表（`質問と回答.読む` の戻り
  か、タブの名 → 格子 の dict）で受ける。前の 1 枚の表（1_質問）の行の並びは読まずに止める。
- 変更の記録のほかに、決まりの MD の `［出所］`（`[出所]`）の行と、台帳（確定した勤怠・その区間）の 直した訳 の `問い:<番号>` を
  `出所の行たち` で同じ形の行にして、同じ照らしへ通せる（`見る` の md・台帳 を渡す）。

Drive を開かない。殻が読んだタブの行・格子と答えの file の名を受けて返すだけ。芯の計算は呼ばない。
"""
