@dataclass(frozen=True)
class 照らした物:
    差の表: tuple[tuple[str, ...], ...]   # 頭の行＋人×項目の行（出口/ の突き合わせの列のまま）
    問いの種: tuple[dict, ...]            # 差を初期設定の問いの種へ（設問.まとめる へ渡す・会社×項目×向き で 1 つ）
    人の状態: dict                        # (支給月, 会社, NO) → 一致・差あり・未突き合わせ
    外した人: tuple[dict, ...]            # 芯で仮が残り照らさなかった人
    照らさなかった項目: tuple[str, ...]   # 芯にあるが つなぎ に欄の無い項目
    照らさなかった月: tuple[tuple[str, str], ...]   # 芯にあるが答えの無い (支給月, 会社)
    要確認: tuple[str, ...]
    月の記録: tuple[dict, ...]            # 照らした 1 会社 1 支給月ごと（差0の月 の印つき）
    差0の月数: dict                       # 会社 → 続けて差 0 の月数・数えた月・まだ見ていない場面
    差の行の数: int = 0                   # 差の表のうち一致でない行（片方だけを含む）

    def 字の形(self) -> dict:
        """JSON へ書ける形（呼び口が使う）。"""
        return {
            "差の表": [list(r) for r in self.差の表],
            "差の行の数": self.差の行の数,
            "問いの種": [dict(q) for q in self.問いの種],
            "人の状態": [{"支給月": k[0], "会社": k[1], "NO": k[2], "状態": v} for k, v in sorted(self.人の状態.items())],
            "外した人": list(self.外した人),
            "照らさなかった項目": list(self.照らさなかった項目),
            "照らさなかった月": [{"支給月": m, "会社": c} for m, c in self.照らさなかった月],
            "要確認": list(self.要確認),
            "月の記録": [dict(r, 場面=list(r["場面"])) for r in self.月の記録],
            "差0の月数": {c: dict(v, 数えた月=list(v["数えた月"]), まだ見ていない場面=list(v["まだ見ていない場面"]))
                         for c, v in self.差0の月数.items()},
        }


def 答えのつなぎ(つなぎ) -> tuple[欄, ...]:
    """つなぎ（{項目, 欄, 形}）→ 答え相手の対応（渡さない・受ける）。"""
    return tuple(欄(項目=x.項目, 欄=x.欄, 形=x.形, 渡す=False, 受ける=True) for x in 対応にする(つなぎ))


def _Nの既定() -> int:
    """N を渡さない時は項目の辞書（初期設定/項目.json の 突き合わせ.差0の月数の目安）の既定＝道具は既定の数を持たない。"""
    return int(_型.項目("突き合わせ.差0の月数の目安")["既定"])


def 照らす(芯の行, 答え, つなぎ, 人の状態: dict | None = None, 給与ソフトが違うで閉じた: dict | None = None,
         場面: dict | None = None, 前の記録=(), N: int | None = None, 仮の人の行=()) -> 照らした物:
    """芯の計算の縦と答えの縦を照らす。

    芯の行: 芯/計算/ の出す人×項目の行（dict か 出口.行.行・状態つき）。仮の人は出口の関所で外れ、照らさない。
    答え: `答えの読み口` の返す 読んだ物（か 行 の並び）。その 要確認 は返す 要確認 の頭に載せる。
    つなぎ: 答えの読み口に渡した物と同じ 1 つ。
    人の状態: 芯の返す {(支給月, 会社, NO): 確認済|仮}（任意）。
    給与ソフトが違うで閉じた: {(会社, 支給月): 数}。答え相手の差の問いを「答えが違う」で閉じた数（任意・立ち上げの窓（殻）が質問と回答から数える）。
    場面: {(会社, 支給月): (入社・退社・年の変わり目・料率の変わる月 …)}（任意）。
    前の記録: 前に照らした 月の記録 の並び（続けて差 0 の月数を前の月から数える時）。
    仮の人の行: `月次.月を回す` の返す `仮の人の行`（関所で外した仮の人の人×項目の行）。渡せば、その人を外さず確定の行として照らす
      （初期設定の照らしは仮の人の額も過去の結果と照らす。照らしの結果は出口へ出ない）。同じ人の行が 芯の行 にも在れば 仮の人の行 が正。
    """
    if 仮の人の行:
        仮 = 行たちにする(仮の人の行)
        仮の人 = {r.人 for r in 仮}
        芯の行 = [*(r for r in 行たちにする(芯の行) if r.人 not in 仮の人), *(replace(r, 状態=確定) for r in 仮)]
        人の状態 = {k: ("確認済" if tuple(str(x) for x in k) in 仮の人 else v) for k, v in (人の状態 or {}).items()}
    答えの行 = 行たちにする(getattr(答え, "行たち", 答え))
    要確認 = list(getattr(答え, "要確認", ()))
    答えの月 = {(r.支給月, r.会社) for r in 答えの行}
    芯 = 行たちにする(芯の行)
    芯, 答えの行, 控除の外 = _控除の当たらない時間を外す(芯, 答えの行)
    照らす行 = [r for r in 芯 if (r.支給月, r.会社) in 答えの月]
    照らさない月 = sorted({(r.支給月, r.会社) for r in 芯 if (r.支給月, r.会社) not in 答えの月},
                     key=lambda k: (支給月の並び(k[0]), k[1]))
    状態 = {tuple(str(x) for x in k): v for k, v in (人の状態 or {}).items() if (str(k[0]), str(k[1])) in 答えの月}
    対応 = 答えのつなぎ(つなぎ)
    通 = 通す(照らす行, 状態)
    結果 = _突.突き合わせる(通, 答えの行, 対応)
    閉じた = {(str(c), m): n for (c, m), n in (給与ソフトが違うで閉じた or {}).items()}
    場面 = {(str(c), m): v for (c, m), v in (場面 or {}).items()}
    記録 = tuple(_突.月の記録(結果, 会社, 月, 閉じた.get((会社, 月), 0), 場面.get((会社, 月), ()))
               for 月, 会社 in sorted(答えの月, key=lambda k: (支給月の並び(k[0]), k[1])))
    今の鍵 = {(r["会社"], r["支給月"]) for r in 記録}
    前 = [r for r in 前の記録 if (str(r["会社"]), r["支給月"]) not in 今の鍵]
    return 照らした物(
        差の表=tuple(結果.表()),
        問いの種=tuple(問いの種(結果.差の行(), 答えの行, つなぎ)),
        人の状態=dict(結果.人の状態),
        外した人=tuple(x.行() for x in 結果.外した人),
        照らさなかった項目=結果.照らさなかった項目 + 控除の外,
        照らさなかった月=tuple(照らさない月),
        要確認=tuple(要確認) + 結果.要確認,
        月の記録=記録,
        差0の月数=_突.続けて差0の月数(list(前) + list(記録), _Nの既定() if N is None else N),
        差の行の数=len(結果.差の行()),
    )


# 控除の額の元の時間の語 → その控除の項目（芯の行の名）。控除が当たらない人（控除の行が 0 か無い）の時間は額に効かない＝照らさない
# （時給の人の 遅刻早退＝欠勤.遅刻早退の控除 が 月給の人だけ引く。芯/集計 はその人の不足も数えるが、給与ソフトは欄を持たない）
控除の元の時間 = {"遅刻早退": "遅刻早退控除"}


def _控除の当たらない時間を外す(芯, 答えの行):
    """芯の行で、時間の語（遅刻早退）が 0 でないのに対の控除（遅刻早退控除）が 0 か無い人の、その時間の行を芯と答えの両方から外す。
    → (芯, 答えの行, 照らさなかった項目に足す字)。芯の数は変えない（照らす行を選ぶだけ）。"""
    控除 = {(r.支給月, r.会社, r.NO, r.項目): r.値 for r in 芯}
    外す = set()
    for r in 芯:
        対 = 控除の元の時間.get(r.項目)
        if 対 and r.値 and not 控除.get((r.支給月, r.会社, r.NO, 対)):
            外す.add((r.支給月, r.会社, r.NO, r.項目))
    if not 外す:
        return 芯, 答えの行, ()
    字 = tuple(f"{語}（控除の当たらない人: {'・'.join(sorted({k[2] for k in 外す if k[3] == 語}))}）"
              for 語 in sorted({k[3] for k in 外す}))
    return ([r for r in 芯 if (r.支給月, r.会社, r.NO, r.項目) not in 外す],
            [r for r in 答えの行 if (r.支給月, r.会社, r.NO, r.項目) not in 外す], 字)


# ── 差 → 初期設定の問いの種（設問.まとめる の 4 つの箱の形・読み方の箱） ──

照らしの印 = "読み方: 照らし/"   # 種の 何が無いか の頭（会社×項目×向き で 1 つ＝同じ違いを月をまたいで聞き直さない）
_根拠の上限 = 3
# 選択肢と、その答えで変わる事（確認ページの「この答えで変わる事」）。どちらにもおすすめの印は付けない
_選択肢 = {
    "値が違う": (("会社の決まりで払っていた", "その決まりを給与のルールとマスタに書き、次の計算から決まりどおりに計算します"),
                ("過去の支給が誤りだった", "法律どおりの計算のまま払います（過去の支給は直しません）")),
    "過去だけ": (("会社の決まりで払っていた", "その項目の決まりを給与のルールとマスタに足し、次の計算から払います"),
                ("その月だけの払いだった", "決まりにせず、払う月にその月だけの物として伺います")),
    "こちらだけ": (("払わない決まりだった", "その決まりを給与のルールとマスタに書き、次の計算から払いません"),
                  ("過去の支給が漏れていた", "法律どおりの計算のまま払います（過去の支給は直しません）")),
}


def _字(v: Decimal) -> str:
    v = v.normalize()
    return str(int(v)) if v == v.to_integral_value() else format(v, "f")


def _形の字(v, 形: str) -> str:
    if v is None:
        return "無し"
    if 形 == "分":
        h, m = divmod(int(v), 60)
        return f"{h}:{m:02d}"
    return _字(v) + (形 if 形 in ("円", "日", "回") else "")


def _資料(出所: str) -> tuple[str, str]:
    """答えの行の出所（`file` か `file#タブ`）→ (資料の名, タブ)。"""
    f, _, t = str(出所).partition("#")
    return f, t


def 問いの種(差の行たち, 答えの行, つなぎ) -> list[dict]:
    """突き合わせの差の行 → 初期設定の問いの種（`設問.まとめる` の種の形）。同じ 会社 × 項目 × 見立て の差は 1 つにまとめる。

    答えの行: 照らした答えの縦（出所＝答えの file と タブ）。つなぎ: 答えの見出しと項目の対応（根拠の場所に欄の名を書く）。"""
    欄の名 = {x.項目: (x.欄, x.形) for x in 対応にする(つなぎ)}
    答えの出所 = {(r.支給月, r.会社, r.NO, r.項目): r.出所 for r in 答えの行}
    # 束ねる鍵は 何が無いか と同じ 会社×項目×向き（見立ては束の中に並べる。鍵が 何が無いか より細かいと
    # 設問.まとめる が同じ 何が無いか の 2 つ目を落とし、その差が聞かれない）。束の中は差の大きい順（見せる値は一番大きい差）
    組: dict[tuple, list] = {}
    for r in 差の行たち:
        向き = "過去だけ" if r.こちら is None else "こちらだけ" if r.給与ソフト is None else "値が違う"
        組.setdefault((r.会社, r.項目, 向き), []).append(r)
    out = []
    for (会社, 項目, 向き), rs in 組.items():
        rs = sorted(rs, key=lambda r: -abs(r.差) if r.差 is not None else 0)
        見立て = "・".join(dict.fromkeys(r.差の見立て for r in rs))
        欄, 形 = 欄の名.get(項目, (項目, "円"))
        人 = list(dict.fromkeys(r.NO for r in rs))
        月たち = list(dict.fromkeys(r.支給月 for r in rs))
        根拠, 資料たち = [], []
        for r in rs:
            f, t = _資料(答えの出所.get((r.支給月, r.会社, r.NO, r.項目), ""))
            if not f:
                continue
            資料たち.append(f)
            if len(根拠) < _根拠の上限:
                根拠.append({"資料": f, "場所": f"{'タブ ' + t + '・' if t else ''}NO {r.NO} の行「{欄}」の欄",
                           "原文": _形の字(r.給与ソフト, 形) if r.給与ソフト is not None else "空欄"})
        if not 資料たち:   # 答えの無い差（こちらだけで答えの file にも行が無い）＝読んだ答えの一覧のどれか
            資料たち = sorted({_資料(x)[0] for x in 答えの出所.values() if _資料(x)[0]})[:1]
            if 資料たち:
                根拠.append({"資料": 資料たち[0], "場所": f"NO {rs[0].NO} の行", "原文": f"「{欄}」の欄が無い"})
        r0 = rs[0]
        こ, 答 = _形の字(r0.こちら, 形), _形の字(r0.給与ソフト, 形)
        if 向き == "値が違う":
            質問 = f"{項目}が、法律どおりの計算と過去の支給とで違います。どちらですか"
            見つけた = f"過去の支給は {答}、法律どおりの計算は {こ} です"
            読み = f"法律どおりに{項目}を {こ} と数えた→過去の支給は {答} で、会社の決まりが違うのかが決まらない"
        elif 向き == "過去だけ":
            質問 = f"{項目}が、過去の支給にはあり、今の決まりにはありません。どちらですか"
            見つけた = f"過去の支給に {項目} {答} があります"
            読み = f"過去の支給に{項目} {答} がある→今の決まりの書類にこの払いが無く、決まりがあるのかが決まらない"
        else:
            質問 = f"{項目}が、法律どおりの計算にはあり、過去の支給にはありません。どちらですか"
            見つけた = f"法律どおりの計算では {項目} {こ} です"
            読み = f"法律どおりに{項目}を {こ} と数えた→過去の支給にこの払いが無く、払わない決まりかが決まらない"
        選 = _選択肢[向き]
        out.append({
            "箱": "読み方", "会社": 会社,
            "何が無いか": f"{照らしの印}「{項目}」/{向き}",
            "質問": 質問,
            "答え方の例": "／".join(w for w, _ in 選),
            "変わる事": {w: v for w, v in 選},
            "分かっている事": [見つけた + (f"（ほか {len(人) - 1} 人・" if len(人) > 1 else "（1 人・") + f"{'、'.join(月たち)} 支給）"],
            "くわしく": [f"違いの見立て: {見立て}。" + (f"法律どおりの値の出所: {r0.差の出所}。" if r0.こちら is not None else "")
                         + "答えをいただくまで決まりにはしません。"],
            "見当": "", "見当の拠り所": "無し",
            "人": 人, "変わる項目": [項目],
            "答えで変わる項目と人": "、".join([項目, *人]),
            "資料": list(dict.fromkeys(資料たち)),
            "根拠": 根拠, "読み": 読み,
            "反映先": "",
        })
    return out
