"""照合の段（確かめと仮.md §1・§2）。芯の計算の縦と答えの縦を、出口/ の突き合わせ 1 本へ渡すだけ。

- 照らし方を別に持たない: `出口.関所.通す` → `出口.突き合わせ.突き合わせる` → `月の記録` → `続けて差0の月数`。
- 答えには何も「渡していない」ので、つなぎ の欄は全部 `渡す=False・受ける=True` にして渡す
  （差の見立ては `入力の違い` にならず、`丸め`・`決まりの違い`・`片方だけ` のどれか）。
- 答えのある 支給月×会社 だけを照らす。芯の行で答えの無い月は `照らさなかった月` に返す。
- 差は 0 だけを一致。差のある行は問い（質問と回答へ回す行）にして返す。**差を見てマスタや計算を直さない。**
- 芯/ を書き換えない・芯/ と 出口/ から呼ばれない（開発の間だけの道具）。Drive を開かない。
"""
from __future__ import annotations

from dataclasses import dataclass

from 出口 import 突き合わせ as _突
from 出口.形 import 欄, 対応にする
from 出口.行 import 支給月の並び, 行たちにする
from 出口.関所 import 通す


@dataclass(frozen=True)
class 照らした物:
    差の表: tuple[tuple[str, ...], ...]   # 頭の行＋人×項目の行（出口/ の突き合わせの列のまま）
    問い: tuple[dict, ...]                # 差を質問と回答へ回す行（同じ見立て・同じ出所は 1 問）
    人の状態: dict                        # (支給月, 会社, NO) → 一致・差あり・未突き合わせ
    外した人: tuple[dict, ...]            # 芯で仮が残り照らさなかった人
    照らさなかった項目: tuple[str, ...]   # 芯にあるが つなぎ に欄の無い項目
    照らさなかった月: tuple[tuple[str, str], ...]   # 芯にあるが答えの無い (支給月, 会社)
    要確認: tuple[str, ...]
    月の記録: tuple[dict, ...]            # 照らした 1 会社 1 支給月ごと（差0の月 の印つき）
    差0の月数: dict                       # 会社 → 続けて差 0 の月数・数えた月・まだ見ていない場面
    差の行の数: int = 0                   # 差の表のうち一致でない行（片方だけを含む）

    def 字の形(self) -> dict:
        """JSON へ書ける形（呼び口が使う）。"""
        return {
            "差の表": [list(r) for r in self.差の表],
            "差の行の数": self.差の行の数,
            "問い": [{k: (list(map(list, v)) if k == "行" else list(v) if isinstance(v, tuple) else v)
                     for k, v in q.items()} for q in self.問い],
            "人の状態": [{"支給月": k[0], "会社": k[1], "NO": k[2], "状態": v} for k, v in sorted(self.人の状態.items())],
            "外した人": list(self.外した人),
            "照らさなかった項目": list(self.照らさなかった項目),
            "照らさなかった月": [{"支給月": m, "会社": c} for m, c in self.照らさなかった月],
            "要確認": list(self.要確認),
            "月の記録": [dict(r, 場面=list(r["場面"])) for r in self.月の記録],
            "差0の月数": {c: dict(v, 数えた月=list(v["数えた月"]), まだ見ていない場面=list(v["まだ見ていない場面"]))
                         for c, v in self.差0の月数.items()},
        }


def 答えのつなぎ(つなぎ) -> tuple[欄, ...]:
    """つなぎ（{項目, 欄, 形}）→ 答え相手の対応（渡さない・受ける）。"""
    return tuple(欄(項目=x.項目, 欄=x.欄, 形=x.形, 渡す=False, 受ける=True) for x in 対応にする(つなぎ))


def 照らす(芯の行, 答え, つなぎ, 人の状態: dict | None = None, 給与ソフトが違うで閉じた: dict | None = None,
         場面: dict | None = None, 前の記録=(), N: int = 3) -> 照らした物:
    """芯の計算の縦と答えの縦を照らす。

    芯の行: 芯/計算/ の出す人×項目の行（dict か 出口.行.行・状態つき）。仮の人は出口の関所で外れ、照らさない。
    答え: `答えの読み口` の返す 読んだ物（か 行 の並び）。その 要確認 は返す 要確認 の頭に載せる。
    つなぎ: 答えの読み口に渡した物と同じ 1 つ。
    人の状態: 芯の返す {(支給月, 会社, NO): 確認済|仮}（任意）。
    給与ソフトが違うで閉じた: {(会社, 支給月): 数}。答え相手の差の問いを「答えが違う」で閉じた数（任意・開発の窓が質問と回答から数える）。
    場面: {(会社, 支給月): (入社・退社・年の変わり目・料率の変わる月 …)}（任意）。
    前の記録: 前に照らした 月の記録 の並び（続けて差 0 の月数を前の月から数える時）。
    """
    答えの行 = 行たちにする(getattr(答え, "行たち", 答え))
    要確認 = list(getattr(答え, "要確認", ()))
    答えの月 = {(r.支給月, r.会社) for r in 答えの行}
    芯 = 行たちにする(芯の行)
    照らす行 = [r for r in 芯 if (r.支給月, r.会社) in 答えの月]
    照らさない月 = sorted({(r.支給月, r.会社) for r in 芯 if (r.支給月, r.会社) not in 答えの月},
                     key=lambda k: (支給月の並び(k[0]), k[1]))
    状態 = {tuple(str(x) for x in k): v for k, v in (人の状態 or {}).items() if (str(k[0]), str(k[1])) in 答えの月}
    対応 = 答えのつなぎ(つなぎ)
    通 = 通す(照らす行, 状態)
    結果 = _突.突き合わせる(通, 答えの行, 対応)
    閉じた = {(str(c), m): n for (c, m), n in (給与ソフトが違うで閉じた or {}).items()}
    場面 = {(str(c), m): v for (c, m), v in (場面 or {}).items()}
    記録 = tuple(_突.月の記録(結果, 会社, 月, 閉じた.get((会社, 月), 0), 場面.get((会社, 月), ()))
               for 月, 会社 in sorted(答えの月, key=lambda k: (支給月の並び(k[0]), k[1])))
    今の鍵 = {(r["会社"], r["支給月"]) for r in 記録}
    前 = [r for r in 前の記録 if (str(r["会社"]), r["支給月"]) not in 今の鍵]
    return 照らした物(
        差の表=tuple(結果.表()),
        問い=結果.問い,
        人の状態=dict(結果.人の状態),
        外した人=tuple(x.行() for x in 結果.外した人),
        照らさなかった項目=結果.照らさなかった項目,
        照らさなかった月=tuple(照らさない月),
        要確認=tuple(要確認) + 結果.要確認,
        月の記録=記録,
        差0の月数=_突.続けて差0の月数(list(前) + list(記録), N),
        差の行の数=len(結果.差の行()),
    )
