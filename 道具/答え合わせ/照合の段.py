"""照合の段（確かめと仮.md §1 初期設定の照らし・§2）。芯の計算の縦と答え（過去の結果）の縦を、出口/ の突き合わせ 1 本へ渡し、
違う所を初期設定の問いの種（`初期設定/設問.py` の 4 つの箱の形）にして返す。本番の 0 段の手順（会社の始めと決まりが変わった時）。

- 照らし方を別に持たない: `出口.関所.通す` → `出口.突き合わせ.突き合わせる` → `月の記録` → `続けて差0の月数`。
- 答えには何も「渡していない」ので、つなぎ の欄は全部 `渡す=False・受ける=True` にして渡す
  （差の見立ては `入力の違い` にならず、`丸め`・`決まりの違い`・`片方だけ` のどれか）。
- 答えのある 支給月×会社 だけを照らす。芯の行で答えの無い月は `照らさなかった月` に返す。
- 差は 0 だけを一致。差のある行は **問いの種**（読み方の箱・会社の決まり）にして返す。殻はそれを `設問.まとめる` の種へ足し、
  ほかの種と 1 枚にまとめて `確認ページ.作る` で聞く（問いの道は設問と確認ページの 1 本）。**差を見てマスタや計算を直さない。**
- 種は 1 会社 × 項目 × 向き（値が違う・過去だけ・こちらだけ）で 1 つ（人・月・見立ては束ねる）。根拠＝答えの file と欄・値の字（実物）・読み（法律どおりの値と過去の値）を
  持たせる（`設問.まとめる` は根拠の無い種を差し戻す）。過去の値は見込みにしない（見当を置かない＝答えまで法律どおり）。
- 芯/ を書き換えない・芯/ と 出口/ と 入口/ から呼ばれない（芯に混ぜない）。Drive を開かない。
"""
from __future__ import annotations

