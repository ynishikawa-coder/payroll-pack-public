def _変更の記録を照らす(r: _結果, マスタの格子, 名から, 物) -> None:
    マスタ = 型の口.名("マスタ")
    D = 型の口.タブの名(マスタ, "変更の記録")
    本 = 型の口.タブの本(マスタ, "変更の記録")
    h, 行 = マスタの格子.get("変更の記録", ([], []))
    シート = 物.get(本)
    見た = {}
    知る: dict[str, set] = {}
    for x in 行:
        c = x.get(鍵, "")
        項目, v, 確 = x.get("項目", ""), x.get("適用支給月", ""), x.get("確かめ", "")
        同じ = tuple(x.get(k, "") for k in h if k)
        if 同じ in 見た:
            r.誤り(c, "前の名の記録", f"同じ行が 2 つ（{見た[同じ]} 行目と同じ）")
            r.案(c, "消す物", {"本": 本, "タブ": D, "行": x["_行"], "訳": f"{見た[同じ]} 行目と全部の列が同じ"},
                 _行の当て(シート, D, x))
            continue
        見た[同じ] = x["_行"]
        if 段の解決.効く月の直しか(項目):
            continue
        セル = f"{_列の字(h, '適用支給月')}{x['_行']}"
        if 項目 in 控.保険料の月で書く項目:
            if v and 控.保険料の月の字(v) is None:
                ym = 支給月の字.読む(v)
                徴 = _徴収(c, x.get("社員ID", ""), マスタの格子)
                r.誤り(c, "適用支給月の字", f"{項目}: 「{v}」（保険料の月 YYYY.MM分 で書く）")
                if ym and 徴 in 控.徴収の月の語:
                    y, m = 控.保険料の月(*ym, 徴)
                    r.案(c, "書く物", {"本": 本, "タブ": D, "セル": セル, "列": "適用支給月", "前": v, "値": f"{y:04d}.{m:02d}分"},
                         _行のセルの当て(シート, D, セル, x))
                else:
                    r.案(c, "問う物", {"本": 本, "タブ": D, "行": x["_行"], "列": "適用支給月", "前": v,
                                      "問い": "保険料の月（YYYY.MM分）はいつか（社保.徴収の月が決まらない）"})
        elif v and not 支給月の字.その形か(v, "殻"):
            殻 = _殻(v)
            r.誤り(c, "適用支給月の字", f"{項目}: 「{v}」")
            if 殻:
                r.案(c, "書く物", {"本": 本, "タブ": D, "セル": セル, "列": "適用支給月", "前": v, "値": 殻},
                     _行のセルの当て(シート, D, セル, x))
            else:
                r.案(c, "問う物", {"本": 本, "タブ": D, "行": x["_行"], "列": "適用支給月", "前": v, "問い": "適用支給月（読めない字）"})
        if 確 not in 段の解決.読み飛ばす確かめ:
            if c not in 知る:
                知る[c] = _知っている名(c, マスタの格子)
            if 項目 and 段の解決._知らない名か(項目, 知る[c]):
                r.誤り(c, "前の名の記録", 項目)
                セル = f"{_列の字(h, '確かめ')}{x['_行']}"
                r.案(c, "書く物", {"本": 本, "タブ": D, "セル": セル, "列": "確かめ",
                                  "前": 確, "値": 段の解決.記録だけ, "訳": f"前の名「{項目}」（今の名の打ち間違いなら名を直す）"},
                     _行のセルの当て(シート, D, セル, x))


_年月 = re.compile(r"(\d{4})[-/.年](\d{1,2})")


def _質問と回答を照らす(口, 物, r: _結果) -> None:
    シート = 型の口.名("質問と回答")
    本 = 型の口.Driveの名("質問と回答")
    if 本 not in 物:
        r.誤り(事務所, "本が無い", 本)
        return
    i = 物[本]
    ts = 口.タブを並べる(i)
    g = {t: _読む(口, i, シート, t, ts, r, 事務所) for t in ("問い", "答え", "振り分け")}
    if any(v is None for v in g.values()):
        return
    hq, 問い = _行たち(g["問い"])
    _, 答え = _行たち(g["答え"])
    _, 振り = _行たち(g["振り分け"])
    D = {t: 型の口.タブの名(シート, t) for t in g}
    誰 = {x.get("問いの鍵", ""): x.get(鍵, "") for x in [*問い, *振り]}
    for x in 問い:
        v = x.get("聞いた支給月", "")
        if re.fullmatch(r"\d{4}-\d{2}", v):
            continue
        c = x.get(鍵, "") or 事務所
        m = _年月.match(unicodedata.normalize("NFKC", x.get("聞いた日", "")))
        r.誤り(c, "聞いた支給月", f"「{v}」")
        if m:
            セル = f"{_列の字(hq, '聞いた支給月')}{x['_行']}"
            r.案(c, "書く物", {"本": 本, "タブ": D["問い"], "セル": セル,
                              "列": "聞いた支給月", "前": v, "値": f"{int(m[1]):04d}-{int(m[2]):02d}", "訳": "聞いた日の年月"},
                 _行のセルの当て(i, D["問い"], セル, x))
        else:
            r.案(c, "問う物", {"本": 本, "タブ": D["問い"], "行": x["_行"], "列": "聞いた支給月", "前": v, "問い": "聞いた日が読めない"})
    値 = {}
    for x in 振り:
        値.setdefault(x.get("問いの鍵", ""), set()).add(x.get("値", ""))
    for x in 答え:
        k = x.get("問いの鍵", "")
        if x.get("回答") and x.get("回答") in 値.get(k, set()) and not x.get("答えの原本へのリンク"):
            c = 誰.get(k) or 事務所
            r.誤り(c, "答えに振り分け")
            r.案(c, "消す物", {"本": 本, "タブ": D["答え"], "行": x["_行"], "訳": "回答が振り分けの値の写し（原本へのリンクが無い）"},
                 _行の当て(i, D["答え"], x))


def 誤りの数(結果: dict) -> int:
    return sum(e["件数"] for v in 結果.values() for e in v["誤り"])


