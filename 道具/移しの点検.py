class 読む口:
    """Drive口 を読むだけに絞る（書く口を持たない）。呼ぶたびに 間 秒あける（1 分 60 回の上限の内）。"""

    def __init__(self, 口, 間: float = 0.0, 眠る=time.sleep) -> None:
        self._口, self._間, self._眠る, self.回数 = 口, 間, 眠る, 0

    def _打つ(self, f, *a):
        if self.回数 and self._間:
            self._眠る(self._間)
        self.回数 += 1
        return f(*a)

    def 子を並べる(self, i):
        return self._打つ(self._口.子を並べる, i)

    def タブを並べる(self, i):
        return self._打つ(self._口.タブを並べる, i)

    def 表を読む(self, i, 範囲):
        return self._打つ(self._口.表を読む, i, 範囲)


def _字(v) -> str:
    return "" if v is None else str(v).strip()


def _行たち(格子) -> tuple[list[str], list[dict]]:
    """格子 → (見出し, [{列: 字, "_行": 行目, "_生": 読んだままの行}])。空の行は外す。"""
    格子 = list(格子 or [])
    if not 格子:
        return [], []
    h = [_字(x) for x in 格子[0]]
    out = []
    for n, r in enumerate(格子[1:], 2):
        if any(_字(v) for v in r):
            out.append({**{c: _字(r[i]) if i < len(r) else "" for i, c in enumerate(h) if c}, "_行": n, "_生": list(r)})
    return h, out


def _列の字(h: list[str], 列: str) -> str:
    return 管理表.列の字(h.index(列)) if 列 in h else ""


class _結果:
    def __init__(self, 当てる用: bool = False) -> None:
        self.会社: dict[str, dict] = {}
        self.当てる用 = 当てる用

    def 箱(self, 顧客ID: str) -> dict:
        return self.会社.setdefault(顧客ID or 事務所, {"誤り": {}, "書く物": [], "消す物": [], "問う物": []})

    def 誤り(self, 顧客ID, 種, 訳=None):
        e = self.箱(顧客ID)["誤り"].setdefault(種, {"件数": 0, "訳": []})
        e["件数"] += 1
        if 訳 and 訳 not in e["訳"] and len(e["訳"]) < 20:
            e["訳"].append(訳)

    def 案(self, 顧客ID, 何, x, 当て=None):
        if self.当てる用 and 当て is not None:
            x = {**x, "_当て": 当て}
        self.箱(顧客ID)[何].append(x)

    def 出す(self) -> dict:
        out = {}
        for k in sorted(self.会社, key=lambda x: (x == 事務所, x)):
            v = self.会社[k]
            out[k] = {"誤り": [{"種": s, **e} for s, e in v["誤り"].items()],
                      "書く物": v["書く物"], "消す物": v["消す物"], "問う物": v["問う物"]}
        return out


def _読む(口, シートid, シート, タブ, タブたち, r: _結果, 顧客ID) -> list[list] | None:
    try:
        return 置き場の口.タブを読む(口, シートid, シート, タブ, タブたち)
    except 置き場の口.引けない as e:
        r.誤り(顧客ID, "型のタブが無い", str(e))
        return None


def _殻(v: str) -> str | None:
    return 支給月の字.そろえる(v, "殻") if v else None


def _月の名(年: int, 月: int, ずれ: int) -> str:
    分 = (年 * 12 + 月 - 1 - ずれ) % 12 + 1
    try:
        return 支給月の字.字にする(年, 月, "置き場", 月分=分)
    except ValueError:
        return f"{年:04d}.{月:02d}支給（{分}月分）"


def _月を足す(y, m, n):
    k = y * 12 + m - 1 + n
    return k // 12, k % 12 + 1


def _セルの当て(シートid: str, タブ: str, セル: str, 格子) -> dict:
    """書く物 1 つを当てる値: シート・Drive のタブ・セル・行（1 起点）・その行の読んだままの字（当てる前に今の行と照らす）。"""
    n = int(re.sub(r"\D", "", セル))
    g = list(格子 or [])
    return {"シート": シートid, "タブ": タブ, "セル": セル, "行": n, "読んだ行": list(g[n - 1]) if n <= len(g) else []}


def _行の当て(シートid: str, タブ: str, x: dict) -> dict:
    """消す物 1 つを当てる値: シート・Drive のタブ・行（1 起点）・その行の読んだままの字（全部の列が今と同じ時だけ消す）。"""
    return {"シート": シートid, "タブ": タブ, "行": x["_行"], "読んだ行": list(x["_生"])}


def _行のセルの当て(シートid: str, タブ: str, セル: str, x: dict) -> dict:
    return {"シート": シートid, "タブ": タブ, "セル": セル, "行": x["_行"], "読んだ行": list(x["_生"])}


def 点検(口, 根id: str, *, 当てる用: bool = False) -> dict:
    """事務所の根を読むだけで照らす → {顧客ID か 事務所: {誤り, 書く物, 消す物, 問う物}}。口は読む口だけを使う。
    当てる用=True なら案に `_当て` を付ける（道具/移しを当てる.py だけが使う・字に出さない）。"""
    r = _結果(当てる用)
    設定 = 型の口.名("事務所の設定")
    物 = 置き場の口.事務所の物(口, 根id)
    設定id = 物[型の口.Driveの名("事務所の設定")]
    タブたち = 口.タブを並べる(設定id)
    置き場の格子 = 置き場の口.タブを読む(口, 設定id, 設定, "置き場", タブたち)
    一覧の格子 = 置き場の口.タブを読む(口, 設定id, 設定, "会社の一覧", タブたち)
    for t, m in 型の口.置き場の登録の赤(置き場の格子, 一覧の格子):
        r.誤り(事務所, "置き場の登録", f"{t}: {m}")
    置き場, _ = 型の口.登録の表を読む(置き場の格子, "置き場")
    一覧, _ = 型の口.登録の表を読む(一覧の格子, "会社の一覧")
    名から = {x["会社"]: x[鍵] for x in 一覧}
    for x in 一覧:
        r.箱(x[鍵])

    # 事務所の本（マスタ・変更の記録・管理表・質問と回答）
    マスタ = 型の口.名("マスタ")
    マスタの格子 = {}
    for タブ in ("社員", "会社", "支給控除の項目", "人ごとの支給控除", "変更の記録"):
        本 = 型の口.タブの本(マスタ, タブ)
        if 本 not in 物:
            r.誤り(事務所, "本が無い", 本)
            continue
        if 本 not in マスタの格子:
            マスタの格子[本] = 口.タブを並べる(物[本])
        g = _読む(口, 物[本], マスタ, タブ, マスタの格子[本], r, 事務所)
        マスタの格子[タブ] = _行たち(g) if g is not None else ([], [])
    管 = {}
    if "管理表" in 物:
        ts = 口.タブを並べる(物["管理表"])
        for タブ in ("月の状況", "会社"):
            D = 管理表.Driveのタブ(タブ)
            if D in ts:
                管[タブ] = 口.表を読む(物["管理表"], f"'{D}'!A1:ZZ")
            else:
                r.誤り(事務所, "型のタブが無い", f"管理表 に「{D}」タブが無い")
    else:
        r.誤り(事務所, "本が無い", "管理表")

    # 会社ごとの 月のフォルダ と 台帳
    月たち = []
    台帳の支給月: dict[str, set] = {}
    for x in 一覧:
        c = x[鍵]
        mine = {p["物"]: p["ID"] for p in 置き場 if p[鍵] == c}
        台帳の支給月[c] = set()
        for 物の名, i in sorted(mine.items()):
            if 型の口.台帳の名か(物の名):
                _台帳を照らす(口, i, 物の名, c, r, 台帳の支給月[c], マスタの格子)
        if "3_月ごと" in mine or 型の口.名("月ごと") in mine:
            fid = mine.get(型の口.名("月ごと")) or mine.get("3_月ごと")
            月たち += _月のフォルダを照らす(口, fid, x, r, 台帳の支給月[c])

    # 管理表（月の段）: 状態の空・月の状況の行
    if "月の状況" in 管:
        try:
            手順 = 管理表.月の段({"会社の一覧": 一覧の格子, "会社": 管.get("会社"), "今の値": 管["月の状況"],
                                "月たち": 月たち, "今日": ""})
        except 管理表.拒む as e:
            r.誤り(事務所, "月の段が拒む", str(e))
            手順 = []
        行目 = {x["_行"]: x[鍵] for x in 一覧}
        for s in 手順:
            if s["する"] == "値を書く":
                c = 行目.get(int(re.sub(r"\D", "", s["セル"])), 事務所)
                r.誤り(c, "状態が空")
                r.案(c, "書く物", {"本": s["ファイル"], "タブ": s["タブ"], "セル": s["セル"], "列": "状態",
                                  "前": "", "値": s["値"], "道": "管理表.py 月の段"},
                     _セルの当て(設定id, s["タブ"], s["セル"], 一覧の格子))
            else:
                v = dict(zip(管理表.今の見出し("月の状況", 管["月の状況"]), s["値"]))
                c = 名から.get(v.get("会社"), 事務所)
                r.誤り(c, "月の状況の行が無い", v.get("支給月"))
                r.案(c, "書く物", {"本": "管理表", "タブ": 管理表.Driveのタブ("月の状況"), "する": "行を足す",
                                  "支給月": v.get("支給月"), "道": "管理表.py 月の段"},
                     {"シート": 物["管理表"], "タブ": 管理表.Driveのタブ("月の状況"), "足す行": list(s["値"]),
                      "読んだ表": [list(x) for x in 管["月の状況"]]})

    _変更の記録を照らす(r, マスタの格子, 名から, 物)
    _質問と回答を照らす(口, 物, r)
    return r.出す()


def _知っている名(c: str, マスタの格子) -> set:
    社員 = [x for x in マスタの格子.get("社員", ([], []))[1] if x.get(鍵) == c]
    部品 = [x for t in ("支給控除の項目", "人ごとの支給控除") for x in マスタの格子.get(t, ([], []))[1] if x.get(鍵) == c]
    h = マスタの格子.get("社員", ([], []))[0]
    return ({it["項目"] for it in 型の口.項目たち()} | set(段の解決.社員の列の名) | set(h) | {x.get("項目", "") for x in 部品}
            | set(段の解決.入力の名たち())) - {""}


def _台帳を照らす(口, i, 物の名, c, r: _結果, 支給月たち: set, マスタの格子) -> None:
    シート = 型の口.名("台帳")
    タブたち = 口.タブを並べる(i)
    勤怠の月, 締めた月 = set(), set()
    for タブ in 台帳のタブ:
        g = _読む(口, i, シート, タブ, タブたち, r, c)
        if g is None:
            continue
        D = 型の口.タブの名(シート, タブ)
        h, 行 = _行たち(g)
        if タブ == "その月だけの指示":
            欠け = [x for x in 型の口.Driveの見出し(シート, タブ) if x not in h]
            for n, 列 in enumerate(欠け):
                r.誤り(c, "指示の型", f"{D} の見出しに {列} が無い")
                セル = f"{管理表.列の字(len(g[0]) + n)}1"
                r.案(c, "書く物", {"本": 物の名, "タブ": D, "セル": セル, "列": 列, "前": "", "値": 列},
                     _セルの当て(i, D, セル, g))
        for x in 行:
            v = x.get("支給月", "")
            殻 = _殻(v)
            if not 支給月の字.その形か(v, "殻"):
                if 殻:
                    r.誤り(c, "支給月の字", f"{D}: 「{v}」")
                    セル = f"{_列の字(h, '支給月')}{x['_行']}"
                    r.案(c, "書く物", {"本": 物の名, "タブ": D, "セル": セル, "列": "支給月", "前": v, "値": 殻},
                         _セルの当て(i, D, セル, g))
                else:
                    r.誤り(c, "支給月の字", f"{D}: 読めない「{v}」")
                    r.案(c, "問う物", {"本": 物の名, "タブ": D, "行": x["_行"], "列": "支給月", "前": v,
                                      "問い": "この行の支給月（読めない字）"})
            if 殻:
                支給月たち.add(殻)
            if タブ in 勤怠のタブ and 殻:
                勤怠の月.add(殻)
            if タブ == "締めの記録" and 殻 and x.get("締めの状態"):
                締めた月.add(殻)
            if タブ == "その月だけの指示":
                確 = x.get("確認", "")
                if 確 not in ("", 段の解決.確認済):
                    r.誤り(c, "指示の型", f"{D}: 確認が「{確}」")
                    r.案(c, "問う物", {"本": 物の名, "タブ": D, "行": x["_行"], "列": "確認", "前": 確,
                                      "問い": "この指示を使うなら 確認済・使わないなら行を消す"})
                名 = x.get("項目", "")
                if 名 and 名 not in _知っている名(c, マスタの格子):
                    r.誤り(c, "指示の型", f"{D}: 型の外の項目「{名}」")
                    r.案(c, "問う物", {"本": 物の名, "タブ": D, "行": x["_行"], "列": "項目", "前": 名,
                                      "問い": "今の項目の名に直すか、前の形の行なら消す"})
    for m in sorted(勤怠の月 - 締めた月):
        r.誤り(c, "締めの記録が無い", m)
        r.案(c, "書く物", {"本": 物の名, "タブ": 型の口.タブの名(シート, "締めの記録"), "支給月": m,
                          "道": "③ 勤怠の締め（締めの記録を書く）を当てる"})


def _月のフォルダを照らす(口, fid, 会社, r: _結果, 台帳の支給月: set) -> list[dict]:
    c = 会社[鍵]
    月 = {}
    for f in 口.子を並べる(fid):
        x = 支給月の字.置き場の字を読む(f["name"])
        if x is None:
            r.誤り(c, "月のフォルダの名", f["name"])
            r.案(c, "問う物", {"本": 型の口.名("月ごと"), "フォルダ": f["name"], "問い": "型の名 `YYYY.MM支給（M月分）` に直すか"})
            continue
        y, m, 分 = x
        月[(y, m)] = ((y * 12 + m - 1) - (分 - 1)) % 12   # 支給月と月分のずれ（0〜2）
    if not 月 and not 台帳の支給月:
        return []
    def ずれ(k):
        前 = [月[x] for x in sorted(月) if x <= k] or [月[x] for x in sorted(月)] or [1]
        return 前[-1]
    要る = set(月)
    if 月:
        k, 終 = min(月), max(月)
        while k <= 終:
            要る.add(k)
            k = _月を足す(*k, 1)
    for v in 台帳の支給月:
        x = 支給月の字.読む(v)
        if x:
            要る.add(x)
    out = []
    for k in sorted(要る):
        if k not in 月:
            名 = _月の名(*k, ずれ(k))
            r.誤り(c, "月のフォルダが無い", 名)
            r.案(c, "書く物", {"本": 型の口.名("月ごと"), "する": "フォルダを作る", "フォルダ": 名,
                              "道": "drive口/置き場.py 月の置き場（作る=True）"}, {"親": fid, "名": 名})
        out.append({"会社": 会社["会社"], "支給月": _月の名(*k, 月.get(k, ずれ(k)))})
    return out


def _徴収(c: str, NO: str, マスタの格子) -> str | None:
    名 = "社保.徴収の月"
    for x in マスタの格子.get("社員", ([], []))[1]:
        if x.get(鍵) == c and x.get("社員ID") == NO and x.get(名):
            return x[名]
    会社 = sorted((x for x in マスタの格子.get("会社", ([], []))[1] if x.get(鍵) == c and x.get("項目") == 名),
                key=lambda x: x.get("適用開始", ""))
