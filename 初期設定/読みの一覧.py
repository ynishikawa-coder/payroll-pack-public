"""「この読みで進めます」の一覧（`docs/設計/設問の作り方.md` §10）。資料から読めた事・閉じた問い・答え合わせで一致した事・
前任の未決のうち決定済みの物を、問いにせず 1 枚の一覧（項目・値・出所）で返す。事務所の担当者が目で見て、違えば直す。

受ける口は全部 `{項目, 値, 出所}` の辞書の列（閉じる段の返す一覧もこの形で渡す）。出所の無い行は受けない（止める）。
同じ項目が幾つかの元から来れば先の元が勝ち、後の元は `ほかの出所` に並べる（黙って捨てない）。
"""
from __future__ import annotations

元の順 = ("資料から読めた", "閉じた問い", "答え合わせで一致", "前任の未決で決定済み")


def _行(x, 元: str) -> dict:
    if not isinstance(x, dict):
        raise TypeError(f"{元}: 行は {{項目, 値, 出所}} の dict で渡す: {x!r}")
    名, 出所 = str(x.get("項目") or "").strip(), str(x.get("出所") or "").strip()
    if not 名:
        raise ValueError(f"{元}: 項目 の無い行: {x!r}")
    if not 出所:
        raise ValueError(f"{元}: {名} に 出所 が無い（出所の無い読みで進めない）")
    return {"項目": 名, "値": x.get("値"), "出所": 出所, "元": 元, "仮": bool(x.get("仮"))}


def 一覧(資料から読めた=(), 閉じた問い=(), 答え合わせで一致=(), 前任の未決で決定済み=()) -> list[dict]:
    """→ [{項目, 値, 出所, 元, 仮, ほかの出所}]（項目の初めて出た順）。仮＝事務所の見当で閉じた等、まだ決まっていない読み
    （閉じる段の 仮 をそのまま持つ。落とすと見当が決まった値に見える）。"""
    out: dict[str, dict] = {}
    for 元, xs in zip(元の順, (資料から読めた, 閉じた問い, 答え合わせで一致, 前任の未決で決定済み)):
        for x in xs or ():
            r = _行(x, 元)
            if r["項目"] in out:
                out[r["項目"]]["ほかの出所"].append({"値": r["値"], "出所": r["出所"], "元": 元, "仮": r["仮"]})
            else:
                out[r["項目"]] = {**r, "ほかの出所": []}
    return list(out.values())


def 会社の値から(会社の値: dict | None) -> list[dict]:
    """始める の入力 `会社の値`（{項目: {値, 書類の名}}）→ {項目, 値, 出所} の列。"""
    return [{"項目": 名, "値": v.get("値") if isinstance(v, dict) else v,
             "出所": f"書類 {v.get('書類の名')}" if isinstance(v, dict) and v.get("書類の名") else ""}
            for 名, v in (会社の値 or {}).items()]
