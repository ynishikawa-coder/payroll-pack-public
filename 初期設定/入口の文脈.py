def 答えの日付(字: str, 始め: str, 終わり: str) -> tuple[list[str], list[str]]:
    """回答の字の中の M/D（か YYYY/M/D）→ 期間の中の日付。期間の外・読めない日は 2 つ目に。"""
    日たち, 外 = [], []
    a, b = date.fromisoformat(始め), date.fromisoformat(終わり)
    期間 = [(a + timedelta(days=i)) for i in range((b - a).days + 1)]
    for x in re.finditer(r"(?<![\d/])(?:(\d{4})/)?(\d{1,2})/(\d{1,2})(?![\d/])", 字):
        y, m, d = x.group(1), int(x.group(2)), int(x.group(3))
        当たる = [t for t in 期間 if t.month == m and t.day == d and (not y or t.year == int(y))]
        (日たち.append(当たる[0].isoformat()) if 当たる else 外.append(x.group(0)))
    return sorted(set(日たち)), 外


_足す区間 = re.compile(r"(?<![\d/-])(?:(\d{4})[/-])?(\d{1,2})[/-](\d{1,2})(?![\d/-])\s*(.*?)(\d{1,2}:\d{2})\s*[〜~ー\-－–]\s*(\d{1,2}:\d{2})")


def 足す物を読む(補足: str, 始め: str, 終わり: str) -> tuple[list[dict], list[str]]:
    """足す物がある の補足の字（「11/2 19:00〜22:00、11/3 夜勤 休憩 1:00〜1:30、日の種類＝休日勤務」）→ ([{日付, 区間の種別, 始め, 終わり, 列}],
    読めない字)。日付と時刻の両方がある所だけ読む。区間の種別の語（休憩など）があればそれ、無ければ労働。列＝値 は同じ所の日にだけ。"""
    out, 外 = [], []
    if not (始め and 終わり):
        return out, 外
    a, b = date.fromisoformat(始め), date.fromisoformat(終わり)
    for 所 in re.split(r"[、,；;\n]", 補足):
        for m in _足す区間.finditer(所):
            y, mo, d = m.group(1), int(m.group(2)), int(m.group(3))
            当たる = [a + timedelta(days=i) for i in range((b - a).days + 1)]
            当たる = [t for t in 当たる if t.month == mo and t.day == d and (not y or t.year == int(y))]
            s, e = 分(m.group(5)), 分(m.group(6))
            if not 当たる or s is None or e is None:
                外.append(m.group(0).strip())
                continue
            種 = next((k for k in 区間の種別たち if k in m.group(4)), "労働")
            out.append({"日付": 当たる[0].isoformat(), "区間の種別": 種, "始め": 時刻(s), "終わり": 時刻(e + 1440 if e <= s else e),
                        "列": {c: v for c, v in _列の答え.findall(所)}})
    return out, 外


