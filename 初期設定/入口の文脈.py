def 締め日(会社名: str, 解いた: dict, 知らせ: list) -> str:
    """期間に使う `支払.締め日`（会社の全員でそろった 1〜28・末）。無い・読めない・そろわない時は 末 で期間を見当する。
    仮と問いはここで出さない＝芯/計算 の 要る値 が 1 つ出す（集計・計算・繋ぎで同じ値に 2 問を出さない）。
    `支払.支給日` は入口の文脈に要らない＝見ない（芯/計算 が見る）。"""
    締めたち, 無い = set(), False
    for (c, _), d in 解いた.get("決まり", {}).items():
        if c != 会社名:
            continue
        x = _日の字(d.get("支払.締め日"))
        if x:
            締めたち.add(x)
        else:
            無い = True
    if len(締めたち) == 1 and not 無い:
        return next(iter(締めたち))
    if 締めたち or 無い:
        知らせ.append(f"{会社名}: 支払.締め日 が無いか 1〜28・末 でない人がいる（期間を 末締めで見当。問いは 芯/計算 が出す）")
    return "末"


def _期間(月: str, 会社名: str, 解いた: dict, 知らせ: list) -> tuple[date, date, str, bool]:
    """その会社のその月の締めの期間 → (始め, 終わり, 支給の月, 支給の月が外れたか)。外れた時は翌月で見当して知らせ（仮は呼ぶ側）。"""
    締め = 締め日(会社名, 解いた, 知らせ)
    支給の月 = "翌月"
    for (c, _), d in 解いた.get("決まり", {}).items():
        if c == 会社名 and not 段.空(d.get("支払.支給の月")):
            支給の月 = str(d["支払.支給の月"]).strip()
            break
    try:
        return (*暦.期間(月, 締め, 支給の月), 支給の月, False)
    except ValueError as e:
        知らせ.append(f"{会社名}: {e}（翌月で期間を見当）")
        return (*暦.期間(月, 締め, "翌月"), 支給の月, True)


def _暦の値(v, 所: str, 知らせ: list):
    """`時間.暦` のセル（JSON の dict）を読む。読めなければ None＋知らせ。"""
    if 段.空(v):
        return None
    try:
        x = 段.値を読む("時間.暦", v)
    except 段.段の誤り as e:
        知らせ.append(f"{所}: {e}")
        return None
    if 段.字をそろえる("時間.暦", x) is not None:  # 段の解決と同じそろえ方（値の形も見る＝芯/計算/暦 が落ちない）
        return x
    知らせ.append(f"{所}: 時間.暦「{v}」が {{\"休みの曜日\": [...], \"祝日\": \"休み\"|\"出勤\", \"会社の休み\": [...]}} の形でない（使わない）")
    return None


def _日の所定の分(v) -> int | None:
    """段を解いた `時間.日の所定`（時間の数の字）→ 分。曜日ごと（dict）・読めない値は None（入口が要確認にする）。"""
    if 段.空(v) or isinstance(v, dict):
        return None
    try:
        m = Decimal(str(v).strip()) * 60
    except InvalidOperation:
        return None
    return int(m) if m == m.to_integral_value() and m > 0 else None


def 入口の文脈(支給月: str, 会社名: str, 解いた: dict, *, 会社=(), 勤務の型=(), 社員=(), 事務所=(), 置き場=None,
           **_ほかのタブ) -> dict:
    """その会社のその支給月の、入口の 文脈 の値（引数の名のまま）と 仮の値・知らせ を返す。"""
    月 = _月(支給月)
    仮の値, 知らせ = [], []
    人たち = sorted(NO for (c, NO) in 解いた.get("決まり", {}) if c == 会社名)

    def 全員を仮に(項目: str, 値, 拠り所: str, 問い: str):
        for NO in 人たち:
            仮の値.append({"会社": 会社名, "NO": NO, "項目": 項目, "値": 値, "拠り所": 拠り所, "問い": 問い})

    # 期間（支払.締め日・支払.支給の月）
    # 外れた 支払.支給の月 は段の解決が渡さず、その会社の全員を仮にし問う（ここは翌月で見当して知らせるだけ）
    始め, 終わり, _, _ = _期間(月, 会社名, 解いた, 知らせ)
    日たち = [始め + timedelta(days=i) for i in range((終わり - 始め).days + 1)]

    # 祝日（法の表）
    祝 = set()
    for y in range(始め.year, 終わり.year + 1):
        try:
            祝 |= 暦.祝日(y, 置き場)[0]
        except 引く口.欠け as e:
            知らせ.append(f"{会社名}: {y} 年の祝日を法の表から引けない（{e}）")
            全員を仮に("時間.暦", "", f"{y} 年の祝日が法の表に無い（祝日を休みに数えていない）",
                   f"法の表/祝日 に {y} 年の行を足してください")

    def 休みの日(暦の値: dict) -> dict:
        return {d.isoformat(): 暦.休みか(d, 暦の値, 祝) for d in 日たち}

    # 会社の暦（会社の段 → 事務所の段 → 項目の既定）
    会社の行 = [r for r in 段.行たち(会社) if str(r.get("会社", "")) == 会社名]
    鍵 = lambda r: "時間.暦" if str(r.get("項目", "")).strip() == "時間.暦" else None  # noqa: E731
