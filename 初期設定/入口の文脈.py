def 日付にそろえる(v) -> str | None:
    """日付の字（`2025-08-01`・`2025/8/1`・全角）→ `YYYY-MM-DD`。読めない・無い日は None。"""
    s = "".join(unicodedata.normalize("NFKC", str(v)).split())
    m = re.fullmatch(r"(\d{4})[/-](\d{1,2})[/-](\d{1,2})", s)
    if not m:
        return None
    try:
        return date(int(m[1]), int(m[2]), int(m[3])).isoformat()
    except ValueError:
        return None


def 日数にそろえる(v, 整数: bool = False) -> str | None:
    """日数の字（`8`・`8日`・`8.5`・`3.0`）→ 数の字（`8`・`8.5`・`3`）。負・読めない・整数が要る所の端数は None。"""
    s = "".join(unicodedata.normalize("NFKC", str(v)).split()).removesuffix("日")
    if not re.fullmatch(r"\d+(\.\d+)?", s):
        return None
    x = Decimal(s)
    if 整数 and x != x.to_integral_value():
        return None
    return str(int(x)) if x == x.to_integral_value() else format(x.normalize(), "f")


def _表Aの行たち(表A) -> list[dict]:
    """入口の 結果（`.日`）・その並び・表 A の行（dict の並びか get_values の形）→ 表 A の行の並び。"""
    if hasattr(表A, "日"):
        return list(表A.日)
    行, 束 = [], []
    for x in 表A or ():
        (行 if hasattr(x, "日") else 束).append(x)
    out = [a for r in 行 for a in r.日]
    return out + (段.行たち(束) if 束 else [])


