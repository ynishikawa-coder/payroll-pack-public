有給の関所の頭 = "有給休暇管理表."  # 関所の行の 項目 の頭（芯の項目と混ざらない）


def 有給の関所へ(有給の入力の結果: dict, 管理表の結果: dict, 段の仮の値=()) -> dict:
    """有給.管理表 の行を、出口の関所（`出口.関所.通す(行, 人の状態)`）が読む形にする。関所の中身は今のまま。

      z = 有給の関所へ(y, 有給.管理表(y["入力"]), r["仮の値"]) → {"行": 人×項目の縦の行, "人の状態": {(支給月, 会社, NO): 確認済|仮}}
      通 = 出口.関所.通す(z["行"], z["人の状態"]) → 有給の出す行(管理表の結果, 通) が出口へ出す行
    仮の人: 管理表の行の 状態＝仮（有給/ が見当した人）と、口の `仮の値`（y）・段の解決の `仮の値`（r。任意）に出た (会社, NO) の人。
      その人の行は全部 状態＝仮 にし、人の状態も 仮（行の値が空でも関所が外す）。問いはここで足さない（各々の 仮の値・問い のまま）。
    行: 管理表の数の列（`有給の関所の列`）のうち値のある物。支給月 は関所の形 `YYYY-MM` に。"""
    会社 = str(有給の入力の結果["入力"]["会社"])
    # (会社, NO) で引く（給与の関所へ と同じ）。会社の無い仮の値は口の会社の物。複数の会社の行を 1 度に回しても別の会社の同じ NO を取り違えない
    仮の人 = {(str(q.get("会社", 会社)), str(q["NO"])) for q in [*有給の入力の結果.get("仮の値", ()), *(段の仮の値 or ())]}
    行たち, 人の状態 = [], {}
    for a in 管理表の結果.get("行", ()):
        月, NO = _月(a["支給月"]), str(a["NO"])
        仮 = a.get("状態") != "確定" or (str(a["会社"]), NO) in 仮の人
        人の状態[(月, str(a["会社"]), NO)] = "仮" if 仮 else "確認済"
        for 列 in 有給の関所の列:
            if not 段.空(a.get(列)):
                行たち.append({"支給月": 月, "会社": str(a["会社"]), "NO": NO, "項目": 有給の関所の頭 + 列, "値": str(a[列]),
                             "状態": "仮" if 仮 else "確定", "出所": "有給/有給.py 管理表"})
    return {"行": 行たち, "人の状態": 人の状態}


def 有給の出す行(管理表の結果: dict, 通った) -> list[dict]:
    """関所を通った人の 有給.管理表 の行だけ（関所が外した人を除く）（03_有給休暇管理表 へ出す行）。`通った` は `出口.関所.通す` の返す物だけ受ける。"""
    from 出口 import 関所
    外した = 関所.通ったかを確かめる(通った).外した人の鍵()  # 数の値が 1 つも無い確定の人も出す（外した人だけを除く）
    return [a for a in 管理表の結果.get("行", ()) if (_月(a["支給月"]), str(a["会社"]), str(a["NO"])) not in 外した]

def 給与の関所へ(計算の結果: dict, 段の仮の値=(), 文脈の仮の値=()) -> dict:
    """芯/計算 の結果を、段の解決と口の仮の人を 仮 にして、出口の関所（`出口.関所.通す(行, 人の状態)`）が読む形にする。関所の中身は今のまま。

      z = 給与の関所へ(芯.計算.計算する(…), r["仮の値"], x["仮の値"]) → 通 = 出口.関所.通す(z["行"], z["人の状態"])
    仮の人: 段の解決の `仮の値`（r。変更の記録の 確かめ＝仮・時間に直せない時間の値・読めない人の休日・委託の所定の見当・委託の雇用分の出勤時間）と
      入口の文脈の `仮の値`（x。支給の月の外れ・祝日が引けない・暦が読めない・出勤簿が無い の外の値）に出た (会社, NO)。
      会社の段の値から来た仮は 段の解決・入口の文脈 がその会社の全員の行に出すので、ここは人ごとに見るだけ（足さない・減らさない）。
      その人の行は全部 状態＝仮 にし、人の状態も 仮（芯が確認済で返した人も関所が外す）。芯が仮にした人・行はそのまま仮。
      問いはここで足さない（各々の 仮の値・問い のまま）。行は写しを返す（計算の結果は変えない）。"""
    仮の人 = {(str(q["会社"]), str(q["NO"])) for q in [*(段の仮の値 or ()), *(文脈の仮の値 or ())]}
    行たち = []
    for a in 計算の結果.get("行", ()):
        a = dict(a)
        if (str(a["会社"]), str(a["NO"])) in 仮の人:
            a["状態"] = "仮"
        行たち.append(a)
    人の状態 = {}
    for k, v in (計算の結果.get("人の状態") or {}).items():
        k = tuple(str(x) for x in k)
        人の状態[k] = "仮" if k[1:] in 仮の人 else v
    for a in 行たち:  # 人の状態に居ない人の行も鍵を置く（行の値が空でも関所が外す）
        k = (str(a["支給月"]), str(a["会社"]), str(a["NO"]))
        if k[1:] in 仮の人:
            人の状態[k] = "仮"
    return {"行": 行たち, "人の状態": 人の状態}


