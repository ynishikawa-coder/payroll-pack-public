def _日の所定の分(v) -> int | None:
    """段を解いた `時間.日の所定`（時間の数の字）→ 分。曜日ごと（dict）・読めない値は None（入口が要確認にする）。"""
    if 段.空(v) or isinstance(v, dict):
        return None
    try:
        m = Decimal(str(v).strip()) * 60
    except InvalidOperation:
        return None
    return int(m) if m == m.to_integral_value() and m > 0 else None


def _時刻の分たち(v) -> list[int]:
    """`時間.所定の始業`・`時間.所定の終業` の値（`h:mm` か 曜日ごとの dict）→ 0:00 からの分の並び。読めない字は飛ばす。"""
    out = []
    for x in (v.values() if isinstance(v, dict) else [v]):
        m = re.fullmatch(r"(\d{1,2}):(\d{2})", "".join(unicodedata.normalize("NFKC", str(x or "")).split()))
        if m and int(m[2]) < 60:
            out.append(int(m[1]) * 60 + int(m[2]))
    return out


def 所定の幅(型の値: dict) -> int | None:
    """段を解いた勤務の型の値の所定の始業〜終業の幅（分）。終業が始業以下なら次の日の時刻。
    曜日ごとの値は同じ曜日どうしで組み、一番長い物。読めなければ None。"""
    a, b = 型の値.get("時間.所定の始業"), 型の値.get("時間.所定の終業")
    組 = [(a.get(k), b.get(k)) for k in a if k in b] if isinstance(a, dict) and isinstance(b, dict) else [(a, b)]
    幅 = []
    for x, y in 組:
        xs, ys = _時刻の分たち(x), _時刻の分たち(y)
        if len(xs) == 1 and len(ys) == 1:
            幅.append((ys[0] - xs[0]) % 1440 or 1440)
    return max(幅) if 幅 else None


