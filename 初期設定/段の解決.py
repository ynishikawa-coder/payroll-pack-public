        # 台帳「月の変動」→ 入力（部品の行の 数量の元＝入力の値 の名・委託.出張日数）。読めない行・渡せない名はその人を仮＋問い 1 つ
        変入, 訳 = 月の変動の入力(変動.get((c, NO), []), 変動の外れ.get((c, NO), []), d)
