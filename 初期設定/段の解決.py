# ---- 時間の値（勤務の型の所定など）----
# 芯が時間の数で読む項目（芯/計算 は `数` で読み h:mm を受けない・芯/集計 は h:mm も読む）＝時間の数の字にそろえて渡す
時間の項目 = ("時間.日の所定", "時間.週の所定", "時間.月の所定時間", "有給.1日の時間", "割増.みなし残業の時間")
# 読む側が分で読む項目（`有給.1日の時間` を読むのは 有給/有給.py だけで、`int` の分で読む＝芯は読まない）＝分の数の字で渡す
分で渡す項目 = ("有給.1日の時間",)
_hmm = re.compile(r"(\d+):(\d{2})(?::00)?")                      # 8:00・202:30・8:00:00（Sheets の経過時間）
_時と分 = re.compile(r"(?:(\d+(?:\.\d+)?)時間)?(?:(\d+)分)?")  # 8時間・7時間30分・480分


def _分(v) -> Decimal | None:
    """時間の値（h:mm・3 桁の時の h:mm・`480分`・`7時間30分`・小数の時間・0）→ 分（整数の Decimal）。分に割り切れない・負・読めない形は None。"""
    if isinstance(v, bool) or v is None:
        return None
    if isinstance(v, (int, Decimal)):
        s = str(v)
    elif isinstance(v, float):
        s = repr(v)
    else:
        s = "".join(unicodedata.normalize("NFKC", str(v)).split())
    if not s or not re.fullmatch(r"[0-9.:時間分]+", s):  # 指数（`1e2`）・符号・ほかの字は読まない
        return None
    m = _hmm.fullmatch(s)
    t = _時と分.fullmatch(s) if not m and ("時間" in s or "分" in s) else None
    try:
        if m:
            if int(m.group(2)) >= 60:
                return None
            分 = Decimal(int(m.group(1)) * 60 + int(m.group(2)))
        elif t and (t.group(1) or t.group(2)):
            分 = Decimal(t.group(1) or 0) * 60 + Decimal(t.group(2) or 0)
        else:
            分 = Decimal(s) * 60
    except InvalidOperation:
        return None
    if not 分.is_finite() or 分 < 0 or 分 != 分.to_integral_value():
        return None
    return 分


def 時間の数(v) -> str | None:
    """時間の値 → 芯の形（時間の数の字。`7:30`→`7.5`・`0:00`→`0`）。
    時間の数に割り切れない（分が 3 の倍数でない＝`7:20`）・読めない形は None（黙って 0 にしない）。"""
    分 = _分(v)
    if 分 is None or int(分) % 3:
        return None
    x = 分 / Decimal(60)
    return format(x.normalize(), "f") if x else "0"


def 分の数(v) -> str | None:
    """時間の値 → 分の数の字（`7:30`→`450`・`7:20`→`440`）。読めない形は None。"""
    分 = _分(v)
    return None if 分 is None else str(int(分))


