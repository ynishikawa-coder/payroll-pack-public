def 集まりへ直す(種たち, タブ: dict, 会社: str) -> dict:
    """人ごとの差を型・集まりの決まりに直してから聞く段（オーナーの決定 2026-11-16）。

    2 人以上を並べた種（足りない値・法の線）の項目が勤務の型か会社の段に置けて、その人たちが ある勤務の型の人の全部
    （幾つかの型の和でもよい）か会社の全員なら、「この型の人たちはこの決まりか」の 1 問に直す: 対象を集まりの札に、
    反映先を 2_マスタ/社員/ → 2_マスタ/勤務の型/（全員は 2_マスタ/会社/）に、法の線の 何が無いか の（人: …）を
    （勤務の型: …）か（全員）に替える。集まりに直らない種（型の一部の人・型の無い人・人だけの項目）はそのまま返す。
    返す物: 種（直した後の並び）・直した（[{何が無いか, 前, 集まり}]）。"""
    人の行 = _その会社(タブ.get("社員", ()), 会社)
    型の人: dict[str, set] = {}
    人の型: dict[str, str] = {}
    for r in 人の行:
        NO, 型名 = str(r.get("NO", "")).strip(), str(r.get("勤務の型", "") or "").strip()
        if NO and 型名:
            人の型[NO] = 型名
            型の人.setdefault(型名, set()).add(NO)
    全員 = {str(r.get("NO", "")).strip() for r in 人の行 if str(r.get("NO", "")).strip()}
    out, 直した = [], []
    for s in 種たち:
        s = dict(s)
        b = s.get("箱") or 箱(s)
        人 = [str(x) for x in s.get("人") or ()]
        名 = _種の項目(s) if b in ("足りない値", "法の線") and len(人) >= 2 else None
        段たち = set(口.項目(名).get("段") or ()) if 名 else set()
        集まり = None
        if 名 and set(人) == 全員 and "会社" in 段たち:
            集まり = ("会社", [])
        elif 名 and "勤務の型" in 段たち and all(p in 人の型 for p in 人):
            型たち = sorted({人の型[p] for p in 人})
            if set().union(*(型の人[x] for x in 型たち)) == set(人):
                集まり = ("勤務の型", 型たち)
        if not 集まり:
            out.append(s)
            continue
        段名, 型たち = 集まり
        札 = "全員" if 段名 == "会社" else f"勤務の型 {'・'.join(型たち)}（{len(人)} 人）"
        前 = str(s.get("何が無いか", ""))
        if b == "法の線":
            s["何が無いか"] = re.sub(r"（人: [^）]*）$", f"（{'全員' if 段名 == '会社' else '勤務の型: ' + '、'.join(型たち)}）", 前)
        先 = f"{_マスタ}/会社/" if 段名 == "会社" else f"{_マスタ}/勤務の型/"
        先たち = [w.strip() for w in re.split(r"[、,]", str(s.get("反映先") or "")) if w.strip()]
        先たち = [w.replace(f"{_マスタ}/社員/", 先) for w in 先たち] or [先 + 名]
        s["反映先"] = "、".join(dict.fromkeys(先たち))
        s["答えで変わる項目と人"] = "、".join([名, *型たち])
        s["集まり"] = 札
        if b == "足りない値":
            s["質問"] = f"{'全員' if 段名 == '会社' else '・'.join(型たち) + 'の人'}の{口.項目(名)['意味']}を、決まりとして教えてください"
        s["種類"] = "会社の決まり"
        直した.append({"何が無いか": s["何が無いか"], "前": 前, "集まり": 札})
        out.append(s)
    return {"種": out, "直した": 直した}


