def _知らせの線を読む(字: str, 集計の字: bool = False) -> tuple | None:
    """知らせの字 → (線, 札, 質問, 反映先)。表に無い字は、芯/計算 の法の線の知らせなら字の型を札に（集計の知らせは表の物だけ＝None）。"""
    for 形, 線, 札, 質問, 先 in _知らせの線:
        if m := re.match(形, 字):
            g = m.groups() or ("",)
            return 線, 札.format(*g), 質問.format(*g), 先.format(*g)
    if 集計の字:
        return None
    札 = re.sub(r"（[^）]*）", "", re.split(r"[＝［]", _字の型(字))[0]).strip()
    # 表に無い線は反映先を決め打ちしない（空＝反映の照らしの「反映先が無い」で人が書く先を決める＝誤った先に書かない）
    return 札, 札, f"{_言い換え(札)[:24]}は、今のとおりですか", ""


def _知らせの種(out: dict, 会社: str, NO: str, 字: str, 出所: str, 線たち) -> None:
    線, 札, 質問, 先 = 線たち
    何 = f"{_知らせの頭}{札}」"
    x = out.setdefault(何, {"箱": "法の線", "会社": 会社, "何が無いか": 何, "出所": 出所, "知らせの線": 線,
                            "質問": 質問, "答え方の例": f"{_知らせの答え}／違う（補足に書く）",
                            "変わる事": {_知らせの答え: "額は変わりません（答えを記録に残します）"},
                            "分かっている事": [], "見当": "", "見当の拠り所": "知らせ（計算は確定・仮にしない）",
                            "反映先": 先, "人": [], "変わる項目": []})
    見える = _言い換え(re.sub(r"［[^］]*］\s*$", "", 字)).strip()
    if not x["分かっている事"] and len(re.sub(r"\s", "", 見える)) <= 60:
        x["分かっている事"].append(見える)
    if NO not in x["人"]:
        x["人"].append(NO)


def 種を集める(回した: dict) -> list[dict]:
    """月次.月を回す（か 賞与を回す）の返す物から、問いの種（足りない値・法の線）を集める。
    同じ 何が無いか の種は人を並べて 1 つにする。見当の額（人ごとの総支給額）を添える。

    - 仮の問い（出所ごとの `問い`）: 入口の要確認は人・日ごとの値を外した読めなさで 1 つに（日付を添える）。同じ根から出た仮
      （入口の要確認 → 集計の「読み取りの確かめが要確認の日がある」→ 計算の「月の数字「語」が仮（芯/集計 問N）」）は根の問い 1 つへ
      まとめる（`_根へまとめる`）。どの種にも 反映先（答えを置く所）を付ける（`_問いの反映先`）。
    - 法の線: 芯/計算 の法の線の行の 赤（法の線で仮に計算した）と 知らせ（計算は確定）、芯/集計 の法の線の知らせ（休憩の長さ・
      会社の残業の数え方）。どれも同じ線は人を並べて 1 つ（人ごとの数は字の型で外す）。知らせは仮にしない＝問いに出すだけ
      （何が無いか `法の線: 知らせ「…」`・答えは記録に残す）。承知（印のある線）は問いにしない。"""
    会社 = str(回した.get("会社", ""))
    out: dict[str, dict] = {}
    台帳の先 = _台帳の要確認の先(回した.get("台帳") or {})
    集計の番号: dict[str, str] = {}
    for 出所, qs in (回した.get("問い") or {}).items():
        for q in qs or ():
            何 = str(q.get("何が無いか") or q.get("項目") or q.get("理由") or "").strip()
            if 出所 == "入口":
                何 = 読みの型(何) or 何
            if not 何:
                continue
            人 = q.get("人") or ([q["NO"]] if q.get("NO") not in (None, "") else [])
            x = out.setdefault(何, {"箱": "足りない値", "会社": 会社, "何が無いか": 何, "出所": 出所,
                                    "見当": str(q.get("見当", "") or ""), "見当の拠り所": str(q.get("見当の拠り所") or q.get("拠り所") or ""),
                                    "答え方の例": str(q.get("答え方の例", "") or ""), "人": [], "変わる項目": [], "反映先": ""})
            if 出所 == "集計" and q.get("番号"):
                集計の番号[str(q["番号"])] = 何
            _足す(x["人"], [_NO(p) for p in 人])
            _足す(x["変わる項目"], q.get("変わる項目"))
            日付 = q.get("日付")
            if 日付 and 出所 in ("入口", "集計"):
                _足す(x.setdefault("日付", []), [日付] if isinstance(日付, str) else 日付)
            先 = [w.strip() for w in re.split(r"[、,]", str(q.get("反映先") or "")) if w.strip()] or _問いの反映先(出所, q, 何, 台帳の先)
            # 日の問いの答え方（答えそのものを入口の文脈.日の答え が読む＝先は質問と回答）
            種類 = 日の答えの種類(何) if 出所 == "入口" else ("日" if 日付 and 日の答えの先 in 先 else "")
            if 種類 == "時刻":   # 要確認の時刻（決まりで人が確かめる時刻）
                時 = 要確認の時刻の理由の形.match(何)
                x["見当"] = x["見当"] or f"{時.group(2)}の時刻で数える"
                x["見当の拠り所"] = x["見当の拠り所"] or "原本に書いてある時刻"
                x["答え方の例"] = (f"{時.group(2)}の時刻で数える／別の時刻で数える（補足に「17:46 で数える」の形で書く）"
                               "／原本を送る")
            elif 種類 == "時刻の値":   # 時刻が読めない・打刻抜け（欄は問いから決まる＝時刻だけ答えればその欄に置く）
                x["答え方の例"] = "時刻が分かる（補足に「17:46 で数える」の形で書く）／原本を送る"
            elif 種類 == "長さ":   # 日またぎと読んだ長さ（読み違いが多い＝推奨を置かない）
                x["答え方の例"] = ("書いてある時刻で数える（その長さ働いた）／時刻が違う（補足に「退は 18:00」の形で書く）"
                               "／原本を送る")
            elif 種類 == "区分":   # 選択肢の答えだけで当たる（入口.口.区分の答えの選択肢＝その日の表 A の列）
                x["答え方の例"] = "／".join([*区分の答えの選択肢, "ほかの区分（補足に「日の種類＝休暇、休暇の種類＝代休」の形で書く）",
                                         "原本を送る"])
            elif 種類 == "日":
                x["答え方の例"] = "分かる（補足に「休日の区分＝法定（2/7）」の形で書く・日付は M/D）／原本を送る"
            x["反映先"] = "、".join(dict.fromkeys([*filter(None, x["反映先"].split("、")), *先]))
    _根へまとめる(out, 集計の番号)
    赤の字: dict[str, list[str]] = {}
    for t in 回した.get("法の線") or ():
        m = re.match(r"\s*(\S+) (\S+): (赤|知らせ): (.*)$", str(t))
        if not m:
            continue
        if m.group(3) == "知らせ":
            _知らせの種(out, m.group(1), m.group(2), m.group(4), "計算", _知らせの線を読む(m.group(4)))
            continue
        字 = re.sub(r"［[^］]*］\s*$", "", m.group(4)).strip()
        鍵 = "法の線: " + _字の型(字)
        線 = re.match(r"(\S+?)[「 ]", 字)
        線 = 線.group(1) if 線 else ""
        行の名 = re.match(r"部品の行「([^」]+)」", 字)
        try:
            名 = 口.項目(線)["意味"]
            反映先 = f"{_マスタ}/会社/{線}"
        except KeyError:
            名 = f"「{行の名.group(1)}」の扱い" if 行の名 else "給与の計算"
            反映先 = f"{_マスタ}/支給控除の項目/{行の名.group(1)}" if 行の名 else ""
        見える字 = _言い換え(字).replace("部品の行", "手当の行")
        # 割増の基礎から除けない手当（37 条 5 項）は 線 を 割増.基礎に入る にして承知できる線に数える（反映先は支給控除の項目の行＝§1.4）
        if 行の名 and "割増の基礎から除く" in 字:
            線 = 承知の口.基礎の線
        承知できる = 線 in 承知の口.承知できる線 and (反映先.startswith(f"{_マスタ}/会社/") or 線 == 承知の口.基礎の線)
        if 承知できる:   # 承知できる線は 法の線.承知 も反映先に（点検の種 法の線の種 と同じ形。無いと「今のまま」の答えを照らしが承知できない線と読む）
            反映先 += f"、2_マスタ/会社/{承知の口.項目}"
        x = out.setdefault(鍵, {"箱": "法の線", "会社": m.group(1), "何が無いか": "法の線: " + 字, "出所": "計算",
                                "線の項目": 線, **_法の線の問い(名, 承知できる),
                                "分かっている事": [f"{見える字}（答えまで法の最低線で計算します）"],
                                "見当": "法の線", "見当の拠り所": "法の線（答えまで法の線で計算する）",
                                "反映先": 反映先, "人": [], "変わる項目": []})
        _足す(赤の字.setdefault(鍵, []), [字])
        if len(赤の字[鍵]) > 1:   # 人ごとに数の違う同じ線＝何が無いか と見つけた事を字の型に（1 人ごとに問いを溢れさせない）
            x["何が無いか"] = 鍵
            x["分かっている事"] = [f"{_言い換え(_字の型(字)).replace('部品の行', '手当の行')}（答えまで法の最低線で計算します）"]
        _足す(x["人"], [m.group(2)])
    for t in (回した.get("知らせ") or {}).get("集計") or ():
        m = re.match(r"\s*(\S+) (\S+): (.*)$", str(t))
        線たち = _知らせの線を読む(m.group(3), 集計の字=True) if m else None
        if 線たち:
            _知らせの種(out, m.group(1), m.group(2), m.group(3), "集計", 線たち)
    額 = 回した.get("見当の額") or {}
    for x in out.values():
        if 額:
            x["額"] = {NO: 額[NO] for NO in x["人"] if NO in 額}
    return list(out.values())


def _日付の行(日付たち) -> str:
    """原本の読めない日の 1 行（見つけた事・60 字まで）: 「原本の 11/3・11/4 ほか 3 日の行です。」"""
    日 = sorted({str(d) for d in 日付たち if str(d).strip()})
    字 = [f"{int(d[5:7])}/{int(d[8:10])}" if re.fullmatch(r"\d{4}-\d{2}-\d{2}", d) else d for d in 日]
    return f"原本の {'・'.join(字[:4])}" + (f" ほか {len(字) - 4} 日" if len(字) > 4 else "") + " の行です。"


def 候補ごとの額(回す, タブ: dict, 会社: str, 段名: str, 項目: str, 候補たち, 誰=None) -> dict:
    """読み方の箱の候補ごとに、その値を置いて回し直した人ごとの総支給額 → {候補: {NO: 総支給額}}。
    回す＝タブ を受けて 月次.月を回す の返す物を返す callable（殻が原本などを束ねて渡す）。段名＝会社・勤務の型・人。
    誰＝勤務の型の名か NO の並び（None は全部の行）。タブは元のまま（写しへ置く）。"""
    out = {}
    for 候補 in 候補たち:
        t = {k: 段.行たち(v) for k, v in タブ.items()}
        if 段名 == "会社":
            t["会社"] = [r for r in t.get("会社", []) if not (str(r.get("会社")) == 会社 and str(r.get("項目")) == 項目)]
            t["会社"].append({"会社": 会社, "項目": 項目, "今の値": 候補, "適用開始": ""})
        else:
            タブ名, 鍵 = (("勤務の型", "型の名") if 段名 == "勤務の型" else ("社員", "NO"))
            t[タブ名] = [{**r, 項目: 候補} if str(r.get("会社")) == 会社 and (誰 is None or str(r.get(鍵)) in set(map(str, 誰))) else r
                       for r in t.get(タブ名, [])]
        o = 回す(t)
        out[str(候補)] = {NO: v.get("総支給額") for NO, v in (o.get("見当の額") or {}).items()}
    return out


