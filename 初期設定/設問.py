def 箱(行: dict) -> str:
    """質問と回答の行の箱（何が無いか の頭の字）。頭の無い行は 足りない値。"""
    何 = str(行.get("何が無いか", "")).strip()
    if 何 == その月 or 何.startswith(その月 + ":"):
        return その月
    for b in ("読み方", "法の線"):
        if 何.startswith(b + ":"):
            return b
    return "足りない値"


def _何の項目(何: str) -> str | None:
    """何が無いか の字 → 項目の名（`法の線: X（…）`・`「X」が無い…`・項目の名そのもの）。項目でなければ None。"""
    m = re.match(r"法の線: ([^\s（「]+)", 何) or re.fullmatch(r"「([^」]+)」が無い.*", 何)
    名 = m.group(1) if m else 何
    try:
        口.項目(名)
        return 名
    except (KeyError, ValueError):
        return None


def 種類(行: dict) -> str:
    """問いの種類（会社の決まり／原本）。質問と回答の列だけから決まる（読み直しても同じ・確認ページの `_種類` と同じ決まり）。

    行の `種類` が勝つ。無ければ箱から: 読み方・法の線＝会社の決まり・その月だけの物＝原本。足りない値は、反映先が全部
    会社の決まりの先（マスタの会社・勤務の型・支給控除の項目・給与のルール.md）なら会社の決まり、ほかの先があれば原本。
    反映先が空なら 何が無いか の項目の段（会社・勤務の型・事務所に置ける＝会社の決まり・人だけ＝原本）・項目でない（原本の名）＝原本・空＝会社の決まり。"""
    if 行.get("種類") in 種類たち:
        return 行["種類"]
    b = 箱(行)
    if b in ("読み方", "法の線"):
        return "会社の決まり"
    if b == その月:
        return "原本"
    先たち = [w.strip() for w in re.split(r"[、,]", str(行.get("反映先") or "")) if w.strip()]
    if 先たち:
        return "会社の決まり" if all(_決まりの先.match(w) for w in 先たち) else "原本"
    何 = str(行.get("何が無いか", "")).strip()
    if not 何:
        return "会社の決まり"
    名 = _何の項目(何)
    if 名 is None:
        return "原本"
    return "会社の決まり" if set(口.項目(名).get("段") or ()) & {"会社", "勤務の型", "事務所"} else "原本"


