# ── ③ 法の線の点検 ────────────────────────────────────────

def _数(v) -> Decimal | None:
    try:
        s = str(v).strip().replace(",", "")
        return Decimal(s) if s else None
    except InvalidOperation:
        return None


def _分(hhmm: str) -> int | None:
    m = re.fullmatch(r"\s*(\d{1,2}):(\d{2})\s*", str(hhmm))
    return int(m.group(1)) * 60 + int(m.group(2)) if m else None


def _語(v) -> str:
    s = re.sub(r"[ 　]", "", str(v or ""))
    s = re.sub(r"（[^）]*）|\([^)]*\)", "", s)
    return s.replace("切り捨て", "切捨て").replace("切り上げ", "切上げ")


def _法の値(名: str, 日: str, 置き場=None):
    線, _, 直し = 線の読み.読み方[名]
    r = 引く口.引く("法の線", 日, 置き場=置き場, 線=線)
    x = 線の読み.欄の値(名, r.値)
    if 直し == "倍":
        return 1 + Decimal(str(x)) / 100
    if 直し == "足す":
        return Decimal(str(x)) / 100
    return x


def _食い違うか(点: dict, 値, 制度, 日: str, 置き場) -> tuple[bool, str] | None:
    """1 つの値を点検表の 1 行に当てる → (食い違うか, 法の値の字)。見られない（読めない・条件の外）は None。"""
    見方 = 点["見方"]
    if 見方 in ("下限", "上限"):
        if 点.get("条件") and (制度 or "通常") not in 点["条件"]["値"]:
            return None
        法 = _法の値(点["読み方"], 日, 置き場)
        会 = _数(値) if 点["項目"].startswith("割増.") else _数(段.時間の数(値) or 値)
        if 会 is None or 法 is None:
            return None
        法 = Decimal(str(法))
        return (会 < 法 if 見方 == "下限" else 会 > 法), format(法.normalize(), "f")
    if 見方 == "時間帯":
        法 = _法の値(点["読み方"], 日, 置き場)
        a, b = (str(値).replace("～", "〜").split("〜") + [""])[:2]
        la, lb = str(法).split("〜")
        ca, cb, xa, xb = _分(a), _分(b), _分(la), _分(lb)
        if None in (ca, cb, xa, xb):
            return None
        cb, xb = cb + (1440 if cb <= ca else 0), xb + (1440 if xb <= xa else 0)
        return (ca > xa or cb < xb), str(法)
    if 見方 == "外れの語":
        return _語(値) in {_語(w) for w in 点["外れ"]}, 点.get("法の値", "")
    if 見方 == "許す語":
        許す = 点.get("許す") or str(口.項目(点["項目"])["選べる値"]).split("・")
        return _語(値) not in {_語(w) for w in 許す}, 点.get("法の値", "")
    return None


def 法の線の点検(タブ: dict, 会社: str, 支給月: str | None = None, *, 日: str | None = None, 置き場=None) -> dict:
    """会社の決まりの全部を法の線の点検表に当てる。

    返す物: 食い違い（[{項目, 名, 段, 誰, 値, 法の値, 法, 承知できる, 承知の印, 状態}]・状態＝食い違い か 承知済）・
    目で見る（既定と違う値が置かれた 目で の項目）・読めない（形が読めず当てられなかった値）。"""
    if not 日:
        日 = f"{段.月(支給月).replace('.', '-')}-01" if 支給月 else dt.date.today().isoformat()
    会値 = 会社の値(タブ, 会社, 支給月)
    会社の印, _ = 承知の口.読む(会値.get(承知の口.項目))
    行たち = [("会社", "会社", 会値, 会社の印)]
    for 段名, 鍵 in (("勤務の型", "型の名"), ("人", "NO")):
        for r in _その会社(タブ.get(_タブの名[段名], ()), 会社):
            印, _ = 承知の口.読む(r.get(承知の口.項目))
            行たち.append((段名, str(r.get(鍵, "")), r, 印 or 会社の印))
    食い, 目, 読めない = {}, [], []
    for 点 in 点検表["行"]:
        名 = 点["項目"]
        if 点["見方"] in ("下限", "上限", "時間帯", "外れの語", "許す語"):
            for 段名, 誰, 値たち, 印 in 行たち:
                v = 値たち.get(名)
                if _空(v):
                    continue
                制度 = 値たち.get("時間.制度") or 会値.get("時間.制度")
                try:
                    r = _食い違うか(点, v, 制度, 日, 置き場)
                except (引く口.欠け, KeyError) as e:
                    読めない.append(f"{名}（{段名}: {誰}）: 法の表を引けない（{e}）")
                    continue
                if r is None:
                    if not (点.get("条件") and (制度 or "通常") not in 点["条件"]["値"]):
                        読めない.append(f"{名}（{段名}: {誰}）「{v}」を法の線に当てられない")
                    continue
                違う, 法の値 = r
                if not 違う:
                    continue
                線 = 点.get("線")
                問 = 印.get(線, "") if 線 else ""
                k = (名, 段名, str(v), 問)
                x = 食い.setdefault(k, {"項目": 名, "名": 点.get("名", 名), "段": 段名, "誰": [], "値": str(v),
                                        "法の値": 法の値, "法": 点["法"], "承知できる": bool(点.get("承知できる")),
                                        "承知の印": 問, "状態": "承知済" if 問 else "食い違い"})
                x["誰"].append(誰)
        elif 点["見方"] == "行":
            除ける = {_語(w) for w in 点検表["除ける訳"] + 点検表["割増そのものの訳"]}
            for r in _その会社(タブ.get("支給控除の項目", ()), 会社):
                訳 = str(r.get("割増の基礎から除く訳") or "").strip()
                if (str(r.get("支給か控除", "")).strip() == "支給" and str(r.get("割増の基礎", "")).strip() == "入らない"
                        and 訳 and _語(訳) not in 除ける):
                    # 承知の印は会社の段（支給控除の項目は会社ごとの行）。印のある行は 承知済（問いにしない）
                    問 = 会社の印.get(点["線"], "") if 点.get("線") else ""
                    k = (名, "支給控除の項目", str(r.get("項目")), 問)
                    食い[k] = {"項目": 名, "名": 点.get("名", 名), "段": "支給控除の項目", "誰": [str(r.get("項目"))],
                             "値": f"割増の基礎から除く（訳: {訳}）", "法の値": "除けるのは " + "・".join(点検表["除ける訳"] + 点検表["割増そのものの訳"]),
                             "法": 点["法"], "承知できる": bool(点.get("承知できる")), "承知の印": 問,
                             "状態": "承知済" if 問 else "食い違い"}
        elif 点["見方"] == "目で":
            既定 = 口.項目(名).get("既定")
            for 段名, 誰, 値たち, _ in 行たち:
                v = 値たち.get(名)
                if 既定 not in (None, "") and not _空(v) and _語(v) != _語(既定):
                    目.append({"項目": 名, "段": 段名, "誰": 誰, "値": str(v), "法": 点["法"]})
    return {"食い違い": list(食い.values()), "目で見る": 目, "読めない": 読めない}


def 法の線の種(点検: dict, 会社: str) -> list[dict]:
    """点検の 食い違い（承知済を除く）→ 法の線の箱の種（承知か直すか）。"""
    out = []
    for x in 点検["食い違い"]:
        if x["状態"] != "食い違い":
            continue
        誰 = "全員" if x["段"] == "会社" else f"{x['段']}: {'、'.join(x['誰'])}"
        if x["段"] == "支給控除の項目":
            反映先 = [f"{_マスタ}/支給控除の項目/{w}" for w in x["誰"]] + \
                ([f"{_マスタ}/会社/{承知の口.項目}"] if x["承知できる"] else [])
        else:
            タブ = _タブの名[x["段"]]
            反映先 = [f"{_マスタ}/{タブ}/{x['項目']}"] + ([f"{_マスタ}/{タブ}/{承知の口.項目}"] if x["承知できる"] else [])
        out.append({
            "箱": "法の線", "会社": 会社,
            "何が無いか": f"法の線: {x['項目']}（{誰}）",
            **_法の線の問い(x["名"], x["承知できる"]),
            "分かっている事": [f"今の決まりは「{x['値']}」、法の最低線は「{x['法の値']}」です（{x['法']}）。"],
            "見当": x["法の値"], "見当の拠り所": "法の線（答えまで法の線で計算する）",
            "答えで変わる項目と人": "、".join([x["項目"], *x["誰"]]),
            "反映先": "、".join(反映先),
            "人": [w for w in x["誰"]] if x["段"] == "人" else [],
            "段": x["段"], "線の名": x["項目"],
        })
    return out


