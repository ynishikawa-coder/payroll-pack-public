def 前の答えとの食い違い(問いたち) -> list[dict]:
    """同じ反映先（同じ人・同じ日・同じ項目）に、違う問いの番号で違う答えがある組。新しい答えが黙って前の答えに勝たない＝問いにする。
    新しい問いの 理由 に `聞き直し: <前の問いの番号>` があれば、記録に残した聞き直し＝食い違いに数えない（前の答え.py と同じ印）。
    問いたち は答えのある問い（問いの番号ごとの一番下の行）を、質問と回答の上から下の順で。"""
    前: dict = {}
    out = []
    for q in 問いたち:
        回答 = 口.答えの芯(q.get("回答"))
        番号 = str(q.get("問いの番号", "")).strip()
        外す = set(前の答え.聞き直し.findall(str(q.get("理由", ""))))
        for w in [w.strip() for w in re.split(r"[、,]", str(q.get("反映先") or "")) if w.strip()]:
            k = _食い違いの鍵(q, w)
            if k is None:
                continue
            p = 前.get(k)
            if p and p["番号"] != 番号 and p["番号"] not in 外す and p["値"] != _答えの値(q, 回答):
                out.append({"問いの番号": 番号, "反映先": w, "前の問い": p["番号"],
                            "訳": f"前の答え {p['番号']}「{p['回答']}」と今の答え「{回答}」が違う"
                                  f"（どちらが正しいかを担当者に聞く。正す時は理由に 聞き直し: {p['番号']}）"})
                continue
            前[k] = {"番号": 番号, "値": _答えの値(q, 回答), "回答": 回答}
    return out


