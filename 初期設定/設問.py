def _口(名: str, 入力: dict):
    if 名 == "点検":
        r = 法の線の点検(入力["タブ"], 入力["会社"], 入力.get("支給月"), 日=入力.get("日"))
        return {**r, "種": 法の線の種(r, 入力["会社"])}
    if 名 == "網":
        return {"種": 型ごとの網(入力["タブ"], 入力["会社"], 既にある=入力.get("既にある"), 足す型=入力.get("足す型", ()),
                             支給月=入力.get("支給月"))}
    if 名 == "その月だけの物":
        return {"種": [その月だけの物の問い(入力["支給月"], 入力["会社"], 入力.get("読んだ"))]}
    if 名 == "種":
        return {"種": 種を集める(入力["回した"])}
    if 名 == "まとめる":
        return まとめる(入力["種"], 会社=入力["会社"], 支給月=入力["支給月"], 今日=入力["今日"],
                    次の問いの番号=入力.get("次の問いの番号", 1), 既にある=入力.get("既にある"),
                    名たち=入力.get("名たち"), 候補の額=入力.get("候補の額"), 誰が聞いた=入力.get("誰が聞いた"),
                    読んだ資料=入力.get("読んだ資料", ()), タブ=入力.get("タブ"), 推し量り=入力.get("推し量り"),
                    根拠=入力.get("根拠"), 今月に当たる=入力.get("今月に当たる", ()))
    if 名 == "集まり":
        return 集まりへ直す(入力["種"], 入力["タブ"], 入力["会社"])
    if 名 == "照らし":
        return 反映の照らし(入力["問い"], 入力["タブ"], 入力["会社"], md=入力.get("md"), 支給月=入力.get("支給月"),
                       台帳=入力.get("台帳"))
    raise SystemExit(f"口 {名!r} は 点検・網・その月だけの物・種・集まり・まとめる・照らし のどれか")


