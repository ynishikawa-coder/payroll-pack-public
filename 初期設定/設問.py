def _円(v) -> str:
    try:
        return f"{int(Decimal(str(v))):,} 円"
    except (InvalidOperation, ValueError, TypeError):
        return "額なし"


def _額の行(額: dict, 名たち: dict | None) -> str:
    """人ごとの額の 1 行（3 人まで名を出し、残りは人数）。"""
    名たち = 名たち or {}
    並び = list(額.items())
    頭 = "、".join(f"{名たち.get(NO, NO)} {_円(v)}" for NO, v in 並び[:3])
    # 「見込み」の字は確認ページの .estimate の枠の外に書かない（qa-html）
    return f"今の値で計算した総支給: {頭}" + (f" ほか {len(並び) - 3} 人" if len(並び) > 3 else "")


def _計(d: dict):
    try:
        return sum(Decimal(str(v)) for v in d.values() if v is not None)
    except InvalidOperation:
        return None


def _候補の行(候補の額: dict) -> str:
    計 = []
    for 候補, d in 候補の額.items():
        try:
            計.append(f"{候補}＝計 {_円(sum(Decimal(str(v)) for v in d.values() if v is not None))}")
        except InvalidOperation:
            計.append(f"{候補}＝額なし")
    return "候補ごとの総支給: " + "／".join(計)


def _言い換え(字: str) -> str:
    """項目の名（`分野.名`）を辞書の 意味 に言い換える（答える人の言葉へ。殻の AI がさらに直してよい）。"""
    for it in sorted(口.項目たち(), key=lambda x: -len(x["項目"])):
        字 = 字.replace(f"「{it['項目']}」", f"「{it['意味']}」").replace(it["項目"], it["意味"])
    return 字


def _何の字(s: dict, 何: str) -> str:
    """何について の「何」の札（答える人の言葉・短く）。"""
    if s.get("項目たち"):
        try:
            return 口.項目(s["項目たち"][0])["意味"] + (" ほか" if len(s["項目たち"]) > 1 else "")
        except KeyError:
            pass
    m = re.match(r"法の線: ([^\s（「]+)", 何) or re.fullmatch(r"「([^」]+)」が無い.*", 何)
    for 名 in ([m.group(1)] if m else []) + [何]:
        try:
            return 口.項目(名)["意味"]
        except KeyError:
            continue
    if 箱(s) == その月:
        return "払う物・引く物・人の変わり"
    行の名 = re.search(r"「([^」]+)」", 何)
    return 行の名.group(1) if 行の名 else _言い換え(何)[:20]


def _誰の札(人: list[str], 名たち: dict | None) -> str:
    名たち = 名たち or {}
    if 人:   # 問いの人（確認ページの span.who・切り抜きに写ってよい名）。何人かは頭の 1 人と人数
        return "人:" + str(名たち.get(人[0], 人[0])) + (f" ほか {len(人) - 1} 人" if len(人) > 1 else "")
    return "全員"


def _並べた名(名たち_: list[str], 上限: int = 3) -> str:
    return "、".join(名たち_[:上限]) + (f" ほか {len(名たち_) - 上限}" if len(名たち_) > 上限 else "")


