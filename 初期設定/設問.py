def 会社の値(タブ: dict, 会社: str, 支給月: str | None = None) -> dict:
    """03_マスタ「会社」の行 → {項目: 今の値}（その支給月以前で最も新しい 適用開始。空の 適用開始 は前から効く）。"""
    月 = 段.月にそろえる(支給月) if 支給月 else None
    out: dict[str, tuple[str, str]] = {}
    for r in _その会社(タブ.get("会社", ()), 会社):
        名 = str(r.get("項目", "")).strip()
        if not 名:
            continue
        始め = 段.月にそろえる(r.get("適用開始")) or "" if not _空(r.get("適用開始")) else ""
        if 月 and 始め and 始め > 月:
            continue
        if 名 not in out or 始め >= out[名][0]:
            out[名] = (始め, r.get("今の値"))
    return {k: v for k, (_, v) in out.items() if not _空(v)}


def _置かれた(タブ: dict, 会社: str, 名: str, 型たち=None, NOたち=None, 支給月=None) -> bool:
    """項目が会社・勤務の型・人のどこかに既定でなく置かれているか（型たち・NOたち は見る行を狭める）。"""
