def _根へまとめる(out: dict, 集計の番号: dict) -> None:
    """同じ根から出た仮の種を根の問い 1 つにまとめる（人ごと）。
    ① 入口から出る集計の仮（読み取りの確かめが要確認の日がある など）→ その人の入口の要確認の種へ。
    ② 芯/計算 の月の数字の仮（「月の数字「語」が仮（芯/集計 問N）」）→ 指す集計の問いの種へ（① で入口へ移った人は入口の種へ）。
    ③ 締めの仮（月次 の 問い「締め」＝確定した勤怠が無い・締まっていない人）→ その人の入口の要確認の種へ
       （読みの要確認が残る人は確定した勤怠へ書かない＝締まっていないのは入口の問いが根。答えれば確定して締まる）。
    まとめた種の 変わる項目 は根に足し、根の `まとめた` に元の 何が無いか を残す。根の無い人の分はそのまま残す。"""
    入口の根: dict[str, list[str]] = {}
    for 何, x in out.items():
        if x["出所"] == "入口":
            for p in x["人"]:
                入口の根.setdefault(p, []).append(何)
    移した: dict[str, dict[str, list[str]]] = {}   # 集計の 何 → {人: [根の 何]}
    空にした = set()

    def 寄せる(元: dict, 根たち: list[str]) -> None:
        for r in 根たち:
            _足す(out[r]["変わる項目"], 元["変わる項目"])
            _足す(out[r].setdefault("まとめた", []), [元["何が無いか"]])

    for 何, x in list(out.items()):
        if x["出所"] not in ("集計", "締め") or (x["出所"] == "集計" and 何 not in _入口から出る集計の仮):
            continue
        残る = []
        for p in x["人"]:
            if 入口の根.get(p):
                寄せる(x, 入口の根[p])
                移した.setdefault(何, {})[p] = 入口の根[p]
            else:
                残る.append(p)
        x["人"] = 残る
        if not 残る:
            空にした.add(何)
    for 何, x in list(out.items()):
        m = _集計の問いを指す.search(何) if x["出所"] == "計算" else None
        if not m:
            continue
        残る = []
        for p in x["人"]:
            根たち: list[str] = []
            for n in m.group(1).split("、"):
                元 = 集計の番号.get(n)
                if 元 in out and 元 not in 空にした and p in out[元]["人"]:
                    _足す(根たち, [元])
                _足す(根たち, 移した.get(元, {}).get(p, []))
            if 根たち:
                寄せる(x, 根たち)
            else:
                残る.append(p)
        x["人"] = 残る
        if not 残る:
            空にした.add(何)
    for 何 in 空にした:
        del out[何]


