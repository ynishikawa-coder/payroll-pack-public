    表 = list(質問の行たち or [])
    if not 表:
        return ""
    if isinstance(表[0], (list, tuple)):
        値 = [list(r) for r in 表]
        訳 = 前の答え.見出しの訳(値)
        if 訳:
            return 訳
        h = {str(x).strip() for x in 値[0]}
    else:
        h = {str(k).strip() for r in 表 for k in r}
    無い = [k for k in _照らしに要る見出し if k not in h]
    if 無い:
        前 = [f"{k}（今の名 {v}）" for k, v in 前の答え.前の見出し.items() if k in h and v in 無い]
        return f"見出しに {'・'.join(無い)} が無い" + (f"・前の見出し {'・'.join(前)}＝寄せる道具で今の型へ直す" if 前 else "")
    悪い = 前の答え.読めない番号(段.行たち(表))
    if 悪い:
        return (f"今の形（Q<支給年月 6 桁>-<順>）でない問いの番号 {'・'.join(悪い[:5])}"
                f"{f' ほか {len(悪い) - 5} 件' if len(悪い) > 5 else ''}＝寄せる道具で今の形へ直す")
    return ""


