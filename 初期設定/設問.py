_決まった語の変わる事 = ("原本を送る", "決まりは無い", "法の線に直して払う", "今の払い方のまま払う", "読んだとおり")


# ── 答えの反映の照らし ──────────────────────────────────────

def 反映の照らし(質問の行たち, タブ: dict, 会社: str, *, md: dict | None = None, 支給月: str | None = None, 置き場=None) -> dict:
    """答えのある問いの 反映先 が、効く設定まで埋まったかの一覧。

    反映先の形: `03_マスタ/<タブ>/<項目>`（会社・勤務の型・社員・支給控除の項目・人ごとの支給控除）か `<md の名>#<見出し>`・
    `04_台帳/月の変動`（読点で並べてよい）。返す物: 行たち（{問いの番号, 反映先, 状態, 訳}）・赤（埋まっていない・答えと値が違う）。
    同じ問いの番号の行が幾つもあれば一番下の行（送り直しの答え）を見る。答えが「分からない」の問いはまだ答えの無い問いと同じに見ない。
    状態: 埋まった／空／答えと値が違う／承知の印が無い／まだ法の線を下回る／反映先が無い／見ていない（md や台帳を渡されていない）。"""
    行たち, 赤 = [], []
    点検 = None
    md = md or {}
    会値 = 会社の値(タブ, 会社, 支給月)
    for q in 口.今の問いの行たち(段.行たち(質問の行たち)):
        回答 = 口.答えの芯(q.get("回答"))
        if not 回答 or 回答 == "分からない" or str(q.get("会社", 会社)).strip() not in ("", 会社):
            continue
        番号 = str(q.get("問いの番号", "")).strip()
        先たち = [w.strip() for w in re.split(r"[、,]", str(q.get("反映先") or "")) if w.strip()]
        b = 箱(q)
        if not 先たち:
            行たち.append({"問いの番号": 番号, "反映先": "", "状態": "反映先が無い", "訳": "答えがあるのに反映先が空"})
            continue
        if b == "法の線" and not _知らせの種か(q):   # 法の線の知らせ（計算は確定）の答えは記録の先を見るだけ（下の 1 つずつの先）
            承知 = "まま" in 回答 or "承知" in 回答
            名 = re.match(r"法の線: ([^\s（「]+)", str(q.get("何が無いか", "")))   # 点検の種「線（誰）」も芯の赤の種「線「値」…」も
            名 = 名.group(1) if 名 else ""
            印先 = [w for w in 先たち if w.endswith("/" + 承知の口.項目)]
            if 承知 and not 印先:
                行たち.append({"問いの番号": 番号, "反映先": "、".join(先たち), "状態": "承知できない線",
                             "訳": f"{名} は承知できる線の外＝法の線で計算し続ける（事務所が会社と話す）"})
                continue
            if 承知:
                ok = False
                for w in 印先:
                    _, タブ名, _ = w.split("/", 2)
                    rows = [会値] if タブ名 == "会社" else _その会社(タブ.get(タブ名, ()), 会社)
                    ok = ok or any(承知の口.読む(r.get(承知の口.項目))[0].get(名) == 番号 for r in rows)
                状態 = "埋まった" if ok else ("承知の印が無い" if 印先 else "反映先が無い")
                訳 = f"{承知の口.項目} に {名}={番号} が無い" if not ok else ""
            else:
                if 点検 is None:
                    点検 = 法の線の点検(タブ, 会社, 支給月, 置き場=置き場)
                残る = [x for x in 点検["食い違い"] if x["項目"] == 名 and x["状態"] == "食い違い"]
                状態, 訳 = ("まだ法の線を下回る", f"{名} が " + "・".join(f"{x['段']} {x['値']}" for x in 残る)) if 残る else ("埋まった", "")
            行たち.append({"問いの番号": 番号, "反映先": "、".join(先たち), "状態": 状態, "訳": 訳})
            continue
        for w in 先たち:
            状態, 訳 = _一つの先(w, q, 回答, タブ, 会社, 会値, md)
            行たち.append({"問いの番号": 番号, "反映先": w, "状態": 状態, "訳": 訳})
    for r in 行たち:
        if r["状態"] not in ("埋まった", "見ていない"):
            赤.append(f"{r['問いの番号']} {r['反映先']}: {r['状態']}" + (f"（{r['訳']}）" if r["訳"] else ""))
    return {"行たち": 行たち, "赤": 赤}


def _一つの先(先: str, q: dict, 回答: str, タブ: dict, 会社: str, 会値: dict, md: dict) -> tuple[str, str]:
    if 先 == 日の答えの先:   # 答えそのものが先（入口の文脈.日の答え が読む。読めない答えは入口の文脈の知らせ）
        return ("見ていない", "直した原本を待つ（口は原本から読む）") if 回答 == "原本を送る" else ("埋まった", "")
    if 先 == 原本の先:
        return "見ていない", "直した原本を月のフォルダの 01_原本 に置いて回し直す（口は原本から読む）"
    if "#" in 先 or 先.endswith(".md"):
        名, _, 見出し = 先.partition("#")
        if 名 not in md:
            return "見ていない", "md を渡されていない"
        本文 = md[名]
        if 見出し:
            m = re.search(rf"^#+\s*{re.escape(見出し)}\s*$(.*?)(?=^#|\Z)", 本文, re.M | re.S)
            本文 = m.group(1) if m else ""
        番号 = str(q.get("問いの番号", "")).strip()
        return ("埋まった", "") if 番号 and 番号 in 本文 else ("空", f"{先} に 出所 {番号} の行が無い")
    部 = 先.split("/")
    if 部[0] != "03_マスタ" or len(部) < 2:
        return "見ていない", "マスタの外（殻が見る）"
    タブ名 = 部[1]
    名 = 部[2] if len(部) > 2 else ""
    誰 = {w.strip() for w in re.split(r"[、,]", str(q.get("答えで変わる項目と人") or "")) if w.strip()}
    if タブ名 == "会社":
        v = 会値.get(名)
        if _空(v):
            # 会社の段に置ける項目でも、勤務の型・人の段に置いてあれば効く
            if 名 and _置かれた(タブ, 会社, 名):
                return "埋まった", ""
            return "空", f"会社のタブに {名} の行が無い"
        return _値を照らす(名, v, q, 回答)
    if タブ名 in ("勤務の型", "社員"):
        鍵 = "型の名" if タブ名 == "勤務の型" else "NO"
        rows = _その会社(タブ.get(タブ名, ()), 会社)
        当たる = [r for r in rows if str(r.get(鍵)) in 誰] or rows
        空の行 = [str(r.get(鍵)) for r in 当たる if _空(r.get(名))]
        if not 当たる or 空の行:
            if not 当たる or len(空の行) == len(当たる):
                if 名 in 会値:   # 会社の段で置いた
                    return _値を照らす(名, 会値[名], q, 回答)
            return "空", f"{タブ名} の {名} が空（{'、'.join(空の行) or '行が無い'}）"
        for r in 当たる:
            s = _値を照らす(名, r.get(名), q, 回答)
            if s[0] != "埋まった":
                return s
        return "埋まった", ""
    if タブ名 in ("支給控除の項目", "人ごとの支給控除"):
        rows = _その会社(タブ.get(タブ名, ()), 会社)
        if not 名:
            return ("埋まった", "") if rows else ("空", f"{タブ名} に行が無い")
        try:
            it = 口.項目(名)
        except (KeyError, ValueError):
            it = None
        if it and it.get("置く所") and タブ名 == "支給控除の項目":   # 列で持つ項目（割増.基礎に入る など）
            return ("埋まった", "") if rows else ("空", f"{タブ名} に行が無い")
        return ("埋まった", "") if any(str(r.get("項目")) == 名 for r in rows) else ("空", f"{タブ名} に {名} の行が無い")
    return "見ていない", f"{タブ名} は照らす口の外"


def _値を照らす(名: str, v, q: dict, 回答: str) -> tuple[str, str]:
    """答えが選べる値の語か 見当のとおり なら、置いた値と同じかを見る（違えば 答えと値が違う）。"""
    try:
        it = 口.項目(名)
    except (KeyError, ValueError):
        return "埋まった", ""
    語たち = {_語(w) for w in str(it.get("選べる値", "")).split("・") if w.strip()}
    期待 = str(q.get("見当", "")) if 回答 == "見当のとおり" else 回答
    if _語(期待) in 語たち and _語(期待) != _語(v):
        return "答えと値が違う", f"答え「{期待}」・置いた値「{v}」"
    return "埋まった", ""


# ── 呼び口 ────────────────────────────────────────────────

def _口(名: str, 入力: dict):
    if 名 == "点検":
        r = 法の線の点検(入力["タブ"], 入力["会社"], 入力.get("支給月"), 日=入力.get("日"))
        return {**r, "種": 法の線の種(r, 入力["会社"])}
    if 名 == "網":
        return {"種": 型ごとの網(入力["タブ"], 入力["会社"], 既にある=入力.get("既にある", ()), 足す型=入力.get("足す型", ()),
                             支給月=入力.get("支給月"))}
    if 名 == "その月だけの物":
        return {"種": [その月だけの物の問い(入力["支給月"], 入力["会社"], 入力.get("読んだ"))]}
    if 名 == "種":
        return {"種": 種を集める(入力["回した"])}
    if 名 == "まとめる":
        return まとめる(入力["種"], 会社=入力["会社"], 支給月=入力["支給月"], 今日=入力["今日"],
                    次の問いの番号=入力.get("次の問いの番号", 1), 既にある=入力.get("既にある", ()),
                    名たち=入力.get("名たち"), 候補の額=入力.get("候補の額"), 誰が聞いた=入力.get("誰が聞いた", "AI"),
                    読んだ資料=入力.get("読んだ資料", ()), タブ=入力.get("タブ"), 推し量り=入力.get("推し量り"))
    if 名 == "集まり":
        return 集まりへ直す(入力["種"], 入力["タブ"], 入力["会社"])
    if 名 == "照らし":
        return 反映の照らし(入力["問い"], 入力["タブ"], 入力["会社"], md=入力.get("md"), 支給月=入力.get("支給月"))
    raise SystemExit(f"口 {名!r} は 点検・網・その月だけの物・種・集まり・まとめる・照らし のどれか")


