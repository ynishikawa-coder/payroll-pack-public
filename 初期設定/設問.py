    out = set(s.get("項目たち") or ())
    for k in ("線の名", "線の項目"):
        if s.get(k):
            out.add(str(s[k]))
    名 = _何の項目(str(s.get("何が無いか", "")).strip())
    if 名:
        out.add(名)
    for w in re.split(r"[、,]", str(s.get("答えで変わる項目と人") or "")):
        if w.strip() and _何の項目(w.strip()):
            out.add(w.strip())
    m = re.match(r"読み方: 網/(.+)/([^/]+)$", str(s.get("何が無いか", "")).strip())
    if m:
        out |= {f"網/{t}/{m.group(2)}" for t in m.group(1).split("・")}
    return out


