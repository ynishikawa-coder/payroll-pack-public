"""新しい会社を型で始める時に、殻が Drive に当てる物を起こして返す。Drive を開かない。過去の答えから値を逆算しない。

  python3 初期設定/始める.py < 入力.json > 出力.json

返す物: 作る置き場・起こすシートの見出し・md 3 枚の本文・会社の一覧と管理表「会社」の行・
変更の記録の行（書類から入れた値）・質問と回答の行（足りない値を見当つきの 1 問に）・知らせ。入力の形は 初期設定/README.md。
置き場の（M月分）は会社の `支払.支給の月`（無ければ項目の既定 翌月）から出す。
"""
import datetime as dt
import importlib.util
import json
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("初期設定_型の口", ここ / "型の口.py")
口 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(口)
_spec = importlib.util.spec_from_file_location("初期設定_確認ページ", ここ.parent / "確認ページ" / "確認ページ.py")
確認ページ = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(確認ページ)

組の木 = ["00_目次", "01_ルール", "03_マスタ", "04_台帳_<支給年>", "10_月ごと/<支給月>/01_原本", "10_月ごと/<支給月>/02_加工",
        "10_月ごと/<支給月>/03_出力/01_取り込み", "10_月ごと/<支給月>/03_出力/02_支給控除一覧",
        "10_月ごと/<支給月>/03_出力/03_有給休暇管理表", "10_月ごと/<支給月>/03_出力/04_明細",
        "20_配る物/<支給月>", "90_履歴"]
組のシート = ["03_マスタ", "04_台帳_<支給年>", "質問と回答"]


def 支給年(支給月: str) -> str:
    return 支給月[:4]


def 月の名(支給月: str, 支給の月=None) -> tuple[str, list[str]]:
    """YYYY.MM支給 → (YYYY.MM支給（M月分）, 知らせ)。M は会社の `支払.支給の月` から（確認ページの `支給月の名と知らせ` の 1 か所）。"""
    return 確認ページ.支給月の名と知らせ(支給月, 支給の月)


def _効く値(名: str, 入力: dict):
    """会社の値か書類の値があればそれ、無ければ項目の既定（null は None）。"""
    会社 = 入力.get("会社の値", {})
    if 名 in 会社:
        return 会社[名]["値"] if isinstance(会社[名], dict) else 会社[名]
    return 口.項目(名).get("既定")


def _要るか(it: dict, 入力: dict) -> bool:
    要る = it.get("要る時")
    if not 要る:
        return True
    値たち = {_効く値(要る["項目"], 入力)}
    for 段 in ("勤務の型", "人"):
        for r in 入力.get(段, []):
            値たち.add(r.get(要る["項目"]))
    return bool(値たち & set(要る["値"]))


def 足りない値(入力: dict) -> list[dict]:
    """聞く項目のうち、会社にも全部の勤務の型にも全部の人にも値が無い物 → [{項目, 段, 誰}]。"""
    会社の値 = 入力.get("会社の値", {})
    out = []
    for it in 口.項目たち():
        if not it.get("聞く") or not _要るか(it, 入力):
            continue
        名 = it["項目"]
        if "会社" in it["段"] and 名 in 会社の値:
            continue
        欠け = {}
        for 段, 鍵 in (("勤務の型", "型の名"), ("人", "NO")):
            if 段 in it["段"]:
                rows = 入力.get(段, [])
                欠け[段] = [str(r.get(鍵)) for r in rows if r.get(名) in (None, "")] if rows else ["（無い）"]
        if "会社" in it["段"]:
            if any(not v for v in 欠け.values()):
                continue  # 下の段の全部に値がある
            out.append({"項目": 名, "段": "会社", "誰": []})
        else:
            段 = next(iter(欠け))
            if 欠け[段]:
                out.append({"項目": 名, "段": 段, "誰": 欠け[段]})
    return out


def 問いを起こす(入力: dict) -> list[dict]:
    """足りない値 1 つにつき 1 問（同じ項目の人や型は 1 問に並べる）。見当は入力の「見当」からだけ取る。"""
    見当たち = 入力.get("見当", {})
    支給月, 会社 = 入力["最初の支給月"], 入力["会社"]
    番号 = int(入力.get("次の問いの番号", 1))
    out = []
    for 欠け in 足りない値(入力):
        it = 口.項目(欠け["項目"])
        見当 = 見当たち.get(it["項目"], {})
        誰 = f"（{欠け['段']}: {'、'.join(欠け['誰'])}）" if 欠け["誰"] else ""
        row = {
            "会社": 会社,
            "問いの番号": f"Q{支給月[:4]}{支給月[5:7]}-{番号:02d}",
            "支給月": 支給月,
            "聞いた日": 入力.get("今日", dt.date.today().isoformat()),
            "誰に": "先方",
            "何が無いか": it["項目"],
            "質問": f"{it['意味']}{誰}を教えてください。選べる値: {it['選べる値']}",
            "見当": str(見当.get("値", "")),
            "見当の拠り所": 見当.get("拠り所", "無し"),
            "答えで変わる項目と人": it["項目"] + (f"、{'、'.join(欠け['誰'])}" if 欠け["誰"] else ""),
            "答え方の例": "見当のとおり／" + it["選べる値"] if 見当 else it["選べる値"],
            "回答": "", "回答日": "",
            "反映先": f"03_マスタ/{ {'会社': '会社', '勤務の型': '勤務の型', '人': '社員'}[欠け['段']] }/{it['項目']}",
            "反映済み": "",
        }
        out.append({k: row.get(k, "") for k in 口.見出し("質問と回答", "質問")})
        番号 += 1
    return out


def 変更の記録(入力: dict) -> list[dict]:
    """書類から入れた会社の値を 1 行ずつ（確かめ＝確認済。出所の無い値は受けない）。"""
    out = []
    for 名, v in 入力.get("会社の値", {}).items():
        口.項目(名)  # 辞書に無い名はここで落ちる
        if not isinstance(v, dict) or not v.get("書類の名"):
            raise ValueError(f"{名}: 会社の値には 書類の名 が要る（書類の無い値は見当にして問いへ）")
        out.append({"会社": 入力["会社"], "記録日": 入力.get("今日", ""), "適用支給月": 入力["最初の支給月"], "NO": "",
                    "項目": 名, "前の値": "", "新しい値": v["値"], "書類の名": v["書類の名"], "問いの番号": "", "確かめ": "確認済"})
    return out


def 始める(入力: dict) -> dict:
    月, 知らせ = 月の名(入力["最初の支給月"], _効く値("支払.支給の月", 入力))
    年 = 支給年(入力["最初の支給月"])
    組 = 入力["組"]
    置き場 = [f"10_会社/{組}/" + p.replace("<支給月>", 月).replace("<支給年>", 年) for p in 組の木]
    シート = {}
    for s in 口.型()["シート"]:
        if s["シート"] in 組のシート:
            名 = s["シート"].replace("<支給年>", 年)
            シート[名] = {t["タブ"]: 口.見出し(s["シート"], t["タブ"]) for t in s["タブ"]}
    md = {m["名"]: 口.雛形(m["名"]).replace("<組>", 組) for m in 口.型()["md の雛形"] if m["置き場"].startswith("10_会社")}
    return {
        "型の版": 口.版(),
        "置き場": 置き場,
        "シート": シート,
        "md": md,
        "会社の一覧の行": {"会社": 入力["会社"], "組": 組, "担当": 入力.get("担当", ""), "状態": "立ち上げ"},
        "管理表の会社の行": {"会社": 入力["会社"], "組": 組, "型の版": 口.版(), "選んだ部品": 入力.get("選んだ部品", "")},
        "変更の記録": 変更の記録(入力),
        "問い": 問いを起こす(入力),
        "知らせ": 知らせ,
    }


if __name__ == "__main__":
    json.dump(始める(json.load(sys.stdin)), sys.stdout, ensure_ascii=False, indent=1)
    print()
