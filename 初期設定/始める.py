# 組のフォルダ（新しい Drive の形）。確認事項のページの置き場の名（8_確認事項・9_履歴）は 確認ページ/確認ページ.py が持つ＝そこから引く
# 名の正本は 型.json の木（写さない）。<支給月> は 名の形.月 の形
_月 = 口.名の形("月")["形"]
組の木 = [口.名("決まり"), 口.名("マスタ"), 口.台帳の名(), *(f"{口.名('月ごと')}/{_月}/{x}" for x in 口.物たち("月の物")),
        確認ページ.置き場の名, 確認ページ.履歴の名]
組のシート = [口.名("マスタ"), 口.台帳の名(), 口.名("質問と回答")]


def 支給年(支給月: str) -> str:
    return 支給月[:4]


def 月の名(支給月: str, 支給の月=None) -> tuple[str, list[str]]:
    """YYYY.MM支給 → (YYYY.MM支給（M月分）, 知らせ)。M は会社の `支払.支給の月` から（確認ページの `支給月の名と知らせ` の 1 か所）。"""
    return 確認ページ.支給月の名と知らせ(支給月, 支給の月)


def _効く値(名: str, 入力: dict):
    """会社の値か書類の値があればそれ、無ければ項目の既定（null は None）。"""
    会社 = 入力.get("会社の値", {})
    if 名 in 会社:
        return 会社[名]["値"] if isinstance(会社[名], dict) else 会社[名]
    return 口.項目(名).get("既定")


def _要るか(it: dict, 入力: dict) -> bool:
    要る = it.get("要る時")
    if not 要る:
        return True
    値たち = {_読み(_効く値(要る["項目"], 入力))}
    for 段 in ("勤務の型", "人"):
        for r in 入力.get(段, []):
            値たち.add(_読み(r.get(要る["項目"])))
    return bool(値たち & {_読み(v) for v in 要る["値"]})


def _読み(v):
    """選べる値の語を空白と後ろの括弧を除いて読む（`4 週 4 休（起算日つき）` と `4週4休` を同じに。芯/集計 の読みと同じ）。"""
    if v is None:
        return None
    s = "".join(str(v).split())
    return s.split("（", 1)[0] if s.endswith("）") and not s.startswith("（") else s


def 足りない値(入力: dict) -> list[dict]:
    """聞く項目のうち、会社にも全部の勤務の型にも全部の人にも値が無い物 → [{項目, 段, 誰}]。"""
    会社の値 = 入力.get("会社の値", {})
    out = []
    for it in 口.項目たち():
        if not it.get("聞く") or not _要るか(it, 入力):
            continue
        名 = it["項目"]
        if "会社" in it["段"] and 名 in 会社の値:
            continue
        欠け = {}
        for 段, 鍵 in (("勤務の型", "型の名"), ("人", "NO")):
            if 段 in it["段"]:
                rows = 入力.get(段, [])
                欠け[段] = [str(r.get(鍵)) for r in rows if r.get(名) in (None, "")] if rows else ["（無い）"]
        if "会社" in it["段"]:
            if any(not v for v in 欠け.values()):
                continue  # 下の段の全部に値がある
            out.append({"項目": 名, "段": "会社", "誰": []})
        else:
            段 = next(iter(欠け))
            if 欠け[段]:
                out.append({"項目": 名, "段": 段, "誰": 欠け[段]})
    return out


def 問いを起こす(入力: dict) -> list[dict]:
    """足りない値 1 つにつき 1 問（同じ項目の人や型は 1 問に並べる）。見当は入力の「見当」からだけ取る。"""
    見当たち = 入力.get("見当", {})
    支給月, 会社 = 入力["最初の支給月"], 入力["会社"]
    # 番号は質問と回答に既にある行の同じ支給年月の次から（`既にある` は必ず渡す＝無ければ []。渡さないと止める＝黙って 01 から振らない）
    番号 = max(int(入力.get("次の問いの番号") or 1), 口.次の問いの番号(入力.get("既にある"), 支給月))
    out = []
    for 欠け in 足りない値(入力):
        it = 口.項目(欠け["項目"])
        見当 = 見当たち.get(it["項目"], {})
        誰 = f"（{欠け['段']}: {'、'.join(欠け['誰'])}）" if 欠け["誰"] else ""
        row = {
            "会社": 会社,
            "問いの番号": 口.問いの番号(支給月, 番号),
            "支給月": 支給月,
            "聞いた日": 入力.get("今日", dt.date.today().isoformat()),
            "何が無いか": it["項目"],
            "質問": f"{it['意味']}{誰}を教えてください。選べる値: {it['選べる値']}",
            "見当": str(見当.get("値", "")),
            "見当の拠り所": 口.拠り所に直す(見当.get("拠り所")),   # 空は型の既定・頭の無い文は 既定（…）
            "答えで変わる項目と人": it["項目"] + (f"、{'、'.join(欠け['誰'])}" if 欠け["誰"] else ""),
            "答え方の例": "見当のとおり／" + it["選べる値"] if 見当 else it["選べる値"],
            "反映先": f"{口.名('マスタ')}/{ {'会社': '会社', '勤務の型': '勤務の型', '人': '社員'}[欠け['段']] }/{it['項目']}",
        }
        out.append(口.問いの行(**row))   # 誰が聞いた・誰に・反映済み などの空の列は型の既定
        番号 += 1
    return out


def 変更の記録(入力: dict) -> list[dict]:
    """書類から入れた会社の値を 1 行ずつ（確かめ＝確認済。出所の無い値は受けない）。"""
    out = []
    for 名, v in 入力.get("会社の値", {}).items():
        口.項目(名)  # 辞書に無い名はここで落ちる
        if not isinstance(v, dict) or not v.get("書類の名"):
            raise ValueError(f"{名}: 会社の値には 書類の名 が要る（書類の無い値は見当にして問いへ）")
        out.append({"会社": 入力["会社"], "記録日": 入力.get("今日", ""), "適用支給月": 入力["最初の支給月"], "NO": "",
                    "項目": 名, "前の値": "", "新しい値": v["値"], "書類の名": v["書類の名"], "問いの番号": "", "確かめ": "確認済"})
    return out


def _照らし(正解: dict):
    """前任の正解を 道具/答え合わせ の照合の段で照らす（芯に混ぜない＝道具を呼ぶだけ）。必要な物が欠ければ止める（黙って飛ばさない）。"""
    if not isinstance(正解, dict):
        raise TypeError("前任の正解 は {答え, 芯の行, つなぎ, 人の状態} の dict で渡す")
    欠け = [k for k in ("答え", "芯の行", "つなぎ") if not 正解.get(k)]
    if 欠け:
        raise ValueError(f"前任の正解 に {'・'.join(欠け)} が無い（照らせない。答え合わせの段は外せない）")
    if str(ここ.parent) not in sys.path:
        sys.path.insert(0, str(ここ.parent))
    from 道具.答え合わせ import 照合の段
    人の状態 = {(str(r["支給月"]), str(r["会社"]), str(r["NO"])): r["状態"] for r in 正解.get("人の状態") or ()}
    return 照合の段.照らす(正解["芯の行"], 正解["答え"], 正解["つなぎ"], 人の状態=人の状態, 仮の人の行=正解.get("仮の人の行") or ())


def _資料の名(出所: str) -> str:
    return str(出所 or "").split("#", 1)[0].rsplit("/", 1)[-1]


def 答え合わせの一致(照らした, 答え) -> list[dict]:
    """差の表から、会社×項目の行が全部 差 0 の項目 → [{項目, 値, 出所: 答え合わせで一致, 拠り所}]。1 行でも差（片方だけを含む）があれば入れない。
    拠り所は 月次/例の確かめ.py の `過去の結果 <支給月> <資料の名> <NO>:<項目> 一致` の形。"""
    頭, *行たち = 照らした.差の表
    i = {k: n for n, k in enumerate(頭)}
    資料 = {}
    for a in getattr(答え, "行たち", 答え) or ():
        g = a.get if isinstance(a, dict) else (lambda k, a=a: getattr(a, k, None))
        資料.setdefault((str(g("支給月")), str(g("会社")), str(g("項目"))), _資料の名(g("出所")))
    束: dict[tuple, list] = {}
    for r in 行たち:
        束.setdefault((r[i["会社"]], r[i["項目"]]), []).append(r)
    out = []
    for (会社, 名), rs in 束.items():
        if any(r[i["差"]] != "0" or r[i["差の見立て"]] for r in rs):
            continue
        拠り所 = "・".join(
            f"過去の結果 {r[i['支給月']].replace('-', '.')}支給 {資料.get((r[i['支給月']], 会社, 名), '')} {r[i['NO']]}:{名} 一致"
            for r in rs)
        値 = "、".join(f"{r[i['NO']]}:{r[i['こちら']]}" for r in rs)
        out.append({"項目": 名, "値": 値, "出所": "答え合わせで一致", "会社": 会社, "拠り所": 拠り所})
    return out


def 閉じたを揃える(閉じた) -> list[dict]:
    """閉じた問いを {項目, 値, 出所, 仮, ...} にそろえる。`設問.閉じる`・`設問.まとめる` の戻りの `閉じた`
    （{何が無いか, 質問, 出所, 値, 仮, 問いの番号?}）をそのまま渡せる（何が無いか＝項目）。"""
    return [{**x, "項目": x.get("項目") or str(x.get("何が無いか", "") or "").strip()} for x in 閉じた or ()]


def 始める(入力: dict) -> dict:
    """返す物（前→後）: 前は 型の版・置き場・シート・md・会社の一覧の行・管理表の会社の行・変更の記録・問い・知らせ。
    後はそれに 答え合わせ・仕分け・読みの一覧・止める・止めた訳 を足す。前任の未決に未仕分けが残れば
    {型の版, 止める: True, 止めた訳, 仕分け} だけを返し、置き場も問いも起こさない（会社を先へ進めない）。"""
    正解 = 入力.get("前任の正解")
    照 = _照らし(正解) if 正解 is not None else None
    一致 = 答え合わせの一致(照, 正解["答え"]) if 照 is not None else []
    閉じた = 閉じたを揃える(入力.get("閉じた"))
    決まった閉じた = [x for x in 閉じた if not x.get("仮")]   # 見当（仮の答え）で閉じた物は前任の未決を決定済みにしない
    分け = 仕分け.仕分ける(入力["前任の未決"], 入力.get("会社の値"), 決まった閉じた, 一致) if 入力.get("前任の未決") is not None else None
    if 分け and 分け["止める"]:
        return {"型の版": 口.版(), "止める": True,
                "止めた訳": [f"前任の未決 {r.get('番号', '')} が未仕分け: {r['訳']}" for r in 分け["未仕分け"]],
                "仕分け": 分け}
    閉じた名 = {x["項目"] for x in [*一致, *閉じた] if x.get("項目")}
    問い = [q for q in 問いを起こす(入力) if q["何が無いか"] not in 閉じた名]
    if 分け:
        問い += _聞く問い(分け["聞く"], 入力, {q["何が無いか"] for q in 問い} | 閉じた名, len(問い))
    # 閉じて外した問いの番号を詰める（番号は既にある行の次から続けて振る）
    始め = max(int(入力.get("次の問いの番号") or 1), 口.次の問いの番号(入力.get("既にある"), 入力["最初の支給月"]))
    問い = [{**q, "問いの番号": 口.問いの番号(入力["最初の支給月"], 始め + n)} for n, q in enumerate(問い)]
    答え合わせ = None if 照 is None else {
        "一致": 一致, "問いの種": [dict(q) for q in 照.問いの種], "差の行の数": 照.差の行の数, "要確認": list(照.要確認)}
    一覧 = 読み.一覧(読み.会社の値から(入力.get("会社の値")), 閉じた, 一致, 分け["決定済み"] if 分け else ())
    return {**_起こす(入力), "問い": 問い, "答え合わせ": 答え合わせ, "仕分け": 分け, "読みの一覧": 一覧,
            "止める": False, "止めた訳": []}


def _聞く問い(聞く, 入力: dict, 既に: set, 先の数: int) -> list[dict]:
    """仕分けで 聞く になった前任の未決（まだ問いに無い項目）→ 質問と回答の行。"""
    支給月 = 入力["最初の支給月"]
    番号 = max(int(入力.get("次の問いの番号") or 1), 口.次の問いの番号(入力.get("既にある"), 支給月)) + 先の数
    out = []
    for r in 聞く:
        名 = r["項目"]
        if 名 in 既に:
            continue
        it = 口.項目(名)
        out.append(口.問いの行(
            会社=入力["会社"], 問いの番号=口.問いの番号(支給月, 番号), 支給月=支給月,
            聞いた日=入力.get("今日", dt.date.today().isoformat()), 何が無いか=名,
            質問=f"{it['意味']}を教えてください（前任の未決 {r.get('番号', '')}）。選べる値: {it['選べる値']}",
            見当="", 見当の拠り所=口.拠り所に直す(None), 答えで変わる項目と人=名, 答え方の例=it["選べる値"],
            反映先=f"{口.名('マスタ')}/会社/{名}"))
        既に.add(名)
        番号 += 1
    return out


def _起こす(入力: dict) -> dict:
    月, 知らせ = 月の名(入力["最初の支給月"], _効く値("支払.支給の月", 入力))
    年 = 支給年(入力["最初の支給月"])
    組 = 入力["組"]
    置き場 = [口.道("会社の根").replace(口.組の印(), 組) + "/" + p.replace("<支給月>", 月).replace("<支給年>", 年) for p in 組の木]
    シート = {}
    for s in 口.型()["シート"]:
        if s["シート"] in 組のシート:
            名 = s["シート"].replace("<支給年>", 年)
            シート[名] = {t["タブ"]: 口.見出し(s["シート"], t["タブ"]) for t in s["タブ"]}
    md = {m["名"]: 口.雛形(m["名"]).replace("<組>", 組) for m in 口.型()["md の雛形"] if m["置き場"].startswith(口.名("会社たち"))}
    return {
        "型の版": 口.版(),
        "置き場": 置き場,
        "シート": シート,
        "md": md,
        "会社の一覧の行": {"会社": 入力["会社"], "組": 組, "担当": 入力.get("担当", ""), "状態": "立ち上げ"},
        "管理表の会社の行": {"会社": 入力["会社"], "組": 組, "型の版": 口.版(), "選んだ部品": 入力.get("選んだ部品", "")},
        "変更の記録": 変更の記録(入力),
        "知らせ": 知らせ,
    }


