def _行の値(タブ: str, x) -> list[str]:
    逆 = {v: k for k, v in _列[タブ].items()}
    out = []
    for 列名 in 見出し(タブ):
        v = getattr(x, 逆[列名]) if 列名 in 逆 else ""
        if isinstance(v, bool):
            v = 済 if v else ""
        out.append(_字(v))
    return out


def _行を足す(タブ: str, 行たち: list[list[str]]) -> dict:
    return {"する": "行を足す", "ファイル": ファイル(), "タブ": Driveのタブ(タブ), "値": 行たち, "書き方": 口.字のまま}


def _値を書く(タブ: str, 行: int, 値たち: dict[str, str]) -> list[dict]:
    """1 行の中の列（列の名 → 値）を書く手順。並んだ列は 1 つの範囲にまとめる。"""
    頭 = 見出し(タブ)
    位置 = sorted((頭.index(k) + 1, _字(v)) for k, v in 値たち.items())
    手順 = []
    i = 0
    while i < len(位置):
        j = i
        while j + 1 < len(位置) and 位置[j + 1][0] == 位置[j][0] + 1:
            j += 1
        始, 終 = 列の字(位置[i][0]), 列の字(位置[j][0])
        範囲 = f"{始}{行}" if i == j else f"{始}{行}:{終}{行}"
        手順.append({"する": "値を書く", "ファイル": ファイル(), "タブ": Driveのタブ(タブ), "範囲": 範囲,
                   "値": [[v for _, v in 位置[i:j + 1]]], "書き方": 口.字のまま})
        i = j + 1
    return 手順


def 問いを書く(問いたち: list[問い]) -> list[dict]:
    """新しい問いを 問い のタブへ足し、選択肢ごとの振り分けを 振り分け のタブへ候補の行（列 選択肢＝見出し）として足す手順。
    候補の行が在る問いの止まりはその行の 対象 だけ（候補の無い問いは会社を止める）。"""
    行たち = [_行の値("問い", q) for q in 問いたち]
    候補 = [_行の値("振り分け", replace(f, 鍵=q.鍵, 顧客ID=f.顧客ID or q.顧客ID, 反映済み=False, 反映した日="", 選択肢=見))
          for q in 問いたち for 見, fs in q.選択肢の振り分け.items() for f in fs]
    return ([_行を足す("問い", 行たち)] if 行たち else []) + ([_行を足す("振り分け", 候補)] if 候補 else [])


def 問いを足す(今の表: 表, 顧客ID: str, 聞いた支給月: str, 聞いた日: str, 文: str, リンク: str,
            選択肢の振り分け: dict[str, list[振り分け]] | None = None) -> tuple[問い, list[dict]]:
    """鍵を振った新しい問い（状態 聞いている）と、それを足す手順。選択肢の振り分けの鍵はこの問いの鍵にそろえる。
    聞いた支給月 は YYYY-MM だけ書ける（記録の月＝「共通」や空などほかの形は ValueError。効く月は振り分けが持つ）。"""
    if not re.fullmatch(r"\d{4}-(0[1-9]|1[0-2])", str(聞いた支給月 or "")):
        raise ValueError(f"聞いた支給月 は YYYY-MM の形だけ書ける（受けたのは {聞いた支給月!r}＝止め方の月は振り分けの 効く月 に書く）")
    鍵 = 鍵を振る(今の表)
    振 = {k: [replace(f, 鍵=鍵, 顧客ID=f.顧客ID or 顧客ID, 反映済み=False, 反映した日="", 選択肢=k, 行=None) for f in v]
         for k, v in (選択肢の振り分け or {}).items()}
    q = 問い(鍵, 顧客ID, 聞いた支給月, 聞いた日, 文, リンク, 聞いている, 振)
    return q, 問いを書く([q])


def 状態を書く(q: 問い, 状態: str) -> list[dict]:
    """問いの 状態 を書く手順（読んだ表の行が要る）。"""
    if q.行 is None:
        raise ValueError(f"問い {q.鍵} の行が分からない（表から読んだ問いを渡す）")
    return _値を書く("問い", q.行, {"状態": 状態})


def 取り下げる(q: 問い) -> list[dict]:
    """問いを取り下げる手順＝状態を 取り下げ にする（答えの文に印を書かない）。"""
    return 状態を書く(q, 取り下げ)


def 振り分けを書く(振り分けたち: list[振り分け]) -> list[dict]:
    """答えから決めた振り分けの行を足す手順。反映済み・反映した日・選択肢はいつも空で書く（済 は `反映済みを照らして書く`
    だけが書く・候補の行は `問いを書く` だけが書く）。値の要る先で値の空の行（`_値が補足から決まる`）は書けない＝ValueError
    （書き戻しが拒んで 済 にならない行を出さない）。"""
    空 = [f for f in 振り分けたち if _値が補足から決まる(f)]
    if 空:
        raise ValueError("値の要る先で値が空の振り分けは書けない（値を補足から決めて渡す）: "
                         + "、".join(f"{f.鍵}/{f.対象}/{f.反映先}/{f.何を}" for f in 空))
    行たち = [_行の値("振り分け", replace(f, 反映済み=False, 反映した日="", 選択肢="")) for f in 振り分けたち]
    return [_行を足す("振り分け", 行たち)] if 行たち else []


def 答えを振り分ける(q: 問い, 振り分けたち: list[振り分け]) -> list[dict]:
    """答えが届いたが選んだだけでは振り分けが決まらない問い（その他・分からない・問いに無い見出し・値が補足から決まる選択肢・
    チャットの答え）を、AI が答えの字から決めた振り分けで閉じる手順＝振り分けを書く ＋ 状態を 答えた に。
    行の分からない問い（表から読んでいない問い）はここで止まる（振り分けだけ入って 聞いている のまま残る形を出さない）。
    振り分けたち が空なら閉じない（反映しない の行を 1 つ渡す＝今の設定のままで合うと確かめた答え）。"""
    if not 振り分けたち:
        raise ValueError(f"問い {q.鍵} の振り分けが無い（今のままで合う答えは 反映先 反映しない の行を渡す）")
    状態 = 状態を書く(q, 答えた)
    return 振り分けを書く([replace(f, 鍵=q.鍵, 顧客ID=f.顧客ID or q.顧客ID) for f in 振り分けたち]) + 状態


def 原本の名(回答日: str, 本文: str, 受付: str = "") -> str:
    """答えの原本の 1 ファイルの名。送信の印（受付）があれば `答え_<受付>.txt`＝送信そのものが名の正本（回答日も中身も
    名に入れない＝同じ送信を別の日・別の貼り方で貼っても同じ名）。受付の無いチャットの答えは
    `答え_<回答日>_チャット_<中身の印 8 字>.txt`。"""
    元 = "".join(c if c.isalnum() or c in "-_" else "_" for c in _字(受付).strip())
    if 元:
        return f"答え_{元}.txt"
    印 = hashlib.sha1(_字(本文).encode("utf-8")).hexdigest()[:8]
    return f"答え_{_字(回答日).strip()}_チャット_{印}.txt"


def 原本の名の送信(名: str) -> str:
    """答えの原本の名（リンクの末尾でもよい）→ 送信の印。今の形 `答え_<受付>.txt` と前の形 `答え_<日>_<受付>_<8 字>.txt`
    のどちらも読む。チャットの答え・読めない名は空。"""
    n = _字(名).strip().rsplit("/", 1)[-1]
    m = re.fullmatch(r"答え_\d{4}-\d{2}-\d{2}_(.+)_[0-9a-f]{8}\.txt", n)
    if m:
        return "" if m.group(1) == "チャット" else m.group(1)
    m = re.fullmatch(r"答え_(.+)\.txt", n)
    return m.group(1) if m else ""


def _原本を作る(本文: str, 回答日: str, 受付: str = "") -> tuple[str, dict]:
    名 = 原本の名(回答日, 本文, 受付)
    return f"{原本の置き場()}/{名}", {"する": "ファイルを作る", "先": 原本の置き場(), "名": 名, "本文": 本文}


def _値が補足から決まる(f: 振り分け) -> bool:
    """値の要る先（反映しない・台帳 の外＝台帳は値を見ない）で値が空の振り分けの行＝値は答えの補足の字から決まる。
    `答えを原本へ入れる`（選んだだけでは書かない）と `照らす`（合わない）の 2 つが同じこの 1 つで決める。"""
    先 = _字(f.反映先).strip()
    return 先 != 反映しない and not _字(f.値).strip() and 先.split("/")[0] != "台帳"


def 答えを原本へ入れる(q: 問い, 選んだ見出し: str, 回答: str, 回答日: str, 受付: str = "",
               原本の本文: str | None = None) -> list[dict]:
    """確認ページの貼り戻しの 1 つの答え → 書く手順:
    (a) 答えの原本に 1 ファイル（原本の本文＝届いた 1 送信を手を加えずに。省けば 回答）・(b) 答え のタブに 1 行（回答は原文のまま）・
    (c) 選んだ選択肢の振り分けをそのまま 振り分け のタブへ・(d) 問いの状態を 答えた に。
    選んだ見出しが その他・分からない（か問いに無い見出し）の時は (c)(d) をしない＝問いは 聞いている のまま。
    振り分けに値の要る先で値の空の行（`_値が補足から決まる`）がある選択肢も同じ＝値は補足の字から AI が `振り分けを書く` で書く
    （値の空の行は書き戻しが拒み 済 にならない＝その人が管理表に戻れない形を出さない）。
    (c) と (d) は 2 つで 1 つ＝表から読んだ問い（行の分かる問い）でなければ (c) も書かず止める（振り分けだけ入って問いが
    聞いている のまま残る形を出さない）。
    1 送信に幾つも問いがあれば (a) は同じ名の 1 ファイル（名は受付から決まる＝当てる側は同じ名を 1 回だけ作る）。"""
    リンク, 作る = _原本を作る(回答 if 原本の本文 is None else 原本の本文, 回答日, 受付)
    手順 = [作る, _行を足す("答え", [_行の値("答え", 答え(q.鍵, 回答, 回答日, リンク))])]
    見 = _字(選んだ見出し).strip()
    if 見 in 開いたままの見出し or 見 not in q.選択肢の振り分け:
        return 手順
    if any(_値が補足から決まる(f) for f in q.選択肢の振り分け[見]):
        return 手順   # 値は答えの補足から決まる＝問いは 聞いている のまま（止まりの候補は残る）
    状態 = 状態を書く(q, 答えた)   # 行が分からなければここで止まる＝振り分けより先に組む
    return 手順 + 振り分けを書く([replace(f, 鍵=q.鍵, 顧客ID=f.顧客ID or q.顧客ID) for f in q.選択肢の振り分け[見]]) + 状態


def チャットの答えを原本へ入れる(文: str, 日: str, 鍵: str = "") -> list[dict]:
    """オーナーがチャットで直に返した文 → 答えの原本に 1 ファイル（文のまま）と 答え のタブに 1 行。
    振り分けはこの口で書かない（AI が文を読んで `振り分けを書く` で書く）。"""
    リンク, 作る = _原本を作る(文, 日)
    return [作る, _行を足す("答え", [_行の値("答え", 答え(鍵, 文, 日, リンク))])]


