def 鍵を振る(今の表: 表 | None = None, 頭: str = "Q") -> str:
    """まだ使っていない問いの鍵を 1 つ返す（`Q<数>`。今の鍵の字の形は見ない＝どんな字が在っても読めて、重ならない物を返す）。"""
    使った = {x.鍵 for x in (今の表.問いたち if 今の表 else [])}
    n = len(使った) + 1
    while f"{頭}{n}" in 使った:
        n += 1
    return f"{頭}{n}"


