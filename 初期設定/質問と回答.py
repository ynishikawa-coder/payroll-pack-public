def _格子を行へ(格子) -> list[dict]:
    if not 格子:
        return []
    頭 = [_字(c).strip() for c in 格子[0]]
    return [{k: _字(r[i]).strip() if i < len(r) else "" for i, k in enumerate(頭)} for r in 格子[1:]
            if any(_字(c).strip() for c in (r or []))]


def _人の列(頭: list[str]) -> str | None:
    for k in ("社員ID", "NO"):
        if k in 頭:
            return k
    return None


def _表の頭(格子) -> list[str]:
    return [_字(c).strip() for c in (格子[0] if 格子 else [])]


答えの印の頭 = "⟦答え:"
答えの印の尾 = "⟧"
答えの印の区切り = "｜"
答えの印の見出し = "答えの印"   # 何を が md の見出しでなく 反映先 に #<見出し> も無い答えの行を置く節（`# 答えの印`・決まりの文は変えない）
_答えの印の禁じ字 = ("\n", "\r", 答えの印の尾, 答えの印の区切り, "<!--", "-->")


def md_の答えの行(f: 振り分け) -> str:
    """md（給与のルール.md・作業のルール.md）へ答えを書く 1 行の正本: `- ⟦答え:<問いの鍵>｜<何を>⟧ <値>`。
    照らす側（`照らす` の md の枝）はこの印の行だけを読む＝本文の字の含みでは照らさない。書く側（書き戻しの口）はこの口で行を作る
    （形を写さない）。鍵・何を・値が空か、改行・印の字（⟧ ｜）・HTML の注の印を含む時は組まない（その振り分けは 済 にならない）。"""
    鍵, 何を, 値 = _字(f.鍵).strip(), _字(f.何を).strip(), _字(f.値).strip()
    if not (鍵 and 何を and 値):
        raise ValueError(f"md の答えの行を組まない: 問いの鍵・何を・値のどれかが空（鍵={鍵!r} 何を={何を!r}）")
    for 字 in (鍵, 何を, 値):
        if any(x in 字 for x in _答えの印の禁じ字):
            raise ValueError(f"md の答えの行を組まない: 改行・印の字（{答えの印の尾} {答えの印の区切り}）・HTML の注の印を含む（{字!r}）")
    return f"- {答えの印の頭}{鍵}{答えの印の区切り}{何を}{答えの印の尾} {値}"


def md_の答えの値たち(本文: str, 鍵: str, 何を: str) -> list[str]:
    """md の本文から `- ⟦答え:<鍵>｜<何を>⟧ <値>` の行（行の頭から・前後の空白は外す）の 値 の並び。印の無い行は読まない。"""
    印 = f"- {答えの印の頭}{_字(鍵).strip()}{答えの印の区切り}{_字(何を).strip()}{答えの印の尾}"
    out = []
    for 行 in _字(本文).splitlines():
        行 = 行.strip()
        if 行 == 印:
            out.append("")
        elif 行.startswith(印 + " "):
            out.append(行[len(印) + 1:].strip())
    return out


def _md_を照らす(f: 振り分け, 先: str, 会社の物: dict) -> bool:
    try:
        行 = md_の答えの行(f)   # 組めない振り分けは書けない＝合わない
    except ValueError:
        return False
    片たち = 口.反映先を読む(先)
    if len(片たち) != 1 or 片たち[0].種 != "md":   # 振り分けの 1 行は先 1 つ（並べた先は照らせない＝合わない）
        return False
    片 = 片たち[0]
    本文 = 会社の物.get(片.甲)
    if not isinstance(本文, str):
        本文 = 会社の物.get(片.md_の名)
    if not isinstance(本文, str):
        return False
    if 片.乙:   # `<md の名>#<見出し>` はその節の中だけを見る（節を引く口の正本は 設問.md_の節）
        本文 = _設問().md_の節(本文, 片.乙)
    値たち = md_の答えの値たち(本文, f.鍵, f.何を)
    値 = 行.split(答えの印の尾, 1)[1].strip()
    return bool(値たち) and all(v == 値 for v in 値たち)   # 同じ印に違う値の行が在れば合わない（どちらが効くか決まらない）


def _設問():
    名 = "初期設定_設問_質問と回答"
    if 名 not in sys.modules:
        spec = importlib.util.spec_from_file_location(名, ここ / "設問.py")
        m = importlib.util.module_from_spec(spec)
        sys.modules[名] = m
        spec.loader.exec_module(m)
    return sys.modules[名]


def _マスタのタブ(マスタ: dict, 名: str) -> tuple[dict | None, list]:
    """反映先の <タブ> を型.json のマスタのタブ（「タブ」か Drive の名）で引き、その型と実物の格子を返す（型に無い名は型 None で名のまま引く）。"""
    型の = next((t for t in 口.シートの型("マスタ")["タブ"] if 名 in (t["タブ"], t.get("名"))), None)
    if 型の is None:
        return None, マスタ.get(名)
    return 型の, next((マスタ[k] for k in (型の["タブ"], 型の.get("名")) if k and k in マスタ), None)


def _会社の行(r: dict) -> str:
    return r.get("顧客ID", r.get("会社", ""))


def _マスタを照らす(f: 振り分け, 片: list[str], 値: str, マスタ: dict) -> bool:
    """マスタ/<タブ>[/<列>] を照らす（`照らす` の マスタ の枝）。"""
    型の, 格子 = _マスタのタブ(マスタ, 片[1].strip())
    頭 = _表の頭(格子)
    行たち = _格子を行へ(格子)
    何を = _字(f.何を).strip() or "/".join(片[2:]).strip()   # 書き戻しと同じ（何を が先・空なら反映先の <列>）
    型の列 = [c["名"] for c in (型の or {}).get("列", [])]
    if {"項目", "今の値", "適用開始"} <= set(型の列):
        # 1 行に 1 項目の会社の表（型.json の マスタ/会社）: 会社の値は 項目 の行の 今の値 が正本
        if f.対象 not in ("", 会社) or not 何を or not {"項目", "今の値", "適用開始"} <= set(頭):
            return False
        選んだ = [r for r in 行たち if _会社の行(r) == f.顧客ID and r["項目"] == 何を]
        if _字(f.効く月).strip():
            月 = _設問().段.月にそろえる(f.効く月)
            if 月 is None:
                return False
            選んだ = [r for r in 選んだ if _設問().段.月にそろえる(r["適用開始"]) == 月]
        elif 選んだ:
            始め = [("" if not r["適用開始"] else _設問().段.月にそろえる(r["適用開始"])) for r in 選んだ]
            if None in 始め:
                return False
            一番 = max(始め)
            選んだ = [r for r, m in zip(選んだ, 始め) if m == 一番]
        return bool(選んだ) and all(r["今の値"] == 値 for r in 選んだ)
    列名 = "/".join(片[2:]).strip() or 何を
    人 = _人の列(頭)
    if 列名 not in 頭 or (f.対象 != 会社 and 人 is None):
        return False
    選んだ = [r for r in 行たち if _会社の行(r) == f.顧客ID and (f.対象 == 会社 or r[人] == f.対象)]
    if not (bool(選んだ) and all(r[列名] == 値 for r in 選んだ)):
        return False
    return f.対象 == 会社 or 記録の効く月が合う(f, 列名, 値, マスタ)


def 記録の効く月が合う(f: 振り分け, 列名: str, 値: str, マスタ: dict) -> bool:
    """人の値に 効く月 が在り 変更の記録 が渡された時、その項目の一番新しい記録（効く月の直しの記録を除く）が この値へ
    変えた記録なら、その 適用支給月 が 効く月 と同じ月か。記録が無い・別の値への記録なら値だけで合う（変わり目の無い答え）。
    保険料の月で書く項目（標準報酬など）は 効く月 を 社保.徴収の月 で保険料の月へ直して `YYYY.MM分` の記録と比べ、比べられなければ合わない。"""
    効く = _字(f.効く月).strip()
    _, 格子 = _マスタのタブ(マスタ, "変更の記録")
    if not 効く or not 格子:
        return True
    月 = _設問().段.月にそろえる(効く)
    行たち = [r for r in _格子を行へ(格子) if _会社の行(r) == f.顧客ID and r.get(_人の列(_表の頭(格子)) or "社員ID", "") == f.対象
            and r.get("項目", "") == 列名 and not _設問().段.効く月の直しか(r.get("項目"))]
    if not 行たち:
        return True
    最後 = 行たち[-1]
    if 最後.get("新しい値", "") != 値:
        return True
    if 月 is None:
        return False
    段 = _設問().段
    if 段.社員の列の名.get(列名, 列名) in _保険料の月で書く項目():
        return _保険料の月の記録が合う(f, 月, 最後.get("適用支給月", ""), マスタ)
    return 段.月にそろえる(最後.get("適用支給月", "")) == 月


def _保険料の月で書く項目() -> tuple[str, ...]:
    from 芯.計算 import 支給控除 as 控   # 正本は芯（段の解決・書き戻しと同じ 1 か所）
    return tuple(控.保険料の月で書く項目)


def _保険料の月の記録が合う(f: 振り分け, 月: str, 記録の字, マスタ: dict) -> bool:
    """標準報酬など（保険料の月 `YYYY.MM分` で書く記録）: 効く月（支給月）をその人の 社保.徴収の月 で保険料の月へ直し、記録の月と同じか。
    記録が印（分）の無い字・徴収の月が社員の行にも マスタ/会社 にも無いか語の外＝比べられない＝合わない（値だけで 済 にしない）。"""
    from 芯.計算 import 支給控除 as 控
    記録の月 = 控.保険料の月の字(記録の字)
    if 記録の月 is None:
        return False
    徴収 = 徴収の月(f, マスタ)
    try:
        return 控.保険料の月(int(月[:4]), int(月[5:]), 徴収) == 記録の月
    except 控.式が無い:
        return False


def 徴収の月(f: 振り分け, マスタ: dict) -> str:
    """その人の 社保.徴収の月: マスタ/社員 の行（段の解決と同じ列の名）→ マスタ/会社 の項目の行（適用開始 が一番新しい行）の順。無ければ ""。"""
    名 = "社保.徴収の月"
    列たち = [k for k, v in _設問().段.社員の列の名.items() if v == 名] + [名]
    _, 格子 = _マスタのタブ(マスタ, "社員")
    頭 = _表の頭(格子)
    人 = _人の列(頭)
    for r in _格子を行へ(格子) if 人 else ():
        if _会社の行(r) == f.顧客ID and r[人] == f.対象:
            for c in 列たち:
                if _字(r.get(c, "")).strip():
                    return _字(r[c]).strip()
    _, 格子 = _マスタのタブ(マスタ, "会社")
    if not {"項目", "今の値", "適用開始"} <= set(_表の頭(格子)):
        return ""
    行たち = [r for r in _格子を行へ(格子) if _会社の行(r) == f.顧客ID and r["項目"] == 名 and _字(r["今の値"]).strip()]
    始め = [("" if not r["適用開始"] else _設問().段.月にそろえる(r["適用開始"])) for r in 行たち]
    if not 行たち or None in 始め:
        return ""
    一番 = max(始め)
    値たち = {_字(r["今の値"]).strip() for r, m in zip(行たち, 始め) if m == 一番}
    return 値たち.pop() if len(値たち) == 1 else ""


def 照らす(f: 振り分け, 実物たち: dict) -> bool:
    """振り分けの 1 行が反映先の実物と合うか（反映済み=済 を書く唯一の門＝合うと言えない時は全部 合わない）。反映しない はいつも合う。
    実物たち = {"マスタ": {タブ: 格子}, "会社": {顧客ID: {"給与のルール.md": 本文, "作業のルール.md": 本文, "台帳": {タブ: 格子}}}}
    - マスタ/<タブ>: <タブ> は型.json のマスタのタブの「タブ」（例 会社）か Drive の名（例 3_会社）のどちらでもよい。
      - 項目・今の値・適用開始 の列を持つタブ（会社＝1 行に 1 項目）: 対象 `会社` で、顧客ID と 項目＝何を で選び、効く月 が在れば
        適用開始 がその月の行・無ければ 適用開始 が一番新しい行（空は一番古い）が 1 つ以上在り、全部の 今の値 が 値 と一字同じ。
        適用開始 が月と読めない行が混じれば合わない。
      - ほかのタブ（マスタ/<タブ>/<列>）: 顧客ID（と対象が社員なら社員ID）で選んだ行が 1 つ以上在り、全部の <列>（無ければ 何を）が
        値 と一字同じ。社員で 効く月 が在り 変更の記録 も渡された時は、その項目の一番新しい記録が この値への記録なら
        適用支給月 が 効く月 と同じ月（効く月の直しの記録は数えない・保険料の月で書く項目は 効く月 を 社保.徴収の月 で
        保険料の月へ直して `YYYY.MM分` の記録と比べる・比べられなければ合わない）。
    - 台帳/<タブ>: 書き戻し（月次/答えの書き戻し.py）が書く形を照らす。<タブ> と 実物たち の台帳の鍵は型.json の台帳のタブの
      「タブ」（例 確定した勤怠）か Drive の名（同じタブの「名」・例 3_確定した勤怠）のどちらでもよい（正本は型.json の 1 か所）。
      - 直した訳 の列を持つタブ（確定した勤怠）: 人の列（NO）が 対象 の行に、直した訳 の片 `問い:<鍵>` を持つ行が在る。対象 `会社` は合わない。
        値 は見ない（日の問いの値の正本は 確定した勤怠 の行＝書き戻しも振り分けの 値 を使わない）。
      - 項目・値・問いの番号 の列を持つタブ（その月だけの指示）: 人の列が 対象（対象 `会社` なら空）・項目 が 何を・問いの番号 が
        この鍵の行が 1 つ以上在り、全部の 値 が 値 と一字同じ。書き戻しは必ず 問いの番号 を書くので、この鍵の行が無ければ
        （同じ項目のほかの月・ほかの問い・番号の空の行しか無くても）書かれていない＝合わない。
      - ほかの形のタブ・人の列の無いタブは照らせない＝合わない。
    - <md の名>（`#<見出し>` つきならその節）: `md_の答えの行` の印の行（問いの鍵と 何を）が在り、その値が全部 値 と一字同じ。
      本文の字の含みでは照らさない。
    値が空（確定した勤怠 を除く）・知らない反映先・実物が渡されていない時は合わない。"""
    先 = _字(f.反映先).strip()
    値 = _字(f.値).strip()
    if 先 == 反映しない:
        return True
    会社の物 = ((実物たち or {}).get("会社") or {}).get(f.顧客ID) or {}
    片 = 先.split("/")
    if _値が補足から決まる(f):
        return False
    if 片[0] == 口.Driveの名("マスタ") and len(片) >= 2:
        return _マスタを照らす(f, 片, 値, (実物たち or {}).get("マスタ") or {})
    if 片[0] == "台帳" and len(片) >= 2:
        名 = "/".join(片[1:]).strip()
        帳 = 会社の物.get("台帳") or {}
        型の = next((t for t in 口.シートの型("台帳")["タブ"] if 名 in (t["タブ"], t.get("名"))), None)
        if 型の is None:
            return False
        格子 = next((帳[k] for k in (型の["タブ"], 型の.get("名")) if k and k in 帳), None)
        頭 = _表の頭(格子)
        人 = _人の列(頭)
        鍵 = _字(f.鍵).strip()
        if 人 is None or not 鍵:
            return False
        行たち = _格子を行へ(格子)
        if "直した訳" in 頭:
            return f.対象 not in ("", 会社) and any(
                r[人] == f.対象 and f"問い:{鍵}" in {x.strip() for x in re.split(r"[、,]", r["直した訳"])} for r in 行たち)
        何を = _字(f.何を).strip()
        if not {"項目", "値", "問いの番号"} <= set(頭) or not 何を or not 値:
            return False
        誰 = "" if f.対象 in ("", 会社) else f.対象
        選んだ = [r for r in 行たち if r[人] == 誰 and r["項目"] == 何を and r["問いの番号"] == 鍵]
        return bool(選んだ) and all(r["値"] == 値 for r in 選んだ)
    if 先.endswith(".md") or ".md#" in 先:
        return _md_を照らす(f, 先, 会社の物)
    return False


def 反映済みを照らして書く(今の表: 表, 実物たち: dict, 今日: str) -> list[dict]:
    """まだ済でない振り分けの行を実物と照らし、合った行だけ 反映済み=済・反映した日=今日 を書く手順。合わない行は書かない。"""
    手順 = []
    for f in 今の表.振り分けたち:
        if f.反映済み or f.行 is None:
            continue
