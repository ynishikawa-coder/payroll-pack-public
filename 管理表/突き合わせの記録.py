"""給与ソフトとの突き合わせの記録と、月の状況「突き合わせ」（続けて差 0 の月数）を書く口。Drive を開かない。

確かめと仮.md §2「差が N か月 0 の数え方」: 会社ごとに、続けて差 0 の月の数を数える（賞与も 1 回を 1 か月）。
数えるには前の月までの回ごとの記録（突き合わせた人・差の行・外した人・給与ソフトが違うで閉じた数・場面）が要る。
その記録の正本は管理表のタブ「突き合わせの記録」（会社×支給月×回に 1 行）。月の状況「突き合わせ」はこの口が記録から
数えて書く値で、読み返さない（数だけでは賞与の回・場面・抜けた月が分からない＝数を写して次の月に足す道を持たない）。

  書く手順(結果, 会社=…, 支給月=…, 回=…, 給与ソフトが違うで閉じた=…, 場面=…, 今の記録=…, 今の月の状況=…,
          会社の一覧=…, 受け持つ組=…, 今日=…, 事務所の既定=…) → {"手順", "記録", "月数"}

結果は `月次.突き合わせる` が返した `突き合わせの結果` だけを受ける（殻が組んだ数・別の会社や別の月の結果は拒む）。
手順は `管理表.書く` が返した物（型の照らし・受け持つ組の照らし・式の字の照らしを通った物）＝殻は順に当てるだけ。
月の回は月の状況のその月の行の「突き合わせ」へ、賞与の回は記録のタブにだけ書く（賞与の状況に突き合わせの列は無い＝Drive の型.md §5）。
前の回を後から突き合わせ直した時は、その回より後の回の数も記録から数え直して書く（数は記録からしか出さない）。
"""
from __future__ import annotations

import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
if str(ここ.parent) not in sys.path:
    sys.path.insert(0, str(ここ.parent))

from 出口 import 突き合わせ as _突  # noqa: E402
from 出口.名と版 import 出す支給月  # noqa: E402
from 出口.行 import 支給月の並び  # noqa: E402
from 初期設定 import 段の解決 as _段, 型の口 as _型  # noqa: E402
from 芯 import 支給月の字, 字  # noqa: E402

try:   # 試験は spec で 管理表.py を読む・殻は repo の根から 管理表.管理表 を読む＝どちらでも同じ 1 つの書く口
    from 管理表 import 管理表 as _表  # noqa: E402
except ImportError:  # pragma: no cover
    import 管理表 as _表  # type: ignore  # noqa: E402

拒む = _表.拒む
記録のタブ = "突き合わせの記録"
回たち = ("月", "賞与")
はい, いいえ = "はい", "いいえ"
Nの項目 = "突き合わせ.差0の月数の目安"   # 事務所の設定「既定」の項目（既定の正本は 初期設定/項目.json）


def _N(事務所の既定, 支給月: str) -> int:
    """事務所の設定「既定」（get_values のまま）から、その支給月に効く N を読む。書いていなければ 項目.json の既定。
    読めない字・適用開始の読めない行は拒む（黙って既定の 3 で数えない）。"""
    if not isinstance(事務所の既定, (list, tuple)):
        raise 拒む(f"事務所の既定 は事務所の設定「既定」のタブの今の値（get_values のまま）で必ず渡す（受けた物: {事務所の既定!r}）")
    外れ: list = []
    行 = [r for r in _段.行たち(事務所の既定) if str(r.get("項目", "")).strip() == Nの項目]
    v = _段.一番新しい(行, lambda r: Nの項目, "今の値", _段.月(支給月), 外れ).get(Nの項目)
    if 外れ:
        raise 拒む(f"事務所の設定/既定/{Nの項目}: 適用開始の読めない行がある＝どの N が効くか決められない")
    所 = f"事務所の設定/既定/{Nの項目}"
    if _段.空(v):
        v, 所 = _型.項目(Nの項目)["既定"], f"初期設定/項目.json の {Nの項目} の既定"
    try:
        n = int(str(v).strip())
    except ValueError:
        n = 0
    if n < 1 or str(n) != str(v).strip():
        raise 拒む(f"{所} {v!r} は 1 以上の整数でない＝続けて差 0 の月数の目安に使えない")
    return n


def _数(v, 名: str) -> int:
    if isinstance(v, bool) or not isinstance(v, int) or v < 0:
        raise 拒む(f"{名} は 0 以上の数で必ず渡す（受けた物: {v!r}）＝黙って 0 と読まない")
    return v


def _中の字(支給月, 回: str) -> str:
    """管理表の字（殻の字・置き場の字）と回 → 出口の字（`YYYY-MM`・`YYYY-MM-賞与`）。読めない字は拒む。"""
    x = 支給月の字.鍵の年月(支給月)
    if x is None:
        raise 拒む(f"{記録のタブ}: 支給月 {支給月!r} が読めない（`YYYY.MM支給` か `YYYY.MM支給（M月分）`）")
    return 出す支給月(支給月の字.字にする(*x, "殻"), 回)


def _記録を読む(行: dict, n: int) -> dict:
    回 = str(行["回"]).strip()
    if 回 not in 回たち:
        raise 拒む(f"{記録のタブ}: {n} 行目の 回 {行['回']!r} は {'・'.join(回たち)} のどれでもない")
    差0 = str(行["差0の月"]).strip()
    if 差0 not in (はい, いいえ):
        raise 拒む(f"{記録のタブ}: {n} 行目の 差0の月 {行['差0の月']!r} は はい・いいえ のどれでもない＝数えられない")
    場面 = tuple(x for x in str(行["場面"]).split("・") if x.strip())
    知らない = [x for x in 場面 if x not in _突.場面たち]
    if 知らない:
        raise 拒む(f"{記録のタブ}: {n} 行目の 場面 {'・'.join(知らない)} は {'・'.join(_突.場面たち)} の外")
    return {"支給月": _中の字(行["支給月"], 回), "会社": str(行["会社"]), "差0の月": 差0 == はい, "場面": 場面}


def 書く手順(結果, *, 会社: str, 支給月: str, 回: str, 給与ソフトが違うで閉じた: int, 場面, 今の記録: list,
          今の月の状況: list, 会社の一覧: dict, 受け持つ組: str, 今日: str, 事務所の既定: list) -> dict:
    """1 会社 1 回の突き合わせの結果から、記録のタブの行と月の状況「突き合わせ」を書く手順を組む。

    支給月: 月を回す・賞与を回す に渡した `YYYY.MM支給`。回: 月 か 賞与。
    給与ソフトが違うで閉じた: その回の差の問いのうち「給与ソフトが違う」で閉じた数（必ず渡す・0 も）。
    場面: その回にあった場面（入社・退社・年の変わり目・料率の変わる月。賞与は出口が足す）の並び。必ず渡す（無ければ空の並び）。
    今の記録・今の月の状況: 管理表のタブの今の値（get_values のまま・1 行目が見出し）。
    事務所の既定: 事務所の設定「既定」のタブの今の値（get_values のまま）。N（`突き合わせ.差0の月数の目安`）をここから読む。
    返す: {"手順": 管理表.書く の手順の並び, "記録": この回の記録, "月数": この回までの続けて差 0 の月数・数えた月・まだ見ていない場面}。"""
    if not isinstance(結果, _突.突き合わせの結果):
        raise 拒む("結果 は 月次.突き合わせる が返した 突き合わせの結果 をそのまま渡す（殻が組んだ数を受けない）")
    if 回 not in 回たち:
        raise 拒む(f"回 {回!r} は {'・'.join(回たち)} のどれでもない")
    if not 支給月の字.その形か(支給月, "殻"):
        raise 拒む(f"支給月 {支給月!r} は 月を回す・賞与を回す に渡した `YYYY.MM支給` のまま渡す")
    閉じた = _数(給与ソフトが違うで閉じた, "給与ソフトが違うで閉じた")
    N = _N(事務所の既定, 支給月)
    if not isinstance(場面, (list, tuple)) or not all(isinstance(x, str) for x in 場面):
        raise 拒む(f"場面 は字の並びで必ず渡す（無ければ空の並び。受けた物: {場面!r}）＝黙って場面の無い回と読まない")
    会社 = str(会社)
    中 = 出す支給月(支給月, 回)
    よそ = sorted({f"{k[1]} {k[0]}" for k in 結果.人の状態 if (k[0], k[1]) != (中, 会社)})
    if よそ:
        raise 拒む(f"結果 に {会社} {中} でない回の人がいる（{'・'.join(よそ)}）＝別の会社・別の回の結果を書かない")
    try:
        記録 = _突.月の記録(結果, 会社, 中, 閉じた, 場面)
    except ValueError as e:
        raise 拒む(str(e)) from e
    if 記録["突き合わせた人"] == 0 and 記録["外した人"] == 0:
        raise 拒む(f"結果 に {会社} {中} の人が 1 人もいない＝突き合わせていない回を差 0 と書かない")

    _表.見出しを照らす(記録のタブ, 今の記録)
    今の行 = _表.行の辞書(記録のタブ, 今の記録)
    記録たち: dict[str, dict] = {}
    for i, r in enumerate(今の行):
        if not 字.同じ(r["会社"], 会社):
            continue
        x = _記録を読む(r, i + 2)
        記録たち[x["支給月"]] = x
    記録たち[中] = 記録
    並び = sorted(記録たち, key=支給月の並び)

    def 数える(まで: str) -> dict:
        return _突.続けて差0の月数([記録たち[k] for k in 並び if 支給月の並び(k) <= 支給月の並び(まで)], N)[会社]

    記録の行, 月の行 = [], []
    for k in 並び:
        if 支給月の並び(k) < 支給月の並び(中):
            continue   # 前の回の数は変わらない（数えるのはその回まで）
        数 = 数える(k)
        k回 = "賞与" if k.endswith("-賞与") else "月"
        殻 = 支給月の字.字にする(*支給月の並び(k)[:2], "殻")
        行 = {"会社": 会社, "支給月": 殻, "回": k回, "続けて差0の月数": str(数["月数"]),
             "まだ見ていない場面": "・".join(数["まだ見ていない場面"]), "更新日": 今日}
        if k == 中:
            行.update({"突き合わせた人": str(記録["突き合わせた人"]), "差の行": str(記録["差の行"]),
                      "外した人": str(記録["外した人"]), "給与ソフトが違うで閉じた": str(記録["給与ソフトが違うで閉じた"]),
                      "場面": "・".join(記録["場面"]), "差0の月": はい if 記録["差0の月"] else いいえ})
        記録の行.append(行)
        if k回 == "月":
            月の行.append({"会社": 会社, "支給月": 殻, "突き合わせ": str(数["月数"])})
    共 = {"会社の一覧": 会社の一覧, "受け持つ組": 受け持つ組, "今日": 今日}
    手順 = _表.書く({"タブ": 記録のタブ, "今の値": 今の記録, "行たち": 記録の行, **共})
    if 月の行:
        手順 += _表.書く({"タブ": "月の状況", "回": "月", "今の値": 今の月の状況, "行たち": 月の行, **共})
    return {"手順": 手順, "記録": 記録, "月数": 数える(中)}
