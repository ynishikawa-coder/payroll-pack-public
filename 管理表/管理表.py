"""状況の正本（00_事務所/管理表）の書く口と、事務所の段の道具。Drive を開かない。

殻が今のタブの値（get_values の 2 次元の配列・1 行目が見出し）を渡し、この口が「書く手順」を返す。殻は手順を順に当てるだけ。

  python3 管理表/管理表.py 書く     < 入力.json   # 窓の口: 受け持つ組の行だけを鍵で探して書く
  python3 管理表/管理表.py 月の行   < 入力.json   # 事務所の段: 会社×支給月の行を起こす
  python3 管理表/管理表.py 会社の行 < 入力.json   # 事務所の段: 会社の行を起こす
  python3 管理表/管理表.py 型の版   < 入力.json   # 会社の「型の版」を読む（寄せる道具の入力の 型の版 へ）
  python3 管理表/管理表.py 寄せの印 < 入力.json   # 会社が「寄せ中」か読む（寄せ中の会社は毎月の仕事を回さない）
  python3 管理表/管理表.py 寄せの行 < 入力.json   # 寄せ中を立てる・止まった理由を書く・外す行（書く へ渡す）
  python3 管理表/管理表.py 突き合わせる月 < 入力.json   # 寄せの突き合わせに使う月（最後に出した月）を月の状況から決めて照らす
  python3 管理表/管理表.py 配った日 < 入力.json   # 会社の「最後に配った日」を読む（寄せ・配りの写しの期限の元）
  python3 管理表/管理表.py 立ち上げ < 入力.json   # 事務所の段: 管理表に型のタブ（見出しまで）を足す
  python3 管理表/管理表.py 回のタブ < 入力.json   # 回（月・賞与）→ その回の状況のタブの名（{"回": "賞与"} → "賞与の状況"）
  python3 管理表/管理表.py 出した物のタブ < 入力.json   # 出した物の今の版とリンクを持つタブの名（書くのは 出荷の口 だけ）

入力の形は 管理表/README.md。
"""
import json
import re
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
if str(ここ.parent) not in sys.path:
    sys.path.insert(0, str(ここ.parent))

from 芯 import 支給月の字  # noqa: E402  支給月の字の正本（鍵の 支給月 はここで読む＝字を写さない）
from 芯 import 字  # noqa: E402  字のそろえ方の正本（鍵・状態の字はそろえて比べる＝書く字はそろえない）


# 書く手順の 書き方: 値は字のまま書く（Sheets の valueInputOption=RAW）＝数だけの字・日付の字を数や日付に読ませない
字のまま = "RAW"


class 拒む(Exception):
    """書く口が書かない時（他の組の行・見出しの違い・選べない値・行を起こす権の無い窓）。"""


def 型() -> dict:
    return json.loads((ここ / "型.json").read_text(encoding="utf-8"))


def タブ(名: str) -> dict:
    for t in 型()["タブ"]:
        if t["タブ"] == 名:
            return t
    raise 拒む(f"型に無いタブ: {名}")


def 回のタブ(回: str) -> str:
    """回（月・賞与）→ その回の状況を持つタブの名（型の「回」）。知らない回は拒む（黙って 月の状況 に書かない）。
    同じ会社・支給月でも回ごとに別のタブの行＝賞与を書いても月の給与の行を上書きしない。"""
    当たり = [t["タブ"] for t in 型()["タブ"] if t.get("回") is not None and t["回"] == 回]
    if len(当たり) != 1:
        raise 拒む(f"回 {回!r} の状況のタブが型に無い（{'・'.join(str(t['回']) for t in 型()['タブ'] if t.get('回'))} のどれか）")
    return 当たり[0]


def 出した物のタブ() -> str:
    """出した物の今の版とリンクを物ごとに 1 行で持つタブの名（型の「書くのは」が 出荷の口 のタブ）。書くのは出荷の口だけ。
    型に 1 つでなければ拒む（黙って回の状況のタブの 止まりの理由 へ版を書かない）。"""
    当たり = [t["タブ"] for t in 型()["タブ"] if t.get("書くのは") == "出荷の口"]
    if len(当たり) != 1:
        raise 拒む(f"出した物のタブ（書くのは 出荷の口）が型に 1 つでない（{当たり}）")
    return 当たり[0]


def 見出し(名: str) -> list[str]:
    return [c["名"] for c in タブ(名)["列"]]


def 全部の見出し() -> dict[str, list[str]]:
    return {t["タブ"]: [c["名"] for c in t["列"]] for t in 型()["タブ"]}


def 列の字(i: int) -> str:
    """見出しの並びの位置（0 始まり）→ 列の字。数え方の正本は 芯.字.列の字（1 始まり）＝ここは 1 足して渡すだけ。"""
    return 字.列の字(i + 1)


def _見出しの違い(名: str, 今: list) -> str:
    型の = 見出し(名)
    無い = [c for c in 型の if c not in 今]
    外 = [c for c in 今 if c not in 型の]
    違い = [f"型に在って無い列 {無い}" if 無い else "", f"型に無い列 {外}" if 外 else "",
          "列の並びが型と違う" if not 無い and not 外 else ""]
    return "・".join(x for x in 違い if x)


def 見出しを照らす(名: str, 値: list[list]) -> None:
    今 = [str(c) for c in (値[0] if 値 else [])]
    if 今 != 見出し(名):
        raise 拒む(f"{名}: 見出しが型と違う（{_見出しの違い(名, 今)}）。事務所の管理表を管理表の型にそろえてから書く"
                 "（タブ「{名}」が無い管理表は `立ち上げ` が足す手順を返す）".replace("{名}", 名))


def 選べる値(列: dict) -> list | None:
    """列の選べる値（型の 選べる値、無ければ 値の役 の字）。照らさない列は None。"""
    if "選べる値" in 列:
        return 列["選べる値"]
    return list(列["値の役"].values()) if "値の役" in 列 else None


def 値の字(タブの名: str, 列の名: str, 役: str) -> str:
    """列の 値の役 の役 → 書く字（字の正本は 管理表/型.json・道具は字を写さない）。知らない役は拒む。"""
    for c in タブ(タブの名)["列"]:
        if c["名"] == 列の名:
            if 役 not in c.get("値の役", {}):
                raise 拒む(f"{タブの名}.{列の名}: 型に無い役 {役!r}")
            return c["値の役"][役]
    raise 拒む(f"{タブの名}: 型に無い列 {列の名}")


def _値を照らす(名: str, 行: dict) -> None:
    for k, v in 行.items():
        if str(v).startswith(("=", "+", "@")):
            raise 拒む(f"{名}.{k}: 式か式に読める字は書かない {v!r}")
    for c in タブ(名)["列"]:
        if c["名"] not in 行:
            continue
        v = 行[c["名"]]
        if (選べる := 選べる値(c)) is not None and v not in 選べる:
            raise 拒む(f"{名}.{c['名']}: 選べない値 {v!r}")
        if c.get("形") == "数" and v != "" and not re.fullmatch(r"\d+", str(v)):
            raise 拒む(f"{名}.{c['名']}: 数でない {v!r}")
        if c.get("形") == "日付" and v != "" and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(v)):
            raise 拒む(f"{名}.{c['名']}: YYYY-MM-DD でない {v!r}")
    if タブ(名).get("回") and str(行.get("外した人", "0") or "0") != "0":
        for c in ("取り込み", "納品"):
            if 行.get(c) == "済":
                raise 拒む(f"{名}.{c}: 外した人が 0 でないので 済 にしない")


def 行の辞書(名: str, 値: list[list]) -> list[dict]:
    h = 見出し(名)
    return [{k: (r[i] if i < len(r) else "") for i, k in enumerate(h)} for r in 値[1:]]


def _鍵の値(名: str, k: str, v, 何: str):
    """鍵の列の値 → 比べる値。支給月は正本（芯/支給月の字.py の 鍵の年月）で (年, 月) に読む＝管理表の字
    `YYYY.MM支給（M月分）` も殻の字 `YYYY.MM支給` も同じ支給月として当たる。読めない字は拒む（黙って別の月・行無しにしない）。"""
    if k != "支給月":
        return str(v)
    x = 支給月の字.鍵の年月(v)
    if x is None:
        raise 拒む(f"{名}: {何}の支給月 {v!r} が読めない（`YYYY.MM支給（M月分）` か `YYYY.MM支給`。docs/毎月の流れ.md「支給月の書き方」）")
    return x


def _探す(名: str, 行たち: list[dict], 鍵の値: dict) -> int | None:
    鍵 = タブ(名)["鍵"]
    探す = {k: _鍵の値(名, k, 鍵の値[k], "探す鍵") for k in 鍵}
    当たり = []
    for i, r in enumerate(行たち):
        if not all(k == "支給月" or 字.同じ(r[k], 鍵の値[k]) for k in 鍵):
            continue
        if "支給月" in 鍵 and _鍵の値(名, "支給月", r["支給月"], f"{i + 2} 行目") != 探す["支給月"]:
            continue
        当たり.append(i)
    if len(当たり) > 1:
        raise 拒む(f"{名}: 鍵 {鍵の値} の行が 2 つある")
    return 当たり[0] if 当たり else None


def 書く(入力: dict) -> list[dict]:
    """窓の書く口。入力: タブ・今の値・会社の一覧（会社→組）・受け持つ組・行たち・今日・回（任意）。

    受け持つ組の会社の行だけを鍵で探して書く。月の状況・会社の行は起こさない（事務所の段）。
    確認ページ・賞与の状況・出した物の行は無ければ足す（組 は会社の一覧の組）。行を消さない。見出し・他の組の行・他のタブには書かない。
    回（月・賞与）を渡したら、タブがその回のタブ（`回のタブ`）でなければ拒む＝賞与の行を 月の状況 に書かない。"""
    名, 値 = 入力["タブ"], 入力["今の値"]
    if 入力.get("回") is not None and 回のタブ(入力["回"]) != 名:
        raise 拒む(f"{名}: 回 {入力['回']} の行は {回のタブ(入力['回'])} に書く（回を取り違えて別の回の行を上書きしない）")
    見出しを照らす(名, 値)
    組の = 入力["会社の一覧"]
    受け持つ = 入力["受け持つ組"]
    h = 見出し(名)
    今の行 = 行の辞書(名, 値)
    手順 = []
    for 行 in 入力["行たち"]:
        会社 = 行.get("会社")
        if 組の.get(会社) != 受け持つ and not (名 == "確認ページ" and 会社 == 受け持つ):
            raise 拒む(f"{名}: 会社 {会社} は受け持つ組 {受け持つ} の会社でない")
        if (タブ(名).get("回") or タブ(名).get("書くのは") == "出荷の口") and "更新日" not in 行 and 入力.get("今日"):
            行 = {**行, "更新日": 入力["今日"]}
        外 = set(行) - set(h)
        if 外:
            raise 拒む(f"{名}: 型に無い列 {sorted(外)}")
        欠け = [k for k in タブ(名)["鍵"] if str(行.get(k, "")) == ""]
        if 欠け:
            raise 拒む(f"{名}: 鍵の列 {欠け} が無い")
        i = _探す(名, 今の行, 行)
        if i is not None and "組" in h and 今の行[i]["組"] != 受け持つ:
            raise 拒む(f"{名}: 行の組が {今の行[i]['組']!r}（受け持つ組でない）")
        if "組" in 行 and (i is None or str(行["組"]) != str(今の行[i]["組"])):
            raise 拒む(f"{名}: 組は窓から書かない（書くのは事務所の段）")
        if i is None:
            if タブ(名)["起こすのは"] != "窓":
                raise 拒む(f"{名}: 鍵 {[行.get(k) for k in タブ(名)['鍵']]} の行が無い（行を起こすのは事務所の段）")
            新 = {k: 行.get(k, "") for k in h}
            if "組" in h:
                新["組"] = 受け持つ   # 会社の組は上で受け持つ組と照らした（窓は組の字を書かない）
            _値を照らす(名, 新)
            手順.append({"する": "行を足す", "タブ": 名, "値": [新[k] for k in h], "書き方": 字のまま})
            今の行.append(新)
            continue
        _値を照らす(名, {**今の行[i], **行})
        for k, v in 行.items():
            if k in タブ(名)["鍵"] or str(今の行[i][k]) == str(v):
                continue
            手順.append({"する": "値を書く", "タブ": 名, "セル": f"{列の字(h.index(k))}{i + 2}", "列": k, "前": 今の行[i][k], "値": v,
                         "書き方": 字のまま})
            今の行[i][k] = v
    return 手順


def 月の行(入力: dict) -> list[dict]:
    """事務所の段。会社の一覧（会社・組・状態）の 止めた 以外の会社について、支給月の行が無ければ足す。"""
    名 = "月の状況"
    if 支給月の字.置き場の字を読む(入力.get("支給月")) is None:
        raise 拒む(f"{名}: 起こす行の支給月 {入力.get('支給月')!r} は `YYYY.MM支給（M月分）` の字で渡す"
                 "（管理表の字＝docs/毎月の流れ.md「支給月の書き方」・芯/支給月の字.py の 置き場）")
    見出しを照らす(名, 入力["今の値"])
    今の行 = 行の辞書(名, 入力["今の値"])
    h = 見出し(名)
    手順 = []
    for c in 入力["会社の一覧"]:
        if 字.同じ(c.get("状態"), "止めた"):
            continue
        鍵 = {"会社": c["会社"], "支給月": 入力["支給月"]}
        if _探す(名, 今の行, 鍵) is None:
            新 = {**{k: "" for k in h}, **鍵, "組": c["組"], "外した人": "0", "更新日": 入力.get("今日", "")}
            手順.append({"する": "行を足す", "タブ": 名, "値": [新[k] for k in h], "書き方": 字のまま})
            今の行.append(新)
    return 手順


def 会社の行(入力: dict) -> list[dict]:
    """事務所の段。会社の行が無ければ足す。型の版は会社の一覧の行ごとに必ず渡す（その会社の Drive の型の版・数）。
    省く・空・数でない時は止める＝黙って 0 と書かない（寄せる道具・見回りが「版 0 の会社」と読み、最初の版から直しを当てる見当になる）。"""
    名 = "会社"
    見出しを照らす(名, 入力["今の値"])
    今の行 = 行の辞書(名, 入力["今の値"])
    h = 見出し(名)
    手順 = []
    for c in 入力["会社の一覧"]:
        if _探す(名, 今の行, c) is None:
            版 = c.get("型の版")
            if isinstance(版, bool) or not (isinstance(版, int) and 版 >= 0 or isinstance(版, str) and re.fullmatch(r"[0-9]+", 版.strip()) is not None):
                raise 拒む(f"{名}: 会社 {c.get('会社')} の 型の版 を数で渡す（その会社の Drive の型の版）。渡さないと 0 と書き、"
                         f"寄せる道具が版 0 の会社と読む（受けた物: {版!r}）")
            新 = {**{k: "" for k in h}, "会社": c["会社"], "組": c["組"], "型の版": str(版).strip(), "選んだ部品": c.get("選んだ部品", "")}
            手順.append({"する": "行を足す", "タブ": 名, "値": [新[k] for k in h], "書き方": 字のまま})
            今の行.append(新)
    return 手順


def 型の版(入力: dict) -> dict:
    """会社のタブの「型の版」を読む口（寄せる道具の入力 `型の版` へ渡す）。入力: 今の値（会社のタブ）・会社たち（無ければ全社）。

    書く口（`書く`）と同じタブ・同じ見出しの照らしで読む＝読む側と書く側の型が 1 つ。行の無い会社は拒む（黙って 0 にしない）。
    空の版は 0（版の無い会社＝寄せる道具.md §1.3）として返し、`版が空` に名を出す。寄せる道具は版に頼らず形からも前の形を
    見つける（直しは前の形を確かめて当てる）ので、空や古い記録でも前の形を黙って通さない。"""
    名 = "会社"
    見出しを照らす(名, 入力["今の値"])
    今の行 = 行の辞書(名, 入力["今の値"])
    会社たち = 入力.get("会社たち") or [r["会社"] for r in 今の行]
    版, 空 = {}, []
    for c in 会社たち:
        i = _探す(名, 今の行, {"会社": c})
        if i is None:
            raise 拒む(f"{名}: 会社 {c} の行が無い（行を起こすのは事務所の段の 会社の行）")
        v = str(今の行[i]["型の版"]).strip()
        if v and not re.fullmatch(r"\d+", v):
            raise 拒む(f"{名}.型の版: 数でない {v!r}（会社 {c}）")
        版[c] = int(v) if v else 0
        if not v:
            空.append(c)
    return {"型の版": 版, "版が空": 空}


def 寄せの印(入力: dict) -> dict:
    """会社のタブの「寄せ」「寄せの理由」を読む口。入力: 今の値（会社のタブ）・会社。返す: {"寄せ中": bool, "理由": 字}。

    寄せる道具.md §1.5 の 1・7: 寄せの間と、寄せが途中で止まった会社は「寄せ中」のまま＝毎月の仕事（月を回す・締める）は
    その会社を回さない。月を回す口・締める口はこの口で読み、寄せ中なら止める。書く口と同じ見出しの照らしで読む＝
    見出しが型と違う・行の無い会社・選べない値は拒む（黙って「寄せ中でない」と読まない）。"""
    名 = "会社"
    見出しを照らす(名, 入力["今の値"])
    今の行 = 行の辞書(名, 入力["今の値"])
    c = 入力.get("会社")
    i = _探す(名, 今の行, {"会社": c})
    if i is None:
        raise 拒む(f"{名}: 会社 {c} の行が無い＝寄せ中か読めない（行を起こすのは事務所の段の 会社の行）")
    行 = 今の行[i]
    中 = 字.同じ(行["寄せ"], "寄せ中")
    if not 中 and str(行["寄せ"]).strip():
        raise 拒む(f"{名}.寄せ: 選べない値 {行['寄せ']!r}（会社 {c}・空か 寄せ中）＝寄せ中か読めない")
    return {"寄せ中": 中, "理由": str(行["寄せの理由"]).strip() if 中 else ""}


def 配った日(入力: dict) -> str:
    """会社のタブの「最後に配った日」を読む口（YYYY-MM-DD か空）。入力: 今の値（会社のタブ）・会社。

    寄せる道具.md §4.2: 寄せ・配りの写し（9_履歴/消す_）の期限は、寄せの回の中の突き合わせが緑になった日（照らす回だけが
    管理表へ書く＝この列）の翌月末。見回りはこの口で読み、空（まだ 1 度も緑になっていない）の会社の写しを並べない。
    書く口と同じ見出しの照らしで読む＝行の無い会社・日付でない値は拒む（黙って空と読まない）。"""
    名 = "会社"
    見出しを照らす(名, 入力["今の値"])
    今の行 = 行の辞書(名, 入力["今の値"])
    c = 入力.get("会社")
    i = _探す(名, 今の行, {"会社": c})
    if i is None:
        raise 拒む(f"{名}: 会社 {c} の行が無い＝最後に配った日が読めない（行を起こすのは事務所の段の 会社の行）")
    v = str(今の行[i]["最後に配った日"]).strip()
    if v and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", v):
        raise 拒む(f"{名}.最後に配った日: YYYY-MM-DD でない {v!r}（会社 {c}）＝写しの期限が決まらない")
    return v


寄せの段 = ("立てる", "止まった", "外す")


def 寄せの行(入力: dict) -> dict:
    """寄せ中の印の行（`書く` の 行たち へそのまま渡す）。入力: 会社・段（立てる・止まった・外す）・理由（止まった だけ）。

    立てる＝書く前に寄せ中にする（理由は空）／止まった＝寄せ中のまま理由を書く（理由が空なら拒む）／外す＝照らしが
    通った時だけ寄せ中と理由を空にする。列の名と選べる値は型（管理表/型.json）から＝殻が列の字を組まない。"""
    段, c, 理由 = 入力.get("段"), 入力.get("会社"), str(入力.get("理由") or "").strip()
    if 段 not in 寄せの段:
        raise 拒む(f"寄せの行: 段 {段!r} は {'・'.join(寄せの段)} のどれか")
    if not c:
        raise 拒む("寄せの行: 会社 が無い")
    if 段 == "止まった" and not 理由:
        raise 拒む("寄せの行: 止まった 時は理由（1 行）を渡す＝寄せ中のまま訳の無い会社を残さない")
    if 段 != "止まった" and 理由:
        raise 拒む(f"寄せの行: 理由は 止まった の時だけ（段 {段}）")
    if "\n" in 理由:
        raise 拒む("寄せの行: 理由は 1 行")
    行 = {"会社": c, "寄せ": "" if 段 == "外す" else "寄せ中", "寄せの理由": 理由}
    _値を照らす("会社", {k: 行.get(k, "") for k in 見出し("会社")})
    return 行


