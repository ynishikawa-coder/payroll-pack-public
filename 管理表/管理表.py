"""状況の正本（事務所の根の直下の管理表）の書く口と、事務所の段の道具。Drive を開かない。

窓が今のタブの値（get_values の 2 次元の配列・1 行目が見出し）を渡し、この口が「書く手順」を返す。窓は手順を順に当てるだけ。

  python3 管理表/管理表.py 書く     < 入力.json   # 窓の口: 受け持つ組の行だけを鍵で探して書く
  python3 管理表/管理表.py 月の行   < 入力.json   # 事務所の段: 会社×支給月の行を起こす
  python3 管理表/管理表.py 会社の行 < 入力.json   # 事務所の段: 会社の行を起こす
  python3 管理表/管理表.py 月の段   < 入力.json   # 事務所の段: 会社の一覧の空の 状態 と、無い 月の状況 の行だけを起こす
  python3 管理表/管理表.py 立ち上げ < 入力.json   # 事務所の段: 管理表に型のタブ（見出しまで）を足す
  python3 管理表/管理表.py 回のタブ < 入力.json   # 回（月・賞与）→ その回の状況のタブの名（{"回": "賞与"} → "賞与の状況"）
  python3 管理表/管理表.py 出した物のタブ < 入力.json   # 出した物の今の版とリンクを持つタブの名
  python3 管理表/管理表.py 置き場の登録を移す < 入力.json   # 事務所の段: 事務所の設定「置き場」を顧客ID と物の 1 行ずつへ移す手順か問い

入力の形は 管理表/README.md。
"""
