def 突き合わせる月(入力: dict) -> dict:
    """寄せの人×項目の突き合わせ（寄せる道具.md §1.6）に使う月を、記録（管理表「月の状況」）から決めて照らす口。
    入力: 今の値（月の状況のタブ）・会社・月（窓が渡す突き合わせる月・殻の字 `YYYY.MM支給`・無ければ空）・無い訳（無ければ空）。
    返す: {"月": 最後に出した月（殻の字）か "", "出した月": [殻の字…], "無い訳": 字}。

    出した月＝その会社の行で 取り込み・計算 が 済／仮 か 納品 が 済 の支給月（出荷の口だけが書く印）。最後に出した月＝その最大。
    出した月が在る会社: 月は最後に出した月でなければ拒む・無い訳は拒む（申告で突き合わせを飛ばさない）。
    出した月が無い会社: 月を渡せば拒む・無い訳が空なら拒む。見出しの違い・読めない支給月・行の無い会社は拒む（黙って「出していない」と読まない）。

    見通し（寄せる道具の 見通す が返した物・任意）と 会社のタブ（管理表「会社」の今の値）を渡すと、変わらない会社を先に決める:
    見通しの 変わる印（書く手順・寄せられない物・足りない値・管理表へ書く・写した物）が全部空で、会社が寄せ中でない（＝前の回が
    途中で止まっていない・寄せ中は 寄せの印 で読む＝申告を信じない）時だけ {"月": "", "出した月": […], "無い訳": "",
    "変わらない": True} を返す＝突き合わせる物（比べる入力）を求めずに終える（寄せる道具.md §1.6）。1 つでも残れば
    "変わらない": False と 残り（何が残るか）を足して上の照らしをそのまま通す＝済にしない。見通しに 変わる印 の鍵が欠ければ拒む。"""
    名 = "月の状況"
    見出しを照らす(名, 入力["今の値"])
    今の行 = 行の辞書(名, 入力["今の値"])
    c = 入力.get("会社")
    if not c:
        raise 拒む("突き合わせる月: 会社 が無い")
    月, 訳 = str(入力.get("月") or "").strip(), str(入力.get("無い訳") or "").strip()
    if 月 and 訳:
        raise 拒む("突き合わせる月: 月と無い訳は片方だけ渡す")
    行たち = [(i, r) for i, r in enumerate(今の行) if 字.同じ(r["会社"], c)]
    足す = {}
    if 入力.get("見通し") is not None:
        残り = _変わる残り(入力["見通し"], 入力.get("会社のタブ"), c)
        if not 残り:
            return {"月": "", "出した月": _出した月(名, 行たち), "無い訳": "", "変わらない": True}
        足す = {"変わらない": False, "残り": 残り}
    if not 行たち:
        raise 拒む(f"{名}: 会社 {c} の行が 1 つも無い＝出した月か読めない（行を起こすのは事務所の段の 月の行）")
    並び = _出した月(名, 行たち)
    if not 並び:
        if 月:
            raise 拒む(f"突き合わせる月: 会社 {c} はまだ 1 度も出していない（月の状況に出した印が無い）のに月 {月!r} を渡した")
        if not 訳:
            raise 拒む(f"突き合わせる月: 会社 {c} はまだ 1 度も出していない＝突き合わせる物が無い訳を渡す")
        return {"月": "", "出した月": [], "無い訳": 訳, **足す}
    if 訳:
        raise 拒む(f"突き合わせる月: 会社 {c} は {並び[-1]} に出している＝無い訳で突き合わせを飛ばさない（月 {並び[-1]} を渡す）")
    if not 月 or _鍵の値(名, "支給月", 月, "渡した月") != 支給月の字.鍵の年月(並び[-1]):
        raise 拒む(f"突き合わせる月: 会社 {c} の最後に出した月は {並び[-1]}（渡した月 {月!r}）＝最後に出した月で突き合わせる")
    return {"月": 並び[-1], "出した月": 並び, "無い訳": "", **足す}


変わる印 = ("書く手順", "寄せられない物", "足りない値", "管理表へ書く", "写した物")   # 見通す の返す鍵（どれかが空でなければ変わる）


def _出した月(名: str, 行たち: list) -> list[str]:
    """出した月＝出した印の在る支給月（殻の字・古い順）。読めない支給月は拒む。"""
    出した = {}
    for i, r in 行たち:
        x = _鍵の値(名, "支給月", r["支給月"], f"{i + 2} 行目")
        if any(str(r[k]).strip() in v for k, v in 出した印.items()):
            出した[x] = 支給月の字.字にする(*x, "殻")
    return [出した[k] for k in sorted(出した)]


def _変わる残り(見通し: dict, 会社のタブ, c: str) -> list[str]:
    """変わらないと言えない訳の並び（空＝変わらない）。見通しの 変わる印 と、会社のタブの寄せ中（前の回が止まった）から読む。"""
    if not isinstance(見通し, dict) or (欠け := [k for k in 変わる印 if k not in 見通し]):
        raise 拒む(f"突き合わせる月: 見通し に {'・'.join(欠け) if isinstance(見通し, dict) else '鍵'} が無い＝変わらないか読めない（見通す の返す物をそのまま渡す）")
    if 見通し.get("会社") != c:
        raise 拒む(f"突き合わせる月: 見通し の会社 {見通し.get('会社')!r} が 会社 {c!r} と違う＝別の会社の見通しで変わらないと言わない（その会社の 見通す の返す物を渡す）")
    if 会社のタブ is None:
        raise 拒む("突き合わせる月: 見通し を渡す時は 会社のタブ（管理表「会社」の今の値）も渡す＝前の回が止まったかを読む")
    残り = [f"{k} {len(見通し[k])} 件" for k in 変わる印 if 見通し[k]]
    印 = 寄せの印({"今の値": 会社のタブ, "会社": c})
    if 印["寄せ中"]:
        残り.append(f"寄せ中（前の回が止まった: {印['理由'] or '理由なし'}）")
    return 残り


def 立ち上げ(入力: dict) -> list[dict]:
    """事務所の段。管理表（00_事務所/管理表）に型のタブを足す手順。入力: 今のタブ＝{タブの名: 今の値（get_values）}（管理表の全部のタブ）。

    型のタブが無ければ見出しまで 1 手で足す（`タブを足す`）。在って見出しが型と同じなら何もしない。在って見出しが違う時は
    書き換えず拒む（前の管理表の値は事務所の物＝列の移し方は事務所が決める・違いを並べる）。型に無いタブ（前の管理表の 全社_会社 など）は
    触らない＝型のタブとは別の物（書く口・型の版を読む口は型のタブの名だけを読む）。何度当てても同じ。
    今のタブは必ず渡す（管理表の全部のタブ・値の無いタブは `[]`）。省く・None・空の {}・dict でない物・値が行の並びでないタブは
    止める＝在るタブを無いと読んで「タブを足す」を返さない（足すと同じ名のタブがぶつかる・前の版の値の上に見出しを置く）。"""
    今 = 入力.get("今のタブ") if isinstance(入力, dict) else None
    if not isinstance(今, dict) or not 今:
        raise 拒む(f"今のタブ（管理表の全部のタブ {{タブの名: 今の値}}・値の無いタブは []）を渡す。渡さないと在るタブを無いと読む"
                 f"＝足す手順を返さない（受けた物: {今!r}）")
    形の違う = [str(k) for k, v in 今.items() if not isinstance(v, (list, tuple)) or any(not isinstance(r, (list, tuple)) for r in v)]
    if 形の違う:
        raise 拒む(f"今のタブの値は get_values の行の並び（値の無いタブは []）で渡す: {'・'.join(形の違う)}")
    手順, 違う = [], []
    for 名, h in 全部の見出し().items():
        if 名 not in 今:
            手順.append({"する": "タブを足す", "タブ": 名, "見出し": list(h), "書き方": 字のまま})
            continue
        値 = 今[名] or []
        見 = [str(c) for c in (値[0] if 値 else [])]
        if not 見 and len(値) <= 1:
            手順.append({"する": "行を足す", "タブ": 名, "値": list(h), "書き方": 字のまま})   # 空のタブに見出しを置く
        elif 見 != h:
            違う.append(f"{名}（{_見出しの違い(名, 見)}）")
    if 違う:
        raise 拒む(f"見出しが型と違うタブ: {'・'.join(違う)}。前の値の移し方は事務所が決める（このタブは書き換えない）")
    return 手順


