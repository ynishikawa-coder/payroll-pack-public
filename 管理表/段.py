# 除いた人の理由 → (段, 次)。マスタの欠けは立ち上げの会社なら 0、毎月の会社なら 1 の ①
_人の段: tuple[tuple[str, str | None, str], ...] = (
    (r"必ず埋める欄が空|^人\.区分「", None, "マスタの欄を埋める"),
    (r"確定した勤怠|締め", 材料, "③ 勤怠の締め: 原本を読み照らし、締めの記録を 締まった にする"),
)


def 赤を段へ(赤: str) -> tuple[str, str]:
    for 形, 段, 次 in 赤の段:
        if re.search(形, 赤):
            return 段, 次
    return 計算, 分けに無い


def 人の訳を段へ(訳: str, 状態: str) -> tuple[str, str]:
    for 形, 段, 次 in _人の段:
        if re.search(形, 訳):
            if 段 is None:
                return (初期設定, f"初期設定で{次}") if 状態 == "立ち上げ" else (材料, f"① マスタの更新: {次}")
            return 段, 次
    if "通すには、" in 訳:
        return 材料, 訳.split("通すには、", 1)[1]
    return 計算, "仮の訳を読んで直す（仮が 0 になってから出す）"


def _足す(足りない: list[dict], 段: str, 対象: str, 何: str, 次: str) -> None:
    """同じ段・同じ訳・同じ次は 1 つにまとめ、対象（会社・NO）を並べる。"""
    for x in 足りない:
        if (x["段"], x["何"], x["次"]) == (段, 何, 次):
            if 対象 not in x["対象"]:
                x["対象"].append(対象)
            return
    足りない.append({"段": 段, "対象": [対象], "何": 何, "次": 次})


def _字(r: dict | None, k: str) -> str:
    return str((r or {}).get(k) or "").strip()


def 段を見る(事実: dict) -> dict:
    """事実 → {会社, 支給月, 回, 段, 足りない, 次にやること, 知らせ}。

    事実: 会社・支給月・回（月・賞与）・状態（会社の一覧の状態・無ければ空）・赤・除いた人・止まり・形の崩れ・出し直しの候補・知らせ
    （出す の試しの返りと同じ鍵）と 行（管理表の回のタブのその会社×支給月の行・無ければ None）。"""
    状態 = _字(事実, "状態")
    out = {k: 事実.get(k, "") for k in ("会社", "支給月", "回")}
    知らせ = [*(事実.get("知らせ") or ()),
            *(f"形の崩れ: {x}" for x in 事実.get("形の崩れ") or ()),
            *(f"出し直しの候補: {x}" for x in 事実.get("出し直しの候補") or ())]
    if 状態 == 止めた:
        return {**out, "段": 止めた, "足りない": [], "次にやること": "無し（会社の一覧で 止めた）", "知らせ": 知らせ}
    足りない: list[dict] = []
    for r in 事実.get("赤") or ():
        段, 次 = 赤を段へ(str(r))
        _足す(足りない, 段, "会社", str(r), 次)
    止まり = list(事実.get("止まり") or ())
    for s in 止まり:
        対象 = "会社" if s.get("対象") in ("会社", "", None) else f"社員ID {s['対象']}"
        _足す(足りない, 材料, 対象, f"答え待ち（問い {s.get('問いの鍵', '')}）: {s.get('何が', '')}", str(s.get("何をすれば通るか", "")))
    for a in 事実.get("除いた人") or ():
        for 訳 in a.get("理由") or ():
            if 止まり and "通すには、" in str(訳):   # 同じ訳は 止まり が持つ（二重に数えない）
                continue
            段, 次 = 人の訳を段へ(str(訳), 状態)
            _足す(足りない, 段, f"NO {a.get('NO', '')}", str(訳), 次)
    行 = 事実.get("行")
    if 行 is None and out["回"] == "月":
        _足す(足りない, 材料, "会社", "管理表「月の状況」にこの支給月の行が無い", "事務所の段で月の行を起こす（管理表/管理表.py 月の行）")
    if _字(行, "確認ページ") == "お答え待ち":
        _足す(足りない, 材料, "会社", "確認ページのお答え待ち", "お答えが来たら答えを当てて回し直す")
    if 足りない:
        段 = min((x["段"] for x in 足りない), key=段たち.index)
        次 = next(x["次"] for x in 足りない if x["段"] == 段)
    elif _字(行, "取り込み") != "済":
        段, 次 = 計算, "出口/出す.py で出す（試しは通る）"
    elif _字(行, "納品") != "済":
        段, 次 = 納品, "給与ソフトと突き合わせ、差 0 の人を納品する（管理表の 突き合わせ・納品 を書く）"
    else:
        段 = 済み
        次 = ("管理表「会社」の 初回の確認の OK の日 を書き、会社の一覧の状態を 毎月 にする" if 状態 == "立ち上げ" else "無し")
    return {**out, "段": 段, "足りない": [{**x, "対象": "・".join(x["対象"])} for x in 足りない],
            "次にやること": 次, "知らせ": 知らせ}


def 管理表の行(見た: dict, 今日: str) -> dict:
    """段を見る の返り → 管理表「段」へ書く行（組は書く口が会社の一覧から書く）。"""
    足りない = " ／ ".join(f"[{x['段'][:1] if x['段'][0].isdigit() else x['段']}] {x['対象']}: {x['何']}"
                        for x in 見た["足りない"])
    return {"会社": 見た["会社"], "支給月": 見た["支給月"], "回": 見た["回"], "段": 見た["段"],
            "足りない物": 足りない, "次にやること": 見た["次にやること"], "更新日": 今日}
