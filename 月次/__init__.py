# ---- 社保の立て替えの残り（社保.引けない月の本人負担＝立て替えて復帰後に引く）を次の月へ渡す ----
# 残りは前の月の確定した結果（関所を通った芯の行）から月次が 台帳「その月だけの指示」の次の月の行にして返す（殻はそのまま書く・人が写さない）。
