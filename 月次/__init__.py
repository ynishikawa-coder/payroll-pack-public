def _項目の単位(行たち) -> dict[str, str]:
    """関所へ渡した行（芯/計算・芯/集計 の行は 単位 を持つ）→ {項目: 単位}。支給控除一覧 の 項目の形 の元（正本は行の単位 1 つ）。
    同じ項目に違う単位が出たら止める。単位の無い行の項目は載せない（書き口が「形が無い」で止める）。"""
    out: dict[str, str] = {}
    for r in 行たち:
        if not isinstance(r, dict) or r.get("単位") not in 形.値の形たち:
            continue
        k = str(r.get("項目"))
        if out.setdefault(k, r["単位"]) != r["単位"]:
            raise ValueError(f"項目「{k}」の行の単位が {out[k]} と {r['単位']} に分かれる（支給控除一覧の形が決まらない）")
    return out


