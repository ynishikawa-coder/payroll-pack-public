    if 表 is None:
        return
    if isinstance(表, (str, bytes, dict)):
        raise ValueError(f"{名} は年の台帳の get_values の形（1 行目が見出しの 2 次元の並び）で渡す（{type(表).__name__} は読まない）")
    xs = list(表)
    if xs and not all(isinstance(r, (list, tuple)) for r in xs):
        raise ValueError(f"{名} は見出しつきの形（get_values の形）だけ受ける。dict の並びは読まない（台帳から読んだままの形で渡す）")


