def _前の支給月の字(月: str) -> str:
    """`YYYY-MM` → 前の支給月の `YYYY-MM`（1 月は前の年の 12 月）。"""
    y, m = (int(x) for x in str(月).split("-")[:2])
    return f"{y - 1}-12" if m == 1 else f"{y}-{m - 1:02d}"


def _前の期間の行(表A, 表B, 前の表A, 前の表B, 会社名: str, 月: str) -> tuple[list, list]:
    """期間の頭の週の判定へ渡す前の期間の行。同じ年の台帳の確定した勤怠に在る前の支給月の行は、ここが台帳から直に読む
    （殻が `前の確定した勤怠` を渡し忘れても欠けない＝前の期間の日を受けていない仮で人が関所で外れない。2026-11 ある顧問先で
    出荷の口が 1 月支給の時しか渡さず、残業のある人が全員外れた）。`前の確定した勤怠`（前の年の台帳＝1 月支給）で渡った日は重ねない。"""
    前 = _前の支給月の字(月)
    前A, 前B = list(前の表A), list(前の表B)
    有る = {(str(a.get("会社", "")), str(a.get("NO", "")), str(a.get("日付", ""))) for a in [*前A, *前B]}

    def 足す(a) -> bool:
        return (str(a.get("会社", "")) == 会社名 and str(a.get("支給月", "")) == 前
                and (str(a.get("会社", "")), str(a.get("NO", "")), str(a.get("日付", ""))) not in 有る)
    return 前A + [a for a in 表A if 足す(a)], 前B + [b for b in 表B if 足す(b)]


def _フレックスの前の月(全A, 全B, 前の全A, 前の全B, 会社名: str, 月: str, 期間の始め, 決まり: dict, 法の線: dict,
                   締めの記録, 前の締めの記録=(), その月の元=None) -> list[dict]:
    """清算期間が 1 か月を超えるフレックスの人の、同じ清算期間の前の月の実働（芯/集計 の `フレックスの前の月` へ渡す形）。
    年の台帳の確定した勤怠（正本）の前の支給月の行を芯/集計 で数え直して作る（前の回の結果を写して残さない＝
    台帳「人ごとの月の数字」は読まない。確定した勤怠が直れば前の月の実働も同じに変わる）。
    同じ年の支給月の行と締めは `全A・全B`・`締めの記録`（今の年の台帳）から、前の年の支給月の行と締めは `前の全A・前の全B`・
    `前の締めの記録`（前の年の台帳）から引く（年をまたぐ清算期間＝例 11〜1 月 も終わりの月を確かな値で出す）。
    前の月を数え直す時の前の期間の行は、その月を回した時と同じ（その月の台帳の前の支給月の行。同じ年なら前の年の台帳も）。
    前の月は **その月に効いていた決まりと法の線** で数え直す: `その月の元(支給月 YYYY-MM)` → (その月の決まり, その月の法の線)。
    元が None を返す月（その月の決まりか法の線が揃わない）・その月にフレックスの長い清算期間でない人の月は渡さない＝後の月が仮
    （今の月の決まりや法の線で数え直して、途中で変わった決まりを黙って前の月へ当てない）。
    遡るのは今の法の線の月の上限−1 か月まで。今の清算期間（今の月の その人の 時間.フレックスの清算期間 の起算日〜今の給与の期間の前）の外の月は
    渡さない（前の清算期間の月を渡すと芯が区切りの外として仮にする）。前の月が台帳に無ければ渡さない＝芯が揃っていないとして仮にする。
    締めの記録でその支給月が 締まった でない人の月と、数え直して仮が残る月（芯が出さない）も渡さない＝後の月が仮。"""
    フ = {(str(k[0]), str(k[1])): v for k, v in 決まり.items() if _フレックスの長い清算か(k, v, 会社名)}
