def _前と今をつなぐ(前, 今, 会社名: str) -> list[dict]:
    """有給の道へ渡す確定した勤怠: 前の確定した勤怠（前の年の台帳・同じ年の前の支給月）と今の支給月の確定した勤怠を、
    その会社の行だけでつなぐ。前に今と同じ人・同じ日の行があれば今の行を取る（同じ年の台帳を前にも渡すと同じ日が
    2 行になり、有給/有給.py が重なりとしてその人を止める＝渡し方の重なりで止めない）。同じ側の中の重なりは除かない
    （台帳そのものの重なり＝有給/ が止める）。"""
    def 鍵(a):
        return str(a.get("NO", "")).strip(), str(a.get("日付", "")).strip()[:10]
    今たち = [a for a in 今 if str(a.get("会社", "")).strip() == 会社名]
    今の日 = {鍵(a) for a in 今たち}
    return [*(a for a in 前 if str(a.get("会社", "")).strip() == 会社名 and 鍵(a) not in 今の日), *今たち]


