        # その月にフレックスの長い清算期間でない人は芯が その月の実働 を出さない（芯/集計 の フレックスの月の実働）＝渡らない
        決 = {k: v for k, v in その月の決まり.items() if (str(k[0]), str(k[1])) in フ and str(k[1]) in 人}
        if not 決:
            continue
