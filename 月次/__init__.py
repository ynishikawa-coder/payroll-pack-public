def _月の変動を足す(タブの行, 読んだ行) -> list[dict]:
    """段の解決へ渡す 月の変動: 台帳の行（タブ）に、入口が今の原本から読んだ行を足す。同じ原本の同じ人×項目は読んだ行が勝つ
    （殻が前の回に書いた行を読み直した物）。読んだ行の 要確認 は渡さない（その人は入口の 要確認 で仮＝問いを 2 つにしない）。"""
    def 鍵(r):
        return tuple(str(r.get(c, "") or "").strip() for c in ("会社", "NO", "項目", "原本の名前"))
    読んだ = list(読んだ行 or ())
    読んだ鍵 = {鍵(r) for r in 読んだ}
    return [*(r for r in 段.行たち(タブの行) if 鍵(r) not in 読んだ鍵),
            *(r for r in 読んだ if str(r.get("確認", "") or "").strip() != 入口の口.要確認)]


def _タブとつなぎ(タブ: dict, つなぎ=()) -> tuple[dict, list[dict]]:
    """殻が渡すタブ → (段の解決.解く へ渡すタブ, つなぎの行)。事務所の設定のタブに ⑥つなぎ（側＝入口・出口の行）を入れてよい
    （README のとおりタブから読む）。引数の `つなぎ=` の行はタブの行の後ろに足す（どちらで渡しても同じに効く）。"""
    段のタブ, 外 = 段.タブを分ける(タブ)
    return 段のタブ, [*段.行たち(外.get("つなぎ", ())), *段.行たち(つなぎ or ())]


def 入口を読む(原本, 文脈):
    """原本の並びを読み、2 つ目からは 口.重ねる で上に重ねる（読む順は作業のルール「読み方と合わせ方」＝殻が並べる）。

    原本: [{"部品": 読み口の名, "値": 殻が読んだ原本の値, "引数": {部品の残りの引数}}]（値は部品の第 1 引数）。"""
    out = None
    for x in 原本:
        r = _読み口(x["部品"]).読む(x["値"], 文脈=文脈, **(x.get("引数") or {}))
        out = r if out is None else 入口の口.重ねる(out, r)
    return out if out is not None else 入口の口.結果()


def _出口へ(通, 会社名: str, 月: str, 出口: dict | None, タブ: dict | None = None, つなぎ=()) -> dict:
    """取り込み の 欄の対応 を渡さず 道具（⑥つなぎ の給与ソフトの呼び名）を渡せば、口が Drive の値から組む
    （`出口.形.欄の対応を組む`: ④支給控除の項目 の 給与ソフトの欄＋⑥つなぎ の会社の行 側＝出口）。殻が手で対応を組まない。
    給与ソフトへ入れない人は ⑥つなぎ の人の行（側＝出口・道具＝<道具>・その道具での番号＝`渡さない`）から口が組む
    （`出口.形.渡さない人を組む`。欄の対応 を渡しても 道具 を渡せば読む）。殻は返った表から行を消さない。"""
    出口 = 出口 or {}
    out = {}
    if 出口.get("取り込み") is not None:
        取 = dict(出口["取り込み"])
        道具 = 取.pop("道具", None)
        if "渡さない人" in 取:   # 置き場は ⑥つなぎ の人の行 1 か所（殻が手で人を外す道を畳む）
            raise ValueError("出口.取り込み: 渡さない人 は渡さない（⑥つなぎ の人の行 側＝出口・道具＝<給与ソフトの呼び名>・"
                             "その道具での番号＝渡さない に書き、道具 を渡せば口が読む）")
        取["渡さない人"] = 形.渡さない人を組む(会社名, 道具, list(つなぎ or ()))
        if "欄の対応" not in 取:
            if not 道具:
                raise ValueError("出口.取り込み: 欄の対応 か 道具（⑥つなぎ の給与ソフトの呼び名）を渡す")
            取["欄の対応"] = 形.欄の対応を組む(会社名, 道具, 段.行たち((タブ or {}).get("支給控除の項目", ())),
                                       list(つなぎ or ()), 支給月=月)
        out["取り込み"] = 書き口.取り込み(通, 会社名, 月, **取)
    if 出口.get("支給控除一覧") is not None:
        out["支給控除一覧"] = 書き口.支給控除一覧(通, 会社名, 月, **出口["支給控除一覧"])
    return out


def 見当の額(行たち) -> dict:
    """芯/計算 の行 → {NO: {総支給額, 差引支給額, 仮}}（仮の人も含む＝問いに添える見込みの額。出口へは出さない）。"""
    out: dict[str, dict] = {}
    for r in 行たち:
        if r.get("項目") in ("総支給額", "差引支給額"):
            d = out.setdefault(str(r["NO"]), {"仮": False})
            d[r["項目"]] = r.get("値")
            d["仮"] = d["仮"] or r.get("状態") == "仮"
    return out


def 前の支給月(支給月: str) -> str:
    """`YYYY.MM支給` の 1 つ前の支給月（`YYYY.MM支給`）。"""
    y, m = (int(v) for v in 段.月(支給月).split("."))
    y, m = (y - 1, 12) if m == 1 else (y, m - 1)
    return f"{y}.{m:02d}支給"


def _前の表(支給月: str, 会社名: str, タブ: dict, 前の原本, *, 区分の読み替え, つなぎ, 人の区分の読み替え, 置き場,
          質問と回答=()) -> dict:
    """前の期間の勤怠（殻が Drive から読んだ前の支給月の原本・月を回す の 原本 と同じ形）→ 前の表 A・B。

    月を回す と同じ部品の並び（段の解決 → 入口の文脈 → 入口を読む）を前の支給月で通す（殻が部品を手で組まない）。
    前の期間の読みに要確認が残る人（入口の 人の状態 が確定でない）は、その人の前の期間の行を前の表 A・B に入れない
    ＝確かめていない日で今の月の週の判定をしない。その人は前の期間の日を受けていない時と同じ道（頭の週に労働があれば仮＋問い）に落ち、
    出口へ出ない ⟦鍵:給与計算/足りない時は仮で計算し出さない⟧。外した訳は知らせに出す。"""
    前の月 = 前の支給月(支給月)
    タブ, つなぎ = _タブとつなぎ(タブ, つなぎ)
    r = 段.解く(前の月, **タブ)
    x = 繋.入口の文脈(前の月, 会社名, r, 置き場=置き場, 質問と回答=質問と回答, **タブ)
    文脈 = 入口の口.文脈(**x["文脈"], 区分の読み替え=dict(区分の読み替え or {}), つなぎ=list(つなぎ or ()),
                      人の区分の読み替え=dict(人の区分の読み替え or {}))
    読んだ = 入口を読む(前の原本, 文脈)
    # 前の期間も、原本の来ない 時間.出勤簿が無い＝無い の人は所定どおり働いたとみなす（今の月と同じ道＝在籍の外の日は置かない）
    前に来た = {str(a.get("NO", "")) for a in 読んだ.日}
    無い人 = [no for no in 文脈.出勤簿が無い if str(no) not in 前に来た]
    if 無い人:
        読んだ = 入口の口.重ねる(入口の口.所定どおりの日(文脈, 無い人), 読んだ)
    確かめていない = {str(NO) for NO, 状態 in 読んだ.人の状態().items() if 状態 != "確定"}
    数 = {}
    for q in 読んだ.要確認:
        数[str(q.get("NO", ""))] = 数.get(str(q.get("NO", "")), 0) + 1
    知らせ = [f"{会社名} {NO or '（NO が引けない）'}: 前の期間（{前の月}）の原本に要確認が {n} 件"
            "＝その人の前の期間の日は週の判定に使わない（期間の頭の週に労働があれば仮＋問い）" for NO, n in sorted(数.items())]
    知らせ += [f"{会社名} {NO}: 前の期間（{前の月}）の読みが確定でない＝その人の前の期間の日は週の判定に使わない"
            for NO in sorted(確かめていない - set(数))]
    使う = [a for a in 読んだ.日 if str(a.get("NO", "")) not in 確かめていない]
    使う区間 = [b for b in 読んだ.区間 if str(b.get("NO", "")) not in 確かめていない]
    return {"前の表A": 使う, "前の表B": 使う区間, "知らせ": 知らせ}


def 月を回す(支給月: str, 会社名: str, タブ: dict, 原本=(), *, 区分の読み替え: dict | None = None, つなぎ=(),
          人の区分の読み替え: dict | None = None,
          前の表A=(), 前の表B=(), 前の原本=None, 法の線: dict | None = None, 有給の値: dict | None = None,
          出口: dict | None = None, 質問と回答=(), 置き場=None) -> dict:
    """1 会社の 1 支給月を回す。呼び順は 月次/README.md「月を回す」。

    支給月: `YYYY.MM支給`（段の解決・有給/ の書き方。入口・芯・出口へは `YYYY-MM` に直して渡す）。
    タブ: 段の解決.解く に渡すタブ（会社・勤務の型・社員・人ごとの支給控除・支給控除の項目・事務所・変更の記録・月の変動・人ごと）。
    原本: 入口を読む の並び。区分の読み替え・つなぎ: 入口の文脈 に足す殻の値（Drive の作業のルール・マスタ⑥つなぎ）。
    人の区分の読み替え: 任意。{人（NO か 勤怠の表記）: {語: 読み}}＝その人だけ 区分の読み替え の上に重ねる（同じ語の夜勤を人ごとの勤務の型へ）。
    前の表A・前の表B: 期間の頭の週が前の期間にかかる時の台帳の前の期間の行。
    前の原本: 任意。前の支給月の勤怠（原本 と同じ形）。渡せば口が 原本 と同じ部品の並びで前の表 A・B を作る（前の表A・B と一緒には渡せない）。
    法の線: 無ければ 法の表/ から期間で引く。
    質問と回答: 任意。01_ルール/質問と回答 の行（列名の dict か get_values の形）。日の問いの答えを読む元はこの 1 本
      （`初期設定/入口の文脈.日の答え` → 入口がその日に当てる: 時刻〔手書きの時刻で数える〕・長さ〔本当にその長さ働いた〕・
      区分〔表 A の列＝値〕）。答えた日は返す 台帳 の勤怠に 確認済・備考（問いの番号と答え）・区分が載る＝殻が出力をそのまま書けば
      答えの記録は消えない。台帳「勤怠」「勤怠の区間」は口の出力のまま＝答えを読む元にしない。前の原本 の読みにも同じ行を渡す。
    有給の値: None なら有給を回さない。{"勤怠の始め", "出勤率が足りない付与日"} で回す。
    出口: {"取り込み": 書き口.取り込み の残りの引数, "支給控除一覧": 書き口.支給控除一覧 の残りの引数}（欄の対応・形 など）。
      取り込み に 欄の対応 を渡さず 道具（⑥つなぎ の給与ソフトの呼び名）を渡せば、口が タブ の 支給控除の項目・つなぎ から組む。
      給与ソフトへ入れない人（給与ソフトに載せない代表など）は ⑥つなぎ の人の行 その道具での番号＝`渡さない` を口が読んで外す
      （取り込みの行にも `空の欄` にも出ず `渡さなかった人` に返る＝突き合わせへそのまま渡す）。`渡さない人` を殻が渡すと止まる。
    つなぎ: ⑥つなぎ の行は タブ の `つなぎ`（事務所の設定のタブのまま）でも この引数でも渡せる（両方なら足す）。段の解決へは渡さない。
      取り込み の 形 は殻が事務所の設定から読んだ値（dict）か 出口.形.形を組む の結果。dict なら書き口が 形を組む を通す（無ければ止まる）。
    """
    タブ, つなぎ = _タブとつなぎ(タブ, つなぎ)   # ⑥つなぎ はタブで渡しても 引数で渡してもよい（段の解決へは渡さない）
    前の知らせ = []
    if 前の原本 is not None:
        if 前の表A or 前の表B:
            raise ValueError("前の原本 と 前の表A・前の表B は一緒に渡せない（前の期間の日を 2 度数える）")
        前 = _前の表(支給月, 会社名, タブ, 前の原本, 区分の読み替え=区分の読み替え, つなぎ=つなぎ,
                  人の区分の読み替え=人の区分の読み替え, 置き場=置き場, 質問と回答=質問と回答)
        前の表A, 前の表B, 前の知らせ = 前["前の表A"], 前["前の表B"], 前["知らせ"]
    r = 段.解く(支給月, **タブ)
    x = 繋.入口の文脈(支給月, 会社名, r, 置き場=置き場, 質問と回答=質問と回答, **タブ)
    月 = x["文脈"]["支給月"]
    文脈 = 入口の口.文脈(**x["文脈"], 区分の読み替え=dict(区分の読み替え or {}), つなぎ=list(つなぎ or ()),
                      人の区分の読み替え=dict(人の区分の読み替え or {}))
    読んだ = 入口を読む(原本, 文脈)
    入口の仮 = _入口の仮の値(読んだ, 会社名)
    if 読んだ.月の変動:   # 今の原本の手当・控除（月の変動）も同じ回の 入力 へ（段の解決の月の変動の読みは 1 つ＝解き直す）
        タブ = {**タブ, "月の変動": _月の変動を足す(タブ.get("月の変動", ()), 読んだ.月の変動)}
        r = 段.解く(支給月, **タブ)

    # 在籍が期間にかからない人（期間の前に辞めた・後に入る）は芯へ渡さず仮にもしない。
    # その月の物が来た人（勤怠・月の変動〔台帳と入口〕・入口の人ごとの支給控除）は外さない（日付の誤りかもしれない＝芯へ渡して仮で問う）
    来た = {str(a.get("NO", "")) for a in [*読んだ.日, *読んだ.月の数字, *読んだ.月の変動, *読んだ.人ごとの支給控除]}
    来た |= {str(k[1]) for k in (r.get("入力") or {}) if str(k[0]) == 会社名}
    # 台帳の月の変動のその支給月の行（支給月の字がそろわない行も）は読めたかに関わらず（読めない行は 入力 に入らず
    # 仮の値 台帳.月の変動 にだけ出る＝その問いを消さない）。前の月の行だけの人は外す（台帳は年の全部の月の行を持つ）
    その月, そろわない = 段.その月の変動(支給月, 段.行たち(タブ.get("月の変動", ())))
    来た |= {str(k[1]) for k in [*その月, *そろわない] if str(k[0]) == 会社名}
    外 = 繋.期間の外の人(会社名, r, x["文脈"]["期間の始め"], x["文脈"]["期間の終わり"], 来た)
    外の仮 = {}   # 外した人の段の解決・入口の文脈の仮（黙って消さず知らせに名を出す。その月に払わない人の値は計算に効かない）
    for q in [*r["仮の値"], *x["仮の値"]]:
        if str(q.get("会社", 会社名)) == 会社名 and str(q.get("NO", "")) in 外:
            外の仮.setdefault(str(q["NO"]), []).append(str(q.get("項目", "")))
    # 原本が 1 枚も来ない 時間.出勤簿が無い＝無い の人（勤怠を管理しない月給の固定給・役員でない家族の従業員など）は、
    # 所定どおり働いたとして表 A を作る（入口の日の部品の「出勤簿が無い＝所定どおりとみなす」の道）。
    # 原本に出た人（来た）は入口がその道で定時扱いにするので足さない。期間の外の人も足さない（払わない人）。
    無い人の所定どおり = [no for no in 文脈.出勤簿が無い if str(no) not in 来た and str(no) not in 外]
    if 無い人の所定どおり:
        読んだ = 入口の口.重ねる(入口の口.所定どおりの日(文脈, 無い人の所定どおり), 読んだ)
        入口の仮 = _入口の仮の値(読んだ, 会社名)   # 日の所定が渡されない人の要確認を寄せ直す
    # 読めた答えでどの日にも当たらなかった物（問いの字が理由と違う・区間が決まらない など）は黙って捨てず知らせに出す
    答えの知らせ = 入口の口.当てなかった日の答え(文脈, 読んだ.日)
    決まり, 人 = _その会社(r["決まり"], 会社名), _その会社(r["人"], 会社名)
    決まり, 人 = ({k: v for k, v in d.items() if str(k[1]) not in 外} for d in (決まり, 人))
    x = {**x, "仮の値": [q for q in x["仮の値"] if str(q.get("NO", "")) not in 外]}
    if 法の線 is None:
        from 芯.集計.法の線の橋 import 法の線を引く
        法の線 = 法の線を引く(x["文脈"]["期間の始め"], x["文脈"]["期間の終わり"], 置き場=置き場)
    集 = 集計する(読んだ.日, 読んだ.区間, 決まり=決まり, 法の線=法の線, 月の口=読んだ.月の数字,
              前の表A=前の表A, 前の表B=前の表B, 支給月=月)
    計 = 計算する(集, 決まり=決まり, 人=人, 入力=_その会社(繋.計算の入力(r["入力"], 集), 会社名), 置き場=置き場)

    段の仮 = [q for q in r["仮の値"] if str(q.get("会社", "")) == 会社名 and str(q.get("NO", "")) not in 外]
    渡す, 出さない = 関所.勤怠の行を分ける(集["行"], 決まり, 集.get("所定で頭打ちの実働"))  # 勤怠の欄（出勤日数・残業時間など）も同じ関所を通す
    z = 繋.給与の関所へ({"行": [*計["行"], *渡す], "人の状態": 計["人の状態"]}, 段の仮, [*x["仮の値"], *入口の仮])
    通 = 関所.通す(z["行"], z["人の状態"])

    out = {
        "支給月": 月, "会社": 会社名,
        "関所を通った": 通,
        "外した人": [a.行() for a in 通.外した人たち],
        **_出口へ(通, 会社名, 月, 出口, タブ, つなぎ),
        # 台帳へ書く表（出口へは出さない）: 型のタブの形（1 行目が型の見出し）。形を作るのは 月次/台帳の形.py の 1 か所
        "台帳": 台帳の形.台帳へ書く形(勤怠=読んだ.日, 勤怠の区間=読んだ.区間, 月の変動=読んだ.月の変動,
                              人ごとの支給控除=読んだ.人ごとの支給控除, 集計の行=集["行"], 人の状態=集["人"],
                              氏名=_氏名(タブ, 会社名)),
        "出口へ出さない勤怠の行": 出さない,
        "期間の外の人": [{"会社": 会社名, "NO": NO, "訳": 訳, "読まなかった仮": 外の仮.get(NO, [])} for NO, 訳 in sorted(外.items())],
        "問い": {"段の解決": 段の仮, "入口の文脈": x["仮の値"], "入口": 読んだ.要確認, "集計": 集["問い"], "計算": 計["問い"]},
        # 問いの種（初期設定/設問.py）: 芯/計算 の法の線の検査の行と、仮の人も含めた人ごとの見当の額（出口へは出さない）
        "法の線": list(計.get("法の線", ())),
        "見当の額": 見当の額(計["行"]),
        "知らせ": {"段の解決": r["知らせ"], "入口の文脈": [*x["知らせ"], *答えの知らせ], "集計": 集["知らせ"], "計算": 計.get("知らせ", []),
                 "月次": [f"{会社名} {NO}: {訳}（在籍が期間の外＝芯へ渡さない）"
                        + (f"。この人の仮の値（{'・'.join(dict.fromkeys(外の仮[NO]))}）は読まなかった" if 外の仮.get(NO) else "")
                        for NO, 訳 in sorted(外.items())] + 前の知らせ},
    }

    if 有給の値 is not None:
        y = 繋.有給の入力(支給月, 会社名, r, 読んだ.日, 社員=タブ.get("社員", ()), **有給の値)
        表 = 有給.管理表(y["入力"], 置き場=置き場)  # 付与日数は 法の表/有給_付与日数
        # 段の解決・入口の文脈・入口の仮も有給の関所へ寄せる（年休の読みと人の値がその仮に乗る）
        zz = 繋.有給の関所へ(y, 表, [*段の仮, *x["仮の値"], *入口の仮])
        通有 = 関所.通す(zz["行"], zz["人の状態"])
        out["有給の出す行"] = 繋.有給の出す行(表, 通有)
        out["有給の外した人"] = [a.行() for a in 通有.外した人たち]
        out["有給の見出し"] = 表.get("見出し")
        out["問い"]["有給"] = [*y["仮の値"], *表.get("問い", ())]
        out["知らせ"]["有給"] = y["知らせ"]
    return out


def 賞与を回す(支給月: str, 会社名: str, タブ: dict, 支給一覧, *, 支給日: str, 出口: dict | None = None,
          つなぎ=(), 置き場=None, **賞与の引数) -> dict:
    """1 会社の 1 回の賞与を回す。呼び順は 月次/README.md「賞与を回す」。

    支給月: 段の解決が読む `YYYY.MM支給`（賞与を払う月）。支給一覧: 賞与を計算する の第 1 引数（人に結んだ後の行）。
    賞与の引数: 前月の課税対象額・前の標準賞与額 など 賞与を計算する の残りの引数（そのまま渡す）。
    段の解決の仮の人（変更の記録の 確かめ＝仮 など）は芯が確認済で返しても関所で外す。
    ⑥つなぎ はタブ（`つなぎ`）でも引数でも渡せる（出口.取り込み に 道具 を渡せば月を回す と同じに欄の対応を組む）。"""
    タブ, つなぎ = _タブとつなぎ(タブ, つなぎ)
    r = 段.解く(支給月, **タブ)
    計 = 賞与を計算する(支給一覧, 支給日=支給日, 決まり=_その会社(r["決まり"], 会社名), 人=_その会社(r["人"], 会社名),
                 置き場=置き場, **賞与の引数)
    段の仮 = [q for q in r["仮の値"] if str(q.get("会社", "")) == 会社名]
    z = 繋.給与の関所へ(計, 段の仮)
    通 = 関所.通す(z["行"], z["人の状態"])
    月 = sorted({a["支給月"] for a in 計["行"]} or {f"{段.月(支給月).replace('.', '-')}-賞与"})[0]
    return {
        "支給月": 月, "会社": 会社名,
        "関所を通った": 通,
        "外した人": [a.行() for a in 通.外した人たち],
        **_出口へ(通, 会社名, 月, 出口, タブ, つなぎ),
        "問い": {"段の解決": 段の仮, "計算": 計["問い"]},
        "法の線": list(計.get("法の線", ())),
        "見当の額": 見当の額(計["行"]),
        "知らせ": {"段の解決": r["知らせ"], "計算": 計.get("知らせ", [])},
    }
