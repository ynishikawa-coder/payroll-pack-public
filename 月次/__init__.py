def 賞与を回す(支給月: str, 会社名: str, タブ: dict, 支給一覧, *, 支給日: str, 出口: dict | None = None,
          つなぎ=(), 置き場=None, 給与のルール: str | None = None, 法の線: dict | None = None,
          問いの表=None, 決定の鍵たち=None, 照らしの結果=None, **賞与の引数) -> dict:
    """1 会社の 1 回の賞与を回す。呼び順は 月次/README.md「賞与を回す」。

    支給月: 段の解決が読む `YYYY.MM支給`（賞与を払う月）。支給一覧: 賞与を計算する の第 1 引数（人に結んだ後の行）。
      行ごとに パックの版（賞与の回の始めに控えた版＝賞与の支給一覧の列）を持つ。その会社の行の版が今のパックの版と違う・空・
      行で割れる時は止める（`_控えた版を照らす`・どちらの版で出すかはオーナーが決める）。
    賞与の引数: 前月の課税対象額・前の標準賞与額 など 賞与を計算する の残りの引数（そのまま渡す）。
    段の解決の仮の人（変更の記録の 確かめ＝仮 など）は芯が確認済で返しても関所で外す。
    給与のルール: 給与のルール.md の字（例の表を読む）。月を回す と同じ 1 つの口（`_例の関所`）で、支給月のマスタの値で例を照らし、
      例が無い・合わない・確かめた日が無い・`書けない` の例が 1 つでもあれば、その会社の全員を関所で外す（出口へ出ない）。
      例の 確かめた人 に照らして通る確かめの出所の無い例も同じに外す（月を回す と同じ）。
    問いの表・決定の鍵たち・照らしの結果: 例の 確かめた人 の出所を照らす証し（月を回す と同じ。質問と回答「質問」のタブ・
      決定DB の鍵か行の URL の並び・照らしの結果）。渡さなければその種類の出所の例は通らない（既定で閉じる。正本は
      例の確かめ.出所の種類たち）。
    法の線: 例を数える法の線。無ければ 法の表/ から支給月の締めの期間で引く（月を回す と同じ）。
    出す物ごとに 証明（形 `証明.形の名`・回＝賞与）を返す＝殻の出荷の口は月と同じ `出口.証明.照らす` で照らす。
    ⑥つなぎ はタブ（`つなぎ`）でも引数でも渡せる（出口.取り込み に 道具 を渡せば月を回す と同じに欄の対応を組む）。"""
    if "確かめてよい人" in 賞与の引数:   # 畳んだ名簿を 賞与を計算する へ黙って流さない
        raise ValueError(_名簿は畳んだ)
    _賞与の始めの版を照らす(支給月, 会社名, 支給一覧)   # 賞与の回の始めに控えた版と今の版が違えば止める（月と同じ部品）
    タブ, 給与のルール = _例を分ける(タブ, 給与のルール)
    例 = _MDの例(給与のルール, 会社名)
    元のタブ, 元のつなぎ, 元の法の線 = dict(タブ or {}), つなぎ, 法の線
    タブ, つなぎ = _タブとつなぎ(_台帳のタブを段へ(タブ), つなぎ)
    r = 段.解く(支給月, **タブ)
    決まり = _その会社(r["決まり"], 会社名)
    if 法の線 is None:   # 例の日を数える法の線（その支給月の締めの期間・月を回す と同じ引き方）
        from 芯.集計.法の線の橋 import 法の線を引く
        x = 繋.入口の文脈(支給月, 会社名, r, 置き場=置き場, **タブ)
        法の線 = 法の線を引く(x["文脈"]["期間の始め"], x["文脈"]["期間の終わり"], 置き場=置き場)
    例の結果, 例の仮 = _例の関所(支給月, 会社名, タブ, 例, 決まり, 法の線, 問いの表=問いの表, 決定の鍵たち=決定の鍵たち,
                          照らしの結果=照らしの結果)
    計 = 賞与を計算する(支給一覧, 支給日=支給日, 決まり=決まり, 人=_その会社(r["人"], 会社名),
                 置き場=置き場, **賞与の引数)
    段の仮 = [q for q in r["仮の値"] if str(q.get("会社", "")) == 会社名]
    z = 繋.給与の関所へ(計, [*段の仮, *例の仮])
    通 = 関所.通す(z["行"], z["人の状態"])
    月 = 名と版.出す支給月(支給月, "賞与")   # 出す名と証明の支給月の字（正本は 出口/名と版.py の 出す支給月）
    違う = sorted({str(a["支給月"]) for a in 計["行"]} - {月})
    if 違う:
        raise ValueError(f"賞与の計算の行の支給月 {'・'.join(違う)} が出口の支給月の字 {月} と違う（支給月 {支給月}）")
    out = {
        "支給月": 月, "会社": 会社名,
        "関所を通った": 通,
        "外した人": [a.行() for a in 通.外した人たち],
        **_出口へ(通, 会社名, 月, 出口, タブ, つなぎ, 項目の単位=_項目の単位(z["行"])),
        "例の確かめ": 例の結果,
        "問い": {"例": _例の問い(例の結果), "段の解決": 段の仮, "計算": 計["問い"]},
        "法の線": list(計.get("法の線", ())),
        "見当の額": 見当の額(計["行"]),
        "知らせ": {"段の解決": r["知らせ"], "計算": 計.get("知らせ", [])},
    }
    out["証明"] = _証明たち(out, 会社名, 月, "賞与", 例の結果, 計算の元(元のタブ, 元のつなぎ, 給与のルール, 支給一覧=支給一覧, 法の線=元の法の線,
                                                                賞与の引数={"支給日": 支給日, **賞与の引数}))
    return out
