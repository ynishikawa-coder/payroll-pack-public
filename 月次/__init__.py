def 答えを確定した勤怠へ(支給月: str, 会社名: str, タブ: dict, 原本, 質問と回答, *, 区分の読み替え: dict | None = None,
                つなぎ=(), 人の区分の読み替え: dict | None = None, 置き場=None) -> dict:
    """質問と回答の日の問いの答えを、年の台帳の 確定した勤怠（2 次）へ書く行にする道具（決定 7。月を回す の中から呼ばない）。

    原本を答え無し（＝読んだままの勤怠と同じ）と答えありで読み、事実の列（`勤怠の照らし.比べない列` の外）が読んだままと違う日だけを
    返す。その日の行と、違う区間の行の 直した訳 に `問い:<番号>`（その日に当てた答えの問いの番号・読点で幾つも）を書く
    （同じままの区間の行は訳を空に＝勤怠の照らし が「1 次と同じ行に訳」で赤にしない）。
    返す物: 確定した勤怠・確定した勤怠の区間（型の表＝1 行目が見出し。答えで変わった日の行だけ）＝殻は確定した勤怠の
      同じ (会社, 支給月, NO, 日付) の日の行と区間の行をこの行で置き換える。
      まだ要確認: 答えを当てても要確認の理由が残る日（書かない＝確定した勤怠は確かめた日だけ）。
      人の状態・要確認: 答えを当てた後の {NO: 確定|仮} と残る要確認（問いの種。読んだままの勤怠を作る と同じ形）。
      知らせ: 当てなかった答え・読めない答え（黙って捨てない）。"""
    共 = dict(区分の読み替え=区分の読み替え, つなぎ=つなぎ, 人の区分の読み替え=人の区分の読み替え, 置き場=置き場)
    前, _, _, 名 = _原本を読む(支給月, 会社名, タブ, 原本, 質問と回答=(), **共)
    後, x, 文脈, _ = _原本を読む(支給月, 会社名, タブ, 原本, 質問と回答=質問と回答, **共)
    一, 二 = (台帳の形.勤怠の表たち(確定=False, 勤怠=r.日, 勤怠の区間=r.区間, 氏名=名) for r in (前, 後))
    日, 区 = 台帳の形.日のタブ[0], 台帳の形.区間のタブ[0]
    比べない = set(勤怠の照らし.比べない列)

    def 鍵(r: dict, 区間: bool = False) -> tuple:
        return (r.get("会社", ""), r.get("支給月", ""), str(r.get("NO", "")), r.get("日付", ""),
                *((str(r.get("区間の番号", "")),) if 区間 else ()))

    def 違う(a: dict | None, b: dict) -> bool:
        return a is None or any(a.get(c, "") != b.get(c, "") for c in b if c not in 比べない)

    日1 = {鍵(r): r for r in 台帳の形.行たち(一[日])}
    間1 = {鍵(r, True): r for r in 台帳の形.行たち(一[区])}
    間2 = {鍵(r, True): r for r in 台帳の形.行たち(二[区])}
    答え = [a for xs in (文脈.日の答え or {}).values() for a in xs]
    消した日 = {k[:4] for k in 間1 if k not in 間2}
    変わった区間の日 = {k[:4] for k, r in 間2.items() if 違う(間1.get(k), r)}
    書く日, 書く区間, まだ = [], [], []
    for r in 台帳の形.行たち(二[日]):
        k = 鍵(r)
        if not (違う(日1.get(k), r) or k in 消した日 or k in 変わった区間の日):
            continue
        番号 = list(dict.fromkeys(str(a.get("番号", "")) for a in 答え
                                if a.get("番号") and f"{a['番号']}の答え「" in str(r.get("備考", ""))))
        if str(r.get("読み取りの確かめ", "")).strip() == 入口の口.要確認 or not 番号:
            まだ.append({"NO": k[2], "日付": k[3], "要確認の理由": r.get("要確認の理由", ""),
                       "訳": "答えの問いの番号が備考に無い" if not 番号 else "答えを当てても要確認"})
            continue
        訳 = "、".join(f"問い:{n}" for n in 番号)
        書く日.append({**r, 台帳の形.直した訳の列: 訳})
        書く区間 += [{**b, 台帳の形.直した訳の列: 訳 if 違う(間1.get(kb), b) else ""}
                 for kb, b in 間2.items() if kb[:4] == k]
    return {**台帳の形.勤怠の表たち(確定=True, 勤怠=書く日, 勤怠の区間=書く区間), "まだ要確認": まだ,
            "人の状態": dict(後.人の状態()), "要確認": list(後.要確認),
            "知らせ": [*x["知らせ"], *入口の口.当てなかった日の答え(文脈, 後.日)]}


def _有給の値を照らす(有給の値) -> None:
    """月を回す の 有給の値 は None（有給を回さない）か 空の dict（回す）だけ。中の鍵は受けない: 取得と出勤率は年の台帳の
    確定した勤怠から数える（前の `勤怠の始め`・`出勤率が足りない付与日` は型の版 27 で畳んだ）＝知らない鍵を黙って飲まない。"""
    if 有給の値 is None:
        return
    if not isinstance(有給の値, dict):
        raise ValueError(f"有給の値 は None（有給を回さない）か {{}}（回す）で渡す（{type(有給の値).__name__} は読まない）")
    if 有給の値:
        raise ValueError(f"有給の値 に {'・'.join(sorted(map(str, 有給の値)))} を渡さない（{{}} で回す。取得と出勤率は"
                         "年の台帳の確定した勤怠から数える＝勤怠の始め・出勤率が足りない付与日 も受けない）")


