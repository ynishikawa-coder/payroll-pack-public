def _前の支給月の字(月: str) -> str:
    """`YYYY-MM` → 前の支給月の `YYYY-MM`（1 月は前の年の 12 月）。"""
    y, m = (int(x) for x in str(月).split("-")[:2])
    return f"{y - 1}-12" if m == 1 else f"{y}-{m - 1:02d}"


def _前の期間の行(表A, 表B, 前の表A, 前の表B, 会社名: str, 月: str) -> tuple[list, list]:
    """期間の頭の週の判定へ渡す前の期間の行。同じ年の台帳の確定した勤怠に在る前の支給月の行は、ここが台帳から直に読む
    （殻が `前の確定した勤怠` を渡し忘れても欠けない＝前の期間の日を受けていない仮で人が関所で外れない。2026-11 ある顧問先で
    出荷の口が 1 月支給の時しか渡さず、残業のある人が全員外れた）。`前の確定した勤怠`（前の年の台帳＝1 月支給）で渡った日は重ねない。"""
    前 = _前の支給月の字(月)
    前A, 前B = list(前の表A), list(前の表B)
    有る = {(str(a.get("会社", "")), str(a.get("NO", "")), str(a.get("日付", ""))) for a in [*前A, *前B]}

    def 足す(a) -> bool:
        return (str(a.get("会社", "")) == 会社名 and str(a.get("支給月", "")) == 前
                and (str(a.get("会社", "")), str(a.get("NO", "")), str(a.get("日付", ""))) not in 有る)
    return 前A + [a for a in 表A if 足す(a)], 前B + [b for b in 表B if 足す(b)]


def _タブとつなぎ(タブ: dict, つなぎ=()) -> tuple[dict, list[dict]]:
    """殻が渡すタブ → (段の解決.解く へ渡すタブ, つなぎの行)。事務所の設定のタブに ⑥つなぎ（側＝入口・出口の行）を入れてよい
    （README のとおりタブから読む）。引数の `つなぎ=` の行はタブの行の後ろに足す（どちらで渡しても同じに効く）。"""
    段のタブ, 外 = 段.タブを分ける(タブ)
    return 段のタブ, [*段.行たち(外.get("つなぎ", ())), *段.行たち(つなぎ or ())]


def 入口を読む(原本, 文脈):
    """原本の並びを読み、2 つ目からは 口.重ねる で上に重ねる（読む順は作業のルール「読み方と合わせ方」＝殻が並べる）。

    原本: [{"部品": 読み口の名, "値": 殻が読んだ原本の値, "引数": {部品の残りの引数}}]（値は部品の第 1 引数）。"""
    out = None
    for x in 原本:
        r = _読み口(x["部品"]).読む(x["値"], 文脈=文脈, **(x.get("引数") or {}))
        out = r if out is None else 入口の口.重ねる(out, r)
    return out if out is not None else 入口の口.結果()


def _出口へ(通, 会社名: str, 月: str, 出口: dict | None, タブ: dict | None = None, つなぎ=()) -> dict:
    """取り込み の 欄の対応 を渡さず 道具（⑥つなぎ の給与ソフトの呼び名）を渡せば、口が Drive の値から組む
    （`出口.形.欄の対応を組む`: ④支給控除の項目 の 給与ソフトの欄＋⑥つなぎ の会社の行 側＝出口）。殻が手で対応を組まない。
    給与ソフトへ入れない人は ⑥つなぎ の人の行（側＝出口・道具＝<道具>・その道具での番号＝`渡さない`）から口が組む
    （`出口.形.渡さない人を組む`。欄の対応 を渡しても 道具 を渡せば読む）。殻は返った表から行を消さない。"""
    出口 = 出口 or {}
    out = {}
    if 出口.get("取り込み") is not None:
        取 = {**_前の版の名(出口), "氏名": _氏名(タブ or {}, 会社名), **出口["取り込み"]}
        道具 = 取.pop("道具", None)
        if "渡さない人" in 取:   # 置き場は ⑥つなぎ の人の行 1 か所（殻が手で人を外す道を畳む）
            raise ValueError("出口.取り込み: 渡さない人 は渡さない（⑥つなぎ の人の行 側＝出口・道具＝<給与ソフトの呼び名>・"
                             "その道具での番号＝渡さない に書き、道具 を渡せば口が読む）")
        取["渡さない人"] = 形.渡さない人を組む(会社名, 道具, list(つなぎ or ()))
        if "欄の対応" not in 取:
            if not 道具:
                raise ValueError("出口.取り込み: 欄の対応 か 道具（⑥つなぎ の給与ソフトの呼び名）を渡す")
            取["欄の対応"] = 形.欄の対応を組む(会社名, 道具, 段.行たち((タブ or {}).get("支給控除の項目", ())),
                                       list(つなぎ or ()), 支給月=月)
        out["取り込み"] = 書き口.取り込み(通, 会社名, 月, **取)
    if 出口.get("支給控除一覧") is not None:
        # 氏名はマスタ「社員」が正本＝口が読む（殻が組まない。渡さないと取り込みの氏名の欄・一覧の氏名の行が空で出た）
        out["支給控除一覧"] = 書き口.支給控除一覧(通, 会社名, 月, **{**_前の版の名(出口), "氏名": _氏名(タブ or {}, 会社名),
                                                       **出口["支給控除一覧"]})
    return out


