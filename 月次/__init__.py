"""1 か月（と賞与の 1 回）を回す口。殻が手で組んでいた部品の呼び順を 1 か所にまとめた組み立て役（3 層の外）。

  月を回す(支給月, 会社名, タブ, 原本, …) → 関所を通った・外した人・有給の出す行・台帳へ書く行・問い・知らせ
  賞与を回す(支給月, 会社名, タブ, 支給一覧, 支給日=…, …) → 関所を通った・外した人・問い・知らせ

殻は Drive・シートから読んだ値を渡し、返った物を書くだけ。呼び順と仮の寄せ方は 月次/README.md が正。
仮の人（段の解決・入口の文脈・入口の要確認・芯・有給/ のどれかで仮が 1 つでも残る人）は、
返す 関所を通った・取り込み・支給控除一覧・有給の出す行 のどこにも出ない ⟦鍵:給与計算/足りない時は仮で計算し出さない⟧。

芯・入口・出口・有給/・初期設定 の部品は今のまま呼ぶだけ（中身と額を変えない）。Drive を開かない。
"""
from __future__ import annotations

import importlib
import importlib.util
import sys
from pathlib import Path

根 = Path(__file__).resolve().parent.parent
if str(根) not in sys.path:
    sys.path.insert(0, str(根))


def _読み込む(名: str, path: Path):
    if 名 in sys.modules:
        return sys.modules[名]
    spec = importlib.util.spec_from_file_location(名, path)
    m = importlib.util.module_from_spec(spec)
    sys.modules[名] = m
    spec.loader.exec_module(m)
    return m


繋 = _読み込む("月次_入口の文脈", 根 / "初期設定" / "入口の文脈.py")  # 段の解決 も 繋.段 で引く（同じ物）
段 = 繋.段
有給 = _読み込む("月次_有給", 根 / "有給" / "有給.py")

from 入口 import 口 as 入口の口  # noqa: E402
from 出口 import 関所, 書き口  # noqa: E402
