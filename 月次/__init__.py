def _締まっていない人(支給月: str, 会社名: str, 表A, 締め: dict[str, str], 照らし, 人たち, 月の数字=(),
                勤怠を取らない人=frozenset(), 区分が読めない人=None) -> dict[str, str]:
    """計算する人のうち、その支給月の確定した勤怠（月の数字の口の人は月の数字）が 1 行も無い人・締めの記録で 締まった でない人・
    勤怠の照らしで挙がった人 → {NO: 訳}。月の数字の口の人も同じ照らしを通る（抜け道を作らない）。
    勤怠を取らない人（入口の文脈の `勤怠を取らない人`＝芯/計算/形.py の 勤怠が要るか が偽の人＝区分の字でなく払い方で決める。役員・役員＋委託の併用で委託分が決まった額の人。入口が「勤怠が無いのが正しい」と扱う人と同じ 1 つの表）
    で確定した勤怠も月の数字も無い人は、勤怠が無いのが正しい＝確定した勤怠を求めず、締めの記録に行が無くても待たない（芯/集計 が
    勤怠なしで数える）。勤怠の行がある時・締めの記録に 締まった でない行がある時・勤怠の照らしで挙がった時は、ほかの人と同じに待つ。
    区分が読めない人（入口の文脈の `区分が読めない人`＝`人.区分` が区分の語で読めない人）は勤怠を取る人か決まらない＝勤怠を待たせず、
    区分の字を名指しして止める（勤怠が来ても締まっても同じ。区分を直すまで計算しない）。
    この人たちは芯へ渡さない（計算しない）。1 人でも居れば、その会社のその月は誰も出口へ出さない（月を回す が全員を待たせる）。"""
    月 = 段.月(支給月, "中")
    在る = {str(a.get("NO", "")) for a in 表A if str(a.get("会社", "")) == 会社名 and str(a.get("支給月", "")) == 月}
    在る |= {str(a.get("NO", "")) for a in 月の数字 if str(a.get("会社", "")).strip() in (会社名, "")
            and 段.月(str(a.get("支給月", ""))) == 段.月(支給月)}
    挙がり: dict[str, list[str]] = {}
    for x in 照らし.挙がり:
        if str(x.get("会社", "")) in (会社名, "") and x["種類"] not in 挙がり.setdefault(str(x["NO"]), []):
            挙がり[str(x["NO"])].append(x["種類"])
    out = {}
    取らない = {str(n) for n in 勤怠を取らない人}
    読めない = {str(k): str(v) for k, v in (区分が読めない人 or {}).items()}
    for NO in sorted(人たち):
        勤怠なしでよい = NO not in 在る and NO in 取らない
        if NO in 読めない:
            out[NO] = (f"人.区分「{読めない[NO]}」が区分の語（{'・'.join(計算の形.区分の語)}）で読めない"
                       "＝勤怠を取る人か決まらない（人.区分 を区分の語で書き直すまで計算しない）")
        elif NO not in 在る and not 勤怠なしでよい:
            out[NO] = "その支給月の確定した勤怠も月の数字も無い（締めるまで計算しない）"
        elif 締め.get(NO) != "締まった" and not (勤怠なしでよい and NO not in 締め):
            out[NO] = f"締めの記録が「{締め.get(NO) or '無い'}」（締まった人だけ計算する）"
        elif 挙がり.get(NO):
            out[NO] = f"勤怠の照らしで挙がった（{'・'.join(挙がり[NO])}）＝締まった にできない"
    return out


def 入口の文脈を組む(支給月: str, 会社名: str, タブ: dict, *, 区分の読み替え=None, つなぎ=(), 人の区分の読み替え=None,
              質問と回答=(), 置き場=None):
    """マスタと台帳のタブ（月を回す と同じ渡し方）→ その会社のその支給月の 入口の口.文脈（休日・人の型・社員の表記などを段の解決から
    組む 1 か所）。返す物: (文脈, 入口の文脈の返す物, 段の解決, 段へ渡したタブ)。原本を読む口が呼ぶ
    （文脈を写して組まない＝休日を見当しない）。"""
    タブ = _台帳のタブを段へ(_例を分ける(タブ, None)[0])
    if "質問と回答" in タブ:
        raise ValueError("質問と回答 はタブで渡さない（答えは 月次.答えを確定した勤怠へ の `質問と回答=` だけが読む）")
    タブ, つなぎ = _タブとつなぎ(タブ, つなぎ)
    r = 段.解く(支給月, **タブ)
    x = 繋.入口の文脈(支給月, 会社名, r, 置き場=置き場, 質問と回答=質問と回答, **タブ)
    文脈 = 入口の口.文脈(**x["文脈"], 区分の読み替え=dict(区分の読み替え or {}), つなぎ=list(つなぎ or ()),
                      人の区分の読み替え=dict(人の区分の読み替え or {}))
    return 文脈, x, r, タブ


def _原本を読む(支給月: str, 会社名: str, タブ: dict, 原本, *, 区分の読み替え, つなぎ, 人の区分の読み替え, 質問と回答, 置き場):
    """入口の読み口を原本の並びの順に呼び 重ね、原本が 1 枚も来ない 時間.出勤簿が無い の人（在籍が期間にかかる人）には
    所定どおりの日を足す → (読んだ, 入口の文脈の返す物, 文脈, {NO: 氏名})。質問と回答 を渡せば日の問いの答えを当てて読む。"""
    文脈, x, r, タブ = 入口の文脈を組む(支給月, 会社名, タブ, 区分の読み替え=区分の読み替え, つなぎ=つなぎ,
                               人の区分の読み替え=人の区分の読み替え, 質問と回答=質問と回答, 置き場=置き場)
    読んだ = 入口を読む(原本, 文脈)
    来た = {str(a.get("NO", "")) for a in [*読んだ.日, *読んだ.月の数字, *読んだ.月の変動, *読んだ.人ごとの支給控除]}
    外 = 繋.期間の外の人(会社名, r, x["文脈"]["期間の始め"], x["文脈"]["期間の終わり"], 来た)
    無い人 = [no for no in 文脈.出勤簿が無い if str(no) not in 来た and str(no) not in 外]
    if 無い人:
        読んだ = 入口の口.重ねる(入口の口.所定どおりの日(文脈, 無い人), 読んだ)
    return 読んだ, x, 文脈, _氏名(タブ, 会社名)


