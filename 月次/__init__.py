    読んだ = 読み口.読む(給与ソフトの出力, str(file名), 元["会社"], 元["支給月"], 元["欄の対応"], 元["形"], 元["時間の書き方"])
    結果 = _突.突き合わせる(元["関所を通った"], 読んだ, 元["欄の対応"], 元["渡さなかった人"])
    return {"結果": 結果, "要確認": [*読んだ.要確認, *結果.要確認]}


