        def その月(表):
            return [a for a in 表 if str(a.get("会社", "")) == 会社名 and str(a.get("支給月", "")) == 前]
        A, B = その月(台A), その月(台B)
        締め = _締めの記録を読む(前, 会社名, 締めの台 or ())
        人 = {str(a.get("NO", "")) for a in A if 締め.get(str(a.get("NO", ""))) == "締まった"}
        if not {k for k in フ if k[1] in 人}:
            continue
        元 = その月の元(前)
        if 元 is None:
            continue
