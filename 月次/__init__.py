def _控えた版を照らす(行たち, 会社名: str, 支給月: str, *, 所: str, 名: str, 書き替え: str) -> None:
    """回の始めに控えたパックの版（行の パックの版）が、今のパックの版と同じ時だけ通す（賞与を回す が賞与の支給一覧で呼ぶ＝型の版 34）。
    違う・空（版の分からない回）・行で割れる時は止める。その回をどちらの版で出すかはオーナーが毎回決める（2026-11-19 オーナー）
    ＝ここで決めない・黙って今の版で回さない。行が無い回は照らす版が無いので通す。
    月を回す の締めた時の版はこの照らしを通さない（2026-11-25 に畳んだ＝`_締めた時の版を読む`）。
    所: 版を控える所の名（止めた文に出す）。名: 控えた版の呼び名。書き替え: 今の版で出す時に殻が版を書き替える所。"""
    今の版 = 証明.パックの版()
    行 = list(行たち)
    if not 行:
        return
    版たち = sorted({str(r.get("パックの版", "") or "").strip() for r in 行})
    if 版たち == [今の版] and 今の版:
        return
    if "" in 版たち:
        訳 = f"{所}に{名}が無い行がある（{会社名} {支給月}・版の列が空）"
    elif len(版たち) > 1:
        訳 = f"{所}の{名}が行で割れている（{会社名} {支給月}: {'・'.join(版たち)}）"
    else:
        訳 = f"{名} {版たち[0]} と今のパックの版 {今の版 or '（読めない）'} が違う（{会社名} {支給月}）"
    raise ValueError(訳 + f"。回の途中で版を変えない（{名}でその回を通す）＝この版では回さない。"
                     f"その回をどちらの版で出すかをオーナーに選択肢の画面で聞く（{名}で出す＝殻がその版のパックを置いて回す／"
                     f"今の版で出す＝{書き替え}）")


