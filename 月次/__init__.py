def _立て替えの残りを次の月へ(通, 会社名: str, 支給月: str, 決まり: dict, 入力: dict, 氏名: dict) -> list[list[str]]:
    """関所を通った人の 社保の立て替えの残り → 台帳「その月だけの指示」の次の支給月の行（1 行目が型の見出し）。
    立て替える式の人は残りが 0 でも書く（次の月の「行が無い＝前の月の結果が無い」と分ける）。式の外の人は残りが在る時だけ。
    仮で外した人の行は書かない（次の月はその人の残りが分からない＝仮）。"""
    from 芯.計算 import 支給控除 as 控
    名, 次 = 控.立て替えの残り, 次の支給月(支給月)
    残り: dict[str, Decimal] = {}
    通った人 = set()
    for a in 通.行たち:
        if a.会社 != 会社名:
            continue
        通った人.add(a.NO)
        if a.項目 == 名:
            残り[a.NO] = a.値
    h = 台帳の形.見出し("その月だけの指示")
    out = [list(h)]
    for NO in sorted(通った人, key=lambda n: (0, int(n), n) if n.isdigit() else (1, 0, n)):
        d = 決まり.get((会社名, NO)) or {}
        if NO in 残り:
            x = 残り[NO]
        else:   # 芯が行を置かない月（残りも引けない額も無い）は入力の残りのまま
            x = Decimal(str((入力.get((会社名, NO)) or {}).get(名) or "0"))   # 段の解決が数の字にそろえた値
        if not (_立て替える人か(d) or x):
            continue
        行 = {"会社": 会社名, "支給月": 次, "NO": NO, "氏名": str(氏名.get(NO, "") or ""), "項目": 名,
             "値": 台帳の形.値の字(x), "中身": f"{支給月の字.殻の字へ(支給月)} の確定した結果の残り（月次が書く）", "問いの番号": ""}
        out.append([行.get(c, "") for c in h])
    return out


