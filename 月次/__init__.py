    タブ, つなぎ = _タブとつなぎ(タブ, つなぎ)
    r = 段.解く(支給月, **タブ)
    x = 繋.入口の文脈(支給月, 会社名, r, 置き場=置き場, 質問と回答=質問と回答, **タブ)
