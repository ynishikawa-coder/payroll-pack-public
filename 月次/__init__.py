def _例の問い(例の結果: dict) -> list[dict]:
    """例の止めごとに 1 問。人の外れ（日の場面に当たる人だけの止め）は、同じ字の人を並べて 1 問にする。
    どの問いも、どの例（見出し・決まり の項目）の問いかを 反映先 に持つ＝事務所の答えの行を、その例の 確かめた人 の出所に
    書けば例の確かめの照らし（例の確かめ._行が例を指す）を通る。項目と字は 確かめる が外れごとに欄で返す物を読む（止めの字は割らない）。
    例を指せない止め（例が渡されない・例が 1 つも無い・当たる例が無い・項目の決まらない外れ）は問いにしない（既定で止める＝
    会社か人は 例の仮 で出口へ出ないまま）。"""
    out = []
    for x in 例の結果.get("合わない") or ():
        先 = _項目から反映先(x.get("項目"))
        if 先:
            out.append({"何が無いか": f"決まりの例: {x['字']}", "反映先": 先})
    人の字: dict[str, tuple[dict, list[str]]] = {}
    for NO, 外れたち in sorted((例の結果.get("人の外れ") or {}).items()):
        for x in 外れたち:
            人の字.setdefault(x["字"], (x, []))[1].append(NO)
    for t, (x, 人) in 人の字.items():
        先 = _項目から反映先(x.get("項目"))
        if 先:
            out.append({"何が無いか": f"決まりの例: {t}", "反映先": 先, "人": 人})
    return out


