def _その月の元を作る(会社名: str, タブ: dict, 置き場, 知らせ: list):
    """前の支給月（YYYY-MM）→ (その月の決まり, その月の法の線)。決まりはマスタの変更の記録をその支給月で段の解決にかけ直し、
    法の線はその月の給与の期間で法の表から引く（`_フレックスの前の月` が前の月を数え直す元）。
    その月の段の解決に仮が残る人は決まりから外す。その月の決まりが解けない（段の誤り）・期間が見当（締め日・支給の月が揃わない）・
    法の線が引けない（法の表の欠け・誤り）月は None＝渡さない（後の月が仮）。その訳は `知らせ` へ足す（事務所が何が揃わないかを見る）。
    それ以外の例外（道具の誤り）は受けずにそのまま上げる（黙って「渡さない」にしない）。"""
    from 芯.集計.法の線の橋 import 法の線を引く
    from 芯.計算.引く口 import 欠け, 表の誤り

    def 元(前: str):
        def 渡さない(訳: str):
            知らせ.append(f"{会社名} {前}: フレックスの清算期間の前の月を数え直さない（{訳}）＝清算の終わりの月が仮")
            return None
        try:
            r = 段.解く(段.月(前, "殻"), **タブ)
        except 段.段の誤り as e:
            return 渡さない(f"その月の決まりが解けない: {e}")
        仮の人 = {str(q.get("NO", "")) for q in r.get("仮の値", ()) if str(q.get("会社", 会社名)) == 会社名}
        決 = {k: v for k, v in _その会社(r["決まり"], 会社名).items() if str(k[1]) not in 仮の人}
        期間の知らせ: list = []
        始め, 終わり, _, 外れた = 繋.給与の期間(段.月(前, "中"), 会社名, r, 期間の知らせ)
        if 外れた or 期間の知らせ:
            return 渡さない("その月の給与の期間が見当: " + "・".join(map(str, 期間の知らせ)))
        try:
            線 = 法の線を引く(始め, 終わり, 置き場=置き場)
        except (欠け, 表の誤り) as e:
            return 渡さない(f"その月の法の線が引けない: {e}")
        return 決, 線
    return 元


def _タブとつなぎ(タブ: dict, つなぎ=()) -> tuple[dict, list[dict]]:
    """殻が渡すタブ → (段の解決.解く へ渡すタブ, つなぎの行)。事務所の設定のタブに ⑥つなぎ（側＝入口・出口の行）を入れてよい
    （README のとおりタブから読む）。引数の `つなぎ=` の行はタブの行の後ろに足す（どちらで渡しても同じに効く）。"""
    段のタブ, 外 = 段.タブを分ける(タブ)
    return 段のタブ, [*段.行たち(外.get("つなぎ", ())), *段.行たち(つなぎ or ())]


def 入口を読む(原本, 文脈):
    """原本の並びを読み、2 つ目からは 口.重ねる で上に重ねる（読む順は作業のルール「読み方と合わせ方」＝殻が並べる）。

    原本: [{"部品": 読み口の名, "値": 殻が読んだ原本の値, "引数": {部品の残りの引数}}]（値は部品の第 1 引数）。"""
    out = None
    for x in 原本:
        r = _読み口(x["部品"]).読む(x["値"], 文脈=文脈, **(x.get("引数") or {}))
        out = r if out is None else 入口の口.重ねる(out, r)
    return out if out is not None else 入口の口.結果()


