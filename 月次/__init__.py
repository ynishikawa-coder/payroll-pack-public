# 入口の読み口（原本の一般の形で選ぶ・入口/README.md §2）。名の外の部品は呼ばない。製品の名で選ばない
# （勤怠ツールの日次の CSV は 日次の勤怠CSV に 引数 {"道具": ⑥つなぎ の呼び名} を殻が渡す）
読み口の名 = ("Excel出勤簿", "PDFタイムカード", "勤怠システムの月報", "集計済み勤怠表", "メールとメモ", "手当控除の一覧",
          "日次の勤怠CSV")


def _読み口(名: str):
    if 名 not in 読み口の名:
        raise ValueError(f"入口の読み口「{名}」は無い（{'・'.join(読み口の名)}）")
    return importlib.import_module(f"入口.{名}")


def _その会社(d: dict, 会社名: str) -> dict:
    return {k: v for k, v in (d or {}).items() if str(k[0]) == 会社名}


def _入口の仮の値(読んだ, 会社名: str) -> list[dict]:
    """入口の 人の状態() が 仮 の人（要確認が残る・NO が引けない）を 仮の値 の形に（関所へ寄せる。問いは入口の 要確認 のまま）。"""
    理由 = {}
    for q in 読んだ.要確認:
        理由.setdefault(str(q.get("NO", "")), []).append(str(q.get("理由", "")))
    return [{"会社": 会社名, "NO": str(NO), "項目": "入口.要確認", "値": "",
             "拠り所": "・".join(理由.get(str(NO), ["読み取りの確かめ＝要確認"])), "問い": ""}
            for NO, 状態 in sorted(読んだ.人の状態().items()) if 状態 != "確定"]


def _月の変動を足す(タブの行, 読んだ行) -> list[dict]:
    """段の解決へ渡す 月の変動: 台帳の行（タブ）に、入口が今の原本から読んだ行を足す。同じ原本の同じ人×項目は読んだ行が勝つ
    （殻が前の回に書いた行を読み直した物）。読んだ行の 要確認 は渡さない（その人は入口の 要確認 で仮＝問いを 2 つにしない）。"""
    def 鍵(r):
        return tuple(str(r.get(c, "") or "").strip() for c in ("会社", "NO", "項目", "原本の名前"))
    読んだ = list(読んだ行 or ())
    読んだ鍵 = {鍵(r) for r in 読んだ}
    return [*(r for r in 段.行たち(タブの行) if 鍵(r) not in 読んだ鍵),
            *(r for r in 読んだ if str(r.get("確認", "") or "").strip() != 入口の口.要確認)]


def 入口を読む(原本, 文脈):
    """原本の並びを読み、2 つ目からは 口.重ねる で上に重ねる（読む順は作業のルール「読み方と合わせ方」＝殻が並べる）。

    原本: [{"部品": 読み口の名, "値": 殻が読んだ原本の値, "引数": {部品の残りの引数}}]（値は部品の第 1 引数）。"""
    out = None
    for x in 原本:
        r = _読み口(x["部品"]).読む(x["値"], 文脈=文脈, **(x.get("引数") or {}))
        out = r if out is None else 入口の口.重ねる(out, r)
    return out if out is not None else 入口の口.結果()


def _出口へ(通, 会社名: str, 月: str, 出口: dict | None) -> dict:
    出口 = 出口 or {}
    out = {}
    if 出口.get("取り込み") is not None:
        out["取り込み"] = 書き口.取り込み(通, 会社名, 月, **出口["取り込み"])
    if 出口.get("支給控除一覧") is not None:
        out["支給控除一覧"] = 書き口.支給控除一覧(通, 会社名, 月, **出口["支給控除一覧"])
    return out


def 月を回す(支給月: str, 会社名: str, タブ: dict, 原本=(), *, 区分の読み替え: dict | None = None, つなぎ=(),
          前の表A=(), 前の表B=(), 法の線: dict | None = None, 有給の値: dict | None = None,
          出口: dict | None = None, 置き場=None) -> dict:
    """1 会社の 1 支給月を回す。呼び順は 月次/README.md「月を回す」。

    支給月: `YYYY.MM支給`（段の解決・有給/ の書き方。入口・芯・出口へは `YYYY-MM` に直して渡す）。
    タブ: 段の解決.解く に渡すタブ（会社・勤務の型・社員・人ごとの支給控除・支給控除の項目・事務所・変更の記録・月の変動・人ごと）。
    原本: 入口を読む の並び。区分の読み替え・つなぎ: 入口の文脈 に足す殻の値（Drive の作業のルール・マスタ⑥つなぎ）。
    前の表A・前の表B: 期間の頭の週が前の期間にかかる時の台帳の前の期間の行。法の線: 無ければ 法の表/ から期間で引く。
    有給の値: None なら有給を回さない。{"勤怠の始め", "出勤率が足りない付与日"} で回す。
    出口: {"取り込み": 書き口.取り込み の残りの引数, "支給控除一覧": 書き口.支給控除一覧 の残りの引数}（欄の対応・形 など）。
      取り込み の 形 は殻が事務所の設定から読んだ値（dict）か 出口.形.形を組む の結果。dict なら書き口が 形を組む を通す（無ければ止まる）。
    """
    r = 段.解く(支給月, **タブ)
    x = 繋.入口の文脈(支給月, 会社名, r, 置き場=置き場, **タブ)
    月 = x["文脈"]["支給月"]
    文脈 = 入口の口.文脈(**x["文脈"], 区分の読み替え=dict(区分の読み替え or {}), つなぎ=list(つなぎ or ()))
    読んだ = 入口を読む(原本, 文脈)
    入口の仮 = _入口の仮の値(読んだ, 会社名)
    if 読んだ.月の変動:   # 今の原本の手当・控除（月の変動）も同じ回の 入力 へ（段の解決の月の変動の読みは 1 つ＝解き直す）
        タブ = {**タブ, "月の変動": _月の変動を足す(タブ.get("月の変動", ()), 読んだ.月の変動)}
        r = 段.解く(支給月, **タブ)

    決まり, 人 = _その会社(r["決まり"], 会社名), _その会社(r["人"], 会社名)
    if 法の線 is None:
        from 芯.集計.法の線の橋 import 法の線を引く
        法の線 = 法の線を引く(x["文脈"]["期間の始め"], x["文脈"]["期間の終わり"], 置き場=置き場)
    集 = 集計する(読んだ.日, 読んだ.区間, 決まり=決まり, 法の線=法の線, 月の口=読んだ.月の数字,
              前の表A=前の表A, 前の表B=前の表B, 支給月=月)
    計 = 計算する(集, 決まり=決まり, 人=人, 入力=_その会社(繋.計算の入力(r["入力"], 集), 会社名), 置き場=置き場)

    段の仮 = [q for q in r["仮の値"] if str(q.get("会社", "")) == 会社名]
    渡す, 出さない = 関所.勤怠の行を分ける(集["行"])  # 勤怠の欄（出勤日数・残業時間など）も同じ関所を通す
    z = 繋.給与の関所へ({"行": [*計["行"], *渡す], "人の状態": 計["人の状態"]}, 段の仮, [*x["仮の値"], *入口の仮])
    通 = 関所.通す(z["行"], z["人の状態"])

    out = {
        "支給月": 月, "会社": 会社名,
        "関所を通った": 通,
        "外した人": [a.行() for a in 通.外した人たち],
        **_出口へ(通, 会社名, 月, 出口),
        # 台帳へ書く行（出口へは出さない）: 入口の表 A・B・月の数字・月の変動・人ごとの支給控除、集計の月の数字（台帳「人ごと」）
        "台帳": {"勤怠": 読んだ.日, "勤怠の区間": 読んだ.区間, "月の数字の口": 読んだ.月の数字, "月の変動": 読んだ.月の変動,
               "人ごとの支給控除": 読んだ.人ごとの支給控除, "人ごと": 集["行"], "人ごとの状態": 集["人"]},
        "出口へ出さない勤怠の行": 出さない,
        "問い": {"段の解決": 段の仮, "入口の文脈": x["仮の値"], "入口": 読んだ.要確認, "集計": 集["問い"], "計算": 計["問い"]},
        "知らせ": {"段の解決": r["知らせ"], "入口の文脈": x["知らせ"], "集計": 集["知らせ"], "計算": 計.get("知らせ", [])},
    }

    if 有給の値 is not None:
        y = 繋.有給の入力(支給月, 会社名, r, 読んだ.日, 社員=タブ.get("社員", ()), **有給の値)
        表 = 有給.管理表(y["入力"], 置き場=置き場)  # 付与日数は 法の表/有給_付与日数
        # 段の解決・入口の文脈・入口の仮も有給の関所へ寄せる（年休の読みと人の値がその仮に乗る）
        zz = 繋.有給の関所へ(y, 表, [*段の仮, *x["仮の値"], *入口の仮])
        通有 = 関所.通す(zz["行"], zz["人の状態"])
        out["有給の出す行"] = 繋.有給の出す行(表, 通有)
        out["有給の外した人"] = [a.行() for a in 通有.外した人たち]
        out["有給の見出し"] = 表.get("見出し")
        out["問い"]["有給"] = [*y["仮の値"], *表.get("問い", ())]
        out["知らせ"]["有給"] = y["知らせ"]
    return out


def 賞与を回す(支給月: str, 会社名: str, タブ: dict, 支給一覧, *, 支給日: str, 出口: dict | None = None,
          置き場=None, **賞与の引数) -> dict:
    """1 会社の 1 回の賞与を回す。呼び順は 月次/README.md「賞与を回す」。

    支給月: 段の解決が読む `YYYY.MM支給`（賞与を払う月）。支給一覧: 賞与を計算する の第 1 引数（人に結んだ後の行）。
    賞与の引数: 前月の課税対象額・前の標準賞与額 など 賞与を計算する の残りの引数（そのまま渡す）。
    段の解決の仮の人（変更の記録の 確かめ＝仮 など）は芯が確認済で返しても関所で外す。"""
    r = 段.解く(支給月, **タブ)
    計 = 賞与を計算する(支給一覧, 支給日=支給日, 決まり=_その会社(r["決まり"], 会社名), 人=_その会社(r["人"], 会社名),
                 置き場=置き場, **賞与の引数)
    段の仮 = [q for q in r["仮の値"] if str(q.get("会社", "")) == 会社名]
    z = 繋.給与の関所へ(計, 段の仮)
    通 = 関所.通す(z["行"], z["人の状態"])
    月 = sorted({a["支給月"] for a in 計["行"]} or {f"{段.月(支給月).replace('.', '-')}-賞与"})[0]
    return {
        "支給月": 月, "会社": 会社名,
        "関所を通った": 通,
        "外した人": [a.行() for a in 通.外した人たち],
        **_出口へ(通, 会社名, 月, 出口),
        "問い": {"段の解決": 段の仮, "計算": 計["問い"]},
        "知らせ": {"段の解決": r["知らせ"], "計算": 計.get("知らせ", [])},
    }
