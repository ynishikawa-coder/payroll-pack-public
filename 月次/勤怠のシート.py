"""確定した勤怠のシート（事務所の担当者へ毎月渡す・人ごとの月の合計と、どう確定させたか）を作る口。Drive を開かない。

置き場（正本は docs/設計/Drive の型.md §2・§4）: その月の置き場の `2_出す物/` に `確定した勤怠_<会社>_<支給月>_v<n>`
（名と版は 出口/名と版.py の `渡す名を付ける`＝出す物と同じ付け方・前の版は会社の根の `9_履歴/` へ）。出荷の口の出す物とは
混ぜない（出す命令〔出口/出す.py〕が書く物に入れない＝確定した勤怠のシートは給与ソフトへ入れる物でなく、担当者が確かめる物）。

中身は 月次/勤怠の照らし.py の `担当者へ渡す表` の 2 つの表（人ごと・直した所）＝シートの 2 つのタブ。表の行を作るのは
その 1 か所（ここで数えない・列を組まない）。殻は返った `書く手順` を〔口: 書く手順を当てる〕で順に当てるだけ。

  作る(会社, 支給月, 今の台帳=…, 今ある名=…, 履歴にある名=…)
    今の台帳: {タブ: get_values}。読んだままの勤怠・その区間・確定した勤怠・その区間・人ごとの月の数字 の 5 つ（〔口: シートを読む〕で
      読んだまま。見出しが型と違えば止める）。その会社×支給月の行だけを使う（ほかの行は読まない）。
    今ある名: その月の置き場の 2_出す物/ の名の並び・履歴にある名: 会社の根の 9_履歴/ の名の並び（どちらも必ず渡す・無ければ []）。
    返す物: {名, 書く手順, 書いた後, 履歴へ移す}
      書く手順: [{する: スプレッドシートを作る, 根: 2_出す物, 名, タブ: 人ごと}, {する: タブを足す, ファイル: 名, タブ: 直した所},
                 {する: 値を書く, ファイル: 名, タブ, 範囲, 値, 書き方: RAW} ×2]
      書いた後: {タブ: 値}
      履歴へ移す: 2_出す物/ から 9_履歴/ へ移す前の版の名（新しい版を置けてから移す）

止める（既定で止める）: 今の台帳のタブが欠ける・見出しが型と違う・その会社×支給月の確定した勤怠が 1 行も無い・
支給月が YYYY.MM支給 でない・今ある名／履歴にある名を渡さない。
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

_根 = Path(__file__).resolve().parent.parent
if str(_根) not in sys.path:
    sys.path.insert(0, str(_根))


def _読む(名: str, 場所: Path):
    if 名 not in sys.modules:
        spec = importlib.util.spec_from_file_location(名, 場所)
        m = importlib.util.module_from_spec(spec)
        sys.modules[名] = m
        spec.loader.exec_module(m)
    return sys.modules[名]


形 = _読む("月次_台帳の形", _根 / "月次" / "台帳の形.py")
書く = _読む("月次_台帳へ書く", _根 / "月次" / "台帳へ書く.py")
照らし = _読む("月次_勤怠の照らし", _根 / "月次" / "勤怠の照らし.py")
from 芯 import 支給月の字  # noqa: E402
from 出口 import 名と版  # noqa: E402
from 芯.字 import 列の字  # noqa: E402

物 = "確定した勤怠"
読むタブ = ("読んだままの勤怠", "読んだままの勤怠の区間", "確定した勤怠", "確定した勤怠の区間", "人ごとの月の数字")
シートのタブ = ("人ごと", "直した所")   # 勤怠の照らし.担当者へ渡す表 の返す 2 つの表の名（シートのタブの名もこのまま）


class 勤怠のシートの誤り(ValueError):
    """確定した勤怠のシートを作らない（台帳が欠ける・形が違う・その月の確定した勤怠が無い）。"""


def _その月(表, タブ: str, 会社: str, 月: tuple) -> list[dict]:
    書く.今の見出しを照らす(タブ, 表)   # 見出しが型と違えば止める（読み違えた列で表を作らない）
    return [r for r in 形.行たち(表)
            if 形.値の字(r.get("会社")).strip() == 会社 and 支給月の字.読む(r.get("支給月")) == 月]


def _格子(行たち: list[dict]) -> list[list[str]]:
    """dict の行 → 1 行目が見出しの格子（見出しは行に出た順・人ごと は数え方で列が変わる）。"""
    h: list[str] = []
    for r in 行たち:
        h += [k for k in r if k not in h]
    return [h, *[["" if r.get(c) is None else str(r.get(c)) for c in h] for r in 行たち]]


def 作る(会社: str, 支給月: str, *, 今の台帳: dict, 今ある名, 履歴にある名) -> dict:
    会社 = str(会社 or "").strip()
    if not 会社:
        raise 勤怠のシートの誤り("会社（会社の呼び名）を渡す")
    if not 支給月の字.その形か(str(支給月 or ""), "殻"):
        raise 勤怠のシートの誤り(f"支給月「{支給月}」は YYYY.MM支給 の字で渡す")
    月 = 支給月の字.読む(支給月)
    if not isinstance(今の台帳, dict):
        raise 勤怠のシートの誤り("今の台帳は {タブの名: get_values の値} で渡す")
    欠け = [k for k in 読むタブ if k not in 今の台帳]
    if 欠け:
        raise 勤怠のシートの誤り(f"今の台帳にタブ {欠け} が無い（{'・'.join(読むタブ)} を get_values で全部渡す）")
    try:
        t = {k: _その月(今の台帳[k], k, 会社, 月) for k in 読むタブ}
    except 書く.台帳へ書く誤り as e:
        raise 勤怠のシートの誤り(str(e)) from e
    if not t["確定した勤怠"]:
        raise 勤怠のシートの誤り(f"確定した勤怠に {会社} の {支給月} の行が無い（勤怠を締めてから作る）")
    表 = 照らし.担当者へ渡す表(t["確定した勤怠"], t["確定した勤怠の区間"], t["読んだままの勤怠"], t["読んだままの勤怠の区間"],
                       人ごとの月の数字=t["人ごとの月の数字"] or None)
    if list(表) != list(シートのタブ):
        raise 勤怠のシートの誤り(f"担当者へ渡す表のタブ {list(表)} が {list(シートのタブ)} と違う")
    try:
        n = 名と版.渡す名を付ける(物, 会社, 名と版.出す支給月(支給月, "月"), 今ある名, 履歴にある名)
    except ValueError as e:
        raise 勤怠のシートの誤り(str(e)) from e
    手順 = [{"する": "スプレッドシートを作る", "根": n.フォルダ, "名": n.名, "タブ": シートのタブ[0]},
           *[{"する": "タブを足す", "ファイル": n.名, "タブ": k} for k in シートのタブ[1:]]]
    後 = {}
    for k in シートのタブ:
        g = _格子(表[k]) if 表[k] else [[]]
        if not 表[k]:
            g = [["（直した所は無い）"]] if k == "直した所" else g
        後[k] = g
        幅 = max(len(r) for r in g) or 1
        手順.append({"する": "値を書く", "ファイル": n.名, "タブ": k, "範囲": f"A1:{列の字(幅)}{len(g)}", "値": g,
                   "書き方": 書く.字のまま})
    return {"名": n.名, "書く手順": 手順, "書いた後": 後, "履歴へ移す": list(n.履歴へ移す)}
