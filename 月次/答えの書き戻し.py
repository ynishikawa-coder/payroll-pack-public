def _会社の行を移す先(g, h, 鍵の列: str, 顧客ID: str, 何を: str, v: str, 月: str) -> tuple[int, str] | None:
    """マスタ/会社 で、値 v の行の 適用開始 だけを 月 へ直してよい行 → (行番号, 前の月 YYYY-MM)。直さない（行を足す）時は None。
    直してよいのは、この顧客ID・項目の行のうち 今の値＝v で 適用開始 が読めて 月 と違い、その間（前の月と 月 の間）に
    同じ項目のほかの行が無い行がちょうど 1 つで、かつ 前の月が 月 より後か、前の月より前に同じ項目の行が在る（値の変わり目が在る）時。
    前の月より前に行が無く 前の月 が 月 より前なら、v は前から効いている＝直すと前の月〜月の間が既定に戻る＝直さない。"""
    行たち = [(i, x, 月の字(x[h.index("適用開始")])) for i, x in enumerate(g[1:], 2)
              if x[h.index(鍵の列)] == 顧客ID and x[h.index("項目")] == 何を]
    候補 = [(i, m) for i, x, m in 行たち if x[h.index("今の値")] == v and m and m != 月
            and not any(n and min(m, 月) < n < max(m, 月) for _, _, n in 行たち)]
    if len(候補) != 1:
        return None
    i, m = 候補[0]
    前に在る = any(n and n < m for _, _, n in 行たち)
    return (i, m) if m > 月 or 前に在る else None


def _人の記録の効く月を直す先(記録, 鍵の列: str, 人の列: str, 顧客ID: str, 対象: str, 何を: str, v: str,
                    月: str) -> tuple[int, str] | None:
    """変更の記録で、この人・項目の一番新しい記録（効く月の直しの記録を除く）が v への記録で 適用支給月 が 月 と違い、
    その間に同じ項目のほかの記録が無い → (行番号, 前の月 YYYY-MM)。直す物が無い（記録が無い・別の値への記録・同じ月）時は None。
    間にほかの記録が在る時は ValueError（効く月だけの直しで決まらない＝人が反映する）。"""
    h = 記録[0]
    if not {"適用支給月", "項目", "新しい値"} <= set(h) or 鍵の列 not in h or 人の列 not in h:
        return None
    行たち = [(i, x) for i, x in enumerate(記録[1:], 2) if x[h.index(鍵の列)] == 顧客ID and x[h.index(人の列)] == 対象
              and x[h.index("項目")] == 何を]   # 効く月の直しの記録は 項目 の頭が違う＝ここに入らない
    if not 行たち:
        return None
    i, x = 行たち[-1]
    m = 月の字(x[h.index("適用支給月")])
