def _読み込む(名: str, path: Path):
    if 名 in sys.modules:
        return sys.modules[名]
    spec = importlib.util.spec_from_file_location(名, path)
    m = importlib.util.module_from_spec(spec)
    sys.modules[名] = m
    spec.loader.exec_module(m)
    return m


