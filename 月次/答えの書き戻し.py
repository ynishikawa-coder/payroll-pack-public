class 書き戻しの誤り(ValueError):
    pass


def _字(v) -> str:
    return "" if v is None else str(v).strip()


def _格子(表, 何: str) -> list[list[str]]:
    """get_values の形（1 行目が見出し）だけを受ける＝書く行の位置が決まる。"""
    if not isinstance(表, (list, tuple)) or not 表 or not isinstance(表[0], (list, tuple)):
        raise 書き戻しの誤り(f"{何} は get_values の形（1 行目が見出しの格子）で渡す")
    h = [_字(c) for c in 表[0]]
    return [h, *[[_字(r[i]) if i < len(r) else "" for i in range(len(h))] for r in 表[1:]]]


def 受付番号(回答) -> str:
    """回答 の字（貼り戻しの形 `… ／ 受付: R<YYMMDD>-<英数 4 字>（版 …）`）→ 受付番号（無ければ ''）。"""
    m = 受付の形.findall(str(回答 or ""))
    return m[-1] if m else ""


def 手順を当てる(今: dict, 手順) -> dict:
    """手順を値の上で当てた後（{(ファイル, タブ): 格子, ("md", 名): 本文}）。殻が当てるのと同じ順。"""
    t = copy.deepcopy(今)
    for x in 手順:
        if x["する"] == "md を書き換える":
            t[("md", x["先"])] = x["本文"]
            continue
        g = t.setdefault((x["ファイル"], x["タブ"]), [])
        if x["する"] == "値を書く":
            m = re.fullmatch(r"A(\d+):[A-Z]+(\d+)", x["範囲"])
            a = int(m.group(1))
            for i, r in enumerate(x["値"]):
                while len(g) < a + i:
                    g.append([])
                g[a + i - 1] = list(r)
        elif x["する"] == "行を足す":
            g.extend(list(r) for r in x["値"])
        elif x["する"] == "行を消す":
            del g[x["行"] - 1]
        else:
            raise 書き戻しの誤り(f"知らない手順 {x['する']!r}")
    return t


def _値を書く(ファイル, タブ, 行番号: int, 行: list) -> dict:
    return {"する": "値を書く", "ファイル": ファイル, "タブ": タブ, "範囲": f"A{行番号}:{列の字(len(行))}{行番号}",
            "値": [list(行)], "書き方": 口.字のまま}


def _行を足す(ファイル, タブ, 行: list) -> dict:
    return {"する": "行を足す", "ファイル": ファイル, "タブ": タブ, "値": [list(行)], "書き方": 口.字のまま}


def _値(q: dict, 回答: str, 名: str | None) -> tuple[str, str]:
    """(書く値, 止める訳)。見当のとおり は 見当。名が在れば、芯が決めているその項目の形で読めた値だけ書く
    （形の正本は 芯/設定.py の 形で読めない訳 の 1 か所。形を決めていない項目・形で読めない文は 人が反映する で止める）。"""
    v = _字(q.get("見当")) if 回答 == "見当のとおり" else 回答
    if not v:
        return "", "書く値が決まらない（見当のとおり なのに見当が空）"
    if 名:
        try:
            口.項目(名)
        except (KeyError, ValueError):
            return "", f"{名} は型の項目に無い（知らない項目は書かない）"
        if 訳 := 芯の設定.形で読めない訳(名, v):
            return "", f"{_人が反映する}（{名} の答え「{v}」: {訳}）"
    return v, ""


_人が反映する = "人が反映する"


def _その月の値の訳(項目: str, v: str) -> str:
    """その月だけの指示へ書く値の止める訳（"" は書いてよい）。読む側の正本は 段の解決.月の変動の入力（変動の数）で、
    数の形で読めない値・字のまま読む欄（変動の欄の項目）は書かない。"""
    if 項目 in 段の解決.変動の欄の項目:
        return f"{_人が反映する}（{項目} は字のまま読む欄＝数の形で照らせない）"
    if 段の解決.変動の数(v) is None:
        return f"{_人が反映する}（{項目} の答え「{v}」は数の形で読めない）"
    return ""


def _md_の行の訳(v: str) -> str:
    """md へ足す 1 行の止める訳（"" は書いてよい）。md を読む芯の側は 例の確かめ.MDから例を読む（`###` の下の表）と
    勤怠の照らし.MDの見出したち（見出し）だけで、`- ` で始まる 1 行はどちらにも読まれない。改行・HTML の注の印は
    見出し・表・注を作れる（例の表を読み替える）ので書かない。"""
    if "\n" in v or "\r" in v or "<!--" in v or "-->" in v:
        return f"{_人が反映する}（答えに改行か HTML の注の印がある＝md の見出し・表に読まれうる）"
    return ""


def _誰(q: dict) -> list[str]:
    return [w for w in (x.strip() for x in re.split(r"[、,]", str(q.get("答えで変わる項目と人") or ""))) if w]


def _NOたち(q: dict) -> set[str]:
    """答えで変わる項目と人 の NO（数字の語）。"""
    return {w for w in _誰(q) if w.isdigit()}


def 書き戻しの手順(質問の行たち, 会社: str, 支給月: str, *, 今日: str, マスタ: dict | None = None, md: dict | None = None,
               台帳: dict | None = None, 台帳の名: str = "", 確定した勤怠の返り: dict | None = None,
               原本のリンク: dict | None = None) -> dict:
    """答えのある問いを反映先へ書き戻す手順（上の決め方）。

    質問の行たち: 質問と回答「質問」の get_values。マスタ: {タブ: get_values}（会社・社員・勤務の型・変更の記録 のうち要る物）。
    md: {名: 本文}。台帳: 年の台帳 {タブ: get_values}（その月だけの指示・確定した勤怠・確定した勤怠の区間）。台帳の名: `台帳_<年>`。
    確定した勤怠の返り: 月次.答えを確定した勤怠へ の返り（{確定した勤怠, 確定した勤怠の区間}）。原本のリンク: 台帳へ書く.勤怠 へ。
    今日: 変更の記録の 記録日（YYYY-MM-DD）。"""
    問の格子 = _格子(質問の行たち, f"{_質問と回答}/{_問いのタブ}")
    訳 = 設問.質問の表の訳(問の格子)
    if 訳:
        return {"手順": [], "記録": [], "開いたまま": [], "開いたままの訳": [], "止める": [{"問いの番号": "", "反映先": "", "訳": 訳}], "問い": [],
                "赤": [f"質問と回答が読めない（{訳}）"]}
    マスタ = {k: _格子(v, f"{_マスタ}/{k}") for k, v in (マスタ or {}).items()}
    台帳 = {k: _格子(v, f"{台帳の名}/{k}") for k, v in (台帳 or {}).items()}
    md = dict(md or {})
    今 = {**{(_マスタ, k): v for k, v in マスタ.items()}, **{(台帳の名, k): v for k, v in 台帳.items()},
         (_質問と回答, _問いのタブ): 問の格子, **{("md", k): v for k, v in md.items()}}

    手順, 記録, 開いた, 開いた訳, 止める = [], [], [], [], []
    書いた番号: dict[str, list[str]] = {}   # 番号 → 書いた（か既に在った）先
    確定の番号 = []
    その月の行 = []
    行たち = 口.格子を行へ(問の格子)
    答えた = []
    for q in 口.今の問いの行たち(行たち):
        回答 = 口.答えの芯(q)
        番号 = _字(q.get("問いの番号"))
        if not 回答 or 設問.閉じた答え(回答) or _字(q.get("会社")) not in ("", 会社):
            continue
        if 設問.前の答え.決まり切らない(q):   # 行ごと渡す（選択肢を読む・受付の印は回答の字から読む）
            if 設問.反映した行か(q):   # 反映済み が 済＝閉じた問い（答えの字を読み直さない・開いたままに数えない）
                continue
            開いた.append(番号)
            if 訳 := 設問.前の答え.止まった訳(q):
                開いた訳.append({"問いの番号": 番号, "訳": 訳})
            continue
        答えた.append(q)
    食い違い = 設問.前の答えとの食い違い(答えた)
    食い違う番号 = {x["問いの番号"] for x in 食い違い}

    def 止(番号, 先, 訳):
        止める.append({"問いの番号": 番号, "反映先": 先, "訳": 訳})

    def 記(q, 先, する):
        記録.append({"受付番号": 受付番号(q.get("回答")), "問いの番号": _字(q.get("問いの番号")), "反映先": 先, "する": する})

    def 今の格子(ファイル, タブ):
        return 今.get((ファイル, タブ))

    def 足す手順(x: dict):
        """手順を足し、後の手順が書いた後の値の上で決まるよう 今 にも当てる。"""
        手順.append(x)
        今.update(手順を当てる(今, [x]))

    for q in 答えた:
        番号 = _字(q.get("問いの番号"))
        if 番号 in 食い違う番号:
            continue
        if 設問.反映した行か(q):   # 反映済み が 済＝閉じた問い（食い違いの照らしには前の答えとして残し、どの先へも書き直さない）
            continue
        回答 = 口.答えの芯(q)
        片たち = 口.反映先を読む(q.get("反映先"))
        if not 片たち:
            止(番号, "", "答えがあるのに反映先が空＝どこへ書くか決まらない")
            continue
        for 片 in 片たち:
            先 = 片.字
            if 先 == 設問.確定した勤怠の先:
                if 回答 == "原本を送る":
                    止(番号, 先, "直した原本を待つ（読んだままの勤怠を作り直してから確定した勤怠へ書く）")
                    continue
                確定の番号.append((q, 先))
                continue
            if 先 == 設問.その月だけの指示の先:
                名たち = [w for w in _誰(q) if not w.isdigit()]
                NOたち = sorted(_NOたち(q))
                項目 = 名たち[0] if len(名たち) == 1 else ""
                if not 項目 or not NOたち:
                    止(番号, 先, "答えで変わる項目と人 に 項目 1 つと NO が要る（その月だけの指示の 1 行が決まらない）")
                    continue
                # 項目は支給控除の名・その月だけの語（型の項目に限らない）。値は 段の解決.月の変動の入力 が読む数の形だけ書く
                v, 訳 = _値(q, 回答, None)
                if not 訳:
                    訳 = _その月の値の訳(項目, v)
                if 訳:
                    止(番号, 先, 訳)
                    continue
                for n in NOたち:
                    その月の行.append(({"会社": 会社, "支給月": 支給月, "NO": n, "氏名": "", "項目": 項目, "値": v,
                                     "中身": _字(q.get("質問")), "問いの番号": 番号}, q))
                continue
            if 先.startswith("台帳/"):
                止(番号, 先, f"年の台帳の答えの先は {'・'.join(設問.台帳の先たち)} だけ")
                continue
            if 先 == 設問.原本の先:
                止(番号, 先, "直した原本を月のフォルダの 1_届いた物 に置いて回し直す（原本は書き換えない）")
                continue
            if 片.種 == "md":
                名, 見出し = 片.甲, 片.乙
                if 名 not in md:
                    止(番号, 先, f"{名} の本文を md で渡されていない")
                    continue
                本文 = 今[("md", 名)]
                if 見出し and _見出しの位置(本文, 見出し) is None:
                    止(番号, 先, f"{名} に 見出し「{見出し}」が無い（節を足すのは人が決める）")
                    continue
                節 = 設問.md_の節(本文, 見出し) if 見出し else 本文
                if 番号 in 節:
                    書いた番号.setdefault(番号, []).append(先)
                    continue
                v = 回答 if 回答 != '見当のとおり' else _字(q.get('見当'))
                if 訳 := _md_の行の訳(v):
                    止(番号, 先, 訳)
                    continue
                行 = f"- {v}（出所: 問い:{番号}" + \
                    (f"・受付 {受付番号(q.get('回答'))}" if 受付番号(q.get("回答")) else "") + "）"
                足す手順({"する": "md を書き換える", "先": 名, "本文": _md_へ足す(本文, 見出し, 行)})
                記(q, 先, "md を書き換える")
                書いた番号.setdefault(番号, []).append(先)
                continue
            if 片.種 == "知らないタブ":
                止(番号, 先, f"{_マスタ} のタブは {'・'.join(口.マスタのタブたち())} だけ")
                continue
            if 片.種 != "マスタ":
                止(番号, 先, "書き戻せる先（MD・マスタ・確定した勤怠・その月だけの指示）の外")
                continue
            タブ名, 名 = 片.甲, 片.乙
            if タブ名 in _決まらないマスタのタブ:
                止(番号, 先, f"{タブ名} の額・適用開始は答えから決まらない（行を起こすのは〔口: 初期設定〕の答えの反映）")
                continue
            g = 今の格子(_マスタ, タブ名)
            if g is None:
                止(番号, 先, f"{_マスタ}/{タブ名} を渡されていない")
                continue
            if not 名:
                止(番号, 先, "反映先に項目の名が無い（どの列か決まらない）")
                continue
            v, 訳 = _値(q, 回答, 名)
            if 訳:
                止(番号, 先, 訳)
                continue
            h = g[0]
            if タブ名 == "会社":
                鍵 = {"会社": 会社, "項目": 名, "適用開始": 支給月}
                月 = 設問.段.月にそろえる(支給月)
                i = next((i for i, r in enumerate(g[1:], 2) if r[h.index("会社")] == 会社 and r[h.index("項目")] == 名
                          and 設問.段.月にそろえる(r[h.index("適用開始")]) == 月), None)
                行 = [{**鍵, "今の値": v}.get(c, "") for c in h] if i is None else [v if c == "今の値" else g[i - 1][j] for j, c in enumerate(h)]
                if i is None:
                    足す手順(_行を足す(_マスタ, タブ名, 行)); 記(q, 先, "行を足す")
                elif 行 != g[i - 1]:
                    足す手順(_値を書く(_マスタ, タブ名, i, 行)); 記(q, 先, "値を書く")
                書いた番号.setdefault(番号, []).append(先)
                continue
            if 名 not in h:
                止(番号, 先, f"{タブ名} に {名} の列が無い")
                continue
            鍵の列 = "NO" if タブ名 == "社員" else "型の名"
            誰 = set(_誰(q)) if タブ名 != "社員" else _NOたち(q)
            当たる = [i for i, r in enumerate(g[1:], 2) if r[h.index("会社")] in ("", 会社) and r[h.index(鍵の列)] in 誰]
            if not 当たる:
                止(番号, 先, f"答えで変わる項目と人 に {タブ名} の {鍵の列} が無い（どの行か決まらない）")
                continue
            for i in 当たる:
                前 = g[i - 1][h.index(名)]
                if 前 != v:
                    行 = list(g[i - 1]); 行[h.index(名)] = v
                    足す手順(_値を書く(_マスタ, タブ名, i, 行)); 記(q, 先, "値を書く")
                if タブ名 == "社員" and 前 != v:
                    x = _変更の記録(今, q, 会社, 支給月, 今日, g[i - 1], h, 名, 前, v)
                    if isinstance(x, str):
                        止(番号, 先, x)
                        break
                    if x:
                        足す手順(x); 記(q, f"{_マスタ}/変更の記録", "行を足す")
            else:
                書いた番号.setdefault(番号, []).append(先)

    # その月だけの指示（台帳へ書く.月の台帳・1 回に全部）
    if その月の行:
        if 設問.その月だけの指示の先.split("/", 1)[1] not in 台帳:
            for _, q in その月の行:
                止(_字(q.get("問いの番号")), 設問.その月だけの指示の先, "年の台帳のタブ その月だけの指示 を渡されていない")
        else:
            h = 書.形.見出し("その月だけの指示")
            表 = [list(h), *[[_字(d.get(c)) for c in h] for d, _ in その月の行]]
            社員 = 口.格子を行へ(マスタ.get("社員") or [])
            o = 書.月の台帳({"その月だけの指示": 表}, 今の台帳={"その月だけの指示": 今[(台帳の名, "その月だけの指示")]},
                          台帳の名=台帳の名, 社員=社員)
            for x in o["書く手順"]:
                足す手順(x)
            for d, q in その月の行:
                if o["書く手順"]:
                    記(q, 設問.その月だけの指示の先, "その月だけの指示へ書く")
                書いた番号.setdefault(d["問いの番号"], []).append(設問.その月だけの指示の先)

    # 確定した勤怠（答えを確定した勤怠へ の返り）
    関所で止まった: set[str] = set()   # 関所（入口の文脈.日の答え）が退けた・どの日にも当たらなかった答えの問い＝開いたまま・済にしない
    if 確定の番号 and isinstance(確定した勤怠の返り, dict) and "止まった答え" in 確定した勤怠の返り:
        止まった訳 = {}
        for d in 確定した勤怠の返り.get("止まった答え") or []:
            止まった訳.setdefault(_字(d.get("問いの番号")), _字(d.get("訳")))
        残す = []
        for q, 先 in 確定の番号:
            番号 = _字(q.get("問いの番号"))
            if 番号 not in 止まった訳:
                残す.append((q, 先))
                continue
            if 番号 not in 関所で止まった:   # 済の問いは 確定の番号 に入らない（上の答えた の回で飛ばす）
                関所で止まった.add(番号)
                開いた.append(番号)
                開いた訳.append({"問いの番号": 番号, "訳": f"日の問いの関所で止まった（{止まった訳[番号]}）＝戻し方: {_関所の戻し方}"})
        確定の番号 = 残す
    if 確定の番号:
        if not isinstance(確定した勤怠の返り, dict):
            for q, 先 in 確定の番号:
                止(_字(q.get("問いの番号")), 先, "答えを確定した勤怠へ の返りを 確定した勤怠の返り で渡す")
        elif "止まった答え" not in 確定した勤怠の返り:   # 前の版の返り＝関所で止まった答えが分からない＝書かずに止める
            for q, 先 in 確定の番号:
                止(_字(q.get("問いの番号")), 先, "確定した勤怠の返り に 止まった答え が無い（答えを確定した勤怠へ を今の版で回し直す）")
        elif any(k not in 台帳 for k in 書.日のタブ[1:] + 書.区間のタブ[1:]):
            for q, 先 in 確定の番号:
                止(_字(q.get("問いの番号")), 先, "年の台帳のタブ 確定した勤怠・確定した勤怠の区間 を渡されていない")
        else:
            社員 = 口.格子を行へ(マスタ.get("社員") or [])
            o = 書.勤怠(確定=True, 勤怠=確定した勤怠の返り.get("確定した勤怠") or [],
                      勤怠の区間=確定した勤怠の返り.get("確定した勤怠の区間") or [],
                      今の台帳={k: 今[(台帳の名, k)] for k in (書.日のタブ[1], 書.区間のタブ[1])}, 台帳の名=台帳の名,
                      社員=社員, 原本のリンク=原本のリンク or {})
            for x in o["書く手順"]:
                足す手順(x)
            for q, 先 in 確定の番号:
                if o["書く手順"]:
                    記(q, 先, "確定した勤怠へ書く")
                書いた番号.setdefault(_字(q.get("問いの番号")), []).append(先)

    # 書いた後の値で照らす（埋まらない先は止める）。全部の先が埋まった問いだけ 反映済み を 済 に
    後の台帳 = {k: 今[(台帳の名, k)] for k in 台帳}
    後のマスタ = {k: 口.格子を行へ(今[(_マスタ, k)]) for k in マスタ}
    後のmd = {k: 今[("md", k)] for k in md}
    照 = 設問.反映の照らし(今[(_質問と回答, _問いのタブ)], 後のマスタ, 会社, md=後のmd, 支給月=支給月, 台帳=後の台帳)
    止めた = {x["問いの番号"] for x in 止める} | 関所で止まった
    状態: dict[str, list] = {}
    for r in 照["行たち"]:
        状態.setdefault(r["問いの番号"], []).append(r)
    for 番号 in sorted(書いた番号):
        if 番号 in 止めた:
            continue
        外 = [r for r in 状態.get(番号, []) if r["状態"] not in ("埋まった", "見ていない")]
        if 外:
            for r in 外:
                止(番号, r["反映先"], f"書いた後も {r['状態']}" + (f"（{r['訳']}）" if r["訳"] else ""))
            continue
        x = _済にする(今[(_質問と回答, _問いのタブ)], 会社, 番号)
        if x:
            足す手順(x)
            q = next(q for q in 答えた if _字(q.get("問いの番号")) == 番号)
            記(q, f"{_質問と回答}/{_問いのタブ}#反映済み", "値を書く")
    赤 = [f"{x['問いの番号']} {x['反映先']}: {x['訳']}" for x in 止める] + \
        [f"{x['問いの番号']} {x['反映先']}: 前の答えと食い違う（{x['訳']}）" for x in 食い違い]
    for x in 手順:
        if x["する"] not in 手順の種類:
            raise 書き戻しの誤り(f"閉じた手順の外 {x['する']!r}")
    return {"手順": 手順, "記録": 記録, "開いたまま": 開いた, "開いたままの訳": 開いた訳, "止める": 止める, "問い": 食い違い, "赤": 赤}


def _見出しの位置(本文: str, 見出し: str):
    """見出しの行の match（md_の節 と同じ読み方・無ければ None）。"""
    鍵 = 口.見出しの字(見出し)
    return next((m for m in re.finditer(r"^(#+)[ \t]*(.*?)[ \t]*$", 本文 or "", re.M)
                 if 口.見出しの字(m.group(2)) == 鍵), None)


def _md_へ足す(本文: str, 見出し: str | None, 行: str) -> str:
    """見出しの節（md_の節 と同じ境）の終わりに 1 行を足した全文。見出しが無い先は本文の終わり。"""
    本文 = 本文 or ""
    if 見出し:
        m = _見出しの位置(本文, 見出し)
        残り = 本文[m.end():]
        e = re.search(rf"^#{{1,{len(m.group(1))}}}(?!#)", 残り, re.M)
        終わり = m.end() + (e.start() if e else len(残り))
    else:
        終わり = len(本文)
    前, 後 = 本文[:終わり].rstrip("\n"), 本文[終わり:]
    return f"{前}\n{行}\n" + (f"\n{後.lstrip(chr(10))}" if 後 else "")


def _変更の記録(今: dict, q: dict, 会社, 支給月, 今日, 社員の行, h, 名, 前, v):
    """社員の列を書いた時の 変更の記録 の 1 行（同じ 会社・NO・項目・問いの番号 の行が在れば書かない）。"""
    g = 今.get((_マスタ, "変更の記録"))
    if g is None:
        return f"{_マスタ}/変更の記録 を渡されていない（社員の値を変えた記録が残らない）"
    gh = g[0]
    番号 = _字(q.get("問いの番号"))
    NO = 社員の行[h.index("NO")]
    if any(r[gh.index("会社")] == 会社 and r[gh.index("NO")] == NO and r[gh.index("項目")] == 名
           and r[gh.index("問いの番号")] == 番号 for r in g[1:]):
        return None
    d = {"会社": 会社, "記録日": 今日, "適用支給月": 支給月, "NO": NO,
         "氏名": 社員の行[h.index("氏名")] if "氏名" in h else "", "項目": 名, "前の値": 前, "新しい値": v,
         "書類の名": "", "問いの番号": 番号, "確かめ": "確認済"}
    return _行を足す(_マスタ, "変更の記録", [d.get(c, "") for c in gh])


def _済にする(格子, 会社: str, 番号: str):
    """質問と回答の 番号 の一番下の行の 反映済み を 済 に（もう済なら None）。"""
    h = 格子[0]
    if "反映済み" not in h:
        return None
    i = max((i for i, r in enumerate(格子[1:], 2) if r[h.index("問いの番号")] == 番号
             and r[h.index("会社")] in ("", 会社)), default=None)
    if i is None or 口.反映済みを読む(格子[i - 1][h.index("反映済み")]):
        return None
    行 = list(格子[i - 1]); 行[h.index("反映済み")] = "済"
    return _値を書く(_質問と回答, _問いのタブ, i, 行)


