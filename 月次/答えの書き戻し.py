"""答えの書き戻し — 確認事項の答えを、反映先（MD・マスタ・確定した勤怠・その月だけの指示）へ書き戻す手順を返す口。

答えは反映先を書き換えるまで計算に使わない（2026-11 オーナー: 答えは必ず引き継ぐ）。行き先は問いの行の 反映先
（読み方の正本は 型の口.反映先を読む・行き先の表は docs/設計/Drive の型.md §9 と docs/毎月の流れ.md）。この口は
値を決めて手順を返すだけで、事務所の置き場を開かない。殻は返った手順を閉じた種類のまま当て、読み直して照らす。

手順の種類（閉じた並び `手順の種類`）:
  - 値を書く {ファイル, タブ, 範囲 A<n>:<列><m>, 値, 書き方 RAW}・行を足す {ファイル, タブ, 値, 書き方 RAW}・
    行を消す {ファイル, タブ, 行}（台帳へ書く の手順と同じ形）
  - md を書き換える {先: md の名, 本文: 書き換えた後の全文}

決め方:
  - 答えの芯が 決まり切らない（分からない など＝正本は 確認ページ/前の答え.py）問いは書かない＝開いたまま。止まった訳と
    戻し方（前の答え.止まった訳）を 開いたままの訳 に添える（事務所がそのまま担当者へ返せる）。
  - 問いを閉じた行・別の会社・答えの無い行は見ない。前の答えと食い違う組は書かずに 問い へ返す（担当者に聞き直す）。
  - 値は答えの芯（`見当のとおり` は 見当）。設定（マスタ 会社・社員・勤務の型）へ書く値は、芯が決めているその項目の形
    （選べる値・額・数・率・時間・日付・時刻・時間帯＝正本は 芯/設定.形で読めない訳）で読めた物だけ。形を決めていない項目
    （字・JSON）と形で読めない文（「ほか」の後ろの文・結論の文の全体を含む）は書かず「人が反映する（理由）」で止める
    （答えの文をそのまま設定へ書くと、芯が読めない値か古い値で計算する）。
  - md: 節の終わりに `- <値>（出所: 問い:<番号>・受付 <受付番号>）`。番号が節に在れば書かない（何度当てても同じ）。
    md を値として読む芯の側は 例の確かめ.MDから例を読む（`###` の下の表）と 勤怠の照らし.MDの見出したち だけで、`- ` の
    1 行はどちらにも読まれない。改行・HTML の注の印（見出し・表・注を作れる）を含む答えは書かず 人が反映する で止める。
  - マスタ 会社: (会社, 項目, 適用開始＝支給月) の行。社員: 答えで変わる項目と人 の NO の行のその列＋変更の記録の 1 行。
    勤務の型: 答えで変わる項目と人 の 型の名 の行のその列。支給控除の項目・人ごとの支給控除 は額と適用開始が答えから
    決まらない＝止める。
  - その月だけの指示: 項目 1 つ・NO・値が決まる答えだけ。値は 段の解決.変動の数 で読めた数だけ（字のまま読む欄＝
    段の解決.変動の欄の項目 と数で読めない値は 人が反映する で止める）。台帳へ書く.月の台帳 の手順。
  - 確定した勤怠: 答えを確定した勤怠へ の返りを 台帳へ書く.勤怠 へ（返りを渡されていなければ止める）。原本を送る は書かない。
    返りの 止まった答え（日の問いの関所＝入口の文脈.日の答え が退けた答え・どの日にも当たらなかった答え）の問いは書かず
    済にせず、開いたまま に訳と戻し方（答え直す）を添えて返す（前の答えで決まった答えでも関所が退ければ答え済みに数えない）。
    返りに 止まった答え が無ければ（前の版の返り）書かずに止める。
  - 反映済み が 済 の行は閉じた問い（答えの字を読み直さない・開いたままに数えない・どの先へも書き直さない＝設問.反映した行か）。
    食い違いの照らしには前の答えとして残す（済の答えと違う後の答えは 問い へ返す）。
  - 原本の先・知らない先・反映先が空 は書かずに止める（訳つき）。
  - 手順を作った後の値で 設問.反映の照らし を回し、書いた問いの先が全部 埋まった の時だけ、質問と回答の行の 反映済み を 済 にする
    （埋まらない先は止める＝黙って済にしない）。
返す物: {手順, 記録 [{受付番号, 問いの番号, 反映先, する}], 開いたまま [問いの番号], 開いたままの訳 [{問いの番号, 訳}], 止める [{問いの番号, 反映先, 訳}], 問い, 赤}。
赤が空でない時、殻は手順を当てずに止まる（手順は止めた問いを含まないが、ひとまとまりで当てる）。
"""
