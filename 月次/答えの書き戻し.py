def _字(v) -> str:
    return "" if v is None else str(v).strip()


def _格子(表, 何: str) -> list[list[str]]:
    """get_values の形（1 行目が見出し）だけを受ける＝書く行の位置が決まる。"""
    if not isinstance(表, (list, tuple)) or not 表 or not isinstance(表[0], (list, tuple)):
        raise 書き戻しの誤り(f"{何} は get_values の形（1 行目が見出しの格子）で渡す")
    h = [_字(c) for c in 表[0]]
    return [h, *[[_字(r[i]) if i < len(r) else "" for i in range(len(h))] for r in 表[1:]]]


def md_の印(本文: str) -> str:
    """md の全文の印（drive口.字にする でそろえた字〔BOM を落とし改行を LF に〕の UTF-8 の sha256）。md を書き換える 手順の
    前の印 と、当てる口が今の全文と照らすのはこの 1 つ＝殻が渡した字が CRLF・BOM のままでも、口が読んだ字と同じ印になる。"""
    return "sha256:" + hashlib.sha256(字にする(本文).encode("utf-8")).hexdigest()


def 手順を当てる(今: dict, 手順) -> dict:
    """手順を値の上で当てた後（{(ファイル, タブ): 格子, ("md", 名): 本文}）。殻が当てるのと同じ順。"""
    t = copy.deepcopy(今)
    for x in 手順:
        if x["する"] == "md を書き換える":
            t[("md", x["先"])] = x["本文"]
            continue
        if x["する"] == "ファイルを作る":
            t[("ファイル", f"{x['先']}/{x['名']}")] = x["本文"]
            continue
        g = t.setdefault((x["ファイル"], x["タブ"]), [])
        if x["する"] == "値を書く":
            m = re.fullmatch(r"A(\d+):[A-Z]+(\d+)", x["範囲"])
            a = int(m.group(1))
            for i, r in enumerate(x["値"]):
                while len(g) < a + i:
                    g.append([])
                g[a + i - 1] = list(r)
        elif x["する"] == "行を足す":
            g.extend(list(r) for r in x["値"])
        elif x["する"] == "行を消す":
            del g[x["行"] - 1]
        else:
            raise 書き戻しの誤り(f"知らない手順 {x['する']!r}")
    return t


