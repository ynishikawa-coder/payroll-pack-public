"""出口の指定の判断の口（〔口: 出荷〕が読む前に呼ぶ）。試算（出口 null＝計算だけ・何も出さない）か正式かをここだけが決める。

殻（事務所の側の口）は事務所の設定から読んだ 出口 をそのまま渡し、返った赤のまま止める（殻に同じ判断を写さない）。
正式（dict）は 取り込み・支給控除一覧 の 2 つの出力の指定と 取り込み.道具（給与ソフトの呼び名）が全部要る。

  python3 月次/出口の指定.py 照らす < 入力.json
    # {"出口": dict|null, "有給の値": 任意|null（受けるが判断に使わない）, "回": "月"|"賞与"}
    # → {"赤", "試算", "出す時の赤", "出す物が無い訳"}
    #   赤＝読む前に止める形の赤／試算＝出口が null／出す時の赤＝〔口: 出荷〕の 出す で止める赤（試算は 照らす で回す）／
    #   出す物が無い訳＝パックの口が出す物を返さなかった時の訳

形の崩れた入力は {"拒む": 訳}・終わりの値 2。
"""
import json
import sys
from pathlib import Path

_根 = Path(__file__).resolve().parent.parent
if str(_根) not in sys.path:
    sys.path.insert(0, str(_根))

from 月次.口の入口 import 拒む, 回す  # noqa: E402  拒むの約束（どの崩れも {"拒む"}・終わりの値 2）は入口の 1 つだけ

出力の指定 = ("取り込み", "支給控除一覧")
回たち = ("月", "賞与")




def 出口の赤(出口) -> list[str]:
    """出口 の形の赤。null＝試算は赤でない。正式（dict）は 2 つの指定と 取り込み.道具 が全部要る（欠けたらパックの計算を呼ぶ前に止める）。"""
    if 出口 is None:
        return []
    if not isinstance(出口, dict):
        return [f"形: 出口 は dict か null で渡す（受けた物: {type(出口).__name__}）"]
    miss = [k for k in 出力の指定 if not isinstance(出口.get(k), dict)]
    if not miss and not str(出口["取り込み"].get("道具") or "").strip():
        miss = ["取り込み.道具"]
    return [f"形: 正式の出口に {'・'.join(miss)} が無い（給与ソフトの呼び名と 2 つの出力の指定は事務所の設定から読んで渡す。"
            "試算は 出口 を null で渡す）"] if miss else []


def 照らす(出口, 有給の値=None, 回: str = "月") -> dict:
    """試算か正式かと、それぞれの止め方。試算は何も書かない（出す では止め、照らす で計算だけ回す）。"""
    試算 = 出口 is None
    賞与 = 回 == "賞与"
    return {
        "赤": 出口の赤(出口),
        "試算": 試算,
        # 有給の値 を渡しても試算は試算（出す は有給の値を常に {} から組んで渡す＝有給の値で出す道を開けない）
        "出す時の赤": ["試算（出口 null）は 照らす で回す。出す は正式の出口を渡す時だけ"] if 試算 else [],
        "出す物が無い訳": f"{'賞与を回す' if 賞与 else '月を回す'} が出す物を返さない（"
        + ("試算＝出口 null は計算だけで何も出さない。出すなら 出口 に 取り込み・支給控除一覧・取り込み.道具 を渡す）"
           if 試算 else "全員が外れていないかを見る）"),
    }


def _口(何: str, x) -> dict:
    if not isinstance(x, dict):
        raise 拒む("入力は JSON の表で渡す")
    if 何 == "照らす":
        回 = x.get("回")
        if 回 not in 回たち:   # 欠けた・知らない回を月とみなさない（既定で止める）
            raise 拒む(f"回 は {'・'.join(回たち)} のどれか（受けた物: {回!r}）")
        return 照らす(x.get("出口"), x.get("有給の値"), 回)
    raise 拒む(f"知らない口: {何}")


if __name__ == "__main__":
    回す(_口)
