月ごとに聞く値 = 遅れた出勤の止める語
_月給の形 = ("月給", "日給月給", "年俸")   # 芯/集計/日.py の 月給の形 と同じ線


def 遅れた出勤の日たち(確定, 確定の区間=(), *, 人の決まり: dict) -> list[dict]:
    """確定した勤怠から、仮に挙げる始業より後の出勤の日 [{NO, 氏名, 日付, 出勤の時刻, 所定の始業, 遅れの分}]。
    人の決まり＝{NO: {項目: 値}}（殻が段の解決で会社・勤務の型・人を重ねた値。`時間.月給者の遅れた出勤`・`時間.遅れた出勤の猶予`・
    `欠勤.遅刻早退の控除`・`支払.賃金の形`・`時間.所定の始業`）。挙げるのは、月給の人（`支払.賃金の形` が 月給・日給月給・年俸）か
    遅刻早退の控除 が 引く の会社の時給・日給の人で（月給の人だけ引く・引かない の会社の時給の人は挙げない）、
    遅れた出勤 が 月ごとに聞く値 の人の、印に 定時扱い の無い・休暇の無い日のうち、出勤（労働の区間の一番早い始め、無ければ 出勤の時刻）が
    所定の始業（日の行の 所定の始業、無ければ人の 時間.所定の始業）より 猶予 を超えて遅い日（遅延証明の分 は遅れから引く）。"""
    区間 = 行に(確定の区間, "確定した勤怠の区間")
    始め: dict[tuple, int] = {}
    for b in 区間:
        分 = 時刻の分(b.get("区間の種別") == "労働" and b.get("始め") or "")
        if 分 is not None:
            k = (b.get("NO", ""), b.get("日付", ""))
            始め[k] = min(始め.get(k, 分), 分)
    out = []
    for r in 行に(確定, "確定した勤怠"):
        no = r.get("NO", "")
        決 = {str(k): _字(v) for k, v in (人の決まり.get(no) or 人の決まり.get(str(no)) or {}).items()}
        if not 遅れた出勤で止める人か(決, 決.get("支払.賃金の形", "")):   # 誰を止めるかは芯と 1 つの線
            continue
        if "定時扱い" in r.get("印", "") or r.get("休暇の種類"):
            continue
        出 = 始め.get((no, r.get("日付", "")))
        if 出 is None:
            出 = 時刻の分(r.get("出勤の時刻", ""))
        始業 = 時刻の分(r.get("所定の始業") or 決.get("時間.所定の始業", ""))
        if 出 is None or 始業 is None:
            continue
        try:
            猶予 = int(決.get(猶予の項目) or 0)
            証明 = int(r.get("遅延証明の分") or 0)
        except ValueError:
            raise 照らしの誤り(f"NO {no} {r.get('日付')}: {猶予の項目} か 遅延証明の分 が分の数でない")
        遅れ = 出 - 始業 - 証明
        if 遅れ > 猶予:
            out.append({"NO": no, "氏名": r.get("氏名", ""), "日付": r.get("日付", ""), "出勤の時刻": 長さの字(出),
                        "所定の始業": 長さの字(始業), "遅れの分": 遅れ})
    return sorted(out, key=lambda d: (d["NO"], d["日付"]))


