def 照らす(読んだまま, 読んだままの区間, 確定, 確定の区間, *, 印字の合計: dict | None = None,
         人ごとの月の数字=None, 決まりの見出したち=None, 問いの番号たち=None) -> 照らしの結果:
    """確定した勤怠（2 次）を機械で照らす。挙がり（1 件 1 行）と、挙がった人の締めの記録の行（状態 まだ）を返す。

    決まりの見出したち・問いの番号たち: 渡せば直した訳の `決まり:<見出し>`・`問い:<番号>` がその中に在るかも見る。
    月を回す は必ず渡す（`MDの見出したち`・`答えのある問いの番号たち` で Drive の字から組む）。渡さない（None）のは部品をじかに呼ぶ試験だけ。
    締めの記録の 残る問いの番号 には、挙がった種類を `照らし:<種類>` で書く（機械の挙がりで、問いの表の番号ではない）。"""
    一1, 区1 = 行に(読んだまま, "読んだままの勤怠"), 行に(読んだままの区間, "読んだままの勤怠の区間")
    一2, 区2 = 行に(確定, "確定した勤怠"), 行に(確定の区間, "確定した勤怠の区間")
    見出し = None if 決まりの見出したち is None else {_字(x) for x in 決まりの見出したち}
    問い = None if 問いの番号たち is None else {_字(x) for x in 問いの番号たち}
    月 = {_鍵(r, 人の鍵の列, "人ごとの月の数字"): r for r in 行に(人ごとの月の数字, "人ごとの月の数字")}

    氏名: dict[tuple, str] = {}
    for r in [*一1, *一2]:
        k = _鍵(r, 人の鍵の列, "勤怠")
        if r.get("氏名") and not 氏名.get(k):
            氏名[k] = r["氏名"]
    挙がり: list[dict] = []

    def 挙げる(k: tuple, 種類: str, 中身: str, 日付: str = "", 番号: str = ""):
        挙がり.append({"会社": k[0], "支給月": k[1], "NO": k[2], "氏名": 氏名.get(k[:3], ""), "日付": 日付,
                     "区間の番号": 番号, "種類": 種類, "中身": 中身})

    日1 = {_鍵(r, 日の鍵の列, "読んだままの勤怠"): r for r in 一1}
    日2 = {_鍵(r, 日の鍵の列, "確定した勤怠"): r for r in 一2}
    間1 = {_鍵(r, 区間の鍵の列, "読んだままの勤怠の区間"): r for r in 区1}
    間2 = {_鍵(r, 区間の鍵の列, "確定した勤怠の区間"): r for r in 区2}
    日の区間2: dict[tuple, list[dict]] = {}
    for k, r in 間2.items():
        日の区間2.setdefault(k[:4], []).append(r)

    # 1. 確定に無い人・日
    人2 = {k[:3] for k in 日2}
    無い人 = set()
    for k in 日1:
        if k[:3] not in 人2:
            無い人.add(k[:3])
        elif k not in 日2:
            挙げる(k, "確定に無い", f"{k[3]} の行が読んだままに在るのに確定した勤怠に無い", k[3])
    for k in sorted(無い人):
        挙げる(k, "確定に無い", "読んだままに在る人が確定した勤怠に 1 日も無い")

    # 2. 区間の時刻（抜け・形・重なり）
    for dk, bs in 日の区間2.items():
        読めた = {"労働": [], "休憩と外出": []}
        for b in sorted(bs, key=lambda b: b.get("区間の番号", "")):
            番 = b.get("区間の番号", "")
            始, 終 = 時刻の分(b.get("始め", "")), 時刻の分(b.get("終わり", ""))
            if 始 is None:
                挙げる(dk, "時刻の形", f"区間 {番} の始め「{b.get('始め', '')}」が読めない（H:MM・0:00〜47:59）", dk[3], 番)
                continue
            if not b.get("終わり"):
                挙げる(dk, "時刻の抜け", f"区間 {番}（{b.get('区間の種別', '')}）の終わりが無い", dk[3], 番)
                continue
            if 終 is None:
                挙げる(dk, "時刻の形", f"区間 {番} の終わり「{b.get('終わり', '')}」が読めない（H:MM・0:00〜47:59）", dk[3], 番)
                continue
            if 始 >= 終:
                挙げる(dk, "時刻の形", f"区間 {番} の始め {b['始め']} が終わり {b['終わり']} より後か同じ", dk[3], 番)
                continue
            組 = "労働" if b.get("区間の種別") == "労働" else "休憩と外出"
            for 番2, a, z in 読めた[組]:
                if 始 < z and a < 終:
                    挙げる(dk, "区間の重なり", f"区間 {番2} と区間 {番}（{組}）が重なる", dk[3], 番)
            読めた[組].append((番, 始, 終))
        労働 = 読めた["労働"]
        if 労働 and max(z for _, _, z in 労働) - min(a for _, a, _ in 労働) > 一日:
            挙げる(dk, "24 時間超え", "最初の労働の始めから最後の終わりまでが 24 時間を超える", dk[3])

    # 3. 日の行（出勤・退勤の片方・労働の合計）
    for dk, r in 日2.items():
        出, 退 = r.get("出勤の時刻", ""), r.get("退勤の時刻", "")
        if bool(出) != bool(退):
            挙げる(dk, "時刻の抜け", f"{'退勤' if 出 else '出勤'}の時刻が無い（片方だけ）", dk[3])
        for 列, v in (("出勤の時刻", 出), ("退勤の時刻", 退)):
            if v and 時刻の分(v) is None:
                挙げる(dk, "時刻の形", f"{列}「{v}」が読めない", dk[3])
        if 出 and 退 and 時刻の分(出) is not None and 時刻の分(退) is not None and 時刻の分(退) - 時刻の分(出) > 一日:
            挙げる(dk, "24 時間超え", f"出勤 {出} から退勤 {退} までが 24 時間を超える", dk[3])
        for 列 in ("休憩の合計", "労働の合計"):
            if r.get(列) and 長さの分(r[列]) is None:
                挙げる(dk, "時刻の形", f"{列}「{r[列]}」が読めない（h:mm か分）", dk[3])
        労 = 長さの分(r.get("労働の合計", ""))
        if 労 is not None and 労 > 一日:
            挙げる(dk, "24 時間超え", f"労働の合計 {r['労働の合計']} が 24 時間を超える", dk[3])
        for 列 in 分の列:
            v = r.get(列, "")
            if v and not re.fullmatch(r"\d+", v):
                挙げる(dk, "時刻の形", f"{列}「{v}」が整数の分でない", dk[3])
            elif 列 in ("時刻の無い休憩", "時刻の無い労働時間") and v and int(v) > 一日:
                挙げる(dk, "24 時間超え", f"{列} {v} 分が 24 時間を超える", dk[3])
        if r.get("原本の時間") and _原本の時間(r["原本の時間"]) is None:
            挙げる(dk, "時刻の形", f"原本の時間「{r['原本の時間']}」が `語=分` を読点で並べた形でない", dk[3])

    # 4. 1 次と 2 次の差と直した訳
    def 訳を照らす(k: tuple, 訳: str, 要る: bool, 何: str, 日付: str, 番号: str = ""):
        if not 訳:
            if 要る:
                挙げる(k, "直した訳が無い", f"{何}が読んだままと違うのに直した訳が空", 日付, 番号)
            return
        if not 要る:
            挙げる(k, "直した訳の形", f"{何}が読んだままと同じなのに直した訳「{訳}」がある", 日付, 番号)
            return
        for x in _訳たち(訳):
            m = re.fullmatch(r"(決まり|問い|読み直し):(.+)", x)
            if not m or not m.group(2).strip():
                挙げる(k, "直した訳の形", f"{何}の直した訳「{x}」が `決まり:<見出し>`・`問い:<番号>`・`読み直し:<日>` の形でない",
                     日付, 番号)
            elif m.group(1) == "読み直し" and not _日付か(m.group(2).strip()):
                挙げる(k, "直した訳の形", f"{何}の直した訳「{x}」の読み直した日が YYYY-MM-DD でない", 日付, 番号)
            elif m.group(1) == "決まり" and 見出し is not None and m.group(2).strip() not in 見出し:
                挙げる(k, "直した訳の形", f"{何}の直した訳の決まり「{m.group(2).strip()}」が作業のルール.md・給与のルール.md の見出しに無い", 日付, 番号)
            elif m.group(1) == "問い" and 問い is not None and m.group(2).strip() not in 問い:
                挙げる(k, "直した訳の形", f"{何}の直した訳の問い「{m.group(2).strip()}」が質問と回答のその会社の答えのある問いに無い", 日付, 番号)

    事実の列 = [c for c in 日の列 if c not in 比べない列]
    区間の事実 = [c for c in 区間の列 if c not in 比べない列]
    区間が変わった日, 区間を消した日 = set(), set()
    for k in sorted(set(間1) | set(間2)):
        if k not in 間2:
            区間を消した日.add(k[:4])
            continue
        違う = k not in 間1 or any(間1[k].get(c, "") != 間2[k].get(c, "") for c in 区間の事実)
        訳を照らす(k, 間2[k].get(訳の列, ""), 違う, f"{k[3]} の区間 {k[4]}", k[3], k[4])
        if 違う:
            区間が変わった日.add(k[:4])
    for dk, r in 日2.items():
        違う = dk not in 日1 or any(日1[dk].get(c, "") != r.get(c, "") for c in 事実の列)
        訳 = r.get(訳の列, "")
        if 違う or dk in 区間を消した日:
            # 区間を消した日は消した区間の行が無い＝日の行に訳を書く
            訳を照らす(dk, 訳, True, f"{dk[3]} の行" + ("" if 違う else "（区間を消した）"), dk[3])
        elif dk in 区間が変わった日:
            if 訳:
                訳を照らす(dk, 訳, True, f"{dk[3]} の行", dk[3])   # 区間を直した日の行の訳は在ってよい（形だけ見る）
        else:
            訳を照らす(dk, 訳, False, f"{dk[3]} の行", dk[3])

    # 5. 原本に印字された合計（渡された印字の合計と、確定した勤怠の 原本の時間 の日の和）
    印字 = {_字(NO): {_字(k): v for k, v in 項目たち.items()} for NO, 項目たち in (印字の合計 or {}).items()}
    for NO in 印字:
        if not any(k[2] == NO for k in [*日2, *日1]):
            挙がり.append({"会社": "", "支給月": "", "NO": NO, "氏名": "", "日付": "", "区間の番号": "",
                         "種類": "確定に無い", "中身": "印字の合計の在る人が確定した勤怠に無い"})
    for pk in sorted({k[:3] for k in 日2}):
        日たち = [r for k, r in 日2.items() if k[:3] == pk]
        日の和: dict[str, int] = {}
        for r in 日たち:
            for 語, v in (_原本の時間(r.get("原本の時間", "")) or {}).items():
                日の和[語] = 日の和.get(語, 0) + v
        照らす項目 = [(項目, 値, True) for 項目, 値 in 印字.get(pk[2], {}).items()]
        照らす項目 += [(語, v, False) for 語, v in 日の和.items() if 語 not in 印字.get(pk[2], {})]
        for 項目, 値, 渡された in 照らす項目:
            # 原本の時間の日の和は、その語の在る日だけで数える語がある（印字の時間数は手書きの日に無い＝その日を足さない）
            素の日 = 日たち if 渡された or 項目 not in 在る日だけの語 else [
                r for r in 日たち if 項目 in (_原本の時間(r.get("原本の時間", "")) or {})]
            ここ = _素の合計(素の日, 項目, 日の区間2)
            if ここ is None and 項目 in 月.get(pk, {}) and 月[pk][項目] != "":
                ここ = 月[pk][項目]
            if ここ is None and not 渡された:
                continue   # 原本の時間 の語のうち数えられない語は照らさない（渡された印字の合計ではない・照らす用の日の値）
            if ここ is None:
                挙げる(pk, "印字の合計を照らせない",
                     f"印字の「{項目}」{_字(値)} を確定した勤怠から数えられない（人ごとの月の数字にも無い）")
            elif not _同じ値(項目, 値, ここ):
                出所 = "印字" if 渡された else "原本の時間の日の和"
                挙げる(pk, "印字の合計と違う", f"「{項目}」が {出所} {_見せる(項目, 値)}／確定した勤怠 {_見せる(項目, ここ)}")

    # 締めの記録
    人の挙がり: dict[tuple, list[str]] = {}
    for x in 挙がり:
        人の挙がり.setdefault((x["会社"], x["支給月"], x["NO"]), [])
        if x["種類"] not in 人の挙がり[(x["会社"], x["支給月"], x["NO"])]:
            人の挙がり[(x["会社"], x["支給月"], x["NO"])].append(x["種類"])
    締め = [{"会社": k[0], "支給月": k[1], "NO": k[2], "氏名": 氏名.get(k, ""), "状態": "まだ", "締めた日": "",
            "残る問いの番号": "、".join(f"照らし:{s}" for s in 種類), "パックの版": _パックの版()}
           for k, 種類 in sorted(人の挙がり.items())]
    全員 = {k[:3] for k in [*日1, *日2]}
    return 照らしの結果(挙がり=挙がり, 締めの記録=締め, 通った人=sorted(全員 - set(人の挙がり)))


def _日付か(s: str) -> bool:
    from datetime import date
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", s):
        return False
    try:
        date.fromisoformat(s)
    except ValueError:
        return False
    return True


def _原本の時間(s: str) -> dict[str, int] | None:
    """原本の時間（`語=分` を読点で）→ {語: 分}。空は {}・形の外は None。"""
    out: dict[str, int] = {}
    for x in _訳たち(s):
        m = re.fullmatch(r"(.+?)=(\d+)", x)
        if not m:
            return None
        out[m.group(1).strip()] = out.get(m.group(1).strip(), 0) + int(m.group(2))
    return out


# 原本の時間の日の和を、その語の在る日だけの素の合計と照らす語（PDF タイムカードの印字の時間数＝出勤から退勤まで は手書きの日に無い）
在る日だけの語 = ("出勤から退勤まで",)


def _素の合計(日たち: list[dict], 項目: str, 日の区間: dict | None = None):
    """素で数える項目 の値（数えられない項目・形の外の値の在る時は None）。
    出勤から退勤まで＝日ごとの労働の区間の長さの和（区間の無い日は 出勤の時刻〜退勤の時刻・時刻の無い日は 時刻の無い労働時間）。
    日の区間: {(会社, 支給月, NO, 日付): [確定した勤怠の区間の行]}。"""
    if 項目 == "出勤から退勤まで":
        計 = 0
        for r in 日たち:
            組 = [b for b in (日の区間 or {}).get(tuple(r.get(c, "") for c in 日の鍵の列), ())
                 if b.get("区間の種別") == "労働"]
            長さ = [(時刻の分(b.get("始め", "")), 時刻の分(b.get("終わり", ""))) for b in 組]
            if not 組 and r.get("出勤の時刻") and r.get("退勤の時刻"):
                長さ = [(時刻の分(r["出勤の時刻"]), 時刻の分(r["退勤の時刻"]))]
            if any(a is None or z is None or z < a for a, z in 長さ):
                return None
            計 += sum(z - a for a, z in 長さ)
            if not 長さ and r.get("時刻の無い労働時間"):
                v = 長さの分(r["時刻の無い労働時間"])
                if v is None:
                    return None
                計 += v
        return 計
    if 項目 in ("総労働", "休憩"):
        列 = "労働の合計" if 項目 == "総労働" else "休憩の合計"
        計 = 0
        for r in 日たち:
            if r.get("日の種類") in 働く日 or r.get(列):
                v = 長さの分(r.get(列, ""))
                if v is None:
                    if 項目 == "総労働" or r.get(列):
                        return None   # 働いた日の労働の合計が空・読めない＝足せない
                    continue
                計 += v
        return 計
    種類 = {"勤務した日": "勤務", "休日に勤務した日": "休日勤務", "欠勤": "欠勤"}.get(項目)
    if 種類 is None:
        return None
    return sum(1 for r in 日たち if r.get("日の種類") == 種類)


def _数(項目: str, v) -> float | None:
    s = _字(v)
    if 項目 in 分の項目 or 項目 == "休憩":
        if ":" in s:
            return 長さの分(s)
    try:
        return float(s)
    except ValueError:
        return None


def _同じ値(項目: str, a, b) -> bool:
    x, y = _数(項目, a), _数(項目, b)
    return x is not None and x == y


def _見せる(項目: str, v) -> str:
    if isinstance(v, int) and (項目 in 分の項目 or 項目 == "休憩"):
        return f"{長さの字(v)}（{v} 分）"
    return _字(v)


