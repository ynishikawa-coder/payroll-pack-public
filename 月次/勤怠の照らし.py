# ---- 読む ----

def _字(v) -> str:
    return "" if v is None else str(v).strip()


def _読める列(名: str) -> tuple | None:
    """タブの名 → 読める列（知らない列は止める）。人ごとの月の数字 は月の語が並ぶ＝照らさない（None）。"""
