def 行に(表, 名: str) -> list[dict]:
    """dict の並びか 1 行目が見出しの 2 次元の並び → dict の並び（値は字・支給月は YYYY.MM支給 にそろえる）。

    勤怠の 4 つのタブは、読める列（台帳の列・確定の方は＋直した訳）の外の列が在れば止める（知らない列を黙って比べずに通さない）。
    2 次元の並びは見出しに読める列が全部要る（欠けた列を空と見ない）。dict の並びで鍵の無い列は空と読む。"""
    表 = list(表 or ())
    列 = _読める列(名)
    if 表 and not isinstance(表[0], dict):
        h = [_字(x) for x in 表[0]]
        if 列 is not None and [c for c in 列 if c not in h]:
            raise 照らしの誤り(f"{名}: 見出しに列（{'・'.join(c for c in 列 if c not in h)}）が無い")
        表 = [dict(zip(h, r)) for r in 表[1:] if any(_字(x) for x in r)]
    out = []
    for r in 表:
        d = {_字(k): _字(v) for k, v in r.items()}
        if 列 is not None and [k for k in d if k not in 列]:
            raise 照らしの誤り(f"{名}: 知らない列（{'・'.join(k for k in d if k not in 列)}）がある"
                           "（台帳の列が変わったら型の版と一緒にここも読む＝黙って比べずに通さない）")
        if "支給月" in d:
            d["支給月"] = 支給月の字.殻の字へ(d["支給月"])
        out.append(d)
    return out


def _鍵(r: dict, 列, 名: str) -> tuple:
    if any(c not in r for c in 列):
        raise 照らしの誤り(f"{名}: 鍵の列（{'・'.join(c for c in 列 if c not in r)}）が無い行がある")
    return tuple(r[c] for c in 列)


def 時刻の分(s: str) -> int | None:
    """H:MM（0:00〜47:59）→ 分。空・形の外は None。"""
    m = re.fullmatch(r"(\d{1,2}):(\d{2})", s or "")
    if not m or int(m.group(2)) >= 60 or int(m.group(1)) >= 48:
        return None
    return int(m.group(1)) * 60 + int(m.group(2))


def 長さの分(s: str) -> int | None:
    """休憩の合計・労働の合計（h:mm か整数の分）→ 分。空・形の外は None。"""
    if re.fullmatch(r"\d+", s or ""):
        return int(s)
    m = re.fullmatch(r"(\d+):(\d{2})", s or "")
    return int(m.group(1)) * 60 + int(m.group(2)) if m and int(m.group(2)) < 60 else None


def 長さの字(分: int) -> str:
    return f"{分 // 60}:{分 % 60:02d}"


def _訳たち(s: str) -> list[str]:
    return [x.strip() for x in re.split(r"[、,]", s or "") if x.strip()]


