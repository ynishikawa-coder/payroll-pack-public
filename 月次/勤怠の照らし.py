def MDの見出したち(*字たち: str) -> list[str]:
    """作業のルール.md・給与のルール.md の字 → 見出し（`#`〜`######` の行の字）の並び。直した訳 `決まり:<見出し>` が指せる物。
    コードの囲みと HTML の注（<!-- -->）の中は読まない。字が字でない（None も）なら止める（黙って見出しの無い md と読まない）。"""
    out: list[str] = []
    for 字 in 字たち:
        if not isinstance(字, str):
            raise ValueError(f"見出しを読む md は字で渡す（{type(字).__name__} は読まない）")
        囲み = False
        for 行 in re.sub(r"<!--.*?-->", "", 字, flags=re.S).splitlines():
            if 行.lstrip().startswith(("```", "~~~")):
                囲み = not 囲み
                continue
            m = None if 囲み else re.fullmatch(r"\s{0,3}#{1,6}\s+(.*?)\s*#*\s*", 行)
            if m and m.group(1).strip():
                out.append(m.group(1).strip())
    return list(dict.fromkeys(out))


