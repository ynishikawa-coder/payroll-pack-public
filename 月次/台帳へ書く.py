class 台帳へ書く誤り(ValueError):
    """書く手順を出さない（書く先の見出しが型と違う・窓が写しの列に違う値を渡した・どの台帳の行か分からない）。"""


# ---------------------------------------------------------------- 照らし
def _字(v) -> str:
    return 形.値の字(v).strip()


def タブの形(値) -> dict:
    """タブの値（get_values の形）→ {"行の数", "指紋"}。読み直した値と同じに比べるため、升は字にし、各行の末尾の空の升と
    末尾の空の行を落としてから数える（get_values は末尾の空を返さない）。指紋は sha256（字の並びの JSON）。"""
    行 = [[_字(c) for c in r] for r in (値 or ())]
    行 = [r[:max([i + 1 for i, c in enumerate(r) if c] or [0])] for r in 行]
    while 行 and not 行[-1]:
        行.pop()
    return {"行の数": len(行),
            "指紋": hashlib.sha256(json.dumps(行, ensure_ascii=False, separators=(",", ":")).encode("utf-8")).hexdigest()}


def 形を照らす(今の台帳: dict, 手順) -> list[str]:
    """手順の中の 形を照らす を全部、今の台帳（{タブ: 〔口: シートを読む〕で読んだままの値}、md・置き場も照らす時は
    {"シート": {ファイル: {タブ: 値}}, "md": {名: 本文}, "置き場": [名]}）で照らす → 外れの訳（空なら当ててよい）。
    戻す手順の形（頭の有無・頭の無い物を触る手順）まで照らすのは `戻す手順を照らす`（殻は戻す手順にはそちらを呼ぶ）。
    〔口: 書く手順を当てる〕は 1 つ目の手順を当てる前にこれを呼び、空でなければ 1 つも当てない（既定で止める）。"""
    外 = []
    開 = _今を開く(今の台帳)
    for x in 手順 or ():
        if not (isinstance(x, dict) and x.get("する") == "形を照らす"):
            continue
        if "md" in x or "在る" in x:
            名 = x.get("md", x.get("在る"))
            if 開 is None:
                外.append(f"{名}: 今が {{タブ: 値}} の形で md・置き場を照らせない（{{\"シート\", \"md\", \"置き場\"}} で渡す）＝当てない")
            elif "在る" in x and not _在るか(名, *開):
                外.append(f"{名} が今に無い（戻す手順を作った時の書き終えた後に在った）＝書きかけか、ほかの手が入った。戻す手順は当てない")
            elif "md" in x and (名 not in 開[1] or _指紋(開[1][名]) != x.get("指紋")):
                外.append(f"md {名} が戻す手順を作った時の書き終えた後と違う＝書きかけか、ほかの手が入った。戻す手順は当てない")
            continue
        タブ = x.get("タブ")
        タブたち = (開[0].get(x.get("ファイル")) or {}) if 開 is not None else (今の台帳 or {})
        if タブ not in タブたち:
            外.append(f"{x.get('ファイル')} の {タブ}: 今のタブが渡されない（形を照らせない＝当てない）")
            continue
        今 = タブの形(タブたち[タブ])
        if (今["行の数"], 今["指紋"]) != (x.get("行の数"), x.get("指紋")):
            外.append(f"{x.get('ファイル')} の {タブ} が戻す手順を作った時の書き終えた後の形と違う（行の数 今 {今['行の数']}・"
                     f"書き終えた後 {x.get('行の数')}）＝書きかけか、ほかの手が入った。戻す手順は当てない。書きかけで落ちたなら、"
                     "同じ入力でもう一度回して書き終えてから戻す手順を当てる（ほかの手が入ったなら事務所の担当者に確かめる）")
    return 外


# ---------------------------------------------------------------- 戻す手順（組む 1 か所と、当てる前の照らし）
# 戻す手順の頭（形を照らす）の 3 つの形と、本体の手順が触る物。形と書きかけからの戻し方の正本は 戻す手順を組む
#   タブ: {"する": "形を照らす", "ファイル", "タブ", "行の数", "指紋"}   md: {"する": "形を照らす", "md", "指紋"}
#   在る: {"する": "形を照らす", "在る": <file・置き場の名>}（file を移す の前の名が在る）
_タブを触る = ("値を書く", "行を足す", "行を消す", "タブを消す")
_頭の要らない = ("置き場の行を書く", "置き場の行を消す")   # 事務所の設定「置き場」の 1 行を鍵で書き戻す（何度当てても同じ）


def _指紋(本文) -> str:
    return hashlib.sha256(str(本文 if 本文 is not None else "").encode("utf-8")).hexdigest()


def _触る物(x) -> tuple | None:
    """本体の手順 1 つが触る物 → ("タブ", ファイル, タブ)・("名", 名)・None（頭の要らない手順）。知らない「する」は止める。"""
    k = x.get("する") if isinstance(x, dict) else None
    if k in _タブを触る:
        return ("タブ", x.get("ファイル"), x.get("タブ"))
    if k == "タブの名を変える":
        return ("タブ", x.get("ファイル"), x.get("前"))
    if k == "タブを足す":
        return ("名", x.get("ファイル"))
    if k == "file を移す":
        return ("名", x.get("前"))
    if k in _頭の要らない:
        return None
    raise 台帳へ書く誤り(f"戻す手順に知らない「する」: {k!r}（組めない＝既定で止める）")


def _作る物(x) -> list[tuple]:
    k = x.get("する")
    if k == "タブの名を変える":
        return [("タブ", x.get("ファイル"), x.get("後"))]
    if k == "タブを足す":
        return [("タブ", x.get("ファイル"), x.get("タブ"))]
    if k == "file を移す":
        return [("名", x.get("後"))]
    return []


def _頭の物(h: dict) -> tuple:
    if "md" in h:
        return ("名", h["md"])
    if "在る" in h:
        return ("名", h["在る"])
    return ("タブ", h.get("ファイル"), h.get("タブ"))


def _今を開く(今) -> tuple[dict, dict, list] | None:
    """今 → (シート {ファイル: {タブ: 値}}, md {名: 本文}, 置き場 [名])。{タブ: 値} の 1 つの台帳の形なら None。"""
    if isinstance(今, dict) and isinstance(今.get("シート"), dict) and all(isinstance(v, dict) for v in 今["シート"].values()):
        return 今["シート"], dict(今.get("md") or {}), list(今.get("置き場") or [])
    return None


def _在るか(名: str, シート: dict, md: dict, 置き場: list) -> bool:
    名たち = [*シート, *md, *置き場]
    return 名 in 名たち or (str(名).endswith("/") and any(str(k).startswith(名) for k in 名たち))


def 戻す手順を組む(書いた後: dict, 本体: list[dict]) -> list[dict]:
    """戻す手順を組む 1 か所。書いた後（書く手順を全部当てた後の {"シート": {ファイル: {タブ: 値}}, "md": {名: 本文}, "置き場": [名]}）と
    戻す本体（書く前へ戻す手順の並び）→ 頭に本体が触る物ごとの 形を照らす を置いた並び。本体が書いた後に無い物を触る（前の手順が
    作る物でもない）・知らない「する」を持つ時は 台帳へ書く誤り（組めない＝戻す手順を出さない）。本体が空なら空。"""
    if not 本体:
        return []
    開 = _今を開く(書いた後)
    if 開 is None:
        raise 台帳へ書く誤り("戻す手順を組む の 書いた後 は {\"シート\": {ファイル: {タブ: 値}}, \"md\": …} の形")
    シート, md, 置き場 = 開
    頭, 見た, 作った = [], set(), set()
    for x in 本体:
        物 = _触る物(x)
        if 物 is not None and 物 not in 作った and 物 not in 見た:
            if 物[0] == "タブ":
                if 物[2] not in シート.get(物[1], {}):
                    raise 台帳へ書く誤り(f"戻す手順が書いた後に無いタブ {物[1]}/{物[2]} を触る（{x.get('する')}）")
                頭.append({"する": "形を照らす", "ファイル": 物[1], "タブ": 物[2], **タブの形(シート[物[1]][物[2]])})
            elif 物[1] in md:
                頭.append({"する": "形を照らす", "md": 物[1], "指紋": _指紋(md[物[1]])})
            elif _在るか(物[1], シート, md, 置き場):
                頭.append({"する": "形を照らす", "在る": 物[1]})
            else:
                raise 台帳へ書く誤り(f"戻す手順が書いた後に無い {物[1]} を触る（{x.get('する')}）")
            見た.add(物)
        作った.update(_作る物(x))
    return [*頭, *本体]


def 戻す手順を照らす(今, 手順) -> list[str]:
    """殻が戻す手順を当てる前に呼ぶ 1 か所 → 外れの訳（空なら当ててよい・空でなければ 1 つも当てない）。
    今は 〔口: シートを読む〕などで読んだままの {"シート": {ファイル: {タブ: 値}}, "md": {名: 本文}, "置き場": [名]} の 1 つの形だけ
    （{タブ: 値} は頭の「ファイル」を照らせない＝止める）。頭（形を照らす）の無い手順・頭の後ろに頭がある手順・頭の無い物を触る手順・
    知らない「する」・今 md の物を 在る の頭で名指す手順（md は指紋の頭だけ＝在るだけでは中身を見ない）は止める。"""
    手順 = list(手順 or ())
    if not 手順:
        return []
    開 = _今を開く(今)
    if 開 is None:
        return ["今が {タブ: 値} の形＝頭の「ファイル」を照らせない。戻す手順は {\"シート\": {ファイル: {タブ: 値}}, \"md\", \"置き場\"} で渡す＝当てない"]
    n = _頭の数(手順)
    if n == 0:
        return ["頭（形を照らす）の無い戻す手順＝当てない（戻す手順は `月次/台帳へ書く.戻す手順を組む` で組んだ物だけ）"]
    頭 = {_頭の物(h) for h in 手順[:n]}
    外 = [f"md {h['在る']} を 在る の頭で名指す（md の頭は指紋だけ＝`戻す手順を組む` で組み直す）＝当てない"
         for h in 手順[:n] if "在る" in h and h["在る"] in 開[1]]
    作った = set()
    for x in 手順[n:]:
        if isinstance(x, dict) and x.get("する") == "形を照らす":
            外.append("形を照らす が頭の後ろに在る（頭は手順の先頭にまとめる）")
            continue
        try:
            物 = _触る物(x)
        except 台帳へ書く誤り as e:
            外.append(str(e))
            continue
        if 物 is not None and 物 not in 頭 and 物 not in 作った:
            外.append(f"頭の無い物を触る手順（{x.get('する')} {'/'.join(str(v) for v in 物[1:])}）＝当てない")
        作った.update(_作る物(x))
    return 外 + 形を照らす(今, 手順[:n])


def _頭の数(手順: list) -> int:
    return next((i for i, x in enumerate(手順) if not (isinstance(x, dict) and x.get("する") == "形を照らす")), len(手順))


def 戻す手順の本体(手順) -> list[dict]:
    """戻す手順 → 先頭の頭（形を照らす）を除いた本体（`戻す手順を組む` に渡した並び）。戻す手順の中身を読む・比べる所はここを呼ぶ
    （頭を除く読み方を写さない）。頭が無い手順はそのまま返す＝頭の有る無しは `戻す手順を照らす` が照らす。"""
    手順 = list(手順 or ())
    return 手順[_頭の数(手順):]


def _年(台帳の名: str) -> int:
    m = re.fullmatch(re.escape(形.台帳).replace(re.escape("<支給年>"), r"(\d{4})"), str(台帳の名 or ""))
    if not m:
        raise 台帳へ書く誤り(f"台帳の名「{台帳の名}」は {形.台帳}（例 台帳_2027）")
    return int(m.group(1))


def _格子か(タブ: str, 表, 何: str) -> list[list]:
    if not isinstance(表, (list, tuple)) or not 表 or not all(isinstance(r, (list, tuple)) for r in 表):
        raise 台帳へ書く誤り(f"{タブ}: {何}は get_values の形（1 行目が見出しの 2 次元の並び）で渡す（dict の並び・見出しの無い表は受けない）")
    return [list(r) for r in 表]


def 今の見出しを照らす(タブ: str, 今の値) -> list[str]:
    """書く先の今のタブ（get_values）の 1 行目が型の見出しと同じか。違えば止める（違いを 1 行ずつ）。返すのは型の見出し。"""
    h = 形.見出し(タブ)
    今 = _格子か(タブ, 今の値, "書く先の今のタブ")
    見 = ["" if c is None else str(c) for c in 今[0]]   # 字のまま照らす（前後の空白を落とさない＝空白の付いた見出しへ書かない）
    while 見 and not 見[-1].strip():   # get_values は後ろの空のセルを返さない・空の見出しの後ろは見ない
        見.pop()
    違い = 形.型の口().見出しの違い(*形.タブたち[タブ], 見)
    if 違い:
        raise 台帳へ書く誤り(f"{タブ}: 書く先の見出しが型と違う（{'・'.join(違い)}）。書かない＝台帳の見出しを今の型へそろえてから書く")
    return h


def _表を照らす(タブ: str, 表, 年: int) -> list[list[str]]:
    """渡した表（パックの口が返した表）の見出し・書き方・支給月の年・同じ鍵の行を照らす → 字の行の並び（見出しを除く）。"""
    h = 形.見出し(タブ)
    xs = _格子か(タブ, 表, "書く表")
    if [_字(c) for c in xs[0]] != h:
        raise 台帳へ書く誤り(f"{タブ}: 書く表の見出しが型と違う（{xs[0]} ≠ {h}）。パックの口が返した表をそのまま渡す（列を手で組まない）")
    out, 鍵たち = [], set()
    for r in xs[1:]:
        if len(r) > len(h) and any(_字(v) for v in r[len(h):]):
            raise 台帳へ書く誤り(f"{タブ}: 見出しの外の列に値の在る行 {r}")
        行 = [_字(r[i]) if i < len(r) else "" for i in range(len(h))]
        if not any(行):
            continue
        d = dict(zip(h, 行))
        ずれ = 形.書き方のずれ(タブ, h, 行)
        if ずれ:
            raise 台帳へ書く誤り(f"{タブ}: NO {d.get('NO', '')} {d.get('日付', '')} の書き方が型と違う {ずれ}")
        y = 支給月の字.読む(d.get("支給月"))
        if y is None:
            raise 台帳へ書く誤り(f"{タブ}: 支給月「{d.get('支給月')}」が読めない")
        # その月だけの指示 は 12 月を回した 次の月（翌年 1 月）の行を同じ台帳に書く（新しい年の台帳を起こす が移す）
        if y[0] != 年 and not (タブ == "その月だけの指示" and y == (年 + 1, 1)):
            raise 台帳へ書く誤り(f"{タブ}: 支給月「{d['支給月']}」の行は {形.台帳.replace('<支給年>', str(年))} に書かない（行の支給月の年の台帳へ）")
        鍵の列 = 行の鍵の列.get(タブ, ("会社", "支給月", "NO"))
        空 = [c for c in 鍵の列 if not d.get(c)]
        if 空:
            raise 台帳へ書く誤り(f"{タブ}: 鍵の列 {空} が空の行 {行}")
        if タブ in 行の鍵の列:
            k = _鍵(d, 鍵の列)
            if k in 鍵たち:
                raise 台帳へ書く誤り(f"{タブ}: 同じ鍵 {dict(zip(鍵の列, (d[c] for c in 鍵の列)))} の行が 2 つ")
            鍵たち.add(k)
        out.append(行)
    return out


# ---------------------------------------------------------------- 関所（写しの列を埋めて照らす 1 か所・どの口もここを通る）
class _通した表:
    """関所（`_通す`・`_勤怠を通す`）が返す、書いてよい行の並びとそのタブ（作り手を縛る鍵は 2026-11-27 に畳んだ）。"""
    __slots__ = ("タブ", "行たち")

    def __init__(self, タブ: str, 行たち: list[list[str]]):
        self.タブ, self.行たち = タブ, 行たち


def _通した表か(x, タブ: str) -> list[list[str]]:
    if x.タブ != タブ:
        raise 台帳へ書く誤り(f"{タブ}: 別のタブ（{x.タブ}）の表は書かない")
    return x.行たち


def _通す(タブ: str, 表, 年: int, 名: dict[tuple[str, str], str]) -> _通した表:
    """日と区間のタブの外（人ごとの月の数字・その月だけの指示・締めの記録・賞与の支給一覧）の関所。
    表の見出し・書き方・年・鍵を照らし、氏名 を社員から埋めて照らす（厳しく＝空なら埋め・違えば止め・社員に居ない NO と
    社員の氏名が空の行は止める）。名: {(会社, NO): 氏名}（`_社員の氏名`）。"""
    if タブ in (*日のタブ, *区間のタブ):
        raise 台帳へ書く誤り(f"{タブ}: 日と区間のタブは 勤怠 の関所（_勤怠を通す）で通す")
    h = 形.見出し(タブ)
    out = []
    for r in _表を照らす(タブ, 表, 年):
        d = dict(zip(h, r))
        if タブ == "人ごとの月の数字" and d.get("状態") not in 人ごとの状態:
            raise 台帳へ書く誤り(f"{タブ}: NO {d['NO']} の 状態「{d.get('状態')}」は {'・'.join(人ごとの状態)}（集計が書く）")
        氏名 = {no: n for (c, no), n in 名.items() if c == d.get("会社")}
        try:
            [d] = 形.氏名を埋める(タブ, [d], 氏名, 厳しく=True)
        except 形.台帳の形の誤り as e:
            raise 台帳へ書く誤り(str(e)) from e
        out.append([形.値の字(d.get(c)) for c in h])
    return _通した表(タブ, out)


def _勤怠を通す(*, 確定: bool, 行たち, 区間たち, 年: int, 名: dict[tuple[str, str], str], 原本のリンク, 日の要約) -> dict[str, _通した表]:
    """日と区間のタブの関所。写しの列（氏名・曜日・出勤と退勤の時刻・休憩と労働の合計・原本のリンク）を
    台帳の形.勤怠の表たち（厳しく=True）で埋めて照らし、表の見出し・書き方・年・鍵を照らす。"""
    if not isinstance(原本のリンク, dict):
        raise 台帳へ書く誤り("原本のリンク（{原本の名前: 原本の在り処}）を渡す（原本のリンクは置き場から口が書く＝窓が書かない）")
    会社, _ = _一つの月([*行たち, *区間たち], "勤怠")
    氏名 = {no: n for (c, no), n in 名.items() if c == 会社}
    try:
        表 = 形.勤怠の表たち(確定=確定, 勤怠=行たち, 勤怠の区間=区間たち, 氏名=氏名, 日の要約=日の要約, 厳しく=True,
                       原本のリンク=原本のリンク)
    except 形.台帳の形の誤り as e:
        raise 台帳へ書く誤り(str(e)) from e
    return {タブ: _通した表(タブ, _表を照らす(タブ, t, 年)) for タブ, t in 表.items()}


def _鍵(d: dict, 列たち) -> tuple:
    return tuple(支給月の字.読む(d.get(c)) if c == "支給月" else _字(d.get(c)) for c in 列たち)


# ---------------------------------------------------------------- 手順を組む（1 か所）
def _タブの手順(ファイル: str, 通した: _通した表, 今の値, 単位たち: set | None = None) -> tuple[list[dict], list[list[str]]]:
    """今のタブ（get_values）に、関所を通した行を単位で置き換えて書く手順と、書いた後のタブの値（読み直して照らす元）。

    単位の同じ今の行を上から渡した行で上書きし、余る渡した行は足し、余る今の行は下から消す。単位の外の行は触らない。"""
    タブ = getattr(通した, "タブ", "")
    行たち = _通した表か(通した, タブ)
    h = 今の見出しを照らす(タブ, 今の値)
    今 = [[_字(r[i]) if i < len(r) else "" for i in range(len(h))] for r in _格子か(タブ, 今の値, "書く先の今のタブ")[1:]]
    単位 = 単位の列[タブ]
    if 単位たち is None:
        単位たち = {_鍵(dict(zip(h, r)), 単位) for r in 行たち}
    当たる = [i for i, r in enumerate(今) if any(r) and _鍵(dict(zip(h, r)), 単位) in 単位たち]
    後 = [list(h), *[list(r) for r in 今]]
    書く = []
    for i, r in zip(当たる, 行たち):
        if 後[i + 1] != r:
            後[i + 1] = list(r)
            書く.append(i)
    手順 = []
    for 始め, 終わり in _続き(書く):
        手順.append({"する": "値を書く", "ファイル": ファイル, "タブ": タブ,
                   "範囲": f"A{始め + 2}:{列の字(len(h))}{終わり + 2}", "値": [list(後[i + 1]) for i in range(始め, 終わり + 1)],
                   "書き方": 字のまま})
    足す = [list(r) for r in 行たち[len(当たる):]]
    if 足す:
        手順.append({"する": "行を足す", "ファイル": ファイル, "タブ": タブ, "値": 足す, "書き方": 字のまま})
        後 += 足す
    for i in sorted(当たる[len(行たち):], reverse=True):
        手順.append({"する": "行を消す", "ファイル": ファイル, "タブ": タブ, "行": i + 2})
        del 後[i + 1]
    return 手順, 後


def _続き(xs: list[int]) -> list[tuple[int, int]]:
    out = []
    for i in sorted(xs):
        if out and out[-1][1] == i - 1:
            out[-1] = (out[-1][0], i)
        else:
            out.append((i, i))
    return out


def _社員の氏名(社員) -> dict[tuple[str, str], str]:
    """マスタ「社員」（get_values の形か列名の dict の並び）→ {(会社, NO): 氏名}。"""
    if 社員 is None:
        raise 台帳へ書く誤り("社員（マスタ「社員」）を渡す（氏名の写しは口が社員から書く＝窓が書かない）")
    return {(_字(r.get("会社")), _字(r.get("NO"))): _字(r.get("氏名")) for r in 形.行たち(社員)}


def _今のタブ(今の台帳, タブ: str):
    if not isinstance(今の台帳, dict):
        raise 台帳へ書く誤り("今の台帳は {タブの名: get_values の値} で渡す（書く先の今の見出しと行を照らす）")
    if タブ not in 今の台帳:
        raise 台帳へ書く誤り(f"{タブ}: 書く先の台帳にタブが無い（今の台帳に {タブ} の get_values を渡す。無いタブは今の型で足す）")
    return 今の台帳[タブ]


# ---------------------------------------------------------------- 口
def 台帳の年(台帳の名: str) -> int:
    """台帳の名（台帳_<支給年>）→ 支給年。名の形が違えば止める（ほかの口と同じ読み）。"""
    return _年(台帳の名)


def 締めの記録の行(書く行, *, 台帳の名: str, 社員) -> list[list[str]]:
    """締めの関所.締める の `書く行` → 台帳「締めの記録」へ足す行。ほかのタブと同じ関所を通し（見出し・年・鍵）、
    氏名 は社員から埋めて照らす（空なら埋め・違えば止め・社員に居ない NO は止める）。"""
    return [list(r) for r in _通す("締めの記録", 形.表にする("締めの記録", 書く行), _年(台帳の名), _社員の氏名(社員)).行たち]


def 新しい台帳(起こした: dict, *, 今ある名=(), 社員) -> list[dict]:
    """年の台帳を起こす.起こす の返す物 → 会社の根に新しい年の台帳を作り、8 タブ（見出しと引き継ぐ行）を書く手順。

    今ある名: 受けるが照らさない（同じ名の台帳の止めは 2026-11-27 に畳んだ。新しいシートを作るだけで在る台帳を上書きしない）。
    社員: マスタ「社員」（必ず渡す）。引き継ぐ行は ほかの口と同じ関所を通す（氏名を空なら埋め・違えば止め・社員に居ない NO は止める）。
    日と区間のタブに引き継ぐ行が在れば止める（勤怠 の口は支給月の年の台帳へだけ書く＝前の年の台帳に新しい年の勤怠の行は手で書いた行）。"""
    名 = 起こした.get("台帳の名")
    年 = _年(名)
    社員の名 = _社員の氏名(社員)
    タブ = 起こした.get("タブ") or {}
    if list(タブ) != list(台帳のタブ):
        raise 台帳へ書く誤り(f"起こした台帳のタブ {list(タブ)} が型の 8 タブ {list(台帳のタブ)} と違う（起こす の返す物をそのまま渡す）")
    通した = {}
    for k in 台帳のタブ:
        if k in (*日のタブ, *区間のタブ):
            行 = _表を照らす(k, タブ[k], 年)
            if 行:
                raise 台帳へ書く誤り(f"{k}: 前の年の台帳に {年} 年の支給月の行が {len(行)} 行在る（勤怠 の口は支給月の年の台帳へだけ書く＝"
                                 "手で書いた行）。前の年の台帳から消し、新しい台帳を起こしてから 月次.台帳へ書く.勤怠 で書く")
            通した[k] = _通した表(k, [])
        else:
            通した[k] = _通す(k, タブ[k], 年, 社員の名)
    手順 = [{"する": "スプレッドシートを作る", "根": "会社の根", "名": 名, "タブ": 台帳のタブ[0]}]
    手順 += [{"する": "タブを足す", "ファイル": 名, "タブ": k} for k in 台帳のタブ[1:]]
    for k in 台帳のタブ:
        行 = _通した表か(通した[k], k)
        h = 形.見出し(k)
        手順.append({"する": "値を書く", "ファイル": 名, "タブ": k, "範囲": f"A1:{列の字(len(h))}{len(行) + 1}",
                   "値": [list(h), *行], "書き方": 字のまま})
    return 手順


def 月の台帳(台帳: dict, *, 今の台帳, 台帳の名: str, 社員) -> dict:
    """月を回す の返す `台帳`（{人ごとの月の数字: 表, その月だけの指示: 表}）→ 在る年の台帳へ書く手順。

    今の台帳: {タブ: get_values}（書くタブの全部）。社員: マスタ「社員」（氏名の写しを照らす）。
    返す物: {書く手順: [...], 書いた後: {タブ: 書いた後の値}}（書いた後の読み直しの照らしは 2026-11-27 に畳んだ）。"""
    年 = _年(台帳の名)
    if not isinstance(台帳, dict) or not 台帳:
        raise 台帳へ書く誤り("台帳（月を回す の返す `台帳`）を渡す")
    外 = sorted(k for k in 台帳 if k not in 月の台帳のタブ)
    if 外:
        raise 台帳へ書く誤り(f"月の台帳へ書くのは {'・'.join(月の台帳のタブ)} だけ（{外} は 勤怠・新しい台帳 の口で書く）")
    会社たち = {_字(r[形.見出し(k).index("会社")]) for k in 月の台帳のタブ if k in 台帳
              for r in _格子か(k, 台帳[k], "書く表")[1:] if any(_字(v) for v in r)}
    if len(会社たち) > 1:
        raise 台帳へ書く誤り(f"月の台帳は 1 回に 1 つの会社だけを渡す（今は {sorted(会社たち)}）")
    名 = _社員の氏名(社員)
    手順, 後 = [], {}
    for タブ in 月の台帳のタブ:
        if タブ not in 台帳:
            continue
        通した, 今 = _通す(タブ, 台帳[タブ], 年, 名), _今のタブ(今の台帳, タブ)
        単位たち = _立て替えの残りの単位(台帳, 通した, 今) if タブ == "その月だけの指示" else None
        x, 後[タブ] = _タブの手順(台帳の名, 通した, 今, 単位たち=単位たち)
        手順 += x
    return {"書く手順": 手順, "書いた後": 後}


def _立て替えの残りの単位(台帳: dict, 通した: _通した表, 今) -> set:
    """その月だけの指示 の置き換える単位。渡した行の (会社, 支給月, NO, 項目) に、回した会社×次の支給月の 立て替えの残り の
    今の行を全部足す（月次が書く項目＝回し直しで仮へ落ちた人の前の回の残りも消す。人が書いた他の項目の行は触らない）。
    回した会社×支給月は 人ごとの月の数字（仮の人も行が在る）の次の支給月と、渡した 立て替えの残り の行の支給月から引く
    （関所を通った人が 0 人で 立て替えの残り の表が見出しだけでも、その月の前の回の行を消す）。"""
    h = 形.見出し("その月だけの指示")
    行たち = _通した表か(通した, "その月だけの指示")
    単位 = 単位の列["その月だけの指示"]
    単位たち = {_鍵(dict(zip(h, r)), 単位) for r in 行たち}
    月たち = {_鍵(d, ("会社", "支給月")) for d in (dict(zip(h, r)) for r in 行たち) if _字(d.get("項目")) == 立て替えの残り}
    if "人ごとの月の数字" in 台帳:
        月たち |= {(_字(d.get("会社")), 支給月の字.読む(支給月の字.ずらす(d.get("支給月"), 1)))
                 for d in 形.行たち(台帳["人ごとの月の数字"]) if any(_字(v) for v in d.values())}
    格子 = _格子か("その月だけの指示", 今, "書く先の今のタブ")
    for r in 格子[1:]:
        d = dict(zip([_字(c) for c in 格子[0]], r))
        if _字(d.get("項目")) == 立て替えの残り and _鍵(d, ("会社", "支給月")) in 月たち:
            単位たち.add(_鍵(d, 単位))
    return 単位たち


def _一つの月(行たち, 何: str) -> tuple[str, tuple]:
    月たち = {(_字(r.get("会社")), 支給月の字.読む(r.get("支給月"))) for r in 行たち}
    if len(月たち) != 1 or None in {m for _, m in 月たち}:
        raise 台帳へ書く誤り(f"{何}は 1 回に 1 つの会社×支給月だけを渡す（今は {sorted(月たち, key=str)}）")
    return next(iter(月たち))


def 勤怠(*, 確定: bool, 勤怠, 勤怠の区間, 今の台帳, 台帳の名: str, 社員, 原本のリンク: dict, 日の要約=None) -> dict:
    """年の台帳の 読んだままの勤怠（確定=False）か 確定した勤怠（確定=True）の日と区間 → 書く手順（その日の行と区間を置き換える）。

    勤怠・勤怠の区間: 書く日の行と、その日の区間の全部（dict の並びか get_values の形。読んだままの勤怠を作る・答えを確定した勤怠へ の
      返す表もそのまま渡せる）。1 回に 1 つの会社×支給月。写しの列（氏名・曜日・出勤の時刻・退勤の時刻・休憩の合計・労働の合計・
      原本のリンク）は口が埋める＝空で渡すか道具の値のまま（違う値は止める）。
    社員: マスタ「社員」（氏名の元）。原本のリンク: {原本の名前: 原本の在り処}（〔口: 置き場を引く〕の置き場の一覧から・必ず渡す。
      原本の種別 が種類 ファイル の行は、名が空・その名の在り処が無ければ止める。原本の名前が容器なら止める＝中の file の名を渡す。
      種類 所定どおり の行〔file が無い日〕は名が空・リンクも空）。
    日の要約: 月を回す の返す `日の要約`（芯の数え）。渡した時だけ 休憩の合計・労働の合計 を書く（無ければ空＝窓は書かない）。
    返す物: {書く手順, 書いた後}（月の台帳 と同じ）。確定した勤怠で書く日の行が 0 なら書く手順は 0（答えを確定した勤怠へ の
      見出しだけの表をそのまま渡せる＝殻が空かを分けない）。読んだままの勤怠で日の行が 0 は止める（読んだ月に日が無い＝読み損ね）。"""
    年 = _年(台帳の名)
    日, 区 = (日のタブ[1], 区間のタブ[1]) if 確定 else (日のタブ[0], 区間のタブ[0])
    行たち, 区間たち = 形.行たち(勤怠), 形.行たち(勤怠の区間)
    if not 行たち and not 確定:
        raise 台帳へ書く誤り(f"{日}: 書く日の行が無い（読んだままの勤怠は読んだ月の日を全部渡す）")
    if 行たち or 区間たち:
        _一つの月([*行たち, *区間たち], f"{日}・{区}")
    日たち = {_鍵(r, 単位の列[日]) for r in 行たち}
    外 = sorted({_鍵(r, 単位の列[区]) for r in 区間たち} - 日たち, key=str)
    if 外:
        raise 台帳へ書く誤り(f"{区}: 日の行の無い区間 {外}（区間は書く日の全部と一緒に渡す）")
    if 行たち:
        通した = _勤怠を通す(確定=確定, 行たち=行たち, 区間たち=区間たち, 年=年, 名=_社員の氏名(社員), 原本のリンク=原本のリンク,
                        日の要約=日の要約)
    else:   # 日の行が 0（答えで変わった日が無い）は書く手順 0（今のタブの見出しは照らす）
        通した = {タブ: _通した表(タブ, []) for タブ in (日, 区)}
    手順, 後 = [], {}
    for タブ in (日, 区):
        x, 後[タブ] = _タブの手順(台帳の名, 通した[タブ], _今のタブ(今の台帳, タブ), 単位たち=日たち)
        手順 += x
    return {"書く手順": 手順, "書いた後": 後}


def 日の要約を書く(日の要約, *, 今の台帳, 台帳の名: str, 社員, 原本のリンク: dict) -> dict:
    """月を回す の返す `日の要約`（芯が数えた日の休憩と労働）→ 年の台帳の 確定した勤怠 の 休憩の合計・労働の合計 を書く手順。

    今の台帳の 確定した勤怠・その区間 から、日の要約の会社×支給月の行を口が選んで 勤怠(確定=True, 日の要約=…) に通す
    （窓は行を選ばない・値を組まない）。読んだままの勤怠には書かない（芯が数えたのは確定した勤怠）。"""
    要約 = list(日の要約 or ())
    if not 要約:
        raise 台帳へ書く誤り("日の要約（月を回す の返す `日の要約`）が空")
    会社, 月 = _一つの月(要約, "日の要約")
    日, 区 = 日のタブ[1], 区間のタブ[1]
    今の日 = _今のタブ(今の台帳, 日)
    今の区 = _今のタブ(今の台帳, 区)
    今の見出しを照らす(日, 今の日)
    今の見出しを照らす(区, 今の区)

    def その月(表):
        return [r for r in 形.行たち(表) if _字(r.get("会社")) == 会社 and 支給月の字.読む(r.get("支給月")) == 月]
    行たち = その月(今の日)
    if not 行たち:
        raise 台帳へ書く誤り(f"{日}: {会社} の {支給月の字.字にする(*月, '殻')} の行が無い（確定した勤怠を書いてから 月を回す）")
    return 勤怠(確定=True, 勤怠=行たち, 勤怠の区間=その月(今の区), 今の台帳=今の台帳, 台帳の名=台帳の名, 社員=社員,
              原本のリンク=原本のリンク, 日の要約=要約)
