"""問いの取り下げ — 配った確認事項の問いを下げる手順を返す口（質問と回答 に `取り下げ→<訳>` の行・管理表の 確認ページ の状況を 取り下げ）。

なぜ在るか（2026-11-27 オーナー: 問いを下げる時も決まった口で）: パックは 質問と回答 の回答が `取り下げ→<訳>` で始まる行を
閉じた問いとして読む（設問.閉じた答え）が、その行を書く口が無く、管理表の 状況＝取り下げ はどのコードも読まなかった
（変えても確認ページは答えを受け付けたまま）。ここは値を決めて手順を返すだけで、事務所の置き場を開かない。殻が当てる。

決め方（問いの番号ごとに、その会社の一番下の行を見る）:
  - 行が無い＝止める。もう `取り下げ→` で始まる＝何もしない（何度当てても同じ）。`出し直し→` で閉じた＝何もしない（知らせ）。
  - 回答が空＝その行へ 回答 `取り下げ→<訳>（版 <版>）`・回答日 を書く。
  - 回答が 決まり切らない（分からない など）＝行を足す（前の行は残す・反映済みは空）。
  - 答えが届いた＝止める（先に〔口: 答えを受け取る〕で書き戻す。答えを黙って捨てない）。
  - 管理表 確認ページ: 会社と確認ページの URL の行。状況が 取り下げ＝何もしない・答えた／差し替え＝止める・
    問いの数が下げる問いの数より多い＝状況は変えない（残る問いへの答えは受け付ける・知らせ）・ほか＝状況を 取り下げ。
  - 確認ページの受付を止めるのは 確認ページ.貼り戻し（下げた問いへの後の答えは書かず知らせ）。
  - 赤が 1 つでも在れば手順は 0（ひとまとまりで当てる）。
返す物: {手順 (質問と回答「質問」への 値を書く・行を足す), 管理表の行 [確認ページ タブの行], 記録 [{問いの番号, する}], 知らせ, 赤}。
"""
from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent
if str(根) not in sys.path:
    sys.path.insert(0, str(根))


def _読み込む(名: str, path: Path):
    if 名 in sys.modules:
        return sys.modules[名]
    spec = importlib.util.spec_from_file_location(名, path)
    m = importlib.util.module_from_spec(spec)
    sys.modules[名] = m
    spec.loader.exec_module(m)
    return m


戻 = _読み込む("月次_答えの書き戻し", ここ / "答えの書き戻し.py")   # 手順の形・当て方・閉じた答えの読みの正本
設問, 口 = 戻.設問, 戻.口
前の答え = _読み込む("取り下げ_前の答え", 根 / "確認ページ" / "前の答え.py")   # 鍵・決まり切らない の正本
頁 = _読み込む("取り下げ_確認ページ", 根 / "確認ページ" / "確認ページ.py")
_表 = 頁.表
頭 = 頁.取り下げの頭
_質問と回答, _問いのタブ = 戻.質問と回答の名, 戻.問いのタブ


def _字(v) -> str:
    return "" if v is None else str(v).strip()


def _鍵(番号) -> str:
    return 前の答え.鍵(番号)


def _台帳の行(確認ページの行たち, 会社: str, 確認ページ: str, 数: int, 赤: list, 知らせ: list) -> list[dict]:
    格 = 戻.格子(確認ページの行たち, "確認ページの行たち（管理表「確認ページ」）")
    h = 格[0]
    for c in ("会社", "載せた日", "確認ページ", "問いの数", "状況"):
        if c not in h:
            赤.append(f"管理表「確認ページ」に見出し {c} が無い")
            return []
    行たち = [dict(zip(h, r)) for r in 格[1:] if r[h.index("会社")] == 会社 and r[h.index("確認ページ")] == 確認ページ]
    if not 行たち:
        赤.append("管理表「確認ページ」にその会社のその確認ページの行が無い＝受付を止めた印を書けない（配った版の URL を渡す）")
        return []
    行 = 行たち[-1]
    状 = 行["状況"]
    if 状 == _表.値の字("確認ページ", "状況", "取り下げ"):
        return []
    if 状 == _表.値の字("確認ページ", "状況", "答えた"):
        赤.append("その確認ページはもうお答えいただいた＝下げない（先に〔口: 答えを受け取る〕で書き戻す）")
        return []
    if 状 == _表.値の字("確認ページ", "状況", "差し替え"):
        赤.append("その確認ページは差し替えた前の版＝今配っている版の URL を渡す")
        return []
    try:
        全 = int(行["問いの数"] or 0)
    except ValueError:
        全 = 0
    if 全 > 数:
        知らせ.append(f"確認ページの問い {全} のうち {数} を下げた＝残る問いへの答えは受け付ける（状況は変えない）")
        return []
    return [頁.取り下げの行(行)]


def 取り下げの手順(質問の行たち, 会社: str, 問いの番号たち, 訳: str, *, 今日: str, 版: str | None = None,
              確認ページの行たち=None, 確認ページ: str | None = None) -> dict:
    赤, 知らせ, 手順, 記録 = [], [], [], []
    訳 = _字(訳)
    if not 訳:
        赤.append("取り下げの訳が空＝なぜ下げたかを 1 行で渡す")
    if "\n" in 訳 or "／" in 訳:
        赤.append("取り下げの訳は 1 行で（改行と ／ は使わない）")
    if 版 is not None and not 頁.版の字の形.fullmatch(_字(版)):
        赤.append(f"版 {版!r} は 版の字（YYYY.MM-v<n>）でない")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", _字(今日)):
        赤.append(f"今日 {今日!r} は YYYY-MM-DD でない")
    番号たち = [_字(x) for x in (問いの番号たち or []) if _字(x)]
    if not 番号たち:
        赤.append("下げる問いの番号が無い")
    格 = 戻.格子(質問の行たち, "質問の行たち")
    h = 格[0]
    for c in ("会社", "問いの番号", "回答", "回答日"):
        if c not in h:
            赤.append(f"質問と回答「質問」に見出し {c} が無い")
    if 赤:
        return {"手順": [], "管理表の行": [], "記録": [], "知らせ": 知らせ, "赤": 赤}
    ix = {c: h.index(c) for c in h}
    回答の字 = f"{頭}{訳}" + (f"（版 {_字(版)}）" if 版 else "")
    for 番号 in dict.fromkeys(番号たち):
        i = max((i for i, r in enumerate(格[1:], 2) if _鍵(r[ix["問いの番号"]]) == _鍵(番号)
                 and r[ix["会社"]] in ("", 会社)), default=None)
        if i is None:
            赤.append(f"{番号} : 質問と回答 に無い問い＝下げられない")
            continue
        行 = list(格[i - 1])
        回答 = 行[ix["回答"]]
        if 回答.startswith(頭):
            continue
        if 設問.閉じた答え(回答):
            知らせ.append(f"{番号} : もう閉じた問い（{回答}）＝書かない")
            continue
        新 = list(行)
        新[ix["回答"]], 新[ix["回答日"]] = 回答の字, _字(今日)
        if "反映済み" in ix:
            新[ix["反映済み"]] = ""
        if not 回答:
            手順.append(戻.値を書く(_質問と回答, _問いのタブ, i, 新))
            記録.append({"問いの番号": 番号, "する": "値を書く"})
        elif 前の答え.決まり切らない({c: 行[ix[c]] for c in h}):   # 行ごと渡す（選択肢を読む）
            手順.append(戻.行を足す(_質問と回答, _問いのタブ, 新))
            記録.append({"問いの番号": 番号, "する": "行を足す"})
        else:
            赤.append(f"{番号} : 答えが届いた＝下げない（先に〔口: 答えを受け取る〕で書き戻す）")
    管理表の行 = []
    if 確認ページ is not None or 確認ページの行たち is not None:
        if not _字(確認ページ) or 確認ページの行たち is None:
            赤.append("確認ページの受付を止めるには 確認ページ（配った版の URL）と 確認ページの行たち を両方渡す")
        else:
            管理表の行 = _台帳の行(確認ページの行たち, 会社, _字(確認ページ), len(dict.fromkeys(番号たち)), 赤, 知らせ)
    if 赤:
        return {"手順": [], "管理表の行": [], "記録": [], "知らせ": 知らせ, "赤": 赤}
    return {"手順": 手順, "管理表の行": 管理表の行, "記録": 記録, "知らせ": 知らせ, "赤": []}


def _口(入力: dict) -> dict:
    return 取り下げの手順(入力["質問の行たち"], 入力["会社"], 入力["問いの番号たち"], 入力.get("訳", ""), 今日=入力["今日"],
                   版=入力.get("版"), 確認ページの行たち=入力.get("確認ページの行たち"), 確認ページ=入力.get("確認ページ"))


if __name__ == "__main__":
    try:
        out = _口(json.load(sys.stdin))
    except (戻.書き戻しの誤り, KeyError) as e:
        out = {"手順": [], "管理表の行": [], "記録": [], "知らせ": [], "赤": [f"{type(e).__name__}: {e}"]}
    json.dump(out, sys.stdout, ensure_ascii=False, indent=1, default=str)
    print()
    sys.exit(2 if out.get("赤") else 0)
