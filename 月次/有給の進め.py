"""有給の始めを進める口: 12 月支給の 月を回す が数えた付与の残りを、新しい年の台帳を起こす時にマスタ「社員」の
有給の始めの日・有給の始めの残り・有給の始めの繰越 へ書く手順にする 1 か所。Drive を開かない。

なぜ在るか（2026-11-22 根治・原因の台帳「有給の始めを進める」）: 有給/ は 数え始め（有給の始めの日の翌日か入社日）から基準の日までの
確定した勤怠を年の台帳から数える。月を回す へ渡るのは今年と前の年の台帳だけ＝数え始めが前の年の台帳より前の人は、年を 1 つ
越すと取得を数えられず止まる。マスタの 有給の始め を前の年の台帳の中の日へ進めれば、有給の残りの元が年をまたいで続く。

いつ書くか: 12 月の 月を回す は今年と前の年の台帳を両方持つ唯一の時（12 月の基準の日の残りはここでしか数えられない）。書くのは
1 月に新しい年の台帳を起こす時（殻の〔口: 書く手順を当てる〕の 起こす が 12 月を 照らす で回し直して `有給の始めを進める` を受け、
起こす の書く手順と一緒に当てる）。12 月の後に書くと 12 月の回し直しで 始め より前の取得が 付与の残り から引かれず残りが変わる＝
回し直しの元を動かさない（有給/有給.py は 始めの日より前の取得も 年 5 日・付与日からの取得・今月の取得 には数える）。

  進める値は 月を回す が作る（`作る`・関所を通った人で、有給/ が仮の無い・生きている付与が 2 つまでの人）。
  書く手順(進める, 新しい支給年=…, 今の社員=…)
    進める: 月を回す(<前の年>.12支給, …) の返す `有給の始めを進める`（会社・支給月・行たち を持つ値。作り手を縛る鍵は 2026-11-27 に畳んだ）
    今の社員: マスタ「社員」の get_values（見出しが型と違えば止める）
    返す物: {書く手順: [{する: 値を書く, ファイル: 2_マスタ, タブ: 社員, 範囲, 値, 書き方: RAW}], 書いた後: {社員: 値},
            進めた: [{会社, NO, 氏名, 前, 後}], 済み: [{会社, NO}]}
止める: 進める値が 12 月支給の月を回す の物でない・新しい支給年の前の年でない・社員に居ない NO か 2 行在る NO・
氏名が違う・マスタの今の 有給の始めの日 が進める日より後（戻さない）。同じ値が既に書いてあれば 済み（書かない）。
"""
from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

_根 = Path(__file__).resolve().parent.parent
if str(_根) not in sys.path:
    sys.path.insert(0, str(_根))


def _読む(名: str, 場所: Path):
    if 名 not in sys.modules:
        spec = importlib.util.spec_from_file_location(名, 場所)
        m = importlib.util.module_from_spec(spec)
        sys.modules[名] = m
        spec.loader.exec_module(m)
    return sys.modules[名]


形 = _読む("月次_台帳の形", _根 / "月次" / "台帳の形.py")
from 芯.字 import 列の字  # noqa: E402

シート, タブ = 形.マスタ, "社員"
列たち = ("有給の始めの日", "有給の始めの残り", "有給の始めの繰越")
字のまま = "RAW"


class 有給の進めの誤り(ValueError):
    """有給の始めを進める手順を出さない。"""


class 進める値:
    """12 月支給の 月を回す が作る、有給の始めを進める値（関所を通った人の行）。"""
    __slots__ = ("会社", "支給月", "行たち")

    def __init__(self, 会社: str, 支給月: str, 行たち: tuple):
        self.会社, self.支給月, self.行たち = 会社, 支給月, tuple(dict(r) for r in 行たち)

    def __len__(self):
        return len(self.行たち)

    def __iter__(self):
        return iter(dict(r) for r in self.行たち)


def 作る(会社: str, 支給月: str, 行たち) -> 進める値:
    """月を回す が呼ぶ（支給月は出す支給月の字 YYYY-MM）。"""
    return 進める値(会社, 支給月, tuple(行たち))


def _字(v) -> str:
    return "" if v is None else str(v).strip()


def 書く手順(進める, *, 新しい支給年, 今の社員) -> dict:
    if not all(hasattr(進める, k) for k in ("会社", "支給月", "行たち")):
        raise 有給の進めの誤り("進める は 会社・支給月・行たち を持つ値（月を回す(<前の年>.12支給) の返す 有給の始めを進める）で渡す")
    s = _字(新しい支給年)
    if not re.fullmatch(r"\d{4}", s):
        raise 有給の進めの誤り(f"新しい支給年「{新しい支給年}」は 4 桁の年")
    前の年 = int(s) - 1
    if 進める.支給月 != f"{前の年}-12":
        raise 有給の進めの誤り(f"進める値は {進める.支給月} の月を回す の物＝{前の年} 年 12 月支給の物でない"
                         "（12 月の基準の日の残りだけを新しい年の始めにする）")
    if not isinstance(今の社員, (list, tuple)) or not 今の社員 or not isinstance(今の社員[0], (list, tuple)):
        raise 有給の進めの誤り("今の社員 はマスタ「社員」の get_values（1 行目が見出し）で渡す")
    見 = ["" if c is None else str(c) for c in 今の社員[0]]
    while 見 and not 見[-1].strip():
        見.pop()
    違い = 形.型の口().見出しの違い(シート, タブ, 見)
    if 違い:
        raise 有給の進めの誤り(f"{シート}「{タブ}」の見出しが型と違う（{'・'.join(違い)}）＝人がタブの見出しを今の型へそろえてから書く")
    h = list(見)
    i会社, iNO, i氏名 = h.index("会社"), h.index("NO"), h.index("氏名")
    ii = [h.index(c) for c in 列たち]
    if ii != list(range(ii[0], ii[0] + len(列たち))):
        raise 有給の進めの誤り(f"{'・'.join(列たち)} が型で並んでいない＝1 つの範囲で書けない")
    行 = [[_字(r[j]) if j < len(r) else "" for j in range(len(h))] for r in 今の社員[1:]]
    後 = [list(h), *[list(r) for r in 行]]
    手順, 進めた, 済み = [], [], []
    for x in 進める:
        会社, NO = _字(x.get("会社")), _字(x.get("NO"))
        if 会社 != 進める.会社:
            raise 有給の進めの誤り(f"NO {NO}: 会社「{会社}」が月を回した会社「{進める.会社}」と違う")
        日 = _字(x.get("有給の始めの日"))
        if not re.fullmatch(rf"{前の年}-\d{{2}}-\d{{2}}", 日):
            raise 有給の進めの誤り(f"{会社} NO {NO}: 有給の始めの日「{日}」が {前の年} 年の日でない")
        当たる = [k for k, r in enumerate(行) if r[i会社] == 会社 and r[iNO] == NO]
        if len(当たる) != 1:
            raise 有給の進めの誤り(f"{会社} NO {NO}: マスタ「社員」に {len(当たる)} 行（ちょうど 1 行の人だけ書く）")
        k = 当たる[0]
        if _字(x.get("氏名")) and 行[k][i氏名] and _字(x.get("氏名")) != 行[k][i氏名]:
            raise 有給の進めの誤り(f"{会社} NO {NO}: 氏名「{x.get('氏名')}」がマスタ「社員」の「{行[k][i氏名]}」と違う")
        新 = [日, _字(x.get("有給の始めの残り")), _字(x.get("有給の始めの繰越"))]
        今 = [行[k][j] for j in ii]
        if 今 == 新:
            済み.append({"会社": 会社, "NO": NO})
            continue
        if 今[0] and 今[0] > 日:
            raise 有給の進めの誤り(f"{会社} NO {NO}: マスタの 有給の始めの日 {今[0]} が進める日 {日} より後（戻さない）")
        for j, v in zip(ii, 新):
            後[k + 1][j] = v
        手順.append({"する": "値を書く", "ファイル": シート, "タブ": タブ,
                   "範囲": f"{列の字(ii[0] + 1)}{k + 2}:{列の字(ii[-1] + 1)}{k + 2}", "値": [新], "書き方": 字のまま})
        進めた.append({"会社": 会社, "NO": NO, "氏名": 行[k][i氏名], "前": dict(zip(列たち, 今)), "後": dict(zip(列たち, 新))})
    return {"書く手順": 手順, "書いた後": {タブ: 後}, "進めた": 進めた, "済み": 済み}
