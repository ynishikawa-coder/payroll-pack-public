"""受け取り口に届いた物を その月の置き場の `1_届いた物/` へ名を付けて写す手順を作る口（〔口: 届いた物を写す〕の芯）。Drive を開かない。

名の正本: docs/設計/Drive の型.md §2「置き場の約束」＝`<頭>_<受け取った日>_<元の名>`（頭＝勤怠_・変更_・メモ_・書類_）。
頭は給与エージェントが中身を読んで選ぶ（docs/毎月の流れ.md 1-①）。名を組むのはここ 1 か所（窓が名を手で組まない）。

  写す手順(届いた物, 今ある名=…)
    届いた物: [{"在り処": 受け取り口の file の id, "元の名": 受け取り口での名のまま, "受け取った日": YYYY-MM-DD, "頭": 勤怠_ など}]
    今ある名: その月の 1_届いた物/ の名の並び（必ず渡す・無ければ []）
    返す物: {書く手順: [{する: ファイルを写す, 元: 在り処, 先: 1_届いた物, 名}], 写し済み: [名]}
      写し済み＝同じ名が既に 1_届いた物/ に在る物（写さない・上書きしない＝同じ物を 2 つ置かない）

止める（既定で止める）: 頭が 4 つの外・受け取った日が YYYY-MM-DD でない・元の名が空か / を含む・元の名が既に頭と日の付いた名
（名を 2 重に付けない）・写しの名（旧_・コピー・（1）・Copy of＝置き場の検査 3 が赤にする名）・同じ回で同じ名を 2 つ作る・
在り処が空・今ある名を渡さない。原本は触らない（受け取り口の物は写すだけ・名を変えない・動かさない）。
"""
from __future__ import annotations

import datetime as dt
import re
import sys
from pathlib import Path

_根 = Path(__file__).resolve().parent.parent
if str(_根) not in sys.path:
    sys.path.insert(0, str(_根))


def _型の口():
    """Drive の木と名の形の正本（初期設定/型.json）を読む口。"""
    from 初期設定 import 型の口
    return 型の口


置き場 = _型の口().名("届いた物")   # 月の置き場（3_月ごと/<月>/）の中（Drive の型 §2）
頭たち = ("勤怠_", "変更_", "メモ_", "書類_")
from 芯 import 字  # noqa: E402  写しの名の並びの正本（置き場の検査と同じ 1 か所）

_付いた名 = re.compile(r"^(?:" + "|".join(map(re.escape, 頭たち)) + r")\d{4}-\d{2}-\d{2}_")


class 届いた物の誤り(ValueError):
    """写す手順を出さない（名が付けられない・同じ名を 2 つ作る）。"""


def 名を付ける(頭: str, 受け取った日: str, 元の名: str) -> str:
    頭 = str(頭 or "")
    if 頭 not in 頭たち:
        raise 届いた物の誤り(f"頭「{頭}」は {'・'.join(頭たち)} のどれか（中身を読んで選ぶ）")
    日 = str(受け取った日 or "").strip()
    try:
        ok = re.fullmatch(r"\d{4}-\d{2}-\d{2}", 日) and dt.date.fromisoformat(日)
    except ValueError:
        ok = False
    if not ok:
        raise 届いた物の誤り(f"受け取った日「{受け取った日}」は YYYY-MM-DD")
    元 = str(元の名 or "")
    if not 元.strip() or "/" in 元 or "\\" in 元 or re.search(r"[\x00-\x1f]", 元):
        raise 届いた物の誤り(f"元の名「{元の名}」は受け取り口の名のまま（空・/ \\ 制御の字は受けない）")
    if _付いた名.match(元):
        raise 届いた物の誤り(f"元の名「{元}」は既に頭と日の付いた名（名を 2 重に付けない＝受け取り口の名のまま渡す）")
    名 = f"{頭}{日}_{元}"
    if 字.写しの名か(元) or 字.写しの名か(名):   # 頭の語（旧_・Copy of）は元の名の頭で照らす（付けた名の頭は 勤怠_ など）
        raise 届いた物の誤り(f"「{名}」は写しの名（旧_・コピー・（1）・Copy of）＝置き場の検査 3 で赤になる。"
                         "受け取り口の同じ物の元を確かめ、写しなら写さない・別の物なら事務所の担当者に元の名を直してもらう")
    return 名


def 写す手順(届いた物, *, 今ある名) -> dict:
    if not isinstance(今ある名, (list, tuple)) or any(not isinstance(n, str) for n in 今ある名):
        raise 届いた物の誤り("今ある名（その月の 1_届いた物/ の名の並び）を名の字の並びで渡す（無ければ []）")
    if not isinstance(届いた物, (list, tuple)) or not 届いた物:
        raise 届いた物の誤り("届いた物（[{在り処, 元の名, 受け取った日, 頭}]）を 1 つ以上渡す")
    在る = set(今ある名)
    手順, 済み, 今回 = [], [], set()
    for x in 届いた物:
        if not isinstance(x, dict):
            raise 届いた物の誤り(f"届いた物の 1 つが dict でない: {x!r}")
        外 = sorted(set(x) - {"在り処", "元の名", "受け取った日", "頭"})
        if 外:
            raise 届いた物の誤り(f"届いた物に知らない名 {外}（在り処・元の名・受け取った日・頭 だけ）")
        if not str(x.get("在り処") or "").strip():
            raise 届いた物の誤り(f"「{x.get('元の名')}」の在り処（受け取り口の file の id）が空")
        名 = 名を付ける(x.get("頭"), x.get("受け取った日"), x.get("元の名"))
        if 名 in 今回:
            raise 届いた物の誤り(f"同じ名「{名}」を 1 回に 2 つ作る（同じ日に同じ名の物が 2 つ届いた＝事務所の担当者に元の名を分けてもらう）")
        今回.add(名)
        if 名 in 在る:
            済み.append(名)
            continue
        手順.append({"する": "ファイルを写す", "元": str(x["在り処"]).strip(), "先": 置き場, "名": 名})
    return {"書く手順": 手順, "写し済み": 済み}
