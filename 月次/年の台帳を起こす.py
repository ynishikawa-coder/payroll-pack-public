class 年の台帳の誤り(ValueError):
    """新しい年の台帳を起こせない（前の年の台帳が欠ける・形が違う・どの年の行か分からない）。"""


def 台帳の名(支給年) -> str:
    return 形.台帳.replace("<支給年>", str(_年(支給年)))


def _年(支給年) -> int:
    s = str(支給年).strip()
    if not re.fullmatch(r"\d{4}", s):
        raise 年の台帳の誤り(f"新しい支給年「{支給年}」は 4 桁の年（例 2027）")
    return int(s)


def _支給年(鍵: str, 行: dict) -> int:
    v = 形._字(行.get("支給月")).strip()
    if not 支給月の字.その形か(v, "殻"):
        raise 年の台帳の誤り(f"{鍵}: 会社 {形._字(行.get('会社'))} NO {形._字(行.get('NO'))} の 支給月「{v}」を読めない（YYYY.MM支給）")
    return 支給月の字.読む(v)[0]


def _表を照らす(鍵: str, 表) -> list[list[str]]:
    if not isinstance(表, (list, tuple)) or not 表 or not isinstance(表[0], (list, tuple)):
        raise 年の台帳の誤り(f"{鍵}: get_values の形（1 行目が見出しの 2 次元の並び）で渡す（dict の並び・見出しの無い表は読まない）")
    if any(not isinstance(r, (list, tuple)) for r in 表):
        raise 年の台帳の誤り(f"{鍵}: 行に 2 次元の並びでない物が混ざる")
    h = [str(c).strip() for c in 表[0]]
    if h != 形.見出し(鍵):
        raise 年の台帳の誤り(f"{鍵}: 見出しが型と違う（{h} ≠ {形.見出し(鍵)}）。型の版をそろえてから起こす")
    return [list(r) for r in 表]


def _空の行か(r) -> bool:
    return not any(形._字(v).strip() for v in r)


def 起こす(新しい支給年, 前の年の台帳: dict | None, *, 今ある名=None, 前の年が無い訳: str = "", 社員=None) -> dict:
    """前の年の台帳（{タブ: get_values}）→ 新しい年の台帳の形と引き継ぐ値。

    返す物:
      台帳の名: `台帳_<新しい支給年>`
      書く手順: 会社の根にこの名の新しいシートを作り 8 タブを書く手順（`月次/台帳へ書く.py` の 新しい台帳）。殻は〔口: 書く手順を当てる〕で
        順に当てるだけ（タブの表を手で写さない）。書いた後に読み直して `型の口.書いた値を照らす(タブの表, 読み直した値)` で照らす
      タブ: {タブ: 表}（8 タブ・型の並び。1 行目が型の見出し、2 行目から引き継ぐ行＝新しい年の支給月の行）
      前の確定した勤怠・前の確定した勤怠の区間: 前の年の 確定した勤怠・その区間（get_values の形・前の年の支給月の行だけ）。
        新しい年の 月を回す へ 前の確定した勤怠=…・前の確定した勤怠の区間=… でそのまま渡す
      引き継いだ行: {タブ: 行の数}
      知らせ: 止めずに知らせる事（12 月の 社保の立て替えの残り の続きの行が無い人・有給の数え始めが前の年の台帳より前の人）
    今ある名: 会社の根の名の並び（必ず渡す・無ければ []）。同じ名の台帳が在れば止める（上書きしない）。
    社員: マスタ「社員」（get_values の形か列名の dict の並び・必ず渡す）。引き継ぐ行は 台帳へ書く の関所で 氏名 を社員から
      埋めて照らす（空なら埋める・違えば止める・社員に居ない NO と社員の氏名が空の NO は止める）。返す `タブ` は関所を通した後の表
      （書く手順の値と同じ）。有給の数え始め（有給の始めの日の翌日・無ければ入社日）が
      前の年の台帳の最初の確定した勤怠の日より前の人を知らせる（新しい年は前の年の台帳までしか渡らない＝有給/ がその人を止める。
      マスタの 有給の始めの日・残り・繰越 を前の年の台帳の中の日へ進める＝有給の残りの元を年をまたいで続ける）。
    """
    年 = _年(新しい支給年)
    前の年 = 年 - 1
    if not isinstance(今ある名, (list, tuple)):
        raise 年の台帳の誤り("今ある名（会社の根の名の並び）を渡す（無ければ []）。渡さないと同じ年の台帳を 2 つ作る")
    if 社員 is None:
        raise 年の台帳の誤り("社員（マスタ「社員」）を渡す（引き継ぐ行の氏名は口が社員から埋めて照らす＝窓が書かない）")
    out = _起こす(年, 前の年, 前の年の台帳, 前の年が無い訳, 社員)
    try:
        out["書く手順"] = _台帳へ書く().新しい台帳(out, 今ある名=今ある名, 社員=社員)
    except ValueError as e:
        raise 年の台帳の誤り(str(e)) from e
    # 返す タブ は関所を通した後の表（書く手順の値そのもの＝写しを 2 つ持たない）
    out["タブ"] = {x["タブ"]: x["値"] for x in out["書く手順"] if x["する"] == "値を書く"}
    return out


def _起こす(年: int, 前の年: int, 前の年の台帳, 前の年が無い訳, 社員) -> dict:
    if 前の年の台帳 is None:
        if not str(前の年が無い訳 or "").strip():
            raise 年の台帳の誤り(f"前の年（{前の年}）の台帳を渡す。会社を始めた年で前の年の台帳が本当に無い時だけ 前の年が無い訳 を書く"
                             "（月の頭の週・有給の取得と出勤率が前の年を読む）")
        return {"台帳の名": 台帳の名(年), "タブ": {k: [list(形.見出し(k))] for k in 台帳のタブ},
                "前の確定した勤怠": [list(形.見出し("確定した勤怠"))], "前の確定した勤怠の区間": [list(形.見出し("確定した勤怠の区間"))],
                "引き継いだ行": {k: 0 for k in 台帳のタブ},
                "知らせ": [f"前の年の台帳は無い（{str(前の年が無い訳).strip()}）。新しい年の月の頭の週・有給は前の年を読まない"]}
    if str(前の年が無い訳 or "").strip():
        raise 年の台帳の誤り("前の年の台帳を渡した時は 前の年が無い訳 を書かない（どちらか 1 つ）")
    if not isinstance(前の年の台帳, dict):
        raise 年の台帳の誤り("前の年の台帳は {タブの名: get_values の値} で渡す")
    前 = sorted(k for k in 前の年の台帳 if k in 前の台帳のタブ)
    if 前:
        raise 年の台帳の誤り(f"前の台帳のタブ {前} は読まない（型の版 27 で畳んだ前のタブ。今の年の台帳は {'・'.join(台帳のタブ)}。寄せの直しを当ててから起こす）")
    外 = sorted(k for k in 前の年の台帳 if k not in 台帳のタブ)
    if 外:
        raise 年の台帳の誤り(f"型に無いタブ {外}（年の台帳は {'・'.join(台帳のタブ)}）")
    欠け = [k for k in 台帳のタブ if k not in 前の年の台帳]
    if 欠け:
        raise 年の台帳の誤り(f"前の年の台帳のタブ {欠け} が無い（8 タブ全部を get_values で渡す。黙って空とみなさない）")

    タブ, 前の年の行, 引き継いだ = {}, {}, {}
    for k in 台帳のタブ:
        表 = _表を照らす(k, 前の年の台帳[k])
        h = 表[0]
        新, 古 = [list(h)], [list(h)]
        for r in 表[1:]:
            if _空の行か(r):
                continue
            d = {c: (r[i] if i < len(r) else "") for i, c in enumerate(h)}
            y = _支給年(k, d)
            if y == 年:
                新.append([d[c] for c in h])
            elif y == 前の年:
                古.append([d[c] for c in h])
            else:
                raise 年の台帳の誤り(f"{k}: 会社 {形._字(d.get('会社'))} NO {形._字(d.get('NO'))} の 支給月「{形._字(d.get('支給月'))}」は"
                                 f" {前の年} 年でも {年} 年でもない（どの年の台帳の行か分からない）")
        タブ[k], 前の年の行[k] = 新, 古
        引き継いだ[k] = len(新) - 1

    if len(前の年の行["確定した勤怠"]) == 1:
        raise 年の台帳の誤り(f"前の年（{前の年}）の台帳の 確定した勤怠 に {前の年} 年の支給月の行が 1 行も無い"
                         "（月の頭の週・有給の取得と出勤率が読めない。前の年の台帳を取り違えていないか確かめる）")
    try:   # 新しい年の 月を回す が読めるかをここで照らす（読めない台帳を起こしてから 1 月に止まらない）
        形.確定した勤怠を読む(前の年の行["確定した勤怠"], 前の年の行["確定した勤怠の区間"])
        形.確定した勤怠を読む(タブ["確定した勤怠"], タブ["確定した勤怠の区間"])
    except 形.台帳の形の誤り as e:
        raise 年の台帳の誤り(f"前の年の台帳の確定した勤怠が読めない: {e}") from e

    return {"台帳の名": 台帳の名(年), "タブ": タブ,
            "前の確定した勤怠": 前の年の行["確定した勤怠"], "前の確定した勤怠の区間": 前の年の行["確定した勤怠の区間"],
            "引き継いだ行": 引き継いだ,
            "知らせ": [*_続きの知らせ(前の年の行, タブ, 前の年, 年), *_有給の知らせ(前の年の行["確定した勤怠"], 社員)]}


def _日(v) -> _date | None:
    s = 形._字(v).strip().replace("/", "-")
    m = re.fullmatch(r"(\d{4})-(\d{1,2})-(\d{1,2})", s)
    if not m:
        return None
    try:
        return _date(*(int(x) for x in m.groups()))
    except ValueError:
        return None


def _有給の知らせ(前の確定, 社員) -> list[str]:
    """有給の数え始めが前の年の台帳の最初の日より前の人（有給/ は 数え始めから基準の日までの確定した勤怠を要る）。"""
    if 社員 is None:
        return []
    最初: dict[tuple, _date] = {}
    for r in 形.行たち(前の確定):
        d = _日(r.get("日付"))
        鍵 = (形._字(r.get("会社")).strip(), 形._字(r.get("NO")).strip())
        if d and (鍵 not in 最初 or d < 最初[鍵]):
            最初[鍵] = d
    out = []
    for r in 形.行たち(社員):
        鍵 = (形._字(r.get("会社")).strip(), 形._字(r.get("NO")).strip())
        if 鍵 not in 最初 or _日(r.get("退職日")) and _日(r.get("退職日")) < 最初[鍵]:
            continue
        始め = _日(r.get("有給の始めの日"))
        数え始め = 始め + timedelta(days=1) if 始め else _日(r.get("入社日"))
        if 数え始め and 数え始め < 最初[鍵]:
            何 = f"有給の始めの日 {始め} の翌日" if 始め else f"有給の始めの日が無く入社日 {数え始め}"
            out.append(f"{鍵[0]} NO {鍵[1]}: 有給の数え始め（{何}）が前の年の台帳の最初の日 {最初[鍵]} より前"
                       "（新しい年は前の年の台帳までしか読まない＝この人の有給は止まる。マスタ「社員」の 有給の始めの日・残り・繰越 を"
                       "前の年の台帳の中の日へ進める＝その日の締めの有給休暇管理表の残りから）")
    return out


def _続きの知らせ(前の年の行: dict, タブ: dict, 前の年: int, 年: int) -> list[str]:
    """12 月支給に 社保の立て替えの残り の行が在る（立て替えが続く）のに、1 月支給の行が無い人を知らせる
    （12 月を回していない・仮で外れた。1 月の 月を回す はその人を仮にする＝止めずに知らせる）。"""
    指示 = 形.行たち(前の年の行["その月だけの指示"])
    一月, 十二月 = 支給月の字.字にする(年, 1, "殻"), 支給月の字.字にする(前の年, 12, "殻")
    新 = {(形._字(r.get("会社")), 形._字(r.get("NO"))) for r in 形.行たち(タブ["その月だけの指示"])
         if 形._字(r.get("項目")) == 立て替えの残り and 形._字(r.get("支給月")) == 一月}
    out = []
    for r in 指示:
        鍵 = (形._字(r.get("会社")), 形._字(r.get("NO")))
        if 形._字(r.get("項目")) == 立て替えの残り and 形._字(r.get("支給月")) == 十二月 and 鍵 not in 新:
            out.append(f"{鍵[0]} NO {鍵[1]}: {十二月} に {立て替えの残り} の行が在るのに {一月} の行が無い"
                       f"（{十二月} を 月を回す で確定すると次の月の行が返る。無いまま 1 月を回すとこの人は仮）")
    return out
