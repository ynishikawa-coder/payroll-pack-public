def _名を付ける(物: str, 会社: str, 支給月: str, 今ある名, 履歴にある名, 置き場の表: dict) -> 出す名:
    """今ある名＝その月の置き場の 2_出す物/ の直下の名・履歴にある名＝会社の根の 9_履歴/ の名（版の番号を戻さないために見る）。

    新しい版はその物・会社・支給月の前の版（どちらの置き場の名も・拡張子つきも）の最大の次。前の版は 出口/出す.py が Drive の
    2_出す物/・9_履歴/ から読んで 2 つとも渡す（前の版が無ければ空の並び `[]`）。渡さない（None）時は止める＝前の版を見ずに黙って v1 を付けない
    （2026-11: 前の仕組みで v6 まで出した置き場に v1 を出しかけた）。名の並びでなく 1 つの字を渡した時も止める。"""
    for 何, 並び in (("今ある名（2_出す物/ の名）", 今ある名), ("履歴にある名（9_履歴/ の名）", 履歴にある名)):
        if not isinstance(並び, (list, tuple)):   # None・字・dict・使い切る並び（generator）も止める
            raise ValueError(f"{物}: {何} を名の並びで渡す（前の版が無ければ []）。渡さないと前の版の番号を見られない＝版を付けない"
                             f"（受けた物: {並び!r}）")
        if any(not isinstance(n, str) for n in 並び):
            raise ValueError(f"{物}: {何} の中身は名の字だけで渡す（Drive の一覧の dict などは名の字へ直す）。字でない物は版を読めない"
                             f"＝黙って v1 を付けない（受けた物: {並び!r}）")
    if 物 not in 置き場の表:
        raise ValueError(f"物「{物}」は {'・'.join(置き場の表)} の外")
    if not str(会社).strip() or str(会社) != str(会社).strip() or re.search(r'[/\\\x00-\x1f]', str(会社)):
        raise ValueError(f"会社は会社の呼び名（型の列「会社」と同じ字・前後の空白と / \\ と制御の字の無い字）で渡す: {会社!r}")
    頭 = 名の頭(物, 会社, 支給月)
    pat = re.compile(re.escape(頭) + r"(\d+)(\.[^./]*)?$")
    前 = []
    for n in 今ある名:
        m = pat.match(str(n))
        if m:
            前.append((int(m.group(1)), str(n)))
    古い = [int(m.group(1)) for m in map(pat.match, map(str, 履歴にある名)) if m]
    版 = max([v for v, _ in 前] + 古い, default=0) + 1
    return 出す名(フォルダ=置き場の表[物], 名=f"{頭}{版}", 版=版,
                 履歴へ移す=tuple(n for _, n in sorted(前)))
