"""会社の決まりの残業の数え方（`割増.残業の数え方`）と、法の線との並べ。

既定（空・`法定どおり`）は何もしない＝月の数字は今の形のまま。
`1日の所定超え` の会社は、勤務の日ごとに「その日の所定を超えた時間」を足して `残業（会社の数え方）` に出す
（払うのはこの方。率を選んで払うのは `芯/計算/`）。`60 時間超（会社の数え方）`＝それ−法の線の 60 時間の境。
`割増.みなし残業の時間` はここでは引かない: 前の道具は月給で役員でない人だけに当てる（給与の形は集計に来ない）ので、
固定残業の分として `芯/計算/` で引く。ここでは値を印に残すだけ。
法の線で数えた法定外（日の法定・週の法定・制度の総枠。`法定外残業`・`60 時間超`）は今のまま並べて出し、
会社の数え方がそれを下回る月は知らせ（問い・仮にはしない）に月と下回る日を出す。法の値はここに書かない（法の線で受ける）。
"""
from .形 import 仮, 詰め

法定どおり = "法定どおり"
所定超え = "1日の所定超え"
選べる値 = ("", 法定どおり, 所定超え)

# 会社の数え方の語（月の数字の口からは来ない。日から出した時だけ出す）
会社の語: tuple[tuple[str, str], ...] = (
    ("残業（会社の数え方）", "分"),
    ("60 時間超（会社の数え方）", "分"),
)
会社の語の名 = frozenset(k for k, _ in 会社の語)
数えられる制度 = ("通常", "事業場外みなし", "専門業務型裁量", "企画業務型裁量", "1か月変形", "1年変形", "1週間変形")


def 日の会社の残業(r) -> int:
    """勤務の日の、その日の所定（休暇の分を引く前）を超えた時間。法定休日・休日勤務の日は数えない（休日の語で払う）。"""
    if r.種類 != "勤務":
        return 0
    return max(0, r.所定内 + r.法定内 + r.法定外 - r.所定)


def 数える(決, 線, 制度: str, 今の結果: list, 値: dict) -> dict | None:
    """会社の数え方の残業。既定なら None（何も足さない）。

    返す物: {"値": {語: 分}, "出所": {語: [日]}, "印": {語: [文]}, "仮": [仮], "知らせ": [文]}
    値: 法の線で数えた月の数字（`法定外残業`・`60 時間超`）。
    """
    数え方 = 詰め(決.引く("割増.残業の数え方"))
    仮たち, 知らせ = [], []
    if 数え方 in ("", 法定どおり):
        return None
    印 = {k: [] for k in 会社の語の名}
    if 数え方 not in 選べる値:
        仮たち.append(仮(f"割増.残業の数え方「{数え方}」は選べる値の外（法定外残業で置いた）", None, 会社の語の名))
        値たち = {"残業（会社の数え方）": 値["法定外残業"], "60 時間超（会社の数え方）": 値["60 時間超"]}
        return {"値": 値たち, "出所": {}, "印": 印, "仮": 仮たち, "知らせ": 知らせ}
    if 制度 not in 数えられる制度:
        仮たち.append(仮(f"時間.制度「{制度}」では 割増.残業の数え方「1日の所定超え」で数えられない（法定外残業で置いた）",
                       None, 会社の語の名))
        値たち = {"残業（会社の数え方）": 値["法定外残業"], "60 時間超（会社の数え方）": 値["60 時間超"]}
        return {"値": 値たち, "出所": {}, "印": 印, "仮": 仮たち, "知らせ": 知らせ}
    日ごと = {r.日付: 日の会社の残業(r) for r in 今の結果}
    会社 = sum(日ごと.values())
    出所 = [d for d, v in 日ごと.items() if v]
    印["残業（会社の数え方）"].append("1日の所定を超えた時間の和（会社の決まり）")
    みなし = 決.引く("割増.みなし残業の時間")
    if みなし not in (None, ""):
        印["残業（会社の数え方）"].append(f"割増.みなし残業の時間 {みなし} は引いていない（月給で役員でない人だけ 芯/計算 で引く）")
    値たち = {"残業（会社の数え方）": 会社}
    出所たち = {"残業（会社の数え方）": 出所}
    if 線.六十時間 is None:
        仮たち.append(仮("法の線に 割増.60時間超の境 が無い", None, frozenset({"60 時間超（会社の数え方）"})))
        値たち["60 時間超（会社の数え方）"] = 0
    else:
        値たち["60 時間超（会社の数え方）"] = max(0, 会社 - 線.六十時間)
        if 値たち["60 時間超（会社の数え方）"]:
            出所たち["60 時間超（会社の数え方）"] = 出所

    # 法の線と並べる（下回っても払う額は会社の決まりのまま。知らせだけ）
    足りない = []
    if 値["法定外残業"] > 会社:
        足りない.append(f"法定外残業 {値['法定外残業']} 分 > 会社の数え方 {会社} 分（{値['法定外残業'] - 会社} 分）")
    if 線.六十時間 is not None and 値["60 時間超"] > 値たち["60 時間超（会社の数え方）"]:
        足りない.append(f"60 時間超 {値['60 時間超']} 分 > 会社の数え方 {値たち['60 時間超（会社の数え方）']} 分")
    if 足りない:
        下回る日 = [r.日付.isoformat() for r in 今の結果 if r.法定外 > 日ごと[r.日付]]
        文 = "会社の残業の数え方（1日の所定超え）が法の線の割増を下回る月: " + "・".join(足りない)
        if 下回る日:
            文 += f"。法定外がその日の所定超えより多い日: {'、'.join(下回る日)}"
        知らせ.append(文 + "（払うのは会社の決まりのまま）")
    return {"値": 値たち, "出所": 出所たち, "印": 印, "仮": 仮たち, "知らせ": 知らせ}
