"""会社の決まりの残業の数え方（`割増.残業の数え方`）と、法の線との並べ。

既定（空・`法定どおり`）は何もしない＝月の数字は今の形のまま。
`1日の所定超え` の会社は、勤務の日ごとに「その日の所定を超えた時間」を足して `残業（会社の数え方）` に出す
（払うのはこの方。率を選んで払うのは `芯/計算/`）。`60 時間超（会社の数え方）`＝それ−法の線の 60 時間の境。
`割増.みなし残業の時間` はここでは引かない: 前の道具は月給で役員でない人だけに当てる（給与の形は集計に来ない）ので、
固定残業の分として `芯/計算/` で引く。ここでは値を印に残すだけ。
法の線で数えた法定外（日の法定・週の法定・制度の総枠。`法定外残業`・`60 時間超`）は今のまま並べて出し、
会社の数え方がそれを下回る月は知らせ（問い・仮にはしない）に月と下回る日を出す。法の値はここに書かない（法の線で受ける）。
`月の総労働が月の所定を超えた分` の会社（型の版 21）は、月に 1 回「勤務の日の総労働＋年休の時間−月の所定」を数える
（日ごと・週ごとの超えを数えない＝法の線を外れる恐れがある＝法の線と並べて下回る月を同じく知らせる）。
月の所定は `割増.月の残業の所定時間`（空＝その人の休日でない日の所定の和・h:mm か時間の数・`基準の人:<NO>`＝その人の
勤務の日と年休の日の所定の和〔芯/集計/__init__.py が先に数えて 基準の所定 で渡す〕）。
管理監督者・高度プロフェッショナルには会社の数え方を当てない（時間外・休日の割増の外＝制度の式どおり・語を出さない）。
`割増.残業の数え方`・`割増.月の残業の所定時間` は勤務の型の段にも置ける（型の版 24）。ここへは段の解決がその人の既定の型の値を
会社の値の上に重ねて渡す（月に 1 つの数え方＝日ごとの勤務の型の列では引かない）。`割増.月の残業の所定時間` は人の段にも置ける
（型の版 24・人の値が型と会社の値に勝つ。`割増.みなし残業の時間` を引く元の残業もその人の月の所定から数える）。
`割増.残業の数え方` も人の段に置ける（型の版 25・同じ勤務の型の中で数え方の違う人。段の解決が人の値を型の値の上に重ねて渡す）。
`欠勤.頭打ちの月の所定`＝割増.月の残業の所定時間 の人には、同じ 月の所定 を遅刻早退の頭打ちの月の所定として出す（`頭打ちの月の所定`・型の版 25）。
"""
from .形 import 仮, 会社の語, 形の誤り, 時間の分, 詰め, 頭打ちの語

法定どおり = "法定どおり"
所定超え = "1日の所定超え"
月の超え = "月の総労働が月の所定を超えた分"
基準の人の頭 = "基準の人:"

# 会社の数え方の語は 形.py の 会社の語（台帳の型の列と同じ 1 か所）
会社の語の名 = frozenset(k for k, _ in 会社の語)
# 月の所定（`割増.月の残業の所定時間`）から出る語＝基準の人の所定が無い 1 回目に仮になりうる語（芯/集計/__init__.py が基準に使えるかを見る）
頭打ちの語の名 = frozenset(k for k, _ in 頭打ちの語)
基準で変わる語 = 会社の語の名 | 頭打ちの語の名
頭打ちを残業の所定で = "割増.月の残業の所定時間"   # `欠勤.頭打ちの月の所定` の値（型の版 25）
数えられる制度 = ("通常", "事業場外みなし", "専門業務型裁量", "企画業務型裁量", "1か月変形", "1年変形", "1週間変形")
当てない制度 = ("管理監督者", "高度プロフェッショナル")   # 時間外・休日の割増の外（労基法 41 条・41 条の 2）＝会社の数え方の語を出さない


def 日の会社の残業(r) -> int:
    """勤務の日の、その日の所定（休暇の分を引く前）を超えた時間。法定休日・休日勤務の日は数えない（休日の語で払う）。"""
    if r.種類 != "勤務":
        return 0
    return max(0, r.所定内 + r.法定内 + r.法定外 - r.所定)


def 基準の人(決) -> str | None:
    """`割増.月の残業の所定時間`＝`基準の人:<NO>` の NO（それ以外は None）。"""
    v = 詰め(決.引く("割増.月の残業の所定時間")).replace("：", ":")
    return v[len(基準の人の頭):].strip() if v.startswith(基準の人の頭) else None


def 基準の所定(今の結果: list, 年休の日: set, 日の所定: dict) -> int | None:
    """基準の人として渡す月の所定（分）: 勤務の日と年休の日の所定の和＝（出勤日数＋年休の日数）×日の所定。
    日の所定: {日付: 分 か None}（休日でない日。月.py が勤務の日は日の結果の所定・ほかの日は決まりから引く）。出ない日があれば None。"""
    xs = [日の所定.get(r.日付) for r in 今の結果 if r.種類 == "勤務" or r.日付 in 年休の日]
    return None if any(x is None for x in xs) else sum(xs)


def 月の所定(決, 日の所定: dict, 基準: dict | None) -> tuple[int | None, str]:
    """`割増.月の残業の所定時間` → (分, 印の文)。出ない時は (None, 訳)。"""
    v = 詰め(決.引く("割増.月の残業の所定時間"))
    NO = 基準の人(決)
    if NO is not None:
        x = (基準 or {}).get(NO)
        if x is None:
            return None, f"割増.月の残業の所定時間 の 基準の人 {NO} の所定が出ない（同じ会社・同じ月の勤怠が無いか、その人が仮）"
        return x, f"月の所定 {x} 分＝基準の人 {NO} の勤務の日と年休の日の所定の和"
    if v:
        try:
            x = 時間の分(v)
        except 形の誤り:
            x = None
        if x is None or x < 0:
            return None, f"割増.月の残業の所定時間「{v}」が読めない（h:mm・時間の数・基準の人:<NO>）"
        return x, f"月の所定 {x} 分（割増.月の残業の所定時間）"
    if any(x is None for x in 日の所定.values()):
        return None, "割増.月の残業の所定時間 が空で、休日でない日の所定が出ない日がある（時間.日の所定）"
    x = sum(日の所定.values())
    return x, f"月の所定 {x} 分＝休日でない日の所定の和"


def 頭打ちの月の所定(決, 日の所定: dict, 基準: dict | None) -> dict | None:
    """`欠勤.頭打ちの月の所定`＝割増.月の残業の所定時間 の人の、遅刻早退の頭打ちで総労働と比べる月の所定（月の語 `月の残業の所定`）。
    ほかの人は None（語を出さない＝芯/計算 は 時間.月の所定時間 で比べる）。`割増.残業の数え方` に関わらず 月の所定 と同じ値で数える。
    返す物: {"値": 分 か None, "印": 文, "仮": [仮]}（出ない時は 値＝None と仮＝芯/計算 は頭打ちしないで仮）。"""
    if 詰め(決.引く("欠勤.頭打ちの月の所定")) != 頭打ちを残業の所定で:
        return None
    所, 訳 = 月の所定(決, 日の所定, 基準)
    if 所 is None:
        return {"値": None, "印": 訳, "仮": [仮(訳 + "（遅刻早退の頭打ちの月の所定）", None, 頭打ちの語の名)]}
    return {"値": 所, "印": f"{訳}（欠勤.頭打ちの月の所定）", "仮": []}


def 数える(決, 線, 制度: str, 今の結果: list, 値: dict, 基準: dict | None = None, 日の所定: dict | None = None) -> dict | None:
    """会社の数え方の残業。既定なら None（何も足さない）。管理監督者・高度プロフェッショナルも None（制度の式どおり）。

    返す物: {"値": {語: 分}, "出所": {語: [日]}, "印": {語: [文]}, "仮": [仮], "知らせ": [文]}
    値: 法の線で数えた月の数字（`法定外残業`・`60 時間超`・`年休の時間`）。
    基準: {NO: 分}（`割増.月の残業の所定時間`＝基準の人:<NO> の時の、その人の 基準の所定）。
    日の所定: {日付: 分 か None}（休日でない日の所定。月で数える時だけ使う）。
    """
    数え方 = 詰め(決.引く("割増.残業の数え方"))
    仮たち, 知らせ = [], []
    if 数え方 in ("", 法定どおり) or 制度 in 当てない制度:
        return None
    印 = {k: [] for k in 会社の語の名}   # 選べる値の外の字は 一人を集計する の最初に 芯/設定 が照らした
    if 制度 not in 数えられる制度:
        仮たち.append(仮(f"時間.制度「{制度}」では 割増.残業の数え方「{数え方}」で数えられない（法定外残業で置いた）",
                       None, 会社の語の名))
        値たち = {"残業（会社の数え方）": 値["法定外残業"], "60 時間超（会社の数え方）": 値["60 時間超"]}
        return {"値": 値たち, "出所": {}, "印": 印, "仮": 仮たち, "知らせ": 知らせ}
    日ごと = {r.日付: 日の会社の残業(r) for r in 今の結果}
    if 数え方 == 月の超え:
        所, 訳 = 月の所定(決, 日の所定 or {}, 基準)
        働いた = sum(r.所定内 + r.法定内 + r.法定外 for r in 今の結果 if r.種類 == "勤務")   # 休日勤務の日は数えない（休日の語で払う）
        if 所 is None:
            仮たち.append(仮(訳 + "（法定外残業で置いた）", None, 会社の語の名))
            会社 = 値["法定外残業"]
        else:
            会社 = max(0, 働いた + 値.get("年休の時間", 0) - 所)
            印["残業（会社の数え方）"].append(f"勤務の日の総労働 {働いた} 分＋年休の時間 {値.get('年休の時間', 0)} 分−{訳}（会社の決まり）")
        出所 = [r.日付 for r in 今の結果 if r.種類 == "勤務" and (r.所定内 + r.法定内 + r.法定外)] if 会社 else []
    else:
        会社 = sum(日ごと.values())
        出所 = [d for d, v in 日ごと.items() if v]
        印["残業（会社の数え方）"].append("1日の所定を超えた時間の和（会社の決まり）")
    みなし = 決.引く("割増.みなし残業の時間")
    if みなし not in (None, ""):
        印["残業（会社の数え方）"].append(f"割増.みなし残業の時間 {みなし} は引いていない（月給で役員でない人だけ 芯/計算 で引く）")
    値たち = {"残業（会社の数え方）": 会社}
    出所たち = {"残業（会社の数え方）": 出所}
    if 線.六十時間 is None:
        仮たち.append(仮("法の線に 割増.60時間超の境 が無い", None, frozenset({"60 時間超（会社の数え方）"})))
        値たち["60 時間超（会社の数え方）"] = 0
    else:
        値たち["60 時間超（会社の数え方）"] = max(0, 会社 - 線.六十時間)
        if 値たち["60 時間超（会社の数え方）"]:
            出所たち["60 時間超（会社の数え方）"] = 出所

    # 法の線と並べる（下回っても払う額は会社の決まりのまま。知らせだけ）
    足りない = []
    if 値["法定外残業"] > 会社:
        足りない.append(f"法定外残業 {値['法定外残業']} 分 > 会社の数え方 {会社} 分（{値['法定外残業'] - 会社} 分）")
    if 線.六十時間 is not None and 値["60 時間超"] > 値たち["60 時間超（会社の数え方）"]:
        足りない.append(f"60 時間超 {値['60 時間超']} 分 > 会社の数え方 {値たち['60 時間超（会社の数え方）']} 分")
    if 足りない:
        下回る日 = [r.日付.isoformat() for r in 今の結果 if r.法定外 > 日ごと[r.日付]] if 数え方 == 所定超え else []
        文 = f"会社の残業の数え方（{数え方}）が法の線の割増を下回る月: " + "・".join(足りない)
        if 下回る日:
            文 += f"。法定外がその日の所定超えより多い日: {'、'.join(下回る日)}"
        知らせ.append(文 + "（払うのは会社の決まりのまま）")
    return {"値": 値たち, "出所": 出所たち, "印": 印, "仮": 仮たち, "知らせ": 知らせ}
