"""月の数字の口（月の合計しか無い会社）を、日から出した物と同じ縦の形に通す。

日の記録が無いので、日から出し直す検査はできない。その旨を全部の行に印して出す（黙って通さない）。
"""
from datetime import date
from decimal import Decimal

from .形 import 仮, 形の誤り, 空, 整数, 数, 日付, 月の語, 単位
from .月 import 行を作る

できない検査 = (
    "日 8 時間・週 40 時間の出し直し",
    "深夜と休憩の重なり",
    "変形労働時間制の三段（日・週・期間）の時間外",
    "休日が週 1 日（4 週 4 日）あるか",
    "打刻の抜け・二重打刻",
    "日の和と月の値の突き合わせ",
    "法定休日の日の特定",
)
印の文 = "日の記録が無い（できない検査: " + "・".join(できない検査) + "）"
無いと仮 = ("所定日数", "出勤日数", "総労働")


def 一人を通す(行たち: list[dict]) -> dict:
    人 = {k: 行たち[0].get(k, "") for k in ("支給月", "会社", "NO", "勤怠の表記")}
    仮たち, 値, 出所 = [], {}, {}
    年休の日 = []
    for r in 行たち:
        項目 = r.get("項目")
        原本 = r.get("原本の名前") or ""
        if 項目 not in 単位:
            仮たち.append(仮(f"月の数字の口に決まった語の外の項目「{項目}」がある（通さない）"))
            continue
        if r.get("読み取りの確かめ") != "確認済":
            仮たち.append(仮("月の数字の口の行が要確認", None, frozenset({項目})))
        if 空(r.get("原本の名前")) or 空(r.get("原本の種別")):
            仮たち.append(仮("月の数字の口の行に原本の名前・種別が無い", None, frozenset({項目})))
        try:
            u = 単位[項目]
            if u == "日付":
                年休の日.append((日付(r.get("値")), 原本))
                continue
            v = 数(r.get("値")) if u == "日" else 整数(r.get("値"))
            if v is None:
                raise 形の誤り("値が空")
            if v < 0 or (u == "日" and (v * 2) != (v * 2).to_integral_value()):
                raise 形の誤り(f"値「{r.get('値')}」は {u} の形でない")
        except 形の誤り as e:
            仮たち.append(仮(f"月の数字の口の値が読めない: {e}", None, frozenset({項目})))
            continue
        if 項目 in 値:
            仮たち.append(仮("月の数字の口に同じ項目が 2 行ある", None, frozenset({項目})))
            continue
        値[項目], 出所[項目] = v, 原本
    for 項目, u in 月の語:
        if u != "日付" and 項目 not in 値:
            値[項目] = Decimal(0) if u == "日" else 0
            if 項目 in 無いと仮:
                仮たち.append(仮(f"月の数字の口に {項目} が無い（0 で置いた）", None, frozenset({項目})))
    和 = 値["所定内"] + 値["法定内残業"] + 値["法定外残業"] + 値["法定休日"]
    if 和 != 値["総労働"]:
        仮たち.append(仮("月の数字の口の総労働が 所定内＋法定内残業＋法定外残業＋法定休日 と合わない", None,
                       frozenset({"総労働", "所定内", "法定内残業", "法定外残業", "法定休日"})))
    for 内, 外 in (("60 時間超", "法定外残業"), ("深夜", "総労働"), ("所定休日", "総労働")):
        if 値[内] > 値[外]:
            仮たち.append(仮(f"月の数字の口の {内} が {外} を超える（内数）", None, frozenset({内, 外})))
    行 = []
    for 項目, u in 月の語:
        if u == "日付":
            for d, 原本 in sorted(年休の日):
                行.append(行を作る(人, 項目, d.isoformat(), [原本], [印の文], 仮たち))
            continue
        行.append(行を作る(人, 項目, 値[項目], [出所[項目]] if 項目 in 出所 else [], [印の文], 仮たち))
    return {"人": 人, "行": 行, "仮": 仮たち, "知らせ": []}
