def 法定休日の決め方(決: 決まり) -> tuple[str, str]:
    """`休日.法定休日の決め方` を (決め方, 括弧の中) で読む。項目の辞書の書き方（`4 週 4 休（起算日つき）`・`曜日を決める（日）`）も
    字だけの書き方（`4週4休`）も同じに読む。括弧の中は 4 週 4 休なら起算日、曜日なら曜日を書いてよい（別の項目が無い時に使う）。"""
    v = 詰め(決.引く("休日.法定休日の決め方")) or "曜日を決める"
    if v.endswith("）") and "（" in v:
        元, 中 = v[:-1].split("（", 1)
        if 元 in 決め方たち:
            return 元, 中
    return v, ""


def 四週の起算日(決: 決まり, 括弧: str):
    """`休日.4週の起算日`、無ければ決め方の括弧に書いた日付（`4週4休（起算日2026-04-01）`）。どちらも無ければ None。"""
    v = 決.引く("休日.4週の起算日")
    if v is not None:
        return v
    m = re.search(r"\d{4}-\d{2}-\d{2}", 括弧 or "")
    return m.group(0) if m else None


def 明けの日たち(区間: dict) -> set:
    """前の日から続く労働（表 B の労働の区間の終わりが 24:00 を越える）がかかる次の日たち。"""
    out = set()
    for d, bs in 区間.items():
        for b in bs:
            if b.get("区間の種別") != "労働":
                continue
            try:
                e = 分(b.get("終わり"))
            except 形の誤り:
                continue
            for k in range(1, 3):
                if e is not None and e > k * 1440:
                    out.add(d + timedelta(days=k))
    return out


def 週の頭(d: date, 起算: str) -> date:
    return d - timedelta(days=(d.weekday() - 曜日.index(起算)) % 7)


def 休日の区分を決める(行たち: list[dict], 決: 決まり, 線: 法の線, 起算: str, 知っている日: set,
                    明け: set = frozenset()) -> tuple[dict, list]:
    """休日・休日勤務の日を 法定／所定 に分ける。表 A に区分があればそれ、空なら `休日.法定休日の決め方`。

    明け: 前の日から続く労働がかかる日（夜勤の明け）。4 週 4 休では、明けの日は暦日の休日でない（休日は午前 0 時から午後 12 時の休業）ので
    休日に数えず、その日へかかった労働は始まりの日の勤務として数える（区分を置かない）。根拠は docs/設計/会社の決まり.md §4.5。"""
    暦, 仮たち, 待ち = {}, [], []
    for r in 行たち:
        if r["日の種類"] not in ("休日", "休日勤務"):
            continue
        k = r.get("休日の区分") or ""
        if k in ("法定", "所定"):
            暦[r["日付"]] = k
        elif k:
            仮たち.append(仮(f"休日の区分「{k}」は選べる値の外", r["日付"]))
            待ち.append(r)
        else:
            待ち.append(r)
    決め方, 括弧 = 法定休日の決め方(決)
    種類 = {r["日付"]: r["日の種類"] for r in 行たち}
    if 決め方 == "4週4休":
        for x in sorted(明け):
            if 種類.get(x) == "休日" and 暦.get(x) == "法定":   # 番方編成の例外（昭 63.3.14 基発 150 号）は芯が持たない
                仮たち.append(仮("夜勤の明けの日に 休日の区分＝法定 がある（暦日の休日でない＝番方編成の例外は芯が持たない）", x))
    if not 待ち:
        return 暦, 仮たち
    if 決め方 == "曜日を決める":
        曜 = 決.引く("休日.法定休日の曜日") or (括弧 if len(括弧) == 1 and 括弧 in 曜日 else "日")
        for r in 待ち:
            暦[r["日付"]] = "法定" if 曜日[r["日付"].weekday()] == 曜 else "所定"
        return 暦, 仮たち
    if 決め方 == "週の最後の休日":
        週たち = {}
        for r in 待ち:
            週たち.setdefault(週の頭(r["日付"], 起算), []).append(r["日付"])
        for 頭, 日たち in 週たち.items():
            週 = [頭 + timedelta(days=i) for i in range(7)]
            if any(暦.get(x) == "法定" for x in 週):
                for x in 日たち:
                    暦[x] = "所定"
                continue
            休んだ = [x for x in 週 if 種類.get(x) == "休日"]
            働いた = sorted(x for x in 日たち if 種類.get(x) == "休日勤務")
            法定の日 = 休んだ[-1] if 休んだ else (働いた[-1] if 働いた else None)
            for x in 日たち:
                暦[x] = "法定" if x == 法定の日 else "所定"
            if not 休んだ and any(x not in 知っている日 for x in 週):
                for x in 働いた:
                    仮たち.append(仮("週の最後の休日が期間の外にかかり法定休日が決まらない", x))
        return 暦, 仮たち
    # 4週4休（決め方の選べる値の外の字は 一人を集計する の最初に 芯/設定 が照らした＝ここまで来るのは 4週4休 だけ）
    起算日 = 四週の起算日(決, 括弧)
    数 = 線.四週の休日数
    明けの休日 = {x for x in 明け if 種類.get(x) == "休日"}
    if 起算日 is None or 数 is None:
        理由 = "休日.4週の起算日 が無い" if 起算日 is None else "法の線に 休日.4週の休日数 が無い"
        for r in 待ち:
            if r["日付"] in 明けの休日:   # 明けの日は休日でない＝区分を置かず、かかった労働は前の日の勤務（訳は仮の中に）
                仮たち.append(仮(f"{理由}（夜勤の明けの日の労働を前の日の勤務で数えた）", r["日付"]))
                continue
            暦[r["日付"]] = "法定"
            if r["日の種類"] == "休日勤務":
                仮たち.append(仮(f"{理由}（休日勤務を法定で置いた）", r["日付"]))
        return 暦, 仮たち
    起算日 = 日付(起算日)
    塊たち = {}
    for r in 待ち:
        塊たち.setdefault((r["日付"] - 起算日).days // 28, []).append(r["日付"])
    for i, 日たち in 塊たち.items():
        塊 = [起算日 + timedelta(days=i * 28 + j) for j in range(28)]
        休んだ = sum(1 for x in 塊 if 種類.get(x) == "休日" and x not in 明けの休日)
        法定の休日勤務 = sum(1 for x in 塊 if 暦.get(x) == "法定" and 種類.get(x) == "休日勤務")
        足りない = max(0, 数 - 休んだ - 法定の休日勤務)
        働いた = sorted(x for x in 日たち if 種類.get(x) == "休日勤務")
        法定たち = set(働いた[len(働いた) - 足りない:]) if 足りない else set()
        for x in 日たち:
            if x in 明けの休日:
                continue   # 明けの日は休日に数えない・かかった労働は始まりの日の勤務（区分を置かない）
            暦[x] = "法定" if x in 法定たち or 種類.get(x) == "休日" else "所定"
        初め = min(知っている日)
        if (初め in 塊 and 種類.get(初め) == "休日" and 初め not in 明けの休日 and 初め in 日たち
                and 初め - timedelta(days=1) not in 知っている日 and max(0, 数 - (休んだ - 1) - 法定の休日勤務) > len(働いた)):
            # 期間の初日が前の期間の夜勤の明けかは前の表 B が無いと分からない＝明けなら休日が足りない塊は仮（前の期間の日を渡せば消える）
            仮たち.append(仮("期間の初日が前の期間の夜勤の明けか分からず（前の期間の表 A・B を受けていない）4 週の休日が決まらない", 初め))
        塊の明け = sorted(x for x in 塊 if x in 明けの休日)
        if 足りない > len(働いた) and 塊の明け and all(x in 知っている日 for x in 塊):
            for x in 塊の明け:   # 明けの日を除くと 4 週の休日が足りず、法定休日の労働の日が決まらない（黙って 35% を落とさない）
                仮たち.append(仮(f"4 週に暦日の休日が {数} 日に足りない（夜勤の明けの日は休日に数えない）＝法定休日の労働の日が決まらない", x))
        if any(x not in 知っている日 for x in 塊):
            for x in 働いた:
                仮たち.append(仮("4 週の塊が期間の外にかかり法定休日が決まらない", x))
    return 暦, 仮たち


def シフトか(決: 決まり, 型) -> bool:
    """その日の勤務の型（無ければ会社）の `時間.暦` が {"シフト": "勤務した日"}（勤務した日が所定の日・入口が働かない日を休日にする）。"""
    v = 決.引く("時間.暦", 型 or None)
    return isinstance(v, dict) and "シフト" in v


def シフトの休日を確かめる(全: dict, 今: dict, 決: 決まり, 線: 法の線, 起算: str, 明け: set = frozenset()) -> list:
    """シフトの人は働いた日が全部 勤務（休日勤務にならない）＝休日の足りない週（4 週 4 休なら 28 日の塊）は、法定休日の労働の日が
    決まらない（黙って 35% を落とさない）。表 A で全部の日が分かる週・塊に、シフトの日が在り休日が足りなければ、その勤務の日を仮にする。"""
    if not any(シフトか(決, a.get("勤務の型")) for a in 今.values()):
        return []
    決め方, 括弧 = 法定休日の決め方(決)
    明けを除く = set()
    if 決め方 == "4週4休" and 四週の起算日(決, 括弧) is not None and 線.四週の休日数 is not None:
        起算日, 要る = 日付(四週の起算日(決, 括弧)), 線.四週の休日数
        明けを除く = set(明け)   # 夜勤の明けの日は暦日の休日でない（休日の区分を決める と同じ読み）
        塊 = lambda d: (d - 起算日).days // 28  # noqa: E731
        日たち = lambda k: [起算日 + timedelta(days=k * 28 + j) for j in range(28)]  # noqa: E731
    else:
        起算日, 要る = None, 1
        if 決め方 == "4週4休":   # 起算日か法の線の 4 週の休日数が無い＝週ごとに休日 1 つで見る（訳は仮の中に）
            決め方 = "4週4休（休日.4週の起算日 か 法の線の 休日.4週の休日数 が無いので週ごとに見た）"
        塊 = lambda d: 週の頭(d, 起算)  # noqa: E731
        日たち = lambda k: [k + timedelta(days=j) for j in range(7)]  # noqa: E731
    out = []
    for k in sorted({塊(d) for d in 今}):
        ds = 日たち(k)
        if any(d not in 全 for d in ds):
            continue   # 期間の外にかかる週・塊は分からない（前の表 A が無ければ見ない）
        if not any(シフトか(決, 全[d].get("勤務の型")) for d in ds if 全[d]["日の種類"] == "勤務"):
            continue
        if sum(1 for d in ds if 全[d]["日の種類"] == "休日" and d not in 明けを除く) < 要る:   # 年休の日は休日でない（労働の義務のある日）
            for d in ds:
                if d in 今 and 全[d]["日の種類"] == "勤務":
                    out.append(仮(f"シフトの人の週（4 週 4 休なら 4 週）に休日が足りない（法定休日の労働の日が決まらない・{決め方}）", d))
    return out


def 週の法定(決: 決まり, 線: 法の線) -> tuple[int, list]:
    v = 時間の分(決.引く("時間.週の法定"))
    if v is None or v <= 線.週の法定 or v == 線.週の法定の特例:
        return (v or 線.週の法定), []
    if 日の.承知か(決, "時間.週の法定"):   # 承知の印（会社の決まり §1.4）: 会社の値で数える（差は 集計する が数え直して出す）
        return v, []
    return 線.週の法定, [仮("時間.週の法定 が法の線を超える（法の線で数えた）", None, frozenset(分ける語))]


def 移す(結果たち: list, 量: int, 元: tuple[str, ...], 先: str = "法定外"):
    """後ろの日から順に、元の時間を先へ移す（後に働いた分ほど超えた分）。"""
    for r in sorted(結果たち, key=lambda r: r.日付, reverse=True):
        for a in 元:
            if 量 <= 0:
                return
            x = min(量, getattr(r, a))
            setattr(r, a, getattr(r, a) - x)
            setattr(r, 先, getattr(r, 先) + x)
            量 -= x


def _所定どおりの週は線の内か(決, 今: dict, 結果: dict, 頭たち, この週の線) -> bool:
    """出勤簿が無い人（`時間.出勤簿が無い`＝無い）で、期間の勤務の日が全部 定時扱い（所定どおりとみなした日）の時、
    期間の中のまるごとの週（7 日とも期間の中）が全部、その週の線（`この週の線(週)`＝まるごとの週が受ける線）の内か。
    頭の週の前の期間の日も同じ所定どおり＝まるごとの週と同じ線で数えれば超えない。変形（1 年変形の 40 時間を超える週など）は
    週の線が所定の和なので、所定どおりの週は線を超えない。当たらない人・まるごとの週が無い時は False（前の期間の日を求める）。"""
    if str(決.引く("時間.出勤簿が無い") or "").strip() != "無い":
        return False
    if any(r.get("日の種類") in ("勤務", "休日勤務") and "定時扱い" not in 語たち(r.get("印")) for r in 今.values()):
        return False   # 打刻のある日が混じる（原本が来た）＝前の期間の日も原本で受ける
    週たち = [[頭 + timedelta(days=i) for i in range(7)] for 頭 in 頭たち]
    まるごと = [週 for 週 in 週たち if all(x in 今 for x in 週)]
    return bool(まるごと) and all(sum(結果[x].法定外でない for x in 週) <= この週の線(週) for 週 in まるごと)


def _途中入退社の清算(決: 決まり, 期, 始め: date, 終わり: date, 仮たち: list, 委託だけ: bool) -> list[str]:
    """1 年変形の期間の途中で退職した人の退職の月（32 条の 4 の 2 の清算の月）。

    実に働いた期間を平均して週 40 時間を超えた分（日と週で数えた分を除く）を割増で払う＝実の期間の全部の日が要る（この部品は
    今の期間と前の期間の日しか受けない）＝`時間.変形の途中入退社`＝実の期間で清算する（既定・法の線）なら仮＋問い。
    清算しない（他の人と同じ日と週の線だけ）は `法の線.承知` の印があれば会社の値のまま（仮にしない・知らせ）、無ければ法の線で仮。
    途中で入社した人の清算の月は期間の終わりの月＝期間の総枠の清算の仮が全員に立つ月（重ねて問わない）。退職の月が期間の終わりの月と
    同じ時も同じ仮に含める。委託だけの人は労基法の労働者でない＝見ない。返す物: 知らせの文。"""
    if 委託だけ:
        return []
    期 = 期 if isinstance(期, dict) else {}
    try:
        退 = 日付(決.引く("人.退職日")) if not 空(決.引く("人.退職日")) else None
        期の終わり = 日付(期["終わりの日"]) if 期.get("終わりの日") else None
    except 形の誤り as e:
        仮たち.append(仮(f"1 年変形の途中入退社を見る日付が読めない（{e}）", None, frozenset(分ける語)))
        return []
    if 退 is None or not (始め <= 退 <= 終わり):
        return []
    if 期の終わり is not None and 始め <= 期の終わり <= 終わり:
        return []   # 期間の終わりの月（期間の総枠の清算の仮が立つ）
    扱い = 詰め(決.引く("時間.変形の途中入退社")) or "実の期間で清算する"
    if 扱い == "清算しない" and 日の.承知か(決, "時間.変形の途中入退社"):
        問い = 承知の印.読む(承知の印.印の値(決.値たち))[0].get("時間.変形の途中入退社", "")
        return [f"承知した食い違い: 時間.変形の途中入退社（{問い}）＝1 年変形の期間の途中で {退} に退職した人を清算しないで数えた"
                "（他の人と同じ日と週の線だけ）。法の線の清算（実の期間の週 40 時間の平均を超えた分・32 条の 4 の 2）は実の期間の全部の日が要り出していない"]
    if 扱い == "清算しない":
        理由 = "時間.変形の途中入退社＝清算しない は法の線（32 条の 4 の 2）の下で承知の印が無い（清算の月を仮）"
    else:
        理由 = "清算は実の期間の全部の日が要る"
    仮たち.append(仮(f"1 年変形の期間の途中で {退} に退職した人の清算の月（実の期間で週 40 時間の平均を超えた分の割増・32 条の 4 の 2。{理由}）",
                   None, frozenset(分ける語)))
    return []


def 一人を集計する(日たち: list[dict], 区間たち: list[dict], 決まりの値: dict, 線: 法の線,
                 前の日たち: list[dict] = (), 前の区間たち: list[dict] = (), 基準: dict | None = None) -> dict:
    """1 人×1 支給月の表 A・B から、月の数字（縦の形）を出す。

    前の日たち・前の区間たち: 期間の頭の週が前の期間にかかる時の、前の期間の表 A・B（週の判定にだけ使う）。
    基準: {NO: 分}＝同じ会社・同じ月のほかの人の 基準の所定（`割増.月の残業の所定時間`＝基準の人:<NO> の人だけ使う）。
    返す物の `基準の所定` は、この人を基準の人にした時の月の所定（勤務の日と年休の日の所定の和・会社の残業.基準の所定）。
    """
    # 最初に全部の設定を 芯/設定の表.json で照らす（選べる値の外の字は既定で数えて仮＋問い。使う所ごとに照らさない）
    照らした, 外れたち = 設定.照らす(決まりの値 or {}, "集計")
    決 = 決まり(照らした)
    人 = {k: 日たち[0].get(k, "") for k in ("支給月", "会社", "NO", "勤怠の表記")}
    仮たち, 知らせ = [仮(x.文()) for x in 外れたち], []
    外れの名 = sorted({x.名 for x in 外れたち})   # 芯/計算 は同じ名の外れで問いを重ねない（集計のこの問い 1 つに寄せる）

    def 読む(行たち):
        out = {}
        for r in 行たち:
            r = dict(r)
            try:
                r["日付"] = 日付(r["日付"])
            except (形の誤り, KeyError) as e:
                仮たち.append(仮(f"表 A の日付が読めない: {e}"))
                continue
            if r["日付"] in out:
                仮たち.append(仮("表 A に同じ日が 2 行ある", r["日付"]))
                continue
            if r.get("日の種類") not in ("勤務", "休日勤務", "休暇", "欠勤", "休日", "休職・休業"):
                仮たち.append(仮(f"日の種類「{r.get('日の種類')}」は選べる値の外", r["日付"]))
                r["日の種類"] = "欠勤"
            out[r["日付"]] = r
        return out

    今 = 読む(日たち)
    前 = {d: r for d, r in 読む(前の日たち).items() if d not in 今}
    if not 今:
        return {"人": 人, "行": [], "仮": 仮たち, "知らせ": 知らせ, "日": {}, "設定の外れ": 外れの名}
    始め, 終わり = min(今), max(今)
    期間 = [始め + timedelta(days=i) for i in range((終わり - 始め).days + 1)]
    欠けた日 = [d for d in 期間 if d not in 今]
    for d in 欠けた日:
        仮たち.append(仮("期間の日に表 A の行が無い", d))
    区間 = {}
    for b in list(区間たち) + list(前の区間たち):
        try:
            区間.setdefault(日付(b["日付"]), []).append(b)
        except (形の誤り, KeyError):
            仮たち.append(仮("表 B の日付が読めない"))
    for d in 区間:
        if d not in 今 and d not in 前:
            仮たち.append(仮("表 B の区間に表 A の行が無い", d))

    起算 = 決.引く("時間.週の起算") or 週の起算の既定   # 曜日の外の字は最初に 芯/設定 が照らした
    全 = {**前, **今}
    明け = 明けの日たち(区間)
    暦, 暦の仮 = 休日の区分を決める(list(全.values()), 決, 線, 起算, set(全), 明け)
    仮たち += [x for x in 暦の仮 if x.日付 is None or x.日付 in 今]
    仮たち += シフトの休日を確かめる(全, 今, 決, 線, 起算, 明け)

    def 区分を引く(x: date):
        """日またぎで引く日の休日の区分。表 A に無い日（期間の外）は決まりで出す。"""
        if x in 全:
            return 暦.get(x), None
        決め方, 括弧 = 法定休日の決め方(決)
        if 決め方 == "曜日を決める":
            曜 = 決.引く("休日.法定休日の曜日") or (括弧 if len(括弧) == 1 and 括弧 in 曜日 else "日")
            return ("法定" if 曜日[x.weekday()] == 曜 else None), None
        return None, "日またぎの勤務が表 A に無い日にかかり、その日が法定休日か決まらない（法定休日でないとして数えた）"

    結果 = {}
    for d, r in sorted(全.items()):
        結果[d] = 日の.日を数える(r, 区間.get(d, []), 決, 線, 区分を引く)
    for d in 今:
        仮たち += 結果[d].仮たち
        知らせ += 結果[d].知らせ
    今の結果 = [結果[d] for d in sorted(今)]

    # 週と制度の判定
    制度 = 日の.制度の値(決, None)
    線の週, 誤り = 週の法定(決, 線)
    仮たち += 誤り
    印 = {}

    def 印す(項目, 文):
        印.setdefault(項目, []).append(文)

    # 委託だけの人（人.区分＝委託）は労基法の労働者でない＝前の期間の日を求めない（週の判定の仮を出さない）。
    # 週の移しは委託の式（芯/計算/委託.py の月額の残業）が受ける数なので今までどおり数える（期間の中の日だけで）。
    # 委託の併用の人の雇用分は労働者＝今までどおり前の期間の日を求める（役員＋委託の併用 も委託の併用と同じに数える）。
    委託だけ = (区分を読む(決.引く("人.区分")) or frozenset()) == frozenset(所定の無い区分)
    if 制度 in 日の.通常系 + 日の.変形:
        週の所定 = 時間の分(決.引く("時間.週の所定"))
        頭たち = sorted({週の頭(d, 起算) for d in 今})

        def この週の線(週) -> int:
            if 制度 in 日の.変形 or any(結果[x].所定が法定を超える for x in 週 if x in 結果):
                # 変形・承知の印で日の所定を日の法定の上で数えた週（会社の決まり §1.4）は、週の線も所定の和（と週の法定の大きい方）
                知る = [結果[x].所定 for x in 週 if x in 結果]
                return max(線の週, 週の所定 if 週の所定 is not None and len(知る) < 7 else sum(知る))
            return 線の週

        所定どおりで超えない = _所定どおりの週は線の内か(決, 今, 結果, 頭たち, この週の線)
        try:   # 読めない入社日は使わない（今までどおり前の期間の日を求める）
            入社 = 日付(決.引く("人.入社日")) if not 空(決.引く("人.入社日")) else None
        except 形の誤り:
            入社 = None
        for 頭 in 頭たち:
            週 = [頭 + timedelta(days=i) for i in range(7)]
            線のこの週 = この週の線(週)
            累 = 0
            移した = False
            for x in 週:
                if x not in 結果:
                    continue
                r = 結果[x]
                超え = min(r.法定外でない, max(0, 累 + r.法定外でない - 線のこの週))
                累 += r.法定外でない
                if 超え and x in 今:
                    移す([r], 超え, ("法定内", "所定内"))
                    移した = True
            # みなした日（定時扱い: 出勤簿が無い人を所定どおりとみなした日など）の時間も働いた時間と同じに週の線で数える。
            # 変形でない（時間.制度 が通常系）なら週の法定を超えた分は法定外＝37 条の割増（仮にしない）。変形なら上の週の線に従う。
            # 入社日より前の日は在籍していない＝労働は 0 と決まっている（前の期間の日を求めない）
            前が無い = [x for x in 週 if x < 始め and x not in 結果 and not (入社 and x < 入社)]
            # 出勤簿が無い人（時間.出勤簿が無い＝無い・期間の日が全部 定時扱い）は前の期間の日も所定どおり＝前の日を受けなくても
            # 期間の中のまるごとの週（同じ所定どおり）がどれもその週の線の内なら頭の週も超えない＝前の日を求めない（受けても同じ答え）。
            # 比べるのはまるごとの週が受ける線（頭の週の欠けた線でない＝変形の 40 時間を超える週も所定の和の線で比べる）
            if 前が無い and not 委託だけ and not 所定どおりで超えない and any(結果[x].法定外でない for x in 週 if x in 今):
                仮たち.append(仮("期間の頭の週が前の期間にかかり、前の期間の日を受けていない（週の法定の判定）",
                               頭, frozenset(分ける語)))
            if 制度 in 日の.変形 and 移した and any(x not in 結果 for x in 週) and 週の所定 is None:
                仮たち.append(仮("変形の週の所定が期間の外にかかり決まらない（時間.週の所定 が無い）",
                               頭, frozenset(分ける語)))
        if 制度 == "1か月変形":
            期 = 決.引く("時間.変形の期間") or {}
            if isinstance(期, dict) and 期.get("起算日") and 日付(期["起算日"]).day != 始め.day:
                仮たち.append(仮("1 か月変形の期間が給与の期間と揃っていない（期間の総枠を給与の期間で数えた）",
                               None, frozenset(分ける語)))
            総枠 = 線の週 * len(期間) // 7
            超え = sum(r.法定外でない for r in 今の結果) - 総枠
            if 超え > 0:
                移す(今の結果, 超え, ("法定内", "所定内"))
        elif 制度 == "1年変形":
            印す("法定外残業", "1 年変形の期間の総枠は期間の終わりに清算する（この月は日と週だけ）")
            期 = 決.引く("時間.変形の期間") or {}
            if isinstance(期, dict) and 期.get("終わりの日") and 始め <= 日付(期["終わりの日"]) <= 終わり:
                仮たち.append(仮("1 年変形の期間の終わりの月（期間の総枠の清算は期間の全部の日が要る）",
                               None, frozenset(分ける語)))
            知らせ += _途中入退社の清算(決, 期, 始め, 終わり, 仮たち, 委託だけ)
    elif 制度 == "フレックス":
        期 = 決.引く("時間.フレックスの清算期間") or {}
        所定総 = 時間の分(期.get("総労働時間")) if isinstance(期, dict) else None
        if 所定総 is None:
            所定総 = sum(r.所定 for r in 今の結果)
            仮たち.append(仮("時間.フレックスの清算期間 の総労働時間が無い（日の所定の和で置いた）",
                           None, frozenset(分ける語 + ("遅刻早退",))))
        if not (isinstance(期, dict) and 期.get("起算日") and 期.get("終わりの日")
                and 日付(期["起算日"]) == 始め and 日付(期["終わりの日"]) == 終わり):
            仮たち.append(仮("フレックスの清算期間が給与の期間と同じでない（1 か月を超える清算はこの部品で書けない）",
                           None, frozenset(分ける語 + ("遅刻早退",))))
        総 = sum(r.所定内 for r in 今の結果)
        枠 = 線の週 * len(期間) // 7
        移す(今の結果, max(0, 総 - 枠), ("所定内",))
        移す(今の結果, max(0, min(総, 枠) - 所定総), ("所定内",), "法定内")
        if 所定総 > 総:
            今の結果[-1].遅刻早退 += 所定総 - 総
            印す("遅刻早退", "フレックスの清算期間の不足の時間")
    else:  # 管理監督者・高度プロフェッショナル
        for r in 今の結果:
            r.所定内 += r.法定内 + r.法定外 + r.法定休日
            r.法定内 = r.法定外 = r.法定休日 = 0
            r.遅刻早退 = 0
        印す("所定内", f"{制度}（時間外・休日の割増の外。全部を所定内に置いた）")

    # 日数と月の数字
    値 = {k: (Decimal(0) if u == "日" else 0) for k, u in 月の語 if u != "日付"}
    出所 = {k: [] for k, _ in 月の語}
    年休の日 = []

    def 足す(項目, x, d):
        if x:
            値[項目] += x
            出所[項目].append(d)

    休出 = 決.引く("休日.休日出勤の数え方") or {}
    休出に入れる = 詰め(休出.get("出勤日数に入れる")) if isinstance(休出, dict) else ""
    半 = Decimal(1) / 2
    出退の無い日 = []   # 勤務の日で出勤から退勤までの長さが分からない日（時刻の無い みなし の日）
    所定が無い = 委託だけ  # 委託など: 働いた日は所定日数に数えない（出勤日数だけ）
    頭打ちの実働 = 0   # 月の語にしない（出口の欄だけ＝月の数字の口・台帳の形を変えない）。所定内 は週・総枠の移しや制度で動くので別に数える
    for r in 今の結果:
        a = 今[r.日付]
        d = r.日付
        型 = a.get("勤務の型") or None
        休 = a.get("休暇の種類") or ""
        休の単位 = a.get("休暇の単位") or ""
        if r.種類 not in ("休日", "休日勤務") and not 所定が無い:
            足す("所定日数", Decimal(1), d)
        if r.種類 == "勤務":
            日数 = Decimal(2) if r.夜勤 and 詰め(決.引く("時間.夜勤の出勤日数", 型)) == "1勤務=2日" else Decimal(1)
            if 休の単位 in ("午前半休", "午後半休") and 詰め(決.引く("時間.半休の日の数え方", 型)).replace("+", "＋") != "有給0.5＋出勤1":
                日数 -= 半
            足す("出勤日数", 日数, d)
            if a.get("働いた場所") == "在宅":
                足す("在宅の日数", 日数, d)
        elif r.種類 == "休日勤務":
            足す("休日勤務日数（法定）" if 暦.get(d) == "法定" else "休日勤務日数（所定）", Decimal(1), d)
            if 休出に入れる == "入れる":
                足す("出勤日数", Decimal(1), d)
                if a.get("働いた場所") == "在宅":
                    足す("在宅の日数", Decimal(1), d)
        elif r.種類 == "欠勤":
            足す("欠勤", Decimal(1), d)
        elif r.種類 == "休職・休業":
            足す("休業", Decimal(1), d)
        # 休暇
        if 休 and r.種類 in ("勤務", "休暇"):
            量 = Decimal(1) if 休の単位 == "全日" else 半 if 休の単位 in ("午前半休", "午後半休") else Decimal(0)
            if 休 == "年休":
                if 休の単位 == "全日":
                    足す("年休（全日）", Decimal(1), d)
                elif 休の単位 in ("午前半休", "午後半休"):
                    足す("年休（半日）", 1, d)
                elif 休の単位 == "時間":
                    try:
                        休んだ分 = 整数(a.get("休暇の時間"))
                        if 休んだ分 is None and r.種類 != "勤務":   # 勤務の日は 日.py の 日を数える が同じ仮を置いた（問いを重ねない）
                            仮たち.append(仮(日の.休暇の時間が空, d))
                        足す("年休（時間）", 休んだ分 or 0, d)
                    except 形の誤り as e:
                        仮たち.append(仮(f"表 A の形の誤り: {e}", d))
                if 休の単位 in ("全日", "午前半休", "午後半休"):
                    年休の日.append(d)
                足す("年休の時間", 年休の日の時間(a, r, 決, 型, 休の単位, d, 仮たち), d)
            elif 休 == "特別休暇（有給）" or (休 in 日の.看護など and 日の.休暇は有給か(休, 決)):
                足す("特別休暇（有給）", 量, d)
            elif 休 == "特別休暇（無給）" or 休 in 日の.看護など:
                足す("特別休暇（無給）", 量, d)
            elif 休 == "出勤扱い" and r.種類 == "休暇":
                足す("出勤日数", 量, d)
            elif 休 == "代休":
                知らせ.append(f"{d}: 代休の日（月の数字の語に代休が無い。代休の相手の日 {a.get('代休の相手の日', '')}）")
            if 休の単位 == "時間" and 休 != "年休":
                知らせ.append(f"{d}: 時間単位の「{休}」（月の数字の語は日で持つので数えていない）")
        if r.種類 == "休暇" and not 休:
            仮たち.append(仮("休暇の日に休暇の種類が無い", d))
        if r.種類 == "休暇" and 休の単位 in ("午前半休", "午後半休"):
            仮たち.append(仮("半休だけで勤務の無い日（残りの半日が分からない。半休として数えた）", d))
        足す("所定内", r.所定内, d)
        足す("法定内残業", r.法定内, d)
        足す("法定外残業", r.法定外, d)
        足す("法定休日", r.法定休日, d)
        足す("所定休日", r.所定休日, d)
        足す("所定休日の法定外", r.所定休日の法定外, d)
        足す("深夜", r.深夜, d)
        足す("遅刻早退", r.遅刻早退, d)
        足す("夜勤の回数", 1 if r.夜勤 else 0, d)
        if r.出勤から退勤 is None:
            出退の無い日.append(d)
        else:
            足す("出勤から退勤まで", r.出勤から退勤, d)
        足す("夜勤の日を除く所定内", 0 if r.夜勤 else r.所定内, d)   # 時給の日勤と日額の夜勤を両方する人の時給の行の数量（二重に払わない）
        if r.種類 == "勤務":   # 日ごとに実に働いた時間をその日の所定（有給の時間を除く）で頭打ちにした和（出口.実働の上限＝所定・型の版 18）
            頭打ちの実働 += min(r.総 + r.法定休日, max(0, r.所定 - r.休暇の分))
        # 曜日ごとの働いた時間（土曜の時間×時給の手当などの数量）。総労働と同じ数え方で、日またぎは始まりの日（表 A の日付）の曜日に置く
        足す(曜日の時間の頭 + 曜日[d.weekday()], r.所定内 + r.法定内 + r.法定外 + r.法定休日, d)
        for k, v in r.印.items():
            印.setdefault(k, []).extend(v)
    値["総労働"] = 値["所定内"] + 値["法定内残業"] + 値["法定外残業"] + 値["法定休日"]
    # 遅刻早退の数え方（会社の決まり `欠勤.遅刻早退の数え方`・型の版 18）: 月の所定の不足で頭打ち＝勤務の日の所定（有給の時間を除く）の和−総労働 を上限に
    数え方 = 詰め(決.引く("欠勤.遅刻早退の数え方"))
    # `日々の不足（月の所定時間−総労働で頭打ち）`（型の版 24）は日々の不足のまま渡し、頭打ちは 芯/計算 が月の所定時間で 1 回だけ取る
    if 数え方 == "日々の不足（月の所定の不足で頭打ち）" and 値["遅刻早退"]:
        所定の和 = sum(max(0, r.所定 - r.休暇の分) for r in 今の結果 if r.種類 == "勤務")
        上 = max(0, 所定の和 - 値["総労働"])
        if 値["遅刻早退"] > 上:
            印す("遅刻早退", f"日々の不足 {値['遅刻早退']} 分を月の所定の不足 {上} 分で頭打ち（欠勤.遅刻早退の数え方）")
            値["遅刻早退"] = 上
    値["年休の日数"] = 値["年休（全日）"] + 値["年休（半日）"] * 半
    出所["年休の日数"] = sorted(set(出所["年休（全日）"] + 出所["年休（半日）"]))
    if 出退の無い日:
        # 長さの分からない日を 0 にすると欄が黙って短くなる＝行を出さない（出口はその欄を空で書き 空の欄 に返す）
        知らせ.append("出勤から退勤まで: 時刻の無い日がある（" + "・".join(d.isoformat() for d in 出退の無い日) + "）＝行を出さない")
    出所["総労働"] = sorted(set(出所["所定内"] + 出所["法定内残業"] + 出所["法定外残業"] + 出所["法定休日"]))
    if 線.六十時間 is None:
        仮たち.append(仮("法の線に 割増.60時間超の境 が無い", None, frozenset({"60 時間超"})))
    else:
        値["60 時間超"] = max(0, 値["法定外残業"] - 線.六十時間)
        if 値["60 時間超"]:
            出所["60 時間超"] = 出所["法定外残業"]

    # 休日でない日の所定（月で数える会社の残業の月の所定・基準の所定）: 勤務の日は日の結果、ほかの日（休暇・欠勤・休業）は表 A か決まり
    日の所定 = {}
    for r in 今の結果:
        if r.種類 in ("休日", "休日勤務"):
            continue
        if r.種類 == "勤務":
            日の所定[r.日付] = r.所定
            continue
        a = 今[r.日付]
        try:
            x = 整数(a.get("所定時間"))
            日の所定[r.日付] = x if x is not None else 時間の分(決.曜日の値("時間.日の所定", r.日付, a.get("勤務の型") or None))
        except 形の誤り:
            日の所定[r.日付] = None
    会社 = 会社の残業.数える(決, 線, 制度, 今の結果, 値, 基準, 日の所定)
    if 会社:
        仮たち += 会社["仮"]
        知らせ += 会社["知らせ"]

    行たち = []
    for 項目, u in 月の語:
        if 項目 == "出勤から退勤まで" and 出退の無い日:
            continue
        if 項目 == "年休を取った日":
            for d in 年休の日:
                行たち.append(行を作る(人, 項目, d.isoformat(), [d], [], 仮たち))
            continue
        行たち.append(行を作る(人, 項目, 値[項目], sorted(set(出所[項目])), 印.get(項目, []), 仮たち))
    if 会社 and 会社["値"]:
        # 会社の数え方の語は、日の時間（時間の語）を変える仮にも効く
        関わる = frozenset(時間の語)
        for 項目, u in 会社の残業.会社の語:
            行たち.append(行を作る(人, 項目, 会社["値"][項目], sorted(set(会社["出所"].get(項目, []))),
                               会社["印"].get(項目, []), 仮たち, u, 関わる))
    return {"人": 人, "行": 行たち, "仮": [x for x in 仮たち], "知らせ": 知らせ, "日": 結果, "設定の外れ": 外れの名, "所定で頭打ちの実働": 頭打ちの実働,
            "基準の所定": 会社の残業.基準の所定(今の結果, set(年休の日), 日の所定)}


# 語の中身がほかの語から出る語: その語を変える仮はこの語にも効く
内の語 = {"夜勤の日を除く所定内": frozenset({"所定内", "夜勤の回数"}),
         "年休の日数": frozenset({"年休（全日）", "年休（半日）"}),
         **{k: frozenset({"総労働"}) for k in 曜日の時間の語}}   # 曜日の時間は総労働の内訳（週の判定で分け直しても和は変わらない）


def 年休の日の時間(a: dict, r, 決: 決まり, 型, 単位: str, d, 仮たち: list) -> int:
    """年休で休んだその日の時間（分。月の語 `年休の時間`・型の版 21）。時給の人の有休の時間（時給×年休の時間）の数量。
    全日: 表 A の 休暇の時間（原本の区分に書かれた時間〔`有給休暇（6:00）`〕を入口が置く）→ 勤務の型の `有給.1日の時間`（分）→ その日の所定。
    半日: その日の休んだ分（`有給.半日`・所定の半分）。時間: 表 A の 休暇の時間。どれも無い日は 0 で見当して仮。"""
    try:
        if 単位 == "時間":
            return 整数(a.get("休暇の時間")) or 0   # 空は上の 年休（時間） の所か 日.py が仮にした（ここで重ねない）
        if 単位 in ("午前半休", "午後半休"):
            return r.休暇の分
        if 単位 != "全日":
            return 0
        x = 整数(a.get("休暇の時間"))
        if x is None:
            x = 整数(決.引く("有給.1日の時間", 型))   # 分の数（段の解決が分に直して渡す・有給/README）
        if x is None:
            x = 時間の分(決.曜日の値("時間.日の所定", d, 型))
    except 形の誤り as e:
        仮たち.append(仮(f"年休の日の時間が読めない: {e}", d, frozenset({"年休の時間"})))
        return 0
    if x is None:
        仮たち.append(仮("年休の日の時間が無い（休暇の時間・有給.1日の時間・時間.日の所定 のどれも無い。0 で置いた）", d,
                       frozenset({"年休の時間"})))
        return 0
    return x


def 行を作る(人: dict, 項目: str, 値, 出所: list, 印: list, 仮たち: list, u: str | None = None,
          関わる: frozenset = frozenset()) -> dict:
    関わる = 関わる | 内の語.get(項目, frozenset())
    効く = [x for x in 仮たち if x.項目 is None or 項目 in x.項目 or 関わる & x.項目]
    return {
        **人,
        "項目": 項目,
        "値": 値,
        "単位": u or 単位[項目],
        "状態": "仮" if 効く else "確定",
        "出所": "、".join(d.isoformat() if isinstance(d, date) else str(d) for d in 出所),
        "印": "、".join(dict.fromkeys(印)),
        "見当": 値 if 効く else "",
        "見当の拠り所": "、".join(dict.fromkeys(x.理由 for x in 効く)),
        "_仮": 効く,
    }
