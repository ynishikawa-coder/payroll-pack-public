"""芯の集計: 表 A「日」・表 B「区間」（または月の数字の口）と決まり・法の線から、月の数字（縦の形）を出す。

呼び口は `集計する` 1 つ。形と使い方は README.md。芯は Drive を開かない（受け取って返すだけ）。
"""
from .形 import 仮, 月の語, 形の誤り, 詰め
from .形 import 法の線 as 線の形
from .月 import 一人を集計する
from .口 import 一人を通す
from .法の線の橋 import 法の線を引く

__all__ = ["集計する", "一人を集計する", "一人を通す", "法の線を引く", "月の語", "形の誤り", "勤怠が無い", "日ごとの実働"]

勤怠が無い = "勤怠が無い（表 A も月の数字の口も来ない。役員は勤怠なしで計算する・ほかの人は勤怠の要らない式が無い）"

鍵の列 = ("支給月", "会社", "NO")
委託の区分 = ("委託", "委託の併用")


def 日ごとの実働(日: dict) -> dict:
    """一人を集計する の 日（{日付: 日の結果}）→ {日付: 分}（芯/計算 の `委託.日ごとの実働` の形）。
    勤務の日の実働（休憩・外出を引いた労働＝法定休日の外＋法定休日・定時扱いとみなしの日はその時間）。
    休日勤務の日は入れない（休日出勤×時給×休日の率で別に払う＝前の道具 timecard_tally の 休日出勤 の行は日ごとに入れない）。
    全日の休暇・欠勤・休日も入れない（半休＋勤務の日は勤務の分を入れる）。"""
    return {d.isoformat(): r.総 + r.法定休日 for d, r in sorted(日.items()) if r.種類 == "勤務"}


def _鍵(r: dict) -> tuple:
    return tuple(str(r.get(k, "")) for k in 鍵の列)


def 集計する(表A=(), 表B=(), *, 決まり: dict | None = None, 法の線: dict, 月の口=(), 前の表A=(), 前の表B=(),
           支給月: str | None = None) -> dict:
    """月の数字を出す。

    表A・表B: 勤怠の形.md 1・2 節の行（列名の dict）。
    決まり: {(会社, NO): {`分野.名`: 値, "勤務の型": {型: {…}}}}。その人のその月に効く値（段の解決は手前で済ませる）。
    法の線: {"時間.日の法定": …, "時間.週の法定": …, "割増.深夜の時間帯": …, …}（形.法の線）。法の表から作るなら `法の線を引く(始め, 終わり)`。
    月の口: 勤怠の形.md 5 節の行（月の合計しか無い会社）。
    前の表A・前の表B: 期間の頭の週が前の期間にかかる時の、前の期間の行（週の判定にだけ使う）。
    支給月: 決まりに居て勤怠の来ない人の支給月（省けば表 A・月の口の支給月が 1 つの時それを使う）。
      勤怠の来ない人は黙って抜けずに、人の状態に `勤怠が無い`: True で返す（役員＝確認済・ほか＝仮と知らせ。問いは芯/計算 が出す）。

    返す物: {"行": 人×項目の行, "人": 人の状態, "問い": 確認の問い, "知らせ": 仮にしない知らせ,
            "日ごとの実働": [{"支給月", "会社", "NO", "日ごと": {日付: 分}}]（決まりの `人.区分` が 委託・委託の併用 で
                           表 A から数えた人だけ。芯/計算 の 入力 の `委託.日ごとの実働` へ渡す＝初期設定/入口の文脈.計算の入力）}
    """
    線 = 線の形.読む(法の線)
    決まり = 決まり or {}
    人たち, 区間, 前A, 前B, 口 = {}, {}, {}, {}, {}
    for r in 表A:
        人たち.setdefault(_鍵(r), []).append(r)
    for r in 表B:
        区間.setdefault(_鍵(r), []).append(r)
    for r in 前の表A:
        前A.setdefault((str(r.get("会社", "")), str(r.get("NO", ""))), []).append(r)
    for r in 前の表B:
        前B.setdefault((str(r.get("会社", "")), str(r.get("NO", ""))), []).append(r)
    for r in 月の口:
        口.setdefault(_鍵(r), []).append(r)

    出た = {}
    for 鍵, 日たち in 人たち.items():
        会社NO = 鍵[1:]
        出た[鍵] = (一人を集計する(日たち, 区間.pop(鍵, []), 決まり.get(会社NO), 線,
                               前A.get(会社NO, []), 前B.get(会社NO, [])))
    for 鍵, 行たち in 口.items():
        if 鍵 in 出た:
            出た[鍵]["仮"].append(仮("表 A と月の数字の口の両方から来た人（日から出した方を使い、口の行は通さない）"))
            for r in 出た[鍵]["行"]:
                r["_仮"] = r["_仮"] + [出た[鍵]["仮"][-1]]
                r["状態"], r["見当"] = "仮", r["値"]
            continue
        出た[鍵] = 一人を通す(行たち)
    知らせ = [f"表 B に表 A の人が無い: {'・'.join(k)}" for k in 区間]
    実働 = [{"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "日ごと": 日ごとの実働(x["日"])} for 鍵, x in 出た.items()
          if x.get("日") and 詰め((決まり.get(鍵[1:]) or {}).get("人.区分")) in 委託の区分]

    # 決まりに居て勤怠の来ない人: 黙って抜けない。役員（`人.区分`）は勤怠が要らない＝確認済。
    # ほかの人は仮。問いは芯/計算 が 1 つ出す（集計と計算で同じ人に 2 問を出さない）＝集計は知らせだけ。
    # 支給月が決まらない時は計算が人を引けないので、集計が問いを出す。
    来た = {k[1:] for k in 出た}
    無い人 = sorted(k for k in 決まり if tuple(map(str, k)) not in 来た)
    無い人の状態, 支給月の問い = [], []
    if 無い人:
        月たち = {k[0] for k in 出た}
        月 = 支給月 or (next(iter(月たち)) if len(月たち) == 1 else None)
        for k in 無い人:
            会社, NO = map(str, k)
            役員 = 詰め((決まり.get(k) or {}).get("人.区分")) == "役員"
            if 月 is None:
                if not 役員:
                    支給月の問い.append((会社, NO))
                知らせ.append(f"{会社} {NO}: {勤怠が無い}。支給月が決まらない（支給月= を渡す）")
                continue
            無い人の状態.append({"支給月": 月, "会社": 会社, "NO": NO, "勤怠の表記": "", "勤怠が無い": True,
                            "状態": "確認済" if 役員 else "仮", "仮の数": 0 if 役員 else 1})
            if not 役員:
                知らせ.append(f"{会社} {NO}: {勤怠が無い}（問いは芯/計算 が出す）")

    # 問い: 同じ理由は人と日を並べて 1 問にする
    問い, 番号 = [], {}
    行たち, 人の状態 = [], []
    for x in 出た.values():
        人 = x["人"]
        for p in x["仮"]:
            if p.理由 not in 番号:
                番号[p.理由] = f"問{len(番号) + 1}"
                問い.append({"番号": 番号[p.理由], "何が無いか": p.理由, "人": [], "日付": [], "変わる項目": []})
            q = 問い[int(番号[p.理由][1:]) - 1]
            if (人["会社"], 人["NO"]) not in q["人"]:
                q["人"].append((人["会社"], 人["NO"]))
            if p.日付 and p.日付.isoformat() not in q["日付"]:
                q["日付"].append(p.日付.isoformat())
        仮の数 = 0
        for r in x["行"]:
            効く = r.pop("_仮")
            r["問い"] = "、".join(dict.fromkeys(番号[p.理由] for p in 効く))
            for p in 効く:
                q = 問い[int(番号[p.理由][1:]) - 1]
                if r["項目"] not in q["変わる項目"]:
                    q["変わる項目"].append(r["項目"])
            仮の数 += r["状態"] == "仮"
            行たち.append(r)
        if x["仮"] and not x["行"]:
            仮の数 += 1
        人の状態.append({**人, "状態": "仮" if 仮の数 else "確認済", "仮の数": 仮の数})
        知らせ += [f"{人['会社']} {人['NO']}: {t}" for t in x["知らせ"]]
    人の状態 += 無い人の状態
    if 支給月の問い:
        問い.append({"番号": f"問{len(問い) + 1}", "何が無いか": f"{勤怠が無い}。支給月が決まらない",
                   "人": 支給月の問い, "日付": [], "変わる項目": ["全部"]})
    return {"行": 行たち, "人": 人の状態, "問い": 問い, "知らせ": 知らせ, "日ごとの実働": 実働}
