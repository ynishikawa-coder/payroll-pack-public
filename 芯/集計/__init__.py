"""芯の集計: 表 A「日」・表 B「区間」（または月の数字の口）と決まり・法の線から、月の数字（縦の形）を出す。

呼び口は `集計する` 1 つ。形と使い方は README.md。芯は Drive を開かない（受け取って返すだけ）。
"""
from . import 会社の残業
from . import 形
from .形 import 仮, 月の語, 形の誤り
from .形 import 法の線 as 線の形
from .月 import 一人を集計する
from .口 import 一人を通す
from .法の線の橋 import 法の線を引く
from 芯.計算 import 承知 as 承知の印
from 芯.計算.形 import 区分を読む

__all__ = ["集計する", "一人を集計する", "一人を通す", "法の線を引く", "月の語", "形の誤り", "勤怠が無い", "日ごとの実働",
           "日の実働", "日の休憩と労働"]

勤怠が無い = "勤怠が無い（表 A も月の数字の口も来ない。役員は勤怠なしで計算する・ほかの人は勤怠の要らない式が無い）"

鍵の列 = ("支給月", "会社", "NO")
委託の区分 = ("委託", "委託の併用")  # 役員＋委託の併用 も委託分がある（区分を読む で語の組にして見る）


def 日の実働(r) -> int:
    """1 日の実働（休憩・外出を引いた労働＝法定休日の外＋法定休日・定時扱いとみなしの日はその時間）。日を足すと月の 総労働。
    委託の日ごとの実働と台帳「勤怠」の 労働の合計 の 1 か所。"""
    return r.総 + r.法定休日


def 日ごとの実働(日: dict) -> dict:
    """一人を集計する の 日（{日付: 日の結果}）→ {日付: 分}（芯/計算 の `委託.日ごとの実働` の形）。
    勤務の日の実働（日の実働）。休日勤務の日は入れない（休日出勤×時給×休日の率で別に払う＝前の道具 timecard_tally の 休日出勤 の行は日ごとに入れない）。
    全日の休暇・欠勤・休日も入れない（半休＋勤務の日は勤務の分を入れる）。"""
    return {d.isoformat(): 日の実働(r) for d, r in sorted(日.items()) if r.種類 == "勤務"}


def 日の休憩と労働(r) -> tuple[int | None, int | None]:
    """1 日の (休憩, 労働)（分）＝芯が数えた値（台帳「勤怠」の写し 休憩の合計・労働の合計 の作り方の 1 か所）。
    休憩＝その日に労働から引いた休憩（休憩の区間・休憩の表・組の間の空き・時刻の無い休憩・長さの表）。労働＝日の実働。
    勤務の日でない日は (None, None)。形の誤り・打刻抜けの日は (None, None)（見当を確かな値に見せない）。時刻も長さも無い日（時刻の無い みなし）の休憩は None。"""
    if r.種類 not in ("勤務", "休日勤務") or r.要約できない:
        return None, None
    return r.休憩, 日の実働(r)


def _法の線で数え直す(日たち, 区間たち, 決まりの値: dict, 線, 前の日たち, 前の区間たち, 会社の行,
                  基準: dict | None = None) -> tuple[dict, list[str]]:
    """承知の印（会社の決まり §1.4）のある集計の線ごとに、その線の印だけを外して法の線で数え直し、月の数字の違う語を返す。

    返す物: ({線: {"問い": 問いの番号, "語": {語: 法の線で数えた値}}}, 知らせの文)。違いの無い線は入れない。
    会社の値で数えた月の数字（払うのはこの方）は変えない。差額（円）は 芯/計算 が この語で計算し直して出す。"""
    # 数える日に効く印だけ（日ごとの読み 承知か と同じ上書きの形。週の線は型の無い読み＝None も入れる）
    日の型たち = [None, *((r.get("勤務の型") or None) for r in 日たち)]
    印 = {k: q for k, q in 承知の印.線たち(決まりの値, 日の型たち).items() if k in 承知の印.集計の線}
    if not 印:
        return {}, []
    会社 = {r["項目"]: r["値"] for r in 会社の行 if r["項目"] != "年休を取った日"}
    差, 文 = {}, []
    for 線名, 問い in 印.items():
        法 = 一人を集計する(日たち, 区間たち, 承知の印.外す(決まりの値, 線名), 線, 前の日たち, 前の区間たち, 基準)
        語 = {r["項目"]: r["値"] for r in 法["行"] if r["項目"] != "年休を取った日" and 会社.get(r["項目"]) != r["値"]}
        if 語:
            差[線名] = {"問い": 問い, "語": 語}
            文.append(f"承知した食い違い: {線名}（{問い}）＝会社の値で数えた。法の線で数えると "
                     + "・".join(f"{k} {会社.get(k, 0)}→{v}" for k, v in 語.items()) + "（差額は 芯/計算 の知らせ）")
    return 差, 文


def _鍵(r: dict) -> tuple:
    return tuple(str(r.get(k, "")) for k in 鍵の列)


def 集計する(表A=(), 表B=(), *, 決まり: dict | None = None, 法の線: dict, 月の口=(), 前の表A=(), 前の表B=(),
           支給月: str | None = None) -> dict:
    """月の数字を出す。

    表A・表B: 勤怠の形.md 1・2 節の行（列名の dict）。
    決まり: {(会社, NO): {`分野.名`: 値, "勤務の型": {型: {…}}}}。その人のその月に効く値（段の解決は手前で済ませる）。
    法の線: {"時間.日の法定": …, "時間.週の法定": …, "割増.深夜の時間帯": …, …}（形.法の線）。法の表から作るなら `法の線を引く(始め, 終わり)`。
    月の口: 勤怠の形.md 5 節の行（月の合計しか無い会社）。
    前の表A・前の表B: 期間の頭の週が前の期間にかかる時の、前の期間の行（週の判定にだけ使う）。
    支給月: 決まりに居て勤怠の来ない人の支給月（省けば表 A・月の口の支給月が 1 つの時それを使う）。
      勤怠の来ない人は黙って抜けずに、人の状態に `勤怠が無い`: True で返す（役員＝確認済・ほか＝仮と知らせ。問いは芯/計算 が出す）。

    返す物: {"行": 人×項目の行, "人": 人の状態, "問い": 確認の問い, "知らせ": 仮にしない知らせ,
            "日ごとの実働": [{"支給月", "会社", "NO", "日ごと": {日付: 分}}]（決まりの `人.区分` が 委託・委託の併用 で
                           表 A から数えた人だけ。芯/計算 の 入力 の `委託.日ごとの実働` へ渡す＝初期設定/入口の文脈.計算の入力）,
            "日の要約": [{"支給月", "会社", "NO", "日付", "休憩", "労働"}]（表 A の日ごとに芯が数えた休憩と労働の分＝日の休憩と労働。
                       台帳「勤怠」の写し 休憩の合計・労働の合計 へ＝月次/台帳の形.py。人が読むだけ＝計算に使わない）}
    """
    線 = 線の形.読む(法の線)
    決まり = 決まり or {}
    人たち, 区間, 前A, 前B, 口 = {}, {}, {}, {}, {}
    for r in 表A:
        人たち.setdefault(_鍵(r), []).append(r)
    for r in 表B:
        区間.setdefault(_鍵(r), []).append(r)
    for r in 前の表A:
        前A.setdefault((str(r.get("会社", "")), str(r.get("NO", ""))), []).append(r)
    for r in 前の表B:
        前B.setdefault((str(r.get("会社", "")), str(r.get("NO", ""))), []).append(r)
    for r in 月の口:
        口.setdefault(_鍵(r), []).append(r)

    出た, 法の線で数えた, 日の要約 = {}, {}, []
    区間たちの表 = {鍵: 区間.pop(鍵, []) for 鍵 in 人たち}
    # `割増.月の残業の所定時間`＝基準の人:<NO>（会社の段＝基準の人も含む全員に同じ値）: 1 回目で全員の 基準の所定 を数え、
    # 2 回目でその値を持つ人だけ数え直す（同じ支給月・同じ会社の人。基準の人は自分の所定を使う）。
    # 基準の人の仮は、会社の数え方の語だけに効く仮（1 回目に基準が無くて付いた仮）を除いて見る
    基準を使う = {鍵 for 鍵 in 人たち if 会社の残業.基準の人(形.決まり(決まり.get(鍵[1:]) or {})) is not None}

    def 数える(鍵, 基準=None):
        会社NO = 鍵[1:]
        x = 一人を集計する(人たち[鍵], 区間たちの表[鍵], 決まり.get(会社NO), 線, 前A.get(会社NO, []), 前B.get(会社NO, []), 基準)
        差, 文 = _法の線で数え直す(人たち[鍵], 区間たちの表[鍵], 決まり.get(会社NO) or {}, 線, 前A.get(会社NO, []),
                             前B.get(会社NO, []), x["行"], 基準)
        return x, 差, 文

    def 基準に使えるか(x) -> bool:
        return x.get("基準の所定") is not None and all(p.項目 and p.項目 <= 会社の残業.会社の語の名 for p in x["仮"])

    一回目 = {鍵: 数える(鍵) for 鍵 in 人たち}
    for 鍵, (x, 差, 文) in 一回目.items():
        if 鍵 in 基準を使う:
            基準 = {k[2]: y["基準の所定"] for k, (y, _, _) in 一回目.items() if k[:2] == 鍵[:2] and 基準に使えるか(y)}
            x, 差, 文 = 数える(鍵, 基準)
        出た[鍵] = x
        if 差:
            法の線で数えた[鍵] = 差
            出た[鍵]["知らせ"] += 文
        今の日 = {str(r.get("日付", "")).strip() for r in 人たち[鍵]}   # 前の表 A の日（週の判定だけに使う）は出さない
        for d, y in sorted(x["日"].items()):
            if d.isoformat() in 今の日:
                休, 労 = 日の休憩と労働(y)
                日の要約.append({"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "日付": d.isoformat(), "休憩": 休, "労働": 労})
    for 鍵, 行たち in 口.items():
        if 鍵 in 出た:
            出た[鍵]["仮"].append(仮("表 A と月の数字の口の両方から来た人（日から出した方を使い、口の行は通さない）"))
            for r in 出た[鍵]["行"]:
                r["_仮"] = r["_仮"] + [出た[鍵]["仮"][-1]]
                r["状態"], r["見当"] = "仮", r["値"]
            continue
        出た[鍵] = 一人を通す(行たち)
    知らせ = [f"表 B に表 A の人が無い: {'・'.join(k)}" for k in 区間]
    実働 = [{"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "日ごと": 日ごとの実働(x["日"])} for 鍵, x in 出た.items()
          if x.get("日") and (区分を読む((決まり.get(鍵[1:]) or {}).get("人.区分")) or frozenset()) & set(委託の区分)]

    # 決まりに居て勤怠の来ない人: 黙って抜けない。役員（`人.区分`）は勤怠が要らない＝確認済（役員＋委託の併用 は委託分に勤怠が要る＝仮）。
    # ほかの人は仮。問いは芯/計算 が 1 つ出す（集計と計算で同じ人に 2 問を出さない）＝集計は知らせだけ。
    # 支給月が決まらない時は計算が人を引けないので、集計が問いを出す。
    来た = {k[1:] for k in 出た}
    無い人 = sorted(k for k in 決まり if tuple(map(str, k)) not in 来た)
    無い人の状態, 支給月の問い = [], []
    if 無い人:
        月たち = {k[0] for k in 出た}
        月 = 支給月 or (next(iter(月たち)) if len(月たち) == 1 else None)
        for k in 無い人:
            会社, NO = map(str, k)
            役員 = 区分を読む((決まり.get(k) or {}).get("人.区分")) == frozenset({"役員"})
            if 月 is None:
                if not 役員:
                    支給月の問い.append((会社, NO))
                知らせ.append(f"{会社} {NO}: {勤怠が無い}。支給月が決まらない（支給月= を渡す）")
                continue
            無い人の状態.append({"支給月": 月, "会社": 会社, "NO": NO, "勤怠の表記": "", "勤怠が無い": True,
                            "状態": "確認済" if 役員 else "仮", "仮の数": 0 if 役員 else 1})
            if not 役員:
                知らせ.append(f"{会社} {NO}: {勤怠が無い}（問いは芯/計算 が出す）")

    # 問い: 同じ理由は人と日を並べて 1 問にする
    問い, 番号 = [], {}
    行たち, 人の状態 = [], []
    for x in 出た.values():
        人 = x["人"]
        for p in x["仮"]:
            if p.理由 not in 番号:
                番号[p.理由] = f"問{len(番号) + 1}"
                問い.append({"番号": 番号[p.理由], "何が無いか": p.理由, "人": [], "日付": [], "変わる項目": []})
            q = 問い[int(番号[p.理由][1:]) - 1]
            if (人["会社"], 人["NO"]) not in q["人"]:
                q["人"].append((人["会社"], 人["NO"]))
            if p.日付 and p.日付.isoformat() not in q["日付"]:
                q["日付"].append(p.日付.isoformat())
        仮の数 = 0
        for r in x["行"]:
            効く = r.pop("_仮")
            r["問い"] = "、".join(dict.fromkeys(番号[p.理由] for p in 効く))
            for p in 効く:
                q = 問い[int(番号[p.理由][1:]) - 1]
                if r["項目"] not in q["変わる項目"]:
                    q["変わる項目"].append(r["項目"])
            仮の数 += r["状態"] == "仮"
            行たち.append(r)
        if x["仮"] and not x["行"]:
            仮の数 += 1
        人の状態.append({**人, "状態": "仮" if 仮の数 else "確認済", "仮の数": 仮の数,
                     **({"法の線で数えた": 法の線で数えた[_鍵(人)]} if _鍵(人) in 法の線で数えた else {}),
                     **({"設定の外れ": x["設定の外れ"]} if x.get("設定の外れ") else {})})
        知らせ += [f"{人['会社']} {人['NO']}: {t}" for t in x["知らせ"]]
    人の状態 += 無い人の状態
    if 支給月の問い:
        問い.append({"番号": f"問{len(問い) + 1}", "何が無いか": f"{勤怠が無い}。支給月が決まらない",
                   "人": 支給月の問い, "日付": [], "変わる項目": ["全部"]})
    # 出口.実働の上限＝所定 の欄（型の版 18）: 日から数えた人だけ（月の数字の口の人は日が無い＝出口が総労働のまま仮にする）
    頭打ち = [{"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "分": x["所定で頭打ちの実働"]} for 鍵, x in 出た.items()
            if "所定で頭打ちの実働" in x]
    return {"行": 行たち, "人": 人の状態, "問い": 問い, "知らせ": 知らせ, "日ごとの実働": 実働, "所定で頭打ちの実働": 頭打ち,
            "日の要約": 日の要約}
