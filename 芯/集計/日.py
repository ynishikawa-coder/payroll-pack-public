def 休暇は有給か(種類: str, 決: 決まり) -> bool:
    if 種類 in 有給の休暇:
        return True
    if 種類 in 看護など:
        return 詰め(決.引く("休暇.子の看護など")) == "有給"
    return False


def 長さの休憩(段たち, 労働の分: int) -> int:
    return max([b for a, b in 段たち if 労働の分 > a], default=0)


def 法の休憩(線: 法の線, 労働の分: int) -> int:
    return 長さの休憩(線.休憩の長さ, 労働の分)


def 会社の休憩の長さ(決: 決まり, 型: str | None) -> tuple[tuple[tuple[int, int], ...], str | None]:
    """会社の `時間.休憩の長さ`（[[超える時間, 休憩の分], …]・初期設定の段の解決が休憩の表の長さの形から作る）。

    読めなければ () と仮の理由（法の線の長さで置く）。34 条より短い時は休憩の 34 条の知らせが別に出る。
    """
    v = 決.引く("時間.休憩の長さ", 型)
    if not v:
        return (), None
    try:
        return tuple(sorted((時間の分(a), 整数(b)) for a, b in v)), None
    except (形の誤り, TypeError, ValueError):
        return (), f"時間.休憩の長さ「{v}」が [[超える時間, 休憩の分], …] の形でない（法の線の長さで置いた）"


def 深夜帯(決: 決まり, 線: 法の線, 型: str | None, d: date) -> tuple[tuple[int, int], list]:
    """会社が広げた深夜帯を使う。法の線より狭い値は法の線で数え仮にする（会社の決まり.md §1.1）。
    承知の印（§1.4）がある時だけ狭い値のまま数える（仮にしない。法の線との差は 集計する が数え直して出す）。"""
    v = 決.引く("割増.深夜の時間帯", 型)
    if v is None:
        return 線.深夜帯, []
    s, e = 時間帯(v)
    if s <= 線.深夜帯[0] and e >= 線.深夜帯[1]:
        return (s, e), []
    if 承知か(決, "割増.深夜の時間帯", 型):
        return (s, e), []
    return 線.深夜帯, [仮("割増.深夜の時間帯 が法の線より狭い（法の線で数えた）", d, frozenset({"深夜"}))]


月給の形 = ("月給", "日給月給", "年俸")   # 芯/計算/支給控除.py の 月給の形 と同じ（欠勤.遅刻早退の控除 の 月給の人だけ引く と同じ線）


def 有給を足すか(決: 決まり, 型) -> bool:
    """`有給.出勤時間に足す`（足さない・足す・月給の人だけ足す・時給の人だけ足す。人の段にも置ける）→ 有給の時間を時間外の判定に足すか。

    だけ の値は `支払.賃金の形` で分ける。賃金の形が空は 形の誤り（呼ぶ側が仮にする＝黙って足さないにしない）。
    選べる値の外の字は 一人を集計する の最初に 芯/設定 が照らした（ここでは照らさない）。"""
    v = 詰め(決.引く("有給.出勤時間に足す", 型))
    if v in ("", "足さない"):
        return False
    if v == "足す":
        return True
    形 = 詰め(決.引く("支払.賃金の形"))
    if not 形:
        raise 形の誤り(f"有給.出勤時間に足す「{v}」なのに 支払.賃金の形 が空（足すか決まらない）")
    return 形 in 月給の形 if v == "月給の人だけ足す" else 形 == "時給"


休暇の時間が空 = "休暇の単位＝時間 なのに 休暇の時間 が空（休んだ分を 0 分で見当した＝原本の時間を表 A の 休暇の時間 に書く）"


def 退勤の境の休憩(境たち, 退勤: int | None, 決: 決まり, 出勤: int | None = None) -> tuple[int, str | None]:
    """`時間.休憩の表` の退勤の境の形の休憩（分）と仮の理由。退勤の時刻が境を越えた（境ちょうどは越えない）境ごとに長さを足す。
    境に区分（`退勤18:00超30分（パート）`）があれば、その `人.区分` を持つ人だけ。性別（`（女）`）があれば、その `人.性別` の人だけ。
    性別で分かれた境があるのに `人.性別` が無い人は、性別の付いた境を引かずに仮の理由を返す（黙ってどちらかの境で数えない）。
    境に休憩の時間帯の始まり（`退勤10:45超15分（10:30〜）`）があれば、出勤がその始まり以後の日は引かない（遅れて出勤した日の出勤前の休憩）。
    始まりの無い境は出勤を見ない（前のまま）。"""
    if not 境たち or 退勤 is None:
        return 0, None
    区分 = 区分を読む(決.引く("人.区分")) or frozenset()
    性別 = 設定.性別の語().get(設定.揃える(決.引く("人.性別")))
    理由 = None
    if 性別 is None and any(b.性別 for b in 境たち):
        理由 = "人.性別 が無い（時間.休憩の表 の退勤の境が性別で分かれる＝性別の付いた境を引かずに数えた）"
    return sum(b.長さ for b in 境たち
               if 退勤 > b.境 and (b.区分 is None or b.区分 in 区分) and (b.性別 is None or b.性別 == 性別)
               and (b.始まり is None or 出勤 is None or 出勤 < b.始まり)), 理由


def 日を数える(行: dict, 区間たち: list[dict], 決: 決まり, 線: 法の線, 暦) -> 日の結果:
    """表 A の 1 行とその日の表 B から、その日の時間を出す。止めずに、形の誤りや足りない値は仮にする。

    暦: 日付 → (`法定`／`所定`／None, 仮の理由／None) を返す呼び口。日またぎで表 A に無い日（期間の外）へかかる時も引く。
    """
    d = 行["日付"]
    型 = 行.get("勤務の型") or None
    r = 日の結果(d, 行["日の種類"])
    印 = 語たち(行.get("印"))
    if 行.get("読み取りの確かめ") != "確認済":
        r.仮たち.append(仮("読み取りの確かめが要確認の日がある", d))
    if "原本に無い" in 印:
        r.仮たち.append(仮("原本に無い日がある（入口が置いた仮の日）", d))
    制度 = 制度の値(決, 型)

    def 誤る(文: str):
        r.仮たち.append(仮(f"表 A・B の形の誤り: {文}", d))
        r.要約できない = True

    # その日の所定
    所定の見当 = None   # その日の所定が、段の解決の置いた見当（決まりの `見当の値`）から来たらその拠り所
    try:
        所定 = 整数(行.get("所定時間"))
        if 所定 is None:
            所定 = 時間の分(決.曜日の値("時間.日の所定", d, 型))
            型の値 = ((決.値たち.get("勤務の型") or {}).get(型) or {}).get("時間.日の所定") if 型 else None
            if 所定 is not None and 空(型の値):
                所定の見当 = (決.引く("見当の値") or {}).get("時間.日の所定")
        始業 = 分(行.get("所定の始業")) if not 空(行.get("所定の始業")) else 分(決.曜日の値("時間.所定の始業", d, 型))
        終業 = 分(行.get("所定の終業")) if not 空(行.get("所定の終業")) else 分(決.曜日の値("時間.所定の終業", d, 型))
        if 始業 is not None and 終業 is not None and 終業 <= 始業:
            終業 += 1440  # 日またぎの所定（17:00〜9:00）は終業を次の日の時刻に読む（時間帯() と同じ読み。同じ時刻は 24 時間）
    except 形の誤り as e:
        誤る(str(e))
        所定, 始業, 終業 = None, None, None
    if r.種類 == "勤務":
        if 所定 is None:
            r.仮たち.append(仮("時間.日の所定 が無い（法の線の日の法定で置いた）", d, 時間だけ))
            所定 = 線.日の法定
        r.所定 = 所定
    if r.種類 not in 勤務の日:
        if any(b.get("区間の種別") == "労働" for b in 区間たち):
            誤る(f"日の種類が「{r.種類}」なのに労働の区間がある")
        return r

    # 勤務の日に休んだ分（半休・時間）
    単位 = 行.get("休暇の単位") or ""
    有給か = 休暇は有給か(行.get("休暇の種類") or "", 決)
    try:
        if 単位 in ("午前半休", "午後半休"):
            半日 = 整数(行.get("休暇の時間"))
            if 半日 is None:
                半日 = 時間の分(決.引く("有給.半日", 型)) if 決.引く("有給.半日", 型) not in (None, "使う", "使わない") else 所定 // 2
            r.休暇の分 = 半日
        elif 単位 == "時間":
            休んだ分 = 整数(行.get("休暇の時間"))
            if 休んだ分 is None:   # 休んだ分が欠けた＝黙って 0 分にしない（勤務・遅刻早退・年休の時間の全部に効く）
                r.仮たち.append(仮(休暇の時間が空, d))
            r.休暇の分 = 休んだ分 or 0
        elif 単位 == "全日":
            誤る("全日の休暇の日に勤務がある")
    except 形の誤り as e:
        誤る(str(e))
    try:
        足す = 有給か and 有給を足すか(決, 型)
    except 形の誤り as e:
        r.仮たち.append(仮(str(e), d))
        足す = False

    # 区間を読む
    労働, 休憩, 外出 = [], [], []
    for b in sorted(区間たち, key=lambda b: 整数(b.get("区間の番号")) or 0):
        種別, 出所 = b.get("区間の種別"), b.get("時刻の出所")
        try:
            s, e = 分(b.get("始め")), 分(b.get("終わり"))
        except 形の誤り as x:
            誤る(str(x))
            continue
        if s is None:
            誤る("区間の始めが空")
            continue
        if e is None:
            if 種別 != "労働":
                誤る("休憩・外出の終わりが空")
                continue
            r.仮たち.append(仮("打刻抜け（終わりを所定の終業で置いた）", d, 時間だけ))
            r.要約できない = True
            e = 終業 if 終業 is not None and 終業 > s else s
        if 出所 == "所定で埋めた":
            r.仮たち.append(仮("所定で埋めた時刻がある", d, 時間だけ))
        if not (0 <= s < 2880 and 0 <= e < 2880):
            誤る("時刻が 0:00〜47:59 の外")
            continue
        if e < s or (e == s and 種別 != "労働"):
            誤る("始めが終わりより後")
            continue
        {"労働": 労働, "休憩": 休憩, "外出": 外出}.get(種別, []).append((s, e, 出所))
        if 種別 not in ("労働", "休憩", "外出"):
            誤る(f"区間の種別「{種別}」は選べる値の外")
    労働.sort()
    for (_, e1, _), (s2, _, _) in zip(労働, 労働[1:]):
        if s2 < e1:
            誤る("労働の区間が重なる")
    for s, e, _ in 休憩 + 外出:
        if not any(a <= s and e <= b for a, b, _ in 労働):
            誤る("休憩・外出の区間が労働の区間の外")
    # 定時扱いだけの日（労働の区間も時刻の無い労働時間も無い勤務の日＝問いの答え「所定どおり出勤した（定時扱い）」・出勤簿が無い人の日）:
    # 所定の始業から終業までを労働に置く（時刻は会社の所定から引く＝入口も答えも時刻を作らない）。始業・終業の無い型は、
    # 時刻の無い労働時間＝日の所定（休んだ分を除く）で数える（下の 時刻の無い労働）
    定時だけ = (r.種類 == "勤務" and "定時扱い" in 印 and not 労働 and 空(行.get("時刻の無い労働時間"))
             and 行.get("働いた場所") != "みなし")
    定時の休憩 = None   # 所定の始業から終業までを置いた日の休憩（その長さ−日の所定＝会社の所定の休憩。法の長さで置かない）
    if 定時だけ and 始業 is not None and 終業 is not None and not r.休暇の分 and 終業 - 始業 >= r.所定:
        労働 = [(始業, 終業, "所定の始業から終業")]
        定時の休憩 = 終業 - 始業 - r.所定
        r.印す("総労働", f"{d} は時刻が無く定時扱い（所定の始業から終業までを労働とし、その間の所定でない {定時の休憩} 分を休憩とした）")

    # 打刻の扱い（丸めは長くする向き＝法の線。短くする向きは承知の印がある時だけ・始業前と終業後は決まりの値）
    # 丸めの単位・向き・始業前と終業後の打刻は 一人を集計する の最初に 芯/設定 が選べる値と照らした（外の字は既定＋仮）
    単位分 = 整数(決.引く("時間.打刻の丸めの単位", 型)) or 1
    向き = 詰め(決.引く("時間.打刻の丸めの向き", 型))
    if 向き == "短くする" and not 承知か(決, "時間.打刻の丸めの向き", 型):
        if 単位分 > 1 and any(出所 in ("打刻", "手書き") for _, _, 出所 in 労働):
            r.仮たち.append(仮("時間.打刻の丸めの向き＝短くする は日ごとに労働時間を短くする（法の線の向き＝長くする向きで数えた）",
                             d, 時間だけ))
        向き = "長くする"
    区 = []
    for s, e, 出所 in 労働:
        if 出所 in ("打刻", "手書き") and 単位分 > 1:
            if 向き == "短くする":
                s, e = -(-s // 単位分) * 単位分, e // 単位分 * 単位分
            else:
                s, e = s // 単位分 * 単位分, -(-e // 単位分) * 単位分
        区.append((s, e))
    if r.種類 == "勤務" and 始業 is not None and (詰め(決.引く("時間.始業前の打刻", 型)) or "所定の始業から") == "所定の始業から":
        区 = [(max(s, 始業), e) for s, e in 区 if e > 始業]
    if r.種類 == "勤務" and 終業 is not None and 詰め(決.引く("時間.終業後の打刻", 型)) == "申請した残業だけ":
        上 = 終業 + (整数(行.get("申請の残業")) or 0)
        区 = [(s, min(e, 上)) for s, e in 区 if s < 上]
    区 = [(s, e) for s, e in 区 if e > s]
    # 始業から扱い（表 A の印・確定した勤怠に問いの答えで置く）: その日の出勤を所定の始業とみなす（遅刻を数えず、労働と残業を始業から数える）。
    # 始業より後の最初の労働の始めだけを始業へ寄せる（始業より前からの日は変えない）
    みなした出勤 = None
    if 始業から扱い in 印 and r.種類 == "勤務" and 区:
        if 始業 is None:
            r.仮たち.append(仮(f"印 {始業から扱い} の日に所定の始業が無い（出勤の時刻のまま数えた）", d, 時間だけ))
        else:
            頭 = min(s for s, _ in 区)
            if 頭 > 始業:
                区 = [(始業 if s == 頭 else s, e) for s, e in 区]
                みなした出勤 = 始業
                r.印す("総労働", f"{d} は出勤を所定の始業とみなした（{始業から扱い}）")
    # 終業前の退勤（`時間.終業前の退勤`＝所定の終業まで）: 所定の終業より前の退勤を所定の終業の退勤とみなす（早退にしない）。
    # 表 A の印 `早退`（原本が早退と示した日）と、休暇の分のある日（半休・時間の休暇＝休んだ分は休暇で数える）は延ばさない。
    # 始業より前から数えた日（始業前の打刻＝打刻のまま）は、所定の始業から終業までの長さを超えて延ばさない（早出の分を二重にみなさない）。
    # 休憩はみなした退勤で引く（定時に帰った日と同じ休憩）。`所定の終業まで（休憩は実の退勤で）` は労働を同じに延ばし、休憩だけを
    # 実の退勤（延ばす前の区間と原本の退勤の時刻）で引く（延ばした所に掛かる休憩の時間帯・退勤の境・長さの休憩を引かない）
    延ばした退勤 = None
    終業前 = 詰め(決.引く("時間.終業前の退勤", 型))
    休憩は実の退勤で = 終業前 == 終業前の退勤_休憩は実の退勤で
    実の区 = 区
    if (r.種類 == "勤務" and 区 and 始業 is not None and 終業 is not None and 終業 > 始業 and "早退" not in 印
            and not r.休暇の分 and not 単位 and 終業前 in ("所定の終業まで", 終業前の退勤_休憩は実の退勤で)):
        末 = max(e for _, e in 区)
        先 = 終業 - max(0, 始業 - min(s for s, _ in 区))
        if 末 < 先:
            区 = [(s, 先 if e == 末 else e) for s, e in 区]
            延ばした退勤 = 先
            r.印す("総労働", f"{d} は所定の終業より前の退勤を所定の終業まで数えた（時間.終業前の退勤）"
                          + ("・休憩は実の退勤で引いた" if 休憩は実の退勤で else ""))
    r.夜勤 = any(e > 1440 for _, e in 区)

    休 = [(s, e) for s, e, _ in 休憩]
    外 = [(s, e) for s, e, _ in 外出]
    正味 = 区間の差(区, 休 + 外)
    # 休憩を決める区間（休憩は実の退勤で の日は延ばす前の区間。ほかは 区 と同じ）
    休の区 = 実の区 if 休憩は実の退勤で and 延ばした退勤 is not None else 区
    休の正味 = 区間の差(休の区, 休 + 外)
    try:
        時刻の無い休憩 = 整数(行.get("時刻の無い休憩"))
        時刻の無い労働 = 整数(行.get("時刻の無い労働時間"))
    except 形の誤り as x:
        誤る(str(x))
        時刻の無い休憩 = 時刻の無い労働 = None
    if 時刻の無い休憩 is not None and 休:
        誤る("時刻の無い休憩と休憩の区間が同じ日にある")
    if 時刻の無い労働 is not None and 区:
        誤る("時刻の無い労働時間と労働の区間が同じ日にある")
        時刻の無い労働 = None
    if 定時だけ and not 労働:
        時刻の無い労働 = max(0, r.所定 - r.休暇の分)
    if 定時の休憩 is not None and 時刻の無い休憩 is None:
        時刻の無い休憩 = 定時の休憩

    # 休憩の出し方（時刻の無い休憩: 空＝書いていない・0＝取っていない）
    置けない休憩 = 0
    組の間 = 0   # 実績で、休憩の区間が無く組が幾つもある日の組の間の空き（休憩とみなす＝労働に入れない）
    出し方 = 詰め(決.引く("時間.休憩の出し方", 型)) or "実績"
    if 時刻の無い休憩 is not None:
        置けない休憩 = 時刻の無い休憩
    elif 区 and not 休:
        表 = 設定.休憩の表を読む(決.引く("時間.休憩の表", 型) or [])   # 形の外の字は 一人を集計する の最初に照らした
        if 出し方.startswith("実績") and len(区) >= 2:
            組の間 = sum(max(0, s2 - e1) for (_, e1), (s2, _) in zip(sorted(区), sorted(区)[1:]))  # 組の間の空きが休憩
        elif (出し方.startswith("実績") or 出し方.startswith("表")) and (表["時間帯"] or 表["境"]):
            休 = [(max(a, s), min(b, e)) for a, b in 表["時間帯"] for s, e in 休の区 if min(b, e) > max(a, s)]
            正味 = 区間の差(正味, 休)
            # 退勤の境（`退勤18:00超30分`）: 退勤の時刻（原本の最後の労働の終わり・丸めの前。終業前の退勤でみなした日はみなした退勤）が境を越えた日だけ、長さの全部を引く
            # （時間帯の重なりで引かない＝18:16 退勤でも 16 分でなく 30 分）。時刻の無い休憩と同じに法定休日の外から引く
            # 境に休憩の始まり（`（10:30〜）`）があれば、出勤（原本の最初の労働の始め・丸めの前。始業から扱いの日はみなした始業）が始まり以後の日は引かない
            境の退勤 = None if 休の区 is not 区 else 延ばした退勤
            境の休憩, 境の仮 = 退勤の境の休憩(表["境"], 境の退勤 or max(e for _, e, _ in 労働), 決, みなした出勤 or min(s for s, _, _ in 労働))
            置けない休憩 += 境の休憩
            if 境の仮:
                r.仮たち.append(仮(境の仮, d, 時間だけ))
        else:
            会社の長さ, 誤り = 会社の休憩の長さ(決, 型)
            if 誤り:
                r.仮たち.append(仮(誤り, d, 時間だけ))
            if not 会社の長さ and 表["長さ"]:   # 休憩の表に長さの形が直に来た時（段の解決は 時間.休憩の長さ へ分けて渡す）
                会社の長さ = tuple(sorted(表["長さ"]))
            if 会社の長さ:
                置けない休憩 = 長さの休憩(会社の長さ, 長さ(休の正味))  # 会社の決まりの長さ（「何時間を超えたら何分」）
            else:
                if not 線.休憩の長さ:
                    r.仮たち.append(仮("法の線に 時間.休憩の長さ が無い（休憩を引けない）", d, 時間だけ))
                elif 出し方.startswith("実績") and 法の休憩(線, 長さ(休の正味)) == 0:
                    pass  # 34 条で休憩の要らない長さ（法の線の一番下の段以下）＝実績の空は 0 分と読む
                elif not 出し方.startswith("長さ"):
                    r.仮たち.append(仮("時間.休憩の表 が無い（法の長さで休憩を置いた）", d, 時間だけ))
                置けない休憩 = 法の休憩(線, 長さ(休の正味))
    夜の元 = 正味 if (詰め(決.引く("割増.深夜に入る休憩", 型)) or "引く") == "引く" else 区間の差(区, 外)

    # 労働の長さと、暦日での分け方（法定休日は暦日で数える）
    帯, 誤り = 深夜帯(決, 線, 型, d)
    r.仮たち += 誤り
    r.深夜 = sum(重なり(夜の元, 帯[0] + k * 1440, 帯[1] + k * 1440) for k in (-1, 0, 1))
    if 置けない休憩 and r.深夜:
        r.印す("深夜", "時刻の無い休憩は深夜帯の外とみなした")
    片 = []  # (暦の区分, 分)
    for s, e in 正味:
        while s < e:
            k = s // 1440
            t = min(e, (k + 1) * 1440)
            区分, 理由 = 暦(d + timedelta(days=k))
            if 理由:
                r.仮たち.append(仮(理由, d, frozenset(("総労働", "法定休日", "所定休日") + 分ける語)))
            片.append((区分, t - s))
            s = t
    if not 正味:
        if 時刻の無い労働 is not None:
            片 = [(暦(d)[0], 時刻の無い労働)]
            r.印す("深夜", f"{d} は時刻の無い労働時間（深夜を数えられない）")
        elif 行.get("働いた場所") != "みなし":
            誤る("勤務の日に労働の区間も時刻の無い労働時間も無い")
    # 出勤から退勤まで: 時刻のある日は原本の労働の区間の長さの和（休憩・外出は区間の中＝含む）。時刻の無い日は時刻の無い労働時間
    # （休憩を引く前の長さ）。どちらも無い日（時刻の無い みなし の日）は None＝月は行を出さない
    r.出勤から退勤 = sum(e - s for s, e, _ in 労働) if 労働 else 時刻の無い労働
    try:
        欄の数え方 = 出勤時間の欄(決, 型)
    except 形の誤り as x:
        r.仮たち.append(仮(str(x), d, frozenset({"出勤から退勤まで"})))
        欄の数え方 = "打刻のまま"
    if 欄の数え方 == "所定の始業から" and 労働 and r.種類 == "勤務":
        if 始業 is None:
            r.仮たち.append(仮("時間.出勤時間の欄＝所定の始業から なのに所定の始業が無い（打刻のままで数えた）", d,
                             frozenset({"出勤から退勤まで"})))
        else:
            r.出勤から退勤 = 拘束(労働, 始業, 終業, みなした出勤, 延ばした退勤, "定時扱い" in 印)
    # 時刻の無い休憩は法定休日の外から先に引く
    引く休憩 = 置けない休憩
    for i, (区分, m) in enumerate(片):
        if 置けない休憩 <= 0:
            break
        if 区分 != "法定":
            x = min(m, 置けない休憩)
            片[i] = (区分, m - x)
            置けない休憩 -= x
    for i, (区分, m) in enumerate(片):
        x = min(m, 置けない休憩)
        片[i] = (区分, m - x)
        置けない休憩 -= x
    r.労働 = 正味
    if r.出勤から退勤 is not None:   # 労働から引いた休憩＝区間で引いた分（外出を除く）＋組の間＋時刻の無い休憩・長さの表で引けた分
        r.休憩 = 長さ(区間の差(区, 外)) - 長さ(正味) + 組の間 + (引く休憩 - 置けない休憩)
    r.法定休日 = sum(m for k, m in 片 if k == "法定")
    r.所定休日 = sum(m for k, m in 片 if k == "所定")
    r.片 = [(k, m) for k, m in 片 if k != "法定" and m]
    r.総 = sum(m for k, m in 片 if k != "法定")

    # 34 条の休憩の長さ（足りなければ知らせ。賃金は実働で払う）
    if 線.休憩の長さ and 区:
        幅 = max(e for _, e in 区) - min(s for s, _ in 区)
        実労働 = r.総 + r.法定休日
        if 幅 - 実労働 < 法の休憩(線, 実労働):
            r.知らせ.append(f"{d}: 休憩が法の長さに足りない")

    # みなし（事業場外の日・裁量の制度の勤務の日）と定時扱い
    if r.種類 == "勤務" and (行.get("働いた場所") == "みなし" or 制度 in 裁量):
        みなし = 時間の分(決.引く("時間.みなし時間", 型))
        if みなし is None:
            r.仮たち.append(仮("時間.みなし時間 が無い（所定で置いた）", d, 時間だけ))
            みなし = r.所定
        r.総 = みなし
        r.所定休日 = 0
        r.印す("総労働", f"{d} はみなしの時間")
    if r.種類 == "勤務" and "定時扱い" in 印:
        r.総 = max(0, r.所定 - r.休暇の分)
        r.印す("総労働", f"{d} は定時扱い")
        if 所定の見当:   # 定時扱いの時間＝日の所定。所定が見当なら時間も見当（黙って確定にしない）
            r.仮たち.append(仮(f"定時扱いの日の時間を 時間.日の所定 の見当（{所定の見当}）で置いた＝勤務の型の 1 日の所定を書く",
                             d, 時間だけ))

    # 日の分け方（所定内 → 法定内残業 → 法定外）
    所定の残り = max(0, r.所定 - r.休暇の分)
    if 制度 in 変形:
        線の日 = max(r.所定, 線.日の法定)
    else:
        線の日 = 線.日の法定
        if r.所定 > 線.日の法定 and 制度 in 通常系:
            if 承知か(決, "時間.日の所定", 型):
                線の日 = r.所定      # 承知の印（§1.4）: 会社の所定までを所定内に数える（法の線との差は 集計する が数え直して出す）
                r.所定が法定を超える = True
            else:
                r.仮たち.append(仮("通常の制度で 時間.日の所定 が日の法定を超える（日の法定で数えた）", d, 時間だけ))
                所定の残り = min(所定の残り, 線.日の法定)
    if 足す:
        線の日 = max(0, 線の日 - r.休暇の分)
    w = r.総
    if 制度 == "フレックス" or 制度 in 外の制度:
        r.所定内 = w  # 期間で数える（月の段）
    else:
        r.所定内 = min(w, 所定の残り)
        r.法定内 = max(0, min(w, 線の日) - r.所定内)
        r.法定外 = max(0, w - max(線の日, r.所定内))
    if (r.種類 == "勤務" and 制度 not in 外の制度 + ("フレックス",) and "定時扱い" not in 印
            and 行.get("働いた場所") != "みなし" and 制度 not in 裁量):
        try:
            証明 = 整数(行.get("遅延証明の分")) or 0
        except 形の誤り as x:
            誤る(str(x))
            証明 = 0
        r.遅刻早退 = max(0, 所定の残り - (r.総 + r.法定休日) - 証明)  # 実に働いた分で見る（法定休日へかかった分も働いた分）
    if 欄の数え方 == "所定内" and r.出勤から退勤 is not None:
        r.出勤から退勤 = r.所定内   # その日の所定内の時間（実働を日の所定で頭打ち。所定の無い休日勤務の日は 0）
    return r


def 出勤時間の欄(決: 決まり, 型: str | None) -> str:
    """`時間.出勤時間の欄`（月の語 出勤から退勤まで の数え方）→ 打刻のまま・所定の始業から・所定内 の 1 つ。
    `所定の始業から（時給の人は所定内）` は `支払.賃金の形` で分ける（時給の人は 所定内・ほかは 所定の始業から）。賃金の形が空は 形の誤り
    （呼ぶ側が仮にする＝黙ってどちらかで数えない）。選べる値の外の字は 一人を集計する の最初に 芯/設定 が照らした（ここでは照らさない）。"""
    v = 詰め(決.引く("時間.出勤時間の欄", 型)) or "打刻のまま"
    if v != 賃金の形で分ける欄:
        return v
    形 = 詰め(決.引く("支払.賃金の形"))
    if not 形:
        raise 形の誤り(f"時間.出勤時間の欄「{v}」なのに 支払.賃金の形 が空（出勤から退勤まで の数え方が決まらない）")
    return "所定内" if 形 == "時給" else "所定の始業から"


def 拘束(労働, 始業: int, 終業: int | None, みなした出勤: int | None, 延ばした退勤: int | None, 定時扱い: bool) -> int:
    """出勤から退勤までを所定の始業から数えた長さ（`時間.出勤時間の欄`＝所定の始業から）。原本の労働の区間（丸めの前）を、
    始業より前は始業から（始業前の打刻の扱いによらない）・始業から扱いの日は出勤を始業・定時扱いの日は始業から終業まで（退勤が終業より後なら退勤まで）・
    終業前の退勤でみなした日はみなした退勤まで、として足す（休憩・外出は区間の中＝含む。組が幾つもある日は組ごとの和）。"""
    区 = sorted((max(s, 始業), e) for s, e, _ in 労働 if e > 始業)
    if not 区:
        return 0
    頭 = 始業 if (みなした出勤 is not None or 定時扱い) else 区[0][0]
    末 = 区[-1][1]
    if 定時扱い and 終業 is not None:
        末 = max(末, 終業)
    if 延ばした退勤 is not None:
        末 = max(末, 延ばした退勤)
    区[0] = (頭, 区[0][1])
    区[-1] = (区[-1][0], 末)
    return sum(e - s for s, e in 区)
