@dataclass
class 日の結果:
    日付: date
    種類: str
    所定: int = 0          # その日の所定（休暇の分を引く前）
    休暇の分: int = 0      # 勤務の日に休んだ分（半休・時間）
    労働: list = field(default_factory=list)  # 正味の労働の区間（休憩・外出を引いた後）
    総: int = 0            # 法定休日の外の労働
    所定内: int = 0
    法定内: int = 0
    法定外: int = 0
    法定休日: int = 0
    所定休日: int = 0
    深夜: int = 0
    遅刻早退: int = 0
    夜勤: bool = False
    出勤から退勤: int | None = 0   # 出勤から退勤までの長さ（労働の区間の始めから終わりまで＝休憩・外出を含む・打刻の丸めの前）。時刻も長さも無い日は None
    休憩: int | None = None   # その日に労働から引いた休憩（休憩の区間・休憩の表の時間帯・組の間の空き・時刻の無い休憩・長さの表）。勤務の日でない日・時刻も長さも無い日は None
    要約できない: bool = False   # 形の誤り・打刻抜けの日＝日の要約（台帳「勤怠」の 休憩の合計・労働の合計）を出さない（黙って見当を確かな値に見せない）
    所定が法定を超える: bool = False   # 承知の印で、通常の制度の日の所定を日の法定の上で数えた日（週の線も所定の和で見る）
    仮たち: list = field(default_factory=list)
    知らせ: list = field(default_factory=list)
    印: dict = field(default_factory=dict)   # 項目 → [印]
    片: list = field(default_factory=list)   # 法定休日の外の労働の (暦の区分, 分) を時刻の順に（所定休日のうち法定外を数える）

    def 印す(self, 項目: str, 文: str):
        self.印.setdefault(項目, []).append(文)

    @property
    def 法定外でない(self) -> int:
        return self.所定内 + self.法定内

    @property
    def 所定休日の法定外(self) -> int:
        """所定休日の時間のうち法定外に入った分（内数）。その日の法定外は時刻の後ろの分（日の線・週の線を超えて後に働いた分）とみなし、
        後ろの片から法定外の分だけ取ってそのうち所定休日の暦の分を足す（1 日まるごと所定休日の日は min(所定休日, 法定外) と同じ）。"""
        残, x = self.法定外, 0
        for 区分, m in reversed(self.片):
            if 残 <= 0:
                break
            t = min(m, 残)
            残 -= t
            if 区分 == "所定":
                x += t
        return min(x, self.所定休日, self.法定外)


