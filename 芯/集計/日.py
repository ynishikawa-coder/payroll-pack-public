"""日→区間の正規化と、日ごとの時間（所定内・法定内残業・法定外・深夜・休日）。

1 日＝表 A の 1 行と、その日の表 B の区間。日またぎは時刻に 24 を足した形のまま受け、暦日・深夜帯で切るのはここ。
法の値は法の線（引数）から、会社の値は決まり（引数）から引く。どちらもコードに書かない。
"""
from dataclasses import dataclass, field
from datetime import date, timedelta

from .形 import (仮, 決まり, 法の線, 形の誤り, 空, 分, 整数, 時間の分, 時間帯, 語たち, 詰め,
                区間の差, 重なり, 長さ, 時間の語, 分ける語)

勤務の日 = ("勤務", "休日勤務")
通常系 = ("通常", "事業場外みなし", "専門業務型裁量", "企画業務型裁量")
変形 = ("1か月変形", "1年変形", "1週間変形")
外の制度 = ("管理監督者", "高度プロフェッショナル")
裁量 = ("専門業務型裁量", "企画業務型裁量")
有給の休暇 = ("年休", "特別休暇（有給）")
看護など = ("子の看護等休暇", "介護休暇", "生理休暇")
時間だけ = frozenset(時間の語 + ("夜勤の回数",))  # 時刻・休憩・所定の見当は日数の項目を変えない


@dataclass
class 日の結果:
    日付: date
    種類: str
    所定: int = 0          # その日の所定（休暇の分を引く前）
    休暇の分: int = 0      # 勤務の日に休んだ分（半休・時間）
    労働: list = field(default_factory=list)  # 正味の労働の区間（休憩・外出を引いた後）
    総: int = 0            # 法定休日の外の労働
    所定内: int = 0
    法定内: int = 0
    法定外: int = 0
    法定休日: int = 0
    所定休日: int = 0
    深夜: int = 0
    遅刻早退: int = 0
    夜勤: bool = False
    仮たち: list = field(default_factory=list)
    知らせ: list = field(default_factory=list)
    印: dict = field(default_factory=dict)   # 項目 → [印]

    def 印す(self, 項目: str, 文: str):
        self.印.setdefault(項目, []).append(文)

    @property
    def 法定外でない(self) -> int:
        return self.所定内 + self.法定内


def 制度の値(決: 決まり, 型: str | None) -> tuple[str, list]:
    v = 詰め(決.引く("時間.制度", 型)) or "通常"
    if v not in 通常系 + 変形 + 外の制度 + ("フレックス",):
        return "通常", [仮(f"時間.制度 の値「{v}」は選べる値の外（通常で数えた）")]
    return v, []


def 休暇は有給か(種類: str, 決: 決まり) -> bool:
    if 種類 in 有給の休暇:
        return True
    if 種類 in 看護など:
        return 詰め(決.引く("休暇.子の看護など")) == "有給"
    return False


def 長さの休憩(段たち, 労働の分: int) -> int:
    return max([b for a, b in 段たち if 労働の分 > a], default=0)


def 法の休憩(線: 法の線, 労働の分: int) -> int:
    return 長さの休憩(線.休憩の長さ, 労働の分)


def 会社の休憩の長さ(決: 決まり, 型: str | None) -> tuple[tuple[tuple[int, int], ...], str | None]:
    """会社の `時間.休憩の長さ`（[[超える時間, 休憩の分], …]・初期設定の段の解決が休憩の表の長さの形から作る）。

    読めなければ () と仮の理由（法の線の長さで置く）。34 条より短い時は休憩の 34 条の知らせが別に出る。
    """
    v = 決.引く("時間.休憩の長さ", 型)
    if not v:
        return (), None
    try:
        return tuple(sorted((時間の分(a), 整数(b)) for a, b in v)), None
    except (形の誤り, TypeError, ValueError):
        return (), f"時間.休憩の長さ「{v}」が [[超える時間, 休憩の分], …] の形でない（法の線の長さで置いた）"


def 深夜帯(決: 決まり, 線: 法の線, 型: str | None, d: date) -> tuple[tuple[int, int], list]:
    """会社が広げた深夜帯を使う。法の線より狭い値は法の線で数え仮にする（会社の決まり.md §1.1）。"""
    v = 決.引く("割増.深夜の時間帯", 型)
    if v is None:
        return 線.深夜帯, []
    s, e = 時間帯(v)
    if s <= 線.深夜帯[0] and e >= 線.深夜帯[1]:
        return (s, e), []
    return 線.深夜帯, [仮("割増.深夜の時間帯 が法の線より狭い（法の線で数えた）", d, frozenset({"深夜"}))]


def 日を数える(行: dict, 区間たち: list[dict], 決: 決まり, 線: 法の線, 暦) -> 日の結果:
    """表 A の 1 行とその日の表 B から、その日の時間を出す。止めずに、形の誤りや足りない値は仮にする。

    暦: 日付 → (`法定`／`所定`／None, 仮の理由／None) を返す呼び口。日またぎで表 A に無い日（期間の外）へかかる時も引く。
    """
    d = 行["日付"]
    型 = 行.get("勤務の型") or None
    r = 日の結果(d, 行["日の種類"])
    印 = 語たち(行.get("印"))
    if 行.get("読み取りの確かめ") != "確認済":
        r.仮たち.append(仮("読み取りの確かめが要確認の日がある", d))
    if "原本に無い" in 印:
        r.仮たち.append(仮("原本に無い日がある（入口が置いた仮の日）", d))
    制度, 誤り = 制度の値(決, 型)
    r.仮たち += [仮(x.理由, d) for x in 誤り]

    def 誤る(文: str):
        r.仮たち.append(仮(f"表 A・B の形の誤り: {文}", d))

    # その日の所定
    所定の見当 = None   # その日の所定が、段の解決の置いた見当（決まりの `見当の値`）から来たらその拠り所
    try:
        所定 = 整数(行.get("所定時間"))
        if 所定 is None:
            所定 = 時間の分(決.曜日の値("時間.日の所定", d, 型))
            型の値 = ((決.値たち.get("勤務の型") or {}).get(型) or {}).get("時間.日の所定") if 型 else None
            if 所定 is not None and 空(型の値):
                所定の見当 = (決.引く("見当の値") or {}).get("時間.日の所定")
        始業 = 分(行.get("所定の始業")) if not 空(行.get("所定の始業")) else 分(決.曜日の値("時間.所定の始業", d, 型))
        終業 = 分(行.get("所定の終業")) if not 空(行.get("所定の終業")) else 分(決.曜日の値("時間.所定の終業", d, 型))
    except 形の誤り as e:
        誤る(str(e))
        所定, 始業, 終業 = None, None, None
    if r.種類 == "勤務":
        if 所定 is None:
            r.仮たち.append(仮("時間.日の所定 が無い（法の線の日の法定で置いた）", d, 時間だけ))
            所定 = 線.日の法定
        r.所定 = 所定
    if r.種類 not in 勤務の日:
        if any(b.get("区間の種別") == "労働" for b in 区間たち):
            誤る(f"日の種類が「{r.種類}」なのに労働の区間がある")
        return r

    # 勤務の日に休んだ分（半休・時間）
    単位 = 行.get("休暇の単位") or ""
    有給か = 休暇は有給か(行.get("休暇の種類") or "", 決)
    try:
        if 単位 in ("午前半休", "午後半休"):
            半日 = 整数(行.get("休暇の時間"))
            if 半日 is None:
                半日 = 時間の分(決.引く("有給.半日", 型)) if 決.引く("有給.半日", 型) not in (None, "使う", "使わない") else 所定 // 2
            r.休暇の分 = 半日
        elif 単位 == "時間":
            r.休暇の分 = 整数(行.get("休暇の時間")) or 0
        elif 単位 == "全日":
            誤る("全日の休暇の日に勤務がある")
    except 形の誤り as e:
        誤る(str(e))
    足す = 有給か and 詰め(決.引く("有給.出勤時間に足す", 型)) == "足す"

    # 区間を読む
    労働, 休憩, 外出 = [], [], []
    for b in sorted(区間たち, key=lambda b: 整数(b.get("区間の番号")) or 0):
        種別, 出所 = b.get("区間の種別"), b.get("時刻の出所")
        try:
            s, e = 分(b.get("始め")), 分(b.get("終わり"))
        except 形の誤り as x:
            誤る(str(x))
            continue
        if s is None:
            誤る("区間の始めが空")
            continue
        if e is None:
            if 種別 != "労働":
                誤る("休憩・外出の終わりが空")
                continue
            r.仮たち.append(仮("打刻抜け（終わりを所定の終業で置いた）", d, 時間だけ))
            e = 終業 if 終業 is not None and 終業 > s else s
        if 出所 == "所定で埋めた":
            r.仮たち.append(仮("所定で埋めた時刻がある", d, 時間だけ))
        if not (0 <= s < 2880 and 0 <= e < 2880):
            誤る("時刻が 0:00〜47:59 の外")
            continue
        if e < s or (e == s and 種別 != "労働"):
            誤る("始めが終わりより後")
            continue
        {"労働": 労働, "休憩": 休憩, "外出": 外出}.get(種別, []).append((s, e, 出所))
        if 種別 not in ("労働", "休憩", "外出"):
            誤る(f"区間の種別「{種別}」は選べる値の外")
    労働.sort()
    for (_, e1, _), (s2, _, _) in zip(労働, 労働[1:]):
        if s2 < e1:
            誤る("労働の区間が重なる")
    for s, e, _ in 休憩 + 外出:
        if not any(a <= s and e <= b for a, b, _ in 労働):
            誤る("休憩・外出の区間が労働の区間の外")

    # 打刻の扱い（丸めは長くする向きだけ・始業前と終業後は決まりの値）
    try:
        単位分 = 整数(決.引く("時間.打刻の丸めの単位", 型)) or 1
    except 形の誤り as x:
        誤る(str(x))
        単位分 = 1
    区 = []
    for s, e, 出所 in 労働:
        if 出所 in ("打刻", "手書き") and 単位分 > 1:
            s, e = s // 単位分 * 単位分, -(-e // 単位分) * 単位分
        区.append((s, e))
    if r.種類 == "勤務" and 始業 is not None and (詰め(決.引く("時間.始業前の打刻", 型)) or "所定の始業から") == "所定の始業から":
        区 = [(max(s, 始業), e) for s, e in 区 if e > 始業]
    if r.種類 == "勤務" and 終業 is not None and 詰め(決.引く("時間.終業後の打刻", 型)) == "申請した残業だけ":
        上 = 終業 + (整数(行.get("申請の残業")) or 0)
        区 = [(s, min(e, 上)) for s, e in 区 if s < 上]
    区 = [(s, e) for s, e in 区 if e > s]
    r.夜勤 = any(e > 1440 for _, e in 区)

    休 = [(s, e) for s, e, _ in 休憩]
    外 = [(s, e) for s, e, _ in 外出]
    正味 = 区間の差(区, 休 + 外)
    try:
        時刻の無い休憩 = 整数(行.get("時刻の無い休憩"))
        時刻の無い労働 = 整数(行.get("時刻の無い労働時間"))
    except 形の誤り as x:
        誤る(str(x))
        時刻の無い休憩 = 時刻の無い労働 = None
    if 時刻の無い休憩 is not None and 休:
        誤る("時刻の無い休憩と休憩の区間が同じ日にある")
    if 時刻の無い労働 is not None and 区:
        誤る("時刻の無い労働時間と労働の区間が同じ日にある")
        時刻の無い労働 = None

    # 休憩の出し方（時刻の無い休憩: 空＝書いていない・0＝取っていない）
    置けない休憩 = 0
    出し方 = 詰め(決.引く("時間.休憩の出し方", 型)) or "実績"
    if 時刻の無い休憩 is not None:
        置けない休憩 = 時刻の無い休憩
    elif 区 and not 休:
        表 = 決.引く("時間.休憩の表", 型) or []
        if 出し方.startswith("実績") and len(区) >= 2:
            pass  # 組の間の空きが休憩
        elif (出し方.startswith("実績") or 出し方.startswith("表")) and 表:
            窓 = [時間帯(x) for x in 表]
            休 = [(max(a, s), min(b, e)) for a, b in 窓 for s, e in 区 if min(b, e) > max(a, s)]
            正味 = 区間の差(正味, 休)
        else:
            会社の長さ, 誤り = 会社の休憩の長さ(決, 型)
            if 誤り:
                r.仮たち.append(仮(誤り, d, 時間だけ))
            if 会社の長さ:
                置けない休憩 = 長さの休憩(会社の長さ, 長さ(正味))  # 会社の決まりの長さ（「何時間を超えたら何分」）
            else:
                if not 線.休憩の長さ:
                    r.仮たち.append(仮("法の線に 時間.休憩の長さ が無い（休憩を引けない）", d, 時間だけ))
                elif 出し方.startswith("実績") and 法の休憩(線, 長さ(正味)) == 0:
                    pass  # 34 条で休憩の要らない長さ（法の線の一番下の段以下）＝実績の空は 0 分と読む
                elif not 出し方.startswith("長さ"):
                    r.仮たち.append(仮("時間.休憩の表 が無い（法の長さで休憩を置いた）", d, 時間だけ))
                置けない休憩 = 法の休憩(線, 長さ(正味))
    夜の元 = 正味 if (詰め(決.引く("割増.深夜に入る休憩", 型)) or "引く") == "引く" else 区間の差(区, 外)

    # 労働の長さと、暦日での分け方（法定休日は暦日で数える）
    帯, 誤り = 深夜帯(決, 線, 型, d)
    r.仮たち += 誤り
    r.深夜 = sum(重なり(夜の元, 帯[0] + k * 1440, 帯[1] + k * 1440) for k in (-1, 0, 1))
    if 置けない休憩 and r.深夜:
        r.印す("深夜", "時刻の無い休憩は深夜帯の外とみなした")
    片 = []  # (暦の区分, 分)
    for s, e in 正味:
        while s < e:
            k = s // 1440
            t = min(e, (k + 1) * 1440)
            区分, 理由 = 暦(d + timedelta(days=k))
            if 理由:
                r.仮たち.append(仮(理由, d, frozenset(("総労働", "法定休日", "所定休日") + 分ける語)))
            片.append((区分, t - s))
            s = t
    if not 正味:
        if 時刻の無い労働 is not None:
            片 = [(暦(d)[0], 時刻の無い労働)]
            r.印す("深夜", f"{d} は時刻の無い労働時間（深夜を数えられない）")
        elif 行.get("働いた場所") != "みなし":
            誤る("勤務の日に労働の区間も時刻の無い労働時間も無い")
    # 時刻の無い休憩は法定休日の外から先に引く
    for i, (区分, m) in enumerate(片):
        if 置けない休憩 <= 0:
            break
        if 区分 != "法定":
            x = min(m, 置けない休憩)
            片[i] = (区分, m - x)
            置けない休憩 -= x
    for i, (区分, m) in enumerate(片):
        x = min(m, 置けない休憩)
        片[i] = (区分, m - x)
        置けない休憩 -= x
    r.労働 = 正味
    r.法定休日 = sum(m for k, m in 片 if k == "法定")
    r.所定休日 = sum(m for k, m in 片 if k == "所定")
    r.総 = sum(m for k, m in 片 if k != "法定")

    # 34 条の休憩の長さ（足りなければ知らせ。賃金は実働で払う）
    if 線.休憩の長さ and 区:
        幅 = max(e for _, e in 区) - min(s for s, _ in 区)
        実労働 = r.総 + r.法定休日
        if 幅 - 実労働 < 法の休憩(線, 実労働):
            r.知らせ.append(f"{d}: 休憩が法の長さに足りない")

    # みなし（事業場外の日・裁量の制度の勤務の日）と定時扱い
    if r.種類 == "勤務" and (行.get("働いた場所") == "みなし" or 制度 in 裁量):
        みなし = 時間の分(決.引く("時間.みなし時間", 型))
        if みなし is None:
            r.仮たち.append(仮("時間.みなし時間 が無い（所定で置いた）", d, 時間だけ))
            みなし = r.所定
        r.総 = みなし
        r.所定休日 = 0
        r.印す("総労働", f"{d} はみなしの時間")
    if r.種類 == "勤務" and "定時扱い" in 印:
        r.総 = max(0, r.所定 - r.休暇の分)
        r.印す("総労働", f"{d} は定時扱い")
        if 所定の見当:   # 定時扱いの時間＝日の所定。所定が見当なら時間も見当（黙って確定にしない）
            r.仮たち.append(仮(f"定時扱いの日の時間を 時間.日の所定 の見当（{所定の見当}）で置いた＝勤務の型の 1 日の所定を書く",
                             d, 時間だけ))

    # 日の分け方（所定内 → 法定内残業 → 法定外）
    所定の残り = max(0, r.所定 - r.休暇の分)
    if 制度 in 変形:
        線の日 = max(r.所定, 線.日の法定)
    else:
        線の日 = 線.日の法定
        if r.所定 > 線.日の法定 and 制度 in 通常系:
            r.仮たち.append(仮("通常の制度で 時間.日の所定 が日の法定を超える（日の法定で数えた）", d, 時間だけ))
            所定の残り = min(所定の残り, 線.日の法定)
    if 足す:
        線の日 = max(0, 線の日 - r.休暇の分)
    w = r.総
    if 制度 == "フレックス" or 制度 in 外の制度:
        r.所定内 = w  # 期間で数える（月の段）
    else:
        r.所定内 = min(w, 所定の残り)
        r.法定内 = max(0, min(w, 線の日) - r.所定内)
        r.法定外 = max(0, w - max(線の日, r.所定内))
    if (r.種類 == "勤務" and 制度 not in 外の制度 + ("フレックス",) and "定時扱い" not in 印
            and 行.get("働いた場所") != "みなし" and 制度 not in 裁量):
        try:
            証明 = 整数(行.get("遅延証明の分")) or 0
        except 形の誤り as x:
            誤る(str(x))
            証明 = 0
        r.遅刻早退 = max(0, 所定の残り - (r.総 + r.法定休日) - 証明)  # 実に働いた分で見る（法定休日へかかった分も働いた分）
    return r
