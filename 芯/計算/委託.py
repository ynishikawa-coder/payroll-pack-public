_月の時間の下限 = Decimal(60 * 60)   # 60:00。1 日（〜24 時間）・1 週（法定 40 時間〜）の値を月の値と取り違えない境（月の所定はふつう 120 時間より上）


def _月の時間(v) -> tuple[Decimal | None, str]:
    """委託.所定時間（1 か月の時間）→ (分, 訳)。訳が空なら読めた。空は (None, 無い)・崩れや 0 以下は (None, 読めない)。
    h:mm でない数は時間の数として見当・60:00 未満は 1 日か 1 週の時間に見える（週 40 時間の 40:00 など）＝見当して訳を返す（仮＋問い）。"""
    s = str(v if v is not None else "").strip()
    if not s:
        return None, "無い"
    try:
        x, 訳 = (分にする(s), "") if ":" in s else (数(s) * 60, "h:mm でない（時間の数として見当）")
    except (形の誤り, TypeError):
        return None, "読めない"
    if x is None or x <= 0:
        return None, "読めない"
    if x < _月の時間の下限:
        訳 = "60:00 未満（月の時間として小さすぎる＝1 日か 1 週の時間に見える。1 か月の時間として見当）"
    return x, 訳


