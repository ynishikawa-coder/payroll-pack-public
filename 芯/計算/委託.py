"""委託分の式（材料: pixel-office の agents/kyuyo/道具/timecard_tally.py の itaku()・kata.py の edge・past・round_yen を今の型へ書き直した物）。

`人.区分` が `委託`（委託だけ）か `委託の併用`（雇用分と委託分を 1 枚で出す）の人の委託分を、1 人の帳へ `委託分の…` の項目で置く。
- 式は `委託.式`（初期設定/項目.json の 委託.*）で選ぶ:
  - `月額`（前の道具の「月給から雇用分を引く」）: 委託.月給−委託.雇用分＋残業×時給×時間外の率＋深夜×時給×深夜の率
    ＋休日出勤（法定休日＋所定休日）×時給×休日の率＋出張日数×委託.出張日額−欠勤日×1 日の所定×時給
    （残業＝法定内＋法定外−所定休日＝休日出勤の日は残業に入れない。会社の数え方の残業があればそれ）
  - `日ごとに時給か日当`: 出た日ごとに、実働が `委託.日当の境`（無しなら 1 日の所定・以上）に届けば 委託.日給、届かなければ 実働×時給。
    ＋休日出勤（法定休日＋所定休日）×時給×休日の率＋通勤日額×出勤日数＋出張日数×出張日額
  - `時給`（境の無い日ごと＝全部の日を時給）・`日給`（全部の日を日当）
  - ほか（`報酬の行のまま`・前の道具の `みなし残業`）はこの芯にまだ式が無い＝委託分を値なしの仮で返す。
- `委託.みなし残業時間`（h:mm・無し）: `月額` の式の残業（会社の数え方の残業か 法定内＋法定外−所定休日）から引く
  （オーナーの答え: 会社の数え方は「1 日の所定超え − みなし」・前の道具の みなし残業 の式もみなしの分は払わない）。
  残業のある月に値が無い・読めない時は引かずに見当で仮＋問い。引いた後が法の線の法定外残業を下回れば知らせ。ほかの式では引かない（知らせ）。
- 時給は 委託.時給、無ければ 委託.日給÷1 日の所定（時間.日の所定）。1 日の所定が 0 なら割らず仮（委託.時給 か 委託.日当の境 を問う）。
  `日ごとに時給か日当` で境が無く所定 0・日給がある人は、全部の日を日当で見当して仮（委託.日当の境 を問う）。
- 丸めは `委託.丸め`（1 語＝全部の行・`残業 10円切上げ・深夜 1円切捨て` の形＝行ごと。行は 残業・深夜・休日・欠勤・日ごと・合計）。
  無ければ 1 円切捨てで見当して仮（前の道具の既定の丸めは契約で決まる値＝写さない）。
- 日ごとの実働の丸めは `委託.実働の丸め`（`15分切捨て` の形＝単位（分）と向き（切捨て・切上げ・四捨五入）か `丸めない`）。
  `日ごとに時給か日当`・`時給` の日ごとの実働を、日当の境と比べる前に日ごとに丸める（前の道具 timecard_tally 376 行の
  勤務の長さの丸め＝日の実働を単位で切り捨て。日当と時給を選ぶのも丸めた実働）。`時間.打刻の丸めの単位`（区間を長くする向きだけ）とは別の値。
  無い・読めない時は丸めずに見当して仮（黙って丸め無しにしない）。日ごとの実働の無い `時間` は日ごとに丸められない＝`丸めない` の外は仮。
- 源泉（所得税法 204 条・205 条）: 委託分の課税計に `法の表/源泉_報酬` の率と境（100 万円）を当てる。`委託.源泉率` が法の率を下回れば法の率で仮。
  表が無い時、`委託.源泉率` があればその率で仮、無ければ値なしの仮（率を手で作らない）。`源泉.報酬`＝対象でない なら 0。
  `源泉.報酬` が 対象・対象でない・空 のどれでもない（並び・知らない字）なら法の率で見当して仮＋問い（黙って法の率で確定しない）。
  `委託.社保と源泉の元に入れる`＝入れる（委託の併用の人だけ）は委託分の源泉を 0 にし、雇用分の雇保の元と源泉の課税対象額へ課税計を足す。
- 委託分の時間と日は月の数字（芯/集計）の語を使う（委託の併用でも委託分は月の全部の時間で数える＝前の道具と同じ。雇用分は決まった額）。
  日ごとの実働（`入力` の `委託.日ごとの実働` {日付: 分か h:mm}）と出張の日数（`入力` の `委託.出張日数`）は月の数字の語に無い＝殻か芯/集計が渡す。
"""
from __future__ import annotations

import re
from decimal import ROUND_FLOOR, Decimal

from .形 import 丸める, 丸めの語か, 形の誤り, 数, 理由, 語をそろえる

前 = "委託分の"
項目たち = tuple(前 + n for n in ("報酬", "残業", "深夜", "休日", "出張", "通勤費", "欠勤控除", "課税計", "源泉所得税", "差引支給額"))
支払合計 = "支払合計"
_式たち = ("月額", "日ごとに時給か日当", "時給", "日給")
_丸めの行 = ("残業", "深夜", "休日", "欠勤", "日ごと", "合計")
_丸めの字 = re.compile(r"^\s*(残業|深夜|休日|欠勤|日ごと|合計)\s*(\d+)\s*円\s*(\S+)\s*$")
_実働の丸めの字 = re.compile(r"^(\d+)分(切捨て|切上げ|四捨五入)$")
丸めない = "丸めない"
_境の字 = re.compile(r"^\s*(.*?)\s*(以上|を超える|超える|超)?\s*$")


def 委託の人か(v: dict) -> bool:
    return v.get("人.区分") in ("委託", "委託の併用")


def 式の語(v) -> str | None:
    """委託.式 → 芯の式の語（頭で見る）。前の道具の名「月給から雇用分を引く」は 月額 と同じ。空は ''・式の外は None。"""
    s = str(v or "").strip()
    if not s:
        return ""
    if s.startswith("月給から雇用分を引く"):
        return "月額"
    return next((w for w in _式たち if s.startswith(w)), None)


def 丸めを読む(v) -> dict | None:
    """委託.丸め → {行: (単位, 語)}。1 語なら全部の行を 1 円で。読めなければ None。"""
    s = str(v or "").strip()
    if 丸めの語か(s):
        return {k: (Decimal(1), s) for k in _丸めの行}
    out = {}
    for part in re.split(r"[・、,]", s):
        m = _丸めの字.match(part)
        if not m or not 丸めの語か(m.group(3)):
            return None
        out[m.group(1)] = (Decimal(m.group(2)), m.group(3))
    return out or None


def 実働の丸めを読む(v):
    """委託.実働の丸め → (単位の分, 向きの語)・`丸めない` は False・空か読めなければ None。"""
    s = 語をそろえる(v)
    if s in (丸めない, "しない", "無し"):
        return False
    m = _実働の丸めの字.match(s)
    if not m or int(m.group(1)) <= 0:
        return None
    return Decimal(m.group(1)), m.group(2)


def _分(v) -> Decimal | None:
    if v is None or str(v).strip() == "":
        return None
    s = str(v).strip()
    if ":" in s:
        m = re.fullmatch(r"(-?)(\d+):([0-5]\d)", s)
        if not m:
            raise 形の誤り(f"時間の形でない（h:mm）: {s!r}")
        x = Decimal(int(m.group(2)) * 60 + int(m.group(3)))
        return -x if m.group(1) else x
    return 数(s)


def 境を読む(v) -> tuple[Decimal | None, str]:
    """委託.日当の境 → (分, 向き)。向きは 以上（既定）か 超える。無し・空は (None, 以上)。"""
    s = str(v or "").strip()
    if not s or s == "無し":
        return None, "以上"
    m = _境の字.match(s)
    return _分(m.group(1)), ("超える" if m.group(2) and m.group(2) != "以上" else "以上")


def 日の所定を使うか(v: dict) -> bool:
    """この人の 計算する が `時間.日の所定` を使うか（式の知識はここ 1 か所。初期設定/段の解決.py が見当の 8 を仮にするかをここで引く）。
    使う所（計算する）: 時給＝委託.日給÷日の所定（委託.時給 が無い時）・月額の欠勤控除（欠勤日×日の所定×時給）と残業・
    日ごとに時給か日当 の境が無い時の境（無し＝日の所定以上）。
    使わない人＝式が 時給・日給・日ごとに時給か日当〔委託.日当の境 が決まっている〕で、委託.時給 が在る人。
    式や境が読めない・式が無い人は使うと見なす。"""
    語 = 式の語(v.get("委託.式"))
    時給 = v.get("委託.時給")
    if 時給 is None or (isinstance(時給, str) and not 時給.strip()) or 語 not in ("時給", "日給", "日ごとに時給か日当"):
        return True
    if 語 == "日ごとに時給か日当":
        try:
            境, _ = 境を読む(v.get("委託.日当の境"))
        except ValueError:
            return True
        return 境 is None
    return False


def 計算する(人) -> Decimal:
    """人＝支給控除.一人（期間・支給日は決めてある）。帳へ 委託分の… を置き、雇用分の雇保と源泉の元へ足す額を返す（入れない時は 0）。"""
    v = 人.v
    帳 = 人.帳
    効く全部 = "・".join(項目たち)

    def 仮(効く, 何が, 見当="", 拠り所="", 答え="値を書く"):
        人._仮(効く, 理由(何が, 見当, 拠り所, 答え))

    def 時(語, 効く):
        return 人.勤怠の数(語, 効く, 全部=True)

    def 値(名, 効く, 見当=Decimal(0), 要る=True):
        x = 数(v.get(名), 名)
        if x is None and 要る:
            仮(効く, f"「{名}」が無い", str(見当), "0 で見当（委託の契約の値）", f"{名} の値を書く")
            return 見当
        return x

    for n in 項目たち:
        帳.置く(n, Decimal(0), "")
    語 = 式の語(v.get("委託.式"))
    if not 語:
        what = "委託.式 が無い" if 語 == "" else f"委託.式「{v.get('委託.式')}」の式はこの芯にまだ無い"
        仮(効く全部, what, "", "委託分は計算しない（前の道具も欠けで止めた）", "委託.式 を 月額・日ごとに時給か日当・時給・日給 から選ぶ")
        for n in (前 + "課税計", 前 + "源泉所得税", 前 + "差引支給額"):   # 黙って 0 に見せない
            帳.置く(n, None, what)
        return Decimal(0)
    丸め = 丸めを読む(v.get("委託.丸め"))
    if 丸め is None:
        仮(効く全部, "委託.丸め が無いか読めない", "1円切捨て", "1 円未満を切り捨てて見当（丸めは委託の契約で決まる）",
           "委託.丸め を 切捨て か `残業 10円切上げ・休日 1円切上げ` の形で書く")
        丸め = {k: (Decimal(1), "切捨て") for k in _丸めの行}

    def 丸(x, 行):
        単位, w = 丸め.get(行, (Decimal(1), "切捨て"))
        return 丸める(x, w, 単位)

    日の所定 = 人._日の所定の時間(人.期間[1])
    時給 = 数(v.get("委託.時給"), "委託.時給")
    日給 = 数(v.get("委託.日給"), "委託.日給")
    if 時給 is None and 日給 is not None and 日の所定:
        時給 = 日給 / 日の所定
    率 = {}
    for 名 in ("割増.時間外の率", "割増.深夜の率", "割増.休日の率"):
        率[名] = 数(v.get(名), 名)
        if 率[名] is None:
            率[名] = 人.法の線(名, 効く全部) or Decimal(0)
    出張 = 数((人.入力 or {}).get("委託.出張日数"), "委託.出張日数") or Decimal(0)
    出張額 = 出張 * (値("委託.出張日額", 前 + "出張") if 出張 else Decimal(0))
    帳.置く(前 + "出張", _切捨て(出張額), f"出張 {出張} 日×委託.出張日額")

    def 時給で(効く):
        if 時給 is None and 日給 is not None and 日の所定 == 0:   # 前の道具は 日給÷(所定 0) で止まる＝答えが無い
            仮(効く, "1 日の所定が 0（委託.日給 から時給が出ない・前の道具は止まる）", "0", "時給 0 で見当",
               "委託.時給 か 委託.日当の境 を書く（か 1 日の所定を確かめる）")
            return Decimal(0)
        if 時給 is None:
            仮(効く, "委託.時給 も 委託.日給 も無い（時給が出ない）", "0", "時給 0 で見当", "委託.時給 を書く")
            return Decimal(0)
        return 時給

    if 語 == "月額":
        月 = 値("委託.月給", 前 + "報酬")
        雇 = 値("委託.雇用分", 前 + "報酬", 要る=v.get("人.区分") == "委託の併用") or Decimal(0)
        帳.置く(前 + "報酬", 月 - 雇, f"委託.月給 {月}−委託.雇用分 {雇}")
        if "残業（会社の数え方）" in 人.勤怠の全部:   # 前の道具の残業＝日ごとの所定超え（芯/集計 の会社の数え方・#26。休日勤務の日は数えない）
            残 = 時("残業（会社の数え方）", 前 + "残業") / 60
        else:
            # 所定休日の労働は残業の語の内数（所定 0 の日）＝休日で払い残業から外す（前の道具 timecard_tally 403〜406 行の continue）
            残 = max(Decimal(0), 時("法定内残業", 前 + "残業") + 時("法定外残業", 前 + "残業") - 時("所定休日", 前 + "残業")) / 60
        残, みなしの字 = _みなしを引く(人, 残, 仮)
        帳.置く(前 + "残業", 丸(残 * 時給で(前 + "残業") * 率["割増.時間外の率"], "残業"),
               f"残業 {残} 時間{みなしの字}×時給×{率['割増.時間外の率']}")
        深 = 時("深夜", 前 + "深夜") / 60
        帳.置く(前 + "深夜", 丸(深 * 時給で(前 + "深夜") * 率["割増.深夜の率"], "深夜"), f"深夜 {深} 時間×時給×{率['割増.深夜の率']}")
        休 = (時("法定休日", 前 + "休日") + 時("所定休日", 前 + "休日")) / 60
        帳.置く(前 + "休日", 丸(休 * 時給で(前 + "休日") * 率["割増.休日の率"], "休日"), f"休日出勤（法定＋所定） {休} 時間×時給×{率['割増.休日の率']}")
        欠 = 時("欠勤", 前 + "欠勤控除")
        if 欠 and not 日の所定:
            仮(前 + "欠勤控除", "時間.日の所定 が無い（委託分の欠勤の時間が出ない）", "0")
        帳.置く(前 + "欠勤控除", 丸(欠 * (日の所定 or 0) * 時給で(前 + "欠勤控除") if 欠 else Decimal(0), "欠勤"),
               f"欠勤 {欠} 日×1 日の所定 {日の所定} 時間×時給")
    else:
        if str(v.get("委託.みなし残業時間") or "").strip() not in ("", *_無しの字):
            人.知らせ.append(f"委託.みなし残業時間 {v.get('委託.みなし残業時間')} は 委託.式＝{語} では引かない（残業の行が無い式。引くのは 月額 だけ）")
        出 = 時("出勤日数", 前 + "報酬")
        日ごと = (人.入力 or {}).get("委託.日ごとの実働")
        境, 向き = 境を読む(v.get("委託.日当の境"))
        if 語 == "日ごとに時給か日当" and 境 is None:
            境 = 日の所定 * 60 if 日の所定 else None
            if 日の所定 == 0 and 日給 is not None:   # 前の道具は境＝cap＝0（以上）で全部の日が日当。黙って確定にせず問う
                境, 向き = Decimal(0), "以上"
                仮(前 + "報酬", "1 日の所定が 0 で 委託.日当の境 が無い（前の道具は境 0＝全部の日を日当）", "全部の日を日当",
                   "境 0 以上＝全部の日を日当で見当", "委託.日当の境 を書く（か 1 日の所定を確かめる）")
        if 語 == "日給":
            報酬 = _切捨て(出 * 値("委託.日給", 前 + "報酬"))
            出所 = f"出勤 {出} 日×委託.日給"
        elif isinstance(日ごと, dict) and 日ごと:
            報酬, 並び = Decimal(0), []
            実丸 = 実働の丸めを読む(v.get("委託.実働の丸め"))
            if 実丸 is None:
                仮(前 + "報酬", "委託.実働の丸め が無いか読めない", "丸めない",
                   "日ごとの実働を丸めずに見当（前の道具は勤務の長さの丸めで日ごとに切り捨てた・丸めは委託の契約で決まる）",
                   "委託.実働の丸め を `15分切捨て` の形か `丸めない` で書く")
            for 日, w in sorted(日ごと.items()):
                w = _分(w) or Decimal(0)
                if 実丸:
                    w = 丸める(w, 実丸[1], 実丸[0])
                届く = 境 is not None and (w >= 境 if 向き == "以上" else w > 境)
                if 語 == "日ごとに時給か日当" and 日給 is not None and 届く:
                    x, why = 日給, "日当"
                else:
                    x, why = 丸(w / 60 * 時給で(前 + "報酬"), "日ごと"), "時給"
                報酬 += x
                並び.append(f"{日} {x}（{why}）")
            出所 = (f"境 {境} 分{向き}は日当・ほかは時給"
                  + (f"（日ごとの実働を {実丸[0]} 分{実丸[1]}）" if 実丸 else "") + ": " + "・".join(並び))
        elif 語 == "時給":
            総 = 時("総労働", 前 + "報酬")
            報酬 = 丸(総 / 60 * 時給で(前 + "報酬"), "日ごと")
            if 実働の丸めを読む(v.get("委託.実働の丸め")) is not False:
                仮(前 + "報酬", "委託.日ごとの実働 が無い（委託.実働の丸め を日ごとに当てられない）", "丸めない",
                   "総労働を丸めずに見当", "日ごとの実働を渡すか 委託.実働の丸め を `丸めない` にする")
            出所 = f"総労働 {総} 分×時給（日ごとの実働が無い＝月で 1 回丸め）"
        else:
            仮(前 + "報酬", "委託.日ごとの実働 が無い（日ごとに時給か日当を選べない）", "出勤の日を全部日当",
               "日ごとの実働は月の数字の語に無い（殻か芯/集計が渡す）", "日ごとの実働を渡す")
            報酬 = _切捨て(出 * (日給 or Decimal(0)))
            出所 = f"見当: 出勤 {出} 日×委託.日給"
        帳.置く(前 + "報酬", 報酬, 出所)
        休 = (時("法定休日", 前 + "休日") + 時("所定休日", 前 + "休日")) / 60
        帳.置く(前 + "休日", 丸(休 * (時給 or Decimal(0)) * 率["割増.休日の率"], "休日") if 休 else Decimal(0),
               f"休日出勤（法定＋所定） {休} 時間×時給×{率['割増.休日の率']}")
        if 休 and 時給 is None:
            時給で(前 + "休日")
        通 = 数(v.get("委託.通勤日額"), "委託.通勤日額") or Decimal(0)
        帳.置く(前 + "通勤費", _切捨て(通 * 出), f"委託.通勤日額 {通}×出勤 {出} 日")

    足す = [前 + n for n in ("報酬", "残業", "深夜", "休日", "出張", "通勤費", "欠勤控除")]
    帳.足し合わせ(前 + "課税計", 足す, {前 + "欠勤控除": -1}, "委託分の和")
    if "合計" in 丸め and v.get("委託.丸め") and not 丸めの語か(v.get("委託.丸め")):
        帳.項目[前 + "課税計"].値 = 丸(帳.項目[前 + "課税計"].値, "合計")
    課税計 = 帳.項目[前 + "課税計"].値
    入れる = v.get("人.区分") == "委託の併用" and v.get("委託.社保と源泉の元に入れる") == "入れる"
    if 入れる:
        帳.置く(前 + "源泉所得税", Decimal(0), "委託.社保と源泉の元に入れる＝入れる（雇用分の源泉で引く）")
    elif v.get("源泉.報酬") == "対象でない":
        帳.置く(前 + "源泉所得税", Decimal(0), "源泉.報酬＝対象でない")
    else:
        帳.置く(前 + "源泉所得税", *_源泉(人, 課税計))
        源 = v.get("源泉.報酬")
        if not (源 is None or 源 == "" or 源 == "対象"):   # 並び・知らない字を黙って 対象 と読まない（対象でない かもしれない）
            仮(前 + "源泉所得税", f"源泉.報酬「{源!r}」が 対象・対象でない のどちらでもない（並びか知らない字）",
               str(帳.項目[前 + "源泉所得税"].値), "法の率で見当（対象でない なら 0）", "源泉.報酬 を 対象 か 対象でない の 1 つで書く")
    帳.足し合わせ(前 + "差引支給額", [前 + "課税計", 前 + "源泉所得税"], {前 + "源泉所得税": -1}, "委託分の課税計−源泉")
    人.委託の流れ = {
        前 + "課税計": 足す,
        前 + "源泉所得税": [前 + "課税計"],
        前 + "差引支給額": [前 + "課税計", 前 + "源泉所得税"],
    }
    return 課税計 if 入れる else Decimal(0)


_無しの字 = ("無し", "なし")


def みなしを読む(v) -> tuple[Decimal | None, str]:
    """委託.みなし残業時間 → (分, 訳)。訳が空なら読めた。無し は 0。
    空は (None, 無い)。h:mm でない数は時間の数として見当（`10` を 10 分と読まない）・崩れや負は (None, 読めない)。"""
    s = str(v if v is not None else "").strip()
    if not s:
        return None, "無い"
    if s in _無しの字:
        return Decimal(0), ""
    try:
        if ":" in s:
            x, 訳 = _分(s), ""
        else:
            x, 訳 = 数(s) * 60, "h:mm でない（時間の数として見当）"
    except (形の誤り, TypeError):
        return None, "読めない"
    if x is None or x < 0:
        return None, "読めない"
    return x, 訳


def _みなしを引く(人, 残: Decimal, 仮) -> tuple[Decimal, str]:
    """月額の式の残業（時間）から 委託.みなし残業時間 を引く（オーナーの答え: 会社の数え方は「1 日の所定超え − みなし」）。
    前の道具（timecard_tally の itaku）は みなし残業 の式で 総勤務−委託の所定時間−委託のみなし残業時間 を追加残業にした＝みなしの分は払わない。
    値が無い・読めない時は引かずに見当で仮＋問い（黙って 0 にしない）。残業が無い月は値を問わない（額が変わらない）。
    引いた後が法の線の法定外残業（所定休日の分を除く）を下回れば知らせ（払うのは会社の決まりのまま・委託分は労基法の賃金の外）。"""
    if 残 <= 0:
        return 残, ""
    v = 人.v
    原 = v.get("委託.みなし残業時間")
    分, 訳 = みなしを読む(原)
    効く = 前 + "残業"
    if 分 is None:
        what = "委託.みなし残業時間 が無い" if 訳 == "無い" else f"委託.みなし残業時間「{原}」が{訳}"
        仮(効く, what, "みなしを引かない", "みなしを引かずに見当（黙って 0 にしない）",
           "委託.みなし残業時間 を h:mm（例 10:00）か 無し で書く")
        return 残, "（みなしを引かずに見当）"
    if 訳:
        仮(効く, f"委託.みなし残業時間「{原}」が{訳}", f"{分 / 60} 時間", "時間の数として見当",
           "委託.みなし残業時間 を h:mm（例 10:00）で書く")
    if not 分:
        return 残, ""
    後 = max(Decimal(0), 残 - 分 / 60)
    法 = _生の分(人, "法定外残業") - _生の分(人, "所定休日")
    if 法 > 0 and 後 * 60 < 法:
        人.知らせ.append(f"委託分の残業（みなし {分 / 60} 時間を引いた後）{後} 時間が法の線の法定外残業 {法 / 60} 時間を下回る"
                       "（払うのは会社の決まりのまま）")
    return 後, f"（みなし {分 / 60} 時間を引いた後・引く前 {残} 時間）"


def _生の分(人, 語) -> Decimal:
    """知らせの照らしだけに使う月の数字（仮の理由を足さない）。"""
    x = 人.勤怠の全部.get(語)
    return (x[0] or Decimal(0)) if x else Decimal(0)


def _切捨て(x: Decimal) -> Decimal:
    """1 円未満を切り捨てる（日数が 0.5 の日など。前の道具の int() と同じ）。"""
    return x.quantize(Decimal(1), rounding=ROUND_FLOOR)


def _源泉(人, 額: Decimal):
    """(税, 出所)。法の表/源泉_報酬（支払日・値 {率%, 境の額, 境を超えた分の率%}）の率。表は手で作らない。"""
    効く = 前 + "源泉所得税"
    会社 = 数(人.v.get("委託.源泉率"), "委託.源泉率")
    表, 出所 = 人.引く("源泉_報酬", 人.支給日.isoformat(), 効く)
    if 表 is None:
        if 会社 is None:
            return None, 出所
        return (額 * 会社).quantize(Decimal(1), rounding=ROUND_FLOOR), f"委託.源泉率 {会社}（法の表が欠け＝法の率と照らせない）"
    低 = 数(str(表["率%"])) / 100
    境 = 数(str(表["境の額"]))
    高 = 数(str(表["境を超えた分の率%"])) / 100
    if 会社 is not None and 会社 < 低:
        人._仮(効く, 理由(f"委託.源泉率 {会社} が法の率 {低} を下回る", str(低), "法の率で計算（所得税法 204 条）", "委託.源泉率 を確かめる"))
    elif 会社 is not None:
        低 = 会社
    税 = min(額, 境) * 低 + max(Decimal(0), 額 - 境) * 高
    return 税.quantize(Decimal(1), rounding=ROUND_FLOOR), f"{出所}・{低}（{境} 円を超えた分は {高}）・課税計 {額}"
