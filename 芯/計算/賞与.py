"""賞与の 1 人（賞与の額 → 標準賞与額・社会保険・雇用保険・源泉・差引支給額）。賞与の額は会社が決める（芯は額を出さない）。

社保の式・端数・丸めの順・年齢・資格・免除は月の給与と同じ（支給控除.一人._社保 を、標準報酬を標準賞与額に、保険料の月を支給月にして呼ぶ）。
法の値は 引く口 で 法の表/ から引く（`標準賞与額の上限`・`雇保の率`・`源泉_賞与の算出率`・`源泉_月額表`）。

- 標準賞与額＝賞与の額の 1,000 円未満切り捨て（健康保険法 45 条 1 項・厚生年金保険法 24 条の 4 第 1 項）。
  健保（介護・子ども子育て支援金も）は年度の累計の上限から同じ年度の前の賞与の標準賞与額（健保）の計を引いた残りまで、厚年は 1 か月の上限まで。
- 雇用保険＝賞与の額×労働者の率（支給日で引く。会社の決まり `雇保.本人負担率` があればその率）。端数は `雇保.端数`。
- 源泉＝（賞与−社会保険計）×算出率（前月の社会保険料等控除後の給与等の金額・扶養の数・甲乙で引く。1 円未満切り捨て）。
  前月の給与が無い・0 以下・社保控除後の賞与がその 10 倍を超える時は月額表で ÷月数・×月数（所得税法 第186条第1項第1号ロ・第2号ロ・第2項）。
  月数は 法の表/源泉_賞与の月額表の月数 から引く（賞与の計算期間が 境の月数 以下なら 境まで、超えるなら 境を超える）。
  月額表の道で計算期間が渡らない人は 境まで で見当して 源泉所得税 を仮＋問い 1 つ。算出率の表の道は計算期間を使わない（仮にしない）。
"""
from __future__ import annotations

from calendar import monthrange
from datetime import date
from decimal import ROUND_FLOOR, Decimal

from .形 import 形の誤り, 数, 理由
from .支給控除 import 一人, 式が無い, 月額表の税額, 社保の項目

社保の計 = 社保の項目 + ("雇用保険",)


def _切り捨て(x: Decimal) -> Decimal:
    return Decimal(x).to_integral_value(rounding=ROUND_FLOOR)


class 賞与の一人(一人):
    """前月: 前月の課税対象額（円・None＝前月の給与が無い）。前の標準: 同じ年度の前の賞与の標準賞与額（健保）の計（円）。
    計算期間: 賞与の計算期間（月数・{"始め", "終わり"}・(始め, 終わり) のどれか。None＝渡されていない）。月額表の道だけが読む。
    見当の理由: 前月・前の標準が渡されていない時の仮の理由（[(効く項目, 理由)]）。"""

    def __init__(self, 支給月, 支給日: date, 値たち, 額, 原本, 前月, 前の標準, 置き場=None, 事前の理由=(), 計算期間=None):
        super().__init__(支給月, 値たち, {}, None, 置き場, 事前の理由)
        self.支給日, self.額, self.原本, self.前月, self.前の標準 = 支給日, 額, 原本, 前月, 前の標準
        self.計算期間 = 計算期間
        self.法の線の行 = []

    def 計算(self):
        v = self.v
        self.期間 = (self.支給日, self.支給日)
        if v.get("人.区分") == "委託":
            raise 式が無い("人.区分＝委託 の報酬の式（源泉.報酬）はこの芯にまだ無い")
        a = 数(self.額, "賞与の額")
        if a is None or a < 0 or a != a.to_integral_value():
            self._仮("全部", 理由(f"賞与の額「{self.額}」が 0 以上の円の整数でない", "0", "0 で置いた", "支給一覧の額を確かめる"))
            a = Decimal(0)
        self.帳.置く("賞与", a, f"賞与:{self.原本 or '原本の名前なし'}")
        退 = v.get("人.退職日")
        if 退 and date.fromisoformat(str(退)) < self.支給日 and a:
            self._仮("全部", 理由(f"退職日 {退} より後の賞与の支払い", "", "在職の人として計算した", "源泉の欄・社保を確かめる"))

        # 標準賞与額（健保は年度の累計・厚年は 1 か月の上限）
        標準 = _切り捨て(a / 1000) * 1000
        日 = self.支給日.isoformat()
        上健, _ = self.引く("標準賞与額の上限", 日, "健康保険・介護保険・子ども・子育て支援金・標準賞与額（健保）", 制度="健保")
        上厚, _ = self.引く("標準賞与額の上限", 日, "厚生年金・標準賞与額（厚年）", 制度="厚年")
        健 = max(Decimal(0), min(標準, Decimal(上健["上限"]) - Decimal(self.前の標準 or 0))) if 上健 else 標準
        厚 = min(標準, Decimal(上厚["上限"])) if 上厚 else 標準
        if a:
            self.v = {**v, "社保.標準報酬": 健, "社保.厚年の標準報酬": 厚, "社保.徴収の月": "当月徴収"}
            self.等級を照らす = False
            self._社保()
            self.v = v
        else:
            for n in 社保の項目:
                self.帳.置く(n, Decimal(0), "賞与の額が 0")
        掛からない = v.get("社保.加入") != "加入" or all(not (self.帳.項目[n].値 or 0) for n in ("健康保険", "厚生年金"))
        self.帳.置く("標準賞与額（健保）", Decimal(0) if 掛からない else 健, "賞与の 1,000 円未満切り捨て・年度の累計の上限")
        self.帳.置く("標準賞与額（厚年）", Decimal(0) if 掛からない else 厚, "賞与の 1,000 円未満切り捨て・1 か月の上限")

        if a:
            self._雇保([], 元=a)
        else:
            self.帳.置く("雇用保険", Decimal(0), "賞与の額が 0")
        self.帳.足し合わせ("社会保険計", 社保の計, None, "社保と雇保の和")
        self.帳.足し合わせ("社保控除後", ["賞与", "社会保険計"], {"社会保険計": -1}, "賞与−社会保険計")
        if self.前月 is not None and a:   # 源泉を算出率で出す時に読む値（賞与が 0 の人は出さない）
            self.帳.置く("前月の社保控除後の給与", Decimal(self.前月), "前月の課税対象額")
        if a:
            self._賞与の源泉()
        else:
            self.帳.置く("源泉所得税", Decimal(0), "賞与の額が 0")
        self.帳.足し合わせ("控除合計", ["社会保険計", "源泉所得税"], None, "社会保険計＋源泉所得税")
        self.帳.足し合わせ("差引支給額", ["賞与", "控除合計"], {"控除合計": -1}, "賞与−控除合計")
        for 名, x in self.帳.項目.items():
            x.理由たち = tuple(dict.fromkeys(list(x.理由たち) + self._効く理由(名)))
        for 名, 元 in (("社会保険計", 社保の計), ("社保控除後", ("社会保険計",)), ("源泉所得税", ("社保控除後",)),
                      ("控除合計", ("社会保険計", "源泉所得税")), ("差引支給額", ("賞与", "控除合計"))):
            x = self.帳.項目.get(名)
            if x is not None:
                足す = [r for n in 元 if n in self.帳.項目 for r in self.帳.項目[n].理由たち]
                x.理由たち = tuple(dict.fromkeys(list(x.理由たち) + 足す))
        return self.帳

    def _賞与の源泉(self):
        v = self.v
        if v.get("源泉.住む所") != "居住者":
            raise 式が無い("源泉.住む所＝非居住者 の率はこの芯にまだ無い（優先 B）")
        欄 = v.get("源泉.欄")
        if 欄 not in ("甲", "乙"):
            raise 式が無い(f"源泉.欄「{欄}」の表はこの芯にまだ無い（丙は優先 B）")
        扶養 = int(数(v.get("源泉.扶養の数"), "源泉.扶養の数") or 0)
        課税 = max(Decimal(0), self.帳.項目["社保控除後"].値)
        前月 = self.前月
        日 = self.支給日.isoformat()
        if 前月 is None or 前月 <= 0 or 課税 > Decimal(前月) * 10:
            表, 出所 = self.引く("源泉_月額表", 日, "源泉所得税")
            月の表, 月の出所 = self.引く("源泉_賞与の月額表の月数", 日, "源泉所得税")
            if 表 is None or 月の表 is None:
                self.帳.置く("源泉所得税", None, 出所 if 表 is None else 月の出所)
                return
            月数, 期間の字 = self._月数(月の表)
            x = _切り捨て(課税 / 月数)
            if 前月 is None or 前月 <= 0:
                税 = 月額表の税額(表, x, 欄, 扶養) * 月数
                出し方 = f"月額表（前月の給与なし・÷{月数}×{月数}・{期間の字}）"
            else:
                税 = (月額表の税額(表, Decimal(前月) + x, 欄, 扶養) - 月額表の税額(表, Decimal(前月), 欄, 扶養)) * 月数
                出し方 = f"月額表（前月の 10 倍を超える・÷{月数}×{月数}・{期間の字}）"
            self.帳.置く("源泉所得税", 税, f"{出所}・{月の出所}・{出し方}・{欄}欄・扶養 {扶養}")
            return
        表, 出所 = self.引く("源泉_賞与の算出率", 日, "源泉所得税")
        if 表 is None:
            self.帳.置く("源泉所得税", None, 出所)
            return
        率 = _算出率(表, int(前月), 欄, 扶養)
        if 率 is None:
            self._仮("源泉所得税", 理由(f"賞与の算出率の表で前月 {前月} 円（{欄}・扶養 {扶養}）が当たらない", "0", "法の表/源泉_賞与の算出率"))
            self.帳.置く("源泉所得税", Decimal(0), 出所)
            return
        self.帳.置く("源泉所得税", _切り捨て(課税 * 率), f"{出所}・算出率 {率 * 100}%・{欄}欄・扶養 {扶養}・前月 {前月}")

    def _月数(self, 月の表: dict) -> tuple[int, str]:
        """法の表/源泉_賞与の月額表の月数 の値と計算期間 → (割って掛ける月数, 出所の字)。渡らない・読めない時は 境まで で見当して仮。"""
        境, 内, 外 = int(月の表["境の月数"]), int(月の表["境まで"]), int(月の表["境を超える"])
        超える = _期間が境を超える(self.計算期間, 境)
        if 超える is None:
            何 = ("賞与の計算期間が渡されていない" if self.計算期間 is None
                  else f"賞与の計算期間「{self.計算期間}」が読めない（月数か 始めと終わりの日）")
            self._仮("源泉所得税", 理由(何, f"{境} か月以下", f"月額表で ÷{内}×{内} として計算（所得税法 第186条・法の表/源泉_賞与の月額表の月数）",
                                    "賞与の計算期間（月数か 始めと終わりの日）を渡す"))
            return 内, f"計算期間 見当 {境} か月以下"
        return (外, f"計算期間 {境} か月を超える") if 超える else (内, f"計算期間 {境} か月以下")


def _算出率(表: dict, 前月: int, 欄: str, 扶養: int) -> Decimal | None:
    """法の表/源泉_賞与の算出率 の 1 行の値 → 率（小数）。甲は扶養 7 人までの列（7 人を超える時は 7 人の列）。"""
    if 欄 == "甲":
        n = min(扶養, 7)
        for 段 in 表["甲"]:
            a, b = 段["甲"][n]
            if (a is None or 前月 >= a) and (b is None or 前月 < b):
                return 数(str(段["率%"])) / 100
    else:
        for 段 in 表["乙"]:
            if (段["以上"] is None or 前月 >= 段["以上"]) and (段["未満"] is None or 前月 < 段["未満"]):
                return 数(str(段["率%"])) / 100
    return None


def _月を足す(d: date, n: int) -> date:
    y, m = divmod(d.month - 1 + n, 12)
    y, m = d.year + y, m + 1
    return date(y, m, min(d.day, monthrange(y, m)[1]))


def _期間が境を超える(期間, 境: int) -> bool | None:
    """賞与の計算期間が 境 か月を超えるか。期間は月数（数・字）か {"始め", "終わり"}・(始め, 終わり)（日は YYYY-MM-DD・両端を含む）。
    日で渡れば 終わり が 始め の 境 か月後の同じ日（無ければ月末）以後の時に超える（例 1/1〜6/30 は 6 か月・1/1〜7/1 は超える）。読めない時は None。"""
    if 期間 is None or isinstance(期間, bool):
        return None
    if isinstance(期間, dict):
        期間 = (期間.get("始め"), 期間.get("終わり"))
    if isinstance(期間, (tuple, list)):
        if len(期間) != 2:
            return None
        try:
            始め, 終わり = (x if isinstance(x, date) else date.fromisoformat(str(x)) for x in 期間)
        except (TypeError, ValueError):
            return None
        if 終わり < 始め:
            return None
        return 終わり >= _月を足す(始め, 境)
    try:
        n = 数(期間, "賞与の計算期間")
    except 形の誤り:
        return None
    if n is None or not n.is_finite() or n <= 0:
        return None
    return n > 境
