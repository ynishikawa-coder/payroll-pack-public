# 芯/集計 が期間の法の線として引く名（要る＝欠ければ止める・任意＝無ければ渡さない）
集計の要る = ("時間.日の法定", "時間.週の法定", "割増.深夜の時間帯")
集計の任意 = ("時間.週の法定の特例", "割増.60時間超の境", "時間.休憩の長さ", "休日.4週の休日数")
# 効く始めより前の日は線が無い（法がまだ無かった）＝芯/集計 は欠けても止めずに無しで渡す線
前は無い線 = frozenset({"月60時間超の時間外の割増"})


def 欄の値(名: str, 値: dict):
    """法の線の行の値（dict）から芯の名の値を取り出す（"倍"・"足す" の率の直しは数で読む側＝芯/計算 がする）。無ければ None。"""
    _, 欄, 直し = 読み方[名]
    if 直し == "時間帯":
        return f"{値['始め']}〜{値['終わり']}"
    x = 値.get(欄)
    if 直し == "段":
        return [[段["労働時間の超え"], 段["休憩の分"]] for 段 in x or ()]
    return x
