# 必ず埋める欄が空の人を仮で計算する時の見当（決定 2026-11-27: 全員を計算し、仮が 1 つでも残る会社は出口へ出さない）。
# 見当は既定ではない＝この字で数えた額は全部が仮（その人の全部の項目が仮＋欄ごとに問い 1 つ）で、確定の額にならない。
必ずの見当 = {
    "人.区分": "社員",
    "時間.制度": "通常",
    "社保.加入": "加入",
    "社保.徴収の月": "翌月徴収",
    "雇保.加入": "加入",
    "源泉.欄": "甲",
    "源泉.扶養の数": "0",
}
if set(必ずの見当) != set(必ずの要る時):
    raise RuntimeError(f"要る値.必ずの見当 {sorted(必ずの見当)} と 必ずの要る時 {sorted(必ずの要る時)} が食い違う")


def _欠けた欄(元: dict, v: dict) -> list[tuple[str, str]]:
    """[(名, 理由の字)]（名の順）。元＝照らす前の値たち、v＝確かめる の返す値たち。"""
    out = []
    for 名 in sorted(必ずの要る時):
        if not _空(v.get(名)) or not 必ずの要る時[名](v):
            continue
        字 = 元.get(名)
        out.append((名, f"{必ずの欠けの頭}{名}" if _空(字) else f"{必ずの欠けの頭}{名}（選べる値に無い字「{字}」を外した）"))
    return out


def 必ずの欠け(元: dict, v: dict) -> list[str]:
    """必ず埋める欄のうち、その人に要るのに空の欄の理由（名の順）。空でなければ 必ずを見当で埋める で仮に計算する。
    元＝段の解決の後の値たち（照らす前）、v＝確かめる の返す値たち（選べる値の外の字は 照らす が外して空にしている）。
    人.区分 が空・読めない人は全部の欄が要る（区分で外れる欄を決められない）。"""
    return [t for _, t in _欠けた欄(元, v)]


def 必ずを見当で埋める(元: dict, 集計の外れ=()) -> tuple[dict, list[tuple[str, 理由]], list[str]]:
    """必ず埋める欄の空を 必ずの見当 で埋めて 確かめる をかけ直す（値たち, 事前, 欠けの理由の字）を返す。
    欠けた欄ごとに ("全部", 理由) を事前に足す＝その人の全部の項目が仮になり、欄ごとに問いが 1 つ立つ（黙って確定しない）。
    区分を見当で埋めると要る欄が増える（社員なら時間の制度も要る）ので、欠けが無くなるまで埋め直す。"""
    w, 欠けたち, 前の事前 = dict(元), [], []
    while True:
        v, 事前 = 確かめる(w, 集計の外れ)
        前の事前 += 事前   # 1 周目の理由（選べる値の外の字など）は見当で字を差し替えた後も問いのまま残す
        欠 = [(名, t) for 名, t in _欠けた欄(w, v) if 名 not in dict(欠けたち)]
        if not 欠:
            break
        for 名, t in 欠:
            欠けたち.append((名, t))
            w[名] = 必ずの見当[名]
    理由たち = [("全部", 理由(t, 必ずの見当[名],
                           f"必ず埋める欄が空＝「{必ずの見当[名]}」で仮に計算した（この人の額は全部が仮。仮が残る会社は出口へ出さない）",
                           f"マスタの {名} を埋める（見当のとおりでも、マスタに書いてから計算し直す）")) for 名, t in 欠けたち]
    return v, list(dict.fromkeys([*前の事前, *理由たち])), [t for _, t in 欠けたち]


# 会社の暦（`時間.暦`）が無い時の仮の理由。入口の文脈（期間の休日を決める）と芯/計算（暦の所定日数）で同じ字＝問い 1 つ
暦が無い = "「時間.暦」が無い"
暦の見当 = "土日祝が休み"
暦の拠り所 = "会社の所定休日の暦（時間.暦）が無い＝土日祝が休みで見当（黙って決めない）"
暦の答え方 = "会社の所定休日の暦（休みの曜日・祝日の扱い・会社の休みの日）を書く。土日祝が休みなら そのとおり と答える"


def 暦が要るか(v: dict) -> bool:
    """芯/計算 が会社の暦から数える人か（月の所定日数・時間を 年平均・その月の暦の所定日数 で出す・入退社を所定日割する・日割を会社のその月の所定日数で割る）。
    役員（所定を持たない）・委託だけの人（給与の部品が 委託 だけ）は使わない。"""
    if not _雇用か(v):
        return False
    暦で = ("年平均", "その月の暦の所定日数")
    return (v.get("時間.月の所定日数の出し方") in 暦で or v.get("時間.月の所定時間の出し方") in 暦で
            or v.get("日割.入退社") == "所定日割"
            or (v.get("日割.割る数") == "会社のその月の所定日数" and v.get("時間.月の所定日数の出し方") != "固定の値"))


# 欠勤.控除の式＝欠勤が多い月だけ出た日で払う の「多い月」の線（会社の段）。N 日以上の線は N を 欠勤.多い月の日数 で持つ
多い月の式 = "欠勤が多い月だけ出た日で払う"
半分の線 = "所定日数の半分を超えた月"
N日の線 = "欠勤が N 日以上の月"


def 多い月の日数(v: dict) -> int | None:
    """N 日以上の線の N（1 以上の整数）。空・数でない・整数でない・1 未満は None（黙って半分の線へ倒さない＝確かめる が仮＋問い）。"""
    字 = v.get("欠勤.多い月の日数")
    if isinstance(字, bool) or isinstance(字, float):
        return None
    try:
        n = Decimal(str(字).strip().replace(",", "")) if not _空(字) else None
    except InvalidOperation:
        return None
    if n is None or not n.is_finite() or n != n.to_integral_value() or n < 1:
        return None
    return int(n)


def 多い月の日数の欠け(v: dict) -> bool:
    """月給の形の人で N 日以上の線を選んだのに N が読めないか（読めない月は半分の線で見当して仮）。"""
    from .支給控除 import 月給の形   # 支給控除 は 要る値 を引く（import の輪を避けて関数の中で引く）
    return (v.get("支払.賃金の形") in 月給の形 and v.get("欠勤.控除の式") == 多い月の式
            and v.get("欠勤.多い月の線") == N日の線 and 多い月の日数(v) is None)


def 外れの理由(x: 設定.外れ) -> 理由:
    e = 設定.表()[x.名]
    選べる = "・".join(e.get("選べる値") or ()) or "表の形"
    見当 = "" if x.置いた is None else str(x.置いた)
    return 理由(x.文(), 見当, f"{x.名} が選べる値の外＝{('「' + 見当 + '」で計算した') if 見当 else '値を外して計算した'}",
               f"{x.名} を選べる値（{選べる}）の 1 つで書く")


def 部品の外れの理由(x: 設定.外れ) -> 理由:
    列 = x.名.rsplit("」の ", 1)[-1]
    選べる = "・".join(設定.部品の列()[列]["選べる値"])
    見当 = "" if x.置いた is None else str(x.置いた)
    return 理由(x.文(), 見当, f"{x.名} が{x.訳}＝{('「' + 見当 + '」で計算した') if 見当 else '値を外して計算した'}",
               f"{x.名} を選べる値（{選べる}）の 1 つで書く")


払う人が居ない = "払う人が居ない"   # 部品の行の 数量の元: 会社はその行を持つが今は払う人が居ない＝芯はその行を使わない


def 払う人の居ない行を除く(v: dict) -> list[tuple[str, 理由]]:
    """項目.行 から 数量の元＝払う人が居ない の行を除く（どの芯の読み手もその行を見ない＝ここ 1 か所）。
    その人に人の額が在れば（払う人が居る）黙って捨てず、行を除いて計算して仮＋問い（⟦鍵:給与計算/足りない時は仮で計算し出さない⟧）。
    月の変動の値（入力）は 段の解決 が 数量の元が入力の値でない行として既に仮にする。"""
    行たち = v.get("項目.行") or []
    除く = [r for r in 行たち if str(r.get("数量の元") or "").strip() == 払う人が居ない]
    if not 除く:
        return []
    v["項目.行"] = [r for r in 行たち if r not in 除く]
    人の額 = v.get("項目.人の額") or {}
    out = []
    for r in 除く:
        額 = 人の額.get(r.get("名"))
        if _空(額) or str(額).strip() in ("0", "0.0"):
            continue
        out.append(("全部", 理由(f"支給控除の項目「{r.get('名')}」は 数量の元＝{払う人が居ない} だが、この人に人の額 {額} が在る",
                                "0", f"その行を除いて計算（{払う人が居ない}＝払わない）",
                                f"この人に払うなら 支給控除の項目「{r.get('名')}」の 数量の元 を払う形（1・勤怠の数:<語>・入力の値）に直す。"
                                "払わないならこの人の人の額を消す")))
    return out


def 確かめる(値たち: dict, 集計の外れ=()) -> tuple[dict, list[tuple[str, 理由]]]:
    """既定で埋め、要るのに無い値を見当で埋めた値たちと、[(効く項目の字, 理由)] を返す（止めない）。
    集計の外れ: 芯/集計 が同じ人で既に選べる値の外として仮＋問いにした名（集計の人の `設定の外れ`）。値は同じに直すが、
    問いは集計の 1 つに寄せて重ねない（同じ原因の問いが 2 つあると、片方だけ答えた時に答え済みの照らしが割れる）。
    その人は集計の状態が仮なので、計算の側でも出口へ出ない（_回す の 集計の状態）。"""
    v = dict(値たち)
    for k, x in 既定.items():
        if _空(v.get(k)):
            v[k] = x
    # 全部の設定を 芯/設定の表.json で照らす（選べる値の外の字は既定か見当で計算して仮＋問い。使う所ごとに照らさない）
    v, 外れたち = 設定.照らす(v, "計算")
    out = [("全部", 外れの理由(x)) for x in 外れたち if x.名 not in set(集計の外れ)]
    # 支給控除の項目の列（項目.行）も 芯/支給控除の列.json で照らす（外の字を各列の既定へ黙って倒さない）
    if v.get("項目.行"):
        v["項目.行"], 行の外れ = 設定.部品の行を照らす(v["項目.行"])
        out += [("全部", 部品の外れの理由(x)) for x in 行の外れ]
        out += 払う人の居ない行を除く(v)
    if str(v.get("支払.給与を払わない") or "").strip() == "はい":
        # 月次は給与を払わない人を芯へ渡さない（期間の外の人）。来たのは勤怠・月の変動が来たか社保に入る人＝黙って 0 にも計算もしない
        out.append(("全部", 理由("支払.給与を払わない＝はい の人に、その月の勤怠・月の変動が来たか 社保.加入＝加入（本人負担が生じる）",
                                "", "給与を払う人として計算した（払わない印と払う物・社保の加入が食い違う）",
                                "払うなら 支払.給与を払わない を いいえ にする。払わないなら、その月の勤怠・月の変動を消すか、"
                                "社保の本人負担の扱い（社保.引けない月の本人負担）を決めて いいえ にする")))
    if _空(v.get("時間.暦")) and 暦が要るか(v):   # 黙って土日祝にしない（暦.所定日数 は無い暦を土日祝で数える＝見当）
        out.append(("全部", 理由(暦が無い, 暦の見当, 暦の拠り所, 暦の答え方)))
    for 名, 要る時, 見当, 拠り所, 効く in 要る:
        if _空(v.get(名)) and 要る時(v):
            if 見当 is not None:
                v[名] = 見当
            out.append((効く, 理由(f"「{名}」が無い", "" if 見当 is None else str(見当), 拠り所,
                                   f"{名} の値を書く（例: 見当のとおり）")))
    if 多い月の日数の欠け(v):
        字 = v.get("欠勤.多い月の日数")
        out.append(("欠勤控除", 理由(
            f"欠勤.多い月の線 が {N日の線} なのに 欠勤.多い月の日数 が{'無い' if _空(字) else f'読めない（「{字}」）'}",
            半分の線, f"欠勤が多い月の線の N が無い＝{半分の線}で見当（黙って決めない）",
            "欠勤.多い月の日数 を 1 以上の整数で書く（例: 10）。半分の線にするなら 欠勤.多い月の線 を 所定日数の半分を超えた月 にする")))
    return v, out
