def _空(v) -> bool:
    return v is None or (isinstance(v, str) and not v.strip()) or v == {} or v == []


def _社保に入る(v: dict) -> bool:
    return v.get("社保.加入") == "加入" and v.get("人.区分") != "委託"


# (項目, 要る時, 見当, 見当の拠り所, 効く項目)。見当 None は「計算しない」（その項目は値なしの仮）。
