既定 = 設定.既定で埋める()


def _空(v) -> bool:
    return v is None or (isinstance(v, str) and not v.strip()) or v == {} or v == []


def _部品に(*名):
    """要る時を給与の部品（芯/計算/形.py の 給与の部品）で言う唯一の形: 名のどれかが部品に在る人に要る。
    区分の組を並べて外さない（新しい組・併せ持つ組が足されても、部品で決まる）。読めない区分（None）は全部の欄が要る側＝真。"""
    def 要る(v: dict) -> bool:
        品 = 給与の部品(v)
        return 品 is None or any(n in 品 for n in 名)
    return 要る


_雇用か = _部品に("雇用")                       # 所定・時間の制度・雇保・賃金の形を読む人
_給与か = _部品に("雇用", "役員報酬")            # 給与として払う部品がある人（社保・源泉・住民税を読む）。委託の部品だけの人は読まない


