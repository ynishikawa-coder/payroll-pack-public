def 確かめる(値たち: dict) -> tuple[dict, list[tuple[str, 理由]]]:
    """既定で埋め、要るのに無い値を見当で埋めた値たちと、[(効く項目の字, 理由)] を返す（止めない）。"""
    v = dict(値たち)
    for k, x in 既定.items():
        if _空(v.get(k)) and not (k == "雇保.加入" and v.get("人.区分") == "役員"):   # 役員は雇保の外（既定で埋めない）
            v[k] = x
    out = []
    for 名, 要る時, 見当, 拠り所, 効く in 要る:
        if _空(v.get(名)) and 要る時(v):
            if 見当 is not None:
                v[名] = 見当
            out.append((効く, 理由(f"「{名}」が無い", "" if 見当 is None else str(見当), 拠り所,
                                   f"{名} の値を書く（例: 見当のとおり）")))
    return v, out
