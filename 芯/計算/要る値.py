"""要る値の確かめ（材料: pixel-office の agents/kyuyo 道具/hitsuyo.py を今の型へ書き直した物）。

その人のその月の計算に要る値が揃っているかを見る。足りない値は **止めずに** 見当で埋め、仮の理由（確認の 1 問の種）を返す。
- 値の名は `docs/設計/会社の決まり.md` §2 の `分野.名`。段の解決（人 → 勤務の型 → 会社 → 事務所）は手前で済んでいる（§1.1）。
- 既定（§2 の「既定」の列）が語の項目は既定で埋める（仮にしない）。既定が「無し」の項目は見当で埋めて仮にする。
- 必ず埋める欄（人.区分・時間.制度・社保.加入・社保.徴収の月・雇保.加入・源泉.欄・源泉.扶養の数）は既定も見当も持たない。
  空ならその人を計算しない（`必ずの欠け`。問いでなく、マスタを埋める欠け＝決定 9・21）。
- 法の値（割増の率・日の法定など）はここに書かない（法の表/法の線.json から 支給控除.py が引く）。
"""
from __future__ import annotations

from decimal import Decimal, InvalidOperation

from 芯 import 設定

from .形 import 給与の部品, 理由

# 会社の決まり §2 の「既定」の列（語の既定だけ。法の線の値は法の表から引く）。芯の読む形の正本は 芯/設定の表.json の 埋める・既定
# （意味の正本は 初期設定/項目.json。食い違えば tests/計算/test_計算_既定と項目の辞書.py が赤）
既定 = 設定.既定で埋める()


def _空(v) -> bool:
    return v is None or (isinstance(v, str) and not v.strip()) or v == {} or v == []


def _雇用か(v: dict) -> bool:
    """雇用の部品がある人（芯/計算/形.py の 給与の部品）。読めない区分は全部の欄が要る側＝真。"""
    品 = 給与の部品(v)
    return 品 is None or "雇用" in 品


def _委託だけか(v: dict) -> bool:
    return 給与の部品(v) == frozenset({"委託"})


def _社保に入る(v: dict) -> bool:
    return v.get("社保.加入") == "加入" and not _委託だけか(v)


# (項目, 要る時, 見当, 見当の拠り所, 効く項目)。見当 None は「計算しない」（その項目は値なしの仮）。
要る = (
    ("支払.締め日", lambda v: True, "末", "締め日が無い＝末締めで見当", "全部"),
    ("支払.支給日", lambda v: True, "末", "支給日が無い＝末日で見当（源泉の表の年を決める）", "源泉所得税"),
    ("支払.賃金の形", _雇用か, "月給", "賃金の形が無い＝月給で見当", "欠勤控除・遅刻早退控除"),
    ("社保.標準報酬", _社保に入る, None, "標準報酬月額が無い＝社保は計算しない", "健康保険・介護保険・子ども・子育て支援金・厚生年金"),
    ("社保.健保の支部", lambda v: _社保に入る(v) and _空(v.get("社保.組合の率")), None,
     "協会けんぽの支部（都道府県）も組合の率も無い＝健保は計算しない", "健康保険・介護保険・子ども・子育て支援金"),
    ("人.生年月日", _社保に入る, "", "生年月日が無い＝介護（40〜64 歳）と年齢の線（70・75 歳）に掛からないとして見当", "介護保険・厚生年金・健康保険"),
    ("住民税.額", lambda v: v.get("住民税.徴収") == "特別徴収" and not _委託だけか(v), "0",
     "特別徴収の額が無い＝0 で見当", "住民税"),
)


# 必ず埋める欄（決定 9・21。芯/設定の表.json の `必ず埋める`）→ その人に要る時。既定を持たない＝空なら黙って社員・甲・加入・通常で数えず、
# その人を計算しない（`必ずの欠け`）。要る時が偽の人は読まない欄（委託だけの人の社保・雇保・源泉・時間の制度、役員の雇保と時間の制度）。
# 表の 必ず埋める とここの鍵が食い違えば import で落ちる（表に足した欄の要る時を書き忘れない）。
必ずの要る時 = {
    "人.区分": lambda v: True,
    "時間.制度": lambda v: 給与の部品(v) not in (frozenset({"委託"}), frozenset({"役員報酬"})),
    "社保.加入": lambda v: not _委託だけか(v),
    "社保.徴収の月": _社保に入る,
    "雇保.加入": _雇用か,
    "源泉.欄": lambda v: not _委託だけか(v),
    "源泉.扶養の数": lambda v: not _委託だけか(v),
}
if set(必ずの要る時) != set(設定.必ず埋める()):
    raise RuntimeError(f"芯/設定の表.json の 必ず埋める {sorted(設定.必ず埋める())} と 要る値.必ずの要る時 {sorted(必ずの要る時)} が食い違う")

必ずの欠けの頭 = "必ず埋める欄が空: "


def 必ずの欠け(元: dict, v: dict) -> list[str]:
    """必ず埋める欄のうち、その人に要るのに空の欄の理由（名の順）。空なら計算してよい。
    元＝段の解決の後の値たち（照らす前）、v＝確かめる の返す値たち（選べる値の外の字は 照らす が外して空にしている）。
    人.区分 が空・読めない人は全部の欄が要る（区分で外れる欄を決められない）。"""
    out = []
    for 名 in sorted(必ずの要る時):
        if not _空(v.get(名)) or not 必ずの要る時[名](v):
            continue
        字 = 元.get(名)
        out.append(f"{必ずの欠けの頭}{名}" if _空(字) else f"{必ずの欠けの頭}{名}（選べる値に無い字「{字}」を外した）")
    return out


# 会社の暦（`時間.暦`）が無い時の仮の理由。入口の文脈（期間の休日を決める）と芯/計算（暦の所定日数）で同じ字＝問い 1 つ
暦が無い = "「時間.暦」が無い"
暦の見当 = "土日祝が休み"
暦の拠り所 = "会社の所定休日の暦（時間.暦）が無い＝土日祝が休みで見当（黙って決めない）"
暦の答え方 = "会社の所定休日の暦（休みの曜日・祝日の扱い・会社の休みの日）を書く。土日祝が休みなら そのとおり と答える"


def 暦が要るか(v: dict) -> bool:
    """芯/計算 が会社の暦から数える人か（月の所定日数・時間を 年平均・その月の暦の所定日数 で出す・入退社を所定日割する・日割を会社のその月の所定日数で割る）。
    役員（所定を持たない）・委託だけの人（給与の部品が 委託 だけ）は使わない。"""
    if not _雇用か(v):
        return False
    暦で = ("年平均", "その月の暦の所定日数")
    return (v.get("時間.月の所定日数の出し方") in 暦で or v.get("時間.月の所定時間の出し方") in 暦で
            or v.get("日割.入退社") == "所定日割"
            or (v.get("日割.割る数") == "会社のその月の所定日数" and v.get("時間.月の所定日数の出し方") != "固定の値"))


# 欠勤.控除の式＝欠勤が多い月だけ出た日で払う の「多い月」の線（会社の段）。N 日以上の線は N を 欠勤.多い月の日数 で持つ
多い月の式 = "欠勤が多い月だけ出た日で払う"
半分の線 = "所定日数の半分を超えた月"
N日の線 = "欠勤が N 日以上の月"


def 多い月の日数(v: dict) -> int | None:
    """N 日以上の線の N（1 以上の整数）。空・数でない・整数でない・1 未満は None（黙って半分の線へ倒さない＝確かめる が仮＋問い）。"""
    字 = v.get("欠勤.多い月の日数")
    if isinstance(字, bool) or isinstance(字, float):
        return None
    try:
        n = Decimal(str(字).strip().replace(",", "")) if not _空(字) else None
    except InvalidOperation:
        return None
    if n is None or not n.is_finite() or n != n.to_integral_value() or n < 1:
        return None
    return int(n)


def 多い月の日数の欠け(v: dict) -> bool:
    """月給の形の人で N 日以上の線を選んだのに N が読めないか（読めない月は半分の線で見当して仮）。"""
    from .支給控除 import 月給の形   # 支給控除 は 要る値 を引く（import の輪を避けて関数の中で引く）
    return (v.get("支払.賃金の形") in 月給の形 and v.get("欠勤.控除の式") == 多い月の式
            and v.get("欠勤.多い月の線") == N日の線 and 多い月の日数(v) is None)


def 外れの理由(x: 設定.外れ) -> 理由:
    e = 設定.表()[x.名]
    選べる = "・".join(e.get("選べる値") or ()) or "表の形"
    見当 = "" if x.置いた is None else str(x.置いた)
    return 理由(x.文(), 見当, f"{x.名} が選べる値の外＝{('「' + 見当 + '」で計算した') if 見当 else '値を外して計算した'}",
               f"{x.名} を選べる値（{選べる}）の 1 つで書く")


def 部品の外れの理由(x: 設定.外れ) -> 理由:
    列 = x.名.rsplit("」の ", 1)[-1]
    選べる = "・".join(設定.部品の列()[列]["選べる値"])
    見当 = "" if x.置いた is None else str(x.置いた)
    return 理由(x.文(), 見当, f"{x.名} が{x.訳}＝{('「' + 見当 + '」で計算した') if 見当 else '値を外して計算した'}",
               f"{x.名} を選べる値（{選べる}）の 1 つで書く")


def 確かめる(値たち: dict, 集計の外れ=()) -> tuple[dict, list[tuple[str, 理由]]]:
    """既定で埋め、要るのに無い値を見当で埋めた値たちと、[(効く項目の字, 理由)] を返す（止めない）。
    集計の外れ: 芯/集計 が同じ人で既に選べる値の外として仮＋問いにした名（集計の人の `設定の外れ`）。値は同じに直すが、
    問いは集計の 1 つに寄せて重ねない（同じ原因の問いが 2 つあると、片方だけ答えた時に答え済みの照らしが割れる）。
    その人は集計の状態が仮なので、計算の側でも出口へ出ない（_回す の 集計の状態）。"""
    v = dict(値たち)
    for k, x in 既定.items():
        if _空(v.get(k)):
            v[k] = x
    # 全部の設定を 芯/設定の表.json で照らす（選べる値の外の字は既定か見当で計算して仮＋問い。使う所ごとに照らさない）
    v, 外れたち = 設定.照らす(v, "計算")
    out = [("全部", 外れの理由(x)) for x in 外れたち if x.名 not in set(集計の外れ)]
    # 支給控除の項目の列（項目.行）も 芯/支給控除の列.json で照らす（外の字を各列の既定へ黙って倒さない）
    if v.get("項目.行"):
        v["項目.行"], 行の外れ = 設定.部品の行を照らす(v["項目.行"])
        out += [("全部", 部品の外れの理由(x)) for x in 行の外れ]
    if _空(v.get("時間.暦")) and 暦が要るか(v):   # 黙って土日祝にしない（暦.所定日数 は無い暦を土日祝で数える＝見当）
        out.append(("全部", 理由(暦が無い, 暦の見当, 暦の拠り所, 暦の答え方)))
    for 名, 要る時, 見当, 拠り所, 効く in 要る:
        if _空(v.get(名)) and 要る時(v):
            if 見当 is not None:
                v[名] = 見当
            out.append((効く, 理由(f"「{名}」が無い", "" if 見当 is None else str(見当), 拠り所,
                                   f"{名} の値を書く（例: 見当のとおり）")))
    if 多い月の日数の欠け(v):
        字 = v.get("欠勤.多い月の日数")
        out.append(("欠勤控除", 理由(
            f"欠勤.多い月の線 が {N日の線} なのに 欠勤.多い月の日数 が{'無い' if _空(字) else f'読めない（「{字}」）'}",
            半分の線, f"欠勤が多い月の線の N が無い＝{半分の線}で見当（黙って決めない）",
            "欠勤.多い月の日数 を 1 以上の整数で書く（例: 10）。半分の線にするなら 欠勤.多い月の線 を 所定日数の半分を超えた月 にする")))
    return v, out
