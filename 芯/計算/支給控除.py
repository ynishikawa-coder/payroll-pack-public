    def 月の所定(self):
        """(月の所定日数, 月の所定時間)。出し方は 時間.月の所定日数の出し方・時間.月の所定時間の出し方。"""
        始め, 終わり = self.期間
        暦の値 = self.v.get("時間.暦")
        効く = "時間外手当・法定内残業手当・60時間超手当・休日手当・深夜手当・欠勤控除・遅刻早退控除"

        def 年():
            y = 終わり.year
            try:
                n, 出所, 仮 = 暦.所定日数(date(y, 1, 1), date(y, 12, 31), 暦の値, self.置き場)
            except 口.欠け as e:
                self._仮(効く, 理由(f"祝日の表が欠け: {e}", "", "年の所定日数を数えられない", "法の表を入れ直す"))
                return None, None
            if 仮:
                self._仮(効く, 理由("祝日の表がまだ（前の年で見当）", "", "法の表/祝日"))
            時間 = Decimal(0)
            d = date(y, 1, 1)
            祝 = 暦.祝日(y, self.置き場)[0]
            while d.year == y:
                if not 暦.休みか(d, 暦の値 or 暦.既定の暦, 祝):
                    h = self._日の所定の時間(d)
                    if h is None:
                        時間 = None
                        break
                    時間 += h
                d += timedelta(days=1)
            return Decimal(n) / 12, (Fraction(時間) / 12 if 時間 is not None else None)   # 時間は ÷12 を分数のまま

        日の出し方 = self.v.get("時間.月の所定日数の出し方")
        時間の出し方 = self.v.get("時間.月の所定時間の出し方")
        if isinstance(暦の値, dict) and "シフト" in 暦の値:
            # シフトの型（決まった休みの曜日が無い）は暦から年・月の所定日数を出せない＝固定の値 か その月の所定日数（勤務した日）で
            暦から = ("年平均", "その月の暦の所定日数")
            if self._所定が要る() and (日の出し方 in 暦から or 時間の出し方 == "年平均"):
                self._仮(効く, 理由("シフトの型（時間.暦＝シフト）は暦から月の所定日数・時間を出せない", "", "所定を 0 で見当",
                                    "時間.月の所定日数の出し方・時間.月の所定時間の出し方 を 固定の値 か その月の所定日数 に"))
            日の出し方 = "暦から出せない" if 日の出し方 in 暦から else 日の出し方
            時間の出し方 = "暦から出せない" if 時間の出し方 == "年平均" else 時間の出し方
        年日, 年時間 = 年() if "年平均" in (日の出し方, 時間の出し方) else (None, None)
        if 日の出し方 == "年平均":
            日数 = 年日
        elif 日の出し方 == "その月の所定日数":
            日数 = self.勤怠の数("所定日数", 効く)
        elif 日の出し方 == "その月の暦日":
            日数 = Decimal((終わり - 始め).days + 1)
        elif 日の出し方 == "その月の暦の所定日数":
            try:
                n, _, 仮 = 暦.所定日数(始め, 終わり, 暦の値, self.置き場)
                日数 = Decimal(n)
                if 仮:
                    self._仮(効く, 理由("祝日の表がまだ（前の年で見当）", "", "法の表/祝日"))
            except 口.欠け as e:
                self._仮(効く, 理由(f"祝日の表が欠け: {e}", "", "その月の暦の所定日数を数えられない", "法の表を入れ直す"))
                日数 = None
        elif 日の出し方 == "固定の値":
            日数 = 数(self.v.get("時間.月の所定日数"), "時間.月の所定日数")
        else:   # 暦から出せない（選べる値の外の字は 要る値 が 芯/設定 で照らした）
            日数 = None
        if 時間の出し方 == "年平均":
            時間 = 年時間
        elif 時間の出し方 == "その月の所定時間":
            日の所定 = self._日の所定の時間(終わり)
            時間 = (self.勤怠の数("所定日数", 効く) * 日の所定) if 日の所定 is not None else None
        elif 時間の出し方 == "固定の値":
            時間 = 時間の値(self.v.get("時間.月の所定時間"), "時間.月の所定時間")   # 時間の数か h:mm（分数で持つ）
        elif 時間の出し方 == "暦から出せない":
            時間 = None
        elif 時間の出し方 == "（出勤日＋有休日）×日の所定":
            # 人の所定（型の版 18）: その月の 出勤日数＋年休の日数（半日は 0.5 日）に日の所定を掛ける（働いた日で所定を決める人）
            日の所定 = self._日の所定の時間(終わり)
            日数たち = self.勤怠の数("出勤日数", 効く) + self.勤怠の数("年休の日数", 効く)
            時間 = 日数たち * 日の所定 if 日の所定 is not None else None
        else:   # 変形の総枠（選べる値の外の字は 要る値 が 芯/設定 で照らした）
            週 = self.法の線("時間.週の法定", 効く)   # 労基法 32 条の 2: 週の法定×期間の暦日÷7（時間未満は切り捨て）
            時間 = (Decimal(週) * ((終わり - 始め).days + 1) / 7).to_integral_value(rounding=ROUND_FLOOR) if 週 is not None else None
        if self._所定が要る():
            if 時間 is None or not 時間:
                self._仮(効く, 理由("月の所定時間が出ない（時間.日の所定 か 時間.月の所定時間 が無い）", "", "割増と遅刻早退の単価を 0 で見当"))
            if 日数 is None or not 日数:
                self._仮(効く, 理由("月の所定日数が出ない", "", "欠勤の単価を 0 で見当"))
        self.月の所定時間の分数 = None if 時間 is None else Fraction(時間)
        return 日数, (None if 時間 is None else 分数を小数に(self.月の所定時間の分数))

    def _所定が要る(self) -> bool:
        """月の所定（日数・時間）を使う月か。割増・欠勤・遅刻早退の時間が 0 で、単価の元に所定を使う行も無い人（勤怠の無い役員など）は要らない。"""
        語たち = ("法定内残業", "法定外残業", "60 時間超", "法定休日", "所定休日", "深夜", "欠勤", "特別休暇（無給）", "遅刻早退", "休業")
        if any(self.勤怠の生の数(k) for k in 語たち):
            return True
        for r in self.v.get("項目.行") or []:
            元 = str(r.get("単価の元") or "")
            if not (self.単価の元(r)[0] in ("時間単価", "日単価") or "所定日数" in 元.replace(" ", "")):
                continue
            種, 語 = self.数量の語(r)
            if 種 in ("1", "入力") or self.勤怠の生の数(語):
                return True
        return False

    # ---- 計算 ----
    def 計算(self):
        v = self.v
        self.期間 = 暦.期間(self.支給月, v["支払.締め日"], v["支払.支給の月"])
        try:
            self.支給日 = 暦.支給日(self.支給月, v["支払.支給日"], v["支払.支給日が休日"], self.置き場)
        except 口.欠け as e:
            self.支給日 = 暦.日にする(*暦.支給月を読む(self.支給月), v["支払.支給日"])
            self._仮("源泉所得税", 理由(f"祝日の表が欠け（支給日の休日を避けられない）: {e}", self.支給日.isoformat()))
        if 委託.委託の人か(v):
            self.委託の元 = 委託.計算する(self)
        if 区分だけか(v, "委託"):   # 委託だけの人（雇用分なし）＝委託分だけを出す
            self.帳.足し合わせ(委託.支払合計, [委託.前 + "差引支給額"], None, "委託分の差引支給額")
            self.委託の流れ[委託.支払合計] = [委託.前 + "差引支給額"]
            self.法の線の行 = []
            self._理由を項目へ()
            self._計へ流す([], [], [], [])
            return self.帳
        制度 = v.get("時間.制度")
        行たち = self.部品の行たち()
        役員 = 区分か(v, "役員")   # 役員＋委託の併用 の役員報酬の分も役員の扱い
        # 役員は所定の時間を持たない（労基法の労働時間の外）＝月の所定と時間単価を出さない
        self.月の所定日数, self.月の所定時間 = (None, None) if 役員 else self.月の所定()
        self.時間単価 = None if 役員 else self._時間単価(行たち)
        支給 = [r for r in 行たち if r.get("支給か控除") == "支給"]
        控除 = [r for r in 行たち if r.get("支給か控除") == "控除"]
        外 = [r for r in 行たち if r.get("支給か控除") == 賃金の外]
        # 欠勤の基礎（月の決まった賃金）と日単価は支給の行を数える前に決める（日単価を単価の元にする行が先に数えられるため。
        # 後で決めると日単価の行が必ず「単価が出ない」で仮になっていた）
        欠勤の基礎 = Decimal(0) if 役員 else self._欠勤の基礎(支給)
