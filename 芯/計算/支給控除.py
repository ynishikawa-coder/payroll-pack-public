    def _欠勤(self, 基礎: Decimal):
        v = self.v
        形 = v.get("支払.賃金の形")
        端数 = v["欠勤.控除の端数"]
        欠勤 = self.勤怠の数("欠勤", "欠勤控除") + self.勤怠の数("特別休暇（無給）", "欠勤控除")
        if self.勤怠の数("休業", "欠勤控除"):
            self._仮("欠勤控除・課税計", 理由("休業の日がある＝休業手当（平均賃金 §3.5）の式はこの芯にまだ無い", "0",
                                          "休業の日は計算していない", "休業の理由と払う額を書く"))
        控除 = Decimal(0)
        割る日, 割る時 = self._欠勤の割る数()
        if self._欠勤を遅刻早退に入れる():
            欠勤 = Decimal(0)   # 欠勤の日の分は芯/集計 が遅刻早退の時間に入れている（二重に引かない）
        if self.まるごと欠勤:
            基礎 = Decimal(0)   # まるごと欠勤の月は日割する行を払っていない＝欠勤控除を出さない
        if 形 in 月給の形 and 欠勤 and 基礎:
            割る = 割る日 if v.get("欠勤.控除の割り方") else (Fraction(str(self.月の所定日数)) if self.月の所定日数 else None)
            式 = v.get("欠勤.控除の式")
            if 式 == "欠勤が多い月だけ出た日で払う":
                式 = "出た日で払う方式" if 欠勤 * 2 > self.勤怠の数("所定日数", "欠勤控除") else "引く方式"
            F = Fraction(str(基礎))
            if not 割る:
                控除 = Decimal(0)
                if v.get("欠勤.控除の割り方"):
                    self._仮("欠勤控除", 理由("欠勤の割る数が出ない（欠勤.控除の割り方）", "0"))
            elif 式 == "引く方式":
                控除 = _小数(F * Fraction(str(欠勤)) / 割る)
            elif 式 == "出た日で払う方式":
                控除 = max(Decimal(0), _小数(F - F * Fraction(str(self.勤怠の数("出勤日数", "欠勤控除"))) / 割る))
            else:
                raise 式が無い(f"欠勤.控除の式「{式}」は選べる値の外")
        self.日単価 = (基礎 / self.月の所定日数) if 基礎 and self.月の所定日数 else None
        self.帳.置く("欠勤控除", 丸める(控除, 端数), f"欠勤 {欠勤} 日・基礎 {基礎}")
        遅 = Decimal(0)
        遅刻 = self.勤怠の数("遅刻早退", "遅刻早退控除")
        引く語 = v.get("欠勤.遅刻早退の控除")
        if 遅刻 and 引く語 in ("引く", "月給の人だけ引く"):
            if 形 in 月給の形 and v.get("時間.月給者の遅れた出勤") == "引く" and v.get("欠勤.控除の割り方"):
                if 割る時:
                    遅 = _小数(Fraction(str(基礎)) * Fraction(str(遅刻)) / 60 / 割る時)
                else:
                    self._仮("遅刻早退控除", 理由("遅刻早退の割る時間が出ない（欠勤.控除の割り方）", "0"))
            elif 形 in 月給の形 and v.get("時間.月給者の遅れた出勤") == "引く" and self.月の所定時間:
                遅 = 基礎 / self.月の所定時間 * _h(遅刻)
            elif 形 == "日給" and 引く語 == "引く":
                日の所定 = self._日の所定の時間(self.期間[1])
                日額 = sum((self.人の額(r) or 0) for r in self.部品の行たち()
                         if r.get("支給か控除") == "支給" and self.数量の語(r)[0] == "日" and (r.get("単価の元") == "人の額"))
                if 日の所定:
                    遅 = 日額 / 日の所定 * _h(遅刻)
        elif 遅刻 and 引く語 != "引かない":
            raise 式が無い(f"欠勤.遅刻早退の控除「{v.get('欠勤.遅刻早退の控除')}」は選べる値の外")
        self.帳.置く("遅刻早退控除", 丸める(遅, 端数), f"遅刻早退 {遅刻} 分")

    def _欠勤の割る数(self):
        """会社の決まり `欠勤.控除の割り方` → (欠勤 1 日の割る数, 遅刻早退 1 時間の割る数)（Fraction か None）。空は今の式（月の所定日数・月の所定時間）。
        - 所定日数で日割り: 月の数字の 所定日数（その月の要出勤日数）・遅刻早退は 所定日数×日の所定
        - 所定時間で日割り: 月の所定時間÷日の所定・遅刻早退は 月の所定時間
        - 時間割り: `欠勤.控除の割る時間`÷日の所定・遅刻早退は `欠勤.控除の割る時間`"""
        v = self.v
        割り方 = v.get("欠勤.控除の割り方")
        if not 割り方:
            return None, None
        日の所定 = self._日の所定の時間(self.期間[1])
        F = (lambda x: Fraction(str(x)) if x else None)
        if 割り方 == "所定日数で日割り":
            日 = F(self.勤怠の数("所定日数", "欠勤控除"))
            return 日, (日 * F(日の所定) if 日 and 日の所定 else None)
        if 割り方 == "所定時間で日割り":
            時 = F(self.月の所定時間)
        elif 割り方 == "時間割り":
            時 = F(数(v.get("欠勤.控除の割る時間"), "欠勤.控除の割る時間"))
        else:
            raise 式が無い(f"欠勤.控除の割り方「{割り方}」は 所定日数で日割り・所定時間で日割り・時間割り の外")
        return (時 / F(日の所定) if 時 and 日の所定 else None), 時

    # ---- 通勤 ----
    def _通勤の上限(self, 通勤):
        上限 = 数(self.v.get("手当.通勤の上限"), "手当.通勤の上限")
        if 上限 is None:
            return
        和 = sum(self.帳.項目[n].値 for n in 通勤)
        超え = 和 - 上限
        for n in 通勤:
            if 超え <= 0:
                break
            d = min(超え, self.帳.項目[n].値)
            self.帳.項目[n].値 -= d
            超え -= d
        if 和 > 上限:
            self.知らせ.append(f"通勤の手当 {和} が 手当.通勤の上限 {上限} を超えた＝超えた分は払わない")

    def _通勤の超えた分の行(self, 通勤) -> str | None:
        """会社の決まり `手当.通勤の限度を超えた分の行`（部品の行の名・例 通勤課税）があれば、非課税の限度を超えた分を通勤の行（後ろの行から）から
        その行（課税）へ移し、行の名を返す（無ければ None＝今の形: 超えた分は行にせず課税計へ）。"""
        名 = str(self.v.get("手当.通勤の限度を超えた分の行") or "").strip()
        self._通勤の限度_移した = Decimal(0)
        if not 名 or not 通勤:
            return None
        if 名 in 決まった項目 or 名 in 通勤:
            raise ValueError(f"手当.通勤の限度を超えた分の行「{名}」は芯の決まった項目か通勤の非課税の行とぶつかる")
        超え = self._通勤の限度(通勤)
        for n in reversed(通勤):
            d = min(超え, self.帳.項目[n].値)
            self.帳.項目[n].値 -= d
            超え -= d
        移した = self._通勤の限度_移した
        x = self.帳.項目.get(名)
        if x is None:
            self.帳.置く(名, 移した, "通勤の非課税の限度を超えた分")
        else:
            x.値 = (x.値 or 0) + 移した
        self._通勤の限度_済み = True
        return None if x is not None else 名

    def _通勤の限度(self, 通勤) -> Decimal:
        """通勤の非課税の限度を超えた分（課税計へ）。限度は人の値 `手当.通勤の非課税の限度`（距離などで手前が法の表から決める）。"""
        if not 通勤 or getattr(self, "_通勤の限度_済み", False):
            return Decimal(0)
        和 = sum(self.帳.項目[n].値 for n in 通勤)
        限度 = 数(self.v.get("手当.通勤の非課税の限度"), "手当.通勤の非課税の限度")
        if 限度 is None:
            self._仮("課税計・非課税計", 理由("手当.通勤の非課税の限度 が無い", "全額を非課税で見当",
                                         "通勤の非課税の限度は距離と手段で決まる", "限度の額を書く"))
            return Decimal(0)
        self._通勤の限度_移した = max(Decimal(0), 和 - 限度)
        return self._通勤の限度_移した

