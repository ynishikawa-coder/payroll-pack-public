    def _割増を置く(self, 鍵: str, 全: dict, 載せる: dict, 出所: str, 何: str):
        """割増の項目（全＝{項目: 全額}）を置き、`鍵` の支給の行へ 載せる の額を足す。項目に残すのは軸3 の差額
        （`軸.差額`＝法の額（全額）−行に載せた額・0 未満は 0）で、行に載せるのは 全額−差額（全額を超えて載せない）。
        `割増.時間外の基礎の行` は時間外手当・60時間超手当の 1.0 倍の分、`割増.法定内残業の行`・`割増.みなし超えの行` は全額。
        ほかの割増の項目・行が項目に無い・課税／社保の報酬／雇保の対象が 入る でない行は、項目に全額のまま仮（黙って違う行へ載せない）。
        行がその人に無い（額の無い人の行）時は項目に全額のまま＋知らせ。"""
        先 = str(self.v.get(鍵) or "").strip()
        載せる = {k: 全[k] - 軸.差額(全[k], a) for k, a in 載せる.items() if k in 全}
        載せる = {k: a for k, a in 載せる.items() if a}
        if not 先 or 先 in 全 or not 載せる:
            for 名, 額 in 全.items():
                self.帳.置く(名, 額, 出所)
            return
        行 = self._行(先)
        訳 = ("ほかの割増の項目" if 先 in 割増の項目 else
              "行が支給控除の項目に無い" if not 行 else "支給の行でない" if 行.get("支給か控除") != "支給" else
              "課税の行でない" if (行.get("課税") or "課税") != "課税" else
              "社保の報酬に入らない行" if (行.get("社保の報酬") or "入る") != "入る" else
              "雇保の対象に入らない行" if (行.get("雇保の対象") or "入る") != "入る" else "")
        x = self.帳.項目.get(先)
        if 訳 or x is None:
            for 名, 額 in 全.items():
                self.帳.置く(名, 額, 出所)
            名たち = "・".join(載せる)
            if 訳:
                self._仮(名たち, 理由(f"{鍵}「{先}」は{訳}（{名たち} のまま計算した）", str(sum(載せる.values())),
                                    f"{名たち} に置いた", f"{鍵} を課税・社保と雇保に入る支給の行の名にするか空にする"))
            else:
                self.知らせ.append(f"{鍵}「{先}」の行がこの人に無い＝{何} {sum(載せる.values())} 円は {名たち} に置いた")
            return
        for 名, 額 in 全.items():
            a = 載せる.get(名, Decimal(0))
            if not a:
                self.帳.置く(名, 額, 出所)
                continue
            x.値 = (x.値 or Decimal(0)) + a
            x.出所 += f"＋{何} {a}（{名}の分・{鍵}・{出所}）"
            self.載せた.setdefault(先, {})[名] = a
            残り = 軸.差額(額, a)
            self.帳.置く(名, 残り, f"{出所}。{何} {a} 円は 行「{先}」に載せた（{鍵}）" if 残り else
                        f"{何} {a} 円は 行「{先}」に載せた（{鍵}）")

