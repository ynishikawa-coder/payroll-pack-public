# ---- 産休・育休の社保の免除（健保法 159 条・159 条の 3、厚年法 81 条の 2・81 条の 2 の 2） ----
育休の14日の決まりの始め = (2022, 10)   # 同じ月の中で始まり終わる育休が 14 日以上の月も免除（令和 4 年 10 月の保険料の月から）
産休育休の欄 = (("育休", "社保.育休の始め", "社保.育休の終わり"), ("産休", "社保.産休の始め", "社保.産休の終わり"))


def _月末(月: tuple[int, int]) -> date:
    return date(月[0], 月[1], monthrange(月[0], 月[1])[1])


def _1か月の終わり(始め: date) -> date:
    """始めの日から数えて 1 か月の期間の終わりの日（民法 143 条: 翌月の同じ日の前の日。同じ日が無ければ翌月の末日）。"""
    y, m = 暦.月を足す(始め.year, 始め.month, 1)
    if 始め.day <= monthrange(y, m)[1]:
        return date(y, m, 始め.day) - timedelta(days=1)
    return date(y, m, monthrange(y, m)[1])


def 産休育休の免除(v: dict, 月: tuple[int, int], 賞与か: bool) -> tuple[str | None, list]:
    """保険料の月（賞与は支給月）の本人の健保・介護・子ども子育て支援金・厚年が産休・育休で免除か → (免除の訳 か None, [仮の理由])。
    - 月末に産休・育休の中の月は免除（始めの月から、終わりの日の翌日の月の前の月まで）。終わりが空＝月末に休みの中と読む。
    - 育休だけ: 同じ月の中で始まり終わる育休が 14 日以上の月も免除（`育休の14日の決まりの始め` の保険料の月から・年月はそこにだけ書く）。
    - 賞与: 支給月の月末に休みの中で、育休は 1 か月を超える時だけ（産休は月末に休みの中なら免除）。
      育休の終わりが空で月末がまだ 1 か月の中なら超えるか分からない＝免除しないで見当して仮＋問い。
    読めない日・始めの無い終わり・始めより前の終わりは、その欄を使わず仮＋問い（黙って免除しない・黙って引かない）。雇保は免除しない（ここは読まない）。"""
    月末 = _月末(月)
    訳: list = []
    for 名, 鍵s, 鍵e in 産休育休の欄:
        字s, 字e = v.get(鍵s), v.get(鍵e)
        空s, 空e = 字s is None or not str(字s).strip(), 字e is None or not str(字e).strip()
        if 空s and 空e:
            continue
        try:
            s = None if 空s else 日付(字s, 鍵s)
            e = None if 空e else 日付(字e, 鍵e)
        except 形の誤り:
            s = e = None
            何 = f"{鍵s}「{字s or ''}」・{鍵e}「{字e or ''}」が日付（YYYY-MM-DD）として読めない"
        else:
            何 = (f"{鍵e}「{字e}」があるのに {鍵s} が空" if s is None else
                  f"{鍵e}「{字e}」が {鍵s}「{字s}」より前" if e is not None and e < s else None)
        if 何:
            訳.append(理由(何, "免除しない", f"{名}の社保の免除を数えられない（免除しない額で見当）",
                          f"{鍵s}・{鍵e} を YYYY-MM-DD で書く（終わりが未定なら終わりは空）"))
            continue
        if s > 月末:
            continue
        月末に中 = e is None or e >= 月末
        if 賞与か:
            if not 月末に中:
                continue
            if 名 == "産休":
                return 名, 訳
            if e is not None:
                if e > _1か月の終わり(s):
                    return 名, 訳
                continue
            if 月末 > _1か月の終わり(s):   # 終わりが空で、月末にもう 1 か月を超えている
                return 名, 訳
            訳.append(理由(f"{鍵e} が空で、賞与の月の末に育休が 1 か月を超えるかが分からない", "免除しない",
                          "賞与の社保は月末に育休の中で育休が 1 か月を超える時だけ免除（健保法 159 条・厚年法 81 条の 2）",
                          f"{鍵e} を YYYY-MM-DD で書く（育休の申出の終わりの予定日）"))
            continue
        if 月末に中:
            return 名, 訳
        if (名 == "育休" and 月 >= 育休の14日の決まりの始め and (s.year, s.month) == 月 and (e.year, e.month) == 月
                and (e - s).days + 1 >= 14):
            return 名, 訳
    return None, 訳


def _月(d, 名: str = "日付") -> tuple[int, int]:
    d = 日付(d, 名)
    return d.year, d.month


def _歳の日(生: date, 歳: int, 誕生日: bool = False) -> date:
    """歳に達する日＝誕生日の前の日（年齢計算ニ関スル法律）。誕生日=True は誕生日そのもの（後期高齢者の健保の終わり）。"""
    try:
        b = 生.replace(year=生.year + 歳)
    except ValueError:   # 2 月 29 日生まれ
        b = date(生.year + 歳, 3, 1)
    return b if 誕生日 else b - timedelta(days=1)
