    @staticmethod
    def 数量の引く数の語(行) -> str:
        """数量の元 `勤怠の数:<語>−<引く数>` の引く数の語（無ければ空）。"""
        s = str(行.get("数量の元") or "").strip()
        for 印 in 引く印:
            if s.startswith("勤怠の数:") and 印 in s:
                return s.split(印, 1)[1].strip()
        return ""

    @staticmethod
    def 数量の語(行) -> tuple[str, str]:
        """数量の元 → (種, 語)。種は 1・日・分・回・入力。`勤怠の数:<語>−<引く数>` の引く数は 数量の引く数の語。"""
        s = str(行.get("数量の元") or "1").strip()
        for 印 in 引く印:
            if s.startswith("勤怠の数:") and 印 in s:
                s = s.split(印, 1)[0].strip()
        if s == "1":
            return "1", ""
        if s == "入力の値":
            return "入力", 行["名"]
        if s.startswith("勤怠の数:"):
            語 = s.split(":", 1)[1].strip()
            if 語 in 日の語:
                return "日", 語
            if 語 in 分の語:
                return "分", 語
            if 語 in 回の語:
                return "回", 語
        raise 式が無い(f"部品の行「{行['名']}」の数量の元「{s}」は選べる値の外")

    @staticmethod
    def 単価の元(行) -> tuple[str, str]:
        """単価の元 → (元, 割る数の語)。`<元>×<掛ける数>÷<割る数>` の形を分ける（掛ける数は `掛ける数の語`）。"""
        元 = str(行.get("単価の元") or "固定の額").strip()
        割る = ""
        if "÷" in 元:
            元, 割る = (x.strip() for x in 元.split("÷", 1))
        return 元.split("×", 1)[0].strip() or "固定の額", 割る

    @staticmethod
    def 掛ける数の語(行) -> str:
        """単価の元の × の後ろ（÷ の前）の語。無ければ空。"""
        元 = str(行.get("単価の元") or "").split("÷", 1)[0]
        return 元.split("×", 1)[1].strip() if "×" in 元 else ""

    def 単価(self, 行) -> Decimal | None:
        元, 割る = self.単価の元(行)
        掛ける = self.掛ける数の語(行)
        if 元 in ("固定の額", "回ごとの額"):
            x = 数(行.get("額"), f"部品の行 {行['名']} の額")
        elif 元 == "人の額":
            x = self.人の額(行)
        elif 元.startswith("額:"):   # ほかの項目の人の額（例 額:資格単価）
            x = 数((self.v.get("項目.人の額") or {}).get(元[2:].strip()), f"人の額 {元[2:]}")
        elif 元.startswith("単価:"):   # 軸2: 項目.単価 の表の名（式・丸め）。式の名は 決まりと人の値・額:<人の額の名>・日の所定・月の所定時間
            x = 軸.単価を引く(元[3:].strip(), self.v.get("項目.単価") or {}, self._単価の式の値())
        elif 元 == "時間単価":
            # 控除の行は切り捨てない所定の単価（端数.月の所定時間 で切り捨てた所定は割増の単価だけ・控除を多くしない＝型の版 18）
            x = (getattr(self, "控除の単価", None) or self.時間単価) if 行.get("支給か控除") == "控除" else self.時間単価
        elif 元 == "日単価":
            x = self.日単価
        elif 元 == 平均賃金:   # 台帳「月の変動」の 項目＝平均賃金（1 銭まで・労基法 12 条の額は事務所が出す）
            x = 数((self.入力 or {}).get(平均賃金), "入力 平均賃金")
        else:
            raise 式が無い(f"部品の行「{行['名']}」の単価の元「{元}」は選べる値の外")
        if x is not None and 掛ける:
            m = self._割る数(掛ける, 行)
            if m is None:
                self._仮(行["名"], 理由(f"部品の行「{行['名']}」の掛ける数「{掛ける}」が出ない", "0"))
                return None
            x = 分数を小数に(Fraction(x) * self._分数(掛ける, m))
        if x is None or not 割る:
            return x
        d = self._割る数(割る, 行)
        if not d:
            self._仮(行["名"], 理由(f"部品の行「{行['名']}」の割る数「{割る}」が 0 か出ない", "0"))
            return None
        return 分数を小数に(Fraction(x) / self._分数(割る, d))

    def _単価の式の値(self) -> dict:
        """項目.単価 の式が引ける名の値（引いた名だけを数に読む＝使わない値の形は見ない）。"""
        d = {k: x for k, x in self.v.items() if not isinstance(x, (dict, list))}
        d.update({f"額:{k}": x for k, x in (self.v.get("項目.人の額") or {}).items()})
        d["日の所定"] = self._日給の割る所定()
        d["月の所定時間"] = getattr(self, "月の所定時間", None)
        return d

    def _分数(self, 語: str, d: Decimal) -> Fraction:
        """`_割る数` の値を分数に。`月の所定時間` と `決まり:<分野.名>` の時間の値は丸めない分数（h:mm の `161:20` も・型の版 21）。"""
        if 語 == "月の所定時間" and self.月の所定時間の分数 is not None:
            return self.月の所定時間の分数
        if 語.startswith("決まり:"):
            f = 時間の値(self.v.get(語[4:].strip()), 語[4:])
            if f is not None:
                return f
        return Fraction(d)

    def _割る数(self, 語: str, 行) -> Decimal | None:
        """単価の元の ÷ の後ろと × の後ろ、数量の元の − の後ろ: `所定日数`（月の所定日数）・`日の所定`（時間）・`月の所定時間`・
        `有給の1日の時間`（`有給.1日の時間`〔分〕を時間に。無ければ既定の `時間.日の所定`）・`決まり:<分野.名>`・月の数字の日の語・数。"""
        if 語 == "所定日数":
            return self.月の所定日数
        if 語 == "日の所定":
            return self._日の所定の時間(self.期間[1])
        if 語 == "有給の1日の時間":
            分 = 数(self.v.get("有給.1日の時間"), "有給.1日の時間")
            return _h(分) if 分 is not None else self._日の所定の時間(self.期間[1])
        if 語 == "月の所定時間":
            return self.月の所定時間
        if 語.startswith("決まり:"):   # 時間の数か h:mm（`173:00`）。分数のままの値は _分数 が読む
            f = 時間の値(self.v.get(語[4:].strip()), 語[4:])
            return None if f is None else 分数を小数に(f)
        if 語 in 日の語:   # 月の数字の日の語（数量の引く数。例 `勤怠の数:出勤日数−在宅の日数`＝在宅の日を除いた出勤の日・型の版 21）
            return self.勤怠の数(語, 行["名"])
        try:
            return 数(語, f"部品の行 {行['名']} の割る数")
        except ValueError:
            raise 式が無い(f"部品の行「{行['名']}」の割る数「{語}」は選べる値の外") from None

