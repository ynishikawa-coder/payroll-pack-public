def _h(分: Decimal) -> Decimal:
    return Decimal(分) / 60


class 一人:
    def __init__(self, 支給月: str, 値たち: dict, 勤怠: dict, 入力: dict, 置き場=None, 事前の理由=()):
        self.支給月, self.v, self.勤怠, self.入力, self.置き場 = 支給月, 値たち, 勤怠, 入力 or {}, 置き場
        self.帳 = 帳()
        self.知らせ: list[str] = []
        self.理由: dict[str, list] = {}       # 効く項目 → 理由
        self.全部の理由: list = []             # 全部の項目に効く理由
        for 効く, r in 事前の理由:
            self._仮(効く, r)
        self.線: dict = {}
        self.等級を照らす = True   # 標準報酬月額が等級表の額かを照らす（賞与の標準賞与額は照らさない）
        self.勤怠の全部 = 勤怠
        self.委託の元 = Decimal(0)        # 委託分を雇保と源泉の元へ入れる額（委託の併用で 入れる の人だけ）
        self.委託の流れ: dict = {}
        self._部品の行: list | None = None
        if 値たち.get("人.区分") == "委託の併用":
            # 雇用分は決まった額（時間外・深夜・休日・欠勤は委託分の式で払う＝前の道具と同じ）。日の語のうち欠勤の外だけ雇用分へ渡す
            self.勤怠 = {k: x for k, x in 勤怠.items() if k in ("所定日数", "出勤日数", "年休（全日）", "特別休暇（有給）")}

    # ---- 仮の理由 ----
    def _仮(self, 効く: str, r: 理由):
        if 効く == "全部":
            self.全部の理由.append(r)
        else:
            for k in 効く.split("・"):
                self.理由.setdefault(k, []).append(r)

    def _効く理由(self, 名: str) -> list:
        return self.全部の理由 + self.理由.get(名, [])

    # ---- 法の表 ----
    def 引く(self, 名: str, 日, 効く: str, **鍵):
        """引いた値。仮で引いたら理由を付ける。欠け（止める）は None と理由。"""
        try:
            r = 口.引く(名, 日, 置き場=self.置き場, **鍵)
        except 口.欠け as e:
            self._仮(効く, 理由(f"法の表が欠け: {e}", "", "表の欠けた時＝止める（前の値で代えない）", "法の表を入れ直すまで待つ"))
            return None, str(e)
        if r.仮:
            self._仮(効く, 理由(f"法の表がまだ: {名}", r.出所, "表の欠けた時＝仮で計算し問う（docs/設計/法の表.md §2.2）",
                                "国の公表の後に計算し直す"))
        return r.値, r.出所

    def 法の線(self, 鍵: str, 効く: str):
        """法の表/法の線.json（1 行＝1 つの線・鍵 `線`）から芯の名の値を引く（読み方は 法の線の読み方.py）。率%は倍（割増）か足す率（深夜）に直す。"""
        線, 欄, 直し = 線の読み.読み方[鍵]
        if 線 not in self.線:
            self.線[線] = self.引く("法の線", self.期間[1].isoformat(), 効く, 線=線)[0]
        値 = self.線[線]
        if 値 is None:
            return None
        x = 線の読み.欄の値(鍵, 値)
        if x is None:
            self._仮(効く, 理由(f"法の線「{線}」に「{欄}」が無い", "", "法の表/法の線.json", "法の表に足す"))
            return None
        return 1 + 数(str(x)) / 100 if 直し == "倍" else 数(str(x)) / 100 if 直し == "足す" else x

    # ---- 勤怠 ----
    def 勤怠の数(self, 語: str, 効く: str, 全部: bool = False) -> Decimal:
        """月の数字の語の値（日・回はそのまま・分は分）。無い語は 0。仮の行なら理由を付ける。
        全部＝True は委託の併用の人の月の全部の数（委託分の式が読む）。"""
        x = (self.勤怠の全部 if 全部 else self.勤怠).get(語)
        if x is None:
            return Decimal(0)
        v, 状態, 問い = x
        if 状態 != "確定" or v is None:
            self._仮(効く, 理由(f"月の数字「{語}」が仮（芯/集計 {問い or '問いなし'}）", str(v or 0), "芯/集計 の見当",
                                "集計の問いの答えを待つ"))
        return v or Decimal(0)

    # ---- 単価の元 ----
    def 部品の行たち(self):
        """項目.行 のうち使える行。芯が自分で作る項目の名とぶつかる行・同じ名の 2 つ目からの行は使わず、
        知らせと仮（理由は人に依らない字＝その行の段（会社）の全員で問い 1 つ）にする（全員を止めない・⟦鍵:給与計算/足りない時は仮で計算し出さない⟧）。"""
        if self._部品の行 is not None:
            return self._部品の行
        使う, 見た = [], set()
        for r in self.v.get("項目.行") or []:
            n = r.get("名")
            if n in 芯の作る名:
                what, 答え = f"部品の行の名「{n}」は芯が自分で作る項目の名とぶつかる", f"支給控除の項目 の行「{n}」の名を変えるか消す"
            elif n in 見た:
                what, 答え = f"部品の行に同じ名「{n}」が 2 つある", f"支給控除の項目 の行「{n}」を 1 つにする"
            else:
                見た.add(n)
                使う.append(r)
                continue
            self.知らせ.append(f"{what}（その行は使わない）")
            self._仮("全部", 理由(what, "その行を使わない", "その行を除いて計算（芯の項目を上書きしない）", 答え))
        self._部品の行 = 使う
        return 使う

    def 人の額(self, 行) -> Decimal | None:
        return 数((self.v.get("項目.人の額") or {}).get(行["名"]), f"人の額 {行['名']}")

    @staticmethod
    def 数量の語(行) -> tuple[str, str]:
        """数量の元 → (種, 語)。種は 1・日・分・回・入力。"""
        s = str(行.get("数量の元") or "1").strip()
        if s == "1":
            return "1", ""
        if s == "入力の値":
            return "入力", 行["名"]
        if s.startswith("勤怠の数:"):
            語 = s.split(":", 1)[1].strip()
            if 語 in 日の語:
                return "日", 語
            if 語 in 分の語:
                return "分", 語
            if 語 in 回の語:
                return "回", 語
        raise 式が無い(f"部品の行「{行['名']}」の数量の元「{s}」は選べる値の外")

    @staticmethod
    def 単価の元(行) -> tuple[str, str]:
        """単価の元 → (元, 割る数の語)。`<元>÷<割る数>` の形を分ける。"""
        元 = str(行.get("単価の元") or "固定の額").strip()
        if "÷" in 元:
            a, b = 元.split("÷", 1)
            return a.strip() or "固定の額", b.strip()
        return 元, ""

    def 単価(self, 行) -> Decimal | None:
        元, 割る = self.単価の元(行)
        if 元 in ("固定の額", "回ごとの額"):
            x = 数(行.get("額"), f"部品の行 {行['名']} の額")
        elif 元 == "人の額":
            x = self.人の額(行)
        elif 元.startswith("額:"):   # ほかの項目の人の額（例 額:資格単価）
            x = 数((self.v.get("項目.人の額") or {}).get(元[2:].strip()), f"人の額 {元[2:]}")
        elif 元 == "時間単価":
            x = self.時間単価
        elif 元 == "日単価":
            x = self.日単価
        else:
            raise 式が無い(f"部品の行「{行['名']}」の単価の元「{元}」は選べる値の外")
        if x is None or not 割る:
            return x
        d = self._割る数(割る, 行)
        if not d:
            self._仮(行["名"], 理由(f"部品の行「{行['名']}」の割る数「{割る}」が 0 か出ない", "0"))
            return None
        return x / d

    def _割る数(self, 語: str, 行) -> Decimal | None:
        """単価の元の ÷ の後ろ: `所定日数`（月の所定日数）・`日の所定`（時間）・`月の所定時間`・`決まり:<分野.名>`・数。"""
        if 語 == "所定日数":
            return self.月の所定日数
        if 語 == "日の所定":
            return self._日の所定の時間(self.期間[1])
        if 語 == "月の所定時間":
            return self.月の所定時間
        if 語.startswith("決まり:"):
            return 数(self.v.get(語[4:].strip()), 語[4:])
        try:
            return 数(語, f"部品の行 {行['名']} の割る数")
        except ValueError:
            raise 式が無い(f"部品の行「{行['名']}」の割る数「{語}」は選べる値の外") from None

    # ---- 所定 ----
    def _日の所定の時間(self, d: date) -> Decimal | None:
        x = self.v.get("時間.日の所定")
        if isinstance(x, dict):
            x = x.get(暦.曜日[d.weekday()])
        return 数(x, "時間.日の所定")

    def 月の所定(self):
        """(月の所定日数, 月の所定時間)。出し方は 時間.月の所定日数の出し方・時間.月の所定時間の出し方。"""
        始め, 終わり = self.期間
        暦の値 = self.v.get("時間.暦")
        効く = "時間外手当・法定内残業手当・60時間超手当・休日手当・深夜手当・欠勤控除・遅刻早退控除"

        def 年():
            y = 終わり.year
            try:
                n, 出所, 仮 = 暦.所定日数(date(y, 1, 1), date(y, 12, 31), 暦の値, self.置き場)
            except 口.欠け as e:
                self._仮(効く, 理由(f"祝日の表が欠け: {e}", "", "年の所定日数を数えられない", "法の表を入れ直す"))
                return None, None
            if 仮:
                self._仮(効く, 理由("祝日の表がまだ（前の年で見当）", "", "法の表/祝日"))
            時間 = Decimal(0)
            d = date(y, 1, 1)
            祝 = 暦.祝日(y, self.置き場)[0]
            while d.year == y:
                if not 暦.休みか(d, 暦の値 or 暦.既定の暦, 祝):
                    h = self._日の所定の時間(d)
                    if h is None:
                        時間 = None
                        break
                    時間 += h
                d += timedelta(days=1)
            return Decimal(n) / 12, (時間 / 12 if 時間 is not None else None)

        日の出し方 = self.v.get("時間.月の所定日数の出し方")
        時間の出し方 = self.v.get("時間.月の所定時間の出し方")
        年日, 年時間 = 年() if "年平均" in (日の出し方, 時間の出し方) else (None, None)
        if 日の出し方 == "年平均":
            日数 = 年日
        elif 日の出し方 == "その月の所定日数":
            日数 = self.勤怠の数("所定日数", 効く)
        elif 日の出し方 == "その月の暦日":
            日数 = Decimal((終わり - 始め).days + 1)
        elif 日の出し方 == "その月の暦の所定日数":
            try:
                n, _, 仮 = 暦.所定日数(始め, 終わり, 暦の値, self.置き場)
                日数 = Decimal(n)
                if 仮:
                    self._仮(効く, 理由("祝日の表がまだ（前の年で見当）", "", "法の表/祝日"))
            except 口.欠け as e:
                self._仮(効く, 理由(f"祝日の表が欠け: {e}", "", "その月の暦の所定日数を数えられない", "法の表を入れ直す"))
                日数 = None
        elif 日の出し方 == "固定の値":
            日数 = 数(self.v.get("時間.月の所定日数"), "時間.月の所定日数")
        else:
            raise 式が無い(f"時間.月の所定日数の出し方「{日の出し方}」は選べる値の外")
        if 時間の出し方 == "年平均":
            時間 = 年時間
        elif 時間の出し方 == "その月の所定時間":
            日の所定 = self._日の所定の時間(終わり)
            時間 = (self.勤怠の数("所定日数", 効く) * 日の所定) if 日の所定 is not None else None
        elif 時間の出し方 == "固定の値":
            時間 = 数(self.v.get("時間.月の所定時間"), "時間.月の所定時間")
        elif 時間の出し方 == "変形の総枠":
            週 = self.法の線("時間.週の法定", 効く)   # 労基法 32 条の 2: 週の法定×期間の暦日÷7（時間未満は切り捨て）
            時間 = (Decimal(週) * ((終わり - 始め).days + 1) / 7).to_integral_value(rounding=ROUND_FLOOR) if 週 is not None else None
        else:
            raise 式が無い(f"時間.月の所定時間の出し方「{時間の出し方}」は選べる値の外")
        if self._所定が要る():
            if 時間 is None or not 時間:
                self._仮(効く, 理由("月の所定時間が出ない（時間.日の所定 か 時間.月の所定時間 が無い）", "", "割増と遅刻早退の単価を 0 で見当"))
            if 日数 is None or not 日数:
                self._仮(効く, 理由("月の所定日数が出ない", "", "欠勤の単価を 0 で見当"))
        return 日数, 時間

    def _所定が要る(self) -> bool:
        """月の所定（日数・時間）を使う月か。割増・欠勤・遅刻早退の時間が 0 で、単価の元に所定を使う行も無い人（勤怠の無い役員など）は要らない。"""
        語たち = ("法定内残業", "法定外残業", "60 時間超", "法定休日", "所定休日", "深夜", "欠勤", "特別休暇（無給）", "遅刻早退", "休業")
        if any((self.勤怠.get(k) or (0,))[0] for k in 語たち):
            return True
        for r in self.v.get("項目.行") or []:
            元 = str(r.get("単価の元") or "")
            if not (元.split("÷")[0].strip() in ("時間単価", "日単価") or "÷所定日数" in 元.replace(" ", "")):
                continue
            種, 語 = self.数量の語(r)
            if 種 in ("1", "入力") or (self.勤怠.get(語) or (0,))[0]:
                return True
        return False

    # ---- 計算 ----
    def 計算(self):
        v = self.v
        self.期間 = 暦.期間(self.支給月, v["支払.締め日"], v["支払.支給の月"])
        try:
            self.支給日 = 暦.支給日(self.支給月, v["支払.支給日"], v["支払.支給日が休日"], self.置き場)
        except 口.欠け as e:
            self.支給日 = 暦.日にする(*暦.支給月を読む(self.支給月), v["支払.支給日"])
            self._仮("源泉所得税", 理由(f"祝日の表が欠け（支給日の休日を避けられない）: {e}", self.支給日.isoformat()))
        区分 = v.get("人.区分")
        if 区分 in ("委託", "委託の併用"):
            self.委託の元 = 委託.計算する(self)
        if 区分 == "委託":   # 委託だけの人（雇用分なし）＝委託分だけを出す
            self.帳.足し合わせ(委託.支払合計, [委託.前 + "差引支給額"], None, "委託分の差引支給額")
            self.委託の流れ[委託.支払合計] = [委託.前 + "差引支給額"]
            self.法の線の行 = []
            for 名, x in self.帳.項目.items():
                x.理由たち = tuple(dict.fromkeys(list(x.理由たち) + self._効く理由(名)))
            self._計へ流す([], [], [], [])
            return self.帳
        制度 = v.get("時間.制度")
        行たち = self.部品の行たち()
        役員 = 区分 == "役員"
        # 役員は所定の時間を持たない（労基法の労働時間の外）＝月の所定と時間単価を出さない
        self.月の所定日数, self.月の所定時間 = (None, None) if 役員 else self.月の所定()
        self.時間単価 = None if 役員 else self._時間単価(行たち)
        self.日単価 = None
        支給 = [r for r in 行たち if r.get("支給か控除") == "支給"]
        控除 = [r for r in 行たち if r.get("支給か控除") == "控除"]
        日割 = self._日割の率()
        self.まるごと欠勤 = self._まるごと欠勤(日割)
        課税, 非課税, 通勤 = [], [], []
        欠勤の基礎 = Decimal(0)
        for r in 支給:
            x = self._部品の額(r, 日割, self.まるごと欠勤)
            if x is None:
                continue
            課税の語 = r.get("課税") or "課税"
            (通勤 if 課税の語 == "通勤の非課税" else 非課税 if 課税の語 == "非課税" else 課税).append(r["名"])
            if self._欠勤で減る(r):
                欠勤の基礎 += self.人の額(r) or 数(r.get("額")) or 0
        self._通勤の上限(通勤)
        超えた分の行 = self._通勤の超えた分の行(通勤)
        if 超えた分の行:
            課税.append(超えた分の行)
        if 役員:   # 役員報酬は決まった額（割増・欠勤控除は労基法の外。最低賃金も当てない＝最低賃金法 2 条）
            for n in 割増の項目 + ("欠勤控除", "遅刻早退控除"):
                self.帳.置く(n, Decimal(0), "役員（労基法の割増・欠勤控除の外）")
        else:
            self._割増(制度)
            self._欠勤(欠勤の基礎)
        # 計
        引く = {"欠勤控除": -1, "遅刻早退控除": -1}
        通勤の超えた分 = self._通勤の限度(通勤)
        self.帳.足し合わせ("課税計", 課税 + list(割増の項目) + ["欠勤控除", "遅刻早退控除"], 引く, "支給の課税の行の和")
        if 通勤の超えた分:
            x = self.帳.項目["課税計"]
            x.値 += 通勤の超えた分
        self.帳.足し合わせ("非課税計", 非課税 + 通勤, None, "支給の非課税の行の和")
        if 通勤の超えた分:
            self.帳.項目["非課税計"].値 -= 通勤の超えた分
        self.帳.足し合わせ("総支給額", ["課税計", "非課税計"], None, "課税計＋非課税計")
        if self.帳.項目["総支給額"].値 == 0 and not self.帳.項目["総支給額"].仮:
            self.知らせ.append("総支給額が 0＝社保・雇保・源泉・住民税は引いていない（引く月かを確かめる）")
            for n in 社保の項目 + 控除の決まった項目:
                self.帳.置く(n, Decimal(0), "総支給額が 0")
        else:
            self._社保()
            self._雇保(課税 + 非課税 + 通勤)
            self.帳.足し合わせ("社会保険計", 社保の項目 + ("雇用保険",), None, "社保と雇保の和")
            self.帳.足し合わせ("課税対象額", ["課税計", "社会保険計"], {"社会保険計": -1}, "課税計−社会保険計")
            if self.委託の元:
                self.帳.項目["課税対象額"].値 += self.委託の元
                self.帳.項目["課税対象額"].出所 += f"＋委託分の課税計 {self.委託の元}（委託.社保と源泉の元に入れる）"
            if self.帳.項目["課税対象額"].値 < 0:
                self.帳.項目["課税対象額"].値 = Decimal(0)
            self._源泉()
            self._住民税()
        for r in 控除:
            self._部品の額(r, None)
        self.帳.足し合わせ("控除計", ["源泉所得税", "住民税"] + [r["名"] for r in 控除 if r["名"] in self.帳.項目], None,
                         "源泉＋住民税＋控除の行")
        self.帳.足し合わせ("控除合計", ["社会保険計", "控除計"], None, "社会保険計＋控除計")
        self.帳.足し合わせ("差引支給額", ["総支給額", "控除合計"], {"控除合計": -1}, "総支給額−控除合計")
        if 区分 == "委託の併用":   # 雇用分と委託分を 1 枚で（支払合計＝雇用分の差引＋委託分の差引）
            self.帳.足し合わせ(委託.支払合計, ["差引支給額", 委託.前 + "差引支給額"], None, "雇用分の差引支給額＋委託分の差引支給額")
            self.委託の流れ[委託.支払合計] = ["差引支給額", 委託.前 + "差引支給額"]
        from . import 検査
        self.法の線の行 = 検査.見る(self)
        # 理由を各項目へ（計は元から引き継いでいる。決まった項目の理由と全部の理由を足す）
        for 名, x in self.帳.項目.items():
            x.理由たち = tuple(dict.fromkeys(list(x.理由たち) + self._効く理由(名)))
        self._計へ流す(課税, 非課税, 通勤, 控除)
        if 区分 == "委託の併用":   # 並びは雇用分 → 委託分 → 支払合計
            後 = [n for n in self.帳.項目 if n.startswith(委託.前)] + [委託.支払合計]
            self.帳.項目 = {**{n: x for n, x in self.帳.項目.items() if n not in 後}, **{n: self.帳.項目[n] for n in 後}}
        return self.帳

    def _計へ流す(self, 課税, 非課税, 通勤, 控除):
        """元の項目の理由を計へ流す（計の値は変えない）。"""
        元たち = {
            "課税計": 課税 + list(割増の項目) + ["欠勤控除", "遅刻早退控除"],
            "非課税計": 非課税 + 通勤,
            "総支給額": ["課税計", "非課税計"],
            "雇用保険": ["総支給額"],
            "社会保険計": list(社保の項目) + ["雇用保険"],
            "課税対象額": ["課税計", "社会保険計"],
            "源泉所得税": ["課税対象額"],
            "控除計": ["源泉所得税", "住民税"] + [r["名"] for r in 控除],
            "控除合計": ["社会保険計", "控除計"],
            "差引支給額": ["総支給額", "控除合計"],
            **self.委託の流れ,
        }
        for 名, 元 in 元たち.items():
            x = self.帳.項目.get(名)
            if x is None:
                continue
            足す = [r for n in 元 if n in self.帳.項目 for r in self.帳.項目[n].理由たち]
            x.理由たち = tuple(dict.fromkeys(list(x.理由たち) + 足す))

    # ---- 欠勤を遅刻早退に入れる人 ----
    def _欠勤を遅刻早退に入れる(self) -> bool:
        """会社の決まり `欠勤.欠勤を遅刻早退に入れる`（入れない・入れる）。入れる人（月給の形）は欠勤の日の分を芯/集計 が遅刻早退の時間に入れている。"""
        x = self.v.get("欠勤.欠勤を遅刻早退に入れる") or "入れない"
        if x not in ("入れない", "入れる"):
            raise 式が無い(f"欠勤.欠勤を遅刻早退に入れる「{x}」は 入れない・入れる の外")
        return x == "入れる" and self.v.get("支払.賃金の形") in 月給の形

    def _まるごと欠勤(self, 日割) -> bool:
        """欠勤を遅刻早退に入れる人の、1 か月まるごと欠勤の月（出勤 0・年休 0・欠勤あり・入退社の月でない）。
        その月は日割する 固定の月額（支給）を払わず、欠勤控除を出さない（日数で割る行は出た日が無い）。"""
        if not self._欠勤を遅刻早退に入れる() or 日割 is not None:
            return False
        出 = self.勤怠の数("出勤日数", "欠勤控除")
        有 = self.勤怠の数("年休（全日）", "欠勤控除") + self.勤怠の数("年休（半日）", "欠勤控除")
        return not 出 and not 有 and bool(self.勤怠の数("欠勤", "欠勤控除"))

    # ---- 部品の行 ----
    def _欠勤で減る(self, r) -> bool:
        if self.数量の語(r)[0] != "1":
            return False
        基礎 = self.v.get("欠勤.控除の基礎")
        if 基礎 == "基本給だけ":
            return r["名"] == "基本給"
        if 基礎 == "月の決まった賃金の全部":
            return True
        if 基礎 == "手当の行ごと":
            return (r.get("欠勤で減る") or "減る") == "減る"
        raise 式が無い(f"欠勤.控除の基礎「{基礎}」は選べる値の外")

    def _部品の額(self, r, 日割, 払わない=False):
        名 = r["名"]
        元 = self.単価の元(r)[0]
        if 元 == "人の額" and self.人の額(r) is None:
            return None   # 人の額の行は額のある人だけ
        種, 語 = self.数量の語(r)
        if 種 == "1":
            数量 = Decimal(1)
        elif 種 == "入力":
            数量 = 数((self.入力 or {}).get(名), f"入力の値 {名}")
            if 数量 is None:
                return None
        elif 種 == "分":
            数量 = _h(self.勤怠の数(語, 名))
        else:
            数量 = self.勤怠の数(語, 名)
        if 元 != "人の額" and 種 not in ("1", "入力") and not 数量:
            return None   # 人の額でない行は数量が 0 の人に出さない
        単価 = self.単価(r)
        if 単価 is None:
            self._仮(名, 理由(f"部品の行「{名}」の単価（{元}）が出ない", "0"))
            単価 = Decimal(0)
        率 = 数(r.get("率"), f"部品の行 {名} の率") or Decimal(1)
        x = 単価 * 数量 * 率
        if str(r.get("条件") or "無し") == "皆勤":
            if self.v.get("手当.皆勤の条件") != "欠勤 0":
                raise 式が無い(f"手当.皆勤の条件「{self.v.get('手当.皆勤の条件')}」の式はこの芯にまだ無い")
            if self.勤怠の数("欠勤", 名):
                x = Decimal(0)
        elif str(r.get("条件") or "無し") != "無し":
            raise 式が無い(f"部品の行「{名}」の条件「{r.get('条件')}」の式はこの芯にまだ無い")
        if 日割 is not None and 種 == "1" and (r.get("日割する") or "する") == "する":
            率2, 出所 = 日割
            x = 丸める(x * 率2, self.v["日割.端数"])
        if 払わない and 種 == "1" and (r.get("日割する") or "する") == "する" and r.get("支給か控除") == "支給":
            x = Decimal(0)   # 欠勤を遅刻早退に入れる人のまるごと欠勤の月（日数で割る行を払わない）
        self.帳.置く(名, self._行を丸める(x, r), f"部品の行「{名}」（{r.get('単価の元') or '固定の額'}×{r.get('数量の元') or '1'}×{率}）")
        return self.帳.項目[名].値

    def _行を丸める(self, x: Decimal, r) -> Decimal:
        """部品の行の `丸め`: 端数の語・`<n>円<語>`（n 円の単位で丸める）・`行の端数`（会社の決まり `端数.行の額`）。空は支給で切上げ・控除で切捨て。"""
        丸め = str(r.get("丸め") or ("切上げ" if r.get("支給か控除") == "支給" else "切捨て")).strip()
        if 丸め == "行の端数":
            丸め = self.v.get("端数.行の額") or "切上げ"
        単位 = Decimal(1)
        if "円" in 丸め:
            a, b = 丸め.split("円", 1)
            if not a.strip().isdigit() or int(a) <= 0:
                raise 式が無い(f"部品の行「{r['名']}」の丸め「{丸め}」は選べる値の外")
            単位, 丸め = Decimal(int(a)), b
        if not 丸めの語か(丸め):
            raise 式が無い(f"部品の行「{r['名']}」の丸め「{丸め}」は選べる値の外")
        return 丸める(x, 丸め, 単位)

    def _日割の率(self):
        """入退社の月の日割の率 (率, 出所) か None。"""
        始め, 終わり = self.期間
        入 = self.v.get("人.入社日")
        出 = self.v.get("人.退職日")
        入 = date.fromisoformat(str(入)) if 入 else None
        出 = date.fromisoformat(str(出)) if 出 else None
        a = max(始め, 入) if 入 else 始め
        b = min(終わり, 出) if 出 else 終わり
        if (a, b) == (始め, 終わり):
            return None
        式 = self.v.get("日割.入退社")
        効く = "課税計"
        if 式 == "しない":
            return None
        if b < a:
            return Decimal(0), "在籍が期間の外"
        if 式 == "暦日割":
            在籍 = Decimal((b - a).days + 1)
        elif 式 == "所定日割":
            try:
                在籍 = Decimal(暦.所定日数(a, b, self.v.get("時間.暦"), self.置き場)[0])
            except 口.欠け as e:
                self._仮(効く, 理由(f"祝日の表が欠け（所定日割ができない）: {e}"))
                return None
        elif 式 == "出た日で払う":
            在籍 = self.勤怠の数("出勤日数", "課税計")
        else:
            raise 式が無い(f"日割.入退社「{式}」は選べる値の外")
        割る = self.v.get("日割.割る数")
        if 割る == "その月の暦日":
            d = Decimal((終わり - 始め).days + 1)
        elif 割る == "その月の所定日数":
            d = self.勤怠の数("所定日数", "課税計")
        elif 割る == "年平均の所定日数":
            d = self.月の所定日数
        else:
            raise 式が無い(f"日割.割る数「{割る}」は選べる値の外")
        if not d:
            self._仮("課税計", 理由("日割の割る数が 0", "日割しない"))
            return None
        return min(Decimal(1), 在籍 / d), f"日割 {式} {在籍}/{d}"

    def _時間単価(self, 行たち) -> Decimal | None:
        """割増の単価（労基則 19 条: 時間・日・月の単価の和）。部品の行の `割増の基礎` が入る支給の行から。"""
        和, 月の和 = Decimal(0), Decimal(0)
        日の所定 = self._日の所定の時間(self.期間[1])
        for r in 行たち:
            if r.get("支給か控除") != "支給" or (r.get("割増の基礎") or "入る") != "入る":
                continue
            元, 割る = self.単価の元(r)
            if 元 in ("時間単価", "日単価"):
                continue
            if str(r.get("条件") or "無し") != "無し":
                continue
            x = self.人の額(r) if 元 == "人の額" and not 割る else 数(r.get("額")) if 元 == "固定の額" and not 割る else self.単価(r)
            if x is None:
                continue
            x *= 数(r.get("率")) or Decimal(1)
            種, 語 = self.数量の語(r)
            if 種 == "分":
                和 += x
            elif 種 == "日":
                if not 日の所定:
                    self._仮("時間外手当・法定内残業手当・60時間超手当・休日手当・深夜手当",
                            理由("日給の行の割増の単価に 時間.日の所定 が無い", "0"))
                    continue
                和 += x / 日の所定
            elif 種 == "1":
                月の和 += x   # 月の額は足してから 1 回で割る（行ごとに割ると割り切れない端数が積もって丸めが 1 円ずれる）
        if 月の和 and not self.月の所定時間:
            return None   # 月の所定時間が出ない＝単価を出さない（要る月は 月の所定 が仮の理由を付けた。最低賃金の検査も見ない）
        if 月の和:
            和 += 月の和 / self.月の所定時間
        return 丸める(和, self.v["端数.時間単価"])

    # ---- 割増 ----
    def _割増(self, 制度):
        v = self.v
        率 = {}
        for 名 in ("割増.時間外の率", "割増.45時間超の率", "割増.60時間超の率", "割増.休日の率", "割増.深夜の率"):
            法 = self.法の線(名, self._割増の効く(名))
            会社 = 数(v.get(名), 名)
            法 = 数(str(法), 名) if 法 is not None else None
            if 会社 is None and 名 == "割増.45時間超の率":
                率[名] = 率["割増.時間外の率"]   # 空＝会社の時間外の率（法の線は時間外と同じ 25%・45 時間超の上乗せは協定の努力義務）
            elif 会社 is None:
                率[名] = 法 or Decimal(0)
            elif 法 is not None and 会社 < 法:
                率[名] = 法
                self._仮(self._割増の効く(名), 理由(f"{名}「{会社}」が法の線 {法} を下回る（会社の決まり §1.1）", str(法),
                                              "法の線の率で計算", "就業規則の率を確かめる"))
            else:
                率[名] = 会社
        率["割増.法定内残業の率"] = 数(v.get("割増.法定内残業の率"), "割増.法定内残業の率")
        u = self.時間単価 or Decimal(0)
        端数の時間 = v["端数.時間外の時間"]
        if not 丸めの語か(端数の時間) and 端数の時間 != "30分未満切捨て30分以上1時間へ切上げ":
            raise 式が無い(f"端数.時間外の時間「{端数の時間}」は選べる値の外")

        def 時間(語, 効く):
            分 = self.勤怠の数(語, 効く)
            if 端数の時間 == "30分未満切捨て30分以上1時間へ切上げ":
                分 = 丸める(分, "四捨五入", Decimal(60))
            return _h(分)

        法定内 = 時間("法定内残業", "法定内残業手当")
        法定外 = 時間("法定外残業", "時間外手当")
        超60 = 時間("60 時間超", "60時間超手当")
        会社の数え方 = 会社の残業 in self.勤怠   # 芯/集計 が 割増.残業の数え方＝1日の所定超え で出した語（#26）
        if 会社の数え方:
            # 払うのは会社の数え方の方（所定超えの全部＝法定内残業も含む＝法定内は 0 にして二重に払わない）
            法定内 = Decimal(0)
            法定外 = 時間(会社の残業, "時間外手当")
            超60 = 時間(会社の60時間超, "60時間超手当")
            # 会社の数え方は休日勤務の日を数えない（#26「休日の語で払う」）＝所定休日の時間も休日の率で休日手当へ
            # （前の道具 timecard_tally 403〜406 行: 休日出勤の日は休出時間＝法定でない休日も含む・残業に入れない。オーナーの答え③）
            所定休 = 時間("所定休日", "休日手当")
        休日 = 時間("法定休日", "休日手当")
        if 会社の数え方:
            休日 += 所定休
        深夜 = 時間("深夜", "深夜手当")
        if 制度 == "管理監督者":
            法定内 = 法定外 = 超60 = 休日 = Decimal(0)
        if 制度 == "高度プロフェッショナル":
            法定内 = 法定外 = 超60 = 休日 = 深夜 = Decimal(0)
        if v.get("割増.深夜を賃金に含む") == "含む":
            深夜 = Decimal(0)
        所定休日の率 = (v.get("休日.休日出勤の数え方") or {}).get("所定休日の率", "週の法定で判定")
        if 所定休日の率 != "週の法定で判定" and self.勤怠の数("所定休日", "休日手当"):
            raise 式が無い(f"休日.休日出勤の数え方 の 所定休日の率「{所定休日の率}」の式はこの芯にまだ無い")
        # 時間外: 45 時間超の率が違う時だけ境で分ける。法定外は 60 時間超を含む＝境で数えるのは 60 時間までの分（min(法定外, 60) − 45）
        通常 = 法定外 - 超60
        超45 = Decimal(0)
        if 率["割増.45時間超の率"] != 率["割増.時間外の率"]:
            境 = self.法の線("協定.月の限度時間", "時間外手当")
            if 境 is not None:
                超45 = max(Decimal(0), 通常 - 数(str(境)))
                通常 -= 超45
        # 固定残業（超えた分を払う）
        固定 = v.get("割増.固定残業")
        固定額 = None
        if isinstance(固定, dict):
            対象 = v.get("割増.固定残業の対象")
            if 対象 not in ("時間外", "法定内残業と時間外"):
                raise 式が無い(f"割増.固定残業の対象「{対象}」の式はこの芯にまだ無い")
            if 固定.get("形") == "時間で":
                引く時間 = 数(固定.get("時間"), "固定残業の時間") or Decimal(0)
                if 対象 == "法定内残業と時間外":   # 固定残業の時間は法定内残業から先に当てる
                    d = min(法定内, 引く時間)
                    法定内 -= d
                    引く時間 -= d
                d = min(通常, 引く時間)
                通常 -= d
                超45 = max(Decimal(0), 超45 - (引く時間 - d))
            elif 固定.get("形") == "額で":
                固定額 = 数(固定.get("額"), "固定残業の額") or Decimal(0)
            else:
                raise 式が無い(f"割増.固定残業 の形「{固定.get('形')}」は 時間で・額で の外")
        elif 固定 not in (None, "無し"):
            raise 式が無い(f"割増.固定残業「{固定}」は 無し・{{形, 時間|額}} の外")
        else:
            # みなし残業の時間（固定残業の時間が無い時だけ・月給で役員でない人だけ＝前の道具 kyuyo_calc 348〜349・423〜424 行）
            みなし = 数(v.get("割増.みなし残業の時間"), "割増.みなし残業の時間")
            if みなし and v.get("支払.賃金の形") == "月給" and v.get("人.区分") != "役員":
                d = min(通常, みなし)
                通常 -= d
                超45 = max(Decimal(0), 超45 - (みなし - d))
        総額 = v["端数.割増の総額"]
        時間外 = u * 通常 * 率["割増.時間外の率"] + u * 超45 * 率["割増.45時間超の率"]
        if 固定額 is not None:
            時間外 = max(Decimal(0), 時間外 - 固定額)
        出所 = f"割増の単価 {u}（労基則 19 条・部品の行の割増の基礎）"
        self.帳.置く("法定内残業手当", 丸める(u * 法定内 * 率["割増.法定内残業の率"], 総額), 出所)
        self.帳.置く("時間外手当", 丸める(時間外, 総額), 出所)
        self.帳.置く("60時間超手当", 丸める(u * 超60 * 率["割増.60時間超の率"], 総額), 出所)
        self.帳.置く("休日手当", 丸める(u * 休日 * 率["割増.休日の率"], 総額), 出所)
        self.帳.置く("深夜手当", 丸める(u * 深夜 * 率["割増.深夜の率"], 総額), 出所)

