    def _部品の額(self, r, 日割, 払わない=False):
        名 = r["名"]
        元 = self.単価の元(r)[0]
        if not self._出す行か(r):
            return None   # 人の額・額:<項目> の行は額のある人だけ
        種, 語 = self.数量の語(r)
        if 種 == "1":
            数量 = Decimal(1)
        elif 種 == "入力":
            数量 = 数((self.入力 or {}).get(名), f"入力の値 {名}")
            if 数量 is None:
                return None
        elif 種 == "分":
            数量 = _h(self.勤怠の数(語, 名))
        else:
            数量 = self.勤怠の数(語, 名)
        引く語 = self.数量の引く数の語(r)
        if 引く語:   # 勤怠の数:<語>−<引く数>（例 出勤日数−所定日数＝所定を超えて出た日。分の語は時間で引く）
            引く = self._割る数(引く語, r)
            if 引く is None:
                self._仮(名, 理由(f"部品の行「{名}」の数量の引く数「{引く語}」が出ない", "0"))
                return None
            数量 = max(Decimal(0), 数量 - 引く)
            if not 数量:
                return None   # 超えた分の無い人に行を出さない
        if 元 != "人の額" and 種 not in ("1", "入力") and not 数量:
            return None   # 人の額でない行は数量が 0 の人に出さない
        単価 = self.単価(r)
        if 単価 is None:
            self._仮(名, self._単価が出ない理由(名, 元))
            単価 = Decimal(0)
        行の率 = 数(r.get("率"), f"部品の行 {名} の率")
        率 = self._休業手当の率(名, 行の率) if 元 == 平均賃金 else (行の率 or Decimal(1))
        x = 単価 * 数量 * 率
        if str(r.get("条件") or "無し") == "皆勤":
            if not self.皆勤を払うか(名, 知らせる=True):
                x = Decimal(0)
        elif str(r.get("条件") or "無し") != "無し":
            raise 式が無い(f"部品の行「{名}」の条件「{r.get('条件')}」の式はこの芯にまだ無い")
        if 日割 is not None and 種 == "1" and (r.get("日割する") or "する") == "する":
            率2, 出所 = 日割
            x = 丸める(x * 率2, self.v["日割.端数"])
        if 払わない and 種 == "1" and (r.get("日割する") or "する") == "する" and r.get("支給か控除") == "支給":
            x = Decimal(0)   # 欠勤を遅刻早退に入れる人のまるごと欠勤の月（日数で割る行を払わない）
        if 種 == "分" and x:
            self._時間給の丸め(名)
        self.帳.置く(名, self._行を丸める(x, r), f"部品の行「{名}」（{r.get('単価の元') or '固定の額'}×{r.get('数量の元') or '1'}×{率}）")
        return self.帳.項目[名].値

    def _休業手当の率(self, 名: str, 行の率: Decimal | None) -> Decimal:
        """平均賃金の行の率: 行の `率` → `休暇.休業手当の率` → 法の線。どこから来た率も法の線（労基法 26 条の 6 割）と比べ、
        下回れば法の線で仮に計算する（会社の決まり §1.1 の割増の率と同じ形・法の値はコードに書かない＝法の表/法の線.json の「休業手当」）。"""
