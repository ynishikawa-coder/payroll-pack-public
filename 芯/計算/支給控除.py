        if 表 is None:
            self.帳.置く("源泉所得税", None, 出所)
            return
        扶養 = int(数(v.get("源泉.扶養の数"), "源泉.扶養の数") or 0)
        self.帳.置く("源泉所得税", 月額表の税額(表, 額, 欄, 扶養), f"{出所}・{欄}欄・扶養 {扶養}・課税対象額 {額}・支給日 {self.支給日}")

