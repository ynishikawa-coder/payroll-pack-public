        for 名, 額 in 全.items():
            a = 載せる.get(名, Decimal(0))
            if not a:
                self.帳.置く(名, 額, 出所)
                continue
            x.値 = (x.値 or Decimal(0)) + a
            x.出所 += f"＋{何} {a}（{名}の分・{鍵}・{出所}）"
            self.載せた.setdefault(先, {})[名] = a
            self.帳.置く(名, 額 - a, f"{出所}。{何} {a} 円は 行「{先}」に載せた（{鍵}）" if 額 - a else
                        f"{何} {a} 円は 行「{先}」に載せた（{鍵}）")

