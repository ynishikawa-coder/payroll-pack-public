    # ---- 欠勤・遅刻早退 ----
    def _欠勤(self, 基礎: Decimal):
        v = self.v
        形 = v.get("支払.賃金の形")
        端数 = v["欠勤.控除の端数"]
        欠勤 = self.勤怠の数("欠勤", "欠勤控除") + self.勤怠の数("特別休暇（無給）", "欠勤控除")
        休業 = self.勤怠の数("休業", "欠勤控除")
        if 休業 and not self._休業手当の行():
            self._仮("欠勤控除・課税計", 理由("休業の日がある＝休業手当の行（単価の元＝平均賃金・数量の元＝勤怠の数:休業）が無い", "0",
                                          "休業の日は計算していない", "支給控除の項目に休業手当の行を足すか、休業の理由と払う額を書く"))
        elif 休業 and v.get("休暇.休業の日の控除") == "欠勤と同じに引く":
            欠勤 += 休業   # 月給の人の休業の日の賃金は欠勤と同じ割り方で引き、休業手当の行で平均賃金×率を払う（§3.5）
        elif 休業 and v.get("休暇.休業の日の控除") not in (None, "", "引かない"):
            raise 式が無い(f"休暇.休業の日の控除「{v.get('休暇.休業の日の控除')}」は 欠勤と同じに引く・引かない の外")
        控除 = Decimal(0)
        割る日, 割る時 = self._欠勤の割る数()
        欠勤から遅刻へ = Decimal(0)
        if self._欠勤を遅刻早退に入れる():
            # 欠勤日数で引かず、欠勤の日×日の所定を遅刻早退の時間へ足す（下で 月の所定時間−総労働 と比べて少ない方にする）
            日の所定 = self._日の所定の時間(self.期間[1])
            if 欠勤 and 日の所定:
                欠勤から遅刻へ = 欠勤 * 日の所定 * 60
            elif 欠勤:
                self._仮("遅刻早退控除", 理由("欠勤を遅刻早退に入れる人の 時間.日の所定 が無い（欠勤の日を遅刻早退に入れられない）", "0"))
            欠勤 = Decimal(0)
        if self.まるごと欠勤:
            基礎 = Decimal(0)   # まるごと欠勤の月は日割する行を払っていない＝欠勤控除を出さない
        if 形 in 月給の形 and 欠勤 and 基礎:
            割る = 割る日 if v.get("欠勤.控除の割り方") else (Fraction(str(self.月の所定日数)) if self.月の所定日数 else None)
            式 = v.get("欠勤.控除の式")
            if 式 == "欠勤が多い月だけ出た日で払う":
                式 = "出た日で払う方式" if 欠勤 * 2 > self.勤怠の数("所定日数", "欠勤控除") else "引く方式"
            F = Fraction(str(基礎))
            if not 割る:
                控除 = Decimal(0)
                if v.get("欠勤.控除の割り方"):
                    self._仮("欠勤控除", 理由("欠勤の割る数が出ない（欠勤.控除の割り方）", "0"))
            elif 式 == "引く方式":
                控除 = 分数を小数に(F * Fraction(str(欠勤)) / 割る)
            else:   # 出た日で払う方式（選べる値の外の字は 要る値 が 芯/設定 で照らした）
                控除 = max(Decimal(0), 分数を小数に(F - F * Fraction(str(self.勤怠の数("出勤日数", "欠勤控除"))) / 割る))
        self.帳.置く("欠勤控除", 丸める(控除, 端数), f"欠勤 {欠勤} 日・基礎 {基礎}")
        遅 = Decimal(0)
        遅刻 = self.勤怠の数("遅刻早退", "遅刻早退控除")
        # `欠勤.遅刻早退の数え方`＝月の所定時間−総労働で頭打ち（型の版 24）: 欠勤の無い月も（欠勤×日の所定＋日々の遅早）と
        # 月の所定時間−総労働 の少ない方を 1 回で取る（芯/集計 は日々の不足のまま渡す）
        月で頭打ち = "".join(str(v.get("欠勤.遅刻早退の数え方") or "").split()) == 月の所定時間で頭打ち
        if 欠勤から遅刻へ or (月で頭打ち and 遅刻):
            遅刻 += 欠勤から遅刻へ
            if self.月の所定時間:   # 所定−総労働 と比べて少ない方（働かなかった分を超えて引かない）
                不足 = max(Decimal(0), 分数を小数に(self.月の所定時間の分数 * 60) - self.勤怠の数("総労働", "遅刻早退控除"))
                if 欠勤:   # 欠勤を日数で別に引く人（入れない）: 欠勤の日の所定は欠勤控除で引いた＝不足から除く（和が働かなかった時間を超えない）
                    日の所定 = self._日の所定の時間(self.期間[1])
                    if 日の所定:
                        不足 = max(Decimal(0), 不足 - 欠勤 * 日の所定 * 60)
                    else:
                        self._仮("遅刻早退控除", 理由("月の所定時間−総労働で頭打ち の欠勤の人に 時間.日の所定 が無い（欠勤の日の所定を不足から除けない）",
                                                 "除かずに頭打ち"))
                遅刻 = min(遅刻, 不足)
            elif 月で頭打ち:
                self._仮("遅刻早退控除", 理由("欠勤.遅刻早退の数え方＝月の所定時間−総労働で頭打ち なのに月の所定時間が出ない", "頭打ちしない"))
        引く語 = v.get("欠勤.遅刻早退の控除")
        if 引く語 == "引かない（所定の不足を知らせる）":
            if 遅刻:
                self.知らせ.append(f"遅刻早退（所定の不足）{遅刻} 分＝引かない（欠勤.遅刻早退の控除）")
            引く語 = "引かない"
        if 遅刻 and 引く語 in ("引く", "月給の人だけ引く"):
            if 形 in 月給の形 and v.get("時間.月給者の遅れた出勤") == "引く" and v.get("欠勤.控除の割り方"):
                if 割る時:
                    遅 = 分数を小数に(Fraction(str(基礎)) * Fraction(str(遅刻)) / 60 / 割る時)
                else:
                    self._仮("遅刻早退控除", 理由("遅刻早退の割る時間が出ない（欠勤.控除の割り方）", "0"))
            elif 形 in 月給の形 and v.get("時間.月給者の遅れた出勤") == "引く" and self.月の所定時間:
                遅 = 分数を小数に(Fraction(基礎) * Fraction(遅刻) / 60 / self.月の所定時間の分数)
            elif 形 == "日給" and 引く語 == "引く":
                日の所定 = self._日の所定の時間(self.期間[1])
                日額 = sum((self.人の額(r) or 0) for r in self.部品の行たち()
                         if r.get("支給か控除") == "支給" and self.数量の語(r)[0] == "日" and (r.get("単価の元") == "人の額"))
                if 日の所定:
                    遅 = 日額 / 日の所定 * _h(遅刻)
        self.帳.置く("遅刻早退控除", 丸める(遅, 端数), f"遅刻早退 {遅刻} 分")

    def _欠勤の割る数(self):
        """会社の決まり `欠勤.控除の割り方` → (欠勤 1 日の割る数, 遅刻早退 1 時間の割る数)（Fraction か None）。空は今の式（月の所定日数・月の所定時間）。
        - 所定日数で日割り: 月の数字の 所定日数（その月の要出勤日数）・遅刻早退は 所定日数×日の所定
        - 所定時間で日割り: 月の所定時間÷日の所定・遅刻早退は 月の所定時間
        - 時間割り: `欠勤.控除の割る時間`÷日の所定・遅刻早退は `欠勤.控除の割る時間`"""
        v = self.v
        割り方 = v.get("欠勤.控除の割り方")
        if not 割り方:
            return None, None
        日の所定 = self._日の所定の時間(self.期間[1])
        F = (lambda x: Fraction(str(x)) if x else None)
        if 割り方 == "所定日数で日割り":
            日 = F(self.勤怠の数("所定日数", "欠勤控除"))
            return 日, (日 * F(日の所定) if 日 and 日の所定 else None)
        if 割り方 == "所定時間で日割り":
            時 = self.月の所定時間の分数 or None
        elif 割り方 == "時間割り":
            時 = 時間の値(v.get("欠勤.控除の割る時間"), "欠勤.控除の割る時間") or None   # h:mm（`173:00`・`161:20`）も分数のまま読む（型の版 21）
        else:
            raise 式が無い(f"欠勤.控除の割り方「{割り方}」は 所定日数で日割り・所定時間で日割り・時間割り の外")
        return (時 / F(日の所定) if 時 and 日の所定 else None), 時

    # ---- 通勤 ----
    def _通勤の上限(self, 通勤):
        上限 = 数(self.v.get("手当.通勤の上限"), "手当.通勤の上限")
        if 上限 is None:
            return
        和 = sum(self.帳.項目[n].値 for n in 通勤)
        超え = 和 - 上限
        for n in 通勤:
            if 超え <= 0:
                break
            d = min(超え, self.帳.項目[n].値)
            self.帳.項目[n].値 -= d
            超え -= d
        if 和 > 上限:
            self.知らせ.append(f"通勤の手当 {和} が 手当.通勤の上限 {上限} を超えた＝超えた分は払わない")

    def _通勤の超えた分の行(self, 通勤) -> str | None:
        """会社の決まり `手当.通勤の限度を超えた分の行`（部品の行の名・例 通勤課税）があれば、非課税の限度を超えた分を通勤の行（後ろの行から）から
        その行（課税）へ移し、行の名を返す（無ければ None＝今の形: 超えた分は行にせず課税計へ）。"""
        名 = str(self.v.get("手当.通勤の限度を超えた分の行") or "").strip()
        self._通勤の限度_移した = Decimal(0)
        if not 名 or not 通勤:
            return None
        if 名 in 決まった項目 or 名 in 通勤:
            raise ValueError(f"手当.通勤の限度を超えた分の行「{名}」は芯の決まった項目か通勤の非課税の行とぶつかる")
        超え = self._通勤の限度(通勤)
        for n in reversed(通勤):
            d = min(超え, self.帳.項目[n].値)
            self.帳.項目[n].値 -= d
            超え -= d
        移した = self._通勤の限度_移した
        x = self.帳.項目.get(名)
        if x is None:
            self.帳.置く(名, 移した, "通勤の非課税の限度を超えた分")
        else:
            x.値 = (x.値 or 0) + 移した
        self._通勤の限度_済み = True
        return None if x is not None else 名

    def _通勤の限度(self, 通勤) -> Decimal:
        """通勤の非課税の限度を超えた分（課税計へ）。限度は人の値 `手当.通勤の非課税の限度`（距離などで手前が法の表から決める）。"""
        if not 通勤 or getattr(self, "_通勤の限度_済み", False):
            return Decimal(0)
        和 = sum(self.帳.項目[n].値 for n in 通勤)
        限度 = 数(self.v.get("手当.通勤の非課税の限度"), "手当.通勤の非課税の限度")
        if 限度 is None:
            self._仮("課税計・非課税計", 理由("手当.通勤の非課税の限度 が無い", "全額を非課税で見当",
                                         "通勤の非課税の限度は距離と手段で決まる", "限度の額を書く"))
            return Decimal(0)
        self._通勤の限度_移した = max(Decimal(0), 和 - 限度)
        return self._通勤の限度_移した

    # ---- 社保 ----
    def _二以上の按分(self) -> Decimal | None:
        """社保.二以上事業所の按分（この事業所の報酬÷全事業所の報酬の合算）→ 0 より大きく 1 以下の割合。空＝二以上事業所勤務でない（None）。
        `0.4`・`40%`・`120000/300000` を読む。読めない・範囲の外は按分しない額で見当して仮＋問い（⟦鍵:給与計算/足りない時は仮で計算し出さない⟧）。"""
        x = self.v.get("社保.二以上事業所の按分")
        if x is None or (isinstance(x, str) and not x.strip()):
            return None
        s = str(x).strip().replace("％", "%").replace("／", "/")
        try:
            if s.endswith("%"):
                r = Decimal(s[:-1].strip()) / 100
            elif "/" in s:
                a, b = s.split("/", 1)
                r = Decimal(a.strip()) / Decimal(b.strip())
            else:
                r = Decimal(s)
        except (ArithmeticError, ValueError):
            r = None
        if r is None or not r.is_finite() or not (0 < r <= 1):
            self._仮("健康保険・介護保険・子ども・子育て支援金・厚生年金",
                    理由(f"社保.二以上事業所の按分「{x}」が 0 より大きく 1 以下の割合として読めない", "按分しない",
                         "二以上事業所勤務の人の保険料は合算の標準報酬×率×この事業所の按分",
                         "年金事務所の決定通知からこの事業所の割合を書く（例 0.4・40%・120000/300000）"))
            return None
        return r

    def _社保(self):
        v = self.v
        for n in 社保の項目:
            self.帳.置く(n, Decimal(0), "")
        if v.get("社保.加入") != "加入" or 区分だけか(v, "委託"):
            for n in 社保の項目:
                self.帳.置く(n, Decimal(0), "社保.加入 が 加入 でない")
            return
        y, m = 暦.支給月を読む(self.支給月)
        徴収 = v.get("社保.徴収の月")
        if 徴収 not in ("翌月徴収", "当月徴収"):
            raise 式が無い(f"社保.徴収の月「{徴収}」は 翌月徴収・当月徴収 の外")
        hy, hm = 暦.月を足す(y, m, -1 if 徴収 == "翌月徴収" else 0)
        保険料の月 = f"{hy:04d}-{hm:02d}"
        月 = (hy, hm)
        取得, 喪失 = v.get("社保.取得日"), v.get("社保.喪失日")
        if (取得 and 月 < _月(取得)) or (喪失 and 月 >= _月(喪失)):
            for n in 社保の項目:
                self.帳.置く(n, Decimal(0), f"保険料の月 {保険料の月} は資格の外")
            return
        免除 = v.get("社保.免除")
        if isinstance(免除, dict) and 免除.get("始め"):
            s = _月(免除["始め"])
            e = _月((date.fromisoformat(str(免除["終わり"])) + timedelta(days=1)).isoformat()) if 免除.get("終わり") else None
            if s <= 月 and (e is None or 月 < e):
                for n in 社保の項目:
                    self.帳.置く(n, Decimal(0), f"保険料の月 {保険料の月} は産休育休の免除")
                return
        標準 = 数(v.get("社保.標準報酬"), "社保.標準報酬")
        if 標準 is None:
            for n in 社保の項目:
                self.帳.置く(n, None, "標準報酬月額が無い")
            return
        健保の等級, 出所1 = self.引く("標準報酬月額", 保険料の月, "健康保険・介護保険・子ども・子育て支援金", 制度="健保")
        厚年の標準 = 数(v.get("社保.厚年の標準報酬"), "社保.厚年の標準報酬")
        if 厚年の標準 is None:
            厚年の等級, 出所2 = self.引く("標準報酬月額", 保険料の月, "厚生年金", 制度="厚年")
            if 厚年の等級:
                g = [x for x in 厚年の等級["等級"] if (x[2] or 0) <= 標準 < (x[3] or 10 ** 12)]
                厚年の標準 = Decimal(g[0][1]) if len(g) == 1 else None
        if 健保の等級 and self.等級を照らす and 標準 not in {Decimal(x[1]) for x in 健保の等級["等級"]}:
            self._仮("健康保険・介護保険・子ども・子育て支援金・厚生年金",
                    理由(f"社保.標準報酬 {標準} が健保の等級表の額に無い", str(標準), "渡された額のまま計算", "標準報酬月額を確かめる"))
        生 = v.get("人.生年月日")
        生 = date.fromisoformat(str(生)) if 生 else None
        端数 = v["社保.端数"]
        # 二以上事業所勤務: 標準報酬は全事業所の合算の物・この事業所はその割合で按分した額を引く（健保・介護・支援金・厚年。雇保は按分しない）
        按分 = self._二以上の按分() if self.按分する else None
        合算, 合算の厚年 = 標準, 厚年の標準
        if 按分 is not None:
            標準 = 標準 * 按分
            厚年の標準 = 厚年の標準 * 按分 if 厚年の標準 is not None else None

        def 丸(x):
            return 丸める(x, 端数)

        効く = "健康保険・介護保険・子ども・子育て支援金・厚生年金"
        歳 = {k: self.法の線(f"年齢.{k}", 効く) for k in ("介護の始め", "介護の終わり", "厚年の終わり", "健保の終わり")}
        if 生 is not None and None in 歳.values():
            生 = None   # 年齢の線が引けない＝年齢の線に掛からないとして見当（仮の理由は 法の線 が付けた）
        健保に入る = 生 is None or 月 < _月(_歳の日(生, int(歳["健保の終わり"]), 誕生日=True).isoformat())
        if 健保に入る:
            組合 = v.get("社保.組合の率")
            支援, 出所s = self.引く("子ども子育て支援金", 保険料の月, "子ども・子育て支援金")
            支援率 = (数(str(支援["率%"])) / 2) if 支援 else Decimal(0)
            if isinstance(組合, dict) and 組合:
                健保率 = 数(組合.get("健保の本人率%"), "組合の健保の本人率%") or Decimal(0)
                介護率 = 数(組合.get("介護の本人率%"), "組合の介護の本人率%") or Decimal(0)
            else:
                健, 出所k = self.引く("健保_協会けんぽ", 保険料の月, "健康保険", 都道府県=v.get("社保.健保の支部"))
                介, 出所i = self.引く("介護_協会けんぽ", 保険料の月, "介護保険")
                健保率 = 数(str(健["率%"])) / 2 if 健 else Decimal(0)
                介護率 = 数(str(介["率%"])) / 2 if 介 else Decimal(0)
            if not (生 and _月(_歳の日(生, int(歳["介護の始め"])).isoformat()) <= 月 < _月(_歳の日(生, int(歳["介護の終わり"])).isoformat())):
                介護率 = Decimal(0)
            p = Decimal(100)
            介護 = 丸(標準 * 介護率 / p)
            支援額 = 丸(標準 * 支援率 / p)
            順 = v.get("社保.丸めの順")
            全部 = 丸(標準 * (健保率 + 介護率 + 支援率) / p)
            if 順 in ("合わせて", "介護を先に"):   # 介護・支援金を丸めて、3 つの和を丸めた額から引いた残りが健保
                健保 = 全部 - 介護 - 支援額
            elif 順 == "別に":
                健保 = 丸(標準 * 健保率 / p)
            elif 順 == "健保＋支援金を先に":     # 健保＋支援金を丸めて支援金を引いた残りが健保・3 つの和の残りが介護
                健保と支援 = 丸(標準 * (健保率 + 支援率) / p)
                健保, 介護 = 健保と支援 - 支援額, 全部 - 健保と支援
            else:   # 支援金を別に＝健保＋介護を丸めて介護を引いた残りが健保・支援金は単独で丸める（選べる値の外の字は 要る値 が 芯/設定 で照らした）
                健保 = 丸(標準 * (健保率 + 介護率) / p) - 介護
            含める = v.get("社保.支援金を健保に含める") or "含めない"
            if 含める == "含める":           # 明細に支援金の行を持たない会社は健保の行に入れて引く
                健保, 支援額 = 健保 + 支援額, Decimal(0)
            按分の字 = f"×按分 {v.get('社保.二以上事業所の按分')}" if 按分 is not None else ""
            出所 = f"標準報酬 {合算}{按分の字}・保険料の月 {保険料の月}・{出所1}"
            self.帳.置く("健康保険", 健保, 出所)
            self.帳.置く("介護保険", 介護, 出所)
            self.帳.置く("子ども・子育て支援金", 支援額, 出所)
        if 生 is None or 月 < _月(_歳の日(生, int(歳["厚年の終わり"])).isoformat()):
            厚, 出所a = self.引く("厚年の率", 保険料の月, "厚生年金")
            if 厚 and 厚年の標準 is not None:
                按分の字 = f"×按分 {v.get('社保.二以上事業所の按分')}" if 按分 is not None else ""
                self.帳.置く("厚生年金", 丸(厚年の標準 * 数(str(厚["率%"])) / 2 / 100), f"標準報酬 {合算の厚年}{按分の字}・{出所a}")
            else:
                self.帳.置く("厚生年金", None, "厚年の率か等級が引けない")

    # ---- 雇保 ----
    def _雇保(self, 支給の行, 元=None):
        """元: 賃金の額（既定は 総支給額 から 雇保の対象＝入らない 行を引いた額。賞与は賞与の額）。率は期間の終わりの日（賞与は支給日）で引く。"""
        v = self.v
        if v.get("雇保.加入") != "加入" or 区分か(v, "役員") or 区分だけか(v, "委託"):
            self.帳.置く("雇用保険", Decimal(0), "雇保.加入 が 加入 でない")
            return
        if 元 is None:
            外 = [n for n in 支給の行 if (self._行(n).get("雇保の対象") or "入る") != "入る"]
            元 = self.帳.項目["総支給額"].値 - sum(self.帳.項目[n].値 for n in 外) + self.委託の元
        本人 = 数(v.get("雇保.本人負担率"), "雇保.本人負担率")
        if 本人 is not None:   # 会社の決まりで本人の率（小数）を持つ時は表を引かない
            self.帳.置く("雇用保険", 丸める(元 * 本人, v["雇保.端数"]), f"賃金 {元}・雇保.本人負担率 {本人}")
            return
        率, 出所 = self.引く("雇保の率", self.期間[1].isoformat(), "雇用保険", 事業の種類=v.get("雇保.事業の種類"))
        if not 率:
            self.帳.置く("雇用保険", None, 出所)
            return
        self.帳.置く("雇用保険", 丸める(元 * 数(str(率["労働者‰"])) / 1000, v["雇保.端数"]), f"賃金 {元}・{出所}")

    def _行(self, 名):
        return next((r for r in self.v.get("項目.行") or [] if r["名"] == 名), {})

    # ---- 源泉 ----
    def _源泉(self):
        v = self.v
        if v.get("源泉.住む所") != "居住者":
            raise 式が無い("源泉.住む所＝非居住者 の率はこの芯にまだ無い（優先 B）")
        欄 = v.get("源泉.欄")
        if 欄 not in ("甲", "乙"):
            raise 式が無い(f"源泉.欄「{欄}」の表はこの芯にまだ無い（丙は優先 B）")
        額 = self.帳.項目["課税対象額"].値
