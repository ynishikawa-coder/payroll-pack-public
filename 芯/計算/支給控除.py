    # ---- 仮の理由 ----
    def _仮(self, 効く: str, r: 理由):
        if 効く == "全部":
            self.全部の理由.append(r)
        else:
            for k in 効く.split("・"):
                self.理由.setdefault(k, []).append(r)

    def _効く理由(self, 名: str) -> list:
        return self.全部の理由 + self.理由.get(名, [])

    def _理由を項目へ(self, 足す=lambda 名: ()):
        """仮の理由を帳の項目へ配る 1 か所（月・委託だけ・賞与の 計算 が最後に呼ぶ。計へ流す前に）。

        理由は効く項目の名で持つ。効く名の項目が帳に無い（数量 0 で行を出さない・式の途中で止めた）時も理由は捨てない＝
        行き先の無い理由は人の最後の額（差引支給額、委託だけの人は 支払合計）が受ける。だから仮の値（空で仮の月の数字など）を
        読んだ人は、その読みがどの項目にも載らなくても仮になり出口へ出ない（⟦鍵:給与計算/足りない時は仮で計算し出さない⟧）。"""
        for 名, x in self.帳.項目.items():
            x.理由たち = tuple(dict.fromkeys(list(x.理由たち) + self._効く理由(名) + list(足す(名))))
        落ちた = [r for k, rs in self.理由.items() if k not in self.帳.項目 for r in rs]
        if not 落ちた:
            return
        受け = next((self.帳.項目[n] for n in ("差引支給額", 委託.支払合計) if n in self.帳.項目), None)
        for x in ([受け] if 受け is not None else self.帳.項目.values()):
            x.理由たち = tuple(dict.fromkeys(list(x.理由たち) + 落ちた))

    def 勤怠の生の数(self, 語: str) -> Decimal:
        """月の数字の語の値を仮の理由を付けずに読む（行を出すか・所定が要るか などの分かれ道だけ。額には使わない）。
        空・仮の値は 0 と読むが、その語を額に使う所は 勤怠の数 で読み理由を付ける＝行を出さなくても _理由を項目へ が人を仮にする。"""
        return (self.勤怠.get(語) or (None,))[0] or Decimal(0)

    # ---- 法の表 ----
    def 引く(self, 名: str, 日, 効く: str, **鍵):
        """引いた値。仮で引いたら理由を付ける。欠け（止める）は None と理由。"""
        try:
            r = 口.引く(名, 日, 置き場=self.置き場, **鍵)
        except 口.欠け as e:
            self._仮(効く, 理由(f"法の表が欠け: {e}", "", "表の欠けた時＝止める（前の値で代えない）", "法の表を入れ直すまで待つ"))
            return None, str(e)
        if r.仮:
            self._仮(効く, 理由(f"法の表がまだ: {名}", r.出所, "表の欠けた時＝仮で計算し問う（docs/設計/法の表.md §2.2）",
                                "国の公表の後に計算し直す"))
        return r.値, r.出所

    def 法の線(self, 鍵: str, 効く: str):
        """法の表/法の線.json（1 行＝1 つの線・鍵 `線`）から芯の名の値を引く（読み方は 法の線の読み方.py）。率%は倍（割増）か足す率（深夜）に直す。"""
        線, 欄, 直し = 線の読み.読み方[鍵]
        if 線 not in self.線:
            self.線[線] = self.引く("法の線", self.期間[1].isoformat(), 効く, 線=線)[0]
        値 = self.線[線]
        if 値 is None:
            return None
        x = 線の読み.欄の値(鍵, 値)
        if x is None:
            self._仮(効く, 理由(f"法の線「{線}」に「{欄}」が無い", "", "法の表/法の線.json", "法の表に足す"))
            return None
        return 1 + 数(str(x)) / 100 if 直し == "倍" else 数(str(x)) / 100 if 直し in ("足す", "割合") else x

