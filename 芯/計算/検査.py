"""法の線の検査（材料: pixel-office の agents/kyuyo 道具/kensa.py の hou と hitsuyo.py の最低賃金を今の形へ書き直した物）。

その人のその月の値と計算の途中の値を、法の表/法の線.json・最低賃金.json と照らす。1 件 1 行「赤: …」か「知らせ: …」。
- 赤のうち賃金が法を下回る物（最低賃金・割増の基礎から除けない手当を除いた）は、その人を仮にする（問いの答えまで出さない）。
- 割増の率が法の線を下回る時は 支給控除.py が法の線の率で仮として計算する（会社の決まり §1.1）。ここは知らせの行を足すだけ。
- 答え合わせ（過去の結果に合うか）は入れない。法の値はコードに書かない（引く口で引く）。
"""
from __future__ import annotations

import re
from decimal import Decimal

from .形 import 区分か, 数, 理由, 時間 as 時間の値
from .承知 import 基礎の線, 最低賃金の含める

賃金の項目 = "課税計"

# 割増の基礎から除ける賃金（労基法 37 条 5 項・労基則 21 条の 7 つ。名でなく中身で判断＝行の `割増の基礎から除く訳` に書く）。
# 正本は 初期設定/法の線の点検.json の 除ける訳（芯は初期設定を読まない＝ここは芯の読む形の写し。
# 食い違えば tests/計算/test_計算_除ける訳と点検表.py が赤）
除ける訳 = ("家族手当", "通勤手当", "別居手当", "子女教育手当", "住宅手当", "臨時の賃金", "1 か月を超える期間ごとの賃金")
# 割増の賃金そのもの（通常の労働時間の賃金でない＝割増の単価の元に入らない。固定残業代は判別できる時だけ割増の支払いに当たる）。
# 正本は 初期設定/法の線の点検.json の 割増そのものの訳（写し。食い違えば同じ試験が赤）
割増そのものの訳 = ("固定残業手当",)


def _語(v) -> str:
    return re.sub(r"[ 　]", "", str(v or ""))


語 = _語   # 訳の語の照らしの揃え方（空白を外す）。支給控除 の最低賃金に算入しない訳も同じ揃え方で照らす


def 除けない行(行たち) -> dict[str, str]:
    """割増の基礎から除けない支給の行 → その行に書いてある訳（空＝書いていない）。

    除ける訳（労基則 21 条の 7 つ）と 割増そのものの訳（固定残業手当）のどれでもない訳・訳の無い行は、法の線では割増の単価に入れる賃金
    （`法の線.承知` に `割増.基礎に入る` の印がある時だけ会社のまま除く＝会社の決まり §1.4）。"""
    除ける = {_語(w) for w in 除ける訳 + 割増そのものの訳}
    out = {}
    for r in 行たち or ():
        if r.get("支給か控除") != "支給" or (r.get("割増の基礎") or "入る") == "入る":
            continue
        訳 = str(r.get("割増の基礎から除く訳") or "").strip()
        if _語(訳) not in 除ける:
            out[r["名"]] = 訳
    return out


def 見る(人) -> list[str]:
    """人＝支給控除.一人（計算した後）。赤・知らせの行を返し、要る所は人に仮の理由を足す。"""
    v, out = 人.v, []
    行たち = v.get("項目.行") or []
    if 区分か(v, "役員"):
        # 役員（役員＋委託の併用 も）は労働者でない＝割増・所定・36 協定・最低賃金（最低賃金法 2 条の労働者）を当てない。知らせ（7）だけ見る
        return _知らせ(人, v, 行たち, out, Decimal(0))
    # 委託の併用の人は雇用分の額と時間だけで見る（人.時間単価・勤怠は雇用分。委託分の項目は見ない）

    # 1 割増の基礎から除いた手当（労基法 37 条 5 項・労基則 21 条の 7 つだけ。名でなく中身で判断＝行に除く訳を書く）
    #   7 つの一覧（除ける訳）は法の表に無い語の照らし＝ここの写しで見る。承知の印（§1.4）がある時は会社のまま除いて仮にしない
    #   その人にその月払った行だけ（払っていない手当は単価に入れる賃金でない＝支給控除.払う除けない行 の 1 か所の読み）
    除けない = 人.払う除けない行(行たち)
    if 除けない and 基礎の線 in 人.承知の印:
        訳たち = "・".join(f"{名}（訳: {訳 or 'なし'}）" for 名, 訳 in 除けない.items())
        out.append(f"承知: 部品の行 {訳たち} を割増の基礎から除く＝事務所が承知（{人.承知の印[基礎の線]}）"
                   "・会社の単価で計算した［労基法 37 条 5 項・労基則 21 条］")
    else:
        for 名, 訳 in 除けない.items():
            何 = f"部品の行「{名}」を割増の基礎から除く訳が無い" if not 訳 else \
                f"部品の行「{名}」の 割増の基礎から除く訳「{訳}」は労基則 21 条の 7 つの外"
            out.append(f"赤: {何}＝割増の単価に入れて仮に計算した［労基法 37 条 5 項・労基則 21 条］")
            人._仮("・".join(("法定内残業手当", "時間外手当", "60時間超手当", "休日手当", "深夜手当")),
                  理由(何, "割増の単価に入れた",
                       "除けるのは労基則 21 条の 7 つだけ（会社の決まり §2 ③）", "除く訳を書くか 割増の基礎 を 入る にする"))

    # 2 割増の率（会社の値が法の線を下回る）
    for 名 in ("割増.時間外の率", "割増.45時間超の率", "割増.60時間超の率", "割増.休日の率", "割増.深夜の率"):
        法, 会社 = 人.法の線(名, 人._割増の効く(名)), 数(v.get(名), 名)
        if 法 is not None and 会社 is not None and 会社 < 数(str(法)) and 名 in 人.承知の印:
            out.append(f"承知: {名}「{会社}」が法の線 {法} を下回る＝事務所が承知（{人.承知の印[名]}）・会社の率で計算した［労基法 37 条・割増令］")
        elif 法 is not None and 会社 is not None and 会社 < 数(str(法)):
            out.append(f"赤: {名}「{会社}」が法の線 {法} を下回る＝法の線で仮に計算した［労基法 37 条・割増令］")
    外の率, 超45の率 = 数(v.get("割増.時間外の率"), "割増.時間外の率"), 数(v.get("割増.45時間超の率"), "割増.45時間超の率")
    if 外の率 is not None and 超45の率 is not None and 超45の率 < 外の率:
        out.append(f"知らせ: 割増.45時間超の率「{超45の率}」が 割増.時間外の率「{外の率}」を下回る＝45 時間を超えた分を低い率で払う"
                   "（法の線は下回らないので仮にしない）＝就業規則・36 協定の率を確かめる［労基法 36 条・平 30 厚労告 323 号 5 条 3 項］")

    # 2 の 2 皆勤の手当を年休を取ったことで払わない月（労基法附則 136 条）。読みは 支給控除 の 皆勤の読み の 1 か所
    #   （皆勤の行のある人で、会社の決まりと法の線の答えが違う月だけ＝その月に額が変わる時）
    from .支給控除 import 皆勤の線, 皆勤の有給も
    条件 = v.get(皆勤の線)
    for 名 in dict.fromkeys(r["名"] for r in 行たち if str(r.get("条件") or "") == "皆勤"):
        年休あり = any(人.勤怠の数(語, 名) for 語 in ("年休（全日）", "年休（半日）", "年休（時間）"))
        if 人.この月は付けないか(名):
            if 年休あり:
                out.append(f"知らせ: 月の変動で「{名}」をこの月 0（付けない）にした月に年休がある＝年休を取ったことが訳なら"
                           "法の線の下（付けない訳を確かめる）［労基法附則 136 条］")
            continue
        会社, 法, 年休 = 人.皆勤の読み(名)
        if 会社 == 法:
            continue
        if 皆勤の線 in 人.承知の印:
            out.append(f"承知: {皆勤の線}「{条件}」で年休を取った月に皆勤の手当を払わない＝事務所が承知（{人.承知の印[皆勤の線]}）"
                       "・会社の決まりで計算した［労基法附則 136 条］")
        elif 条件 == 皆勤の有給も:
            out.append(f"赤: {皆勤の線}「{条件}」は年休を取った月に皆勤の手当を払わない＝法の線（欠勤 0）で払って仮に計算した"
                       "［労基法附則 136 条］")
        else:
            out.append(f"知らせ: {皆勤の線}「{条件}」で年休（{年休}）の日を出勤に数えて所定日数に届いた＝皆勤の手当を払った"
                       "（年休の日を出勤に数えない決まりなら 法の線.承知 に 手当.皆勤の条件 の印）［労基法附則 136 条］")
        break   # 線の行は人に 1 つ

    # 3 所定が法定を超える（通常の制度）
    if v.get("時間.制度") == "通常":
        日, 週 = 人.法の線("時間.日の法定", "時間外手当"), 人.法の線("時間.週の法定", "時間外手当")
        x = v.get("時間.日の所定")
        日の所定たち = list(x.values()) if isinstance(x, dict) else [x]
        if 日 is not None and any((数(d) or 0) > 数(str(日)) for d in 日の所定たち):
            out.append(f"赤: 時間.日の所定 {x} が日の法定 {日} を超える（通常の制度）［労基法 32 条］")
        週の所定 = 時間の値(v.get("時間.週の所定"), "時間.週の所定")   # 時間の数か h:mm（`38:31`）
        if 週 is not None and 週の所定 is not None and 週の所定 > 数(str(週)):
            out.append(f"赤: 時間.週の所定 {v.get('時間.週の所定')} が週の法定 {週} を超える（通常の制度）［労基法 32 条］")

    # 4 36 協定の線（その月だけで見られる物）
    外 = 人.勤怠の数("法定外残業", "時間外手当")
    休 = 人.勤怠の数("法定休日", "休日手当")
    上限, 限度 = 人.法の線("協定.単月の上限", "時間外手当"), 人.法の線("協定.月の限度時間", "時間外手当")
    if 上限 is not None and 外 + 休 >= 数(str(上限)) * 60:
        out.append(f"赤: 時間外と休日の労働 {外 + 休} 分が単月の上限 {上限} 時間に達する［労基法 36 条 6 項 2 号］")
    elif 限度 is not None and 外 > 数(str(限度)) * 60:
        out.append(f"知らせ: 時間外 {外} 分が月の限度時間 {限度} 時間を超える＝特別条項の協定と年 6 回までを確かめる［労基法 36 条 4 項・5 項］")

    # 5 固定残業の額が時間分に足りない（額と時間を分けて示す）
    固定 = v.get("割増.固定残業")
    if isinstance(固定, dict) and 固定.get("形") == "額で" and 固定.get("時間") not in (None, ""):
        要る = (人.時間単価 or 0) * 数(固定["時間"]) * (人.法の線("割増.時間外の率", "時間外手当") or 0)
        if 数(固定.get("額")) < 要る:
            out.append(f"赤: 固定残業の額 {固定.get('額')} が {固定['時間']} 時間分の割増 {要る:.0f} を下回る［労基法 37 条・最判 平 24.3.8］")

    # 6 最低賃金（最低賃金法 4 条。比べる賃金から 最低賃金に算入しない賃金〔法 4 条 3 項・規則 1 条＝法の表/法の線.json〕だけを除く。
    #   割増の基礎から除いた住宅手当などは除かない＝支給控除 が割増の単価と別に出した 最低賃金の単価）。
    #   印 `最低賃金=問N（含める:家族手当）`＝会社は算入しない手当を含めて比べる＝法の線の下の比べ方（法は会社が含めることを許さない）:
    #   含めても下回れば赤で仮。含めて届き法の線の単価で下回る時だけ、承知した食い違い（法の線の単価と差額を知らせる・会社の決まり §1.4）
    県 = v.get("会社.事業場の都道府県")
    印 = 人.承知の印.get("最低賃金")
    問い, 含める = 最低賃金の含める(印)
    if not 県:
        out.append("知らせ: 会社.事業場の都道府県 が無い＝最低賃金を見られない［最低賃金法 4 条］")
    else:
        最, _ = 人.引く("最低賃金", 人.期間[1].isoformat(), 賃金の項目, 都道府県=県)
        法の単価 = getattr(人, "最低賃金の単価", None)   # 端数.月の所定時間 で切り捨てない所定の単価（型の版 18）
        会社の単価 = getattr(人, "最低賃金の会社の単価", None)
        if 区分か(v, "委託の併用"):
            法の単価, 会社の単価 = _併用の単価(人, 行たち), _併用の単価(人, 行たち, 会社=True, 知らせる=False)
        額 = 数(str(最["時間額"])) if 最 is not None else None
        if 額 is None or 法の単価 is None:
            pass
        elif 含める and 会社の単価 is not None and 会社の単価 < 額:
            out.append(f"赤: 時間あたりの賃金 {会社の単価}（{'・'.join(sorted(含める))} を含めても）が {県} の最低賃金 {額} を下回る"
                       "［最低賃金法 4 条］")
            人._仮("全部", 理由(f"時間あたりの賃金 {会社の単価}（{'・'.join(sorted(含める))} を含めて）が最低賃金 {額}（{県}）を下回る",
                             str(会社の単価), "計算はそのままの額", "賃金を直すか 計算の基の値を確かめる"))
        elif 法の単価 < 額 and 印 is not None:
            含め = f"（{'・'.join(sorted(含める))} を含めると {会社の単価}）" if 含める else ""
            out.append(f"承知: 時間あたりの賃金 {法の単価}{含め} が {県} の最低賃金 {額} を下回る＝事務所が承知（{問い}）"
                       "・会社の額で計算した［最低賃金法 4 条］")
            人.承知した["最低賃金"] = (法の単価, 額)   # 法の線の単価と最低賃金の差額を 計算する の知らせに残す
        elif 法の単価 < 額:
            out.append(f"赤: 時間あたりの賃金 {法の単価} が {県} の最低賃金 {額} を下回る［最低賃金法 4 条］")
            人._仮("全部", 理由(f"時間あたりの賃金 {法の単価} が最低賃金 {額}（{県}）を下回る", str(法の単価),
                             "計算はそのままの額", "賃金を直すか 計算の基の値を確かめる"))

    return _知らせ(人, v, 行たち, out, 外)


def _併用の単価(人, 行たち, 会社: bool = False, 知らせる: bool = True):
    """委託の併用の人の最低賃金の単価＝雇用分の額 ÷ 雇用として働いた時間（勤怠ソフトの出勤時間）。
    ⟦鍵:給与計算/委託の併用の最低賃金の時間⟧。時間は `入力` の `委託.雇用分の出勤時間`（分か h:mm・月の和）。
    雇用分の額＝支給の部品の行のうち最低賃金と比べる賃金に入る行（支給控除.最低賃金に入るか＝法の表の 最低賃金に算入しない賃金 の
    訳でない行。会社＝True は印の（含める:…）の訳も入れる）で条件の無い行の、その月の額（委託分・割増・皆勤は入れない）。
    時間が無ければ月の所定時間で割った単価（人.時間単価）で見て、仮＋問い（前の道具は給与ソフトの固定の出勤時間＝timecard_tally 491〜495 行）。"""
    from .委託 import 分にする
    from .形 import 形の誤り
    元 = (人.入力 or {}).get("委託.雇用分の出勤時間")
    try:
        時間 = 分にする(元)
        訳 = "が無い" if 時間 is None else "が 0 か負" if 時間 <= 0 else ""
    except 形の誤り:
        時間, 訳 = None, f"の形が読めない（{元!r}）"
    if 訳:
        見当 = getattr(人, "最低賃金の会社の単価" if 会社 else "最低賃金の単価", None)
        if 知らせる:   # 法の線と会社の 2 回読む＝仮は 1 回
            人._仮("全部", 理由(f"委託の併用の人の雇用分の出勤時間（勤怠ソフトの出勤時間）{訳}", str(見当 or ""),
                             "最低賃金を雇用分の額÷月の所定時間で見当", "入力 の 委託.雇用分の出勤時間 を分か h:mm で渡す"))
        return 見当
    額 = Decimal(0)
    for r in 行たち:
        if r.get("支給か控除") != "支給" or not 人.最低賃金に入るか(r, 会社=会社) or str(r.get("条件") or "無し") != "無し":
            continue
        x = 人.帳.項目.get(r["名"])
        if x is not None and x.値 is not None:
            額 += x.値
    return (額 / (時間 / 60)).quantize(Decimal("0.01"))


def _知らせ(人, v, 行たち, out, 外) -> list[str]:
    # 7 知らせ（仮にしない）
    if 区分か(v, "役員") and v.get("雇保.加入") == "加入":
        out.append("知らせ: 役員に 雇保.加入＝加入 がある＝雇保は引いていない（兼務役員なら 人.区分 を直す）［雇保法 4 条］")
    for r in 行たち:
        if r.get("支給か控除") == "支給" and str(r.get("数量の元") or "").strip() == "勤怠の数:総労働" and 外:
            out.append(f"知らせ: 部品の行「{r['名']}」が総労働で払い、時間外手当も 1.0 を含む率で払う＝時間外の 1.0 が二重（所定内で払う形か確かめる）")
    return out
