"""芯の計算: 芯/集計 の月の数字と、会社の決まり・人の値（`分野.名`）と、法の表から、支給控除を人×項目の縦で返す。

呼び口は `計算する` 1 つ。法の表を引く口は `引く口.引く` 1 つ（芯に 1 つだけ）。形と使い方は README.md。
芯は Drive を開かない（受け取って返すだけ）。答え（過去の結果）を受ける口を持たない。
"""
from __future__ import annotations

from decimal import Decimal

from . import 要る値
from .引く口 import 欠け, 引く, 引いた, 表の誤り
from .形 import 仮, 確定, 確認済, 円, 数, 理由
from .支給控除 import 一人, 式が無い, 月額表の税額
from .賞与 import 賞与の一人

__all__ = ["計算する", "賞与を計算する", "引く", "引いた", "欠け", "表の誤り", "月額表の税額", "勤怠が無い"]

_鍵の列 = ("支給月", "会社", "NO")


def _鍵(r: dict) -> tuple[str, str, str]:
    return tuple(str(r.get(k, "")) for k in _鍵の列)


勤怠が無い = "月の数字が無い（勤怠を入れない人。役員のほかは勤怠の要らない式が無い）"


def 計算する(月の数字, *, 決まり: dict | None = None, 人: dict | None = None, 入力: dict | None = None, 置き場=None,
           支給月: str | None = None) -> dict:
    """支給控除を計算する。

    月の数字: 芯/集計 の `集計する` の返す物（{"行", "人", …}）か、その "行" の並び（1 人×1 項目の縦）。
    決まり: {(会社, NO): {`分野.名`: 値}}。その人のその月に効く会社の決まり（段の解決は手前で済ませる）。
    人: {(会社, NO): {`分野.名`: 値}}。マスタの人の値（決まりの上に重ねる）。
    入力: {(会社, NO): {部品の行の名: 値}}。部品の行の数量の元が `入力の値` の物（月の変動）。
    置き場: 法の表の置き場（既定は repo の 法の表/。試験だけ渡す）。
    支給月: 決まり・人に居て月の数字の無い人の支給月（省けば月の数字の支給月が 1 つの時それを使う）。
      月の数字の無い人（集計が `勤怠が無い` とした人も）は計算せず、差引支給額を値なしの仮で返し問いにする（黙って抜けない）。
      ただし `人.区分`＝役員 の人は勤怠の要らない役員報酬の式で計算する（勤怠なしで社保と源泉を引く）。
    `人.区分`＝委託・委託の併用 の人は委託分の式（委託.py）で 委託分の… の項目と 支払合計 を返す。

    返す物: {"行": 人×項目の行, "人": 人の状態の行, "人の状態": {(支給月, 会社, NO): 確認済|仮}（出口.関所.通す へそのまま渡す）,
             "問い": 確認の問い, "知らせ": 仮にしない知らせ, "法の線": 赤と知らせ}
    """
    決まり, 人の値, 入力 = 決まり or {}, 人 or {}, 入力 or {}
    if isinstance(月の数字, dict):
        集計の人 = {_鍵(p): p for p in 月の数字.get("人", [])}
        集計の行 = 月の数字.get("行", [])
    else:
        集計の人, 集計の行 = {}, list(月の数字)
    人たち: dict = {}
    for r in 集計の行:
        if r.get("項目") == "年休を取った日":
            人たち.setdefault(_鍵(r), {})
            continue
        人たち.setdefault(_鍵(r), {})[r["項目"]] = (数(r.get("値")), r.get("状態") or "", r.get("問い") or "")
    for k in 集計の人:
        人たち.setdefault(k, {})
    無い人 = {k for k, p in 集計の人.items() if p.get("勤怠が無い")}
    来た = {k[1:] for k in 人たち}
    外の人 = sorted({tuple(map(str, k)) for k in (*決まり, *人の値)} - 来た)
    月たち = {k[0] for k in 人たち}
    月 = 支給月 or (next(iter(月たち)) if len(月たち) == 1 else None)
    if 月 is not None:
        for 会社, NO in 外の人:
            人たち[(月, 会社, NO)] = {}
            無い人.add((月, 会社, NO))

    前の知らせ = [f"{会社} {NO}: {勤怠が無い}。支給月が決まらない（支給月= を渡す）" for 会社, NO in 外の人] if 外の人 and 月 is None else []
    return _回す(sorted(人たち), 決まり, 人の値, 集計の人,
                lambda 鍵, 値たち, 事前: 一人(鍵[0], 値たち, 人たち[鍵], 入力.get(鍵[1:]), 置き場, 事前),
                無い人=frozenset(無い人), 前の知らせ=前の知らせ)


def 賞与を計算する(賞与, *, 支給日: str, 決まり: dict | None = None, 人: dict | None = None,
                 前月の課税対象額: dict | None = None, 前の標準賞与額: dict | None = None, 置き場=None,
                 計算期間: dict | None = None) -> dict:
    """賞与の社保・雇保・源泉・差引支給額を計算する（賞与の額は会社が決めた額を受ける）。

    賞与: [{"会社", "NO", "額", "原本の名前"}]（支給一覧を人に結んだ後の行。結ぶのは入口・殻）。
    支給日: YYYY-MM-DD（標準賞与額の上限・雇保の率・源泉の表を引く日。行の 支給月 は `YYYY-MM-賞与`）。
    決まり・人: 計算する と同じ（社保・雇保・源泉の値を読む）。
    前月の課税対象額: {(会社, NO): 円}（前月の 計算する の `課税対象額`。無い人＝前月の給与が無い）。None＝渡されていない＝前月の給与なしで見当して仮。
    前の標準賞与額: {(会社, NO): 円}（同じ年度のこれより前の賞与の 標準賞与額（健保）の計。無い人は 0）。None＝渡されていない＝0 で見当して仮。
    計算期間: {(会社, NO): 月数 | {"始め", "終わり"}}（賞与の計算期間。任意）。源泉を月額表で出す人（前月の給与なし・10 倍超）だけが読み、
      法の表/源泉_賞与の月額表の月数 の境を超えれば ÷12×12 など。月額表で出す人に無ければ境までの月数で見当して源泉を仮＋問い。算出率の表の人は読まない。
    返す物: 計算する と同じ形。
    """
    from datetime import date
    決まり, 人の値 = 決まり or {}, 人 or {}
    日 = date.fromisoformat(支給日)
    支給月 = f"{支給日[:7]}-賞与"
    行 = {(str(r["会社"]), str(r["NO"])): r for r in 賞与}
    前月の理由 = 理由("前月の課税対象額が渡されていない", "前月の給与なし", "月額表で計算（÷・× の月数は 法の表/源泉_賞与の月額表の月数）",
                  "前月の 計算する の課税対象額を渡す")
    前の理由 = 理由("同じ年度の前の賞与の標準賞与額（健保）の計が渡されていない", "0", "前の賞与なしとして年度の上限を数えた",
                  "前の賞与の 標準賞与額（健保）を渡す")

    def 作る(鍵, 値たち, 事前):
        k = 鍵[1:]
        事前 = [(効く, r) for 効く, r in 事前 if not r.何が無いか.startswith(("「社保.標準報酬」", "「住民税.額」"))]
        if 前月の課税対象額 is None:
            事前.append(("源泉所得税", 前月の理由))
        if 前の標準賞与額 is None:
            事前.append(("健康保険・介護保険・子ども・子育て支援金・標準賞与額（健保）", 前の理由))
        前月 = (前月の課税対象額 or {}).get(k)
        return 賞与の一人(支給月, 日, 値たち, 行[k].get("額"), 行[k].get("原本の名前"), 数(前月) if 前月 is not None else None,
                       数((前の標準賞与額 or {}).get(k)) or Decimal(0), 置き場, 事前, (計算期間 or {}).get(k))

    return _回す([(支給月, *k) for k in sorted(行)], 決まり, 人の値, {}, 作る)


def _回す(鍵たち, 決まり: dict, 人の値: dict, 集計の人: dict, 作る, *, 無い人=frozenset(), 前の知らせ=()) -> dict:
    """人ごとに 作る(鍵, 値たち, 事前の理由) の 一人 を計算し、人×項目の縦・人の状態・問い（理由ごとに 1 問）にまとめる（計算する・賞与を計算する が使う）。"""
    問い, 番号 = [], {}
    行たち, 状態たち, 知らせ, 法の線 = [], [], [], []

    def 問いの番号(r: 理由, 人の鍵) -> str:
        if r not in 番号:
            番号[r] = f"計{len(番号) + 1}"
            問い.append({"番号": 番号[r], "何が無いか": r.何が無いか, "見当": r.見当, "見当の拠り所": r.拠り所,
                       "答え方の例": r.答え方の例, "人": [], "変わる項目": []})
        q = 問い[int(番号[r][1:]) - 1]
        if 人の鍵 not in q["人"]:
            q["人"].append(人の鍵)
        return 番号[r]

    知らせ += list(前の知らせ)

    def 値なしの仮(鍵, r: 理由, 拠り所: str):
        n = 問いの番号(r, 鍵[1:])
        q = 問い[int(n[1:]) - 1]
        if "全部" not in q["変わる項目"]:
            q["変わる項目"].append("全部")
        行たち.append({"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "項目": "差引支給額", "値": None, "単位": "円",
                     "状態": 仮, "出所": "", "見当": "", "見当の拠り所": 拠り所, "問いの番号": n})
        状態たち.append({"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "状態": 仮, "仮の数": 1})

    for 鍵 in 鍵たち:
        支給月, 会社, NO = 鍵
        値たち = {**決まり.get((会社, NO), {}), **人の値.get((会社, NO), {})}
        if 鍵 in 無い人 and 値たち.get("人.区分") != "役員":
            r = 理由(勤怠が無い, "", "月の数字が無い人は計算しない（役員のほかは勤怠の要らない式が無い）",
                    "この人の月の数字（勤怠）を渡す・勤怠を入れない人の式を決める")
            値なしの仮(鍵, r, r.拠り所)
            continue
        値たち, 事前 = 要る値.確かめる(値たち)
        x = 作る(鍵, 値たち, 事前)
        try:
            帳 = x.計算()
        except 式が無い as e:
            r = 理由(f"式が無い: {e}", "", "この芯に式がまだ無い（D8 が当てる）", "決まりの値を確かめる")
            値なしの仮(鍵, r, r.拠り所)
            continue
        仮の数 = 0
        for 名, y in 帳.項目.items():
            ns = [問いの番号(r, (会社, NO)) for r in y.理由たち]
            for n in ns:
                q = 問い[int(n[1:]) - 1]
                if 名 not in q["変わる項目"]:
                    q["変わる項目"].append(名)
            仮か = y.仮
            仮の数 += 仮か
            行たち.append({
                "支給月": 支給月, "会社": 会社, "NO": NO, "項目": 名,
                "値": 円(y.値) if y.値 is not None else None, "単位": "円",
                "状態": 仮 if 仮か else 確定, "出所": y.出所,
                "見当": (str(y.値) if y.値 is not None else "") if 仮か else "",
                "見当の拠り所": "・".join(r.拠り所 for r in y.理由たち if r.拠り所) if 仮か else "",
                "問いの番号": "・".join(dict.fromkeys(ns)),
            })
        集 = 集計の人.get(鍵)
        if 集 and 集.get("状態") not in (None, 確認済) and not (集.get("勤怠が無い") and 値たち.get("人.区分") == "役員"):
            仮の数 += 1
            知らせ.append(f"{会社} {NO}: 芯/集計 の状態が仮（集計の問いの答えまで出さない）")
        状態たち.append({"支給月": 支給月, "会社": 会社, "NO": NO, "状態": 仮 if 仮の数 else 確認済, "仮の数": 仮の数})
        知らせ += [f"{会社} {NO}: {t}" for t in x.知らせ]
        法の線 += [f"{会社} {NO}: {t}" for t in x.法の線の行]
    人の状態 = {(x["支給月"], x["会社"], x["NO"]): x["状態"] for x in 状態たち}
    return {"行": 行たち, "人": 状態たち, "人の状態": 人の状態, "問い": 問い, "知らせ": 知らせ, "法の線": 法の線}
