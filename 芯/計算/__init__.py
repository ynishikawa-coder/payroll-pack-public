_鍵の列 = ("支給月", "会社", "NO")


def _鍵(r: dict) -> tuple[str, str, str]:
    return tuple(str(r.get(k, "")) for k in _鍵の列)


勤怠が無い = "月の数字が無い（勤怠を入れない人。役員のほかは勤怠の要らない式が無い）"


def 計算する(月の数字, *, 決まり: dict | None = None, 人: dict | None = None, 入力: dict | None = None, 置き場=None,
           支給月: str | None = None) -> dict:
    """支給控除を計算する。

    月の数字: 芯/集計 の `集計する` の返す物（{"行", "人", …}）か、その "行" の並び（1 人×1 項目の縦）。
    決まり: {(会社, NO): {`分野.名`: 値}}。その人のその月に効く会社の決まり（段の解決は手前で済ませる）。
    人: {(会社, NO): {`分野.名`: 値}}。マスタの人の値（決まりの上に重ねる）。
    入力: {(会社, NO): {部品の行の名: 値}}。部品の行の数量の元が `入力の値` の物（月の変動）。
    置き場: 法の表の置き場（既定は repo の 法の表/。試験だけ渡す）。
    支給月: 決まり・人に居て月の数字の無い人の支給月（省けば月の数字の支給月が 1 つの時それを使う）。
      月の数字の無い人（集計が `勤怠が無い` とした人も）は計算せず、差引支給額を値なしの仮で返し問いにする（黙って抜けない）。
      ただし `人.区分`＝役員 の人は勤怠の要らない役員報酬の式で計算する（勤怠なしで社保と源泉を引く）。
    `人.区分`＝委託・委託の併用 の人は委託分の式（委託.py）で 委託分の… の項目と 支払合計 を返す。

    返す物: {"行": 人×項目の行, "人": 人の状態の行, "人の状態": {(支給月, 会社, NO): 確認済|仮}（出口.関所.通す へそのまま渡す）,
             "問い": 確認の問い, "知らせ": 仮にしない知らせ, "法の線": 赤と知らせ,
             "止めた": [{支給月, 会社, NO, 理由: ["必ず埋める欄が空: <名>", …]}]（計算しなかった人。差引支給額を値なしの仮で返す＝出口へ出ない）}
    必ず埋める欄（芯/設定の表.json の 必ず埋める＝人.区分・時間.制度・社保.加入・社保.徴収の月・雇保.加入・源泉.欄・源泉.扶養の数）が
    その人に要るのに空なら、その人は計算しない（黙って社員・甲・加入・通常で数えない。問いでなくマスタを埋める欠け）。
    """
    決まり, 人の値, 入力 = 決まり or {}, 人 or {}, 入力 or {}
    if isinstance(月の数字, dict):
        集計の人 = {_鍵(p): p for p in 月の数字.get("人", [])}
        集計の行 = 月の数字.get("行", [])
    else:
        集計の人, 集計の行 = {}, list(月の数字)
    人たち: dict = {}
    for r in 集計の行:
        if r.get("項目") == "年休を取った日":
            人たち.setdefault(_鍵(r), {})
            continue
        人たち.setdefault(_鍵(r), {})[r["項目"]] = (数(r.get("値")), r.get("状態") or "", r.get("問い") or "")
    for k in 集計の人:
        人たち.setdefault(k, {})
    無い人 = {k for k, p in 集計の人.items() if p.get("勤怠が無い")}
    来た = {k[1:] for k in 人たち}
    外の人 = sorted({tuple(map(str, k)) for k in (*決まり, *人の値)} - 来た)
    月たち = {k[0] for k in 人たち}
    月 = 支給月 or (next(iter(月たち)) if len(月たち) == 1 else None)
    if 月 is not None:
        for 会社, NO in 外の人:
            人たち[(月, 会社, NO)] = {}
            無い人.add((月, 会社, NO))

    前の知らせ = [f"{会社} {NO}: {勤怠が無い}。支給月が決まらない（支給月= を渡す）" for 会社, NO in 外の人] if 外の人 and 月 is None else []

    def 承知の差(鍵, 値たち, x, 帳) -> list[str]:
        """承知した食い違い（会社の決まり §1.4）の線ごとに、法の線ならいくらかと差額の知らせ（仮にしない）。
        率の線と集計の線は、その線の印だけを外し（集計の線は 芯/集計 が法の線で数え直した月の数字に替えて）計算し直した総支給額と比べる。
        最低賃金は 最低賃金の時間額との差×所定内の時間（1 円未満は切り上げ＝労働者に有利な向き）。"""
        数えた = (集計の人.get(鍵) or {}).get("法の線で数えた") or {}
        out = []
        for 線 in [k for k in 承知の印.承知できる線 if k in x.承知した or k in 数えた]:
            問い = x.承知の印.get(線) or 数えた[線].get("問い", "")
            if 線 == "最低賃金":
                会社, 法 = x.承知した[線]
                分 = (人たち[鍵].get("所定内") or (None,))[0] or 分数を小数に((x.月の所定時間の分数 or 0) * 60)
                差額 = ((法 - 会社) * 分 / 60).quantize(Decimal(1), rounding=ROUND_CEILING)
                out.append(f"承知した食い違い: 最低賃金（{問い}）＝時間あたり {会社} 円（法の線 {法} 円）を会社の額で計算した。"
                           f"法の線なら 所定内 {分} 分で 差額 {差額} 円")
                continue
            勤怠 = dict(人たち[鍵])
            for 語, v in (数えた.get(線) or {}).get("語", {}).items():
                勤怠[語] = (数(v), "確定", "")
            y = 一人(鍵[0], 承知の印.外す(値たち, 線), 勤怠, 入力.get(鍵[1:]), 置き場, ())
            何 = (f"会社の値 {x.承知した[線][0]}（法の線 {x.承知した[線][1]}）" if 線 in x.承知した else
                 "法の線で数えると " + "・".join(f"{k} {(人たち[鍵].get(k) or (0,))[0]}→{v}" for k, v in 数えた[線]["語"].items()))
            try:
                法の額 = y.計算().項目["総支給額"].値
            except (式が無い, 形の誤り) as e:
                out.append(f"承知した食い違い: {線}（{問い}）＝{何}を会社の値で計算した。法の線の額は出せない（{e}）")
                continue
            会社の額 = 帳.項目["総支給額"].値
            if 法の額 is None or 会社の額 is None:
                out.append(f"承知した食い違い: {線}（{問い}）＝{何}を会社の値で計算した。法の線の額は出せない（総支給額が無い）")
                continue
            重なり, 行の名 = _同じ時間を払う行(線, y, 帳, 人たち[鍵], x.載せた) if 線 in 率の線 else (Decimal(0), [])
            法の額 -= 重なり
            添え = (f"・同じ時間を数量に払う行「{'・'.join(行の名)}」の {円(重なり)} 円は法の線の率に含めた"
                   if 行の名 else "")
            out.append(f"承知した食い違い: {線}（{問い}）＝{何}を会社の値で計算した。"
                       f"法の線なら総支給額 {円(法の額)} 円（差額 {円(法の額 - 会社の額)} 円{添え}）")
        return out

    return _回す(sorted(人たち), 決まり, 人の値, 集計の人,
                lambda 鍵, 値たち, 事前: 一人(鍵[0], 値たち, 人たち[鍵], 入力.get(鍵[1:]), 置き場, 事前),
                無い人=frozenset(無い人), 前の知らせ=前の知らせ, 承知の差=承知の差)


# 承知の差で、率の線ごとに「その率を掛けた時間」を数量に含む月の数字の語（その語の時間に払う支給の行は、法の線の率の 1.0 などに当たる）
率の線 = {"割増.時間外の率": ("法定外残業", "残業（会社の数え方）"), "割増.45時間超の率": ("法定外残業", "残業（会社の数え方）"),
         "割増.60時間超の率": ("法定外残業", "残業（会社の数え方）", "60 時間超", "60 時間超（会社の数え方）"),
         "割増.休日の率": ("法定休日",), "割増.深夜の率": ("深夜",)}


def _同じ時間を払う行(線: str, y, 帳, 勤怠: dict, 載せた: dict | None = None) -> tuple[Decimal, list[str]]:
    """承知した率の線の時間を、会社が別の支給の行（数量の元 `勤怠の数:<語>`・語は 率の線[線]）で払っている分（円）と行の名。

    その行はその時間への会社の払い（時間外・休日なら 1.0 の分、深夜なら会社の加算）＝法の線ではその線の率の払い（1.25 などはその時間の賃金の全部・
    深夜の 0.25 は加算）に数える物なので、法の線で計算し直した総支給額からはこの分を引く
    （引かないと、時給×法定外残業 の行で 1.0 を払い率を 0 にした会社の差額が 1.25 倍で出る）。
    行の額のうち、その線の時間（y.割増の時間）が行の時間に占める分だけ（60 時間超の線なら 60 時間を超えた分だけ）。
    載せた: 芯が割増の賃金をその行へ載せた額（`割増.法定内残業の行`・`割増.時間外の基礎の行`＝{行: {元の項目: 額}}）。
    それは会社の別の払いでなく芯が数えた割増の一部（法の線で数え直した方にも載る）なので、行の額から除いて数える。"""
    時間 = y.割増の時間.get(線) or Decimal(0)
    if not 時間:
        return Decimal(0), []
    和, 名たち = Decimal(0), []
    for r in y.v.get("項目.行") or []:
        if r.get("支給か控除") != "支給" or r.get("名") not in 帳.項目:
            continue
        try:
            種, 語 = 一人.数量の語(r)
        except 式が無い:
            continue
        if 種 != "分" or 語 not in 率の線[線] or 一人.数量の引く数の語(r):
            continue
        分 = 数((勤怠.get(語) or (None,))[0]) or Decimal(0)
        額 = (帳.項目[r["名"]].値 or Decimal(0)) - sum(((載せた or {}).get(r["名"]) or {}).values(), Decimal(0))
        if not 分 or 額 <= 0:
            continue
        和 += 額 * min(Decimal(1), 時間 * 60 / 分)
        名たち.append(r["名"])
    return 和.quantize(Decimal(1), rounding=ROUND_FLOOR), 名たち   # 引く分は切り捨て（差額は労働者に有利な向き）


def 賞与を計算する(賞与, *, 支給日: str, 決まり: dict | None = None, 人: dict | None = None,
                 前月の課税対象額: dict | None = None, 前の標準賞与額: dict | None = None, 置き場=None,
                 計算期間: dict | None = None) -> dict:
    """賞与の社保・雇保・源泉・差引支給額を計算する（賞与の額は会社が決めた額を受ける）。

    賞与: [{"会社", "NO", "額", "原本の名前"}]（支給一覧を人に結んだ後の行。結ぶのは入口・殻）。
    支給日: YYYY-MM-DD（標準賞与額の上限・雇保の率・源泉の表を引く日。行の 支給月 は `YYYY-MM-賞与`）。
    決まり・人: 計算する と同じ（社保・雇保・源泉の値を読む）。
    前月の課税対象額: {(会社, NO): 円}（前月の 計算する の `課税対象額`。無い人＝前月の給与が無い）。None＝渡されていない＝前月の給与なしで見当して仮。
    前の標準賞与額: {(会社, NO): 円}（同じ年度のこれより前の賞与の 標準賞与額（健保）の計。無い人は 0）。None＝渡されていない＝0 で見当して仮。
    計算期間: {(会社, NO): 月数 | {"始め", "終わり"}}（賞与の計算期間。任意）。源泉を月額表で出す人（前月の給与なし・10 倍超）だけが読み、
      法の表/源泉_賞与の月額表の月数 の境を超えれば ÷12×12 など。月額表で出す人に無ければ境までの月数で見当して源泉を仮＋問い。算出率の表の人は読まない。
    返す物: 計算する と同じ形。
    """
    from datetime import date
    決まり, 人の値 = 決まり or {}, 人 or {}
    日 = date.fromisoformat(支給日)
    支給月 = 支給月の字.字にする(日.year, 日.month, "中", 賞与=True)
    行 = {(str(r["会社"]), str(r["NO"])): r for r in 賞与}
    前月の理由 = 理由("前月の課税対象額が渡されていない", "前月の給与なし", "月額表で計算（÷・× の月数は 法の表/源泉_賞与の月額表の月数）",
                  "前月の 計算する の課税対象額を渡す")
    前の理由 = 理由("同じ年度の前の賞与の標準賞与額（健保）の計が渡されていない", "0", "前の賞与なしとして年度の上限を数えた",
                  "前の賞与の 標準賞与額（健保）を渡す")

    def 作る(鍵, 値たち, 事前):
        k = 鍵[1:]
        事前 = [(効く, r) for 効く, r in 事前 if not r.何が無いか.startswith(("「社保.標準報酬」", "「住民税.額」"))]
        if 前月の課税対象額 is None:
            事前.append(("源泉所得税", 前月の理由))
        if 前の標準賞与額 is None:
            事前.append(("健康保険・介護保険・子ども・子育て支援金・標準賞与額（健保）", 前の理由))
        前月 = (前月の課税対象額 or {}).get(k)
        return 賞与の一人(支給月, 日, 値たち, 行[k].get("額"), 行[k].get("原本の名前"), 数(前月) if 前月 is not None else None,
                       数((前の標準賞与額 or {}).get(k)) or Decimal(0), 置き場, 事前, (計算期間 or {}).get(k))

    return _回す([(支給月, *k) for k in sorted(行)], 決まり, 人の値, {}, 作る)


def _回す(鍵たち, 決まり: dict, 人の値: dict, 集計の人: dict, 作る, *, 無い人=frozenset(), 前の知らせ=(), 承知の差=None) -> dict:
    """人ごとに 作る(鍵, 値たち, 事前の理由) の 一人 を計算し、人×項目の縦・人の状態・問い（理由ごとに 1 問）にまとめる（計算する・賞与を計算する が使う）。"""
    問い, 番号 = [], {}
    行たち, 状態たち, 知らせ, 法の線, 止めた = [], [], [], [], []

    def 問いの番号(r: 理由, 人の鍵) -> str:
        if r not in 番号:
            番号[r] = f"計{len(番号) + 1}"
            問い.append({"番号": 番号[r], "何が無いか": r.何が無いか, "見当": r.見当, "見当の拠り所": r.拠り所,
                       "答え方の例": r.答え方の例, "人": [], "変わる項目": []})
        q = 問い[int(番号[r][1:]) - 1]
        if 人の鍵 not in q["人"]:
            q["人"].append(人の鍵)
        return 番号[r]

    知らせ += list(前の知らせ)

    def 値なしの仮(鍵, r: 理由, 拠り所: str):
        n = 問いの番号(r, 鍵[1:])
        q = 問い[int(n[1:]) - 1]
        if "全部" not in q["変わる項目"]:
            q["変わる項目"].append("全部")
        行たち.append({"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "項目": "差引支給額", "値": None, "単位": "円",
                     "状態": 仮, "出所": "", "見当": "", "見当の拠り所": 拠り所, "問いの番号": n})
        状態たち.append({"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "状態": 仮, "仮の数": 1})

    for 鍵 in 鍵たち:
        支給月, 会社, NO = 鍵
        値たち = {**決まり.get((会社, NO), {}), **人の値.get((会社, NO), {})}
        if 鍵 in 無い人 and not 区分だけか(値たち, "役員"):
            r = 理由(勤怠が無い, "", "月の数字が無い人は計算しない（役員のほかは勤怠の要らない式が無い）",
                    "この人の月の数字（勤怠）を渡す・勤怠を入れない人の式を決める")
            値なしの仮(鍵, r, r.拠り所)
            continue
        集 = 集計の人.get(鍵)
        集計の外れ = (集.get("設定の外れ") or ()) if 集 and 集.get("状態") == "仮" else ()
        元の値たち = 値たち
        値たち, 事前 = 要る値.確かめる(値たち, 集計の外れ)
        欠け = 要る値.必ずの欠け(元の値たち, 値たち)
        if 欠け:   # 必ず埋める欄が空＝黙って既定で数えない。その人を計算せず出口へ出さない（問いでなくマスタを埋める欠け＝決定 9・21）
            止めた.append({"支給月": 支給月, "会社": 会社, "NO": NO, "理由": 欠け})
            # 欠けは問いにしない。同じ人のほかの仮の理由（選べる値の外の字など）は問いのまま残す（埋めた後に重ねて聞かない）
            ns = list(dict.fromkeys(問いの番号(r, (会社, NO)) for _, r in 事前))
            for n in ns:
                q = 問い[int(n[1:]) - 1]
                if "全部" not in q["変わる項目"]:
                    q["変わる項目"].append("全部")
            行たち.append({"支給月": 支給月, "会社": 会社, "NO": NO, "項目": "差引支給額", "値": None, "単位": "円",
                         "状態": 仮, "出所": "", "見当": "", "見当の拠り所": "・".join(欠け), "問いの番号": "・".join(ns)})
            状態たち.append({"支給月": 支給月, "会社": 会社, "NO": NO, "状態": 仮, "仮の数": 1})
            知らせ.append(f"{会社} {NO}: 計算しない（{'・'.join(欠け)}。マスタを埋めてから計算する）")
            continue
        x = 作る(鍵, 値たち, 事前)
        try:
            帳 = x.計算()
        except 式が無い as e:
            r = 理由(f"式が無い: {e}", "", "この芯に式がまだ無い（D8 が当てる）", "決まりの値を確かめる")
            値なしの仮(鍵, r, r.拠り所)
            continue
        except 形の誤り as e:   # 読めない値で月を止めない（その人だけ値なしの仮＋問い）
            r = 理由(f"決まりの値が読めない: {e}", "", "値が読めない人は計算しない（ほかの人は計算する）",
                    "その値を選べる値の形で書き直す")
            値なしの仮(鍵, r, r.拠り所)
            continue
        仮の数 = 0
        for 名, y in 帳.項目.items():
            ns = [問いの番号(r, (会社, NO)) for r in y.理由たち]
            for n in ns:
                q = 問い[int(n[1:]) - 1]
                if 名 not in q["変わる項目"]:
                    q["変わる項目"].append(名)
            仮か = y.仮
            仮の数 += 仮か
            行たち.append({
                "支給月": 支給月, "会社": 会社, "NO": NO, "項目": 名,
                "値": 円(y.値) if y.値 is not None else None, "単位": "円",
                "状態": 仮 if 仮か else 確定, "出所": y.出所,
                "見当": (str(y.値) if y.値 is not None else "") if 仮か else "",
                "見当の拠り所": "・".join(r.拠り所 for r in y.理由たち if r.拠り所) if 仮か else "",
                "問いの番号": "・".join(dict.fromkeys(ns)),
            })
        集 = 集計の人.get(鍵)
        if 集 and 集.get("状態") not in (None, 確認済) and not (集.get("勤怠が無い") and 区分だけか(値たち, "役員")):
            仮の数 += 1
            知らせ.append(f"{会社} {NO}: 芯/集計 の状態が仮（集計の問いの答えまで出さない）")
        状態たち.append({"支給月": 支給月, "会社": 会社, "NO": NO, "状態": 仮 if 仮の数 else 確認済, "仮の数": 仮の数})
        知らせ += [f"{会社} {NO}: {t}" for t in x.知らせ]
        if 承知の差 is not None:
            知らせ += [f"{会社} {NO}: {t}" for t in 承知の差(鍵, 値たち, x, 帳)]
        法の線 += [f"{会社} {NO}: {t}" for t in x.法の線の行]
    人の状態 = {(x["支給月"], x["会社"], x["NO"]): x["状態"] for x in 状態たち}
    return {"行": 行たち, "人": 状態たち, "人の状態": 人の状態, "問い": 問い, "知らせ": 知らせ, "法の線": 法の線, "止めた": 止めた}
