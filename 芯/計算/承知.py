"""承知した食い違いの印（`法の線.承知`）の読み方。芯/集計 と 芯/計算 の両方が読む（読み方はここ 1 か所）。

会社の今の払い方が法の線を下回る時、事務所が承知した食い違いに限り、会社の値のまま計算して出口へ出す（会社の決まり §1.1・§1.4）。
印の無い線は今のまま法の線の値で仮（⟦鍵:給与計算/足りない時は仮で計算し出さない⟧）。
印の形（会社・勤務の型・人の段＝型の版 6。下の段の印は上の段の印をまるごと上書きする＝人は段の解決が手前で重ね、日ごとの勤務の型は `印の値` が読む）:
  {線の名: 問いの番号}（例 {"割増.時間外の率": "問12", "最低賃金": "問13"}）
  または [{"線": 線の名, "問い": 問いの番号}, …]
  または字 `割増.時間外の率=問12、最低賃金=問13`（Drive のセルにそのまま書く形。区切りは 、 , 改行・= は ＝ でもよい）
問いの番号＝事務所が会社に聞いた「質問と回答」の問いの番号（承知の出所）。番号の無い線・知らない線は承知に数えない（法の線で仮）。
法の値はここに書かない（線の名だけ）。
"""
from __future__ import annotations

import re

項目 = "法の線.承知"
基礎の線 = "割増.基礎に入る"   # 37 条 5 項・労基則 21 条（検査・設問・支給控除 が同じ名で読む）

# 芯/集計 が日・週を数える所で読む線（法の線で数え直した月の数字との差を 芯/計算 へ渡す）
集計の線 = (
    "時間.日の所定",           # 通常の制度で日の所定が日の法定を超える（32 条）＝所定までを所定内に数える
    "時間.週の法定",           # 週の法定が法の線を超える（32 条・労基則 25 条の 2）
    "時間.打刻の丸めの向き",   # 日ごとに労働時間を短くする丸め（24 条の全額払い）
    "割増.深夜の時間帯",       # 深夜帯が法の線より狭い（37 条 4 項）
    "時間.変形の途中入退社",   # 1 年変形の途中で入社・退職した人を清算しない（32 条の 4 の 2）
)
# 芯/計算 が率・単価を当てる所で読む線
計算の線 = (
    "割増.時間外の率", "割増.45時間超の率", "割増.60時間超の率", "割増.休日の率", "割増.深夜の率",   # 37 条・割増令（0＝払わない）
    "割増.基礎に入る",         # 37 条 5 項・労基則 21 条（除けない手当を割増の単価から除く＝一律の住宅手当・皆勤手当）
    "最低賃金",                # 最低賃金法 4 条
    "手当.皆勤の条件",         # 労基法附則 136 条（年休を取った月に皆勤の手当を払わない）
)
承知できる線 = 集計の線 + 計算の線


def 読む(値) -> tuple[dict[str, str], list[str]]:
    """印の値 → ({線: 問いの番号}, [読めない訳])。読めない線は返す dict に入れない（承知に数えない）。"""
    if 値 is None or 値 == "" or 値 == {} or 値 == []:
        return {}, []
    組 = []
    if isinstance(値, dict):
        組 = list(値.items())
    elif isinstance(値, list):
        for x in 値:
            if isinstance(x, dict):
                組.append((x.get("線"), x.get("問い")))
            else:
                組.append((x, None))
    elif isinstance(値, str):
        for 片 in (w.strip() for w in re.split(r"[、,，\n]", 値)):
            if not 片:
                continue
            線, 印, 問い = 片.replace("＝", "=").partition("=")
            組.append((線, 問い if 印 else None))
    else:
        return {}, [f"{項目}「{値}」が {{線: 問いの番号}} の形でない（承知に数えない＝法の線で仮）"]
    out, 訳 = {}, []
    for 線, 問い in 組:
        線, 問い = str(線 or "").strip(), str(問い or "").strip()
        if 線 not in 承知できる線:
            訳.append(f"{項目} の線「{線}」は承知できる線の外（{'・'.join(承知できる線)}）＝承知に数えない")
        elif not 問い:
            訳.append(f"{項目} の線「{線}」に問いの番号（質問と回答の出所）が無い＝承知に数えない（法の線で仮）")
        else:
            out[線] = 問い
    return out, 訳


def _空(v) -> bool:
    return v is None or (isinstance(v, str) and not v.strip())


def 外す(値たち: dict, 線: str) -> dict:
    """値たちから 1 つの線の印を外した写し（法の線で数え直す時に使う）。勤務の型の段の印も外す。
    空の印（None・空白の字）はそのまま残す（`印の値` の約束＝空なら上の段の印。{} に替えると上の段の印を消してしまう）。"""
    def 外した(v):
        印, _ = 読む(v)
        印.pop(線, None)
        return 印

    out = dict(値たち)
    if 項目 in out and not _空(out[項目]):
        out[項目] = 外した(out[項目])
    型たち = out.get("勤務の型")
    if isinstance(型たち, dict):
        out["勤務の型"] = {k: ({**t, 項目: 外した(t[項目])} if isinstance(t, dict) and 項目 in t and not _空(t[項目]) else t)
                       for k, t in 型たち.items()}
    return out


def 印の値(値たち: dict, 型: str | None = None):
    """その日の印の値（芯/集計 の `決まり.引く(項目, 型)` と同じ読み）: 型の印が空でなければ型の印、空なら段を解いた 1 つの値の印。
    下の段の印は上の段の印をまるごと上書きする（足し合わせない）。"""
    if 型:
        t = (値たち.get("勤務の型") or {}).get(型) if isinstance(値たち.get("勤務の型"), dict) else None
        v = t.get(項目) if isinstance(t, dict) else None
        if not _空(v):
            return v
    return 値たち.get(項目)


def 線たち(値たち: dict, 日の型たち=None) -> dict[str, str]:
    """どこかの日に効く印の全部（{線: 問いの番号}。数え直す線を決めるのに使う）。

    日ごとの読み（`印の値`＝芯/集計 の `承知か`）と同じく、日ごとに効く 1 つの段の印だけを数え、その和を返す
    （上の段と下の段の印を足し合わせない）。問いの番号はその日に効く段の物（先に出た日の物）。
    日の型たち: 数える日の勤務の型の名の並び（空・None＝型の無い日）。省けば、段を解いた値と勤務の型の全部の型の日が在り得るとして数える。"""
    if 日の型たち is None:
        型たち = 値たち.get("勤務の型") if isinstance(値たち.get("勤務の型"), dict) else {}
        日の型たち = [None, *型たち]
    out: dict[str, str] = {}
    for 型 in dict.fromkeys(日の型たち):
        for k, q in 読む(印の値(値たち, 型))[0].items():
            out.setdefault(k, q)
    return out
