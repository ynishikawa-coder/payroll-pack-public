"""給与から引けない社保の 3 行（社保の引けない額・社保の立て替えの返し・社保の立て替えの残り）を出口で正しく扱う（作り物の 1 人）。

- 社保の引けない額・社保の立て替えの返し は芯の作る名＝⑥つなぎ の会社の行（欄.<名>）で給与ソフトの欄へ載る。
- 社保の立て替えの残り は残高（支給でも控除でもない）＝取り込み・支給控除一覧・突き合わせに出さない（月次が台帳へ回す）。
  欄の対応で残りに欄を当てたら止める。
"""
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "計算"))

from 作る_計算 import 人, 回す, 決まり, 値たち  # noqa: E402
from 出口 import 書き口, 形, 突き合わせ, 関所  # noqa: E402

月 = "2027-02"
休職の勤怠 = {"出勤日数": "0", "欠勤": "20", "総労働": "0", "所定内": "0", "法定内残業": "0", "法定外残業": "0", "深夜": "0",
          "遅刻早退": "0"}
形の値 = {"名": "作り物の給与ソフト", "鍵の欄": "NO", "氏名の欄": "氏名", "後ろの欄": "メモ", "文字コード": "utf-8"}


def _つなぎ(*名と欄):
    return [{"会社": "C1", "NO": "", "側": "出口", "道具": "作り物の給与ソフト", "その道具での番号": f"欄.{名}", "その道具での名": 欄}
            for 名, 欄 in 名と欄]


def _対応(*名と欄):
    return 形.欄の対応を組む("C1", "作り物の給与ソフト", (), _つなぎ(("差引支給額", "差引支給額"), *名と欄))


def _通す(tmp, 休職か: bool, 残り: str):
    決 = 決まり(**{"社保.引けない月の本人負担": "立て替えて復帰後に引く",
                  "項目.行": [r for r in 決まり()["項目.行"] if r["名"] != "親睦会費"]})
    r = 回す(tmp, 決=決, 人の値=人(**({"項目.人の額": {"基本給": "280000", "職務手当": "20000", "通勤手当": "0"}} if 休職か else {})),
           上書き=休職の勤怠 if 休職か else None, 入力={("C1", "0001"): {"社保の立て替えの残り": 残り}})
    assert r["人"][0]["状態"] != "仮"
    return 関所.通す(r["行"], r["人の状態"]), 値たち(r)


def _列(物, 欄):
    return 物.表[1][list(物.表[0]).index(欄)]


def test_休職の月は引けない額が欄に載り残りは出さない(tmp_path):
    通, v = _通す(tmp_path, True, "1000")
    assert v["社保の引けない額"] > 0 and v["社保の立て替えの残り"] == v["社保の引けない額"] + 1000
    取 = 書き口.取り込み(通, "C1", 月, _対応(("社保の引けない額", "社保立替")), 形の値)
    assert _列(取, "社保立替") == str(v["社保の引けない額"])
    assert "社保の立て替えの残り" not in 取.載せなかった項目        # 残高は載せない物の一覧にも出さない（出す物でない）
    一覧 = 書き口.支給控除一覧(通, "C1", 月)[0]
    名たち = [row[0] for row in 一覧.表]
    assert "社保の引けない額" in 名たち and "社保の立て替えの残り" not in 名たち


def test_復帰の月は返しが欄に載る(tmp_path):
    通, v = _通す(tmp_path, False, "50000")
    assert v["社保の立て替えの返し"] == 50000 and v["社保の立て替えの残り"] == 0
    取 = 書き口.取り込み(通, "C1", 月, _対応(("社保の立て替えの返し", "立替の返し")), 形の値)
    assert _列(取, "立替の返し") == "50000"
    assert "社保の立て替えの残り" not in 取.載せなかった項目
    assert "社保の立て替えの残り" not in [row[0] for row in 書き口.支給控除一覧(通, "C1", 月)[0].表]


def test_残りに欄を当てたら止める(tmp_path):
    """注入: 残高を給与ソフトの欄へ渡す・受けて照らす対応。"""
    通, _ = _通す(tmp_path, True, "0")
    対応 = _対応(("社保の立て替えの残り", "立替の残り"))
    with pytest.raises(ValueError, match="立て替えの残高"):
        書き口.取り込み(通, "C1", 月, 対応, 形の値)
    with pytest.raises(ValueError, match="立て替えの残高"):
        突き合わせ.突き合わせる(通, [], 対応)


def test_突き合わせは残りを照らさなかった項目に出さない(tmp_path):
    通, _ = _通す(tmp_path, True, "0")
    結果 = 突き合わせ.突き合わせる(通, [], _対応(("社保の引けない額", "社保立替")))
    assert "社保の立て替えの残り" not in 結果.照らさなかった項目
