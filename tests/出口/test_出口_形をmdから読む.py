"""給与ソフトの形を 事務所のルール.md の「## 1 給与ソフトと取り込みの形」から読む・出す物の時間の書き方を決まりから決める。

根: 出す.py が出口へ 名たち だけを渡し、取り込み（給与ソフトの形）と支給控除一覧（時間の書き方）が月次の奥で
「出口 に 取り込み・支給控除一覧 が無い」と止まっていた（形の置き場は在るのに読む口が無かった）。
注入: 共通の形・会社の小見出しの上書き・説明の箇条書きを読まない・同じ鍵 2 つ／合う小見出し 2 つ／節が無いは止める。
時間の書き方は会社のマスタ（決まり）から・人ごとに分かれたら止める・無ければ項目の辞書の既定。値は全部作り物。"""
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))

import 月次  # noqa: E402
from 出口 import 形  # noqa: E402

md = """# 事務所のルール（作り物）

## 1 給与ソフトと取り込みの形

何を書くか: 説明の行（読まない）。

- 名: 作り物の給与ソフト
- 鍵の欄: 作り物の番号
- 文字コード: utf-8
- 作り物の説明: 読まない

### 作り物の他社

- 鍵の欄: 作り物の他社の番号

### 作り物の三社

- 文字コード: cp932

## 2 事務所の既定

- 名: 読まない
"""


def test_共通の形を読み説明の箇条書きと次の節は読まない():
    assert 形.形をmdから読む(md) == {"名": "作り物の給与ソフト", "鍵の欄": "作り物の番号", "文字コード": "utf-8"}
    assert 形.形を組む(形.形をmdから読む(md)).名 == "作り物の給与ソフト"


def test_会社の小見出しは呼び名か顧客IDで合えば共通を上書きする():
    assert 形.形をmdから読む(md, ("作り物の他社", None))["鍵の欄"] == "作り物の他社の番号"
    assert 形.形をmdから読む(md, ("別の呼び名", "作り物の三社"))["文字コード"] == "cp932"
    assert 形.形をmdから読む(md, ("合わない会社", "C-9999"))["鍵の欄"] == "作り物の番号"


@pytest.mark.parametrize("字, 会社たち, 訳", [
    ("# 作り物\n\n## 2 事務所の既定\n", (), "節が無い"),
    ("## 1 給与ソフトと取り込みの形\n\n- 名: 甲\n- 名: 乙\n", (), "名 が 2 つ"),
    (md, ("作り物の他社", "作り物の三社"), "2 つ合う"),
])
def test_読めない形は止まる(字, 会社たち, 訳):
    with pytest.raises(ValueError, match=訳):
        形.形をmdから読む(字, 会社たち)


def test_時間の書き方は決まりから読み人ごとに分かれたら止まり無ければ既定():
    assert 月次._時間の書き方({"0001": {"出口.時間の書き方": "10進（h.hh）"}, "0002": {"出口.時間の書き方": "10進"}}) == "10進"
    with pytest.raises(ValueError, match="分かれる"):
        月次._時間の書き方({"0001": {"出口.時間の書き方": "10進"}, "0002": {"出口.時間の書き方": "60進"}})
    with pytest.raises(ValueError):
        月次._時間の書き方({"0001": {"出口.時間の書き方": "作り物の書き方"}})
    assert 月次._時間の書き方({"0001": {}}) in 形.時間の書き方たち
