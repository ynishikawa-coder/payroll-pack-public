"""出す物の版は、同じ物・会社・支給月の前の版（2_出す物/ と 9_履歴/ の名）の最大の次。前の版の名を渡さない時は止める
（黙って v1 にしない）。作り物の会社だけ（注入の試験）。

根（2026-11-19）: 前の仕組みで 2_出す物/ に v6・9_履歴/ に v1〜v5 を出した置き場へ、殻が前の版の名を渡さずに v1 を付けかけた。
"""
import pytest

from 出口 import 名と版, 書き口, 関所
import tests.出口.出口_作り物 as 作

会社, 月 = "作り物の会社", "2026-11"


def test_前の版が2つの置き場に在れば最大の次で_今の版は履歴へ移す():
    今 = [f"取り込み_{会社}_{月}_v6", f"支給控除一覧_雇用_{会社}_{月}_v2", "別の物.csv"]
    履歴 = [f"取り込み_{会社}_{月}_v{n}" for n in range(1, 6)] + [f"取り込み_{会社}_2026-10_v9"]
    n = 名と版.名を付ける("取り込み", 会社, 月, 今, 履歴)
    assert n.名 == f"取り込み_{会社}_{月}_v7" and n.版 == 7 and n.履歴へ移す == (f"取り込み_{会社}_{月}_v6",)
    n = 名と版.名を付ける("支給控除一覧_雇用", 会社, 月, 今, 履歴)
    assert n.名 == f"支給控除一覧_雇用_{会社}_{月}_v3" and n.履歴へ移す == (f"支給控除一覧_雇用_{会社}_{月}_v2",)
    # 履歴にだけ在る（今の版を移した後）・拡張子つきでも番号を戻さない
    assert 名と版.名を付ける("取り込み", 会社, 月, [], [f"取り込み_{会社}_{月}_v8.csv"]).版 == 9


def test_前の版が無い置き場は空の並びを渡して_v1():
    assert 名と版.名を付ける("取り込み", 会社, 月, [], []).名 == f"取り込み_{会社}_{月}_v1"


@pytest.mark.parametrize("今, 履歴", [(None, []), ([], None), (None, None), (f"取り込み_{会社}_{月}_v6", []), ([], {"取り込み": []})])
def test_前の版の名を並びで渡さなければ止める(今, 履歴):
    with pytest.raises(ValueError, match="名の並びで渡す"):
        名と版.名を付ける("取り込み", 会社, 月, 今, 履歴)
    with pytest.raises(TypeError):
        名と版.名を付ける("取り込み", 会社, 月)   # 引数を省けない


def test_書き口も前の版の名を渡さなければ止め_置き場の名の並びをそのまま受ける():
    通 = 関所.通す(作.行たち)
    with pytest.raises(ValueError, match="名の並びで渡す"):
        書き口.取り込み(通, "9", 作.月, 作.対応, {**作.形の値, "文字コード": "utf-8"}, "60進")
    with pytest.raises(ValueError, match="名の並びで渡す"):
        書き口.支給控除一覧(通, "9", 作.月, 委託の人=作.委託)
    with pytest.raises(ValueError, match="名の並びで渡す"):   # 物ごとの dict に出す物の鍵が欠けても止める
        書き口.支給控除一覧(通, "9", 作.月, 委託の人=作.委託, 今ある名={"支給控除一覧_雇用": []}, 履歴にある名={"支給控除一覧_雇用": []})
    置き場 = [f"支給控除一覧_雇用_9_{作.月}_v2", f"支給控除一覧_業務委託_9_{作.月}_v4", f"取り込み_9_{作.月}_v6"]
    雇用, 委託 = 書き口.支給控除一覧(通, "9", 作.月, 委託の人=作.委託, 今ある名=置き場, 履歴にある名=[])
    assert (雇用.名.版, 委託.名.版) == (3, 5)
    assert 書き口.取り込み(通, "9", 作.月, 作.対応, {**作.形の値, "文字コード": "utf-8"}, "60進", 今ある名=置き場, 履歴にある名=[f"取り込み_9_{作.月}_v1"]).名.版 == 7
