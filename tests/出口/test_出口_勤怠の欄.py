"""勤怠の欄（集計の数の行）を計算の行と一緒に関所へ渡す道。日付など数でない行は関所で止めずに出さない物へ分ける（作り物の値だけ）。"""
from decimal import Decimal

import pytest

from 出口 import 関所

人 = {"支給月": "2027-02", "会社": "9", "NO": "0001", "勤怠の表記": "作り物の人"}


def 集(項目, 値, 単位, 状態="確定", 問い=""):
    return {**人, "項目": 項目, "値": 値, "単位": 単位, "状態": 状態, "出所": "作り物.csv", "印": "", "見当": "",
            "見当の拠り所": "", "問い": 問い}


計算の行 = [{**{k: 人[k] for k in ("支給月", "会社", "NO")}, "項目": "差引支給額", "値": 250000, "単位": "円", "状態": "確定",
           "出所": "", "見当": "", "見当の拠り所": "", "問いの番号": ""}]
集計の行 = [集("出勤日数", Decimal("19.5"), "日"), 集("法定外残業", 600, "分"), 集("年休（半日）", 1, "回"),
          集("年休を取った日", "2027-01-12", "日付"), 集("年休を取った日", "2027-01-20", "日付")]


def test_日付の行は関所へ流さず出さない物に分ける():
    渡す, 出さない = 関所.勤怠の行を分ける(集計の行, {}, None, {})
    assert [r["項目"] for r in 渡す] == ["出勤日数", "法定外残業", "年休（半日）"]
    assert [r["値"] for r in 出さない] == ["2027-01-12", "2027-01-20"]


def test_混ぜたままでは関所が止まる_分ければ通る():
    with pytest.raises(ValueError):
        関所.通す(計算の行 + 集計の行, {})
    渡す, _ = 関所.勤怠の行を分ける(集計の行, {}, None, {})
    通 = 関所.通す(計算の行 + 渡す, {("2027-02", "9", "0001"): "確認済"})
    assert {r.項目: r.値 for r in 通.行たち} == {"差引支給額": 250000, "出勤日数": Decimal("19.5"),
                                               "法定外残業": 600, "年休（半日）": 1}


def test_勤怠の欄に仮があれば人ごと外し集計の問いを出す():
    渡す, _ = 関所.勤怠の行を分ける([集("法定外残業", 600, "分", "仮", "問1、問2")], {}, None, {})
    通 = 関所.通す(計算の行 + 渡す, {})
    assert 通.行たち == () and 通.外した人たち[0].問いの番号 == ("問1", "問2")


def test_単位の無い行と数でない値は出さない物():
    渡す, 出さない = 関所.勤怠の行を分ける([集("出勤日数", "十", "日"), {**集("総労働", 9600, ""), "単位": None}], {}, None, {})
    assert 渡す == [] and len(出さない) == 2


def test_集計の返す物をそのまま分けられる():
    import sys
    from pathlib import Path
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "集計"))
    from 作る_集計 import 数える, 既定の決まり, 月
    x = 数える(*月(), 既定の決まり(**{"時間.休憩の表": ["12:00〜13:00"]}))
    渡す, 出さない = 関所.勤怠の行を分ける(x["行"], {}, None, {})
    assert {r["単位"] for r in 渡す} <= {"日", "分", "回"} and all(r["単位"] == "日付" for r in 出さない)
    通 = 関所.通す(渡す, {(p["支給月"], p["会社"], p["NO"]): p["状態"] for p in x["人"]})
    assert len(通.行たち) == len(渡す) and 通.外した人たち == ()


# ---- 出口.実働の上限（人の段・出口の欄だけ・型の版 18）----
頭 = [{"支給月": "2027-02", "会社": "9", "NO": "0001", "分": 9000}]   # 芯/集計 が日ごとに所定で頭打ちにした実働の和


def _実働(決まり=None, 頭打ち=頭, 状態="確定"):
    決まり = {} if 決まり is None else 決まり
    行 = [集("総労働", 9600, "分", 状態=状態), 集("所定内", 8880, "分"), 集("法定外残業", 600, "分")]
    渡す, _ = 関所.勤怠の行を分ける(行, 決まり, 頭打ち, {})
    return {r["項目"]: r for r in 渡す}


def test_実働の上限が空かなしなら総労働のまま():
    for 決 in (None, {}, {("9", "0001"): {}}, {("9", "0001"): {"出口.実働の上限": "なし"}}):
        assert _実働(決)["総労働"]["値"] == 9600


def test_実働の上限が所定なら総労働の欄を日ごとに頭打ちにした実働で書く():
    r = _実働({("9", "0001"): {"出口.実働の上限": "所定"}})
    assert r["総労働"]["値"] == 9000 and r["総労働"]["状態"] == "確定"     # 前 9,600 分 → 後 9,000 分（所定内 8,880 分は使わない）
    assert r["法定外残業"]["値"] == 600 and r["所定内"]["値"] == 8880
    assert _実働({("9", "0002"): {"出口.実働の上限": "所定"}})["総労働"]["値"] == 9600   # ほかの人の値は効かない


def test_頭打ちの実働が無い人と知らない値は総労働のまま仮_総労働の仮は残る():
    assert _実働({("9", "0001"): {"出口.実働の上限": "所定"}}, 頭打ち=[])["総労働"]["状態"] == "仮"
    assert _実働({("9", "0001"): {"出口.実働の上限": "週40"}})["総労働"]["状態"] == "仮"
    assert _実働({("9", "0001"): {"出口.実働の上限": "所定"}}, 状態="仮")["総労働"]["状態"] == "仮"


def test_委託の併用の雇用分の出勤日数で出勤日数の欄を書く():
    """段の解決の 入力 の 委託.雇用分の出勤日数（型の版 19）が在る人だけ、出勤日数 の行の値をその日数にする（ほかの行・人は変えない）。"""
    他 = {**集("出勤日数", Decimal("22"), "日"), "NO": "0002"}
    行 = [*集計の行, 他]
    渡す, _ = 関所.勤怠の行を分ける(行, {}, None, 入力={("9", "0001"): {"委託.雇用分の出勤日数": "20", "委託.雇用分の出勤時間": "127:30"}})
    値 = {(r["NO"], r["項目"]): r["値"] for r in 渡す}
    assert 値[("0001", "出勤日数")] == Decimal("20") and 値[("0002", "出勤日数")] == Decimal("22")
    assert 値[("0001", "法定外残業")] == 600
    assert next(r for r in 渡す if r["NO"] == "0001" and r["項目"] == "出勤日数")["出所"].startswith("委託.雇用分の出勤日数")
    # 仮の行は状態をそのまま（関所が外す）・見当も同じ日数
    渡す, _ = 関所.勤怠の行を分ける([集("出勤日数", Decimal("23"), "日", "仮")], {}, None, 入力={("9", "0001"): {"委託.雇用分の出勤日数": "20.5"}})
    assert 渡す[0]["状態"] == "仮" and 渡す[0]["値"] == 渡す[0]["見当"] == Decimal("20.5")
    # 入力が空なら行はそのまま
    assert 関所.勤怠の行を分ける(集計の行, {}, None, {})[0] == [r for r in 集計の行 if r["単位"] != "日付"]
