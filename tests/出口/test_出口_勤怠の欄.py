"""勤怠の欄（集計の数の行）を計算の行と一緒に関所へ渡す道。日付など数でない行は関所で止めずに出さない物へ分ける（作り物の値だけ）。"""
from decimal import Decimal

import pytest

from 出口 import 関所

人 = {"支給月": "2027-02", "会社": "9", "NO": "0001", "勤怠の表記": "作り物の人"}


def 集(項目, 値, 単位, 状態="確定", 問い=""):
    return {**人, "項目": 項目, "値": 値, "単位": 単位, "状態": 状態, "出所": "作り物.csv", "印": "", "見当": "",
            "見当の拠り所": "", "問い": 問い}


計算の行 = [{**{k: 人[k] for k in ("支給月", "会社", "NO")}, "項目": "差引支給額", "値": 250000, "単位": "円", "状態": "確定",
           "出所": "", "見当": "", "見当の拠り所": "", "問いの番号": ""}]
集計の行 = [集("出勤日数", Decimal("19.5"), "日"), 集("法定外残業", 600, "分"), 集("年休（半日）", 1, "回"),
          集("年休を取った日", "2027-01-12", "日付"), 集("年休を取った日", "2027-01-20", "日付")]


def test_日付の行は関所へ流さず出さない物に分ける():
    渡す, 出さない = 関所.勤怠の行を分ける(集計の行)
    assert [r["項目"] for r in 渡す] == ["出勤日数", "法定外残業", "年休（半日）"]
    assert [r["値"] for r in 出さない] == ["2027-01-12", "2027-01-20"]


def test_混ぜたままでは関所が止まる_分ければ通る():
    with pytest.raises(ValueError):
        関所.通す(計算の行 + 集計の行)
    渡す, _ = 関所.勤怠の行を分ける(集計の行)
    通 = 関所.通す(計算の行 + 渡す, {("2027-02", "9", "0001"): "確認済"})
    assert {r.項目: r.値 for r in 通.行たち} == {"差引支給額": 250000, "出勤日数": Decimal("19.5"),
                                               "法定外残業": 600, "年休（半日）": 1}


def test_勤怠の欄に仮があれば人ごと外し集計の問いを出す():
    渡す, _ = 関所.勤怠の行を分ける([集("法定外残業", 600, "分", "仮", "問1、問2")])
    通 = 関所.通す(計算の行 + 渡す)
    assert 通.行たち == () and 通.外した人たち[0].問いの番号 == ("問1", "問2")


def test_単位の無い行と数でない値は出さない物():
    渡す, 出さない = 関所.勤怠の行を分ける([集("出勤日数", "十", "日"), {**集("総労働", 9600, ""), "単位": None}])
    assert 渡す == [] and len(出さない) == 2


def test_集計の返す物をそのまま分けられる():
    import sys
    from pathlib import Path
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "集計"))
    from 作る_集計 import 数える, 既定の決まり, 月
    x = 数える(*月(), 既定の決まり(**{"時間.休憩の表": ["12:00〜13:00"]}))
    渡す, 出さない = 関所.勤怠の行を分ける(x["行"])
    assert {r["単位"] for r in 渡す} <= {"日", "分", "回"} and all(r["単位"] == "日付" for r in 出さない)
    通 = 関所.通す(渡す, {(p["支給月"], p["会社"], p["NO"]): p["状態"] for p in x["人"]})
    assert len(通.行たち) == len(渡す) and 通.外した人たち == ()
