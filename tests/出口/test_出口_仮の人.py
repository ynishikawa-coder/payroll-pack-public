# ---- 給与ソフトの形はパックに持たない（⟦鍵:給与計算/パックに製品ごとの物を置かない⟧）----

def test_給与ソフトの形を渡さなければ止まり_既定の形で書かない():
    通 = 関所.通す(作.行たち)
    for 足りない in ({}, {"名": "作り物の給与ソフト"}, {**作.形の値},             # 名・鍵の欄・文字コード のどれかが無い
                    {**作.形の値, "鍵の欄": "", "文字コード": "utf-8"}):
        with pytest.raises(ValueError):
            書き口.取り込み(通, "9", 作.月, 作.対応, 足りない, "60進")
        with pytest.raises(ValueError):
            読み口.読む(作.給与ソフトの出力, "出力.csv", "9", 作.月, 作.対応, 足りない, "60進")
    with pytest.raises(ValueError):
        形.形を組む(None)
    with pytest.raises(ValueError, match="の外"):
        形.形を組む({**作.形の値, "文字コード": "utf-8", "謎": "x"})
    with pytest.raises(ValueError):
        形.形を組む(形.給与ソフトの形(名="作り物の給与ソフト"))   # 型で組んでも 鍵の欄・文字コード が無ければ止まる
    assert not hasattr(形, "形を選ぶ") and not hasattr(形, "給与ソフトたち")


def test_給与ソフトの形は_dict_でも型でも同じ取り込みになる():
    通 = 関所.通す(作.行たち)
    d = {**作.形の値, "文字コード": "utf-8"}
    a = 書き口.取り込み(通, "9", 作.月, 作.対応, d, "60進")
    b = 書き口.取り込み(通, "9", 作.月, 作.対応, 形.形を組む(d), "60進")
    assert a.表 == b.表 and a.表[0][0] == "NO" and a.表[0][-1] == "メモ"
