def _取り込みの人(通):
    f = 形.形を組む({**作.形の値, "文字コード": "utf-8"})
    return {row[0] for row in 書き口.取り込み(通, "9", 作.月, 作.対応, f, "60進").表[1:]}


def test_状態を書かない行は仮に数える():
    from decimal import Decimal
    from 出口.行 import 行
    通 = 関所.通す([行(支給月=作.月, 会社="9", NO="0001", 項目="出勤日数", 値=Decimal(20))])
    assert [x.NO for x in 通.外した人たち] == ["0001"] and _取り込みの人(通) == set()


def test_関所を通ったは関所の外で作れず仮の行を足せない():
    import dataclasses
    from 出口.行 import 行にする
    仮の行 = 行にする(作.R("0002", "基本給", 180000, "仮"))
    with pytest.raises(TypeError):
        関所.関所を通った(行たち=(仮の行,), 外した人たち=())
    通 = 関所.通す(作.行たち)
    with pytest.raises(ValueError):
        dataclasses.replace(通, 行たち=通.行たち + (仮の行,))
    確定の行 = 行にする(作.R("0002", "出勤日数", 18))   # 外した人の確定の行も足せない
    with pytest.raises(ValueError):
        dataclasses.replace(通, 行たち=通.行たち + (確定の行,))
    object.__setattr__(通, "行たち", 通.行たち + (仮の行,))   # 作った後に替えても後ろの部品が止める
    with pytest.raises(ValueError):
        _取り込みの人(通)


def test_人の状態の知らない語は外す():
    通 = 関所.通す(作.行たち, 人の状態={(作.月, "9", "0001"): "要確認", (作.月, "9", "0004"): "確認済"})
