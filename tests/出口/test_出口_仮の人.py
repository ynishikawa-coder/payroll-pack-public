"""仮が 1 つでも残る人は出口のどの file にも出ない（確かめと仮.md §3）。"""
import pytest

from 出口 import 書き口, 形, 突き合わせ, 関所, 読み口
import 出口_作り物 as 作


def test_仮の人は取り込みにも支給控除一覧にも出ない():
    通 = 関所.通す(作.行たち)
    assert [(x.NO, x.仮の数, x.問いの番号) for x in 通.外した人たち] == [("0002", 1, ("Q-作り物-01",))]
    f = 形.形を組む({**作.形の値, "文字コード": "utf-8"})
    出す = [書き口.取り込み(通, "9", 作.月, 作.対応, f, "60進", 委託の人=作.委託, 委託も取り込む=True)]
    出す += 書き口.支給控除一覧(通, "9", 作.月, 委託の人=作.委託)
    for o in 出す:
        assert all("0002" not in c for row in o.表 for c in row), o.物
        assert all("仮" not in c for row in o.表 for c in row), o.物


def test_人の状態が仮なら行に仮が無くても外す():
    通 = 関所.通す(作.行たち, 人の状態={(作.月, "9", "0001"): "仮"})
    assert {x.NO for x in 通.外した人たち} == {"0001", "0002"}


def test_関所を通らない行は書き口も突き合わせも受けない():
    f = 形.形を組む({**作.形の値, "文字コード": "utf-8"})
    with pytest.raises(TypeError):
        書き口.取り込み(作.行たち, "9", 作.月, 作.対応, f, "60進")
    with pytest.raises(TypeError):
        突き合わせ.突き合わせる(作.行たち, [], 作.対応)


def test_仮で外した人は給与ソフトに居ても突き合わせない():
    通 = 関所.通す(作.行たち)
    f = 形.形を組む({**作.形の値, "文字コード": "utf-8"})
    読 = 読み口.読む(作.給与ソフトの出力, "出力.csv", "9", 作.月, 作.対応, f, "60進")
    結 = 突き合わせ.突き合わせる(通, 読, 作.対応, 渡さなかった人=作.委託)
    assert all(r.NO != "0002" for r in 結.行たち)
    assert 結.人の状態[(作.月, "9", "0002")] == "未突き合わせ"
    assert 突き合わせ.月の記録(結, "9", 作.月)["差0の月"] is False


