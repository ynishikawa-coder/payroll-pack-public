def _1字変える(表, NO, 列, 足す="0"):
    h, *行 = [list(r) for r in 表]
    i = next(k for k, r in enumerate(行) if str(r[h.index("NO")]) == NO)
    行[i][h.index(列)] = str(行[i][h.index(列)]) + 足す
    return [h, *行]


