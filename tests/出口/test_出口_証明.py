def _列を書く(表, 列, 値):
    """表の全部の行の 列 に 値 を書く（列が無ければ足す）。"""
    h, *行 = [list(r) for r in 表]
    if 列 not in h:
        h, 行 = [*h, 列], [[*r, ""] for r in 行]
    for r in 行:
        r[h.index(列)] = 値
    return [h, *行]


