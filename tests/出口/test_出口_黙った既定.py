"""出口の黙った既定を畳んだ注入の試験（作り物の値だけ）。前は渡し忘れ・欠けた値を既定で埋めて進み、仮の人・委託の人・分の欄が
黙って給与ソフトへ渡る形になっていた。今は既定を持たず、渡し忘れ（None・形の違う値）と欠けを止める。

- 関所.通す の 人の状態（前: None＝人の状態が無いと読み、段の解決の仮の人が確定で出た）
- 関所.勤怠の行を分ける の 決まり・入力（前: None＝無いと読み、実働の上限・委託の雇用分の出勤日数が黙って当たらなかった）
- 書き口.取り込み・支給控除一覧 の 委託の人（前: () ＝居ないと読み、委託の人が雇用として渡った）
- 書き口.支給控除一覧 の 項目の形（前: 無い項目は数のまま＝分の項目が 600 のように分の数で出た）
- 形.対応にする の 形・渡す・受ける（前: 形＝円・渡す/受ける＝はい と読み、知らない語は いいえ と読んだ）
- 形.欄の対応を組む の ⑥つなぎ の項目の形（前: 芯/集計 の語に無い項目は円と読み、分の項目も分の数のまま渡せた）
- 書き口.取り込み の 時間の書き方（分の欄を書くのに無ければ、表を組む前に止める）
"""
import pytest

from 出口 import 書き口, 形, 関所
import 出口_作り物 as 作

人 = {"支給月": "2027-02", "会社": "9", "NO": "0001", "勤怠の表記": "作り物の人", "状態": "確定", "出所": "作り物.csv",
     "印": "", "見当": "", "見当の拠り所": "", "問い": ""}
形の値 = {**作.形の値, "文字コード": "utf-8", "委託も取り込む": "いいえ"}


def _通():
    return 関所.通す(作.行たち, {})


@pytest.mark.parametrize("値", [None, [], "確認済"])
def test_通すは人の状態を渡さなければ止める(値):
    with pytest.raises(TypeError):
        関所.通す(作.行たち)                                    # 前: 人の状態 None で進んだ
    with pytest.raises(TypeError, match="人の状態"):
        関所.通す(作.行たち, 値)


@pytest.mark.parametrize("決まり, 入力", [(None, {}), ({}, None), ([], {}), ({}, "")])
def test_勤怠の行を分けるは決まりと入力を渡さなければ止める(決まり, 入力):
    行 = [{**人, "項目": "出勤日数", "値": 20, "単位": "日"}]
    with pytest.raises(TypeError):
        関所.勤怠の行を分ける(行)                                 # 前: 決まり・入力 None で進んだ
    with pytest.raises(TypeError, match="決まり|入力"):
        関所.勤怠の行を分ける(行, 決まり, None, 入力)


@pytest.mark.parametrize("委託", [None, "0003", {"0003": True}, 3])
def test_委託の人を並びで渡さなければ止める(委託):
    with pytest.raises(TypeError, match="委託の人"):
        書き口.取り込み(_通(), "9", 作.月, 作.対応, 形の値, "60進", 委託の人=委託, 今ある名=[], 履歴にある名=[])
    with pytest.raises(TypeError, match="委託の人"):
        書き口.支給控除一覧(_通(), "9", 作.月, 時間の書き方="60進", 項目の形=作.項目の形, 委託の人=委託, 今ある名=[], 履歴にある名=[])


def test_委託の人を省けば止め_空の並びなら居ない():
    with pytest.raises(TypeError):                              # 前: 委託の人=() で 0003 が雇用として取り込みに載った
        書き口.取り込み(_通(), "9", 作.月, 作.対応, 形の値, "60進", 今ある名=[], 履歴にある名=[])
    with pytest.raises(TypeError):
        書き口.支給控除一覧(_通(), "9", 作.月, 時間の書き方="60進", 項目の形=作.項目の形, 今ある名=[], 履歴にある名=[])
    取 = 書き口.取り込み(_通(), "9", 作.月, 作.対応, 形の値, "60進", 委託の人=作.委託, 今ある名=[], 履歴にある名=[])
    assert [r[0] for r in 取.表[1:]] == ["0001", "0004"]          # 委託の 0003 は載らない


def test_項目の形を渡さないか欠ければ止める():
    with pytest.raises(TypeError):                              # 前: 項目の形 None で全部を数のまま書いた
        書き口.支給控除一覧(_通(), "9", 作.月, 時間の書き方="60進", 委託の人=作.委託, 今ある名=[], 履歴にある名=[])
    with pytest.raises(TypeError, match="項目の形"):
        書き口.支給控除一覧(_通(), "9", 作.月, 時間の書き方="60進", 項目の形=None, 委託の人=作.委託, 今ある名=[], 履歴にある名=[])
    欠け = {k: v for k, v in 作.項目の形.items() if k != "法定外残業"}
    with pytest.raises(ValueError, match="法定外残業"):         # 前: 法定外残業 が 600（分の数）のまま出た
        書き口.支給控除一覧(_通(), "9", 作.月, 時間の書き方="60進", 項目の形=欠け, 委託の人=作.委託, 今ある名=[], 履歴にある名=[])


def test_分の項目は時間の書き方が無ければ止める():
    with pytest.raises(ValueError, match="時間の書き方"):
        書き口.支給控除一覧(_通(), "9", 作.月, 項目の形=作.項目の形, 委託の人=作.委託, 今ある名=[], 履歴にある名=[])
    雇用, _ = 書き口.支給控除一覧(_通(), "9", 作.月, 時間の書き方="60進", 項目の形=作.項目の形, 委託の人=作.委託,
                           今ある名=[], 履歴にある名=[])
    assert dict((r[0], r[1]) for r in 雇用.表)["法定外残業"] == "10.00"   # 600 分 → 60進 の 10.00


@pytest.mark.parametrize("欠け", ["形", "渡す", "受ける"])
def test_欄の対応の行に形と渡すと受けるが無ければ止める(欠け):
    行 = {"項目": "出勤日数", "欄": "出勤日数", "形": "日", "渡す": True, "受ける": True}
    with pytest.raises(ValueError, match=欠け):                 # 前: 形＝円・渡す/受ける＝はい と読んだ
        形.対応にする([{k: v for k, v in 行.items() if k != 欠け}])
    with pytest.raises(ValueError, match=欠け):
        形.対応にする([{**行, 欠け: ""}])


@pytest.mark.parametrize("語, 読み", [("はい", True), ("いいえ", False), (True, True), (False, False), ("○", True), ("×", False)])
def test_渡すと受けるははいかいいえの語だけ受ける(語, 読み):
    (x,) = 形.対応にする([{"項目": "出勤日数", "欄": "出勤日数", "形": "日", "渡す": 語, "受ける": True}])
    assert x.渡す is 読み
    with pytest.raises(ValueError, match="渡す"):               # 前: 知らない語は いいえ と読んだ
        形.対応にする([{"項目": "出勤日数", "欄": "出勤日数", "形": "日", "渡す": "渡さない", "受ける": True}])


def _つなぎの行(名, 欄):
    return {"会社": "9", "NO": "", "側": "出口", "道具": "作り物の給与ソフト", "その道具での番号": f"欄.{名}", "その道具での名": 欄}


def test_つなぎの項目の形が引けなければ円と読まず止める():
    with pytest.raises(ValueError, match="作り物の分の欄"):     # 前: 形＝円 と読み、分の数のまま給与ソフトへ渡った
        形.欄の対応を組む("9", "作り物の給与ソフト", (), [_つなぎの行("作り物の分の欄", "作り物の欄")])
    組 = {g["項目"]: g["形"] for g in 形.欄の対応を組む("9", "作り物の給与ソフト", [{"会社": "9", "項目": "作り物の手当", "給与ソフトの欄": ""}], [
        _つなぎの行("法定外残業", "残業時間"), _つなぎの行("出勤日数", "出勤日数"), _つなぎの行("総支給額", "総支給額"),
        _つなぎの行("作り物の手当", "手当")])}
    assert 組 == {"法定外残業": "分", "出勤日数": "日", "総支給額": "円", "作り物の手当": "円"}   # 芯の単位・芯の作る項目・④の項目
    with pytest.raises(ValueError, match="作り物の手当"):       # 別の会社の ④ の項目は円の拠り所にしない
        形.欄の対応を組む("9", "作り物の給与ソフト", [{"会社": "8", "項目": "作り物の手当", "給与ソフトの欄": ""}],
                    [_つなぎの行("作り物の手当", "手当")])


def test_つなぎの形の引けない項目は全部を1回で返し初期設定の欠けと名乗る():
    # 前: 最初の 1 つで止まり、1 つ直して回すたびに次の 1 つが出た（止まる回数が欠けの数だけ増えた）
    with pytest.raises(ValueError) as e:
        形.欄の対応を組む("9", "作り物の給与ソフト", (), [_つなぎの行("作り物の甲", "欄甲"), _つなぎの行("法定外残業", "残業時間"),
                                                    _つなぎの行("作り物の乙", "欄乙"), _つなぎの行("作り物の甲", "欄丙")])
    m = str(e.value)
    assert m.startswith(形.初期設定の欠けの頭) and "「作り物の甲」" in m and "「作り物の乙」" in m
    assert m.count("作り物の甲") == 1


@pytest.mark.parametrize("書き方", [None, "", "作り物の書き方"])
def test_取り込みは分の欄を書くのに時間の書き方が無ければ止める(書き方):
    with pytest.raises(ValueError, match="残業時間.*時間の書き方"):
        書き口.取り込み(_通(), "9", 作.月, 作.対応, 形の値, 書き方, 委託の人=作.委託, 今ある名=[], 履歴にある名=[])
    分の無い対応 = [x for x in 作.対応 if x["形"] != "分"]          # 分の欄が無ければ 時間の書き方 は要らない
    取 = 書き口.取り込み(_通(), "9", 作.月, 分の無い対応, 形の値, 書き方, 委託の人=作.委託, 今ある名=[], 履歴にある名=[])
    assert 取.表[0] == ("NO", "氏名", "出勤日数", "メモ")
