"""欄の対応: 1 つの欄に幾つかの項目を足す（時給・日給・基本給 → 基本給の欄）と、勤怠の欄・芯が作る項目の欄を
Drive の値（④支給控除の項目 の 給与ソフトの欄・⑥つなぎ の会社の行 側＝出口）から組む。作り物の値だけ（製品の名は置かない）。"""
from decimal import Decimal

import pytest

from 出口 import 書き口, 形, 読み口, 突き合わせ, 関所
import 出口_作り物 as 作

月 = 作.月
R = 作.R
行たち = [
    R("0001", "基本給", 200000), R("0001", "出勤日数", 20), R("0001", "法定外残業", 600), R("0001", "総支給額", 215000),
    R("0002", "時給", 150000), R("0002", "日給", 8000), R("0002", "出勤日数", 18), R("0002", "法定外残業", 0), R("0002", "総支給額", 158000),
]
形の値 = {**作.形の値, "文字コード": "utf-8"}
項目の行 = [
    {"会社": "9", "項目": "基本給", "給与ソフトの欄": "基本給"},
    {"会社": "9", "項目": "時給", "給与ソフトの欄": "基本給"},
    {"会社": "9", "項目": "日給", "給与ソフトの欄": "基本給"},
    {"会社": "9", "項目": "皆勤手当", "給与ソフトの欄": ""},                          # 欄の無い項目は対応に入れない
    {"会社": "8", "項目": "基本給", "給与ソフトの欄": "別の会社の欄"},                  # 別の会社の行は読まない
]
つなぎ = [
    {"会社": "9", "NO": "", "側": "出口", "道具": "作り物の給与ソフト", "その道具での番号": "欄.出勤日数", "その道具での名": "出勤日数"},
    {"会社": "9", "NO": "", "側": "出口", "道具": "作り物の給与ソフト", "その道具での番号": "欄.法定外残業", "その道具での名": "残業時間"},
    {"会社": "9", "NO": "", "側": "出口", "道具": "作り物の給与ソフト", "その道具での番号": "受ける.総支給額", "その道具での名": "総支給額"},
    {"会社": "9", "NO": "", "側": "入口", "道具": "作り物の給与ソフト", "その道具での番号": "列.日付", "その道具での名": "日付"},
    {"会社": "9", "NO": "", "側": "出口", "道具": "別の給与ソフト", "その道具での番号": "欄.出勤日数", "その道具での名": "別の欄"},
]


def _対応():
    return 形.欄の対応を組む("9", "作り物の給与ソフト", 項目の行, つなぎ)


def test_Drive_の値から対応を組む_勤怠の欄の形は芯の単位():
    組 = {g.欄: g for g in 形.欄の組たち(_対応())}
    assert list(組) == ["基本給", "出勤日数", "残業時間", "総支給額"]
    assert 組["基本給"].項目たち == ("基本給", "時給", "日給") and 組["基本給"].形 == "円"
    assert 組["出勤日数"].形 == "日" and 組["残業時間"].形 == "分"
    assert 組["総支給額"].渡す is False and 組["総支給額"].受ける is True


def test_時給の人も基本給の欄に足して渡す_勤怠の欄も渡す():
    t = 書き口.取り込み(関所.通す(行たち), "9", 月, _対応(), 形の値, "60進")
    頭 = list(t.表[0])
    assert 頭 == ["NO", "氏名", "基本給", "出勤日数", "残業時間", "メモ"]
    行 = {r[0]: dict(zip(頭, r)) for r in t.表[1:]}
    assert 行["0001"]["基本給"] == "200000" and 行["0002"]["基本給"] == "158000"   # 時給 150000＋日給 8000
    assert 行["0001"]["残業時間"] == "10.00" and 行["0002"]["出勤日数"] == "18"
    assert 行["0002"]["残業時間"] == "0.00" and t.空の欄 == () and t.載せなかった項目 == ("総支給額",)


def test_足す欄は足した値と照らす():
    通 = 関所.通す(行たち)
    出力 = "NO,氏名,基本給,出勤日数,残業時間,総支給額,メモ\r\n0001,,200000,20,10.00,215000,\r\n0002,,158000,18,0.00,158001,\r\n"
    読 = 読み口.読む(出力, "作り物の出力.csv", "9", 月, _対応(), 形の値, "60進")
    assert ("0002", "基本給＋時給＋日給", Decimal("158000")) in {(r.NO, r.項目, r.値) for r in 読.行たち}
    結 = 突き合わせ.突き合わせる(通, 読, _対応())
    差 = [(r.NO, r.項目) for r in 結.差の行()]
    assert 差 == [("0002", "総支給額")], 差                  # 基本給の欄は 150000＋8000＝158000 で一致
    assert ("0002", "基本給＋時給＋日給") in {(r.NO, r.項目) for r in 結.行たち if r.一致}


def test_同じ項目を2つの欄に出すと止まる_足す欄の形がそろわなければ止まる():
    with pytest.raises(ValueError, match="同じ項目"):
        形.欄の対応を組む("9", "作り物の給与ソフト", 項目の行, [*つなぎ, {**つなぎ[0], "その道具での名": "出勤日数2"}])
    with pytest.raises(ValueError, match="そろわない"):
        形.対応にする([{"項目": "基本給", "欄": "基本給"}, {"項目": "出勤日数", "欄": "基本給", "形": "日"}])


def test_適用開始が先の行は使わない():
    行 = [{"会社": "9", "項目": "基本給", "給与ソフトの欄": "基本給", "適用開始": "2026.01支給"},
         {"会社": "9", "項目": "基本給", "給与ソフトの欄": "新しい欄", "適用開始": "2027.04支給"}]
    assert 形.欄の対応を組む("9", None, 行, 支給月=月) == [{"項目": "基本給", "欄": "基本給", "形": "円"}]
