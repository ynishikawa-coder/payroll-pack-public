"""取り込みを 2_出す物 のスプレッドシートの表で渡す（給与ソフトの形の 渡し方＝表。人が給与ソフトへ写す事務所）。作り物の値だけ。

- 渡し方＝表 は文字コードが要らない（CSV を作らない）。CSV の表と同じ行を返し、窓が当てる書く手順（RAW）を返す。
- 渡し方を書かない形は前からの CSV のまま（文字コードが無ければ止まる）。知らない渡し方は止まる。
"""
import pytest

from 出口 import 書き口, 形, 関所
import 出口_作り物 as 作


def test_表で渡す形は文字コードが要らず書く手順をRAWで返す():
    通 = 関所.通す(作.行たち, {})
    表 = 書き口.取り込み(通, "9", 作.月, 作.対応, {**作.形の値, "渡し方": "表"}, "60進", 氏名={"0001": "作り物 一郎"},
                    委託の人=[], 今ある名=[f"取り込み_9_{作.月}_v1"], 履歴にある名=[])
    csv = 書き口.取り込み(通, "9", 作.月, 作.対応, {**作.形の値, "文字コード": "utf-8"}, "60進", 氏名={"0001": "作り物 一郎"}, 委託の人=[], 今ある名=[], 履歴にある名=[])
    assert 表.表 == csv.表 and 表.表[0][:2] == ("NO", "氏名")      # 鍵の欄 NO・氏名の欄 氏名・1 人 1 行（横）
    with pytest.raises(ValueError, match="CSV を作らない"):
        表.csvの中身()
    移す, 作る, 書く = 表.書く手順()
    assert 移す == {"する": "file を移す", "前": f"2_出す物/取り込み_9_{作.月}_v1", "後": f"9_履歴/取り込み_9_{作.月}_v1", "後の根": "会社の根"}
    assert 作る == {"する": "スプレッドシートを作る", "フォルダ": "2_出す物", "名": f"取り込み_9_{作.月}_v2", "タブ": "取り込み"}
    assert 書く["書き方"] == "RAW" and 書く["値"] == [list(r) for r in 表.表]
    assert 書く["範囲"] == f"A1:{chr(64 + len(表.表[0]))}{len(表.表)}" and 書く["ファイル"] == f"2_出す物/取り込み_9_{作.月}_v2"
    assert 書く["値"][1][0] == "0001"                                # NO は字のまま（頭の 0）


def test_支給控除一覧も書く手順で表に書ける():
    (雇用,) = [x for x in 書き口.支給控除一覧(関所.通す(作.行たち, {}), "9", 作.月, 時間の書き方="60進", 項目の形=作.項目の形, 委託の人=[], 今ある名=[], 履歴にある名=[]) if x.物 == "支給控除一覧_雇用"]
    assert 雇用.書く手順()[-1]["タブ"] == "支給控除一覧_雇用" and 雇用.書く手順()[0]["フォルダ"] == "2_出す物"


def test_渡し方を書かない形はCSVのまま_知らない渡し方は止まる():
    通 = 関所.通す(作.行たち, {})
    with pytest.raises(ValueError, match="文字コード"):
        書き口.取り込み(通, "9", 作.月, 作.対応, 作.形の値, "60進", 委託の人=[], 今ある名=[], 履歴にある名=[])              # 前からの形＝CSV は文字コードが要る
    with pytest.raises(ValueError, match="文字コード"):
        書き口.取り込み(通, "9", 作.月, 作.対応, {**作.形の値, "渡し方": "CSV"}, "60進", 委託の人=[], 今ある名=[], 履歴にある名=[])
    c = 書き口.取り込み(通, "9", 作.月, 作.対応, {**作.形の値, "文字コード": "utf-8"}, "60進", 委託の人=[], 今ある名=[], 履歴にある名=[])
    assert c.csvの中身().startswith("NO,".encode()) and c.渡し方 == "CSV"
    with pytest.raises(ValueError, match="表に書かない"):
        c.書く手順()
    with pytest.raises(ValueError, match="の外"):
        形.形を組む({**作.形の値, "渡し方": "紙"})
