"""回帰の見張り: 作り物の小さな人×項目 → 取り込みの形・支給控除一覧・突き合わせの表・月数が黙って変わらない。

ここの期待の値を変える時は、変えた理由を PR に書く（出口の形が変わった＝給与ソフトへ渡る物が変わる）。
"""
from 出口 import 書き口, 名と版, 形, 突き合わせ, 関所, 読み口
import 出口_作り物 as 作

F = 形.形を組む({**作.形の値, "文字コード": "cp932"})


def _結果():
    通 = 関所.通す(作.行たち)
    読 = 読み口.読む(作.給与ソフトの出力.encode("cp932"), "出力.csv", "9", 作.月, 作.対応, F, "60進")
    assert 読.要確認 == ()
    return 通, 突き合わせ.突き合わせる(通, 読, 作.対応, 渡さなかった人=作.委託)


def test_取り込みの形():
    通 = 関所.通す(作.行たち)
    o = 書き口.取り込み(通, "9", 作.月, 作.対応, F, "60進", 氏名={"0001": "作り物 一"}, 委託の人=作.委託)
    assert o.名 == 名と版.出す名("01_取り込み", "取り込み_9_2026-11_v1", 1, ())
    assert o.csvの中身().decode("cp932") == (
        "NO,氏名,出勤日数,残業時間,メモ\r\n"
        "0001,作り物 一,20,10.00,\r\n"
        "0004,,21,1.30,\r\n"
    )
    assert o.載せなかった項目 == ("基本給", "総支給")
    賞与 = 書き口.取り込み(関所.通す([作.R("0001", "賞与", 300000, 月="2026-12-賞与")]), "9", "2026-12-賞与",
                     [dict(項目="賞与", 欄="賞与額")], F)
    assert (賞与.名.名, 賞与.表) == ("賞与の取り込み_9_2026-12-賞与_v1", (("NO", "氏名", "賞与額", "メモ"), ("0001", "", "300000", "")))


def test_業務委託の縦の表は1本():
    通 = 関所.通す(作.行たち)
    雇用, 委託 = 書き口.支給控除一覧(通, "9", 作.月, ["基本給", "法定外残業", "総支給"], {"法定外残業": "分"}, "時:分",
                            委託の人=作.委託)
    assert 雇用.表 == (("項目", "0001", "0004", "合計"), ("基本給", "200000", "210000", "410000"),
                     ("法定外残業", "10:00", "1:30", "11:30"), ("総支給", "215000", "212500", "427500"),
                     ("出勤日数", "20", "21", "41"))
    assert 委託.名.名 == "支給控除一覧_業務委託_9_2026-11_v1"
    assert 委託.表 == (("項目", "0003", "合計"), ("総支給", "50000", "50000"), ("出勤日数", "10", "10"), ("報酬", "50000", "50000"))


def test_突き合わせの表():
    _, 結 = _結果()
    assert 結.表() == [
        ("支給月", "会社", "NO", "項目", "こちら", "給与ソフト", "差", "差の見立て", "差の出所"),
        ("2026-11", "9", "0001", "出勤日数", "20", "20", "0", "", ""),
        ("2026-11", "9", "0001", "法定外残業", "600", "600", "0", "", ""),
        ("2026-11", "9", "0001", "総支給", "215000", "215000", "0", "", ""),
        ("2026-11", "9", "0004", "出勤日数", "21", "20", "1", "入力の違い", "作り物の原本"),
        ("2026-11", "9", "0004", "法定外残業", "90", "90", "0", "", ""),
        ("2026-11", "9", "0004", "総支給", "212500", "212499", "1", "丸め", "作り物の原本"),
    ]
    assert [(q["差の見立て"], q["人"], q["項目"]) for q in 結.問い] == [
        ("入力の違い", ("0004",), ("出勤日数",)), ("丸め", ("0004",), ("総支給",))]
    assert 結.人の状態 == {(作.月, "9", "0001"): "一致", (作.月, "9", "0004"): "差あり", (作.月, "9", "0002"): "未突き合わせ"}
    assert 結.照らさなかった項目 == ("基本給",) and 結.照らさなかった人 == ("0003",)


def test_差0の月の数え方():
    _, 結 = _結果()
    今月 = 突き合わせ.月の記録(結, "9", 作.月)
    assert (今月["突き合わせた人"], 今月["差の行"], 今月["外した人"], 今月["差0の月"]) == (2, 2, 1, False)
    零 = lambda m, *s: dict(支給月=m, 会社="9", 差0の月=True, 場面=s)
    assert 突き合わせ.続けて差0の月数([零("2026-08"), 零("2026-09", "入社"), 零("2026-10"), 零("2026-10-賞与", "賞与")]) == {
        "9": {"月数": 4, "N": 3, "数えた月": ("2026-08", "2026-09", "2026-10", "2026-10-賞与"),
              "まだ見ていない場面": ("退社", "年の変わり目", "料率の変わる月")}}
    # 外れた月（今月）で 0 に戻る・間に記録の無い月でも切れる
    assert 突き合わせ.続けて差0の月数([零("2026-10"), 今月])["9"]["月数"] == 0
    assert 突き合わせ.続けて差0の月数([零("2026-08"), 零("2026-10")])["9"]["数えた月"] == ("2026-10",)


