"""出口の名の支給月の字（出口/名と版.py の 出す支給月）は入口と同じ正本（芯/支給月の字.py の 字にする）から作る。
正本の字の組み方がずれれば、この試験と入口の試験（test_入口_支給月の字）が同時に赤。"""
import pytest

from 出口 import 名と版
from 芯 import 支給月の字


@pytest.mark.parametrize("字, 回, 出す", [("2026.11支給", "月", "2026-11"), ("2026-11", "月", "2026-11"),
                                     ("2026.11支給", "賞与", "2026-11-賞与"), ("2026-11-賞与", "賞与", "2026-11-賞与")])
def test_出す支給月は正本の字(字, 回, 出す):
    assert 名と版.出す支給月(字, 回) == 出す == 支給月の字.字にする(2026, 11, 賞与=回 == "賞与")


@pytest.mark.parametrize("字", ["2026.11", "2026/11", "2026年11月", "2026.1支給", "2026.13支給", "2026.11支給\n", "2026-11-賞与"])
def test_出口の受けない字は止める(字):
    with pytest.raises(ValueError):
        名と版.出す支給月(字, "月")


def test_入口の文脈の字と出口の字が同じ():
    import importlib.util
    from pathlib import Path
    p = Path(__file__).resolve().parents[2] / "初期設定" / "入口の文脈.py"
    s = importlib.util.spec_from_file_location("出口_支給月の字_文脈", p)
    m = importlib.util.module_from_spec(s)
    s.loader.exec_module(m)
    x = m.入口の文脈("2026.11支給", "作り物の会社", {"決まり": {}, "人": {}})
    assert x["文脈"]["支給月"] == 名と版.出す支給月("2026.11支給", "月")
    assert 名と版.名を付ける("取り込み", "作り物の会社", 名と版.出す支給月("2026.11支給"), 今ある名=[], 履歴にある名=[]).名 == "取り込み_作り物の会社_2026-11_v1"


def test_欄の対応は読めない適用開始を止め_読める字は正本で比べる():
    """注入: 支給控除の項目 の 適用開始 に読めない字。前は "" に読み＝適用開始の無い行として、まだ効かない欄を黙って出した。"""
    from 出口 import 形
    行 = {"会社": "作り物の会社", "項目": "寮費", "給与ソフトの欄": "欄1"}
    assert 形.欄の対応を組む("作り物の会社", 支給控除の項目=[{**行, "適用開始": "2026.12支給"}], 支給月="2026.11支給") == []
    assert len(形.欄の対応を組む("作り物の会社", 支給控除の項目=[{**行, "適用開始": "2026-11"}], 支給月="2026.11支給")) == 1
    with pytest.raises(ValueError):
        形.欄の対応を組む("作り物の会社", 支給控除の項目=[{**行, "適用開始": "来月から"}], 支給月="2026.11支給")


def test_突き合わせの次の月は年をまたぐ():
    from 出口 import 突き合わせ
    assert 突き合わせ._次の月("2026-12") == "2027-01" and 突き合わせ._次の月("2026-11-賞与") == "2026-12"
