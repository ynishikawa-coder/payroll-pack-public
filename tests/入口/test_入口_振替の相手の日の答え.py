"""振替の相手の日の答え（質問と回答の 列）を、確定した勤怠（台帳＝YYYY-MM-DD の列）へ届く形に直してから表 A に置く。
読めない日付の答えは当てず、要確認のまま残す（黙って字のまま置くと台帳の書き込みで止まる）。作り物の値だけ。"""
import 入口_作り物 as 作
from 入口 import Excel出勤簿

表 = {"勤怠の表記": "作り物 一郎", "原本の名前": "勤怠_20261108_出勤簿.xlsx",
     "見出し": ["日付", "出勤", "退勤", "区分"],
     "行": [["2026/11/2", "", "", "振休"]]}


def 読む(値):
    答え = {"作り物 一郎": [{"番号": "Q1", "何が無いか": "振替の相手の日が無い", "種類": "区分", "答え": "x",
                         "列": {"振替の相手の日": 値}}]}
    r = Excel出勤簿.読む(表, 作.文脈(日の答え=答え))
    a = next(x for x in r.日 if x["日付"] == "2026-11-02")
    return a, [q["理由"] for q in r.要確認 if q["日付"] == "2026-11-02"]


def test_月と日の答えは期間の日付に直して置く():
    for 値 in ("11/5", "2026/11/5", "5", "5日"):
        a, 理由 = 読む(値)
        assert a["振替の相手の日"] == "2026-11-05", 値
        assert "振替の相手の日が無い" not in 理由


def test_期間の外でも年月日の答えは日付に直して置く():
    a, 理由 = 読む("2026/10/31")
    assert a["振替の相手の日"] == "2026-10-31"
    assert "振替の相手の日が無い" not in 理由


def test_読めない日付の答えは当てず要確認のまま():
    # 字・暦に無い日・年の無い期間の外の日（どの年か決まらない）は当てない
    for 値 in ("来週の土曜", "2026/2/30", "10/31"):
        a, 理由 = 読む(値)
        assert a["振替の相手の日"] == "", 値
        assert "振替の相手の日が無い" in 理由, 値


def test_メモの読めない相手の日は字のまま置かず要確認():
    from 入口 import メールとメモ
    連絡 = [dict(作.連絡[1], 代休の相手の日="先月のどこか")]
    r = メールとメモ.読む(連絡, 作.文脈(), 作.手当の辞書, 作.手当の単価)
    a = next(x for x in r.日 if x["日付"] == "2026-11-06")
    assert a["代休の相手の日"] == ""
    assert any("先月のどこか" in q["理由"] for q in r.要確認 if q["日付"] == "2026-11-06")
