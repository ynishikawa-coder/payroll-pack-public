"""C7 の直す所 2・3・4・12 の試験（作り物だけ）。

- 実働の欄のある出勤簿: 実働は 原本の時間 の 総労働 へ写し、時間数（退−出）と合わなくても要確認にしない
- 休日の 3 段（会社・勤務の型・人。狭い方が勝つ）と、今の 1 つの休日だけを渡す呼び方の互換
- 時間.出勤簿が無い の人: 空の勤務日は所定どおり働いたとみなす（印 定時扱い・備考に残す）
- 所定の無い人（人.区分＝委託 など）: 空の日は働いていない日（休日・要確認にしない）
"""
import 入口_作り物 as 作
from 入口 import 口, Excel出勤簿


def 日(r, no, d):
    return next(a for a in r.日 if a["NO"] == no and a["日付"] == d)


def 理由(r, no, d=None):
    return [q["理由"] for q in r.要確認 if q["NO"] == no and (d is None or q["日付"] == d)]


# 2026-11-01（日）〜 2026-11-07（土）。会社の休日は 11/1 と 11/7
def 出勤簿(見出し, 行たち):
    return {"原本の名前": "勤怠_20261108_出勤簿.xlsx", "見出し": ["氏名"] + 見出し, "行": [["作り物 二子"] + r for r in 行たち]}


def 平日の5日(出="9:00", 退="18:00"):
    return [[f"2026/11/{d}", 出, 退] for d in range(2, 7)]


def 土日(n):
    return [["2026/11/1"] + [""] * n, ["2026/11/7"] + [""] * n]


# ---- 2: 実働の欄 ----
def test_実働の欄は原本の時間へ写し要確認にしない():
    for 語 in ("実働", "労働時間"):
        表 = 出勤簿(["日付", "出勤", "退勤", "休憩", 語], [r + ["60", "8:00"] for r in 平日の5日()] + 土日(4))
        r = Excel出勤簿.読む(表, 作.文脈())
        assert 理由(r, "2") == [], 語
        a = 日(r, "2", "2026-11-02")
        assert a["原本の時間"] == "総労働=480" and a["読み取りの確かめ"] == 口.確認済
        assert r.人の状態() == {"2": "確定"}


def test_実働はExcelの小数とh_mm_ssも読む():
    表 = 出勤簿(["日付", "出勤", "退勤", "実働"], [["2026/11/2", "9:00", "17:00", "0.3125"], ["2026/11/3", "9:00", "17:00", "7:30:00"]])
    r = Excel出勤簿.読む(表, 作.文脈())
    assert 日(r, "2", "2026-11-02")["原本の時間"] == "総労働=450"
    assert 日(r, "2", "2026-11-03")["原本の時間"] == "総労働=450"


def test_時間数の欄は今までどおり退マイナス出と照らす():
    表 = 出勤簿(["日付", "出勤", "退勤", "時間数", "実働"], [["2026/11/2", "9:00", "18:00", "9:00", "8:00"],
                                                ["2026/11/3", "9:00", "18:00", "8:00", "8:00"]])
    r = Excel出勤簿.読む(表, 作.文脈())
    assert 理由(r, "2", "2026-11-02") == []
    assert any("印字の時間数" in x for x in 理由(r, "2", "2026-11-03"))


def test_殻が読み替えで実働を時間数へ寄せることもできる():
    表 = dict(出勤簿(["日付", "出勤", "退勤", "実働"], [["2026/11/2", "9:00", "18:00", "9:00"]]), 読み替え={"実働": "時間数"})
    r = Excel出勤簿.読む(表, 作.文脈())
    assert 日(r, "2", "2026-11-02")["原本の時間"] == "" and 理由(r, "2", "2026-11-02") == []


# ---- 3: 休日の 3 段 ----
def test_今の1つの休日だけの呼び方はそのまま():
    c = 作.文脈()
    assert c.休日か("2026-11-07") and c.休日か("2026-11-01") and not c.休日か("2026-11-02")
    assert c.休日か("2026-11-07", "2", "作り物 二子")


def test_型の休日と人の休日_狭い方が勝つ():
    c = 作.文脈(
        休日={"2026-11-01"},                                   # 会社は日曜だけ
        人の型={"2": "月〜金", "作り物 一郎": "月〜土"},
        型の休日={"月〜金": {"2026-11-07"}, "月〜土": {"2026-11-03": False}},
        人の休日={"2": {"2026-11-04": True, "2026-11-01": False}},  # その人だけの休み・その人は日曜に出る現場
    )
    assert c.休日か("2026-11-07", "2") and not c.休日か("2026-11-07", "1", "作り物 一郎")
    assert c.休日か("2026-11-04", "2") and not c.休日か("2026-11-04", "1", "作り物 一郎")
    assert not c.休日か("2026-11-01", "2") and c.休日か("2026-11-01", "1", "作り物 一郎")
    assert not c.休日か("2026-11-03", "1", "作り物 一郎")  # 型の段で 勤務日 と書いた日


def test_月から金の型の土曜と人だけの休みは要確認にならない():
    行たち = [[f"2026/11/{d}", "9:00", "18:00"] for d in (2, 3, 5, 6)] + [["2026/11/4", "", ""]] + 土日(2)
    表 = 出勤簿(["日付", "出勤", "退勤"], 行たち)
    前 = Excel出勤簿.読む(表, 作.文脈(休日={"2026-11-01"}))
    assert set(q["日付"] for q in 前.要確認) == {"2026-11-04", "2026-11-07"}
    c = 作.文脈(休日={"2026-11-01"}, 人の型={"2": "月〜金"}, 型の休日={"月〜金": {"2026-11-07"}},
              人の休日={"作り物 二子": {"2026-11-04"}})
    r = Excel出勤簿.読む(表, c)
    assert 理由(r, "2") == []
    assert 日(r, "2", "2026-11-07")["日の種類"] == "休日" and 日(r, "2", "2026-11-04")["日の種類"] == "休日"
    assert 日(r, "2", "2026-11-02")["勤務の型"] == "月〜金"
    assert r.人の状態() == {"2": "確定"}


def test_型の休日に働いた日は休日勤務():
    表 = 出勤簿(["日付", "出勤", "退勤"], [["2026/11/4", "9:00", "12:00"]])
    r = Excel出勤簿.読む(表, 作.文脈(人の型={"2": "月〜金"}, 型の休日={"月〜金": {"2026-11-04"}}))
    assert 日(r, "2", "2026-11-04")["日の種類"] == "休日勤務"


# ---- 4: 出勤簿が無い ----
def test_出勤簿が無い人の空の日は所定どおりとみなす():
    表 = 出勤簿(["日付", "出勤", "退勤", "区分"], [[f"2026/11/{d}", "", "", ""] for d in range(1, 8)])
    前 = Excel出勤簿.読む(表, 作.文脈())
    assert len(理由(前, "2")) == 5
    c = 作.文脈(出勤簿が無い={"2": 480})
    r = Excel出勤簿.読む(表, c)
    assert 理由(r, "2") == []
    a = 日(r, "2", "2026-11-02")
    assert a["日の種類"] == "勤務" and "定時扱い" in a["印"] and a["時刻の無い労働時間"] == "480"
    assert a["所定時間"] == "480" and "所定どおり働いたとみなした" in a["備考"]
    assert 日(r, "2", "2026-11-07")["日の種類"] == "休日" and 日(r, "2", "2026-11-07")["印"] == ""
    assert r.人の状態() == {"2": "確定"}


def test_出勤簿が無い人も書かれた区分と時刻はそのまま():
    表 = 出勤簿(["日付", "出勤", "退勤", "区分"], [["2026/11/2", "", "", "有給"], ["2026/11/3", "9:00", "12:00", ""]])
    r = Excel出勤簿.読む(表, 作.文脈(出勤簿が無い={"作り物 二子": "480"}))
    assert 日(r, "2", "2026-11-02")["日の種類"] == "休暇"
    a = 日(r, "2", "2026-11-03")
    assert a["日の種類"] == "勤務" and "定時扱い" not in a["印"]
    assert 日(r, "2", "2026-11-04")["日の種類"] == "勤務"  # 原本に無い日もみなす
    assert 理由(r, "2") == []


def test_出勤簿が無い人に所定時間が無ければ要確認():
    表 = 出勤簿(["日付", "出勤", "退勤"], [["2026/11/2", "", ""]])
    r = Excel出勤簿.読む(表, 作.文脈(出勤簿が無い={"作り物 二子"}))
    assert "出勤簿が無い人の日の所定時間が渡されていない" in 理由(r, "2", "2026-11-02")
    assert r.人の状態() == {"2": "仮"}


# ---- 12: 所定の無い人（委託） ----
def test_委託の人の空の日は働いていない日():
    表 = 出勤簿(["日付", "出勤", "退勤"], [["2026/11/2", "9:00", "15:00"], ["2026/11/3", "", ""], ["2026/11/7", "10:00", "12:00"]])
    前 = Excel出勤簿.読む(表, 作.文脈())
    assert 理由(前, "2", "2026-11-03")
    r = Excel出勤簿.読む(表, 作.文脈(人の区分={"2": "委託"}))
    assert 理由(r, "2") == []
    for d in ("2026-11-01", "2026-11-03", "2026-11-04"):
        a = 日(r, "2", d)
        assert a["日の種類"] == "休日" and "働いていない日" in a["備考"] and "原本に無い" not in a["印"], d
    assert 日(r, "2", "2026-11-02")["日の種類"] == "勤務"
    assert 日(r, "2", "2026-11-07")["日の種類"] == "勤務"  # 所定の無い人に休日勤務は無い
    assert r.人の状態() == {"2": "確定"}


def test_所定の無い人は区分のほかに名指しでも渡せる_社員はそのまま():
    表 = 出勤簿(["日付", "出勤", "退勤"], [["2026/11/3", "", ""]])
    assert 理由(Excel出勤簿.読む(表, 作.文脈(所定の無い人={"作り物 二子"})), "2") == []
    assert 理由(Excel出勤簿.読む(表, 作.文脈(人の区分={"2": "社員"})), "2", "2026-11-03")
