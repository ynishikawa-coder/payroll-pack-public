"""C11 の穴 1: 区分「有休」の日に時刻と実働もある日（半日の有休と勤務を 1 日に書いた形）の読み（作り物だけ）。

- 勤務の区間が全部 正午 から後＝午前半休＋勤務・全部 13:00 までに終わる＝午後半休＋勤務（区間はそのまま）
- 休暇の時間がある＝時間＋勤務
- 長さが原本から決まらない（全日の時刻・昼をまたぐ短い時刻・時刻の無い労働時間・打刻抜け）＝要確認（全日にも半日にもしない）
- どの読み口も同じ（区分の読みは 口._一日 に寄る）。時刻の無い有休・休日の有休＋時刻は今までどおり
"""
import pytest

import 入口_作り物 as 作
from 入口 import 口, Excel出勤簿, PDFタイムカード, 勤怠システムの月報, メールとメモ
from 芯.集計 import 集計する

決まらない = "年休の日に勤務の時刻がある（年休の長さ＝半日か時間かが原本から決まらない）"


def 日(r, no, d):
    return next(a for a in r.日 if a["NO"] == no and a["日付"] == d)


def 区間(r, no, d):
    return [(b["区間の種別"], b["始め"], b["終わり"]) for b in r.区間 if b["NO"] == no and b["日付"] == d]


def 理由(r, no, d=None):
    return [q["理由"] for q in r.要確認 if q["NO"] == no and (d is None or q["日付"] == d)]


def 出勤簿(行たち, 見出し=("日付", "出勤", "退勤", "実働", "区分")):
    return {"原本の名前": "勤怠_20261108_出勤簿.xlsx", "見出し": ["氏名", *見出し],
            "行": [["作り物 二子"] + r for r in 行たち]}


def 一日(出, 退, 区分="有休", 実働="", d="2026/11/4"):
    r = Excel出勤簿.読む(出勤簿([[d, 出, 退, 実働, 区分]]), 作.文脈())
    return r, 日(r, "2", "2026-11-04")


@pytest.mark.parametrize("出, 退, 単位", [("13:00", "18:00", "午前半休"), ("12:00", "17:30", "午前半休"),
                                      ("9:00", "12:00", "午後半休"), ("8:30", "13:00", "午後半休")])
def test_有休と勤務の時刻は半休と勤務に読む(出, 退, 単位):
    r, a = 一日(出, 退, 実働="4:00")
    assert (a["日の種類"], a["休暇の種類"], a["休暇の単位"]) == ("勤務", "年休", 単位)
    assert a["読み取りの確かめ"] == 口.確認済 and 理由(r, "2", "2026-11-04") == []
    assert 区間(r, "2", "2026-11-04") == [("労働", 出, 退)]
    assert "半休＋勤務と読んだ" in a["備考"] and a["働いた場所"] == "事業所"


@pytest.mark.parametrize("出, 退", [("9:00", "18:00"), ("10:00", "15:00"), ("12:00", "13:00"), ("22:00", "6:00")])
def test_有休の長さが決まらない日は要確認(出, 退):
    r, a = 一日(出, 退)
    assert a["日の種類"] == "勤務" and a["休暇の種類"] == "年休" and a["休暇の単位"] == ""
    assert 決まらない in 理由(r, "2", "2026-11-04") and a["読み取りの確かめ"] == 口.要確認
    assert r.人の状態()["2"] == "仮"


def test_打刻抜けの有休も長さを決めない():
    r, a = 一日("13:00", "")
    assert a["休暇の単位"] == "" and 決まらない in 理由(r, "2", "2026-11-04")


def test_休暇の時間がある有休は時間と勤務():
    c = 作.文脈(区分の読み替え={"時間有休": {"日の種類": "休暇", "休暇の種類": "年休", "休暇の単位": "全日", "休暇の時間": "120"}})
    r = Excel出勤簿.読む(出勤簿([["2026/11/4", "9:00", "16:00", "", "時間有休"]]), c)
    a = 日(r, "2", "2026-11-04")
    assert (a["日の種類"], a["休暇の単位"], a["休暇の時間"]) == ("勤務", "時間", "120")
    assert 理由(r, "2", "2026-11-04") == []


@pytest.mark.parametrize("語", ["有給", "年休", "有給休暇", "年次有給休暇"])
def test_有休の語はどれも同じ(語):
    r, a = 一日("13:00", "18:00", 区分=語)
    assert a["休暇の単位"] == "午前半休" and 理由(r, "2", "2026-11-04") == []


def test_他の読み口も同じ():
    c = 作.文脈()
    カード = {"勤怠の表記": "作り物 一郎", "原本の名前": "勤怠_20261108_カード.pdf", "見出し": ["日", "出", "退", "区分"],
            "行": [["4", "13:00", "18:00", "有休"], ["5", "9:00", "18:00", "有休"]]}
    月報 = {"勤怠の表記": "作り物 一郎", "原本の名前": "勤怠_20261108_月報.pdf", "見出し": ["日付", "休暇", "出勤", "退勤"],
          "行": [["11/4", "有給", "13:00", "18:00"], ["11/5", "有給", "9:00", "18:00"]]}
    for r in (PDFタイムカード.読む([カード], c), 勤怠システムの月報.読む([月報], c)):
        assert 日(r, "1", "2026-11-04")["休暇の単位"] == "午前半休" and 理由(r, "1", "2026-11-04") == []
        assert 決まらない in 理由(r, "1", "2026-11-05")
    メール = [{"種類": "勤怠", "勤怠の表記": "作り物 一郎", "日付": "11/4", "区分": "有休", "出": "9:00", "退": "12:00",
             "原本の名前": "勤怠_20261108_メール.txt"}]
    r = メールとメモ.読む(メール, c)
    assert 日(r, "1", "2026-11-04")["休暇の単位"] == "午後半休" and 理由(r, "1", "2026-11-04") == []


