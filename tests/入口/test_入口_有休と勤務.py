def test_半休と勤務に読んだ日は芯で仮にならず年休の半日に数える():
    行 = [[f"2026/11/{d}", "9:00", "18:00", "", ""] for d in (2, 3, 5, 6)] + [["2026/11/4", "13:00", "18:00", "", "有休"]]
    行 += [["2026/11/1", "", "", "", ""], ["2026/11/7", "", "", "", ""]]
    r = Excel出勤簿.読む(出勤簿(行), 作.文脈())
    assert r.人の状態() == {"2": "確定"}
    法の線 = {"時間.日の法定": "8", "時間.週の法定": "40", "割増.深夜の時間帯": "22:00〜5:00", "割増.60時間超の境": "60",
           "時間.休憩の長さ": [["6", 45], ["8", 60]], "休日.4週の休日数": 4}
    決 = {"時間.日の所定": "8", "時間.所定の始業": "9:00", "時間.所定の終業": "18:00", "時間.休憩の表": ["12:00〜13:00"]}
    x = 集計する(r.日, r.区間, 決まり={("作り物の会社", "2"): 決}, 法の線=法の線)
    値 = {q["項目"]: q["値"] for q in x["行"]}
    assert 値["年休（半日）"] == 1 and 値["出勤日数"] == 4.5
    assert not any("休暇の日に" in q["何が無いか"] or "労働の区間" in q["何が無いか"] for q in x["問い"])
