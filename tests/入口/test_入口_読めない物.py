"""読めない物・無い物が 要確認（人は仮）の印で返り、黙って確定にならない。"""
import pytest

import 入口_作り物 as 作
from 入口 import 口, PDFタイムカード, Excel出勤簿, 勤怠システムの月報, 集計済み勤怠表, メールとメモ, 手当控除の一覧
from 入口 import 日次の勤怠CSV


def 日(r, no, d):
    return next(a for a in r.日 if a["NO"] == no and a["日付"] == d)


def 理由(r, no, d=None):
    return [q["理由"] for q in r.要確認 if q["NO"] == no and (d is None or q["日付"] == d)]


def test_黒塗りで退が無い日は打刻抜けで要確認():
    r = PDFタイムカード.読む([作.カード], 作.文脈())
    a = 日(r, "1", "2026-11-06")
    assert a["読み取りの確かめ"] == "要確認" and "打刻抜け" in a["印"] and "黒塗り" in a["備考"]
    assert r.人の状態() == {"1": "仮"}


def test_休憩0は取っていない_空は書いていない():
    r = PDFタイムカード.読む([作.カード], 作.文脈())
    assert 日(r, "1", "2026-11-07")["時刻の無い休憩"] == "0"
    assert 日(r, "1", "2026-11-03")["時刻の無い休憩"] == ""


def test_式のエラーは要確認_原本に無い日は休日か欠勤で要確認():
    r = Excel出勤簿.読む(作.出勤簿, 作.文脈())
    assert any("式のエラー" in x for x in 理由(r, "2", "2026-11-04"))
    assert 日(r, "2", "2026-11-07")["日の種類"] == "休日" and "原本に無い" in 日(r, "2", "2026-11-07")["印"]
    assert 日(r, "2", "2026-11-01")["読み取りの確かめ"] == "要確認"
    assert 日(r, "2", "2026-11-06")["休暇の種類"] == "代休"
    assert "代休の相手の日が無い" in 理由(r, "2", "2026-11-06")


def test_メモを重ねると_重ねた日だけ置き換わる():
    c = 作.文脈()
    基 = Excel出勤簿.読む(作.出勤簿, c)
    上 = メールとメモ.読む(作.連絡, c, 作.手当の辞書, 作.手当の単価)
    r = 口.重ねる(基, 上)
    assert 日(r, "2", "2026-11-06")["代休の相手の日"] == "2026-11-01"
    assert 理由(r, "2", "2026-11-06") == []
    assert 日(r, "2", "2026-11-05")["日の種類"] == "休暇"
    assert any("来週" in x for x in 理由(r, "2"))  # 日付に読めない連絡は他の日を上書きせず要確認だけ
    assert 日(r, "2", "2026-11-01")["日の種類"] == "休日" and 日(r, "2", "2026-11-01")["原本の種別"] == "Excel出勤簿"
    assert any("曖昧" in x for x in 理由(r, "1", "2026-11-04"))
    assert r.人の状態()["2"] == "仮"


def test_月報の打刻エラーと読めない区分は要確認():
    r = 勤怠システムの月報.読む([作.月報], 作.文脈())
    assert any("打刻エラー" in x for x in 理由(r, "1", "2026-11-03"))
    assert any("免除" in x for x in 理由(r, "1", "2026-11-05"))
    a = 日(r, "1", "2026-11-02")
    assert "手で直した" in a["印"] and a["原本の時間"] == "所定内=480"
    assert 日(r, "1", "2026-11-07")["日の種類"] == "休日勤務"


def test_日次の勤怠CSV_つなぎに無い人は仮のNO_顧客だけの区分は要確認():
    r = 日次の勤怠CSV.読む(作.日次のCSV, "勤怠_日次.csv", 作.文脈(つなぎ=作.つなぎ), 作.道具)
    assert "仮:作り物 三郎" in r.人の状態() and r.人の状態()["仮:作り物 三郎"] == "仮"
    assert any("作り物の区分" in x for x in 理由(r, "1", "2026-11-04"))
    r2 = 日次の勤怠CSV.読む(作.日次のCSV, "勤怠_日次.csv", 作.文脈(つなぎ=作.つなぎ, 区分の読み替え={"作り物の区分": "出勤"}), 作.道具)
    assert 理由(r2, "1", "2026-11-04") == []
    assert 日(r2, "1", "2026-11-07")["休日の区分"] == "所定"


def test_日次の勤怠CSV_列が無ければ止まり_列名を渡せば読む():
    csv字 = 作.日次のCSV.replace("出勤時刻", "始業")
    with pytest.raises(ValueError):
        日次の勤怠CSV.読む(csv字, "勤怠_日次.csv", 作.文脈(つなぎ=作.つなぎ), 作.道具)
    r = 日次の勤怠CSV.読む(csv字, "勤怠_日次.csv", 作.文脈(つなぎ=作.つなぎ), 作.道具, 列名={**作.列名, "出": "始業"})
    assert 日(r, "1", "2026-11-02")["日の種類"] == "勤務"


def test_集計表_対応の無い欄と足し算の合わない人は要確認():
    r = 集計済み勤怠表.読む(作.集計表, 作.文脈(), 作.集計表の対応, "60進", 見ない=("部署",))
    assert r.人の状態() == {"1": "確定", "2": "仮"}
    assert any("謎の欄" in x for x in 理由(r, "2"))
    assert all(x["項目"] in 口.月の項目 for x in r.月の数字)
    with pytest.raises(ValueError):
        集計済み勤怠表.読む(作.集計表, 作.文脈(), {"氏名": "勤怠の表記", "出勤日数": "出勤の日"})


def test_手当控除_辞書に無い項目と引けない人と単価の無い物は要確認():
    r = 手当控除の一覧.読む(作.手当, 作.文脈(), "変更_手当.pdf", 作.手当の辞書, {})
    assert any("書類だけの言い方" in x for x in 理由(r, "2"))
    assert any("単価" in x for x in 理由(r, "1"))
    assert "仮:作り物 四郎" in r.人の状態()
    r2 = 手当控除の一覧.読む(作.手当, 作.文脈(), "変更_手当.pdf", 作.手当の辞書, 作.手当の単価)
    assert [x["値"] for x in r2.月の変動 if x["NO"] == "1"] == ["5400"]


