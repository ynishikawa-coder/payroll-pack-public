def test_日次の勤怠CSV_列名と道具を渡さなければ止まり_既定の列名で読まない():
    人だけ = [t for t in 作.つなぎ if t["NO"]]   # 列名の行（NO 空）が無い つなぎ
    with pytest.raises(ValueError, match="既定の列名は持たない"):
        日次の勤怠CSV.読む(作.日次のCSV, "勤怠_日次.csv", 作.文脈(つなぎ=人だけ), 作.道具)
    with pytest.raises(ValueError, match="既定の列名は持たない"):
        日次の勤怠CSV.読む(作.日次のCSV, "勤怠_日次.csv", 作.文脈(つなぎ=作.つなぎ), "別の道具")
    with pytest.raises(ValueError, match="道具"):
        日次の勤怠CSV.読む(作.日次のCSV, "勤怠_日次.csv", 作.文脈(つなぎ=作.つなぎ), "")
    with pytest.raises(ValueError, match="の外"):
        日次の勤怠CSV.読む(作.日次のCSV, "勤怠_日次.csv", 作.文脈(つなぎ=作.つなぎ), 作.道具, 列名={**作.列名, "謎": "x"})
    # 列名を引数で渡しても つなぎ の列の行で渡しても同じに読む
    a = 日次の勤怠CSV.読む(作.日次のCSV, "勤怠_日次.csv", 作.文脈(つなぎ=人だけ), 作.道具, 列名=作.列名)
    b = 日次の勤怠CSV.読む(作.日次のCSV, "勤怠_日次.csv", 作.文脈(つなぎ=作.つなぎ), 作.道具)
    assert a.日 == b.日 and a.区間 == b.区間
