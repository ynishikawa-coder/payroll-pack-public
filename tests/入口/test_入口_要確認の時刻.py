"""会社の決まり `時間.要確認の時刻`（作業のルールの「手書きの退勤は要確認」など）を入口が当てる（作り物の原本だけ）。"""
import 入口_作り物 as 作
from 入口 import PDFタイムカード, メールとメモ


def _理由(r, no, d):
    return [q["理由"] for q in r.要確認 if q["NO"] == no and q["日付"] == d]


def test_手書きの退は決まりがあれば要確認():
    # 作り物のカード: 11/4 の退は「13:00(手)」＝手書き
    r = PDFタイムカード.読む([作.カード], 作.文脈(要確認の時刻={("退", "手書き")}))
    assert any("退の時刻が手書き" in x for x in _理由(r, "1", "2026-11-04"))


def test_決まりが無ければ手書きでも今までどおり():
    r = PDFタイムカード.読む([作.カード], 作.文脈())
    assert not any("手書き" in x for x in _理由(r, "1", "2026-11-04"))


def test_出だけを決めた時は退の手書きを要確認にしない():
    r = PDFタイムカード.読む([作.カード], 作.文脈(要確認の時刻={("出", "手書き")}))
    assert not any("手書き" in x for x in _理由(r, "1", "2026-11-04"))


def test_メモの退も手書き():
    連絡 = [{"種類": "勤怠", "勤怠の表記": "作り物 一郎", "日付": "11/2", "出": "9:00", "退": "18:00", "原本の名前": "作り物のメモ"}]
    r = メールとメモ.読む(連絡, 作.文脈(要確認の時刻={("*", "手書き")}))
    assert any("退の時刻が手書き" in x for x in _理由(r, "1", "2026-11-02"))


# ── 印字の時間数を原本の時間へ写す・手書きの日は時間数を求めない ──

_2日のカード = {
    "勤怠の表記": "作り物 一郎", "原本の名前": "勤怠_20261108_カード.pdf",
    "見出し": ["日", "出", "退", "休憩", "時間数"],
    "行": [["2", "9:00", "18:15", "60", "9:15"],       # 印字 9:15 の日
           ["3", "9:00", "18:00(手)", "60", ""]],       # 手書きの退勤の日（印字の時間数は無い）
}


def test_印字の時間数は原本の時間へ写し_手書きの日は時間数を求めない():
    from 入口.口 import 読みの型
    文 = 作.文脈(要確認の時刻={("退", "手書き")})
    r = PDFタイムカード.読む([_2日のカード], 文)
    A = {a["日付"]: a for a in r.日 if a["NO"] == "1"}
    assert A["2026-11-02"]["原本の時間"] == "出勤から退勤まで=555"
    assert A["2026-11-03"]["原本の時間"] == ""
    二日 = ("2026-11-02", "2026-11-03")   # カードに無い日（原本にこの日が無い）は見ない
    理由 = [(q["日付"], q["理由"]) for q in r.要確認 if q["NO"] == "1" and q["日付"] in 二日]
    assert 理由 == [("2026-11-03", "退の時刻が手書き（時間.要確認の時刻＝人が確かめる）")], 理由
    # 手書きの答えを当てると要確認は 0（印字の時間数の要確認が残らない）
    何 = 読みの型(理由[0][1])
    答え = {"1": [{"番号": "Q1", "何が無いか": 何, "種類": "時刻", "答え": "手書きの時刻で数える", "列": {}, "時刻": {}, "日付": []}]}
    r = PDFタイムカード.読む([_2日のカード], 作.文脈(要確認の時刻={("退", "手書き")}, 日の答え=答え))
    assert [q for q in r.要確認 if q["NO"] == "1" and q["日付"] in 二日] == []


def test_カードの月のメモは最後の日の原本の時間へ():
    カード = {**_2日のカード, "月のメモ": {"夜休憩の回数": "3", "読めない": "三回"}}
    r = PDFタイムカード.読む([カード], 作.文脈())
    A = {a["日付"]: a for a in r.日 if a["NO"] == "1" and a["原本の時間"]}
    assert A["2026-11-03"]["原本の時間"] == "夜休憩の回数=3"
    assert any("月のメモ 読めない 三回" in a["備考"] for a in r.日 if a["NO"] == "1")
