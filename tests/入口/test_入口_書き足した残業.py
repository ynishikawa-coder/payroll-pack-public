"""手書きで余白・欄に足された残業 → 表 A の 書き足した残業。作り物の値だけ。

1. 日の行に結べて時間に読めた書き足しは 分の整数の字 で列に置く（備考に字で入れない）
2. 読めない字（`1h`・書き方の決まらない数）は推さず、備考に字のまま残して要確認（その人は仮）
3. 日の行に結べない余白の書き足し（表の メモ）は今までどおり 行に結べない字 の要確認
"""
import 入口_作り物 as 作
from 入口 import Excel出勤簿, PDFタイムカード, 口, _日の表

列 = "書き足した残業"


def _日(r, d):
    return next(a for a in r.日 if a["日付"] == d)


def _理由(r, d):
    return [q["理由"] for q in r.要確認 if q["日付"] == d]


def _出勤簿(足):
    return {"勤怠の表記": "作り物 一郎", "原本の名前": "勤怠_20261108_出勤簿.xlsx",
            "見出し": ["日付", "出勤", "退勤", "書き足した残業"], "行": [["2026/11/2", "9:00", "18:00", 足]]}


def test_列は表Aの列にある():
    assert 列 in 口.表Aの列


def test_出勤簿の書き足した残業は分で列に入り備考に入らない():
    r = Excel出勤簿.読む(_出勤簿("1:30"), 作.文脈())
    a = _日(r, "2026-11-02")
    assert a[列] == "90" and "残業" not in a["備考"]
    assert not any("書き足した残業" in x for x in _理由(r, "2026-11-02"))


def test_カードの手書きの印つきの書き足しも分で入る():
    カード = {"勤怠の表記": "作り物 一郎", "原本の名前": "勤怠_20261108_カード.pdf",
            "見出し": ["日", "出", "退", "残業（手書き）"], "行": [["2", "9:00", "18:00", "(手)残業 0:45"]]}
    a = _日(PDFタイムカード.読む([カード], 作.文脈()), "2026-11-02")
    assert a[列] == "45" and a["備考"] == ""


def test_書き足しの無い日は列が空():
    a = _日(Excel出勤簿.読む(_出勤簿(""), 作.文脈()), "2026-11-02")
    assert a[列] == ""


def test_読めない書き足しは備考に残して要確認():
    for 字 in ("1h", "30分", "1.5", "0:00", "?"):
        r = Excel出勤簿.読む(_出勤簿(字), 作.文脈())
        a = _日(r, "2026-11-02")
        assert a[列] == "", 字
        assert f"書き足した残業 {字}" in a["備考"], 字
        assert f"書き足した残業「{字}」が時間に読めない" in _理由(r, "2026-11-02"), 字
        assert r.人の状態()["1"] == "仮", 字


def test_書き方の決まった表は数だけの字も読む():
    assert _日の表.書き足した残業("1.5", "10進")[0] == "90"
    assert _日の表.書き足した残業("1.30", "60進")[0] == "90"
    assert _日の表.書き足した残業("1.5", "分")[0] == ""   # 書き方が決まらない＝90 分か 110 分か推さない


def test_日の行に結べない余白の書き足しは今までどおり要確認():
    表 = dict(_出勤簿(""), メモ=["11/2 残業 1:00"])
    r = Excel出勤簿.読む(表, 作.文脈())
    assert _日(r, "2026-11-02")[列] == ""
    assert 口.結べない字の理由("11/2 残業 1:00") in _理由(r, "2026-11-02")
