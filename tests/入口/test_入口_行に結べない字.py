"""日の行・人に結べない字（日の空いた行の注・名の空いた行・表の頭や余白のメモ）を入口が黙って捨てず、
字ごと要確認に出す（その人は仮＝出口へ出ない）。作り物の値だけ。"""
import 入口_作り物 as 作
from 入口 import 口, Excel出勤簿, PDFタイムカード, 集計済み勤怠表
from 入口 import 日次の勤怠CSV


def 理由(r, no):
    return [q["理由"] for q in r.要確認 if q["NO"] == no]


def 結べない(r, no, 字):
    return any(字 in x and 口.読みの型(x) == 口.結べない字の型 for x in 理由(r, no))


何人もの出勤簿 = {
    "原本の名前": "勤怠_20261108_出勤簿.xlsx",
    "見出し": ["氏名", "日付", "出勤", "退勤", "備考"],
    "行": [
        ["作り物 一郎", "2026/11/2", "9:00", "18:00", ""],
        ["作り物 二子", "2026/11/2", "9:00", "18:00", ""],
        ["", "", "", "", "土曜日の出勤は計算しない"],
    ],
}


def test_何人もの表で名も日も空の行の注は表の全員の要確認に字ごと出る():
    r = Excel出勤簿.読む(何人もの出勤簿, 作.文脈())
    assert 結べない(r, "1", "土曜日の出勤は計算しない")
    assert 結べない(r, "2", "土曜日の出勤は計算しない")
    assert r.人の状態() == {"1": "仮", "2": "仮"}


def test_一人一枚の表で日の空いた行の注は字ごと要確認に残る():
    表 = {"勤怠の表記": "作り物 一郎", "原本の名前": "勤怠_20261108_出勤簿.xlsx",
         "見出し": ["日付", "出勤", "退勤", "備考"],
         "行": [["2026/11/2", "9:00", "18:00", ""], ["", "", "", "土曜日の出勤は計算しない"]]}
    r = Excel出勤簿.読む(表, 作.文脈())
    assert 結べない(r, "1", "土曜日の出勤は計算しない")


def test_表のメモは名の出た人だけを要確認にする():
    表 = dict(何人もの出勤簿, 行=何人もの出勤簿["行"][:2], メモ=["夜勤 19:00〜22:00 作り物 一郎"])
    r = Excel出勤簿.読む(表, 作.文脈())
    assert 結べない(r, "1", "夜勤 19:00〜22:00")
    assert not any("夜勤" in x for x in 理由(r, "2"))


def test_名の出ない表のメモは表の全員を要確認にする():
    表 = dict(何人もの出勤簿, 行=何人もの出勤簿["行"][:2], メモ=["祝日は休み"])
    r = Excel出勤簿.読む(表, 作.文脈())
    assert 結べない(r, "1", "祝日は休み") and 結べない(r, "2", "祝日は休み")


def test_カードの数でない月のメモは要確認():
    カード = dict(作.カード, 月のメモ={"夜勤": "19:00〜22:00"})
    r = PDFタイムカード.読む([カード], 作.文脈())
    assert 結べない(r, "1", "19:00〜22:00")


def test_日の行の備考に区間に無い時刻の範囲があれば要確認():
    表 = {"勤怠の表記": "作り物 一郎", "原本の名前": "勤怠_20261108_出勤簿.xlsx",
         "見出し": ["日付", "出勤", "退勤", "備考"],
         "行": [["2026/11/2", "", "", "夜勤 19:00〜22:00"], ["2026/11/3", "9:00", "18:00", "9:00〜18:00 通常"]]}
    r = Excel出勤簿.読む(表, 作.文脈())
    two = [q["理由"] for q in r.要確認 if q["日付"] == "2026-11-02"]
    three = [q["理由"] for q in r.要確認 if q["日付"] == "2026-11-03"]
    assert any("19:00〜22:00" in x for x in two)
    assert not any("時刻の範囲" in x for x in three)


def test_結べない字は確かめたの答えで外せる():
    型 = 口.結べない字の型
    assert 口.日の答えの種類(型) == "区分"
    答え = {"1": [{"番号": "Q1", "何が無いか": 型, "種類": "区分", "答え": "読んだ（足す物は無い）", "列": {}}],
           "2": [{"番号": "Q2", "何が無いか": 型, "種類": "区分", "答え": "確かめた（勤怠に足す物は無い）", "列": {}}]}
    r = Excel出勤簿.読む(何人もの出勤簿, 作.文脈(日の答え=答え))
    assert not any(口.読みの型(x) == 型 for x in 理由(r, "1") + 理由(r, "2"))


def test_結べない字は括弧に足す物を書いた確かめたでは外れない():
    型 = 口.結べない字の型
    答え = {"1": [{"番号": "Q1", "何が無いか": 型, "種類": "区分", "答え": "読んだ（土曜は休日）", "列": {}}]}
    r = Excel出勤簿.読む(何人もの出勤簿, 作.文脈(日の答え=答え))
    assert any(口.読みの型(x) == 型 for x in 理由(r, "1"))


def test_日次のCSVの読めない日付と人の無い行は要確認():
    csv字 = (作.日次のCSV
            + "A-01,作り物 一郎,11月5日ごろ,出勤,09:00,18:00,1:00,8:00,0:00,0:00\n"
            + ",,,,,,,,,夜勤は別紙\n")
    r = 日次の勤怠CSV.読む(csv字, "勤怠_20261108_日次.csv", 作.文脈(つなぎ=作.つなぎ), 作.道具)
    assert any("11月5日ごろ" in x for x in 理由(r, "1"))
    assert 結べない(r, "1", "夜勤は別紙")
    # 期間の外と読める日付（12/01）は今までどおり黙って読まない
    assert not any("2026/12/01" in x for x in 理由(r, "1"))


def test_集計表の人の無い行は表の全員の要確認():
    表 = dict(作.集計表, 行=作.集計表["行"] + [["", "", "", "", "", "", "", "", "", "", "夜勤手当は別"]])
    r = 集計済み勤怠表.読む(表, 作.文脈(), 作.集計表の対応, "60進", 見ない=("部署",))
    assert 結べない(r, "1", "夜勤手当は別") and 結べない(r, "2", "夜勤手当は別")
    assert r.人の状態() == {"1": "仮", "2": "仮"}
