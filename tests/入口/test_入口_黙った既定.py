"""入口の黙った既定を畳んだ注入の試験（作り物の値だけ）。

- 集計済み勤怠表の 時間の書き方 は既定を持たない: 渡さない・60進／10進 の外の字は止める（前: 黙って 60進 と読んだ）。
- 休暇の種類だけで単位の無い日（殻の 区分の読み替え の語に単位が無い）は 全日 で埋めず要確認＝その人は仮
  （前: 黙って 休暇の単位＝全日 にして確定で出た）。
"""
import pytest

import 入口_作り物 as 作
from 入口 import 口, Excel出勤簿, 集計済み勤怠表


def test_集計表の時間の書き方を渡さなければ止める():
    with pytest.raises(TypeError):
        集計済み勤怠表.読む(作.集計表, 作.文脈(), 作.集計表の対応)          # 前: 60進 と読んで進んだ
    for 字 in (None, "", "時:分", "60"):
        with pytest.raises(ValueError, match="時間の書き方"):
            集計済み勤怠表.読む(作.集計表, 作.文脈(), 作.集計表の対応, 字)
    for 字 in ("60進", "10進"):                                            # 決まった 2 つの字は今までどおり読む
        assert 集計済み勤怠表.読む(作.集計表, 作.文脈(), 作.集計表の対応, 字, 見ない=("部署",)).人の状態()


def test_単位の無い休暇の語は全日で埋めず要確認():
    c = 作.文脈(区分の読み替え={"作り物の休み": {"日の種類": "休暇", "休暇の種類": "年休"}})
    r = Excel出勤簿.読む({"原本の名前": "勤怠_20261108_出勤簿.xlsx", "見出し": ["氏名", "日付", "出勤", "退勤", "実働", "区分"],
                        "行": [["作り物 二子", "2026/11/4", "", "", "", "作り物の休み"]]}, c)
    a = next(x for x in r.日 if x["NO"] == "2" and x["日付"] == "2026-11-04")
    assert a["休暇の種類"] == "年休" and a["休暇の単位"] == ""               # 前: 全日
    assert a["読み取りの確かめ"] == 口.要確認
    assert "休暇の種類があるのに単位が無い" in [q["理由"] for q in r.要確認 if q["NO"] == "2"]
    assert r.人の状態()["2"] == "仮"
