"""入口と芯/集計（型の版 21）: 区分の語の後ろの（h:mm）はその日の休暇の時間。休暇の語でない語に付いた時は読めない（黙って捨てない）。"""
import 入口_作り物 as 作
from 入口 import 口


def test_有給の区分の後ろの時間はその日の休暇の時間():
    f, bad = 口.区分を読む("有給休暇（6:00）", 作.文脈())
    assert bad == [] and f["休暇の種類"] == "年休" and f["休暇の単位"] == "全日" and f["休暇の時間"] == "360"
    f, bad = 口.区分を読む("午前半休(3:30)", 作.文脈())
    assert bad == [] and f["休暇の単位"] == "午前半休" and f["休暇の時間"] == "210"


def test_休暇でない語の時間は読めない():
    f, bad = 口.区分を読む("出勤（8:00）", 作.文脈())
    assert bad == ["出勤（8:00）"] and "休暇の時間" not in f


def test_時間の無い有給は今までどおり():
    f, bad = 口.区分を読む("有給休暇", 作.文脈())
    assert bad == [] and "休暇の時間" not in f
