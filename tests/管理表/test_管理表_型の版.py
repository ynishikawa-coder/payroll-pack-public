"""管理表「会社」の 型の版 を書く口。作り物の会社だけ。"""
import importlib.util
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("管理表_試験_型の版", ここ.parent.parent / "管理表" / "管理表.py")
管理表 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(管理表)


def _今の値(*行):
    h = 管理表.見出し("会社")
    return [h] + [[{"会社": c, "組": "作り物の組", "型の版": v}.get(k, "") for k in h] for c, v in 行]


def test_型の版と配った日の行はそのまま書く口へ渡せる():
    手順 = 管理表.書く({"タブ": "会社", "今の値": _今の値(("作り物A", "3")), "会社の一覧": {"作り物A": "作り物の組"},
                     "受け持つ組": "作り物の組", "行たち": [{"会社": "作り物A", "型の版": "11", "最後に配った日": "2026-11-16"}]})
    assert {(s["列"], s["値"]) for s in 手順} == {("型の版", "11"), ("最後に配った日", "2026-11-16")}


def test_書く手順は字のまま書く印を持つ():
    手順 = 管理表.書く({"タブ": "会社", "今の値": _今の値(("作り物A", "3")), "会社の一覧": {"作り物A": "作り物の組"},
                     "受け持つ組": "作り物の組", "行たち": [{"会社": "作り物A", "型の版": "12"}]})
    assert 手順 and all(s["書き方"] == "RAW" for s in 手順)


def test_前の形の管理表は無い列を並べて拒む():
    # 前の形の 会社 タブ（型の版・選んだ部品 の列が無い）。書く口は無い列を言って拒む（黙って書かない）
    前 = [["会社", "組", "最後に配った日"], ["作り物A", "作り物の組", ""]]
    with pytest.raises(管理表.拒む, match="型の列.*型の版.*タブに無い"):
        管理表.書く({"タブ": "会社", "今の値": 前, "会社の一覧": {"作り物A": "作り物の組"}, "受け持つ組": "作り物の組",
                   "行たち": [{"会社": "作り物A", "型の版": "12"}]})


def test_立ち上げは型のタブを足し_違うタブは拒み_何度当てても同じ():
    全部 = 管理表.全部の見出し()
    D = 管理表.Driveのタブ
    手順 = 管理表.立ち上げ({"今のタブ": {"全社_会社": [["会社", "組"]], D("月の状況"): [全部["月の状況"]]}})
    assert {(s["する"], s["タブ"]) for s in 手順} == {("タブを足す", D(t)) for t in
                                                   ("確認ページ", "会社", "賞与の状況", "突き合わせの記録", "出した物")}
    assert next(s for s in 手順 if s["タブ"] == D("会社"))["見出し"] == 全部["会社"]
    assert 管理表.立ち上げ({"今のタブ": {D(k): [h] for k, h in 全部.items()}}) == []
    with pytest.raises(管理表.拒む, match="会社（型に在って無い列"):
        管理表.立ち上げ({"今のタブ": {**{D(k): [h] for k, h in 全部.items()}, D("会社"): [["会社", "組"]]}})
