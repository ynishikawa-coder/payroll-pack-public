"""管理表の鍵（会社など）と会社の一覧の 状態 は、字のそろえ方の正本（芯/字.py）でそろえて比べる（台帳の束 K3）。
書く字はそろえない（行の字を勝手に書き換えない）。作り物の会社だけ。

根（2026-11-20）: `_探す` が鍵の値を字のそのままの一致で比べた（会社が「作り物の会社 」の行が見つからず、行が重なるか書き込みが
拒まれる）。`月の行` が 状態 == "止めた" を字のそのままの一致で見た（「止めた 」の会社にも月の行が作られる）。
"""
import importlib.util
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("管理表_試験_字の揺れ", ここ.parent.parent / "管理表" / "管理表.py")
管理表 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(管理表)

会社, 組 = "作り物の会社", "作り物の組"
支給月 = "2027.06支給（6月分）"
幅の無い字 = "​"
揺れた会社 = [会社 + " ", " " + 会社, 会社 + "　", "作り物の" + 幅の無い字 + "会社"]


def _表(名, *行たち):
    h = 管理表.見出し(名)
    return [h] + [[{**{k: "" for k in h}, **r}[k] for k in h] for r in 行たち]


@pytest.mark.parametrize("揺れ", 揺れた会社)
def test_会社の字が揺れた行も探して書き_鍵の字は書き換えない(揺れ):
    値 = _表("月の状況", {"会社": 揺れ, "組": 組, "支給月": 支給月, "外した人": "0"})
    手順 = 管理表.書く({"タブ": "月の状況", "今の値": 値, "会社の一覧": {会社: 組}, "受け持つ組": 組, "今日": "2027-06-30",
                     "行たち": [{"会社": 会社, "支給月": 支給月, "取り込み": "済", "外した人": "0"}]})
    assert [x["する"] for x in 手順] == ["値を書く", "値を書く"]   # 取り込み・更新日（行は足さない）
    assert all(x["列"] not in ("会社", "支給月") for x in 手順)


@pytest.mark.parametrize("揺れ", 揺れた会社)
def test_会社の字が揺れた行が在れば月の行を重ねて足さない(揺れ):
    値 = _表("月の状況", {"会社": 揺れ, "組": 組, "支給月": 支給月, "外した人": "0"})
    assert 管理表.月の行({"今の値": 値, "会社の一覧": [{"会社": 会社, "組": 組, "状態": "毎月"}], "支給月": 支給月}) == []


@pytest.mark.parametrize("状態", ["止めた", "止めた ", " 止めた", "止" + 幅の無い字 + "めた", "止めた　"])
def test_状態の字が揺れても止めた会社に月の行を足さない(状態):
    値 = _表("月の状況")
    一覧 = [{"会社": 会社, "組": 組, "状態": 状態}, {"会社": "作り物の別の会社", "組": 組, "状態": "毎月"}]
    手順 = 管理表.月の行({"今の値": 値, "会社の一覧": 一覧, "支給月": 支給月, "今日": "2027-06-01"})
    h = 管理表.見出し("月の状況")
    assert [x["値"][h.index("会社")] for x in 手順] == ["作り物の別の会社"]


def test_書く字は渡された字のまま():
    値 = _表("月の状況")
    手順 = 管理表.月の行({"今の値": 値, "会社の一覧": [{"会社": 会社 + " ", "組": 組, "状態": "毎月"}], "支給月": 支給月})
    h = 管理表.見出し("月の状況")
    assert [x["値"][h.index("会社")] for x in 手順] == [会社 + " "]
