"""管理表/管理表.py 月の段（会社の一覧の空の 状態 と、無い 月の状況 の行だけを起こす）の試験。値は作り物だけ。

防ぐ故障: 前の形から移した事務所で 月の状況 の行と 会社の一覧.状態 が空のまま毎月の流れが進む／起こす時に在る行・字の在るセルを上書きする／
  止めた会社の行を起こす／初回の確認が済んだ会社を 立ち上げ に戻す。
"""
import importlib.util
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("管理表_試験_月の段", 根 / "管理表" / "管理表.py")
管理表 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(管理表)

月 = 管理表.見出し("月の状況")
会社の見出し = 管理表.見出し("会社")


def 一覧(*行):
    return [["顧客ID", "会社", "組", "担当", "状態"], *[list(r) for r in 行]]


def 月の行(会社, 支給月, **kw):
    d = {k: "" for k in 月}
    d.update(会社=会社, 組="作り物の組", 支給月=支給月, **kw)
    return [d[k] for k in 月]


def 会社の行(会社, OK=""):
    d = {k: "" for k in 会社の見出し}
    d.update({"会社": 会社, "組": "作り物の組", "型の版": "1", "初回の確認の OK の日": OK})
    return [d[k] for k in 会社の見出し]


def 入力(**kw):
    return {"会社の一覧": 一覧(("901", "作り物A", "作り物の組", "", ""), ("902", "作り物B", "作り物の組", "", "毎月"),
                             ("903", "作り物C", "作り物の組", "", "止めた"), ("904", "作り物D", "作り物の組", "", "")),
            "会社": [会社の見出し, 会社の行("作り物A", "2099-01-05"), 会社の行("作り物D")],
            "今の値": [月, 月の行("作り物B", "2099.02支給（1月分）", 集計="済")],
            "月たち": [{"会社": c, "支給月": "2099.02支給（1月分）"} for c in ("作り物A", "作り物B", "作り物C", "作り物D")],
            "今日": "2099-02-01", **kw}


def test_空の状態だけを書き_OKの日で毎月と立ち上げを分ける():
    手 = [x for x in 管理表.月の段(入力()) if x["する"] == "値を書く"]
    assert [(x["セル"], x["前"], x["値"]) for x in 手] == [("E2", "", "毎月"), ("E5", "", "立ち上げ")]
    assert all(x["タブ"] == "2_会社の一覧" and x["列"] == "状態" for x in 手)


def test_在る行は触らず_止めた会社は起こさない():
    手 = 管理表.月の段(入力())
    足す = [x["値"] for x in 手 if x["する"] == "行を足す"]
    assert sorted(r[月.index("会社")] for r in 足す) == ["作り物A", "作り物D"]
    assert all(x["する"] in ("値を書く", "行を足す") for x in 手)
    # 在る行（作り物B）へは何も書かない＝月の状況へ 値を書く 手順が 1 つも無い
    assert not [x for x in 手 if x["する"] == "値を書く" and x["タブ"] != "2_会社の一覧"]


def test_もう一度当てると何もしない():
    x = 入力()
    手 = 管理表.月の段(x)
    後の一覧 = [list(r) for r in x["会社の一覧"]]
    for s in 手:
        if s["する"] == "値を書く":
            後の一覧[int(s["セル"][1:]) - 1][4] = s["値"]
    後の値 = x["今の値"] + [s["値"] for s in 手 if s["する"] == "行を足す"]
    assert 管理表.月の段({**x, "会社の一覧": 後の一覧, "今の値": 後の値}) == []


def test_知らない会社と読めない支給月は拒む():
    with pytest.raises(管理表.拒む):
        管理表.月の段(入力(月たち=[{"会社": "作り物Z", "支給月": "2099.02支給（1月分）"}]))
    with pytest.raises(管理表.拒む):
        管理表.月の段(入力(月たち=[{"会社": "作り物A", "支給月": "2099.02支給"}]))


def test_状態の列が無い一覧は拒む():
    with pytest.raises(管理表.拒む):
        管理表.月の段(入力(会社の一覧=[["顧客ID", "会社", "組"], ["901", "作り物A", "作り物の組"]]))
