"""管理表「会社」の寄せ中の印（寄せる道具.md §1.5 の 1・7）。作り物の会社だけ。

誤りの類: 寄せが途中で止まった会社が半ば寄った形のまま毎月の仕事へ進む／寄せ中のまま訳が残らない／印が読めない時に
「寄せ中でない」と黙って読む。→ 印の列の名と選べる値は型から読み、読めない時は拒む。
"""
import importlib.util
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("管理表_試験_寄せの印", ここ.parent.parent / "管理表" / "管理表.py")
管理表 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(管理表)


def _今の値(*行):
    h = 管理表.見出し("会社")
    return [h] + [[{"会社": c, "組": "作り物の組", "型の版": "3", "寄せ": 寄せ, "寄せの理由": 理由}.get(k, "") for k in h]
                  for c, 寄せ, 理由 in 行]


def test_寄せ中と理由を読む():
    v = _今の値(("作り物A", "寄せ中", "書く手順 2/5 で落ちた"), ("作り物B", "", ""))
    assert 管理表.寄せの印({"今の値": v, "会社": "作り物A"}) == {"寄せ中": True, "理由": "書く手順 2/5 で落ちた"}
    assert 管理表.寄せの印({"今の値": v, "会社": "作り物B"}) == {"寄せ中": False, "理由": ""}


@pytest.mark.parametrize("今の値, 会社, 当たる", [
    (_今の値(("作り物A", "", "")), "作り物C", "行が無い"),
    (_今の値(("作り物A", "寄せ済み", "")), "作り物A", "選べない値"),
    ([["会社", "組", "型の版"], ["作り物A", "作り物の組", "3"]], "作り物A", "見出し"),
])
def test_読めない印は寄せ中でないと読まず拒む(今の値, 会社, 当たる):
    with pytest.raises(管理表.拒む, match=当たる):
        管理表.寄せの印({"今の値": 今の値, "会社": 会社})


def test_寄せの行は書く口を通って立てる_止まった_外すを書く():
    v = _今の値(("作り物A", "", ""))
    書く = lambda 行: 管理表.書く({"タブ": "会社", "今の値": v, "会社の一覧": {"作り物A": "作り物の組"},
                              "受け持つ組": "作り物の組", "行たち": [行]})
    立てる = 書く(管理表.寄せの行({"会社": "作り物A", "段": "立てる"}))
    assert [(s["列"], s["値"]) for s in 立てる] == [("寄せ", "寄せ中")]
    止 = 書く(管理表.寄せの行({"会社": "作り物A", "段": "止まった", "理由": "照らしが合わない"}))
    assert {(s["列"], s["値"]) for s in 止} == {("寄せ", "寄せ中"), ("寄せの理由", "照らしが合わない")}
    v2 = _今の値(("作り物A", "寄せ中", "照らしが合わない"))
    外す = 管理表.書く({"タブ": "会社", "今の値": v2, "会社の一覧": {"作り物A": "作り物の組"}, "受け持つ組": "作り物の組",
                     "行たち": [管理表.寄せの行({"会社": "作り物A", "段": "外す"})]})
    assert {(s["列"], s["値"]) for s in 外す} == {("寄せ", ""), ("寄せの理由", "")}


@pytest.mark.parametrize("入力, 当たる", [
    ({"会社": "作り物A", "段": "止まった"}, "理由"),
    ({"会社": "作り物A", "段": "止まった", "理由": "一\n二"}, "1 行"),
    ({"会社": "作り物A", "段": "外す", "理由": "x"}, "止まった の時だけ"),
    ({"会社": "作り物A", "段": "消す"}, "どれか"),
    ({"段": "立てる"}, "会社"),
])
def test_寄せの行は訳の無い止まりと知らない段を拒む(入力, 当たる):
    with pytest.raises(管理表.拒む, match=当たる):
        管理表.寄せの行(入力)


def test_見出しの並びが型と違えば寄せ中でないと読まず拒む():
    """列の名は同じで並びだけ違う（寄せ と 寄せの理由 を入れ替えた）管理表を、並びのまま読んで寄せ中を見落とさない。"""
    h = 管理表.見出し("会社")
    i, j = h.index("寄せ"), h.index("寄せの理由")
    def 入れ替え(r):
        r = list(r)
        r[i], r[j] = r[j], r[i]
        return r
    v = [入れ替え(r) for r in _今の値(("作り物A", "寄せ中", ""))]
    with pytest.raises(管理表.拒む, match="見出し"):
        管理表.寄せの印({"今の値": v, "会社": "作り物A"})
