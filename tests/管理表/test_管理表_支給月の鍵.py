"""管理表の鍵の支給月は正本（芯/支給月の字.py）で読む: 管理表の字 `YYYY.MM支給（M月分）` の行を、出荷の口が渡す殻の字
`YYYY.MM支給` で探して当たる。読めない字・別の月は拒む（注入の試験）。作り物の会社だけ。

根（2026-11-19）: 管理表「月の状況」の行の支給月は決まりどおり `2026.11支給（11月分）` なのに、書く口が鍵を字のまま比べたので、
出荷の口（`出す前の照らし.py 管理表の行` は `2026.11支給` を渡す）が「鍵の行が無い」で止まった。
"""
import importlib.util
from pathlib import Path

import pytest

from 芯 import 支給月の字

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("管理表_試験_支給月の鍵", ここ.parent.parent / "管理表" / "管理表.py")
管理表 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(管理表)

会社, 組 = "作り物の会社", "作り物の組"
一覧 = {会社: 組, "作り物の別の会社": "作り物の別の組"}
置き場の字 = "2027.06支給（6月分）"


def _月の状況(*行たち):
    h = 管理表.見出し("月の状況")
    return [h] + [[{**{k: "" for k in h}, "外した人": "0", **r}[k] for k in h] for r in 行たち]


def _書く(値, 支給月, タブ="月の状況", 回="月"):
    行 = {"会社": 会社, "支給月": 支給月, "取り込み": "済", "外した人": "0"}
    return 管理表.書く({"タブ": タブ, "今の値": 値, "会社の一覧": 一覧, "受け持つ組": 組, "行たち": [行], "今日": "2027-06-30", "回": 回})


@pytest.mark.parametrize("渡す字", ["2027.06支給", 置き場の字])
def test_管理表の字の行を殻の字でも置き場の字でも探して書く(渡す字):
    値 = _月の状況({"会社": "作り物の別の会社", "組": "作り物の別の組", "支給月": 置き場の字},
                {"会社": 会社, "組": 組, "支給月": "2027.05支給（5月分）"},
                {"会社": 会社, "組": 組, "支給月": 置き場の字})
    手順 = _書く(値, 渡す字)
    assert [(x["セル"], x["値"]) for x in 手順 if x["列"] == "取り込み"] == [("F4", "済")]
    assert all(x["列"] != "支給月" for x in 手順)   # 鍵の字は書き換えない（管理表の字のまま）


@pytest.mark.parametrize("渡す字", ["2027-06", "2027.06", "2027.6支給", " 2027.06支給", "２０２７.06支給", "2027.06支給(6月分)",
                                 "2027.06支給（9月分）", "2027.13支給", "", "2027.06支給（6月分）だけ"])
def test_探す鍵の支給月が殻の字でも置き場の字でもなければ拒む(渡す字):
    値 = _月の状況({"会社": 会社, "組": 組, "支給月": 置き場の字})
    with pytest.raises(管理表.拒む, match="支給月|鍵の列"):
        _書く(値, 渡す字)


def test_別の月の行しか無ければ行が無いで止まる():
    値 = _月の状況({"会社": 会社, "組": 組, "支給月": "2027.05支給（5月分）"})
    with pytest.raises(管理表.拒む, match="行が無い"):
        _書く(値, "2027.06支給")


@pytest.mark.parametrize("行の字", ["2027-06", "2027.06支給（6月分", "6月分"])
def test_同じ会社の行の支給月が読めなければ黙って飛ばさず拒む(行の字):
    値 = _月の状況({"会社": 会社, "組": 組, "支給月": 行の字}, {"会社": 会社, "組": 組, "支給月": 置き場の字})
    with pytest.raises(管理表.拒む, match="2 行目の支給月"):
        _書く(値, "2027.06支給")


def test_同じ支給月を別の字で2行持てば2つあると拒む():
    値 = _月の状況({"会社": 会社, "組": 組, "支給月": "2027.06支給"}, {"会社": 会社, "組": 組, "支給月": 置き場の字})
    with pytest.raises(管理表.拒む, match="2 つある"):
        _書く(値, 置き場の字)


def test_賞与の状況も同じ読みで探す_殻の字の行を置き場の字で探して当たる():
    h = 管理表.見出し("賞与の状況")
    値 = [h, [{**{k: "" for k in h}, "会社": 会社, "組": 組, "支給月": "2027.06支給", "外した人": "0"}[k] for k in h]]
    手順 = _書く(値, 置き場の字, タブ="賞与の状況", 回="賞与")
    assert [x["する"] for x in 手順] == ["値を書く", "値を書く"] and {x["列"] for x in 手順} == {"取り込み", "更新日"}


def test_月の行は置き場の字だけで起こし_ほかの字は拒む():
    入 = {"今の値": _月の状況(), "会社の一覧": [{"会社": 会社, "組": 組}], "今日": "2027-06-01"}
    手順 = 管理表.月の行({**入, "支給月": 置き場の字})
    assert 手順[0]["値"][管理表.見出し("月の状況").index("支給月")] == 置き場の字
    for 字 in ("2027.06支給", "2027-06", "2027.06支給（9月分）"):
        with pytest.raises(管理表.拒む, match="YYYY.MM支給（M月分）"):
            管理表.月の行({**入, "支給月": 字})
    # 起こした行は殻の字で探して当たる（月の行が起こす字と書く口が探す字が 1 つの正本で合う）
    値 = _月の状況({"会社": 会社, "組": 組, "支給月": 置き場の字})
    assert 管理表.月の行({**入, "今の値": 値, "支給月": 置き場の字}) == []
    assert _書く(値, "2027.06支給")


def test_支給月の字の置き場の形は正本が組み_ちょうどの形だけ読む():
    assert 支給月の字.字にする(2027, 6, "置き場", 月分=6) == 置き場の字
    assert 支給月の字.字にする(2027, 1, "置き場", 月分=11) == "2027.01支給（11月分）"   # 翌々月払い・年をまたぐ
    for 月分 in (7, 3, 0, 13):
        with pytest.raises(ValueError):
            支給月の字.字にする(2027, 6, "置き場", 月分=月分)
    with pytest.raises(ValueError):
        支給月の字.字にする(2027, 6, "置き場")
    with pytest.raises(ValueError):
        支給月の字.字にする(2027, 6, "殻", 月分=6)
    assert 支給月の字.置き場の字を読む(置き場の字) == (2027, 6, 6)
    assert 支給月の字.鍵の年月(置き場の字) == 支給月の字.鍵の年月("2027.06支給") == (2027, 6)
    for 字 in ("2027.06支給（06月分）", "2027.06支給(6月分)", "2027-06", None, 202706):
        assert 支給月の字.鍵の年月(字) is None, 字


def test_命令の書く口も同じ読みで当たる(tmp_path):
    import json
    import subprocess
    import sys
    値 = _月の状況({"会社": 会社, "組": 組, "支給月": 置き場の字})
    入 = {"タブ": "月の状況", "今の値": 値, "会社の一覧": 一覧, "受け持つ組": 組, "回": "月", "今日": "2027-06-30",
         "行たち": [{"会社": 会社, "支給月": "2027.06支給", "取り込み": "済", "外した人": "0"}]}
    r = subprocess.run([sys.executable, str(ここ.parent.parent / "管理表" / "管理表.py"), "書く"], input=json.dumps(入, ensure_ascii=False),
                       capture_output=True, text=True, cwd=tmp_path)
    assert r.returncode == 0, r.stdout + r.stderr
    assert any(x["列"] == "取り込み" for x in json.loads(r.stdout))
