"""管理表は回（月・賞与）で行を分ける: 同じ会社・同じ支給月の月の給与と賞与を書いても、互いの行を上書きしない。作り物の会社だけ。

根: 月の状況 は会社×支給月で 1 行だけで、賞与の出荷を書くと同じ支給月の月の給与の行（取り込み・止まりの理由の今の版）を上書きした。
ここでは回ごとのタブ（月の状況・賞与の状況）へ分け、回を取り違えた書き方（賞与の行を 月の状況 へ）を拒むことを見る（注入の試験）。
"""
import importlib.util
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("管理表_試験_回", ここ.parent.parent / "管理表" / "管理表.py")
管理表 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(管理表)

会社, 組, 月 = "作り物の会社", "作り物の組", "2027.06支給"
一覧 = {会社: 組, "作り物の別の会社": "作り物の別の組"}


def _当てる(値: list[list], 手順: list[dict], タブ: str) -> list[list]:
    """殻が書く手順を当てるのと同じ（値を書く＝セル・行を足す＝下へ）。試験の中だけの小さな当て口。"""
    値 = [list(r) for r in 値]
    h = 値[0]
    for x in 手順:
        assert x["タブ"] == タブ and x["書き方"] == "RAW"
        if x["する"] == "行を足す":
            値.append(list(x["値"]))
        else:
            列, 行 = h.index(x["列"]), int("".join(c for c in x["セル"] if c.isdigit())) - 1
            assert x["セル"].startswith(管理表.列の字(列))
            値[行][列] = x["値"]
    return 値


def _月の状況():
    h = 管理表.見出し("月の状況")
    行 = {**{k: "" for k in h}, "会社": 会社, "組": 組, "支給月": 月, "外した人": "0"}
    return [h, [行[k] for k in h]]


def _書く(タブ, 値, 行, 回=None):
    x = {"タブ": タブ, "今の値": 値, "会社の一覧": 一覧, "受け持つ組": 組, "行たち": [行], "今日": "2027-06-30"}
    if 回 is not None:
        x["回"] = 回
    return 管理表.書く(x)


def test_回のタブは型の回から引き_知らない回は拒む():
    assert 管理表.回のタブ("月") == "月の状況" and 管理表.回のタブ("賞与") == "賞与の状況"
    with pytest.raises(管理表.拒む, match="回"):
        管理表.回のタブ("月給")


def test_同じ支給月の月の給与と賞与を書いても互いを上書きしない():
    月の値 = _月の状況()
    賞与の値 = [管理表.見出し("賞与の状況")]
    月の行 = {"会社": 会社, "支給月": 月, "取り込み": "済", "外した人": "0", "止まりの理由": "今の版: 取り込み_作り物_2027-06_v1 u1"}
    賞与の行 = {"会社": 会社, "支給月": 月, "取り込み": "仮", "外した人": "1", "止まりの理由": "今の版: 賞与の取り込み_作り物_2027-06-賞与_v1 u2"}
    月の値 = _当てる(月の値, _書く(管理表.回のタブ("月"), 月の値, 月の行, "月"), "月の状況")
    賞与の値 = _当てる(賞与の値, _書く(管理表.回のタブ("賞与"), 賞与の値, 賞与の行, "賞与"), "賞与の状況")
    月の後 = dict(zip(月の値[0], 月の値[1]))
    assert (月の後["取り込み"], 月の後["止まりの理由"]) == ("済", 月の行["止まりの理由"])
    assert len(賞与の値) == 2
    賞与の後 = dict(zip(賞与の値[0], 賞与の値[1]))
    assert (賞与の後["取り込み"], 賞与の後["外した人"], 賞与の後["組"]) == ("仮", "1", 組)
    # 賞与をもう一度書いても月の行は変わらない・賞与の行は 1 行のまま（鍵で探して書く）
    賞与の値 = _当てる(賞与の値, _書く("賞与の状況", 賞与の値, {**賞与の行, "外した人": "0", "取り込み": "済"}, "賞与"), "賞与の状況")
    assert len(賞与の値) == 2 and dict(zip(賞与の値[0], 賞与の値[1]))["取り込み"] == "済"
    assert dict(zip(月の値[0], 月の値[1])) == 月の後


def test_回を取り違えた書き方は拒む():
    with pytest.raises(管理表.拒む, match="賞与の状況 に書く"):
        _書く("月の状況", _月の状況(), {"会社": 会社, "支給月": 月, "取り込み": "仮"}, "賞与")
    with pytest.raises(管理表.拒む, match="月の状況 に書く"):
        _書く("賞与の状況", [管理表.見出し("賞与の状況")], {"会社": 会社, "支給月": 月}, "月")


def test_賞与の状況も同じ仕切りで拒む():
    空 = [管理表.見出し("賞与の状況")]
    with pytest.raises(管理表.拒む, match="受け持つ組"):
        _書く("賞与の状況", 空, {"会社": "作り物の別の会社", "支給月": 月}, "賞与")
    with pytest.raises(管理表.拒む, match="済 にしない"):
        _書く("賞与の状況", 空, {"会社": 会社, "支給月": 月, "外した人": "2", "取り込み": "済"}, "賞与")
    with pytest.raises(管理表.拒む, match="組は窓から書かない"):
        _書く("賞与の状況", 空, {"会社": 会社, "支給月": 月, "組": 組}, "賞与")
    with pytest.raises(管理表.拒む, match="見出しが型と違う"):
        _書く("賞与の状況", [管理表.見出し("月の状況")], {"会社": 会社, "支給月": 月}, "賞与")


def test_立ち上げは月の状況の在る前の管理表に賞与の状況のタブだけを足す():
    今 = {名: [h] for 名, h in 管理表.全部の見出し().items() if 名 != "賞与の状況"}
    手順 = 管理表.立ち上げ({"今のタブ": 今})
    assert [(x["する"], x["タブ"]) for x in 手順] == [("タブを足す", "賞与の状況")]
    assert 手順[0]["見出し"] == 管理表.見出し("賞与の状況")
