"""管理表「突き合わせの記録」と月の状況「突き合わせ」（続けて差 0 の月数）を書く口。作り物の会社だけ。

防ぐ故障: 突き合わせの結果から月の状況「突き合わせ」を書く口が無く、給与ソフトを外すかを事務所が決める元の数が
管理表に残らない。数を手で写すと、賞与の回・抜けた月・場面が分からず、別の会社や別の月の結果でも数が増える。
誤りの類（注入）: 管理表.書く の照らしで、見出しの違うタブへ書く／事務所の段の起こす行（月の状況）を窓が起こす。→ どれも拒む。
"""
import importlib
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
for p in (str(根), str(根 / "tests" / "出口")):
    if p not in sys.path:
        sys.path.insert(0, p)

from 出口 import 関所, 読み口, 突き合わせ, 形  # noqa: E402

記録 = importlib.import_module("管理表.突き合わせの記録")
表 = 記録._表
組 = "作り物の組"
会社 = "作り物A"
一覧 = {会社: 組, "作り物B": "別の組"}
既定の見出し = ["項目", "今の値", "適用開始"]
既定 = [既定の見出し]   # 事務所の設定「既定」に N を書いていない＝項目.json の既定
F = 形.形を組む({"名": "作り物の給与ソフト", "鍵の欄": "NO", "文字コード": "utf-8"})
対応 = [dict(項目="総支給", 欄="総支給額", 形="円", 渡す=False, 受ける=True)]


def _結果(月="2026-11", 給与ソフト="215000", 会社名=会社, 仮=False):
    行 = [dict(支給月=月, 会社=会社名, NO="0001", 項目="総支給", 値=215000, 出所="作り物", 状態="仮" if 仮 else "確定")]
    通 = 関所.通す(行, {})
    読 = 読み口.読む(f"NO,総支給額\n0001,{給与ソフト}\n", "出力.csv", 会社名, 月, 対応, F)
    return 突き合わせ.突き合わせる(通, 読, 対応)


def _月の状況(*月):
    h = 表.見出し("月の状況")
    return [h] + [[{"会社": 会社, "組": 組, "支給月": m, "外した人": "0"}.get(k, "") for k in h] for m in 月]


def _空の記録():
    return [表.見出し(記録.記録のタブ)]


def _当てる(値, 手順, タブ):
    値 = [list(r) for r in 値]
    h = 値[0]
    for s in 手順:
        if s["タブ"] != 表.Driveのタブ(タブ):
            continue
        if s["する"] == "行を足す":
            値.append(list(s["値"]))
        else:
            列 = s["セル"].rstrip("0123456789")
            i = int(s["セル"][len(列):]) - 1
            j = h.index(s["列"])
            値[i] += [""] * (j + 1 - len(値[i]))
            値[i][j] = s["値"]
    return 値


def _書く(結果, 支給月, 回="月", 今の記録=None, 月の状況=None, 閉じた=0, 場面=()):
    """支給月・回は試験の月の状況を組むためだけ（口へは渡さない＝会社・支給月・回は結果の人から取る）。"""
    return 記録.書く手順(結果, 給与ソフトが違うで閉じた=閉じた, 場面=場面,
                    今の記録=今の記録 if 今の記録 is not None else _空の記録(),
                    今の月の状況=月の状況 if 月の状況 is not None else _月の状況(支給月),
                    会社の一覧=一覧, 受け持つ組=組, 今日="2026-11-22", 事務所の既定=既定)


def _回す(並び):
    """(中の支給月, 回, 給与ソフトの値, 場面) を順に突き合わせ、記録と月の状況へ当てた後の値を返す。"""
    月たち = sorted({m[:7] for m, *_ in 並び})
    月次の字 = {m: f"{m[:4]}.{m[5:7]}支給" for m in 月たち}
    記, 状 = _空の記録(), _月の状況(*[f"{m[:4]}.{m[5:7]}支給（{int(m[5:7]) - 1 or 12}月分）" for m in 月たち])
    for m, 回, 値, 場面 in 並び:
        r = _書く(_結果(m, 値), 月次の字[m[:7]], 回, 記, 状, 場面=場面)
        記, 状 = _当てる(記, r["手順"], 記録.記録のタブ), _当てる(状, r["手順"], "月の状況")
    return 記, 状, r


def _列(値, 名):
    i = 値[0].index(名)
    return [r[i] if i < len(r) else "" for r in 値[1:]]


def test_差0の月を続けて数え_月の状況の突き合わせへ書く():
    記, 状, r = _回す([("2026-09", "月", "215000", ("入社",)), ("2026-10", "月", "215000", ()),
                     ("2026-11", "月", "215000", ())])
    assert _列(状, "突き合わせ") == ["1", "2", "3"]
    assert _列(記, "続けて差0の月数") == ["1", "2", "3"] and _列(記, "差0の月") == ["はい"] * 3
    assert r["月数"]["月数"] == 3 and r["月数"]["まだ見ていない場面"] == ("退社", "賞与", "年の変わり目", "料率の変わる月")
    assert set(_列(状, "更新日")) == {"2026-11-22"}


def test_賞与も1回を1か月に数え_記録のタブにだけ書く():
    記, 状, r = _回す([("2026-10", "月", "215000", ()), ("2026-10-賞与", "賞与", "215000", ()),
                     ("2026-11", "月", "215000", ())])
    assert _列(記, "回") == ["月", "賞与", "月"] and _列(記, "続けて差0の月数") == ["1", "2", "3"]
    assert _列(状, "突き合わせ") == ["1", "3"]   # 賞与の回は月の状況に書かない（賞与の状況に列は無い）
    assert "賞与" not in r["月数"]["まだ見ていない場面"]


def test_差のある月で0に戻り_抜けた月でも切れる():
    記, 状, _ = _回す([("2026-09", "月", "215000", ()), ("2026-10", "月", "215001", ()), ("2026-11", "月", "215000", ())])
    assert _列(状, "突き合わせ") == ["1", "0", "1"] and _列(記, "差の行") == ["0", "1", "0"]
    記, 状, _ = _回す([("2026-08", "月", "215000", ()), ("2026-11", "月", "215000", ())])
    assert _列(状, "突き合わせ") == ["1", "1"]


def test_前の回を突き合わせ直すと後の回の数も記録から数え直す():
    記, 状, _ = _回す([("2026-09", "月", "215000", ()), ("2026-10", "月", "215001", ()), ("2026-11", "月", "215000", ())])
    r = _書く(_結果("2026-10", "215000"), "2026.10支給", "月", 記, 状, 閉じた=0)
    記, 状 = _当てる(記, r["手順"], 記録.記録のタブ), _当てる(状, r["手順"], "月の状況")
    assert _列(状, "突き合わせ") == ["1", "2", "3"] and _列(記, "続けて差0の月数") == ["1", "2", "3"]
    # 給与ソフトが違うで閉じた月は差 0 に数えない（事務所の入力の直しが要った月）
    r = _書く(_結果("2026-10", "215000"), "2026.10支給", "月", 記, 状, 閉じた=1)
    状 = _当てる(状, r["手順"], "月の状況")
    assert _列(状, "突き合わせ") == ["1", "0", "1"]


