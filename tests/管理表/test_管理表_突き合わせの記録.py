def test_注入_Nの既定を持つのは項目の辞書だけ():
    """口・出口・答え合わせの道具のどれも N の既定の数を持たない（既定の正本は 初期設定/項目.json の 1 か所）。"""
    import ast
    import inspect

    from 道具.答え合わせ import 照合の段
    assert inspect.signature(照合の段.照らす).parameters["N"].default is None
    assert 照合の段._Nの既定() == int(記録._型.項目(記録.Nの項目)["既定"])
    for p in (根 / "道具" / "答え合わせ" / "__main__.py",):
        for n in ast.walk(ast.parse(p.read_text(encoding="utf-8"))):
            if isinstance(n, ast.Call) and n.args and getattr(n.args[0], "value", None) == "--N":
                d = {k.arg: k.value for k in n.keywords}
                assert getattr(d.get("default"), "value", "無") is None, f"{p.name} の --N が既定の数を持つ"


def test_注入_文書もNの既定の数を写さない():
    """使い方の例・設計の紙に N の既定の数を写すと、項目の辞書を直した時に食い違う＝数は 初期設定/項目.json の 1 か所。"""
    import re
    写し = re.compile(r"--N \d|差0の月数の目安[^\n]{0,80}既定[^\n]{0,40}の \d|N は事務所の設定（推奨 \d")
    当たり = [f"{p.relative_to(根)}:{i}" for p in 根.rglob("*.md") if ".git" not in p.parts and "CHANGELOG" not in p.name
            for i, l in enumerate(p.read_text(encoding="utf-8").splitlines(), 1) if 写し.search(l)]
    assert not 当たり, "N の既定の数を文書へ写した: " + "・".join(当たり)
