"""管理表/段.py（会社×支給月×回の段・足りない物・次にやること）の試験。値は作り物だけ。

防ぐ故障: 初期設定の欠け（つなぎ・決まり・置き場）が勤怠の来た後に 1 つずつ見つかる／足りない物の一部だけを見せる／
  前の段が欠けるのに後ろの段だと言う／分けに無い訳を黙って落とす／立ち上げの会社が済んでも毎月へ移る道が分からない。
"""
import importlib.util
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("段_試験", 根 / "管理表" / "段.py")
段 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(段)
_spec2 = importlib.util.spec_from_file_location("管理表_試験_段", 根 / "管理表" / "管理表.py")
管理表 = importlib.util.module_from_spec(_spec2)
_spec2.loader.exec_module(管理表)

月の行 = {"会社": "作り物の会社", "支給月": "2099.01支給（1月分）", "取り込み": "", "納品": "", "確認ページ": ""}


def 事実(**kw):
    return {"会社": "作り物の会社", "支給月": "2099.01支給", "回": "月", "状態": "毎月", "行": dict(月の行), **kw}


@pytest.mark.parametrize("赤, 段の名", [
    ("事務所のルール の給与ソフトの形が読めない（ValueError: 初期設定が済んでいない: ⑥つなぎ の項目 作り物手当 の形が引けない）", "0 初期設定"),
    ("置き場: 会社 作り物の会社 の置き場に 給与のルール が無い（作り物）＝計算の元を読めない", "0 初期設定"),
    ("給与のルール.md が読めない", "0 初期設定"),
    ("質問と回答: 作り物の訳", "0 初期設定"),
    ("この月の勤怠が来ていない（2099-01 の月のフォルダが無い）", "1 材料をそろえる"),
    ("置き場: 3_月ごと に 2099-01 支給の月のフォルダが 2 つ（1 つでなければ選ばず止める）", "1 材料をそろえる"),
    ("台帳_2099 の「名」が読めない（作り物）", "1 材料をそろえる"),
    ("マスタ の「人」が読めない（作り物）＝計算の元が欠ける", "1 材料をそろえる"),
    ("回す: パックの口が止めた（作り物）", "2 給与計算"),
    ("置き場: 会社（会社の一覧の呼び名）が無い（作り物）", "0 初期設定"),
    ("置き場: 1_決まり/給与のルール が引けない（ValueError: 作り物）", "0 初期設定"),
    ("9_履歴/ の名が読めない（作り物）", "0 初期設定"),
    ("支給月: 2099-1 が YYYY-MM でない", "2 給与計算"),
    ("置き場: 3_月ごと の月のフォルダが引けない（作り物）", "1 材料をそろえる"),
])
def test_赤の訳を段に振り分ける(赤, 段の名):
    assert 段.赤を段へ(赤)[0] == 段の名


def test_分けに無い訳は2に置き_表へ足す目印を付ける():
    assert 段.赤を段へ("作り物の見たことの無い訳") == ("2 給与計算", 段.分けに無い)


def test_足りない物は全部並べ_段は一番前():
    見た = 段.段を見る(事実(赤=["この月の勤怠が来ていない（2099-01 の月のフォルダが無い）",
                             "事務所のルール の給与ソフトの形が読めない（ValueError: 初期設定が済んでいない: ⑥つなぎ の項目 作り物手当・作り物控除 の形が引けない）",
                             "給与のルール.md が読めない"]))
    assert 見た["段"] == "0 初期設定"
    assert [x["段"] for x in 見た["足りない"]] == ["1 材料をそろえる", "0 初期設定", "0 初期設定"]
    assert "⑥つなぎ" in 見た["次にやること"]


def test_同じ訳の人はまとめて対象を並べる_マスタの欠けは状態で段が変わる():
    除いた = [{"NO": "3", "理由": ["必ず埋める欄が空: 作り物の欄"]}, {"NO": "5", "理由": ["必ず埋める欄が空: 作り物の欄"]}]
    毎月 = 段.段を見る(事実(除いた人=除いた))
    assert 毎月["足りない"] == [{"段": "1 材料をそろえる", "対象": "NO 3・NO 5", "何": "必ず埋める欄が空: 作り物の欄",
                              "次": "① マスタの更新: マスタの欄を埋める"}]
    立ち上げ = 段.段を見る(事実(状態="立ち上げ", 除いた人=除いた))
    assert 立ち上げ["段"] == "0 初期設定"


def test_締まっていない人は1の締め_答え待ちは止まりの1つだけに数える():
    見た = 段.段を見る(事実(
        除いた人=[{"NO": "2", "理由": ["締めの記録が「作り物」（締まるまで仮）"]},
                {"NO": "4", "理由": ["作り物の問い。通すには、作り物の答えを書く"]}],
        止まり=[{"対象": "4", "問いの鍵": "作り物の鍵", "何が": "作り物の問い", "何をすれば通るか": "作り物の答えを書く"}]))
    assert 見た["段"] == "1 材料をそろえる"
    assert [(x["対象"], x["次"]) for x in 見た["足りない"]] == [
        ("社員ID 4", "作り物の答えを書く"), ("NO 2", "③ 勤怠の締め: 原本を読み照らし、締めの記録を 締まった にする")]


def test_足りない物が無ければ管理表の行で2_3_済みを決める():
    assert 段.段を見る(事実())["段"] == "2 給与計算"
    assert 段.段を見る(事実(行={**月の行, "取り込み": "済"}))["段"] == "3 突き合わせと納品"
    済 = 段.段を見る(事実(行={**月の行, "取り込み": "済", "納品": "済"}))
    assert (済["段"], 済["次にやること"]) == ("済み", "無し")
    初回 = 段.段を見る(事実(状態="立ち上げ", 行={**月の行, "取り込み": "済", "納品": "済"}))
    assert "初回の確認の OK の日" in 初回["次にやること"] and "毎月" in 初回["次にやること"]


def test_月の行が無い_お答え待ち_止めた():
    assert 段.段を見る(事実(行=None))["足りない"][0]["何"].startswith("管理表「月の状況」にこの支給月の行が無い")
    assert 段.段を見る(事実(行={**月の行, "確認ページ": "お答え待ち"}))["段"] == "1 材料をそろえる"
    assert 段.段を見る(事実(状態="止めた", 赤=["作り物"]))["段"] == "止めた"


def test_管理表の行は段のタブの列だけで書く口が通す():
    見た = 段.段を見る(事実(赤=["給与のルール.md が読めない"]))
    行 = 段.管理表の行(見た, "2099-01-10")
    h = 管理表.見出し("段")
    assert set(行) <= set(h)
    assert 行["足りない物"] == "[0] 会社: 給与のルール.md が読めない"
    手順 = 管理表.書く({"タブ": "段", "今の値": [h], "会社の一覧": {"作り物の会社": "作り物の組"},
                     "受け持つ組": "作り物の組", "行たち": [行], "今日": "2099-01-10"})
    assert [s["する"] for s in 手順] == ["行を足す"]
    assert dict(zip(h, 手順[0]["値"]))["組"] == "作り物の組"


def test_段の選べる値は段の部品と同じ():
    列 = next(c for c in 管理表.タブ("段")["列"] if c["名"] == "段")
    assert 列["選べる値"] == [*段.段たち, 段.止めた]
