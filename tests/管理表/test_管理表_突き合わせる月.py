"""寄せの突き合わせに使う月（寄せる道具.md §1.6）を記録から決める口。作り物の会社だけ。

誤りの類: 出したことのある会社が「まだ出していない」の申告 1 つで人×項目の突き合わせを飛ばす／最後でない月で突き合わせて
寄せ中を外す／記録が読めない時に「出していない」と黙って読む。→ 出した月は管理表「月の状況」の出荷の印から決め、
申告と食い違えば拒む。
"""
import importlib.util
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("管理表_試験_突き合わせる月", ここ.parent.parent / "管理表" / "管理表.py")
管理表 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(管理表)


def _行(会社, 支給月, **印):
    return [{"会社": 会社, "組": "作り物の組", "支給月": 支給月, "外した人": "0", **印}.get(k, "") for k in 管理表.見出し("月の状況")]


def _今の値():
    return [管理表.見出し("月の状況"),
            _行("作り物A", "2026.09支給（8月分）", 取り込み="済", 納品="済"),
            _行("作り物A", "2026.10支給（9月分）", 取り込み="仮"),
            _行("作り物A", "2026.11支給（10月分）", 原本="済"),
            _行("作り物B", "2026.11支給（10月分）", 原本="済"),
            _行("作り物C", "2026.10支給（9月分）", 納品="済")]


def _口(**入力):
    return 管理表.突き合わせる月({"今の値": _今の値(), **入力})


def test_出した会社は最後に出した月だけを通す():
    assert _口(会社="作り物A", 月="2026.10支給") == {"月": "2026.10支給", "出した月": ["2026.09支給", "2026.10支給"], "無い訳": ""}
    assert _口(会社="作り物A", 月="2026.10支給（9月分）")["月"] == "2026.10支給"
    assert _口(会社="作り物C", 月="2026.10支給")["月"] == "2026.10支給"


def test_まだ出していない会社は無い訳で通す():
    assert _口(会社="作り物B", 無い訳="2026.11支給 から始めた会社") == {"月": "", "出した月": [], "無い訳": "2026.11支給 から始めた会社"}


@pytest.mark.parametrize("入力, 当たる", [
    ({"会社": "作り物A", "無い訳": "まだ出していない"}, "無い訳で突き合わせを飛ばさない"),   # 申告で突き合わせを飛ばす
    ({"会社": "作り物C", "無い訳": "まだ出していない"}, "無い訳で突き合わせを飛ばさない"),
    ({"会社": "作り物A", "月": "2026.09支給"}, "最後に出した月"),   # 最後でない月
    ({"会社": "作り物A", "月": "2026.11支給"}, "最後に出した月"),   # まだ出していない月
    ({"会社": "作り物A"}, "最後に出した月"),
    ({"会社": "作り物B"}, "無い訳を渡す"),
    ({"会社": "作り物B", "月": "2026.11支給"}, "まだ 1 度も出していない"),
    ({"会社": "作り物A", "月": "2026.10支給", "無い訳": "x"}, "片方だけ"),
    ({"会社": "作り物D", "無い訳": "まだ出していない"}, "行が 1 つも無い"),   # 記録が無いのを「出していない」と読まない
    ({"会社": "作り物A", "月": "十月"}, "読めない"),
    ({"無い訳": "x"}, "会社 が無い"),
])
def test_申告と記録が食い違えば拒む(入力, 当たる):
    with pytest.raises(管理表.拒む, match=当たる):
        _口(**入力)


def test_読めない記録は出していないと読まず拒む():
    v = _今の値() + [_行("作り物B", "11月", 取り込み="済")]
    with pytest.raises(管理表.拒む, match="読めない"):
        管理表.突き合わせる月({"今の値": v, "会社": "作り物B", "無い訳": "まだ出していない"})
    h = 管理表.見出し("月の状況")
    入れ替え = [h[:3] + [h[4], h[3]] + h[5:]] + [r[:3] + [r[4], r[3]] + r[5:] for r in _今の値()[1:]]
    with pytest.raises(管理表.拒む, match="見出し"):
        管理表.突き合わせる月({"今の値": 入れ替え, "会社": "作り物A", "月": "2026.10支給"})


def test_出した印は出荷の口が書く印と同じ():
    """出荷の口（出す前の照らし.py 管理表の行）が書く列と値が、出した印に在る（片方だけ変えると赤）。"""
    src = (ここ.parent.parent / "plugins" / "payroll-agent" / "bin" / "出す前の照らし.py").read_text(encoding="utf-8")
    for 列, 値 in (("取り込み", "済"), ("取り込み", "仮"), ("納品", "済")):
        assert f'行["{列}"]' in src and 値 in 管理表.出した印[列]


def _会社(寄せ="", 理由=""):
    h = 管理表.見出し("会社")
    return [h] + [[{"会社": c, "組": "作り物の組", "型の版": "34", "寄せ": 寄せ if c == "作り物A" else "",
                    "寄せの理由": 理由 if c == "作り物A" else ""}.get(k, "") for k in h] for c in ("作り物A", "作り物B")]


def _見通し(**変わる):
    return {"会社": "作り物A", "知らせ": ["読んだだけ"], **{k: [] for k in 管理表.変わる印}, **変わる}


def test_変わらない会社は比べる入力を求めずに終える():
    """見通しで変わる物が 0・足りない値が 0・前の回が止まっていない会社は、月も無い訳も要らない（記録が無い会社も）。"""
    assert _口(会社="作り物A", 見通し=_見通し(), 会社のタブ=_会社()) == {
        "月": "", "出した月": ["2026.09支給", "2026.10支給"], "無い訳": "", "変わらない": True}
    assert _口(会社="作り物B", 見通し=_見通し(会社="作り物B"), 会社のタブ=_会社())["変わらない"] is True


@pytest.mark.parametrize("見通し, 会社のタブ, 残り", [
    (_見通し(足りない値=[{"所": "マスタ/社員", "値": "有給の始めの日"}]), _会社(), "足りない値 1 件"),   # 変わらないが計算に要る値が欠ける
    (_見通し(寄せられない物=[{"種類": "行き先の無い列"}]), _会社(), "寄せられない物 1 件"),
    (_見通し(書く手順=[{"する": "値を書く"}]), _会社(), "書く手順 1 件"),
    (_見通し(管理表へ書く=[{"会社": "作り物A"}]), _会社(), "管理表へ書く 1 件"),
    (_見通し(写した物=["9_履歴/消す_2026-12-01_x"]), _会社(), "写した物 1 件"),
    (_見通し(), _会社("寄せ中", "書く途中で落ちた"), "前の回が止まった: 書く途中で落ちた"),   # 変わらないが前の回が失敗
])
def test_変わらなくても残りが在れば済にせず比べる入力を求める(見通し, 会社のタブ, 残り):
    with pytest.raises(管理表.拒む, match="最後に出した月"):
        _口(会社="作り物A", 見通し=見通し, 会社のタブ=会社のタブ)
    o = _口(会社="作り物A", 月="2026.10支給", 見通し=見通し, 会社のタブ=会社のタブ)
    assert o["変わらない"] is False and o["月"] == "2026.10支給" and any(残り in x for x in o["残り"])


@pytest.mark.parametrize("入力, 当たる", [
    ({"見通し": {"書く手順": []}, "会社のタブ": _会社()}, "寄せられない物・足りない値・管理表へ書く・写した物 が無い"),   # 鍵の欠けを空と読まない
    ({"見通し": _見通し()}, "会社のタブ"),   # 前の回が止まったかを読まずに変わらないと言わない
    ({"見通し": _見通し(), "会社のタブ": _会社("止めた")}, "選べない値"),
    ({"見通し": _見通し(会社="作り物B"), "会社のタブ": _会社()}, "見通し の会社"),   # 別の会社の変わらない見通しで済にしない
    ({"見通し": {k: v for k, v in _見通し().items() if k != "会社"}, "会社のタブ": _会社()}, "見通し の会社"),   # 会社の無い見通し
])
def test_変わらないか読めない見通しは拒む(入力, 当たる):
    with pytest.raises(管理表.拒む, match=当たる):
        _口(会社="作り物A", **入力)
