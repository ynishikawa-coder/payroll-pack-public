"""有給.付与の表 の値は字の揺れをそろえて選べる値と比べる（有給/有給.py の 付与日数）。値は作り物だけ。

防ぐ故障（台帳 束 K3）: 「会社の表（法以上）」の字のそのままの一致で見ていたので、半角の括弧や空白で書くと黙って法の表で
数えた。選べる値のどれでもない字も黙って法の表で数えた（仮にしない＝出口へ出た）。
"""
from decimal import Decimal

import 有給.有給 as Y

会社の表 = "11,12,13,14,16,18,20"   # 作り物（各段で法の表 10・11・12・14・16・18・20 以上）


def test_半角の括弧や空白で書いた会社の表の選択も会社の表で数える():
    for 字 in ("会社の表（法以上）", "会社の表(法以上)", " 会社の表 ( 法以上 ) ", "会社の表​（法以上）"):
        assert Y.付与日数(0, Decimal(10), "通常", {"有給.付与の表": 字, "有給.会社の表": 会社の表}) == (Decimal(11), None)


def test_選べる値でない字は法の数で仮にする():
    数, 理由 = Y.付与日数(0, Decimal(10), "通常", {"有給.付与の表": "会社の表", "有給.会社の表": 会社の表})
    assert 数 == 10 and 理由 and "選べる値" in 理由


def test_無い時と法の表は法の数で仮にしない():
    assert Y.付与日数(0, Decimal(10), "通常", {}) == (Decimal(10), None)
    assert Y.付与日数(0, Decimal(10), "通常", {"有給.付与の表": "法の表"}) == (Decimal(10), None)
    assert Y.付与日数(0, Decimal(10), "通常", {"有給.付与の表": ""}) == (Decimal(10), None)
