"""作り物の例: 法の付与をしない人の承知（法の線.承知 の 有給.付与・労基法 39 条）と、出勤率の期間が有給の始めの日より前にかかって止まる時の訳。

- 承知の印のある人は 付与 0・出勤率を数えない・次の付与日数 0 で確定の行に出し、知らせ（線・人・問いの番号・法なら何日）を返す。
- 印が無ければ今までどおり出勤率を数える（勤怠が無ければ止まる）。
- 有給の始めの日が付与日（09-16）なのに 有給.揃えた日 が 10-01 だと、始めの日の後すぐの 10-01 の付与が前の 1 年の勤怠を求めて止まる。
  訳は 始めの日と揃えた日を事務所の有給管理表で照らす よう添える。揃えた日が 09-16 なら止まらない。"""
import datetime as dt
import importlib.util
from pathlib import Path

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("有給_付与の承知", ここ.parent.parent / "有給" / "有給.py")
有給 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(有給)

_t = importlib.util.spec_from_file_location("有給_年の台帳の試験", ここ / "test_有給_年の台帳.py")
_台帳の試験 = importlib.util.module_from_spec(_t)
_t.loader.exec_module(_台帳の試験)
台帳 = _台帳の試験.台帳

揃える = 有給.揃える値[0]
承知の印 = {"法の線.承知": "有給.付与=問-作り物-1"}
付与しない人 = {"NO": "2", "氏名": "作り物の二", "入社日": "2020-04-01", "時間.週の所定日数": 5, "時間.週の所定": 40,
             "有給.1日の時間": 480, "有給の始めの日": "2026-09-15", "有給の始めの残り": 0, "有給の始めの繰越": 0}
始めの日の人 = {"NO": "1", "氏名": "作り物", "入社日": "2015-04-01", "時間.週の所定日数": 5, "時間.週の所定": 40,
             "有給.1日の時間": 480, "有給の始めの日": "2026-09-16", "有給の始めの残り": 20, "有給の始めの繰越": 20}


def 入力(人たち, 揃えた日="09-16", 行たち=None):
    return {"会社": "作り物の会社", "支給月": "2026.11支給", "基準の日": "2026-10-31",
            "会社の値": {"有給.付与の基準日": 揃える, "有給.揃えた日": 揃えた日},
            "人": 人たち, "確定した勤怠": 行たち if 行たち is not None else 台帳("2026-09-16", "2026-10-31", NO="1")}


# ---- 承知の印で付与 0・確定・知らせ ----

def test_承知の印のある人は付与0で確定し知らせを返す():
    """出勤簿の無い人（台帳に行が 1 つも無い）でも、印があれば止めずに 付与 0・残り 0・次の付与日数 0 で確定。"""
    結果 = 有給.管理表(入力([{**付与しない人, **承知の印}]))
    assert 結果["止めた人"] == [] and 結果["問い"] == []
    行 = 結果["行"][0]
    assert (行["付与日"], 行["付与日数"], 行["繰越日数"], 行["残日数"]) == ("2026-09-16", "0", "0", "0")
    assert (行["次の付与日"], 行["次の付与日数"], 行["状態"]) == ("2027-09-16", "0", "確定")
    assert 行["年5日の期限"] == ""
    [知らせ] = 結果["知らせ"]
    # 線・人・問いの番号・法なら何日（入社 2020-04-01 → 2026-09-16 は法の付与日 2026-10-01〔勤続 6 年 6 か月〕の前倒し＝20 日）
    assert "有給.付与" in 知らせ and "NO 2" in 知らせ and "問-作り物-1" in 知らせ
    assert "2026-09-16 に 20 日" in 知らせ and "次の 2027-09-16 に 20 日" in 知らせ


def test_承知の印は字でもJSONでも読む():
    for 印 in ({"有給.付与": "問-作り物-1"}, "割増.深夜の率=問-作り物-9、有給.付与＝問-作り物-1"):
        結果 = 有給.管理表(入力([{**付与しない人, "法の線.承知": 印}]))
        assert 結果["行"][0]["付与日数"] == "0" and 結果["行"][0]["状態"] == "確定", 印


def test_承知の印に問いの番号が無ければ承知に数えず止まる():
    結果 = 有給.管理表(入力([{**付与しない人, "法の線.承知": "有給.付与"}]))
    assert 結果["行"] == [] and len(結果["止めた人"]) == 1


def test_印のある人の年休の行は残りを超えたとして問う():
    """付与しないのに年休を取った行があれば黙って捨てず、残りを超えた で問う（仮）。"""
    行たち = 台帳("2026-09-16", "2026-10-31", NO="1") + 台帳("2026-10-01", "2026-10-31", NO="2",
                                                            変える={"2026-10-05": _台帳の試験.年休})
    結果 = 有給.管理表(入力([{**付与しない人, **承知の印}], 行たち=行たち))
    assert 結果["行"][0]["状態"] == "仮"
    assert any(q["何が無いか"] == "有給の残り" for q in 結果["問い"])


# ---- 印が無ければ止まる ----

def test_印が無ければ出勤率を数えようとして止まる():
    結果 = 有給.管理表(入力([付与しない人]))
    assert 結果["行"] == [] and 結果["知らせ"] == []
    assert "出勤率" in 結果["止めた人"][0]["理由"] or "取得を数える" in 結果["止めた人"][0]["理由"]


def test_ほかの線だけの印では付与しない承知にならない():
    結果 = 有給.管理表(入力([{**付与しない人, "法の線.承知": "割増.深夜の率=問-作り物-9"}]))
    assert 結果["行"] == [] and len(結果["止めた人"]) == 1


# ---- 始めの日と揃えた日のずれ ----

def test_始めの日0916で揃えた日1001だと止まり訳が照らす所を指す():
    """始めの日 2026-09-16 の後に 10-01 の付与ができ、その出勤率の期間 2025-10-01〜2026-09-30 が始めの日より前にかかる。"""
    結果 = 有給.管理表(入力([始めの日の人], 揃えた日="10-01"))
    理由 = 結果["止めた人"][0]["理由"]
    assert "付与日 2026-10-01 の出勤率" in 理由
    assert "有給の始めの日 2026-09-16 より前にかかる" in 理由
    assert "有給.揃えた日（10-01）" in 理由 and "事務所の有給管理表" in 理由


def test_揃えた日0916なら止まらず始めの残りのまま():
    行 = 有給.管理表(入力([始めの日の人]))["行"][0]
    assert (行["付与日"], 行["付与日数"], 行["繰越日数"], 行["残日数"], 行["状態"]) == ("2026-09-16", "20", "20", "40", "確定")
    assert (行["次の付与日"], 行["次の付与日数"]) == ("2027-09-16", "20")


def test_始めの日より後だけの期間で欠けた時は訳を添えない():
    """出勤率の期間が始めの日より後だけなら、ずれの訳は添えない（今までどおりの訳）。"""
    人 = {**始めの日の人, "有給の始めの日": "2024-09-16"}
    結果 = 有給.管理表({**入力([人]), "基準の日": "2026-10-31"})
    理由 = 結果["止めた人"][0]["理由"]
    assert "事務所の有給管理表" not in 理由
