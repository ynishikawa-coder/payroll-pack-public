# ---- 年をまたぐ基準日 ----

def test_年をまたぐ基準日は前の年の台帳の取得も引く():
    """支給 2026.01（基準 2026-01-31）。前の年の台帳（2025）の 12 月に 2 日・今年の台帳（2026）の 1 月に 1 日取る。
    付与 2025-10-01 の出勤率は 2024-10-01〜2025-09-30＝前の前の年（2024）の台帳も要る。"""
    前の前 = 台帳("2024-10-01", "2024-12-31")
    前 = 台帳("2025-01-01", "2025-12-31", 変える={"2025-12-01": 年休, "2025-12-02": 年休})
    今年 = 台帳("2026-01-01", "2026-01-31", 変える={"2026-01-13": 年休})
    行 = 一行(有給.管理表(入力(前の前 + 前 + 今年, 基準="2026-01-31", 支給月="2026.01支給", 人=始めの値)))
    assert (行["付与日"], 行["残日数"], 行["今月の取得日数"], 行["付与日からの取得日数"]) == ("2025-10-01", "13", "1", "3")
    assert 行["年5日の期限"] == "2026-09-30" and 行["年5日の残り"] == "2"


def test_年をまたぐ基準日で前の年の台帳が欠けると止まる():
    前の前 = 台帳("2024-10-01", "2024-12-31")
    今年 = 台帳("2026-01-01", "2026-01-31")
    理由 = _止めた(有給.管理表(入力(前の前 + 今年, 基準="2026-01-31", 支給月="2026.01支給", 人=始めの値)))
    assert "2025-04-01 から" in 理由


def test_揃えた日で前倒しした初回は短い期間で8割を割ると止める():
    """揃えた日 04-01・入社 2025-01-06 → 初回 2025-04-01（法の日 2025-07-06 より前倒し）。短くなった分は出勤とみなす（平 6.1.4 基発 1 号）が
    その数え方は表せないので、短い期間で 8 割を割る時は止める。割らなければ付与する。"""
    会社の値 = {"有給.付与の基準日": "会社で揃えた日（斉一的付与）", "有給.揃えた日": "04-01"}
    変える = {d.isoformat(): 欠勤 for d in 平日("2025-01-06", "2025-03-31")[:20]}
    入 = 入力(台帳("2025-01-06", "2025-11-30", 変える=変える), 人={"入社日": "2025-01-06"})
    入["会社の値"] = 会社の値
    assert "前倒し" in _止めた(有給.管理表(入))
    入 = 入力(台帳("2025-01-06", "2025-11-30"), 人={"入社日": "2025-01-06"})
    入["会社の値"] = 会社の値
    assert 一行(有給.管理表(入))["付与日"] == "2025-04-01"


@pytest.mark.parametrize("空", ["消す", None, "", " "])
def test_始めの日の残りの欄が空なら0と読まず聞いて仮(空):
    """始めの日だけ書いて残りの欄が空だと、残りが黙って 0 になり確定で出していた（前の値の既定が空・同じ根の残り 2026-11-19）。"""
    人 = dict(始めの値)
    if 空 == "消す":
        del 人["有給の始めの残り"]
    else:
        人["有給の始めの残り"] = 空
    結果 = 有給.管理表(入力(台帳("2024-10-01", "2025-11-30"), 人=人))
    assert 一行(結果)["状態"] == "仮"
    assert "有給の始めの残り" in [q["何が無いか"] for q in 結果["問い"]]
    # 0 と書いた欄は空でない＝聞かずに確定
    結果 = 有給.管理表(入力(台帳("2024-10-01", "2025-11-30"), 人={**始めの値, "有給の始めの残り": 0}))
    assert 一行(結果)["状態"] == "確定" and "有給の始めの残り" not in [q["何が無いか"] for q in 結果["問い"]]
