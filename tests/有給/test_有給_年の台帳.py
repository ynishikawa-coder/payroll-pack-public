# ---- 出勤率 8 割 ----

def _期間に(種類: dict, 日数: int):
    """出勤率の期間 2024-10-01〜2025-09-30 の平日の頭から 日数 を 種類 にする。"""
    return {d.isoformat(): 種類 for d in 平日("2024-10-01", "2025-09-30")[:日数]}


欠勤 = {"日の種類": "欠勤"}


def test_出勤率が8割を割る人に付与しない():
    """期間の平日 261 日のうち 60 日欠勤＝出勤 201/261＝77%。2025-10-01 の付与は 0 日（残りは前の付与の 5 だけ）。"""
    行 = 一行(有給.管理表(入力(台帳("2024-10-01", "2025-11-30", 変える=_期間に(欠勤, 60)), 人=始めの値)))
    assert (行["付与日"], 行["付与日数"], 行["残日数"], 行["状態"]) == ("2025-10-01", "0", "5", "確定")
    assert 行["年5日の期限"] == ""


def test_出勤率が8割ちょうどなら付与する():
    """261 日のうち 52 日欠勤＝209/261＝80.08%（8 割以上）。53 日欠勤＝208/261＝79.7% は付与しない。"""
    assert 一行(有給.管理表(入力(台帳("2024-10-01", "2025-11-30", 変える=_期間に(欠勤, 52)), 人=始めの値)))["付与日数"] == "11"
    assert 一行(有給.管理表(入力(台帳("2024-10-01", "2025-11-30", 変える=_期間に(欠勤, 53)), 人=始めの値)))["付与日数"] == "0"


