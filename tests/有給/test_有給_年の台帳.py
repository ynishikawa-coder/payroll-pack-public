"""作り物の例: 有給を年の台帳（今年と前の年）の「確定した勤怠」から数える（労基法 39 条・115 条・平 25.7.10 基発 0710 第 3 号）。
前の月までの取得を引く・要る期間の台帳が無ければ止める（黙って 0 にしない）・出勤率 8 割・時効 2 年・年をまたぐ基準日。"""
import datetime as dt
import importlib.util
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("有給_年の台帳", ここ.parent.parent / "有給" / "有給.py")
有給 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(有給)

D = dt.date.fromisoformat


def 台帳(始め, 終わり, NO="1", 変える=None):
    """[始め, 終わり] の全部の日の確定した勤怠（平日＝勤務・土日＝休日）。変える＝{日付: {列: 値}}。支給月は日付の月（末締め）。"""
    変える = {D(k) if isinstance(k, str) else k: v for k, v in (変える or {}).items()}
    out, d = [], D(始め)
    while d <= D(終わり):
        r = {"会社": "作り物の会社", "支給月": f"{d:%Y-%m}", "NO": NO, "氏名": "作り物", "日付": d.isoformat(),
             "日の種類": "休日" if d.weekday() >= 5 else "勤務", "休暇の種類": "", "休暇の単位": "", "休暇の時間": ""}
        r.update(変える.get(d, {}))
        out.append(r)
        d += dt.timedelta(days=1)
    return out


年休 = {"日の種類": "休暇", "休暇の種類": "年休", "休暇の単位": "全日"}


def 平日(始め, 終わり):
    d, out = D(始め), []
    while d <= D(終わり):
        if d.weekday() < 5:
            out.append(d)
        d += dt.timedelta(days=1)
    return out


def 入力(行たち, 基準="2025-11-30", 支給月="2025.11支給", 人=None):
    p = {"NO": "1", "氏名": "作り物", "入社日": "2024-04-01", "時間.週の所定日数": 5, "時間.週の所定": 40, "有給.1日の時間": 480}
    p.update(人 or {})
    return {"会社": "作り物の会社", "支給月": 支給月, "基準の日": 基準, "会社の値": {}, "人": [p], "確定した勤怠": 行たち}


def 一行(結果):
    assert 結果["止めた人"] == [], 結果["止めた人"]
    assert len(結果["行"]) == 1
    return 結果["行"][0]


