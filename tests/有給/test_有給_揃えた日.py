"""作り物の回帰の見張り: 会社で揃えた付与の日（斉一的付与）は前倒しだけ（労基法 39 条・平 6.1.4 基発 1 号）。
初回だけ入社 6 か月の日に与え、2 回目から揃えた日へ前倒しする選び方と、月だけの揃えた日を日に作らないこと。"""
import datetime as dt
import importlib.util
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("有給_揃えた日", ここ.parent.parent / "有給" / "有給.py")
有給 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(有給)

揃える, 初回は入社日 = 有給.揃える値


def _日たち(入社日, 初回は法の日):
    return [d for d, _, _ in 有給.付与の日たち(入社日, dt.date(2028, 12, 31), "10-01", None, 初回は法の日)]


def test_揃えた日は初回も前倒しする():
    assert _日たち(dt.date(2026, 5, 15), False) == [dt.date(2026, 10, 1), dt.date(2027, 10, 1), dt.date(2028, 10, 1)]


def test_初回は入社6か月の日で2回目から揃えた日():
    # 入社 2026-05-15: 初回＝法の付与日 2026-11-15・2 回目＝(2026-11-15, 2028-05-15] の一番後の 10-01＝2027-10-01
    assert _日たち(dt.date(2026, 5, 15), True) == [dt.date(2026, 11, 15), dt.date(2027, 10, 1), dt.date(2028, 10, 1)]


def test_初回は入社日からでも2回目は法の付与日より後にしない():
    # 入社 2026-02-01: 初回 2026-08-01・2 回目の法の日 2027-08-01 → その前の 10-01＝2026-10-01（前倒しだけ）
    日たち = _日たち(dt.date(2026, 2, 1), True)
    assert 日たち[:2] == [dt.date(2026, 8, 1), dt.date(2026, 10, 1)]
    for (付与日, _, 法の日) in 有給.付与の日たち(dt.date(2026, 2, 1), dt.date(2030, 12, 31), "10-01", None, True):
        assert 付与日 <= 法の日


def _入力(基準日の値, 揃えた日):
    会社の値 = {"有給.付与の基準日": 基準日の値}
    if 揃えた日 is not None:
        会社の値["有給.揃えた日"] = 揃えた日
    return {"会社": "作り物の会社", "支給月": "2027.10支給", "基準の日": "2027-10-31", "会社の値": 会社の値,
            "人": [{"NO": "1", "氏名": "作り物", "入社日": "2026-05-15", "時間.週の所定日数": 5, "時間.週の所定": 40,
                    "有給.1日の時間": 480}], "勤怠": []}


def test_管理表は初回は入社日からの値で2回目の付与を揃えた日に置く():
    結果 = 有給.管理表(_入力(初回は入社日, "10-01"))
    行 = 結果["行"][0]
    assert (行["付与日"], 行["付与日数"], 行["状態"]) == ("2027-10-01", "11", "確定")
    assert 結果["問い"] == []


@pytest.mark.parametrize("揃えた日", [None, "10", "10月", "13-01"])
def test_月だけや無い揃えた日は日を作らず問う(揃えた日):
    結果 = 有給.管理表(_入力(初回は入社日, 揃えた日))
    assert 結果["行"][0]["状態"] == "仮"
    assert any(q["何が無いか"].startswith("有給.揃えた日") for q in 結果["問い"])
