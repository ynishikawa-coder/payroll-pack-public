def _入力(週の所定):
    return {"会社": "作り物の会社", "支給月": "2025.11支給", "基準の日": "2025-10-31", "会社の値": {},
            "人": [{"NO": "1", "氏名": "作り物", "入社日": "2025-04-01", "時間.週の所定日数": 4, "時間.週の所定": 週の所定,
                    "有給.1日の時間": 450}], "勤怠": []}


def test_管理表は時間の数の週の所定で比例か通常かを分ける():
    """殻は 時間.週の所定 を ×60 せず段の解決の値（時間の数）のまま渡す。"""
    通常の行 = 有給.管理表(_入力(30))["行"][0]
    比例の行 = 有給.管理表(_入力(29.5))["行"][0]
    assert (通常の行["付与日数"], 通常の行["状態"]) == ("10", "確定")
    assert (比例の行["付与日数"], 比例の行["状態"]) == ("7", "確定")


