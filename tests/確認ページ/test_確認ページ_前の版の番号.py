"""確認ページの版は、同じ組・支給月の前の版（置き場 8_確認事項/ と 9_履歴/ の名）の最大の次。前の版の名を渡さない時は止める
（黙って v1 にしない）。作り物の組だけ（注入の試験）。

根（2026-11-19）: 出す物の名（出口/名と版）と同じ原因＝`作る` の `今ある名` が既定の空で、殻が渡さないと前の版を見ずに v1 を付けた。
前の版を 9_履歴/ へ移した後は、置き場の名だけでは番号が戻った。
"""
import pytest

from tests.確認ページ.test_確認ページ import 口, 問い, 読んだ   # 同じ読み方の 1 か所（確認ページ/ は package でない）

組, 支給月, 月 = "作り物の組", "2099.04支給", "2099.04支給（3月分）"


def _名(版, 頭=""):
    return f"{頭}確認事項_{組}_{月}_v{版}.html"


def _作る(**足す):
    return 口.作る({"組": 組, "支給月": 支給月, "用": "毎月", "問い": 問い, "読んだ資料": 読んだ, **足す})


def test_v1からv3が在れば_v4で_今の置き場のv3を差し替える():
    v = 口.次の版(組, 支給月, [_名(1), _名(2), _名(3)], [])
    assert (v["版"], v["前の版たち"]) == (4, [_名(3)])
    r = _作る(今ある名=[_名(3)], 履歴にある名=[_名(1, "消す_2099-05-31_"), _名(2, "消す_2099-05-31_")])
    assert (r["赤"], r["版"], r["名"], r["前の版"]) == ([], 4, _名(4), _名(3))


def test_履歴にだけ在る前の版も数え_番号を戻さない():
    # 前の版を 9_履歴/ へ移した後（置き場は空）・分けた枚・前の形の名も最大に数える
    assert 口.次の版(組, 支給月, [], [_名(1, "消す_2099-05-31_"), _名(3)])["版"] == 4
    assert 口.次の版(組, 支給月, [], [f"消す_2099-05-31_確認事項_{組}_{月}_v5-2.html"])["版"] == 6
    assert 口.次の版(組, 支給月, [], [f"確認ページ_{組}_{月}_v6.html"])["版"] == 7
    # 9_履歴/ のほかの物（出す物の前の版・ほかの月・ほかの組・下書き）は数えずに飛ばす（止めない）
    ほか = ["取り込み_作り物の組_2099-03_v9", _名(9).replace(月, "2099.05支給（4月分）"), _名(9).replace(組, "別の組"),
          _名(9, "下書き_"), "メモ.md"]
    v = 口.次の版(組, 支給月, [], ほか)
    assert (v["版"], v["前の版"], v["前の版たち"]) == (1, None, [])
    r = _作る(今ある名=[], 履歴にある名=[_名(2, "消す_2099-05-31_")])
    assert (r["赤"], r["版"], r["前の版"]) == ([], 3, None)


def test_前の版が無い置き場は空の並びを2つ渡して_v1():
    r = _作る(今ある名=[], 履歴にある名=[])
    assert (r["赤"], r["版"], r["名"]) == ([], 1, _名(1))


@pytest.mark.parametrize("足す", [
    {},                                                     # どちらも渡さない
    {"今ある名": [_名(3)]},                                  # 履歴を渡さない
    {"履歴にある名": []},                                    # 置き場を渡さない
    {"今ある名": None, "履歴にある名": []},
    {"今ある名": [], "履歴にある名": None},
    {"今ある名": _名(3), "履歴にある名": []},               # 名の並びでなく 1 つの字
    {"今ある名": [], "履歴にある名": {"確認事項": []}},     # dict
    {"今ある名": (n for n in [_名(3)]), "履歴にある名": []},  # 使い切る並び（generator）
    {"今ある名": [{"name": _名(3)}], "履歴にある名": []},   # Drive の一覧の dict をそのまま
    {"今ある名": [], "履歴にある名": [None]},
])
def test_前の版の名を並びで渡さなければ止める(足す):
    with pytest.raises(ValueError, match="名の並びで渡す|名の字だけで渡す"):
        _作る(**足す)
    with pytest.raises(ValueError, match="名の並びで渡す|名の字だけで渡す"):
        口._口("作る", {"組": 組, "支給月": 支給月, "用": "毎月", "問い": 問い, "読んだ資料": 読んだ, **足す})
    if 足す and not any(type(v).__name__ == "generator" for v in 足す.values()):
        with pytest.raises(ValueError, match="名の並びで渡す|名の字だけで渡す"):
            口.次の版(組, 支給月, 足す.get("今ある名"), 足す.get("履歴にある名"))
    with pytest.raises(TypeError):
        口.次の版(組, 支給月, [])   # 引数を省けない
