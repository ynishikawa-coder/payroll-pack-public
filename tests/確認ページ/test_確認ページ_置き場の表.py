"""確認事項の置き場の正本は 1 か所（docs/設計/Drive の型.md §3「確認事項の置き場の表」）。道具はそれを直に読む。

前は 確認ページ.py の 置き場() が組「事務所」に `00_事務所/8_確認事項/` を返し、型の文書の `00_事務所/` と食い違っていた
（置き場の正本が 2 つ）。ここは、道具の返す置き場が型の文書の表とずれたら赤になる事と、表が読めない時に置き場を推し量らず
止まる事を見る。
"""
import importlib.util
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
型の文書 = 根 / "docs" / "設計" / "Drive の型.md"

_s = importlib.util.spec_from_file_location("確認ページ_置き場の表", 根 / "確認ページ" / "確認ページ.py")
口 = importlib.util.module_from_spec(_s)
_s.loader.exec_module(口)

月 = "2099.01支給"


def _表を書き替えた文書(tmp_path: Path, 前: str, 後: str) -> Path:
    s = 型の文書.read_text(encoding="utf-8")
    assert 前 in s, 前
    p = tmp_path / "Drive の型.md"
    p.write_text(s.replace(前, 後, 1), encoding="utf-8")
    return p


def test_道具の置き場は型の文書の表と同じ():
    表 = 口.置き場の表を読む(型の文書)
    assert 表 == {"<会社>": ("10_会社/<会社>/8_確認事項/", "10_会社/<会社>/9_履歴/"), "事務所": ("00_事務所/", "00_事務所/9_履歴/")}
    # 道具の返す物が表と 1 字でも違えば赤（道具に置き場を写して食い違わせた時）
    assert 口.置き場("事務所", 月) == 表["事務所"][0]
    assert 口.置き場("作り物の組", 月) == 表["<会社>"][0].replace("<会社>", "作り物の組")
    名 = "確認事項_事務所_2099.01支給（12月分）_v1.html"
    assert 口.差し替え("事務所", 月, 名, "2099-03-31")["先"] == f"{表['事務所'][1]}消す_2099-03-31_{名}"
    assert 口.置き場の名 == "8_確認事項" and 口.履歴の名 == "9_履歴"
    assert 口.置き場の名たち == {"<会社>": "8_確認事項", "事務所": "00_事務所"}


def test_型の文書の表を変えると道具がそれに従う_食い違いを入れられない(tmp_path, monkeypatch):
    # わざと前の食い違い（事務所の置き場 00_事務所/8_確認事項/）を型の文書の側に入れる＝道具はその表を読んで同じ所を返す
    p = _表を書き替えた文書(tmp_path, "| `事務所` | `00_事務所/` |", "| `事務所` | `00_事務所/8_確認事項/` |")
    monkeypatch.setattr(口, "置き場の表", 口.置き場の表を読む(p))
    assert 口.置き場("事務所", 月) == "00_事務所/8_確認事項/"
    # 読んだ表と道具の返す物が違えば、上の試験（今の型の文書と照らす）が赤になる
    assert 口.置き場("事務所", 月) != 口.置き場の表を読む(型の文書)["事務所"][0]


@pytest.mark.parametrize("前,後", [
    ("### 確認事項の置き場の表", "### 置き場"),                                # 表の見出しが無い
    ("| 問い | 置き場 | 前の版 |", "| 問い | 所 | 前の版 |"),                 # 列の名が違う
    ("| `事務所` | `00_事務所/` | `00_事務所/9_履歴/` |\n", ""),             # 事務所の行が無い
    ("| `事務所` | `00_事務所/` |", "| `事務所` | `00_事務所` |"),             # / で終わらない
    ("| `<会社>` | `10_会社/<会社>/8_確認事項/` |", "| `<会社>` | `10_会社/8_確認事項/` |"),  # 会社の名を持たない
])
def test_表が読めなければ置き場を推し量らず止まる(tmp_path, 前, 後):
    p = _表を書き替えた文書(tmp_path, 前, 後)
    with pytest.raises(ValueError):
        口.置き場の表を読む(p)


def test_表が無い文書でも止まる(tmp_path):
    with pytest.raises(ValueError):
        口.置き場の表を読む(tmp_path / "無い.md")


def test_事務所の置き場では確認事項でない物を数えず_確認事項は今までどおり読む():
    今ある = ["事務所のルール.md", "事務所の設定", "管理表", "質問と回答", "9_履歴/",
            "確認事項_事務所_2099.01支給（12月分）_v1.html", "下書き_確認事項_事務所_2099.01支給（12月分）_v2.html"]
    v = 口.次の版("事務所", 月, 今ある)
    assert v["版"] == 2 and v["置き場"] == "00_事務所/" and v["前の版"] == "確認事項_事務所_2099.01支給（12月分）_v1.html"
    # 前の形の名・ほかの組の名・頭が在るのに形の読めない名は、事務所の置き場でも止める（黙って版を数え直さない）
    for 悪い in ("確認ページ_事務所_2099.01支給（12月分）_v1.html", "確認事項_作り物の組_2099.01支給（12月分）_v1.html",
               "確認事項_事務所_v1.html"):
        with pytest.raises(ValueError):
            口.次の版("事務所", 月, 今ある + [悪い])
    # 会社の置き場（8_確認事項 だけの所）は今までどおり確認事項でない名も止める
    with pytest.raises(ValueError):
        口.次の版("作り物の組", 月, ["管理表"])


def test_型の文書の事務所の木に置き場と前の版が在る():
    s = 型の文書.read_text(encoding="utf-8")
    木 = s[s.index("### 事務所の根"):s.index("### 会社の根")]
    assert "確認事項_事務所_<支給月>_v<版>.html" in 木 and "9_履歴/" in 木
