"""確認事項の置き場の正本は 1 か所（初期設定/型.json の 木.確認事項の置き場）。道具は 型の口 からそれを読む。

前は 確認ページ.py が docs/設計/Drive の型.md §3 の表を直に読み、型.json と文書の 2 つが木の正本だった
（さらに前は 置き場() が組「事務所」に `00_事務所/8_確認事項/` を返し、型の文書の `00_事務所/` と食い違っていた）。
ここは、道具の返す置き場が型.json とずれたら赤になる事と、表が読めない時に置き場を推し量らず止まる事を見る。
"""
import importlib.util
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]

_s = importlib.util.spec_from_file_location("確認ページ_置き場の表", 根 / "確認ページ" / "確認ページ.py")
口 = importlib.util.module_from_spec(_s)
_s.loader.exec_module(口)
型 = 口.型

月 = "2099.01支給"


def test_道具の置き場は型の木と同じ():
    表 = 口.置き場の表を確かめる(型.確認事項の置き場の表())
    assert 表 == {"<組>": ("10_会社/<組>/8_確認事項/", "10_会社/<組>/9_履歴/"), "事務所": ("00_事務所/", "00_事務所/9_履歴/")}
    assert 口.置き場の表 == 表
    # 道具の返す物が表と 1 字でも違えば赤（道具に置き場を写して食い違わせた時）
    assert 口.置き場("事務所", 月) == 表["事務所"][0]
    assert 口.置き場("作り物の組", 月) == 表["<組>"][0].replace("<組>", "作り物の組")
    名 = "確認事項_事務所_2099.01支給（12月分）_v1.html"
    assert 口.差し替え("事務所", 月, 名, "2099-03-31")["先"] == f"{表['事務所'][1]}消す_2099-03-31_{名}"
    assert 口.置き場の名 == 型.名("確認事項") and 口.履歴の名 == 型.名("履歴")
    assert 口.置き場の名たち == {"<組>": 型.名("確認事項"), "事務所": 型.名("事務所")}


def test_型の木を変えると道具がそれに従う_食い違いを入れられない(monkeypatch):
    # わざと前の食い違い（事務所の置き場 00_事務所/8_確認事項/）を型の側に入れる＝道具はその表を読んで同じ所を返す
    表 = dict(型.確認事項の置き場の表())
    表["事務所"] = ("00_事務所/8_確認事項/", 表["事務所"][1])
    monkeypatch.setattr(口, "置き場の表", 口.置き場の表を確かめる(表))
    assert 口.置き場("事務所", 月) == "00_事務所/8_確認事項/"
    assert 口.置き場("事務所", 月) != 型.確認事項の置き場の表()["事務所"][0]


@pytest.mark.parametrize("直す", [
    lambda t: t.pop("事務所"),                                                # 事務所の行が無い
    lambda t: t.update({"事務所": ("00_事務所", "00_事務所/9_履歴/")}),       # / で終わらない
    lambda t: t.update({"<組>": ("10_会社/8_確認事項/", "10_会社/<組>/9_履歴/")}),  # 組の名を持たない
    lambda t: t.update({"<組>": ("10_会社/<組>/8_確認事項/",)}),              # 前の版が無い
    lambda t: t.update({"ほか": ("x/", "y/")}),                               # 知らない行
])
def test_表が読めなければ置き場を推し量らず止まる(直す):
    表 = dict(型.確認事項の置き場の表())
    直す(表)
    with pytest.raises(ValueError):
        口.置き場の表を確かめる(表)


def test_事務所の置き場では確認事項でない物を数えず_確認事項は今までどおり読む():
    今ある = list(型.物たち("事務所の物")) + [f"{型.名('履歴')}/",
            "確認事項_事務所_2099.01支給（12月分）_v1.html", "下書き_確認事項_事務所_2099.01支給（12月分）_v2.html"]
    v = 口.次の版("事務所", 月, 今ある, [])
    assert v["版"] == 2 and v["置き場"] == "00_事務所/" and v["前の版"] == "確認事項_事務所_2099.01支給（12月分）_v1.html"
    # 前の形の名・ほかの組の名・頭が在るのに形の読めない名は、事務所の置き場でも止める（黙って版を数え直さない）
    for 悪い in ("確認ページ_事務所_2099.01支給（12月分）_v1.html", "確認事項_作り物の組_2099.01支給（12月分）_v1.html",
               "確認事項_事務所_v1.html"):
        with pytest.raises(ValueError):
            口.次の版("事務所", 月, 今ある + [悪い], [])
    # 会社の置き場（8_確認事項 だけの所）は今までどおり確認事項でない名も止める
    with pytest.raises(ValueError):
        口.次の版("作り物の組", 月, [型.名("管理表")], [])


def test_名の形は型の名の形から作る():
    形 = 型.名の形("確認事項")
    assert 形["形"].startswith(口.名の頭 + "_") and 口.下書きの頭 == 形["下書きの頭"]
    assert 口.名("事務所", 月, 1) == "確認事項_事務所_2099.01支給（12月分）_v1.html"
