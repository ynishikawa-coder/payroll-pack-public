"""確認事項を置く名・版・前の版の移しは 確認ページ.配る手順 の 1 か所（束 E・2026-11-22）。作り物の値だけ。

根: 配る窓は窓が組んだ名のまま置き、同じシートの前の file の中身を上書きし、前の版を 9_履歴 へ移さず、下書き_ の名を残した。
ここは、外れた名（前と同じ版・飛んだ版・下書きのまま配る）をわざと渡すと止まる事と、前の版の全部の枚と残った下書きを
消す日つきで移す手順が返る事を見る。
根（レビュー red 2026-11-22）: 問いが 12 問を超えて枚に分けた版（`_v<版>-<枚>.html`）を、配る手順 が枚の無い名と 1 file ずつ
比べたので、1 枚目も 2 枚目も必ず止まった。ここは 1 つの版の全部の枚を 1 度に受けて通す事と、枚を 1 つずつ・欠けた・多い・
名だけ付け替えた枚を渡すと止まる事を、本物の 作る が返した枚で見る。
"""
import importlib.util
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
_s = importlib.util.spec_from_file_location("確認ページ_配る手順", 根 / "確認ページ" / "確認ページ.py")
口 = importlib.util.module_from_spec(_s)
_s.loader.exec_module(口)

組, 支 = "作り物の組", "2099.04支給"
月 = 口.支給月の名(支)


def _名(v, 下書き=False, 枚=None):
    return 口.名(組, 支, v, 下書き=下書き, 枚=枚)


def _物(v, 下書き=False, 数=1):
    """作る が返す形の (名, html)（枚の印と __版__ だけを持つ作り物の中身）。"""
    out = []
    for k in range(1, 数 + 1):
        枚 = k if 数 > 1 else None
        h = (f"<!doctype html>\n{口.枚の印(k, 数)}\n"
             f'<input type="hidden" name="__版__" value="{口.版の字(支, v, 枚=枚)}">')
        out.append((_名(v, 下書き=下書き, 枚=枚), h))
    return out


def test_配り直しは新しい版の名と前の版と下書きの移し():
    今 = [_名(1, 枚=1), _名(1, 枚=2), _名(2, 下書き=True)]
    r = 口.配る手順(組, 支, _物(2), 今, [], "2099-04-15")
    assert r["名たち"] == [_名(2)] and r["版"] == 2 and r["上書き"] == []
    先 = 口.置き場の表[口.会社の印][1].replace(口.会社の印, 組)
    assert [x["先"] for x in r["移す"]] == [f"{先}消す_2099-05-31_{n}" for n in 今]
    assert all(x["する"] == "移す" and x["元"].startswith(r["置き場"]) for x in r["移す"])


@pytest.mark.parametrize("置く名", [
    _名(1),                       # 前と同じ版
    _名(3),                       # 飛んだ版
    _名(2, 下書き=True),           # 下書きのまま配る
    "確認事項_作り物の組_v2.html",  # 手で組んだ形の外れた名
])
def test_外れた名をわざと渡すと止まる(置く名):
    with pytest.raises(ValueError):
        口.配る手順(組, 支, [(置く名, _物(2)[0][1])], [_名(1)], [], "2099-04-15")


def test_9_履歴の版も数える():
    with pytest.raises(ValueError):
        口.配る手順(組, 支, _物(1), [], [f"消す_2099-03-31_{_名(1)}"], "2099-04-15")
    assert 口.配る手順(組, 支, _物(2), [], [f"消す_2099-03-31_{_名(1)}"], "2099-04-15")["移す"] == []


def test_下書きを置き直す時は同じ名の下書きを上書きし前の版は移さない():
    r = 口.配る手順(組, 支, _物(2, 下書き=True), [_名(1), _名(2, 下書き=True)], [], "2099-04-15", 下書き=True)
    assert r["上書き"] == [_名(2, 下書き=True)] and r["移す"] == []


# ── 枚に分けた版（12 問を超えた）は全部の枚を 1 つの単位で受ける ─────────────────────────────

_t = importlib.util.spec_from_file_location("確認ページ_の試験の作り物", 根 / "tests" / "確認ページ" / "test_確認ページ.py")
_作り物 = importlib.util.module_from_spec(_t)
_t.loader.exec_module(_作り物)   # 作る の検査を通る作り物の問いと読んだ資料（test_確認ページ.py の 12 問超えと同じ）


def _問い(n):
    元 = _作り物.問い
    return [元[0], *({**元[2], "問いの番号": f"Q209904-{k:02d}", "対象": f"全員／4 月支給／締め日 {k}"} for k in range(10, 9 + n))]


def _作った枚(今, 履歴, n=13):
    r = 口.作る({"組": 組, "支給月": 支, "用": "毎月", "問い": _問い(n), "読んだ資料": _作り物.読んだ,
               "今ある名": 今, "履歴にある名": 履歴})
    assert r["赤"] == [], r["赤"][:3]
    return r


def test_作るが分けた枚を1度に渡すと通り前の版の移しは1回():
    r = _作った枚([_名(1)], [])
    assert len(r["枚たち"]) == 2
    物 = [(x["名"], x["html"]) for x in r["枚たち"]]
    p = 口.配る手順(組, 支, 物, [_名(1)], [], "2099-04-15")
    assert p["名たち"] == [_名(2, 枚=1), _名(2, 枚=2)]
    assert [x["元"].rsplit("/", 1)[-1] for x in p["移す"]] == [_名(1)]


def test_作るが分けた下書きの枚も1度に置き直せる():
    r = _作った枚([_名(1), _名(2, 下書き=True)], [])
    物 = [(x["下書きの名"], x["html"]) for x in r["枚たち"]]
    p = 口.配る手順(組, 支, 物, [_名(1), _名(2, 下書き=True)], [], "2099-04-15", 下書き=True)
    assert p["名たち"] == [_名(2, 下書き=True, 枚=1), _名(2, 下書き=True, 枚=2)]
    assert p["上書き"] == []
    assert [x["元"].rsplit("/", 1)[-1] for x in p["移す"]] == [_名(2, 下書き=True)]   # 枚の分け方が変わった古い下書き


def test_注入_枚を1つずつ渡すと止まる():
    r = _作った枚([_名(1)], [])
    for x in r["枚たち"]:
        with pytest.raises(ValueError):
            口.配る手順(組, 支, [(x["名"], x["html"])], [_名(1)], [], "2099-04-15")


def test_注入_枚の数や名が作るの返す物と違えば止まる():
    r = _作った枚([_名(1)], [])
    一, 二 = [(x["名"], x["html"]) for x in r["枚たち"]]
    三 = (_名(2, 枚=3), 二[1])
    for 物 in ([一, 二, 三],                       # 多い（ほかの回の枚が混ざった）
               [二, 一],                           # 並びが違う
               [(_名(2), 一[1])],                   # 分けた枚を分けない名で
               [(一[0], 一[1]), (二[0], 一[1])]):   # 名だけ付け替えた枚
        with pytest.raises(ValueError):
            口.配る手順(組, 支, 物, [_名(1)], [], "2099-04-15")
    with pytest.raises(ValueError, match="置く物は"):   # 1 字の名を渡す（前の 1 file ずつの形）＝形の照らしが止める
        口.配る手順(組, 支, 一[0], [_名(1)], [], "2099-04-15")


def test_注入_3枚に分けた版の前の2枚だけを渡すと枚の印で止まる():
    # 名の並び（2 枚の版の名）と各枚の __版__ は合う＝枚の印（k/3）だけがこの欠けを拒む（レビュー red 2026-11-22・再レビュー）
    r = _作った枚([], [], n=25)
    物 = [(x["名"], x["html"]) for x in r["枚たち"]]
    assert len(物) == 3
    口.配る手順(組, 支, 物, [], [], "2099-04-15")   # 全部の枚なら通る
    with pytest.raises(ValueError, match="枚の印"):
        口.配る手順(組, 支, 物[:2], [], [], "2099-04-15")


def test_注入_別の版の中身を名だけ付け替えると止まる():
    物 = _物(2)
    with pytest.raises(ValueError):
        口.配る手順(組, 支, [(_名(3), 物[0][1])], [_名(1), _名(2)], [], "2099-04-15")


def test_作るの枚には枚の印が1つずつ在る():
    r = _作った枚([], [], n=25)
    assert [口.枚の印を読む(x["html"]) for x in r["枚たち"]] == [(1, 3), (2, 3), (3, 3)]
    r = _作った枚([], [], n=3)
    assert 口.枚の印を読む(r["html"]) == (1, 1)


def test_消す日は移した日の翌月末():
    assert 口.前の版の消す日("2099-12-10") == "2100-01-31"
    with pytest.raises(ValueError):
        口.前の版の消す日("2099/12/10")
