def test_外へ通信しない自己完結のHTML():
    for r in (作る(), 作る("立ち上げ", 宛先="copy")):
        h = r["html"]
        assert not re.search(r"https?://|//[a-z0-9.-]+\.[a-z]{2,}/", h, re.I)
        assert not re.search(r"<script\b[^>]*\bsrc=|<link\b|<img\b[^>]*\bsrc=\"(?!data:)|<iframe\b|@import|url\(", h, re.I)
        assert not re.search(r"\bfetch\s*\(|XMLHttpRequest|sendBeacon|WebSocket|EventSource", h)
        assert re.search(r"<form>", h) and not re.search(r"<form\b[^>]*\b(action|method)=", h)
        assert "{{" not in h and "<!--問い-->" not in h


def 写しの文字列(行たち, 選んだ, 補足, 全体) -> str:
    """qa-html の写す形の貼り戻しの文字列（雛形の qa:js の build と同じ形）を、画面の字から作る。"""
    lines = ["# 題 — 回答", ""]
    for i, 行 in enumerate(行たち):
        lines.append(f"■ 問{i + 1}: {行['質問']}")
        lines.append("   → 回答: " + (選んだ[i] or "（未選択）"))
        if 補足[i]:
            lines.append("   → 補足: " + 補足[i])
        lines.append("")
    lines += ["■ その他・全体の意向:", "   " + (全体 or "（なし）")]
    return "\n".join(lines)


