def 骨(html: str) -> dict:
    """HTML から見張る骨だけを抜く（CSS・JS の中身は見ない）。"""
    箱たち = []
    for m in re.finditer(r'<fieldset class="q" data-qkey="([^"]+)" data-qlabel="[^"]*" data-kind="([^"]+)" data-group="([^"]+)"'
                         r'(?: data-glabel="([^"]*)")?>(.*?)</fieldset>', html, re.S):
        中 = m.group(5)
        箱たち.append({
            "鍵": m.group(1), "形": m.group(2), "まとまり": m.group(3), "まとまりの見出し": m.group(4),
            "まとまりの1行": (re.search(r'<p class="glead">(.*?)</p>', 中) or [None, None])[1],
            "何について": re.findall(r"<span(?: class=\"who\")?>(.*?)</span>", re.search(r'<p class="about">(.*?)</p>', 中).group(1)),
            "問い": re.search(r"<legend>(.*?)</legend>", 中).group(1),
            "なぜ": re.search(r'<p class="why" data-why="([^"]+)">', 中).group(1),
            "見つけた事": list(re.search(r'<div class="known" data-docs="([^"]*)">(.*?)</div>', 中, re.S).groups()),
            "切り抜き": [list(x) for x in re.findall(r'<figure class="clip" data-doc="([^"]*)" data-shows="([^"]*)">', 中)],
            "くわしく": re.search(r'<details class="more"><summary>くわしく</summary>(.*?)</details>', 中, re.S).group(1),
            "根拠": [list(x) for x in re.findall(r'<li data-doc="([^"]*)" data-where="([^"]*)">(.*?)</li>', 中, re.S)],
            "読み": re.findall(r'<p class="reading">(.*?)</p>', 中, re.S),
            "見込み": [list(x) for x in re.findall(r'<p class="estimate" data-basis="([^"]*)">(.*?)</p>', 中, re.S)],
            "選択肢": [[v, re.sub(r"<[^>]+>", "", b), re.sub(r"<[^>]+>", "", 変 or ""), re.sub(r"<[^>]+>", "", 添 or ""), "tag-rec" in b]
                     + ([True] if 要 else [])
                    for v, 要, b, 変, 添 in re.findall(r'<input type="radio" name="[^"]+" value="([^"]*)"(?: required)?( data-supp="need")?><span><b>(.*?)</b>'
                                                  r'(?:<small class="chg">(.*?)</small>)?(?:<small>(.*?)</small>)?</span>', 中)],
            "補足": f'name="supp_{m.group(1)}"' in 中,
        })
    return {
        "宛先": re.search(r'<body data-dest="([^"]+)"', html).group(1),
        "題": re.search(r"<title>(.*?)</title>", html).group(1),
        "前書き": re.search(r'<p class="lead">(.*?)</p>', html).group(1),
        "読んだ資料": [list(x) for x in re.findall(r'<li data-doc="([^"]+)" data-url="([^"]*)"(?: data-no-url="([^"]*)")?>(.*?)</li>', html)],
        "答えるまで": re.search(r'<p class="hold">(.*?)</p>', html).group(1),
        "版": re.search(r'name="__版__" value="([^"]*)"', html).group(1),
        "箱": 箱たち,
        "自由記入": 'name="__自由記入__"' in html,
        "印": [k for k in ("css", "foot", "js") if html.count(f"<!--qa:{k}-->") == 1 and html.count(f"<!--/qa:{k}-->") == 1],
    }


