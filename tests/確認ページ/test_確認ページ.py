def 骨(html: str) -> dict:
    """HTML から見張る骨だけを抜く（CSS・JS の中身は見ない）。"""
    箱たち = []
    for m in re.finditer(r'<fieldset class="q" data-qkey="([^"]+)" data-qlabel="[^"]*" data-kind="([^"]+)">(.*?)</fieldset>', html, re.S):
        中 = m.group(3)
        箱たち.append({
            "鍵": m.group(1), "形": m.group(2),
            "問い": re.search(r"<legend>(.*?)</legend>", 中).group(1),
            "分かっている事": re.findall(r'<div class="known">(.*?)</div>', 中),
            "選択肢": [[v, re.sub(r"<[^>]+>", "", b), "tag-rec" in b]
                    for v, b in re.findall(r'<input type="radio" name="[^"]+" value="([^"]*)"><span><b>(.*?)</b>', 中)],
            "決まる事": re.search(r'<p class="decides">(.*?)</p>', 中).group(1),
            "補足": f'name="supp_{m.group(1)}"' in 中,
        })
    return {
        "宛先": re.search(r'<body data-dest="([^"]+)">', html).group(1),
        "題": re.search(r"<title>(.*?)</title>", html).group(1),
        "前書き": re.search(r'<header class="top">.*?<p>(.*?)</p>', html, re.S).group(1),
        "箱": 箱たち,
        "自由記入": 'name="__自由記入__"' in html,
        "印": [k for k in ("css", "toc", "foot", "js") if f"<!--qa:{k}-->" in html and f"<!--/qa:{k}-->" in html],
    }


