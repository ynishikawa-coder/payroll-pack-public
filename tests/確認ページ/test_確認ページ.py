# ── 貼り戻し（qa-html/2 の答え → 質問と回答の行） ──

def _値(html: str, 鍵: str, 見出し: str) -> str:
    """HTML の上の選択肢の鍵（value）を見出しから引く（答える人が押した物）。"""
    for b in 骨(html)["箱"]:
        if b["鍵"] == 鍵:
            return next(v for v, 見, *_ in b["選択肢"] if 見.replace("おすすめ", "") == 見出し)
    raise KeyError(鍵)


def 答えのJSON(html: str, 選ぶ: dict, 補足=None, 全体="", 受付="R990402-7KQ4", 版=None) -> dict:
    """型の JS の payload と同じ形（qa-html/2）を、HTML の上の見出しを選んで作る。"""
    補足 = 補足 or {}
    版 = 版 or 骨(html)["版"]
    answers = {k: [_値(html, k, v)] for k, v in 選ぶ.items()}
    return {"form": "qa-html/2", "title": 骨(html)["題"], "version": 版, "receipt": 受付, "answered_at": "2099-04-02T10:00:00+09:00",
            "answers": answers, "labels": {k: [v] for k, v in 選ぶ.items()}, "supp": 補足, "free": 全体}


def 貼り戻しの字(html: str, p: dict) -> str:
    """型の JS の pasteText と同じ形（1 行目 # 件名 — 回答・2 行目 版と受付番号・■ 問N [鍵]・最後に qa-json）。"""
    lines = [f"# {p['title']} — 回答", f"版: {p['version']} ／ 受付番号: {p['receipt']}", ""]
    for i, b in enumerate(骨(html)["箱"], 1):
        k = b["鍵"]
        lines += [f"■ 問{i} [{k}]: {b['問い']}", "   → 回答: " + ("、".join(p["labels"].get(k, [])) or "（未選択）")]
        if p["supp"].get(k):
            lines.append("   → 補足: " + p["supp"][k])
        lines.append("")
    lines += ["■ その他・全体の意向:", "   " + (p["free"] or "（なし）"), "", "qa-json: " + json.dumps(p, ensure_ascii=False)]
    return "\n".join(lines)


