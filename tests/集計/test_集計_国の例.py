"""① 国が答えを決めている例（労基法 32 条・35 条・37 条・34 条と通達の数え方）。作り物の 1 人だけ。"""
from 作る_集計 import 一つ, 区, 数える, 既定の決まり, 日, 月


def 働く(d, 始め, 終わり, 休憩=("12:00", "13:00"), 種類="勤務", **列):
    bs = [区(d, 1, 始め, 終わり)] + ([区(d, 2, *休憩, "休憩")] if 休憩 else [])
    return 日(d, 種類, **列), bs


def test_日8時間を超えた分は法定外():
    x = 数える(*月(上書き={"2026-11-03": 働く("2026-11-03", "9:00", "20:00")}))
    assert 一つ(x, "法定外残業") == 120
    assert 一つ(x, "所定内") == 21 * 480
    assert 一つ(x, "総労働") == 21 * 480 + 120


def test_所定を超え日8時間までは法定内残業():
    x = 数える(*月(), 既定の決まり(**{"時間.日の所定": "7", "時間.所定の終業": "17:00"}))
    assert 一つ(x, "所定内") == 21 * 420
    assert 一つ(x, "法定内残業") == 21 * 60
    assert 一つ(x, "法定外残業") == 0


def test_深夜帯の重なり_休憩は引く():
    上 = {"2026-11-03": 働く("2026-11-03", "13:00", "23:00", ("17:00", "18:00")),
          "2026-11-04": 働く("2026-11-04", "20:00", "29:30", ("24:00", "25:00"))}
    x = 数える(*月(上書き=上))
    assert 一つ(x, "深夜") == 60 + (420 - 60)
    assert 一つ(x, "夜勤の回数") == 1


def test_深夜に入る休憩を引かない会社():
    上 = {"2026-11-04": 働く("2026-11-04", "20:00", "29:30", ("24:00", "25:00"))}
    x = 数える(*月(上書き=上), 既定の決まり(**{"割増.深夜に入る休憩": "引かない"}))
    assert 一つ(x, "深夜") == 420


def test_週40時間を超えた所定休日の労働は法定外():
    # 平日 7 時間×5 日＝35 時間、土曜 8 時間 → 40 時間までの 5 時間は法定内、超えた 3 時間は法定外
    上 = {f"2026-11-0{i}": 働く(f"2026-11-0{i}", "9:00", "17:00") for i in range(2, 7)}
    上["2026-11-07"] = 働く("2026-11-07", "9:00", "18:00", 種類="休日勤務")
    x = 数える(*月(上書き=上))
    assert 一つ(x, "法定内残業") == 300
    assert 一つ(x, "法定外残業") == 180
    assert 一つ(x, "所定休日") == 480
    assert 一つ(x, "休日勤務日数（所定）") == 1
    assert 一つ(x, "遅刻早退") == 5 * 60  # 所定 8 時間に 1 時間ずつ足りない


def test_法定休日の労働は週40時間に入れず深夜も数える():
    上 = {"2026-11-08": 働く("2026-11-08", "9:00", "18:00", 種類="休日勤務"),
          "2026-11-15": 働く("2026-11-15", "18:00", "23:00", None, 種類="休日勤務")}
    x = 数える(*月(上書き=上))
    assert 一つ(x, "法定休日") == 480 + 300
    assert 一つ(x, "深夜") == 60
    assert 一つ(x, "法定外残業") == 0
    assert 一つ(x, "休日勤務日数（法定）") == 2
    assert 一つ(x, "出勤日数") == 21


def test_法定休日は暦日_0時からが休日労働():
    # 土曜（所定休日）22:00〜日曜 3:00 → 土曜の 2 時間は所定休日、日曜の 3 時間は法定休日
    x = 数える(*月(上書き={"2026-11-14": 働く("2026-11-14", "22:00", "27:00", None, 種類="休日勤務")}))
    assert 一つ(x, "所定休日") == 120
    assert 一つ(x, "法定休日") == 180
    assert 一つ(x, "深夜") == 300


def test_月60時間を超えた法定外():
    上 = {}
    A, _ = 月()
    for a in A:
        if a["日の種類"] == "勤務":
            上[a["日付"]] = 働く(a["日付"], "9:00", "22:00")
    x = 数える(*月(上書き=上))
    assert 一つ(x, "法定外残業") == 21 * 240
    assert 一つ(x, "60 時間超") == 21 * 240 - 3600


def test_1か月変形は週の所定と期間の総枠で数える():
    # 1 週目の平日を所定 9 時間（週 45 時間）にした 30 日の期間。週の線は 45 時間、期間の総枠は 40×30/7 時間（分未満は切捨て）
    上 = {f"2026-11-0{i}": 働く(f"2026-11-0{i}", "9:00", "19:00", 所定時間="540") for i in range(2, 7)}
    x = 数える(*月(上書き=上), 既定の決まり(**{"時間.制度": "1か月変形"}))
    総枠 = 40 * 60 * 30 // 7
    assert 一つ(x, "法定外残業") == 5 * 540 + 16 * 480 - 総枠
    x = 数える(*月(上書き=上), 既定の決まり(**{"時間.日の所定": "8"}))  # 通常の制度なら日 8 時間を超えた分
    assert 一つ(x, "法定外残業") == 5 * 60


def test_休憩が34条の長さに足りない日は知らせる():
    x = 数える(*月(上書き={"2026-11-03": 働く("2026-11-03", "9:00", "17:00", None, 時刻の無い休憩="0")}))
    assert any("休憩が法の長さに足りない" in t for t in x["知らせ"])
    assert x["人"][0]["状態"] == "確認済"


def test_期間の終わりの日またぎも法定休日は暦日():
    # 期間 11-01〜11-07。土 11-07（休日勤務・所定）22:00〜翌 6:00 → 翌日曜 0:00 からの 6 時間は法定休日（表 A に無い日でも）
    x = 数える(*月(日数=7, 上書き={"2026-11-07": 働く("2026-11-07", "22:00", "30:00", None, 種類="休日勤務", 時刻の無い休憩="0")}))
    assert 一つ(x, "法定休日") == 360
    assert 一つ(x, "所定休日") == 120
    assert x["人"][0]["状態"] == "確認済"
    # 法定休日を週の最後の休日で決める会社は、期間の外の日が法定休日か決まらない → 仮と問い
    x = 数える(*月(日数=7, 上書き={"2026-11-07": 働く("2026-11-07", "22:00", "30:00", None, 種類="休日勤務", 時刻の無い休憩="0")}),
             既定の決まり(**{"休日.法定休日の決め方": "週の最後の休日"}))
    行 = {r["項目"]: r for r in x["行"]}
    assert 行["法定休日"]["状態"] == "仮" and 行["休日勤務日数（所定）"]["状態"] == "確定"
    assert any("表 A に無い日" in q["何が無いか"] for q in x["問い"])


def test_日またぎで法定休日へかかった分は遅刻早退にしない():
    # 土 11-07 を勤務日（所定 8 時間）にし 22:00〜翌 6:00。翌日曜 0:00 からの 6 時間は法定休日で、所定を欠いてはいない
    上 = {"2026-11-07": 働く("2026-11-07", "22:00", "30:00", None, 時刻の無い休憩="0")}
    x = 数える(*月(上書き=上))
    assert 一つ(x, "法定休日") == 360
    assert 一つ(x, "遅刻早退") == 0
