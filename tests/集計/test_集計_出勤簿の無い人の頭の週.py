"""出勤簿が無い人（時間.出勤簿が無い＝無い・勤務の日が全部 定時扱い）の期間の頭の週（作り物の値だけ）。

前の期間の日も所定どおり＝期間の中のまるごとの週が週の線の内なら、前の期間の日を求めない（受けても同じ答え）。
期間の中の週が線を超える所定・打刻のある日が混じる人・出勤簿のある人は今までどおり前の期間の日を求める。
"""
from datetime import date, timedelta

from 作る_集計 import 区, 数える, 既定の決まり, 日

前の理由 = "期間の頭の週が前の期間にかかり、前の期間の日を受けていない（週の法定の判定）"


def _所定どおり(始め=date(2026, 11, 4), 日数=30, 土曜も=False, 打刻の日=None):
    A, B = [], []
    for i in range(日数):
        d = 始め + timedelta(days=i)
        s = d.isoformat()
        if d.weekday() == 6 or (d.weekday() == 5 and not 土曜も):
            A.append(日(s, "休日"))
        elif s == 打刻の日:
            A.append(日(s))
            B += [区(s, 1, "9:00", "18:00"), 区(s, 2, "12:00", "13:00", "休憩")]
        else:
            A.append(日(s, 印="定時扱い"))
    return A, B


def _問い(x):
    return [q["何が無いか"] for q in x["問い"]]


def test_出勤簿が無い人は週の線の内なら前の期間の日を求めない():
    x = 数える(*_所定どおり(), 既定の決まり(**{"時間.出勤簿が無い": "無い"}))
    assert 前の理由 not in _問い(x)


def test_出勤簿のある人は今までどおり求める():
    assert 前の理由 in _問い(数える(*_所定どおり(), 既定の決まり()))


def test_所定どおりでも週の線を超える週なら求める():
    x = 数える(*_所定どおり(土曜も=True), 既定の決まり(**{"時間.出勤簿が無い": "無い"}))
    assert 前の理由 in _問い(x)


def test_打刻のある日が混じれば求める():
    x = 数える(*_所定どおり(打刻の日="2026-11-10"), 既定の決まり(**{"時間.出勤簿が無い": "無い"}))
    assert 前の理由 in _問い(x)
