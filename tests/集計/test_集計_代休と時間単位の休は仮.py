"""代休の日・年休でない時間単位の休を知らせだけで流さない（作り物の値だけ）。

- 月給などの人の代休の日: 引くかの決まりがパックに無い＝その人を仮にする（出口へ出さない）
- 時給・日給の人の代休の日: 払いが無い＝知らせだけ（仮にしない）
- 年休でない時間単位の休: 休んだ分を数える所が無い＝賃金の形を問わず仮
- 代休の日も時間単位の休も無い人の結果は変わらない（回帰の見張り）
"""
from 作る_集計 import 区, 数える, 既定の決まり, 日, 月
from 芯.集計 import 月 as 月の


def _平日(A):
    return [r["日付"] for r in A if r["日の種類"] == "勤務"]


def _代休の月():
    A, _ = 月()
    a = _平日(A)[2]
    return 月(上書き={a: (日(a, "休暇", 休暇の種類="代休", 休暇の単位="全日", 代休の相手の日="2026-11-01"), [])}), a


def _問い(x, 理由):
    return [q for q in x["問い"] if q["何が無いか"] == 理由]


def test_月給の人の代休の日は仮で止める():
    (A, B), a = _代休の月()
    for 形 in ("月給", "日給月給", "年俸", ""):
        x = 数える(A, B, 既定の決まり(**{"支払.賃金の形": 形}))
        assert x["人"][0]["状態"] == "仮", 形
        (q,) = _問い(x, 月の.代休の日を引くか)
        assert q["日付"] == [a] and q["人"] == [("作り物の会社", "1")]
        assert not [t for t in x["知らせ"] if "代休" in t]


def test_時給と日給の人の代休の日は知らせだけ():
    (A, B), a = _代休の月()
    for 形 in ("時給", "日給"):
        x = 数える(A, B, 既定の決まり(**{"支払.賃金の形": 形}))
        assert x["人"][0]["状態"] == "確認済", (形, x["問い"])
        assert [t for t in x["知らせ"] if a in t and "代休の日" in t], x["知らせ"]


def test_年休でない時間単位の休は仮で止める():
    A, _ = 月()
    a = _平日(A)[3]
    働く = [区(a, 1, "9:00", "16:00"), 区(a, 2, "12:00", "13:00", "休憩")]
    for 休 in ("特別休暇（無給）", "特別休暇（有給）", "子の看護等休暇", "代休"):
        for 形 in ("時給", "月給"):
            A2, B2 = 月(上書き={a: (日(a, 休暇の種類=休, 休暇の単位="時間", 休暇の時間="120"), 働く)})
            x = 数える(A2, B2, 既定の決まり(**{"支払.賃金の形": 形}))
            assert x["人"][0]["状態"] == "仮", (休, 形)
            理由たち = [q["何が無いか"] for q in x["問い"]]
            # 月給の人の時間単位の代休は代休の問い 1 つにまとめる（同じ日に 2 問を重ねない）
            if 休 == "代休" and 形 == "月給":
                assert 理由たち == [月の.代休の日を引くか], 理由たち
            else:
                assert 理由たち == [月の.時間単位の休を数えない.format(休=休)], 理由たち


def test_年休の時間単位は今までどおり数える():
    A, _ = 月()
    a = _平日(A)[3]
    働く = [区(a, 1, "9:00", "16:00"), 区(a, 2, "12:00", "13:00", "休憩")]
    A2, B2 = 月(上書き={a: (日(a, 休暇の種類="年休", 休暇の単位="時間", 休暇の時間="120"), 働く)})
    x = 数える(A2, B2, 既定の決まり(**{"支払.賃金の形": "月給"}))
    assert x["人"][0]["状態"] == "確認済", x["問い"]


def test_代休の日の無い人の結果は変わらない():
    """回帰の見張り: 代休の日も時間単位の休も無い人は、賃金の形を問わず仮にならず、行も同じ。"""
    A, B = 月()
    基 = 数える(A, B)
    assert 基["人"][0]["状態"] == "確認済" and not 基["問い"]
    for 形 in ("月給", "時給", ""):
        x = 数える(A, B, 既定の決まり(**{"支払.賃金の形": 形}))
        assert x["人"][0]["状態"] == "確認済" and not x["問い"], 形
        assert x["行"] == 基["行"], 形
        assert x["知らせ"] == 基["知らせ"], 形
