"""日またぎの所定（始業 17:00・終業 9:00）の終業を次の日の時刻に読む。

終業を同じ日の 9:00 と読むと、終業後の打刻を 申請した残業だけ にした型で労働の区間が全部落ち、
夜勤の日が「勤務の日に労働の区間も時刻の無い労働時間も無い」で仮になっていた。
"""
from 作る_集計 import 区, 数える, 既定の決まり, 日, 月, 値

夜 = {"2026-11-05": (日("2026-11-05"), [区("2026-11-05", 1, "17:00", "33:00"), 区("2026-11-05", 2, "24:00", "26:00", "休憩")])}


def test_日またぎの所定の終業は次の日():
    決 = 既定の決まり(**{"時間.日の所定": "14", "時間.所定の始業": "17:00", "時間.所定の終業": "9:00",
                      "時間.制度": "1 か月変形", "時間.終業後の打刻": "申請した残業だけ"})
    A, B = 月(上書き=夜)
    A = [a for a in A if a["日付"] == "2026-11-05" or a["日の種類"] != "勤務"] + [
        dict(a, 日の種類="休日") for a in A if a["日付"] != "2026-11-05" and a["日の種類"] == "勤務"]
    B = [b for b in B if b["日付"] == "2026-11-05"]
    x = 数える(A, B, 決)
    assert 値(x, "総労働") == [14 * 60]
    assert not any("労働の区間も" in q["何が無いか"] for q in x["問い"])


def test_始業と終業が同じ時刻は24時間の所定():
    """始業 == 終業（9:00〜9:00）は 0 時間でなく次の日の同じ時刻まで（24 時間の勤務）と読む。"""
    当直 = {"2026-11-05": (日("2026-11-05"), [区("2026-11-05", 1, "9:00", "33:00"), 区("2026-11-05", 2, "12:00", "16:00", "休憩")])}
    決 = 既定の決まり(**{"時間.日の所定": "20", "時間.所定の始業": "9:00", "時間.所定の終業": "9:00",
                      "時間.制度": "1 か月変形", "時間.終業後の打刻": "申請した残業だけ"})
    A, B = 月(上書き=当直)
    A = [a for a in A if a["日付"] == "2026-11-05" or a["日の種類"] != "勤務"] + [
        dict(a, 日の種類="休日") for a in A if a["日付"] != "2026-11-05" and a["日の種類"] == "勤務"]
    B = [b for b in B if b["日付"] == "2026-11-05"]
    assert 値(数える(A, B, 決), "総労働") == [20 * 60]
