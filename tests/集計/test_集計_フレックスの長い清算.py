"""作り物の回帰の見張り: フレックスの清算期間が 1 か月を超える時（労基法 32 条の 3 第 1 項第 2 号・第 2 項）。

起算日から 1 か月ごとの区切りで、実働が週平均 50 時間の線（50 時間×暦日÷7）を超えた分がその月の法定外。
清算の終わりの月は、清算期間の実働から各月の週平均の線を超えた分を除き、清算期間の総枠（週 40 時間×暦日÷7）を超えた分も法定外。
前の月の実働は 集計する(フレックスの前の月=) で受ける（前の月の返す物 `フレックスの月の実働` をそのまま渡す）。

答えは厚生労働省「フレックスタイム制のわかりやすい解説＆導入の手引き」の 4〜6 月の例（実働 220・180・140 時間・総枠 520 時間
→ 4 月 5.8 時間・6 月 14.2 時間）を分で数え直した値（線は分の切り捨て: 4 月の線 12857 分→ 343 分・6 月の清算 857 分）。
法の線は試験が引数で渡す（作り物の値。芯のコードには書かない）。"""
from datetime import date, timedelta

from 作る_集計 import 一つ, 人の鍵, 日, 区, 既定の決まり, 法の線
from 芯.集計 import 集計する

期 = {"起算日": "2026-04-01", "終わりの日": "2026-06-30", "総労働時間": "520"}


def _月(始め: date, 日数: int, 働く日: int, 時間: int):
    """平日の頭から 働く日 の日だけ 9:00 から 時間 働く（休憩 12:00〜13:00）。ほかは休日。"""
    A, B, n = [], [], 0
    for i in range(日数):
        d = 始め + timedelta(days=i)
        s = d.isoformat()
        if d.weekday() < 5 and n < 働く日:
            n += 1
            A.append(日(s))
            B += [区(s, 1, "9:00", f"{10 + 時間}:00"), 区(s, 2, "12:00", "13:00", "休憩")]
        else:
            A.append(日(s, "休日"))
    return A, B


def _前(始め, 終わり, 実働):
    return {"会社": 人の鍵["会社"], "NO": 人の鍵["NO"], "始め": 始め, "終わり": 終わり, "実働": 実働}


国の例の前 = [_前("2026-04-01", "2026-04-30", 220 * 60), _前("2026-05-01", "2026-05-31", 180 * 60)]


def _数える(A, B, 期=期, 線=法の線, **足す):
    決 = 既定の決まり(**{"時間.制度": "フレックス", "時間.フレックスの清算期間": 期, **足す.pop("決", {})})
    return 集計する(A, B, 決まり={(人の鍵["会社"], 人の鍵["NO"]): 決}, 法の線=線, **足す)


def _六月(**足す):
    return _数える(*_月(date(2026, 6, 1), 30, 20, 7), **足す)   # 20 日×7 時間＝140 時間


def _状態(x):
    return x["人"][0]["状態"]


def _仮の文(x):
    return " ".join(q["何が無いか"] for q in x["問い"])


def test_国の例_途中の月は週平均の線を超えた分だけ():
    x = _数える(*_月(date(2026, 4, 1), 30, 22, 10))   # 22 日×10 時間＝220 時間
    assert _状態(x) == "確認済"
    assert 一つ(x, "法定外残業") == 13200 - 50 * 60 * 30 // 7 == 343
    assert 一つ(x, "法定内残業") == 0 and 一つ(x, "遅刻早退") == 0   # 総枠と不足は終わりの月に数える
    assert x["フレックスの月の実働"] == [{"支給月": 人の鍵["支給月"], **_前("2026-04-01", "2026-04-30", 13200)}]


def test_国の例_清算の終わりの月に総枠を超えた分を出す():
    x = _六月(フレックスの前の月=国の例の前)
    assert _状態(x) == "確認済"
    # 全実 32400 − 4 月の週平均の超え 343 − 総枠 40×91÷7＝31200
    assert 一つ(x, "法定外残業") == 857
    assert 一つ(x, "法定内残業") == 0 and 一つ(x, "遅刻早退") == 0


def test_清算期間の不足は終わりの月の遅刻早退():
    x = _六月(フレックスの前の月=[_前("2026-04-01", "2026-04-30", 9600), _前("2026-05-01", "2026-05-31", "160:00")])
    assert _状態(x) == "確認済"
    assert 一つ(x, "法定外残業") == 0
    assert 一つ(x, "遅刻早退") == 31200 - (9600 + 9600 + 8400)


def test_所定の総労働時間から総枠までは法定内():
    x = _六月(フレックスの前の月=国の例の前, 期={**期, "総労働時間": "500"})
    assert 一つ(x, "法定外残業") == 857
    assert 一つ(x, "法定内残業") == 31200 - 30000


def test_前の月の実働が無い終わりの月は仮():
    x = _六月()
    assert _状態(x) == "仮" and "前の月の実働が揃っていない" in _仮の文(x)
    x = _六月(フレックスの前の月=国の例の前[:1])
    assert _状態(x) == "仮"
    x = _六月(フレックスの前の月=[*国の例の前, _前("2026-03-01", "2026-03-31", 9600)])   # 清算期間の外の月
    assert _状態(x) == "仮"


def test_3か月を超える清算期間は仮():
    x = _六月(フレックスの前の月=国の例の前, 期={**期, "終わりの日": "2026-07-31"})
    assert _状態(x) == "仮" and "法の線の外" in _仮の文(x)


def test_週平均の線が無いと仮():
    線 = {k: v for k, v in 法の線.items() if k != "時間.フレックスの週平均の線"}
    x = _六月(フレックスの前の月=国の例の前, 線=線)
    assert _状態(x) == "仮"


def test_清算期間の途中の入社は仮():
    x = _六月(フレックスの前の月=国の例の前, 決={"人.入社日": "2026-05-10"})
    assert _状態(x) == "仮" and "32 条の 3 の 2" in _仮の文(x)


def test_区切りと給与の期間が揃わないと仮():
    x = _六月(期={**期, "起算日": "2026-04-15", "終わりの日": "2026-07-14"})
    assert _状態(x) == "仮" and "揃っていない" in _仮の文(x)


def test_1か月の清算期間は今のまま():
    x = _六月(期={"起算日": "2026-06-01", "終わりの日": "2026-06-30", "総労働時間": "160"})
    assert _状態(x) == "確認済"
    assert 一つ(x, "法定外残業") == 0 and 一つ(x, "遅刻早退") == 9600 - 8400
    assert x["フレックスの月の実働"] == []
