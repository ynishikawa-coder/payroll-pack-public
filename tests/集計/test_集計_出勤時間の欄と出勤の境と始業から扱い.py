根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "集計"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from 芯 import 設定  # noqa: E402
import 作る_集計 as 集  # noqa: E402

D = "2026-11-04"


def _一日(区間たち, 印="", **決まり):
    """D の 1 日だけの月（作り物）→ 結果。"""
    A = [集.日(D, 印=印)]
    B = [集.区(D, i + 1, *x) for i, x in enumerate(区間たち)]
    return 集.集計する(A, B, 決まり={("作り物の会社", "1"): 決まり}, 法の線=集.法の線)


def _ほかの仮が無い(x):
    """1 日だけの月なので期間の頭の週の仮は出る。それより外の仮（この試験の決まりから出る物）が無い。"""
    return [q["何が無いか"] for q in x["問い"] if "期間の頭の週" not in q["何が無いか"]] == []


def _行(x, 項目):
    (r,) = [r for r in x["行"] if r["項目"] == 項目]
    return r


# ---- 1 出勤時間の欄（みどり工房・型 朝8時: 始業 8:00・終業 17:00・日の所定 8:00） ----

朝8時 = {"時間.日の所定": "8", "時間.所定の始業": "8:00", "時間.所定の終業": "17:00"}
早く来た日 = [("7:40", "17:30"), ("12:00", "13:00", "休憩")]


def test_既定と打刻のままは前と同じ数():
    前 = _一日(早く来た日, **朝8時)
    assert _行(前, "出勤から退勤まで")["値"] == 590                      # 7:40〜17:30＝9:50
    for v in ("打刻のまま",):
        x = _一日(早く来た日, **朝8時, **{"時間.出勤時間の欄": v})
        assert x["行"] == 前["行"]


def test_所定の始業からは始業前の打刻を始業から数える():
    x = _一日(早く来た日, **朝8時, **{"時間.出勤時間の欄": "所定の始業から"})
    r = _行(x, "出勤から退勤まで")
    assert (r["値"], r["状態"]) == (570, "確定")                          # 8:00〜17:30＝9:30（休憩は含む）
    assert _行(x, "総労働")["値"] == _行(_一日(早く来た日, **朝8時), "総労働")["値"]   # 労働の数えは変えない


def test_所定の始業からは始業前の打刻が打刻のままの会社でも始業から():
    x = _一日(早く来た日, **朝8時, **{"時間.出勤時間の欄": "所定の始業から", "時間.始業前の打刻": "打刻のまま"})
    assert _行(x, "出勤から退勤まで")["値"] == 570


def test_定時扱いの日は始業から終業まで():
    区 = [("8:00", "15:00")]
    assert _行(_一日(区, 印="定時扱い", **朝8時), "出勤から退勤まで")["値"] == 420            # 打刻のまま＝7:00
    x = _一日(区, 印="定時扱い", **朝8時, **{"時間.出勤時間の欄": "所定の始業から"})
    assert _行(x, "出勤から退勤まで")["値"] == 540                                         # 拘束＝9:00

    # 時刻の無い定時扱いの日（問いの答え「所定どおり出勤した（定時扱い）」）: 芯がマスタの所定の始業〜終業を引き、
    # その間の所定でない分を休憩とする（法の長さの休憩で置かない＝仮を足さない）。始業・終業の無い型は日の所定で数える
    無 = _一日([], 印="定時扱い", **朝8時)
    assert (_行(無, "総労働")["値"], _行(無, "総労働")["状態"]) == (480, "確定")
    assert _行(_一日([], 印="定時扱い", **朝8時, **{"時間.出勤時間の欄": "所定の始業から"}), "出勤から退勤まで")["値"] == 540
    assert _ほかの仮が無い(無)
    型だけ = _一日([], 印="定時扱い", **{"時間.日の所定": "8"})
    assert (_行(型だけ, "総労働")["値"], _行(型だけ, "総労働")["状態"]) == (480, "確定")


def test_終業前の退勤のみなしを当てる():
    x = _一日([("8:00", "16:30")], **朝8時, **{"時間.出勤時間の欄": "所定の始業から", "時間.終業前の退勤": "所定の終業まで"})
    assert _行(x, "出勤から退勤まで")["値"] == 540
    y = _一日([("8:00", "16:30")], **朝8時, **{"時間.出勤時間の欄": "所定の始業から"})
    assert _行(y, "出勤から退勤まで")["値"] == 510


def test_所定内は実働を日の所定で頭打ち():
    x = _一日(早く来た日, **朝8時, **{"時間.出勤時間の欄": "所定内"})
    assert _行(x, "出勤から退勤まで")["値"] == 480                      # 実働 8:30 → 8:00
    y = _一日([("8:00", "15:00"), ("12:00", "13:00", "休憩")], **朝8時, **{"時間.出勤時間の欄": "所定内"})
    assert _行(y, "出勤から退勤まで")["値"] == 360                      # 実働 6:00 はそのまま


@pytest.mark.parametrize("賃金の形, 値", [("時給", 480), ("月給", 570), ("日給月給", 570)])
def test_賃金の形で分ける値(賃金の形, 値):
    x = _一日(早く来た日, **朝8時, **{"時間.出勤時間の欄": "所定の始業から（時給の人は所定内）", "支払.賃金の形": 賃金の形})
    r = _行(x, "出勤から退勤まで")
    assert (r["値"], r["状態"]) == (値, "確定")


def test_賃金の形で分ける値なのに賃金の形が空なら黙って決めず仮():
    x = _一日(早く来た日, **朝8時, **{"時間.出勤時間の欄": "所定の始業から（時給の人は所定内）"})
    assert _行(x, "出勤から退勤まで")["状態"] == "仮"
    assert _行(x, "総労働")["状態"] == "確定"                             # 効くのは出勤時間の欄だけ


def test_選べる値の外の字は照らして仮():
    x = _一日(早く来た日, **朝8時, **{"時間.出勤時間の欄": "拘束"})
    assert not _ほかの仮が無い(x)


# ---- 2 休憩の表の退勤の境に休憩の始まり（はるかぜ企画・型 9 時） ----

九時 = {"時間.日の所定": "7:15", "時間.所定の始業": "9:00", "時間.所定の終業": "17:30"}
始まりの表 = "退勤10:45超15分（10:30〜）、退勤12:45超45分（12:00〜）、退勤15:15超15分（15:00〜）"


def _休憩(出勤, 表=始まりの表, 退勤="17:30", **他):
    x = _一日([(出勤, 退勤)], **九時, **{"時間.休憩の表": 表}, **他)
    (y,) = [r for r in x["日の要約"] if r["日付"] == D]
    return y["休憩"], x


@pytest.mark.parametrize("出勤, 休憩", [
    ("9:00", 75), ("12:30", 15),                 # 遅れて出勤した日は出勤前の朝・昼を引かない
    ("11:59", 60), ("12:00", 15),                # 始まりちょうどの出勤は引かない（以後）
    ("15:00", 0),
])
def test_出勤が休憩の始まり以後なら引かない(出勤, 休憩):
    v, x = _休憩(出勤)
    assert v == 休憩, (出勤, v)
    assert _ほかの仮が無い(x)


def test_始まりの無い境は前のまま():
    v, _ = _休憩("12:30", 表="退勤10:45超15分、退勤12:45超45分、退勤15:15超15分")
    assert v == 75


def test_区分と始まりは一緒に書ける():
    表 = 設定.休憩の表を読む("退勤12:45超45分（パート）（12:00〜）")
    (b,) = 表["境"]
    assert (b.境, b.長さ, b.区分, b.始まり) == (765, 45, "パート", 720)


@pytest.mark.parametrize("字", ["退勤12:45超45分（13:00〜）", "退勤12:45超45分（12:00〜）（11:00〜）", "退勤12:45超45分（12時から）"])
def test_読めない始まりは表の外(字):
    with pytest.raises(ValueError):
        設定.休憩の表を読む(字)


# ---- 3 始業から扱い（やまびこ運送・始業 7:00・終業 16:00・休憩 12:00〜13:00） ----

七時 = {"時間.日の所定": "8", "時間.所定の始業": "7:00", "時間.所定の終業": "16:00"}


def _遅れ(退勤, 印=""):
    return _一日([("8:28", 退勤), ("12:00", "13:00", "休憩")], 印=印, **七時)


def test_印が無い日は今までどおり遅刻():
    x = _遅れ("16:00")
    assert _行(x, "遅刻早退")["値"] == 88 and _行(x, "総労働")["値"] == 392


def test_始業から扱いの日は遅刻を数えず始業から働いたとみなす():
    x = _遅れ("16:00", 印="始業から扱い")
    assert _行(x, "遅刻早退")["値"] == 0 and _行(x, "総労働")["値"] == 480
    assert _ほかの仮が無い(x)


def test_始業から扱いの日の残業はその日の拘束で数える():
    assert _行(_遅れ("18:30"), "法定外残業")["値"] == 62                 # 8:28〜18:30−1:00＝9:02
    x = _遅れ("18:30", 印="始業から扱い")
    assert _行(x, "総労働")["値"] == 630 and _行(x, "法定外残業")["値"] == 150   # 7:00〜18:30−1:00＝10:30


def test_始業より前に来た日は始業から扱いでも変えない():
    区 = [("6:50", "16:00"), ("12:00", "13:00", "休憩")]
    assert _一日(区, 印="始業から扱い", **七時)["行"] == _一日(区, **七時)["行"]


def test_始業から扱いは出勤時間の欄と休憩の境にも効く():
    x = _一日([("8:28", "16:00")], 印="始業から扱い", **七時,
              **{"時間.出勤時間の欄": "所定の始業から", "時間.休憩の表": "退勤8:15超15分（8:00〜）"})
    assert _行(x, "出勤から退勤まで")["値"] == 540                      # 7:00〜16:00
    (y,) = [r for r in x["日の要約"] if r["日付"] == D]
    assert y["休憩"] == 15                                                # みなした出勤 7:00 は 8:00 より前＝引く


# ---- 台帳: 始業から扱い は問いの答えでだけ置く ----

_spec = importlib.util.spec_from_file_location("月次_台帳の形_出勤の扱い", 根 / "月次" / "台帳の形.py")
形 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(形)


def _台帳の日(**他):
    return {"会社": "作り物の会社", "支給月": "2027-02", "NO": "1", "勤怠の表記": "作り物", "日付": "2027-02-01", "日の種類": "勤務",
            "働いた場所": "事業所", "読み取りの確かめ": "確認済", "原本の名前": "作り物.xlsx", "原本の種別": "Excel出勤簿", **他}


def test_始業から扱いは問いの訳と一緒なら確定した勤怠を通る():
    表 = 形.勤怠の表たち(確定=True, 勤怠=[_台帳の日(印="始業から扱い", 直した訳="問い:Q202702-07")])
    A, _ = 形.確定した勤怠を読む(表["確定した勤怠"])
    assert A[0]["印"] == "始業から扱い"


@pytest.mark.parametrize("訳", ["", "決まり:作業のルール"])
def test_始業から扱いに問いの訳が無ければ止める(訳):
    with pytest.raises(形.台帳の形の誤り, match="始業から扱い"):
        形.勤怠の表たち(確定=True, 勤怠=[_台帳の日(印="遅刻、始業から扱い", 直した訳=訳)])
    表 = 形.勤怠の表たち(確定=True, 勤怠=[_台帳の日(印="遅刻")])
    h = 表["確定した勤怠"][0]
    行 = [("遅刻、始業から扱い" if c == "印" else 訳 if c == "直した訳" else v) for c, v in zip(h, 表["確定した勤怠"][1])]
    with pytest.raises(形.台帳の形の誤り, match="始業から扱い"):
        形.確定した勤怠を読む([h, 行])


def test_始業から扱いは読んだままの勤怠に置けない():
    with pytest.raises(形.台帳の形の誤り, match="確定した勤怠にだけ"):
        形.勤怠の表たち(確定=False, 勤怠=[_台帳の日(印="始業から扱い")])
