"""答え済みの決まりを表す 3 つ（作り物の会社と作り物の値だけ）。

1. `時間.出勤時間の欄`（月の語 出勤から退勤まで の数え方）: 打刻のまま（既定＝前のまま）・所定の始業から（拘束＝退勤−始業。
   始業前の打刻は始業から・定時扱いの日は始業から終業まで・終業前の退勤のみなしを当てる）・所定内（その日の所定内の時間）・
   所定の始業から（時給の人は所定内）（支払.賃金の形 で分ける。賃金の形が空なら黙って決めず仮）。作り物『みどり工房』の型 朝8時。
2. 休憩の表の退勤の境に休憩の始まり（`退勤10:45超15分（10:30〜）`）: 出勤が始まり以後の日は引かない。始まりの無い境は前のまま。
   作り物『はるかぜ企画』の型 9 時。
3. 表 A の印 `始業から扱い`（会社が認めたその日だけの遅れ）: その日の出勤を所定の始業とみなし、遅刻を数えず労働と残業を始業から数える。
   台帳では確定した勤怠に 直した訳 `問い:<番号>` と一緒の時だけ通す。作り物『やまびこ運送』の始業 7:00。
"""
import importlib.util
