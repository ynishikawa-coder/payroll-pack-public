"""曜日の時間: その曜日の日の総労働（土曜に働いた時間に払う手当などの数量）。7 つの和は総労働・日またぎは始まりの日の曜日。"""
from 作る_集計 import 区, 数える, 既定の決まり, 日, 月, 一つ, 法の線, 人の鍵

from 芯.集計 import 集計する

曜 = "月火水木金土日"
土曜の出勤 = {"2026-11-07": (日("2026-11-07", "休日勤務"), [区("2026-11-07", 1, "9:00", "15:00")])}
# 金曜の夜勤（22:00〜翌 6:00・休憩 1 時間）は土曜へかかっても金曜の時間
金曜の夜勤 = {"2026-11-13": (日("2026-11-13"), [区("2026-11-13", 1, "22:00", "30:00"),
                                             区("2026-11-13", 2, "25:00", "26:00", "休憩")])}


def test_曜日ごとの時間と和():
    x = 数える(*月(上書き=土曜の出勤))
    assert 一つ(x, "曜日の時間:土") == 6 * 60
    assert 一つ(x, "曜日の時間:日") == 0
    assert 一つ(x, "曜日の時間:月") == 5 * 8 * 60          # 2026-11 の月曜は 5 日
    assert sum(一つ(x, f"曜日の時間:{c}") for c in 曜) == 一つ(x, "総労働")
    r = [r for r in x["行"] if r["項目"] == "曜日の時間:土"][0]
    assert (r["状態"], r["出所"]) == ("確定", "2026-11-07")


def test_日またぎは始まりの日の曜日():
    x = 数える(*月(上書き=金曜の夜勤))
    assert 一つ(x, "曜日の時間:土") == 0
    assert 一つ(x, "曜日の時間:金") == 3 * 8 * 60 + 7 * 60   # 金曜 4 日のうち 1 日が夜勤 7 時間
    assert sum(一つ(x, f"曜日の時間:{c}") for c in 曜) == 一つ(x, "総労働")


def _口(d):
    return [{**人の鍵, "項目": k, "値": v, "原本の名前": "作り物.csv", "原本の種別": "集計済み勤怠表",
             "読み取りの確かめ": "確認済"} for k, v in d.items()]


def _通す(d):
    return 集計する(月の口=_口(d), 決まり={("作り物の会社", "1"): 既定の決まり()}, 法の線=法の線)


基 = {"所定日数": "20", "出勤日数": "20", "総労働": "9600", "所定内": "9600"}


def test_月の数字の口に曜日の時間が無い時():
    x = _通す(基)
    assert [r for r in x["行"] if r["項目"].startswith("曜日の時間:")] == []   # 分けられない＝行を出さない（使う人だけ 芯/計算 が仮）
    assert x["人"][0]["状態"] == "確認済"
    x = _通す({"所定日数": "20", "出勤日数": "0", "欠勤": "20", "総労働": "0"})
    assert {r["値"] for r in x["行"] if r["項目"].startswith("曜日の時間:")} == {0}   # 働いていない人は 0


def test_月の数字の口の曜日の時間():
    x = _通す({**基, "曜日の時間:月": "2400", "曜日の時間:火": "2400", "曜日の時間:水": "2400", "曜日の時間:木": "2400"})
    r = {r["項目"]: r for r in x["行"] if r["項目"].startswith("曜日の時間:")}
    assert (r["曜日の時間:月"]["値"], r["曜日の時間:土"]["値"]) == (2400, 0)   # 1 つでも来たら来ない曜日は 0
    assert x["人"][0]["状態"] == "確認済"
    x = _通す({**基, "曜日の時間:土": "480"})
    assert x["人"][0]["状態"] == "仮"
    assert any("曜日の時間 の和が 総労働 と合わない" in q["何が無いか"] for q in x["問い"])
