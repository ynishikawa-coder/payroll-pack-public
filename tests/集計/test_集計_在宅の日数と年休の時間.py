"""月の語 在宅の日数・年休の時間（型の版 21）を表 A から数える（作り物の値だけ）。

- 在宅の日数: 勤務の日のうち 働いた場所＝在宅 の日（半休の日は 0.5）
- 年休の時間: 全日は表 A の 休暇の時間 → 勤務の型の 有給.1日の時間（分）→ その日の所定。半休は休んだ分
"""
from 作る_集計 import 区, 一つ, 数える, 既定の決まり, 日, 月


def _平日(A):
    return [r["日付"] for r in A if r["日の種類"] == "勤務"]


def _働く(d, **列):
    return (日(d, **列), [区(d, 1, "9:00", "18:00"), 区(d, 2, "12:00", "13:00", "休憩")])


def test_在宅の日数は勤務の日で働いた場所が在宅の日():
    A, _ = 月()
    a, b, c = _平日(A)[:3]
    A, B = 月(上書き={a: _働く(a, 働いた場所="在宅"), b: _働く(b, 働いた場所="在宅"), c: _働く(c, 働いた場所="会社")})
    結果 = 数える(A, B)
    assert 一つ(結果, "在宅の日数") == 2
    assert 一つ(結果, "出勤日数") == 21
    assert 一つ(数える(*月()), "在宅の日数") == 0


def test_年休の時間は休暇の時間と有給の1日の時間と所定の順():
    A, _ = 月()
    a, b, c = _平日(A)[:3]
    休 = dict(休暇の種類="年休", 休暇の単位="全日")
    A, B = 月(上書き={a: (日(a, "休暇", 休暇の時間="360", **休), []),            # 原本の区分の時間（6:00）
                     b: (日(b, "休暇", **休), []),                               # 型の 有給.1日の時間 も無い → その日の所定 8 時間
                     c: (日(c, "休暇", **休), [])})
    結果 = 数える(A, B)
    assert 一つ(結果, "年休の時間") == 360 + 480 + 480
    決 = 既定の決まり(**{"有給.1日の時間": "420"})                                # 有給.1日の時間 は分の数（段の解決が直して渡す）
    assert 一つ(数える(A, B, 決), "年休の時間") == 360 + 420 + 420
    assert 一つ(数える(*月()), "年休の時間") == 0
