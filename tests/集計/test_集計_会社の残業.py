"""会社の決まりの残業の数え方（1 日の所定超え。みなしは 芯/計算 で引く）と法の線の並べ（作り物の値だけ）。"""
from 作る_集計 import 一つ, 値, 区, 数える, 既定の決まり, 日, 月

会社の語 = ("残業（会社の数え方）", "60 時間超（会社の数え方）")


def 下回る知らせ(結果):
    return [t for t in 結果["知らせ"] if "法の線の割増を下回る" in t]


def test_既定は月の数字を変えない():
    A, B = 月()
    既定 = 数える(A, B)
    assert not any(r["項目"] in 会社の語 for r in 既定["行"])
    法定どおり = 数える(A, B, 既定の決まり(**{"割増.残業の数え方": "法定どおり"}))
    assert 法定どおり == 既定


def test_1日の所定超えを足しみなしは引かない():
    # 所定 7 時間・実働 8 時間の平日が 21 日 → 21 時間（みなしは 芯/計算 が月給で役員でない人だけ引く）
    A, B = 月()
    決 = 既定の決まり(**{"時間.日の所定": "7", "時間.所定の終業": "17:00",
                       "割増.残業の数え方": "1日の所定超え", "割増.みなし残業の時間": "10"})
    結果 = 数える(A, B, 決)
    行 = {r["項目"]: r for r in 結果["行"]}
    assert 行["残業（会社の数え方）"]["値"] == 21 * 60
    assert "みなし残業の時間 10 は引いていない" in 行["残業（会社の数え方）"]["印"]
    assert 行["60 時間超（会社の数え方）"]["値"] == 0
    assert 行["法定外残業"]["値"] == 0          # 法の線の数え方は並べて今のまま出す
    assert 行["法定内残業"]["値"] == 21 * 60
    assert not 下回る知らせ(結果)                  # 法を下回らない月は知らせない
    assert all(r["状態"] == "確定" for r in 結果["行"])


def test_所定8で日の残業だけなら知らせない():
    # 所定 8・平日 21 日を 19:00 まで → 会社 21 時間＝法定外 21 時間（みなしがあっても下回りではない）
    上書き = {}
    for r in 月()[0]:
        if r["日の種類"] == "勤務":
            d = r["日付"]
            上書き[d] = (日(d), [区(d, 1, "9:00", "19:00"), 区(d, 2, "12:00", "13:00", "休憩")])
    A, B = 月(上書き=上書き)
    結果 = 数える(A, B, 既定の決まり(**{"割増.残業の数え方": "1日の所定超え", "割増.みなし残業の時間": "10"}))
    assert 一つ(結果, "残業（会社の数え方）") == 一つ(結果, "法定外残業") == 21 * 60
    assert not 下回る知らせ(結果)


def test_法の割増を下回る月と日を知らせる():
    # 所定 8 時間。平日 5 日は 20:00 まで（日の法定外 2 時間）・土曜 1 日に 8 時間（週 40 を超える）
    上書き = {}
    for d in ("2026-11-02", "2026-11-03", "2026-11-04", "2026-11-05", "2026-11-06"):
        上書き[d] = (日(d), [区(d, 1, "9:00", "20:00"), 区(d, 2, "12:00", "13:00", "休憩")])
    s = "2026-11-07"
    上書き[s] = (日(s, "休日勤務"), [区(s, 1, "9:00", "18:00"), 区(s, 2, "12:00", "13:00", "休憩")])
    A, B = 月(上書き=上書き)
    決 = 既定の決まり(**{"割増.残業の数え方": "1日の所定超え", "割増.みなし残業の時間": "10"})
    結果 = 数える(A, B, 決)
    assert 一つ(結果, "残業（会社の数え方）") == 10 * 60       # 日 2×5（休日勤務の日は数えない）
    assert 一つ(結果, "法定外残業") == 18 * 60                 # 日 2×5 ＋ 週 40 を超えた土曜 8
    (知らせ,) = 下回る知らせ(結果)
    assert "法定外残業 1080 分 > 会社の数え方 600 分（480 分）" in 知らせ
    assert "多い日: 2026-11-07（" in 知らせ                    # 平日は日の所定超え＝日の法定外
    # 知らせだけ（問い・仮にはしない）
    assert not 結果["問い"]
    assert all(p["状態"] == "確認済" for p in 結果["人"])


def test_60時間超はみなしを引かずに数える():
    # 平日 21 日を 9:00〜22:00（休憩 1 時間）＝日 12 時間・所定 8 → 日 4 時間×21 = 84 時間
    上書き = {}
    for r in 月()[0]:
        if r["日の種類"] == "勤務":
            d = r["日付"]
            上書き[d] = (日(d), [区(d, 1, "9:00", "22:00"), 区(d, 2, "12:00", "13:00", "休憩")])
    A, B = 月(上書き=上書き)
    決 = 既定の決まり(**{"割増.残業の数え方": "1日の所定超え", "割増.みなし残業の時間": "10"})
    結果 = 数える(A, B, 決)
    assert 一つ(結果, "残業（会社の数え方）") == 84 * 60
    assert 一つ(結果, "60 時間超（会社の数え方）") == 一つ(結果, "60 時間超") == 24 * 60
    assert not 下回る知らせ(結果)


def test_選べる値の外は仮にして法定外で置く():
    A, B = 月()
    結果 = 数える(A, B, 既定の決まり(**{"割増.残業の数え方": "週の所定超え"}))
    行 = {r["項目"]: r for r in 結果["行"] if r["項目"] in 会社の語}
    assert 行["残業（会社の数え方）"]["状態"] == "仮"
    assert 行["残業（会社の数え方）"]["値"] == 一つ(結果, "法定外残業")
    assert 一つ(結果, "所定内") == 値(数える(A, B), "所定内")[0]   # 仮は会社の語にだけ効く
    assert [r for r in 結果["行"] if r["項目"] == "所定内"][0]["状態"] == "確定"


def test_管理監督者は所定超えで数えず仮():
    A, B = 月()
    結果 = 数える(A, B, 既定の決まり(**{"時間.制度": "管理監督者", "割増.残業の数え方": "1日の所定超え"}))
