# ---- 月の総労働が月の所定を超えた分（型の版 21）----
月の数え方 = "月の総労働が月の所定を超えた分"


def _平日(A):
    return [r["日付"] for r in A if r["日の種類"] == "勤務"]


def test_月で数えると日の超えと不足を月で相殺し法の線を下回る月を知らせる():
    # 平日 21 日×8 時間。1 日は 20:00 まで（日の法定外 2 時間）・1 日は 16:00 で帰る（不足 2 時間）→ 月の総労働＝月の所定
    A, B = 月()
    長, 短 = _平日(A)[:2]
    A, B = 月(上書き={長: (日(長), [区(長, 1, "9:00", "20:00"), 区(長, 2, "12:00", "13:00", "休憩")]),
                     短: (日(短), [区(短, 1, "9:00", "16:00"), 区(短, 2, "12:00", "13:00", "休憩")])})
    結果 = 数える(A, B, 既定の決まり(**{"割増.残業の数え方": 月の数え方}))
    assert 一つ(結果, "残業（会社の数え方）") == 0
    assert 一つ(結果, "法定外残業") == 2 * 60                     # 法の線の数え方は並べて今のまま
    (知らせ,) = 下回る知らせ(結果)
    assert f"会社の残業の数え方（{月の数え方}）が法の線の割増を下回る月" in 知らせ
    assert "法定外がその日の所定超えより多い日" not in 知らせ     # 月で数える会社は日を並べない
    assert all(r["状態"] == "確定" for r in 結果["行"])
    # 1日の所定超え なら 2 時間（前のまま）
    assert 一つ(数える(A, B, 既定の決まり(**{"割増.残業の数え方": "1日の所定超え"})), "残業（会社の数え方）") == 2 * 60


def test_月の所定を決めた値と年休の時間で数える():
    # 平日 21 日のうち 1 日は年休（全日）＝働いた 160 時間。月の所定 160:00 → 160＋年休 8−160＝8 時間
    A, B = 月()
    休 = _平日(A)[0]
    A, B = 月(上書き={休: (日(休, "休暇", 休暇の種類="年休", 休暇の単位="全日"), [])})
    決 = 既定の決まり(**{"割増.残業の数え方": 月の数え方, "割増.月の残業の所定時間": "160:00"})
    結果 = 数える(A, B, 決)
    行 = {r["項目"]: r for r in 結果["行"]}
    assert 行["年休の時間"]["値"] == 8 * 60
    assert 行["残業（会社の数え方）"]["値"] == 8 * 60
    assert "年休の時間 480 分" in 行["残業（会社の数え方）"]["印"]
    assert 行["60 時間超（会社の数え方）"]["値"] == 0
    # 空＝休日でない日の所定の和（21 日×8）→ 0
    assert 一つ(数える(A, B, 既定の決まり(**{"割増.残業の数え方": 月の数え方})), "残業（会社の数え方）") == 0
    # 読めない値は仮（法定外で置く）
    仮の = 数える(A, B, 既定の決まり(**{"割増.残業の数え方": 月の数え方, "割増.月の残業の所定時間": "百六十"}))
    行 = {r["項目"]: r for r in 仮の["行"] if r["項目"] in 会社の語}
    assert 行["残業（会社の数え方）"]["状態"] == "仮"


def _もう一人(行たち, NO):
    return [{**r, "NO": NO} for r in 行たち]


def test_基準の人の所定を他の人に当てる():
    # 会社の段の項目＝基準の人も含む全員に同じ決まり（前は全員が基準を使う人になり、基準が空で全員が仮＝レビューの赤）。
    # 基準の人（NO 1）は 1 日欠勤＝（出勤 20＋年休 0）×8＝160 時間＝自分の所定 → 0。NO 2 は平日 21 日を全部 8 時間＝168 時間 → 8 時間
    from 作る_集計 import 集計する, 法の線
    A1, B1 = 月()
    欠 = _平日(A1)[0]
    A1, B1 = 月(上書き={欠: (日(欠, "欠勤"), [])})
    A2, B2 = 月()
    決 = 既定の決まり(**{"割増.残業の数え方": 月の数え方, "割増.月の残業の所定時間": "基準の人:1"})
    結果 = 集計する([*_もう一人(A2, "2"), *A1], [*_もう一人(B2, "2"), *B1],
                 決まり={("作り物の会社", "1"): 決, ("作り物の会社", "2"): 決}, 法の線=法の線)
    行 = {r["項目"]: r for r in 結果["行"] if r["NO"] == "2"}
    assert 行["残業（会社の数え方）"]["値"] == 8 * 60
    assert "基準の人 1" in 行["残業（会社の数え方）"]["印"]
    assert 行["残業（会社の数え方）"]["状態"] == "確定"
    基準 = {r["項目"]: r for r in 結果["行"] if r["NO"] == "1"}
    assert 基準["残業（会社の数え方）"]["値"] == 0 and 基準["残業（会社の数え方）"]["状態"] == "確定"
    assert all(p["状態"] == "確認済" for p in 結果["人"])
    決2 = 決
    # 基準の人が来ない月は仮
    結果 = 集計する(_もう一人(A2, "2"), _もう一人(B2, "2"), 決まり={("作り物の会社", "2"): 決2}, 法の線=法の線)
    行 = {r["項目"]: r for r in 結果["行"] if r["NO"] == "2"}
    assert 行["残業（会社の数え方）"]["状態"] == "仮"
