"""夜勤の日を除く所定内: 時給の日勤と日額の夜勤を両方する人の時給の行の数量（夜勤の日の時間を時給で二重に払わない）。

前の道具の ④の数量の語「夜勤の日を除く出勤時間」と同じ役目。夜勤の回数・所定内・残業の数え方は変えない。
"""
from 作る_集計 import 区, 数える, 既定の決まり, 日, 月, 一つ

# 平日の日勤（9:00〜18:00・休憩 1 時間）に、11/5 だけ 22:00〜翌 6:00 の夜勤（休憩 1 時間）
夜 = {"2026-11-05": (日("2026-11-05"), [区("2026-11-05", 1, "22:00", "30:00"), 区("2026-11-05", 2, "25:00", "26:00", "休憩")])}


def test_夜勤の日の所定内を除く():
    x = 数える(*月(上書き=夜))
    assert 一つ(x, "夜勤の回数") == 1
    # 平日 21 日のうち 20 日が日勤 8 時間。夜勤の日の 7 時間は除く
    assert 一つ(x, "夜勤の日を除く所定内") == 20 * 8 * 60
    assert 一つ(x, "所定内") == 20 * 8 * 60 + 7 * 60


def test_夜勤の無い人は所定内と同じ():
    x = 数える(*月())
    assert 一つ(x, "夜勤の日を除く所定内") == 一つ(x, "所定内")


def test_月の数字の口に無い時():
    from 芯.集計 import 集計する
    from 作る_集計 import 法の線, 人の鍵

    def 口(d):
        return [{**人の鍵, "項目": k, "値": v, "原本の名前": "作り物.csv", "原本の種別": "集計済み勤怠表",
                 "読み取りの確かめ": "確認済"} for k, v in d.items()]
    基 = {"所定日数": "20", "出勤日数": "20", "総労働": "9600", "所定内": "9600"}
    x = 集計する(月の口=口(基), 決まり={("作り物の会社", "1"): 既定の決まり()}, 法の線=法の線)
    r = [r for r in x["行"] if r["項目"] == "夜勤の日を除く所定内"][0]
    assert (r["値"], r["状態"]) == (9600, "確定")   # 夜勤の無い人は 所定内 のまま
    x = 集計する(月の口=口({**基, "夜勤の回数": "2"}), 決まり={("作り物の会社", "1"): 既定の決まり()}, 法の線=法の線)
    assert [r for r in x["行"] if r["項目"] == "夜勤の日を除く所定内"] == []   # 夜勤のある人は分けられない＝行を出さない
    assert x["人"][0]["状態"] == "確認済"           # その語を使わない会社の人を仮にしない（使う人だけ 芯/計算 が仮）
    x = 集計する(月の口=口({**基, "夜勤の回数": "2", "夜勤の日を除く所定内": "8000"}),
                 決まり={("作り物の会社", "1"): 既定の決まり()}, 法の線=法の線)
    r = [r for r in x["行"] if r["項目"] == "夜勤の日を除く所定内"][0]
    assert (r["値"], r["状態"]) == (8000, "確定")
