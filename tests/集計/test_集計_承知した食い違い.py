"""承知した食い違いの印（`法の線.承知`・会社の決まり §1.4）の集計の線（作り物の値だけ）。

印のある線は会社の値で数えて仮にせず、法の線で数え直した月の数字を人の状態の `法の線で数えた` と知らせに出す。
印の無い線・問いの番号の無い印は今のまま法の線で仮。
"""
from 作る_集計 import 一つ, 区, 数える, 既定の決まり, 日, 月


def 夜勤の月(日の所定="14"):
    """平日 5 日だけ 8:00〜23:00（休憩 1 時間＝実働 14 時間）。ほかは休日。"""
    上書き = {}
    for i in range(1, 31):
        s = f"2026-11-{i:02d}"
        if s in ("2026-11-02", "2026-11-04", "2026-11-06", "2026-11-10", "2026-11-12"):
            上書き[s] = (日(s), [区(s, 1, "8:00", "23:00"), 区(s, 2, "12:00", "13:00", "休憩")])
        else:
            上書き[s] = (日(s, "休日"), [])
    A, B = 月(上書き=上書き)
    決 = 既定の決まり(**{"時間.日の所定": 日の所定, "時間.所定の始業": "8:00", "時間.所定の終業": "23:00"})
    return A, B, 決


def test_通常の制度で所定が法定を超える日は印が無ければ法の線で仮():
    A, B, 決 = 夜勤の月()
    結果 = 数える(A, B, 決)
    assert 一つ(結果, "法定外残業") == 5 * 6 * 60
    assert 結果["人"][0]["状態"] == "仮"
    assert "法の線で数えた" not in 結果["人"][0]


def test_所定14時間の印があれば所定までを所定内に数え法の線の数を並べる():
    A, B, 決 = 夜勤の月()
    決["法の線.承知"] = {"時間.日の所定": "問7"}
    結果 = 数える(A, B, 決)
    assert 一つ(結果, "所定内") == 5 * 14 * 60
    # 週の線も所定の和（週 3 日 42 時間・2 日 28 時間）＝所定の中は時間外にしない
    assert 一つ(結果, "法定外残業") == 0
    assert 結果["人"][0]["状態"] == "確認済" and not 結果["問い"]
    差 = 結果["人"][0]["法の線で数えた"]["時間.日の所定"]
    assert 差["問い"] == "問7"
    assert 差["語"]["法定外残業"] == 5 * 6 * 60 and 差["語"]["所定内"] == 5 * 8 * 60
    assert any(t.startswith("作り物の会社 1: 承知した食い違い: 時間.日の所定（問7）") for t in 結果["知らせ"])


def test_問いの番号の無い印は承知に数えない():
    A, B, 決 = 夜勤の月()
    決["法の線.承知"] = {"時間.日の所定": ""}
    結果 = 数える(A, B, 決)
    assert 結果["人"][0]["状態"] == "仮" and 一つ(結果, "法定外残業") == 5 * 6 * 60


def 端数の月():
    """平日を 9:07〜18:10 の打刻（休憩 12:00〜13:00）。"""
    上書き = {}
    for r in 月()[0]:
        if r["日の種類"] == "勤務":
            d = r["日付"]
            上書き[d] = (日(d), [区(d, 1, "9:07", "18:10"), 区(d, 2, "12:00", "13:00", "休憩")])
    return 月(上書き=上書き)


def test_短くする丸めは印が無ければ長くする向きで仮():
    A, B = 端数の月()
    決 = 既定の決まり(**{"時間.打刻の丸めの単位": "15", "時間.打刻の丸めの向き": "短くする", "時間.始業前の打刻": "打刻のまま"})
    結果 = 数える(A, B, 決)
    長 = 数える(A, B, 既定の決まり(**{"時間.打刻の丸めの単位": "15", "時間.始業前の打刻": "打刻のまま"}))
    assert 一つ(結果, "総労働") == 一つ(長, "総労働")
    assert 結果["人"][0]["状態"] == "仮"


def test_短くする丸めの印があれば短くして法の線の数を並べる():
    A, B = 端数の月()
    決 = 既定の決まり(**{"時間.打刻の丸めの単位": "15", "時間.打刻の丸めの向き": "短くする", "時間.始業前の打刻": "打刻のまま",
                       "法の線.承知": [{"線": "時間.打刻の丸めの向き", "問い": "問3"}]})
    結果 = 数える(A, B, 決)
    平日 = sum(1 for r in A if r["日の種類"] == "勤務")
    # 9:07→9:15・18:10→18:00 ＝ 7 時間 45 分（長くする向きは 9:00〜18:15 ＝ 8 時間 15 分）
    assert 一つ(結果, "総労働") == 平日 * (7 * 60 + 45)
    assert 結果["人"][0]["状態"] == "確認済"
    差 = 結果["人"][0]["法の線で数えた"]["時間.打刻の丸めの向き"]["語"]
    assert 差["総労働"] == 平日 * (8 * 60 + 15) and 差["法定外残業"] == 平日 * 15


def test_印のある人だけ数え直す_印の無い人の形は今のまま():
    A, B = 月()
    結果 = 数える(A, B)
    assert "法の線で数えた" not in 結果["人"][0]
    assert not any("承知した食い違い" in t for t in 結果["知らせ"])


def test_型の印は会社の印をまるごと上書きし数え直す線もそれに合わせる():
    # 型の版 6: 勤務の型の段の印。夜勤の型の日は型の印だけ（会社の 時間.日の所定 の印は効かない）＝法の線で仮・数え直さない
    A, B, 決 = 夜勤の月()
    for r in A:
        if r["日の種類"] == "勤務":
            r["勤務の型"] = "夜勤"
    決["法の線.承知"] = {"時間.日の所定": "問7"}
    決["勤務の型"] = {"夜勤": {"時間.日の所定": "14", "法の線.承知": "時間.打刻の丸めの向き=問3"}}
    結果 = 数える(A, B, 決)
    assert 結果["人"][0]["状態"] == "仮" and 一つ(結果, "法定外残業") == 5 * 6 * 60
    assert "時間.日の所定" not in (結果["人"][0].get("法の線で数えた") or {})
    # 型の印に 時間.日の所定 を書けば、その型の日は所定まで所定内（会社の印が無くても）
    決["法の線.承知"] = {}
    決["勤務の型"]["夜勤"]["法の線.承知"] = "時間.日の所定=問8"
    結果 = 数える(A, B, 決)
    assert 結果["人"][0]["状態"] == "確認済" and 一つ(結果, "所定内") == 5 * 14 * 60
    assert 結果["人"][0]["法の線で数えた"]["時間.日の所定"]["問い"] == "問8"
