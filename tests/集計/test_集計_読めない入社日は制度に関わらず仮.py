"""注入の試験: 人.入社日 が書いてあるのに日付として読めない時、黙って「入社日なし」と読まず、どの制度でも同じ仮＋問いを 1 つ立てる。

前は 通常・変形 の枝の中だけで読み、読めなければ黙って None にしていた（フレックス・管理監督者などは読みもしない）。"""
import pytest

from 作る_集計 import 数える, 既定の決まり, 月

制度たち = ["通常", "1か月変形", "フレックス", "管理監督者"]


def _入社日の問い(x):
    return [q for q in x["問い"] if "人.入社日" in str(q)]


@pytest.mark.parametrize("制度", 制度たち)
def test_読めない入社日はどの制度でも仮を1つ立てる(制度):
    x = 数える(*月(), 既定の決まり(**{"時間.制度": 制度, "人.入社日": "2026-13-45"}))
    assert x["人"][0]["状態"] == "仮"
    assert len(_入社日の問い(x)) == 1


@pytest.mark.parametrize("制度", 制度たち)
def test_空の入社日と読める入社日は仮にしない(制度):
    for 値 in ("", "2020-04-01"):
        x = 数える(*月(), 既定の決まり(**{"時間.制度": 制度, "人.入社日": 値}))
        assert not _入社日の問い(x)
