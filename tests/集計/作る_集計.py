def 日(d, 種類="勤務", **列):
    return {**人の鍵, "日付": d, "日の種類": 種類, "原本の名前": "作り物.csv", "原本の種別": "Excel出勤簿",
            "読み取りの確かめ": "確認済", **列}


def 区(d, 番号, 始め, 終わり, 種別="労働", 出所="打刻"):
    return {**人の鍵, "日付": d, "区間の番号": 番号, "区間の種別": 種別, "始め": 始め, "終わり": 終わり, "時刻の出所": 出所}


def 月(始め=date(2026, 11, 1), 日数=30, 上書き=None):
    """平日は 9:00〜18:00（休憩 12:00〜13:00）、土日は休日の 1 か月。上書き={日: (表 A の行, [表 B の行])}。"""
    A, B = [], []
    上書き = 上書き or {}
    for i in range(日数):
        d = 始め + timedelta(days=i)
        s = d.isoformat()
        if s in 上書き:
            a, bs = 上書き[s]
            A.append(a)
            B += bs
        elif d.weekday() >= 5:
            A.append(日(s, "休日"))
        else:
            A.append(日(s))
            B += [区(s, 1, "9:00", "18:00"), 区(s, 2, "12:00", "13:00", "休憩")]
    return A, B


