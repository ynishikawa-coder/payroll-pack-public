"""法の表/法の線.json → 集計の法の線の橋と、勤怠の来ない人を黙って抜かないこと（作り物の値だけ）。"""
import json
from datetime import date

import pytest

from 作る_集計 import 人の鍵, 数える, 既定の決まり, 月, 法の線
from 芯.計算.引く口 import 欠け
from 芯.集計 import 勤怠が無い, 法の線を引く, 集計する
from 芯.集計.形 import 形の誤り
from 芯.集計.形 import 法の線 as 線の形


def test_法の表から作る線は手で渡す線と同じに読める():
    線 = 法の線を引く(date(2026, 11, 1), date(2026, 11, 30))
    assert 線の形.読む(線) == 線の形.読む(法の線)
    assert 線["出所"] and all(x.startswith("法の表/法の線") for x in 線["出所"])


def test_法の表から作る線で集計しても月の数字が変わらない():
    A, B = 月()
    手 = 集計する(A, B, 決まり={("作り物の会社", "1"): 既定の決まり()}, 法の線=法の線)
    表 = 集計する(A, B, 決まり={("作り物の会社", "1"): 既定の決まり()}, 法の線=法の線を引く("2026-11-01", "2026-11-30"))
    assert 手 == 表


def test_60時間超の線は効く始めより前に無い():
    assert "割増.60時間超の境" not in 法の線を引く("2023-03-01", "2023-03-31")
    with pytest.raises(形の誤り, match="期間を分けて"):
        法の線を引く("2023-03-20", "2023-04-19")


def test_表が無ければ止まる(tmp_path):
    with pytest.raises(欠け):
        法の線を引く("2026-11-01", 置き場=tmp_path)


def test_要る線の行が無ければ止まる(tmp_path):
    (tmp_path / "法の線.json").write_text(json.dumps({
        "表の名": "法の線", "基準": "労働した日", "引く鍵": ["線"], "欠けた時": "止める",
        "行": [{"鍵": {"線": "深夜帯"}, "効く始め": None, "効く終わり": None, "状態": "出た",
                "値": {"始め": "22:00", "終わり": "05:00"}}]}, ensure_ascii=False), encoding="utf-8")
    with pytest.raises(欠け, match="法定労働時間"):
        法の線を引く("2026-11-01", 置き場=tmp_path)


def test_勤怠の来ない人は黙って抜けず仮と知らせで返る_問いは計算が出す():
    A, B = 月()
    手 = 数える(A, B)
    x = 集計する(A, B, 決まり={("作り物の会社", "1"): 既定の決まり(), ("作り物の会社", "9"): {}}, 法の線=法の線)
    assert x["行"] == 手["行"] and x["問い"] == 手["問い"]   # 勤怠の来た人の結果は変わらない・集計は 2 問目を出さない
    assert x["人"][0] == 手["人"][0]
    無い = x["人"][1]
    assert (無い["支給月"], 無い["NO"], 無い["状態"], 無い["仮の数"], 無い["勤怠が無い"]) == (人の鍵["支給月"], "9", "仮", 1, True)
    assert any("作り物の会社 9" in t and 勤怠が無い in t for t in x["知らせ"])


def test_勤怠の来ない役員は確認済():
    A, B = 月()
    x = 集計する(A, B, 決まり={("作り物の会社", "1"): 既定の決まり(), ("作り物の会社", "8"): {"人.区分": "役員"}}, 法の線=法の線)
    役員 = x["人"][1]
    assert (役員["NO"], 役員["状態"], 役員["仮の数"], 役員["勤怠が無い"]) == ("8", "確認済", 0, True)
    assert not any("作り物の会社 8" in t and "問い" in t for t in x["知らせ"])


def test_支給月が決まらなければ知らせと問い():
    x = 集計する(決まり={("作り物の会社", "9"): {}, ("作り物の会社", "8"): {"人.区分": "役員"}}, 法の線=法の線)
    assert x["人"] == [] and sum("支給月が決まらない" in t for t in x["知らせ"]) == 2
    (q,) = x["問い"]
    assert q["人"] == [("作り物の会社", "9")] and "支給月が決まらない" in q["何が無いか"]
    y = 集計する(決まり={("作り物の会社", "9"): {}}, 法の線=法の線, 支給月="2026-11")
    assert y["人"][0]["状態"] == "仮" and y["問い"] == []
