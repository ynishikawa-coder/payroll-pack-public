"""時間.遅れた出勤の丸め（勤務の型の段・型の版 36）の集計の線（作り物の値だけ）。

始業より遅れた最初の打刻だけを、始業から数えて N 分単位で切り上げる。日ごとに労働時間を短くする丸め（24 条の全額払い）なので、
法の線.承知 に印がある時だけ丸め、印が無ければ丸めずに数えて仮にする。始業どおり・始業より前の出勤は丸めない。
"""
from 作る_集計 import 一つ, 区, 数える, 既定の決まり, 日, 月


def 遅れの月(始め="9:07"):
    """平日を <始め>〜18:10 の打刻（休憩 12:00〜13:00）。始業 9:00・終業 18:00。"""
    上書き = {}
    for r in 月()[0]:
        if r["日の種類"] == "勤務":
            d = r["日付"]
            上書き[d] = (日(d), [区(d, 1, 始め, "18:10"), 区(d, 2, "12:00", "13:00", "休憩")])
    A, B = 月(上書き=上書き)
    return A, B, sum(1 for r in A if r["日の種類"] == "勤務")


def _決(**足す):
    return 既定の決まり(**{"時間.始業前の打刻": "打刻のまま", **足す})


def test_既定の1分は丸めない():
    A, B, 平日 = 遅れの月()
    結果 = 数える(A, B, _決())
    assert 一つ(結果, "総労働") == 平日 * (8 * 60 + 3)   # 9:07〜18:10 − 休憩 1 時間
    assert 結果["人"][0]["状態"] == "確認済"


def test_印が無ければ丸めずに数えて仮():
    A, B, 平日 = 遅れの月()
    結果 = 数える(A, B, _決(**{"時間.遅れた出勤の丸め": "15"}))
    assert 一つ(結果, "総労働") == 平日 * (8 * 60 + 3)
    assert 結果["人"][0]["状態"] == "仮"


def test_印があれば遅れた出勤だけを切り上げ法の線の数を並べる():
    A, B, 平日 = 遅れの月()
    結果 = 数える(A, B, _決(**{"時間.遅れた出勤の丸め": "15", "法の線.承知": [{"線": "時間.遅れた出勤の丸め", "問い": "問5"}]}))
    # 9:07→9:15（終業側は丸めない）＝ 9:15〜18:10 − 休憩 1 時間 ＝ 7 時間 55 分
    assert 一つ(結果, "総労働") == 平日 * (7 * 60 + 55)
    assert 結果["人"][0]["状態"] == "確認済"
    差 = 結果["人"][0]["法の線で数えた"]["時間.遅れた出勤の丸め"]
    assert 差["問い"] == "問5" and 差["語"]["総労働"] == 平日 * (8 * 60 + 3)


def test_始業どおりと始業前の出勤は丸めない():
    for 始め, 分 in (("9:00", 8 * 60 + 10), ("8:50", 8 * 60 + 20)):
        A, B, 平日 = 遅れの月(始め)
        結果 = 数える(A, B, _決(**{"時間.遅れた出勤の丸め": "15", "法の線.承知": [{"線": "時間.遅れた出勤の丸め", "問い": "問5"}]}))
        assert 一つ(結果, "総労働") == 平日 * 分, 始め
        assert 結果["人"][0]["状態"] == "確認済", 始め


def test_単位の境の遅れは切り上げた先が単位の刻み():
    A, B, 平日 = 遅れの月("9:16")
    結果 = 数える(A, B, _決(**{"時間.遅れた出勤の丸め": "15", "法の線.承知": [{"線": "時間.遅れた出勤の丸め", "問い": "問5"}]}))
    assert 一つ(結果, "総労働") == 平日 * (7 * 60 + 40)   # 9:16→9:30
