def _初日だけ休む塊(前=False):
    # 起算日 11/1・塊 11/1〜28 の休日は 1・8・15・22 の 4 日だけ（ほかは全部勤務）。初日 11/1 が前の期間の夜勤の明けかで足りるかが変わる
    休む = {"2026-11-01", "2026-11-08", "2026-11-15", "2026-11-22"}
    上書き = {}
    for i in range(30):
        s = f"2026-11-{i + 1:02d}"
        if s in 休む:
            上書き[s] = (日(s, "休日"), [])
        else:
            上書き[s] = (日(s), [区(s, 1, "9:00", "18:00"), 区(s, 2, "12:00", "13:00", "休憩")])
    A, B = 月(上書き=上書き)
    他 = {}
    if 前:
        a, b = _夜勤("2026-10-31")
        他 = {"前の表A": [a], "前の表B": b}
    return A, B, 他


def test_期間の初日が前の夜勤の明けか分からない塊は仮():
    A, B, _ = _初日だけ休む塊()
    x = 数える(A, B, _決())
    assert [q for q in x["問い"] if "期間の初日が前の期間の夜勤の明けか分からず" in q["何が無いか"]], x["問い"]


def test_前の期間の日を渡せば初日が明けと分かる():
    A, B, 他 = _初日だけ休む塊(前=True)
    x = 数える(A, B, _決(), **他)
    assert not [q for q in x["問い"] if "期間の初日が前の期間" in q["何が無いか"]]
    assert [q for q in x["問い"] if "夜勤の明けの日は休日に数えない" in q["何が無いか"]], x["問い"]


def test_シフトの休日の確かめも明けを休日に数えない():
    # シフトの型の人: 塊 11/1〜28 の休日が 4 日（うち 1 日が夜勤の明け）＝明けを除くと 3 日で足りない＝勤務の日が仮
    決 = _決(**{"勤務の型": {"シフト": {"時間.暦": {"シフト": "勤務した日"}}}})
    休む = {"2026-11-07", "2026-11-14", "2026-11-21", "2026-11-25"}
    上書き = {}
    for i in range(30):
        s = f"2026-11-{i + 1:02d}"
        if s in 休む:
            上書き[s] = (日(s, "休日", 勤務の型="シフト"), [])
        elif s == "2026-11-24":
            a, b = _夜勤(s)
            上書き[s] = (dict(a, 勤務の型="シフト"), b)
        else:
            上書き[s] = (日(s, 勤務の型="シフト"), [区(s, 1, "9:00", "18:00"), 区(s, 2, "12:00", "13:00", "休憩")])
    A, B = 月(上書き=上書き)
    x = 数える(A, B, 決)
    assert [q for q in x["問い"] if "シフトの人" in q["何が無いか"]], x["問い"]


