"""4 週 4 休: 項目の辞書の書き方（`4 週 4 休（起算日つき）`）を読む・夜勤の明けの日を休日に数えない（前の日から続く労働は始まりの日の勤務）。"""
from 作る_集計 import 区, 数える, 既定の決まり, 日, 月, 値


def _夜勤(d):
    """21:00〜翌 9:00（休憩 翌 2:00〜3:00）＝翌日の 0:00〜9:00 に 8 時間かかる。"""
    return 日(d), [区(d, 1, "21:00", "33:00"), 区(d, 2, "26:00", "27:00", "休憩")]


def _決(決め方="4 週 4 休（起算日つき）", **足す):
    return 既定の決まり(**{"休日.法定休日の決め方": 決め方, "休日.4週の起算日": "2026-11-01", **足す})


def _選べる値の外(x):
    return [q for q in x["問い"] if "選べる値の外" in q["何が無いか"]]


def test_辞書の書き方の4週4休を読む():
    for 書き方 in ("4 週 4 休（起算日つき）", "4週4休", "4 週 4 休"):
        x = 数える(*月(), _決(書き方))
        assert not _選べる値の外(x), (書き方, x["問い"])
        assert x["人"][0]["状態"] == "確認済", (書き方, x["問い"])


def test_括弧に書いた起算日を読む():
    決 = 既定の決まり(**{"休日.法定休日の決め方": "4 週 4 休（起算日 2026-11-01）"})
    x = 数える(*月(), 決)
    assert not [q for q in x["問い"] if "4週の起算日" in q["何が無いか"]], x["問い"]
    assert x["人"][0]["状態"] == "確認済", x["問い"]


def test_曜日を決める_括弧の既定も読む():
    x = 数える(*月(), 既定の決まり(**{"休日.法定休日の決め方": "曜日を決める（日）"}))
    assert not _選べる値の外(x), x["問い"]


def test_明けの日へかかった労働は法定休日にしない():
    # 11/4（水）夜勤 → 11/5（木）は表 A で休日（明け）。土日の休日で 4 週 4 休は足りる。
    A, B = 月(上書き={"2026-11-04": _夜勤("2026-11-04"),
                     "2026-11-05": (日("2026-11-05", "休日"), [])})
    for 書き方 in ("4週4休", "4 週 4 休（起算日つき）"):
        x = 数える(A, B, _決(書き方))
        assert sum(値(x, "法定休日")) == 0, (書き方, x["行"])
        assert sum(値(x, "所定休日")) == 0
        assert x["人"][0]["状態"] == "確認済", (書き方, x["問い"])


def test_明けを除くと休日が足りない塊は仮():
    # 11/1〜28 の塊: 暦日の休日は 3 日（7・14・21）だけ、あとは夜勤の明け 4 日＝休日に数えると 7 日・明けを除くと 3 日。
    上書き = {"2026-11-07": (日("2026-11-07", "休日"), []), "2026-11-14": (日("2026-11-14", "休日"), []),
             "2026-11-21": (日("2026-11-21", "休日"), [])}
    for 夜, 明 in (("02", "03"), ("09", "10"), ("16", "17"), ("23", "24")):
        上書き[f"2026-11-{夜}"] = _夜勤(f"2026-11-{夜}")
        上書き[f"2026-11-{明}"] = (日(f"2026-11-{明}", "休日"), [])
    A, B = 月(上書き=上書き)
    A = [a if a["日付"] in 上書き or a["日の種類"] != "休日" else 日(a["日付"], "勤務") for a in A]
    for a in A:   # 土日も勤務にした日に区間を足す
        if a["日の種類"] == "勤務" and not any(b["日付"] == a["日付"] for b in B):
            B += [区(a["日付"], 1, "9:00", "18:00"), 区(a["日付"], 2, "12:00", "13:00", "休憩")]
    x = 数える(A, B, _決())
    assert x["人"][0]["状態"] == "仮"
    (q,) = [q for q in x["問い"] if "夜勤の明けの日は休日に数えない" in q["何が無いか"]]
    assert sorted(q["日付"]) == ["2026-11-03", "2026-11-10", "2026-11-17", "2026-11-24"]
    assert sum(値(x, "法定休日")) == 0


def test_曜日を決める会社は法定休日の0時からの労働をそのまま法定休日に数える():
    # 見張り: 法定休日（日）の 0:00〜24:00 にかかった労働は休日労働（平 6.5.31 基発 331 号）＝明けの扱いは 4 週 4 休だけ。
    A, B = 月(上書き={"2026-11-07": _夜勤("2026-11-07")})   # 土の夜勤 → 日の 0:00〜9:00
    A = [dict(a, 日の種類="休日勤務") if a["日付"] == "2026-11-07" else a for a in A]
    x = 数える(A, B, 既定の決まり())
    assert sum(値(x, "法定休日")) == 480


def test_明けの日に区分を法定と書いたら仮():
    # 番方編成の例外（昭 63.3.14 基発 150 号）は芯が持たない＝明けの日に 法定 と書いても黙って 35% にしない
    A, B = 月(上書き={"2026-11-04": _夜勤("2026-11-04"),
                     "2026-11-05": (日("2026-11-05", "休日", 休日の区分="法定"), [])})
    x = 数える(A, B, _決())
    assert x["人"][0]["状態"] == "仮"
    (q,) = [q for q in x["問い"] if "明けの日に 休日の区分＝法定" in q["何が無いか"]]
