"""汎用の項目 11 個の残り（型の版 18）: 遅刻早退の数え方と、休憩を取らずに早退した日（作り物の値だけ）。

- `欠勤.遅刻早退の数え方`＝日々の不足（月の所定の不足で頭打ち）: 勤務の日の所定（有給の時間を除く）の和−総労働 を上限にする。
- 休憩を取らずに早退した日: 取らなかった休憩は早退の時間に数えない（項目にせず 芯/集計 の決まり。日の遅刻早退は 所定−実に働いた時間）。
"""
from 作る_集計 import 区, 一つ, 数える, 既定の決まり, 日, 月

遅 = "2026-11-04"     # 10:00 出勤（60 分の遅刻）
残 = "2026-11-05"     # 19:00 退勤（60 分の残業）
半 = "2026-11-06"     # 午前半休（有給 4 時間）＋14:00〜18:00


def _月(*日たち):
    上 = {遅: (日(遅), [区(遅, 1, "10:00", "18:00"), 区(遅, 2, "12:00", "13:00", "休憩")]),
         残: (日(残), [区(残, 1, "9:00", "19:00"), 区(残, 2, "12:00", "13:00", "休憩")]),
         半: (日(半, 休暇の単位="午前半休", 休暇の種類="年休", 休暇の時間="240"), [区(半, 1, "14:00", "18:00")])}
    return 月(上書き={d: 上[d] for d in 日たち})


def test_空と日々の不足は今の数え方のまま():
    A, B = _月(遅, 残)
    今 = 数える(A, B)
    for 値 in ("", "日々の不足"):
        x = 数える(A, B, 既定の決まり(**{"欠勤.遅刻早退の数え方": 値}))
        assert x["行"] == 今["行"]                       # 空・既定の値なら行は 1 つも変わらない
    assert 一つ(今, "遅刻早退") == 60 and 一つ(今, "法定外残業") == 60


def test_月の所定の不足で頭打ちにすると残業で埋まった遅刻は数えない():
    A, B = _月(遅, 残)
    x = 数える(A, B, 既定の決まり(**{"欠勤.遅刻早退の数え方": "日々の不足（月の所定の不足で頭打ち）"}))
    assert 一つ(x, "遅刻早退") == 0                       # 前 60 分 → 後 0 分（所定の和−総労働＝0）
    assert 一つ(x, "法定外残業") == 60                    # 残業の時間は変えない
    (r,) = [r for r in x["行"] if r["項目"] == "遅刻早退"]
    assert "頭打ち" in r["印"] and r["状態"] == "確定"


def test_頭打ちは有給の時間を不足に数えない():
    # 有給 4 時間を所定に残すと 所定の和−総労働＝240 分で遅刻 60 分がそのまま残る。有給の時間を除く＝0 分
    A, B = _月(遅, 残, 半)
    x = 数える(A, B, 既定の決まり(**{"欠勤.遅刻早退の数え方": "日々の不足（月の所定の不足で頭打ち）"}))
    assert 一つ(x, "遅刻早退") == 0
    assert 一つ(数える(A, B), "遅刻早退") == 60


def test_足りない月は不足のまま():
    A, B = _月(遅)
    x = 数える(A, B, 既定の決まり(**{"欠勤.遅刻早退の数え方": "日々の不足（月の所定の不足で頭打ち）"}))
    assert 一つ(x, "遅刻早退") == 60


def test_月の所定時間で頭打ちは集計では日々の不足のまま渡し仮にしない():
    # 型の版 24: 頭打ちは 芯/計算 が月の所定時間−総労働で 1 回だけ取る（集計と計算の 2 段にしない）
    A, B = _月(遅, 残)
    x = 数える(A, B, 既定の決まり(**{"欠勤.遅刻早退の数え方": "日々の不足（月の所定時間−総労働で頭打ち）"}))
    (r,) = [r for r in x["行"] if r["項目"] == "遅刻早退"]
    assert r["値"] == 60 and r["状態"] == "確定"


def test_選べる値の外は日々の不足で数えて仮():
    A, B = _月(遅, 残)
    x = 数える(A, B, 既定の決まり(**{"欠勤.遅刻早退の数え方": "まとめて"}))
    (r,) = [r for r in x["行"] if r["項目"] == "遅刻早退"]
    assert r["値"] == 60 and r["状態"] == "仮"


# ---- 休憩を取らずに早退した日（項目にしない・芯/集計 の決まり）----
D = "2026-11-10"


def _早退(区間たち, **列):
    A, B = 月(上書き={D: (日(D, **列), 区間たち)})
    return 一つ(数える(A, B), "遅刻早退")


def test_休憩の前に早退した日は休憩の長さを早退に数えない():
    # 9:00〜12:00 で帰った＝所定 8 時間−働いた 3 時間＝5 時間（終業 18:00 までの 6 時間から取らなかった休憩 1 時間を引いた長さ）
    assert _早退([区(D, 1, "9:00", "12:00")]) == 300


def test_休憩を取らなかったと書いた日は休憩を早退に数えない():
    # 9:00〜15:00 で休憩 0 分（時刻の無い休憩＝0＝取っていない）＝働いた 6 時間・早退 2 時間（休憩の 1 時間は早退に数えない）
    assert _早退([区(D, 1, "9:00", "15:00")], 時刻の無い休憩="0") == 120


# ---- 出口.実働の上限＝所定 の欄（日ごとに所定で頭打ちにした実働の和。所定内 とは別に数える）----
def _頭打ち(x):
    (v,) = [y["分"] for y in x["所定で頭打ちの実働"]]
    return v


def test_日ごとに所定で頭打ちにした実働は残業の日を所定で止め遅刻の日は働いた分():
    A, B = _月(遅, 残)
    x = 数える(A, B)
    平日 = sum(1 for a in A if a["日の種類"] == "勤務")
    assert _頭打ち(x) == 平日 * 480 - 60                  # 残業の日は 480 分で止め、遅刻の日は 420 分
    assert 一つ(x, "総労働") == 平日 * 480                # 総労働は残業 60 分を含む（計算は変えない）


def test_管理監督者でも日ごとの頭打ちは同じ_所定内は全部になる():
    A, B = _月(遅, 残)
    x = 数える(A, B, 既定の決まり(**{"時間.制度": "管理監督者"}))
    平日 = sum(1 for a in A if a["日の種類"] == "勤務")
    assert 一つ(x, "所定内") == 平日 * 480                # 制度で全部を所定内に置く＝所定内は頭打ちの代わりにならない
    assert _頭打ち(x) == 平日 * 480 - 60
