"""作り物の回帰の見張り: 1 年変形の期間の途中で退職・入社した人の清算の月（労基法 32 条の 4 の 2）。

清算（実の期間を平均して週 40 時間を超えた分）は実の期間の全部の日が要る＝`時間.変形の途中入退社`＝実の期間で清算する（既定）なら仮。
清算しない は `法の線.承知` の印があれば会社の値のまま（仮にしない・知らせ）、無ければ法の線で仮。途中でない人は今のまま。
期間の終わりの月（途中で入社した人の清算の月も）は期間の総枠の仮が全員に立つ＝重ねて問わない。"""
from 作る_集計 import 数える, 既定の決まり, 月

期 = {"起算日": "2026-04-01", "終わりの日": "2027-03-31"}


def _決(**足す):
    return 既定の決まり(**{"時間.制度": "1年変形", "時間.変形の期間": 期, "時間.週の所定": "40", **足す})


def _状態(x):
    return x["人"][0]["状態"]


def test_途中でない人は今のまま():
    assert _状態(数える(*月(), _決(**{"人.入社日": "2020-04-01"}))) == "確認済"


def test_期間の途中で退職した月は清算が要り仮():
    x = 数える(*月(日数=20), _決(**{"人.退職日": "2026-11-20"}))
    assert _状態(x) == "仮"
    assert any("途中で" in str(q) and "32 条の 4 の 2" in str(q) for q in x["問い"])


def test_清算しないは印が無ければ仮():
    x = 数える(*月(日数=20), _決(**{"人.退職日": "2026-11-20", "時間.変形の途中入退社": "清算しない"}))
    assert _状態(x) == "仮"


def test_清算しないの印があれば仮にせず知らせる():
    x = 数える(*月(日数=20), _決(**{"人.退職日": "2026-11-20", "時間.変形の途中入退社": "清算しない",
                                 "法の線.承知": {"時間.変形の途中入退社": "問9"}}))
    assert _状態(x) == "確認済"
    assert any("承知した食い違い: 時間.変形の途中入退社（問9）" in t for t in x["知らせ"])


def test_期間の終わりの月の退職は仮を1つだけ立てる():
    from datetime import date
    # 表の日が期間の終わりの日まで在る＝期間の総枠の仮に含める（途中退職の問いを重ねない）
    x = 数える(*月(始め=date(2027, 3, 1), 日数=31), _決(**{"人.退職日": "2027-03-20"}))
    assert _状態(x) == "仮" and not any("途中で" in str(q) for q in x["問い"])
    # 表の日が退職日まで＝期間の終わりの日が範囲に無い＝途中退職の仮だけ
    x = 数える(*月(始め=date(2027, 3, 1), 日数=20), _決(**{"人.退職日": "2027-03-20"}))
    assert _状態(x) == "仮" and sum("途中で" in str(q) for q in x["問い"]) == 1


def test_期間の終わりの日の退職は途中でない():
    from datetime import date
    x = 数える(*月(始め=date(2027, 3, 1), 日数=31), _決(**{"人.退職日": "2027-03-31", "時間.変形の途中入退社": "清算しない"}))
    assert not any("途中で" in str(q) for q in x["問い"])
