def test_入口がどれでも同じ月の数字():
    # 日から出した月の数字を月の数字の口へ通しても、同じ語・同じ値で出る（状態と印だけが違う）
    決 = 既定の決まり(**{"時間.休憩の表": ["12:00〜13:00"]})
    x = 数える(*月(上書き=上書き), 決)
    口 = [{**人の鍵, "項目": r["項目"], "値": str(r["値"]), "原本の名前": "作り物の月報.csv",
          "原本の種別": "集計済み勤怠表", "読み取りの確かめ": "確認済"} for r in x["行"]]
    y = 数える([], [], 決, 月の口=口)
    assert [(r["項目"], str(r["値"])) for r in y["行"]] == [(r["項目"], str(r["値"])) for r in x["行"]]
    assert y["人"][0]["状態"] == "確認済"
    assert all("日の記録が無い" in r["印"] for r in y["行"])


def 口の行(*組):
    return [{**人の鍵, "項目": k, "値": v, "原本の名前": "作り物の月報.csv", "原本の種別": "集計済み勤怠表",
             "読み取りの確かめ": "確認済"} for k, v in 組]


def test_月の数字の口の足し算が合わなければ仮():
    y = 数える([], [], 月の口=口の行(("所定日数", "20"), ("出勤日数", "20"), ("総労働", "9600"), ("所定内", "9000")))
    状態 = {r["項目"]: r["状態"] for r in y["行"]}
    assert 状態["総労働"] == 状態["所定内"] == "仮"
    assert 状態["出勤日数"] == "確定"
    assert [q["何が無いか"] for q in y["問い"]] == ["月の数字の口の総労働が 所定内＋法定内残業＋法定外残業＋法定休日 と合わない"]


def test_月の数字の口の語の外は通さず仮():
    y = 数える([], [], 月の口=口の行(("所定日数", "20"), ("出勤日数", "20"), ("総労働", "0"), ("残業代", "1")))
    assert "残業代" not in {r["項目"] for r in y["行"]}
    assert y["人"][0]["状態"] == "仮"
