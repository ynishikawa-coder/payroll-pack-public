def 見る(結果, 出勤日数):
    行 = {r["項目"]: r for r in 結果["行"] if r["項目"] != "年休を取った日"}
    assert {k: 行[k]["値"] for k in 時間の仮} == 時間の仮
    assert {k: 行[k]["値"] for k in 日数} == 日数
    assert 行["出勤日数"]["値"] == 出勤日数
    # 休憩を書いていない 2 日（11-03・11-08）はどちらも 6 時間ちょうど＝34 条で休憩の要らない長さなので 0 分と読み仮にしない
    assert {k for k, r in 行.items() if r["状態"] == "仮"} == set()
    assert sorted(r["値"] for r in 結果["行"] if r["項目"] == "年休を取った日") == ["2026-11-03", "2026-11-06"]
    assert 結果["問い"] == []
    assert 結果["人"][0]["状態"] == "確認済"


