"""C11 の穴 2: 委託だけの人（人.区分＝委託）は労基法の労働者でない＝前の期間の日を求めない（作り物の値だけ）。

週の移しは委託の式（芯/計算/委託.py の月額の残業）が受ける数なので今までどおり（社員と同じ数）。委託の併用の人も今までどおり。
"""
from datetime import date

from 作る_集計 import 区, 一つ, 数える, 既定の決まり, 日, 月

前の理由 = "期間の頭の週が前の期間にかかり、前の期間の日を受けていない（週の法定の判定）"


def _水曜から():
    """2026-11-04（水）から 30 日。頭の週（日曜起算）は前の期間にかかる。"""
    return 月(始め=date(2026, 11, 4))


def _土曜も():
    """平日 8 時間＋土曜 8 時間（週 48 時間）の 1 か月（2026-11）。"""
    上 = {}
    for d in (7, 14, 21, 28):
        s = f"2026-11-{d:02d}"
        上[s] = (日(s), [区(s, 1, "9:00", "18:00"), 区(s, 2, "12:00", "13:00", "休憩")])
    return 月(上書き=上)


def _問い(x):
    return [q["何が無いか"] for q in x["問い"]]


def test_委託だけの人は前の期間の日が無くても仮にならない():
    x = 数える(*_水曜から(), 既定の決まり(**{"人.区分": "委託"}))
    assert 前の理由 not in _問い(x)
    assert all(p["状態"] == "確認済" for p in x["人"])


def test_社員と委託の併用は今までどおり前の期間の日を求める():
    for 決 in (既定の決まり(), 既定の決まり(**{"人.区分": "委託の併用"})):
        x = 数える(*_水曜から(), 決)
        assert 前の理由 in _問い(x), 決


def test_委託だけの人も週の移しと委託の式が受ける数は今までどおり():
    社員 = 数える(*_土曜も())
    委託 = 数える(*_土曜も(), 既定の決まり(**{"人.区分": "委託"}))
    併用 = 数える(*_土曜も(), 既定の決まり(**{"人.区分": "委託の併用"}))
    assert 一つ(社員, "法定外残業") == 一つ(併用, "法定外残業") == 一つ(委託, "法定外残業") == 4 * 480
    for 項目 in ("総労働", "所定内", "法定内残業", "出勤日数", "深夜", "法定休日", "所定休日",
               "休日勤務日数（法定）", "休日勤務日数（所定）"):
        assert 一つ(委託, 項目) == 一つ(社員, 項目), 項目


def test_委託だけの人の頭の週も期間の中の日だけで移す():
    A, B = _水曜から()
    社員 = 数える(A, B)
    委託 = 数える(A, B, 既定の決まり(**{"人.区分": "委託"}))
    for 項目 in ("所定内", "法定内残業", "法定外残業", "総労働"):
        assert 一つ(委託, 項目) == 一つ(社員, 項目), 項目


def test_委託だけの人も日の所定を超えた分は今までどおり残業の語に置く():
    A, B = 月(上書き={"2026-11-04": (日("2026-11-04"), [区("2026-11-04", 1, "9:00", "20:00"),
                                                       区("2026-11-04", 2, "12:00", "13:00", "休憩")])})
    社員 = 数える(A, B)
    委託 = 数える(A, B, 既定の決まり(**{"人.区分": "委託"}))
    for 項目 in ("法定内残業", "法定外残業", "所定内"):
        assert 一つ(委託, 項目) == 一つ(社員, 項目), 項目
    assert 一つ(委託, "法定外残業") == 120
