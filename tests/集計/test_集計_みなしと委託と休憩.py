"""R11・#24 の続き: みなした日で出る週の法定外も法定外（変形でなければ 37 条の割増・仮にしない）・委託の人の所定日数・会社の休憩の長さ（作り物の値だけ）。"""
from datetime import date, timedelta

from 作る_集計 import 区, 一つ, 数える, 既定の決まり, 日, 月

def _土曜(印=None):
    """土曜を 8 時間の勤務にした 1 か月（2026-11）。印=定時扱い なら時刻の無い労働時間で所定どおりとみなした日。"""
    上 = {}
    for i in range(30):
        d = date(2026, 11, 1) + timedelta(days=i)
        if d.weekday() == 5:
            s = d.isoformat()
            if 印:
                上[s] = (日(s, 時刻の無い労働時間="480", 印=印), [])
            else:
                上[s] = (日(s), [区(s, 1, "9:00", "18:00"), 区(s, 2, "12:00", "13:00", "休憩")])
    return 月(上書き=上)


def _状態(x, 項目):
    (r,) = [r for r in x["行"] if r["項目"] == 項目]
    return r["状態"]


def _印(x, 項目):
    (r,) = [r for r in x["行"] if r["項目"] == 項目]
    return r.get("印")


def test_みなした日で出る週の法定外も法定外で仮にしない():
    """週 48 の所定を 8h×6 でみなす人（変形でない）: 週 40 を超えた 8h が法定外＝37 条の割増の数に出る・仮も問いも出ない。"""
    x = 数える(*_土曜("定時扱い"), 既定の決まり(**{"時間.週の所定": "48"}))
    assert 一つ(x, "法定外残業") == 4 * 480
    assert _状態(x, "法定外残業") == "確定" and _状態(x, "出勤日数") == "確定"
    assert x["問い"] == []
    # みなした日である印は消さない（確認ページで見える）
    assert "定時扱い" in str(_印(x, "総労働"))
    # 働いた日で出る同じ形と数が揃う
    assert 一つ(x, "法定外残業") == 一つ(数える(*_土曜(), 既定の決まり(**{"時間.週の所定": "48"})), "法定外残業")


def test_1か月変形ならみなした日も変形の週の線で数える():
    """変形の値（時間.制度＝1か月変形）がある時はその判定: 週の線＝max(週の所定 48, 40) なので週では法定外にならない。"""
    x = 数える(*_土曜("定時扱い"), 既定の決まり(**{"時間.週の所定": "48", "時間.制度": "1か月変形"}))
    普通 = 数える(*_土曜(), 既定の決まり(**{"時間.週の所定": "48", "時間.制度": "1か月変形"}))
    assert 一つ(x, "法定外残業") == 一つ(普通, "法定外残業")
    assert [q["何が無いか"] for q in x["問い"]] == [q["何が無いか"] for q in 普通["問い"]]


def test_働いた日で出る週の法定外は今までどおり確定():
    x = 数える(*_土曜(), 既定の決まり(**{"時間.週の所定": "48"}))
    assert 一つ(x, "法定外残業") == 4 * 480
    assert _状態(x, "法定外残業") == "確定" and x["問い"] == []


def test_みなした日があっても週の法定外が出なければ仮にしない():
    A, B = 月(上書き={"2026-11-04": (日("2026-11-04", 時刻の無い労働時間="480", 印="定時扱い"), [])})
    x = 数える(A, B)
    assert 一つ(x, "法定外残業") == 0 and x["問い"] == []


def test_委託の人の働いた日は所定日数に数えない():
    A, B = 月()
    社員 = 数える(A, B)
    委託 = 数える(A, B, 既定の決まり(**{"人.区分": "委託"}))
    assert 一つ(社員, "所定日数") == 21 and 一つ(委託, "所定日数") == 0
    assert 一つ(委託, "出勤日数") == 一つ(社員, "出勤日数") == 21
    assert 一つ(委託, "総労働") == 一つ(社員, "総労働")


def _休憩の無い日(決):
    A, B = 月(上書き={"2026-11-04": (日("2026-11-04"), [区("2026-11-04", 1, "9:00", "18:00")])})
    return 数える(A, B, 決)


def test_会社の休憩の長さで休憩を置き仮にしない():
    法 = _休憩の無い日(既定の決まり())
    会社 = _休憩の無い日(既定の決まり(**{"時間.休憩の出し方": "長さで", "時間.休憩の長さ": [["6:00", 45], ["8:00", 60]]}))
    assert 一つ(会社, "総労働") == 一つ(法, "総労働")
    assert 会社["問い"] == [] and _状態(会社, "総労働") == "確定"
    短い = _休憩の無い日(既定の決まり(**{"時間.休憩の長さ": [["5:59", 30]]}))   # 会社の長さが法より短い＝30 分だけ引く
    assert 一つ(短い, "総労働") == 一つ(法, "総労働") + 30
    assert 短い["問い"] == [] and any("34 条" in t or "休憩" in t for t in 短い["知らせ"])


def test_勤務の型ごとの休憩の長さを引く():
    決 = 既定の決まり(**{"勤務の型": {"短い日": {"時間.休憩の長さ": [["5:00", 15]]}}})
    A, B = 月(上書き={"2026-11-04": (日("2026-11-04", 勤務の型="短い日"), [区("2026-11-04", 1, "9:00", "18:00")])})
    法 = _休憩の無い日(既定の決まり())
    x = 数える(A, B, 決)
    assert 一つ(x, "総労働") == 一つ(法, "総労働") + 45
    assert x["問い"] == [] or all("休憩の表" not in q["何が無いか"] for q in x["問い"])


def test_休憩の長さの形が違えば法の線で置き仮():
    x = _休憩の無い日(既定の決まり(**{"時間.休憩の長さ": "6時間超45分"}))
    assert 一つ(x, "総労働") == 一つ(_休憩の無い日(既定の決まり()), "総労働")
    assert any("時間.休憩の長さ" in q["何が無いか"] for q in x["問い"])
