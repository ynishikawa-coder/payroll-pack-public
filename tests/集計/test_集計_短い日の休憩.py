"""C13 の穴 9: 休憩を実績で出す型で、休憩の欄が空の短い日（34 条で休憩の要らない長さ）は 0 分と読み仮にしない（作り物の値だけ）。

法の休憩の境は法の線（試験では 作る_集計.法の線 の `時間.休憩の長さ`）から引く。
"""
from 作る_集計 import 区, 一つ, 数える, 既定の決まり, 日, 月

S = "2026-11-04"


def _一日(行, 区間たち, 決=None):
    A, B = 月(上書き={S: (行, 区間たち)})
    return 数える(A, B, 決 or 既定の決まり())


def _状態(x, 項目):
    (r,) = [r for r in x["行"] if r["項目"] == 項目]
    return r["状態"]


def _基準():
    """その日を休みにした月（総労働の差でその日の分を見る）。"""
    return 一つ(_一日(日(S, "休日"), []), "総労働")


def test_6時間以下で休憩が空なら0分で仮にしない():
    x = _一日(日(S), [区(S, 1, "9:00", "15:00")])          # ちょうど 6 時間（法の線の段は「超える」）
    assert 一つ(x, "総労働") - _基準() == 360
    assert x["問い"] == [] and _状態(x, "総労働") == "確定"


def test_半日の有休と短い勤務の日も仮にしない():
    x = _一日(日(S, 休暇の単位="午前半休", 休暇の種類="年休", 休暇の時間="240"), [区(S, 1, "13:00", "18:00")])
    assert 一つ(x, "総労働") - _基準() == 300
    assert x["問い"] == [] and _状態(x, "総労働") == "確定"


def test_6時間を超えて休憩が空なら今までどおり仮():
    x = _一日(日(S), [区(S, 1, "9:00", "15:01")])
    assert 一つ(x, "総労働") - _基準() == 361 - 45           # 法の長さで見当
    assert any("休憩の表" in q["何が無いか"] for q in x["問い"])
    assert _状態(x, "総労働") != "確定"


def test_実績の休憩がある短い日は変わらない():
    x = _一日(日(S), [区(S, 1, "9:00", "15:00"), 区(S, 2, "12:00", "12:15", "休憩")])
    assert 一つ(x, "総労働") - _基準() == 345
    assert x["問い"] == [] and _状態(x, "総労働") == "確定"


def test_表で出す型は短い日でも表が無ければ今までどおり仮():
    """見張り: 直したのは実績で出す型だけ。表で出す型の「表が無い」は設定の穴なので仮のまま。"""
    x = _一日(日(S), [区(S, 1, "9:00", "15:00")], 既定の決まり(**{"時間.休憩の出し方": "表で"}))
    assert 一つ(x, "総労働") - _基準() == 360
    assert any("休憩の表" in q["何が無いか"] for q in x["問い"])
