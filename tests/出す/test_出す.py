def 有給の作り物(取り込み, 会社, 支給月, 前):
    """取り込みと同じ人の作り物の有給休暇管理表（給与の月は 月次.月を回す が有給の値 {} で必ず組む＝作り物の 月を回す も返す）。"""
    名 = 名と版.名を付ける("有給休暇管理表", 会社, 名と版.出す支給月(支給月, "月"),
                      **{k: [n for n in v if "有給" in n] for k, v in 前.items()})
    表 = (("NO", "氏名"), *((r[0], r[1]) for r in 取り込み.表[1:]))
    return SimpleNamespace(物="有給休暇管理表", 名=名, 表=表, 渡し方="表", csvの中身=lambda: b"", 人=tuple(r[0] for r in 表[1:]))


def 回す口(*, 仮=None):
    """作り物の 月次.月を回す の返り（出す物の名は 出す.py が Drive から読んで渡す 前の版の名 で本物の 名を付ける が付ける）。"""
    def 回す(口, 置き場, 会社, 支給月, 回):
        前 = 出す.前の版の名(口, 置き場)[0]
        名 = 名と版.名を付ける("取り込み", 会社, 名と版.出す支給月(支給月, 回), **前)
        表 = copy.deepcopy(手.表)
        x = SimpleNamespace(物="取り込み", 名=名, 表=表, 渡し方="表", csvの中身=lambda: b"", 人=tuple(r[0] for r in 表[1:]))
        o = {"取り込み": x, "支給控除一覧": [], "外した人": [], "仮の人の行": [], "待つ訳": []}
        if 回 == "月":
            o["有給休暇管理表"] = 有給の作り物(x, 会社, 支給月, 前)
        o.update(仮 or {})
        return o, []
    return 回す


def _取り込みの名(口, 置き場) -> list[str]:
    return [x["name"] for x in 口.子を並べる(置き場["2_出す物"]) if x["name"].startswith("取り込み")]


def 移せる(口):
    """作り物の Drive に 移す を足す（親を替えるだけ）。drive口 に 移す が入るまでの試験の口。"""
    def 移す(fid, 親id):
        口.物[fid]["親"] = 親id
    口.移す = 移す
    return 口


def _中身(口):
    return {k: (v["name"], v["親"]) for k, v in 口.物.items()}


def test_緑なら_2_出す物と_9_履歴と管理表へ書く():
    口, 置き場 = 置き場を作る(前の版=True)
    移せる(口)
    前の名 = [x["name"] for x in 口.子を並べる(置き場["2_出す物"])]
    code, out = 出す.出す(口, 置き場, "2099-01", "給与", 回す=回す口())
    assert code == 0, out
    assert out["出した"] is True
    新 = out["置いた"][0]["名"]
    assert 新.endswith("v2") or 新.endswith("2")
    assert _取り込みの名(口, 置き場) == [新]   # 2_出す物 には最新の版 1 つだけ
    assert [x["物"] for x in out["置いた"]] == ["取り込み", "有給休暇管理表"]   # 給与の月は有給休暇管理表も毎月出す
    assert [x["name"] for x in 口.子を並べる(置き場["9_履歴"])] == 前の名   # 前の版を 9_履歴 へ移す
    月 = 口.表を読む(置き場["管理表"], f"'{表.Driveのタブ('月の状況')}'!A1:Z")
    assert 月[1][月の見出し.index("取り込み")] == "済" and len(月) == 2   # 同じ会社・支給月の行を上書き（足さない）
    出 = 口.表を読む(置き場["管理表"], f"'{表.Driveのタブ('出した物')}'!A1:Z")
    assert 出[1][:5] == [手.会社, 手.月, "月", "取り込み", 新] and 出[1][5] == 口.リンク(口.名で引く(置き場["2_出す物"], 新)["id"])   # リンクの口が開く URL を返す
    json.dumps(out, ensure_ascii=False)


def test_3回出しても_2_出す物は最新だけ_9_履歴は重ならない():
    口, 置き場 = 置き場を作る()
    移せる(口)
    名たち = []
    for _ in range(3):
        code, out = 出す.出す(口, 置き場, "2099-01", "給与", 回す=回す口())
        assert code == 0, out
        名たち.append(out["置いた"][0]["名"])
    assert len(set(名たち)) == 3
    assert _取り込みの名(口, 置き場) == 名たち[-1:]
    assert sorted(x["name"] for x in 口.子を並べる(置き場["9_履歴"]) if x["name"].startswith("取り込み")) == sorted(名たち[:-1])
    出 = 口.表を読む(置き場["管理表"], f"'{表.Driveのタブ('出した物')}'!A1:Z")
    出 = [r for r in 出[1:] if r[3] == "取り込み"]
    assert len(出) == 1 and 出[0][4] == 名たち[-1]   # 出した物 は今の版を上書き（行を積まない）


