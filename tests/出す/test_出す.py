def test_同じ月の月次と賞与は出した物の行がぶつからない():
    """出した物の鍵は 会社・支給月・回・物。回を鍵に入れないと、同じ月の賞与の取り込みが月次の取り込みの行を上書きした。"""
    口, 置き場 = 置き場を作る()
    移せる(口)
    口.物[置き場["管理表"]]["タブ"][表.Driveのタブ("賞与の状況")] = []   # 支度: 管理表に賞与の状況のタブを足す
    口.表へ書く(置き場["管理表"], f"'{表.Driveのタブ('賞与の状況')}'!A1", [月の見出し])
    for 回 in ("給与", "賞与", "給与"):
        code, out = 出す.出す(口, 置き場, "2099-01", 回, 回す=回す口())
        assert code == 0, out
    出 = 口.表を読む(置き場["管理表"], f"'{表.Driveのタブ('出した物')}'!A1:Z")
    出 = [r for r in 出[1:] if r[3] == "取り込み"]
    assert sorted(r[2] for r in 出) == ["月", "賞与"]   # 回ごとに 1 行（月次を出し直しても賞与の行は残る）
    assert len({r[4] for r in 出}) == 2


