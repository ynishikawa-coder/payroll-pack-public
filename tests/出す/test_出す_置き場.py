def _同居の格子(持ち主: str, 格子たち: dict) -> list:
    """Drive の 1 つのタブの格子。型の「同じタブ」で 持ち主 のタブに同居する役（締めの記録）があれば、本物の台帳と同じく
    見出しは 持ち主の列＋同居する役の列（同じ名は 1 つ）で、行は 会社・支給月・NO で 1 人 1 行に合わせる。
    格子たち: {役: 格子}（役ごとの見出しの格子。無い役は行なし）。"""
    from 月次 import 年の台帳を起こす as 年
    台帳 = 型の口.名("台帳")
    役たち = [持ち主, *[t for t in 年.台帳のタブ if 型の口.タブ(台帳, t).get("同じタブ") == 持ち主]]
    頭 = list(dict.fromkeys(c for t in 役たち for c in ((格子たち.get(t) or [型の口.見出し(台帳, t)])[0])))
    if len(役たち) == 1 and 格子たち.get(持ち主):
        return [list(x) for x in 格子たち[持ち主]]
    行たち: dict = {}
    for t in 役たち:
        g = 格子たち.get(t) or [型の口.見出し(台帳, t)]
        for r in g[1:]:
            v = dict(zip(g[0], r))
            行たち.setdefault((v.get("会社"), v.get("支給月"), v.get("NO")), {}).update(v)
    return [頭, *[[v.get(c, "") for c in 頭] for v in 行たち.values()]]


def _前の版の名(kw: dict) -> dict:
    """月次へ渡った 出口 の頭の名（今ある名・履歴にある名）だけ（取り込み・支給控除一覧 は 名を付ける の外）。"""
    return {k: v for k, v in (kw.get("出口") or {}).items() if k in ("今ある名", "履歴にある名")}


def _台帳の持ち主のタブ() -> list[str]:
    """年の台帳の役のうち Drive のタブを持つ役（型の「同じタブ」で他の役のタブに同居する役は除く）。"""
    from 月次 import 年の台帳を起こす as 年
    台帳 = 型の口.名("台帳")
    return [t for t in 年.台帳のタブ if not 型の口.タブ(台帳, t).get("同じタブ")]


