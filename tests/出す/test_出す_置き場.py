def _行(頭, **値):
    return [値.get(c, "") for c in 頭]


def _表を置く(d, 本id: str, シート: str, タブ: str, 頭: list, 行たち=()) -> None:
    """型のシートとタブ（役の名）→ Drive のタブの名（型の口.タブの名）で見出しと行を置く（名を直に書かない）。"""
    名 = 型の口.タブの名(シート, タブ)
    d.物[本id]["タブ"].setdefault(名, [])   # 支度は作り物の中へ直にタブを足す（作り物の 表へ書く は無いタブで止まる）
    d.表へ書く(本id, f"'{名}'!A1", [list(頭), *[list(r) for r in 行たち]])


