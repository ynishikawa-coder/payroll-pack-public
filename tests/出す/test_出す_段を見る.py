def test_書けない時は終わりの値1(monkeypatch, capsys):
    monkeypatch.setenv(見る.drive口.根の変数名の既定, "作り物の根")
    monkeypatch.setattr(見る.drive口, "開く", lambda **kw: object())
    import drive口.置き場 as 置
    monkeypatch.setattr(置, "会社の置き場", lambda 口, 根, 会社: {"顧客ID": "作り物1", "会社": 会社})
    monkeypatch.setattr(見る, "状態を読む", lambda 口, 根, 顧客ID: "毎月")
    monkeypatch.setattr(見る, "事実を集める", lambda *a, **kw: {"会社": "作り物の会社", "支給月": "2099.01支給", "回": "月", "状態": "毎月", "行": None})
    def 書けない(*a):
        raise RuntimeError("作り物")
    monkeypatch.setattr(見る, "書く", 書けない)
    assert 見る.main(["--会社", "作り物の会社", "--支給月", "2099-01", "--回", "給与", "--書く"]) == 1
    assert "書けない" in capsys.readouterr().out
