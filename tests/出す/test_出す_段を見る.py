def 会社の置き場(口, *, 月のフォルダ=True, 履歴=True):
    根id = 口.根を作る()
    管理表 = 口.シートを作る(根id, "管理表", [表.Driveのタブ(t) for t in ("月の状況", "出した物", "段")])
    行 = {"会社": 手.会社, "組": "作り物の組", "支給月": "2099.01支給（1月分）", "外した人": "0"}
    口.表へ書く(管理表, f"'{表.Driveのタブ('月の状況')}'!A1", [月の見出し, [行.get(k, "") for k in 月の見出し]])
    口.表へ書く(管理表, f"'{表.Driveのタブ('出した物')}'!A1", [表.見出し("出した物")])
    口.表へ書く(管理表, f"'{表.Driveのタブ('段')}'!A1", [表.見出し("段")])
    p = {"管理表": 管理表, "会社": 手.会社, "組": "作り物の組", "顧客ID": "作り物1"}
    if 履歴:
        p["9_履歴"] = 口.フォルダを作る(根id, "9_履歴")
    p["3_月ごと"] = 口.フォルダを作る(根id, "3_月ごと")
    if 月のフォルダ:
        月 = 口.フォルダを作る(p["3_月ごと"], "2099.01支給（1月分）")
        口.フォルダを作る(月, "1_届いた物")
        口.フォルダを作る(月, "2_出す物")
    return p


def 回す_欠け(赤):
    呼んだ = []

    def 回す(口, 置き場, 会社, 支給月, 回):
        呼んだ.append(支給月)
        return {}, list(赤)
    return 回す, 呼んだ


def test_勤怠の来ない月も決まり_つなぎの欠けを先に見せる():
    口 = 作り物のDrive()
    p = 会社の置き場(口, 月のフォルダ=False)
    回す, 呼んだ = 回す_欠け(["給与のルール.md が読めない", "置き場: 2_出す物 が無い＝前の版の番号が分からない"])
    見た = 見る.段の口.段を見る(見る.事実を集める(口, p, "2099-01", "給与", 状態="立ち上げ", 回す=回す))
    assert 呼んだ == ["2099.01支給"]
    assert 見た["段"] == "0 初期設定"
    何 = [x["何"] for x in 見た["足りない"]]
    assert any("この月の勤怠が来ていない" in x for x in 何) and "給与のルール.md が読めない" in 何
    assert not any("前の版の番号" in x for x in 何)   # 勤怠が来ていない訳と同じ（二重に見せない）


def test_試しは何も書かず_書くは段のタブの1行だけ_2度目は上書き():
    口 = 作り物のDrive()
    p = 会社の置き場(口)
    回す, _ = 回す_欠け(["給与のルール.md が読めない"])
    前 = {k: (v["name"], v["親"]) for k, v in 口.物.items()}
    前の月 = 口.表を読む(p["管理表"], f"'{表.Driveのタブ('月の状況')}'!A1:ZZ")
    見た = 見る.段の口.段を見る(見る.事実を集める(口, p, "2099-01", "給与", 状態="毎月", 回す=回す))
    assert 見た["段"] == "0 初期設定" and 見た["支給月"] == "2099.01支給"
    見る.書く(口, p, 見た, "2099-01-10")
    見る.書く(口, p, {**見た, "次にやること": "作り物の次"}, "2099-01-11")
    assert {k: (v["name"], v["親"]) for k, v in 口.物.items()} == 前   # ファイルを作らない・移さない
    assert 口.表を読む(p["管理表"], f"'{表.Driveのタブ('月の状況')}'!A1:ZZ") == 前の月
    段の表 = 口.表を読む(p["管理表"], f"'{表.Driveのタブ('段')}'!A1:ZZ")
    assert len(段の表) == 2
    行 = dict(zip(段の表[0], 段の表[1]))
    assert (行["会社"], 行["組"], 行["支給月"], 行["回"], 行["段"], 行["次にやること"], 行["更新日"]) == (
        手.会社, "作り物の組", "2099.01支給", "月", "0 初期設定", "作り物の次", "2099-01-11")


