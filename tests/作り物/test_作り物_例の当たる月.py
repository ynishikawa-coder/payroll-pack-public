C, 前の月, 後の月 = 作.C, 作.支給月, "2027.03支給"   # 作り物の会社の月は 2027.02支給


def _例(**E1):
    見出し, *行 = 作._例()
    行 = [dict(zip(見出し, r)) for r in 行]
    行[0].update(E1)
    return 行


def _代休の例(支給月):
    return {"会社": C, "例の番号": "E3", "決まり": "休日.代休の日の控除", "種類": "日", "支給月": 支給月,
            "勤務の型": "日勤", "人の値": "支払.賃金の形=月給", "日付": "2027-02-04", "日の種類": "休暇（代休・全日）", "区間": "",
            "期待": "所定日数=1・出勤日数=0・欠勤=0", "確かめた日": "2026-11-01", "確かめた人": "作り物 確かめる人（R261101-AAAA）",
            "備考": ""}


def _タブ(後から: dict, **kw):
    """後から: {名: 値} を 後の月 から当たる会社の行として足したタブ。"""
    t = 作._タブ(**kw)
    t["会社"] = [*t["会社"], *({"会社": C, "項目": k, "今の値": v, "適用開始": 後の月} for k, v in 後から.items())]
    return t


def _確かめる(支給月, タブ, 例):
    return 月次.例の確かめ.確かめる(支給月, C, タブ, 例, 法の線=作る_集計.法の線, 段=月次.段, 繋=月次.繋,
                                **作.例の確かめの出所(C))


def test_後の月から当たる決まりの例は前の月に数えず外す():
    タブ, 例 = _タブ({"休日.代休の日の控除": "引かない"}), [*_例(), _代休の例(後の月)]
    r = _確かめる(前の月, タブ, 例)
    assert r["通った"], r["止め"]
    assert r["当たらない例"] == ["E3"] and r["数"] == 2
    # その例の月では、その月の決まりで解いて照らす
    r = _確かめる(後の月, タブ, 例)
    assert r["通った"] and r["当たらない例"] == [] and r["数"] == 3, r["止め"]


def test_前の月を回し直しても会社の全員が出る(tmp_path):
    o = 作.確定して回す(前の月, C, _タブ({"休日.代休の日の控除": "引かない"}),
                    [{"部品": "Excel出勤簿", "値": 作._出勤簿()}], 法の線=作る_集計.法の線,
                    置き場=作る_計算.置き場(tmp_path), 例=[*_例(), _代休の例(後の月)])
    assert o["例の確かめ"]["通った"] and {r.NO for r in o["関所を通った"].行たち} == set(作.人たち)


def test_もう当たらない名は覆いに数えず後の月の値の例を求める():
    # 始業前の打刻 を 後の月 から 打刻のまま に変えた。前の月の値で確かめた E1 は、後の月には 始業前の打刻 を覆わない
    # （ほかの名は同じ値＝E1 は例の月で照らして覆う）＝後の月の値の例が無いので覆いが止める
    タブ, 例 = _タブ({"時間.始業前の打刻": "打刻のまま"}), _例(支給月=前の月)
    r = _確かめる(前の月, タブ, 例)
    assert r["通った"] and r["当たらない例"] == [], r["止め"]
    r = _確かめる(後の月, タブ, 例)
    assert not r["通った"] and r["当たらない例"] == []
    assert [x["決まり"] for x in r["合わない"]] == ["時間.始業前の打刻"] and r["合わない"][0]["例の番号"] == "（覆い）"


def test_一部の名だけ後の月から当たる例は例の月で照らしほかの名を覆う():
    # 代休の例に 時間.暦 も書いた: 前の月では 代休の日の控除 は当たらないが 時間.暦 は同じ値＝例は外さず、例の月の決まりで照らす
    例 = [*_例(), {**_代休の例(後の月), "決まり": "休日.代休の日の控除・時間.暦"}]
    r = _確かめる(前の月, _タブ({"休日.代休の日の控除": "引かない"}), 例)
    assert r["通った"] and r["当たらない例"] == [] and r["数"] == 3, r["止め"]


def test_決まりの値が同じ月の例は例の月で解いて照らす():
    # 例の支給月が回す月と違っても、決まりの値が同じなら当たる＝取り違えたマスタは止まる（黙って外さない）
    r = _確かめる(前の月, 作._タブ(), _例(支給月=後の月))
    assert r["通った"] and r["当たらない例"] == [], r["止め"]
    r = _確かめる(前の月, 作._タブ(型={"日勤": {"時間.始業前の打刻": "打刻のまま"}}), _例(支給月=後の月))
    assert not r["通った"] and r["合わない"][0]["例の番号"] == "E1"


