def test_事務所の行で後の月から替わる名も回す月の例を求める():
    # 事務所の設定の行（適用開始つき）で 始業前の打刻 が後の月から替わる。前の月の値で確かめた E1 は後の月にその名を覆わない
    # ＝会社の行で替わる時と同じに、後の月の値の例が無ければ覆いが止める（段を問わない）
    事務所 = [{"項目": "時間.始業前の打刻", "今の値": "打刻のまま", "適用開始": 後の月}]
    r = _確かめる(後の月, 作._タブ(事務所=事務所), _例(支給月=前の月))
    assert not r["通った"] and r["当たらない例"] == []
    assert [(x["例の番号"], x["決まり"]) for x in r["合わない"]] == [("（覆い）", "時間.始業前の打刻")]
    # 名が 1 つだけの例は回す月に当たらず外れるが、その名の後の月の例が無いので同じに止める
    r = _確かめる(後の月, 作._タブ(事務所=事務所), _例(支給月=前の月, 決まり="時間.始業前の打刻"))
    assert not r["通った"] and r["当たらない例"] == ["E1"]
    assert ("（覆い）", "時間.始業前の打刻") in [(x["例の番号"], x["決まり"]) for x in r["合わない"]]
    # 前の月を回す時は E1 の月の値＝止めない
    assert _確かめる(前の月, 作._タブ(事務所=事務所), _例(支給月=前の月))["通った"]


# ---- 決まりの値を引く道を 段.解く の 1 本にした（例の人の 2 つの月の値を全部比べる・覆いと見分けの「今」も回す月の 解く）----
# 根: 事務所の段・変更の記録で戻した人の段を、名を含むかで拾った例の名だけで比べていたので、名を書かない例・綴りの揺れた例が
# 後の月の値を覆ったまま通り、事務所の段の値は見分けの「今」に入らず止めすぎた。

_E1の値の名 = "時間.所定の始業・時間.所定の終業・時間.日の所定・時間.暦・時間.週の起算・時間.制度"
_後後 = "2027.04支給"
_事務所の後から = [{"項目": "時間.始業前の打刻", "今の値": "打刻のまま", "適用開始": 後の月}]


def _後の月の値のE9(**kw):
    return {**_例()[0], "例の番号": "E9", "支給月": 後の月, "期待": "労働=8:40・休憩=1:00・法定外残業=0:40・遅刻早退=0:00", **kw}


def _覆い(r) -> list[str]:
    return [x["決まり"] for x in r["合わない"] if x["例の番号"] == "（覆い）"]


def test_名を書かない例も例の人の2つの月の値を全部比べる():
    # E1 は 始業前の打刻 を書かない。事務所で後の月から替わる＝E1 は後の月の値を覆わない＝後の月の値の例を求める
    例 = _例(支給月=前の月, 決まり=f"{_E1の値の名}")
    r = _確かめる(後の月, 作._タブ(事務所=_事務所の後から), 例)
    assert not r["通った"] and _覆い(r) == ["時間.始業前の打刻"], r["止め"]
    # 対照: 事務所に行が無い（前の月の値のまま）は通る・会社の行で替わるのも止まる
    assert _確かめる(後の月, 作._タブ(), 例)["通った"]
    r = _確かめる(後の月, _タブ({"時間.始業前の打刻": "打刻のまま"}), 例)
    assert not r["通った"] and "時間.始業前の打刻" in _覆い(r)


