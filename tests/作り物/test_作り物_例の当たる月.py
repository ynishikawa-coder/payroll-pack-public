def test_今までどおり止まる物と通る物():
    # 2 つの名が同時に替わる
    事務所2 = [*_事務所の後から, {"項目": "時間.終業後の打刻", "今の値": "申請した残業だけ", "適用開始": 後の月}]
    k2 = f"時間.始業前の打刻・{_E1の値の名}・時間.終業後の打刻"
    assert not _確かめる(後の月, 作._タブ(事務所=事務所2), _例(支給月=前の月, 決まり=k2))["通った"]
    E9 = _後の月の値のE9(決まり="時間.始業前の打刻・時間.所定の始業")
    assert not _確かめる(後の月, 作._タブ(事務所=事務所2), [*_例(支給月=前の月, 決まり=k2), E9])["通った"]
    # 例の支給月が回す月より後
    事務所前 = [{"項目": "時間.始業前の打刻", "今の値": "所定の始業から", "適用開始": ""}, *_事務所の後から]
    assert not _確かめる(前の月, 作._タブ(事務所=_事務所の後から), _例(支給月=後の月))["通った"]
    assert not _確かめる(前の月, 作._タブ(事務所=事務所前), _例(支給月=後の月))["通った"]
    assert _確かめる(前の月, 作._タブ(事務所=_事務所の後から), [*_例()[1:], _後の月の値のE9()])["通った"]
    assert not _確かめる(前の月, 作._タブ(事務所=事務所前), [*_例()[1:], _後の月の値のE9()])["通った"]
    # 会社の行で 所定の始業 が後の月から替わり、前の月の値の E1 だけ: 期待が所定の始業に頼らない例は 2 つの月とも通る
    for 月 in (前の月, 後の月):
        assert _確かめる(月, _タブ({"時間.所定の始業": "8:00"}), _例(支給月=前の月))["通った"], 月
