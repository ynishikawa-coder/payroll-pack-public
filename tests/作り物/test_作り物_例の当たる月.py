"""例の確かめは、例をその例の 支給月（その例が当たる月）の決まりで解き、回す月に当たらない例は数えずに外す
（docs/設計/Drive の型.md §4 の例の表・月次/README.md「例の確かめ」）。

根: 例を回す月の決まりで解いていたので、後の月から当たる決まりの例（代休の日の控除が翌月から）を前の月で回し直すと、
芯が空の決まりで仮に数えて合わず、その会社の全員が仮になった。会社・人・値は作り物（tests/初期設定 の作り物の会社 C1）。
"""
