会社, 月 = "作り物の会社", "2027-02"


def _日(NO, 日付, 種類="勤務"):
    return {"会社": 会社, "支給月": 月, "NO": NO, "勤怠の表記": f"ひょうき{NO}", "日付": 日付, "日の種類": 種類}


def _区(NO, 日付, 番号, 種別, 始め, 終わり):
    return {"会社": 会社, "支給月": 月, "NO": NO, "日付": 日付, "区間の番号": 番号, "区間の種別": 種別,
            "始め": 始め, "終わり": 終わり, "時刻の出所": "打刻"}


def _列(表, 列):
    i = 表[0].index(列)
    return [r[i] for r in 表[1:]]


def test_型の列の並び():
    h = 形.見出し("読んだままの勤怠")
