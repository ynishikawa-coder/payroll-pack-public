"""見張り: 業務委託の人の法定休日の割増の率（`委託.法定休日の率`）の意味が決まるまで、法定休日に働いた委託の人を出さない（作り物の値だけ）。

実の会社の欄は 0 で、0 が「割増なし」か「未記入」か分からない（オーナーの決定 2026-11-19＝事務所に確かめるまで出さない）。
前は芯がこの欄を読まず、社員と同じ休日の率で黙って払った（0 が割増なしなら払いすぎ）。
1. 欄が数だけ・無し・空で、法定休日の時間が 1 分でもある月 → 委託分の休日 と人が仮・問いは 1 つ（欄の名と 割増なし／未記入 を名指し）
2. 法定休日の無い月 → 欄を読まない＝今までどおり確認済（所定休日だけ働いた月も）
3. 答えを受ける口: 社員と同じ率・割増なし・欄の率どおり <率> なら止めずにその率で計算（式 月額・みなし残業）
4. 委託だけの人が 2 人居ても問いは 1 つ（同じ会社の同じ欄の字）
"""
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "計算"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from 作る_計算 import 人, 決まり, 月の数字, 置き場  # noqa: E402
from test_計算_役員と委託 import _報酬の表, _回す, _値, _状態  # noqa: E402
from 芯.計算 import 計算する  # noqa: E402

_会社 = {"委託.式": "月額", "委託.丸め": "切捨て", "委託.出張日額": "5000", "委託.みなし残業時間": "無し"}
_法定休日 = {"法定休日": "60"}   # 1 時間（1 分でもあれば止める）


def _委託(**上書き):
    return 人(**{"人.区分": "委託", "委託.月給": "300000", "委託.時給": "2000", **上書き})


def _回す委託(tmp, 欄, 上書き=None):
    決 = 決まり(**_会社, **({} if 欄 is None else {"委託.法定休日の率": 欄}))
    return _回す(tmp, 決, _委託(), 月=月の数字(上書き=上書き))


def _欄の問い(r):
    return [q for q in r["問い"] if "委託.法定休日の率" in q["何が無いか"]]


@pytest.mark.parametrize("欄", ["0", "1.35", "無し", "", None])
def test_意味の決まらない欄で法定休日に働いた委託の人は仮で問い1つ(tmp_path, 欄):
    r = _回す委託(tmp_path, 欄, _法定休日)
    assert _状態(r)["委託分の休日"] == "仮" and _状態(r)["支払合計"] == "仮"
    assert r["人"][0]["状態"] == "仮"   # 仮が残る人は出口へ出ない
    qs = _欄の問い(r)
    assert len(qs) == 1, r["問い"]
    assert "割増なし" in qs[0]["何が無いか"] and "未記入" in qs[0]["何が無いか"]
    assert "社員と同じ率" in qs[0]["答え方の例"] and "欄の率どおり" in qs[0]["答え方の例"]
    assert _値(r)["委託分の休日"] == 2700   # 見当は社員と同じ休日の率（1 時間×2,000×1.35）


@pytest.mark.parametrize("欄", ["0", "無し", None])
def test_法定休日の無い月は欄を読まず今までどおり(tmp_path, 欄):
    r = _回す委託(tmp_path, 欄)
    assert r["人"][0]["状態"] == "確認済" and _欄の問い(r) == []
    r = _回す委託(tmp_path / "b", 欄, {"所定休日": "480", "法定外残業": "1080"})   # 所定休日だけ働いた月
    assert r["人"][0]["状態"] == "確認済" and _値(r)["委託分の休日"] == 21600   # 8 時間×2,000×1.35（今までどおり）


@pytest.mark.parametrize("欄, 額", [("社員と同じ率", 2700), ("割増なし", 2000), ("欄の率どおり 1.5", 3000),
                                   ("欄の率どおり：1.25", 2500)])
def test_欄の意味が書いてあれば止めずにその率(tmp_path, 欄, 額):
    r = _回す委託(tmp_path, 欄, {**_法定休日, "所定休日": "60", "法定外残業": "660"})
    assert r["人"][0]["状態"] == "確認済" and _欄の問い(r) == []
    assert _値(r)["委託分の休日"] == 額 + 2700   # 法定 1 時間×欄の率＋所定 1 時間×社員の休日の率 1.35


def test_みなし残業の式も欄の率の上乗せ(tmp_path):
    会社 = {"委託.式": "みなし残業", "委託.丸め": "切捨て", "委託.所定時間": "170:00", "委託.みなし残業時間": "10:00"}
    人の値 = 人(**{"人.区分": "委託", "委託.報酬": "300000", "委託.定額残業": "25000", "委託.時給": "2000"})
    月 = 月の数字(上書き={"法定休日": "480", "深夜": "0"})
    止め = _回す(tmp_path / "a", 決まり(**会社, **{"委託.法定休日の率": "0"}), 人の値, 月=月)
    assert 止め["人"][0]["状態"] == "仮" and len(_欄の問い(止め)) == 1
    なし = _回す(tmp_path / "b", 決まり(**会社, **{"委託.法定休日の率": "割増なし"}), 人の値, 月=月)
    assert なし["人"][0]["状態"] == "確認済" and _値(なし)["委託分の休日"] == 0   # 上乗せ 0
    同じ = _回す(tmp_path / "c", 決まり(**会社, **{"委託.法定休日の率": "社員と同じ率"}), 人の値, 月=月)
    assert 同じ["人"][0]["状態"] == "確認済" and _値(同じ)["委託分の休日"] == 5600   # 8×2,000×0.35


def test_委託の人が2人でも問いは1つ(tmp_path):
    決 = 決まり(**_会社, **{"委託.法定休日の率": "0"})
    月 = 月の数字(上書き=_法定休日) + 月の数字(NO="0002", 上書き=_法定休日)
    鍵たち = [("C1", "0001"), ("C1", "0002")]
    r = 計算する(月, 決まり={k: 決 for k in 鍵たち}, 人={k: _委託() for k in 鍵たち},
             置き場=_報酬の表(置き場(tmp_path)), 支給月="2027-02")
    assert [x["状態"] for x in r["人"]] == ["仮", "仮"]
    assert len(_欄の問い(r)) == 1, r["問い"]
