# ---- 2 照らしの材料の欠け（入口） ----

def _読む(カード):
    import 入口_作り物 as 作
    from 入口 import PDFタイムカード
    return PDFタイムカード.読む([カード], 作.文脈())


def _理由(r, d):
    return [q["理由"] for q in r.要確認 if q["日付"] == d]


def _週(日2):
    """作り物の 1 週（11/1・11/7 は休日・11/3〜6 は 9:00〜18:00 の時間数つき）の 11/2 を 日2 にした行。"""
    行 = [["1", "", "", "", "", "", "", ""], 日2]
    行 += [[str(d), "9:00", "18:00", "", "", "60", "9:00", ""] for d in range(3, 7)]
    return 行 + [["7", "", "", "", "", "", "", ""]]


def _カード(行たち, 読み2=None):
    import 入口_作り物 as 作
    c = {**作.カード, "行": 行たち if len(行たち) > 2 else _週(行たち[0]) + 行たち[1:]}
    if 読み2 is not None:
        c["読み2"] = 読み2
    return c


def test_時間数を抜いた日は確認済にならない():
    r = _読む(_カード([["2", "9:00", "18:00", "", "", "60", "", ""]]))
    assert any("印字の時間数が無い" in x for x in _理由(r, "2026-11-02"))
    assert r.人の状態()["1"] == "仮"
    # 時間数の在る日は今までどおり照らして確認済
    r = _読む(_カード([["2", "9:00", "18:00", "", "", "60", "9:00", ""]]))
    assert _理由(r, "2026-11-02") == [] and r.人の状態()["1"] == "確定"


def test_合計の時間数が無い表は要確認():
    r = _読む(_カード([["2", "9:00", "18:00", "", "", "60", "9:00", ""], ["合計", "", "", "", "", "", "", ""]]))
    assert r.人の状態()["1"] == "仮"


def test_2つの読みが合わない日は要確認():
    行 = [["2", "9:00", "18:16", "", "", "60", "9:16", ""]]
    r = _読む(_カード(行, 読み2=_週(["2", "9:00", "18:15", "", "", "60", "9:15", ""])))
    assert _理由(r, "2026-11-02") and r.人の状態()["1"] == "仮"
    r = _読む(_カード(行, 読み2=_週(list(行[0]))))
    assert _理由(r, "2026-11-02") == [] and r.人の状態()["1"] == "確定"


# ---- 3 休憩の退勤の境 ----
D = "2026-11-04"


def _休憩(退勤, 表="12:00〜13:00、退勤18:00超30分", **足す):
    # 休憩の区間の無い日（休憩の表が効く日）。休憩の区間がある日は区間が勝つ
    A, B = 集.月(上書き={D: (集.日(D), [集.区(D, 1, "9:00", 退勤)])})
    x = 集.数える(A, B, 集.既定の決まり(**{"時間.休憩の表": 表, **足す}))
    (y,) = [r for r in x["日の要約"] if r["日付"] == D]
    return y["休憩"], x


@pytest.mark.parametrize("退勤, 休憩", [("17:59", 60), ("18:00", 60), ("18:01", 90)])
def test_退勤の境の1分前とちょうどと1分後(退勤, 休憩):
    v, x = _休憩(退勤)
    assert v == 休憩 and x["人"][0]["状態"] == "確認済"


def test_区分ごとの境はその区分の人だけ():
    assert _休憩("18:30", "12:00〜13:00、退勤18:00超30分（パート）", **{"人.区分": "パート"})[0] == 90
    assert _休憩("18:30", "12:00〜13:00、退勤18:00超30分（パート）", **{"人.区分": "社員"})[0] == 60


@pytest.mark.parametrize("古い字", ["18:00を超えたら30分", "退勤が18時を過ぎたら30分", "12:00〜13:00、18時超30分休憩"])
def test_古い書き方の境は仮(古い字):
    _, x = _休憩("18:30", 古い字)
    assert x["人"][0]["状態"] == "仮"
    assert all(r["状態"] == "仮" for r in x["行"])
    assert any(q["何が無いか"].startswith("時間.休憩の表") for q in x["問い"])


# ---- 4 回帰: 始業前の打刻 6:50 出勤・始業 7:00 ----

def _早出(値):
    A, B = 集.月(上書き={D: (集.日(D), [集.区(D, 1, "6:50", "16:00"), 集.区(D, 2, "12:00", "13:00", "休憩")])})
    x = 集.数える(A, B, 集.既定の決まり(**{"時間.所定の始業": "7:00", "時間.所定の終業": "16:00", "時間.始業前の打刻": 値}))
    (y,) = [r for r in x["日の要約"] if r["日付"] == D]
    return y["労働"], x


def test_始業前の打刻は所定の始業から数える():
    for 値 in ("所定の始業から", ""):   # 既定も 所定の始業から
        労働, x = _早出(値)
        assert 労働 == 480, 値           # 7:00〜16:00−休憩 60 分（6:50〜7:00 の 10 分を数えない）
    労働, x = _早出("打刻のまま")
    assert 労働 == 490


def test_始業前の打刻の外の字は黙って打刻のままにしない():
    労働, x = _早出("始業から数える")   # 前は外の字が黙って打刻のまま（490 分）で確定になった
    assert 労働 == 480 and x["人"][0]["状態"] == "仮"
    assert any(q["何が無いか"].startswith("時間.始業前の打刻「始業から数える」は選べる値の外") for q in x["問い"])


# ---- 5 静的: 読む名は全部表に在る・畳んだ照らしが戻らない ----
_表 = set(設定.表())
_分野 = {n.split(".")[0] for n in _表}
# 表に無くてよい 分野.名 の字: 法の線の名（法の表から引く・会社の決まりでない）と、入力・行の名・承知の印
_表の外でよい = set(法の線の読み方.読み方) | {
    "委託.雇用分の出勤時間", "委託.出張日数", "委託.日ごとの実働",   # 計算する の 入力 の語（段の解決・芯/集計 が渡す）
    "割増.法定内残業の行", "割増.時間外の基礎の行",                 # 割増を載せた支給の行の印
    "割増.基礎に入る",                                            # 承知の印（法の線.承知）
    "源泉.報酬＝対象でない",                                       # 理由の字
}


def _芯の字():
    for d in ("集計", "計算"):
        for f in sorted((根 / "芯" / d).glob("*.py")):
            for n in ast.walk(ast.parse(f.read_text(encoding="utf-8"))):
                if isinstance(n, ast.Constant) and isinstance(n.value, str):
                    yield f, n.value


def test_芯の集計と計算が読む会社の決まりの名は全部表に在る():
    外 = sorted({(f.name, s) for f, s in _芯の字()
                if re.fullmatch(r"[^\s.「」（）]+\.[^\s.「」（）:]+", s) and s.split(".")[0] in _分野
                and s not in _表 and s not in _表の外でよい})
    assert 外 == [], f"芯/設定の表.json に無い名を芯が読む（表に足すか読む名を直す）: {外}"


def test_表に無い名を集計が読むと落ちる():
    from 芯.集計.形 import 決まり
    with pytest.raises(設定.表に無い名):
        決まり({}).引く("時間.作り物の無い名")


# 「は選べる値の外」の手書きの照らしは、会社の決まりでない物（表 A・B の列・部品の行・端数の語の読み口）にだけ残る
_残ってよい照らし = ("区間の種別", "休日の区分", "日の種類", "部品の行", "端数の語")


def test_畳んだ選べる値の外の手書きの照らしが戻らない():
    戻った = []
    for d in ("集計", "計算"):
        for f in sorted((根 / "芯" / d).glob("*.py")):
            for i, 行 in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
                if "は選べる値の外" not in 行 or 行.lstrip().startswith("#"):
                    continue
                if not any(w in 行 for w in _残ってよい照らし):
                    戻った.append(f"{f.name}:{i}")
    assert 戻った == [], f"使う所ごとの照らしは芯/設定.py の 照らす 1 か所へ（表の 選べる値 に足す）: {戻った}"


# ---- 6 集計と計算の両方が読む名の問いは 1 つ ----

def test_集計が照らした名は計算が問いを重ねない(tmp_path):
    from 芯.計算 import 計算する
    名 = "時間.制度"
    assert set(設定.表()[名]["読む所"]) == {"集計", "計算"}
    決 = 計.決まり(**{名: 外の字})
    人の行 = {"支給月": "2027-02", "会社": "C1", "NO": "0001", "状態": "仮", "仮の数": 1, "設定の外れ": [名]}
    r = 計算する({"行": 計.月の数字(), "人": [人の行]}, 決まり={("C1", "0001"): 決}, 人={("C1", "0001"): 計.人()},
                置き場=計.置き場(tmp_path))
    assert not any(q["何が無いか"].startswith(f"{名}「{外の字}」") for q in r["問い"]), r["問い"]
    assert r["人"][0]["状態"] == "仮"        # 集計の状態が仮＝出口へ出ない
    # 集計が照らしていない（集計の人が無い）なら計算が問う
    r = 計.回す(tmp_path / "b", 決=決)
    assert any(q["何が無いか"].startswith(f"{名}「{外の字}」") for q in r["問い"])
