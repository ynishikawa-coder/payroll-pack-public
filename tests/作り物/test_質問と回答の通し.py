def test_止まりの理由は1回で全部集まり誰の何をすれば通るかを持つ():
    問いたち = [
        _問("Q1", "聞いている", {"はい": [_振("Q1", "E01")]}),
        _問("Q3", "答えた"), _問("Q4", "答えた"), _問("Q6", "答えた"), _問("Q7", "答えた"), _問("Q8", "答えた"),
        _問("Q9", "聞いている", {"はい": [_振("Q9", "E04")]}),
        _問("Q10", "取り下げ", {"はい": [_振("Q10", "E07")]}),
        _問("Q13", "答えた"),
    ]
    答えたち = [_答("Q3"), _答("Q4"), _答("Q6"), _答("Q7"), _答("Q8"), _答("Q9", "分からない"), _答("Q13")]
    振り分けたち = [
        _振("Q3", "E02", 済=True), _振("Q4", "E03"), _振("Q6", "会社", 反映先="反映しない"),
        _振("Q7", "E05", 効く月="2099-06"), _振("Q8", "E06", 効く月="2099-04"),
        # 1 つの答えが 2 人に効く（片方だけ済）
        _振("Q13", "E08", 済=True), _振("Q13", "E02"),
    ]
    止, 候補 = _集める(問いたち, 答えたち, 振り分けたち)
    assert _対象たち(止) == {("E01", "Q1"), ("E03", "Q4"), ("E04", "Q9"), ("E02", "Q13")}
    for s in 止:
        assert str(s["何が"]).strip() and str(s["何をすれば通るか"]).strip()
    assert len(候補) == 1 and "Q8" in str(候補[0])
    # 会社は止まらず、仮の残る 4 人だけが出ない
    assert _出す人(止) == ["E05", "E06", "E07", "E08"]

    # 会社に効く止まりが 1 つ足されても、ほかの理由も落とさず全部返る（最初の誤りで返さない）
    止2, _ = _集める(問いたち + [_問("Q5", "答えた")], 答えたち + [_答("Q5")],
                  振り分けたち + [_振("Q5", "会社", 反映先="給与のルール.md")])
    assert _対象たち(止2) == _対象たち(止) | {("会社", "Q5")}
    assert _出す人(止2) == []


# --- 表の格子から読んで止まりまで（人は表を書かない＝書く口の見出しの並びで作る） ---

def _格子(タブ, 行たち):
    頭 = 質問と回答.見出し(タブ)
    return [頭] + [[r.get(n, "") for n in 頭] for r in 行たち]


def test_格子から読んだ表でも同じに止まる():
    格子たち = {
        質問と回答.Driveのタブ("問い"): _格子("問い", [
            {"問いの鍵": "Q20", "顧客ID": C, "状態": "答えた"},
            {"問いの鍵": "Q21", "顧客ID": C, "状態": "答えた"},
            {},  # 空の行は飛ばす
            {"問いの鍵": "Q22", "顧客ID": 他, "状態": "聞いている"},
        ]),
        質問と回答.Driveのタブ("答え"): _格子("答え", [
            {"問いの鍵": "Q20", "回答": "はい"}, {"問いの鍵": "Q21", "回答": "いいえ"}]),
        質問と回答.Driveのタブ("振り分け"): _格子("振り分け", [
            {"問いの鍵": "Q20", "顧客ID": C, "対象": "E01", "反映先": "マスタ/社員", "反映済み": "済"},
            # 済 の 1 字だけが済（ほかの字はまだ）
            {"問いの鍵": "Q21", "顧客ID": C, "対象": "E02", "反映先": "マスタ/社員", "反映済み": "はい"},
        ]),
    }
    t = 質問と回答.読む(格子たち)
    止, 候補 = _止まりと候補(月次.止まりを集める(t, C, 月, list(出し済み)))
    assert _対象たち(止) == {("E02", "Q21")}
    assert 候補 == []
    assert _出す人(止) == [e for e in 社員たち if e != "E02"]


