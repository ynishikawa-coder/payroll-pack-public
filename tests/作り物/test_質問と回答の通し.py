def _出す人(止まりたち):
    """止まり → 出口へ出してよい人。月を回す と同じ本物の道を通す（写しで決めない）:
    `月次._止まりを仮へ` で仮の行と待つ訳 → `繋.給与の関所へ`・`出口.関所.通す` で仮の人を外す → 出口/出す.py の `除く人` で除く人。
    計算の行は全員を確定で置く（仮は止まりからだけ来る）。"""
    会社名 = "作り物の会社"
    問いの仮, 待つ訳 = 月次._止まりを仮へ(止まりたち, 会社名, 社員たち)
    計 = {"行": [{"支給月": 月, "会社": 会社名, "NO": e, "項目": "総支給額", "値": "1000", "状態": "確定"} for e in 社員たち],
         "人の状態": {(月, 会社名, e): 月次.関所.確認済 for e in 社員たち}}
    z = 月次.繋.給与の関所へ(計, 問いの仮)
    通 = 月次.関所.通す(z["行"], z["人の状態"])
    除いた, 赤 = _出す.除く人({"待つ訳": 待つ訳, "外した人": [a.行() for a in 通.外した人たち]})
    assert 赤 == []
    除 = {a["NO"] for a in 除いた}
    assert {a.NO for a in 通.外した人たち} == 除   # 関所で外した人と出口が除く人が同じ（関所の行は外した人だけ残らない）
    assert all(r.NO not in 除 for r in 通.行たち)
    return [e for e in 社員たち if e not in 除]


