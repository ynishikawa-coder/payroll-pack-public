def 届かない見本(見本: tuple, r: dict) -> list[str]:
    """見本 (名, 字, 段, タブ) が期待の所へ届かない時の訳。期待の所: 会社＝全員の上の段・勤務の型＝型 日勤 の人の上の段と、全員の
    勤務の型 日勤 の中・人＝人 0001 の上の段・人 の値と、0001 の 勤務の型 の全部の中（勤務の型 の段にも置ける名）。
    読めない字は どの所にも無く、知らせ か 仮の値 に名と字が出る事。まとめる名は、芯 が支給月ごとに選ぶ中の名が _選ぶ支給月 の通りな事。"""
