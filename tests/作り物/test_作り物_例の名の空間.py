    if w == 読めない:
        知らせ = json.dumps([r.get("知らせ"), r.get("仮の値")], ensure_ascii=False, default=str)
        out = [f"{名}（{段} {x}）{v!r}: 読めない字が渡った {got!r}" for x, got in 所 if got is not None]
