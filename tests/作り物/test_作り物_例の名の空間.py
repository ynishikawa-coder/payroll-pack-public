def 三つの照らし(表: dict = _設定の表) -> tuple[list[str], list[str], list[str]]:
    """出した鍵の外れ・出所の無い鍵・置いた値に従わない鍵（届かない見本を含む）を、解くを回すタブの全部で（解く は 1 タブ 1 回）。"""
    タブたち = list(_解くを回すタブ())
    出力たち = [_解く(t) for t in タブたち]
    出所, 従わない = [], []
    for t, r in zip(タブたち, 出力たち):
        a, b = _照らす(t, r, 表)
        出所 += a
        従わない += b
    見本 = 見本のタブ()
