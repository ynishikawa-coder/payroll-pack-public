def _解くを包む(monkeypatch, 足す, 欄たち=("決まり", "人")) -> None:
    """解く の出力の 決まり・人 の各人 (鍵, d) に 足す を当てる形へ差し替える（足す は d か (鍵, d) を取る）。"""
    元 = 月次.段.解く
    二つ = 足す.__code__.co_argcount == 2

    def 包み(支給月, **t):
        r = 元(支給月, **t)
        for 欄 in 欄たち:
            for 鍵, d in r[欄].items():
                足す(鍵, d) if 二つ else 足す(d)
