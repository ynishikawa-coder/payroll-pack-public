def 段の解決の字の外れ(src: str, 表: dict, 辞書の名: set[str], 内の鍵: set[str]) -> list[str]:
    """段の解決.py の字で、項目の外 の名（分けた・写した鍵は表から引く）と、字で書いた鍵の名（`d["分野.名"] = …`）で
    表（項目の外 でない）・項目の辞書・内の鍵 に無い名と、字を組んで作る鍵（`d[名 + "…"] = …`・`d[f"…"] = …`）。"""
    外 = {n for n, e in 表.items() if e.get("項目の外")}
    読める = {n for n in 表 if n not in 外} | 辞書の名 | 内の鍵
    out = []
    for n in ast.walk(ast.parse(src)):
        if isinstance(n, ast.Constant) and n.value in 外:
            out.append(f"{n.lineno}: 項目の外 の名「{n.value}」")
        if isinstance(n, ast.Subscript) and isinstance(n.ctx, ast.Store):
            k = n.slice
            if isinstance(k, ast.Constant) and isinstance(k.value, str) and "." in k.value and k.value not in 読める | 外:
                out.append(f"{n.lineno}: 表に無い鍵「{k.value}」")
            elif isinstance(k, (ast.JoinedStr, ast.BinOp)):
                out.append(f"{n.lineno}: 字を組んで作る鍵")
    return out


