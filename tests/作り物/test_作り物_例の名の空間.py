def 出した鍵の外れ(鍵たち: set[str], 表: dict) -> list[str]:
    """解く が出した鍵で、マスタの項目の名（表に在り 項目の外 でない）・分けた鍵（マスタの項目 を持つ）・写した鍵（写す元 を
    持つ）・内の鍵 のどれでもない物（新しく分けた・写した鍵に欄が無い／表に無い鍵）と、見当の値 に出した名（見当の値/<名>）で
    芯が見当を読む名でない物。見当の値 は内の鍵として外し、中の名を照らす。"""
    def 読める(k):
        if k.startswith(_見当の印):
            return k.removeprefix(_見当の印) in _見当を読む名
        e = 表.get(k)
        if e is None:
            return k in _内の鍵
        return not e.get("項目の外") or bool(e.get("マスタの項目") or e.get("写す元"))
    return sorted(k for k in 鍵たち if not 読める(k))


def マスタの項目の外れ(表: dict) -> list[str]:
    """マスタの項目・写す元 の値が表に無い名か 項目の外 の名（マスタの項目の名でない）の行と、
    マスタの項目・写す元 を 項目の外 でない行に付けた行・両方を付けた行。"""
    def 外れ(e):
        値 = [e[f] for f in ("マスタの項目", "写す元") if f in e]
        return 値 and (len(値) > 1 or not e.get("項目の外") or any(m not in 表 or 表[m].get("項目の外") for m in 値))
    return sorted(n for n, e in 表.items() if 外れ(e))


