"""見張り: 前任の台帳の列を 単価×量×率・出口の欄・穴 へ当てはめた案（初期設定/台帳の当てはめ.py・作り物の表だけ）。"""
import importlib.util
from decimal import Decimal as D
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("初期設定_台帳の当てはめ", 根 / "初期設定" / "台帳の当てはめ.py")
当 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(当)

台帳 = {
    "列": ["NO", "残業手当", "深夜の残業", "祝日手当", "備考の額", "差引"],
    "人": [
        {"NO": "1", "残業手当": "21250", "深夜の残業": "7650", "祝日手当": "24000", "備考の額": "777", "差引": "1"},
        {"NO": "2", "残業手当": "4250", "深夜の残業": "", "祝日手当": "0", "備考の額": "5", "差引": "2"},
    ],
}
単価 = {"1": {"日給の時間": "1700", "日給": "12000"}, "2": {"日給の時間": "1700", "日給": "12000"}}
量 = {"1": {"法定外": "10", "法定外の深夜": "3", "祝日の日数": "2"}, "2": {"法定外": "2", "法定外の深夜": "0", "祝日の日数": "0"}}
率 = ("1", "1.25", "1.5")


def _案():
    return {a["列"]: a for a in 当.当てはめる(台帳, 単価, 量, 率たち=率, 出口の欄たち=("差引",))}


def test_列ごとに単価と量と率へ当てはめる():
    a = _案()
    assert "NO" not in a
    assert (a["残業手当"]["当てはめ"], a["残業手当"]["単価"], a["残業手当"]["量"], a["残業手当"]["率"]) == ("単価×量×率", "日給の時間", "法定外", D("1.25"))
    assert (a["深夜の残業"]["量"], a["深夜の残業"]["率"]) == ("法定外の深夜", D("1.5"))
    assert (a["祝日手当"]["単価"], a["祝日手当"]["量"], a["祝日手当"]["率"]) == ("日給", "祝日の日数", D("1"))
    assert a["差引"]["当てはめ"] == "出口の欄"


def test_合わない列は穴として起票する():
    a = _案()
    assert a["備考の額"]["当てはめ"] == "穴" and "起票" in a["備考の額"]["訳"]


def test_1人でも合わなければ穴で近い式に寄せない():
    誤り = {**台帳, "人": [dict(台帳["人"][0]), {**台帳["人"][1], "残業手当": "4300"}]}
    a = {x["列"]: x for x in 当.当てはめる(誤り, 単価, 量, 率たち=率)}
    assert a["残業手当"]["当てはめ"] == "穴"


def test_率を渡さなければ法の率で当てない():
    a = {x["列"]: x for x in 当.当てはめる(台帳, 単価, 量)}   # 既定は 1 だけ（法の率をここに書かない）
    assert a["残業手当"]["当てはめ"] == "穴" and a["祝日手当"]["当てはめ"] == "単価×量×率"


def test_数で読めない値は穴():
    誤り = {**台帳, "人": [{**台帳["人"][0], "祝日手当": "二万"}, 台帳["人"][1]]}
    a = {x["列"]: x for x in 当.当てはめる(誤り, 単価, 量, 率たち=率)}
    assert a["祝日手当"]["当てはめ"] == "穴"
