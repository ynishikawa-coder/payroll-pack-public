"""見張り: 仮が残る人は人ごとに除き、ほかの人は出す（会社の全員を待たせない）。値は作り物だけ。

根: 出口/出す.py は仮が 1 人でも残ると会社の全員を止めていた（仮の人 1 人のために 2_出す物・管理表 が空のまま）。
注入: 仮 1 人・ほか 2 人の月を回し、2 人だけが 2_出す物 へ出て、除いた 1 人が理由つきで返る事。2 回回しても同じ。
"""
import copy
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
for p in (根 / "tests" / "出す", 根 / "tests" / "給与エージェント", 根):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

import test_出す as 試  # noqa: E402
import 手伝い as 手  # noqa: E402
from 管理表 import 管理表 as 管理表の型  # noqa: E402  管理表の Drive のタブの名（型 39 は 1_月の状況 など）

表 = [["従業員コード", "氏名", "基本給"], ["1", "作り物 一郎", "1000"], ["2", "作り物 二郎", "2000"]]   # 月次が仮の NO 3 を外した残り（鍵の欄の名は事務所の形しだい）
仮 = {"外した人": [{"NO": "3", "理由": ["基本給が仮"]}], "仮の人の行": [{"NO": "3"}], "待つ訳": ["NO 3: 作り物の勤怠が届いていない"]}


def _回す口():
    def 回す(口, 置き場, 会社, 支給月, 回):
        o, 赤 = 試.回す口(仮=copy.deepcopy(仮))(口, 置き場, 会社, 支給月, 回)
        o["取り込み"].表 = copy.deepcopy(表)
        o["取り込み"].人 = ("1", "2")   # 作る口が付ける 載せた人（出す.py は見出しの名から人を当てない）
        return o, 赤
    return 回す


def _回して読む(口, 置き場):
    code, out = 試.出す.出す(口, 置き場, "2099-01", "給与", 回す=_回す口())
    assert code == 0 and out["出した"] is True, out
    sid = 口.名で引く(置き場["2_出す物"], out["置いた"][0]["名"])["id"]
    出た = 口.表を読む(sid, "'取り込み'!A1:Z")
    月 = 口.表を読む(置き場["管理表"], f"'{管理表の型.Driveのタブ('月の状況')}'!A1:Z")
    return out, 出た, 月


def test_仮1人ほか2人なら2人だけ出て除いた1人が返る():
    口, 置き場 = 試.置き場を作る()
    out, 出た, 月 = _回して読む(試.移せる(口), 置き場)
    assert [r[0] for r in 出た[1:]] == ["1", "2"]
    assert out["除いた人"] == [{"NO": "3", "理由": ["作り物の勤怠が届いていない", "基本給が仮"]}]
    assert 月[1][試.月の見出し.index("取り込み")] == "仮" and 月[1][試.月の見出し.index("外した人")] == "1"


def test_2回回して同じ結果():
    口, 置き場 = 試.置き場を作る()
    試.移せる(口)
    a = _回して読む(口, 置き場)
    b = _回して読む(口, 置き場)
    assert a[0]["除いた人"] == b[0]["除いた人"] and a[1] == b[1] and a[2] == b[2]
    assert len(口.子を並べる(置き場["2_出す物"])) == 1   # 2_出す物 は最新の版 1 つだけ
