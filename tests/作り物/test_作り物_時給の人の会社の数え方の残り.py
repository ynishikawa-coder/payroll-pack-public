"""見張り: 時給の人で `割増.残業の数え方`＝1日の所定超え の会社が、法の線の法定外より少なく数えた月の残りの時間を払う（作り物の値だけ）。

時給の人の所定内の行は 所定内 の時間だけを払う。週の法定（40 時間）を超えたが、その日の所定は超えない時間は
法の線では 法定外残業 に入り（所定内に入らない）、会社の数え方（その日の所定を超えた時間の和）にも入らない。
前は 法定外＝会社の数え方−法定内 で残りを捨て、どの行もこの時間を払わなかった（知らせだけ）。
1. 残りの時間（勤務の日の 法定内残業＋法定外残業−所定休日−会社の数え方）を 割増.法定内残業の率 で 法定内残業手当 に払う
2. 率は会社の設定から読む（既定 1.00・1.25 の会社は 1.25）
3. 月給の人は所定内の時間を月給で払い済み＝今までどおり（足さない）
4. 会社の数え方が法の線を下回らない月は何も足さない
"""
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "計算"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from 作る_計算 import 人, 回す, 決まり, 値たち  # noqa: E402

時給の行 = [{"名": "時給", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:所定内"}]
額 = {"項目.人の額": {"時給": "1051"}}
# 所定内 135 時間・会社の数え方 330 分・法の線の法定外 810 分（週の法定を超えた 480 分はその日の所定の内）
勤怠 = {"出勤日数": "19", "欠勤": "0", "総労働": "9000", "所定内": "8100", "法定内残業": "0", "法定外残業": "810",
        "60 時間超": "0", "深夜": "0", "遅刻早退": "0", "残業（会社の数え方）": "330", "60 時間超（会社の数え方）": "0"}


def _回す(tmp, 決=None, 上書き=None, 形="時給"):
    if 形 == "時給":
        決 = {"支払.賃金の形": "時給", "項目.行": 時給の行, **(決 or {})}
        人の値 = 人(**額)
    else:
        人の値 = 人()
    return 回す(tmp, 決=決まり(**(決 or {})), 人の値=人の値, 上書き={**勤怠, **(上書き or {})})


def _行(r):
    return {x["項目"]: x for x in r["行"]}


def test_会社の数え方が法定外を下回る時給の人は残りの時間を法定内残業の率で払う(tmp_path):
    r = _回す(tmp_path)
    v = 値たち(r)
    assert v["時給"] == 1051 * 135
    assert v["法定内残業手当"] == 8408   # 残り 480 分＝8 時間×1,051×1.00
    assert v["時間外手当"] == 7226       # 会社の数え方 330 分＝5.5 時間×1,051×1.25＝7,226.25（端数.割増の総額 の既定で丸め）
    # 時給 1,051 は作り物の最低賃金の表を下回る＝人は最低賃金の問いで仮。残りの時間の払いでは問いを立てない
    assert [q for q in r["問い"] if "法定内残業" in q["何が無いか"] or "会社の数え方" in q["何が無いか"]] == []


def test_残りの時間の率は会社の法定内残業の率(tmp_path):
    v = 値たち(_回す(tmp_path, 決={"割増.法定内残業の率": "1.25"}))
    assert v["法定内残業手当"] == 10510   # 8 時間×1,051×1.25


def test_月給の人は残りを足さない(tmp_path):
    v = 値たち(_回す(tmp_path, 形="月給"))
    assert v["法定内残業手当"] == 0


def test_会社の数え方が下回らない月は足さない(tmp_path):
    v = 値たち(_回す(tmp_path, 上書き={"残業（会社の数え方）": "810"}))
    assert v["法定内残業手当"] == 0
    assert v["時間外手当"] == 17736      # 13.5 時間×1,051×1.25＝17,735.625（端数.割増の総額 の既定で丸め）


def test_書き足した残業は書き足した時間と時給と率の積だけ増える(tmp_path):
    # 書き足した残業 120 分は法の線（法定外）と会社の数え方の両方に足して来る＝残りの 480 分は動かない
    前 = 値たち(_回す(tmp_path / "前"))
    後 = 値たち(_回す(tmp_path / "後", 上書き={"法定外残業": "930", "総労働": "9120", "残業（会社の数え方）": "450"}))
    assert 後["法定内残業手当"] == 前["法定内残業手当"] == 8408
    増え = (後["法定内残業手当"] + 後["時間外手当"]) - (前["法定内残業手当"] + 前["時間外手当"])
    assert 増え == 2627   # 2 時間×1,051×1.25＝2,627.5（7.5 時間×1,051×1.25＝9,853.125 の丸め−7,226）
