"""回帰の見張り: 寄せ（道具/寄せ/書き方.py）が台帳・マスタの 支給月・日付・時刻 の字を型の書き方へそろえ、見回りの書き方のずれの赤が 0 になる。

型の書き方（docs/設計/Drive の型.md「書き方を 1 つに固定」）: 支給月 `YYYY.MM支給`・日付 `YYYY-MM-DD`・時刻 `h:mm`。
- 字だけで同じ値に決まる物だけ直す（支給月は段の解決が同じ支給月と読む字＝`2027-02`・`2027.01支給（12月分）`・`2026年12月支給` など）。
  直した後も段の解決が読む支給月は同じ（値の意味は変えない）。値の数も変わらない（値の保ち）。
- 決まらない字（`2月分`・秒が 0 でない時刻・暦に無い日）は寄せられない物として問いに残し、何も書かない（1 社は全部か無し）。
  答え `値:<型の書き方の字>` で直す。型の書き方でない答えは問いのまま。
- 書いた後にもう一度寄せると書く手順 0。作り物の値だけ。
"""
import copy
import datetime as dt
import importlib.util
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根 / "道具" / "寄せ"))
import 当てる  # noqa: E402
import 直し as 直しの形  # noqa: E402
import 自己検査  # noqa: E402
import 見回り  # noqa: E402

_spec = importlib.util.spec_from_file_location("作り物_書き方_段の解決", 根 / "初期設定" / "段の解決.py")
段 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(段)

今日 = dt.date(2027, 2, 20)
型 = 当てる.型を開く(根 / "初期設定" / "型.json")
台帳 = "台帳_2000"
会社名 = "作り物の会社"


def 行(rows, **v):
    return [v.get(c, "") for c in rows[0]]


def 会社(区間=None, 前提=None):
    c = 自己検査.雛形(型)
    c["会社"] = 会社名
    L = c["シート"][台帳]
    for 支給月, 日付, 始め, 終わり in 区間 or [("2027-02", "2027/1/5", "8:30:00", "17:30"), ("2027-02", "2027-01-06", "9:00", "18:00:00"),
                                          ("2027.02支給", "2027年1月7日", "8:00", "12:00")]:
        L["読んだままの勤怠の区間"].append(行(L["読んだままの勤怠の区間"], 会社=会社名, 支給月=支給月, NO="1", 日付=日付, 区間の番号="1", 区間の種別="労働",
                             始め=始め, 終わり=終わり, 時刻の出所="打刻"))
    for 支給月, 項目, 値 in 前提 or [("2027.01支給（12月分）", "要出勤日数", "24"), ("2026年12月支給", "要出勤日数", "25"),
                                  ("2027-02", "締めの始め", "2027-01-01")]:
        L["その月だけの指示"].append(行(L["その月だけの指示"], 会社=会社名, 支給月=支給月, NO="1", 項目=項目, 値=値))
    L["読んだままの勤怠"].append(行(L["読んだままの勤怠"], 会社=会社名, 支給月="2027-02", NO="1", 日付="2027/2/10", 勤怠の表記="作り物"))
    return c


def 寄せる(c):
    return 当てる.見通す(c, 型, 直しの形.読む(), 今日)


def 列(c, t, 名):
    rows = c["シート"][台帳][t]
    return [r[rows[0].index(名)] for r in rows[1:]]


def 書いて読む(前, r):
    書いた = 当てる.手順を当てる(前, r["書く手順"])
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    return 書いた


def test_字だけで決まる物を型の書き方へそろえ見回りの赤が0になる():
    前 = 会社()
    assert len(見回り.書き方を見る(前)) == 11   # 支給月 6（区間 2・その月だけの指示 3・読んだままの勤怠 1）・日付 3（区間 2・読んだままの勤怠 1）・時刻 2
    r = 寄せる(前)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    assert r["値の保ち"]["合う"] and r["値の保ち"]["前の空でない値"] == r["値の保ち"]["後へ移った"]
    後 = r["寄せた後の値"]
    assert 見回り.書き方を見る(後) == []
    assert 列(後, "読んだままの勤怠の区間", "支給月") == ["2027.02支給"] * 3
    assert 列(後, "読んだままの勤怠の区間", "日付") == ["2027-01-05", "2027-01-06", "2027-01-07"]
    assert 列(後, "読んだままの勤怠の区間", "始め") == ["8:30", "9:00", "8:00"]
    assert 列(後, "読んだままの勤怠の区間", "終わり") == ["17:30", "18:00", "12:00"]
    assert 列(後, "その月だけの指示", "支給月") == ["2027.01支給", "2026.12支給", "2027.02支給"]
    assert 列(後, "その月だけの指示", "値") == ["24", "25", "2027-01-01"]       # 照らす列の外は変えない
    assert 列(後, "読んだままの勤怠", "支給月") == ["2027.02支給"] and 列(後, "読んだままの勤怠", "日付") == ["2027-02-10"]
    # 値の意味は変えない: 段の解決が読む支給月は前と同じ
    for t in ("読んだままの勤怠の区間", "その月だけの指示", "読んだままの勤怠"):
        assert [段.月にそろえる(v) for v in 列(前, t, "支給月")] == [段.月にそろえる(v) for v in 列(後, t, "支給月")]
    # 書く手順は値を字のまま書く（RAW）だけ。直した所は知らせに出る
    assert {x["する"] for x in r["書く手順"]} <= {"file を写す", "値を書く"}
    assert all(x["書き方"] == "RAW" for x in r["書く手順"] if x["する"] == "値を書く")
    assert any("支給月 の字を型の書き方へそろえた" in x for x in r["知らせ"])
    # 書いた後の見回りは赤でない・もう一度寄せると書く手順 0
    書いた = 書いて読む(前, r)
    assert 見回り.見回り([書いた], 直しの形.読む(), 当てる.型を読む(型)["版"], 今日)["赤"] is False
    r2 = 寄せる(書いた)
    assert r2["書く手順"] == [] and r2["寄せられない物"] == []


def test_字だけで決まらない物は問いに残し何も書かない():
    前 = 会社(区間=[("2月分", "2027-01-05", "8:30:15", "17:30"), ("2027-02", "2027/2/30", "9:00", "18:00")])
    r = 寄せる(前)
    鍵たち = sorted(x["鍵"] for x in r["寄せられない物"])
    assert 鍵たち == [f"{台帳}/読んだままの勤怠の区間/書き方:始め/2行目", f"{台帳}/読んだままの勤怠の区間/書き方:支給月/2行目", f"{台帳}/読んだままの勤怠の区間/書き方:日付/3行目"]
    assert {x["種類"] for x in r["寄せられない物"]} == {"書き方の合わない値"}
    assert r["書く手順"] == [] and r["寄せた後の値"]["シート"] == 当てる.物(前).出す()["シート"]   # 全部か無し
    # 型の書き方でない答えは問いのまま。型の書き方で答えれば直す
    c = copy.deepcopy(前)
    c["人の答え"] = {f"{台帳}/読んだままの勤怠の区間/書き方:支給月/2行目": "値:2月", f"{台帳}/読んだままの勤怠の区間/書き方:始め/2行目": "値:8:30",
                  f"{台帳}/読んだままの勤怠の区間/書き方:日付/3行目": "値:2027-02-28"}
    r = 寄せる(c)
    assert [x["鍵"] for x in r["寄せられない物"]] == [f"{台帳}/読んだままの勤怠の区間/書き方:支給月/2行目"]
    c["人の答え"][f"{台帳}/読んだままの勤怠の区間/書き方:支給月/2行目"] = "値:2027.02支給"
    r = 寄せる(c)
    assert r["寄せられない物"] == []
    後 = r["寄せた後の値"]
    assert 列(後, "読んだままの勤怠の区間", "支給月") == ["2027.02支給"] * 2
    assert 列(後, "読んだままの勤怠の区間", "始め") == ["8:30", "9:00"] and 列(後, "読んだままの勤怠の区間", "日付") == ["2027-01-05", "2027-02-28"]
    assert 見回り.書き方を見る(後) == []


def test_型の書き方の字は触らない():
    c = 会社(区間=[("2027.02支給", "2027-01-05", "8:30", "29:00")], 前提=[("2027.02支給", "要出勤日数", "24")])
    c["シート"][台帳]["読んだままの勤怠"] = c["シート"][台帳]["読んだままの勤怠"][:1]
    assert 見回り.書き方を見る(c) == []
    r = 寄せる(c)
    assert r["書く手順"] == [] and r["寄せられない物"] == []
