def 寄せる(会社, 直したち=None):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(根 / "初期設定" / "型.json"),
                      直しの形.読む() if 直したち is None else 直したち, 今日)


def 前の形():
    return json.loads((根 / "tests" / "寄せ" / "作り物の前の形.json").read_text(encoding="utf-8"))


def 寄せた後():
    return json.loads((根 / "tests" / "寄せ" / "作り物の寄せた後.json").read_text(encoding="utf-8"))["寄せた後の値"]


def 行を足す(rows, **値):
    行 = dict.fromkeys(rows[0], "")
    行.update(値)
    rows.append([行[k] for k in rows[0]])


def 行たち(r, t="支給控除の項目"):
    rows = (r["寄せた後の値"] if r["書く手順"] or not r["見通しの値"] else r["見通しの値"])["シート"][M][t]
    return {x[rows[0].index("項目")]: dict(zip(rows[0], x)) for x in rows[1:]}


def 問いの鍵(r):
    return [x["鍵"] for x in r["寄せられない物"]]


def 二回目は手順0(会社, r):
    assert r["寄せられない物"] == [] and r["値の保ち"]["合う"], r["寄せられない物"]
    書いた = 当てる.手順を当てる(会社, r["書く手順"])
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    r2 = 寄せる(書いた)
    assert r2["書く手順"] == [] and r2["寄せられない物"] == [], (r2["書く手順"][:2], r2["寄せられない物"])


def 通勤日額の会社(訳=None):
    """前の道具の形（型の版 0）に、割増の基礎 の空の支給の行（通勤日額）と控除の行を足す。"""
    c = 前の形()
    t = c["シート"][M]["支給控除の項目"]
    if 訳 is not None:
        t[0] = t[0] + ["割増の基礎から除く訳"]
        for r in t[1:]:
            r.append("")
    行を足す(t, 項目="作り物の通勤日額", 支給か控除か="支給", 計算の仕方="固定", 課税="課税",
          **({"割増の基礎から除く訳": 訳} if 訳 is not None else {}))
    行を足す(t, 項目="作り物の天引き", 支給か控除か="控除", 計算の仕方="固定")
    人 = c["シート"][M]["人ごとの支給控除"]
    head = 人[0]
    x = dict.fromkeys(head, "")
    x.update({head[0]: "1", head[1]: "作り物の通勤日額", head[2]: "500"})
    人.append([x[k] for k in head])
    x = dict.fromkeys(head, "")
    x.update({head[0]: "1", head[1]: "作り物の天引き", head[2]: "100"})
    人.append([x[k] for k in head])
    return c


# ---- 1 割増の基礎の空

鍵 = f"{支}/前の道具の空:割増の基礎/項目=作り物の通勤日額"


def test_前の道具の空は黙って入るにせず_除く訳が無ければ問い():
    c = 通勤日額の会社()
    r = 寄せる(c)
    assert 問いの鍵(r) == [鍵] and r["書く手順"] == []
    (q,) = r["寄せられない物"]
    assert q["種類"] == "前の道具の空" and "除く訳:<" in q["選べる答え"][0] and "入る" in q["選べる答え"]


def test_除く訳を答えれば入らないと訳を書き_二度目は手順0():
    c = 通勤日額の会社()
    c["人の答え"] = {鍵: "除く訳:通勤手当"}
    r = 寄せる(c)
    行 = 行たち(r)
    assert (行["作り物の通勤日額"]["割増の基礎"], 行["作り物の通勤日額"]["割増の基礎から除く訳"]) == ("入らない", "通勤手当")
    assert 行["作り物の天引き"]["割増の基礎"] == ""          # 控除の行の空は割増に関わらない＝触らない
    assert 行["基本給"]["割増の基礎"] == "入る"              # 前の形に ○ が書いてある行は直し 4 の読み
    二回目は手順0(c, r)


