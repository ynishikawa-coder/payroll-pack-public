# ---- 2 有給.出勤時間に足す の範囲

def _有給の会社(値):
    c = 寄せた後()
    c["型の版"] = 19
    t = c["シート"][M]["会社"]
    t.append(["作り物の会社", "有給.出勤時間に足す", 値, "", ""])
    社員 = c["シート"][M]["社員"]
    i = 社員[0].index("有給.出勤時間に足す")
    社員[0] = 社員[0][:i] + 社員[0][i + 1:]          # 版 19 の社員には列が無い
    c["シート"][M]["社員"] = [社員[0]] + [r[:i] + r[i + 1:] for r in 社員[1:]]
    return c


def _有給の値(r):
    rows = (r["寄せた後の値"] if r["書く手順"] or not r["見通しの値"] else r["見通しの値"])["シート"][M]["会社"]
    return [x[2] for x in rows[1:] if x[1] == "有給.出勤時間に足す"]


def test_前の語の月給の人だけは今の語へ_社員に列を足す():
    c = _有給の会社("月給の人だけ")
    r = 寄せる(c)
    assert 問いの鍵(r) == [] and _有給の値(r) == ["月給の人だけ足す"]
    assert "有給.出勤時間に足す" in r["寄せた後の値"]["シート"][M]["社員"][0]
    二回目は手順0(c, r)


def test_時給の人だけも今の語へ_今の語はそのまま():
    assert _有給の値(寄せる(_有給の会社("時給の人だけ"))) == ["時給の人だけ足す"]
    r = 寄せる(_有給の会社("足す"))
    assert 問いの鍵(r) == [] and _有給の値(r) == ["足す"]
    # わざと範囲を落とす読み（時給の人だけ足す→足す＝全員へ広げる）を直しに入れても、今の語は芯の選べる値から読むので範囲のまま
    直したち = copy.deepcopy(直しの形.読む())
    op = next(x for d in 直したち if d["版"] == 20 for x in d["操作"] if x.get("行") == {"項目": "有給.出勤時間に足す"})
    op["読み"].update({"時給の人だけ": "足す", "時給の人だけ足す": "足す"})
    r = 寄せる(_有給の会社("時給の人だけ足す"), 直したち)
    assert 問いの鍵(r) == [] and _有給の値(r) == ["時給の人だけ足す"]


def test_読めない語は問い():
    c = _有給の会社("ときどき")
    r = 寄せる(c)
    鍵 = [k for k in 問いの鍵(r) if "有給.出勤時間に足す" in k]
    assert 鍵 and r["書く手順"] == []
    # 人の答えの値もマスタの値と同じ読みで読む: 前の語の答え（時給の人だけ）は範囲ごと今の語へ・読めない答えは書かず問いに残す
    c["人の答え"] = {鍵[0]: "値:時給の人だけ"}
    r = 寄せる(c)
    assert 問いの鍵(r) == [] and _有給の値(r) == ["時給の人だけ足す"]
    c["人の答え"] = {鍵[0]: "値:時給の人だけ有給を足す"}
    r = 寄せる(c)
    assert 鍵[0] in 問いの鍵(r) and r["書く手順"] == []


def test_芯は賃金の形で足すかを分け_人の値が会社に勝つ値をそのまま読む():
    def 足す(値, 形):
        return 有給を足すか(決まり({"有給.出勤時間に足す": 値, "支払.賃金の形": 形}), None)
    assert 足す("足す", "時給") and not 足す("足さない", "月給") and not 足す(None, "月給")
    assert 足す("月給の人だけ足す", "月給") and 足す("月給の人だけ足す", "日給月給") and 足す("月給の人だけ足す", "年俸")
    assert not 足す("月給の人だけ足す", "時給") and not 足す("月給の人だけ足す", "日給")
    assert 足す("時給の人だけ足す", "時給") and not 足す("時給の人だけ足す", "月給")
    # 選べる値の外の字（ときどき）は 一人を集計する の最初に 芯/設定 が照らす（使う所で照らさない＝仮は 集計 の試験で見る）
    from 芯 import 設定
    assert not 設定.選べる値の字か("有給.出勤時間に足す", "ときどき")
    try:
        足す("月給の人だけ足す", None)
    except 形の誤り:
        pass
    else:
        raise AssertionError("賃金の形が空でも足すかが決まった")


def test_有給の日の時間外の判定が月給の人だけ足すで分かれる():
    sys.path.insert(0, str(根 / "tests" / "集計"))
    import 作る_集計 as 作
    from 芯.集計 import 集計する
    # 午後半休（年休 4 時間）の日に 9:00〜12:00・13:00〜19:00 の 9 時間働いた: 足す なら日の線から有給の 4 時間を引き、時間外が増える
    上書き = {"2026-11-02": (作.日("2026-11-02", 休暇の種類="年休", 休暇の単位="午後半休", 休暇の時間="240"),
                             [作.区("2026-11-02", 1, "9:00", "12:00"), 作.区("2026-11-02", 2, "13:00", "19:00")])}
    A, B = 作.月(上書き=上書き)

    def 時間外(値, 形):
        決 = {("作り物の会社", "1"): {"時間.日の所定": "8", "時間.週の所定": "40", "有給.出勤時間に足す": 値, "支払.賃金の形": 形}}
        r = 集計する(A, B, 決まり=決, 法の線=作.法の線)
        return {x["項目"]: x["値"] for x in r["行"]}
    月給, 時給 = 時間外("月給の人だけ足す", "月給"), 時間外("月給の人だけ足す", "時給")
    assert 月給 == 時間外("足す", "月給") and 時給 == 時間外("足さない", "時給")
    assert 月給 != 時給
