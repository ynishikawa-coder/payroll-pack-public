"""回帰の見張り: 給与ソフトへ入れない人（給与ソフトに載せない代表など）を ⑥つなぎ の人の行 1 か所で外す。

置き場: 2_マスタ ⑥つなぎ の人の行（NO＝その人・側＝出口・道具＝給与ソフトの呼び名・その道具での番号＝`渡さない`）。
- 口（`月次.月を回す` の 出口.取り込み に 道具 を渡す）が読み、取り込みの行にも `空の欄` にも出さず `渡さなかった人` に返す。
- 支給控除一覧（こちらの出力）には今までどおり載る。委託の人の外し方（委託も取り込む）は前と同じ。
- 殻が `渡さない人` を手で渡す道は止める（置き場を 1 つに）。作り物の値だけ。
"""
import importlib.util
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "出口", 根 / "tests" / "計算", 根 / "tests" / "集計"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from 出口 import 書き口, 形, 突き合わせ, 関所, 読み口  # noqa: E402
import 出口_作り物 as 作  # noqa: E402

F = 形.形を組む({**作.形の値, "文字コード": "utf-8"})
道具 = "作り物の給与ソフト"


def _人の行(NO, 番号="渡さない", 会社="9", 側="出口", 道具=道具):
    return {"会社": 会社, "NO": NO, "側": 側, "道具": 道具, "その道具での番号": 番号, "その道具での名": ""}


def test_渡さない人はつなぎの人の行の出口の渡さないだけから組む():
    つなぎ = [
        _人の行("0004"),
        _人の行("0001", 番号="1001"),                 # 給与ソフトでの番号の行＝外さない
        _人の行("0002", 道具="別の作り物の給与ソフト"),  # 別の給与ソフト＝この取り込みには効かない
        _人の行("0003", 側="入口"),                    # 入口の行＝読まない
        _人の行("0005", 会社="8"),                     # 別の会社
        {"会社": "9", "NO": "", "側": "出口", "道具": 道具, "その道具での番号": "欄.出勤日数", "その道具での名": "出勤日数"},
    ]
    assert 形.渡さない人を組む("9", 道具, つなぎ) == ("0004",)
    assert 形.渡さない人を組む("9", None, つなぎ) == ()   # どの給与ソフトか分からなければ読まない
    # 欄の対応を組む は人の行を読まない（前と同じ）
    assert [g["項目"] for g in 形.欄の対応を組む("9", 道具, (), つなぎ)] == ["出勤日数"]


def test_渡さない人は取り込みの行にも空の欄にも出ず渡さなかった人に返る():
    # 0005 は残業の値が無い＝載せれば 空の欄 に出る人（給与ソフトに載せない代表の例）
    通 = 関所.通す([*作.行たち, 作.R("0005", "出勤日数", 22), 作.R("0005", "総支給", 500000)])
    前 = 書き口.取り込み(通, "9", 作.月, 作.対応, F, "60進", 委託の人=作.委託)
    assert "0005 残業時間" in 前.空の欄 and "0005" in {r[0] for r in 前.表[1:]}
    assert 前.渡さなかった人 == ("0003",)

    o = 書き口.取り込み(通, "9", 作.月, 作.対応, F, "60進", 委託の人=作.委託, 渡さない人=["0005"])
    assert [r[0] for r in o.表[1:]] == ["0001", "0004"]
    assert not any(x.startswith("0005") for x in o.空の欄)
    assert o.渡さなかった人 == ("0003", "0005")
    assert o.表[1:] == tuple(r for r in 前.表[1:] if r[0] != "0005")   # 他の人の行は変わらない
    # 委託も取り込む でも 渡さない人 は外す（置き場の違う 2 つの外し方が 1 つの集まりで効く）
    o2 = 書き口.取り込み(通, "9", 作.月, 作.対応, F, "60進", 委託の人=作.委託, 委託も取り込む=True, 渡さない人=["0005"])
    assert [r[0] for r in o2.表[1:]] == ["0001", "0003", "0004"] and o2.渡さなかった人 == ("0005",)
    # 支給控除一覧（こちらの出力）には載る
    雇用, _ = 書き口.支給控除一覧(通, "9", 作.月, 委託の人=作.委託)
    assert "0005" in 雇用.表[0]
    # 渡さなかった人 をそのまま突き合わせへ渡せば照らさない人に返る
    読 = 読み口.読む(作.給与ソフトの出力.encode("utf-8"), "出力.csv", "9", 作.月, 作.対応, F, "60進")
    結 = 突き合わせ.突き合わせる(通, 読, 作.対応, 渡さなかった人=o.渡さなかった人)
    assert set(結.照らさなかった人) == {"0003", "0005"}


# ---- 口（月次.月を回す）が ⑥つなぎ から読む ----
_spec = importlib.util.spec_from_file_location("作り物_給与ソフトへ入れない人_月次", 根 / "tests" / "月次" / "test_月次.py")
月 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(月)


def _月を回す(tmp_path, つなぎ, **取り込みの足し):
    出口 = {"取り込み": {"道具": 道具, **月._出口()["取り込み"], **取り込みの足し}, "支給控除一覧": {}}
    return 月.作.確定して回す(月.支給月, 月.C, 月.作._タブ(人=月._人()), [{"部品": "Excel出勤簿", "値": 月.作._出勤簿()}],
                         法の線=月.作る_集計.法の線, 例=月.作._例(), 出口=出口, つなぎ=つなぎ, 置き場=月.作る_計算.置き場(tmp_path))


def test_口はつなぎの人の行から外し_殻が渡す道は止まる(tmp_path):
    人 = sorted(月.人たち)
    外す = 人[0]
    前 = _月を回す(tmp_path / "a", [])["取り込み"]
    assert {r[0] for r in 前.表[1:]} == set(人) and 前.渡さなかった人 == ()

    o = _月を回す(tmp_path / "b", [{**_人の行(外す, 会社=月.C)}])
    取 = o["取り込み"]
    assert {r[0] for r in 取.表[1:]} == set(人) - {外す}
    assert 取.渡さなかった人 == (外す,)
    assert not any(x.startswith(外す) for x in 取.空の欄)
    assert 取.表[1:] == tuple(r for r in 前.表[1:] if r[0] != 外す)
    assert 外す in o["支給控除一覧"][0].表[0]   # こちらの一覧には載る

    with pytest.raises(ValueError, match="渡さない人"):
        _月を回す(tmp_path / "c", [], 渡さない人=[外す])
