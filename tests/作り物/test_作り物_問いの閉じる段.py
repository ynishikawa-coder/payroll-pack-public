"""設問の閉じる段（設問.閉じる・まとめる が必ず通す）: マスタ・会社の決まりの md・質問と回答の 回答（G）と 見当（K）・前の答え の
4 か所で決まっている種は問いにせず、出所つきで 閉じた に返す。決まっていなければ問いに残る。値は作り物。"""
import importlib.util
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))


def _読む(path: Path, 名: str):
    s = importlib.util.spec_from_file_location(名, path)
    m = importlib.util.module_from_spec(s)
    sys.modules[名] = m
    s.loader.exec_module(m)
    return m


設問 = _読む(根 / "初期設定" / "設問.py", "作り物_閉じる段_設問")
前の答え = _読む(根 / "確認ページ" / "前の答え.py", "作り物_閉じる段_前の答え")

C = "作り物の会社"
月 = "2099.05支給"
項 = "時間.月給者の遅れた出勤"
_根拠 = {"根拠": [{"資料": "作り物の給与規程", "場所": "2 ページ 第 9 条", "原文": "遅れは別に定める"}],
        "読み": "規程に遅れの扱いが無いと読みました。"}


def _種(**kw):
    return {"何が無いか": 項, "種類": "会社の決まり", **_根拠, **kw}


def _閉じる(種たち, **kw):
    kw.setdefault("既にある", [])
    return 設問.閉じる(種たち, 会社=C, 支給月=月, **kw)


def _行(no, 何, **kw):
    return {"会社": C, "問いの番号": no, "支給月": 月, "何が無いか": 何, "質問": "作り物の問い", "回答": "", **kw}


# ── マスタ ──
def test_マスタに値が在れば閉じ_無ければ問いに残る():
    タブ = {"会社": [{"会社": C, "項目": 項, "今の値": "引かない", "適用開始": ""}]}
    r = _閉じる([_種()], タブ=タブ)
    assert r["種"] == [] and r["閉じた"][0]["出所"] == f"2_マスタ/会社/{項}" and r["閉じた"][0]["値"] == "引かない"
    r = _閉じる([_種()], タブ={"会社": [{"会社": C, "項目": "時間.打刻の丸めの単位", "今の値": "1", "適用開始": ""}]})
    assert len(r["種"]) == 1 and r["閉じた"] == []


def test_一部の人だけの値では人の問いを閉じない():
    タブ = {"社員": [{"会社": C, "NO": "1", 項: "引く"}, {"会社": C, "NO": "2", 項: ""}]}
    assert len(_閉じる([_種(人=["1", "2"])], タブ=タブ)["種"]) == 1
    assert _閉じる([_種(人=["1"])], タブ=タブ)["種"] == []


def test_法の線の種はマスタに値が在っても閉じない():
    タブ = {"会社": [{"会社": C, "項目": 項, "今の値": "引く", "適用開始": ""}]}
    s = _種(何が無いか=f"法の線: {項}（作り物）")
    assert len(_閉じる([s], タブ=タブ)["種"]) == 1


# ── 会社の決まりの md ──
def test_mdの節に字が在れば閉じ_節が空か無ければ問いに残る():
    s = _種(何が無いか="読み方: 遅れの扱い", 反映先="給与のルール.md#遅刻")
    md = {"給与のルール.md": "# 給与のルール\n## 遅刻\n遅れた分は引く\n## 早退\n"}
    r = _閉じる([s], md=md)
    assert r["種"] == [] and r["閉じた"][0]["出所"] == "給与のルール.md#遅刻" and r["閉じた"][0]["値"] == "遅れた分は引く"
    assert len(_閉じる([{**s, "反映先": "給与のルール.md#早退"}], md=md)["種"]) == 1
    assert len(_閉じる([s], md={"給与のルール.md": "# 給与のルール\n"})["種"]) == 1


# ── 質問と回答 G 列（回答） ──
def test_同じ何が無いかに決まった回答が在れば閉じ_分からないや空なら閉じない():
    r = _閉じる([_種()], 既にある=[_行("Q209905-01", 項, 回答="引く")])
    assert r["種"] == [] and r["閉じた"][0] == {"何が無いか": 項, "質問": 項, "出所": "質問と回答/Q209905-01/回答",
                                                 "値": "引く", "仮": False, "問いの番号": "Q209905-01"}
    for a in ("", "分からない", "確認中"):
        assert len(_閉じる([_種()], 既にある=[_行("Q209905-01", 項, 回答=a)])["種"]) == 1, a


def test_原本の種は別の月の回答で閉じない():
    何 = "始業より後の出勤: 2099.05支給"
    s = {"何が無いか": 何, "種類": "原本", **_根拠}
    assert _閉じる([s], 既にある=[_行("Q209905-02", 何, 回答="全部控除")])["種"] == []
    assert len(_閉じる([s], 既にある=[{**_行("Q209904-02", 何, 回答="全部控除"), "支給月": "2099.04支給"}])["種"]) == 1


# ── 質問と回答 K 列（見当＝仮の答え） ──
def test_答えが無く事務所の見当が在れば仮で閉じ_既定の見当では閉じない():
    r = _閉じる([_種()], 既にある=[_行("Q209905-03", 項, 見当="引く", 見当の拠り所="資料（作り物の給与規程）")])
    assert r["種"] == [] and r["閉じた"][0]["仮"] is True and r["閉じた"][0]["出所"] == "質問と回答/Q209905-03/見当"
    r = _閉じる([_種()], 既にある=[_行("Q209905-03", 項, 見当="引く", 見当の拠り所="既定")])
    assert len(r["種"]) == 1 and r["閉じた"] == []


# ── 前の答え ──
def test_別の番号でも同じmdの節を指す答え済みの問いで閉じる():
    前 = _行("Q209903-07", "読み方: 遅刻の時間", 反映先="給与のルール.md#遅刻", 回答="引く", 支給月="2099.03支給")
    s = _種(何が無いか="読み方: 遅れの扱い", 反映先="給与のルール.md#遅刻", 質問="遅れて来た日の扱いを教えてください")
    r = _閉じる([s], 既にある=[前])
    assert r["種"] == [] and r["閉じた"][0]["出所"] == "前の答え/Q209903-07"
    assert len(_閉じる([{**s, "反映先": "給与のルール.md#早退"}], 既にある=[前])["種"]) == 1


def test_設定の項目はmdの節まで数え_md名だけは数えない():
    assert 前の答え.設定の項目("給与のルール.md#遅刻、2_マスタ/会社") >= {"給与のルール.md#遅刻"}
    assert not any(".md" in x for x in 前の答え.設定の項目("給与のルール.md"))


# ── まとめる は閉じる段を飛ばせない ──
def test_まとめるは必ず閉じる段を通し閉じた種を問いにしない():
    md = {"給与のルール": "# 給与のルール\n## 遅刻\n遅れた分は引く\n"}
    s = _種(何が無いか="読み方: 遅れの扱い", 反映先="給与のルール.md#遅刻")
    m = 設問.まとめる([s], 会社=C, 支給月=月, 今日="2099-05-01", 既にある=[], md=md, 読んだ資料=["作り物の給与規程"])
    assert m["問い"] == [] and m["閉じた"][0]["出所"] == "給与のルール.md#遅刻"
    m = 設問.まとめる([s], 会社=C, 支給月=月, 今日="2099-05-01", 既にある=[], 読んだ資料=["作り物の給与規程"])
    assert len(m["問い"]) == 1 and m["閉じた"] == []
