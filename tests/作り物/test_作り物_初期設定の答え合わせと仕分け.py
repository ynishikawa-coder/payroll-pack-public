"""始める の答え合わせ（差 0 は問いにせず閉じる）・前任の未決の仕分け（未仕分けで止める）・読みの一覧。作り物の数だけ。"""
import importlib.util
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]


def _読む(名, file):
    s = importlib.util.spec_from_file_location(名, 根 / "初期設定" / file)
    m = importlib.util.module_from_spec(s)
    s.loader.exec_module(m)
    return m


始 = _読む("作り物_始める_答え合わせ", "始める.py")
仕 = _読む("作り物_未決の仕分け", "未決の仕分け.py")
読 = _読む("作り物_読みの一覧", "読みの一覧.py")

月, 会社 = "2026-10", "9"
つなぎ = [dict(項目="基本給", 欄="基本給", 形="円"), dict(項目="残業手当", 欄="残業手当", 形="円"),
       dict(項目="支払.締め日", 欄="締め日", 形="円")]


def _芯(no, 項目, 値):
    return dict(支給月=月, 会社=会社, NO=no, 項目=項目, 値=値, 状態="確定", 出所="作り物の計算", 問いの番号="")


def _答(no, 項目, 値):
    return dict(支給月=月, 会社=会社, NO=no, 項目=項目, 値=値, 出所="作り物の前任の結果.csv#10月")


def _正解(締め日の答え=25, 残業の答え=12000):
    return {
        "芯の行": [_芯("0001", "基本給", 200000), _芯("0002", "基本給", 180000), _芯("0001", "残業手当", 12500),
                 _芯("0001", "支払.締め日", 25)],
        "答え": [_答("0001", "基本給", 200000), _答("0002", "基本給", 180000), _答("0001", "残業手当", 残業の答え),
               _答("0001", "支払.締め日", 締め日の答え)],
        "つなぎ": つなぎ, "人の状態": [],
    }


def _入力(**足す):
    return {"会社": "作り物の会社", "組": "作り物の組", "最初の支給月": "2099.04支給", "今日": "2099-03-01", "既にある": [],
            "会社の値": {"支払.支給日": {"値": "翌月 10 日", "書類の名": "書類_2099-03-01_作り物"}}, **足す}


def _問いの名(r):
    return [q["何が無いか"] for q in r["問い"]]


# ── 答え合わせ（B） ──

def test_差0の項目は問いにせず答え合わせで一致で閉じる():
    前 = 始.始める(_入力())
    assert "支払.締め日" in _問いの名(前)          # 正解が無ければ今まで通り聞く
    assert 前["答え合わせ"] is None
    後 = 始.始める(_入力(前任の正解=_正解()))
    assert "支払.締め日" not in _問いの名(後)      # 差 0 に植えた項目は問いにならない
    一致 = {x["項目"]: x for x in 後["答え合わせ"]["一致"]}
    assert set(一致) == {"基本給", "支払.締め日"}
    assert 一致["支払.締め日"]["出所"] == "答え合わせで一致"
    assert 一致["支払.締め日"]["拠り所"] == "過去の結果 2026.10支給 作り物の前任の結果.csv 0001:支払.締め日 一致"
    assert "0002:180000" in 一致["基本給"]["値"]
    # 読みの一覧に答え合わせの元で載る
    行 = {x["項目"]: x for x in 後["読みの一覧"]}
    assert 行["支払.締め日"]["元"] == "答え合わせで一致" and 行["支払.締め日"]["出所"] == "答え合わせで一致"
    # 外した問いの番号は詰めて続く
    assert [q["問いの番号"] for q in 後["問い"]] == [始.口.問いの番号("2099.04支給", n + 1) for n in range(len(後["問い"]))]


def test_差のある項目は問いに残る():
    後 = 始.始める(_入力(前任の正解=_正解(締め日の答え=20)))
    assert "支払.締め日" in _問いの名(後)          # 差がある＝閉じない
    種 = [q["何が無いか"] for q in 後["答え合わせ"]["問いの種"]]
    assert "読み方: 照らし/「支払.締め日」/値が違う" in 種
    assert "読み方: 照らし/「残業手当」/値が違う" in 種
    assert {x["項目"] for x in 後["答え合わせ"]["一致"]} == {"基本給"}
    assert 後["答え合わせ"]["差の行の数"] == 2


def test_正解の欠けた渡し方は照らしを飛ばさず止める():
    正解 = _正解()
    del 正解["芯の行"]
    with pytest.raises(ValueError, match="芯の行"):
        始.始める(_入力(前任の正解=正解))


# ── 前任の未決の仕分け（C） ──

def test_未仕分けが残る間は始めるが止まる():
    r = 始.始める(_入力(前任の未決=[{"番号": "未決-1", "問い": "作り物の決まりの話"}, {"番号": "未決-2", "項目": "支払.締め日"}]))
    assert r["止める"] is True
    assert "置き場" not in r and "問い" not in r      # 置き場も問いも起こさない
    assert [x["番号"] for x in r["仕分け"]["未仕分け"]] == ["未決-1"]
    assert "未決-1" in r["止めた訳"][0]
    # 人が 4 つのどれかと出所を付ければ進む
    r = 始.始める(_入力(前任の未決=[{"番号": "未決-1", "問い": "作り物の決まりの話", "仕分け": "給与の外", "出所": "担当者 2099-03-01"}]))
    assert r["止める"] is False and r["仕分け"]["給与の外"][0]["番号"] == "未決-1"


@pytest.mark.parametrize("行, 分類", [
    ({"項目": "支払.支給日"}, "決定済み"),                     # 会社の値（書類）で決まる
    ({"項目": "支払.支給の月"}, "決定済み"),                   # 項目の既定で計算する
    ({"項目": "時間.月の所定日数"}, "決定済み"),               # 閉じた問いで決まる
    ({"項目": "突き合わせ.差0の月数の目安"}, "計算に効かない"),
    ({"項目": "作り物の分野.何か"}, "給与の外"),
    ({"項目": "支払.締め日"}, "聞く"),
    ({"問い": "項目の無い話"}, "未仕分け"),
    ({"問い": "出所の無い人の仕分け", "仕分け": "聞く"}, "未仕分け"),
    ({"問い": "4 つに無い仕分け", "仕分け": "あとで", "出所": "担当者"}, "未仕分け"),
    ({"項目": "支払.作り物の無い名"}, "未仕分け"),               # 分野は在るが辞書に無い名
])
def test_仕分けは行ごとに正しい分類に入る(行, 分類):
    閉じた = [{"項目": "時間.月の所定日数", "値": "20", "出所": "質問と回答 2099.04-01"}]
    r = 仕.仕分ける([行], 会社の値=_入力()["会社の値"], 閉じた=閉じた)
    入った = [k for k in (*仕.分類たち, "未仕分け") if r[k]]
    assert 入った == [分類]
    assert r["止める"] is (分類 == "未仕分け")
    if 分類 == "決定済み":
        assert r["決定済み"][0]["出所"]                 # 決定済みは必ず出所を持つ


def test_決定済みの出所は決めた元を指す():
    閉じた = [{"項目": "時間.月の所定日数", "値": "20", "出所": "質問と回答 2099.04-01"}]
    r = 仕.仕分ける([{"項目": "支払.支給日"}, {"項目": "時間.月の所定日数"}, {"項目": "支払.支給の月"}],
                  会社の値=_入力()["会社の値"], 閉じた=閉じた)
    出所 = {x["項目"]: x["出所"] for x in r["決定済み"]}
    assert 出所 == {"支払.支給日": "書類 書類_2099-03-01_作り物", "時間.月の所定日数": "質問と回答 2099.04-01",
                  "支払.支給の月": "初期設定/項目.json の既定"}


def test_聞くの行だけが問いになり閉じた項目は問いにならない():
    閉じた = [{"項目": "時間.月の所定日数", "値": "20", "出所": "質問と回答 2099.04-01"}]
    r = 始.始める(_入力(閉じた=閉じた, 前任の未決=[{"番号": "未決-3", "項目": "支払.締め日"},
                                         {"番号": "未決-4", "項目": "突き合わせ.差0の月数の目安"}]))
    名 = _問いの名(r)
    assert 名.count("支払.締め日") == 1                    # 足りない値と未決の聞くで 2 問にしない
    assert "時間.月の所定日数" not in 名 and "突き合わせ.差0の月数の目安" not in 名
    assert {x["項目"] for x in r["読みの一覧"]} >= {"支払.支給日", "時間.月の所定日数"}


def test_計算に効かないは芯にも読み手にも名が無い時だけ():
    assert not 仕.計算に効くか(仕.口.項目("突き合わせ.差0の月数の目安"))
    assert 仕.計算に効くか(仕.口.項目("支払.締め日"))


# ── 読みの一覧（E） ──

def test_読みの一覧は先の元が勝ち後の元はほかの出所に残す():
    r = 読.一覧(資料から読めた=[{"項目": "支払.支給日", "値": "10 日", "出所": "書類 作り物"}],
              閉じた問い=[{"項目": "支払.支給日", "値": "15 日", "出所": "質問と回答 2099.04-02"},
                     {"項目": "支払.締め日", "値": "末日", "出所": "質問と回答 2099.04-03"}])
    assert [(x["項目"], x["値"], x["元"]) for x in r] == [("支払.支給日", "10 日", "資料から読めた"), ("支払.締め日", "末日", "閉じた問い")]
    assert r[0]["ほかの出所"] == [{"値": "15 日", "出所": "質問と回答 2099.04-02", "元": "閉じた問い", "仮": False}]


def test_読みの一覧は見当で閉じた仮の印を落とさない():
    r = 読.一覧(閉じた問い=[{"項目": "支払.締め日", "値": "末日", "出所": "質問と回答/Q209904-03/見当", "仮": True},
                       {"項目": "支払.支給日", "値": "10 日", "出所": "質問と回答/Q209904-04/回答", "仮": False}])
    assert [(x["項目"], x["仮"]) for x in r] == [("支払.締め日", True), ("支払.支給日", False)]


def test_読みの一覧は出所の無い行を受けない():
    with pytest.raises(ValueError, match="出所"):
        読.一覧(閉じた問い=[{"項目": "支払.締め日", "値": "末日", "出所": ""}])
    with pytest.raises(TypeError):
        読.一覧(答え合わせで一致=["支払.締め日"])


# ── 閉じる段の戻りをそのまま渡す（設問.閉じる → 始める） ──

def test_閉じる段の戻りをそのまま渡せ_見当で閉じた物は未決を決定済みにしない():
    import sys
    sys.path.insert(0, str(根))
    設問 = _読む("作り物_始める_設問", "設問.py")
    名 = "時間.月の所定日数"

    def _行(no, **kw):
        return {"会社": "作り物の会社", "問いの番号": no, "支給月": "2099.04支給", "何が無いか": 名, "質問": "作り物の問い",
                "回答": "", **kw}

    種 = [{"何が無いか": 名, "種類": "会社の決まり"}]
    答えた = 設問.閉じる(種, 会社="作り物の会社", 支給月="2099.04支給", 既にある=[_行("Q209904-01", 回答="20")])["閉じた"]
    見当だけ = 設問.閉じる(種, 会社="作り物の会社", 支給月="2099.04支給",
                       既にある=[_行("Q209904-01", 見当="20", 見当の拠り所="資料（作り物の規程）")])["閉じた"]
    assert 答えた and 見当だけ and 見当だけ[0]["仮"] is True
    未決 = [{"番号": "未決-5", "項目": 名}]
    r = 始.始める(_入力(閉じた=答えた, 前任の未決=未決))
    assert 名 not in _問いの名(r)                          # 閉じた問いは問いに戻らない
    assert [x["番号"] for x in r["仕分け"]["決定済み"]] == ["未決-5"]
    r = 始.始める(_入力(閉じた=見当だけ, 前任の未決=未決))
    assert [x["番号"] for x in r["仕分け"]["決定済み"]] == []    # 仮の答えでは決定済みにしない
