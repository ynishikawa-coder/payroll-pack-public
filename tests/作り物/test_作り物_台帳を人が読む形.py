def test_版15の会社を今の版へ寄せると畳んだ台帳のタブは値を変えず消す問いへ_マスタは氏名が埋まる():
    """直し 16 が足した写しの列（氏名・曜日 など）の台帳のタブ（勤怠・勤怠の区間・月の変動）は型の版 27 で畳んだ＝
    版 15 の会社を今の版へ寄せると、そのタブへの前の直しは当てず、値を変えずに消す問い（9_履歴 へ写して消す）へ。
    マスタ「人ごとの支給控除」には直し 16 の 氏名 が足され、社員から埋まる。"""
    c = {"会社": 会社, "型の版": 15, "シート": _版15の会社()["シート"]}
    前 = copy.deepcopy(c["シート"])
    r = 当てる.見通す(c, 当てる.型を開く(根 / "初期設定" / "型.json"), 直しの形.読む(), dt.date(2026, 11, 18))
    assert r["値の保ち"]["合う"], r["値の保ち"]
    assert not [x for x in r["寄せられない物"] if x["所"].startswith("台帳")], r["寄せられない物"]
    消す = {(x["置き場"], x["物"]) for x in r["消す問い"]}
    assert {("台帳_2026", f"タブ {t}") for t in ("勤怠", "勤怠の区間", "月の変動")} <= 消す, 消す
    後 = r["見通しの値"] or r["寄せた後の値"]
    for t in ("勤怠", "勤怠の区間", "月の変動"):
        assert 後["シート"]["台帳_2026"][t] == 前["台帳_2026"][t], t   # 畳んだタブへは前の直しを当てない（値も列も変えない）
    def 辞(rows):
        return [dict(zip(rows[0], r)) for r in rows[1:]]
    assert 辞(後["シート"]["2_マスタ"]["人ごとの支給控除"])[0]["氏名"] == "作り物 一郎"


def test_見回りは書き方のずれを赤にする():
    c = {"会社": 会社, "型の版": 16, "置き場": ["3_月ごと/2026.11支給（10月分）/", "3_月ごと/2026年11月/"],
         "シート": {"台帳_2026": {"勤怠": [["会社", "支給月", "NO", "日付", "出勤の時刻"],
                                         [会社, "2026.11支給", "1", "2026-10-01", "9:00"],
                                         [会社, "2026-11", "1", "2026/10/02", "9時"]]}}}
    r = 見回り.見回り([c], [], 16, dt.date(2026, 11, 17))
    assert r["赤"]
    ずれ = {x["ずれ"].split("「")[0] for x in r["書き方のずれ"]}
    assert ずれ == {"支給月", "日付", "出勤の時刻", "月の置き場の名"}
    assert all("3行目" in x["所"] for x in r["書き方のずれ"] if x["ずれ"].startswith(("支給月", "日付", "出勤")))
    assert "書き方のずれ" in r["人が見る物"]
    ok = 見回り.見回り([{**c, "置き場": c["置き場"][:1], "シート": {"台帳_2026": {"勤怠": c["シート"]["台帳_2026"]["勤怠"][:2]}}}],
                   [], 16, dt.date(2026, 11, 17))
    assert not ok["赤"] and ok["書き方のずれ"] == []


