"""回帰の見張り: 台帳とマスタを人が開けば、誰の・いつの・何時から何時まで・どこから読んで・なぜ要確認か が 1 行で読める（型の版 16）。

- 月次.月を回す の返す台帳に 氏名・曜日・休憩の合計・労働の合計 が入る（道具が書く写し・計算は区間と分の列を読む。
  休憩の合計・労働の合計 は芯が数えた日の値＝tests/作り物/test_作り物_勤怠の要約は芯の数え.py）。
- 氏名がマスタ「社員」と違えば書く前に止める／要約（休憩・労働の合計）が区間と食い違えば止める／要確認の行に理由が無ければ止める。
- 書き方（支給月・日付・時刻）が型と違えば止める。
"""
import importlib.util
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
if str(根) not in sys.path:
    sys.path.insert(0, str(根))

_spec = importlib.util.spec_from_file_location("作り物_台帳を人が読む形", 根 / "月次" / "台帳の形.py")
形 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(形)
_spec2 = importlib.util.spec_from_file_location("作り物_台帳を人が読む形_月次", 根 / "tests" / "月次" / "test_月次.py")
月次の試験 = importlib.util.module_from_spec(_spec2)
_spec2.loader.exec_module(月次の試験)

会社, 月 = "作り物の会社", "2027-02"


def _日(NO, 日付, **kw):
    return {"会社": 会社, "支給月": 月, "NO": NO, "勤怠の表記": f"ひょうき{NO}", "日付": 日付, "日の種類": "勤務",
            "読み取りの確かめ": "確認済", **kw}


def _列(表, 列):
    i = 表[0].index(列)
    return [r[i] for r in 表[1:]]


def test_列の並びは人が左から読む順():
    h = 形.見出し("読んだままの勤怠")   # 型の版 27: 確定した勤怠 も同じ並び＋末尾 直した訳
    assert 形.見出し("確定した勤怠") == [*h, "直した訳"]
    assert h[:11] == ["会社", "支給月", "NO", "氏名", "勤怠の表記", "日付", "曜日", "出勤の時刻", "退勤の時刻", "休憩の合計", "労働の合計"]
    assert h[-8:] == ["原本の時間", "要確認の理由", "原本の名前", "原本の場所", "原本のリンク", "原本の種別", "読み取りの確かめ", "備考"]
    for 鍵 in ("その月だけの指示", "人ごとの支給控除"):
        x = 形.見出し(鍵)
        assert x[x.index("NO") + 1] == "氏名"


def test_曜日は日付から_要約は日の要約を_hmm():
    日たち = [_日("1", "2027-02-01"), _日("1", "2027-02-02"), _日("1", "2027-02-05", 日の種類="休日")]
    要約 = [{"支給月": 月, "会社": 会社, "NO": "1", "日付": "2027-02-01", "休憩": 60, "労働": 480},
          {"支給月": 月, "会社": 会社, "NO": "1", "日付": "2027-02-02", "休憩": None, "労働": None}]
    o = 形.勤怠の表たち(確定=False, 勤怠=日たち, 氏名={"1": "作り物 一郎"}, 日の要約=要約)["読んだままの勤怠"]
    assert _列(o, "曜日") == ["月", "火", "金"]
    assert _列(o, "休憩の合計") == ["1:00", "", ""]
    assert _列(o, "労働の合計") == ["8:00", "", ""]


def test_氏名がマスタと違えば止める():
    with pytest.raises(形.台帳の形の誤り, match="氏名"):
        形.勤怠の表たち(確定=False, 勤怠=[_日("1", "2027-02-01", 氏名="別の人")], 氏名={"1": "作り物 一郎"})
    with pytest.raises(形.台帳の形の誤り, match="氏名"):
        形.氏名を埋める("その月だけの指示", [{"会社": 会社, "支給月": 月, "NO": "1", "氏名": "別の人", "項目": "作り物手当", "値": "1"}],
                    {"1": "作り物 一郎"})
    # 同じ字なら通る
    o = 形.勤怠の表たち(確定=False, 勤怠=[_日("1", "2027-02-01", 氏名="作り物 一郎")], 氏名={"1": "作り物 一郎"})
    assert _列(o["読んだままの勤怠"], "氏名") == ["作り物 一郎"]


def test_要約と芯の数えが食い違えば止める():
    要約 = [{"支給月": 月, "会社": 会社, "NO": "1", "日付": "2027-02-01", "休憩": 60, "労働": 480}]
    with pytest.raises(形.台帳の形の誤り, match="労働の合計"):
        形.勤怠の表たち(確定=False, 勤怠=[_日("1", "2027-02-01", 労働の合計="9:00")], 日の要約=要約)
    with pytest.raises(形.台帳の形の誤り, match="休憩の合計"):
        形.勤怠の表たち(確定=False, 勤怠=[_日("1", "2027-02-01", 休憩の合計="0:45")], 日の要約=要約)


def test_要確認の行に理由が無ければ止める():
    with pytest.raises(形.台帳の形の誤り, match="要確認の理由"):
        形.勤怠の表たち(確定=False, 勤怠=[_日("1", "2027-02-01", 読み取りの確かめ="要確認")])
    o = 形.勤怠の表たち(確定=False, 勤怠=[_日("1", "2027-02-01", 読み取りの確かめ="要確認", 要確認の理由="退の欄が読めない",
                               原本の名前="作り物.pdf", 原本の場所="p.1 3行目")])
    assert _列(o["読んだままの勤怠"], "要確認の理由") == ["退の欄が読めない"]
    assert _列(o["読んだままの勤怠"], "原本の場所") == ["p.1 3行目"]


def test_書き方が型と違えば止める():
    for kw in ({"日付": "2027/02/01"}, {"所定の始業": "9時"}, {"支給月": "2027年2月"}):
        with pytest.raises(形.台帳の形の誤り, match="書き方"):
            形.勤怠の表たち(確定=False, 勤怠=[{**_日("1", "2027-02-01"), **kw}])


def test_月を回すの台帳に人が読む列が載る(tmp_path):
    tabs, _, o = 月次の試験._回す(tmp_path)
    氏名 = {a["NO"]: a["氏名"] for a in 月次の試験.段.行たち(tabs["社員"])}
    # 殻が確定した勤怠を書く形（休憩の合計・労働の合計 は 月を回す の返す 日の要約＝芯の数え）
    表 = 形.勤怠の表たち(確定=True, 勤怠=o["読んだまま"]["表A"], 勤怠の区間=o["読んだまま"]["表B"], 氏名=氏名, 日の要約=o["日の要約"])
    勤怠 = 月次の試験.段.行たち(表["確定した勤怠"])
    assert 勤怠
    assert all(a["氏名"] == 氏名[a["NO"]] and a["氏名"] for a in 勤怠)
    assert all(a["曜日"] == 形.曜日(a["日付"]) and a["曜日"] for a in 勤怠)
    働いた日 = [a for a in 勤怠 if a["出勤の時刻"]]
    assert 働いた日 and all(形._分(a["休憩の合計"]) is not None for a in 働いた日 if a["退勤の時刻"])
    assert any(a["労働の合計"] for a in 働いた日)
    assert all(a["要確認の理由"] for a in 勤怠 if a["読み取りの確かめ"] == "要確認")


def test_委託と変更の記録の氏名は殻が書く前に埋める口を通す():
    名 = {"1": "作り物 一郎"}
    o = 形.氏名を埋める("委託", [{"会社": 会社, "支給月": 月, "NO": "1", "項目": "作り物報酬", "値": "1"}], 名)
    assert o[0]["氏名"] == "作り物 一郎"
    o = 形.氏名を埋める("変更の記録", [{"会社": 会社, "NO": "", "項目": "作り物"}, {"会社": 会社, "NO": "9", "項目": "作り物"}], 名)
    assert [r["氏名"] for r in o] == ["", ""]
    with pytest.raises(形.台帳の形の誤り, match="氏名"):
        形.氏名を埋める("委託", [{"会社": 会社, "NO": "1", "氏名": "別の人"}], 名)
