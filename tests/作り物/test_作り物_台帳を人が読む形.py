def test_曜日と休憩と労働の合計は区間から_hmm():
    日たち = [_日("1", "2027-02-01"), _日("1", "2027-02-02"), _日("1", "2027-02-03", 時刻の無い休憩="15"),
            _日("1", "2027-02-04"), _日("1", "2027-02-05", 日の種類="休日")]
    区間たち = [
        _区("1", "2027-02-01", 1, "労働", "9:00", "18:00"), _区("1", "2027-02-01", 2, "休憩", "12:00", "13:00"),
        # 外出も労働から引く・休憩が労働の外にはみ出た分は労働から引かない
        _区("1", "2027-02-02", 1, "労働", "22:00", "30:30"), _区("1", "2027-02-02", 2, "外出", "25:00", "25:30"),
        _区("1", "2027-02-02", 3, "休憩", "30:00", "31:00"),
        # 時刻の無い休憩は休憩に足し労働から引く
        _区("1", "2027-02-03", 1, "労働", "9:00", "17:00"),
        # 打刻抜け（分からない＝空）
        _区("1", "2027-02-04", 1, "労働", "9:00", ""),
    ]
    o = 形.台帳へ書く形(勤怠=日たち, 勤怠の区間=区間たち, 氏名={"1": "作り物 一郎"})["勤怠"]
    assert _列(o, "曜日") == ["月", "火", "水", "木", "金"]
    assert _列(o, "休憩の合計") == ["1:00", "1:00", "0:15", "0:00", ""]
    assert _列(o, "労働の合計") == ["8:00", "7:30", "7:45", "", ""]
    # 計算に使う列は分のまま（写しは足すだけ）
    assert _列(o, "時刻の無い休憩")[2] == "15"


def test_氏名がマスタと違えば止める():
    with pytest.raises(形.台帳の形の誤り, match="氏名"):
        形.台帳へ書く形(勤怠=[_日("1", "2027-02-01", 氏名="別の人")], 氏名={"1": "作り物 一郎"})
    with pytest.raises(形.台帳の形の誤り, match="氏名"):
        形.台帳へ書く形(月の変動=[{"会社": 会社, "支給月": 月, "NO": "1", "氏名": "別の人", "項目": "作り物手当", "値": "1"}],
                    氏名={"1": "作り物 一郎"})
    # 同じ字なら通る
    o = 形.台帳へ書く形(勤怠=[_日("1", "2027-02-01", 氏名="作り物 一郎")], 氏名={"1": "作り物 一郎"})
    assert _列(o["勤怠"], "氏名") == ["作り物 一郎"]


