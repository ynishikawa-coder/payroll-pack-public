def test_直し16は版15のシートに列を足し値を変えない():
    直したち = [d for d in 直しの形.読む() if d["版"] == 16]
    assert len(直したち) == 1
    o = 当てる.物({"会社": 会社, "型の版": 15, "シート": _版15の会社()["シート"]})
    前 = copy.deepcopy(o.シート)
    記 = 当てる.記録()
    K = 当てる.型を読む(当てる.型を開く(根 / "初期設定" / "型.json"))
    for 番, op in enumerate(直したち[0]["操作"], 1):
        当てる.当てる操作(o, op, K, 記, 16, 番, {})
    def 辞(rows):
        return [dict(zip(rows[0], r)) for r in rows[1:]]
    # 在る値は変わらない
    for f, tabs in 前.items():
        for t, rows in tabs.items():
            for a, b in zip(辞(rows), 辞(o.シート[f][t])):
                assert all(b[k] == v for k, v in a.items() if v != ""), (f, t)
    勤怠 = 辞(o.シート["04_台帳_2026"]["勤怠"])[0]
    assert (勤怠["氏名"], 勤怠["曜日"], 勤怠["出勤の時刻"], 勤怠["退勤の時刻"], 勤怠["休憩の合計"], 勤怠["労働の合計"]) == \
        ("作り物 一郎", "木", "9:00", "18:00", "1:00", "8:00")
    assert (勤怠["要確認の理由"], 勤怠["原本の場所"], 勤怠["原本のリンク"]) == ("", "", "")
    assert 辞(o.シート["04_台帳_2026"]["月の変動"])[0]["氏名"] == "作り物 一郎"
    assert 辞(o.シート["03_マスタ"]["人ごとの支給控除"])[0]["氏名"] == "作り物 一郎"
    assert all(r["氏名"] == "作り物 一郎" for r in 辞(o.シート["04_台帳_2026"]["勤怠の区間"]))
    # 列は型の並び（足した列は人が左から読む所へ）
    assert o.シート["04_台帳_2026"]["勤怠"][0][:11] == ["会社", "支給月", "NO", "氏名", "勤怠の表記", "日付", "曜日", "出勤の時刻",
                                                  "退勤の時刻", "休憩の合計", "労働の合計"]


def test_見回りは書き方のずれを赤にする():
    c = {"会社": 会社, "型の版": 16, "置き場": ["10_月ごと/2026.11支給（10月分）/", "10_月ごと/2026年11月/"],
         "シート": {"04_台帳_2026": {"勤怠": [["会社", "支給月", "NO", "日付", "出勤の時刻"],
                                         [会社, "2026.11支給", "1", "2026-10-01", "9:00"],
                                         [会社, "2026-11", "1", "2026/10/02", "9時"]]}}}
    r = 見回り.見回り([c], [], 16, dt.date(2026, 11, 17))
    assert r["赤"]
    ずれ = {x["ずれ"].split("「")[0] for x in r["書き方のずれ"]}
    assert ずれ == {"支給月", "日付", "出勤の時刻", "月の置き場の名"}
    assert all("3行目" in x["所"] for x in r["書き方のずれ"] if x["ずれ"].startswith(("支給月", "日付", "出勤")))
    assert "書き方のずれ" in r["人が見る物"]
    ok = 見回り.見回り([{**c, "置き場": c["置き場"][:1], "シート": {"04_台帳_2026": {"勤怠": c["シート"]["04_台帳_2026"]["勤怠"][:2]}}}],
                   [], 16, dt.date(2026, 11, 17))
    assert not ok["赤"] and ok["書き方のずれ"] == []


