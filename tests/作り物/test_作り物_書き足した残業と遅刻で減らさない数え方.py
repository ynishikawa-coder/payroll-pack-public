"""見張り: 会社の残業の数え方に足した 2 つ（作り物の値だけ）。

1. 表 A の列 `書き足した残業`（分）: 打刻の外で働いた残業。芯は働いた時間（法の線の総）と 日の会社の残業 の両方に
   この値を足す（空＝0）。既定（法定どおり）の会社も法の線で払う（黙って落とさない）。足す所が決まらない日は仮にする。
2. `割増.残業の数え方`＝`1日の所定超え（遅刻で減らさない）`: その日の遅れた出勤の分を足して数える
   （終業後の時間を残業とする＝遅刻で残業を減らさない）。既定の `1日の所定超え` は今の式（実に働いた時間で数える）のまま。
"""
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "集計"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from 作る_集計 import 一つ, 区, 数える, 既定の決まり, 日, 月  # noqa: E402

所定超え = "1日の所定超え"
遅刻で減らさない = "1日の所定超え（遅刻で減らさない）"
会社の語 = ("残業（会社の数え方）", "60 時間超（会社の数え方）")
水 = "2026-11-04"


def _数える(数え方, 行=None, 区たち=None):
    上書き = {水: (日(水, **(行 or {})), 区たち or [区(水, 1, "9:00", "18:00"), 区(水, 2, "12:00", "13:00", "休憩")])}
    A, B = 月(上書き=上書き)
    決 = 既定の決まり(**({"割増.残業の数え方": 数え方} if 数え方 else {}))
    return 数える(A, B, 決)


def _遅れた日(終わり="19:00"):
    return [区(水, 1, "9:30", 終わり), 区(水, 2, "12:00", "13:00", "休憩")]


# 1. 書き足した残業

def test_書き足した残業は会社の残業に足す():
    結果 = _数える(所定超え, {"書き足した残業": "90"})
    assert 一つ(結果, "残業（会社の数え方）") == 90
    assert 一つ(結果, "法定外残業") == 90         # 打刻の後に働いた時間＝法の線の働いた時間にも足す（日の法定 8 時間の外）
    assert 一つ(結果, "法定内残業") == 0
    assert 一つ(結果, "総労働") == 一つ(_数える(所定超え), "総労働") + 90


def test_書き足した残業は打刻の残業の上に足す():
    結果 = _数える(所定超え, {"書き足した残業": "45"},
                 [区(水, 1, "9:00", "19:00"), 区(水, 2, "12:00", "13:00", "休憩")])
    assert 一つ(結果, "残業（会社の数え方）") == 60 + 45


def test_書き足した残業が空なら0():
    結果 = _数える(所定超え, {"書き足した残業": ""})
    assert 一つ(結果, "残業（会社の数え方）") == 0


def test_法定どおりの会社で書き足した残業が法の線で払われる():
    # 前は会社の数え方の側にだけ足し、法定どおりの会社では黙って落ちた。今は法の線の働いた時間に足す
    結果 = _数える(None, {"書き足した残業": "90"})
    assert not any(r["項目"] in 会社の語 for r in 結果["行"])
    assert 一つ(結果, "法定外残業") == 90
    assert 結果["問い"] == []


def test_書き足した残業は遅刻早退を埋めない_打刻が所定に届かない日は仮():
    # 9:00〜17:00（休憩 1 時間）＝打刻 7 時間・所定 8 時間＋書き足し 90 分: 法の線では 60 分が所定内に入り会社の残業と食い違う＝仮
    結果 = _数える(所定超え, {"書き足した残業": "90"}, [区(水, 1, "9:00", "17:00"), 区(水, 2, "12:00", "13:00", "休憩")])
    assert 一つ(結果, "遅刻早退") == 60
    assert any("書き足した残業" in q["何が無いか"] for q in 結果["問い"])


def test_勤務の日でない日の書き足した残業は仮():
    結果 = _数える(None, {"書き足した残業": "30", "日の種類": "欠勤"}, [])
    assert any("書き足した残業" in q["何が無いか"] for q in 結果["問い"])


def test_月の超えで数える会社も書き足した残業を足す():
    結果 = _数える("月の総労働が月の所定を超えた分", {"書き足した残業": "90"})
    assert 一つ(結果, "残業（会社の数え方）") == 90


# 2. 遅刻で減らさない数え方

def test_既定の1日の所定超えは遅刻で残業を減らす今の式のまま():
    # 9:30〜19:00（休憩 1 時間）＝実働 8.5 時間・所定 8 → 30 分
    assert 一つ(_数える(所定超え, 区たち=_遅れた日()), "残業（会社の数え方）") == 30


def test_遅刻で減らさない数え方は終業後の時間を残業とする():
    結果 = _数える(遅刻で減らさない, 区たち=_遅れた日())
    assert 一つ(結果, "残業（会社の数え方）") == 60
    assert 一つ(結果, "法定外残業") == 30          # 法の線は実に働いた時間のまま


def test_遅延証明のある遅れも減らさない():
    結果 = _数える(遅刻で減らさない, {"遅延証明の分": "30"}, _遅れた日())
    assert 一つ(結果, "残業（会社の数え方）") == 60


def test_遅刻して終業前に帰った日は残業が無い():
    assert 一つ(_数える(遅刻で減らさない, 区たち=_遅れた日("17:00")), "残業（会社の数え方）") == 0


def test_遅刻の無い日は今の式と同じ():
    区たち = [区(水, 1, "9:00", "19:00"), 区(水, 2, "12:00", "13:00", "休憩")]
    assert (一つ(_数える(遅刻で減らさない, 区たち=区たち), "残業（会社の数え方）")
            == 一つ(_数える(所定超え, 区たち=区たち), "残業（会社の数え方）") == 60)


def test_遅刻で減らさない数え方にも書き足した残業を足す():
    結果 = _数える(遅刻で減らさない, {"書き足した残業": "15"}, _遅れた日())
    assert 一つ(結果, "残業（会社の数え方）") == 60 + 15


_午前半休 = {"休暇の種類": "年次有給休暇", "休暇の単位": "午前半休", "休暇の時間": "240"}


def test_半休の日は遅れを足さない():
    # 午前に半休（休暇の分 240 分）で 13:00 から出た日は遅刻でない＝遅れを足さない（足せば遅れ 240 分で 60 分の会社の残業が出る）
    結果 = _数える(遅刻で減らさない, _午前半休, [区(水, 1, "13:00", "18:00")])
    assert 一つ(結果, "残業（会社の数え方）") == 0
    assert 一つ(結果, "残業（会社の数え方）") == 一つ(_数える(所定超え, _午前半休,
                                                       [区(水, 1, "13:00", "18:00")]), "残業（会社の数え方）")


def test_書き足した残業は法の線と会社の数え方の両方に同じだけ足す():
    # 時給の人の残り（法定内＋法定外−会社の数え方）は書き足しで動かない＝書き足した時間は会社の数え方の割増でそのまま払う
    前, 後 = _数える(所定超え), _数える(所定超え, {"書き足した残業": "120"})
    def 残り(r):
        return 一つ(r, "法定内残業") + 一つ(r, "法定外残業") - 一つ(r, "残業（会社の数え方）")
    assert 残り(後) == 残り(前)
    assert 一つ(後, "残業（会社の数え方）") - 一つ(前, "残業（会社の数え方）") == 120
