"""回帰の見張り: 出勤から退勤まで（休憩を含む出勤〜退勤の長さの和）と 年休の日数（半日の有給を 0.5 日に数えた年休の日の和）。

給与ソフトの 出勤時間 の欄と 有給日数 の欄へ、欄の対応（`欄.<項目>`）で当てられる。作り物の値だけ。
直した所の外（総労働・年休（全日）・年休（半日）・特別休暇）は前と同じに数える。
"""
import sys
from datetime import date
from decimal import Decimal
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "集計"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from 作る_集計 import 区, 数える, 既定の決まり, 日, 月, 一つ, 法の線, 人の鍵  # noqa: E402
from 出口 import 書き口, 関所  # noqa: E402
from 芯.集計 import 集計する  # noqa: E402
from 芯.集計.形 import 出す語  # noqa: E402
from 入口 import 口 as 入口の口  # noqa: E402

決 = 既定の決まり(**{"時間.休憩の表": ["12:00〜13:00"]})


def 行(x, 項目):
    return [r for r in x["行"] if r["項目"] == 項目]


def test_出勤から退勤までは休憩を含み総労働は休憩を引く():
    x = 数える(*月(), 決)
    # 平日 21 日 × 9:00〜18:00（9 時間・休憩 1 時間を含む）
    assert 一つ(x, "出勤から退勤まで") == 21 * 9 * 60
    assert 一つ(x, "総労働") == 21 * 8 * 60   # 前と同じ（休憩を引いた働いた時間）
    assert 行(x, "出勤から退勤まで")[0]["状態"] == "確定"


def test_組が幾つもある日は組ごとの長さの和_端の分も残す():
    s = "2026-11-04"
    上 = {s: (日(s), [区(s, 1, "8:57", "12:00"), 区(s, 2, "13:30", "18:46")])}
    x = 数える(*月(上書き=上), 決)
    # 20 日 × 9 時間 ＋ 11/4 の (3:03 ＋ 5:16)
    assert 一つ(x, "出勤から退勤まで") == 20 * 9 * 60 + (183 + 316)


def test_時刻の無い労働の日はその長さ_時刻の無いみなしの日がある人は行を出さない():
    s = "2026-11-04"
    x = 数える(*月(上書き={s: (日(s, 時刻の無い労働時間="540", 時刻の無い休憩="60"), [])}), 決)
    assert 一つ(x, "出勤から退勤まで") == 21 * 9 * 60
    x = 数える(*月(上書き={s: (日(s, 働いた場所="みなし"), [])}),
             既定の決まり(**{"時間.休憩の表": ["12:00〜13:00"], "時間.みなし時間": "8"}))
    assert 行(x, "出勤から退勤まで") == []           # 0 で黙って短くしない（出口は欄を空で書き 空の欄 に返す）
    assert any("出勤から退勤まで" in t for t in x["知らせ"])
    assert x["人"][0]["状態"] == "確認済"            # その欄を使わない会社の人を仮にしない


def test_半日の有給は0点5日として年休の日数に足す():
    上 = {"2026-11-04": (日("2026-11-04", "休暇", 休暇の種類="年休", 休暇の単位="全日"), []),
         "2026-11-05": (日("2026-11-05", 休暇の種類="年休", 休暇の単位="午前半休"),
                        [区("2026-11-05", 1, "13:00", "18:00")]),
         "2026-11-06": (日("2026-11-06", 休暇の種類="年休", 休暇の単位="午後半休"),
                        [区("2026-11-06", 1, "9:00", "13:00")]),
         "2026-11-09": (日("2026-11-09", "休暇", 休暇の種類="特別休暇（有給）", 休暇の単位="全日"), [])}
    x = 数える(*月(上書き=上), 決)
    assert 一つ(x, "年休の日数") == Decimal("2")       # 全日 1 ＋ 半日 2 回 × 0.5
    assert (一つ(x, "年休（全日）"), 一つ(x, "年休（半日）")) == (Decimal(1), 2)   # 前と同じ
    assert 一つ(x, "特別休暇（有給）") == Decimal(1)   # 特別休暇は年休の日数に入れない（前のまま）
    assert 行(x, "年休の日数")[0]["状態"] == "確定"


def 口(d):
    return [{**人の鍵, "項目": k, "値": v, "原本の名前": "作り物.csv", "原本の種別": "集計済み勤怠表",
             "読み取りの確かめ": "確認済"} for k, v in d.items()]


基 = {"所定日数": "20", "出勤日数": "19", "総労働": "9120", "所定内": "9120", "年休（全日）": "1", "年休（半日）": "1"}


def 口で(d):
    return 集計する(月の口=口(d), 決まり={("作り物の会社", "1"): 既定の決まり()}, 法の線=法の線)


def test_月の数字の口_年休の日数は全日と半日から出し_来た値は照らす():
    x = 口で(基)
    assert [r["値"] for r in 行(x, "年休の日数")] == [Decimal("1.5")]
    assert x["人"][0]["状態"] == "確認済"
    x = 口で({**基, "年休の日数": "1.5"})
    assert x["人"][0]["状態"] == "確認済"
    x = 口で({**基, "年休の日数": "2"})
    assert x["人"][0]["状態"] == "仮"


def test_月の数字の口_出勤から退勤までは来れば通し_無ければ働いた人は行を出さない():
    assert [r["値"] for r in 行(口で({**基, "出勤から退勤まで": "10260"}), "出勤から退勤まで")] == [10260]
    x = 口で(基)
    assert 行(x, "出勤から退勤まで") == [] and x["人"][0]["状態"] == "確認済"
    x = 口で({"所定日数": "20", "出勤日数": "0", "総労働": "0"})
    assert [r["値"] for r in 行(x, "出勤から退勤まで")] == [0]


def test_入口の月の項目は芯の月の語と同じ():
    # 入口は芯を import しない＝写しの並びが黙ってずれないよう見張る（会社の数え方の語・頭打ちの月の所定の語は月の数字の口から来ない）
    from 芯.集計.形 import 月の語
    assert 入口の口.月の項目 == dict(月の語)
    assert set(dict(出す語)) - set(入口の口.月の項目) == {"残業（会社の数え方）", "60 時間超（会社の数え方）", "月の残業の所定"}


def test_欄の対応で出勤時間と有給日数の欄へ書ける():
    上 = {"2026-11-05": (日("2026-11-05", 休暇の種類="年休", 休暇の単位="午前半休"),
                        [区("2026-11-05", 1, "13:00", "18:00")])}
    x = 数える(*月(上書き=上), 決)
    渡す, _ = 関所.勤怠の行を分ける(x["行"], {}, None, {})
    通 = 関所.通す(渡す, {(p["支給月"], p["会社"], p["NO"]): p["状態"] for p in x["人"]})
    対応 = [{"項目": "出勤から退勤まで", "欄": "出勤時間", "形": "分", "渡す": True, "受ける": True},
            {"項目": "年休の日数", "欄": "有給日数", "形": "日", "渡す": True, "受ける": True},
            {"項目": "総労働", "欄": "総労働時間", "形": "分", "渡す": True, "受ける": True}]
    形 = {"名": "作り物の給与ソフト", "鍵の欄": "社員番号", "渡し方": "表"}
    表 = 書き口.取り込み(通, "作り物の会社", "2026-11", 対応, 形, "時:分", 委託の人=[], 今ある名=[], 履歴にある名=[]).表
    頭, 一 = 表[0], dict(zip(表[0], 表[1]))
    assert 頭 == ("社員番号", "出勤時間", "有給日数", "総労働時間")
    # 20 日 × 9 時間 ＋ 午前半休の日の 13:00〜18:00（5 時間）＝ 185:00
    assert 一["出勤時間"] == "185:00"
    assert 一["有給日数"] == "0.5"
    assert 一["総労働時間"] == f"{20 * 8 + 5}:00"
