"""見張り: 欠勤.控除の式＝欠勤が多い月だけ出た日で払う の「多い月」の線を会社ごとに選べる（作り物の値だけ）。

- 欠勤.多い月の線＝欠勤が N 日以上の月: 欠勤がちょうど N 日の月は出た日で払う方式、N−1 日（線が N+1 日）の月は引く方式。
- 既定（所定日数の半分を超えた月）の会社は、新しい行を置いても置かなくても結果が今までと同じ。
- N 日以上の線で N が空・数でない・整数でない・1 未満: 黙って半分の線へ倒さず、その人を仮にして問いを出す（出口へ出ない）。
金額は手で書かず、同じ月を 控除の式＝引く方式・出た日で払う方式 で回した額と比べる（2 つの式が違う額になる月で見る）。
"""
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "計算"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

import 作る_計算 as 計  # noqa: E402

月 = {"欠勤": "5", "出勤日数": "14"}   # 出勤＋欠勤≠所定（1 日は年休）＝引く方式と出た日で払う方式の額が違う
N日 = {"欠勤.多い月の線": "欠勤が N 日以上の月"}


def _回す(tmp, 上書き=月, **決):
    d = tmp / str(len(list(tmp.iterdir())))   # 計.回す は回すたびに 法の表 を写す＝回ごとに別の dir
    d.mkdir()
    return 計.回す(d, 決=計.決まり(**決), 上書き=上書き)


def _額(結果):
    return 計.値たち(結果)["欠勤控除"]


def _式の額(tmp, 式, 上書き=月):
    return _額(_回す(tmp, 上書き, **{"欠勤.控除の式": 式}))


def test_N日ちょうどで出た日で払い_一つ手前で引く(tmp_path):
    引く, 出た日 = _式の額(tmp_path, "引く方式"), _式の額(tmp_path, "出た日で払う方式")
    assert 引く != 出た日
    ちょうど = _回す(tmp_path, **N日, **{"欠勤.多い月の日数": "5"})
    手前 = _回す(tmp_path, **N日, **{"欠勤.多い月の日数": "6"})
    assert _額(ちょうど) == 出た日 and _額(手前) == 引く
    assert [p["状態"] for p in ちょうど["人"] + 手前["人"]] == ["確認済", "確認済"]
    # 欠勤の日数の側で N−1 日（線は同じ 5 日）も引く方式
    四日 = {"欠勤": "4", "出勤日数": "15"}
    assert _額(_回す(tmp_path, 四日, **N日, **{"欠勤.多い月の日数": "5"})) == _式の額(tmp_path, "引く方式", 四日)


@pytest.mark.parametrize("上書き", [月, {"欠勤": "11", "出勤日数": "8"}])   # 半分を超えない月・超える月
def test_既定の会社は今までと同じ(tmp_path, 上書き):
    前 = _回す(tmp_path, 上書き)
    for 決 in ({"欠勤.多い月の線": "所定日数の半分を超えた月"},
               {"欠勤.多い月の線": "所定日数の半分を超えた月", "欠勤.多い月の日数": "1"},   # 線が既定なら N は読まない
               {"欠勤.多い月の日数": ""}):
        後 = _回す(tmp_path, 上書き, **決)
        assert 後["行"] == 前["行"] and 後["人"] == 前["人"] and 後["問い"] == 前["問い"]
    半分を超える = int(上書き["欠勤"]) * 2 > 20
    assert _額(前) == _式の額(tmp_path, "出た日で払う方式" if 半分を超える else "引く方式", 上書き)


@pytest.mark.parametrize("N", [None, "", "  ", "十", "2.5", "0", "-3"])
def test_Nが読めないと仮で止める(tmp_path, N):
    決 = dict(N日) if N is None else {**N日, "欠勤.多い月の日数": N}
    結果 = _回す(tmp_path, **決)
    assert [p["状態"] for p in 結果["人"]] == ["仮"]
    assert any("欠勤.多い月の日数" in q["何が無いか"] for q in 結果["問い"])
    assert _額(結果) == _式の額(tmp_path, "引く方式")   # 見当は半分の線（5 日×2 は 20 を超えない＝引く方式）
    # 月給でない人には効かない線＝N が読めなくても仮にしない
    時給 = _回す(tmp_path, **決, **{"支払.賃金の形": "時給"})
    assert not any("欠勤.多い月の日数" in q["何が無いか"] for q in 時給["問い"])
