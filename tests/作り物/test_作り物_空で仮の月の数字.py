"""見張り: 月の数字で値が空・状態＝仮 の語を額に使う人は、計算で仮になり出口へ出ない（作り物の値だけ）。

根: 部品の行の数量に使う語が空・仮だと、芯/計算 は数量 0 と読んで行を出さず、その行の名に付けた仮の理由が帳のどの項目にも
載らずに捨てられていた＝集計の問いの答え待ちの語が黙って 0 になり、人が「確認済」で出口へ出た。
注入: 日・分・回 の語を空・仮にした行（割増の基礎＝入る の日の行など）を持つ人が、仮になり関所で外れることを見る。
同じ語が確定の 0 なら今までどおり確認済（行を出さないだけで仮にしない）。
行の語が月の数字に無い時に「黙って 0 にしない」かを決める条件の語（夜勤の回数・総労働・出勤日数）が空・仮の形も見る。
"""
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "計算"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from 作る_計算 import 人, 決まり, 月の数字, 置き場  # noqa: E402

from 出口 import 関所  # noqa: E402
from 芯.計算 import 計算する  # noqa: E402

鍵 = ("2027-02", "C1", "0001")


def _回す(tmp, 語, 値, 状態, 単価の元="固定の額"):
    行 = [*決まり()["項目.行"], {"名": "作り物の手当", "支給か控除": "支給", "単価の元": 単価の元, "額": "500",
                                "数量の元": f"勤怠の数:{語}", "割増の基礎": "入る"}]
    月 = [r for r in 月の数字() if r["項目"] != 語]
    月.append({"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "項目": 語, "値": 値, "単位": "", "状態": 状態, "問い": "問9"})
    return 計算する(月, 決まり={鍵[1:]: 決まり(**{"項目.行": 行})}, 人={鍵[1:]: 人()}, 置き場=置き場(tmp))


語たち = [("休日勤務日数（法定）", "固定の額"), ("深夜", "固定の額"), ("夜勤の回数", "回ごとの額")]


@pytest.mark.parametrize("語, 元", 語たち)
def test_空で仮の語を数量に使う人は仮で出口へ出ない(tmp_path, 語, 元):
    r = _回す(tmp_path, 語, "", "仮", 元)
    assert r["人"][0]["状態"] == "仮"
    v = {x["項目"]: x for x in r["行"]}
    assert v["差引支給額"]["状態"] == "仮"
    assert any(語 in q["何が無いか"] for q in r["問い"]), r["問い"]
    通った = 関所.通す(r["行"], r["人の状態"])
    assert not 通った.行たち and 通った.外した人の鍵() == {鍵}


@pytest.mark.parametrize("語, 元", 語たち)
def test_確定の0なら行を出さず確認済のまま(tmp_path, 語, 元):
    r = _回す(tmp_path, 語, "0", "確定", 元)
    assert r["人"][0]["状態"] == "確認済"
    assert "作り物の手当" not in {x["項目"] for x in r["行"]}


def test_帳に載らない項目の理由も人の最後の額が受ける(tmp_path):
    # 仕組みの見張り: 理由を付けた名の項目が帳に無くても理由は捨てない（_理由を項目へ の 1 か所）
    from 芯.計算.支給控除 import 一人
    from 芯.計算.形 import 数, 理由
    from 芯.計算 import 要る値
    値たち, 事前 = 要る値.確かめる({**決まり(), **人()}, ())
    x = 一人(鍵[0], 値たち, {r["項目"]: (数(r["値"]), "確定", "") for r in 月の数字()}, {}, 置き場(tmp_path), 事前)
    x._仮("帳に無い項目", 理由("作り物の理由", "0"))
    帳 = x.計算()
    assert "帳に無い項目" not in 帳.項目
    assert any(r.何が無いか == "作り物の理由" for r in 帳.項目["差引支給額"].理由たち)


# 行の語が月の数字に無い時に「黙って 0 にしない」かを決める条件の語（夜勤の回数・総労働・出勤日数）が空・仮の形
条件の語たち = [("夜勤の日を除く所定内", "夜勤の回数"), ("曜日の時間:月", "総労働"), ("在宅の日数", "出勤日数")]


@pytest.mark.parametrize("行の語, 条件の語", 条件の語たち)
def test_行の語が無く条件の語が空で仮なら仮で出口へ出ない(tmp_path, 行の語, 条件の語):
    行 = [*決まり()["項目.行"], {"名": "作り物の手当", "支給か控除": "支給", "単価の元": "固定の額", "額": "500",
                                "数量の元": f"勤怠の数:{行の語}"}]
    月 = [x for x in 月の数字() if x["項目"] not in (行の語, 条件の語)]
    月.append({"支給月": 鍵[0], "会社": 鍵[1], "NO": 鍵[2], "項目": 条件の語, "値": "", "単位": "", "状態": "仮", "問い": "問9"})
    r = 計算する(月, 決まり={鍵[1:]: 決まり(**{"項目.行": 行})}, 人={鍵[1:]: 人()}, 置き場=置き場(tmp_path))
    assert r["人"][0]["状態"] == "仮"
    assert any(条件の語 in q["何が無いか"] for q in r["問い"]), r["問い"]
    assert not 関所.通す(r["行"], r["人の状態"]).行たち
