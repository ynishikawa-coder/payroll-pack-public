def _要約の列(o):
    rows = o.シート["台帳_2026"]["読んだままの勤怠"]
    return [(r["休憩の合計"], r["労働の合計"]) for r in (dict(zip(rows[0], v)) for v in rows[1:])]


def test_寄せは前の寄せが書いた違う要約を芯の数えへ直す():
    for 表, 期待 in (("12:00〜13:00", "1:00"), ("6:00超45分、8:00超60分", "1:00")):
        o = _今の版の会社(表)
        前 = copy.deepcopy(o.シート)
        記 = 当てる.記録()
        勤怠の要約.当てる(o, 記)
        assert _要約の列(o) == [(期待, "9:14"), (期待, "9:14"), ("", "")]
        assert any("芯の数えで書いた" in x and "直した 4" in x and "空にした 1" in x for x in 記.知らせ), 記.知らせ
        assert 記.数["捨てた（直しの持たない）"] == 1
        # 写しの 2 列のほかは変わらない
        h = o.シート["台帳_2026"]["読んだままの勤怠"][0]
        for a, b in zip(前["台帳_2026"]["読んだままの勤怠"][1:], o.シート["台帳_2026"]["読んだままの勤怠"][1:]):
            assert [x for c, x in zip(h, a) if c not in 勤怠の要約.列たち] == [x for c, x in zip(h, b) if c not in 勤怠の要約.列たち]
        # 何度当てても同じ
        記2 = 当てる.記録()
        勤怠の要約.当てる(o, 記2)
        assert _要約の列(o) == [(期待, "9:14"), (期待, "9:14"), ("", "")] and not 記2.当てた


