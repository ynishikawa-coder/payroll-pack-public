def _区(d, 番号, 始め, 終わり, 種別="労働"):
    return {k: v for k, v in 区(d, 番号, 始め, 終わり, 種別).items() if k != "勤怠の表記"}   # 勤怠の区間 のタブの列だけ


def _写し(A, B, 決):
    x = 数える(A, B, 決)
    o = 形.勤怠の表たち(確定=False, 勤怠=A, 勤怠の区間=B, 日の要約=x["日の要約"])["読んだままの勤怠"]
    return [(r["休憩の合計"], r["労働の合計"]) for r in (dict(zip(o[0], v)) for v in o[1:])], x


def test_休憩の区間の無い会社でも休憩を拾い芯の総労働と合う():
    """お客さんで起きた形: 1 日 1 組の打刻（休憩は区間に無い）。前は 0:00 と 10:44 が出た。"""
    A = [日("2026-11-02"), 日("2026-11-03")]
    B = [_区("2026-11-02", 1, "8:30", "19:14"), _区("2026-11-03", 1, "9:00", "18:00")]
    for 決 in (既定の決まり(**表で), 既定の決まり(**長さで), 既定の決まり()):
        写し, x = _写し(A, B, 決)
        # 始業前の 30 分は所定の始業から数える（芯の決まりの既定）・休憩 60 分は表／長さ／法の長さで引く
        assert 写し == [("1:00", "9:14"), ("1:00", "8:00")]
        assert sum(形._分(労) for _, 労 in 写し) == 一つ(x, "総労働")


def test_組の間の空き_時刻の無い休憩_打刻抜け_休日():
    A = [日("2026-11-02"), 日("2026-11-03", 時刻の無い休憩="45", 時刻の無い労働時間="540"), 日("2026-11-04"),
         日("2026-11-07", "休日"), 日("2026-11-05")]
    B = [_区("2026-11-02", 1, "9:00", "12:00"), _区("2026-11-02", 2, "13:00", "18:00"),   # 組の間の 1 時間が休憩（実績）
         _区("2026-11-04", 1, "9:00", ""),                                               # 打刻抜け＝芯は終業で見当＝空
         _区("2026-11-05", 1, "9:00", "18:00"), _区("2026-11-05", 2, "12:00", "12:45", "休憩"),
         _区("2026-11-05", 3, "15:00", "15:15", "外出")]                                  # 外出は休憩に入れず労働から引く
    写し, x = _写し(A, B, 既定の決まり())
    # 時刻の無い労働時間は休憩を引く前の長さ（芯の読み）＝540−45。前の写しは 9:00 と出した
    assert 写し == [("1:00", "8:00"), ("0:45", "8:15"), ("", ""), ("", ""), ("0:45", "8:00")]


