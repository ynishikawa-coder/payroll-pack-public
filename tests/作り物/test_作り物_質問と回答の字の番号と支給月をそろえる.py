"""回帰の見張り: 事務所の 質問と回答 を寄せる口（道具/寄せ/質問と回答.py）が、問いの番号の列の外に残る前の形も型へそろえる。

前は口が 問いの番号 の列だけを読み替え、次の 2 つが寄せた後も前の形のまま残った（2026-11-19 に事務所の表で知らせが出た類）:
  1. 文の中でこの表の問いを指す番号の前の形（回答の「出し直し→Q2099.11-02」・理由の「聞き直し: Q2099.11-01」）
  2. 支給月の欄の前の形（例 2099.11。型は YYYY.MM支給）
- 1 は、問いの番号の列に当てるのと同じ事務所の読み替えを、この表の問いを指す書き方の番号にだけ当てる（読み替えの中身はパックに置かない）。
  ほかの欄の文の中の番号（質問の「作り物の他社（Q2099.11-05）」）は他の表の問いを指す＝変えない・止めない。読み替えるとこの表の別の
  問いと同じ字になる他社の参照（作り物の他社（Q2099.11-02）→ この表の Q209911-02）も変えない（取り違えを作らない）。
- 2 は、型の列の意味が YYYY.MM支給 の列に、寄せの 値をそろえる（形 支給月）を型の作りとして当てる（どの事務所にも同じ）。
- 既に型の 26 列へ寄せた表に残った物も、同じ口を回し直せばそろう（2 回目は書く手順 0）。
- そろえられない字（読み替えに無い前の形の番号・支給月に読めない字）は書かずに止めて名指しする（何も消さない）。
作り物だけ（作り物の年 2099・作り物の文）。
"""
import copy
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根 / "道具" / "寄せ"))
import 質問と回答  # noqa: E402
import 当てる  # noqa: E402

型の口 = 当てる.型の口
ファイル = "00_事務所/質問と回答"
見出し = ["問いの番号", "支給月", "聞いた日", "誰に", "誰が聞いた", "質問", "理由", "回答", "回答日"]
前の形の表 = [
    見出し,
    ["Q2099.11-01", "2099.11", "2099-10-20", "事務所", "AI", "作り物の委託の割増の率は 0 でよいですか\n根拠: 作り物の他社（Q2099.11-05）",
     "書いてない", "出し直し→Q2099.12-01", ""],
    ["Q2099.11-02", "2099.11", "2099-10-20", "事務所", "AI", "作り物の別の会社も同じ率ですか（作り物の他社の Q2099.11-02・Q2099.11-01）",
     "聞き直し: Q2099.11-01・作り物の訳", "0 でよい（作り物の他社 Q2099.11-05 と同じ）", "2099-10-22"],
    ["Q2099.12-01", "2099.12支給", "2099-11-20", "事務所", "AI", "作り物の深夜の割増は 25% でよいですか（Q2099.11-01 の組み直し）", "",
     "出し直し→Q2099.12-02・出し直し→Q2099.11-02", ""],
]
# 事務所の寄せの記録に置く「前の形の読み替え」の作り物（問いの番号の列への読み替えだけ）
読み替え = [
    {"する": "値の語を読み替える", "ファイル": ファイル, "タブ": "質問", "列": "問いの番号", "前": "Q2099.11-", "後": "Q209911-", "合わせ": "頭"},
    {"する": "値の語を読み替える", "ファイル": ファイル, "タブ": "質問", "列": "問いの番号", "前": "Q2099.12-", "後": "Q209912-", "合わせ": "頭"},
]


def _列(rows, 名):
    i = rows[0].index(名)
    return [r[i] for r in rows[1:]]


def test_支給月の列は型の列の意味から読む():
    assert 質問と回答.支給月の列 == ["支給月"]
    assert any(op["する"] == "値をそろえる" and op["列"] == "支給月" and op["形"] == "支給月" for op in 質問と回答.型の作り())


def test_字の中の前の番号と支給月の前の形を型へそろえる():
    r = 質問と回答.寄せる(copy.deepcopy(前の形の表), 読み替え)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    後 = r["寄せた後の値"]
    assert 後[0] == 型の口.見出し("質問と回答", "質問")
    assert _列(後, "問いの番号") == ["Q209911-01", "Q209911-02", "Q209912-01"]
    assert _列(後, "回答") == ["出し直し→Q209912-01", "0 でよい（作り物の他社 Q2099.11-05 と同じ）",
                              "出し直し→Q209912-02・出し直し→Q209911-02"]   # この表を指す番号だけ・ほかの字は変えない
    assert _列(後, "理由") == ["書いてない", "聞き直し: Q209911-01・作り物の訳", ""]
    assert _列(後, "質問") == _列(前の形の表, "質問")   # 他の表を指す番号（この表の番号と同じ字になる物も）は変えない
    assert _列(後, "支給月") == ["2099.11支給", "2099.11支給", "2099.12支給"]
    assert 質問と回答.字の中の前の番号(後) == []
    assert 質問と回答._値の数(後) == 質問と回答._値の数(前の形の表) + 3   # 足したのは 会社 の 3 つだけ（字を替えても数は同じ）
    again = 質問と回答.寄せる(後, 読み替え)
    assert again["寄せられない物"] == [] and again["書く手順"] == []


def test_既に型の列へ寄せた表に残った前の形も_口を回し直せばそろう():
    """問いの番号は今の形・回答と支給月に前の形が残る表（前の口で寄せた後の形）。"""
    型の表 = 質問と回答.寄せる(copy.deepcopy(前の形の表), 読み替え)["寄せた後の値"]
    残り = copy.deepcopy(型の表)
    残り[2][残り[0].index("回答")] = "出し直し→Q2099.11-01"
    残り[1][残り[0].index("支給月")] = "2099.11"
    r = 質問と回答.寄せる(残り, 読み替え)
    assert r["寄せられない物"] == []
    後 = r["寄せた後の値"]
    assert 後[2][後[0].index("回答")] == "出し直し→Q209911-01" and 後[1][後[0].index("支給月")] == "2099.11支給"
    (書く,) = r["書く手順"]
    assert 書く["書き方"] == "RAW" and 書く["範囲"] == "A1:Z4"


def test_他の表を指す番号は変えず止めもしない():
    """質問・回答の文の中の他社の番号（前の形のまま・この表の番号と同じ字になる物も）は、読み替えず照らしにも数えない。"""
    r = 質問と回答.寄せる(copy.deepcopy(前の形の表), 読み替え)
    assert r["寄せられない物"] == []
    後 = r["寄せた後の値"]
    assert "作り物の他社（Q2099.11-05）" in 後[1][後[0].index("質問")]
    assert "作り物の他社の Q2099.11-02・Q2099.11-01" in 後[2][後[0].index("質問")]   # 読み替えると この表の Q209911-02 と同じ字になる
    assert "作り物の他社 Q2099.11-05 と同じ" in 後[2][後[0].index("回答")]          # 回答でも 出し直し→ の外は他の表の番号


def test_番号の切れ目でだけ読み替える():
    全体 = [("Q2099.11-01", "Q209911-01", "全体")]
    assert 質問と回答.字の中の番号を読み替える("Q2099.11-01・Q2099.11-012", 全体) == "Q209911-01・Q2099.11-012"
    assert 質問と回答.字の中の番号を読み替える("XQ2099.11-01", 全体) == "XQ2099.11-01"
    丸ごと = [("Q2099.11-", "Q209911-99", "頭で全体")]
    assert 質問と回答.字の中の番号を読み替える("前は Q2099.11-07 です", 丸ごと) == "前は Q209911-99 です"


def test_読み替えに無い字の中の前の番号は止めて名指しする():
    表 = copy.deepcopy(前の形の表)
    表[1][見出し.index("回答")] = "出し直し→Q2098.01-03"   # この表を指すのに読み替えに無い前の形（そろえられない）
    r = 質問と回答.寄せる(表, 読み替え)
    assert r["書く手順"] == [] and r["戻す手順"] == []
    (x,) = r["寄せられない物"]
    assert x["鍵"] == f"{ファイル}/質問/問いの番号" and "Q2098.01-03" in x["中身"] and "回答" in x["中身"]
    assert r["寄せた後の値"] == 表   # 何も書かない・消さない


@pytest.mark.parametrize("字", ["作り物の来月", "2099.13"])
def test_支給月に読めない字は止めて名指しする(字):
    表 = copy.deepcopy(前の形の表)
    表[3][見出し.index("支給月")] = 字
    r = 質問と回答.寄せる(表, 読み替え)
    assert r["書く手順"] == []
    (x,) = r["寄せられない物"]
    assert x["種類"] == "形の合わない値" and 字 in x["中身"] and "支給月" in x["中身"]
    assert r["寄せた後の値"] == 表


def test_支給月に読めない字は事務所の読み替えに足せばそろう():
    表 = copy.deepcopy(前の形の表)
    表[3][見出し.index("支給月")] = "作り物の来月"
    足す = {"する": "値の語を読み替える", "ファイル": ファイル, "タブ": "質問", "列": "支給月", "前": "作り物の来月", "後": "2099.12支給"}
    止まる = 質問と回答.寄せる(copy.deepcopy(表), 読み替え)
    assert "値の語を読み替える" in 止まる["寄せられない物"][0]["選べる答え"][0]
    r = 質問と回答.寄せる(表, 読み替え + [足す])
    assert r["寄せられない物"] == [] and _列(r["寄せた後の値"], "支給月")[2] == "2099.12支給"
