"""時間.月給者の遅れた出勤: 空なら決まりの問いと仮。3 つ目の値（原則引く、会社が認めた日だけ始業から）はこの版では
遅れた日を全部仮にして止める（問いを出さない・答えも印も見ない。答えを戻す口は 2026-11-27 に畳んだ）。人・時刻は作り物。"""
import importlib.util
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))


def _読む(path: Path, 名: str):
    s = importlib.util.spec_from_file_location(名, path)
    m = importlib.util.module_from_spec(s)
    sys.modules[名] = m
    s.loader.exec_module(m)
    return m


照 = _読む(根 / "月次" / "勤怠の照らし.py", "作り物_遅れた出勤_照らし")
設問 = _読む(根 / "初期設定" / "設問.py", "作り物_遅れた出勤_設問")

C, 月 = "作り物の会社", "2099.05支給"
聞く = 照.月ごとに聞く値


def _日(no, 日付, 出, **kw):
    return {"会社": C, "支給月": 月, "NO": no, "氏名": f"作り物{no}", "日付": 日付, "出勤の時刻": 出, "退勤の時刻": "18:00",
            "所定の始業": "9:00", "印": "", "直した訳": "", **kw}


def _決(値=聞く, 形="月給", 猶予="5", 控除="引く"):
    return {"時間.月給者の遅れた出勤": 値, "支払.賃金の形": 形, "時間.遅れた出勤の猶予": 猶予, "欠勤.遅刻早退の控除": 控除}


def _三日():
    return [_日("1", "2099-04-01", "9:20"), _日("1", "2099-04-02", "9:00"), _日("1", "2099-04-03", "9:45"),
            _日("2", "2099-04-01", "10:00")]


def _仮の日(r):
    return {(x["NO"], x["日付"]) for x in r["仮たち"]}


三日の遅れ = {("1", "2099-04-01"), ("1", "2099-04-03"), ("2", "2099-04-01")}


def test_3つ目の値の会社は遅れた日を全部仮にし問いを出さない():
    r = 照.遅れた出勤の問い(_三日(), 人の決まり={"1": _決(), "2": _決()}, 支給月=月, 会社=C)
    assert r["種"] == [] and _仮の日(r) == 三日の遅れ
    m = 設問.まとめる(r["種"], 会社=C, 支給月=月, 今日="2099-05-01", 既にある=[], 読んだ資料=["確定した勤怠"])
    assert m["問い"] == [] and m["差し戻し"] == []


@pytest.mark.parametrize("回答", ["全部控除", "全部始業から扱う", "一部だけ違う", "分からない"])
def test_答えの行と始業から扱いの印が在っても仮は外れない(回答):
    既に = [{"会社": C, "支給月": 月, "何が無いか": f"始業より後の出勤: {x}（3 日・00000000）", "問いの番号": "Q209905-04",
            "回答": 回答, "始業からの日": "1 2099-04-03"} for x in ("2099年5月支給", "2099.05支給")]
    確定 = [{**r, "印": "始業から扱い", "直した訳": "問い:Q209905-04"} for r in _三日()]
    r = 照.遅れた出勤の問い(確定, 人の決まり={"1": _決(), "2": _決()}, 支給月=月, 会社=C, 既にある=既に)
    assert r["種"] == [] and _仮の日(r) == 三日の遅れ


@pytest.mark.parametrize("値", ["引く", "引かない"])
def test_引くか引かないの会社は問いも仮も出さない(値):
    r = 照.遅れた出勤の問い(_三日(), 人の決まり={"1": _決(値), "2": _決(値)}, 支給月=月)
    assert r["種"] == [] and r["日たち"] == [] and r["仮たち"] == []


def test_定時扱いの日と猶予の内の日は仮にしない():
    日 = [_日("1", "2099-04-01", "9:20", 印="定時扱い"), _日("1", "2099-04-02", "9:05"), _日("1", "2099-04-03", "9:06")]
    r = 照.遅れた出勤の問い(日, 人の決まり={"1": _決()}, 支給月=月)
    assert _仮の日(r) == {("1", "2099-04-03")}


def test_月給の人だけ引く会社の時給の人は仮にしない_引く会社なら仮():
    日 = [_日("3", "2099-04-01", "9:30")]
    assert 照.遅れた出勤の問い(日, 人の決まり={"3": _決(形="時給", 控除="月給の人だけ引く")}, 支給月=月)["仮たち"] == []
    assert _仮の日(照.遅れた出勤の問い(日, 人の決まり={"3": _決(形="時給", 控除="引く")}, 支給月=月)) == {("3", "2099-04-01")}


def test_決まりが空なら決まりの問いを出し遅れた日を仮にする():
    r = 照.遅れた出勤の問い(_三日(), 人の決まり={"1": _決(""), "2": _決("")}, 支給月=月)
    assert [s["何が無いか"] for s in r["種"]] == ["時間.月給者の遅れた出勤"]
    assert _仮の日(r) == 三日の遅れ
