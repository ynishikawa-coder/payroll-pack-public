"""回帰の見張り: 古い形の会社の 質問と回答 を今の形へ移す（道具/寄せ/古い形を移す.py・寄せる道具.md §6）。

作り物の会社（作り物の名と数）:
- 古い並び（型の列が欠け・並びが違う・仮の答えの列＝前の名）→ 事務所の読み替え（試験の中だけの作り物）と型の作りで型の見出しになる。
- 見当（仮の答え）のうち、マスタ 会社 の値と同じ物・md の節に見当と出所の番号が在る物だけ 回答 へ写り 反映済み が 済。
- マスタと違う・反映先が台帳・md に出所が無い見当は動かない（残した に訳つき）。
- 既に今の形の会社（1 回目の後）に回すと差 0（2 回回しても同じ）。試しでは書く手順が出ない。
- タブ 質問 と管理表「会社」の行が無ければ足す。型に無い列が残れば止めて何も書かない（全部か無し）。
"""
import copy
import subprocess
import json
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根 / "道具" / "寄せ"))
import 古い形を移す as 移  # noqa: E402
import 当てる  # noqa: E402

F, T = 移.ファイル, 移.タブ
会社 = "作り物の会社"
仮 = "作り物の仮の答え"   # 前の形の列の名（作り物）
見出し = ["問いの番号", "支給月", "質問", "答え", 仮, "反映先", "答えで変わる項目と人"]
古い表 = [
    見出し,
    ["Q209912-01", "2099.12支給", "作り物の締め日は何日ですか", "", "20", "2_マスタ/会社/作り物の締め日", ""],
    ["Q209912-02", "2099.12支給", "作り物の深夜の率は", "", "25%", "2_マスタ/会社/作り物の深夜の率", ""],
    ["Q209912-03", "2099.12支給", "作り物の手当の決まりは", "", "月 1000 円", "給与のルール.md#作り物の手当", ""],
    ["Q209912-04", "2099.12支給", "作り物の 3 日の出勤は", "", "出勤", "台帳/確定した勤怠", "1"],
    ["Q209912-05", "2099.12支給", "作り物の賞与の月は", "", "7 月", "給与のルール.md#作り物の賞与", ""],
    ["Q209912-06", "2099.12支給", "作り物の答え済み", "はい", "いいえ", "2_マスタ/会社/作り物の締め日", ""],
]
読み替え = [
    {"する": "列の名を変える", "ファイル": F, "タブ": T, "前": "答え", "後": "回答"},
    {"する": "列の名を変える", "ファイル": F, "タブ": T, "前": 仮, "後": "見当"},
]
マスタ = {"会社": [["会社", "項目", "今の値", "適用開始"],
                  [会社, "作り物の締め日", "20", ""],
                  [会社, "作り物の深夜の率", "30%", ""]]}
md = {"給与のルール.md": "# 作り物の決まり\n\n## 作り物の手当\n- 月 1000 円（出所 Q209912-03）\n\n## 作り物の賞与\n- 7 月\n"}
管理表の会社 = [["会社", "組", "型の版", "選んだ部品", "寄せ", "寄せの理由", "最後に配った日", "写しの場所", "初回の確認の OK の日"]]


def _入力(**k):
    d = {"会社": 会社, "組": "作り物の組", "型の版": 3, "質問": copy.deepcopy(古い表), "読み替え": 読み替え,
         "マスタ": マスタ, "md": md, "管理表の会社": copy.deepcopy(管理表の会社), "今日": "2099-11-30"}
    d.update(k)
    return d


def _行(rows, 番号):
    h = rows[0]
    return next(dict(zip(h, r)) for r in rows[1:] if r[h.index("問いの番号")] == 番号)


def test_古い並びが今の並びになり_決まる見当だけ回答へ移る():
    r = 移.移す(_入力(), 書く=True)
    assert r["寄せられない物"] == []
    後 = r["後の値"]["質問"]
    assert 後[0] == 移.型の見出し
    assert all(c == 会社 for c in (row[0] for row in 後[1:]))
    q1, q3 = _行(後, "Q209912-01"), _行(後, "Q209912-03")
    assert (q1["回答"], q1["反映済み"], q1["回答日"]) == ("20", 移.済, "2099-11-30")
    assert (q3["回答"], q3["反映済み"]) == ("月 1000 円", 移.済)
    for n in ("Q209912-02", "Q209912-04", "Q209912-05"):   # マスタと違う・台帳の先・md に出所が無い
        q = _行(後, n)
        assert (q["回答"], q["反映済み"]) == ("", ""), n
    q6 = _行(後, "Q209912-06")   # 答え済みは上書きしない
    assert (q6["回答"], q6["見当"]) == ("はい", "いいえ")
    assert {x["問いの番号"] for x in r["残した"]} == {"Q209912-02", "Q209912-04", "Q209912-05"}
    何 = [x["何"] for x in r["差"]]
    assert 何.count("見当を回答へ") == 2 and "列の並び" in 何 and "管理表の行を足す" in 何
    する = [x["する"] for x in r["書く手順"]]
    assert する == ["値を書く", "行を足す"]
    assert r["書く手順"][1]["値"][:3] == [会社, "作り物の組", "3"]


def test_試しでは書く手順が出ない():
    r = 移.移す(_入力())
    assert r["試し"] and r["書く手順"] == [] and r["戻す手順"] == []
    assert r["差"] == 移.移す(_入力(), 書く=True)["差"]


def test_今の形の会社に回すと何も変わらない():
    一 = 移.移す(_入力(), 書く=True)
    二 = 移.移す(_入力(質問=一["後の値"]["質問"], 読み替え=[], 管理表の会社=一["後の値"]["管理表の会社"]), 書く=True)
    assert 二["寄せられない物"] == [] and 二["差"] == [] and 二["書く手順"] == []
    assert 二["後の値"]["質問"] == 一["後の値"]["質問"]


def test_タブが無ければ足す():
    r = 移.移す(_入力(質問=None, 読み替え=[]), 書く=True)
    assert r["書く手順"][0] == {"する": "タブを足す", "ファイル": F, "タブ": T, "見出し": 移.型の見出し}
    assert r["後の値"]["質問"] == [移.型の見出し]


def test_型に無い列が残れば止めて何も書かない():
    r = 移.移す(_入力(読み替え=読み替え[:1]), 書く=True)   # 仮の答えの列の行き先を言わない
    assert any(x["種類"] == "行き先の無い列" for x in r["寄せられない物"])
    assert r["書く手順"] == [] and r["差"] == []
    assert r["後の値"]["質問"] == 当てる.そろえる(古い表)


def test_管理表の行に型の版が無ければ止める():
    r = 移.移す(_入力(型の版=None), 書く=True)
    assert r["寄せられない物"] and r["書く手順"] == []


def test_呼び口は既定が試し(tmp_path):
    p = tmp_path / "入力.json"
    p.write_text(json.dumps(_入力(), ensure_ascii=False), encoding="utf-8")
    c = subprocess.run([sys.executable, str(根 / "道具" / "寄せ" / "古い形を移す.py"), "--入力", str(p)],
                       capture_output=True, text=True, encoding="utf-8")
    assert c.returncode == 0, c.stderr
    assert json.loads(c.stdout)["書く手順"] == []
