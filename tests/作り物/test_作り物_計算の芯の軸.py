# ---- 時間.月給者の遅れた出勤 の第 3 の値は芯で「引く」と同じ額にし、止める線の人は遅れの有無によらず仮（この版は扱わない） ----
def test_遅れた出勤の原則引くは引くと同じ額で止める線の人を全員仮にする(tmp_path):
    def 回(語):
        d = tmp_path / 語
        d.mkdir()
        r = 計.回す(d, 決=計.決まり(**{"時間.月給者の遅れた出勤": 語}), 上書き={"遅刻早退": "90"})
        return r, 計.値たち(r)
    _, 引かない = 回("引かない")
    r引く, 引く = 回("引く")
    r, 原則 = 回("原則引く、会社が認めた日だけ始業から")
    assert r引く["人"][0]["状態"] != "仮" and r["人"][0]["状態"] == "仮"
    assert 引く["遅刻早退控除"] > 0 and 原則["遅刻早退控除"] == 引く["遅刻早退控除"] != 引かない["遅刻早退控除"]
    d = tmp_path / "遅れ無し"
    d.mkdir()
    r0 = 計.回す(d, 決=計.決まり(**{"時間.月給者の遅れた出勤": "原則引く、会社が認めた日だけ始業から"}), 上書き={"遅刻早退": "0"})
    # 月の遅刻早退が 0 でも仮（遅れて来て終業後まで働いた日・印 始業から扱い の日は月の数が 0 になる＝月の数で見分けない）
    assert r0["人"][0]["状態"] == "仮"
    # 月の所定時間で頭打ちし控除が 0 に削れる人も、勤怠に遅刻早退が在れば仮（削れた値で判定しない）
    d = tmp_path / "頭打ち"
    d.mkdir()
    頭打ち = {"欠勤.遅刻早退の数え方": "日々の不足（月の所定時間−総労働で頭打ち）", "時間.月給者の遅れた出勤": "原則引く、会社が認めた日だけ始業から"}
    r1 = 計.回す(d, 決=計.決まり(**頭打ち), 上書き={"遅刻早退": "90", "欠勤": "0", "出勤日数": "20", "総労働": "12000"})
    assert 計.値たち(r1)["遅刻早退控除"] == 0 and r1["人"][0]["状態"] == "仮"


