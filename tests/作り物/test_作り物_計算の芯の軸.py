# ---- 割増.時間外の基礎の行 は軸3 の差額を通る（行に 1.0 倍の分・手当には 法の額−載せた額） ----
def test_時間外の基礎の行は軸3の差額で手当の残りを出す(tmp_path, monkeypatch):
    def 回(名):
        d = tmp_path / 名
        d.mkdir()
        return 計.値たち(計.回す(d, 決=計.決まり(**{"割増.時間外の基礎の行": "基本給"}),
                               上書き={"法定外残業": "4800", "60 時間超": "1200"}))
    正 = 回("正")
    法 = 計.値たち(計.回す(tmp_path, 上書き={"法定外残業": "4800", "60 時間超": "1200"}))
    載せた = 正["基本給"] - 法["基本給"]
    assert 載せた > 0 and 正["時間外手当"] + 正["60時間超手当"] + 載せた == 法["時間外手当"] + 法["60時間超手当"]
