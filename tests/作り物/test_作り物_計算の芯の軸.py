# ---- 件 7 を 計算する から（固定残業（額で）が時間外・休日・深夜を覆う） ----
def _固定を回す(tmp, 対象, 額="30000"):
    d = tmp / str(len(list(tmp.iterdir())))
    d.mkdir()
    決 = 計.決まり(**{"割増.固定残業": {"形": "額で", "額": 額}, "割増.固定残業の対象": 対象})
    r = 計.回す(d, 決=決, 上書き={"法定外残業": "600", "深夜": "120", "法定休日": "480", "所定休日": "0"})
    return {x["項目"]: x for x in r["行"]}


def test_件7_固定残業が休日と深夜も覆うと不足だけを払う(tmp_path):
    前 = _固定を回す(tmp_path, "時間外")                       # 今の既定: 時間外だけを覆う
    法 = {k: 前[k]["値"] for k in ("休日手当", "深夜手当")}
    全 = _固定を回す(tmp_path, "時間外", 額="0")["時間外手当"]["値"]   # 覆わない時の時間外の法の額
    後 = _固定を回す(tmp_path, "時間外・休日・深夜")
    払う = sum(後[k]["値"] for k in ("時間外手当", "休日手当", "深夜手当"))
    assert abs(払う - max(0, 全 + 法["休日手当"] + 法["深夜手当"] - 30000)) <= 2   # 3 つの和から固定額を引いた不足だけ（端数は項目ごと）
    assert all(後[k]["状態"] != "仮" for k in ("時間外手当", "休日手当", "深夜手当"))
    assert 後["時間外手当"]["値"] == 0 and 払う < 前["時間外手当"]["値"] + 法["休日手当"] + 法["深夜手当"]
    assert 前["時間外手当"]["値"] == max(0, 全 - 30000)             # 既定（時間外だけ）は前の振る舞いのまま


