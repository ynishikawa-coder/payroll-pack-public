def 区(日, 種類, 始め, 終わり, 区分="法定外", 曜日="月"):
    h = lambda s: int(s.split(":")[0]) * 60 + int(s.split(":")[1])  # noqa: E731
    return {"日": 日, "日の種類": 種類, "曜日": 曜日, "始め": h(始め), "終わり": h(終わり), "法の区分": 区分}


