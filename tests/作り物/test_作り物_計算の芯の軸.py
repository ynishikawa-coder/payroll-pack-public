def _日給を回す(tmp, 支給月, 所定=曜日の所定, 行=日給の行, 単価=None, 額=None):
    d = tmp / str(len(list(tmp.iterdir())))
    d.mkdir()
    決 = 計.決まり(**{"支払.賃金の形": "日給", "時間.日の所定": 所定, "項目.行": 行,
                    "時間.暦": {"休みの曜日": ["日"], "祝日": "出勤", "会社の休み": []}, **({"項目.単価": 単価} if 単価 else {})})
    return 計.回す(d, 支給月=支給月, 決=決, 人の値=計.人(**{"項目.人の額": 額 or {"日給": "12000"}}),
                 上書き={"法定内残業": "0", "法定外残業": "600", "深夜": "0", "遅刻早退": "0"})


def _行(結果, 名):
    return next(r for r in 結果["行"] if r["項目"] == 名)


@pytest.mark.parametrize("支給月", ["2027-02", "2027-03", "2027-08"])   # 期間の終わりが 日・水・土（土は所定 5）の月
def test_件4_日給の割増の単価は期間の終わりの曜日で変わらない(tmp_path, 支給月):
    r = _行(_日給を回す(tmp_path, 支給月), "時間外手当")
    assert r["値"] == 1600 * 10 * 1.25 == 20000          # 期間[1] の曜日の所定なら 土＝5h で 30,000・日＝無くて仮
    assert r["状態"] != "仮"


