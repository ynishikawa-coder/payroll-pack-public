"""回帰の見張り: 有給.出勤時間に足す の範囲（月給の人だけ足す・時給の人だけ足す）を芯が賃金の形で分ける。作り物の値だけ。"""
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
if str(根) not in sys.path:
    sys.path.insert(0, str(根))

from 芯.集計.形 import 決まり, 形の誤り  # noqa: E402
from 芯.集計.日 import 有給を足すか  # noqa: E402


def test_芯は賃金の形で足すかを分け_人の値が会社に勝つ値をそのまま読む():
    def 足す(値, 形):
        return 有給を足すか(決まり({"有給.出勤時間に足す": 値, "支払.賃金の形": 形}), None)
    assert 足す("足す", "時給") and not 足す("足さない", "月給") and not 足す(None, "月給")
    assert 足す("月給の人だけ足す", "月給") and 足す("月給の人だけ足す", "日給月給") and 足す("月給の人だけ足す", "年俸")
    assert not 足す("月給の人だけ足す", "時給") and not 足す("月給の人だけ足す", "日給")
    assert 足す("時給の人だけ足す", "時給") and not 足す("時給の人だけ足す", "月給")
    # 選べる値の外の字（ときどき）は 一人を集計する の最初に 芯/設定 が照らす（使う所で照らさない＝仮は 集計 の試験で見る）
    from 芯 import 設定
    assert not 設定.選べる値の字か("有給.出勤時間に足す", "ときどき")
    try:
        足す("月給の人だけ足す", None)
    except 形の誤り:
        pass
    else:
        raise AssertionError("賃金の形が空でも足すかが決まった")


def test_有給の日の時間外の判定が月給の人だけ足すで分かれる():
    sys.path.insert(0, str(根 / "tests" / "集計"))
    import 作る_集計 as 作
    from 芯.集計 import 集計する
    # 午後半休（年休 4 時間）の日に 9:00〜12:00・13:00〜19:00 の 9 時間働いた: 足す なら日の線から有給の 4 時間を引き、時間外が増える
    上書き = {"2026-11-02": (作.日("2026-11-02", 休暇の種類="年休", 休暇の単位="午後半休", 休暇の時間="240"),
                             [作.区("2026-11-02", 1, "9:00", "12:00"), 作.区("2026-11-02", 2, "13:00", "19:00")])}
    A, B = 作.月(上書き=上書き)

    def 時間外(値, 形):
        決 = {("作り物の会社", "1"): {"時間.日の所定": "8", "時間.週の所定": "40", "有給.出勤時間に足す": 値, "支払.賃金の形": 形}}
        r = 集計する(A, B, 決まり=決, 法の線=作.法の線)
        return {x["項目"]: x["値"] for x in r["行"]}
    月給, 時給 = 時間外("月給の人だけ足す", "月給"), 時間外("月給の人だけ足す", "時給")
    assert 月給 == 時間外("足す", "月給") and 時給 == 時間外("足さない", "時給")
    assert 月給 != 時給
