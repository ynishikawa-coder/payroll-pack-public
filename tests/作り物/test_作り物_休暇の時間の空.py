"""見張り: 休暇の単位＝時間 なのに 休暇の時間 が空の日は、黙って 0 分にせず仮（作り物の値だけ）。

根: 必要な数が空だと 芯/集計 が黙って 0 分と読み、休んだ分の無い日（遅刻早退・年休の時間 0）として確定に見えていた。
注入: 勤務の日・休暇の日のどちらに空を入れても、その人が仮になり問いが 1 つ出ることを見る。時間が書かれていれば仮にしない。
"""
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "集計"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

import 作る_集計 as 集  # noqa: E402

D = "2026-11-04"
訳 = "休暇の単位＝時間 なのに 休暇の時間 が空"


def _数える(種類, 時間, 区間):
    A, B = 集.月(上書き={D: (集.日(D, 種類, 休暇の種類="年休", 休暇の単位="時間", 休暇の時間=時間), 区間)})
    return 集.数える(A, B)


def _問い(x):
    return [q["何が無いか"] for q in x["問い"] if 訳 in q["何が無いか"]]


@pytest.mark.parametrize("種類, 区間", [("勤務", [集.区(D, 1, "11:00", "18:00")]), ("休暇", [])])
def test_休暇の時間が空なら仮で問いは1つ(種類, 区間):
    x = _数える(種類, "", 区間)
    assert x["人"][0]["状態"] == "仮"
    assert {r["状態"] for r in x["行"] if r["項目"] in ("総労働", "遅刻早退", "年休（時間）", "年休の時間")} <= {"仮"}
    assert len(_問い(x)) == 1, x["問い"]


@pytest.mark.parametrize("種類, 区間", [("勤務", [集.区(D, 1, "11:00", "18:00")]), ("休暇", [])])
def test_休暇の時間が書かれていれば仮にしない(種類, 区間):
    x = _数える(種類, "120", 区間)
    assert _問い(x) == []
    assert 集.値(x, "年休（時間）") == [120]
