"""見張り: マスタに書けなかった 2 つの会社の決まりを項目にした（型の版 23・作り物の値と一般の語だけ）。

根治の D＝誤りの類をわざと入れて、仕組みが拒む（仮にして出口へ出さない）か、決まりどおりに数えることを示す。
1. 休憩の退勤の境が性別で分かれる（`退勤19:45超15分（女）`）: 人.性別 で境を選ぶ。境の 1 分前・ちょうど・1 分後で分かれる。
   性別で分かれた境があるのに 人.性別 が空・外の字の人は、黙ってどちらかの境で数えず仮。（…）が区分でも性別でもない字は表の外で仮。
2. 終業前の退勤（`時間.終業前の退勤`＝所定の終業まで）: 所定の終業より前の退勤を所定の終業の退勤とみなし早退にしない。
   表 A の印 `早退` の日・休暇の分のある日は延ばさない。始業前から数えた日は所定の長さを超えて延ばさない。
   休憩の退勤の境はみなした退勤で引く。既定（空）は打刻のまま。
3. 終業前の退勤＝`所定の終業まで（休憩は実の退勤で）`: 労働は所定の終業まで延ばし、休憩だけを実の退勤で引く（退勤の境・時間帯・
   長さの 3 つの休憩の形のどれも、延ばした所に掛かる休憩を引かない）。所定の終業まで・打刻のまま と 1 日で見分けられる。
"""
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
for p in (根, 根 / "tests" / "集計"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from 芯 import 設定  # noqa: E402
import 作る_集計 as 集  # noqa: E402

D = "2026-11-04"
# 作り物の会社の表: 夜の休憩の境が男女で 30 分ずれ、夜ごはんの境は共通
表 = "退勤10:45超15分（男）、退勤11:15超15分（女）、退勤13:30超45分、退勤19:15超15分（男性）、退勤19:45超15分（女性）、退勤20:14超15分"


def _日(出勤, 退勤, 印="", **決まり):
    A, B = 集.月(上書き={D: (集.日(D, 印=印), [集.区(D, 1, 出勤, 退勤)])})
    x = 集.数える(A, B, 集.既定の決まり(**{"時間.休憩の表": 表, "時間.所定の始業": 出勤, "時間.所定の終業": "16:15", **決まり}))
    (y,) = [r for r in x["日の要約"] if r["日付"] == D]
    return y, x


def _仮の訳(x):
    return [q["何が無いか"] for q in x["問い"]]


# ---- 1 性別で分かれる退勤の境 ----

@pytest.mark.parametrize("性別, 退勤, 休憩", [
    ("男", "10:45", 0), ("男", "10:46", 15), ("女", "10:46", 0), ("女", "11:15", 0), ("女", "11:16", 15),
    ("男", "19:15", 60), ("男", "19:16", 75), ("女", "19:45", 60), ("女", "19:46", 75),
    ("男", "20:14", 75), ("男", "20:15", 90), ("女", "20:15", 90),
    ("男性", "19:16", 75), ("女性", "19:16", 60),   # 揺れは読む時にそろえる
])
def test_性別の境は1分前とちょうどと1分後で分かれる(性別, 退勤, 休憩):
    y, x = _日("7:00", 退勤, **{"人.性別": 性別})
    assert y["休憩"] == 休憩, (性別, 退勤, y)
    assert x["人"][0]["状態"] == "確認済"


def test_境の休憩が無ければ働いた時間はそのまま():
    # 7:00〜10:30 は朝の境（10:46）の前＝休憩を引かない（時間帯の重なりで 10:00〜10:15 を引かない）
    y, _ = _日("7:00", "10:30", **{"人.性別": "男"})
    assert (y["休憩"], y["労働"]) == (0, 210)


@pytest.mark.parametrize("性別", ["", "作り物の外の字"])
def test_性別が無い人は性別の境で黙って数えず仮(性別):
    y, x = _日("7:00", "19:30", **({"人.性別": 性別} if 性別 else {}))
    assert x["人"][0]["状態"] == "仮"
    assert {r["状態"] for r in x["行"] if r["項目"] in ("総労働", "法定外残業")} == {"仮"}
    assert any("人.性別" in t for t in _仮の訳(x)), _仮の訳(x)


def test_性別で分かれない表は性別が無くても仮にしない():
    A, B = 集.月(上書き={D: (集.日(D), [集.区(D, 1, "9:00", "18:30")])})
    x = 集.数える(A, B, 集.既定の決まり(**{"時間.休憩の表": "12:00〜13:00、退勤18:00超30分"}))
    assert x["人"][0]["状態"] == "確認済"


@pytest.mark.parametrize("字", ["退勤19:45超15分（女の人）", "退勤19:45超15分（作り物の外の字）"])
def test_区分でも性別でもない括弧は表の外で仮(字):
    assert not 設定.選べる値の字か("時間.休憩の表", 字)
    A, B = 集.月(上書き={D: (集.日(D), [集.区(D, 1, "9:00", "20:00")])})
    x = 集.数える(A, B, 集.既定の決まり(**{"時間.休憩の表": 字, "人.性別": "女"}))
    assert x["人"][0]["状態"] == "仮"


def test_区分と性別の境は混ぜられる():
    r = 設定.休憩の表を読む("退勤18:00超30分（パート）、退勤19:45超15分（女）")
    assert [(b.区分, b.性別) for b in r["境"]] == [("パート", None), (None, "女")]


# ---- 2 終業前の退勤 ----

def _定時(退勤, 値="所定の終業まで", 印=""):
    # 所定 9:00〜18:15・日の所定 8:00・休憩は退勤の境（女の境の会社）
    return _日("9:00", 退勤, 印=印, **{"人.性別": "女", "時間.所定の終業": "18:15", "時間.終業前の退勤": 値})


@pytest.mark.parametrize("退勤", ["11:05", "16:30", "18:14", "18:15"])
def test_所定の終業までは定時の退勤とみなし早退にしない(退勤):
    y, x = _定時(退勤)
    # 9:00〜18:15 − 朝（女 11:15 超）15・昼 45 ＝ 60 分（夜の境の前）
    assert (y["労働"], y["休憩"]) == (495, 60), y
    assert 集.値(x, "遅刻早退") == [0]
    assert x["人"][0]["状態"] == "確認済"


def test_所定の終業より後の退勤はそのまま():
    y, _ = _定時("19:00")
    assert (y["労働"], y["休憩"]) == (600 - 60, 60)


def test_早退の印の日は延ばさない():
    y, x = _定時("16:30", 印="早退")
    assert (y["労働"], y["休憩"]) == (450 - 60, 60)
    assert 集.値(x, "遅刻早退") == [480 - 390]


@pytest.mark.parametrize("値", ["", "打刻のまま"])
def test_既定は打刻のまま(値):
    y, x = _定時("16:30", 値=値)
    assert y["労働"] == 450 - 60 and 集.値(x, "遅刻早退") == [90]


def test_終業前の退勤の外の字は黙って延ばさない():
    y, x = _定時("16:30", 値="定時にする")
    assert y["労働"] == 450 - 60   # 既定（打刻のまま）で数えて仮
    assert x["人"][0]["状態"] == "仮"
    assert any(t.startswith("時間.終業前の退勤「定時にする」は選べる値の外") for t in _仮の訳(x))


@pytest.mark.parametrize("単位, 時間, 退勤", [("午後半休", "240", "13:00"), ("午前半休", "240", "16:00"), ("時間", "120", "16:00"), ("時間", "", "16:00")])
def test_休暇の分のある日は延ばさない(単位, 時間, 退勤):
    # 休んだ分は休暇で数える＝延ばすと休暇と労働が二重になる（午後半休 9:00〜13:00 が 8 時間の労働に見えない）
    A, B = 集.月(上書き={D: (集.日(D, 休暇の単位=単位, 休暇の時間=時間, 休暇の種類="有給"), [集.区(D, 1, "9:00", 退勤)])})
    x = 集.数える(A, B, 集.既定の決まり(**{"時間.休憩の表": 表, "人.性別": "女", "時間.所定の終業": "18:15",
                                         "時間.終業前の退勤": "所定の終業まで"}))
    (y,) = [r for r in x["日の要約"] if r["日付"] == D]
    延ばさない = _日("9:00", 退勤, **{"人.性別": "女", "時間.所定の終業": "18:15"})[0]
    assert y["労働"] == 延ばさない["労働"] < 480, (y, 延ばさない)


def test_始業より前から数えた日は所定の長さを超えて延ばさない():
    # 始業前の打刻＝打刻のまま で 7:00 出勤・16:00 退勤（所定 9:00〜18:15）: 早出の 2 時間を数えた上で 18:15 まで延ばさない
    y, x = _日("7:00", "16:00", **{"人.性別": "女", "時間.所定の始業": "9:00", "時間.所定の終業": "18:15",
                                   "時間.始業前の打刻": "打刻のまま", "時間.終業前の退勤": "所定の終業まで"})
    assert y["労働"] == 555 - 60   # 7:00〜16:15（所定の始業から終業までの長さ 9:15）− 朝と昼 60 分


# ---- 3 所定の終業まで（休憩は実の退勤で）----

実で = "所定の終業まで（休憩は実の退勤で）"
夕のある表 = 表 + "、退勤16:45超15分（女）"


def _夕(退勤, 値, 印="", **決まり):
    # 所定 9:00〜18:15・女の夕の境 16:45 超（作り物）
    return _日("9:00", 退勤, 印=印, **{"人.性別": "女", "時間.所定の終業": "18:15", "時間.休憩の表": 夕のある表,
                                      "時間.終業前の退勤": 値, **決まり})


@pytest.mark.parametrize("値, 労働, 休憩, 早退", [
    ("所定の終業まで", 555 - 75, 75, 0),   # みなした退勤 18:15 で朝・昼・夕を引く
    (実で, 555 - 60, 60, 0),              # 労働は 18:15 まで・休憩は実の退勤 16:00 で朝・昼だけ
    ("打刻のまま", 420 - 60, 60, 120),     # 労働も休憩も 16:00（早退 2 時間）
])
def test_実の退勤で休憩を引く値は1日でほかの2つと見分けられる(値, 労働, 休憩, 早退):
    y, x = _夕("16:00", 値)
    assert (y["労働"], y["休憩"]) == (労働, 休憩), y
    assert 集.値(x, "遅刻早退") == [早退]
    assert x["人"][0]["状態"] == "確認済"


def test_実の退勤が夕の境を越えた日は夕も引く():
    y, _ = _夕("17:00", 実で)
    assert (y["労働"], y["休憩"]) == (555 - 75, 75)


def test_実の退勤で休憩を引く値も早退の印の日は延ばさない():
    y, x = _夕("16:00", 実で, 印="早退")
    assert (y["労働"], y["休憩"]) == (420 - 60, 60) and 集.値(x, "遅刻早退") == [120]


@pytest.mark.parametrize("値, 労働", [("所定の終業まで", 555 - 75), (実で, 555 - 60)])
def test_時間帯の休憩も実の退勤より後の帯を引かない(値, 労働):
    y, _ = _夕("16:00", 値, **{"時間.休憩の表": "11:00〜11:15、12:00〜12:45、17:00〜17:15"})
    assert y["労働"] == 労働, y


@pytest.mark.parametrize("値, 労働", [("所定の終業まで", 555 - 60), (実で, 555)])
def test_長さの休憩も実の退勤までの長さで決める(値, 労働):
    # 9:00〜14:00（5 時間）の実の労働は休憩が要らない長さ。延ばした 9:15 で長さを決めない
    y, _ = _夕("14:00", 値, **{"時間.休憩の表": "", "時間.休憩の出し方": "長さで",
                             "時間.休憩の長さ": [["6:00", 45], ["8:00", 60]]})
    assert y["労働"] == 労働, y


def test_実の退勤で休憩を引く値は選べる値の表に在る():
    assert 実で in 設定.表()["時間.終業前の退勤"]["選べる値"]
