"""回帰の見張り: 事務所の設定「置き場」を 1 つの (顧客ID, 物) に 1 行の今の形へ移す口（管理表/管理表.py の 置き場の登録を移す・
docs/設計/Drive の型.md §8）。Drive を開かない純な関数。作り物の値だけ（C0001・作り物A・組X・id-根-X など）。

- パ-1: 古い形（物=組の根・会社が空の組の行・台帳の 1 行）→ 会社ごとの 会社の根 の行（同じ ID）・顧客ID・年ごとの台帳の行を書く手順
- パ-2: 同じ (顧客ID, 物) に違う ID → 書く手順は 0 で問いが 1 つ
- パ-3: 会社の一覧に顧客ID が無い・空の行が在る → 拒む（振るのは 事務所の設定を寄せる・事務所に聞かない）
- パ-5: 移した後の表は置き場の検査（型の口.置き場の登録の赤）で緑・二度目は手順 0
"""
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
import 管理表.管理表 as 管理表  # noqa: E402
from 月次 import 台帳へ書く as 書  # noqa: E402

型の口 = 管理表.型の口
版 = 型の口.版()
一覧 = [["顧客ID", "会社", "組", "担当", "状態"], ["C0001", "作り物A", "組X", "", ""], ["C0002", "作り物B", "組X", "", ""]]
古い表 = [["会社", "組", "物", "ID"],
        ["", "組X", "組の根", "id-根-X"],
        ["作り物A", "組X", "2_マスタ", "id-マスタ-X"],
        ["", "組X", 型の口.台帳の名(), "id-台帳-1行"],
        ["作り物A", "組X", "2_マスタ", "id-マスタ-X"]]   # 同じ行の重なりは 1 行に畳む
台帳 = {"組X": {"2026": ["id-台帳-2026"], "2027": ["id-台帳-2027"]}}


def _移す(置き場, 会社の一覧=一覧, 台帳=台帳):
    return 管理表.置き場の登録を移す({"置き場": 置き場, "会社の一覧": 会社の一覧, "型の版": 版, "台帳": 台帳})


def test_パ1_古い形は会社ごと_顧客ID_年ごとの台帳の行を書く手順になる():
    r = _移す(古い表)
    assert r["問い"] == []
    後 = r["後の表"]
    assert 後[0] == ["顧客ID", "会社", "組", "物", "ID"]
    assert sorted(map(tuple, 後[1:])) == sorted([
        ("C0001", "作り物A", "組X", "会社の根", "id-根-X"), ("C0002", "作り物B", "組X", "会社の根", "id-根-X"),
        ("C0001", "作り物A", "組X", "2_マスタ", "id-マスタ-X"),
        ("C0001", "作り物A", "組X", "台帳_2026", "id-台帳-2026"), ("C0002", "作り物B", "組X", "台帳_2026", "id-台帳-2026"),
        ("C0001", "作り物A", "組X", "台帳_2027", "id-台帳-2027"), ("C0002", "作り物B", "組X", "台帳_2027", "id-台帳-2027")])
    [手] = r["手順"]
    assert (手["する"], 手["ファイル"], 手["タブ"], 手["書き方"]) == ("値を書く", 型の口.道("事務所", "事務所の設定"), 型の口.タブの名("事務所の設定", "置き場"), "RAW")
    assert 手["値"] == 後 and 手["範囲"] == f"A1:E{len(後)}"
    [戻] = 書.戻す手順の本体(r["戻す"])
    assert 戻["範囲"] == 手["範囲"]
    # 戻すと前の表（空いた所は空の字で消す）
    assert [[c for c in row[:4]] for row in 戻["値"][:len(古い表)]] == 古い表
    assert all(c == "" for row in 戻["値"][len(古い表):] for c in row)


def test_パ2_同じ顧客IDと物に違うIDは手順0で問い1つ():
    表 = [["顧客ID", "会社", "組", "物", "ID"],
         ["C0001", "作り物A", "組X", "会社の根", "id-根-X"],
         ["C0001", "作り物A", "組X", "会社の根", "id-根-Y"]]
    r = _移す(表)
    assert r["手順"] == [] and r["戻す"] == [] and r["後の表"] is None
    assert len(r["問い"]) == 1 and r["問い"][0]["相手"] == "事務所の担当者"
    assert "C0001" in r["問い"][0]["訳"] and "会社の根" in r["問い"][0]["訳"]


def test_パ3_会社の一覧に顧客IDが無ければ拒み_事務所に聞かない():
    # 顧客ID は仕組みが振る（2026-11-27 の決め・Drive の型 §8「顧客ID を振る」）＝この口は振らず、事務所への問いも返さない
    for 会社の一覧 in ([["会社", "組", "担当", "状態"], ["作り物A", "組X", "", ""]],
                   [["顧客ID", "会社", "組", "担当", "状態"], ["001", "作り物A", "組X", "", ""], ["", "作り物B", "組X", "", ""]]):
        with pytest.raises(管理表.拒む, match="事務所の設定を寄せる"):
            _移す(古い表, 会社の一覧)


def test_台帳の年が決まらなければ問い():
    for 年たち in ({}, {"2026": ["id-a", "id-b"]}, {"26": ["id-a"]}):
        r = _移す(古い表, 台帳={"組X": 年たち})
        assert r["手順"] == [] and r["問い"], 年たち


def test_パ5_移した後の表は置き場の検査で緑で_二度目は手順0():
    r = _移す(古い表)
    assert 型の口.置き場の登録の赤(r["後の表"], 一覧) == []
    二度目 = _移す(r["後の表"])
    assert 二度目["問い"] == [] and 二度目["手順"] == [] and 二度目["戻す"] == []


def test_組が空の行は割り当てず問い():
    # 会社も組も空の置き場の行は、会社の一覧の組が空の会社へ当たってしまう＝問い（置き場・会社の一覧のどちらの空でも）
    表 = [["会社", "組", "物", "ID"], ["", "", "組の根", "id-根-Z"]]
    r = _移す(表)
    assert r["手順"] == [] and r["後の表"] is None and any("組が空" in q["訳"] for q in r["問い"]), r["問い"]
    組の空の一覧 = 一覧 + [["C0003", "作り物C", "", "", ""]]
    r = _移す(表, 組の空の一覧)
    assert r["手順"] == [] and r["後の表"] is None
    assert any(q["所"].endswith("会社の一覧") and "組 が空" in q["訳"] for q in r["問い"]), r["問い"]


def test_型の版が数でなければ拒むで返す():
    import pytest
    for v in ("abc", "", None):
        with pytest.raises(管理表.拒む):
            管理表.置き場の登録を移す({"置き場": 古い表, "会社の一覧": 一覧, "型の版": v, "台帳": 台帳})


def test_型の版が違えば拒む():
    import pytest
    with pytest.raises(Exception):
        管理表.置き場の登録を移す({"置き場": 古い表, "会社の一覧": 一覧, "型の版": 版 - 1, "台帳": 台帳})
