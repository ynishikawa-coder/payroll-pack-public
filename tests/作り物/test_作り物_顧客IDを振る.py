"""回帰の見張り: 顧客ID は仕組みが振る（2026-11-27 オーナーの決め ⟦鍵:給与の初期設定/顧客IDは仕組みが振る⟧・docs/設計/Drive の型.md §8「顧客ID を振る」）。
事務所の段の口 管理表.事務所の設定を寄せる 。Drive を開かない純な関数。
作り物の値だけ（作り物A・組X・id-根-A など）。

- 振-a: 会社の一覧に 顧客ID の列が無い → 列を足し、上の行から 001, 002… を振り、置き場へ写す
- 振-b: 顧客ID が一部だけ在る → 空の行へ次の番号（在る数の一番大きい物 + 1）・在る番号は変えない・数でない字は数えず残す
- 振-c: 止めた会社が在る → 止めた会社の番号も使った数に数える＝二度と使わない・行は残る
- 振-d: 二度当てると手順 0（何度当てても同じ）・戻す手順で前の表へ戻る
"""
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
import 管理表.管理表 as 管理表  # noqa: E402
from 月次 import 台帳へ書く as 書  # noqa: E402

型の口 = 管理表.型の口
版 = 型の口.版()
一覧の型 = 型の口.見出し("事務所の設定", "会社の一覧")
事務所 = 型の口.道("事務所", "事務所の設定")
一覧タブ = 型の口.タブの名("事務所の設定", "会社の一覧")   # 管理表 の手順と後の表は Drive のタブの名（型 39）
置き場タブ = 型の口.タブの名("事務所の設定", "置き場")
古い置き場 = [["会社", "組", "物", "ID"],
          ["作り物A", "組X", "会社の根", "id-根-A"],
          ["作り物B", "組X", "会社の根", "id-根-B"],
          ["作り物C", "組X", "会社の根", "id-根-C"]]


def _寄せる(会社の一覧, 置き場=古い置き場):
    return 管理表.事務所の設定を寄せる({"型の版": 版, "会社の一覧": 会社の一覧, "置き場": 置き場})


def _番号(表) -> dict:
    h = 表[0]
    return {r[h.index("会社")]: r[h.index("顧客ID")] for r in 表[1:]}


def _置き場の番号(表) -> dict:
    h = 表[0]
    return {(r[h.index("会社")], r[h.index("物")]): r[h.index("顧客ID")] for r in 表[1:]}


def test_振a_顧客IDの列が無ければ足して001から振り置き場へ写す():
    一覧 = [["会社", "組", "担当", "状態"], ["作り物A", "組X", "", "毎月"], ["作り物B", "組X", "", "毎月"],
          ["作り物C", "組X", "", "立ち上げ"]]
    r = _寄せる(一覧)
    assert r["問い"] == []
    assert r["後の表"]["会社の一覧"][0] == 一覧の型
    assert _番号(r["後の表"]["会社の一覧"]) == {"作り物A": "001", "作り物B": "002", "作り物C": "003"}
    assert [x["顧客ID"] for x in r["振った"]] == ["001", "002", "003"]
    assert _置き場の番号(r["後の表"]["置き場"]) == {("作り物A", "会社の根"): "001", ("作り物B", "会社の根"): "002",
                                              ("作り物C", "会社の根"): "003"}
    assert {(x["する"], x["ファイル"], x["タブ"], x["書き方"]) for x in r["手順"]} == {
        ("値を書く", 事務所, 一覧タブ, "RAW"), ("値を書く", 事務所, 置き場タブ, "RAW")}
    # 置き場の検査で緑
    assert 型の口.置き場の登録の赤(r["後の表"]["置き場"], r["後の表"]["会社の一覧"]) == []


def test_振b_一部だけ在れば空の行へ次の番号_在る番号と数でない字は変えない():
    一覧 = [一覧の型, ["005", "作り物A", "組X", "", "毎月"], ["", "作り物B", "組X", "", "毎月"],
          ["C0001", "作り物C", "組X", "", "毎月"]]
    r = _寄せる(一覧)
    assert r["問い"] == []
    assert _番号(r["後の表"]["会社の一覧"]) == {"作り物A": "005", "作り物B": "006", "作り物C": "C0001"}
    assert r["振った"] == [{"行": 3, "会社": "作り物B", "顧客ID": "006"}]   # 間の 001〜004 は埋めない


def test_振c_止めた会社の番号は二度と使わない_行も残る():
    一覧 = [一覧の型, ["001", "作り物A", "組X", "", "毎月"], ["002", "作り物B", "組X", "", "止めた"],
          ["", "作り物C", "組X", "", "立ち上げ"]]
    r = _寄せる(一覧)
    後 = r["後の表"]["会社の一覧"]
    assert _番号(後) == {"作り物A": "001", "作り物B": "002", "作り物C": "003"}
    assert ["002", "作り物B", "組X", "", "止めた"] in 後   # 止めた会社の行は番号を持ったまま残る
    # 止めた会社が一番大きい番号を持っていても、新しい会社はその次（止めた番号を使い直さない）
    一覧2 = [一覧の型, ["001", "作り物A", "組X", "", "毎月"], ["007", "作り物B", "組X", "", "止めた"],
           ["", "作り物C", "組X", "", "立ち上げ"]]
    assert _番号(_寄せる(一覧2)["後の表"]["会社の一覧"])["作り物C"] == "008"
    # 置き場にだけ残る番号（会社の一覧から行を消してしまった番号）も使った数に数える
    assert 管理表.次の顧客ID(["001", "002", "", "C0009", "012"]) == "013"
    assert 管理表.次の顧客ID([]) == "001"


def test_振d_二度当てると手順0_戻す手順で前の表へ戻る():
    一覧 = [["会社", "組", "担当", "状態"], ["作り物A", "組X", "", "毎月"], ["作り物B", "組X", "", "止めた"]]
    置き場 = 古い置き場[:3]
    一 = _寄せる(一覧, 置き場)
    二 = _寄せる(一["後の表"]["会社の一覧"], 一["後の表"]["置き場"])
    assert 二["手順"] == [] and 二["戻す"] == [] and 二["問い"] == [] and 二["振った"] == []
    assert 二["後の表"] == 一["後の表"]
    戻す = {x["タブ"]: x["値"] for x in 書.戻す手順の本体(一["戻す"])}
    assert [r[:4] for r in 戻す[一覧タブ][:len(一覧)]] == 一覧
    assert all(c == "" for r in 戻す[一覧タブ] for c in r[4:])
    assert [r[:4] for r in 戻す[置き場タブ][:len(置き場)]] == 置き場
    for タブ in (一覧タブ, 置き場タブ):
        手 = next(x for x in 一["手順"] if x["タブ"] == タブ)
        assert len(戻す[タブ]) == len(手["値"]) and 手["範囲"] == next(
            x for x in 書.戻す手順の本体(一["戻す"]) if x["タブ"] == タブ)["範囲"]


def test_会社が空の行は振らずに問い_型に無い列は拒む():
    r = _寄せる([一覧の型, ["001", "作り物A", "組X", "", ""], ["", "", "組X", "", "毎月"]])
    assert r["手順"] == [] and r["振った"] == [] and len(r["問い"]) == 1 and "3 行目" in r["問い"][0]["訳"]
    with pytest.raises(管理表.拒む, match="型に無い列"):
        _寄せる([一覧の型 + ["作り物の列"], ["001", "作り物A", "組X", "", "", "x"]])
    with pytest.raises(管理表.拒む, match="型の版"):
        管理表.事務所の設定を寄せる({"型の版": 版 - 1, "会社の一覧": [一覧の型], "置き場": []})
