_md = """# 事務所のルール

## 1 給与ソフトと取り込みの形

### 作り物の給与ソフト
- 名: 作り物の給与ソフト
- 文字コード: UTF-8
{足す}
## 2 つぎ
- 何か: 読まない
"""


def test_mdの形の節の知らない鍵は止める():
    assert not 集め.集める(_入力(事務所のルール=_md.format(足す="")))["止める"]
    r = 集め.集める(_入力(事務所のルール=_md.format(足す="- 文字こーど: UTF-8\n")))
    assert r["止める"] and "文字こーど" in r["止めた訳"][0]


def _つなぎ(名):
    return [{"会社": 会社, "NO": "", "側": "出口", "道具": "作り物の給与ソフト", "その道具での名": f"{名}の欄",
             "その道具での番号": f"欄.{名}"}]


def _行(項目, **k):
    return {"会社": 会社, "項目": 項目, "支給か控除": "支給", "給与ソフトの欄": "", "適用開始": "", **k}


@pytest.mark.parametrize("名, 行", [
    ("固定残業手当", _行("固定残業手当", 割増の基礎から除く訳="固定残業手当")),
    ("通勤手当", _行("通勤手当", 課税="通勤の非課税")),
])
def test_つなぎの固定残業と通勤は支給控除の項目の行で引ける(名, 行):
    額で = {"割増.固定残業": "額で"} if 名 == "固定残業手当" else {}
    r = 集め.集める(_入力(つなぎ=_つなぎ(名), 支給控除の項目=[行], 会社の値=額で))
    assert not r["止める"], r["止めた訳"]
    r = 集め.集める(_入力(つなぎ=_つなぎ(名), 支給控除の項目=[], 会社の値=額で))
    assert r["止める"] and any("形が引けない" in x and "④支給控除の項目" in x for x in r["止めた訳"]), r["止めた訳"]


def test_固定残業の額での形と支給控除の項目の行が食い違えば止める():
    行 = _行("固定残業手当", 割増の基礎から除く訳="固定残業手当")
    assert 集め.集める(_入力(会社の値={"割増.固定残業": "額で"}))["止める"]
    assert 集め.集める(_入力(支給控除の項目=[行], 会社の値={"割増.固定残業": "無し"}))["止める"]
    assert not 集め.集める(_入力(支給控除の項目=[行], 会社の値={"割増.固定残業": "額で"}))["止める"]
