def test_読めない週の所定は有給の問いの1つだけ(tmp_path):
    r, y, 表, 通 = _関所まで(tmp_path, 型={"時間.週の所定": "18h"})
    assert not [q for q in r["仮の値"] if q["項目"] == "時間.週の所定"]  # 段の解決は仮と問いを足さない
    assert any("時間.週の所定" in t and "18h" in t for t in r["知らせ"])  # 知らせは出す（黙らない）
    assert "時間.週の所定" not in next(p for p in y["入力"]["人"] if p["NO"] == "0002")
    問い = [q for q in 表["問い"] if "NO 0002" in q["答えで変わる項目と人"]]
    assert [q["何が無いか"] for q in 問い] == ["時間.週の所定"]
    assert "0002" in {x.NO for x in 通.外した人たち}  # 仮のまま出口へ出ない


def test_読めない有給の1日の時間も有給の問いの1つだけ(tmp_path):
    r, y, 表, 通 = _関所まで(tmp_path, 型={"有給.1日の時間": "6h"})
    assert not [q for q in r["仮の値"] if q["項目"] == "有給.1日の時間"]
    assert any("有給.1日の時間" in t for t in r["知らせ"])
    # 時間単位の取得が無い月は 有給/ も要らない＝問いは無く確定（値を使う所が要る時だけ問う）
    assert next(a for a in 表["行"] if a["NO"] == "0002")["状態"] == "確定"
    y["入力"]["勤怠"].append({"支給月": 支給月, "NO": "0002", "日付": "2027-02-09", "休暇の種類": "年休",
                            "休暇の単位": "時間", "休暇の時間": "120"})
    表 = 有給.管理表(y["入力"])
    assert [q["何が無いか"] for q in 表["問い"] if "NO 0002" in q["答えで変わる項目と人"]] == ["有給.1日の時間"]
