# ---- 有給の関所へ は (会社, NO) で仮を引く（給与の関所へ と同じ）: 複数の会社を 1 度に回しても同じ NO を取り違えない ----
C2 = "C2"


def _2社(表):
    """作り物の C1 の管理表の行を、別の会社 C2 の同じ NO の人として写して足す（2 社を 1 度に回す形）。"""
    return {**表, "行": [*表["行"], *({**a, "会社": C2} for a in 表["行"])]}


@pytest.mark.parametrize("仮の会社", [C, C2])
def test_複数の会社の同じNOは仮の会社の人だけ外す(tmp_path, 仮の会社):
    _, y, 表, _ = _関所まで(tmp_path)
    表2 = _2社(表)
    z = 繋.有給の関所へ(y, 表2, [{"会社": 仮の会社, "NO": "0001", "項目": "時間.日の所定", "値": "6時", "拠り所": "作り物"}])
    通 = 関所.通す(z["行"], z["人の状態"])
    外 = {(x.会社, x.NO) for x in 通.外した人たち}
    assert (仮の会社, "0001") in 外  # 止め漏れない
    別 = C2 if 仮の会社 == C else C
    assert (別, "0001") not in 外  # 別の会社の同じ NO は取り違えて止めない
    assert 外 == {(仮の会社, "0001"), (C, "0003"), (C2, "0003")}  # ほかは 有給/ の仮（0003）だけ
    出 = {(a["会社"], a["NO"]) for a in 繋.有給の出す行(表2, 通)}
    assert (別, "0001") in 出 and (仮の会社, "0001") not in 出


