def _タブ(記録=(), 会社の足し=(), 事務所=(), 項目の足し=(), 人=None):
    d = {"支払.締め日": "末", "支払.支給日": "25", "支払.支給の月": "当月", "支払.賃金の形": "月給",
         "社保.健保の支部": "東京都", "雇保.事業の種類": "一般", "会社.事業場の都道府県": "東京都", "時間.週の起算": "月"}
    会社 = [{"会社": c, "項目": k, "今の値": v, "適用開始": ""} for c in (C, "C2") for k, v in d.items()] + list(会社の足し)
    勤務の型 = [{"会社": c, "型の名": "日勤", "時間.日の所定": "8:00", "時間.所定の始業": "9:00", "時間.所定の終業": "18:00"}
            for c in (C, "C2")]
    社員 = [{"会社": C, "NO": NO, "氏名": f"作り物 {名}", "勤怠の表記": 名, "勤務の型": "日勤", "生年月日": "1980-05-10",
           "入社日": "2020-04-01", "社保.標準報酬": "320000", "源泉.扶養の数": "1", "住民税.7月以降": "10000",
           **({"人.区分": "役員", "勤務の型": ""} if NO == 役員 else {}), **(人 or {}).get(NO, {})}
          for NO, 名 in 人たち.items()]
    社員.append({"会社": "C2", "NO": "0001", "氏名": "作り物 よそ", "勤怠の表記": "よそ", "勤務の型": "日勤"})
