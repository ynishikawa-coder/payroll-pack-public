def test_知らない項目の人は有給の関所でも止まる():
    from 有給 import 有給
    def 状態(記録):
        tabs = _タブ(記録=記録, 人={NO: {"時間.週の所定日数": "5"} for NO in 人たち})
        r = 段.解く(支給月, **tabs)
        y = 繋.有給の入力(支給月, C, r, (), **tabs)
        z = 繋.有給の関所へ(y, 有給.管理表(y["入力"]), r["仮の値"])
        return {k[2]: v for k, v in z["人の状態"].items()}
    前, 後 = 状態([]), 状態([_記録(項目="標準報酬月額", 確かめ="確認済")])
    assert 前["0002"] == "確認済" and 後 == {**前, "0002": "仮"}


