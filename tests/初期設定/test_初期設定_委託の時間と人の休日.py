"""段の解決: 委託の併用の出勤時間を 入力 へ写す段と、人の休日を入口の 文脈.人の休日 へ渡す段。作り物の会社 C1 の値だけ。

- 会社の 委託.ソフトの出勤時間の欄（欄の名）で、台帳「月の変動」の 項目（無ければ 台帳「人ごと」の列）から、その月の出勤時間を
  芯/計算 の 入力 の 委託.雇用分の出勤時間 へ写す（委託の併用の人だけ）。引けなければ知らせ（芯が所定で見当し仮）
- 社員の列 休日.人の休日 → 人の休日（入口の 文脈.人の休日 の形: 日付の set か {日付: bool}）。芯/計算 の 人 には渡さない
"""
import importlib.util
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根))
sys.path.insert(0, str(根 / "tests" / "計算"))
_spec = importlib.util.spec_from_file_location("初期設定_段の解決_委託の時間", 根 / "初期設定" / "段の解決.py")
段 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(段)

from 入口.口 import 文脈  # noqa: E402

C = "C1"
会社 = [{"会社": C, "項目": "委託.ソフトの出勤時間の欄", "今の値": "出勤時間", "適用開始": ""}]


def _社員(**列):
    return [{"会社": C, "NO": "0001", "氏名": "作り物 一郎", "人.区分": "委託の併用", **列},
            {"会社": C, "NO": "0002", "氏名": "作り物 二郎", "人.区分": "社員"}]


def test_月の変動の欄の行から雇用分の出勤時間を写す():
    月の変動 = [{"会社": C, "支給月": "2027.02支給", "NO": "0001", "項目": "出勤時間", "値": "150:00"},
             {"会社": C, "支給月": "2027.01支給", "NO": "0001", "項目": "出勤時間", "値": "99:00"}]
    人ごと = [{"会社": C, "支給月": "2027.02支給", "NO": "0001", "出勤時間": "140:00"}]
    r = 段.解く("2027.02支給", 会社=会社, 社員=_社員(), 月の変動=月の変動, 人ごと=人ごと)
    assert r["入力"] == {(C, "0001"): {"委託.雇用分の出勤時間": "150:00"}}  # 委託の併用の人だけ・その月・月の変動が先


def test_月の変動に無ければ人ごとの列から():
    人ごと = [{"会社": C, "支給月": "2027.02支給", "NO": "0001", "出勤時間": "140:00"}]
    r = 段.解く("2027.02支給", 会社=会社, 社員=_社員(), 人ごと=人ごと)
    assert r["入力"][(C, "0001")]["委託.雇用分の出勤時間"] == "140:00"


def test_引けなければ知らせて写さない():
    r = 段.解く("2027.02支給", 会社=会社, 社員=_社員())
    assert r["入力"] == {} and any("雇用分の出勤時間を引けない" in s for s in r["知らせ"])
    r = 段.解く("2027.02支給", 社員=_社員())
    assert any("委託.ソフトの出勤時間の欄 が空" in s for s in r["知らせ"])


def test_写した時間で芯の最低賃金が所定の見当にならない(tmp_path):
    import 作る_計算
    from 芯.計算 import 計算する
    月の変動 = [{"会社": C, "支給月": "2027.02支給", "NO": "0001", "項目": "出勤時間", "値": "150:00"}]
    r = 段.解く("2027.02支給", 会社=会社, 社員=_社員(), 月の変動=月の変動)
    入力 = {("C1", "0001"): r["入力"][(C, "0001")]}
    人 = 作る_計算.人(**{"人.区分": "委託の併用", "委託.月給": "50000"})
    結果 = 計算する(作る_計算.月の数字(), 決まり={("C1", "0001"): 作る_計算.決まり(**{"委託.式": "月額"})},
                 人={("C1", "0001"): 人}, 入力=入力, 置き場=作る_計算.置き場(tmp_path), 支給月="2027-02")
    assert not any("雇用分の出勤時間" in q["何が無いか"] for q in 結果["問い"])


def test_人の休日を入口の文脈の形で渡す():
    r = 段.解く("2027.08支給", 社員=_社員(**{"休日.人の休日": "2027-08-13、2027-08-14"}))
    assert r["人の休日"] == {(C, "0001"): {"2027-08-13", "2027-08-14"}}
    assert "休日.人の休日" not in r["人"][(C, "0001")] and "休日.人の休日" not in r["決まり"][(C, "0001")]
    j = 段.解く("2027.08支給", 社員=_社員(**{"休日.人の休日": '{"2027-08-13": true, "2027-08-15": false}'}))
    assert j["人の休日"][(C, "0001")] == {"2027-08-13": True, "2027-08-15": False}
    # 入口の 文脈 へ NO を鍵にしてそのまま渡せる（人 → 型 → 会社 の 3 段）
    文 = 文脈(支給月="2027-08", 会社=C, 期間の始め="2027-08-01", 期間の終わり="2027-08-31", 休日={"2027-08-15"},
            人の休日={no: v for (c, no), v in j["人の休日"].items()})
    assert 文.休日か("2027-08-13", "0001") and not 文.休日か("2027-08-15", "0001") and 文.休日か("2027-08-15", "0002")


def test_人の休日の形が違えば知らせて渡さない():
    r = 段.解く("2027.08支給", 社員=_社員(**{"休日.人の休日": "お盆"}))
    assert r["人の休日"] == {} and any("休日.人の休日" in s for s in r["知らせ"])


# ---- 会社の段の定数（委託.雇用分の出勤時間）: 月の変動 > 人ごと > 会社 ----
def _会社(定数, 欄=True):
    rows = [{"会社": C, "項目": "委託.雇用分の出勤時間", "今の値": 定数, "適用開始": ""}]
    return (会社 if 欄 else []) + rows


def test_会社の定数が入力へ届く_欄が無くても():
    for 欄 in (True, False):
        r = 段.解く("2027.02支給", 会社=_会社("160", 欄), 社員=_社員())
        assert r["入力"] == {(C, "0001"): {"委託.雇用分の出勤時間": "160:00"}}, 欄  # 時間の数を芯の読む h:mm に
        assert not any("雇用分の出勤時間を引けない" in s for s in r["知らせ"])
    for 字, 後 in (("160:00", "160:00"), ("152:30", "152:30"), ("162.5", "162:30"), ("160時間", "160:00")):
        r = 段.解く("2027.02支給", 会社=_会社(字), 社員=_社員())
        assert r["入力"][(C, "0001")]["委託.雇用分の出勤時間"] == 後, 字


def test_人ごとと月の変動が会社の定数に勝つ():
    人ごと = [{"会社": C, "支給月": "2027.02支給", "NO": "0001", "出勤時間": "140:00"}]
    月の変動 = [{"会社": C, "支給月": "2027.02支給", "NO": "0001", "項目": "出勤時間", "値": "150:00"}]
    r = 段.解く("2027.02支給", 会社=_会社("160"), 社員=_社員(), 人ごと=人ごと)
    assert r["入力"][(C, "0001")]["委託.雇用分の出勤時間"] == "140:00"
    r = 段.解く("2027.02支給", 会社=_会社("160"), 社員=_社員(), 人ごと=人ごと, 月の変動=月の変動)
    assert r["入力"][(C, "0001")]["委託.雇用分の出勤時間"] == "150:00"
    r = 段.解く("2027.03支給", 会社=_会社("160"), 社員=_社員(), 人ごと=人ごと, 月の変動=月の変動)
    assert r["入力"][(C, "0001")]["委託.雇用分の出勤時間"] == "160:00"  # その月の行が無ければ会社の定数


def test_会社の定数が読めなければ渡さず仮():
    r = 段.解く("2027.02支給", 会社=_会社("たくさん"), 社員=_社員())
    assert r["入力"] == {}
    assert [(x["NO"], x["項目"]) for x in r["仮の値"]] == [("0001", "委託.雇用分の出勤時間")] and r["仮の値"][0]["問い"]


