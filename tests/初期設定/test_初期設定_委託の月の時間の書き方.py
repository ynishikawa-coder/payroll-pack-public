"""段の解決: `委託.所定時間`・`委託.みなし残業時間` の数だけの字を、会社の `出口.時間の書き方` で読み分けて h:mm で 芯/計算 へ渡す。

芯/計算/委託.py は h:mm だけを確かな値として読み、数（`160.50`・`160`）は「時間の数として見当」の仮にする。
- 60進: `160.30`→`160:30`・`160.00`・`160`→`160:00`（1 桁・60 以上は字のまま＝芯が仮）
- 10進: `160.5`・`160.50`→`160:30`（分に割り切れない小数は字のまま＝芯が仮）
- 書き方が無い・h:mm・無し は触らない（今のまま）。会社の行が事務所の既定に勝つ
"""
import importlib.util
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根))
_spec = importlib.util.spec_from_file_location("初期設定_段の解決_委託の月の時間", 根 / "初期設定" / "段の解決.py")
段 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(段)

from 芯.計算 import 委託  # noqa: E402

C = "C1"


def _決まり(書き方=None, 事務所の書き方=None, **項目):
    会社 = [{"会社": C, "項目": k, "今の値": v, "適用開始": ""} for k, v in 項目.items()]
    if 書き方 is not None:
        会社.append({"会社": C, "項目": "出口.時間の書き方", "今の値": 書き方, "適用開始": ""})
    事務所 = [] if 事務所の書き方 is None else [{"項目": "出口.時間の書き方", "今の値": 事務所の書き方, "適用開始": ""}]
    社員 = [{"会社": C, "NO": "0001", "氏名": "作り物 一郎", "人.区分": "委託"}]
    r = 段.解く("2027.02支給", 会社=会社, 事務所=事務所, 社員=社員)
    return r["決まり"][(C, "0001")]


def _二つ(書き方, 所定, みなし, **他):
    d = _決まり(書き方, **{"委託.所定時間": 所定, "委託.みなし残業時間": みなし}, **他)
    return d.get("委託.所定時間"), d.get("委託.みなし残業時間")


def test_60進は点の後ろ2桁を分と読みhmmで渡す():
    assert _二つ("60進（h:mm）", "160.30", "10.00") == ("160:30", "10:00")
    assert _二つ("60進", "160", "0") == ("160:00", "0:00")


def test_60進の1桁と60以上は字のまま():
    assert _二つ("60進", "160.3", "10.75") == ("160.3", "10.75")


def test_10進は時間の数と読みhmmで渡す_分に割り切れない小数は字のまま():
    assert _二つ("10進（h.hh）", "160.50", "10.5") == ("160:30", "10:30")
    assert _二つ("10進", "160", "10.33") == ("160:00", "10.33")


def test_書き方が無ければ触らない_hmmと無しも触らない():
    assert _二つ(None, "160.50", "10") == ("160.50", "10")
    assert _二つ("60進", "160:30", "無し") == ("160:30", "無し")


def test_事務所の既定でも読み_会社の行が勝つ():
    assert _二つ(None, "160.50", "10.30", 事務所の書き方="10進") == ("160:30", "10:18")
    assert _二つ("60進", "160.50", "10.30", 事務所の書き方="10進") == ("160:50", "10:30")


def test_芯はhmmで渡った値を仮にせず_書き方の無い数は今のまま仮():
    所定, みなし = _二つ("10進", "160.50", "10.5")
    assert 委託._月の時間(所定) == (160 * 60 + 30, "") and 委託.みなしを読む(みなし) == (10 * 60 + 30, "")
    所定, みなし = _二つ(None, "160.50", "10.5")
    assert 委託._月の時間(所定)[1] and 委託.みなしを読む(みなし)[1]   # 訳あり＝芯が見当の仮
