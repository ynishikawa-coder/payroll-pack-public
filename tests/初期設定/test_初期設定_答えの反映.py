# ── 2 前の答えとの食い違い ──

def test_同じ人の同じ日に前の答えと違う答えは問いになる():
    前 = _日の問("Q209901-01", "18:00 で数える")
    後 = _日の問("Q209902-05", "17:30 で数える")
    台帳 = {"確定した勤怠": _勤怠(("0001", "問い:Q209901-01・問い:Q209902-05"))}
    r = 設問.反映の照らし([前, 後], {}, C, 台帳=台帳)
    assert [(x["問いの番号"], x["前の問い"]) for x in r["問い"]] == [("Q209902-05", "Q209901-01")]
    assert ("Q209902-05", 勤, "前の答えと食い違う") in _状態(r) and any("食い違う" in x for x in r["赤"])
    # 同じ答え・別の日（対象が違う）・記録に残した聞き直しは食い違いでない
    assert 設問.反映の照らし([前, {**後, "回答": "18:00 で数える"}], {}, C, 台帳=台帳)["赤"] == []
    別の日 = {**後, "対象": "人: 作り物 一郎／1 月 6 日／退勤の時刻"}
    assert 設問.反映の照らし([前, 別の日], {}, C, 台帳=台帳)["赤"] == []
    聞き直し = {**後, "理由": "聞き直し: Q209901-01・打刻の写しが届いた"}
    assert 設問.反映の照らし([前, 聞き直し], {}, C, 台帳=台帳)["赤"] == []


def test_会社の同じ項目に前の答えと違う答えは問いになる():
    t = {"会社": [{"会社": C, "項目": "欠勤.遅刻早退の控除", "今の値": "引かない", "適用開始": ""}]}
