# ── 5 道具の都合の赤（閉じた行・md の下の段の節・事実の変わらない日・一部の人だけ値のある社員の先）──

def _一次(日の種類="勤務", **足す):
    return [{"会社": C, "支給月": "2099.01支給", "NO": "0001", "氏名": "作り物 一郎", "勤怠の表記": "一郎", "日付": d,
             "日の種類": 日の種類 if d == "2099-01-05" else "勤務", "出勤の時刻": "9:00", "退勤の時刻": "18:00", **足す}
            for d in ("2099-01-04", "2099-01-05", "2099-01-06")]


def _四つ():
    md = {"人のルール.md": "# 人のルール\n\n## NO0001 作り物 一郎\n\n### 通勤\n\n- 片道 2 km（出所 Q209901-07）\n\n"
                          "### 手当\n\n- なし\n\n## NO0002 作り物 二郎\n\n- 出所 Q209901-99\n"}
    タブ = {"勤務の型": [{"会社": C, "型の名": "日勤", "時間.所定の始業": "9:00"}],
           "社員": [{"会社": C, "NO": "0001", "勤怠の表記": "一郎", "勤務の型": "日勤", "時間.所定の始業": "8:30"},
                   {"会社": C, "NO": "0002", "勤務の型": "日勤", "時間.所定の始業": ""}]}
    問い = [
        _問("Q209901-05", "出し直し→Q209901-06", "2_マスタ/会社/時間.所定の終業"),
        _問("Q209901-07", "片道 2 km", "人のルール.md#NO0001 作り物 一郎"),
        _問("Q209901-09", "出勤した日（時刻は原本どおり）（1/5）", 勤, 支給月="2099.01支給", 何が無いか="区分が読めない",
           対象="人:一郎様／1 月 5 日／日の区分", 答えで変わる項目と人="日の種類"),
        _問("Q209901-10", "9 時から", "2_マスタ/社員/時間.所定の始業", 答えで変わる項目と人="時間.所定の始業"),
    ]
    台帳 = {"確定した勤怠": _一次(), "読んだままの勤怠": _一次()}
    return 問い, タブ, md, 台帳


def test_道具の都合の行は赤にしない():
    問い, タブ, md, 台帳 = _四つ()
    r = 設問.反映の照らし(問い, タブ, C, md=md, 台帳=台帳)
    assert r["赤"] == [], r["赤"]
    # 閉じた行（出し直し）は照らさない＝行が無い（取り下げは 問い の 状態 が正本＝答えの文を読まない）
    assert {x["問いの番号"] for x in r["行たち"]} == {"Q209901-07", "Q209901-09", "Q209901-10"}
    assert "読んだまま＝答えどおり" in next(x["訳"] for x in r["行たち"] if x["問いの番号"] == "Q209901-09")

    # 印を足す答え（所定どおり出勤した（定時扱い））: 1 次の印に含まれれば答えどおり（ほかの印と並んでも）・無ければ赤
    定時 = [{**q, "回答": "所定どおり出勤した（定時扱い）（1/5）"} if q["問いの番号"] == "Q209901-09" else q for q in 問い]
    for 印, 赤 in (("手書き、定時扱い", False), ("", True)):
        t = {"確定した勤怠": _一次(印=印), "読んだままの勤怠": _一次(印=印)}
        r = 設問.反映の照らし(定時, タブ, C, md=md, 台帳=t)
        assert ("Q209901-09" in {x["問いの番号"] for x in r["行たち"] if x["状態"] != "埋まった"}) == 赤, (印, r["行たち"])


def test_本当に写し漏れた行は赤():
    問い, タブ, md, 台帳 = _四つ()
    # 人のルールの節に出所の番号が無い（下の段の ### を越えて次の ## の行は節の外）
    md2 = {"人のルール.md": md["人のルール.md"].replace("Q209901-07", "Q209901-00").replace("Q209901-99", "Q209901-07")}
    # 答えで事実が変わる日（1 次は欠勤）を、確定した勤怠へ書かずに 1 次のまま写した
    台帳2 = {"確定した勤怠": _一次("欠勤"), "読んだままの勤怠": _一次("欠勤")}
    # 型にも会社にも値の無い人（0002）
    タブ2 = {**タブ, "勤務の型": [{"会社": C, "型の名": "日勤", "時間.所定の始業": ""}]}
    # 出し直しの前の答え（閉じていない）
    問い2 = [{**問い[0], "回答": "18:00"}, *問い[1:]]
    r = 設問.反映の照らし(問い2, タブ2, C, md=md2, 台帳=台帳2)
    赤 = {x["問いの番号"] for x in r["行たち"] if x["状態"] != "埋まった"}
    assert 赤 == {"Q209901-05", "Q209901-07", "Q209901-09", "Q209901-10"}, r["行たち"]
    # 読んだままの勤怠を渡さない＝事実が変わらないかを照らせない＝赤のまま
    r = 設問.反映の照らし(問い[2:3], タブ, C, 台帳={"確定した勤怠": _一次()})
    assert r["赤"]
    # 確定した勤怠が 1 次と違うのに訳が無い日は、読んだままと言えない
    台帳3 = {"確定した勤怠": _一次(印="手で直した"), "読んだままの勤怠": _一次()}
    assert 設問.反映の照らし(問い[2:3], タブ, C, 台帳=台帳3)["赤"]
