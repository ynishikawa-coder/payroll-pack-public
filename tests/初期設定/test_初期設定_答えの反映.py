"""答えの反映の照らし（初期設定/設問.py の 反映の照らし）の台帳の先・前の答えとの食い違い・反映済みの欄の試験。作り物の値だけ。

防ぐ故障（決定 7「確認事項の答えは必ず反映先を書き換える」・2026-11-18）:
1. 反映先が 確定した勤怠・その月だけの指示 の答えを、台帳へ書かずに残しても照らしが通る（台帳を渡さないと黙って見ていないになる）。
2. 同じ反映先（同じ人・同じ日・同じ項目）の前の答えと違う答えが、黙って前の答えに勝つ。
3. 反映済み の欄の書き方がまちまち（済・反映済み・未・空・日付）で、読めない字を黙って空と読む・済と書けば照らしを飛ばす。
4. 「不明」「確かめる」の答えを答え済みに数えて反映先を探す。
"""
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
_s = importlib.util.spec_from_file_location("答えの反映_設問", 根 / "初期設定" / "設問.py")
設問 = importlib.util.module_from_spec(_s)
_s.loader.exec_module(設問)

C = "作り物の会社"
勤 = 設問.確定した勤怠の先
指 = 設問.その月だけの指示の先


def _問(番号, 回答, 反映先, **足す):
    return {"会社": C, "問いの番号": 番号, "何が無いか": "その月だけの物", "回答": 回答, "反映先": 反映先, **足す}


def _日の問(番号="Q209901-01", 回答="18:00 で数える", **足す):
    return _問(番号, 回答, 勤, **{"対象": "人: 作り物 一郎／1 月 5 日／退勤の時刻", "答えで変わる項目と人": "退勤の時刻、0001", **足す})


def _勤怠(*訳たち):
    return [{"会社": C, "支給月": "2099.01支給", "NO": no, "氏名": "作り物 一郎", "日付": "2099-01-05", "直した訳": 訳}
            for no, 訳 in 訳たち]


def _状態(r):
    return [(x["問いの番号"], x["反映先"], x["状態"]) for x in r["行たち"]]


# ── 1 台帳の先 ──

def test_確定した勤怠の答えを反映せず残すと赤():
    q = _日の問()
    # 台帳を渡さない＝照らせない（黙って見ていないにしない）
    r = 設問.反映の照らし([q], {}, C)
    assert _状態(r) == [("Q209901-01", 勤, "台帳が無い")] and r["赤"]
    # 確定した勤怠に 問い:<番号> の行が無い（別の問いの行・決まりで直した行だけ）＝反映していない
    for 行 in (_勤怠(("0001", "問い:Q209901-02")), _勤怠(("0001", "決まり:休憩の引き方")), _勤怠(("0002", "問い:Q209901-01"))):
        r = 設問.反映の照らし([q], {}, C, 台帳={"確定した勤怠": 行})
        assert _状態(r) == [("Q209901-01", 勤, "空")] and r["赤"], 行
    # 反映すれば緑（区間のタブに書いた答えも数える）
    assert 設問.反映の照らし([q], {}, C, 台帳={"確定した勤怠": _勤怠(("0001", "問い:Q209901-01"))})["赤"] == []
    assert 設問.反映の照らし([q], {}, C, 台帳={"確定した勤怠": [], "確定した勤怠の区間": _勤怠(("0001", "問い：Q209901-01"))})["赤"] == []


def test_確定した勤怠は答えで変わる人の全員に行が要る():
    q = _日の問(答えで変わる項目と人="退勤の時刻、0001、0002")
    r = 設問.反映の照らし([q], {}, C, 台帳={"確定した勤怠": _勤怠(("0001", "問い:Q209901-01"))})
    assert r["赤"] and "NO 0002" in r["行たち"][0]["訳"]
    台帳 = {"確定した勤怠": _勤怠(("0001", "問い:Q209901-01"), ("0002", "決まり:丸め・問い:Q209901-01"))}
    assert 設問.反映の照らし([q], {}, C, 台帳=台帳)["赤"] == []


def test_その月だけの指示の答えを反映せず残すと赤():
    q = _問("Q209901-03", "今月だけ通勤手当を 0 円にする", 指, 対象="人: 作り物 一郎／2099.01支給／通勤手当", 答えで変わる項目と人="0001")
    assert 設問.反映の照らし([q], {}, C)["赤"]
    行 = {"会社": C, "支給月": "2099.01支給", "NO": "0001", "氏名": "作り物 一郎", "項目": "通勤手当", "値": "0", "中身": "今月だけ",
         "問いの番号": "Q209901-03"}
    assert 設問.反映の照らし([q], {}, C, 台帳={"その月だけの指示": [{**行, "問いの番号": "Q209901-04"}]})["赤"]
    assert 設問.反映の照らし([q], {}, C, 台帳={"その月だけの指示": [行]})["赤"] == []
    # get_values の形（1 行目が見出し）でも読む
    assert 設問.反映の照らし([q], {}, C, 台帳={"その月だけの指示": [list(行), list(行.values())]})["赤"] == []


# ── 2 前の答えとの食い違い ──

def test_同じ人の同じ日に前の答えと違う答えは問いになる():
    前 = _日の問("Q209901-01", "18:00 で数える")
    後 = _日の問("Q209902-05", "17:30 で数える")
    台帳 = {"確定した勤怠": _勤怠(("0001", "問い:Q209901-01・問い:Q209902-05"))}
    r = 設問.反映の照らし([前, 後], {}, C, 台帳=台帳)
    assert [(x["問いの番号"], x["前の問い"]) for x in r["問い"]] == [("Q209902-05", "Q209901-01")]
    assert ("Q209902-05", 勤, "前の答えと食い違う") in _状態(r) and any("食い違う" in x for x in r["赤"])
    # 同じ答え・別の日（対象が違う）・記録に残した聞き直しは食い違いでない
    assert 設問.反映の照らし([前, {**後, "回答": "18:00 で数える"}], {}, C, 台帳=台帳)["赤"] == []
    別の日 = {**後, "対象": "人: 作り物 一郎／1 月 6 日／退勤の時刻"}
    assert 設問.反映の照らし([前, 別の日], {}, C, 台帳=台帳)["赤"] == []
    聞き直し = {**後, "理由": "聞き直し: Q209901-01・打刻の写しが届いた"}
    assert 設問.反映の照らし([前, 聞き直し], {}, C, 台帳=台帳)["赤"] == []


def test_会社の同じ項目に前の答えと違う答えは問いになる():
    t = {"会社": [{"会社": C, "項目": "欠勤.遅刻早退の控除", "今の値": "引かない", "適用開始": ""}]}
    前 = {**_問("Q209901-01", "引く", "2_マスタ/会社/欠勤.遅刻早退の控除"), "何が無いか": "読み方: 遅刻早退"}
    後 = {**前, "問いの番号": "Q209903-02", "回答": "引かない"}
    r = 設問.反映の照らし([前, 後], t, C)
    assert [x["前の問い"] for x in r["問い"]] == ["Q209901-01"]
    # 同じ番号の送り直し（一番下の行が正）は食い違いでない
    assert 設問.反映の照らし([前, {**前, "回答": "引かない"}], t, C)["問い"] == []


# ── 3 反映済み の欄 ──

def test_反映済みの欄は読める書き方だけ受ける():
    for v in ("済", "反映済み", "2099-01-20", "2099/1/20", "", "未"):
        assert 設問.反映済みを読む(v) is not None, v
    for v in ("OK", "done", "○", "一部"):
        assert 設問.反映済みを読む(v) is None, v
    q = _日の問()
    台帳 = {"確定した勤怠": _勤怠(("0001", "問い:Q209901-01"))}
    r = 設問.反映の照らし([{**q, "反映済み": "OK"}], {}, C, 台帳=台帳)
    assert ("Q209901-01", 勤, "反映済みが読めない") in _状態(r) and r["赤"]
    # 済と書いても照らしを飛ばさない（埋まっていなければ 反映済みなのに埋まっていない）
    r = 設問.反映の照らし([{**q, "反映済み": "済"}], {}, C, 台帳={"確定した勤怠": []})
    assert _状態(r) == [("Q209901-01", 勤, "反映済みなのに埋まっていない")] and r["赤"]
    for v in ("済", "反映済み", "2099-01-20", "", "未"):
        assert 設問.反映の照らし([{**q, "反映済み": v}], {}, C, 台帳=台帳)["赤"] == [], v


