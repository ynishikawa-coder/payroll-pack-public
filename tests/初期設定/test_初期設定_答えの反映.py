# ── 5 前の形の質問と回答（レビュー #192 の赤 1 回目） ──
# 防ぐ故障: get_values の形で渡した質問と回答が (a) 1 行目が URL の行 → 照らす行が 0 で黙って緑 (b) 見出しが ID → 番号が空で行が
# 1 行に畳まれ前の答えとの食い違いが消える。どれも訳を名指しして照らさずに止める（番号の形の照らしは畳んだ＝問いの鍵は 問い の行が正本）。

_見出し = ["会社", "問いの番号", "質問", "対象", "答えで変わる項目と人", "回答", "反映先", "理由"]


def _表(*問たち, 見出し=_見出し):
    return [list(見出し), *[[q.get(k, "") for k in _見出し] for q in 問たち]]


def test_前の形の質問と回答は名指しして止める():
    前 = _日の問("Q209901-01", "18:00 で数える")
    後 = _日の問("Q209902-05", "19:00 で数える")
    台帳 = {"確定した勤怠": _勤怠(("0001", "問い:Q209901-01・問い:Q209902-05"))}
    # 今の形の表なら食い違いを出す（止める形が今の表を止めない）
    r = 設問.反映の照らし(_表(前, 後), {}, C, 台帳=台帳)
    assert [x["前の問い"] for x in r["問い"]] == ["Q209901-01"]
    for 表, 訳 in (
            ([["https://example.invalid/login"], *_表(前, 後)], "見出しは 2 行目に在り 1 行目が見出しでない"),            # (a)
            (_表(前, 後, 見出し=["会社", "ID", *_見出し[2:]]), "前の見出し ID（今の名 問いの番号）"),                    # (b)
            ):
        r = 設問.反映の照らし(表, {}, C, 台帳=台帳)
        assert [x["状態"] for x in r["行たち"]] == ["質問と回答が読めない"] and 訳 in r["赤"][0], (訳, r)
    # 列名の dict の並びでも同じ（ID の見出し）
    r = 設問.反映の照らし([{("ID" if k == "問いの番号" else k): v for k, v in q.items()} for q in (前, 後)], {}, C, 台帳=台帳)
    assert "前の見出し ID" in r["赤"][0]


