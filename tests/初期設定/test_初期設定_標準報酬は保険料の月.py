"""標準報酬の変更の記録は 適用支給月 に保険料の月（YYYY.MM分）で書く。支給月→保険料の月は芯（支給控除.保険料の月）の 1 か所で直す。

作り物の 1 人。9 月の定時決定（保険料の月 2027-09 から 340000）は、翌月徴収なら 2027-10 支給から・当月徴収なら 2027-09 支給から効く。
古い書き方（改定の月か支給月の `YYYY.MM支給`・印の無い `YYYY.MM`）の行は使わずに止めて問う（仮の値＝出口へ出さない）。
"""
import importlib.util
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("初期設定_段の解決_保険料の月", 根 / "初期設定" / "段の解決.py")
段 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(段)

C = "作り物の会社"


翌月 = [{"会社": C, "項目": "社保.徴収の月", "今の値": "翌月徴収", "適用開始": ""}]


def _解く(支給月, 記録, 会社=翌月):
    社員 = [{"会社": C, "NO": "0001", "氏名": "作り物 一郎", "社保.標準報酬": "340000"}]
    return 段.解く(支給月, 社員=社員, 変更の記録=記録, 会社=list(会社))


def _記録(字, 確かめ="確認済"):
    return [{"会社": C, "NO": "0001", "記録日": "2027-07-10", "適用支給月": 字, "項目": "社保.標準報酬",
             "前の値": "320000", "新しい値": "340000", "確かめ": 確かめ}]


def _標準(r):
    return r["人"][(C, "0001")]["社保.標準報酬"]


def _古い(r):
    return [q for q in r["仮の値"] if q["項目"] == "変更の記録.適用支給月"]


@pytest.mark.parametrize("字", ["2027.09分", "2027年9月分", "２０２７．０９分", "2027-09分"])
def test_翌月徴収は保険料の月の次の支給月から効く(字):
    assert _標準(_解く("2027.09支給", _記録(字))) == "320000"   # 保険料の月 2027-08
    r = _解く("2027.10支給", _記録(字))                          # 保険料の月 2027-09
    assert _標準(r) == "340000" and _古い(r) == []


def test_当月徴収は保険料の月と同じ支給月から効く():
    会社 = [{"会社": C, "項目": "社保.徴収の月", "今の値": "当月徴収", "適用開始": ""}]
    assert _標準(_解く("2027.08支給", _記録("2027.09分"), 会社)) == "320000"
    r = _解く("2027.09支給", _記録("2027.09分"), 会社)
    assert _標準(r) == "340000" and _古い(r) == []


@pytest.mark.parametrize("字", ["2027.10支給", "2027.09", "2027-09", "2027年9月"])
def test_印の無い古い書き方の行は使わずに止めて問う(字):
    """注入: 支給月の字・印の無い字で書いた標準報酬の行は、どの月から効くか決まらない＝黙って効かせず仮＋問い。"""
    r = _解く("2027.10支給", _記録(字))
    q = _古い(r)
    assert [x["NO"] for x in q] == ["0001"] and "YYYY.MM分" in q[0]["問い"]
    assert _標準(r) == "340000"   # その行は使わない（今の値のまま・その人は仮で出口へ出ない）


def test_芯の保険料の月は1か所で語の外は止める():
    from 芯.計算.支給控除 import 式が無い, 保険料の月, 保険料の月の字
    assert 保険料の月(2027, 1, "翌月徴収") == (2026, 12) and 保険料の月(2027, 1, "当月徴収") == (2027, 1)
    with pytest.raises(式が無い):
        保険料の月(2027, 1, "")
    assert 保険料の月の字("2027.09分") == (2027, 9) and 保険料の月の字("2027.09支給") is None and 保険料の月の字("2027.13分") is None


def test_徴収の月が空なら行を使わず止めて問う():
    """注入: 徴収の月が空＝どの支給月から効くか決まらない。行は使わず（前の値へ戻さない）、黙って飛ばさず仮＋問い。"""
    r = _解く("2027.09支給", _記録("2027.09分"), 会社=())
    q = _古い(r)
    assert [x["NO"] for x in q] == ["0001"] and "社保.徴収の月" in q[0]["問い"]
    assert _標準(r) == "340000"
