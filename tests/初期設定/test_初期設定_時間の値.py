def test_残業の数え方を勤務の型に置くとその型の人だけ月で数え_ほかの型は会社の数え方():
    """型の版 24: 会社の一部の勤務の型だけ月の総労働で数える。前は型の段に置けず（段の解決が型の列を黙って捨て）会社の値が全員に当たった。"""
    import 作る_集計
    型 = [{"会社": C, "型の名": "日勤", "時間.日の所定": "8:00"},
         {"会社": C, "型の名": "月の型", "時間.日の所定": "8:00",
          "割増.残業の数え方": "月の総労働が月の所定を超えた分", "割増.月の残業の所定時間": "160:00"}]
    社員 = [{"会社": C, "NO": "1", "氏名": "作り物 一郎", "勤務の型": "日勤"},
          {"会社": C, "NO": "2", "氏名": "作り物 二郎", "勤務の型": "月の型"}]
    r = _解く(会社=_会社(**{"割増.残業の数え方": "1日の所定超え"}), 勤務の型=型, 社員=社員)
    日勤, 月の型 = r["決まり"][(C, "1")], r["決まり"][(C, "2")]
    assert 日勤["割増.残業の数え方"] == "1日の所定超え" and "割増.月の残業の所定時間" not in 日勤
    assert 月の型["割増.残業の数え方"] == "月の総労働が月の所定を超えた分" and 月の型["割増.月の残業の所定時間"] == "160:00"
    assert r["仮の値"] == []
    # 平日 21 日 × 9:00〜18:00（休憩 1 時間）＝168 時間。日の所定 8 時間は超えない＝日勤は 0・月の型は 168−160＝8 時間
    A, B = 作る_集計.月()
    始終 = {"時間.所定の始業": "9:00", "時間.所定の終業": "18:00"}
    一 = 作る_集計.数える(A, B, {**日勤, **始終})
    二 = 作る_集計.数える(A, B, {**月の型, **始終})
    assert 作る_集計.値(一, "残業（会社の数え方）") == [0]
    assert 作る_集計.値(二, "残業（会社の数え方）") == [8 * 60]
    assert all(x["状態"] == "確定" for x in 二["行"] if x["項目"] == "残業（会社の数え方）")


