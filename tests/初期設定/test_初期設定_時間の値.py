"""段の解決: 時間の値（勤務の型の所定・有給 1 日の時間・みなし残業の時間）を芯が読む時間の数にそろえる（作り物の会社 C1 の値だけ）。

- h:mm・3 桁の時の h:mm（`202:30`）・`480分`・`7時間30分`・小数の時間・0 を読み、芯/計算 が `数` で受ける時間の数の字で渡す
  （h:mm のまま渡すと 芯/計算 が 形の誤り で落ちる）
- `有給.1日の時間` は読む側（有給/有給.py・int の分）に合わせ分の数の字で渡す（`7:30`→`450`・`7:20`→`440`）
- 読めない形は黙って 0 にせず、知らせ＋その値を使う人を 仮の値（問いつき）にし、芯へは渡さない
- `割増.残業の数え方`・`割増.みなし残業の時間` は項目の辞書にあり、会社の段から芯/集計・芯/計算 へ届く
"""
import importlib.util
import json
import sys
from decimal import Decimal
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根))
sys.path.insert(0, str(根 / "tests" / "集計"))
sys.path.insert(0, str(根 / "tests" / "計算"))
_spec = importlib.util.spec_from_file_location("初期設定_段の解決_時間の値", 根 / "初期設定" / "段の解決.py")
段 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(段)

C = "C1"
鍵 = (C, "0001")


def _会社(**項目):
    return [{"会社": C, "項目": k, "今の値": v, "適用開始": ""} for k, v in 項目.items()]


def _型(**列):
    return [{"会社": C, "型の名": "日勤", **列}]


def _社員(**列):
    return [{"会社": C, "NO": "0001", "氏名": "作り物 一郎", "勤務の型": "日勤", **列}]


def _解く(支給月="2027.02支給", **他):
    return 段.解く(支給月, **他)


