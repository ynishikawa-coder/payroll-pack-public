def test_芯の計算は直した月の所定時間を受ける_hmmのままだと形の誤り(tmp_path):
    import 作る_計算
    from 芯.計算.形 import 形の誤り
    段の決 = _解く(会社=_会社(**{"時間.月の所定時間": "202:30"}), 社員=_社員(勤務の型=""))["決まり"][鍵]
    決 = 作る_計算.決まり(**{"時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": 段の決["時間.月の所定時間"]})
