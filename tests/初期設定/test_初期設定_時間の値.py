def test_戻した名だけを直し_今の値と前の値が同じ字でも取り違えない():
    """今の値 `1分`（置く で "1"）と記録の前の値 "1"（1 時間）が同じ字でも、戻した方は分の数へ直す（60 倍ずれない）。"""
    記録 = [{"会社": C, "NO": "0001", "項目": "有給.1日の時間", "前の値": "1", "今の値": "1分",
            "適用支給月": "2027.04支給", "記録日": "2027-03-01", "確かめ": "確認済"}]
    型 = _型(**{"有給.1日の時間": "1分"})
    r = _解く(勤務の型=型, 社員=_社員(), 変更の記録=記録)
    assert r["決まり"][鍵]["有給.1日の時間"] == "60" and r["決まり"][鍵]["勤務の型"]["日勤"]["有給.1日の時間"] == "60"
    r = _解く(勤務の型=型, 社員=_社員(), 変更の記録=[{**記録[0], "適用支給月": "2027.01支給"}])
    assert r["決まり"][鍵]["有給.1日の時間"] == "1"


def test_読めない時間は渡さず知らせとその人の仮の値():
    r = _解く(勤務の型=_型(**{"時間.日の所定": "8時", "時間.週の所定": "40:00"}), 社員=_社員())
    決 = r["決まり"][鍵]
    assert "時間.日の所定" not in 決 and "時間.日の所定" not in 決["勤務の型"]["日勤"]
    assert 決["時間.週の所定"] == "40"
    assert any("時間.日の所定「8時」を時間に直せない" in s for s in r["知らせ"])
    (仮,) = r["仮の値"]
    assert (仮["会社"], 仮["NO"], 仮["項目"], 仮["値"]) == (C, "0001", "時間.日の所定", "8時") and 仮["問い"]
    json.dumps(r["仮の値"], ensure_ascii=False)  # 殻へ JSON で渡せる（印の物が残らない）


