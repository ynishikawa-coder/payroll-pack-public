def test_red1_結べない字の問いに日付の無い列の答えは全部の日へ当てない():
    型 = 口.結べない字の型
    前 = Excel出勤簿.読む(七日の表, 作.文脈())
    assert len({q["日付"] for q in 前.要確認 if 口.読みの型(q["理由"]) == 型}) == 7
    out, 知らせ = _答え(_問い("Q1", 口.結べない字の理由("作り物の注 土曜も出る"), "ほかの区分 ／ 補足: 日の種類＝休日勤務"))
    assert out == {} and len(知らせ) == 1 and "要確認のまま" in 知らせ[0]
    # 口へ直に渡しても（前の版の答えの形）当てない
    直 = {"1": [{"番号": "Q1", "何が無いか": 型, "種類": "区分", "答え": "ほかの区分", "列": {"日の種類": "休日勤務"}, "日付": []}]}
    for 文 in (out, 直):
        r = Excel出勤簿.読む(七日の表, 作.文脈(日の答え=文))
        assert len({q["日付"] for q in r.要確認 if 口.読みの型(q["理由"]) == 型}) == 7
        assert [a["日の種類"] for a in r.日] == [a["日の種類"] for a in 前.日]   # 平日・年休の日も書き換わらない
        assert r.人の状態()["1"] == "仮"


