def _範囲の理由(r, d):
    return [q["理由"] for q in r.要確認 if q["日付"] == d and 口.読みの型(q["理由"]) == 口.時刻の範囲の型]


def test_red2_時刻の範囲の問いに列の答えや足す物を書いた確かめたでは外れない():
    理由 = _範囲の理由(Excel出勤簿.読む(夜勤の表, 作.文脈()), "2026-11-02")
    assert 理由
    for 答え in ("出勤した日（時刻は原本どおり）", "ほかの区分 ／ 補足: 日の種類＝勤務", "確かめた（夜勤は別に足す）",
                 "足す物がある", "足す物がある ／ 補足: 夜勤は別に足す"):
        out, 知らせ = _答え(_問い("Q1", 理由[0], 答え))
        assert out == {} and len(知らせ) == 1, 答え
        r = Excel出勤簿.読む(夜勤の表, 作.文脈(日の答え=out))
        assert _範囲の理由(r, "2026-11-02"), 答え
        assert r.人の状態()["1"] == "仮", 答え


def test_足す物があるは補足の日付と時刻をその日にだけ足す():
    理由 = _範囲の理由(Excel出勤簿.読む(夜勤の表, 作.文脈()), "2026-11-02")
    out, 知らせ = _答え(_問い("Q1", 理由[0], "足す物がある（日付と時刻・区分を補足に書く） ／ 補足: 11/2 19:00〜22:00"))
    assert 知らせ == [] and out["1"][0]["日付"] == ["2026-11-02"]
    r = Excel出勤簿.読む(夜勤の表, 作.文脈(日の答え=out))
    二 = [(b["区間の種別"], b["始め"], b["終わり"]) for b in r.区間 if b["日付"] == "2026-11-02"]
    三 = [(b["区間の種別"], b["始め"], b["終わり"]) for b in r.区間 if b["日付"] == "2026-11-03"]
    assert ("労働", "19:00", "22:00") in 二 and ("労働", "19:00", "22:00") not in 三
    assert _範囲の理由(r, "2026-11-02") == []
    assert _範囲の理由(r, "2026-11-03")   # 名指さなかった日は要確認のまま


