"""問いの番号は、質問と回答に既にある行の同じ支給年月の一番大きい順の次。既にある行を渡さない時は止める
（黙って Q<年月>-01 から振り直さない）。作り物の会社だけ（注入の試験）。

根（2026-11-19）: 出す物の版の番号（出口/名と版）・確認ページの版と同じ原因＝`設問.まとめる` の `既にある` と
`始める` の番号が既定の空・既定の 1 で、殻が渡さないと既にある番号と重ねて振った（同じ番号は送り直しの行と読まれ、
答え済みの問いも重ね外しが効かずにもう一度出た）。
"""
import importlib.util
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]


def _読む(名, path):
    s = importlib.util.spec_from_file_location(名, path)
    m = importlib.util.module_from_spec(s)
    s.loader.exec_module(m)
    return m


口 = _読む("問いの番号_型の口", 根 / "初期設定" / "型の口.py")
設問 = _読む("問いの番号_設問", 根 / "初期設定" / "設問.py")
始める = _読む("問いの番号_始める", 根 / "初期設定" / "始める.py")

C, 支給月 = "作り物の会社", "2099.04支給"


def _行(n, 月="209904"):
    return {"会社": C, "問いの番号": f"Q{月}-{n:02d}", "支給月": 支給月, "何が無いか": f"作り物の項目 {n}"}


def test_既にある行がQ01からQ03なら次は4():
    assert 口.次の問いの番号([_行(1), _行(2), _行(3)], 支給月) == 4
    assert 口.次の問いの番号([_行(9, "209903")], 支給月) == 1   # ほかの支給年月は数えない
    assert 口.次の問いの番号([], 支給月) == 1


@pytest.mark.parametrize("既にある", [None, "Q209904-03", {"問いの番号": "Q209904-03"}, (r for r in [_行(3)]), ["Q209904-03"]])
def test_既にある行を並びで渡さなければ止める(既にある):
    with pytest.raises(ValueError, match="既にある"):
        口.次の問いの番号(既にある, 支給月)
    with pytest.raises(ValueError, match="既にある"):
        設問.まとめる([], 会社=C, 支給月=支給月, 今日="2099-04-01", 既にある=既にある)
    with pytest.raises(ValueError, match="既にある"):
        始める.問いを起こす({"会社": C, "組": "作り物の組", "最初の支給月": 支給月, "既にある": 既にある})


def test_まとめると始めるは既にある行を省けない():
    with pytest.raises(TypeError):
        設問.まとめる([], 会社=C, 支給月=支給月, 今日="2099-04-01")
    with pytest.raises(ValueError, match="既にある"):
        設問._口("まとめる", {"種": [], "会社": C, "支給月": 支給月, "今日": "2099-04-01"})
    with pytest.raises(ValueError, match="既にある"):
        始める.問いを起こす({"会社": C, "組": "作り物の組", "最初の支給月": 支給月})


def test_始めるの問いは既にある番号の次から():
    問い = 始める.問いを起こす({"会社": C, "組": "作り物の組", "最初の支給月": 支給月, "今日": "2099-03-01",
                         "既にある": [_行(1), _行(2), _行(3)]})
    assert 問い and 問い[0]["問いの番号"] == "Q209904-04"
    assert [q["問いの番号"] for q in 問い] == [f"Q209904-{n:02d}" for n in range(4, 4 + len(問い))]


def test_見出しつきの格子でも既にある番号の次から():
    # get_values の形（1 行目が見出し）も dict の行と同じに読む（main で受けていた形を止めない・レビューの red 2026-11-19）
    格子 = [["会社", "問いの番号", "支給月", "何が無いか"], *[[C, f"Q209904-{n:02d}", 支給月, f"作り物の項目 {n}"] for n in (1, 2, 3)]]
    assert 口.次の問いの番号(格子, 支給月) == 4
    assert 口.次の問いの番号(格子[:1], 支給月) == 1
    種 = {**設問.その月だけの物の問い(支給月, C), "根拠": [{"資料": "作り物の給与規程", "場所": "3 ページ 第 5 条", "原文": "賃金は毎月支払う"}],
         "読み": "規程にこの月だけの物の決まりが無いと読みました。"}
    m = 設問.まとめる([種], 会社=C, 支給月=支給月, 今日="2099-04-01", 既にある=格子,
                    読んだ資料=[{"名": "作り物の給与規程", "url": "https://drive.example.invalid/d/1"}])
    assert [q["問いの番号"] for q in m["問い"]] == ["Q209904-04"], m
    問い = 始める.問いを起こす({"会社": C, "組": "作り物の組", "最初の支給月": 支給月, "今日": "2099-03-01", "既にある": 格子})
    assert 問い and 問い[0]["問いの番号"] == "Q209904-04"


# --- 型ごとの網 も 既にある を必ず受ける（同じ根の残り・v0.35.0） ---

def test_網は既にあるを省けず_行の並びでなければ止める():
    with pytest.raises(TypeError):
        設問.型ごとの網({}, C)   # 既定の () を畳んだ
    for v in (None, "Q209904-01", {"問いの番号": "Q209904-01"}, (r for r in []), [["問いの番号"], "Q209904-01"], [1]):
        with pytest.raises(ValueError, match="既にある"):
            設問.型ごとの網({}, C, 既にある=v)
    with pytest.raises(ValueError, match="既にある"):
        設問._口("網", {"タブ": {}, "会社": C})   # 命令の口で 既にある を省いても止める
