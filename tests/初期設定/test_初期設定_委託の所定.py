def _定時扱いの月(定時扱い=True):
    import 作る_集計
    上書き = {"2026-11-04": (作る_集計.日("2026-11-04", 時刻の無い労働時間="480", 印="定時扱い"), [])} if 定時扱い else None
    return 作る_集計.月(上書き=上書き)


def test_見当の所定で定時扱いの日を置けば芯の集計が仮にする():
    import 作る_集計
    決 = {**_時給の人の決まり(), "時間.所定の始業": "9:00", "時間.所定の終業": "18:00"}
    x = 作る_集計.数える(*_定時扱いの月(), 決)
    総 = [r for r in x["行"] if r["項目"] == "総労働"][0]
    assert 総["状態"] == "仮" and "見当" in 総["見当の拠り所"]
    # 定時扱いの日が無い月・勤務の型に所定が在る人・見当の印が無い人は仮にしない
    assert all(r["状態"] == "確定" for r in 作る_集計.数える(*_定時扱いの月(False), 決)["行"] if r["項目"] == "総労働")
    印なし = {k: v for k, v in 決.items() if k != "見当の値"}
    assert all(r["状態"] == "確定" for r in 作る_集計.数える(*_定時扱いの月(), 印なし)["行"] if r["項目"] == "総労働")


def test_見当の所定で定時扱いの日がある時給の委託の人は仮と問い(tmp_path):
    import 作る_集計
    from test_計算_役員と委託 import _報酬の表
    import 作る_計算
    from 芯.計算 import 計算する
    鍵 = ("作り物の会社", "1")
    段の決 = _時給の人の決まり()

    def 回す(tmp, 定時扱い):
        集 = 作る_集計.数える(*_定時扱いの月(定時扱い), {**段の決, "時間.所定の始業": "9:00", "時間.所定の終業": "18:00"})
        # 日ごとの実働を渡さない＝委託.実働の丸め を 丸めない に（無いとそれだけで仮＝この試験が見る 見当の所定 と別の理由になる）
        決 = 作る_計算.決まり(**{k: v for k, v in 段の決.items() if k.startswith("委託.")}, **{"委託.実働の丸め": "丸めない"})
        人 = 作る_計算.人(**{"人.区分": "委託", "委託.時給": "1200"})
        return 計算する(集["行"], 決まり={鍵: 決}, 人={鍵: 人}, 置き場=_報酬の表(作る_計算.置き場(tmp)), 支給月="2026-11")

    r = 回す(tmp_path / "a", True)
    assert r["人"][0]["状態"] == "仮" and r["問い"]
    assert any("見当" in str(q) for q in r["問い"])
    r = 回す(tmp_path / "b", False)
    assert r["人"][0]["状態"] == "確認済", r["問い"]
