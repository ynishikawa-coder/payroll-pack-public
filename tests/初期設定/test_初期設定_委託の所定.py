"""段の解決: 委託だけの人の `時間.日の所定` は勤務の型の所定、空なら前の道具どおり 8（作り物の会社 C1 の値だけ）。

前の道具 pixel-office agents/kyuyo/道具/timecard_tally.py 318・498 行: 勤務の型の 1日の所定時間（空なら 8:00）を日の所定と委託の日当の境に使い、
`委託の所定時間` は委託のみなし残業（563 行）にだけ使う。
- 委託だけ・勤務の型の所定あり → その値（委託.所定時間 は写さない・会社の値のまま渡す）
- 委託だけ・所定が空 → 8 で計算し（芯/集計 の「時間.日の所定 が無い」は出ない）、その人を 仮の値 に 1 つ（出さない）
- 委託の併用・社員には置かない（雇用分の所定が空なら仮のまま）
- 委託.日当の境 の既定（無し＝1 日の所定以上）は勤務の型の所定（無ければ 8）を読む
"""
import importlib.util
import json
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根))
sys.path.insert(0, str(根 / "tests" / "集計"))
sys.path.insert(0, str(根 / "tests" / "計算"))
_spec = importlib.util.spec_from_file_location("初期設定_段の解決_委託の所定", 根 / "初期設定" / "段の解決.py")
段 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(段)

C = "C1"
所定の仮 = "時間.日の所定 が無い"


def _会社(**項目):
    return [{"会社": C, "項目": k, "今の値": v, "適用開始": ""} for k, v in 項目.items()]


def _社員(区分="委託", **列):
    return [{"会社": C, "NO": "0001", "氏名": "作り物 一郎", "人.区分": 区分, **列}]


def _決まり(支給月="2027.02支給", **他):
    r = 段.解く(支給月, **他)
    return r["決まり"][(C, "0001")], r


def _集計(決):
    import 作る_集計
    A, B = 作る_集計.月()
    return json.dumps(作る_集計.数える(A, B, {**決, "時間.所定の始業": "9:00", "時間.所定の終業": "18:00"}),
                      ensure_ascii=False, default=str)


def test_委託だけで所定が空なら前の道具どおり8で計算しその人を仮の値に1つ():
    決, r = _決まり(会社=_会社(**{"委託.所定時間": "7:30"}), 社員=_社員())
    assert 決["時間.日の所定"] == "8" and r["知らせ"] == []
    (仮,) = r["仮の値"]  # 8 は足りない値の見当＝その人は出さない（足りない時は仮で計算し出さない）
    assert (仮["会社"], 仮["NO"], 仮["項目"], 仮["値"]) == (C, "0001", "時間.日の所定", "8") and "前の道具どおり 8" in 仮["拠り所"] and 仮["問い"]
    assert 決["委託.所定時間"] == "7:30"  # 日の所定へ写さず、会社の値のまま（芯/計算 の委託のみなし残業が読む）
    assert 所定の仮 not in _集計(決)


def test_委託だけでも勤務の型の所定があればそれを使う():
    型 = [{"会社": C, "型の名": "短時間", "時間.日の所定": "6:00"}]
    決, r = _決まり(会社=_会社(**{"委託.所定時間": "7:30"}), 勤務の型=型, 社員=_社員(勤務の型="短時間"))
    assert 決["時間.日の所定"] == "6" and 決["勤務の型"]["短時間"]["時間.日の所定"] == "6" and r["仮の値"] == []


def test_委託の併用には置かない():
    型 = [{"会社": C, "型の名": "日勤", "時間.日の所定": "8"}]
    決, _ = _決まり(会社=_会社(**{"委託.所定時間": "6:00"}), 勤務の型=型, 社員=_社員("委託の併用", 勤務の型="日勤"))
    assert 決["時間.日の所定"] == "8" and 決["勤務の型"]["日勤"]["時間.日の所定"] == "8"
    # 雇用分の所定が無い併用の人にも置かない（雇用分の時間外・欠勤の単価を見当で決めない＝仮のまま）
    決, _ = _決まり(会社=_会社(**{"委託.所定時間": "6:00"}), 社員=_社員("委託の併用"))
    assert "時間.日の所定" not in 決
    assert 所定の仮 in _集計(決)


def test_社員には置かない_読めない所定は8で上書きせず仮():
    決, _ = _決まり(会社=_会社(**{"委託.所定時間": "6:00"}), 社員=_社員("社員"))
    assert "時間.日の所定" not in 決
    型 = [{"会社": C, "型の名": "日勤", "時間.日の所定": "8時"}]
