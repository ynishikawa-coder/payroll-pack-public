def test_芯の集計がそのまま受ける_長さの形の人も止まらない():
    A, B = 作る_集計.月()
    r = 解く("2026.11支給")
    for NO, 型 in (("0001", "日勤"), ("0003", "短い日")):
        決 = {**r["決まり"][(C, NO)], "時間.所定の始業": "9:00", "時間.所定の終業": "18:00"}
        A2 = [{**a, "会社": C, "NO": NO, "勤務の型": 型} for a in A]
        B2 = [{**b, "会社": C, "NO": NO} for b in B if b["区間の種別"] == "労働"]  # 休憩を書いていない月
        out = 作る_集計.集計する(A2, B2, 決まり={(C, NO): 決}, 法の線=作る_集計.法の線)
        assert out["人"], NO
    # 時間帯の形の人は表の休憩で確定・長さの形の人は 芯/集計 が会社の長さを読むまで仮（出さない）
    決 = {**r["決まり"][(C, "0001")], "時間.所定の始業": "9:00", "時間.所定の終業": "18:00"}
    A2 = [{**a, "会社": C, "NO": "0001", "勤務の型": "日勤"} for a in A]
    B2 = [{**b, "会社": C, "NO": "0001"} for b in B if b["区間の種別"] == "労働"]
    (人,) = 作る_集計.集計する(A2, B2, 決まり={(C, "0001"): 決}, 法の線=作る_集計.法の線)["人"]
    assert 人["状態"] == "確認済"


