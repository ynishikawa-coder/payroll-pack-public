def test_通勤の限度と除く訳が型に在り段の解決が芯へ渡す(tmp_path):
    spec = importlib.util.spec_from_file_location("初期設定_型の口_段の試験", 根 / "初期設定" / "型の口.py")
    口 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(口)
    assert "手当.通勤の非課税の限度" in 口.見出し("03_マスタ", "社員")
    assert "割増の基礎から除く訳" in 口.見出し("03_マスタ", "支給控除の項目")
    社員 = [{"会社": C, "NO": "0001", "手当.通勤の非課税の限度": "150000"}]
    額 = [{"会社": C, "NO": "0001", "項目": k, "額": v, "適用開始": ""}
         for k, v in (("基本給", "280000"), ("職務手当", "20000"), ("通勤手当", "12000"))]
    r = 段.解く("2027.02支給", 社員=社員, 支給控除の項目=_通勤の行たち(), 人ごとの支給控除=額)
    p, d = r["人"][(C, "0001")], r["決まり"][(C, "0001")]
    assert p["手当.通勤の非課税の限度"] == "150000"
    assert next(x for x in d["項目.行"] if x["名"] == "通勤手当")["割増の基礎から除く訳"] == "通勤手当"
    基 = {k: v for k, v in 作る_計算.人().items() if k not in ("手当.通勤の非課税の限度", "項目.人の額")}
    結果 = 計算する(作る_計算.月の数字(), 決まり={(C, "0001"): 作る_計算.決まり(**{"項目.行": d["項目.行"]})},
                 人={(C, "0001"): {**基, **p}}, 置き場=作る_計算.置き場(tmp_path), 支給月="2027-02")
    assert 結果["人"][0]["状態"] == "確認済", 結果["問い"]
    # 運べなければ（殻が置かないと）赤＋仮になる所＝この 2 つの列の意味
    r = 段.解く("2027.02支給", 社員=[{"会社": C, "NO": "0001"}], 支給控除の項目=_通勤の行たち(""), 人ごとの支給控除=額)
    結果 = 計算する(作る_計算.月の数字(), 決まり={(C, "0001"): 作る_計算.決まり(**{"項目.行": r["決まり"][(C, "0001")]["項目.行"]})},
                 人={(C, "0001"): {**基, **r["人"][(C, "0001")]}}, 置き場=作る_計算.置き場(tmp_path / "b"), 支給月="2027-02")
    assert 結果["人"][0]["状態"] != "確認済"
