def _出勤簿():
    行 = []
    d = date(2027, 2, 1)
    while d.month == 2:
        出る = d.weekday() < 5 and d.isoformat() not in ("2027-02-11", "2027-02-23")  # 土日祝は休み
        for 名 in 人たち.values():
            行.append([名, d.strftime("%Y/%-m/%-d"), *(("9:00", "18:00", "60") if 出る else ("", "", "")), ""])
        d += timedelta(days=1)
    return {"原本の名前": "勤怠_20270301_出勤簿.xlsx", "見出し": ["氏名", "日付", "出勤", "退勤", "休憩", "区分"], "行": 行}


def _通す(tmp_path, 置き場の手=None, **tabs引数):
    import 作る_計算
    import 作る_集計
    from 芯.集計 import 集計する
    from 芯.計算 import 計算する
    tabs = _タブ(**tabs引数)
    置き場 = 作る_計算.置き場(tmp_path)
    if 置き場の手:
        置き場の手(置き場)
    r = 段.解く(支給月, **tabs)
    x = 繋.入口の文脈(支給月, C, r, 置き場=置き場, **tabs)
    読んだ = Excel出勤簿.読む(_出勤簿(), 文脈(**x["文脈"]))
    集 = 集計する(読んだ.日, 読んだ.区間, 決まり=r["決まり"], 法の線=作る_集計.法の線)
    計 = 計算する(集["行"], 決まり=r["決まり"], 人=r["人"], 入力=繋.計算の入力(r["入力"], 集), 置き場=置き場)
    z = 繋.給与の関所へ(計, r["仮の値"], x["仮の値"])
    return r, x, 計, z, 関所.通す(z["行"], z["人の状態"])


def _出た人(通):
    return {r.NO for r in 通.行たち}


def test_仮が無ければ芯の結果のまま関所を通る(tmp_path):
    r, x, 計, z, 通 = _通す(tmp_path)
    assert r["仮の値"] == [] and x["仮の値"] == []
    assert set(計["人の状態"].values()) == {"確認済"}, 計["問い"]
    assert z["行"] == 計["行"] and z["人の状態"] == 計["人の状態"]
    assert _出た人(通) == set(人たち) and 通.外した人たち == ()


