    文脈の所 = len(re.findall(r"全員を仮に\(\"", 文の所)) + len(re.findall(r"仮の値\.append\(", 文の所)) - 1  # 全員を仮に の中の 1 つ
    assert 段の所 == 15 and 文脈の所 == 4
    assert sum(1 for x in 仮の所 if x[3] == "段") >= 段の所 and sum(1 for x in 仮の所 if x[3] == "文脈") >= 文脈の所


