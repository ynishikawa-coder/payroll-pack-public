@pytest.mark.parametrize("名, 引数, 仮の人, 出所, 項目", 仮の所, ids=[x[0] for x in 仮の所])
def test_段の解決と口の仮が残る人は出口へ出ない(tmp_path, 名, 引数, 仮の人, 出所, 項目):
    r, x, 計, z, 通 = _通す(tmp_path, **引数)
    出た仮 = r["仮の値"] if 出所 == "段" else x["仮の値"]
    assert {q["NO"] for q in 出た仮 if q["項目"] == 項目} == 仮の人
    外 = {k.NO for k in 通.外した人たち}
    assert 仮の人 <= 外  # 段の解決・口の仮が 1 つでも残る人は外す（殻の手で 人の状態 へ写さない）
    assert not (_出た人(通) & 仮の人)
    assert all(z["人の状態"][k] == "仮" for k in z["人の状態"] if k[2] in 仮の人)
    assert all(a["状態"] == "仮" for a in z["行"] if a["NO"] in 仮の人)
    # 仮の無い人は今までどおり（芯の結果のまま）
    芯の仮 = {k[2] for k, v in 計["人の状態"].items() if v != "確認済"}
    assert 外 == 仮の人 | 芯の仮
    for a, b in zip(z["行"], 計["行"]):
        if a["NO"] not in 仮の人:
            assert a == b


