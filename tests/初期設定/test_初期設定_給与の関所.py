def 確定して回す(支給月_, 会社, tabs, 原本, *, 区分の読み替え=None, 人の区分の読み替え=None, 質問と回答=(), 前の原本=None,
           つなぎ=(), 置き場=None, **引数):
    """試験の道: 原本 → 月次.読んだままの勤怠を作る（AI の道具・1 次）→ 質問と回答があれば 月次.答えを確定した勤怠へ
    （答えで変わった日の行＝直した訳 `問い:<番号>`）→ 読みが確定した人だけを 台帳の形.勤怠の表たち（確定した勤怠の表）に
    答えの行を重ねる → 月次.月を回す（確定した勤怠だけを読む）。要確認が残る人は締まっていない＝確定した勤怠へ書かない。"""
    import 月次
    def 確定(月_, 原本_):
        共 = dict(区分の読み替え=区分の読み替え, つなぎ=つなぎ, 人の区分の読み替え=人の区分の読み替え, 置き場=置き場)
        読 = 月次.読んだままの勤怠を作る(月_, 会社, tabs, 原本_, **共)
        状態, 答, 答えの日 = 読["人の状態"], None, set()
        if 質問と回答:
            答 = 月次.答えを確定した勤怠へ(月_, 会社, tabs, 原本_, 質問と回答, **共)
            状態 = 答["人の状態"]
            答えの日 = {(str(r["NO"]), r["日付"]) for r in 月次.台帳の形.行たち(答["確定した勤怠"])}
            読 = {**読, "知らせ": [*読["知らせ"], *答["知らせ"]], "要確認": 答["要確認"], "答え": 答}
        済 = {str(NO) for NO, s in 状態.items() if s == "確定"}
        残す = lambda a: str(a.get("NO", "")) in 済 and (str(a.get("NO", "")), a.get("日付")) not in 答えの日
        表 = 月次.台帳の形.勤怠の表たち(確定=True, 勤怠=[a for a in 読["表A"] if 残す(a)],
                                 勤怠の区間=[b for b in 読["表B"] if 残す(b)], 氏名=月次._氏名(tabs, 会社))
        if 答:
            NO列 = 表["確定した勤怠"][0].index("NO")
            表 = {k: [*v, *[r for r in 答[k][1:] if str(r[NO列 if k == "確定した勤怠" else 答[k][0].index("NO")]) in 済]]
                 for k, v in 表.items()}
        月の数字 = [a for a in 読["月の数字"] if str(a.get("NO", "")) in 済]
        return 表, 読, 月の数字
    表, 読, 月の数字 = 確定(支給月_, 原本)
    if 前の原本 is not None:
        if "前の確定した勤怠" in 引数 or "前の確定した勤怠の区間" in 引数:
            raise ValueError("前の原本と前の確定した勤怠は一緒に渡せない（どちらの前の期間を使うか決まらない）")
        前, _, _ = 確定(月次.前の支給月(支給月_), 前の原本)
        引数 = {**引数, "前の確定した勤怠": 前["確定した勤怠"], "前の確定した勤怠の区間": 前["確定した勤怠の区間"]}
    tabs = {**tabs, "その月だけの指示": [*月次.台帳の形.行たち(tabs.get("その月だけの指示", ())), *読["その月だけの指示"]]}
    if "例" in 引数:   # 試験の例の行は 給与のルール.md の字にして渡す（月を回す は MD だけから例を読む）
        例 = 引数.pop("例")
        列 = 月次.例の確かめ.MDの例の列
        md = ["# 給与のルール（作り物）", ""]
        for i, e in enumerate(月次.例の確かめ.行たち(例 or ())):
            md += [f"### 例 {i + 1}", "", "| " + " | ".join(列) + " |", "|" + "---|" * len(列),
                   "| " + " | ".join(str(e.get(c, "") or "").replace("|", "\\|") for c in 列) + " |", ""]
        引数["給与のルール"] = None if 例 is None else "\n".join(md)
    if "締めの記録" not in 引数:   # 読みが確定した人（確定した勤怠へ書いた人）を 締まった、ほかを まだ にする
        NO列 = 表["確定した勤怠"][0].index("NO")
        書いた = {str(r[NO列]) for r in 表["確定した勤怠"][1:]}
        人 = sorted({*書いた, *(str(a.get("NO", "")) for a in 読["表A"])})
        引数["締めの記録"] = [list(月次.勤怠の照らし.締めの列)] + [
            [会社, 支給月_, NO, "", "締まった" if NO in 書いた else "まだ", "", ""] for NO in 人]
    o = 月次.月を回す(支給月_, 会社, tabs, 確定した勤怠=表["確定した勤怠"], 確定した勤怠の区間=表["確定した勤怠の区間"],
                  読んだままの勤怠=読["読んだままの勤怠"], 読んだままの勤怠の区間=読["読んだままの勤怠の区間"],
                  月の数字=月の数字, つなぎ=つなぎ, 置き場=置き場, **引数)
    # 読んだまま＝道具の返す物（1 次・要確認・答えの知らせ）。読みの要確認は道具の問いの種＝殻が月の問いと一緒に 設問 へ渡す
    return {**o, "問い": {**o["問い"], "入口": 読["要確認"]}, "読んだまま": 読, "確定した勤怠": 表}
