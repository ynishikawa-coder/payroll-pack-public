@pytest.mark.parametrize("字, 渡す", [("当月", "当月"), (" 翌月 ", "翌月"), ("翌々月", "翌々月"), ("来月", None), ("翌月払い", None)])
def test_支給の月の字をそろえる(字, 渡す):
    r = 段.解く(支給月, **_タブ(会社={"支払.支給の月": 字}))
    d = r["決まり"][(C, "0001")]
    assert d.get("支払.支給の月") == 渡す
    問い = [q for q in r["仮の値"] if q["項目"] == "支払.支給の月"]
    assert len(問い) == (0 if 渡す else len(人たち))  # 人ごとに 1 つ（同じ人×項目に 2 つ出さない）
    assert all("当月・翌月・翌々月" in q["問い"] for q in 問い)


def test_読めない暦は芯へ渡さず問いは人ごとに1つ(tmp_path):
    r, x, 計, z, 通 = _通す(tmp_path, 会社={"時間.暦": "土日祝"}, 型={"短時間": {"時間.暦": "土日"}})
    d = r["決まり"][(C, "0001")]
    assert "時間.暦" not in d and all("時間.暦" not in v for v in d["勤務の型"].values())
    for NO in 人たち:  # 会社の段と型の段の 2 つの所に 1 つずつ（入口の文脈は知らせだけ＝二重に問わない）
        assert sorted(q["拠り所"].split(" の")[0] for q in r["仮の値"] if q["NO"] == NO and q["項目"] == "時間.暦") == \
            ["03_マスタ/会社/C1/時間.暦", "03_マスタ/勤務の型/C1/短時間/時間.暦"]
    assert not [q for q in x["仮の値"] if q["項目"] == "時間.暦"]
    assert _出た人(通) == set()


