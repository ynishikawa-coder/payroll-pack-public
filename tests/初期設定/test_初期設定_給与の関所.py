def test_読めない人の休日は見当で数え問いは1つ(tmp_path):
    r, x, 計, z, 通 = _通す(tmp_path, 人={"0002": {"休日.人の休日": "お盆"}})
    q = [q for q in [*r["仮の値"], *x["仮の値"]] if q["項目"] == "休日.人の休日"]
    assert [(a["会社"], a["NO"]) for a in q] == [(C, "0002")] and q[0]["問い"]  # 段の解決の 1 つだけ（入口の文脈と二重にしない）
    assert x["仮の値"] == [] and r["人の休日"] == {}  # 読めない字は入口へ渡さない
    assert any("休日.人の休日" in s for s in r["知らせ"])
    # 計算は続く（会社と型の休日で見当）: 0002 の行も芯は出す。関所が外すだけ
    assert any(a["NO"] == "0002" for a in 計["行"])
    assert _出た人(通) == {"0001", "0003"} and {k.NO for k in 通.外した人たち} == {"0002"}
