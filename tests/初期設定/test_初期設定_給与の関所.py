def test_仮を出す所を全部拾う():
    """段の解決・入口の文脈が 仮の値 を足す所の数を見張る。増えたら 仮の所 に例を足し、給与の関所へ が拾うかを見る。"""
    import re
    段の所 = len(re.findall(r"仮の値\.append\(", (根 / "初期設定" / "段の解決.py").read_text(encoding="utf-8")))
    文 = (根 / "初期設定" / "入口の文脈.py").read_text(encoding="utf-8")
