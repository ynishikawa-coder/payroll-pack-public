"""住民税の 6 月分と 7 月以降（型の版 4・直し 4）。作り物の会社 C1 の値だけ。

- 段の解決は社員の列 住民税.6月分・住民税.7月以降 を 住民税.額 の {6月分, 7月以降} にまとめるだけ（月を見ない）
- 人ごとの支給控除の行 住民税.額（優先 B）が在ればそれが勝ち、2 つの列は渡さない（二重にしない）
- 選ぶのは芯/計算 の 1 か所: 特別徴収は 6 月支給分から新しい年度＝支給月が 6 月なら 6月分・7 月〜翌 5 月は 7月以降
  （前の道具 pixel-office agents/kyuyo の kyuyo_calc も支給月の月で選ぶ）
"""
import importlib.util
import sys
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根))
sys.path.insert(0, str(根 / "tests" / "計算"))
_spec = importlib.util.spec_from_file_location("初期設定_段の解決_住民税", 根 / "初期設定" / "段の解決.py")
段 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(段)

import 作る_計算  # noqa: E402
from 芯.計算 import 計算する  # noqa: E402

C = "C1"


def _社員(**列):
    return [{"会社": C, "NO": "0001", "氏名": "作り物 一郎", **列}]


def test_2つの列を住民税の額へまとめる():
    r = 段.解く("2027.06支給", 社員=_社員(**{"住民税.6月分": "9100", "住民税.7月以降": "9000"}))
    p = r["人"][(C, "0001")]
    assert p["住民税.額"] == {"6月分": "9100", "7月以降": "9000"}
    assert "住民税.6月分" not in p and "住民税.7月以降" not in p


def test_片方だけでもまとめる_無い月は芯が仮にする():
    p = 段.解く("2027.06支給", 社員=_社員(**{"住民税.7月以降": "9000"}))["人"][(C, "0001")]
    assert p["住民税.額"] == {"7月以降": "9000"}


def test_人ごとの支給控除の行が勝つ():
    r = 段.解く("2027.06支給", 社員=_社員(**{"住民税.6月分": "9100", "住民税.7月以降": "9000"}),
               人ごとの支給控除=[{"会社": C, "NO": "0001", "項目": "住民税.額", "額": "8000", "適用開始": ""}])
    p = r["人"][(C, "0001")]
    assert p["住民税.額"] == "8000"
    assert "住民税.6月分" not in p and "住民税.7月以降" not in p


def test_変更の記録で7月以降の額が月ごとに引ける():
    記録 = [{"会社": C, "NO": "0001", "項目": "住民税.7月以降", "前の値": "8000", "新しい値": "9000",
           "適用支給月": "2027.07支給", "記録日": "2027-06-10", "確かめ": "確認済"}]
    社員 = _社員(**{"住民税.6月分": "9100", "住民税.7月以降": "9000"})
    前 = 段.解く("2027.05支給", 社員=社員, 変更の記録=記録)["人"][(C, "0001")]
    後 = 段.解く("2027.07支給", 社員=社員, 変更の記録=記録)["人"][(C, "0001")]
    assert 前["住民税.額"]["7月以降"] == "8000" and 後["住民税.額"]["7月以降"] == "9000"


@pytest.mark.parametrize("支給月, 額", [("2027-05", 9000), ("2027-06", 9100), ("2027-07", 9000)])
def test_芯は支給月で1つを選ぶ(tmp_path, 支給月, 額):
    p = 段.解く(支給月.replace("-", ".") + "支給", 社員=_社員(**{"住民税.6月分": "9100", "住民税.7月以降": "9000"}))["人"][(C, "0001")]
    人 = 作る_計算.人(**{"住民税.額": p["住民税.額"]})
    r = 作る_計算.回す(tmp_path, 支給月=支給月, 人の値=人)
    assert 作る_計算.値たち(r)["住民税"] == 額
