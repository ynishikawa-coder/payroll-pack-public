def test_法の線の点検は3つの穴を食い違いに出す():
    t = _タブ(会社の行=[("時間.打刻の丸めの向き", "短くする"), ("割増.休日の率", "0")],
              項目=[{"項目": "作り物の役の手当", "支給か控除": "支給", "割増の基礎": "入らない", "割増の基礎から除く訳": "会社の決まり"},
                    {"項目": "作り物の家族手当", "支給か控除": "支給", "割増の基礎": "入らない", "割増の基礎から除く訳": "家族手当"}])
    r = 設問.法の線の点検(t, C, "2099.04支給")
    食い = {x["項目"]: x for x in r["食い違い"]}
    assert set(食い) == {"時間.打刻の丸めの向き", "割増.休日の率", "割増.基礎に入る"}
    assert 食い["割増.休日の率"]["法の値"] == "1.35" and 食い["割増.休日の率"]["承知できる"]
    assert 食い["割増.基礎に入る"]["誰"] == ["作り物の役の手当"] and 食い["割増.基礎に入る"]["承知できる"]
    種 = 設問.法の線の種(r, C)
    assert {s["何が無いか"] for s in 種} == {"法の線: 時間.打刻の丸めの向き（全員）", "法の線: 割増.休日の率（全員）",
                                         "法の線: 割増.基礎に入る（支給控除の項目: 作り物の役の手当）"}
    基礎 = next(s for s in 種 if s["何が無いか"].startswith("法の線: 割増.基礎に入る"))
    assert 基礎["反映先"] == "2_マスタ/支給控除の項目/作り物の役の手当、2_マスタ/会社/法の線.承知"
    assert "今の払い方のまま払う" in 基礎["答え方の例"]
    # 会社独自の決まりは在るのが当たり前（2026-11-16）＝承知できる線は今の払い方の確認（線ごとに 1 回の承知で以降はそのまま）。
    # おすすめの印は付けない（2026-11-17 オーナー: 見込みを前提にさせない）
    assert all(s["箱"] == "法の線" and s["答え方の例"] == "今の払い方のまま払う／法の線に直して払う" for s in 種)
    assert all(設問.種類(s) == "会社の決まり" for s in 種)


