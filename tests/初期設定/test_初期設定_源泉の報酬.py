"""段の解決: 会社のタブの `源泉.報酬` を型どおり 1 つの値で芯へ渡す（作り物の会社 C1 の値だけ）。

- 置く所がほかのタブの項目（源泉.報酬 など）を会社のタブに書いた時は 1 つの値（並びにしない＝芯が字で比べられる）
- 会社の行の束（置く所＝03_マスタ「会社」の行。休暇.特別休暇）だけ効く行を全部並べる
- 並び・知らない字・同じ適用開始で食い違う行は渡さず、知らせ＋その人を 仮の値＋問い 1 つ（黙って法の率で確定しない）
- 段の解決から芯/計算 まで通して: 対象でない の委託だけの人は源泉 0
"""
import importlib.util
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根))
sys.path.insert(0, str(根 / "tests" / "計算"))
_spec = importlib.util.spec_from_file_location("初期設定_段の解決_源泉の報酬", 根 / "初期設定" / "段の解決.py")
段 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(段)

C = "C1"


def _解く(*行, 支給月="2027.02支給"):
    会社 = [{"会社": C, "項目": k, "今の値": v, "適用開始": a} for k, v, a in 行]
    return 段.解く(支給月, 会社=会社, 社員=[{"会社": C, "NO": "0001", "人.区分": "委託"}])


def test_源泉の報酬は1つの値で渡る_並びにしない():
    r = _解く(("源泉.報酬", "対象でない", ""))
    assert r["決まり"][(C, "0001")]["源泉.報酬"] == "対象でない"
    assert [x for x in r["仮の値"] if x["項目"] == "源泉.報酬"] == [] and r["知らせ"] == []
    # 全角の空白や前後の空白はそろえる
    assert _解く(("源泉.報酬", " 対象　でない ", ""))["決まり"][(C, "0001")]["源泉.報酬"] == "対象でない"


def test_源泉の報酬は適用開始で一番新しい行():
    行 = (("源泉.報酬", "対象", ""), ("源泉.報酬", "対象でない", "2027.02支給"))
    assert _解く(*行, 支給月="2027.01支給")["決まり"][(C, "0001")]["源泉.報酬"] == "対象"
    assert _解く(*行)["決まり"][(C, "0001")]["源泉.報酬"] == "対象でない"


def test_会社の行の束は今までどおり並び():
    r = _解く(("休暇.特別休暇", "作り物の休み・1・有給", ""), ("休暇.特別休暇", "作り物の休み2・2・無給", ""))
    assert r["決まり"][(C, "0001")]["休暇.特別休暇"] == ["作り物の休み・1・有給", "作り物の休み2・2・無給"]


def _仮と知らせ(r):
    (仮,) = [x for x in r["仮の値"] if x["項目"] == "源泉.報酬"]
    assert "源泉.報酬" not in r["決まり"][(C, "0001")]          # 渡さない
    assert (仮["会社"], 仮["NO"]) == (C, "0001") and 仮["問い"] and "対象" in 仮["問い"]
    assert any("源泉.報酬" in t for t in r["知らせ"])


def test_並びや知らない字は渡さず仮と問い1つ():
    _仮と知らせ(_解く(("源泉.報酬", '["対象でない"]', "")))
    _仮と知らせ(_解く(("源泉.報酬", "対象外", "")))


def test_同じ適用開始で食い違う行は1つに決めず仮と問い1つ():
    _仮と知らせ(_解く(("源泉.報酬", "対象", ""), ("源泉.報酬", "対象でない", "")))
    # 同じ値が 2 行なら 1 つに決まる
    r = _解く(("源泉.報酬", "対象でない", ""), ("源泉.報酬", "対象でない", ""))
    assert r["決まり"][(C, "0001")]["源泉.報酬"] == "対象でない" and r["知らせ"] == []
    assert [x for x in r["仮の値"] if x["項目"] == "源泉.報酬"] == []


def test_段の解決から芯まで通して対象でないの委託だけの人は源泉0(tmp_path):
    import 作る_計算
    from test_計算_役員と委託 import _報酬の表
    from 芯.計算 import 計算する
    r = _解く(("源泉.報酬", "対象でない", ""), ("委託.式", "日給", ""), ("委託.丸め", "切捨て", ""))
    鍵 = (C, "0001")
    決 = 作る_計算.決まり(**{k: v for k, v in r["決まり"][鍵].items() if k.startswith(("委託.", "源泉."))})
    人 = 作る_計算.人(**{"人.区分": "委託", "委託.日給": "10000", "委託.時給": "1250"})
    out = 計算する(作る_計算.月の数字(上書き={"出勤日数": "3", "法定休日": "0", "所定休日": "0"}), 決まり={鍵: 決}, 人={鍵: 人},
               置き場=_報酬の表(作る_計算.置き場(tmp_path)), 支給月="2027-02")
    v = {x["項目"]: x["値"] for x in out["行"]}
    assert v["委託分の報酬"] == 30000 and v["委託分の源泉所得税"] == 0 and v["支払合計"] == 30000
    assert out["人の状態"][("2027-02", C, "0001")] == "確認済"
