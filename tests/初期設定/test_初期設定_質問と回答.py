def _台(タブ, 格子, 対象="E01", 何を="立替", 値="1200", 鍵="Q2", 反映先=None):
    f = qa.振り分け(鍵, "C900", 対象, 反映先 or "台帳/その月だけの指示", 何を, 値)
    return qa.照らす(f, {"会社": {"C900": {"台帳": {タブ: 格子}}}})


def _指(*行):
    return [_指示頭, *[["C900", "2099.01支給", n, "作り物", 項, 値, "x", 鍵] for n, 項, 値, 鍵 in 行]]


def test_その月だけの指示は_NO_項目_値_で合い_問いの番号で絞る():
    for タブ in ("5_その月だけの指示", "その月だけの指示"):     # Drive の名でも型の名でも引ける
        assert _台(タブ, _指(("E01", "立替", "1200", "Q2")))
    assert not _台("5_その月だけの指示", _指(("E01", "立替", "999", "Q2")))                      # 値が違う
    assert not _台("5_その月だけの指示", _指(("E02", "立替", "1200", "Q2")))                     # 人が違う
    assert not _台("5_その月だけの指示", _指(("E01", "手当", "1200", "Q2")))                     # 項目が違う
    assert _台("5_その月だけの指示", _指(("E01", "立替", "1200", "Q2"), ("E01", "立替", "5", "Q9")))   # 問いの番号で絞る
    assert not _台("5_その月だけの指示", _指(("E01", "立替", "1200", "Q8"), ("E01", "立替", "5", "Q9")))  # 番号の合う行が無く値が割れる
    assert not _台("5_その月だけの指示", _指(("E01", "立替", "1200", "Q8")))                     # 値は合うが別の問いの行＝書かれていない
    assert not _台("5_その月だけの指示", _指(("E01", "立替", "1200", "")))                       # 番号の空の行＝書かれていない
    assert not _台("5_その月だけの指示", [_指示頭[:-1], ["C900", "2099.01支給", "E01", "作り物", "立替", "1200", "x"]])  # 問いの番号 の列が無い
    assert _台("5_その月だけの指示", _指(("", "立替", "1200", "Q2")), 対象="会社")                 # 会社の指示は NO が空の行
    assert not _台("5_その月だけの指示", [["氏名", "項目", "値"], ["作り物", "立替", "1200"]])       # 人の列が無い
    assert not _台("5_その月だけの指示", _指(("E01", "立替", "1200", "Q2")), 何を="")


