def _md(本文, 値="20日締め", 先="給与のルール.md", 鍵="Q1", 何を="締め"):
    return qa.照らす(qa.振り分け(鍵, "C900", "会社", 先, 何を, 値), {"会社": {"C900": {"給与のルール.md": 本文}}})


def test_md_は印の行の値が一字同じ時だけ合う_本文の字の含みでは合わない():
    印 = qa.md_の答えの行(qa.振り分け("Q1", "C900", "会社", "給与のルール.md", "締め", "20日締め"))
    assert 印 == "- ⟦答え:Q1｜締め⟧ 20日締め"
    assert _md(f"# 作り物\n{印}\n")                                        # 合う道
    assert not _md("# 作り物\n25日締め とする。20日締め にはしない\n")        # (a) 否定の文に値の字が在る
    assert not _md("# 作り物\n手当は 1000円\n", 値="1")                       # (b) 値が別の数の中に在る
    assert not _md("# 作り物\n- ⟦答え:Q1｜締め⟧ 25日締め\n")                 # 印は在るが値が違う
    assert not _md(f"# 作り物\n{印}\n- ⟦答え:Q1｜締め⟧ 25日締め\n")         # 同じ印に違う値＝どちらが効くか決まらない
    assert not _md(f"# 作り物\n{印}\n", 鍵="Q2")                             # 別の問いの印
    assert not _md(f"  ~ {印}x\n")                                           # 行の頭からの印でない
    assert not _md("")                                                       # 空の本文
    assert not qa.照らす(qa.振り分け("Q1", "C900", "会社", "給与のルール.md", "締め", "20日締め"), {})   # 実物なし


