"""始める の置き場の（M月分）が会社の `支払.支給の月` から出ること（確認ページの名と同じ 1 か所の式）。作り物の会社だけ。"""
import importlib.util
import re
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("初期設定_始める_月の名", 根 / "初期設定" / "始める.py")
始める = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(始める)


def _入力(**会社の値):
    return {"会社": "作り物の会社", "組": "作り物の組", "最初の支給月": "2099.04支給", "今日": "2099-03-01", "既にある": [],
            "会社の値": {k: {"値": v, "書類の名": "書類_2099-03-01_作り物"} for k, v in 会社の値.items()}}


@pytest.mark.parametrize("支給の月, 月分", [("当月", 4), ("翌月", 3), ("翌々月", 2), (None, 3)])
def test_始めるの置き場は会社の支給の月で月分を出す(支給の月, 月分):
    r = 始める.始める(_入力(**({"支払.支給の月": 支給の月} if 支給の月 else {})))
    月 = f"2099.04支給（{月分}月分）"
    assert f"10_会社/作り物の組/3_月ごと/{月}/1_届いた物" in r["置き場"]
    assert f"10_会社/作り物の組/3_月ごと/{月}/2_出す物" in r["置き場"]
    assert {"10_会社/作り物の組/8_確認事項", "10_会社/作り物の組/9_履歴"} <= set(r["置き場"])
    # 会社の根の下は今の形の名だけ（Drive の型 §2）＝前の形のフォルダ（0n_・10_・20_・90_ の頭など）は作らない
    今の形 = r"10_会社/作り物の組/(1_決まり|2_マスタ|台帳_\d{4}|3_月ごと/[^/]+/(1_届いた物|2_出す物)|8_確認事項|9_履歴)"
    assert not [x for x in r["置き場"] if not re.fullmatch(今の形, x)], r["置き場"]
    # 会社にも事務所にも無ければ翌月で置き知らせる（項目の既定へ黙って落とさない＝2026-11-28 決まりを集める段）
    assert len(r["知らせ"]) == (1 if 支給の月 is None else 0), r["知らせ"]
    assert 月 == 始める.確認ページ.支給月の名("2099.04支給", 支給の月)


def test_始めるの支給の月が読めない時は翌月で知らせる():
    r = 始める.始める(_入力(**{"支払.支給の月": "来月"}))
    assert "10_会社/作り物の組/3_月ごと/2099.04支給（3月分）/2_出す物" in r["置き場"]
    assert len(r["知らせ"]) == 1 and "読めない" in r["知らせ"][0]


def test_始めるは会社ごとの質問と回答を起こさない():
    # 質問と回答は事務所の根に 1 冊（型 41）。会社ごとに起こすと前の 1 タブの形（会社ごとの 8_確認事項 の本）が戻る
    r = 始める.始める(_入力())
    assert 始める.口.名("質問と回答") not in r["シート"], sorted(r["シート"])
    assert set(r["シート"]) == {始める.口.名("マスタ"), "台帳_2099"}, sorted(r["シート"])


def test_始めるの支給の月は事務所の既定の行から引く():
    入力 = {**_入力(), "事務所": [{"項目": "支払.支給の月", "今の値": "当月", "適用開始": ""}]}
    r = 始める.始める(入力)
    assert "10_会社/作り物の組/3_月ごと/2099.04支給（4月分）/2_出す物" in r["置き場"]
    assert r["知らせ"] == []
