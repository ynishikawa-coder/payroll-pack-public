# ---- 3: 支払.締め日・支払.支給日 ----
def test_締め日と支給日が無ければ末で見当し問いは芯の1つだけ(tmp_path):
    import 作る_計算
    from test_計算_役員と委託 import _報酬の表
    from 芯.計算 import 計算する
    r, tabs = _解く(_会社(**{"支払.締め日": None, "支払.支給日": None}))
    x = 繋.入口の文脈(支給月, C, r, 置き場=作る_計算.置き場(tmp_path), **tabs)
    assert (x["文脈"]["期間の始め"], x["文脈"]["期間の終わり"]) == ("2027-02-01", "2027-02-28")  # 末で見当
    assert x["仮の値"] == []  # 繋ぎは仮も問いも出さない（二重にしない）
    assert any("支払.締め日" in t for t in x["知らせ"])
    決 = r["決まり"][(C, "0002")]
    assert "支払.締め日" not in 決 and "支払.支給日" not in 決  # 黙って既定を埋めない
    # 問いは 芯/計算 の 要る値 が出す（締め日・支給日 それぞれ 1 つ）
    鍵 = (C, "0002")
    結果 = 計算する(作る_計算.月の数字(NO="0002"), 決まり={鍵: 決}, 人={鍵: r["人"][鍵]},
                 置き場=_報酬の表(作る_計算.置き場(tmp_path / "2")), 支給月="2027-02")
    問 = [q["何が無いか"] for q in 結果["問い"]]
    assert 問.count("「支払.締め日」が無い") == 1 and 問.count("「支払.支給日」が無い") == 1


