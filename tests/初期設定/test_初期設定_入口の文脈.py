# ---- 2: 委託.日ごとの実働（段の解決 → 入口 → 集計 → 計算） ----
出勤簿 = {
    "原本の名前": "勤怠_20270301_出勤簿.xlsx",
    "見出し": ["氏名", "日付", "出勤", "退勤", "休憩", "区分"],
    "行": [
        ["いちろう", "2027/2/1", "9:00", "18:00", "60", ""],   # 480 分＝境（所定 8 時間）以上＝日当
        ["いちろう", "2027/2/2", "9:00", "13:00", "", ""],     # 240 分＝時給
        ["いちろう", "2027/2/3", "10:00", "17:00", "60", ""],  # 360 分＝時給
    ],
}
殻が作っていた実働 = {"2027-02-01": 480, "2027-02-02": 240, "2027-02-03": 360}  # 前の道具: 打刻の和−休憩（日ごと）


def _通す(tmp_path):
    import 作る_計算
    import 作る_集計
    from test_計算_役員と委託 import _報酬の表
    from 芯.集計 import 集計する
    from 芯.計算 import 計算する
    人ごと = [{"会社": C, "NO": "0001", "項目": k, "額": v, "適用開始": ""}
            for k, v in (("委託.日給", "10000"), ("委託.時給", "1500"))]
    会社 = _会社(**{"委託.式": "日ごとに時給か日当", "委託.丸め": "1円切捨て"})
    社員 = [_社員()[0]]
    tabs = {"会社": 会社, "勤務の型": 勤務の型, "社員": 社員, "人ごとの支給控除": 人ごと}
    r = 段.解く(支給月, **tabs)
    置き場 = _報酬の表(作る_計算.置き場(tmp_path))
    x = 繋.入口の文脈(支給月, C, r, 置き場=置き場, **tabs)
    読んだ = Excel出勤簿.読む(出勤簿, 文脈(**x["文脈"]))
    集 = 集計する(読んだ.日, 読んだ.区間, 決まり=r["決まり"], 法の線=作る_集計.法の線)
    入力 = 繋.計算の入力(r["入力"], 集)
    鍵 = (C, "0001")

    def 計算(入):
        return 計算する(集["行"], 決まり={鍵: r["決まり"][鍵]}, 人={鍵: r["人"][鍵]}, 入力=入, 置き場=置き場,
                     支給月="2027-02")
    return 集, 入力, 計算(入力), 計算({鍵: {"委託.日ごとの実働": 殻が作っていた実働}})


def test_集計の日ごとの実働を委託の入力へ渡す(tmp_path):
    集, 入力, 結果, 殻の結果 = _通す(tmp_path)
    assert 集["日ごとの実働"] == [{"支給月": "2027-02", "会社": C, "NO": "0001", "日ごと": 殻が作っていた実働}]
    assert 入力 == {(C, "0001"): {"委託.日ごとの実働": 殻が作っていた実働}}
    値 = {x["項目"]: x["値"] for x in 結果["行"]}
    assert 値["委託分の報酬"] == 10000 + 4 * 1500 + 6 * 1500
    assert not any("日ごとの実働" in q["何が無いか"] for q in 結果["問い"])
    # 殻が手で作った 委託.日ごとの実働 を渡した時と同じ
    assert [(x["項目"], x["値"], x["状態"]) for x in 結果["行"]] == [(x["項目"], x["値"], x["状態"]) for x in 殻の結果["行"]]


def test_日ごとの実働は委託の人の勤務の日だけ():
    import 作る_集計
    from 芯.集計 import 集計する
    A, B = 作る_集計.月(日数=7, 上書き={
        "2026-11-07": (作る_集計.日("2026-11-07", "休日勤務"), [作る_集計.区("2026-11-07", 1, "9:00", "12:00")])})
    社員の結果 = 集計する(A, B, 決まり={("作り物の会社", "1"): 作る_集計.既定の決まり()}, 法の線=作る_集計.法の線)
    assert 社員の結果["日ごとの実働"] == []  # 委託でない人は出さない
    委 = 集計する(A, B, 決まり={("作り物の会社", "1"): 作る_集計.既定の決まり(**{"人.区分": "委託の併用"})},
               法の線=作る_集計.法の線)
    (x,) = 委["日ごとの実働"]
    assert x["日ごと"] == {f"2026-11-0{d}": 480 for d in range(2, 7)}  # 休日勤務の日は入れない


def test_計算の入力は段の入力を残す():
    段の入力 = {(C, "0002"): {"委託.雇用分の出勤時間": "150:00"}}
    out = 繋.計算の入力(段の入力, {"日ごとの実働": [{"会社": C, "NO": "0002", "日ごと": {"2027-02-01": 300}},
                                              {"会社": C, "NO": "0009", "日ごと": {}}]})
    assert out == {(C, "0002"): {"委託.雇用分の出勤時間": "150:00", "委託.日ごとの実働": {"2027-02-01": 300}}}
    assert 段の入力 == {(C, "0002"): {"委託.雇用分の出勤時間": "150:00"}}
