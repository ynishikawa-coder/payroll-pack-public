"""段の解決の後の繋ぎ（初期設定/入口の文脈.py）。作り物の会社 C1 の値だけ。

1. 入口の文脈: 決まり（支払.締め日・支払.支給の月・時間.暦・勤務の型・時間.出勤簿が無い・人.区分）から入口の 文脈 の値を作る
2. 委託.日ごとの実働: 芯/集計 が表 A・B から {日付: 分} を出し、計算の入力 が 芯/計算 の 入力 へ足す
   （前の道具 timecard_tally の 日ごとの実働＝打刻の和−休憩・休日出勤の行は入れない と同じ）
3. 支払.締め日・支払.支給日: マスタに行が無ければ値を埋めず、期間は末で見当して知らせ。仮と問いは 芯/計算 の 要る値 の 1 つだけ
殻の手を使わず 段の解決 → 入口 → 集計 → 計算 を通し、殻が手で作っていた物と同じになるかを見る。
"""
