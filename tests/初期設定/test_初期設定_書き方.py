"""書き方の 1 か所（初期設定/型の口.py）: 殻の書く口が RAW を選べず入力扱いだけの時に字のまま入れる形と、書いた後の照らし。作り物の値だけ。"""
import importlib.util
import sys
from decimal import Decimal
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
_s = importlib.util.spec_from_file_location("試験_型の口_書き方", 根 / "初期設定" / "型の口.py")
口 = importlib.util.module_from_spec(_s)
_s.loader.exec_module(口)


def test_入力扱いでも字のまま_字の頭に印_数と空はそのまま():
    格子 = [["NO", "日付", "出"], ["0001", "2027/2/3", "9:00"], ["", Decimal("12"), 5]]
    assert 口.入力扱いでも字のまま(格子) == [["'NO", "'日付", "'出"], ["'0001", "'2027/2/3", "'9:00"], ["", Decimal("12"), 5]]


def test_入力扱いの手順は値を書く手順だけを変える():
    手順 = [{"する": "file を移す", "前": "a", "後": "b"},
          {"する": "値を書く", "値": [["0001", "2027.02支給"]], "書き方": "RAW"}]
    移す, 書く = 口.入力扱いの手順(手順)
    assert 移す == 手順[0]
    assert 書く["書き方"] == "USER_ENTERED" and 書く["値"] == [["'0001", "'2027.02支給"]]
    assert 手順[1]["値"] == [["0001", "2027.02支給"]]   # 元の手順は変えない


def test_書いた値を照らす_数や日付に読まれた所を返す():
    書いた = [["0001", "2027/2/3", "所定"], ["0002", "9:00", 12]]
    assert 口.書いた値を照らす(書いた, [["0001", "2027/2/3", "所定"], ["0002", "9:00", "12"]]) == []
    assert 口.書いた値を照らす([[Decimal("12.50")]], [["12.5"]]) == []          # 数で書いた値は数で比べる
    assert 口.書いた値を照らす([["12.50"]], [["12.5"]]) != []                   # 字で書いた値は字のまま
    違う = 口.書いた値を照らす(書いた, [["1", "46421", "所定"], ["0002", "9:00:00", "12"]])
    assert 違う == ["1行1列: 書いた「0001」・読んだ「1」", "1行2列: 書いた「2027/2/3」・読んだ「46421」",
                  "2行2列: 書いた「9:00」・読んだ「9:00:00」"]


def test_出口の書く手順も入力扱いを選べる():
    sys.path.insert(0, str(根 / "tests" / "出口"))
    import 出口_作り物 as 作
    from 出口 import 書き口, 関所
    表 = 書き口.取り込み(関所.通す(作.行たち, {}), "9", 作.月, 作.対応, {**作.形の値, "渡し方": "表"}, "60進", 委託の人=[], 今ある名=[], 履歴にある名=[])
    書く = 表.書く手順("USER_ENTERED")[-1]
