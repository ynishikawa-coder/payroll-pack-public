"""tests 全体の pytest の設定。

作り物の事務所は「既定」のタブに、芯/設定の表.json の見当のとおりの答えを書いてある、として回す（`見当を答えた事務所`）。
パックは既定を持たない＝空の決まりは見当で仮に計算し、その人を仮＋問いにして出口へ出さない（芯/設定.py の 空を見当で埋める）。
多くの試験は「決まりは答え済み」の前提で 1 つの決まりの振る舞いを見る＝ここでその答えを 1 か所で渡す（試験ごとに 58 の名を書かない）。
答えの無い決まりが仮になる事を見る試験は `@pytest.mark.既定の答え無し` を付けて、この答えを外す（tests/計算/test_計算_黙って埋めない.py）。
"""
import pytest

from 芯 import 設定


def pytest_configure(config):
    config.addinivalue_line("markers", "既定の答え無し: 作り物の事務所の「既定」の答えを外す（空の決まりを仮＋問いにする事を見る）")


会社の決まりで要る人だけ = ("委託.社保と源泉の元に入れる",)


@pytest.fixture(autouse=True)
def 見当を答えた事務所(request, monkeypatch):
    if request.node.get_closest_marker("既定の答え無し"):
        return
    元 = 設定.空を見当で埋める

    def 答え済み(値たち, 読む所):
        値, _ = 元(値たち, 読む所)
        # 要る人だけ 芯/計算/要る値.py が問う会社の決まりも、事務所の「既定」に見当のとおりが書いてある
        #（支払.賃金の形 は人ごとの値＝答えを渡さない）
        for 名 in 会社の決まりで要る人だけ:
            if 読む所 in 設定.表()[名]["読む所"] and 値.get(名) in (None, ""):
                値[名] = 設定.表()[名]["見当"]
        return 値, []   # 事務所の「既定」に見当のとおりが書いてある＝空ではない（仮にしない）

    monkeypatch.setattr(設定, "空を見当で埋める", 答え済み)
