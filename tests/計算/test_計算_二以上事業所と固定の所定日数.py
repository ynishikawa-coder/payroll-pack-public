"""型の版 9 の 2 つの穴（作り物の 1 人・期待値は試験の中で法の表の値と四則で手で出す）。

- 社保.二以上事業所の按分: 二以上事業所勤務の人は 合算の標準報酬×率×按分 で健保・介護・支援金・厚年を出す（雇保と賞与は按分しない）。
  読めない・範囲の外の値は按分しない額で見当して仮＋問い。
- 時間.月の所定日数（固定の値）: シフトの型でも固定の日数で日単価・欠勤の割る数を出す（暦から出さない＝仮にしない）。
"""
import json
from decimal import ROUND_FLOOR, Decimal
from pathlib import Path

from 作る_計算 import 人, 回す, 決まり, 値たち, 置き場
from 芯.計算 import 賞与を計算する


def _率(d: Path, 名: str, 月: str, **鍵) -> Decimal:
    j = json.loads((d / f"{名}.json").read_text(encoding="utf-8"))
    for r in j["行"]:
        if any(r["鍵"].get(k) != v for k, v in 鍵.items()):
            continue
        s, e = r["効く始め"], r["効く終わり"]
        if (s is None or s <= 月[:len(s)]) and (e is None or 月[:len(e)] <= e):
            return Decimal(str(r["値"]["率%"])) / 2
    raise KeyError(名)


def _丸(x: Decimal) -> int:   # 50 銭以下切捨て 50 銭超切上げ（社保.端数 の既定）
    f = x.to_integral_value(rounding=ROUND_FLOOR)
    return int(f + 1) if x - f > Decimal("0.5") else int(f)


社保 = ("健康保険", "介護保険", "子ども・子育て支援金", "厚生年金")


def _問いに(r, 語):
    return any(語 in q["何が無いか"] for q in r["問い"])


# ---- 二以上事業所の按分

def test_二以上事業所は合算の標準報酬に按分を掛けて丸める(tmp_path):
    d = 置き場(tmp_path / "表")
    月 = "2027-01"   # 支給月 2027-02・翌月徴収
    健, 介, 支 = _率(d, "健保_協会けんぽ", 月, 都道府県="東京都"), _率(d, "介護_協会けんぽ", 月), _率(d, "子ども子育て支援金", 月)
    厚 = _率(d, "厚年の率", 月)
    基 = Decimal(320000) * Decimal("0.4")   # 合算の標準報酬 320,000・この事業所の割合 0.4
    R = (lambda x: _丸(基 * x / 100))
    期待 = {"健康保険": R(健 + 介 + 支) - R(介) - R(支), "介護保険": R(介), "子ども・子育て支援金": R(支), "厚生年金": R(厚)}
    元 = 値たち(回す(tmp_path / "元"))
    for 字 in ("0.4", "40%", "128000/320000"):
        r = 回す(tmp_path / 字.replace("/", "_"), 人の値=人(**{"社保.二以上事業所の按分": 字}))
        v = 値たち(r)
        assert {k: v[k] for k in 社保} == 期待, 字
        assert v["雇用保険"] == 元["雇用保険"]                      # 雇保は按分しない
        assert r["人"][0]["状態"] != "仮" and not _問いに(r, "二以上事業所の按分")
    assert 元["健康保険"] > 期待["健康保険"]


def test_按分が空か1なら今までどおり(tmp_path):
    元 = 値たち(回す(tmp_path / "元"))
    for 字 in ("", "1"):
        v = 値たち(回す(tmp_path / f"x{字}", 人の値=人(**{"社保.二以上事業所の按分": 字})))
        assert {k: v[k] for k in 社保} == {k: 元[k] for k in 社保}


def test_按分が読めないか範囲の外なら按分しない額で仮と問い(tmp_path):
    元 = 値たち(回す(tmp_path / "元"))
    for i, 字 in enumerate(("1.2", "0", "-0.3", "四割", "1/0")):
        r = 回す(tmp_path / str(i), 人の値=人(**{"社保.二以上事業所の按分": 字}))
        v = 値たち(r)
        assert {k: v[k] for k in 社保} == {k: 元[k] for k in 社保}, 字
        assert r["人"][0]["状態"] == "仮" and _問いに(r, "二以上事業所の按分"), 字   # 仮が残る人は出口へ出さない


def test_賞与は按分しない(tmp_path):
    k = ("C1", "0001")

    def 賞与(sub, 人の値):
        return 値たち(賞与を計算する([{"会社": "C1", "NO": "0001", "額": 500000, "原本の名前": "作り物"}], 支給日="2027-02-26",
                                 決まり={k: 決まり()}, 人={k: 人の値}, 前月の課税対象額={k: 300000},
                                 前の標準賞与額={k: 0}, 置き場=置き場(tmp_path / sub), 計算期間={k: 6}))

    a, b = 賞与("a", 人()), 賞与("b", 人(**{"社保.二以上事業所の按分": "0.4"}))
    assert {n: a[n] for n in 社保} == {n: b[n] for n in 社保} and a["健康保険"] > 0


# ---- 固定の月の所定日数とシフトの型

def test_シフトの型は固定の月の所定日数で欠勤を引き仮にしない(tmp_path):
    def 決(暦, 日数):
        return 決まり(**{**({"時間.暦": 暦} if 暦 else {}), "時間.月の所定日数の出し方": "固定の値", "時間.月の所定日数": 日数,
                         "時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "160"})

    シフト = {"シフト": "勤務した日"}
    r22 = 回す(tmp_path / "a", 決=決(シフト, "22"))
    r20 = 回す(tmp_path / "b", 決=決(シフト, "20"))
    暦の会社 = 値たち(回す(tmp_path / "c", 決=決(None, "22")))
    v22, v20 = 値たち(r22), 値たち(r20)
    assert not _問いに(r22, "シフトの型") and not _問いに(r22, "月の所定日数が出ない")
    assert v22["欠勤控除"] == 暦の会社["欠勤控除"]          # 固定の値は暦を見ない＝シフトの型でも同じ額
    assert v20["欠勤控除"] > v22["欠勤控除"] > 0               # 割る数が小さいほど 1 日の控除が大きい


def test_固定の値で月の所定日数が空なら仮(tmp_path):
    r = 回す(tmp_path, 決=決まり(**{"時間.暦": {"シフト": "勤務した日"}, "時間.月の所定日数の出し方": "固定の値",
                                   "時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "160"}))
    assert r["人"][0]["状態"] == "仮" and _問いに(r, "月の所定日数が出ない")
