# ---- 国税庁「源泉徴収税額表 令和9年分」19〜22 頁の「税額表の使い方」の設例
# https://www.nta.go.jp/publication/pamph/gensen/zeigakuhyo2027/data/19-22.pdf

def test_月額表_甲欄の使用例(tmp_path):
    """支給 420,000 円・社会保険料等 63,400 円・扶養親族等 2 人 → 6,860 円。"""
    表 = 引く("源泉_月額表", "2027-01-25", 置き場=置き場(tmp_path)).値
    assert 月額表の税額(表, Decimal(420000 - 63400), "甲", 2) == 6860


def test_月額表_乙欄の使用例(tmp_path):
    """支給 80,750 円・社会保険料等なし・申告書なし → 80,750 × 3.063％（1 円未満切り捨て）＝ 2,473 円。"""
    表 = 引く("源泉_月額表", "2027-01-25", 置き場=置き場(tmp_path)).値
    assert 月額表の税額(表, Decimal(80750), "乙", 0) == 2473


# ---- 協会けんぽ「令和8年3月分からの保険料額表（東京支部）」https://www.kyoukaikenpo.or.jp/assets/R8_13tokyo.pdf
# 30（27）等級 500,000 円: 健保の折半 24,625.0・厚年の折半 45,750・支援金 1,150 の折半 575。
# 1 等級 58,000 円: 健保の折半 2,856.5 → 被保険者負担の 50 銭以下は切り捨て（通貨の単位法 3 条・額表の注）＝ 2,856。

def test_保険料額表_東京_30等級の折半(tmp_path):
    v = 値たち(回す(tmp_path, 決=決まり(**{"社保.丸めの順": "別に"}),
                   人の値=人(**{"人.生年月日": "1990-04-01", "社保.標準報酬": "500000"})))
    assert (v["健康保険"], v["子ども・子育て支援金"], v["介護保険"], v["厚生年金"]) == (24625, 575, 0, 45750)


def test_保険料額表_東京_1等級の折半の端数(tmp_path):
    v = 値たち(回す(tmp_path, 決=決まり(**{"社保.丸めの順": "別に"}),
                   人の値=人(**{"人.生年月日": "1990-04-01", "社保.標準報酬": "58000"})))
    assert v["健康保険"] == 2856
    assert v["厚生年金"] == 88000 * Decimal("18.3") / 100 / 2   # 厚年は 1 等級 88,000 円（4,026 の折半＝8,052÷2）


def test_介護は40歳に達した日の月から(tmp_path):
    """40 歳に達した日＝誕生日の前日（年齢計算ニ関スル法律）。その日の属する月分から介護（介護保険法 9 条）。
    2 月 1 日生まれは 1 月 31 日に 40 歳＝1 月分から。2 月 2 日生まれは 2 月分から。保険料の月は翌月徴収で支給月の前の月。"""
    v1 = 値たち(回す(tmp_path / "a", 人の値=人(**{"人.生年月日": "1987-02-01"})))
    v2 = 値たち(回す(tmp_path / "b", 人の値=人(**{"人.生年月日": "1987-02-02"})))
    assert v1["介護保険"] > 0 and v2["介護保険"] == 0


# ---- 割増の率（労基法 37 条・割増令）: 時給 1,000 円の人の 1 時間あたり
# 時間外 1,250 円・60 時間を超えた時間外 1,500 円・法定休日 1,350 円・深夜の加算 250 円（厚生労働省「割増賃金の基礎となる賃金とは」の率の例）

def test_割増の率_時給1000円(tmp_path):
    決 = 決まり(**{"支払.賃金の形": "時給", "項目.行": [
        {"名": "基本給", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:所定内"}]})
    人の値 = 人(**{"項目.人の額": {"基本給": "1000"}})
    v = 値たち(回す(tmp_path, 決=決, 人の値=人の値,
                   上書き={"法定内残業": "0", "法定外残業": "3660", "60 時間超": "60", "法定休日": "60", "深夜": "60",
                         "欠勤": "0", "遅刻早退": "0"}))
    assert v["60時間超手当"] == 1500
    assert v["時間外手当"] == 1250 * 60
    assert v["休日手当"] == 1350
    assert v["深夜手当"] == 250


# ---- 端数の通達（昭 63.3.14 基発 150 号）: 1 時間あたりの単価・1 か月の割増の総額の 1 円未満は 50 銭未満切捨て・50 銭以上切上げ

def test_通達の端数():
    assert 丸める(Decimal("1837.5"), "50銭未満切捨て以上切上げ") == 1838
    assert 丸める(Decimal("1837.49"), "50銭未満切捨て以上切上げ") == 1837


# ---- 雇用保険の被保険者負担の 1 円未満: 50 銭以下切り捨て・50 銭 1 厘以上切り上げ（厚生労働省「令和8年度 雇用保険料率のご案内」の注）
# https://www.mhlw.go.jp/content/001692566.pdf（一般の事業 労働者負担 5/1,000）

def test_雇保の率と端数(tmp_path):
    率 = 引く("雇保の率", "2026-11-30", 置き場=置き場(tmp_path), 事業の種類="一般").値["労働者‰"]
    assert 丸める(Decimal(300300) * 率 / 1000, "50銭以下切捨て50銭超切上げ") == 1501      # 1,501.5
    assert 丸める(Decimal(300302) * 率 / 1000, "50銭以下切捨て50銭超切上げ") == 1502      # 1,501.51
