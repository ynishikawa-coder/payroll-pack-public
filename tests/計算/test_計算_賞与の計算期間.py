"""賞与の源泉を月額表で出す時の ÷・× の月数（賞与の計算期間）。作り物の 1 人（社保・雇保なし＝社保控除後＝賞与の額・扶養 0）。

期待の額は 法の表/源泉_月額表.json の 2027 年（令和 9 年分）の行を手で引いた額（芯の式を呼ばない）:
- 甲 0 人: 150,000 円＝2,080・200,000 円＝4,170・350,000 円＝11,390・400,000 円＝15,320・550,000 円＝35,360
- 乙: 200,000 円＝19,200・400,000 円＝88,300
決まり: 所得税法 第186条第1項第1号ロ・第2号ロ・第2項（計算期間が 6 か月を超える時は ÷12・×12）。月数は 法の表/源泉_賞与の月額表の月数。
"""
from 作る_計算 import 人, 決まり, 値たち, 置き場
from 芯.計算 import 賞与を計算する

k = ("C1", "0001")


def _賞与(tmp_path, 計算期間, 前月=None, 欄="甲", 額=2400000, 渡す=True):
    u = 人(**{"社保.加入": "未加入", "雇保.加入": "未加入", "源泉.扶養の数": "0", "源泉.欄": 欄})
    return 賞与を計算する([{"会社": "C1", "NO": "0001", "額": 額, "原本の名前": "作り物"}], 支給日="2027-02-26",
                       決まり={k: 決まり()}, 人={k: u},
                       前月の課税対象額={k: 前月} if 前月 is not None else {}, 前の標準賞与額={},
                       計算期間=({k: 計算期間} if 計算期間 is not None else {}) if 渡す else None, 置き場=置き場(tmp_path))


def _源泉(r):
    v = 値たち(r)
    assert v["社保控除後"] == 2400000
    return v["源泉所得税"]


def _確定(r):
    return r["人"][0]["状態"] == "確認済" and r["問い"] == []


def test_前月の給与なし_6か月以下は6で割って6を掛ける(tmp_path):
    r = _賞与(tmp_path, 6)
    assert _源泉(r) == 15320 * 6 == 91920            # 2,400,000÷6＝400,000 → 15,320
    assert _確定(r)


def test_前月の給与なし_7か月は12で割って12を掛ける(tmp_path):
    r = _賞与(tmp_path, 7)
    assert _源泉(r) == 4170 * 12 == 50040            # 2,400,000÷12＝200,000 → 4,170
    assert _確定(r)
    assert "÷12×12" in next(x["出所"] for x in r["行"] if x["項目"] == "源泉所得税")


def test_前月の10倍を超える_6か月と12か月(tmp_path):
    """前月 150,000 円・社保控除後 2,400,000 円（10 倍＝1,500,000 円を超える）。"""
    r = _賞与(tmp_path, 6, 前月=150000)
    assert _源泉(r) == (35360 - 2080) * 6 == 199680   # 400,000＋150,000＝550,000
    assert _確定(r)
    r = _賞与(tmp_path / "b", 12, 前月=150000)
    assert _源泉(r) == (11390 - 2080) * 12 == 111720  # 200,000＋150,000＝350,000
    assert _確定(r)


def test_乙欄も同じ月数(tmp_path):
    """第186条第1項第1号ロの括弧書き「次号ロ及び次項において同じ」＝乙欄（第2号ロ）も 6 か月を超えれば ÷12・×12。"""
    assert _源泉(_賞与(tmp_path, 6, 欄="乙")) == 88300 * 6 == 529800
    assert _源泉(_賞与(tmp_path / "b", 7, 欄="乙")) == 19200 * 12 == 230400


def test_始めと終わりの日で渡す_境は6か月ちょうど(tmp_path):
    for i, (期間, 期待) in enumerate([
        ({"始め": "2026-08-01", "終わり": "2027-01-31"}, 91920),   # 6 か月ちょうど＝以下
        (("2026-08-01", "2027-02-01"), 50040),                     # 6 か月と 1 日＝超える
        ({"始め": "2026-07-01", "終わり": "2027-01-31"}, 50040),   # 7 か月
        ({"始め": "2026-08-31", "終わり": "2027-02-27"}, 91920),   # 2/28 の前の日まで＝以下（月末の寄せ）
        ({"始め": "2026-08-31", "終わり": "2027-02-28"}, 50040),
    ]):
        r = _賞与(tmp_path / str(i), 期間)
        assert _源泉(r) == 期待, 期間
        assert _確定(r)


def test_月額表の道で計算期間が無い時は6か月以下で見当して仮と問い1つ(tmp_path):
    for i, r in enumerate([_賞与(tmp_path / "a", None), _賞与(tmp_path / "b", None, 渡す=False),
                           _賞与(tmp_path / "c", None, 前月=150000)]):
        assert _源泉(r) in (91920, 199680), i
        assert r["人"][0]["状態"] == "仮"
        assert [q["何が無いか"] for q in r["問い"]] == ["賞与の計算期間が渡されていない"]
        源泉 = next(x for x in r["行"] if x["項目"] == "源泉所得税")
        差引 = next(x for x in r["行"] if x["項目"] == "差引支給額")
        assert 源泉["状態"] == "仮" and 差引["状態"] == "仮" and 源泉["問いの番号"] == "計1"
        assert next(x for x in r["行"] if x["項目"] == "社会保険計")["状態"] == "確定"


def test_読めない計算期間は仮と問い(tmp_path):
    for i, 期間 in enumerate(["半年", 0, {"始め": "2027-01-31", "終わり": "2026-08-01"}, ("2026-08-01",)]):
        r = _賞与(tmp_path / str(i), 期間)
        assert _源泉(r) == 91920 and r["人"][0]["状態"] == "仮"
        assert len(r["問い"]) == 1 and r["問い"][0]["何が無いか"].startswith("賞与の計算期間「")


def test_算出率の道は計算期間を使わず仮にしない(tmp_path):
    """前月 300,000 円・社保控除後 2,400,000 円（10 倍以下）＝算出率の表。計算期間が無くても確定・どの期間でも同じ額。"""
    額たち = {_源泉(_賞与(tmp_path / str(i), 期間, 前月=300000)) for i, 期間 in enumerate([None, 6, 12, "読めない"])}
    assert len(額たち) == 1
    r = _賞与(tmp_path / "x", None, 前月=300000, 渡す=False)
    assert _確定(r)
