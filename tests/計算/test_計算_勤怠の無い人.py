"""勤怠を入れない人（月の数字の無い人）が計算から黙って抜けないこと。式は作らない＝値なしの仮と問い（作り物の値だけ）。"""
import json
from pathlib import Path

from 作る_計算 import 人, 回す, 決まり, 置き場, 月の数字
from 芯.計算 import 勤怠が無い, 計算する

期待 = json.loads((Path(__file__).parent / "計算_見張り_期待.json").read_text(encoding="utf-8"))


def _縦(結果, NO="0001"):
    return [[r["項目"], r["値"], r["状態"]] for r in 結果["行"] if r["NO"] == NO]


def _回す(tmp, 月の=None, **他):
    return 計算する(月の数字() if 月の is None else 月の,
                   決まり={("C1", "0001"): 決まり(), ("C1", "0009"): 決まり()},
                   人={("C1", "0001"): 人(), ("C1", "0009"): 人()}, 置き場=置き場(tmp), **他)


def test_月の数字の無い人は値なしの仮と問いで返る(tmp_path):
    r = _回す(tmp_path)
    assert _縦(r) == 期待["月給_2027-02"]           # 月の数字の来た人は変わらない
    assert _縦(r, "0009") == [["差引支給額", None, "仮"]]
    assert r["人の状態"] == {("2027-02", "C1", "0001"): "確認済", ("2027-02", "C1", "0009"): "仮"}
    (q,) = [q for q in r["問い"] if q["何が無いか"] == 勤怠が無い]
    assert q["人"] == [("C1", "0009")] and q["変わる項目"] == ["全部"]


def test_集計が勤怠が無いとした人は計算しない(tmp_path):
    集 = {"行": 月の数字(), "人": [{"支給月": "2027-02", "会社": "C1", "NO": "0001", "状態": "確認済", "仮の数": 0},
                              {"支給月": "2027-02", "会社": "C1", "NO": "0009", "状態": "仮", "仮の数": 1, "勤怠が無い": True}]}
    r = _回す(tmp_path, 集)
    assert _縦(r, "0009") == [["差引支給額", None, "仮"]]
    assert r["人の状態"][("2027-02", "C1", "0009")] == "仮"


def test_支給月が決まらなければ知らせる(tmp_path):
    r = _回す(tmp_path, [])
    assert r["行"] == [] and sum("支給月が決まらない" in t for t in r["知らせ"]) == 2
    r = _回す(tmp_path / "b", [], 支給月="2027-02")
    assert {x["NO"] for x in r["行"]} == {"0001", "0009"} and set(r["人の状態"].values()) == {"仮"}


def test_決まりと人の値に居ない人は今までどおり(tmp_path):
    assert _縦(回す(tmp_path)) == 期待["月給_2027-02"]
