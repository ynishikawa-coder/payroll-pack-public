"""固定残業手当の額は 1 か所（型の版 42・作り物の 1 人）。

額は ④ の訳 固定残業手当 の行（単価の元＝人の額 なら ② の人の額）だけに書き、割増.固定残業 は形・時間・対象だけを持つ。
前は 割増.固定残業 の 額 と ④ の行の 2 か所に同じ額を書き、片方だけ直すと黙って食い違った。
食い違い・足りない時は新しい止め方を足さず、今の道（見当で計算して仮＋問い＝その人は出口へ出さない）に乗せる。
"""
from 作る_計算 import 人, 回す, 決まり, 値たち, 固定残業, 固定残業の行

鍵 = ("C1", "0001")


def _問い(r, 語):
    return [q for q in r["問い"] if 語 in q["何が無いか"]]


def _人の額の行で(tmp, 額="30000", 固定=None):
    """正本の形: ④ の行は 単価の元＝人の額、額は ② の人の額。"""
    行 = {**固定残業の行, "単価の元": "人の額"}
    人の値 = 人()
    人の値["項目.人の額"] = {**人の値["項目.人の額"], **({"固定残業手当": 額} if 額 is not None else {})}
    決 = 決まり(**{"項目.行": 決まり()["項目.行"] + [行],
                 **({"割増.固定残業": 固定, "割増.固定残業の対象": "時間外"} if 固定 is not None else {})})
    return 回す(tmp, 決=決, 人の値=人の値)


def test_額は行の人の額から読み覆った残りを払う(tmp_path):
    全 = 値たち(回す(tmp_path / "a"))["時間外手当"]                    # 固定残業の無い時の時間外の法の額
    r = _人の額の行で(tmp_path / "b", "30000", {"形": "額で"})
    assert r["人"][0]["状態"] != "仮", r["問い"]
    assert 値たち(r)["固定残業手当"] == 30000
    assert 値たち(r)["時間外手当"] == max(0, 全 - 30000)
    少ない = 値たち(_人の額の行で(tmp_path / "c", "5000", {"形": "額で"}))
    assert 少ない["時間外手当"] == max(0, 全 - 5000)                  # ② の額だけを直せば覆う額も変わる（2 か所に書かない）


def test_古い形の額があれば仮で問う(tmp_path):
    # 行と古い 額 の両方: 行の額で見当（古い 額 は読まない）して仮＋問い
    r = _人の額の行で(tmp_path / "a", "30000", {"形": "額で", "額": "99999"})
    assert r["人"][0]["状態"] == "仮"
    assert _問い(r, "古い形")
    assert 値たち(r)["時間外手当"] == 値たち(_人の額の行で(tmp_path / "b", "30000", {"形": "額で"}))["時間外手当"]
    # 古い 額 だけ（行が無い）: 古い 額 で見当して仮＋問い（行が無い問いは重ねない）
    古い形 = {**固定残業(None), "割増.固定残業": {"形": "額で", "額": "30000"}}
    古い = 回す(tmp_path / "c", 決=決まり(**古い形))
    assert 古い["人"][0]["状態"] == "仮" and _問い(古い, "古い形") and not _問い(古い, "行（② の人の額）が無い")
    assert 値たち(古い)["時間外手当"] == 値たち(回す(tmp_path / "d", 決=決まり(**固定残業("30000"))))["時間外手当"]


def test_額でなのに行が無いと全部払って仮で問う(tmp_path):
    全 = 値たち(回す(tmp_path / "a"))["時間外手当"]
    r = 回す(tmp_path / "b", 決=決まり(**固定残業(None)))
    assert r["人"][0]["状態"] == "仮"
    q = _問い(r, "行（② の人の額）が無い")
    assert q and "どちらが正しいか" in str(q[0])
    assert 値たち(r)["時間外手当"] == 全
    # 行はあるがこの人に ② の人の額が無い（行を出さない人）も同じ
    無い人 = _人の額の行で(tmp_path / "c", None, {"形": "額で"})
    assert 無い人["人"][0]["状態"] == "仮" and _問い(無い人, "行（② の人の額）が無い")


def test_行があるのに設定が無しや空なら全部払って仮で問う(tmp_path):
    全 = 値たち(回す(tmp_path / "a"))["時間外手当"]
    for i, 固定 in enumerate(("無し", None)):
        r = _人の額の行で(tmp_path / f"b{i}", "30000", 固定)
        assert r["人"][0]["状態"] == "仮", 固定
        assert _問い(r, "訳 固定残業手当 の行「固定残業手当」"), 固定
        assert 値たち(r)["時間外手当"] == 全                          # 黙って行の額を当てない＝時間外を全部払う見当


def test_時間での人に行があっても仮にしない(tmp_path):
    r = _人の額の行で(tmp_path, "30000", {"形": "時間で", "時間": "10"})
    assert not _問い(r, "固定残業"), r["問い"]


def test_固定残業の額が時間分に足りないと検査が赤(tmp_path):
    r = 回す(tmp_path, 決=決まり(**固定残業("1000", 時間="20")))
    assert any("赤: 固定残業の額 1000 が 20 時間分の割増" in x for x in r["法の線"]), r["法の線"]
