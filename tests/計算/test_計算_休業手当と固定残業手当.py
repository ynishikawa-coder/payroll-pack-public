"""型の版 21 の 2 つの形（作り物の 1 人で前後の差を見る・期待値は試験の中で手で出す）。

- 休業手当: 単価の元＝平均賃金（入力 平均賃金）× 勤怠の数:休業 × 率（空＝休暇.休業手当の率・それも空なら法の線 60%）。
  前は休業の日があると「式が無い」で仮だった。法の線を下回る率は法の線で仮。休業手当は割増の単価に入れない
- 固定残業手当: 割増の基礎から除く訳＝固定残業手当 の行は赤にせず割増の単価から除く（前は労基則 21 条の 7 つの外＝赤＋単価に入れて仮）
"""
from 作る_計算 import 人, 回す, 決まり, 値たち

鍵 = ("C1", "0001")
休業の行 = {"名": "休業手当", "支給か控除": "支給", "単価の元": "平均賃金", "数量の元": "勤怠の数:休業"}


def _休業(tmp, 行=None, 入力=None, **決):
    行たち = 決まり()["項目.行"] + ([行] if 行 else [])
    return 回す(tmp, 決=決まり(**{"項目.行": 行たち, **決}), 上書き={"休業": "2"},
              入力={鍵: 入力} if 入力 is not None else None)


def test_休業手当の行が無ければ前のまま仮(tmp_path):
    r = _休業(tmp_path)
    assert "仮" in set(r["人の状態"].values())


def test_休業手当は平均賃金と率と休業の日で払い仮を外す(tmp_path):
    無し = 値たち(回す(tmp_path / "a"))
    r = _休業(tmp_path / "b", 休業の行, {"平均賃金": "9876.54"})
    後 = 値たち(r)
    assert 後["休業手当"] == 11852                       # 9,876.54×2 日×0.60＝11,851.848 → 支給の行は切上げ
    assert "仮" not in set(r["人の状態"].values())
    assert 後["時間外手当"] == 無し["時間外手当"]         # 割増の単価に入れない（休暇の語）
    assert 後["欠勤控除"] == 無し["欠勤控除"]             # 休暇.休業の日の控除 の既定＝引かない
    assert 後["課税計"] == 無し["課税計"] + 11852


def test_平均賃金が無ければ仮(tmp_path):
    r = _休業(tmp_path, 休業の行, {})
    assert "仮" in set(r["人の状態"].values())


def test_会社の率と法の線(tmp_path):
    高い = 値たち(_休業(tmp_path / "a", 休業の行, {"平均賃金": "10000"}, **{"休暇.休業手当の率": "0.8"}))
    assert 高い["休業手当"] == 16000
    低い = _休業(tmp_path / "b", 休業の行, {"平均賃金": "10000"}, **{"休暇.休業手当の率": "0.5"})
    assert 値たち(低い)["休業手当"] == 12000                # 法の線 60% で計算して仮
    assert "仮" in set(低い["人の状態"].values())
    行の率 = 値たち(_休業(tmp_path / "c", {**休業の行, "率": "1"}, {"平均賃金": "10000"}))
    assert 行の率["休業手当"] == 20000                      # 行の率が先
    低い行 = _休業(tmp_path / "d", {**休業の行, "率": "0.5"}, {"平均賃金": "10000"})   # 行の率も法の線と比べる（レビューの赤）
    assert 値たち(低い行)["休業手当"] == 12000
    assert "仮" in set(低い行["人の状態"].values())


def test_月給の人の休業の日を欠勤と同じに引く(tmp_path):
    引く = 値たち(_休業(tmp_path / "a", 休業の行, {"平均賃金": "10000"}, **{"休暇.休業の日の控除": "欠勤と同じに引く"}))
    欠勤3 = 値たち(回す(tmp_path / "b", 上書き={"欠勤": "3"}))
    assert 引く["欠勤控除"] == 欠勤3["欠勤控除"] > 0          # 欠勤 1＋休業 2 を欠勤の式で引く
    assert 引く["休業手当"] == 12000


固定 = {"名": "固定残業手当", "支給か控除": "支給", "単価の元": "人の額", "割増の基礎": "入らない"}


def _固定(tmp, 行):
    人の値 = 人()
    人の値["項目.人の額"] = {**人の値["項目.人の額"], "固定残業手当": "30000"}
    return 回す(tmp, 決=決まり(**{"項目.行": 決まり()["項目.行"] + [行]}), 人の値=人の値)


def test_固定残業手当の訳で除くと赤にせず単価に入れない(tmp_path):
    無し = 値たち(回す(tmp_path / "a"))
    除く = _固定(tmp_path / "b", {**固定, "割増の基礎から除く訳": "固定残業手当"})
    assert not any("固定残業手当" in x for x in 除く["法の線"])
    assert "仮" not in set(除く["人の状態"].values())
    assert 値たち(除く)["時間外手当"] == 無し["時間外手当"]        # 単価は基本給と職務手当だけ
    外 = _固定(tmp_path / "c", {**固定, "割増の基礎から除く訳": "皆勤手当"})   # 7 つの外の訳は前のまま赤＋単価に入れて仮
    assert any("赤:" in x and "固定残業手当" in x for x in 外["法の線"])
    assert 値たち(外)["時間外手当"] > 無し["時間外手当"]


def test_控除の割る時間はhmmを分数のまま読む(tmp_path):
    # 型の版 21: 前は 数() で読み h:mm で止まった（殻が小数 4 桁に丸めて渡し、1 円ずれうる）
    決 = {"欠勤.控除の割り方": "時間割り"}
    数で = 値たち(回す(tmp_path / "a", 決=決まり(**決, **{"欠勤.控除の割る時間": "173"})))
    hmm = 値たち(回す(tmp_path / "b", 決=決まり(**決, **{"欠勤.控除の割る時間": "173:00"})))
    assert 数で["欠勤控除"] == hmm["欠勤控除"] > 0 and 数で["遅刻早退控除"] == hmm["遅刻早退控除"] > 0
    端 = 値たち(回す(tmp_path / "c", 決=決まり(**決, **{"欠勤.控除の割る時間": "161:20"})))
    from fractions import Fraction
    from decimal import Decimal, ROUND_FLOOR
    基礎 = Fraction(300000)                                    # 基本給＋職務手当（通勤は減らない）
    期待 = Decimal((基礎 * 30 / 60 / Fraction(9680, 60)).numerator) / Decimal((基礎 * 30 / 60 / Fraction(9680, 60)).denominator)
    assert 端["遅刻早退控除"] == 期待.to_integral_value(ROUND_FLOOR)   # 遅刻 30 分×基礎÷161⅓ 時間（切捨て）
