"""芯の 除ける訳（芯/計算/検査.py）と、法の線の点検表の 除ける訳（初期設定/法の線の点検.json＝正本）が食い違えば赤。

芯は初期設定を読まない（3 層の線）。語の照らしは法の表に持たない（法の表/法の線.json の 注）ので、
芯は写しを持ち、ここで正本と突き合わせる（tests/計算/test_計算_既定と項目の辞書.py と同じ形）。
"""
import json
from pathlib import Path

from 芯.計算 import 検査

根 = Path(__file__).resolve().parents[2]


def test_芯の除ける訳と点検表の除ける訳がそろう():
    正本 = json.loads((根 / "初期設定" / "法の線の点検.json").read_text(encoding="utf-8"))["除ける訳"]
    assert list(検査.除ける訳) == list(正本), "初期設定/法の線の点検.json が正本（芯/計算/検査.py の 除ける訳 を合わせる）"
    assert len(検査.除ける訳) == 7   # 労基則 21 条


def test_除けない行は訳の無い行と7つの外の訳の行():
    行 = [{"名": "通勤手当", "支給か控除": "支給", "割増の基礎": "入らない", "割増の基礎から除く訳": "通勤手当"},
         {"名": "作り物の家族手当", "支給か控除": "支給", "割増の基礎": "入らない", "割増の基礎から除く訳": "家族 手当"},
         {"名": "作り物の皆勤手当", "支給か控除": "支給", "割増の基礎": "入らない", "割増の基礎から除く訳": "皆勤手当"},
         {"名": "作り物の役の手当", "支給か控除": "支給", "割増の基礎": "入らない"},
         {"名": "基本給", "支給か控除": "支給"},
         {"名": "作り物の控除", "支給か控除": "控除", "割増の基礎": "入らない"}]
    assert 検査.除けない行(行) == {"作り物の皆勤手当": "皆勤手当", "作り物の役の手当": ""}
