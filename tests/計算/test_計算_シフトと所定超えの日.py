def test_月の途中の入社を会社のその月の所定日数で日割りする(tmp_path):
    """型の版 24: 日割.割る数＝会社のその月の所定日数。月の数字の 所定日数（人の勤怠＝入社日から後だけ）で割ると在籍の日と同じになり
    日割りされない（前の値 その月の所定日数）。期間 2027-01 の会社の所定日数＝平日 21 日−祝日 2 日（01-01・01-11）＝19 日。"""
    基 = {"日割.入退社": "出た日で払う"}
    入社 = 人(**{"人.入社日": "2027-01-15"})
    勤怠 = {"所定日数": "12", "出勤日数": "12", "欠勤": "0"}
    前 = 値たち(回す(tmp_path / "a", 決=決まり(**基, **{"日割.割る数": "その月の所定日数"}), 人の値=入社, 上書き=勤怠))
    assert 前["基本給"] == 280000                              # 12÷12＝日割りされない（直す前の穴）
    r = 回す(tmp_path / "b", 決=決まり(**基, **{"日割.割る数": "会社のその月の所定日数"}), 人の値=入社, 上書き=勤怠)
    assert 値たち(r)["基本給"] == -(-280000 * 12 // 19)       # 月額×出勤した日数÷会社の所定日数・切上げ（日割.端数 の既定）
    assert r["人"][0]["状態"] != "仮"
    # 時間.月の所定日数の出し方＝固定の値 なら 時間.月の所定日数 で割る
    固定 = {"時間.月の所定日数の出し方": "固定の値", "時間.月の所定日数": "20"}
    v = 値たち(回す(tmp_path / "c", 決=決まり(**基, **固定, **{"日割.割る数": "会社のその月の所定日数"}), 人の値=入社, 上書き=勤怠))
    assert v["基本給"] == 280000 * 12 // 20
    # シフトの型で固定の値が無ければ日割しないで仮
    r = 回す(tmp_path / "d", 決=決まり(**基, **{"日割.割る数": "会社のその月の所定日数", "時間.暦": {"シフト": "勤務した日"}}),
            人の値=入社, 上書き=勤怠)
    assert r["人"][0]["状態"] == "仮" and any("会社のその月の所定日数" in q["何が無いか"] for q in r["問い"])


# ── 入退社の月の日割（穴 3）: 決めていない会社は仮＋問い・欠けた日を引く形・年平均は暦の 1 年÷12・暦日割は今と同じ ──
# 期間 2027-01（31 日・会社の暦の所定 19 日）・入社 2027-01-15＝在籍の暦日 17 日・在籍の所定 11 日（欠けた所定 8 日）。
# 2027 年の会社の暦（土日祝が休み）の所定日数＝245 日 → 年平均の所定日数＝245÷12。月額（基本給）280000・日割.端数＝切上げ（既定）。
_入社の月 = {"人.入社日": "2027-01-15"}
_入社の月の勤怠 = {"所定日数": "12", "出勤日数": "12", "欠勤": "0"}


def test_入退社の月の払い方を決めていない会社は暦日割で見当して仮と問い(tmp_path):
    """日割.入退社 が無い会社: 黙って暦日割にしない＝入退社の月の人は暦日割の額で見当して仮（出口へ出ない）＋問い 1 つ。
    在籍が期間の全部の人は日割が要らない＝仮にしない（決めていない会社の全員を止めない）。"""
    r = 回す(tmp_path / "a", 決=決まり(), 人の値=人(**_入社の月), 上書き=_入社の月の勤怠)
    assert 値たち(r)["基本給"] == -(-280000 * 17 // 31)          # 見当＝暦日割の額
    assert r["人"][0]["状態"] == "仮"
    (q,) = [q for q in r["問い"] if q["何が無いか"] == "「日割.入退社」が無い"]
    assert q["見当"] == "暦日割" and "欠けた日を引く" in q["答え方の例"]
    r = 回す(tmp_path / "b", 決=決まり())
    assert r["人"][0]["状態"] != "仮" and not any("日割" in q["何が無いか"] for q in r["問い"])
    assert 値たち(r)["基本給"] == 280000


def test_欠けた日を引く形は月額から欠けた日と日額の積を引く(tmp_path):
    """日割.形＝欠けた日を引く: 月額 − 欠けた所定日 8 × 日額（月額÷年平均の所定日数）。在籍の日を払う形（月額×在籍 11÷割る数）と違う額。"""
    基 = {"日割.入退社": "所定日割", "日割.割る数": "年平均の所定日数"}
    引く = 回す(tmp_path / "a", 決=決まり(**基, **{"日割.形": "欠けた日を引く"}), 人の値=人(**_入社の月), 上書き=_入社の月の勤怠)
    assert 値たち(引く)["基本給"] == -(-280000 * (245 - 8 * 12) // 245)   # 280000 − 8 × 280000÷(245÷12)
    assert 引く["人"][0]["状態"] != "仮"
    払う = 値たち(回す(tmp_path / "b", 決=決まり(**基), 人の値=人(**_入社の月), 上書き=_入社の月の勤怠))
    assert 払う["基本給"] == -(-280000 * 11 * 12 // 245) != 値たち(引く)["基本給"]
    # 欠けた日が割る数を超えても負にしない（0 円で止める）
    少 = 回す(tmp_path / "c", 決=決まり(**{"日割.入退社": "暦日割", "日割.割る数": "その月の所定日数", "日割.形": "欠けた日を引く"}),
             人の値=人(**_入社の月), 上書き=_入社の月の勤怠)
    assert 値たち(少)["基本給"] == 0


def test_年平均の所定日数は会社の暦の1年を数えて12で割る(tmp_path):
    """日割.割る数＝年平均の所定日数: その年の会社の暦の所定日数 245÷12 で割る。その月の所定日数（期間の暦 19 日・勤怠 12 日）では割らない。"""
    v = 値たち(回す(tmp_path / "a", 決=決まり(**{"日割.入退社": "暦日割", "日割.割る数": "年平均の所定日数"}),
                   人の値=人(**_入社の月), 上書き=_入社の月の勤怠))
    assert v["基本給"] == -(-280000 * 17 * 12 // 245)
    assert v["基本給"] not in (-(-280000 * 17 // 19), 280000)
    # シフトの型は暦から 1 年の所定日数を出せない＝日割しないで見当して仮＋問い
    r = 回す(tmp_path / "b", 決=決まり(**{"日割.入退社": "暦日割", "日割.割る数": "年平均の所定日数", "時間.暦": {"シフト": "勤務した日"}}),
            人の値=人(**_入社の月), 上書き=_入社の月の勤怠)
    assert r["人"][0]["状態"] == "仮" and any("年平均の所定日数" in q["何が無いか"] for q in r["問い"])


