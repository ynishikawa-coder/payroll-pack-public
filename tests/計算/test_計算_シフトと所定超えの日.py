"""シフトの型の月の所定と、所定日数を超えて出た日の上乗せ（数量の元 `勤怠の数:<語>−<引く数>`）。期待値は試験の中で手で出す。"""
from 作る_計算 import 人, 回す, 決まり, 値たち


def test_所定日数を超えて出た日の上乗せ(tmp_path):
    """基本給＋(出勤日数−22)×基本給÷22（月の所定日数＝固定の値 22）。超えない人には行を出さない。"""
    行 = [*決まり()["項目.行"],
         {"名": "所定超えの日", "支給か控除": "支給", "単価の元": "額:基本給÷所定日数", "数量の元": "勤怠の数:出勤日数−所定日数",
          "割増の基礎": "入らない", "割増の基礎から除く訳": "臨時の賃金"}]
    決 = 決まり(**{"時間.月の所定日数の出し方": "固定の値", "時間.月の所定日数": "22", "項目.行": 行})
    v = 値たち(回す(tmp_path, 決=決, 上書き={"出勤日数": "25", "欠勤": "0"}))
    assert v["所定超えの日"] == -(-280000 * 3 // 22)       # 切上げ（支給の行の既定）
    v = 値たち(回す(tmp_path / "b", 決=決, 上書き={"出勤日数": "20", "欠勤": "0"}))
    assert "所定超えの日" not in v


def test_額の行はその項目の額の無い人に出さず仮にしない(tmp_path):
    """単価の元 額:<項目> の行は、人の額の行と同じく、その項目の額のある人だけ（時給の人など基本給の額の無い人に出して仮にしない）。"""
    行 = [*決まり()["項目.行"],
         {"名": "時給", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:所定内"},
         {"名": "所定超えの日", "支給か控除": "支給", "単価の元": "額:基本給÷所定日数", "数量の元": "勤怠の数:出勤日数−所定日数",
          "割増の基礎": "入らない", "割増の基礎から除く訳": "臨時の賃金"}]
    決 = 決まり(**{"時間.月の所定日数の出し方": "固定の値", "時間.月の所定日数": "22", "項目.行": 行, "支払.賃金の形": "時給"})
    r = 回す(tmp_path, 決=決, 人の値=人(**{"項目.人の額": {"時給": "1500", "通勤手当": "12000"}}),
            上書き={"出勤日数": "25", "欠勤": "0"})
    assert "所定超えの日" not in 値たち(r)
    assert not any("所定超えの日" in q["何が無いか"] for q in r["問い"])


def test_シフトの型は暦から年平均の所定を出さず仮(tmp_path):
    決 = 決まり(**{"時間.暦": {"シフト": "勤務した日"}})
    r = 回す(tmp_path, 決=決)
    assert any("シフトの型" in q["何が無いか"] for q in r["問い"])
    決 = 決まり(**{"時間.暦": {"シフト": "勤務した日"}, "時間.月の所定日数の出し方": "固定の値", "時間.月の所定日数": "22",
                 "時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "176"})
    r = 回す(tmp_path / "b", 決=決)
    assert not any("シフトの型" in q["何が無いか"] for q in r["問い"])


def test_シフトの型の所定日割の入退社は仮(tmp_path):
    """日割.入退社＝所定日割 は暦の所定日数で在籍を数える＝シフトの型は全部の日を所定に数えてしまう＝暦日割で見当して仮。"""
    基 = {"時間.月の所定日数の出し方": "固定の値", "時間.月の所定日数": "22", "時間.月の所定時間の出し方": "固定の値",
          "時間.月の所定時間": "176", "日割.入退社": "所定日割"}
    r = 回す(tmp_path, 決=決まり(**基, **{"時間.暦": {"シフト": "勤務した日"}}), 人の値=人(**{"人.入社日": "2027-01-15"}))
    行 = {a["項目"]: a for a in r["行"]}
    assert 行["課税計"]["状態"] == "仮" and r["人"][0]["状態"] == "仮" and any("所定日割" in q["何が無いか"] for q in r["問い"])
    r = 回す(tmp_path / "b", 決=決まり(**基), 人の値=人(**{"人.入社日": "2027-01-15"}))
    assert not any("所定日割" in q["何が無いか"] for q in r["問い"])
