"""芯の見当（芯/設定の表.json の 見当＝空の時に仮で数える値）と、項目の辞書の既定（初期設定/項目.json の問いの見当＝正本）が食い違えば赤。

パックは既定を持たない: 空の決まりは見当で仮に計算し、その人を仮＋問いにする（芯/設定.py の 空を見当で埋める）。
問いに見せる見当と、仮で数えた見当が違うと、「見当のとおり」と答えた人の額が仮の額と変わる＝ここで照らす。
芯は初期設定を読まない（層: 初期設定 → 芯 の向きだけ）。芯は辞書の既定を芯の読む形で持ち、ここで辞書と照らす。
字は芯が読む時と同じ揃え方（形.語をそろえる＝空白・切り捨て の字の揺れ）で比べる。
芯の見当が dict の項目（休日.休日出勤の数え方）は、辞書の既定の「・」で区切った語の並びと照らす。
法の線から来る項目（芯/計算/法の線の読み方.py に載る名）は、辞書に既定（法の値の写し）を持たず、`法の線から` に読み方の線を持つ
（写すと未決の仕分け・読みの一覧から会社のマスタへ法の値が出所なしで書かれる）。
"""
import json
from pathlib import Path

from 芯.計算.形 import 語をそろえる
from 芯 import 設定
from 芯.計算.法の線の読み方 import 読み方

辞書 = {it["項目"]: it for it in json.loads(
    (Path(__file__).resolve().parents[2] / "初期設定" / "項目.json").read_text(encoding="utf-8"))["項目"]}

# 空を見当で埋める項目（要る人だけ 芯/計算 が埋める名は外す＝辞書の既定は null で、要る値.要る が問いを立てる）
既定 = {n: e["見当"] for n, e in 設定.表().items() if e.get("見当") is not None and n not in 設定.要る人だけの見当}

# 辞書に項目が無く、芯だけが見当を持つ項目＝芯/設定の表.json の 項目の外 に訳を書いた名（訳の正本はその 1 か所）
芯だけ = {e["名"]: e["項目の外"] for e in json.loads(
    (Path(__file__).resolve().parents[2] / "芯" / "設定の表.json").read_text(encoding="utf-8"))["項目"] if e.get("項目の外")}


def 法の線の写し(辞書: dict) -> list[str]:
    """法の線から来る項目が辞書に法の値を写している・印が読み方の線と違う訳の並び（空なら良い）。"""
    違う = []
    for 名, it in 辞書.items():
        線 = 読み方[名][0] if 名 in 読み方 else None
        if 線 is None:
            if it.get("法の線から"):
                違う.append(f"{名}: 法の線から {it['法の線から']!r} だが 芯/計算/法の線の読み方.py に無い")
            continue
        if it.get("既定") is not None:
            違う.append(f"{名}: 既定 {it['既定']!r} は法の値の写し（null にし、法の表/法の線.json の線 {線} から引く）")
        if it.get("法の線から") != 線:
            違う.append(f"{名}: 法の線から {it.get('法の線から')!r} が読み方の線 {線!r} と違う")
    return 違う


def _芯の字(v) -> str:
    return "・".join(v.values()) if isinstance(v, dict) else str(v)


def test_芯の見当は辞書の既定と同じ():
    違う = []
    for 名, v in 既定.items():
        if 名 in 芯だけ:
            continue
        assert 名 in 辞書, f"{名} が 初期設定/項目.json に無い（芯/設定の表.json の 項目の外 に訳を書くか辞書へ足す）"
        辞 = 辞書[名].get("既定")
        if 辞 is None or 語をそろえる(_芯の字(v)) != 語をそろえる(辞):
            違う.append(f"{名}: 芯={_芯の字(v)!r} 辞書={辞!r}")
    assert not 違う, "芯の見当と項目.json の既定が違う（項目.json が正本。芯/設定の表.json の 見当 を合わせる）:\n" + "\n".join(違う)
    写し = 法の線の写し(辞書)
    assert not 写し, "項目.json が法の線の値を写している（正本は 法の表/法の線.json）:\n" + "\n".join(写し)


def test_芯だけの見当は辞書に無い():
    assert not set(芯だけ) & set(辞書), "辞書に入ったので 芯/設定の表.json の 項目の外 を消し、上の照らしに入れる"


def test_照らしは食い違いを赤にする():
    """照らしが空回りしていない（辞書の字を 1 つ変えると違うと読む）。"""
    assert 語をそろえる("50 銭以下切捨て") != 語をそろえる(既定["社保.端数"])
    assert 語をそろえる("居住者（日本に住む）") != 語をそろえる(既定["源泉.住む所"])
    # 法の線の項目の既定に法の値を写す・印を外す・印の線を違える・読み方に無い名に印を付ける は赤
    def 直す(名, **欄):  # 欄の値 ... はその欄を消す
        it = {**辞書[名], **欄}
        return {**辞書, 名: {k: v for k, v in it.items() if v is not ...}}
    assert 法の線の写し(直す("割増.深夜の時間帯", 既定="22:00〜5:00"))
    assert 法の線の写し(直す("割増.時間外の率", 法の線から=...))
    assert 法の線の写し(直す("割増.休日の率", 法の線から="深夜帯"))
    assert 法の線の写し(直す("支払.支給の月", 法の線から="深夜帯"))


def test_パックは既定を持たない():
    """芯/設定の表.json に 既定・埋める の鍵が無い（空を黙って埋めて確定にする道を持たない）。"""
    残る = [n for n, e in 設定.表().items() if "既定" in e or "埋める" in e]
    assert not 残る, f"既定・埋める の鍵が残る（見当にして空を仮＋問いにする）: {残る}"
