"""芯/計算: 時間.月の所定時間 の h:mm（分が 3 の倍数でない `161:20`）と分に割り切れない小数の時間（`161.36`）を受ける（作り物の値だけ）。

- `161:20` は 161⅓ 時間＝10 進では循環小数。分数のまま割るので、割増・遅刻早退の単価が丸めの境で 1 円ずれない
  （作り物: 基礎 300,322 円÷161⅓ 時間＝ちょうど 1,861.5 円。`50銭以下切捨て` なら 1,861 円・`四捨五入` なら 1,862 円）
- `161.36` は時間の数のまま（黙って丸めない）
- 読めない字は 形の誤り（段の解決 が先に仮にして渡さない。殻が直に渡した時は 芯/計算 がその人を仮にして問う）
"""
import sys
from fractions import Fraction
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
sys.path.insert(0, str(ここ.parent.parent))
sys.path.insert(0, str(ここ))

from 作る_計算 import 人, 値たち, 回す, 決まり  # noqa: E402
from 芯.計算.形 import 形の誤り, 時間  # noqa: E402

基礎の額 = {"基本給": "280322", "職務手当": "20000", "通勤手当": "12000"}   # 割増の基礎 300,322 円（通勤手当は入らない）


def _回す(tmp_path, 所定, 端数="50銭以下切捨て", **他):
    決 = 決まり(**{"時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": 所定, "端数.時間単価": 端数, **他})
    return 回す(tmp_path, 決=決, 人の値=人(**{"項目.人の額": 基礎の額}))


@pytest.mark.parametrize("字, 分数", [
    ("161:20", Fraction(484, 3)), (" 161:20 ", Fraction(484, 3)), ("0:00", Fraction(0)), ("161.36", Fraction("161.36")),
    ("160", Fraction(160)), (160, Fraction(160)), ("", None), (None, None),
])
def test_時間はhmmも時間の数も分数で読む(字, 分数):
    assert 時間(字) == 分数


@pytest.mark.parametrize("字", ["abc", "161:75", "161:2", 161.36])
def test_時間は読めない字とfloatを受けない(字):
    with pytest.raises(形の誤り):
        時間(字)


def test_hmmの所定で割増の単価が丸めの境でずれない(tmp_path):
    r = _回す(tmp_path / "a", "161:20")
    v = 値たち(r)
    assert r["問い"] == [] and all(x["状態"] == "確定" for x in r["行"])
    assert v["法定内残業手当"] == 1861 * 2                       # 単価 1,861.5 を 50銭以下切捨て＝1,861 円×法定内 2 時間
    assert v["遅刻早退控除"] == 930                               # 300,322×0.5 時間÷161⅓＝930.75 を切捨て（既定の 端数.控除）
    v = 値たち(_回す(tmp_path / "b", "161:20", 端数="四捨五入"))
    assert v["法定内残業手当"] == 1862 * 2


def test_割り切れる所定はhmmでも時間の数でも同じ額(tmp_path):
    a = 値たち(_回す(tmp_path / "a", "202:30"))
    b = 値たち(_回す(tmp_path / "b", "202.5"))
    assert a == b


def test_割り切れない小数の時間はそのまま割る(tmp_path):
    r = _回す(tmp_path / "a", "161.36")
    v = 値たち(r)
    assert r["問い"] == []
    assert v["法定内残業手当"] == 1861 * 2                       # 300,322÷161.36＝1,861.19… を切捨て


@pytest.mark.parametrize("字", ["abc", "161:75"])
def test_読めない月の所定時間はその人を仮にして問う(tmp_path, 字):
    r = _回す(tmp_path, 字)
    assert r["人"][0]["状態"] == "仮"
    assert any("時間.月の所定時間" in q["何が無いか"] for q in r["問い"])


def test_年平均で割り切れない所定も分数のまま割る_回帰の見張り(tmp_path):
    """年平均（既定）: 2027 年の作り物の暦は所定 245 日×8 時間＝1,960 時間÷12＝163⅓ 時間（10 進では循環小数）。
    ÷12 を分数のまま持つので、固定の値 `163:20` と同じ額になり、単価 300,125÷163⅓＝ちょうど 1,837.5 円の境でずれない。"""
    from datetime import date

    from 作る_計算 import 置き場
    from 芯.計算 import 暦
    assert 暦.所定日数(date(2027, 1, 1), date(2027, 12, 31), None, 置き場(tmp_path / "暦"))[0] == 245   # 前提（作り物の祝日の表）
    額 = {"基本給": "280125", "職務手当": "20000", "通勤手当": "12000"}
    年 = 回す(tmp_path / "a", 決=決まり(**{"時間.月の所定時間の出し方": "年平均", "端数.時間単価": "50銭以下切捨て"}),
             人の値=人(**{"項目.人の額": 額}))
    固定 = 回す(tmp_path / "b", 決=決まり(**{"時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "163:20",
                                          "端数.時間単価": "50銭以下切捨て"}), 人の値=人(**{"項目.人の額": 額}))
    assert 年["問い"] == [] and 値たち(年) == 値たち(固定)
    assert 値たち(年)["法定内残業手当"] == 1837 * 2
