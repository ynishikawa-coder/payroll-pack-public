"""端数の語（丸めの語）が選べる値の外でも、月を止めずに仮＋問いにする（作り物の値だけ）。

前は `丸める` の 形の誤り が `計算する` の外まで上がり、その会社の月が丸ごと落ちていた。
今は 要る値.確かめる が 芯/設定の表.json で照らし、既定の語で計算して仮＋問いにし、見落とした所は `計算する` がその人だけ値なしの仮にする。
⟦鍵:給与計算/足りない時は仮で計算し出さない⟧（仮の人は出口へ出ない）。
"""
import pytest
from 作る_計算 import 人, 値たち, 回す, 決まり

from 芯 import 設定

端数の項目 = sorted(n for n, e in 設定.表().items() if e["形"] == "端数の語" and "計算" in e["読む所"])


def _問い(r):
    return [q["何が無いか"] for q in r["問い"]]


@pytest.mark.parametrize("項目", 端数の項目)
def test_選べる値の外の端数の語は既定で計算して仮と問い(tmp_path, 項目):
    r = 回す(tmp_path, 決=決まり(**{項目: "切り捨てる（作り物の語）"}))
    素 = 値たち(回す(tmp_path / "b"))
    assert r["人"][0]["状態"] == "仮"
    assert [q for q in _問い(r) if q.startswith(f"{項目}「切り捨てる（作り物の語）」は選べる値の外")]
    # 既定の語で最後まで計算した（値なしで落ちない）
    v = 値たち(r)
    assert v["差引支給額"] == 素["差引支給額"]


def test_端数の語をそろえた字は仮にしない(tmp_path):
    # `切り上げ`・`切上げ` のような字の違いは今までどおり同じ語（語をそろえる）
    r = 回す(tmp_path, 決=決まり(**{"日割.端数": "切り上げ", "社保.端数": "50 銭以下切捨て 50 銭超切上げ"}))
    assert r["人"][0]["状態"] == "確認済" and _問い(r) == []


def test_仮の人が1人いてもほかの人は計算する(tmp_path):
    from 芯.計算 import 計算する

    from 作る_計算 import 月の数字, 置き場
    行 = [*月の数字(NO="0001"), *月の数字(NO="0002")]
    決 = {("C1", "0001"): 決まり(**{"端数.割増の総額": "切り捨てる（作り物の語）"}), ("C1", "0002"): 決まり()}
    r = 計算する({"行": 行, "人": []}, 決まり=決, 人={("C1", NO): 人() for NO in ("0001", "0002")},
                置き場=置き場(tmp_path))
    状態 = {x["NO"]: x["状態"] for x in r["人"]}
    assert 状態 == {"0001": "仮", "0002": "確認済"}
