"""委託の式が `時間.日の所定` を使うかの印（芯/計算/委託.py の 日の所定を使うか）と、計算する の額が合うかの見張り（作り物の値だけ）。

印が偽の人は 日の所定 を 8 から 10 に変えても委託分の額が 1 円も変わらない（段の解決はこの印で見当の 8 を仮にしない）。
印が真の人の例は、日の所定で額が変わる。式を直して印とずれたらここが赤になる。
"""
import pytest

from 芯.計算 import 委託
from 作る_計算 import 人, 決まり, 月の数字
from test_計算_役員と委託 import _回す, _値

_日ごと = {"2027-01-05": "10:00", "2027-01-06": "8:30", "2027-01-07": "5:30"}


def _委託分(tmp, 所定, 決の値, 人の値):
    決 = 決まり(**{"委託.丸め": "切捨て", "委託.実働の丸め": "丸めない", "時間.日の所定": 所定, **決の値})
    月 = 月の数字(上書き={"出勤日数": "3", "法定休日": "0", "所定休日": "0"})
    d = tmp / f"所定{所定}"
    d.mkdir()
    r = _回す(d, 決, 人(**{"人.区分": "委託", **人の値}), 月=月, 入力={"委託.日ごとの実働": _日ごと})
    return {k: v for k, v in _値(r).items() if k.startswith(委託.前)}


使わない = [
    ({"委託.式": "日ごとに時給か日当", "委託.日当の境": "8:00"}, {"委託.日給": "12000", "委託.時給": "1500"}),
    ({"委託.式": "日ごとに時給か日当", "委託.日当の境": "9:00 超"}, {"委託.日給": "12000", "委託.時給": "1500"}),
    ({"委託.式": "時給"}, {"委託.時給": "1500"}),
]
使う = [
    ({"委託.式": "日ごとに時給か日当", "委託.日当の境": "無し"}, {"委託.日給": "12000", "委託.時給": "1500"}),
    ({"委託.式": "日ごとに時給か日当", "委託.日当の境": "8:00"}, {"委託.日給": "12000"}),
]


@pytest.mark.parametrize("決の値, 人の値", 使わない)
def test_印が偽の人は日の所定で額が変わらない(tmp_path, 決の値, 人の値):
    assert not 委託.日の所定を使うか({**決の値, **人の値})
    assert _委託分(tmp_path, "8", 決の値, 人の値) == _委託分(tmp_path, "10", 決の値, 人の値)


@pytest.mark.parametrize("決の値, 人の値", 使う)
def test_印が真の例は日の所定で額が変わる(tmp_path, 決の値, 人の値):
    assert 委託.日の所定を使うか({**決の値, **人の値})
    assert _委託分(tmp_path, "8", 決の値, 人の値) != _委託分(tmp_path, "10", 決の値, 人の値)


def test_段の解決は芯の印を引くだけ():
    """式の知識（どの式が日の所定を使うか）を初期設定に 2 つ目として書き直さない。"""
    from pathlib import Path
    本文 = (Path(__file__).resolve().parents[2] / "初期設定" / "段の解決.py").read_text(encoding="utf-8")
    assert "委託.日の所定を使うか(" in 本文
    assert "日ごとに時給か日当" not in 本文.split("def 委託で日の所定を使うか")[1].split("\ndef ")[0]
