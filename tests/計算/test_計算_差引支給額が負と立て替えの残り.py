"""払えない額・消える立て替えを「確認済」で出さない（作り物の 1 人）。

- 差引支給額が負（給与が少しの月に住民税や控除の行がある）: 引けない分の扱いは会社ごと＝負のまま仮にして、
  どの控除がいくらかを名指しした問い 1 つを出す（黙って 0 に丸めない・翌月へ回さない）。
- 社保の立て替えの残りが在るのに式が 毎月請求: 返し方が決まっていない＝黙って読み飛ばさず仮＋問い 1 つ。
"""
from 作る_計算 import 人, 回す, 決まり, 値たち

鍵 = ("C1", "0001")
少し出た = {"出勤日数": "2", "欠勤": "18", "総労働": "960", "所定内": "960", "法定内残業": "0", "法定外残業": "0", "深夜": "0",
         "遅刻早退": "0"}
月給 = {"項目.人の額": {"基本給": "280000", "職務手当": "20000", "通勤手当": "0"}}


def _回す(tmp, 上書き=None, 入力=None, 親睦会費=True):
    行 = 決まり()["項目.行"] if 親睦会費 else [r for r in 決まり()["項目.行"] if r["名"] != "親睦会費"]
    決 = 決まり(**{"社保.引けない月の本人負担": "毎月請求", "項目.行": 行})
    r = 回す(tmp, 決=決, 人の値=人(**月給), 上書き=上書き, 入力={鍵: 入力} if 入力 else None)
    return r, 値たち(r)


def test_差引支給額が負なら仮で控除を名指しして問う(tmp_path):
    """注入: 出勤 2 日・欠勤 18 日・毎月請求・住民税 10000（再現の人）。"""
    r, v = _回す(tmp_path, 少し出た)
    assert v["差引支給額"] < 0                      # 黙って 0 に丸めない
    assert r["人"][0]["状態"] == "仮"               # 確認済で出口へ出さない
    問い = [q for q in r["問い"] if "差引支給額が" in q["何が無いか"]]
    assert len(問い) == 1
    assert f"住民税 {v['住民税']}" in 問い[0]["何が無いか"] and f"親睦会費 {v['親睦会費']}" in 問い[0]["何が無いか"]
    assert str(-v["差引支給額"]) in 問い[0]["何が無いか"]
    assert "社保の立て替えの残り" not in v           # 黙って翌月へ回さない


def test_差引支給額が0以上の人は仮にしない(tmp_path):
    """回帰: 給与の足りる月は今のまま（問いを足さない）。"""
    r, v = _回す(tmp_path)
    assert v["差引支給額"] > 0 and r["人"][0]["状態"] != "仮"
    assert not any("差引支給額が" in q["何が無いか"] for q in r["問い"])


def test_立て替えの残りがある毎月請求の人は仮で問う(tmp_path):
    """注入: 入力に 社保の立て替えの残り が在るのに式が 毎月請求（給与の足りる月）。"""
    r, v = _回す(tmp_path, 入力={"社保の立て替えの残り": "50000"})
    assert r["人"][0]["状態"] == "仮"
    問い = [q for q in r["問い"] if "社保の立て替えの残り" in q["何が無いか"]]
    assert len(問い) == 1 and "50000" in 問い[0]["何が無いか"] and "毎月請求" in 問い[0]["何が無いか"]
    assert "社保の立て替えの返し" not in v


def test_引けない月でも立て替えの残りを読み飛ばさない(tmp_path):
    """注入: 給与の無い月（引けない額あり）に残りが在る毎月請求の人も同じく仮＋問い。"""
    休職 = {**少し出た, "出勤日数": "0", "欠勤": "20", "総労働": "0", "所定内": "0"}
    r, v = _回す(tmp_path, 休職, 入力={"社保の立て替えの残り": "50000"}, 親睦会費=False)
    assert v["社保の引けない額"] > 0 and r["人"][0]["状態"] == "仮"
    assert any("社保の立て替えの残り" in q["何が無いか"] for q in r["問い"])


def test_残りが無い毎月請求の人は仮にしない(tmp_path):
    r, _ = _回す(tmp_path, 入力={"社保の立て替えの残り": "0"})
    assert r["人"][0]["状態"] != "仮"
