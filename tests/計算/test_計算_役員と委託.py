"""役員と委託の式（⟦鍵:給与計算/役員と委託と残業の扱い⟧）。作り物の値だけ。

- 役員: 勤怠なしで決まった役員報酬から社保と源泉を引く。最低賃金・割増・欠勤控除を当てない（最低賃金法 2 条）。
- 委託だけ・委託の併用: 委託分の式（前の道具 timecard_tally の itaku を今の型へ）。併用は 1 枚の縦に雇用分と委託分。最低賃金は雇用分だけで見る。
- 委託の日当の境: 日ごとに時給か日当（以上・を超える）。
- 委託の源泉: 法の表/源泉_報酬（率と 100 万円の境・所得税法 204・205 条）。試験の置き場に国の率の表を置く（芯は値を持たない）。
"""
import json
from decimal import Decimal

from 作る_計算 import 人, 決まり, 置き場, 月の数字
from 芯.計算 import 計算する

鍵 = ("C1", "0001")


def _報酬の表(d, 置く=True):
    if 置く:
        出典 = {"URL": "作り物（試験だけ・所得税法 204 条 1 項・205 条 1 号の率）", "取った日": "2026-11-11"}
        (d / "源泉_報酬.json").write_text(json.dumps({
            "表の名": "源泉_報酬", "基準": "支払日", "単位": "率", "引く鍵": [], "欠けた時": "止める",
            "行": [{"鍵": {}, "効く始め": "2013-01-01", "効く終わり": "2037-12-31", "状態": "出た",
                    "値": {"率%": "10.21", "境の額": 1000000, "境を超えた分の率%": "20.42"}, "出典": 出典}]},
            ensure_ascii=False), encoding="utf-8")
    else:
        (d / "源泉_報酬.json").unlink(missing_ok=True)
    return d


def _回す(tmp, 決=None, 人の値=None, 月=None, 入力=None, 表=True):
    return 計算する(月の数字() if 月 is None else 月,
                   決まり={鍵: 決 if 決 is not None else 決まり()},
                   人={鍵: 人の値 if 人の値 is not None else 人()},
                   入力={鍵: 入力} if 入力 else None, 置き場=_報酬の表(置き場(tmp), 表), 支給月="2027-02")


def _値(r):
    return {x["項目"]: x["値"] for x in r["行"]}


def _状態(r):
    return {x["項目"]: x["状態"] for x in r["行"]}


# ---- 役員

def _役員の決まり(**上書き):
    d = 決まり(**{"項目.行": [{"名": "役員報酬", "支給か控除": "支給", "単価の元": "人の額"}]})
    del d["時間.日の所定"]   # 役員は所定の時間を持たない
    d.update(上書き)
    return d


def _役員(**上書き):
    return 人(**{"人.区分": "役員", "項目.人の額": {"役員報酬": "500000"}, "社保.標準報酬": "500000", **上書き})


def test_役員は勤怠なしで社保と源泉が引かれて出る(tmp_path):
    r = _回す(tmp_path, _役員の決まり(), _役員(), 月=[])
    v = _値(r)
    assert r["人の状態"] == {("2027-02", "C1", "0001"): "確認済"}
    assert v["役員報酬"] == 500000 and v["総支給額"] == 500000
    assert v["健康保険"] > 0 and v["厚生年金"] > 0 and v["源泉所得税"] > 0
    assert v["雇用保険"] == 0 and v["時間外手当"] == 0 and v["欠勤控除"] == 0
    assert v["差引支給額"] == v["総支給額"] - v["控除合計"]
    assert r["問い"] == [] and r["法の線"] == []


def test_役員は最低賃金で赤にならない(tmp_path):
    # 低い役員報酬と勤怠のある役員でも、最低賃金・割増・欠勤控除を当てない（同じ額の社員は赤）
    低 = {"項目.人の額": {"役員報酬": "60000"}, "社保.標準報酬": "58000"}
    r = _回す(tmp_path, _役員の決まり(), _役員(**低))
    assert r["法の線"] == [] and r["人"][0]["状態"] == "確認済"
    v = _値(r)
    assert v["時間外手当"] == 0 and v["欠勤控除"] == 0 and v["遅刻早退控除"] == 0
    社員 = _回す(tmp_path / "b", 決まり(**{"項目.行": [{"名": "役員報酬", "支給か控除": "支給", "単価の元": "人の額"}]}),
               人(**低))
    assert any("最低賃金" in t for t in 社員["法の線"]) and 社員["人"][0]["状態"] == "仮"


