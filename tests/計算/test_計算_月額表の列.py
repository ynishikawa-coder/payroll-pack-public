"""源泉の月額表の行は、行の中の位置でなく 表.列 の名で読む（芯/計算/支給控除.py の 月額表の税額）。値は作り物の表だけ。

防ぐ故障（台帳 束 K3）: 月額表の行を r[0]〜r[3] の位置で読んでいたので、表の列の並びが変わると違う欄の額が黙って税になった。
正解の値は、下の作り物の表に手で書いた欄の額から起こす（今の出力から写さない）。
"""
from decimal import Decimal

import pytest

from 芯.計算.支給控除 import 月額表の税額

# 作り物の表: 100,000 以上 200,000 未満の 1 行。甲は扶養 0〜7 人で 1000・900・…・300 円、乙は 5000 円。
甲 = [1000, 900, 800, 700, 600, 500, 400, 300]


def 表(列):
    行 = {"以上": 100000, "未満": 200000, "甲0〜7人": 甲, "乙": 5000}
    return {"下の端": {"未満": 100000, "甲": 0, "乙の率%": 3},
            "7人を超える1人ごとに引く": 50, "従たる給与の1人ごとに引く": 10,
            "表": {"列": list(列), "行": [[行[c] for c in 列]]},
            "甲の区間": [], "乙の区間": [], "点": []}


@pytest.mark.parametrize("列", [("以上", "未満", "甲0〜7人", "乙"), ("乙", "甲0〜7人", "未満", "以上"),
                                ("未満", "乙", "以上", "甲0〜7人")])
def test_列の並びが変わっても同じ欄の額を引く(列):
    t = 表(列)
    assert 月額表の税額(t, Decimal(150000), "甲", 0) == 1000
    assert 月額表の税額(t, Decimal(150000), "甲", 2) == 800
    assert 月額表の税額(t, Decimal(150000), "甲", 9) == 300 - 50 * 2     # 7 人を超える 2 人分を引く
    assert 月額表の税額(t, Decimal(150000), "乙", 1) == 5000 - 10


def test_要る列の名が無い表は止める():
    t = 表(("以上", "未満", "甲0〜7人", "乙"))
    t["表"]["列"] = ["以上", "未満", "甲", "乙"]
    with pytest.raises(ValueError, match="甲0〜7人"):
        月額表の税額(t, Decimal(150000), "甲", 0)
    t = 表(("以上", "未満", "甲0〜7人", "乙"))
    t["表"]["行"][0] = t["表"]["行"][0][:3]
    with pytest.raises(ValueError, match="形でない"):
        月額表の税額(t, Decimal(150000), "甲", 0)


def test_本物の表は列の名を持つ():
    import json
    from pathlib import Path
    根 = Path(__file__).resolve().parents[2]
    for r in json.loads((根 / "法の表" / "源泉_月額表.json").read_text(encoding="utf-8"))["行"]:
        assert 月額表の税額(r["値"], Decimal(r["値"]["表"]["行"][0][0]), "甲", 0) >= 0
