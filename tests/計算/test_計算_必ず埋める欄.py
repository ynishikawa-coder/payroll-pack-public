必ず = ("人.区分", "源泉.欄", "源泉.扶養の数", "社保.加入", "雇保.加入", "時間.制度", "社保.徴収の月")
前の既定 = {"人.区分": "社員", "源泉.欄": "甲", "源泉.扶養の数": "0", "社保.加入": "加入", "雇保.加入": "加入",
          "時間.制度": "通常", "社保.徴収の月": "翌月徴収"}   # この直しの前に空を黙って埋めていた字


def _空にして回す(tmp, 名):
    """名を決まりからも人の値からも抜いて回す（段の解決の後に空＝マスタのどの段にも無い）。"""
    決, 人の値 = 決まり(), 人()
    決.pop(名, None)
    人の値.pop(名, None)
    return 回す(tmp, 決=決, 人の値=人の値)


def test_必ず埋める欄は表に7つで既定を持たない():
    表 = 設定.表()
    assert set(設定.必ず埋める()) == set(必ず)
    for 名 in 必ず:
        assert "既定" not in 表[名] and not 表[名].get("埋める"), 名
        assert 名 not in 設定.既定で埋める(), 名
    辞書 = {it["項目"]: it for it in json.loads((根 / "初期設定" / "項目.json").read_text(encoding="utf-8"))["項目"]}
    assert {n for n, it in 辞書.items() if it.get("必ず埋める")} == set(必ず)   # 辞書（正本の意味）と芯の表が同じ 7 つ
    assert all("既定" not in 辞書[n] for n in 必ず)


@pytest.mark.parametrize("名", 必ず)
def test_欄を空にするとその人は計算されず理由が返る(tmp_path, 名):
    r = _空にして回す(tmp_path, 名)
    assert r["人"] == [{"支給月": "2027-02", "会社": "C1", "NO": "0001", "状態": "仮", "仮の数": 1}], 名
    assert [(x["項目"], x["値"], x["状態"]) for x in r["行"]] == [("差引支給額", None, "仮")], 名   # 額を 1 つも出さない
    assert r["止めた"] == [{"支給月": "2027-02", "会社": "C1", "NO": "0001", "理由": [f"必ず埋める欄が空: {名}"]}], 名
    assert r["行"][0]["見当の拠り所"] == f"必ず埋める欄が空: {名}"
    assert r["問い"] == [], "欠けは問いでなくマスタを埋める欠け（決定 9）"
    assert any(f"必ず埋める欄が空: {名}" in t for t in r["知らせ"])
    通 = 関所.通す(r["行"], r["人の状態"])
    assert 通.行たち == () and [x.NO for x in 通.外した人たち] == ["0001"]


def test_欄が幾つも空なら全部を理由に並べる(tmp_path):
    決, 人の値 = 決まり(), 人()
    for 名 in 必ず:
        決.pop(名, None)
        人の値.pop(名, None)
    r = 回す(tmp_path, 決=決, 人の値=人の値)
    # 社保.加入 が空なら社保に入るか決まらない＝保険料を引く月はまだ求めない（社保.加入 を埋めた後に要れば止まる）
    assert r["止めた"][0]["理由"] == [f"必ず埋める欄が空: {n}" for n in sorted(必ず) if n != "社保.徴収の月"]


def test_選べる値の外の字も外して止め_外の字の問いは残す(tmp_path):
    r = 回す(tmp_path, 人の値=人(**{"源泉.欄": "作り物の外の字"}))
