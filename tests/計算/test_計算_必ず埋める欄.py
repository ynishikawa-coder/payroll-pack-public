"""必ず埋める欄（決定 9・21）: 人.区分・源泉.欄・社保.加入・雇保.加入・時間.制度・源泉.扶養の数・社保.徴収の月（保険料を引く月）。

空のマスタから黙って社員・甲・加入・通常・扶養 0・翌月徴収で確定した額が出ない。根治の D＝欄を 1 つずつ空にして、
芯がその人を計算せず、理由「必ず埋める欄が空: <名>」を返し、出口の関所で外れることを示す。作り物の値だけ。
- 欄ごと（7 つ）: 空にすると計算されず理由が返る（行は値なしの差引支給額だけ＝額を出さない）
- 回帰: 値を置いた人は前の既定を書いた時と同じ額で確認済（計算の見張り 計算_見張り_期待.json は書き換えていない）
- 誤りを戻すと赤: 既定で埋める道へ 1 欄を戻すと、空の人に額が出る（この試験が見る所が効いている）
- 要らない人には求めない: 委託だけの人の社保・雇保・源泉・時間の制度、役員（役員＋委託の併用 も）の雇保と時間の制度
"""
import json
