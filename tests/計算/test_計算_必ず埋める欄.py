def test_要らない人には求めない(tmp_path):
    # 委託だけの人: 社保・雇保・源泉・時間の制度・保険料を引く月を読まない（人.区分 だけ要る）
    委 = 人(**{"人.区分": "委託", "委託.月給": "300000", "委託.時給": "2000"})
    for n in ("社保.加入", "雇保.加入", "源泉.欄", "源泉.扶養の数"):
        委.pop(n)
    決 = 決まり(**{"委託.式": "月額", "委託.丸め": "切捨て", "委託.みなし残業時間": "無し"})
    for n in ("時間.制度", "社保.徴収の月"):
        決.pop(n)
    r = 回す(tmp_path, 決=決, 人の値=委)
    assert r["止めた"] == [] and r["人"][0]["状態"] == "確認済", r["問い"]
    # 役員: 雇保と時間の制度は読まない
    役 = 人(**{"人.区分": "役員", "項目.人の額": {"役員報酬": "500000"}, "社保.標準報酬": "500000"})
    役.pop("雇保.加入")
    決 = 決まり(**{"項目.行": [{"名": "役員報酬", "支給か控除": "支給", "単価の元": "人の額"}]})
    決.pop("時間.制度")
    del 決["時間.日の所定"]
    r = 計算する([], 決まり={("C1", "0001"): 決}, 人={("C1", "0001"): 役}, 置き場=置き場(tmp_path / "役"), 支給月="2027-02")
    assert r["止めた"] == [], r["止めた"]
    # 兼務役員は使用人の分で雇保に入る＝雇保.加入 が要る
    兼 = 人(**{"人.区分": "兼務役員"})
    兼.pop("雇保.加入")
    r = 回す(tmp_path / "兼", 人の値=兼)
    assert r["止めた"][0]["理由"] == ["必ず埋める欄が空: 雇保.加入"]
    # 社保に入らない人は保険料を引く月が要らない
    r = 回す(tmp_path / "社", 決={k: v for k, v in 決まり().items() if k != "社保.徴収の月"}, 人の値=人(**{"社保.加入": "加入しない"}))
    assert r["止めた"] == []


