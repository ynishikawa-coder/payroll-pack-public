"""賞与で差引支給額が負になる人を「確認済」で出さない（作り物の 1 人）。

今の率では賞与の控除が賞与の額を超えないので、会社の決まり 雇保.本人負担率 を 1 を超える作り物の率にして負を作る（注入）。
止め方は月給と同じ 一人._負の差引（1 つの正本）: 値は負のまま仮にし、引く控除を名指しした問い 1 つを出す。
"""
from 作る_計算 import 人, 決まり, 値たち, 置き場
from 芯.計算 import 賞与を計算する

k = ("C1", "0001")


def _賞与(tmp_path, 本人負担率):
    u = 人(**{"社保.加入": "加入しない", "雇保.加入": "加入", "源泉.扶養の数": "0", "源泉.欄": "甲"})
    決 = 決まり(**({"雇保.本人負担率": 本人負担率} if 本人負担率 else {}))
    return 賞与を計算する([{"会社": "C1", "NO": "0001", "額": 300000, "原本の名前": "作り物"}], 支給日="2027-02-26",
                     決まり={k: 決}, 人={k: u}, 前月の課税対象額={k: 300000}, 前の標準賞与額={k: 0},
                     計算期間={k: 6}, 置き場=置き場(tmp_path))


def test_賞与の差引支給額が負なら仮で控除を名指しして問う(tmp_path):
    """注入: 雇保.本人負担率 1.5（雇用保険 450,000 円＞賞与 300,000 円）。"""
    r = _賞与(tmp_path, "1.5")
    v = 値たち(r)
    assert v["雇用保険"] == 450000
    assert v["差引支給額"] < 0                       # 黙って 0 に丸めない
    assert r["人"][0]["状態"] == "仮"                # 確認済で出口へ出さない
    問い = [q for q in r["問い"] if "差引支給額が" in q["何が無いか"]]
    assert len(問い) == 1
    assert f"社会保険計 {v['社会保険計']}" in 問い[0]["何が無いか"]
    assert str(-v["差引支給額"]) in 問い[0]["何が無いか"]


def test_賞与の差引支給額が0以上の人は仮にしない(tmp_path):
    """回帰: 普通の率の人は今のまま（問いを足さない）。"""
    r = _賞与(tmp_path, None)
    v = 値たち(r)
    assert v["差引支給額"] > 0 and r["人"][0]["状態"] != "仮"
    assert not any("差引支給額が" in q["何が無いか"] for q in r["問い"])
