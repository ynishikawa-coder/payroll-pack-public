def test_人ごとの率と印で時給の人と月給の人の差額を分ける(tmp_path):
    from decimal import Decimal
    共 = 決まり(**{"割増.時間外の率": "0", "法の線.承知": {"割増.時間外の率": "問20"}})   # 会社の段＝月給の人
    時給の人 = {**共, "割増.時間外の率": "1.00", "法の線.承知": {"割増.時間外の率": "問21"}}   # 段の解決が型・人の段を重ねた値
    鍵 = [("C1", "0001"), ("C1", "0002")]
    r = 計算する([*月の数字(), *月の数字(NO="0002")], 決まり=dict(zip(鍵, (共, 時給の人))),
              人={k: 人() for k in 鍵}, 置き場=置き場(tmp_path))
    v = {(x["NO"], x["項目"]): x["値"] for x in r["行"]}
    法 = 値たち(回す(tmp_path / "b"))
    assert v[("0001", "時間外手当")] == 0 and v[("0002", "時間外手当")] > 0
    assert [x["状態"] for x in r["人"]] == ["確認済", "確認済"]
    一, 二 = (next(t for t in 承知の知らせ(r) if t.startswith(f"C1 {n}:")) for n in ("0001", "0002"))
    assert "（問20）＝会社の値 0" in 一 and f"差額 {法['総支給額'] - v[('0001', '総支給額')]} 円" in 一
    # 時給の人の差額は 1.25 − 1.00 の分（率そのものでない）
    差額 = 法["総支給額"] - v[("0002", "総支給額")]
    assert "（問21）＝会社の値 1.00" in 二 and f"差額 {差額} 円）" in 二
    assert abs(Decimal(差額) - Decimal(法["時間外手当"]) / 5) <= 1


