def 承知の知らせ(r):
    return [t for t in r["知らせ"] if "承知した食い違い" in t]


def test_時間外を払わない印は会社の率0で確定し差額を知らせる(tmp_path):
    決 = 決まり(**{"割増.時間外の率": "0", "法の線.承知": {"割増.時間外の率": "問12"}})
    r = 回す(tmp_path, 決=決)
    v = {x["項目"]: x for x in r["行"]}
    法 = 値たち(回す(tmp_path / "b"))
    assert v["時間外手当"]["値"] == 0 and v["時間外手当"]["状態"] == "確定"
    assert r["人"][0]["状態"] == "確認済"
    (t,) = 承知の知らせ(r)
    差額 = 法["総支給額"] - v["総支給額"]["値"]
    assert 差額 == 法["時間外手当"] > 0
    assert t == (f"C1 0001: 承知した食い違い: 割増.時間外の率（問12）＝会社の値 0（法の線 1.25）を会社の値で計算した。"
                 f"法の線なら総支給額 {法['総支給額']} 円（差額 {差額} 円）")
    assert any(x.startswith("C1 0001: 承知: 割増.時間外の率") for x in r["法の線"])


