def test_線たちは日ごとの読みと同じ上書きの形():
    # 下の段（勤務の型）の印は上の段の印をまるごと上書き＝その型の日にしか来ない人は上の段の線を数え直さない
    from 芯.計算 import 承知
    値 = {"法の線.承知": {"時間.日の所定": "問7", "割増.深夜の時間帯": "問1"},
         "勤務の型": {"T": {"法の線.承知": "割増.深夜の時間帯=問9"}, "U": {"法の線.承知": ""}, "V": {}}}
    assert 承知.線たち(値, ["T"]) == {"割増.深夜の時間帯": "問9"}
    assert 承知.線たち(値, ["U", "V"]) == 承知.線たち(値, [None]) == {"時間.日の所定": "問7", "割増.深夜の時間帯": "問1"}
    assert 承知.線たち(値, ["T", None]) == {"割増.深夜の時間帯": "問9", "時間.日の所定": "問7"}
    assert set(承知.線たち(値)) == {"時間.日の所定", "割増.深夜の時間帯"}   # 日の型を渡さない時は在り得る日の全部
    assert 承知.印の値(値, "T") == "割増.深夜の時間帯=問9" and 承知.印の値(値, "U") == 値["法の線.承知"]


