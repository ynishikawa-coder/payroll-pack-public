# ---- 割増.時間外の基礎の行（型の版 7。法の線ではない＝率は変えない。1.0 倍の分を載せる行だけ）----
def _単価(r):
    from decimal import Decimal
    (x,) = [x for x in r["行"] if x["項目"] == "時間外手当"]
    return Decimal(x["出所"].split("割増の単価 ")[1].split("（")[0])


def test_時間外の1倍の分を基本給の行に載せ残業手当は割増の分だけ(tmp_path):
    from decimal import ROUND_HALF_UP, Decimal
    前 = 値たち(回す(tmp_path / "a", 上書き={"法定外残業": "4800", "60 時間超": "1200"}))
    r = 回す(tmp_path / "b", 決=決まり(**{"割増.時間外の基礎の行": "基本給"}), 上書き={"法定外残業": "4800", "60 時間超": "1200"})
    後 = 値たち(r)
    u = _単価(r)
    基礎 = (u * 60).quantize(Decimal(1), ROUND_HALF_UP), (u * 20).quantize(Decimal(1), ROUND_HALF_UP)   # 60 時間まで・60 時間超
    assert 前["時間外手当"] > 0 and 前["60時間超手当"] > 0
    assert 後["時間外手当"] == 前["時間外手当"] - 基礎[0] and 後["60時間超手当"] == 前["60時間超手当"] - 基礎[1]
    assert abs(Decimal(後["時間外手当"]) - u * 60 * Decimal("0.25")) <= 1   # 残業手当は 0.25 倍の分だけ
    assert 後["基本給"] == 前["基本給"] + 基礎[0] + 基礎[1]
    for k in ("課税計", "総支給額", "雇用保険", "社会保険計", "源泉所得税", "差引支給額", "法定内残業手当"):
        assert 後[k] == 前[k], k
    assert r["人"][0]["状態"] == "確認済" and not 承知の知らせ(r)


