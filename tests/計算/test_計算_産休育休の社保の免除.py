"""産休・育休の社保の本人の保険料の免除（社員の列 育休の始め・育休の終わり・産休の始め・産休の終わり → 社保.育休の始め ほか）。

健保法 159 条・厚年法 81 条の 2: 月末に休みの中の月は免除。2022-10 からは同じ月の中で始まり終わる育休が 14 日以上の月も免除。
賞与は月末に休みの中で、育休は 1 か月を超える時だけ。雇用保険は免除しない。作り物の 1 人（支給月 2027-02・翌月徴収＝保険料の月 2027-01）。
"""
from decimal import Decimal

from 作る_計算 import 人, 回す, 決まり, 値たち, 置き場
from 芯.計算 import 賞与を計算する

社保 = ("健康保険", "介護保険", "子ども・子育て支援金", "厚生年金")


def _月(tmp, **人の値):
    r = 回す(tmp, 人の値=人(**人の値))
    return r, 値たち(r)


def _免除(v):
    return all(v[n] == 0 for n in 社保)


def test_月末に育休の中の月は免除_雇保は免除しない(tmp_path):
    _, 元 = _月(tmp_path / "元")
    r, v = _月(tmp_path / "a", **{"社保.育休の始め": "2026-12-01", "社保.育休の終わり": "2027-03-31"})
    assert _免除(v) and 元["健康保険"] > 0
    assert v["雇用保険"] == 元["雇用保険"]
    assert r["人"][0]["状態"] != "仮"
    # 終わりが空＝月末に休みの中
    _, v = _月(tmp_path / "b", **{"社保.育休の始め": "2027-01-31"})
    assert _免除(v)


def test_終わりの日の翌日の月は免除しない(tmp_path):
    # 2027-01-30 に終わる（翌日 01-31 も 1 月）＝1 月の月末は休みの外。始めは 12 月＝同じ月の中ではない
    _, v = _月(tmp_path / "a", **{"社保.育休の始め": "2026-12-01", "社保.育休の終わり": "2027-01-30"})
    assert not _免除(v)
    # 2026-12-31 に終わる＝保険料の月 2027-01 は休みの外
    _, v = _月(tmp_path / "b", **{"社保.育休の始め": "2026-12-01", "社保.育休の終わり": "2026-12-31"})
    assert not _免除(v)


def test_同じ月の中で14日以上の育休は免除_13日は免除しない(tmp_path):
    _, v = _月(tmp_path / "a", **{"社保.育休の始め": "2027-01-05", "社保.育休の終わり": "2027-01-18"})   # 14 日
    assert _免除(v)
    _, v = _月(tmp_path / "b", **{"社保.育休の始め": "2027-01-05", "社保.育休の終わり": "2027-01-17"})   # 13 日
    assert not _免除(v)


def test_14日の決まりは産休に当てない(tmp_path):
    _, v = _月(tmp_path / "a", **{"社保.産休の始め": "2027-01-05", "社保.産休の終わり": "2027-01-25"})
    assert not _免除(v)
    _, v = _月(tmp_path / "b", **{"社保.産休の始め": "2026-11-20", "社保.産休の終わり": "2027-02-25"})
    assert _免除(v)


def test_14日の決まりは2022年10月の保険料の月から():
    from 芯.計算.支給控除 import 産休育休の免除
    v = {"社保.育休の始め": "2022-09-05", "社保.育休の終わり": "2022-09-25"}
    assert 産休育休の免除(v, (2022, 9), False)[0] is None
    v = {"社保.育休の始め": "2022-10-05", "社保.育休の終わり": "2022-10-25"}
    assert 産休育休の免除(v, (2022, 10), False)[0] == "育休"


def test_読めない日と前後の逆は免除しないで仮(tmp_path):
    """注入: 字の誤り・終わりが始めより前・始めの無い終わり → 黙って免除しない・黙って引かない（仮＋問い＝出口へ出さない）。"""
    for i, 値 in enumerate(({"社保.育休の始め": "2027/01/xx"},
                           {"社保.育休の始め": "2027-01-20", "社保.育休の終わり": "2027-01-05"},
                           {"社保.育休の終わり": "2027-03-31"})):
        r, v = _月(tmp_path / f"x{i}", **値)
        assert r["人"][0]["状態"] == "仮", 値
        assert any("育休" in q["何が無いか"] for q in r["問い"]), 値


def _賞与(tmp, sub, 支給日, **人の値):
    k = ("C1", "0001")
    return 賞与を計算する([{"会社": "C1", "NO": "0001", "額": 500000, "原本の名前": "作り物"}], 支給日=支給日,
                     決まり={k: 決まり()}, 人={k: 人(**人の値)}, 前月の課税対象額={k: 300000},
                     前の標準賞与額={k: 0}, 置き場=置き場(tmp / sub), 計算期間={k: 6})


def test_賞与は月末に育休の中で1か月を超える時だけ免除(tmp_path):
    元 = 値たち(_賞与(tmp_path, "元", "2027-02-26"))
    assert 元["健康保険"] > 0
    # 1 か月を超える（01-15〜02-28）
    v = 値たち(_賞与(tmp_path, "a", "2027-02-26", **{"社保.育休の始め": "2027-01-15", "社保.育休の終わり": "2027-02-28"}))
    assert _免除(v) and v["雇用保険"] == 元["雇用保険"]
    # ちょうど 1 か月（02-01〜02-28）＝超えない＝免除しない（月の給与なら免除の月）
    v = 値たち(_賞与(tmp_path, "b", "2027-02-26", **{"社保.育休の始め": "2027-02-01", "社保.育休の終わり": "2027-02-28"}))
    assert not _免除(v)
    # 同じ月の 14 日以上でも月末が休みの外なら免除しない（14 日の決まりは賞与に当てない）
    v = 値たち(_賞与(tmp_path, "c", "2027-02-26", **{"社保.育休の始め": "2027-02-01", "社保.育休の終わり": "2027-02-20"}))
    assert not _免除(v)
    # 産休は月末に休みの中なら免除
    v = 値たち(_賞与(tmp_path, "d", "2027-02-26", **{"社保.産休の始め": "2027-02-20", "社保.産休の終わり": "2027-04-30"}))
    assert _免除(v)


def test_賞与で育休の終わりが空で1か月の中なら仮(tmp_path):
    r = _賞与(tmp_path, "a", "2027-02-26", **{"社保.育休の始め": "2027-02-10"})
    assert not _免除(値たち(r))
    assert r["人"][0]["状態"] == "仮" and any("1 か月を超える" in q["何が無いか"] for q in r["問い"])
    v = 値たち(_賞与(tmp_path, "b", "2027-02-26", **{"社保.育休の始め": "2027-01-10"}))   # 月末にもう 1 か月を超えている
    assert _免除(v)
