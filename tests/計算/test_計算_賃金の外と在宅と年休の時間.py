"""型の版 21 の 3 つの形（作り物の 1 人で前後の差を見る・期待値は試験の中で手で出す）。

- 支給か控除＝賃金の外: 総支給・課税・社保・雇保の外で差引支給額に足す。法の検査（割増の基礎から除く訳）は名前でなく印で外す
- 数量の引く数に月の数字の日の語: 日額×（出勤日数−在宅の日数）
- 年休の時間: 時給×年休の時間（休暇の語＝割増の単価に入れない）
"""
from 作る_計算 import 回す, 決まり, 値たち


def test_賃金の外の行は総支給と税と社保の外で差引支給額に足す(tmp_path):
    前 = 回す(tmp_path / "a")
    行 = 決まり()["項目.行"] + [{"名": "実費の弁償", "支給か控除": "賃金の外", "単価の元": "固定の額", "額": "30000"}]
    後 = 回す(tmp_path / "b", 決=決まり(**{"項目.行": 行}))
    a, b = 値たち(前), 値たち(後)
    for 名 in ("総支給額", "課税計", "非課税計", "雇用保険", "源泉所得税", "時間外手当", "控除合計"):
        assert a[名] == b[名], 名
    assert b["実費の弁償"] == 30000 and b["差引支給額"] == a["差引支給額"] + 30000
    assert not any("実費の弁償" in x for x in 後["法の線"])          # 割増の基礎から除く訳が無くても赤にしない
    assert 後["人の状態"] == 前["人の状態"]
    並び = [r["項目"] for r in 後["行"]]
    assert 並び.index("控除合計") < 並び.index("実費の弁償") < 並び.index("差引支給額")


def test_賃金の外の行の丸めの既定は払う物と同じ切上げ(tmp_path):
    # 前は 丸め が空の 賃金の外 の行が控除と同じ切捨てだった（100.5 → 100）
    行 = 決まり()["項目.行"] + [{"名": "実費の弁償", "支給か控除": "賃金の外", "単価の元": "固定の額", "額": "100.5"}]
    assert 値たち(回す(tmp_path / "a", 決=決まり(**{"項目.行": 行})))["実費の弁償"] == 101


def test_日額の通勤の日数から在宅の日を除く(tmp_path):
    行 = [r for r in 決まり()["項目.行"] if r["名"] != "通勤手当"] + [
        {"名": "通勤手当", "支給か控除": "支給", "単価の元": "固定の額", "額": "132", "課税": "通勤の非課税",
         "割増の基礎": "入らない", "割増の基礎から除く訳": "通勤手当", "欠勤で減る": "減らない"}]
    前 = 値たち(回す(tmp_path / "a", 決=決まり(**{"項目.行": [{**r, "数量の元": "勤怠の数:出勤日数"} if r["名"] == "通勤手当" else r for r in 行]}),
                    上書き={"在宅の日数": "2"}))
    後 = 値たち(回す(tmp_path / "b", 決=決まり(**{"項目.行": [{**r, "数量の元": "勤怠の数:出勤日数−在宅の日数"} if r["名"] == "通勤手当" else r for r in 行]}),
                    上書き={"在宅の日数": "2"}))
    assert 前["通勤手当"] == 132 * 19 and 後["通勤手当"] == 132 * 17


def test_時給の人の有休は時給と年休の時間で払い割増の単価に入れない(tmp_path):
    行 = [{"名": "時給", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:総労働"},
         {"名": "有給手当", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:年休の時間"}]
    from 作る_計算 import 人
    人の値 = 人(**{"項目.人の額": {"時給": "1110", "有給手当": "1110"}})
    決 = 決まり(**{"項目.行": 行, "支払.賃金の形": "時給"})
    無し = 値たち(回す(tmp_path / "a", 決=決, 人の値=人の値, 上書き={"年休の時間": "0"}))
    有り = 値たち(回す(tmp_path / "b", 決=決, 人の値=人の値, 上書き={"年休の時間": "360"}))
    assert 無し.get("有給手当", 0) == 0 and 有り["有給手当"] == 6660          # 1,110×6 時間
    assert 有り["時間外手当"] == 無し["時間外手当"]                             # 割増の単価は時給だけ（有休の行は入れない）


