"""時給の人の有休（時給×有給 1 日の時間×日数）と、夜勤の日を除く所定内の時給の行を部品の行で書く。

期待値は試験の中で手で出す（作り物の 1 人・時給 1,200 円・夜勤 1 回の日額 15,000 円）。
"""
from 作る_計算 import 人, 回す, 決まり, 値たち

時給の行 = [
    {"名": "時給", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:夜勤の日を除く所定内"},
    {"名": "夜勤手当", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:夜勤の回数", "割増の基礎": "入らない",
     "割増の基礎から除く訳": "臨時の賃金"},
    {"名": "有休", "支給か控除": "支給", "単価の元": "人の額×有給の1日の時間", "数量の元": "勤怠の数:年休（全日）"},
]
額 = {"項目.人の額": {"時給": "1200", "夜勤手当": "15000", "有休": "1200"}}
勤怠 = {"出勤日数": "18", "欠勤": "0", "総労働": "8400", "所定内": "8400", "夜勤の日を除く所定内": "7200",
        "夜勤の回数": "2", "年休（全日）": "2", "法定内残業": "0", "法定外残業": "0", "深夜": "0", "遅刻早退": "0"}


def _回す(tmp, 決=None, 人の値=None, 上書き=None):
    return 回す(tmp, 決=決まり(**{"支払.賃金の形": "時給", "項目.行": 時給の行, **(決 or {})}),
               人の値=人(**額, **(人の値 or {})), 上書き={**勤怠, **(上書き or {})})


def test_有休は時給と有給の1日の時間と日数(tmp_path):
    v = 値たち(_回す(tmp_path, 人の値={"有給.1日の時間": "360"}))   # 6 時間（段の解決は分の数の字で渡す）
    assert v["有休"] == 1200 * 6 * 2


def test_有給の1日の時間が無ければ日の所定(tmp_path):
    v = 値たち(_回す(tmp_path))
    assert v["有休"] == 1200 * 8 * 2                    # 時間.日の所定 8


def test_夜勤の日の時間は時給で払わない(tmp_path):
    v = 値たち(_回す(tmp_path))
    assert v["時給"] == 1200 * 7200 // 60               # 120 時間
    assert v["夜勤手当"] == 15000 * 2


def test_有休の行は割増の単価に入れない(tmp_path):
    v = 値たち(_回す(tmp_path, 上書き={"法定外残業": "60", "総労働": "8460"}))
    assert v["時間外手当"] == 1500                       # 1,200×1.25×1 時間（有休の行を足すと 2 倍になる）


def test_掛ける数が出ない時は仮(tmp_path):
    r = _回す(tmp_path, 決={"時間.日の所定": ""})
    行 = {a["項目"]: a for a in r["行"]}
    assert 行["有休"]["状態"] == "仮"


def test_夜勤の日を除く所定内が無く夜勤のある人は使う行だけ仮(tmp_path):
    """月の数字の口から分けられず行の来ない人: その語を数量に使う行だけ所定内で見当して仮（使わない会社の人は仮にしない）。"""
    from 作る_計算 import 月の数字, 置き場
    from 芯.計算 import 計算する
    上 = {k: v for k, v in 勤怠.items() if k != "夜勤の日を除く所定内"}
    行 = 月の数字(上書き=上)
    r = 計算する(行, 決まり={("C1", "0001"): 決まり(**{"支払.賃金の形": "時給", "項目.行": 時給の行})},
               人={("C1", "0001"): 人(**額)}, 置き場=置き場(tmp_path))
    行たち = {a["項目"]: a for a in r["行"]}
    assert 行たち["時給"]["状態"] == "仮" and 行たち["時給"]["値"] == 1200 * 8400 // 60
