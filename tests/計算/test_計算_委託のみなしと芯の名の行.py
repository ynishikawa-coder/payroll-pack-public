"""委託.みなし残業時間 と、芯が作る項目の名の部品の行（作り物の値だけ）。

- 委託.みなし残業時間: 月額の式の残業（会社の数え方の 1 日の所定超え か 法定内＋法定外−所定休日）から引く
  （オーナーの答え: 会社の数え方は「1 日の所定超え − みなし 10h」・前の道具 timecard_tally の itaku の みなし残業 の式もみなしの分は払わない）。
  無い・読めない時は引かずに見当で仮＋問い（黙って 0 にしない）。引いた後が法定外を下回れば知らせ。
- 支給控除の項目 の行に芯が作る名（住民税・健康保険・欠勤控除・委託分の… など）や同じ名が 2 つ来ても全員を止めない:
  その行を使わず、知らせ＋その会社の人を仮（問い 1 つ）。
"""
from decimal import Decimal

from 作る_計算 import 人, 決まり, 置き場, 月の数字
from 芯.計算 import 計算する

鍵 = ("C1", "0001")
_会社 = {"委託.式": "月額", "委託.丸め": "切捨て", "委託.出張日額": "5000"}
_所定超え = {"残業（会社の数え方）": "1260", "60 時間超（会社の数え方）": "0"}   # 1 日の所定超え 21 時間（法定外 10 時間）


def _回す(tmp, 決, 人の値, 上書き=None, 入力=None):
    return 計算する(月の数字(上書き=上書き), 決まり={鍵: 決}, 人={鍵: 人の値}, 入力={鍵: 入力} if 入力 else None,
                   置き場=置き場(tmp), 支給月="2027-02")


def _値(r):
    return {x["項目"]: x["値"] for x in r["行"]}


def _併用(**上書き):
    return 人(**{"人.区分": "委託の併用", "項目.人の額": {"基本給": "250000"}, "社保.標準報酬": "260000",
                "委託.月給": "550000", "委託.雇用分": "250000", "委託.時給": "2000", **上書き})


def _併用の決まり(**上書き):
    return 決まり(**{**_会社, "項目.行": [{"名": "基本給", "支給か控除": "支給", "単価の元": "人の額"}], **上書き})


_時間 = {"委託.雇用分の出勤時間": "160:00"}


# ---- 委託.みなし残業時間

def test_委託の併用で1日の所定超えからみなし10時間を引く(tmp_path):
    r = _回す(tmp_path, _併用の決まり(**{"委託.みなし残業時間": "10:00"}), _併用(), 上書き=_所定超え, 入力=_時間)
    v = _値(r)
    assert v["委託分の残業"] == 27500                      # (21−10) 時間×2,000×1.25
    assert r["人"][0]["状態"] == "確認済" and r["問い"] == []
    assert not any("下回る" in t for t in r["知らせ"])       # 11 時間 ≧ 法定外 10 時間


def test_みなしを引いて法定外を下回れば知らせ(tmp_path):
    r = _回す(tmp_path, _併用の決まり(**{"委託.みなし残業時間": "15:00"}), _併用(), 上書き=_所定超え, 入力=_時間)
    assert _値(r)["委託分の残業"] == 15000                  # (21−15) 時間×2,000×1.25
    assert r["人"][0]["状態"] == "確認済"                    # 知らせだけ（仮にしない）
    assert any("下回る" in t and "法定外残業 10" in t for t in r["知らせ"])


def test_みなしは会社の数え方の無い人も月額の残業から引く(tmp_path):
    # 法定内 120 分＋法定外 600 分＝12 時間 − みなし 10 時間＝2 時間
    r = _回す(tmp_path, 決まり(**_会社, **{"委託.みなし残業時間": "10:00"}), 人(**{"人.区分": "委託", "委託.月給": "300000",
                                                                                 "委託.時給": "2000"}))
    assert _値(r)["委託分の残業"] == 5000 and r["人"][0]["状態"] == "確認済"
    # みなしが残業より長い月は 0（負にしない）
    r = _回す(tmp_path / "b", 決まり(**_会社, **{"委託.みなし残業時間": "20:00"}), 人(**{"人.区分": "委託", "委託.月給": "300000",
                                                                                       "委託.時給": "2000"}))
    assert _値(r)["委託分の残業"] == 0


def test_みなしが無い時は引かずに仮と問い(tmp_path):
    r = _回す(tmp_path, _併用の決まり(), _併用(), 上書き=_所定超え, 入力=_時間)
    v = _値(r)
    assert v["委託分の残業"] == 52500                      # 引かずに見当（21 時間）
    assert r["人"][0]["状態"] == "仮"
    assert [q["何が無いか"] for q in r["問い"]] == ["委託.みなし残業時間 が無い"]
    assert "委託分の残業" in r["問い"][0]["変わる項目"]


def test_みなしが読めない時も仮で時間の数は時間で見当(tmp_path):
    for i, 字 in enumerate(("1:xx", "-1:00", "abc")):
        r = _回す(tmp_path / str(i), _併用の決まり(**{"委託.みなし残業時間": 字}), _併用(), 上書き=_所定超え, 入力=_時間)
        assert _値(r)["委託分の残業"] == 52500 and r["人"][0]["状態"] == "仮", 字
        assert any("読めない" in q["何が無いか"] for q in r["問い"]), 字
    r = _回す(tmp_path / "h", _併用の決まり(**{"委託.みなし残業時間": "10"}), _併用(), 上書き=_所定超え, 入力=_時間)
    assert _値(r)["委託分の残業"] == 27500 and r["人"][0]["状態"] == "仮"   # 10 を 10 分でなく 10 時間で見当


def test_みなしは無しなら引かず残業の無い月は問わない(tmp_path):
    r = _回す(tmp_path, _併用の決まり(**{"委託.みなし残業時間": "無し"}), _併用(), 上書き=_所定超え, 入力=_時間)
    assert _値(r)["委託分の残業"] == 52500 and r["人"][0]["状態"] == "確認済"
    零 = {"残業（会社の数え方）": "0", "60 時間超（会社の数え方）": "0", "法定外残業": "0", "法定内残業": "0"}
    r = _回す(tmp_path / "b", _併用の決まり(), _併用(), 上書き=零, 入力=_時間)
    assert _値(r)["委託分の残業"] == 0 and r["人"][0]["状態"] == "確認済" and r["問い"] == []


# ---- 芯が作る項目の名の部品の行

def _行(*足す):
    return [{"名": "基本給", "支給か控除": "支給", "単価の元": "人の額"},
            {"名": "職務手当", "支給か控除": "支給", "単価の元": "人の額"},
            {"名": "通勤手当", "支給か控除": "支給", "単価の元": "人の額", "課税": "通勤の非課税", "割増の基礎": "入らない",
             "割増の基礎から除く訳": "通勤手当", "欠勤で減る": "減らない"},
            {"名": "親睦会費", "支給か控除": "控除", "単価の元": "固定の額", "額": "1000"}, *足す]


def test_芯の名の行は使わず会社の全員を仮で問い1つ(tmp_path):
    元 = _値(計算する(月の数字() + 月の数字(NO="0002"), 決まり={("C1", n): 決まり() for n in ("0001", "0002")},
                    人={("C1", n): 人() for n in ("0001", "0002")}, 置き場=置き場(tmp_path / "a")))
    悪い = [{"名": n, "支給か控除": "控除", "単価の元": "固定の額", "額": "5000"} for n in ("住民税", "健康保険", "欠勤控除", "委託分の報酬")]
    決 = 決まり(**{"項目.行": _行(*悪い)})
    r = 計算する(月の数字() + 月の数字(NO="0002"), 決まり={("C1", n): 決 for n in ("0001", "0002")},
               人={("C1", n): 人() for n in ("0001", "0002")}, 置き場=置き場(tmp_path / "b"))
    assert {x["状態"] for x in r["人"]} == {"仮"} and len(r["人"]) == 2
    assert len(r["問い"]) == 4 and all(q["人"] == [("C1", "0001"), ("C1", "0002")] for q in r["問い"])
    assert all("芯が自分で作る項目の名とぶつかる" in q["何が無いか"] for q in r["問い"])
    assert any("住民税" in t and "使わない" in t for t in r["知らせ"])
    # その行を使わない＝芯の項目は上書きされない（行の無い時と同じ額）
    v = {(x["NO"], x["項目"]): x["値"] for x in r["行"]}
    assert v[("0001", "住民税")] == 元["住民税"] and v[("0001", "差引支給額")] == 元["差引支給額"]


def test_同じ名の行は2つ目を使わず仮(tmp_path):
    決 = 決まり(**{"項目.行": _行({"名": "親睦会費", "支給か控除": "控除", "単価の元": "固定の額", "額": "9000"})})
    r = 計算する(月の数字(), 決まり={鍵: 決}, 人={鍵: 人()}, 置き場=置き場(tmp_path))
    assert _値(r)["親睦会費"] == 1000 and r["人"][0]["状態"] == "仮"
    assert [q["何が無いか"] for q in r["問い"]] == ["部品の行に同じ名「親睦会費」が 2 つある"]
