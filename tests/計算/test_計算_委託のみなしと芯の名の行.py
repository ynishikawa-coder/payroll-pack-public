def test_みなし残業の式の法定休日は休日の率の上乗せだけ足す(tmp_path):
    # 法定休日 8 時間は総労働の内（時給の分は追加残業）。所定 170 時間で追加は 0＝上乗せ 0.35 の分だけ
    r = _回す(tmp_path, 決まり(**{**_みなしの会社, "委託.所定時間": "170:00"}), _みなしの人(), 上書き={"法定休日": "480"})
    v = _値(r)
    assert v["委託分の休日"] == 5600 and v["委託分の残業"] == 12500   # 8×2,000×0.35


def test_みなし残業の式の追加残業は時間外の率を掛けてから丸める(tmp_path):
    # 会社の決まり（作り物の値）: 所定 160:00・みなし 32:00・時給 1,500・定額残業 60,000・時間外の率は空（法の 1.25）・総労働 218:36
    # 追加 26.6 時間×1,500×1.25＝49,875（率を掛けずに 39,900 にしない）
    会社 = {**_みなしの会社, "委託.所定時間": "160:00", "委託.みなし残業時間": "32:00", "割増.時間外の率": ""}
    r = _回す(tmp_path, 決まり(**会社), _みなしの人(**{"委託.時給": "1500", "委託.定額残業": "60000"}),
             上書き={"総労働": "13116", "深夜": "0"})
    assert _値(r)["委託分の残業"] == 109875 and r["人"][0]["状態"] == "確認済"
    # 率を掛けた後に 委託.丸め（追加 0:01×1,500×1.25＝31.25 → 切捨て 31・切上げ 32）
    for 丸め, 額 in (("切捨て", 31), ("切上げ", 32)):
        r = _回す(tmp_path / 丸め, 決まり(**{**会社, "委託.丸め": 丸め}),
                 _みなしの人(**{"委託.時給": "1500", "委託.定額残業": "60000"}), 上書き={"総労働": "11521", "深夜": "0"})
        assert _値(r)["委託分の残業"] == 60000 + 額, 丸め


def test_みなし残業の式の追加に入った法定休日の時間は時間外の率を重ねない(tmp_path):
    # 総労働 160 時間（内 法定休日 8 時間）−所定 145−みなし 5＝追加 10 時間。法定休日でない時間は 152−150＝2 時間だけ時間外
    # 残業＝12,500＋(2×1.25＋8×1)×2,000＝33,500・休日＝8×2,000×0.35＝5,600（法定休日 8 時間に掛かる率は合わせて 1.35＝休日の率 1 回だけ）
    r = _回す(tmp_path, 決まり(**{**_みなしの会社, "委託.所定時間": "145:00"}), _みなしの人(), 上書き={"法定休日": "480", "深夜": "0"})
    v = _値(r)
    assert v["委託分の残業"] == 33500 and v["委託分の休日"] == 5600
    # 法定休日が追加より多い時は、追加の全部が時給×1（時間外の率 0 時間）
    r = _回す(tmp_path / "b", 決まり(**{**_みなしの会社, "委託.所定時間": "150:00"}), _みなしの人(), 上書き={"法定休日": "600", "深夜": "0"})
    assert _値(r)["委託分の残業"] == 12500 + 5 * 2000 and _値(r)["委託分の休日"] == 7000


def test_みなし残業の式の所定やみなしが無い読めない時は仮と問い(tmp_path):
    for i, (上書き, 字) in enumerate(((({"委託.所定時間": ""}), "委託.所定時間 が無い"),
                                    ({"委託.所定時間": "8:00"}, "60:00 未満"),
                                    ({"委託.所定時間": "40:00"}, "60:00 未満"),
                                    ({"委託.所定時間": "abc"}, "読めない"),
                                    ({"委託.みなし残業時間": ""}, "委託.みなし残業時間 が無い"))):
        r = _回す(tmp_path / str(i), 決まり(**{**_みなしの会社, **上書き}), _みなしの人())
        assert r["人"][0]["状態"] == "仮", 上書き
        assert any(字 in q["何が無いか"] for q in r["問い"]), 上書き
    # 所定が 1 日の時間に見える時は 1 か月の時間として見当（8 時間＝追加 147 時間×2,000×1.25）
    r = _回す(tmp_path / "x", 決まり(**{**_みなしの会社, "委託.所定時間": "8:00"}), _みなしの人())
    assert _値(r)["委託分の残業"] == 12500 + 147 * 2500
    # 境の 60:00 ちょうどは月の時間として読む（仮にしない）
    r = _回す(tmp_path / "y", 決まり(**{**_みなしの会社, "委託.所定時間": "60:00"}), _みなしの人(), 上書き={"深夜": "0"})
    assert r["人"][0]["状態"] == "確認済" and _値(r)["委託分の残業"] == 12500 + 95 * 2500


