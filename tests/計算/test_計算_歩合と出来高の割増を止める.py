"""賃金の形が 歩合・出来高・年俸 の人と、割増の基礎に入る出来高・歩合の形の行（数量が 入力の値・回の数）に額のある人は、
割増の単価の式がパックに無い＝割増の付く時間がある月は割増の項目を仮にして出口へ出さない（月給の式で黙って出さない）。

月給・日給月給・日給・時給の人の縦は変わらない（計算_見張り_期待.json の 形_* は直す前の芯〔main 6c8b62d〕で出した縦）。
"""
import json
from pathlib import Path

import pytest

from 作る_計算 import 人, 回す, 決まり
from 芯.計算 import 支給控除

期待 = json.loads((Path(__file__).parent / "計算_見張り_期待.json").read_text(encoding="utf-8"))
割増 = ("法定内残業手当", "時間外手当", "60時間超手当", "休日手当", "深夜手当")
止めた語 = "割増の式がパックに無い"


def _縦(結果):
    return [[r["項目"], r["値"], r["状態"]] for r in 結果["行"]]


def _行(結果):
    return {r["項目"]: r for r in 結果["行"]}


def _問いに在る(結果, 語):
    return any(語 in json.dumps(q, ensure_ascii=False) for q in 結果["問い"])


def _割増は仮(結果, 語):
    行 = _行(結果)
    for n in 割増:
        assert 行[n]["状態"] == "仮", n
    assert 結果["人"][0]["状態"] == "仮"
    assert _問いに在る(結果, 語)


歩合の行 = [{"名": "歩合給", "支給か控除": "支給", "単価の元": "人の額"},
           {"名": "通勤手当", "支給か控除": "支給", "単価の元": "人の額", "課税": "通勤の非課税", "割増の基礎": "入らない",
            "割増の基礎から除く訳": "通勤手当", "欠勤で減る": "減らない"}]
歩合の額 = {"項目.人の額": {"歩合給": "300000", "通勤手当": "12000"}}
割増の時間が無い = {"法定内残業": "0", "法定外残業": "0", "60 時間超": "0", "深夜": "0", "法定休日": "0", "所定休日": "0"}


def _歩合(tmp, 形="歩合", 上書き=None):
    return 回す(tmp, 決=決まり(**{"支払.賃金の形": 形, "項目.行": 歩合の行}), 人の値=人(**歩合の額), 上書き=上書き)


@pytest.mark.parametrize("形", ["歩合", "出来高"])
def test_歩合と出来高で割増の付く時間がある人は仮(tmp_path, 形):
    _割増は仮(_歩合(tmp_path, 形), "歩合・出来高の人の" + 止めた語)


@pytest.mark.parametrize("形", ["歩合", "出来高"])
def test_歩合と出来高で割増の付く時間が無い月は止めない(tmp_path, 形):
    r = _歩合(tmp_path, 形, 割増の時間が無い)
    行 = _行(r)
    for n in 割増:
        assert 行[n]["状態"] != "仮" and 行[n]["値"] == 0, n
    assert not _問いに在る(r, 止めた語)


def test_深夜だけでも歩合は仮(tmp_path):
    _割増は仮(_歩合(tmp_path, 上書き={**割増の時間が無い, "深夜": "60"}), "歩合・出来高の人の" + 止めた語)


def test_年俸で割増の付く時間がある人は仮(tmp_path):
    _割増は仮(回す(tmp_path, 決=決まり(**{"支払.賃金の形": "年俸"})), "年俸の人の" + 止めた語)


件数の行 = {"名": "件数手当", "支給か控除": "支給", "単価の元": "回ごとの額", "額": "500", "数量の元": "入力の値"}


def _件数(tmp, 行, 件数):
    決 = 決まり()
    決["項目.行"] = 決["項目.行"] + [行]
    return 回す(tmp, 決=決, 入力={("C1", "0001"): {"件数手当": 件数}})


def test_月給でも割増の基礎に入る出来高の形の行に額がある人は仮(tmp_path):
    r = _件数(tmp_path, 件数の行, "40")
    assert _行(r)["件数手当"]["値"] == 20000
    _割増は仮(r, "出来高・歩合の形の行（件数手当）を割増の単価に入れる式がパックに無い")


def test_出来高の形の行でも割増の基礎から除ける訳があれば止めない(tmp_path):
    r = _件数(tmp_path, {**件数の行, "割増の基礎": "入らない", "割増の基礎から除く訳": "臨時の賃金"}, "40")
    assert not _問いに在る(r, 止めた語)
    assert all(_行(r)[n]["状態"] != "仮" for n in 割増)


def test_出来高の形の行でもこの月の額が0なら止めない(tmp_path):
    r = _件数(tmp_path, 件数の行, "0")
    assert not _問いに在る(r, 止めた語)
    assert all(_行(r)[n]["状態"] != "仮" for n in 割増)


# ---- 回帰の見張り: 月給・日給月給・日給・時給の人の縦は変わらない ----
時給の行 = [{"名": "時給", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:所定内"}]
日給の行 = [{"名": "日給", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:出勤日数"}]
形たち = {
    "月給": ({}, {}),
    "日給月給": ({"支払.賃金の形": "日給月給"}, {}),
    "日給": ({"支払.賃金の形": "日給", "項目.行": 日給の行}, {"項目.人の額": {"日給": "12000"}}),
    "時給": ({"支払.賃金の形": "時給", "項目.行": 時給の行}, {"項目.人の額": {"時給": "1500"}}),
}


@pytest.mark.parametrize("形", list(形たち))
def test_ほかの賃金の形の人の縦は変わらない(tmp_path, 形):
    決, 額 = 形たち[形]
    r = 回す(tmp_path, 決=決まり(**決), 人の値=人(**額))
    assert _縦(r) == 期待[f"形_{形}"]
    assert not _問いに在る(r, 止めた語)


# ---- 注入: 止める所を外すと赤 ----
def test_止める所を外すと歩合が月給の式で黙って出る(tmp_path, monkeypatch):
    monkeypatch.setattr(支給控除.一人, "_式の無い割増を止める", lambda self, 時間たち: None)
    r = _歩合(tmp_path)
    with pytest.raises(AssertionError):
        _割増は仮(r, "歩合・出来高の人の" + 止めた語)
    assert _行(r)["時間外手当"]["状態"] != "仮"   # 外すと月給の式の額が確定で出る＝この止める所が要る


def test_式の無い形の表を空にすると年俸が黙って出る(tmp_path, monkeypatch):
    monkeypatch.setattr(支給控除, "式の無い賃金の形", {})
    r = 回す(tmp_path, 決=決まり(**{"支払.賃金の形": "年俸"}))
    assert _行(r)["時間外手当"]["状態"] != "仮"
