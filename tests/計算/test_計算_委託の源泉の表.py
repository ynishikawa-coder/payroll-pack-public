"""② 見張り: repo の 法の表/源泉_報酬.json（試験の作り物の表でなく）で、委託の人の源泉が仮にならないこと。

芯/計算/委託.py（#27）がまだ main に無い間は飛ばす（入ったら回る）。
"""
import pytest

pytest.importorskip("芯.計算.委託")

from 作る_計算 import 人, 決まり, 置き場, 月の数字  # noqa: E402
from 芯.計算 import 計算する  # noqa: E402


def test_委託の人の源泉はrepoの表で仮にならない(tmp_path):
    鍵 = ("C1", "0001")
    r = 計算する(月の数字(上書き={"欠勤": "0", "法定内残業": "0", "法定外残業": "0", "深夜": "0"}),
                決まり={鍵: 決まり(**{"委託.式": "月額", "委託.丸め": "切捨て"})},
                人={鍵: 人(**{"人.区分": "委託", "委託.月給": "300000", "委託.時給": "2000"})},
                置き場=置き場(tmp_path), 支給月="2027-02")
    行 = {x["項目"]: x for x in r["行"]}
    assert 行["委託分の課税計"]["値"] == 300000
    assert (行["委託分の源泉所得税"]["値"], 行["委託分の源泉所得税"]["状態"]) == (30630, "確定")   # 300,000×10.21%
    assert "源泉_報酬" in 行["委託分の源泉所得税"]["出所"]
    assert r["人"][0]["状態"] == "確認済"
