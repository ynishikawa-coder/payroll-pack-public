"""空の会社の決まりを黙って既定で埋めない（作り物の値だけ）。

前: 芯/設定の表.json の 28 の名が `埋める: true` で、日割.割る数 などが空なら黙って既定（暦日など）で埋めて確定にした。
後: パックは既定を持たない。空の名は 見当 で仮に計算し、その人の全部の値を仮＋その名の問いにして、出口の関所で外す。
- 計算の名（日割.割る数）: 空なら仮・問いが 1 つ・関所で外れる。見当の字を置いた人と同じ額（見当が効く）
- 集計の名（割増.残業の数え方）: 空なら全部の行が仮・外れの名に載る・問いが立つ
- 誤りを戻すと赤: 空を黙って見当で埋める道へ戻すと、空の人が確認済になる（この試験の見る所が効いている）
"""
import sys
from pathlib import Path

import pytest

for p in (Path(__file__).resolve().parent, Path(__file__).resolve().parents[1] / "集計"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

from 作る_計算 import 回す, 決まり, 人  # noqa: E402
from 作る_集計 import 月, 数える, 既定の決まり  # noqa: E402
from 芯 import 設定  # noqa: E402
from 出口 import 関所  # noqa: E402

pytestmark = pytest.mark.既定の答え無し

# 作り物の事務所が「既定」のタブに書いた答え（見当のとおり）＝空なのはその名だけ、にする
_答え = {n: e["見当"] for n, e in 設定.表().items()
       if e.get("見当") is not None and n not in 設定.要る人だけの見当}


def _答えた決まり(抜く=None, **足す):
    決 = {**{n: v for n, v in _答え.items() if "計算" in (設定.表()[n].get("読む所") or ["計算"])}, **決まり(), **足す}
    if 抜く:
        決.pop(抜く, None)
    return 決


def test_日割の割る数が空なら仮で問いが立ち出口へ出ない(tmp_path):
    r = 回す(tmp_path, 決=_答えた決まり(抜く="日割.割る数"), 人の値=人())
    置いた = 回す(tmp_path / "置いた", 決=_答えた決まり(**{"日割.割る数": _答え["日割.割る数"]}), 人の値=人())
    assert 置いた["人"][0]["状態"] == "確認済"
    assert r["人"][0]["状態"] == "仮" and all(x["状態"] == "仮" for x in r["行"])
    q = [q for q in r["問い"] if "日割.割る数" in q["何が無いか"]]
    assert len(q) == 1 and q[0]["人"] == [("C1", "0001")]
    assert {x["項目"]: x["値"] for x in r["行"]} == {x["項目"]: x["値"] for x in 置いた["行"]}   # 見当で数えた額
    通 = 関所.通す(r["行"], r["人の状態"])
    assert 通.行たち == () and 通.外した人の鍵() == {("2027-02", "C1", "0001")}   # 仮が残る人は出口へ出ない


def test_集計の決まりが空なら全部の行が仮で外れの名に載る():
    A, B = 月()
    集計の答え = {n: v for n, v in _答え.items() if "集計" in (設定.表()[n].get("読む所") or [])}
    答えた = 数える(A, B, 既定の決まり(**集計の答え))
    空 = 数える(A, B, 既定の決まり(**{k: v for k, v in 集計の答え.items() if k != "割増.残業の数え方"}))
    assert "割増.残業の数え方" not in 答えた["人"][0].get("設定の外れ", [])
    assert 空["人"][0]["状態"] == "仮" and all(x["状態"] == "仮" for x in 空["行"])
    assert "割増.残業の数え方" in 空["人"][0]["設定の外れ"]
    assert any("割増.残業の数え方" in q["何が無いか"] for q in 空["問い"])


def test_黙って埋める道へ戻すと空の人が確認済になる(tmp_path, monkeypatch):
    元 = 設定.空を見当で埋める
    monkeypatch.setattr(設定, "空を見当で埋める", lambda 値たち, 読む所: (元(値たち, 読む所)[0], []))
    r = 回す(tmp_path, 決=_答えた決まり(抜く="日割.割る数"), 人の値=人())
    assert r["人"][0]["状態"] == "確認済"   # 上の試験が拒む形（黙って暦日で確定）


def test_行の端数で端数の行の額が空なら仮で切上げの見当(tmp_path):
    """部品の行の丸め `行の端数` で 端数.行の額 が空: 黙って切上げで確定しない（見当で数えてその行を仮）。"""
    行 = 決まり()["項目.行"] + [{"名": "日当", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:出勤日数",
                              "丸め": "行の端数", "割増の基礎": "入らない", "割増の基礎から除く訳": "家族手当"}]
    u = {**人(), "項目.人の額": {**人()["項目.人の額"], "日当": "333.3"}}
    r = 回す(tmp_path, 決=_答えた決まり(**{"項目.行": 行}), 人の値=u)
    日当 = next(x for x in r["行"] if x["項目"] == "日当")
    assert 日当["状態"] == "仮" and 日当["値"] == 6333 and r["人"][0]["状態"] == "仮"   # 333.3×19 → 見当の切上げ
    assert any("端数.行の額" in q["何が無いか"] for q in r["問い"])
    置いた = 回す(tmp_path / "置いた", 決=_答えた決まり(**{"項目.行": 行, "端数.行の額": "切捨て"}), 人の値=u)
    assert next(x for x in 置いた["行"] if x["項目"] == "日当")["状態"] != "仮"


# ---- レビュー 1 回目の赤: 空を見逃して見当が黙って確定になる道 ----

@pytest.mark.parametrize("名, 読む所", [("日割.割る数", "計算"), ("割増.深夜を賃金に含む", "計算"), ("休日.法定休日の曜日", "集計")])
def test_ほかの勤務の型にだけ値が在っても上の段が空なら見当で仮(名, 読む所):
    """型 A にだけ値が在る会社の、型 B の人・型の無い人（上の段が空）を空と見る（芯の読み手は上の段を読む）。"""
    値 = 設定.表()[名]["見当"]
    v = {"勤務の型": {"A": {名: 値}, "B": {}}}
    埋めた値, 埋めた = 設定.空を見当で埋める(v, 読む所)
    assert 名 in 埋めた and 埋めた値["勤務の型"]["A"][名] == 値
    assert 名 not in 設定.空を見当で埋める({**v, 名: 値}, 読む所)[1]   # 上の段に値が在る人（その人の型を重ねた）は空でない


def test_委託の併用で社保と源泉の元に入れるが空なら入れないの見当で仮():
    from 芯.計算 import 要る値
    v, 仮 = 要る値.確かめる({"人.区分": "委託の併用"})
    assert v["委託.社保と源泉の元に入れる"] == "入れない"
    assert any("委託.社保と源泉の元に入れる" in str(r) for _, r in 仮), 仮
    _, 社員だけ = 要る値.確かめる({"人.区分": "社員"})
    assert not any("委託.社保と源泉の元に入れる" in str(r) for _, r in 社員だけ)
