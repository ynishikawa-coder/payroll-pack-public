"""作り物の回帰の見張り: `休日.休日出勤の数え方` の 所定休日の率＝時間外の率で払う（所定休日の時間を全部 時間外の率＝法の線の上）。

所定休日の時間のうち法定外に入っていない分（所定休日−所定休日の法定外）だけを法定内残業から時間外の率へ移す（二重に払わない）。
期待値は試験の中で手で出す（月給 300000・月の所定時間は年平均の暦から＝単価は 週の法定で判定 の結果から逆に読まず、差で見る）。"""
from decimal import Decimal

import pytest

from 作る_計算 import 回す, 決まり, 値たち

時間外で = {"出勤日数に入れる": "入れない", "所定休日の率": "時間外の率で払う"}
# 所定休日に 8 時間（480 分）。うち 120 分は週 40 を超えて法定外（法定外 600 の内）・360 分は週の内（法定内残業 360 の内）
休出 = {"欠勤": "0", "総労働": "9960", "法定内残業": "360", "法定外残業": "600", "所定休日": "480", "所定休日の法定外": "120"}


def test_週の内の所定休日の時間を時間外の率へ移す(tmp_path):
    法 = 値たち(回す(tmp_path / "a", 上書き=休出))
    会社 = 値たち(回す(tmp_path / "b", 決=決まり(**{"休日.休日出勤の数え方": 時間外で}), 上書き=休出))
    # 法定内 360 分は全部 所定休日の分＝法定内残業手当は 0 に、その 6 時間は時間外の率（法定内残業の率 1.00 の 1.25 倍）で時間外手当へ
    assert 会社["法定内残業手当"] == 0 < 法["法定内残業手当"]
    assert abs(会社["時間外手当"] - 法["時間外手当"] - 法["法定内残業手当"] * Decimal("1.25")) <= 1   # 端数の丸めの 1 円まで
    assert 会社["総支給額"] > 法["総支給額"]


def test_法定外に入った所定休日の分は二重に払わない(tmp_path):
    全部法定外 = {**休出, "法定内残業": "0", "法定外残業": "960", "所定休日の法定外": "480", "総労働": "9840"}
    法 = 値たち(回す(tmp_path / "a", 上書き=全部法定外))
    会社 = 値たち(回す(tmp_path / "b", 決=決まり(**{"休日.休日出勤の数え方": 時間外で}), 上書き=全部法定外))
    assert 会社["時間外手当"] == 法["時間外手当"] and 会社["総支給額"] == 法["総支給額"]


def test_所定休日の法定外が月の数字に無ければ全部を移して仮(tmp_path):
    無い = {k: v for k, v in 休出.items() if k != "所定休日の法定外"}
    r = 回す(tmp_path, 決=決まり(**{"休日.休日出勤の数え方": 時間外で}), 上書き=無い)
    v = {x["項目"]: x for x in r["行"]}
    assert v["時間外手当"]["状態"] == "仮" and r["人"][0]["状態"] == "仮"


def test_所定休日に働かない月は今と同じ(tmp_path):
    法 = 値たち(回す(tmp_path / "a", 上書き={"欠勤": "0"}))
    会社 = 値たち(回す(tmp_path / "b", 決=決まり(**{"休日.休日出勤の数え方": 時間外で}), 上書き={"欠勤": "0"}))
    assert 会社 == 法


def test_休日の率で払うは式がまだ無いまま(tmp_path):
    r = 回す(tmp_path, 決=決まり(**{"休日.休日出勤の数え方": {"所定休日の率": "休日の率で払う"}}), 上書き=休出)
    assert r["人"][0]["状態"] == "仮"


@pytest.mark.parametrize("足す", [
    {"割増.みなし残業の時間": "16"},
    {"割増.固定残業": {"形": "時間で", "時間": "16"}, "割増.固定残業の対象": "時間外"},
    {"割増.固定残業": {"形": "時間で", "時間": "14"}, "割増.固定残業の対象": "法定内残業と時間外"},
    {"割増.固定残業": {"形": "額で", "額": "40000"}, "割増.固定残業の対象": "時間外"},
    {"割増.時間外の率": "0", "法の線.承知": {"割増.時間外の率": "問1"}},
])
def test_みなしや固定残業の人も選ばない時より下げない(tmp_path, 足す):
    法 = 値たち(回す(tmp_path / "a", 決=決まり(**足す), 上書き=休出))
    会社 = 値たち(回す(tmp_path / "b", 決=決まり(**{"休日.休日出勤の数え方": 時間外で, **足す}), 上書き=休出))
    assert 会社["総支給額"] >= 法["総支給額"]


def test_みなし残業はみなしの時間を当てた後に移した分を払う(tmp_path):
    みなし = {"割増.みなし残業の時間": "16"}
    法 = 値たち(回す(tmp_path / "a", 決=決まり(**みなし), 上書き=休出))
    会社 = 値たち(回す(tmp_path / "b", 決=決まり(**{"休日.休日出勤の数え方": 時間外で, **みなし}), 上書き=休出))
    # みなし 16 時間が法定外 10 時間を覆い、移した 6 時間は覆わない＝法定内残業手当の 1.25 倍が時間外手当に出る
    assert 会社["法定内残業手当"] == 0
    assert abs(会社["時間外手当"] - 法["法定内残業手当"] * Decimal("1.25")) <= 1


@pytest.mark.parametrize("足す", [{}, {"割増.みなし残業の時間": "16"}, {"割増.時間外の率": "0", "法の線.承知": {"割増.時間外の率": "問1"}}])
def test_会社の数え方の人は所定休日を休日の率のまま払う(tmp_path, 足す):
    会社の語 = {**休出, "残業（会社の数え方）": "600", "60 時間超（会社の数え方）": "0"}
    法 = 値たち(回す(tmp_path / "a", 決=決まり(**足す), 上書き=会社の語))
    会社 = 値たち(回す(tmp_path / "b", 決=決まり(**{"休日.休日出勤の数え方": 時間外で, **足す}), 上書き=会社の語))
    assert 会社 == 法 and 会社["休日手当"] > 0
