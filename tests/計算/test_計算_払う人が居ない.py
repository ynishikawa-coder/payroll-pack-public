"""支給控除の項目の 数量の元＝払う人が居ない（会社はその行を持つが今は払う人が居ない）の線（作り物の値だけ）。

芯はその行を使わない（要る値.確かめる が 項目.行 から除く）。人の額が在る人は黙って捨てず、行を除いて計算して仮＋問い。
"""
from 作る_計算 import 回す, 値たち, 決まり


def _行を足して(行, 人の額=None):
    d = 決まり()
    d["項目.行"] = [dict(x) for x in d["項目.行"]] + [行]
    if 人の額 is not None:
        d["項目.人の額"] = {**d["項目.人の額"], **人の額}
    return d


def _職務手当を(数量の元):
    d = 決まり()
    d["項目.行"] = [{**x, "数量の元": 数量の元} if x["名"] == "職務手当" else dict(x) for x in d["項目.行"]]
    return d


def test_払う人が居ない行は使わず仮にしない(tmp_path):
    元 = 回す(tmp_path / "元")
    r = 回す(tmp_path / "後", 決=_行を足して({"名": "作り物の日額手当", "支給か控除": "支給", "単価の元": "人の額",
                                             "数量の元": "払う人が居ない"}))
    assert r["人"][0]["状態"] == "確認済" and r["問い"] == []
    v = 値たち(r)
    assert "作り物の日額手当" not in v and v["総支給額"] == 値たち(元)["総支給額"]


def test_人の額が在る人は行を除いて計算し仮と問い(tmp_path):
    元 = 値たち(回す(tmp_path / "元"))
    r = 回す(tmp_path / "後", 決=_職務手当を("払う人が居ない"))   # 作り物の人は 職務手当 の人の額 20000 を持つ
    assert r["人"][0]["状態"] == "仮"
    assert [q for q in r["問い"] if q["何が無いか"].startswith("支給控除の項目「職務手当」は 数量の元＝払う人が居ない")]
    v = 値たち(r)
    assert "職務手当" not in v
    assert v["総支給額"] <= 元["総支給額"] - 20000   # 職務手当は残業の単価の元にも入るので、残業の手当も減る


def test_払う人が居ないは数量の元の選べる値_型の意味にも在る():
    import json
    from pathlib import Path
    型 = json.loads((Path(__file__).resolve().parents[2] / "初期設定" / "型.json").read_text(encoding="utf-8"))
    意味 = [c["意味"] for s in 型["シート"] for t in s["タブ"] if t["タブ"] == "支給控除の項目" for c in t["列"] if c["名"] == "数量の元"]
    assert 意味 and "払う人が居ない" in 意味[0]


def test_給与を払わない人が芯に来たら計算して仮と問い(tmp_path):
    """月次は 支払.給与を払わない＝はい の人を芯へ渡さない。来たら（勤怠・月の変動・社保の加入が食い違う）黙って出さず仮で問う。"""
    from 作る_計算 import 人
    r = 回す(tmp_path, 人の値=人(**{"支払.給与を払わない": "はい"}))
    assert r["人"][0]["状態"] == "仮"
    assert [q for q in r["問い"] if q["何が無いか"].startswith("支払.給与を払わない＝はい の人に")]
    assert 回す(tmp_path / "いいえ", 人の値=人(**{"支払.給与を払わない": "いいえ"}))["人"][0]["状態"] == "確認済"
