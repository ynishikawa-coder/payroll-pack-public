"""手当.皆勤の条件＝出勤日数が会社の暦の所定日数に届く（作り物の会社『ひなた紙工』の値だけ）。

出勤日数が所定日数に届く はその人の勤務の型の暦の所定日数と比べる＝出勤の土曜が休みの型の人は自分の暦で届いて毎月払う。
会社の答え「ほかの方と出勤日数が違えば付けず先方に確認」は、会社の段の暦の所定日数と比べる値で書く（届かない月は払わず知らせ）。
期間 2027-01: 会社の暦（日曜と祝日が休み・会社の休み 01-02・01-04）＝31−日曜 5−祝日 2−2＝22 日。人 X の型の暦の所定日数＝19 日。
"""
from 作る_計算 import 人, 値たち, 回す, 決まり

from 芯.計算.支給控除 import 皆勤の会社の暦, 皆勤の所定日数

会社の暦 = {"休みの曜日": ["日"], "祝日": "休み", "会社の休み": ["2027-01-02", "2027-01-04"]}
皆勤の行 = {"名": "皆勤手当", "支給か控除": "支給", "単価の元": "固定の額", "額": "7000", "条件": "皆勤", "欠勤で減る": "減らない"}


def ひなた紙工(tmp, 条件, 出勤日数, 会社の暦=会社の暦):
    決 = 決まり(**{"手当.皆勤の条件": 条件})
    決["項目.行"] = [*決["項目.行"], 皆勤の行]
    if 会社の暦 is not None:
        決["時間.会社の暦"] = 会社の暦   # 段の解決が会社の段の 時間.暦 を写す鍵（人の 時間.暦 は型の暦＝土日休み）
    勤怠 = {"所定日数": "19", "出勤日数": str(出勤日数), "欠勤": "0", "遅刻早退": "0"}
    return 回す(tmp, 決=決, 上書き=勤怠)


def test_型の暦で届く人も会社の暦に届かなければ払わず知らせる(tmp_path):
    前 = ひなた紙工(tmp_path / "a", 皆勤の所定日数, 19)
    assert 値たち(前)["皆勤手当"] == 7000                      # 今の値: 自分の型の暦（19 日）で届く＝払う
    r = ひなた紙工(tmp_path / "b", 皆勤の会社の暦, 19)
    assert 値たち(r).get("皆勤手当", 0) == 0                   # 新しい値: 会社の暦 22 日に届かない＝払わない
    assert [t for t in r["知らせ"] if "皆勤手当" in t and "会社の暦の所定日数 22 日" in t and "先方に確かめる" in t], r["知らせ"]
    assert r["人"][0]["状態"] == "確認済", r["問い"]


def test_会社の暦に届けば払う(tmp_path):
    r = ひなた紙工(tmp_path, 皆勤の会社の暦, 22)
    assert 値たち(r)["皆勤手当"] == 7000
    assert not [t for t in r["知らせ"] if "皆勤手当" in t and "届かない" in t]


def test_会社の暦が無ければその人の所定日数で比べて仮(tmp_path):
    r = ひなた紙工(tmp_path, 皆勤の会社の暦, 19, 会社の暦=None)
    assert 値たち(r)["皆勤手当"] == 7000
    assert r["人"][0]["状態"] == "仮"
    assert any("会社の段の 時間.暦 が無い" in q["何が無いか"] for q in r["問い"])
