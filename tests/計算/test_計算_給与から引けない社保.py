"""休職などで給与が無い・足りない月の社保の本人負担（社保.引けない月の本人負担・作り物の 1 人）。

- 空: 引けない額がある人は見当（毎月請求）で計算して仮＝出口へ出さない（黙って 0 にしない）。
- 毎月請求: 社保の行は本人負担の全額のまま、引けない額を 社保の引けない額 で差引支給額へ戻す（差引を負にしない）。
- 立て替えて復帰後に引く: 社保の立て替えの残り＝前の残り（入力）＋引けない額。給与のある月に 社保の立て替えの返し で引く。
"""
from decimal import Decimal

from 作る_計算 import 人, 回す, 決まり, 値たち

社保 = ("健康保険", "介護保険", "子ども・子育て支援金", "厚生年金")
鍵 = ("C1", "0001")
休職 = {"項目.人の額": {"基本給": "280000", "職務手当": "20000", "通勤手当": "0"}}
休職の勤怠 = {"出勤日数": "0", "欠勤": "20", "総労働": "0", "所定内": "0", "法定内残業": "0", "法定外残業": "0", "深夜": "0",
          "遅刻早退": "0"}


def _回す(tmp, 式=None, 人の値=休職, 入力=None):
    決 = 決まり(**({"社保.引けない月の本人負担": 式} if 式 else {}), **{"項目.行": [r for r in 決まり()["項目.行"] if r["名"] != "親睦会費"]})
    r = 回す(tmp, 決=決, 人の値=人(**人の値), 入力={鍵: 入力} if 入力 else None, 上書き=休職の勤怠 if 人の値 is 休職 else None)
    return r, 値たち(r)


def test_給与が無い月で式が空なら仮で出さない(tmp_path):
    r, v = _回す(tmp_path)
    計 = sum(v[n] for n in 社保)
    assert 計 > 0 and v["総支給額"] == 0
    assert v["社保の引けない額"] == 計 and v["差引支給額"] == 0
    assert r["人"][0]["状態"] == "仮"
    assert any("社保.引けない月の本人負担" in q["何が無いか"] for q in r["問い"])


def test_毎月請求は引けない額を返し差引を負にしない(tmp_path):
    r, v = _回す(tmp_path, "毎月請求")
    計 = sum(v[n] for n in 社保)
    assert v["社保の引けない額"] == 計 and v["差引支給額"] == 0
    assert "社保の立て替えの残り" not in v
    assert r["人"][0]["状態"] != "仮"


def test_立て替えは前の残りに足して返す(tmp_path):
    r, v = _回す(tmp_path, "立て替えて復帰後に引く", 入力={"社保の立て替えの残り": "1000"})
    計 = sum(v[n] for n in 社保)
    assert v["社保の立て替えの残り"] == 計 + 1000 and v["差引支給額"] == 0
    assert r["人"][0]["状態"] != "仮"


def test_立て替えの残りは復帰後の給与から引く(tmp_path):
    _, 元 = _回す(tmp_path / "元", "立て替えて復帰後に引く", 人の値={})
    r, v = _回す(tmp_path / "a", "立て替えて復帰後に引く", 人の値={}, 入力={"社保の立て替えの残り": "50000"})
    assert v["社保の立て替えの返し"] == 50000 and v["社保の立て替えの残り"] == 0
    assert v["差引支給額"] == 元["差引支給額"] - 50000
    assert "社保の引けない額" not in v and r["人"][0]["状態"] != "仮"


def test_給与の足りる月は式を読まない(tmp_path):
    """引けない額が無い人は式が空でも仮にしない（式は要る時だけ）。"""
    r, v = _回す(tmp_path, 人の値={})
    assert "社保の引けない額" not in v and r["人"][0]["状態"] != "仮"


def test_選べる値の外の字は仮(tmp_path):
    """注入: 選べる値の外の字は黙って どちらか にしない。"""
    r, v = _回す(tmp_path, "後で考える")
    assert r["人"][0]["状態"] == "仮"


def test_部品の行が芯の3行の名とぶつかれば仮(tmp_path):
    """注入: 支給控除の項目に 社保の引けない額・社保の立て替えの返し・社保の立て替えの残り の名の行（芯が作る名とぶつかる）。"""
    for 名 in ("社保の引けない額", "社保の立て替えの返し", "社保の立て替えの残り"):
        決 = 決まり(**{"項目.行": [*決まり()["項目.行"], {"名": 名, "支給か控除": "控除", "単価の元": "固定の額", "額": "100"}]})
        r = 回す(tmp_path / 名, 決=決)
        assert r["人"][0]["状態"] == "仮", 名
        assert any("芯が自分で作る項目の名とぶつかる" in q["何が無いか"] and 名 in q["何が無いか"] for q in r["問い"]), 名
