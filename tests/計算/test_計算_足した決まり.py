def _表の値(d: Path, 名: str, 日: str, **鍵):
    """法の表を試験の手で引く（芯の引く口を使わない 2 つ目の道）。"""
    j = json.loads((d / f"{名}.json").read_text(encoding="utf-8"))
    for r in j["行"]:
        if any(r["鍵"].get(k) != v for k, v in 鍵.items()):
            continue
        s, e = r["効く始め"], r["効く終わり"]
        if (s is None or s <= 日[:len(s)]) and (e is None or 日[:len(e)] <= e):
            return r["値"]
    raise LookupError(名)


def _50銭以下切捨て(x: Decimal) -> int:
    f = x.to_integral_value(rounding=ROUND_FLOOR)
    return int(f + 1) if x - f > Decimal("0.5") else int(f)


