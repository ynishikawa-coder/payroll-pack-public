def _社保の率(d, 保険料の月="2027-01"):
    健 = Decimal(str(_表の値(d, "健保_協会けんぽ", 保険料の月, 都道府県="東京都")["率%"])) / 2
    介 = Decimal(str(_表の値(d, "介護_協会けんぽ", 保険料の月)["率%"])) / 2
    支 = Decimal(str(_表の値(d, "子ども子育て支援金", 保険料の月)["率%"])) / 2
    return 健, 介, 支


def test_社保の丸めの順と支援金を健保に含める(tmp_path):
    d = 置き場(tmp_path / "表")
    健, 介, 支 = _社保の率(d)
    標 = Decimal(320000)                               # 1980-05-10 生まれ＝保険料の月 2027-01 は介護に掛かる
    R = (lambda x: _50銭以下切捨て(標 * x / 100))
    for 順, 期待 in (
        ("介護を先に", {"健康保険": R(健 + 介 + 支) - R(介) - R(支), "介護保険": R(介), "子ども・子育て支援金": R(支)}),
        ("健保＋支援金を先に", {"健康保険": R(健 + 支) - R(支), "介護保険": R(健 + 介 + 支) - R(健 + 支), "子ども・子育て支援金": R(支)}),
        ("支援金を別に", {"健康保険": R(健 + 介) - R(介), "介護保険": R(介), "子ども・子育て支援金": R(支)}),
    ):
        v = 値たち(回す(tmp_path / 順, 決=決まり(**{"社保.丸めの順": 順})))
        assert {k: v[k] for k in 期待} == 期待, 順
    v = 値たち(回す(tmp_path / "含める", 決=決まり(**{"社保.丸めの順": "介護を先に", "社保.支援金を健保に含める": "含める"})))
    assert v["健康保険"] == R(健 + 介 + 支) - R(介) and v["子ども・子育て支援金"] == 0


