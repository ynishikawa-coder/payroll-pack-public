"""最低賃金と比べる賃金（最低賃金法 4 条 3 項・規則 1 条。作り物の会社『あおば製作』の値だけ）。

比べる賃金から除けるのは 法の表/法の線.json の 最低賃金に算入しない賃金（臨時・1 か月超・割増・精皆勤・通勤・家族手当）だけ。
割増の基礎から除いた住宅手当（労基則 21 条で除ける）は最低賃金では除けない＝割増の単価と別に出す。
会社が家族手当を含めて比べると決めた時は `法の線.承知` の 最低賃金 の印に（含める:家族手当）を書く（含めても下回れば赤のまま）。
"""
import json

from 作る_計算 import 月の数字, 置き場

from 芯.計算 import 計算する

県 = "作り物県"


def _置き場(tmp):
    d = 置き場(tmp)
    (d / "最低賃金.json").write_text(json.dumps({
        "表の名": "最低賃金", "基準": "労働した日", "単位": "円", "引く鍵": ["都道府県"], "欠けた時": "仮で計算し問う",
        "行": [{"鍵": {"都道府県": 県}, "効く始め": None, "効く終わり": None, "状態": "出た", "値": {"時間額": 1150},
                "出典": {"URL": "作り物（試験だけ）"}}]}, ensure_ascii=False), encoding="utf-8")
    return d


def _行(名, 訳=None, 条件=None):
    r = {"名": 名, "支給か控除": "支給", "単価の元": "人の額", "欠勤で減る": "減らない"}
    if 訳:
        r.update({"割増の基礎": "入らない", "割増の基礎から除く訳": 訳})
    if 条件:
        r["条件"] = 条件
    return r


def あおば製作(tmp, 行たち, 額, 承知=None):
    決 = {
        "支払.締め日": "末", "支払.支給日": "25", "支払.賃金の形": "月給", "時間.日の所定": "8",
        "時間.暦": {"休みの曜日": ["土", "日"], "祝日": "休み", "会社の休み": []},
        "社保.健保の支部": "東京都", "雇保.事業の種類": "一般", "会社.事業場の都道府県": 県,
        "時間.制度": "通常", "社保.徴収の月": "翌月徴収",
        "時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "160", "端数.時間単価": "しない",
        "項目.行": [_行("基本給"), *行たち],
    }
    if 承知:
        決["法の線.承知"] = 承知
    人 = {"人.生年月日": "1980-05-10", "社保.標準報酬": "200000", "源泉.扶養の数": "0", "人.区分": "社員",
         "社保.加入": "加入", "雇保.加入": "加入", "源泉.欄": "甲", "住民税.額": {"6月分": "0", "7月以降": "0"},
         "項目.人の額": {"基本給": "180000", **額}}
    勤怠 = {"欠勤": "0", "遅刻早退": "0", "出勤日数": "20"}
    return 計算する(月の数字(上書き=勤怠), 決まり={("C1", "0001"): 決}, 人={("C1", "0001"): 人}, 置き場=_置き場(tmp))


def _赤(r):
    return [t for t in r["法の線"] if "最低賃金" in t and ": 赤:" in t]


def test_割増の基礎から除いた住宅手当は最低賃金に含めて比べる(tmp_path):
    """190,000÷160＝1,187.5 ≧ 1,150＝赤にしない（割増の単価は住宅手当を除いた 1,125 のまま）。"""
    r = あおば製作(tmp_path, [_行("住宅手当", 訳="住宅手当")], {"住宅手当": "10000"})
    assert not _赤(r), r["法の線"]
    assert r["人"][0]["状態"] == "確認済", r["問い"]


def test_算入しない訳の手当を除くと下回り赤で仮(tmp_path):
    """逆の試験（前の挙動）: 同じ 10,000 を比べる賃金から除くと 180,000÷160＝1,125 ＜ 1,150＝赤で仮。"""
    for 訳 in ("家族手当", "通勤手当"):
        r = あおば製作(tmp_path / 訳, [_行("作り物の手当", 訳=訳)], {"作り物の手当": "10000"})
        (t,) = _赤(r)
        assert "1125" in t, t
        assert r["人"][0]["状態"] == "仮"


def test_皆勤の手当は払った月も比べる賃金に入れない(tmp_path):
    """精皆勤手当（条件＝皆勤）は最低賃金法 4 条 3 項 3 号で算入しない＝払っても 1,125 で赤。"""
    r = あおば製作(tmp_path, [_行("皆勤手当", 条件="皆勤")], {"皆勤手当": "10000"})
    (t,) = _赤(r)
    assert "1125" in t, t


def test_家族手当を含める印は法の線の単価と差額を残す承知(tmp_path):
    """会社の答え「家族手当は含めて比べる」は法の線の下の比べ方（法 4 条 3 項は会社が含めることを許さない）。
    含めて 1,187.5 で届き、法の線の単価 1,125 で下回る＝赤にせず承知した食い違い（法の線の単価・差額を知らせる・会社の決まり §1.4）。"""
    r = あおば製作(tmp_path, [_行("家族手当", 訳="家族手当")], {"家族手当": "10000"},
                承知={"最低賃金": "問13（含める:家族手当）"})
    assert not _赤(r), r["法の線"]
    assert any(t.startswith("C1 0001: 承知: 時間あたりの賃金 1125") and "家族手当 を含めると 1187.5" in t and "問13" in t
               for t in r["法の線"]), r["法の線"]
    (t,) = [t for t in r["知らせ"] if "承知した食い違い: 最低賃金" in t]
    assert "（問13（含める:家族手当））" in t and "時間あたり 1125 円（法の線 1150 円）" in t and "差額 " in t, t
    assert r["人"][0]["状態"] == "確認済", r["問い"]


def test_含める印でも法の線で届けば承知の知らせを出さない(tmp_path):
    r = あおば製作(tmp_path, [_行("家族手当", 訳="家族手当")], {"家族手当": "10000"},
                承知={"最低賃金": "問13（含める:家族手当）"})
    r2 = あおば製作(tmp_path / "b", [_行("家族手当", 訳="家族手当"), _行("住宅手当", 訳="住宅手当")],
                 {"家族手当": "10000", "住宅手当": "10000"}, 承知={"最低賃金": "問13（含める:家族手当）"})
    assert not [t for t in r2["知らせ"] if "承知した食い違い: 最低賃金" in t]   # 法の線で 1,187.5＝届く
    assert not _赤(r2) and r2["人"][0]["状態"] == "確認済"


def test_含める印は下回ることの承知でない(tmp_path):
    """含めても下回る（家族手当 1,000 → 181,000÷160＝1,131.25）なら赤で仮（承知した食い違いにしない）。"""
    r = あおば製作(tmp_path, [_行("家族手当", 訳="家族手当")], {"家族手当": "1000"},
                承知={"最低賃金": "問13（含める:家族手当）"})
    (t,) = _赤(r)
    assert "1131.25" in t, t
    assert r["人"][0]["状態"] == "仮"
    assert not [t for t in r["知らせ"] if "承知した食い違い" in t]
