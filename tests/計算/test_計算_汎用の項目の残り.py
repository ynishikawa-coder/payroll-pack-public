# ---- 9: 端数.月の所定時間（切り捨てた所定は割増の単価だけ）----
def test_月の所定時間の時間未満を切り捨てるのは割増の単価だけ(tmp_path):
    基 = {"時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "161:20"}
    前 = 値たち(回す(tmp_path / "a", 決=決まり(**基)))
    後 = 値たち(回す(tmp_path / "b", 決=決まり(**基, **{"端数.月の所定時間": "時間未満切り捨て"})))
    # 単価: 300,000÷161⅓＝1,859.50…→1,860 ／ 300,000÷161＝1,863.35…→1,863。時間外 10 時間×1.25
    assert 前["時間外手当"] == 23250 and 後["時間外手当"] == 23288     # 1,860×12.5 ／ 1,863×12.5＝23,287.5→23,288
    assert 前["遅刻早退控除"] == 後["遅刻早退控除"] == 929             # 控除は切り捨てない所定（300,000×0.5÷161⅓＝929.75…）
    assert 前["欠勤控除"] == 後["欠勤控除"]


