"""汎用の項目 11 個の残り（型の版 18・決めたい事の推奨どおり）: 作り物の 1 人で前後の差を見る。期待値は試験の中で手で出す。

月給 基本給 280,000＋職務手当 20,000＝基礎 300,000・欠勤 1 日・遅刻早退 30 分・総労働 9,600 分・法定外 600 分・日の所定 8（作る_計算）。
"""
from 作る_計算 import 人, 回す, 決まり, 値たち

固定170 = {"時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "170", "欠勤.控除の式": "引く方式"}


def _状態(結果, 項目):
    (r,) = [r for r in 結果["行"] if r["項目"] == 項目]
    return r["状態"]


def test_足した項目が空なら結果は変わらない(tmp_path):
    今 = 回す(tmp_path / "a")
    空 = 回す(tmp_path / "b", 決=決まり(**{"欠勤.遅刻早退の数え方": "", "端数.月の所定時間": "", "端数.時間給の丸め": "",
                                     "割増.みなし超えの行": "", "出口.実働の上限": ""}))
    assert 値たち(今) == 値たち(空) and 今["人の状態"] == 空["人の状態"]
    既定 = 回す(tmp_path / "c", 決=決まり(**{"端数.月の所定時間": "しない", "端数.時間給の丸め": "月に 1 回"}))
    assert 値たち(今) == 値たち(既定)


# ---- 2: 欠勤を遅刻早退に入れる人の足し込み（芯/計算 側・少ない方を引く）----
def test_欠勤を遅刻早退に入れる人は欠勤の日を遅刻早退に足す(tmp_path):
    前 = 値たち(回す(tmp_path / "a", 決=決まり(**固定170)))
    後 = 値たち(回す(tmp_path / "b", 決=決まり(**固定170, **{"欠勤.欠勤を遅刻早退に入れる": "入れる"})))
    assert 前["欠勤控除"] > 0 and 前["遅刻早退控除"] == 882          # 前: 欠勤は日数で引く・遅刻 300,000×0.5÷170＝882.35…
    # 後: 遅刻 30＋欠勤 1 日×8 時間＝510 分。所定−総労働＝170×60−9,600＝600 分＞510 分＝510 分で引く
    assert 後["欠勤控除"] == 0 and 後["遅刻早退控除"] == 15000      # 300,000×510÷60÷170


def test_欠勤を遅刻早退に入れる人は所定の不足の方が少なければそれで引く(tmp_path):
    後 = 値たち(回す(tmp_path, 決=決まり(**固定170, **{"欠勤.欠勤を遅刻早退に入れる": "入れる"}), 上書き={"総労働": "9900"}))
    assert 後["遅刻早退控除"] == 8823                               # 所定の不足 10,200−9,900＝300 分＜510 分＝300,000×300÷60÷170＝8,823.5…


# ---- 型の版 24: 月の所定時間−総労働で頭打ち（欠勤の無い月も 1 回で取る）----
月で頭打ち = {"欠勤.遅刻早退の数え方": "日々の不足（月の所定時間−総労働で頭打ち）"}


def test_月の所定時間で頭打ちは欠勤の無い月も所定の不足で引く(tmp_path):
    # 欠勤 0・遅刻 30 分・働いた時間 9,600 分（作る_計算 の既定）。月の所定 160:20＝9,620 分＝不足 20 分＜30 分
    決 = {"時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "160:20"}
    前 = 値たち(回す(tmp_path / "a", 決=決まり(**決), 上書き={"欠勤": "0"}))
    後 = 値たち(回す(tmp_path / "b", 決=決まり(**決, **月で頭打ち), 上書き={"欠勤": "0"}))
    assert 前["遅刻早退控除"] == 935                                 # 前: 日々の不足 30 分のまま＝300,000×30÷60÷160⅓＝935.5…
    assert 後["遅刻早退控除"] == 623                                 # 後: 300,000×20÷60÷160⅓＝623.7…（切捨て）


def test_月の所定時間で頭打ちと欠勤を遅刻早退に入れるは少ない方を1回で取る(tmp_path):
    # 欠勤 1 日×8 時間＋遅刻 30＝510 分・所定の不足 10,200−9,900＝300 分＝300 分で引く（欠勤を入れる今の形と同じ答え）
    後 = 値たち(回す(tmp_path, 決=決まり(**固定170, **月で頭打ち, **{"欠勤.欠勤を遅刻早退に入れる": "入れる"}), 上書き={"総労働": "9900"}))
    assert 後["欠勤控除"] == 0 and 後["遅刻早退控除"] == 8823


# ---- 8: 引かない（所定の不足を知らせる）----
