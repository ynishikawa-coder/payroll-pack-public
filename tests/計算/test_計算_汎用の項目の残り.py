@pytest.mark.parametrize("総労働, 遅刻早退控除", [
    ("9600", 882),    # 不足 10,200−9,600＝600 分−欠勤 1 日×8 時間＝120 分＞30 分＝30 分で引く（300,000×30÷60÷170＝882.35…）
    ("9700", 588),    # 不足 500 分−480 分＝20 分＜30 分＝20 分で引く（300,000×20÷60÷170＝588.23…）
    ("9720", 0),      # 不足 480 分＝欠勤の日の所定だけ＝遅刻 30 分はほかの日の残業で埋まった＝引かない
])
def test_月の所定時間で頭打ちと欠勤を遅刻早退に入れないは欠勤の日の所定を不足から除く(tmp_path, 総労働, 遅刻早退控除):
    # 欠勤は日数で別に引く（欠勤控除）＝月の所定時間−総労働 に残る欠勤の日の所定を頭打ちの上限から除く
    # （除かないと欠勤控除と遅刻早退控除の和が働かなかった時間を超える。集計の 月の所定の不足で頭打ち が勤務の日の所定だけを足すのと同じ）
    入れない = 値たち(回す(tmp_path / "a", 決=決まり(**固定170), 上書き={"総労働": 総労働}))
