"""日単価（月の決まった賃金÷月の所定日数）を単価の元にする行（作り物の 1 人・期待値は四則で手で出す）。

日単価は支給の行を数える前に決める（前は欠勤控除の所で後から決めていた＝日単価の行が必ず「単価が出ない」で仮になっていた）。
"""
from decimal import Decimal

from 作る_計算 import 人, 回す, 決まり, 値たち

日単価の行 = {"名": "休日出勤手当", "支給か控除": "支給", "単価の元": "日単価", "数量の元": "勤怠の数:出勤日数",
           "割増の基礎": "入らない", "割増の基礎から除く訳": "臨時の賃金"}


def _決(**上書き):
    d = 決まり(**上書き)
    return {**d, "項目.行": d["項目.行"] + [日単価の行]}


def test_固定の所定日数なら日単価の行は確定で月の決まった賃金を日数で割った額(tmp_path):
    r = 回す(tmp_path, 決=_決(**{"時間.月の所定日数の出し方": "固定の値", "時間.月の所定日数": "20",
                                  "時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "160"}))
    v = 値たち(r)
    # 欠勤で減る行（既定の 欠勤.控除の基礎 は空＝下の決まりで読む）のうち 基本給 280,000＋職務手当 20,000＝300,000 ÷ 20 日 × 出勤 19 日
    基礎 = Decimal(280000 + 20000)
    assert Decimal(str(v["休日出勤手当"])) == 基礎 / 20 * 19
    assert not any("休日出勤手当" in q["何が無いか"] and "単価" in q["何が無いか"] for q in r["問い"])


def test_月の決まった賃金の無い人には出ない訳を分けて仮(tmp_path):
    人の値 = 人(**{"項目.人の額": {"通勤手当": "12000"}})
    r = 回す(tmp_path, 決=_決(**{"時間.月の所定日数の出し方": "固定の値", "時間.月の所定日数": "20",
                                  "時間.月の所定時間の出し方": "固定の値", "時間.月の所定時間": "160"}), 人の値=人の値)
    assert r["人"][0]["状態"] == "仮"
    assert any("月の決まった賃金の無い人に当たる" in q["何が無いか"] for q in r["問い"])
