# ---- 引く口（docs/設計/法の表.md §1.2・§2.2）

def _表(d: Path, 名, 欠けた時, 行):
    d.mkdir(exist_ok=True)
    (d / f"{名}.json").write_text(json.dumps({"表の名": 名, "基準": "月分", "引く鍵": [], "欠けた時": 欠けた時, "行": 行},
                                            ensure_ascii=False), encoding="utf-8")


def test_引く口の欠けと仮と重なり(tmp_path):
    行 = [{"鍵": {}, "効く始め": "2026-03", "効く終わり": "2027-02", "状態": "出た", "値": {"率%": 1}},
          {"鍵": {}, "効く始め": "2027-03", "効く終わり": None, "状態": "まだ", "値": None}]
    _表(tmp_path, "止める表", "止める", 行)
    _表(tmp_path, "仮の表", "仮で計算し問う", 行)
    _表(tmp_path, "重なる表", "止める", [dict(行[0]), dict(行[0])])
    assert 引く("止める表", "2027-02-15", 置き場=tmp_path).値 == {"率%": 1}
    with pytest.raises(欠け):
        引く("止める表", "2027-03", 置き場=tmp_path)
    r = 引く("仮の表", "2027-03", 置き場=tmp_path)
    assert r.仮 and r.値 == {"率%": 1} and r.出所.startswith("仮:")
    with pytest.raises(表の誤り):
        引く("重なる表", "2026-05", 置き場=tmp_path)
    with pytest.raises(欠け):
        引く("無い表", "2026-05", 置き場=tmp_path)
    assert 引く("止める表", {"月分": "2026-04", "支払日": "2027-09-01"}, 置き場=tmp_path).値 == {"率%": 1}
