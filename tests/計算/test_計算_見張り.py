"""② 見張り: 作り物の小さな月の数字から出る支給控除の縦が黙って変わらないこと。要る値が欠けた人・仮の月の数字の人が仮で返ること。

値が変わる直しをした時は、変わった項目と理由を PR に書いてから 計算_見張り_期待.json を直す。
"""
import json
from pathlib import Path

import pytest

from 作る_計算 import 人, 回す, 決まり, 値たち, 置き場, 月の数字
from 芯.計算 import 欠け, 引く, 表の誤り, 計算する

期待 = json.loads((Path(__file__).parent / "計算_見張り_期待.json").read_text(encoding="utf-8"))


def _縦(結果):
    return [[r["項目"], r["値"], r["状態"]] for r in 結果["行"]]


def _源泉の表を抜いて回す(tmp, 支給月="2026-11"):
    """源泉の月額表から 2026 年（令和 8 年分）の行を抜いた置き場で回す＝源泉の表が欠けた月を作る。"""
    d = 置き場(tmp)
    f = d / "源泉_月額表.json"
    t = json.loads(f.read_text(encoding="utf-8"))
    t["行"] = [x for x in t["行"] if x["効く始め"] != "2026-01-01"]
    f.write_text(json.dumps(t, ensure_ascii=False), encoding="utf-8")
    return 計算する(月の数字(支給月), 決まり={("C1", "0001"): 決まり()}, 人={("C1", "0001"): 人()}, 置き場=d)


def test_月給の人の縦が変わらない(tmp_path):
    r = 回す(tmp_path)
    assert _縦(r) == 期待["月給_2027-02"]
    assert r["人"] == [{"支給月": "2027-02", "会社": "C1", "NO": "0001", "状態": "確認済", "仮の数": 0}]
    assert r["問い"] == [] and r["法の線"] == []


def test_出口の入力の形で返す(tmp_path):
    """出口/README.md の入力の形（支給月・会社・NO・項目・値・状態・出所・見当・見当の拠り所・問いの番号）をそのまま出口の関所が受ける。"""
    from 出口.関所 import 通す
    r = 回す(tmp_path)
    for x in r["行"]:
        assert {"支給月", "会社", "NO", "項目", "値", "状態", "出所", "見当", "見当の拠り所", "問いの番号"} <= set(x)
    通った = 通す(r["行"], r["人の状態"])
    assert len(通った.行たち) == len(r["行"]) and 通った.外した人たち == ()
    仮 = _源泉の表を抜いて回す(tmp_path / "b")
    assert 通す(仮["行"], 仮["人の状態"]).行たち == ()


def test_源泉の表が欠けた月は源泉だけ仮(tmp_path):
    """源泉の月額表に支払日の行が無い（ここでは 2026 年の行を抜く）＝止める表＝源泉は値なしの仮・ほかの社保は確定（法の表.md §2.2）。"""
    r = _源泉の表を抜いて回す(tmp_path)
    assert _縦(r) == 期待["月給_2026-11"]
    assert r["人"][0]["状態"] == "仮"
    assert [q["変わる項目"] for q in r["問い"]] == [["源泉所得税", "控除計", "控除合計", "差引支給額"]]


def test_2026年支給の源泉は令和8年分の表で確定(tmp_path):
    """2026-11-25 支給は 法の表 の令和 8 年分の月額表で引ける＝源泉は確定・人は仮でない・出口へ出る（C7 の直す所 1）。
    課税対象額 261,905 円・扶養 1 人 → 260,000 円以上 263,000 円未満の行の甲 1 人＝4,920 円（国税庁 令和 8 年分 月額表 01-07.pdf）。"""
    from 出口.関所 import 通す
    r = 回す(tmp_path, 支給月="2026-11")
    v = {x["項目"]: x for x in r["行"]}
    assert v["課税対象額"]["値"] == 261905
    assert (v["源泉所得税"]["値"], v["源泉所得税"]["状態"]) == (4920, "確定")
    assert r["人"][0]["状態"] != "仮" and r["人"][0]["仮の数"] == 0
    assert len(通す(r["行"], r["人の状態"]).行たち) == len(r["行"])


