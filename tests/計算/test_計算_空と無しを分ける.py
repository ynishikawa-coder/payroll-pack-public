"""「名は在るのに空」を「名が無い」と同じに読まない（作り物の 1 人）。

前は `数(...) or 0` が空・崩れ・負を黙って 0 にして「確認済」で出した。今は 1 つの正本 形.名の数 が
名が無い＝(None,"")／名は在るのに空・数でない・負＝(None, 訳) を分け、訳が在る所は 0 で見当して仮＋問い 1 つにする。
各試験は前の `or 0` の形なら赤になる注入（名は在るのに空）と、名が無い時は今のままの回帰を組にする。
"""
from decimal import Decimal

import pytest

from 作る_計算 import 人, 回す, 決まり, 値たち, 置き場
from 芯.計算 import 賞与を計算する
from 芯.計算.形 import 名の数

鍵 = ("C1", "0001")
空たち = ("", "  ", None, "abc", "-1")


# ---- 正本: 形.名の数

def test_名の数は名が無いのと空を分ける():
    assert 名の数({}, "x") == (None, "")
    assert 名の数(None, "x") == (None, "")
    assert 名の数({"x": "3"}, "x") == (Decimal(3), "")
    assert 名の数({"x": "0"}, "x") == (Decimal(0), "")
    for 値 in 空たち:
        n, 訳 = 名の数({"x": 値}, "x")
        assert n is None and 訳, 値          # 名は在るのに足りない＝訳つき（黙って 0 にしない）


def _仮の問い(r, 語):
    return r["人"][0]["状態"] == "仮" and any(語 in q["何が無いか"] for q in r["問い"])


# ---- 割増.固定残業 の 時間（額は ④ の行の 1 か所＝型の版 42。額の欠けは test_計算_固定残業の額は行の1か所）

def test_固定残業の時間が無い空なら黙って0で確定しない(tmp_path):
    for i, 値 in enumerate(("<無し>",) + 空たち):
        固 = {"形": "時間で"} if 値 == "<無し>" else {"形": "時間で", "時間": 値}
        r = 回す(tmp_path / str(i), 決=決まり(**{"割増.固定残業": 固, "割増.固定残業の対象": "時間外"}))   # 検査も落ちない
        assert _仮の問い(r, "割増.固定残業（時間で）の 時間"), 値


def test_固定残業の時間が書いてあれば仮にしない(tmp_path):
    r = 回す(tmp_path, 決=決まり(**{"割増.固定残業": {"形": "時間で", "時間": "3"}, "割増.固定残業の対象": "時間外"}))
    assert not any("割増.固定残業" in q["何が無いか"] for q in r["問い"])


# ---- 社保.組合の率

def test_組合の健保の率が無い空なら黙って0で確定しない(tmp_path):
    for i, 値 in enumerate(("<無し>",) + 空たち):
        率 = {"介護の本人率%": "0.9"} if 値 == "<無し>" else {"健保の本人率%": 値, "介護の本人率%": "0.9"}
        r = 回す(tmp_path / str(i), 決=決まり(**{"社保.組合の率": 率}))
        assert _仮の問い(r, "社保.組合の率 の 健保の本人率%"), 値


def test_組合の介護の率は介護の年齢の人だけ問う(tmp_path):
    率 = {"健保の本人率%": "5"}
    中 = 回す(tmp_path / "a", 決=決まり(**{"社保.組合の率": 率}))                                  # 1980 年生まれ＝介護の年齢
    assert _仮の問い(中, "社保.組合の率 の 介護の本人率%")
    外 = 回す(tmp_path / "b", 決=決まり(**{"社保.組合の率": 率}), 人の値=人(**{"人.生年月日": "1995-05-10"}))
    assert not any("社保.組合の率" in q["何が無いか"] for q in 外["問い"])
    assert 値たち(外)["健康保険"] > 0


# ---- 社保の立て替えの残り（名は在るのに空）

def test_立て替えの残りの名は在るのに空なら仮(tmp_path):
    決 = 決まり(**{"社保.引けない月の本人負担": "毎月請求"})
    for i, 値 in enumerate(("", "  ", None)):
        r = 回す(tmp_path / str(i), 決=決, 入力={鍵: {"社保の立て替えの残り": 値}})
        assert _仮の問い(r, "社保の立て替えの残り"), 値


# ---- 賞与: 前の標準賞与額

def _賞与(tmp_path, 前):
    return 賞与を計算する([{"会社": "C1", "NO": "0001", "額": 300000, "原本の名前": "作り物"}], 支給日="2027-02-26",
                     決まり={鍵: 決まり()}, 人={鍵: 人()}, 前月の課税対象額={鍵: 300000}, 前の標準賞与額=前,
                     計算期間={鍵: 6}, 置き場=置き場(tmp_path))


def test_前の標準賞与額が空なら前の賞与なしで確定しない(tmp_path):
    for i, 値 in enumerate(空たち):
        r = _賞与(tmp_path / str(i), {鍵: 値})
        assert _仮の問い(r, "前の賞与の標準賞与額"), 値
    r = _賞与(tmp_path / "0円", {鍵: 0})
    assert not any("前の賞与の標準賞与額" in q["何が無いか"] for q in r["問い"])
