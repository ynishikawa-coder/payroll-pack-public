"""委託の時給を 委託.日給÷1 日の所定 で出す時、所定が 0 なら割らずに仮＋問い（作り物の値だけ）。

前の道具 timecard_tally の itaku は `hr = 日給 / (cap / 60)` で cap＝0 だと止まる＝答えが無い。
芯は止まらず仮にして問う（仮が残る人は出口へ出さない）。
日給と時給の両方がある人でも、所定 0・境が空なら前の道具は境 0＝全部の日を日当にする＝黙って時給で確定にせず、全部日当で見当して仮＋問い。
"""
from 作る_計算 import 人, 決まり, 月の数字
from test_計算_役員と委託 import _回す, _値, _状態

_日ごと = {"2027-01-05": "8:00", "2027-01-06": "6:00", "2027-01-07": "5:30"}


def _回す日ごと(tmp, 所定, 人の値):
    決 = 決まり(**{"委託.式": "日ごとに時給か日当", "委託.丸め": "切捨て", "委託.実働の丸め": "丸めない", "委託.日当の境": "無し",
                  "時間.日の所定": 所定})
    月 = 月の数字(上書き={"出勤日数": "3", "法定休日": "0", "所定休日": "0"})
    return _回す(tmp, 決, 人(**{"人.区分": "委託", **人の値}), 月=月, 入力={"委託.日ごとの実働": _日ごと})


def test_所定0で日給だけの人は割らずに仮と問い(tmp_path):
    r = _回す日ごと(tmp_path, "0", {"委託.日給": "12000"})
    assert _状態(r)["委託分の報酬"] == "仮" and r["人"][0]["状態"] == "仮"
    assert any("1 日の所定が 0" in q["何が無いか"] and "委託.日当の境" in q["答え方の例"] for q in r["問い"])


def test_所定0で境が空なら両方ある人も全部日当の見当で仮と問い(tmp_path):
    r = _回す日ごと(tmp_path, "0", {"委託.日給": "12000", "委託.時給": "1500"})
    assert _値(r)["委託分の報酬"] == 36000 and _状態(r)["委託分の報酬"] == "仮" and r["人"][0]["状態"] == "仮"
    assert any("委託.日当の境 が無い" in q["何が無いか"] for q in r["問い"])


def test_所定0でも時給だけの人は全部時給で確定(tmp_path):
    r = _回す日ごと(tmp_path, "0", {"委託.時給": "1500"})   # 前の道具も日給が無ければ全部の日を時給
    assert _値(r)["委託分の報酬"] == 12000 + 9000 + 8250 and _状態(r)["委託分の報酬"] == "確定"


def test_所定8hなら日給を所定で割って時給(tmp_path):
    r = _回す日ごと(tmp_path, "8", {"委託.日給": "12000"})   # 8:00 は日当・6:00 と 5:30 は 12000÷8＝1500 の時給
    assert _値(r)["委託分の報酬"] == 12000 + 9000 + 8250 and _状態(r)["委託分の報酬"] == "確定"
