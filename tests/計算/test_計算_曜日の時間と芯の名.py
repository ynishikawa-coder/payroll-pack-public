"""部品の行の式: 数量の元 `勤怠の数:曜日の時間:<曜日>`（土曜の時間に払う手当）と、芯の名（休日手当）とぶつかる会社の行の直し方。

期待値は試験の中で手で出す（作り物の 1 人・土曜の時間の額 1,200 円）。
"""
from 作る_計算 import 人, 回す, 決まり, 値たち, 月の数字, 置き場

from 芯.計算 import 計算する

鍵 = ("C1", "0001")
土曜の行 = {"名": "土曜割増", "支給か控除": "支給", "単価の元": "人の額", "数量の元": "勤怠の数:曜日の時間:土", "率": "0.25"}


def _決(*足す):
    d = 決まり()
    return 決まり(**{"項目.行": d["項目.行"] + list(足す)})


def _人():
    d = 人()
    return 人(**{"項目.人の額": {**d["項目.人の額"], "土曜割増": "1200"}})


def test_土曜の時間に単価と率を掛ける(tmp_path):
    r = 回す(tmp_path, 決=_決(土曜の行), 人の値=_人(), 上書き={"曜日の時間:土": "480", "曜日の時間:月": "9120"})
    v = 値たち(r)
    assert v["土曜割増"] == 1200 * 8 // 4                 # 1,200 円×0.25×8 時間
    assert {x["項目"]: x["状態"] for x in r["行"]}["土曜割増"] == "確定"


def test_曜日の時間が無く働いた人は仮(tmp_path):
    """月の数字の口から曜日に分けられず行の来ない人（総労働はある）: 黙って 0 にせず 0 で見当して仮＋問い。"""
    r = 回す(tmp_path, 決=_決(土曜の行), 人の値=_人())
    行 = {x["項目"]: x for x in r["行"]}
    assert 行["土曜割増"]["状態"] == "仮" and r["人"][0]["状態"] == "仮"
    assert any("曜日の時間:土" in q["何が無いか"] for q in r["問い"])


def test_曜日の時間を使わない人は仮にしない(tmp_path):
    r = 回す(tmp_path)
    assert r["人"][0]["状態"] == "確認済"


def test_休日手当とぶつかる行の問いに直し方(tmp_path):
    行 = {"名": "休日手当", "支給か控除": "支給", "単価の元": "固定の額", "額": "5000"}
    r = 計算する(月の数字(), 決まり={鍵: _決(行)}, 人={鍵: 人()}, 置き場=置き場(tmp_path))
    (q,) = r["問い"]
    assert "芯が自分で作る項目の名とぶつかる" in q["何が無いか"]
    assert "名を芯の名と別にする" in q["答え方の例"] and "法定休日の労働の割増" in q["答え方の例"]
    assert "その欄に当てている間はできない" in q["答え方の例"]   # 芯と同じ欄に出せるとは書かない


def test_別の名にした会社の休日手当は芯の休日手当と並ぶ(tmp_path):
    行 = {"名": "休日手当（会社）", "支給か控除": "支給", "単価の元": "固定の額", "額": "5000"}
    r = 計算する(月の数字(上書き={"法定休日": "60", "総労働": "9660"}), 決まり={鍵: _決(行)}, 人={鍵: 人()},
               置き場=置き場(tmp_path))
    v = 値たち(r)
    assert v["休日手当（会社）"] == 5000 and v["休日手当"] > 0
    assert r["問い"] == [] and r["人"][0]["状態"] == "確認済"
