"""欠勤で固定残業手当を減らした月の前払いの額は会社ごとの決まり（型の版 43・作り物の 1 人）。

割増.固定残業の欠勤の月 は 減らした後の額・減らす前の設定の額 の 2 つから選ぶ。空の会社は減らした後の額で計算し（仮にしない）、
減った月に限り知らせ＝会社ごとに 1 回の問いを出す。減らす前の設定の額 の会社は、減らす前の ④ の行の額を前払いとみなす。
"""
from 作る_計算 import 回す, 決まり, 値たち, 固定残業

import 初期設定.設問 as 設問

# まるごと欠勤の月（欠勤を遅刻早退に入れる人＝日割する行を払わない）でも、時間外の時間がある作り物の月
まるごと = {"出勤日数": "0", "欠勤": "20", "総労働": "600", "所定内": "0", "法定内残業": "0", "法定外残業": "600", "深夜": "0",
          "遅刻早退": "0"}
減る行 = {"日割する": "する", "欠勤で減る": "減る"}


# 一部だけ欠勤の月（行は全額払い、欠勤控除で減らす）
一部 = {"出勤日数": "15", "欠勤": "5", "法定外残業": "1200", "遅刻早退": "0"}
欠勤なし = {"出勤日数": "20", "欠勤": "0", "遅刻早退": "0"}


def _回す(tmp, 決め=None, 上書き=まるごと, 額="30000", 入れる="入れる"):
    固 = 固定残業(額)
    固["項目.行"] = [{**r, **減る行} if r["名"] == "固定残業手当" else r for r in 固["項目.行"]]
    決 = 決まり(**{"欠勤.欠勤を遅刻早退に入れる": 入れる, **固,
                 **({"割増.固定残業の欠勤の月": 決め} if 決め is not None else {})})
    return 回す(tmp, 決=決, 上書き=上書き)


def _固定残業の仮(r):
    """固定残業で仮にした問い（作り物のまるごと欠勤の月は控除が引けない別の仮が出る＝それは数えない）。"""
    return [q for q in r["問い"] if "固定残業" in str(q)]


def _知らせ(r):
    return [x for x in r["法の線"] if "固定残業手当を欠勤で減らした月" in x]


def test_決まりが空なら減らした後の額で計算し仮にせず知らせる(tmp_path):
    r = _回す(tmp_path / "a")
    v = 値たち(r)
    assert v["固定残業手当"] == 0
    assert not _固定残業の仮(r), r["問い"]
    assert _知らせ(r), r["法の線"]
    後 = _回す(tmp_path / "b", "減らした後の額")
    assert 値たち(後)["時間外手当"] == v["時間外手当"] and not _知らせ(後)   # 空と同じ額・選んだ会社には問わない


def test_減らす前の設定の額を選んだ会社は減らす前の額を前払いとみなす(tmp_path):
    後 = 値たち(_回す(tmp_path / "a", "減らした後の額"))["時間外手当"]
    assert 後 > 0
    r = _回す(tmp_path / "b", "減らす前の設定の額")
    assert 値たち(r)["固定残業手当"] == 0
    assert 値たち(r)["時間外手当"] == max(0, 後 - 30000)
    assert not _知らせ(r) and not _固定残業の仮(r)


def test_減っていない月は問わない(tmp_path):
    r = _回す(tmp_path, 上書き=欠勤なし)
    assert 値たち(r)["固定残業手当"] == 30000 and not _知らせ(r)


def test_一部だけ欠勤の月も欠勤控除で減らした額を前払いとみなす(tmp_path):
    空 = _回す(tmp_path / "a", 上書き=一部, 入れる="入れない")
    後 = _回す(tmp_path / "b", "減らした後の額", 上書き=一部, 入れる="入れない")
    前 = _回す(tmp_path / "c", "減らす前の設定の額", 上書き=一部, 入れる="入れない")
    v空, v後, v前 = 値たち(空), 値たち(後), 値たち(前)
    assert v空["固定残業手当"] == 30000 and v空["欠勤控除"] > 0   # 行は全額払い・欠勤控除で減らす
    assert _知らせ(空) and not _固定残業の仮(空)                   # 空は知らせ（問い）・仮にしない
    assert v後["時間外手当"] == v空["時間外手当"] and not _知らせ(後)
    assert not _知らせ(前) and v前["時間外手当"] < v後["時間外手当"]   # 減らす前の額を前払いとみなす＝払う時間外が少ない


def test_問いは会社ごとに1回で選択肢は決まりの2つ(tmp_path):
    r = _回す(tmp_path)
    行 = [f"C1 {NO}: {x.split(': ', 1)[1]}" for NO in ("0001", "0002") for x in _知らせ(r)]
    種 = [s for s in 設問.種を集める({"会社": "C1", "問い": {}, "法の線": 行}) if "前払いの額" in s["何が無いか"]]
    assert len(種) == 1 and 種[0]["人"] == ["0001", "0002"]
    assert 種[0]["答え方の例"] == "減らした後の額／減らす前の設定の額"
    assert set(種[0]["変わる事"]) == {"減らした後の額", "減らす前の設定の額"}
    assert "割増.固定残業の欠勤の月" in 種[0]["反映先"]
