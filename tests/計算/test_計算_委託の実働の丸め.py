"""芯/計算 委託: 委託の日ごとの実働の丸め `委託.実働の丸め`（作り物の値だけ）。

前の道具 pixel-office agents/kyuyo/道具/timecard_tally.py 376 行（畳んだ commit 69cfdf3b4 の 1 つ前）: 勤務の長さの丸め（分）で日の実働を
`work // 単位 * 単位`＝切り捨て。日当と時給を選ぶ境（596 行）も丸めた実働と比べる。
- 15分切捨て: 3:37 → 3:30（前の道具と一致）。日当の境と比べるのも丸めた後
- 丸めない: そのまま。無い・読めない: 丸めずに見当して仮＋問い 1 つ（黙って丸め無しで確定にしない）
- 日ごとの実働の無い `時給` は日ごとに丸められない＝`丸めない` の外は仮
"""
from 作る_計算 import 人, 決まり, 月の数字
from test_計算_役員と委託 import _回す, _値, _状態

from 芯.計算.委託 import 実働の丸めを読む

_月 = 月の数字(上書き={"出勤日数": "1", "法定休日": "0", "所定休日": "0"})


def _回す時給(tmp, 実働の丸め=None, 日ごと=None, 式="時給", **他):
    d = {"委託.式": 式, "委託.丸め": "切捨て", **他}
    if 実働の丸め is not None:
        d["委託.実働の丸め"] = 実働の丸め
    入力 = {"委託.日ごとの実働": 日ごと} if 日ごと else None
    return _回す(tmp, 決まり(**d), 人(**{"人.区分": "委託", "委託.時給": "2000", "委託.日給": "16000"}), 月=_月, 入力=入力)


def test_読む():
    assert 実働の丸めを読む("15分切捨て") == (15, "切捨て")
    assert 実働の丸めを読む("15 分 切り捨て") == (15, "切捨て")
    assert 実働の丸めを読む("30分切上げ") == (30, "切上げ")
    assert 実働の丸めを読む("丸めない") is False
    for 字 in ("", None, "15", "切捨て", "0分切捨て", "15分", "15分ほど"):
        assert 実働の丸めを読む(字) is None, 字


def test_15分切捨てで前の道具と一致(tmp_path):
    r = _回す時給(tmp_path, "15分切捨て", {"2027-01-05": "3:37"})   # 10:22〜13:59
    assert _値(r)["委託分の報酬"] == 7000 and _状態(r)["委託分の報酬"] == "確定"   # 3:30×2000
    assert "15 分切捨て" in next(x["出所"] for x in r["行"] if x["項目"] == "委託分の報酬")


def test_丸めないはそのまま確定(tmp_path):
    r = _回す時給(tmp_path, "丸めない", {"2027-01-05": "3:37"})
    assert _値(r)["委託分の報酬"] == 7233 and _状態(r)["委託分の報酬"] == "確定"   # 217 分×2000÷60 の 1 円切捨て


def test_日当の境と比べるのは丸めた実働(tmp_path):
    日 = {"2027-01-05": "7:55"}
    r = _回す時給(tmp_path / "a", "15分切上げ", 日, 式="日ごとに時給か日当", **{"委託.日当の境": "8:00"})
    assert _値(r)["委託分の報酬"] == 16000   # 7:55 → 8:00 で境に届く＝日当
    r = _回す時給(tmp_path / "b", "丸めない", 日, 式="日ごとに時給か日当", **{"委託.日当の境": "8:00"})
    assert _値(r)["委託分の報酬"] == 15833   # 届かない＝時給


def test_無い読めない時は丸めずに見当して仮と問い1つ(tmp_path):
    for 値 in (None, "15", "15分ほど"):
        r = _回す時給(tmp_path / str(値), 値, {"2027-01-05": "3:37", "2027-01-06": "2:10"})
        assert _値(r)["委託分の報酬"] == 7233 + 4333 and _状態(r)["委託分の報酬"] == "仮", 値
        assert r["人"][0]["状態"] == "仮"
        (q,) = [q for q in r["問い"] if "委託.実働の丸め" in q["何が無いか"]]
        assert "丸めない" in q["答え方の例"] and "15分切捨て" in q["答え方の例"]


def test_日ごとの実働の無い時給は丸めないの外は仮(tmp_path):
    r = _回す時給(tmp_path / "a", "丸めない")
    assert _状態(r)["委託分の報酬"] == "確定"
    r = _回す時給(tmp_path / "b", "15分切捨て")
    assert _状態(r)["委託分の報酬"] == "仮"
    assert any("委託.実働の丸め を日ごとに当てられない" in q["何が無いか"] for q in r["問い"])


def test_月額と日給は実働の丸めを問わない(tmp_path):
    for 式 in ("月額", "日給"):
        r = _回す(tmp_path / 式, 決まり(**{"委託.式": 式, "委託.丸め": "切捨て", "委託.みなし残業時間": "無し"}),
                 人(**{"人.区分": "委託", "委託.月給": "200000", "委託.日給": "10000"}), 月=_月)
        assert not any("委託.実働の丸め" in q["何が無いか"] for q in r["問い"]), 式
