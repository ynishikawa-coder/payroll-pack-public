def test_呼び口の出所を見る(tmp_path):
    (tmp_path / "答え.json").write_text(json.dumps({"行": [dict(出所="縦.xlsx#10月")]}), encoding="utf-8")
    (tmp_path / "問い.json").write_text(json.dumps(_問い, ensure_ascii=False), encoding="utf-8")
    def 回す(記録):
        (tmp_path / "記録.json").write_text(json.dumps(記録, ensure_ascii=False), encoding="utf-8")
        rc = main(["出所を見る", "--変更の記録", str(tmp_path / "記録.json"), "--答え", str(tmp_path / "答え.json"),
                   "--答えの資料", "書類_過去の明細.pdf", "--質問と回答", str(tmp_path / "問い.json"), "--会社", "9",
                   "--出す", str(tmp_path / "出所.json")])
        return rc, json.loads((tmp_path / "出所.json").read_text(encoding="utf-8"))
    rc, d = 回す([_記録(問いの番号="Q202611-01")])
    assert rc == 0 and d["止める"] is False and d["外れの数"] == 0
    rc, d = 回す([_記録(書類の名="縦.xlsx"), _記録(書類の名="書類_過去の明細.pdf")])
    assert rc == 1 and d["止める"] is True and [x["訳"] for x in d["外れ"]] == ["過去の結果が書類"] * 2


