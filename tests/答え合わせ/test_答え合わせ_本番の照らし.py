# ── 照らしの問いが今の設問の形で出る ──

def test_照らしの差は設問の種の形():
    種 = _照らす().問いの種
    assert len(種) == 3
    for s in 種:
        # 設問の 4 つの箱の 1 つ（読み方）・種類は会社の決まり（質問と回答の列だけから決まる）
        assert s["箱"] == "読み方" and 設問.箱(s) == "読み方" and 設問.種類(s) == "会社の決まり"
        assert s["何が無いか"].startswith(段.照らしの印)
        # 根拠（資料・場所・原文）と AI の読みを持つ・見当は置かない（過去の値を見込みにしない）
        assert s["根拠"] and all(e["資料"] and e["場所"] and e["原文"] for e in s["根拠"]) and s["読み"]
        assert s["見当"] == "" and s["見当の拠り所"] == "無し"
        # 古い問いの形（突き合わせの「質問と回答へ回す行」）を持たない
        assert not {"文", "行", "差の見立て", "差の出所"} & set(s)
        assert s["答え方の例"] != "／".join(突.答え方) and "（推奨）" not in s["答え方の例"]
    基本給 = next(s for s in 種 if "「基本給」" in s["何が無いか"])
    assert 基本給["根拠"] == [{"資料": "縦.xlsx", "場所": "タブ 10月・NO 0004 の行「基本給」の欄", "原文": "160000円"}]
    assert "165000円" in 基本給["読み"] and "160000円" in 基本給["読み"]


def test_照らしの種はまとめると確認ページを通る():
    m = 設問.まとめる(list(_照らす().問いの種), 会社=作.会社, 支給月="2026.11支給", 今日="2026-11-18", 読んだ資料=読んだ)
    assert m["差し戻し"] == [] and m["オーナーに聞く"] == [] and m["出さなかった"] == []
    assert m["種類ごとの数"] == {"会社の決まり": 3, "原本": 0}
    assert [q["問いの番号"] for q in m["問い"]] == ["Q202611-01", "Q202611-02", "Q202611-03"]
    assert 確認.問いの検査(m["問い"]) == []
    r = 確認.作る({"組": "作り物の組", "支給月": "2026.11支給", "用": "立ち上げ", "問い": m["問い"], "読んだ資料": 読んだ})
    assert r["赤"] == [], r["赤"]
    assert r["部"] == {"会社の決まり": 3, "原本": 0} and "基本給が、法律どおりの計算と過去の支給とで違います" in r["html"]
    # 同じ違いは既にある問いとして聞き直さない（月をまたいでも 会社×項目×向き で 1 つ）
    again = 設問.まとめる(list(_照らす().問いの種), 会社=作.会社, 支給月="2026.12支給", 今日="2026-11-18",
                       読んだ資料=読んだ, 既にある=m["問い"])
    assert again["問い"] == [] and len(again["出さなかった"]) == 3


def test_根拠の無い照らしの種は差し戻す():
    """根拠を外した種は問いにならない（設問.まとめる が差し戻す）＝照らしの種が根拠を持つ事がこの道の要。"""
    種 = [{k: v for k, v in s.items() if k != "根拠"} for s in _照らす().問いの種]
    m = 設問.まとめる(種, 会社=作.会社, 支給月="2026.11支給", 今日="2026-11-18", 読んだ資料=読んだ)
    assert m["問い"] == [] and len(m["差し戻し"]) == 3


def test_呼び口の差に問いの種(tmp_path):
    (tmp_path / "つなぎ.json").write_text(json.dumps({"欄": 作.つなぎ}), encoding="utf-8")
