def test_照らしの差は設問の種の形():
    種 = _照らす().問いの種
    assert len(種) == 3
    for s in 種:
        # 設問の 4 つの箱の 1 つ（読み方）・種類は会社の決まり（質問と回答の列だけから決まる）
        assert s["箱"] == "読み方" and 設問.箱(s) == "読み方" and 設問.種類(s) == "会社の決まり"
        assert s["何が無いか"].startswith(段.照らしの印)
        # 根拠（資料・場所・原文）と AI の読みを持つ・見当は置かない（過去の値を見込みにしない）
        assert s["根拠"] and all(e["資料"] and e["場所"] and e["原文"] for e in s["根拠"]) and s["読み"]
        assert s["見当"] == "" and s["見当の拠り所"] == "無し"
        # 古い問いの形（突き合わせの「質問と回答へ回す行」）を持たない
        assert not {"文", "行", "差の見立て", "差の出所"} & set(s)
        assert s["答え方の例"] != "／".join(突.答え方) and "（推奨）" not in s["答え方の例"]
    基本給 = next(s for s in 種 if "「基本給」" in s["何が無いか"])
    assert 基本給["根拠"] == [{"資料": "縦.xlsx", "場所": "タブ 10月・NO 0004 の行「基本給」の欄", "原文": "160000円"}]
    assert "165000円" in 基本給["読み"] and "160000円" in 基本給["読み"]


