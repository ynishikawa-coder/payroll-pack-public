def test_控除の当たらない人の遅刻早退は照らさない():
    つなぎ = [*作.つなぎ, dict(項目="遅刻早退", 欄="遅刻早退時間", 形="分")]
    答え = [dict(支給月=作.月, 会社=作.会社, NO="0006", 項目=k, 値=v, 状態="確定", 出所="横.csv")
          for k, v in (("基本給", "100000"), ("遅刻早退", "0"))]
    # 時給の人: 遅刻早退 2:00 を数えたが 控除＝月給の人だけ引く で 遅刻早退控除 は 0
    芯 = [作.R("0006", "基本給", 100000), 作.R("0006", "遅刻早退", 120), 作.R("0006", "遅刻早退控除", 0)]
    r = 段.照らす(芯, 答え, つなぎ)
    assert r.差の行の数 == 0 and any(x.startswith("遅刻早退（控除の当たらない人: 0006）") for x in r.照らさなかった項目)
    # 控除が当たる人（遅刻早退控除 が 0 でない）は照らす＝時間の差は差のまま
    芯2 = [作.R("0006", "基本給", 100000), 作.R("0006", "遅刻早退", 120), 作.R("0006", "遅刻早退控除", 1500)]
    assert 段.照らす(芯2, 答え, つなぎ).差の行の数 == 1
