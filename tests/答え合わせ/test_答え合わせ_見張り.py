def test_差の表():
    答え = list(_一覧表().行たち) + list(_明細().行たち)
    r = 段.照らす(作.芯の行, 答え, 作.つなぎ)
    差 = [x for x in r.差の表 if x[6] != "0"]
    assert 差 == [
        ("支給月", "会社", "NO", "項目", "こちら", "給与ソフト", "差", "差の見立て", "差の出所"),
        ("2026-10", "9", "0002", "残業手当", "", "0", "片方だけ", "片方だけ", "横.csv"),
        ("2026-10", "9", "0003", "総支給", "153001", "153000", "1", "丸め", "作り物の原本"),
        ("2026-10", "9", "0004", "基本給", "165000", "160000", "5000", "決まりの違い", "作り物の原本"),
    ]
    assert len(r.差の表) == 17 and r.差の行の数 == 3
    assert [(q["差の見立て"], q["人"], q["項目"]) for q in r.問い] == [
        ("片方だけ", ("0002",), ("残業手当",)), ("丸め", ("0003",), ("総支給",)), ("決まりの違い", ("0004",), ("基本給",))]
    # 仮の人（0005）は答えがあっても照らさない・答えの無い月は照らさない
    assert r.外した人 == ({"支給月": "2026-10", "会社": "9", "NO": "0005", "仮の数": 1, "問いの番号": "Q-1"},)
    assert r.人の状態[("2026-10", "9", "0005")] == "未突き合わせ"
    assert r.照らさなかった月 == (("2026-09", "9"),)
    assert r.要確認 == ()
    assert [(m["支給月"], m["差0の月"]) for m in r.月の記録] == [("2026-10", False)]
    assert r.差0の月数["9"]["月数"] == 0


def test_差0の月を続けて数える():
    """3 か月の答えが芯と全部合う時、続けて差 0 の月は 3。月をまたぐ前の記録も数える。"""
    芯, 答え = [], []
    for m in ("2026-08", "2026-09", "2026-10"):
        for no, v in (("0001", 200000), ("0002", 180000)):
            芯.append(作.R(no, "基本給", v, 月_=m))
            答え.append(dict(支給月=m, 会社=作.会社, NO=no, 項目="基本給", 値=v, 状態="確定", 出所="作り物の答え"))
    r = 段.照らす(芯[:4], 答え[:4], 作.つなぎ)
    assert r.差の行の数 == 0 and r.差0の月数["9"]["月数"] == 2
    r2 = 段.照らす(芯[4:], 答え[4:], 作.つなぎ, 前の記録=r.月の記録)
    assert r2.差0の月数["9"]["数えた月"] == ("2026-08", "2026-09", "2026-10")
    # 答えが違うで閉じた問いのある月は差 0 に数えない
    r3 = 段.照らす(芯, 答え, 作.つなぎ, 給与ソフトが違うで閉じた={("9", "2026-09"): 1})
    assert r3.差0の月数["9"]["数えた月"] == ("2026-10",)


def test_読めない物は要確認へ():
    w = []
    assert 表にする("x.pdf", b"%PDF-1.4 ...", 要確認=w) == [] and w == ["x.pdf: PDF は読まない（給与ソフトから xlsx か CSV で出し直す）"]
    t = 表にする("a.csv", "NO,基本給,手当X\n0001,1000,5\n0002,abc,\n,7,\n".encode())
    r = 口.一覧表を読む(t, 作.会社, 作.月, 作.つなぎ)
    assert [(x.NO, x.項目, str(x.値)) for x in r.行たち] == [("0001", "基本給", "1000")]
    assert r.要確認 == (
        "a.csv: つなぎ に無い見出し「手当X」（読んでいない）",
        "a.csv 0002 基本給: 数でない値: 'abc'（読んでいない）",
        "a.csv: 鍵の無い行（列）に値がある（読んでいない）",
    )
    # 2 つの表で同じ人×項目の値が違えば前の値のまま要確認
    t2 = 表にする("b.csv", b"NO,\xe5\x9f\xba\xe6\x9c\xac\xe7\xb5\xa6\n0001,1001\n")
    r2 = 口.一覧表を読む(t + t2, 作.会社, 作.月, 作.つなぎ)
    assert r2.要確認[-1] == "b.csv 0001 基本給: a.csv の値 1000 と違う値 1001（前の値のまま）"


def test_氏名でNOを引く():
    t = 表にする("c.csv", "氏名,基本給\n作り物 一,1000\n作り物 二,2000\n作り物 三,3000\n".encode())
    r = 口.一覧表を読む(t, 作.会社, 作.月, 作.つなぎ, 氏名からNO={"作り物 一": "0001", "作り物　二": "0002"})
    assert [(x.NO, str(x.値)) for x in r.行たち] == [("0001", "1000"), ("0002", "2000")]
    assert r.要確認 == ("c.csv「作り物 三」: 氏名で NO が引けない（この人の値は読んでいない）",)


def test_呼び口(tmp_path):
    (tmp_path / "横.csv").write_bytes(作.一覧表_横.encode("cp932"))
    (tmp_path / "つなぎ.json").write_text(json.dumps({"欄": 作.つなぎ, "読まない見出し": list(作.読まない見出し)}), encoding="utf-8")
    芯 = [dict(r, 値=str(r["値"])) for r in 作.芯の行 if r["NO"] in ("0001",)]
    (tmp_path / "芯.json").write_text(json.dumps({"行": 芯}, ensure_ascii=False), encoding="utf-8")
    assert main(["読む", "--形", "一覧表", "--会社", "9", "--支給月", 作.月, "--つなぎ", str(tmp_path / "つなぎ.json"),
                 "--時間の書き方", "60進", "--文字コード", "cp932", "--出す", str(tmp_path / "答え.json"),
                 str(tmp_path / "横.csv")]) == 0
    答え = json.loads((tmp_path / "答え.json").read_text(encoding="utf-8"))
    答え["行"] = [x for x in 答え["行"] if x["NO"] == "0001"]
    (tmp_path / "答え.json").write_text(json.dumps(答え, ensure_ascii=False), encoding="utf-8")
    assert main(["照らす", "--芯", str(tmp_path / "芯.json"), "--答え", str(tmp_path / "答え.json"),
                 "--つなぎ", str(tmp_path / "つなぎ.json"), "--出す", str(tmp_path / "差.json")]) == 0
    差 = json.loads((tmp_path / "差.json").read_text(encoding="utf-8"))
    assert 差["差の行の数"] == 0 and len(差["差の表"]) == 5
    assert 差["照らさなかった月"] == [{"支給月": "2026-09", "会社": "9"}]
