"""答え合わせの つなぎ（{項目, 欄, 形}）は 渡す＝いいえ・受ける＝はい を口が明示で付ける（作り物の値だけ）。

出口.形.対応にする は 形・渡す・受ける の欠けた行を止める（前: 形＝円・渡す/受ける＝はい と黙って読んだ）。答えは過去の給与ソフトの
出力＝渡さない・受けるの意味が決まっているので、答えの読み口 の `答えの対応にする` だけがそれを付ける。形 の欠けは止まる。
"""
import pytest

import 答え合わせ_作り物 as 作
from 出口.形 import 対応にする
from 道具.答え合わせ.答えの読み口 import 答えの対応にする


def test_答えの対応は渡さず受ける():
    対応 = 答えの対応にする(作.つなぎ)
    assert [(x.項目, x.形, x.渡す, x.受ける) for x in 対応][:2] == [("基本給", "円", False, True), ("残業手当", "円", False, True)]
    with pytest.raises(ValueError, match="渡す"):             # 出口の口へそのまま渡せば止まる（はい と読まない）
        対応にする(作.つなぎ)


def test_答えのつなぎに形が無ければ止める():
    with pytest.raises(ValueError, match="形"):              # 前: 形＝円 と読んで分の欄を円で照らした
        答えの対応にする([dict(項目="残業時間", 欄="残業 時間")])
