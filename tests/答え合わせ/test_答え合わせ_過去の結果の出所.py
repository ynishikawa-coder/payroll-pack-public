def _材料():
    答え = _一覧表()
    照 = 段.照らす(作.芯の行, list(答え.行たち), 作.つなぎ, 人の状態={})
    return 出所を見る.答えの資料(答え.行たち), 照, list(答え.行たち)


def _記録(書類):
    return {"会社": "9", "NO": "0001", "項目": "基本給", "新しい値": "200000", "書類の名": 書類, "問いの番号": "",
            "確かめ": "確認済"}


def _見る(記録, **kw):
    資料, 照, 行 = _材料()
    kw.setdefault("照らし", 照)
    kw.setdefault("答えの行", 行)
    return 出所を見る.見る(記録, 資料, (), 会社="9", **kw)


def test_人と項目で一致した過去の結果は出所に数えて進む():
    r = _見る([_記録("過去の結果 2026.10支給 横 0001:総支給・0001:残業手当 一致"),
              _記録("過去の結果 2026-10 縦.xlsx 0003:基本給 で一致、書類_作り物の給与規程.pdf")])
