def test_例の確かめた人の過去の結果も照らしで見る():
    md = {"給与のルール.md": "# 給与のルール\n\n### 終業前の退勤\n\n文。\n\n" + _頭
          + _例の行("E01", "事務所（過去の結果 2026.10支給 横 0001:総支給 一致）")
          + _例の行("E02", "事務所（過去の結果 2026.10支給 縦 0003:総支給 一致）")
          + _例の行("E03", "事務所（R261119-AB12）")}
