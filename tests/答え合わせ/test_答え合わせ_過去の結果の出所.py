def test_わざと外した過去の結果は止める():
    """注入: 差のある人×項目・片方だけ・照らしに無い人・違う資料・違う月・形の欠け を書くと、どれも止める。"""
    記録 = [_記録("過去の結果 2026.10支給 縦 0003:総支給 一致"),          # 差 1（丸め）
          _記録("過去の結果 2026.10支給 横 0002:残業手当 一致"),        # 片方だけ
          _記録("過去の結果 2026.10支給 横 0999:総支給 一致"),          # 照らしに無い人
          _記録("過去の結果 2026.10支給 縦 0001:総支給 一致"),          # 0001 の答えは 横.csv
          _記録("過去の結果 2026.09支給 横 0001:総支給 一致"),          # 照らしていない月
          _記録("過去の結果 横 0001:総支給 一致"),                      # 支給月が無い
          _記録("過去の結果 2026.10支給 0001:総支給 一致"),             # 資料の名が無い
          _記録("過去の結果 2026.10支給 横 一致"),                      # 人×項目が無い
          _記録("過去の結果 2026.10支給 横 0001:総支給 一致しない")]     # 一致と書いていない
    r = _見る(記録)
    assert r.止める
    assert [(x["行の番号"], x["訳"]) for x in r.外れ] == [
        (1, "過去の結果と一致していない"), (2, "過去の結果と一致していない"),
        (3, "過去の結果と一致していない"), (3, "過去の結果の資料が違う"),
        (4, "過去の結果の資料が違う"),
        (5, "過去の結果と一致していない"), (5, "過去の結果の資料が違う"),
        (6, "過去の結果の形が読めない"), (7, "過去の結果の形が読めない"), (8, "過去の結果の形が読めない"),
        (9, "過去の結果の形が読めない")]


