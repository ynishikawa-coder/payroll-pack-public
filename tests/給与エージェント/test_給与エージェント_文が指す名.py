"""plugin payroll-agent の文（docstring・md）が指すパックの部品の名が在るかの試験。

防ぐ故障: 部品の名を変えた・消したのに、それを正本として指す文が古い名のまま残る（読む窓が無い名を探す）。
  指し方の 1 つだけを見て、ほかの指し方（道具の口の名・部品.名）や消えた file を指す文が緑のまま残る。
名の指し方の読み方は正本 bin/口の約束.py の 死んだ名 の 1 か所（口の一覧と同じ物を読む＝ここに写さない）。
保証しない事: ` で囲まない名・文の中の言い回しで指す名。
"""
from 手伝い import PLUGIN, 根

import 口の約束 as K  # noqa: E402


def test_plugin_の文が指す名は全部在る():
    files = sorted(p for p in PLUGIN.rglob("*") if p.suffix in (".py", ".md") and "__pycache__" not in p.parts)
    外れ = [f"{p.relative_to(根)}: {x}" for p in files for x in K.死んだ名(根, p.read_text(encoding="utf-8"), 口の行だけ=False)]
    assert 外れ == []


def test_注入_どの指し方でも消した名と無いfileは赤():
    def 照らす(text):
        return K.死んだ名(根, text, 口の行だけ=False)
    正しい = ("正本: 初期設定/型の口.py の `問いの番号の形`・`管理表/管理表.py 書く・寄せの印`・`月次.月を回す`・"
             "`管理表.py 書く`・`出口.名と版`\n")
    assert 照らす(正しい) == []
    assert 照らす(正しい.replace("問いの番号の形", "作り物の消えた名")) == ["初期設定/型の口.py に 作り物の消えた名 が無い"]
    assert 照らす(正しい.replace("寄せの印", "作り物の口")) == ["管理表/管理表.py に口 作り物の口 が無い"]
    assert 照らす(正しい.replace("月を回す", "作り物を回す")) == ["月次 に 作り物を回す が無い"]
    assert 照らす(正しい.replace("名と版", "作り物の版")) == ["出口 に 作り物の版 が無い"]
    assert 照らす(正しい.replace("初期設定/型の口.py", "作り物/無い.py")) == ["指す file が無い: 作り物/無い.py"]
    assert 照らす(正しい.replace("`管理表.py 書く`", "`作り物の無い.py 書く`")) == ["指す file が無い: 作り物の無い.py"]


def test_注入_在るfileを名だけで指しても部品の名と読まず_無いfileは赤():
    """`口の約束.py` を 部品 口の約束 の名 py と読まない（在る file を指す正しい文を赤にしない）。"""
    assert K.死んだ名(根, "詳しくは `口の約束.py`・`bin/口の約束.py`・`口の一覧.md` を見る。", 口の行だけ=False) == []
    assert K.死んだ名(根, "詳しくは `作り物の無い.py` を見る。", 口の行だけ=False) == ["指す file が無い: 作り物の無い.py"]
    assert K.死んだ名(根, "置き場は `確認事項_<組>_v<版>.html`・`**/<名>.py`。", 口の行だけ=False) == []


def test_注入_囲みの対をまたいで名と読まない():
    """前の ` の閉じと次の ` の開きの間の字（`a`・b.py の `c`）を 1 つの囲みと読まない。"""
    assert K.死んだ名(根, "`問いの番号の形`・確認ページ/確認ページ.py の `受付番号の形`。", 口の行だけ=False) == []
