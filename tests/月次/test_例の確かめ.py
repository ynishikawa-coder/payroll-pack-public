from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
sys.path.insert(0, str(根 / "tests" / "計算"))
sys.path.insert(0, str(根 / "tests" / "集計"))
_spec = importlib.util.spec_from_file_location("例の確かめ_試験_作り物", 根 / "tests" / "初期設定" / "test_初期設定_給与の関所.py")
作 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(作)

import 作る_計算  # noqa: E402
import 作る_集計  # noqa: E402
import 月次  # noqa: E402

C, 支給月, 人たち = 作.C, 作.支給月, 作.人たち
確かめる = 月次.例の確かめ.確かめる


def _確かめる(例, **タブの上書き):
    return 確かめる(支給月, C, 作._タブ(**タブの上書き), 例, 法の線=作る_集計.法の線, 段=月次.段, 繋=月次.繋)


def _例(*上書き):
    """作._例() の行を {列: 値} で上書きした並び（上書き[i] は i 番目の例の行へ）。"""
    見出し, *行 = 作._例()
    行 = [dict(zip(見出し, r)) for r in 行]
    for i, d in enumerate(上書き):
        行[i].update(d)
    return 行


def _回す(tmp_path, 例):
    return 月次.月を回す(支給月, C, 作._タブ(), [{"部品": "Excel出勤簿", "値": 作._出勤簿()}], 法の線=作る_集計.法の線,
                     置き場=作る_計算.置き場(tmp_path), 例=例)


def test_決まりどおりの例は通る():
    r = _確かめる(作._例())
    assert r == {"通った": True, "数": 2, "合わない": [], "止め": []}


def test_選べる値の中で取り違えたマスタは例で止まる():
    # 決まり（MD）は「始業前の打刻は始業から数える」。マスタに選べる値の 打刻のまま を書いた＝字の照らしは通る
    r = _確かめる(作._例(), 型={"日勤": {"時間.始業前の打刻": "打刻のまま"}})
    assert not r["通った"]
    (x,) = r["合わない"]
    assert x["例の番号"] == "E1" and "労働: 例 8:30・芯 8:40" in x["訳"] and "法定外残業: 例 0:30・芯 0:40" in x["訳"]


def test_締め日を取り違えたマスタは月の例で止まる():
    r = _確かめる(作._例(), 会社={"支払.締め日": "20"})
    assert not r["通った"] and [x["例の番号"] for x in r["合わない"]] == ["E2"]
    assert "締めの始め" in r["合わない"][0]["訳"]


