def test_マスタに値のある決まりに例が無ければ止まる():
    # レビュー（#159）の注入: 取り違えたマスタ（打刻のまま）で、例を締めの例だけにする＝その決まりを照らす例が無い
    r = _確かめる(_例()[1:], 型={"日勤": {"時間.始業前の打刻": "打刻のまま"}})
    assert not r["通った"]
    覆い = {x["決まり"] for x in r["合わない"] if x["例の番号"] == "（覆い）"}
    assert {"時間.始業前の打刻", "時間.所定の始業", "時間.日の所定"} <= 覆い
    # 社員の列の値（人ごとの契約の事実）は覆いに数えない
    r = _確かめる(作._例(), 人={"0001": {"時間.週の所定": "40:00"}})
    assert r["通った"], r["止め"]


def test_例が値の取り違えを見分けなければ止まる():
    # レビュー（#159）の注入: 始業前の打刻 を名に書いた例の期待が 休憩 だけ＝打刻のまま に替えても合う
    r = _確かめる(_例({"期待": "休憩=1:00"}))
    assert not r["通った"]
    (x,) = r["合わない"]
    assert x["例の番号"] == "（見分け）" and x["決まり"] == "時間.始業前の打刻" and "打刻のまま" in x["訳"]
    # 取り違えたマスタ（打刻のまま）でも、期待が 休憩 だけの例は合う＝見分けで止まる（レビューの 2 つ目の形）
    r = _確かめる(_例({"期待": "休憩=1:00"}), 型={"日勤": {"時間.始業前の打刻": "打刻のまま"}})
    assert not r["通った"] and [x["例の番号"] for x in r["合わない"]] == ["（見分け）"] and "所定の始業から" in r["止め"][0]
    # 数えの外れがある時は見分けを出さない（2 重に出さない）
    r = _確かめる(作._例(), 型={"日勤": {"時間.始業前の打刻": "打刻のまま"}})
    assert all(x["例の番号"] != "（見分け）" for x in r["合わない"])


