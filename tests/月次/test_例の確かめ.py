"""例の確かめ（月次/例の確かめ.py）の試験。作り物の会社 C1 の値だけ（tests/初期設定/test_初期設定_給与の関所.py の作り物）。

根: 給与のルール.md に書いた決まりと、計算が読むマスタの値が同じ事を言っているかを、誰も機械で確かめていなかった。
選べる値の中で取り違えた値（始業前の打刻 所定の始業から ↔ 打刻のまま）は、字の照らしも欄の埋まりの照らしも通る。
ここでは、その誤りの類をわざと入れて、月の口が会社の全員を出口へ出さないことを見る（注入の試験）。
"""
