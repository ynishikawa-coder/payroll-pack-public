def test_例が通らない月は会社の全員が出口へ出ない(tmp_path):
    出た = _回す(tmp_path / "a", 作._例())
    assert {r.NO for r in 出た["関所を通った"].行たち} == set(人たち) and 出た["例の確かめ"]["通った"]
    for 例 in (_例({"期待": "労働=8:40・休憩=1:00・法定外残業=0:40・遅刻早退=0:00"}), _例({"確かめた日": ""}), None, []):
        o = _回す(tmp_path / str(id(例)), 例)
        assert {r.NO for r in o["関所を通った"].行たち} == set(), 例
        assert {a["NO"] for a in o["外した人"]} == set(人たち)
        assert [q["何が無いか"] for q in o["問い"]["例"]] == [f"決まりの例: {t}" for t in o["例の確かめ"]["止め"]] != []
        assert any(q["何が無いか"].startswith("決まりの例:") for q in _種(o))
        # 見当の額は出す（問いに添える）が出口へは出ない
        assert set(o["見当の額"]) == set(人たち)


