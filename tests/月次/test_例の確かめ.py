def test_段の分かれた休憩の表の人も例に書けて読めない例でも月は落ちない(tmp_path):
    表 = "5:59超30分、8:00超60分"
    人 = {"0001": {"時間.休憩の表": 表}}
    E3 = {**_E3, "決まり": "給与のルール.md#2 休憩は長さで（時間.休憩の表）", "人の値": f"時間.休憩の表={表}",
          "区間": "労働 9:00-18:00", "期待": "労働=8:00・休憩=1:00"}
    r = _確かめる([*_例(), E3], 人=人)
    assert r["通った"], r
    # 値の中の 、 で切らない（名=値 の形でない欠片を作らない）・人の値に読めない字の例は 例が読めない で止まり、覆い（人）で落ちない
    assert 月次.例の確かめ._対(f"時間.休憩の表={表}・人.区分=パート") == [("時間.休憩の表", 表), ("人.区分", "パート")]
    for 悪い in ("時間.休憩の表", "=5:59超30分"):
        r = _確かめる([*_例(), {**E3, "人の値": 悪い}], 人=人)
        assert not r["通った"] and any("例が読めない" in x["訳"] for x in r["合わない"]), 悪い
        assert any(x["例の番号"] == "（覆い）" for x in r["合わない"])   # 読めない例はその人の値を覆わない
    o = 月次.月を回す(支給月, C, 作._タブ(人=人), [{"部品": "Excel出勤簿", "値": 作._出勤簿()}], 法の線=作る_集計.法の線,
                   置き場=作る_計算.置き場(tmp_path), 例=[*_例(), {**E3, "人の値": "時間.休憩の表"}])
    assert not o["例の確かめ"]["通った"]
