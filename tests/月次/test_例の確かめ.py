def test_社員の列に置いた数え方の決まりも例で覆う():
    # 人 0001 だけが 申請した残業だけ（社員の列）。会社と型の例 E1・E2 だけでは、その人の決まりは照らされない
    人 = {"0001": {"時間.終業後の打刻": "申請した残業だけ"}}
    r = _確かめる(作._例(), 人=人)
    assert not r["通った"] and [(x["例の番号"], x["決まり"]) for x in r["合わない"]] == [("（覆い）", "時間.終業後の打刻")]
    assert "申請した残業だけ" in r["合わない"][0]["訳"]
    # 人の値にその値を置いた例を足せば通る
    assert _確かめる([*_例(), _E3], 人=人)["通った"]
    # 人の値に別の値を置いた例は、その人の値を覆わない
    assert not _確かめる([*_例(), {**_E3, "人の値": "時間.終業後の打刻=打刻のまま", "期待": "労働=8:30・休憩=1:00・法定外残業=0:30"}],
                       人=人)["通った"]
    # 契約の量（日の所定 など時間の形）は事実＝覆いに数えない
    assert _確かめる(作._例(), 人={"0001": {"時間.日の所定": "6:00"}})["通った"]


def test_人の値の例が値の取り違えを見分けなければ止まる():
    人 = {"0001": {"時間.終業後の打刻": "申請した残業だけ"}}
    # 終業の前に帰る日では 打刻のまま と見分けない
    E3 = {**_E3, "区間": "労働 8:50-17:00、休憩 12:00-13:00", "期待": "労働=7:00・休憩=1:00・法定外残業=0:00・遅刻早退=1:00"}
