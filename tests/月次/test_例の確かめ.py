def _確かめる(例, **タブの上書き):
    return 確かめる(支給月, C, 作._タブ(**タブの上書き), 例, 法の線=作る_集計.法の線, 段=月次.段, 繋=月次.繋)


def _例(*上書き):
    """作._例() の行を {列: 値} で上書きした並び（上書き[i] は i 番目の例の行へ）。"""
    見出し, *行 = 作._例()
    行 = [dict(zip(見出し, r)) for r in 行]
    for i, d in enumerate(上書き):
        行[i].update(d)
    return 行


def _回す(tmp_path, 例):
    return 作.確定して回す(支給月, C, 作._タブ(), [{"部品": "Excel出勤簿", "値": 作._出勤簿()}], 法の線=作る_集計.法の線,
                     置き場=作る_計算.置き場(tmp_path), 例=例)


