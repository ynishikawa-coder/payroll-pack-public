def _中抜けの出勤簿(名):
    """作._出勤簿() の 名 の人だけ 2027-02-03 を 9:00-12:00・13:00-18:00 の 2 組（休憩の欄は空）にした出勤簿。"""
    d = 作._出勤簿()
    行 = [[*r[:5], "", "", r[5]] for r in d["行"]]
