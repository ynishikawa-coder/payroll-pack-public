"""締めの記録の判断の口（月次/締めの関所.py）。殻が持っていた締める・締め直す・締めた時の版の判断をここで照らす。作り物の値だけ。

根（2026-11-24）: 型が古い台帳で締めるか・締め直すの答えが同じ会社・同じ回か・締めた時の版はどれか を殻（事務所の側の口）が
自分で決めていた＝パックの版を上げても殻の判断は古いまま。判断をパックの口 1 つに寄せ、殻は台帳と決定DB を読み書きするだけにした。
"""
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parent.parent.parent
口 = 根 / "月次" / "締めの関所.py"
_s = importlib.util.spec_from_file_location("締めの関所_試験", 口)
関 = importlib.util.module_from_spec(_s)
_s.loader.exec_module(関)

C, M = "作り物の会社", "2000.01支給"
見出し = ["会社", "支給月", "NO", "氏名", "状態", "締めた日", "締めた人"]


def _行(*NO):
    return [{"会社": C, "支給月": M, "NO": n, "状態": "締まった"} for n in NO]


def _記録(版たち: dict | None = None, 列=True):
    h = 見出し + (["パックの版"] if 列 else [])
    rows = [[C, M, n, "", "締まった", "", ""] + ([v] if 列 else []) for n, v in (版たち or {}).items()]
    return [h, *rows]


def _cli(何, x):
    r = subprocess.run([sys.executable, "-I", str(口), 何], input=json.dumps(x, ensure_ascii=False),
                       capture_output=True, text=True, cwd=根)
    return r.returncode, json.loads(r.stdout)


# ---- 締める
def test_今の版を押して締める():
    got = 関.締める(_行("0001"), _記録(), 版="v9.9.9", 型に列=True)
    assert got["赤"] == [] and got["書く行"][0]["パックの版"] == "v9.9.9" and got["パックの版"] == "v9.9.9"


def test_型が古い台帳では締めない():
    # 口の約束: 型に パックの版 の列が在るのに台帳に無い＝寄せてから締める（版を書かずに締めない）
    got = 関.締める(_行("0001"), _記録(列=False), 版="v9.9.9", 型に列=True)
    assert "型が古い台帳" in got["赤"][0] and "書く行" not in got


def test_同じ月を別の版で締めた行が在れば締めない():
    got = 関.締める(_行("0002"), _記録({"0001": "v0.0.1"}), 版="v9.9.9", 型に列=True)
    assert "月を版で割らない" in got["赤"][0] and "v0.0.1" in got["赤"][0]


def test_同じ版で締めた行の続きは締める():
    got = 関.締める(_行("0002"), _記録({"0001": "v9.9.9"}), 版="v9.9.9", 型に列=True)
    assert got["赤"] == []


@pytest.mark.parametrize("行, 訳", [
    ([], "1 行以上"),
    ([{"会社": C, "支給月": M, "NO": ""}], "鍵"),
    ([{"会社": C, "支給月": M, "NO": "1", "パックの版": "v1"}], "パックの版 を書かない"),
    ([{"会社": C, "支給月": M, "NO": "1"}, {"会社": "別の作り物の会社", "支給月": M, "NO": "2"}], "1社・1支給月"),
])
def test_締める行の形が崩れていれば締めない(行, 訳):
    assert 訳 in 関.締める(行, _記録(), 版="v9.9.9", 型に列=True)["赤"][0]


def test_置いたパックの型には版の列が在る():
    assert 関.型に版の列が在るか() is True


def test_口から呼んでも型が古い台帳を止める():
    rc, out = _cli("締める", {"行": _行("0001"), "締めの記録": _記録(列=False)})
    assert rc == 0 and "型が古い台帳" in out["赤"][0]


# ---- 締め直す（オーナーの答え）
URL = "https://www." + "notion" + ".so/作り物-" + "0" * 31 + "1"   # 公開の検査に当たる字を置かない（作り物の行）


答え = f"決定DB 2000-01-31 {URL}"


def test_答えは決定DBの行の形だけ():
    assert 関.答えの行(f"決定DB 2000-01-31 {URL}") == {"赤": [], "行": "0" * 31 + "1"}
    assert "オーナーが選んだ時だけ" in 関.答えの行("今の版で出すと言われた")["赤"][0]


@pytest.mark.parametrize("文", [
    f"会社: 別の作り物の会社 支給月: {M} 範囲: 今の版で出す",     # 別の会社
    f"会社: {C} 支給月: 2000.02支給 範囲: 今の版で出す",            # 別の回
    f"会社: {C} 支給月: {M} 範囲: 締めた時の版で出す",              # 別の範囲
])
def test_別の会社や回の答えで締め直さない(文):
    # 口の約束: 決定DB の行の字に同じ会社・同じ支給月・範囲 今の版で出す が無ければ締め直さない
    got = 関.締め直す(C, M, 答え, 文, _記録({"0001": "v0.0.1"}), 版="v9.9.9")
    assert "別の会社・別の回・別の範囲の答え" in got["赤"][0] and "書く行" not in got


def test_同じ会社と回の答えなら行を全部今の版へ():
    文 = f"会社: {C}\n支給月: {M}\n範囲: 今の版で出す"
    got = 関.締め直す(C, M, 答え, 文, _記録({"0001": "v0.0.1", "0002": "v0.0.1"}), 版="v9.9.9")
    assert got["赤"] == [] and {r["パックの版"] for r in got["書く行"]} == {"v9.9.9"} and len(got["書く行"]) == 2


def test_型が古い台帳は締め直さない():
    文 = f"会社: {C} 支給月: {M} 範囲: 今の版で出す"
    assert "型が古い台帳" in 関.締め直す(C, M, 答え, 文, _記録(列=False), 版="v9.9.9")["赤"][0]


@pytest.mark.parametrize("答えの字", ["", "今の版で出すと言われた", None])
def test_決定DBの行の形でない答えでは締め直さない(答えの字):
    # 口の約束: 答えが決定DB の行の形でなければ、文が同じ会社・同じ回でも締め直さない
    文 = f"会社: {C} 支給月: {M} 範囲: 今の版で出す"
    got = 関.締め直す(C, M, 答えの字, 文, _記録({"0001": "v0.0.1"}), 版="v9.9.9")
    assert "オーナーが選んだ時だけ" in got["赤"][0] and "書く行" not in got


# ---- 出荷の口の 締めた時の版で回す
def test_締めた時の版で回すのは答えが在る月の給与だけ():
    assert 関.締めた時の版で回すか("", "月")
    assert 関.締めた時の版で回すか("受付-1", "賞与")
    assert 関.締めた時の版で回すか("受付-1", "月") == []


@pytest.mark.parametrize("版たち, 訳", [
    ({}, "行が無い"),
    ({"0001": ""}, "版が無い行"),
    ({"0001": "v0.0.1", "0002": "v0.0.2"}, "行で割れている"),
])
def test_締めた時の版が決まらなければ回さない(版たち, 訳):
    assert 訳 in 関.締めた時の版の印(C, M, _記録(版たち))["赤"][0]


def test_締めた時の版を返す():
    assert 関.締めた時の版の印(C, M, _記録({"0001": "v0.0.1", "0002": "v0.0.1"})) == {"赤": [], "版": "v0.0.1"}


@pytest.mark.parametrize("何, 入力", [
    ("知らない", "{}"),                                                       # 知らない口
    ("締める", "{ 崩れた"),                                                   # JSON でない
    ("締める", "[]"),                                                         # 入力が表でない
    ("締める", json.dumps({"行": [{"会社": C, "支給月": M, "NO": "1"}], "締めの記録": [見出し, 5]})),  # 記録の行が列でない
    ("締めた時の版", json.dumps({"会社": C, "支給月": M, "締めの記録": "表"})),  # 締めの記録が表でない
])
def test_形の崩れた入力は拒む(何, 入力):
    # 口の約束: 形の崩れた入力はどの崩れでも 拒む と終わりの値 2（traceback と終わりの値 1 で抜けない）
    r = subprocess.run([sys.executable, "-I", str(口), 何], input=入力, capture_output=True, text=True, cwd=根)
    assert r.returncode == 2 and "拒む" in json.loads(r.stdout)
