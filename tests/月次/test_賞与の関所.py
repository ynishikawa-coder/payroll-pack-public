def _確かめた日を消す(例):
    見出し, *行 = 例
    行 = [list(r) for r in 行]
    行[0][見出し.index("確かめた日")] = ""
    return [見出し, *行]


def _確かめた人を替える(例, 人):
    見出し, *行 = 例
    return [見出し, *[[*r[:見出し.index("確かめた人")], 人, *r[見出し.index("確かめた人") + 1:]] for r in 行]]


def _期待を違える(例):
    見出し, *行 = 例
    行 = [list(r) for r in 行]
    i = next(n for n, r in enumerate(行) if r[見出し.index("種類")] == "月")
    行[i][見出し.index("期待")] = "締めの始め=2027-01-31・締めの終わり=2027-02-27"
    return [見出し, *行]


@pytest.mark.parametrize("名, 例", [
    ("例を渡さない", None),
    ("給与のルール.md に例の表が無い", 作._例()[:1]),
    ("例が合わない", _期待を違える(作._例())),
    ("確かめた日が無い", _確かめた日を消す(作._例())),
    ("確かめの出所が無い", _確かめた人を替える(作._例(), "作り物 確かめる人")),
    ("AI の名だけ", _確かめた人を替える(作._例(), "Claude")),
])
def test_例を通らない会社の賞与は誰も出ず_証明は通らない(tmp_path, 名, 例):
    o = _回す(tmp_path, 例=例)
    assert not o["例の確かめ"]["通った"], 名
    assert all(v == set() for v in _出た人(o).values()), (名, _出た人(o))
    assert {a["NO"] for a in o["外した人"]} == set(人たち)
    assert o["問い"]["例"] and all(q["反映先"] == "1_決まり/給与のルール.md の例の表" for q in o["問い"]["例"])
    for d in [o["取り込み"], *o["支給控除一覧"]]:
        r = 証明.照らす(d, o["証明"][d.物], 入力=_元(例))
        assert not r["通す"] and any("例の照らしを通っていない" in x for x in r["赤"]), (名, r)


def test_仮が残る人は出ず_残りの人は証明付きで出る(tmp_path):
    # 段の解決の仮（変更の記録の 確かめ＝仮）の 0002 と、芯の仮（月額表の道で計算期間が無い）の 0003
    o = _回す(tmp_path, タブ=作._タブ(変更の記録=作._記録),
             前月の課税対象額={(C, "0001"): 280000, (C, "0002"): 280000})
    assert {a["NO"] for a in o["外した人"]} == {"0002", "0003"}
    assert all(v == {"0001"} for v in _出た人(o).values()), _出た人(o)
    d = o["取り込み"]
    p = o["証明"][d.物]
    assert p["関所"] == {"通った": True, "外した人": 2}
    入 = _元(タブ=作._タブ(変更の記録=作._記録))
    入["賞与の引数"]["前月の課税対象額"] = {(C, "0001"): 280000, (C, "0002"): 280000}
    assert 証明.照らす(d, p, 入力=入)["通す"]
    # 注入: 賞与を回す に渡した引数（前月の課税対象額）と違う元では通さない（計算が読む賞与の引数も証明が結ぶ）
    r = 証明.照らす(d, p, 入力=_元(タブ=作._タブ(変更の記録=作._記録)))
    assert not r["通す"] and any("入力の指紋が合わない（賞与の引数）" in x for x in r["赤"]), r


def test_月と賞与を取り違えた証明は通さない(tmp_path):
    o = _回す(tmp_path)
    d = o["取り込み"]
    p = o["証明"][d.物]
    入 = _元()
    for 上書き, 訳 in (({"回": "月"}, "回 月 が物 賞与の取り込み と合わない"),
                     ({"回": ""}, "回 が無い"), ({"回": "冬"}, "どれでもない"),
                     ({"名": "取り込み_C1_2027-02_v1"}, "名が違う")):
        r = 証明.照らす(d, {**p, **上書き}, 入力=入)
        assert not r["通す"] and any(訳 in x for x in r["赤"]), (上書き, r)
    # 支給控除一覧（物では月と見分けない）は 回 で直した支給月の字（出口/名と版.py の 出す支給月）で証明の支給月と名を照らす
    s = o["支給控除一覧"][0]
    q = o["証明"][s.物]
    r = 証明.照らす(s, {**q, "回": "月"}, 入力=入)
    assert not r["通す"] and any("回 月 と合わない" in x for x in r["赤"]), r
    r = 証明.照らす(s, {**q, "回": "月", "支給月": "2027-02"}, 入力=入)   # 証明の回と支給月を揃えて変えても名で止まる
    assert not r["通す"] and any("名" in x and "取り違え" in x for x in r["赤"]), r
    # 付ける側も、回が物と合わなければ付けない（止める）
    with pytest.raises(ValueError, match="証明を付けない"):
        証明.証明を付ける(d, 会社=C, 支給月=支給月, 回="月", 外した人=0, 例の結果=o["例の確かめ"], 入力=入)


