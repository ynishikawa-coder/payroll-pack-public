def test_mdへ書いた行は照らすで合う_節の見出しつきの反映先も():
    """書き戻しが md へ書く行は 質問と回答.md_の答えの行 の印の行＝照らす（反映済み=済 を書く唯一の門）が合うと読む。"""
    答 = 書.質問と回答
    for 反映先, 何を in (("給与のルール.md", "欠勤"), ("給与のルール.md#欠勤", "半日の扱い")):
        md = {"給与のルール.md": "## 欠勤\n- 引く\n## 遅刻\n- 引く\n"}
        行 = 例.例の振り分け("Q-作-35", 顧, 反映先=反映先, 何を=何を, 値="半日は引かない")
        r = 書.振り分けの書き戻し([行], 顧, 月, 今日="2099-02-01", md=md)
        assert r["赤"] == [] and r["書いた"] == ["Q-作-35"], (反映先, r)
        後 = 書.手順を当てる({("md", k): v for k, v in md.items()}, r["手順"])[("md", "給与のルール.md")]
        f = 答.振り分け(**{k: v for k, v in 行.items()})
        assert 答.照らす(f, {"会社": {顧: {"給与のルール.md": 後}}}), (反映先, 後)
        assert not 答.照らす(f, {"会社": {顧: md}})   # 書く前は合わない
        assert 後.index("⟦答え:Q-作-35") < 後.index("## 遅刻")   # 欠勤 の節の中に書く


def test_見出しでない何をの答えは答えの印の節へ印だけを足し_照らすで合う():
    """何を が md の見出しでなく 反映先 に #<見出し> も無い答え: 決まりの文に触らず `# 答えの印` の節へ印だけを足す。"""
    答 = 書.質問と回答
    元 = "## 欠勤\n- 引く\n## 遅刻\n- 引く\n"
    f1 = 例.例の振り分け("Q-作-38", 顧, 反映先="給与のルール.md", 何を="作り物の扱い", 値="半日は引かない")
    r = 書.振り分けの書き戻し([f1], 顧, 月, 今日="2099-02-01", md={"給与のルール.md": 元})
    assert r["赤"] == [] and r["書いた"] == ["Q-作-38"], r
    後 = 書.手順を当てる({("md", "給与のルール.md"): 元}, r["手順"])[("md", "給与のルール.md")]
