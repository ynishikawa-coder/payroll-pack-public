def test_照らすは保険料の月の記録を徴収の月で直して比べ_比べられなければ合わない():
    答 = 書.質問と回答
    照 = lambda 効く月, マ: 答.照らす(答.振り分け(**_人の振り("Q-作-52", 効く月, 何を=_列, 値="100000")), {"マスタ": マ})
    マ = _人マ((_列, "90000", "100000", "2099.04分"))
    assert not 照("2099-02", マ)          # 徴収の月が社員にも会社にも無い＝比べられない＝済にしない（書き戻しは人が反映する）
    assert not 照("2099-05", マ)
    人 = lambda 徴収: {**マ, "社員": [[*マ["社員"][0], "社保.徴収の月"], [*マ["社員"][1], 徴収]]}
    assert not 照("2099-02", 人("翌月徴収"))   # 支給月 2099-02 の保険料の月は 2099-01 ≠ 2099.04分
    assert 照("2099-05", 人("翌月徴収"))       # 支給月 2099-05 → 保険料の月 2099-04
    assert 照("2099-04", 人("当月徴収")) and not 照("2099-05", 人("当月徴収"))
    assert not 照("2099-05", 人("いつか"))       # 語の外
    会 = {**マ, "会社": [["顧客ID", "項目", "今の値", "適用開始"], [顧, "社保.徴収の月", "翌月徴収", ""]]}
    assert 照("2099-05", 会) and not 照("2099-04", 会)   # 社員に無ければ マスタ/会社 の項目の行
    印なし = _人マ((_列, "90000", "100000", "2099.04支給"))
    assert not 照("2099-05", {**印なし, "社員": 人("翌月徴収")["社員"]})   # 印（分）の無い記録＝比べられない


