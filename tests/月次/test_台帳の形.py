"""月次 の 台帳 の形（月次/台帳の形.py）: 型の台帳のタブの形（1 行目が型の見出し）で返す。作り物の値だけ。"""
import importlib.util
import sys
from decimal import Decimal
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
_spec = importlib.util.spec_from_file_location("月次_台帳の形_試験", 根 / "月次" / "台帳の形.py")
形 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(形)

from 芯.集計.形 import 出す語  # noqa: E402


def _行(NO, 項目, 値, 状態="確定"):
    return {"支給月": "2027-02", "会社": "作り物の会社", "NO": NO, "項目": 項目, "値": 値, "状態": 状態, "出所": ""}


def test_型の人ごとの列は芯が出す語を全部持つ():
    # 芯/集計 が出す語（月の語と会社の数え方の語）が 1 つでも型に無いと、月次 が止まり殻が書けない（語を足したら型の版を上げる）
    h = 形.見出し("人ごと")
    assert h[:5] == ["会社", "支給月", "NO", "氏名", "状態"] and h[5:] == [語 for 語, _ in 出す語]


def test_会社の数え方の残業も台帳に残る():
    # 割増.残業の数え方＝1日の所定超え の人の払う残業の語（前は「型の列に無い月の語」で月次が止まった）
    表 = 形.人ごとの表([_行("1", "法定外残業", 600), _行("1", "残業（会社の数え方）", 900), _行("1", "60 時間超（会社の数え方）", 0),
                      _行("2", "法定外残業", 60)])
    行 = {r[2]: dict(zip(表[0], r)) for r in 表[1:]}
    assert 行["1"]["残業（会社の数え方）"] == "900" and 行["1"]["60 時間超（会社の数え方）"] == "0"
    assert 行["2"]["残業（会社の数え方）"] == ""      # 法定どおりの人は空


def test_人ごとは1人1行で型の見出しの並び():
    表 = 形.人ごとの表([_行("2", "出勤日数", Decimal("18")), _行("2", "総労働", 8640), _行("10", "出勤日数", Decimal("17.5")),
                      _行("10", "年休を取った日", "2027-02-03"), _行("10", "年休を取った日", "2027-02-04")],
                     人の状態=[{"支給月": "2027-02", "会社": "作り物の会社", "NO": "10", "状態": "仮"}],
                     氏名={"2": "作り物 二郎"})
    h = 表[0]
    assert h == 形.見出し("人ごと")
    行 = {r[2]: dict(zip(h, r)) for r in 表[1:]}
    assert [r[2] for r in 表[1:]] == ["2", "10"]                      # NO の数の順
    assert 行["2"]["支給月"] == "2027.02支給" and 行["2"]["氏名"] == "作り物 二郎" and 行["2"]["状態"] == "確認済"
    assert 行["2"]["出勤日数"] == "18" and 行["2"]["総労働"] == "8640" and 行["2"]["深夜"] == ""
    assert 行["10"]["状態"] == "仮" and 行["10"]["出勤日数"] == "17.5"
    assert 行["10"]["年休を取った日"] == "2027-02-03、2027-02-04"


def test_行が仮なら人の状態に無くても仮():
    表 = 形.人ごとの表([_行("1", "出勤日数", 0, 状態="仮")])
    assert dict(zip(表[0], 表[1]))["状態"] == "仮"


def test_型に無い語と列は止める():
    with pytest.raises(形.台帳の形の誤り, match="型の列に無い月の語"):
        形.人ごとの表([_行("1", "作り物の語", 1)])
    with pytest.raises(形.台帳の形の誤り, match="型の列に無い値"):
        形.台帳へ書く形(月の変動=[{"会社": "作り物の会社", "支給月": "2027-02", "NO": "1", "項目": "作り物手当", "値": "1",
                                "作り物の列": "x"}])


def test_入口の行は型の並びへ_支給月は型の書き方():
    o = 形.台帳へ書く形(月の変動=[{"確認": "確認済", "値": "1000", "項目": "作り物手当", "NO": "1", "支給月": "2027-02",
                                 "会社": "作り物の会社", "原本の名前": "作り物.pdf", "_中の印": 1}])
    assert o["月の変動"] == [形.見出し("月の変動"), ["作り物の会社", "2027.02支給", "1", "作り物手当", "1000", "作り物.pdf", "確認済"]]
    assert set(o) == {"勤怠", "勤怠の区間", "月の変動", "人ごと", "人ごとの支給控除"}
    assert all(v == [形.見出し(k)] for k, v in o.items() if k != "月の変動")
