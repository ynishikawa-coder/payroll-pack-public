def test_確定した勤怠は書いて読むと表ABに戻る():
    表 = 形.勤怠の表たち(確定=True, 勤怠=[_日(時刻の無い休憩=60, 直した訳="問い:Q202702-01")], 勤怠の区間=[_区()],
                     氏名={"1": "作り物 一郎"})
    assert 表["確定した勤怠"][0] == 形.見出し("確定した勤怠")
    行 = dict(zip(表["確定した勤怠"][0], 表["確定した勤怠"][1]))
    assert 行["支給月"] == "2027.02支給" and 行["出勤の時刻"] == "9:00" and 行["退勤の時刻"] == "18:00" and 行["直した訳"] == "問い:Q202702-01"
    A, B = 形.確定した勤怠を読む(表["確定した勤怠"], 表["確定した勤怠の区間"])
    assert A == [{**_日(時刻の無い休憩=60)}]                  # 写しの列・直した訳 は芯へ渡さない。分は整数に戻る
    assert B == [_区()]


