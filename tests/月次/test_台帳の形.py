# ---- 列名の dict の並び（行たち の形）で渡しても、型の見出しと照らす（2 次元の並びと同じ関所） ----
def _dictの表(表):
    return 形.行たち(表)


def test_確定した勤怠はdictの並びでも2次元と同じに読める():
    # 確定した勤怠を読む を dict の並びで呼ぶ所（行たち の形）が壊れない＝2 次元と同じ A・B
    表 = 形.勤怠の表たち(確定=True, 勤怠=[_日(時刻の無い休憩=60, 直した訳="問い:Q202702-01")], 勤怠の区間=[_区()],
                     氏名={"1": "作り物 一郎"})
    二次元 = 形.確定した勤怠を読む(表["確定した勤怠"], 表["確定した勤怠の区間"])
    辞書 = 形.確定した勤怠を読む(_dictの表(表["確定した勤怠"]), _dictの表(表["確定した勤怠の区間"]))
    assert 辞書 == 二次元 and 辞書[0] == [_日(時刻の無い休憩=60)] and 辞書[1] == [_区()]
    # "_" で始まる内の鍵は見出しに数えない
    内つき = [{**r, "_行": i} for i, r in enumerate(_dictの表(表["確定した勤怠"]), 2)]
    assert 形.確定した勤怠を読む(内つき, _dictの表(表["確定した勤怠の区間"])) == 二次元


@pytest.mark.parametrize("どれ, 壊す", [
    ("勤怠", lambda r: {**r, "作り物の列": ""}),                                       # 型に無い列（値が空でも）
    ("勤怠", lambda r: {c: v for c, v in r.items() if c != "直した訳"}),               # 型の列が無い（前の版）
    ("勤怠", lambda r: {("訳" if c == "直した訳" else c): v for c, v in r.items()}),    # 列の名が違う
    ("区間", lambda r: {c: v for c, v in r.items() if c != "時刻の出所"}),
])
def test_確定した勤怠のdictの見出しが型と違えば止める(どれ, 壊す):
    表 = 形.勤怠の表たち(確定=True, 勤怠=[_日()], 勤怠の区間=[_区()])
    勤怠, 区間 = _dictの表(表["確定した勤怠"]), _dictの表(表["確定した勤怠の区間"])
    if どれ == "勤怠":
        勤怠 = [壊す(r) for r in 勤怠]
    else:
        区間 = [壊す(r) for r in 区間]
    with pytest.raises(形.台帳の形の誤り, match="見出しが型と違う"):
        形.確定した勤怠を読む(勤怠, 区間)
