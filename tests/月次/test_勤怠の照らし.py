会社, 月 = "作り物の会社", "2027.02支給"


def _日(NO, 日付, 種類="勤務", 出="9:00", 退="18:00", 休="1:00", 労="8:00", **他):
    r = {c: "" for c in 照.日の列}
    r |= {"会社": 会社, "支給月": 月, "NO": NO, "氏名": f"作り物{NO}", "勤怠の表記": f"作り物{NO}", "日付": 日付,
          "日の種類": 種類}
    if 種類 in ("勤務", "休日勤務"):
        r |= {"出勤の時刻": 出, "退勤の時刻": 退, "休憩の合計": 休, "労働の合計": 労, "働いた場所": "事業所"}
    if 種類 == "休暇":
        r |= {"休暇の種類": "年休", "休暇の単位": "全日"}
    return r | 他


def _間(NO, 日付, 番, 種別, 始, 終):
    return {"会社": 会社, "支給月": 月, "NO": NO, "氏名": f"作り物{NO}", "日付": 日付, "区間の番号": str(番),
            "区間の種別": 種別, "始め": 始, "終わり": 終, "時刻の出所": "打刻"}


def _月():
    """誤りの無い作り物の月: 2 人×3 日。"""
    日 = [_日("1", "2027-01-05"), _日("1", "2027-01-06"), _日("1", "2027-01-07", "休日"),
         _日("2", "2027-01-05"), _日("2", "2027-01-06", "休暇"), _日("2", "2027-01-07", "欠勤")]
    間 = []
    for NO, d in (("1", "2027-01-05"), ("1", "2027-01-06"), ("2", "2027-01-05")):
        間 += [_間(NO, d, 1, "労働", "9:00", "18:00"), _間(NO, d, 2, "休憩", "12:00", "13:00")]
    確定 = [r | {"直した訳": ""} for r in copy.deepcopy(日)]
    確定の間 = [r | {"直した訳": ""} for r in copy.deepcopy(間)]
    return 日, 間, 確定, 確定の間


def _照らす(日, 間, 確定, 確定の間, **kw):
    return 照.照らす(日, 間, 確定, 確定の間, **kw)


def _種類(結果, NO=None):
    return {x["種類"] for x in 結果.挙がり if NO is None or x["NO"] == NO}


def _引く(行たち, NO, 日付, 番=None):
    return next(r for r in 行たち if r["NO"] == NO and r["日付"] == 日付 and (番 is None or r["区間の番号"] == str(番)))


def test_誤りの無い月は何も挙がらない():
    結果 = _照らす(*_月(), 印字の合計={"1": {"総労働": "16:00", "勤務した日": 2}, "2": {"欠勤": 1, "休憩": 60}})
    assert 結果.挙がり == [] and 結果.締めの記録 == []
    assert 結果.通った人 == [(会社, 月, "1"), (会社, 月, "2")]


def test_二次元の表と_YYYY_MM_の支給月も読む():
    日, 間, 確定, 確定の間 = _月()

    def 表(行たち, 列):
        return [list(列)] + [[r.get(c, "") for c in 列] for r in 行たち]
    確定 = [r | {"支給月": "2027-02"} for r in 確定]
    結果 = _照らす(表(日, 照.日の列), 表(間, 照.区間の列), 表(確定, [*照.日の列, "直した訳"]),
                 表(確定の間, [*照.区間の列, "直した訳"]))
    assert 結果.挙がり == []


