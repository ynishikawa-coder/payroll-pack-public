"""答えの書き戻しの口（月次/答えの書き戻し.py）。作り物の値だけ。

- 6 つの先（MD・マスタ・確定した勤怠・その月だけの指示・「分からない」・決まらない先）で、
  手順が返る → 当てると先が変わる → 2 回当てても同じ（2 回目の手順は 0）→ 分からないは開いたまま → 決まらない先は訳つきで止まる。
- 書いた問いは 反映済み が 済 になり、記録に 受付番号・問いの番号・反映先 が残る。
"""
import copy
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
_p = 根 / "月次" / "答えの書き戻し.py"
_s = importlib.util.spec_from_file_location("月次_答えの書き戻し_試験", _p)
戻 = importlib.util.module_from_spec(_s)
_s.loader.exec_module(戻)
口 = 戻.口
形 = 戻.書.形

会社, 月, 台帳の名 = "作り物の会社", "2027.02支給", "台帳_2027"
M, Q = 口.名("マスタ"), 口.名("質問と回答")
_問の見出し = 口.見出し(Q, "質問")


def _表(見出し, *行たち):
    return [list(見出し), *[[str(d.get(c, "")) for c in 見出し] for d in 行たち]]


def _問(番号, 反映先, 回答, **足す):
    return {"会社": 会社, "問いの番号": 番号, "支給月": 月, "質問": "作り物の問い", "回答": 回答, "反映先": 反映先, **足す}


def _受(答え, 印="AAAA"):
    return f"{答え} ／ 受付: R270201-{印}（版 2027.02-v1）"


def _マスタ():
    社員 = _表(口.見出し(M, "社員"), {"会社": 会社, "NO": "1", "氏名": "作り物 一郎", "社保.標準報酬": "200000"},
              {"会社": 会社, "NO": "2", "氏名": "作り物 二郎", "社保.標準報酬": "220000"})
    return {"社員": 社員, "会社": _表(口.見出し(M, "会社")), "変更の記録": _表(口.見出し(M, "変更の記録"))}


def _台帳():
    return {k: [list(形.見出し(k))] for k in ("その月だけの指示", "確定した勤怠", "確定した勤怠の区間")}


def _確定の返り():
    日 = {"会社": 会社, "支給月": "2027-02", "NO": "1", "勤怠の表記": "ひょうき1", "日付": "2027-02-01", "日の種類": "勤務",
         "読み取りの確かめ": "確認済", "原本の名前": "作り物の出勤簿.pdf", "直した訳": "問い:Q202702-03"}
    区 = {"会社": 会社, "支給月": "2027-02", "NO": "1", "日付": "2027-02-01", "区間の番号": "1", "区間の種別": "労働",
         "始め": "10:00", "終わり": "18:00"}
    return 形.勤怠の表たち(確定=True, 勤怠=[日], 勤怠の区間=[区])


def _問たち():
    return _表(_問の見出し,
               _問("Q202702-01", "給与のルール.md#休日と時間外", _受("引かない", "AAAA")),
               _問("Q202702-02", "2_マスタ/社員/社保.標準報酬", _受("240000", "BBBB"), 答えで変わる項目と人="社保.標準報酬、1"),
               _問("Q202702-03", "台帳/確定した勤怠", _受("10 時に来た", "CCCC"), 答えで変わる項目と人="1"),
               _問("Q202702-04", "台帳/その月だけの指示", _受("500", "DDDD"), 答えで変わる項目と人="通勤手当、2"),
               _問("Q202702-05", "2_マスタ/会社/日割.入退社", _受("分からない", "EEEE")),
               _問("Q202702-06", "", _受("引く", "FFFF")))


def _今():
    return {**{(M, k): v for k, v in _マスタ().items()}, **{(台帳の名, k): v for k, v in _台帳().items()},
            (Q, "質問"): _問たち(), ("md", "給与のルール.md"): "# 給与のルール\n\n## 休日と時間外\n- 前からの決まり\n\n## 欠勤\n- 引く\n"}


def _回す(今):
    return 戻.書き戻しの手順(今[(Q, "質問")], 会社, 月, 今日="2027-02-05",
                       マスタ={k[1]: v for k, v in 今.items() if k[0] == M},
                       md={k[1]: v for k, v in 今.items() if k[0] == "md"},
                       台帳={k[1]: v for k, v in 今.items() if k[0] == 台帳の名}, 台帳の名=台帳の名,
                       確定した勤怠の返り=_確定の返り(), 原本のリンク={"作り物の出勤簿.pdf": "作り物://原本/1"})


def _列(格子, 列):
    i = 格子[0].index(列)
    return [r[i] for r in 格子[1:]]


def test_6つの先で手順が返り当てると変わり2回目は同じ():
    今 = _今()
    o = _回す(今)
    assert o["手順"] and {x["する"] for x in o["手順"]} <= set(戻.手順の種類)
    後 = 戻.手順を当てる(今, o["手順"])

    # MD: 節の終わりに 1 行・ほかの節は触らない
    md = 後[("md", "給与のルール.md")]
    assert "- 引かない（出所: 問い:Q202702-01・受付 R270201-AAAA）\n\n## 欠勤\n- 引く\n" in md
    # マスタ 社員: NO 1 だけ・変更の記録に前→後
    assert _列(後[(M, "社員")], "社保.標準報酬") == ["240000", "220000"]
    記 = 口.格子を行へ(後[(M, "変更の記録")])
    assert [(r["NO"], r["項目"], r["前の値"], r["新しい値"], r["問いの番号"]) for r in 記] == \
        [("1", "社保.標準報酬", "200000", "240000", "Q202702-02")]
    # 確定した勤怠: 答えの日の行が入る
    assert _列(後[(台帳の名, "確定した勤怠")], "直した訳") == ["問い:Q202702-03"]
    assert _列(後[(台帳の名, "確定した勤怠")], "氏名") == ["作り物 一郎"]
    # その月だけの指示: 1 行（氏名は社員から）
    指 = 口.格子を行へ(後[(台帳の名, "その月だけの指示")])
    assert [(r["NO"], r["氏名"], r["項目"], r["値"], r["問いの番号"]) for r in 指] == \
        [("2", "作り物 二郎", "通勤手当", "500", "Q202702-04")]
    # 反映済み: 書いた 4 つだけ 済
    問 = 後[(Q, "質問")]
    assert dict(zip(_列(問, "問いの番号"), _列(問, "反映済み"))) == {
        "Q202702-01": "済", "Q202702-02": "済", "Q202702-03": "済", "Q202702-04": "済", "Q202702-05": "", "Q202702-06": ""}
    # 記録: どの受付番号をどこへ
    先 = {(r["受付番号"], r["反映先"]) for r in o["記録"]}
    assert {("R270201-AAAA", "給与のルール.md#休日と時間外"), ("R270201-BBBB", "2_マスタ/社員/社保.標準報酬"),
            ("R270201-CCCC", "台帳/確定した勤怠"), ("R270201-DDDD", "台帳/その月だけの指示")} <= 先
    assert not {r["受付番号"] for r in o["記録"]} & {"R270201-EEEE", "R270201-FFFF"}

    # 分からない は開いたまま・先が空 は訳つきで止まる
    assert o["開いたまま"] == ["Q202702-05"]
    assert [(x["問いの番号"], x["訳"]) for x in o["止める"]] == [("Q202702-06", "答えがあるのに反映先が空＝どこへ書くか決まらない")]
    assert o["赤"] == ["Q202702-06 : 答えがあるのに反映先が空＝どこへ書くか決まらない"]

    # 2 回目: 手順 0・当てても同じ
    o2 = _回す(後)
    assert o2["手順"] == [] and o2["記録"] == []
    assert 戻.手順を当てる(後, o2["手順"]) == 後
    assert o2["開いたまま"] == ["Q202702-05"] and o2["止める"] == o["止める"]


def test_選べる値の外と見出しの無いmdと渡されていない先は書かずに止める():
    問 = _表(_問の見出し,
             _問("Q202702-11", "2_マスタ/勤務の型/時間.制度", _受("作り物の制度"), 答えで変わる項目と人="時間.制度、作り物の型"),
             _問("Q202702-12", "給与のルール.md#無い節", _受("引かない")),
             _問("Q202702-13", "台帳/確定した勤怠", _受("10 時に来た"), 答えで変わる項目と人="1"),
             _問("Q202702-14", "3_月ごと/1_届いた物", _受("原本を送る")))
    型 = _表(口.見出し(M, "勤務の型"), {"会社": 会社, "型の名": "作り物の型", "時間.制度": "通常"})
    o = 戻.書き戻しの手順(問, 会社, 月, 今日="2027-02-05", マスタ={"勤務の型": 型}, md={"給与のルール.md": "## 欠勤\n- 引く\n"},
                      台帳=_台帳(), 台帳の名=台帳の名)
    訳 = {x["問いの番号"]: x["訳"] for x in o["止める"]}
    assert set(訳) == {"Q202702-11", "Q202702-12", "Q202702-13", "Q202702-14"}
    assert "選べる値" in 訳["Q202702-11"] and "無い節" in 訳["Q202702-12"]
    assert "確定した勤怠の返り" in 訳["Q202702-13"] and "原本は書き換えない" in 訳["Q202702-14"]
    assert o["手順"] == [] and len(o["赤"]) == 4


def test_前の答えと食い違う後の答えは書かずに問いへ返す():
    問 = _表(_問の見出し,
             _問("Q202702-21", "2_マスタ/社員/社保.標準報酬", _受("240000"), 答えで変わる項目と人="社保.標準報酬、1"),
             _問("Q202702-22", "2_マスタ/社員/社保.標準報酬", _受("260000", "BBBB"), 答えで変わる項目と人="社保.標準報酬、1"))
    o = 戻.書き戻しの手順(問, 会社, 月, 今日="2027-02-05", マスタ=_マスタ())
    # 前の答え（-21）は書き、後から違う値を答えた -22 は黙って勝たせず問いへ返す（済にしない）
    assert [x["問いの番号"] for x in o["問い"]] == ["Q202702-22"] and o["赤"]
    後 = 戻.手順を当てる({(M, k): v for k, v in _マスタ().items()} | {(Q, "質問"): 問}, o["手順"])
    assert _列(後[(M, "社員")], "社保.標準報酬") == ["240000", "220000"]
    assert dict(zip(_列(後[(Q, "質問")], "問いの番号"), _列(後[(Q, "質問")], "反映済み"))) == {"Q202702-21": "済", "Q202702-22": ""}


def test_口はJSONで回り赤なら2で終わる():
    今 = _今()
    入力 = {"質問の行たち": 今[(Q, "質問")], "会社": 会社, "支給月": 月, "今日": "2027-02-05",
          "マスタ": {k[1]: v for k, v in 今.items() if k[0] == M}, "md": {"給与のルール.md": 今[("md", "給与のルール.md")]},
          "台帳": {k[1]: v for k, v in 今.items() if k[0] == 台帳の名}, "台帳の名": 台帳の名,
          "確定した勤怠の返り": _確定の返り(), "原本のリンク": {"作り物の出勤簿.pdf": "作り物://原本/1"}}
    p = subprocess.run([sys.executable, str(_p)], input=json.dumps(入力, ensure_ascii=False), capture_output=True, text=True)
    assert p.returncode == 2, p.stderr
    out = json.loads(p.stdout)
    assert out["開いたまま"] == ["Q202702-05"] and out["手順"]
    # 決まらない先を除くと 0 で終わる
    入力["質問の行たち"] = copy.deepcopy(入力["質問の行たち"])[:-1]
    p = subprocess.run([sys.executable, str(_p)], input=json.dumps(入力, ensure_ascii=False), capture_output=True, text=True)
    assert p.returncode == 0, p.stdout + p.stderr
