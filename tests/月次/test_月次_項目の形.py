"""支給控除一覧の 項目の形 は口（月次）が芯の行の単位から組む（殻が手で写さない）。作り物の値だけ。

前: 殻が 項目の形 を渡さなければ、書き口が形の無い項目を数のまま書いた（分の項目が 600 のような分の数で出た）。
後: 口が関所へ渡した行の 単位 から組む。殻が渡した形が行の単位と違えば止める。同じ項目の単位が分かれても止める。
"""
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))

import 月次  # noqa: E402
from 出口 import 関所  # noqa: E402

月 = "2026-11"


def _行(no, 項目, 値, 単位):
    return dict(支給月=月, 会社="9", NO=no, 項目=項目, 値=値, 単位=単位, 出所="作り物の原本", 状態="確定", 問いの番号="")


行たち = [_行("0001", "法定外残業", 600, "分"), _行("0001", "基本給", 200000, "円"), _行("0001", "出勤日数", 20, "日"),
        _行("0004", "法定外残業", 90, "分"), _行("0004", "基本給", 210000, "円"), _行("0004", "出勤日数", 21, "日")]


def _取り込み():
    """出口を渡したら 取り込み・支給控除一覧 の両方を作る（片方は止まる）＝取り込みも作り物で渡す。"""
    from 出口.形 import 対応にする
    対応 = 対応にする([{"項目": "基本給", "欄": "基本給", "形": "円", "渡す": True, "受ける": True}])
    return {"道具": "作り物の給与ソフト", "欄の対応": 対応, "時間の書き方": "60進",
            "形": {"名": "作り物の給与ソフト", "鍵の欄": "NO", "氏名の欄": "氏名", "後ろの欄": "メモ", "文字コード": "utf-8",
                  "委託も取り込む": "いいえ"}}


def _一覧(一覧の引数, 行=行たち):
    出口 = {"今ある名": [], "履歴にある名": [], "取り込み": _取り込み(), "支給控除一覧": {"時間の書き方": "60進", **一覧の引数}}
    return 月次._出口へ(関所.通す(行, {}), "9", 月, 出口, {}, (), 項目の単位=月次._項目の単位(行))["支給控除一覧"]


def test_項目の形は行の単位から口が組む():
    assert 月次._項目の単位(行たち) == {"法定外残業": "分", "基本給": "円", "出勤日数": "日"}
    (雇用,) = [x for x in _一覧({}) if x.物 == "支給控除一覧_雇用"]
    assert dict((r[0], r[1]) for r in 雇用.表)["法定外残業"] == "10.00"      # 600 分を 60進 で書く（数のまま 600 でない）


def test_殻の渡した形が行の単位と違えば止める():
    with pytest.raises(ValueError, match="法定外残業"):
        _一覧({"項目の形": {"法定外残業": "円"}})
    assert _一覧({"項目の形": {"法定外残業": "分"}})                          # 同じなら通る


def test_同じ項目の単位が分かれれば止める():
    with pytest.raises(ValueError, match="単位が"):
        月次._項目の単位([*行たち, _行("0005", "法定外残業", 1.5, "日")])
