"""賞与の 1 回の元を型どおりに台帳「賞与の支給一覧」へ置けば、読む口（月次.賞与の元を読む）が 賞与を回す へ渡す形に直して回る。
欠けた元・形の違う元は既定で止まる（注入の試験）。作り物の会社 C1 の値だけ。

根: 賞与だけの元（支給一覧・支給日・前月の課税対象額・前の標準賞与額・計算期間）を置く型が無く、殻の出荷の口は賞与の元を受けられず止まっていた。
"""
import importlib.util
import sys
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("賞与の元_試験_関所", ここ / "test_賞与の関所.py")
関 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(関)

import 月次  # noqa: E402
from 出口 import 証明  # noqa: E402

C, 人たち, 支給月, 支給日 = 関.C, list(関.人たち), 関.支給月, 関.支給日
_版 = 関._版   # 証明のパックの版を試験の版に（autouse の fixture を借りる）


def _列():
    return 月次.台帳の形.見出し("賞与の支給一覧")


def _行(**値):
    h = _列()
    assert not set(値) - set(h)
    return [str(値.get(c, "")) for c in h]


def _表(**上書き):
    """関所の試験が手で渡す元（関._一覧・関._賞与の引数）と同じ中身を、型どおりに台帳の 1 タブに置いた表。"""
    行 = [_行(**{"会社": C, "支給月": 支給月, "NO": NO, "氏名": f"作り物 {NO}", "額": "500000", "支給日": 支給日,
                "前月の課税対象額": "280000", "前の標準賞与額": "0", "原本の名前": "賞与_作り物.xlsx", "パックの版": 関.版,
                **上書き.get(NO, {})})
         for NO in 人たち]
    # 別の会社・別の支給月の行は読まない
    行 += [_行(会社="作り物の別の会社", 支給月=支給月, NO="0001", 額="1", 支給日=支給日, 前月の課税対象額="0", 前の標準賞与額="0",
              原本の名前="x"),
          _行(会社=C, 支給月="2026.12支給", NO="0001", 額="1", 支給日="2026-12-10", 前月の課税対象額="0", 前の標準賞与額="0",
              原本の名前="x")]
    return [_列(), *行]


def test_型どおりの元を読めば手で渡した元と同じに直る():
    o = 月次.賞与の元を読む(_表(), C, 支給月)
    手 = 関._賞与の引数()
    assert o["支給一覧"] == 関._一覧()
    assert o["支給日"] == 手["支給日"]
    assert o["賞与の引数"] == {"前月の課税対象額": 手["前月の課税対象額"], "前の標準賞与額": 手["前の標準賞与額"], "計算期間": {}}


def test_読んだ元で賞与を回すが回り_証明は読んだ元で通る(tmp_path):
    o = 月次.賞与の元を読む(_表(), C, 支給月)
    共 = dict(置き場=関.作る_計算.置き場(tmp_path), 法の線=関.作る_集計.法の線, 出口=関._出口(),
             給与のルール=関.例をMDに(関.作._例()))
    タブ = 関.作._タブ()
    r = 月次.賞与を回す(支給月, C, タブ, o["支給一覧"], 支給日=o["支給日"], **o["賞与の引数"], **共)
    assert r["例の確かめ"]["通った"] and r["外した人"] == []
    assert all(v == set(人たち) for v in 関._出た人(r).values()), 関._出た人(r)
    # 手で元を渡した回と同じ表が出る（読む口は元の中身を変えない）
    手 = 関._回す(tmp_path / "手")
    assert r["取り込み"].表 == 手["取り込み"].表
    # 殻の出荷の口が組む計算の元（月次.計算の元・読んだ元のまま）で照らすが通す
    元 = 月次.計算の元(タブ, (), 共["給与のルール"], 支給一覧=o["支給一覧"], 法の線=共["法の線"],
                  賞与の引数={"支給日": o["支給日"], **o["賞与の引数"]})
    for d in [r["取り込み"], *r["支給控除一覧"]]:
        assert 証明.照らす(d, r["証明"][d.物], 入力=元) == {"通す": True, "赤": []}


def test_前月の給与なしと計算期間を読む():
    o = 月次.賞与の元を読む(_表(**{人たち[0]: {"前月の課税対象額": "前月の給与なし", "計算期間の始め": "2026-08-01",
                                            "計算期間の終わり": "2027-01-31"}}), C, 支給月)
    a = o["賞与の引数"]
    # 前月の給与なしは値 None で置く（鍵を落とさない＝芯は鍵の無い人を仮にする）
    assert a["前月の課税対象額"][(C, 人たち[0])] is None and a["前月の課税対象額"][(C, 人たち[1])] is not None
    assert a["計算期間"] == {(C, 人たち[0]): {"始め": "2026-08-01", "終わり": "2027-01-31"}}


_一 = 人たち[0]


@pytest.mark.parametrize("名, 上書き, 語", [
    ("額が空", {_一: {"額": ""}}, "額"),
    ("額がカンマつき", {_一: {"額": "500,000"}}, "額"),
    ("支給日が空", {_一: {"支給日": ""}}, "支給日"),
    ("支給日が無い日", {_一: {"支給日": "2027-02-30"}}, "支給日"),
    ("支給日が行で違う", {_一: {"支給日": "2027-02-25"}}, "支給日が行で違う"),
    ("支給日が支給月の月でない", {n: {"支給日": "2027-03-10"} for n in 人たち}, "取り違え"),
    ("前月の課税対象額が空", {_一: {"前月の課税対象額": ""}}, "前月の課税対象額"),
    ("前の標準賞与額が空", {_一: {"前の標準賞与額": ""}}, "前の標準賞与額"),
    ("計算期間が片方だけ", {_一: {"計算期間の始め": "2026-08-01"}}, "計算期間"),
    ("計算期間が逆さ", {_一: {"計算期間の始め": "2027-01-31", "計算期間の終わり": "2026-08-01"}}, "計算期間"),
    ("原本の名前が空", {_一: {"原本の名前": ""}}, "原本の名前"),
    ("NO が空", {_一: {"NO": ""}}, "NO が空"),
])
def test_元が欠けたり形が違えば止まる(名, 上書き, 語):
    with pytest.raises(月次.賞与の元.賞与の元の誤り, match=語):
        月次.賞与の元を読む(_表(**上書き), C, 支給月)


def test_行が無い_重なる_表の形が違えば止まる():
    誤り = 月次.賞与の元.賞与の元の誤り
    with pytest.raises(誤り, match="行が無い"):
        月次.賞与の元を読む([_列()], C, 支給月)
    with pytest.raises(誤り, match="行が無い"):
        月次.賞与の元を読む(_表(), C, "2027.06支給")
    表 = _表()
    with pytest.raises(誤り, match="2 つある"):
        月次.賞与の元を読む([*表, 表[1]], C, 支給月)
    with pytest.raises(誤り, match="見出しが型と違う"):
        月次.賞与の元を読む([[*_列()[:-1]], *[r[:-1] for r in 表[1:]]], C, 支給月)
    with pytest.raises(誤り, match="get_values"):
        月次.賞与の元を読む([dict(zip(_列(), r)) for r in 表[1:]], C, 支給月)
    with pytest.raises(誤り, match="YYYY.MM支給"):
        月次.賞与の元を読む(表, C, "2027-02")

