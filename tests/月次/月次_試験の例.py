"""試験の例の行（前のマスタ「例」と同じ列の作り物）を 給与のルール.md の字にする（月次.月を回す・賞与を回す は MD の字だけから例を読む）。"""
import 月次


def 例をMDに(例) -> str | None:
    if 例 is None:
        return None
    列 = 月次.例の確かめ.MDの例の列
    md = ["# 給与のルール（作り物）", ""]
    for i, e in enumerate(月次.例の確かめ.行たち(例)):
        # 決まり の升は例の 決まり の字のまま（名だけ）。見出しは例の 見出し（無ければ `例 i`）
        見出し = str(e.get("見出し", "") or "") or f"例 {i + 1}"
        md += [f"### {見出し}", "", "| " + " | ".join(列) + " |", "|" + "---|" * len(列),
               "| " + " | ".join(str(e.get(c, "") or "").replace("|", "\\|") for c in 列) + " |", ""]
    return "\n".join(md)


# 作り物の例の 確かめた人 の出所が引く質問と回答の行（確かめた人 は照らさない＝2026-11-27 に畳んだ。
# 行は形の例）。作り物の例はこの受付番号と問いの番号を書く。
例の受付たち = ("R261101-AAAA", "R261102-BBBB")
例の問いの番号 = "Q202611-03"
例の決定の鍵たち = ["作り物/例の確かめ"]


def 例の反映先() -> str:
    """作り物の例の答えの行の 反映先（型の列）。確かめる は受付番号・問いの番号の答えの行が照らしている例を指す時だけ通す
    （指し方の正本は 例の確かめ._行が例を指す: `2_マスタ/<タブ>/<その例の 決まり の項目>`）。作り物の例はどの項目の例も
    この行を出所に書くので、芯/設定の表.json の項目を全部指す（例ごとに答えの行を分ける試験は自分で 反映先 を書く）。"""
    from 芯 import 設定
    return "、".join(f"2_マスタ/会社/{n}" for n in 設定.表())


def 例の答えの行たち(会社: str) -> list[dict]:
    """作り物の例の出所の答えの行（質問と回答の行の形）。例の値は反映した後の設定にある＝反映済み は 済（済でない答えは
    月を回す が会社を止める＝反映されていない答えの問いたち）。"""
    反映先 = 例の反映先()
    return [{"会社": 会社, "問いの番号": f"Q202611-{i + 1:02d}", "回答": f"確かめた ／ 受付: {r}（版 1）", "反映先": 反映先,
             "反映済み": "済"}
            for i, r in enumerate(例の受付たち)] + [{"会社": 会社, "問いの番号": 例の問いの番号, "回答": "確かめた",
                                                  "反映先": 反映先, "反映済み": "済"}]


def 例の問いの表(会社: str, 行たち=()) -> list[list[str]]:
    """質問と回答（get_values の形）: 行たち（{列: 値}）に作り物の例の出所の答えの行を足す。"""
    行 = [*行たち, *例の答えの行たち(会社)]
    h = list(dict.fromkeys(k for r in 行 for k in r))
    return [h] + [[str(r.get(c, "")) for c in h] for r in 行]


def 例の出所(会社: str) -> dict:
    """確かめる・月を回す へ渡す出所の照らしの材料（作り物の例の答えの行・決定DB の鍵の並び）。"""
    return dict(問いの表=例の問いの表(会社), 決定の鍵たち=list(例の決定の鍵たち))
