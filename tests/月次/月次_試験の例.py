def 例の問い(鍵: str, 顧客ID: str, *, 状態: str = "聞いている", 聞いた支給月: str = "", 文: str = "",
           選択肢の振り分け: dict | None = None) -> dict:
    """質問と回答 の 問い のタブの 1 行（初期設定/質問と回答.py の 読む が返す問いと同じ属）。"""
    return {"鍵": 鍵, "顧客ID": 顧客ID, "聞いた支給月": 聞いた支給月, "状態": 状態, "文": 文 or f"作り物の問い {鍵}",
            "選択肢の振り分け": dict(選択肢の振り分け or {})}


def 例の振り分け(鍵: str, 顧客ID: str, *, 対象: str = "会社", 反映先: str = "マスタ/社員", 何を: str = "基本給",
             値: str = "", 効く月: str = "", 反映済み=False, 反映した日: str = "") -> dict:
    """質問と回答 の 振り分け のタブの 1 行（対象＝会社 か 社員ID・反映先は 5 種の正の形）。"""
    return {"鍵": 鍵, "顧客ID": 顧客ID, "対象": 対象, "反映先": 反映先, "何を": 何を, "値": 値, "効く月": 効く月,
            "反映済み": 反映済み, "反映した日": 反映した日}


def 例の表(顧客ID: str, 問いたち=(), 振り分けたち=(), 答えたち=()):
    """質問と回答 を読んだ表（問いたち・答えたち・振り分けたち）。作り物の例の出所の答えた問い（例の受付・例の問いの番号）を足す。"""
    from types import SimpleNamespace
    済 = [例の問い(例の問いの番号, 顧客ID, 状態="答えた")]
    return SimpleNamespace(問いたち=[*問いたち, *済], 答えたち=list(答えたち), 振り分けたち=list(振り分けたち))


def 日の問いの帳(行たち, 顧客ID: str, *, 日付: str = ""):
    """日の問いの作り物（設問.まとめる が出す問いの行に 回答・回答日 を足した物）→ 質問と回答 の 3 タブの表（例の表）。
    問い＝鍵・聞いた支給月・選択肢の振り分け（答え方の例の選択肢）、答え＝回答・回答日、振り分け＝答えで変わる人ごと
    （対象＝社員ID・反映先・何を＝何が無いか・値＝行の 問いの日付 か 日付）。人の NO が無い行は 対象＝会社 の振り分け 1 つ。"""
    import re
    問いたち, 答えたち, 振り分けたち = [], [], []
    for q in 行たち:
        鍵 = str(q.get("問いの鍵", ""))
        選 = [o.strip() for o in re.split(r"[／｜\n]", str(q.get("答え方の例", "") or "")) if o.strip()]
        問いたち.append(例の問い(鍵, 顧客ID, 状態="答えた" if str(q.get("回答", "")).strip() else "聞いている",
                             聞いた支給月=str(q.get("支給月", "")), 選択肢の振り分け={o: [] for o in 選}))
        if str(q.get("回答", "")).strip():
            答えたち.append({"鍵": 鍵, "回答": str(q["回答"]), "回答日": str(q.get("回答日", "")), "原本リンク": ""})
        人 = [w.strip() for w in re.split(r"[、,]", str(q.get("答えで変わる項目と人", "") or "")) if w.strip().isdigit()]
        for 対象 in 人 or ["会社"]:
            振り分けたち.append(例の振り分け(鍵, 顧客ID, 対象=対象, 反映先=str(q.get("反映先", "")),
                                    何を=str(q.get("何が無いか", "")), 値=str(q.get("問いの日付") or 日付)))
    return 例の表(顧客ID, 問いたち, 振り分けたち, 答えたち)


def 例の出所(会社: str, **kw) -> dict:
    """確かめる・月を回す へ渡す出所の照らしの材料（作り物の 質問と回答 の表・顧客ID〔作り物は会社名と同じ字〕・決定DB の鍵の並び）。
    kw は 例の表 へ（問いたち・振り分けたち・答えたち）。"""
    return dict(質問と回答=例の表(会社, **kw), 顧客ID=会社, 決定の鍵たち=list(例の決定の鍵たち))


