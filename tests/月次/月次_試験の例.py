"""試験の例の行（前のマスタ「例」と同じ列の作り物）を 給与のルール.md の字にする（月次.月を回す・賞与を回す は MD の字だけから例を読む）。"""
import 月次


def 例をMDに(例) -> str | None:
    if 例 is None:
        return None
    列 = 月次.例の確かめ.MDの例の列
    md = ["# 給与のルール（作り物）", ""]
    for i, e in enumerate(月次.例の確かめ.行たち(例)):
        # 決まり の升は例の 決まり の字のまま（名だけ）。見出しは例の 見出し（無ければ `例 i`）
        見出し = str(e.get("見出し", "") or "") or f"例 {i + 1}"
        md += [f"### {見出し}", "", "| " + " | ".join(列) + " |", "|" + "---|" * len(列),
               "| " + " | ".join(str(e.get(c, "") or "").replace("|", "\\|") for c in 列) + " |", ""]
    return "\n".join(md)


# 作り物の例の 確かめた人 の出所が引く質問と回答の行（確かめた人 は照らさない＝2026-11-27 に畳んだ。
# 行は形の例）。作り物の例はこの受付番号と問いの番号を書く。
例の受付たち = ("R261101-AAAA", "R261102-BBBB")
例の問いの番号 = "Q202611-03"
