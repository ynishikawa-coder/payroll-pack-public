"""1 か月を回す口（月次/）が台帳「月の変動」を 芯/計算 の 入力 へ渡す試験。作り物の会社 C1 の値だけ。

1. 月の変動に手当・控除のある人が口を通って確認済で額が出る（台帳の行・入口が今の原本から読んだ行のどちらでも）。
   月の変動の値は常に額（入口/手当控除の一覧 は個数×単価を額で書く）＝単価の元＝固定の額（空も）× 数量の元＝入力の値 の行へ渡す。
2. 読めない月の変動の行（値が数でない・支給控除の項目に無い名・確認済でない・支給月がそろわない・同じ名に 2 つの値・
   数量の元が入力の値でない部品の行・単価の元が 人の額・回ごとの額 などの 入力の値 の行＝額を数量と読むと単価×額 になる）の人は
   仮＋問い 1 つで、出口へ出ない ⟦鍵:給与計算/足りない時は仮で計算し出さない⟧。
3. 回帰の見張り: 月の変動の無い会社（タブが無い・空・ほかの月の行だけ）の結果は前と同じ。
"""
import importlib.util
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
sys.path.insert(0, str(根 / "tests" / "月次"))
_spec = importlib.util.spec_from_file_location("月次_試験_月の変動の元", 根 / "tests" / "月次" / "test_月次.py")
元 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(元)

作, C, 支給月, 人たち = 元.作, 元.C, 元.支給月, 元.人たち
段 = 元.段

_手当の項目 = [
    {"会社": C, "項目": "出張手当", "支給か控除": "支給", "数量の元": "入力の値", "適用開始": ""},           # 値＝額（単価の元が空）
    {"会社": C, "項目": "寮費", "支給か控除": "控除", "単価の元": "固定の額", "数量の元": "入力の値", "課税": "課税", "適用開始": ""},
    {"会社": C, "項目": "弁当代", "支給か控除": "控除", "単価の元": "固定の額", "数量の元": "入力の値", "適用開始": ""},
    # 単価の元 が額でない 入力の値 の行（月の変動の値＝額を数量と読めない）
    {"会社": C, "項目": "食事代", "支給か控除": "控除", "単価の元": "人の額", "数量の元": "入力の値", "適用開始": ""},
    {"会社": C, "項目": "昼食代", "支給か控除": "控除", "単価の元": "回ごとの額", "額": "300", "数量の元": "入力の値", "適用開始": ""},
    {"会社": C, "項目": "皆勤手当", "支給か控除": "支給", "単価の元": "人の額", "適用開始": ""},           # 数量の元＝1（毎月）
]


def _項目():
    return [*作._タブ()["支給控除の項目"], *_手当の項目]


def _人ごと():
    return [*作._タブ()["人ごとの支給控除"], {"会社": C, "NO": "0001", "項目": "食事代", "額": "400", "適用開始": ""}]


def _変動(NO, 項目, 値, 月="2027.02支給", 確認="確認済", 原本="書類_20270301_手当.pdf"):
    return {"会社": C, "支給月": 月, "NO": NO, "項目": 項目, "値": 値, "原本の名前": 原本, "確認": 確認}


def _回す(tmp_path, 月の変動=None, 原本=None):
    tabs引数 = {"支給控除の項目": _項目(), "人ごとの支給控除": _人ごと()}
    if 月の変動 is not None:
        tabs引数["月の変動"] = 月の変動
    return 元._回す(tmp_path, 原本=原本, **tabs引数)[2]


def _額(o, NO) -> dict:
    return {r.項目: r.値 for r in o["関所を通った"].行たち if r.NO == NO}


_手当の変動 = [_変動("0001", "出張手当", "5,000"), _変動("0001", "寮費", "12000円"), _変動("0002", "弁当代", "4000")]


# ---- 1. 月の変動に手当・控除のある人が確認済で額が出る ----
def test_月の変動の手当と控除が口を通って確認済で出る(tmp_path):
    o = _回す(tmp_path, 月の変動=_手当の変動)
    assert o["外した人"] == [] and o["問い"]["段の解決"] == []
    一, 二 = _額(o, "0001"), _額(o, "0002")
    assert 一["出張手当"] == 5000 and 一["寮費"] == 12000      # 固定の額（空も）× 入力の値＝月の変動の値が額
    assert 二["弁当代"] == 4000
    assert "出張手当" not in 二 and "寮費" not in 二 and "弁当代" not in 一   # 月の変動の無い人には出ない
    assert {r.NO for r in o["関所を通った"].行たち} == set(人たち)
    # 出張手当は課税の支給＝差引支給額に足される（月の変動の無い 0003 との差）
    無し = _額(o, "0003")
    assert 一["総支給額"] == 無し["総支給額"] + 5000


def test_入口が今の原本から読んだ月の変動も同じ回に渡る(tmp_path):
    # 手当控除の一覧（毎月変わる額＝月の変動）を口に渡す＝殻が台帳に書く前でも同じ回の 入力 へ（台帳の行と同じ額）
    一覧 = {"部品": "手当控除の一覧",
          "値": [{"勤怠の表記": "いちろう", "項目": "出張手当", "額": "5000"}, {"勤怠の表記": "いちろう", "項目": "寮費", "額": "12000"},
                {"勤怠の表記": "じろう", "項目": "弁当代", "個数": "10", "単価": "400"}],   # 書類どおりの単価
          "引数": {"原本の名前": "書類_20270301_手当.pdf",
                 "項目の辞書": {n: {"毎月同じ": False} for n in ("出張手当", "寮費", "弁当代")}}}
    原本 = [{"部品": "Excel出勤簿", "値": 作._出勤簿()}, 一覧]
    読んだ口 = _回す(tmp_path / "a", 原本=原本)
    台帳の口 = _回す(tmp_path / "b", 月の変動=_手当の変動)
    assert 読んだ口["外した人"] == [] and _額(読んだ口, "0001") == _額(台帳の口, "0001")
    assert {(a["NO"], a["項目"]) for a in 読んだ口["台帳"]["月の変動"]} == {("0001", "出張手当"), ("0001", "寮費"), ("0002", "弁当代")}
    # 殻が前の回に台帳へ書いた行と、同じ原本を読み直した行は 1 つ（2 行と数えて仮にしない）
    もう一度 = _回す(tmp_path / "c", 月の変動=[{**a, "支給月": "2027.02支給"} for a in 読んだ口["台帳"]["月の変動"]], 原本=原本)
    assert もう一度["外した人"] == [] and _額(もう一度, "0001") == _額(台帳の口, "0001")


# ---- 2. 読めない行の人は仮＋問い 1 つで出口へ出ない ----
_読めない = [
    ("値が数でない", [_変動("0001", "寮費", "千二百円")]),
    ("項目に無い名", [_変動("0001", "寮の費用", "12000")]),
    ("確認済でない", [_変動("0001", "寮費", "12000", 確認="要確認")]),
    ("支給月がそろわない", [_変動("0001", "寮費", "12000", 月="来月")]),
    ("同じ名に2つの値", [_変動("0001", "寮費", "12000"), _変動("0001", "寮費", "3000", 原本="書類_20270305_寮.pdf")]),
    ("数量の元が入力の値でない", [_変動("0001", "皆勤手当", "5000")]),
    ("人の額×入力の値", [_変動("0001", "食事代", "4000")]),       # 400×4000 で確定させない
    ("回ごとの額×入力の値", [_変動("0001", "昼食代", "1800")]),   # 300×1800 で確定させない
]


@pytest.mark.parametrize("名, 変動", _読めない, ids=[x[0] for x in _読めない])
def test_読めない月の変動の行の人は仮で出口へ出ない(tmp_path, 名, 変動):
    o = _回す(tmp_path, 月の変動=[*変動, _変動("0002", "弁当代", "4000")])
    問い = [q for q in o["問い"]["段の解決"] if q["項目"] == "台帳.月の変動"]
    assert [q["NO"] for q in 問い] == ["0001"] and 問い[0]["問い"]   # 人ごとに 1 つ
    出 = 元._仮の人が出ない(o, {"0001"})
    assert 出["関所を通った"] == {"0002", "0003"}
    assert _額(o, "0002")["弁当代"] == 4000                         # ほかの人は今までどおり出る


def test_入口の書類どおりの一覧でも額でない行の人は仮で出ない(tmp_path):
    # 入口/手当控除の一覧 は 食事代 個数 10 × 単価 400 を 値＝4000（額）で書く。人の額 × 入力の値 の行へ数量として渡すと
    # 400×4000＝1,600,000 で確定してしまう＝渡さず仮＋問い 1 つ
    一覧 = {"部品": "手当控除の一覧",
          "値": [{"勤怠の表記": "いちろう", "項目": "食事代", "個数": "10", "単価": "400"}],
          "引数": {"原本の名前": "書類_20270301_食事.pdf", "項目の辞書": {"食事代": {"毎月同じ": False}}}}
    o = _回す(tmp_path, 原本=[{"部品": "Excel出勤簿", "値": 作._出勤簿()}, 一覧])
    assert [a["値"] for a in o["台帳"]["月の変動"]] == ["4000"]
    assert [q["NO"] for q in o["問い"]["段の解決"] if q["項目"] == "台帳.月の変動"] == ["0001"]
    元._仮の人が出ない(o, {"0001"})
    assert not any(r.項目 == "食事代" for r in o["関所を通った"].行たち)


def test_社員に居ないNOの行は知らせ(tmp_path):
    o = _回す(tmp_path, 月の変動=[_変動("0099", "寮費", "12000")])
    assert o["外した人"] == [] and any("社員」に居ない NO" in s for s in o["知らせ"]["段の解決"])


# ---- 3. 回帰の見張り: 月の変動の無い会社は前と同じ ----
@pytest.mark.parametrize("月の変動", [None, [], [_変動("0001", "寮費", "12000", 月="2027.01支給")]],
                         ids=["タブが無い", "空", "ほかの月の行だけ"])
def test_月の変動の無い会社の結果は前と同じ(tmp_path, 月の変動):
    tabs, 置き場, o = 元._回す(tmp_path, 月の変動=月の変動) if 月の変動 is not None else 元._回す(tmp_path)
    通, 有給の行 = 元._手で組む(tabs, 置き場)
    assert o["関所を通った"].行たち == 通.行たち and o["外した人"] == [] and o["有給の出す行"] == 有給の行
    r = 段.解く(支給月, **作._タブ())
    assert r["入力"] == {} and not [q for q in r["仮の値"] if q["項目"] == "台帳.月の変動"]
    assert all("額" not in x for d in r["決まり"].values() for x in d.get("項目.行", []))  # 入力の値 の無い行に額を置かない
