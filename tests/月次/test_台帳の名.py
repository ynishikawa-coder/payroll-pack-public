"""月次/台帳の名.py: 物の名（鍵）を型のタブの名へ結ぶ。締めの記録の置き場は 6_計算の結果（人ごと）。"""
import importlib.util
import sys
from pathlib import Path

import pytest

_根 = Path(__file__).resolve().parents[2]
if str(_根) not in sys.path:
    sys.path.insert(0, str(_根))

from drive口.作り物 import 作り物のDrive  # noqa: E402


def _読む(名, 道):
    spec = importlib.util.spec_from_file_location(名, _根 / 道)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


名 = _読む("試験_台帳の名", "月次/台帳の名.py")
関所 = _読む("試験_締めの関所", "月次/締めの関所.py")

番号つき = ["1_読んだままの勤怠", "2_読んだままの勤怠の区間", "3_確定した勤怠", "4_確定した勤怠の区間",
          "5_その月だけの指示", "6_計算の結果（人ごと）", "7_賞与の支給一覧"]


@pytest.mark.parametrize("鍵, 先", [
    ("読んだままの勤怠", "1_読んだままの勤怠"), ("確定した勤怠の区間", "4_確定した勤怠の区間"),
    ("その月だけの指示", "5_その月だけの指示"), ("賞与の支給一覧", "7_賞与の支給一覧"),
    ("締めの記録", "6_計算の結果（人ごと）"), ("人ごとの月の数字", "6_計算の結果（人ごと）"),
])
def test_番号つきの名へ結ぶ(鍵, 先):
    assert 名.タブの名("台帳", 鍵, 番号つき) == 先


def test_同じ名のタブが在ればそれ():
    assert 名.タブの名("台帳", "締めの記録", ["締めの記録", "計算の結果（人ごと）"]) == "締めの記録"


def test_結べない名は鍵のまま返す():
    assert 名.タブの名("台帳", "知らないタブ", 番号つき) == "知らないタブ"


def test_締めの記録は作り物のDriveの6_計算の結果へ書かれる():
    口 = 作り物のDrive()
    根 = 口.根を作る()
    台帳 = 口.シートを作る(根, "台帳_2026", list(番号つき))
    見出し = ["会社", "支給月", "NO", "氏名", "状態"]
    for t in 番号つき:
        口.表へ書く(台帳, f"'{t}'!A1", [見出し] if t == "6_計算の結果（人ごと）" else [["会社"]])
    タブ = 名.タブの名("台帳", "締めの記録", 口.タブを並べる(台帳))
    assert タブ == "6_計算の結果（人ごと）"
    行 = [{"会社": "作り物の会社", "支給月": "2026.11支給", "NO": "1", "氏名": "作り物 一郎", "状態": "締めた"}]
    o = 関所.締める(行, 口.表を読む(台帳, f"'{タブ}'!A1:Z"))
    assert o["赤"] == []
    口.表へ足す(台帳, f"'{タブ}'!A1", [[r[c] for c in 見出し] for r in o["書く行"]])
    assert 口.表を読む(台帳, "'6_計算の結果（人ごと）'!A1:Z") == [見出し, ["作り物の会社", "2026.11支給", "1", "作り物 一郎", "締めた"]]
    assert "締めの記録" not in 口.タブを並べる(台帳)
