D = dt.date.fromisoformat


def _台帳(始め, 終わり, 変える):
    out, d = [], D(始め)
    while d <= D(終わり):
        r = {"会社": 会社, "支給月": f"{d:%Y-%m}", "NO": "1", "氏名": "作り物", "日付": d.isoformat(),
             "日の種類": "休日" if d.weekday() >= 5 else "勤務", "休暇の種類": "", "休暇の単位": "", "休暇の時間": ""}
        r.update(変える.get(d.isoformat(), {}))
        out.append(r)
        d += dt.timedelta(days=1)
    return out


