def test_回し直しで仮へ落ちた人の前の回の立て替えの残りを消す_人が書いた他の項目と他の月は触らない():
    h = 形.見出し("その月だけの指示")
    今 = _空の台帳()
    氏 = {"1": "作り物 一郎", "2": "作り物 二郎"}
    残り = lambda NO, 値, 支給月="2027.03支給": _行("その月だけの指示", 会社=会社, 支給月=支給月, NO=NO, 氏名=氏[NO],
                                             項目="社保の立て替えの残り", 値=値)
    手 = _行("その月だけの指示", 会社=会社, 支給月="2027.03支給", NO="2", 氏名="作り物 二郎", 項目="通勤手当", 値="500")
    今["その月だけの指示"] += [残り("1", "1000"), 残り("2", "3000"), 手, 残り("2", "700", "2027.04支給")]
    # 回し直し: 2 の人は仮へ落ちた（立て替えの残りの行が無い）・1 の人は残りが変わった
    o = 書.月の台帳({**_月の表(_人ごと("1", "作り物 一郎", "18"), _人ごと("2", "作り物 二郎", "17")),
                  "その月だけの指示": [h, 残り("1", "1200")]}, 今の台帳=今, 台帳の名=台帳, 社員=社員)
    後 = _照らす(今, o)
    assert 後["その月だけの指示"][1:] == [残り("1", "1200"), 手, 残り("2", "700", "2027.04支給")]
    # 関所を通った人が 0 人（表が見出しだけ）でも、人ごとの月の数字の次の支給月の前の回の行を消す
    o2 = 書.月の台帳({**_月の表(_人ごと("1", "作り物 一郎", "18")), "その月だけの指示": [h]},
                  今の台帳=後, 台帳の名=台帳, 社員=社員)
    assert _照らす(後, o2)["その月だけの指示"][1:] == [手, 残り("2", "700", "2027.04支給")]


