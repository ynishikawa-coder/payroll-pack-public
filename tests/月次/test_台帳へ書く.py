def 当てる(今: dict, 手順: list[dict]) -> dict:
    """書く手順を値の上で当てる（殻が Sheets に当てるのと同じ順・作り物の殻）。"""
    t = copy.deepcopy(今)
    for x in 手順:
        g = t.setdefault(x["タブ"], [])
        if x["する"] == "値を書く":
            m = re.fullmatch(r"A(\d+):[A-Z]+(\d+)", x["範囲"])
            a = int(m.group(1))
            for i, r in enumerate(x["値"]):
                while len(g) < a + i:
                    g.append([])
                g[a + i - 1] = list(r)
        elif x["する"] == "行を足す":
            g += [list(r) for r in x["値"]]
        elif x["する"] == "行を消す":
            del g[x["行"] - 1]
        elif x["する"] in ("スプレッドシートを作る", "タブを足す"):
            t.setdefault(x["タブ"], [])
        else:
            raise AssertionError(x)
    return t


def _照らす(今, o):
    後 = 当てる(今, o["書く手順"])
    for タブ, 書いた後 in o["書いた後"].items():
        assert 型の口.書いた値を照らす(書いた後, 後[タブ]) == [], タブ
    return 後


