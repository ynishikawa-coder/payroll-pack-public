# ---------------------------------------------------------------- 勤怠（読んだまま・確定）
def _日(NO="1", 日付="2027-02-01", **kw):
    return {"会社": 会社, "支給月": "2027-02", "NO": NO, "勤怠の表記": f"ひょうき{NO}", "日付": 日付, "日の種類": "勤務",
            "読み取りの確かめ": "確認済", "原本の名前": "作り物の出勤簿.pdf", **kw}


def _区(NO="1", 日付="2027-02-01", 番号="1", 種別="労働", 始め="9:00", 終わり="18:00"):
    return {"会社": 会社, "支給月": "2027-02", "NO": NO, "日付": 日付, "区間の番号": 番号, "区間の種別": 種別, "始め": 始め, "終わり": 終わり}


def _列(表, 列):
    i = 表[0].index(列)
    return [r[i] for r in 表[1:]]


def test_勤怠の写しの列は口が埋める():
    今 = _空の台帳()
    o = 書.勤怠(確定=False, 勤怠=[_日(), _日(日付="2027-02-02", 日の種類="休日")], 勤怠の区間=[_区()],
             今の台帳=今, 台帳の名=台帳, 社員=社員, 原本のリンク=リンク)
    後 = _照らす(今, o)
    日 = 後["読んだままの勤怠"]
    assert _列(日, "氏名") == ["作り物 一郎"] * 2 and _列(日, "曜日") == ["月", "火"]
    assert _列(日, "出勤の時刻") == ["9:00", ""] and _列(日, "退勤の時刻") == ["18:00", ""]
    assert _列(日, "原本のリンク") == ["作り物://原本/1"] * 2
    assert _列(日, "休憩の合計") == ["", ""]           # 日の要約（芯の数え）が無ければ空
    assert _列(後["読んだままの勤怠の区間"], "氏名") == ["作り物 一郎"]


