# ---------------------------------------------------------------- 手順の文書の照らし
手順の文書 = (根 / "plugins" / "payroll-agent" / "skills" / "payroll-steps" / "SKILL.md", 根 / "docs" / "毎月の流れ.md",
          根 / "plugins" / "payroll-agent" / "口の一覧.md", 根 / "plugins" / "payroll-agent" / "決まり.md")
_台帳の語 = re.compile(r"年の台帳|台帳_|人ごとの月の数字|読んだままの勤怠|確定した勤怠")


def 台帳をシートに書く段(本文: str) -> list[str]:
    """〔口: シートに書く〕で年の台帳へ書く段（同じ文に年の台帳の語）。外すのは口の一覧の〔口: シートに書く〕の定めの行
    （1 列目がその口の行）だけ＝文の字（「書かない」など）では外さない。定めの行は 年の台帳は書かない の注を持つことを別に照らす。"""
    out = []
    for line in 本文.splitlines():
        if line.startswith("| 〔口: シートに書く〕 |"):
            continue
        for 文 in re.split(r"(?<=。)", line):
            if "〔口: シートに書く〕" in 文 and _台帳の語.search(文):
                out.append(文.strip())
    return out


