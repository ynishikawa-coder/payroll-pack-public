# ── 見出しの字: 組む口（月次._項目から反映先）・読む口（型の口.反映先を読む と 例の確かめ._行が例を指す）・節を引く口（設問.md_の節）が
# 1 つの正本（型の口.見出しの字）を通ることを、月を回す口から往復で当てる（見出しの字は作り物）。
# 根: 例の鍵は見出しを NFKC でそろえて反映先を組み、md_の節 は字のまま引いた＝全角の括弧の見出しは節へ書いても節を引けなかった。
# また 、 , を含む見出しは反映先を読む口が 2 片に割り、例の確かめが通らないままその人は仮で止まった（止まった訳も無かった）。
_見出しの受付 = "R261127-0001"   # 作り物の事務所が例の問いに答えた受付番号（作り物）
_全角の見出し = "２　始業前の打刻（作り物）"   # 全角の英数・空白・括弧
_区切りの見出し = "2 始業前の打刻、作り物"


def _見出しの例(見出し: str):
    """作._例() の E1 の見出しを替え、確かめた人 の出所をまだ答えの無い受付番号にした例。"""
    頭, *行 = 作._例()
    行 = [dict(zip(頭, r)) for r in 行]
    行[0]["見出し"] = 見出し
    行[0]["確かめた人"] = f"作り物 確かめる人（{_見出しの受付}）"
    return 行


def _見出しで回す(tmp_path, 見出し: str):
    return 作.確定して回す(支給月, C, 作._タブ(), [{"部品": "Excel出勤簿", "値": 作._出勤簿()}], 法の線=作る_集計.法の線,
                     置き場=作る_計算.置き場(tmp_path), 例=_見出しの例(見出し))


def test_全角の括弧の見出しの例は例の確かめを通り節も引ける(tmp_path):
    # 2026-11-27: 出所の照らしを畳んだ＝答えの行が無くても例の確かめは通り全員が出る
    後 = _見出しで回す(tmp_path / "後", _全角の見出し)
    assert 後["例の確かめ"]["通った"], 後["例の確かめ"]["止め"]
    assert {r.NO for r in 後["関所を通った"].行たち} == set(人たち)
    問い = {"反映先": 型.md_の反映先("給与のルール", _全角の見出し), "何が無いか": "決まりの例: 例 E1"}
    assert 問い["反映先"] == "給与のルール.md#2 始業前の打刻(作り物)"
    # 給与のルール.md の全角のままの見出しの節を引ける（前は md_の節 が '' を返した）
    md = {"給与のルール.md": f"### {_全角の見出し}\n- 例 E1 を確かめた［出所: Q1］\n\n### ほかの決まり\n"}
    # 節を引く口と例を指す口は同じそろえを通す
    assert _設問().md_の節(md["給与のルール.md"], "2 始業前の打刻(作り物)").strip().startswith("- 例 E1")
    assert 月次.例の確かめ._行が例を指す({"反映先": 問い["反映先"]}, _見出しの例(_全角の見出し)[0])


def test_区切りを含む見出しの例は割れた反映先を組まず見出しの訳で止まる(tmp_path):
    o = _見出しで回す(tmp_path, _区切りの見出し)
    assert not o["例の確かめ"]["通った"] and not o["関所を通った"].行たち
    assert {a["NO"] for a in o["外した人"]} == set(人たち)
    assert any("例 E1" in t and "反映先の区切りの字" in t for t in o["例の確かめ"]["止め"]), o["例の確かめ"]["止め"]
    # 割れる反映先の問いは出さない（前は `給与のルール.md#2 始業前の打刻、作り物` を出し、読む口が 2 片に割った）
    assert not [q for q in o["問い"]["例"] if "例 E1" in q["何が無いか"]], o["問い"]["例"]
    # 組む口も組まない（全角の ， もそろえた後の , で見る）
    for 見 in (_区切りの見出し, "2 始業前の打刻，作り物", "2 始業前の打刻,作り物"):
        try:
            型.md_の反映先("給与のルール", 見)
        except ValueError as x:
            assert "反映先の区切りの字" in str(x)
        else:
            raise AssertionError(f"区切りを含む見出し {見!r} の反映先を組んだ")
