def test_人の止めの問いは決まりの項目を反映先に持つ(tmp_path):
    # 日の場面（休憩を書いていない日）に結んだ決まりの例が無い月: その日がある人だけの問い。反映先 はその決まりの項目
    出勤簿 = 作._出勤簿()
    行 = [[*r[:5], "", "", r[5]] for r in 出勤簿["行"]]
    for r in 行:
        if r[0] == 人たち["0002"] and r[1] == "2027/2/3":
            r[2:8] = ["9:00", "12:00", "", "13:00", "18:00", ""]
    出勤簿 = {**出勤簿, "見出し": ["氏名", "日付", "出勤", "退勤", "休憩", "出勤", "退勤", "区分"], "行": 行}
    o = 作.確定して回す(支給月, C, 作._タブ(型={"日勤": {"時間.休憩の出し方": "表"}}), [{"部品": "Excel出勤簿", "値": 出勤簿}],
                   法の線=作る_集計.法の線, 置き場=作る_計算.置き場(tmp_path), 例=作._例())
    assert [q.get("人") for q in o["問い"]["例"]] == [["0002"]]
    # 反映先は 質問と回答 の振り分けの 5 種の形（`マスタ/<タブ>`＋何を＝列）
    assert {k: o["問い"]["例"][0][k] for k in ("反映先", "何を")} == {"反映先": "マスタ/勤務の型", "何を": "時間.休憩の出し方"}


