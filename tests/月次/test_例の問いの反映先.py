def test_マスタの反映先のタブは型のタブだけを通す(tmp_path):
    名 = 型.名("マスタ")
    for w in (f"{名}/何でもないタブ/時間.始業前の打刻", f"{名}//時間.始業前の打刻", 名):
        assert [x.種 for x in 型.反映先を読む(w)] == ["知らないタブ"], w
        # 例の確かめの出所の行として数えない
        assert not 月次.例の確かめ._行が例を指す({"反映先": w}, {"例の番号": "E9", "決まり": "時間.始業前の打刻"}), w
    # タブの並びは型の正本（型.json の役 マスタ のシート）から引く
    assert 型.マスタのタブたち() == tuple(t["タブ"] for t in 型.シートの型("マスタ")["タブ"])
    for t in 型.マスタのタブたち():
        assert [x.種 for x in 型.反映先を読む(型.マスタの反映先(t, "時間.始業前の打刻"))] == ["マスタ"], t
    try:
        型.マスタの反映先("何でもないタブ", "時間.始業前の打刻")
    except ValueError:
        pass
    else:
        raise AssertionError("型に無いタブの反映先を組んだ")


