def _人(上書き=None):
    return {NO: {**_入社[NO], **(上書き or {}).get(NO, {})} for NO in 人たち}


def _出口():
    対応 = 対応にする([{"項目": "基本給", "欄": "基本給", "形": "円"}, {"項目": "差引支給額", "欄": "差引支給額", "形": "円"},
                   {"項目": "出勤日数", "欄": "出勤日数", "形": "日"}])
    return {"取り込み": {"欄の対応": 対応, "形": {"名": "作り物の給与ソフト", "鍵の欄": "NO", "氏名の欄": "氏名", "後ろの欄": "メモ", "文字コード": "utf-8"}}, "支給控除一覧": {}}


def _回す(tmp_path, 出勤簿=None, 原本=None, 置き場の手=None, 人=None, **tabs引数):
    tabs = 作._タブ(人=_人(人), **tabs引数)
    置き場 = 作る_計算.置き場(tmp_path)
    if 置き場の手:
        置き場の手(置き場)
    原本 = 原本 if 原本 is not None else [{"部品": "Excel出勤簿", "値": 出勤簿 or 作._出勤簿()}]
    return tabs, 置き場, 月次.月を回す(支給月, C, tabs, 原本, 法の線=作る_集計.法の線, 有給の値=有給の値, 出口=_出口(),
                                 置き場=置き場)


def _出た人(o) -> dict:
    """出口向けの物ごとに出た NO。"""
    取 = o["取り込み"]
    鍵 = list(取.表[0]).index("NO") if 取.表 else 0
    return {"関所を通った": {r.NO for r in o["関所を通った"].行たち},
            "取り込み": {str(row[鍵]) for row in 取.表[1:]},
            "支給控除一覧": {str(h) for x in o["支給控除一覧"] for h in x.表[0][1:-1]},
            "有給の出す行": {a["NO"] for a in o["有給の出す行"]}}


def _手で組む(tabs, 置き場):
    """今の正しい順（初期設定/README.md と 出口/README.md の 勤怠の行を分ける を両方満たす順）を手で組む。"""
    r = 段.解く(支給月, **tabs)
    x = 繋.入口の文脈(支給月, C, r, 置き場=置き場, **tabs)
    読んだ = Excel出勤簿.読む(作._出勤簿(), 文脈(**x["文脈"]))
    集 = 集計する(読んだ.日, 読んだ.区間, 決まり=r["決まり"], 法の線=作る_集計.法の線)
    計 = 計算する(集, 決まり=r["決まり"], 人=r["人"], 入力=繋.計算の入力(r["入力"], 集), 置き場=置き場)
    渡す, _ = 関所.勤怠の行を分ける(集["行"])
    z = 繋.給与の関所へ({"行": 計["行"] + 渡す, "人の状態": 計["人の状態"]}, r["仮の値"], x["仮の値"])
    通 = 関所.通す(z["行"], z["人の状態"])
    y = 繋.有給の入力(支給月, C, r, 読んだ.日, 社員=tabs["社員"], **有給の値)
    表 = 有給.管理表(y["入力"], 置き場=置き場)
    zz = 繋.有給の関所へ(y, 表, r["仮の値"])
    return 通, 繋.有給の出す行(表, 関所.通す(zz["行"], zz["人の状態"]))


def test_全員確認済なら手で組んだ順と同じ(tmp_path):
    tabs, 置き場, o = _回す(tmp_path)
    通, 有給の行 = _手で組む(tabs, 置き場)
    assert o["関所を通った"].行たち == 通.行たち and o["外した人"] == [] and 通.外した人たち == ()
    assert o["有給の出す行"] == 有給の行 and o["有給の外した人"] == []
    出 = _出た人(o)
    assert all(v == set(人たち) for v in 出.values()), 出
    assert {a["項目"] for a in o["台帳"]["人ごと"]} >= {"出勤日数", "総労働"}  # 台帳へ書く集計の月の数字
    assert any(r.項目 == "出勤日数" for r in o["関所を通った"].行たち)  # 勤怠の欄も関所を通って出口へ


def _仮の人が出ない(o, 仮の人):
    出 = _出た人(o)
    for 物, 誰 in 出.items():
        assert not (誰 & 仮の人), (物, 誰 & 仮の人)
    assert 仮の人 <= {a["NO"] for a in [*o["外した人"], *o["有給の外した人"]]}
    return 出


