def test_賞与も段の解決で仮の人は出ない(tmp_path):
    tabs = 作._タブ(変更の記録=作._記録)
    置き場 = 作る_計算.置き場(tmp_path)
    一覧 = [{"会社": C, "NO": NO, "額": 500000, "原本の名前": "賞与_作り物.xlsx"} for NO in 人たち]
    前月 = {(C, NO): 280000 for NO in 人たち}
    前 = {(C, NO): 0 for NO in 人たち}
    o = 月次.賞与を回す("2027.02支給", C, tabs, 一覧, 支給日="2027-02-26", 前月の課税対象額=前月, 前の標準賞与額=前, 置き場=置き場)
