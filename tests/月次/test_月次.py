def _前の出勤簿(要確認の日=None):
    行 = []
    d = date(2027, 1, 1)
    while d.month == 1:
        出る = d.weekday() < 5 and d.isoformat() not in ("2027-01-01", "2027-01-11")
        for 名 in 人たち.values():
            区分 = "謎の区分" if (名, d.isoformat()) == 要確認の日 else ""
            行.append([名, d.strftime("%Y/%-m/%-d"), *(("9:00", "18:00", "60") if 出る else ("", "", "")), 区分])
        d += timedelta(days=1)
    return {"原本の名前": "勤怠_20270201_出勤簿.xlsx", "見出し": ["氏名", "日付", "出勤", "退勤", "休憩", "区分"], "行": 行}


