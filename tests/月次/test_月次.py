def test_賞与の計算期間は口がそのまま渡す(tmp_path):
    # 前月の給与が無い人＝月額表の道。計算期間が無ければ芯が源泉を仮＝口は出さない、渡せば出る（#64 の引数を口が通す）
    tabs = 作._タブ()
    置き場 = 作る_計算.置き場(tmp_path)
    一覧 = [{"会社": C, "NO": NO, "額": 500000, "原本の名前": "賞与_作り物.xlsx"} for NO in 人たち]
    前 = {(C, NO): 0 for NO in 人たち}
    共 = dict(支給日="2027-02-26", 前月の課税対象額={}, 前の標準賞与額=前, 置き場=置き場)
    無し = 月次.賞与を回す("2027.02支給", C, tabs, 一覧, **共)
    在る = 月次.賞与を回す("2027.02支給", C, tabs, 一覧, 計算期間={(C, NO): 6 for NO in 人たち}, **共)
    assert {r.NO for r in 無し["関所を通った"].行たち} == set() and {a["NO"] for a in 無し["外した人"]} == set(人たち)
    assert {r.NO for r in 在る["関所を通った"].行たち} == set(人たち)
