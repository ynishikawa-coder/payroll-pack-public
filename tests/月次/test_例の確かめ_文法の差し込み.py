"""例の確かめの 確かめた人 の文法に字を差し込む試験（月次/例の確かめ.py の 確かめた人を読む）。名・番号・URL・資料の名は作り物だけ。

根（2026-11-27 の見直しの赤）: 片の字を種類ごとに含みで見ていたので、資料の名や片の前後・中に字を混ぜても通った。
種類ごとの文法を表（`出所の種類たち`）に 1 つずつ持ち、字の全体と片の全体がぴったり当たる時だけ通す形にした。
ここでは種類ごとに、証しをそろえて通る字を 1 つ置き、括弧の中の前・各字の間・後と括弧の後に、隠しに使える字を機械で
差し込み、どれも止まる事を見る。通ってよいのは、文法が許す形（片の間の ・ 、 の前後に空白 1 つ）になった時と、
升の端の空白（升の字としてそろえて落とす）だけ。
"""
import sys
import unicodedata
from datetime import date
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))

import 月次  # noqa: E402

読む = 月次.例の確かめ.確かめた人を読む
今日 = date(2027, 3, 10)
会社 = "作り物の会社"
問いの表 = [["会社", "問いの番号", "回答", "反映先"],
          [会社, "Q202611-05", "変わりは無い ／ 受付: R261120-0009", "2_マスタ/社員/人.入社日"]]
差の表 = [["支給月", "会社", "NO", "項目", "差"], ["2026-09", 会社, "0001", "総支給", "0"]]
答えの行 = [{"支給月": "2026-09", "会社": 会社, "NO": "0001", "項目": "総支給", "出所": "作り物の一覧.pdf"}]
鍵 = ["作り物/例の確かめ", "https://example.invalid/作り物の決定の行"]

# (名, 括弧の中, 証し)。括弧の中が種類の文法の片。どれも証しをそろえれば通る
通る字 = (
    ("R", "R261120-0009", {"問いの表": 問いの表}),
    ("Q", "Q202611-05", {"問いの表": 問いの表}),
    ("R・Q", "R261120-0009・Q202611-05", {"問いの表": 問いの表}),
    ("決定DB の鍵", "決定DB 2027-03-01 ⟦鍵:作り物/例の確かめ⟧", {"決定の鍵たち": 鍵}),
    ("決定DB の URL", "決定DB 2027-03-01 https://example.invalid/作り物の決定の行", {"決定の鍵たち": 鍵}),
    ("過去の結果", "過去の結果 2026.09支給 作り物の一覧 0001:総支給 一致", {"照らしの結果": {"差の表": 差の表, "答えの行": 答えの行}}),
)

# 隠しに使える字（見えない字・全角の空白・ほかの区切り・括弧・結合の字・片の区切り・余りの語・半角の空白・1 字の余り）
差す字 = ("​", "　", "／", "｜", "\t", "\n", "；", "（", "）", "️", "・", " - ", "。", "総務", " ", "X")


def _文法が許す形か(中: str, i: int, 差す: str) -> bool:
    """差した後も文法が許す形か: 片の間の ・ 、 の前後に空白を 1 つだけ足した時（片の間の正本は `_片の間`。全角の空白は
    NFKC で半角になる）。"""
    if unicodedata.normalize("NFKC", 差す) != " ":
        return False
    前, 後 = 中[:i], 中[i:]
    return (前.endswith(("・", "、")) and not 後.startswith(" ")) or (後.startswith(("・", "、")) and not 前.endswith(" "))


def _差し込みの組() -> list:
    組 = []
    for 名, 中, 証し in 通る字:
        for i in range(len(中) + 1):   # 括弧の中の前・各字の間・後
            for 差す in 差す字:
                if _文法が許す形か(中, i, 差す):
                    continue
                組.append(pytest.param(f"担当（{中[:i]}{差す}{中[i:]}）", 証し, id=f"{名}-{i}-{unicodedata.name(差す[0], 'X')}"))
        for 差す in 差す字:   # 括弧の後（升の端の空白は升の字としてそろえて落とす＝片ではない。正本は `_字`）
            if not 差す.strip():
                continue
            組.append(pytest.param(f"担当（{中}）{差す}", 証し, id=f"{名}-後-{unicodedata.name(差す[0], 'X')}"))
    return 組


差し込みの組 = _差し込みの組()


@pytest.mark.parametrize("名, 中, 証し", 通る字, ids=[t[0] for t in 通る字])
def test_差す前の字は通る(名, 中, 証し):
    _, 出所, 訳 = 読む(f"担当（{中}）", 今日=今日, 会社名=会社, **証し)
    assert 訳 is None and 出所


@pytest.mark.parametrize("字, 証し", 差し込みの組)
def test_どこへ差しても止まる(字, 証し):
    _, _, 訳 = 読む(字, 今日=今日, 会社名=会社, **証し)
    assert 訳, repr(字)


def test_差し込みの組は種類ごとに在る():
    assert len(差し込みの組) > 1000
    for 名, _, _ in 通る字:
        assert any(p.id.startswith(f"{名}-") for p in 差し込みの組), 名
