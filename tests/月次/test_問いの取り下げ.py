"""問いの取り下げの口（月次/問いの取り下げ.py）。作り物の値だけ。

- 聞いている問いを取り下げると 質問と回答「1_問い」の 状態 が 取り下げ になる（答えの文に印を書かない）→ 2 回当てても同じ。
- 答えた問い・表に無い問いは止まる（手順 0）。管理表 確認ページ の状況は 取り下げ（全部下げた時だけ）。
- 確認ページの受付を止める: 下げた問いへの後の答えは 貼り戻し が書かず知らせる。
"""
import copy
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
_p = 根 / "月次" / "問いの取り下げ.py"
_s = importlib.util.spec_from_file_location("月次_問いの取り下げ_試験", _p)
下 = importlib.util.module_from_spec(_s)
sys.modules[_s.name] = 下
_s.loader.exec_module(下)
qa, 頁, 表 = 下.qa, 下.頁, 下._表

会社, 今日, 版 = "作り物の会社", "2027-02-10", "2027.02-v1"
URL = "https://作り物/確認ページ/1"
訳 = "仕組みが振る値と決めた（作り物の訳）"
問い頭 = qa.見出し("問い")


def _問(鍵, 状態="聞いている"):
    v = {"問いの鍵": 鍵, "顧客ID": "C900", "聞いた支給月": "2027-02", "聞いた日": "2027-02-01", "問いの文": "作り物の問い",
         "状態": 状態}
    return [v.get(c, "") for c in 問い頭]


def _格子(*行たち):
    行たち = 行たち or (_問("Q202702-01"), _問("Q202702-02"))
    return {"1_問い": [問い頭, *map(list, 行たち)], "2_答え": [qa.見出し("答え")], "3_振り分け": [qa.見出し("振り分け")]}


def _台帳(状況="待ち", 数="2"):
    見 = 表.見出し("確認ページ")
    d = {"載せた日": "2027-02-01", "会社": 会社, "支給月": "2027.02支給", "何の確認か": "立ち上げ", "問いの数": 数,
         "確認ページ": URL, "状況": 表.値の字("確認ページ", "状況", 状況)}
    return [list(見), [str(d.get(c, "")) for c in 見]]


def _回す(格子たち, 鍵たち=("Q202702-01", "Q202702-02"), **kw):
    kw.setdefault("確認ページの行たち", _台帳())
    kw.setdefault("確認ページ", URL)
    kw.setdefault("会社", 会社)
    return 下.取り下げの手順(格子たち, list(鍵たち), 訳, 今日=今日, 版=版, **kw)


def _当てる(格子たち, 手順):
    """値を書く（1 つの升）を作り物の格子へ当てる。"""
    後 = copy.deepcopy(格子たち)
    for x in 手順:
        assert x["する"] == "値を書く" and x["タブ"] == "1_問い", x
        m = re.fullmatch(r"([A-Z]+)(\d+)", x["範囲"])
        列 = sum((ord(c) - 64) * 26 ** i for i, c in enumerate(reversed(m.group(1)))) - 1
        後["1_問い"][int(m.group(2)) - 1][列] = x["値"][0][0]
    return 後


def _状態(格子たち):
    return {q.鍵: q.状態 for q in qa.読む(格子たち).問いたち}


def test_聞いている問いは状態を取り下げにして2回当てても同じ():
    g = _格子()
    o = _回す(g)
    assert o["赤"] == [] and [(x["問いの鍵"], x["する"], x["訳"], x["版"]) for x in o["記録"]] == [
        ("Q202702-01", "取り下げ", 訳, 版), ("Q202702-02", "取り下げ", 訳, 版)]
    後 = _当てる(g, o["手順"])
    assert _状態(後) == {"Q202702-01": "取り下げ", "Q202702-02": "取り下げ"}
    assert len(後["1_問い"]) == len(g["1_問い"]) and 後["2_答え"] == g["2_答え"]   # 行を足さず答えに印を書かない
    # 管理表: 全部下げた＝状況を 取り下げ（鍵の列と状況だけ）・管理表の書く口がそのまま受ける
    (行,) = o["管理表の行"]
    assert 行 == {"会社": 会社, "載せた日": "2027-02-01", "確認ページ": URL, "状況": 表.値の字("確認ページ", "状況", "取り下げ")}
    手 = 表.書く({"タブ": "確認ページ", "今の値": _台帳(), "会社の一覧": {会社: "作り物の組"}, "受け持つ組": "作り物の組",
                 "行たち": [行], "今日": 今日})
    assert 手 and all(x.get("する") == "値を書く" for x in 手)
    # 2 回目: 手順 0・台帳も書かない
    o2 = _回す(後, 確認ページの行たち=_台帳("取り下げ"))
    assert o2["赤"] == [] and o2["手順"] == [] and o2["管理表の行"] == [] and o2["記録"] == []


def test_鍵はハイフンと下線を同じ問いに読む():
    o = _回す(_格子(), ("Q202702_01",), 確認ページ=None, 確認ページの行たち=None)
    assert o["赤"] == [] and [x["問いの鍵"] for x in o["記録"]] == ["Q202702-01"]


def test_答えた問いは止まり何も返さない():
    o = _回す(_格子(_問("Q202702-01"), _問("Q202702-02", "答えた")))
    assert o["手順"] == [] and o["管理表の行"] == [] and o["記録"] == []
    assert len(o["赤"]) == 1 and "Q202702-02" in o["赤"][0] and "答えた" in o["赤"][0]
    # 台帳が 答えた でも止まる
    o = _回す(_格子(), 確認ページの行たち=_台帳("答えた"))
    assert o["手順"] == [] and o["赤"] and "お答えいただいた" in o["赤"][0]


def test_一部だけ下げると状況は変えない():
    o = _回す(_格子(), ("Q202702-01",))
    assert o["赤"] == [] and [x["問いの鍵"] for x in o["記録"]] == ["Q202702-01"]
    assert o["管理表の行"] == [] and any("残る問い" in k for k in o["知らせ"])
    assert _状態(_当てる(_格子(), o["手順"])) == {"Q202702-01": "取り下げ", "Q202702-02": "聞いている"}


def test_渡し方の誤りは止める():
    g = _格子()
    assert 下.取り下げの手順(g, ["Q202702-01"], "", 今日=今日)["赤"]
    assert 下.取り下げの手順(g, ["Q202702-01"], "二行の\n訳", 今日=今日)["赤"]
    assert 下.取り下げの手順(g, ["Q202702-01"], 訳, 今日="2027/02/10")["赤"]
    assert 下.取り下げの手順(g, ["Q202702-01"], 訳, 今日=今日, 版="v1")["赤"]
    assert 下.取り下げの手順(g, [], 訳, 今日=今日)["赤"]
    assert 下.取り下げの手順(g, ["Q202702-09"], 訳, 今日=今日)["赤"]
    assert 下.取り下げの手順([["問いの鍵"]], ["Q202702-01"], 訳, 今日=今日)["赤"]
    assert 下.取り下げの手順(g, ["Q202702-01"], 訳, 今日=今日, 確認ページ=URL)["赤"]
    o = 下.取り下げの手順(g, ["Q202702-01"], 訳, 今日=今日, 会社=会社, 確認ページ="https://作り物/別",
                    確認ページの行たち=_台帳())
    assert o["赤"] and o["手順"] == []


def test_下げた問いへの後の答えは確認ページが受け付けない():
    g = _格子(_問("Q202702-01"))
    後 = _当てる(g, _回す(g, ("Q202702-01",), 確認ページの行たち=_台帳(数="1"))["手順"])
    問いの行たち = [{"問いの鍵": "Q202702-01", "問いの番号": "Q202702-01", "質問": "作り物の問い"}]
    答え = {"form": "qa-html/2", "title": "作り物", "version": 版, "receipt": "R270211-CCCC",
          "answered_at": "2027-02-11T10:00:00+09:00", "answers": {"Q202702_01": ["作り物の値"]},
          "labels": {"Q202702_01": ["作り物の値"]}, "supp": {}, "free": ""}
    r = 頁.貼り戻し(後, 問いの行たち, 答え, "2027-02-11", 版)
    assert r["赤"] == [] and r["手順"] == []
    assert any("取り下げた" in k for k in r["知らせ"])


def test_口はJSONで回り赤なら2で終わる():
    入力 = {"格子たち": _格子(), "会社": 会社, "問いの鍵たち": ["Q202702-01", "Q202702-02"], "訳": 訳, "今日": 今日, "版": 版,
          "確認ページの行たち": _台帳(), "確認ページ": URL}
    p = subprocess.run([sys.executable, str(_p)], input=json.dumps(入力, ensure_ascii=False), capture_output=True, text=True)
    assert p.returncode == 0, p.stdout + p.stderr
    out = json.loads(p.stdout)
    assert len(out["手順"]) == 2 and len(out["管理表の行"]) == 1
    入力 = copy.deepcopy(入力)
    入力["問いの鍵たち"] = ["Q202702-09"]
    p = subprocess.run([sys.executable, str(_p)], input=json.dumps(入力, ensure_ascii=False), capture_output=True, text=True)
    assert p.returncode == 2 and json.loads(p.stdout)["赤"]
    p = subprocess.run([sys.executable, str(_p)], input="{}", capture_output=True, text=True)
    assert p.returncode == 2 and json.loads(p.stdout)["赤"]
