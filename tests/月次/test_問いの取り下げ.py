"""問いの取り下げの口（月次/問いの取り下げ.py）。作り物の値だけ。

- 答え 0 件の問いを取り下げると 質問と回答 の一番下の行が `取り下げ→<訳>` になり、閉じた問いとして読まれる
  （設問.閉じた答え・書き戻しの手順は開いたままに数えない）→ 2 回当てても同じ（2 回目の手順は 0）。
- 答えのある問いは止まる（手順 0）。分からない の問いは行を足す。管理表 確認ページ の状況は 取り下げ（全部下げた時だけ）。
- 確認ページの受付を止める: 下げた問いへの後の答えは 貼り戻し が書かず知らせる。
"""
import copy
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
_p = 根 / "月次" / "問いの取り下げ.py"
_s = importlib.util.spec_from_file_location("月次_問いの取り下げ_試験", _p)
下 = importlib.util.module_from_spec(_s)
_s.loader.exec_module(下)
戻, 口, 設問, 頁, 表 = 下.戻, 下.口, 下.設問, 下.頁, 下._表

会社, 月, 今日, 版 = "作り物の会社", "2027.02支給", "2027-02-10", "2027.02-v1"
Q = 口.名("質問と回答")
URL = "https://作り物/確認ページ/1"
訳 = "仕組みが振る値と決めた（作り物の訳）"


def _表(見出し, *行たち):
    return [list(見出し), *[[str(d.get(c, "")) for c in 見出し] for d in 行たち]]


def _問(番号, 回答="", **足す):
    return {"会社": 会社, "問いの番号": 番号, "支給月": 月, "質問": "作り物の問い", "回答": 回答, "反映先": "2_マスタ/会社/作り物", **足す}


def _問たち(*行たち):
    return _表(口.見出し(Q, "質問"), *(行たち or (_問("Q202702-01"), _問("Q202702-02"))))


def _台帳(状況="待ち", 数="2"):
    return _表(表.見出し("確認ページ"), {"載せた日": "2027-02-01", "会社": 会社, "支給月": 月, "何の確認か": "立ち上げ",
                                    "問いの数": 数, "確認ページ": URL, "状況": 表.値の字("確認ページ", "状況", 状況)})


def _回す(問, 番号たち=("Q202702-01", "Q202702-02"), **kw):
    kw.setdefault("確認ページの行たち", _台帳())
    kw.setdefault("確認ページ", URL)
    return 下.取り下げの手順(問, 会社, list(番号たち), 訳, 今日=今日, 版=版, **kw)


def _一番下(格子, 番号):
    h = 格子[0]
    return [dict(zip(h, r)) for r in 格子[1:] if r[h.index("問いの番号")] == 番号][-1]


def test_答え0件の問いは閉じた問いとして読まれ2回当てても同じ():
    問 = _問たち()
    o = _回す(問)
    assert o["赤"] == [] and [x["する"] for x in o["記録"]] == ["値を書く", "値を書く"]
    後 = 戻.手順を当てる({(Q, "質問"): 問}, o["手順"])[(Q, "質問")]
    for 番号 in ("Q202702-01", "Q202702-02"):
        r = _一番下(後, 番号)
        assert r["回答"] == f"取り下げ→{訳}（版 {版}）" and r["回答日"] == 今日
        assert 設問.閉じた答え(r["回答"])
    assert len(後) == len(問)   # 行は足さない（空の行へ書く）
    # 管理表: 全部下げた＝状況を 取り下げ（鍵の列と状況だけ）・管理表の書く口がそのまま受ける
    (行,) = o["管理表の行"]
    assert 行 == {"会社": 会社, "載せた日": "2027-02-01", "確認ページ": URL, "状況": 表.値の字("確認ページ", "状況", "取り下げ")}
    手 = 表.書く({"タブ": "確認ページ", "今の値": _台帳(), "会社の一覧": {会社: "作り物の組"}, "受け持つ組": "作り物の組",
                 "行たち": [行], "今日": 今日})
    assert 手 and all(x.get("する") == "値を書く" for x in 手)
    # 書き戻しは下げた問いを開いたままに数えない
    w = 戻.書き戻しの手順(後, 会社, 月, 今日=今日, マスタ={})
    assert w["開いたまま"] == [] and w["手順"] == [] and w["赤"] == []

    # 2 回目: 手順 0・当てても同じ・台帳も書かない
    台帳の後 = _台帳("取り下げ")
    o2 = _回す(後, 確認ページの行たち=台帳の後)
    assert o2["赤"] == [] and o2["手順"] == [] and o2["管理表の行"] == [] and o2["記録"] == []
    assert 戻.手順を当てる({(Q, "質問"): 後}, o2["手順"])[(Q, "質問")] == 後


def test_答えのある問いは止まり何も返さない():
    問 = _問たち(_問("Q202702-01"), _問("Q202702-02", "引かない ／ 受付: R270201-AAAA（版 2027.02-v1）"))
    o = _回す(問)
    assert o["手順"] == [] and o["管理表の行"] == [] and o["記録"] == []
    assert len(o["赤"]) == 1 and "Q202702-02" in o["赤"][0] and "答えを受け取る" in o["赤"][0]
    # 台帳が 答えた でも止まる
    o = _回す(_問たち(), 確認ページの行たち=_台帳("答えた"))
    assert o["手順"] == [] and o["赤"] and "お答えいただいた" in o["赤"][0]


def test_分からないは行を足し一部だけ下げると状況は変えない():
    問 = _問たち(_問("Q202702-01", "分からない ／ 受付: R270201-BBBB（版 2027.02-v1）", 反映済み=""), _問("Q202702-02"))
    o = _回す(問, ("Q202702-01",))
    assert o["赤"] == [] and o["記録"] == [{"問いの番号": "Q202702-01", "する": "行を足す"}]
    assert o["管理表の行"] == [] and any("残る問い" in k for k in o["知らせ"])
    後 = 戻.手順を当てる({(Q, "質問"): 問}, o["手順"])[(Q, "質問")]
    assert len(後) == len(問) + 1 and 設問.閉じた答え(_一番下(後, "Q202702-01")["回答"])
    assert _一番下(後, "Q202702-02")["回答"] == ""
    assert _回す(後, ("Q202702-01",))["手順"] == []


def test_渡し方の誤りは止める():
    問 = _問たち()
    assert 下.取り下げの手順(問, 会社, ["Q202702-01"], "", 今日=今日)["赤"]
    assert 下.取り下げの手順(問, 会社, ["Q202702-01"], "二つ／の訳", 今日=今日)["赤"]
    assert 下.取り下げの手順(問, 会社, ["Q202702-01"], 訳, 今日="2027/02/10")["赤"]
    assert 下.取り下げの手順(問, 会社, ["Q202702-01"], 訳, 今日=今日, 版="v1")["赤"]
    assert 下.取り下げの手順(問, 会社, [], 訳, 今日=今日)["赤"]
    assert 下.取り下げの手順(問, 会社, ["Q202702-09"], 訳, 今日=今日)["赤"]
    assert 下.取り下げの手順(問, 会社, ["Q202702-01"], 訳, 今日=今日, 確認ページ=URL)["赤"]
    o = 下.取り下げの手順(問, 会社, ["Q202702-01"], 訳, 今日=今日, 確認ページ="https://作り物/別", 確認ページの行たち=_台帳())
    assert o["赤"] and o["手順"] == []


def test_下げた問いへの後の答えは確認ページが受け付けない():
    問 = _問たち(_問("Q202702-01"))
    後 = 戻.手順を当てる({(Q, "質問"): 問}, _回す(問, ("Q202702-01",), 確認ページの行たち=_台帳(数="1"))["手順"])[(Q, "質問")]
    行たち = [dict(zip(後[0], r)) for r in 後[1:]]
    答え = {"form": "qa-html/2", "title": "作り物", "version": 版, "receipt": "R270211-CCCC",
          "answered_at": "2027-02-11T10:00:00+09:00", "answers": {"Q202702_01": ["作り物の値"]},
          "labels": {"Q202702_01": ["作り物の値"]}, "supp": {}, "free": ""}
    r = 頁.貼り戻し(行たち, 答え, "2027-02-11", 版)
    assert r["赤"] == [] and r["行たち"] == []
    assert any("取り下げた" in k for k in r["知らせ"])


def test_口はJSONで回り赤なら2で終わる():
    入力 = {"質問の行たち": _問たち(), "会社": 会社, "問いの番号たち": ["Q202702-01", "Q202702-02"], "訳": 訳, "今日": 今日, "版": 版,
          "確認ページの行たち": _台帳(), "確認ページ": URL}
    p = subprocess.run([sys.executable, str(_p)], input=json.dumps(入力, ensure_ascii=False), capture_output=True, text=True)
    assert p.returncode == 0, p.stdout + p.stderr
    out = json.loads(p.stdout)
    assert len(out["手順"]) == 2 and len(out["管理表の行"]) == 1
    入力 = copy.deepcopy(入力)
    入力["問いの番号たち"] = ["Q202702-09"]
    p = subprocess.run([sys.executable, str(_p)], input=json.dumps(入力, ensure_ascii=False), capture_output=True, text=True)
    assert p.returncode == 2 and json.loads(p.stdout)["赤"]
    p = subprocess.run([sys.executable, str(_p)], input="{}", capture_output=True, text=True)
    assert p.returncode == 2 and json.loads(p.stdout)["赤"]
