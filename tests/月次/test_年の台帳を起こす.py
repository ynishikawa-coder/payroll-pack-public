# ---- 注入の試験: 欠けた前の年・知らない形は既定で止める ----

def test_前の年の台帳が無い会社も止めずに起き空を0で埋めない():
    # 前の年の台帳の有る無しで会社ごと止めない（前の年の日が要る人だけを 月を回す が人ごとに止める＝test_月を回す の 前の年の台帳が無い会社）
    o = 起.起こす(2027, None, 今ある名=[], 社員=社員)
    assert all(表 == [形.見出し(k)] for k, 表 in o["タブ"].items())
    assert o["前の確定した勤怠"] == [形.見出し("確定した勤怠")]   # 見出しだけ＝前の年の日は無いまま（0 の行を作らない）
    assert o["前の確定した勤怠の区間"] == [形.見出し("確定した勤怠の区間")]
    assert "人ごとに止める" in o["知らせ"][0]


