"""新しい年の台帳を起こす口（月次/年の台帳を起こす.py）。作り物の値だけ。

- 前の年の台帳から新しい年の台帳ができる（8 タブ・型の見出し）
- 引き継ぐ値が落ちない（往復: 起こした台帳と返った前の年の行を合わせると、前の年の台帳の行が 1 行も欠けず増えない）
- 前の年の台帳が欠ける・形が違う・どの年か分からない行があると止まる（注入の試験）
- 返った前の年の確定した勤怠を 月を回す と同じ読み口が読める
"""
import importlib.util
import sys
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
_spec = importlib.util.spec_from_file_location("月次_年の台帳を起こす_試験", 根 / "月次" / "年の台帳を起こす.py")
起 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(起)
形 = 起.形

会社 = "作り物の会社"


def _行(タブ, **値):
    h = 形.見出し(タブ)
    外 = set(値) - set(h)
    assert not 外, 外
    return [str(値.get(c, "")) for c in h]


def _日(NO, 日付, 支給月):
    return _行("確定した勤怠", 会社=会社, 支給月=支給月, NO=NO, 日付=日付, 日の種類="勤務", 読み取りの確かめ="確認済")


def _区間(NO, 日付, 支給月):
    return _行("確定した勤怠の区間", 会社=会社, 支給月=支給月, NO=NO, 日付=日付, 区間の番号="1", 区間の種別="労働",
              始め="9:00", 終わり="18:00")


def _前の年の台帳():
    t = {k: [list(形.見出し(k))] for k in 起.台帳のタブ}
    t["確定した勤怠"] += [_日("1", "2025-12-01", "2026.01支給"), _日("1", "2026-11-30", "2026.12支給"),
                       _日("2", "2026-11-30", "2026.12支給")]
    t["確定した勤怠の区間"] += [_区間("1", "2025-12-01", "2026.01支給"), _区間("1", "2026-11-30", "2026.12支給")]
    t["読んだままの勤怠"] += [_行("読んだままの勤怠", 会社=会社, 支給月="2026.12支給", NO="1", 日付="2026-11-30")]
    t["読んだままの勤怠の区間"] += [_行("読んだままの勤怠の区間", 会社=会社, 支給月="2026.12支給", NO="1", 日付="2026-11-30",
                                区間の番号="1")]
    t["人ごとの月の数字"] += [_行("人ごとの月の数字", 会社=会社, 支給月="2026.12支給", NO="1", 状態="確認済")]
    t["締めの記録"] += [_行("締めの記録", 会社=会社, 支給月="2026.12支給", NO="1", 状態="締まった", 締めた日="2026-12-05")]
    # 12 月を回した 月次 が返した 1 月の 社保の立て替えの残り（年をまたぐ続きの値）と、12 月の行
    t["その月だけの指示"] += [
        _行("その月だけの指示", 会社=会社, 支給月="2026.12支給", NO="2", 項目="社保の立て替えの残り", 値="3000"),
        _行("その月だけの指示", 会社=会社, 支給月="2027.01支給", NO="2", 項目="社保の立て替えの残り", 値="1500",
           中身="2026.12支給 の確定した結果の残り（月次が書く）"),
        _行("その月だけの指示", 会社=会社, 支給月="2026.11支給", NO="1", 項目="通勤手当", 値="500"),
    ]
    return t


def test_8つのタブが型の見出しで起きる():
    o = 起.起こす(2027, _前の年の台帳())
    assert o["台帳の名"] == "台帳_2027"
    assert list(o["タブ"]) == list(起.台帳のタブ) and len(起.台帳のタブ) == 8
    for k, 表 in o["タブ"].items():
        assert 表[0] == 形.見出し(k)


def test_新しい年の行だけ引き継ぎ前の年の行は前の確定した勤怠へ():
    o = 起.起こす("2027", _前の年の台帳())
    指示 = 形.行たち(o["タブ"]["その月だけの指示"])
    assert [(r["支給月"], r["NO"], r["項目"], r["値"]) for r in 指示] == [("2027.01支給", "2", "社保の立て替えの残り", "1500")]
    assert o["引き継いだ行"] == {k: (1 if k == "その月だけの指示" else 0) for k in 起.台帳のタブ}
    assert len(o["前の確定した勤怠"]) == 4 and len(o["前の確定した勤怠の区間"]) == 3
    assert o["知らせ"] == []


def test_往復で行が落ちない():
    前 = _前の年の台帳()
    o = 起.起こす(2027, 前)
    元 = sorted(tuple(r) for k in 起.台帳のタブ for r in 前[k][1:])
    新 = sorted(tuple(r) for k in 起.台帳のタブ for r in o["タブ"][k][1:])
    前の年 = [tuple(r) for k in 起.台帳のタブ for r in 前[k][1:] if r[1].startswith("2026.")]
    assert sorted(新 + 前の年) == 元
    # 前の年の確定した勤怠は渡した値のまま（月を回す の 前の確定した勤怠 へそのまま渡す）
    assert o["前の確定した勤怠"] == 前["確定した勤怠"] and o["前の確定した勤怠の区間"] == 前["確定した勤怠の区間"]


def test_返った前の年の確定した勤怠を月を回すの読み口が読む():
    o = 起.起こす(2027, _前の年の台帳())
    A, B = 形.確定した勤怠を読む(o["前の確定した勤怠"], o["前の確定した勤怠の区間"])
    assert {(a["NO"], a["日付"], a["支給月"]) for a in A} == {("1", "2025-12-01", "2026-01"), ("1", "2026-11-30", "2026-12"),
                                                         ("2", "2026-11-30", "2026-12")}
    assert len(B) == 2


def test_12月の立て替えの続きの行が無い人を知らせる():
    t = _前の年の台帳()
    t["その月だけの指示"] = [r for r in t["その月だけの指示"] if r[1] != "2027.01支給"]
    o = 起.起こす(2027, t)
    assert len(o["知らせ"]) == 1 and "NO 2" in o["知らせ"][0] and "2027.01支給" in o["知らせ"][0]


def test_有給の数え始めが前の年の台帳より前の人を知らせる():
    社員 = [["会社", "NO", "入社日", "退職日", "有給の始めの日"],   # マスタ「社員」の一部の列（読む列だけ）
          [会社, "1", "2020-04-01", "", "2024-11-30"],    # 2024-12-01 から数える＝前の年の台帳（2025-12-01 から）より前
          [会社, "2", "2020-04-01", "", "2026-11-29"],    # 前の年の台帳の中
          [会社, "3", "2020-04-01", "2024-01-31", ""]]    # 前の年に居ない人は見ない
    o = 起.起こす(2027, _前の年の台帳(), 社員=社員)
    assert len(o["知らせ"]) == 1 and "NO 1" in o["知らせ"][0] and "有給の始めの日" in o["知らせ"][0]


# ---- 注入の試験: 欠けた前の年・知らない形は既定で止める ----

def test_前の年の台帳が無いと止まる():
    with pytest.raises(起.年の台帳の誤り, match="前の年"):
        起.起こす(2027, None)


def test_会社を始めた年は訳を書けば空の台帳が起きる():
    o = 起.起こす(2027, None, 前の年が無い訳="2027.01支給 から始めた会社")
    assert all(表 == [形.見出し(k)] for k, 表 in o["タブ"].items())
    assert o["前の確定した勤怠"] == [形.見出し("確定した勤怠")]
    with pytest.raises(起.年の台帳の誤り, match="どちらか"):
        起.起こす(2027, _前の年の台帳(), 前の年が無い訳="取り違え")


def test_タブが欠けると止まる():
    t = _前の年の台帳()
    del t["確定した勤怠の区間"]
    with pytest.raises(起.年の台帳の誤り, match="無い"):
        起.起こす(2027, t)


@pytest.mark.parametrize("名", ["勤怠", "月の変動", "知らないタブ"])
def test_前の台帳のタブや型に無いタブは止まる(名):
    t = _前の年の台帳()
    t[名] = [["会社"]]
    with pytest.raises(起.年の台帳の誤り):
        起.起こす(2027, t)


def test_dictの並びは止まる():
    t = _前の年の台帳()
    t["その月だけの指示"] = 形.行たち(t["その月だけの指示"])
    with pytest.raises(起.年の台帳の誤り, match="get_values"):
        起.起こす(2027, t)


def test_見出しが型と違うと止まる():
    t = _前の年の台帳()
    t["締めの記録"][0] = t["締めの記録"][0][:-1]
    with pytest.raises(起.年の台帳の誤り, match="見出し"):
        起.起こす(2027, t)


@pytest.mark.parametrize("支給月", ["2025.12支給", "2026-12", "2026.13支給", ""])
def test_どの年か分からない行は止まる(支給月):
    t = _前の年の台帳()
    t["人ごとの月の数字"].append(_行("人ごとの月の数字", 会社=会社, 支給月=支給月, NO="9"))
    with pytest.raises(起.年の台帳の誤り, match="支給月"):
        起.起こす(2027, t)


def test_前の年の確定した勤怠が無いと止まる():
    t = _前の年の台帳()
    t["確定した勤怠"] = [t["確定した勤怠"][0]]
    t["確定した勤怠の区間"] = [t["確定した勤怠の区間"][0]]
    with pytest.raises(起.年の台帳の誤り, match="1 行も無い"):
        起.起こす(2027, t)


def test_前の年の台帳を取り違えると止まる():
    # 2026 年の台帳を 2028 年を起こすのに渡した（前の年は 2027）＝どの行も 2027 年でも 2028 年でもない
    with pytest.raises(起.年の台帳の誤り):
        起.起こす(2028, _前の年の台帳())


def test_読めない確定した勤怠は止まる():
    t = _前の年の台帳()
    i = 形.見出し("確定した勤怠").index("読み取りの確かめ")
    t["確定した勤怠"][1][i] = "要確認"
    with pytest.raises(起.年の台帳の誤り, match="読めない"):
        起.起こす(2027, t)


def test_年の字が読めないと止まる():
    with pytest.raises(起.年の台帳の誤り, match="4 桁"):
        起.起こす("27", _前の年の台帳())
