# ---- 前の年の確定した勤怠だけを返す口（毎月の 月を回す へ渡す。1 月だけでなく 2〜12 月も） ----

def test_前の年の確定した勤怠だけを返す口は起こすと同じ値を返す():
    前 = _前の年の台帳()
    o = 起.起こす(2027, 前, 今ある名=[], 社員=社員)
    y = 起.前の年の確定した勤怠(2027, 前, 社員=社員)
    assert set(y) == {"前の確定した勤怠", "前の確定した勤怠の区間", "知らせ"}   # 書く手順・タブを返さない（台帳を起こさない）
