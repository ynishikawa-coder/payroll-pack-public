"""社保の立て替えの残り（社保.引けない月の本人負担＝立て替えて復帰後に引く）を前の月の確定した結果から次の月へ渡す（作り物の会社 C1）。

1. 前の月に残りがある人は、その月の 台帳「その月だけの指示」の行（月次が前の月の結果から書いた物）で返しが引かれ、
   残りは次の支給月の その月だけの指示 の行として返る（人が写さない）。返った表を次の月の段の解決へ渡すと 入力 になる。
2. 立て替える式の人にその月の行が無い（前の月の確定した結果が無い）なら、残りを黙って 0 にせず仮＋問い 1 つ（出口へ出ない）。
3. 回帰の見張り: 式が立て替えでない会社は行が無くても今のまま（仮にしない・次の月の行も書かない）。
"""
import importlib.util
import sys
from decimal import Decimal
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
sys.path.insert(0, str(根 / "tests" / "月次"))
_spec = importlib.util.spec_from_file_location("月次_試験_立て替えの残りの元", 根 / "tests" / "月次" / "test_月次.py")
元 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(元)

作, C, 支給月, 人たち, 段, 月次 = 元.作, 元.C, 元.支給月, 元.人たち, 元.段, 元.月次
名 = "社保の立て替えの残り"
立て替え = {"社保.引けない月の本人負担": "立て替えて復帰後に引く"}


def _行(NO, 値, 月=支給月):
    return {"会社": C, "支給月": 月, "NO": NO, "項目": 名, "値": 値, "中身": "2027.01支給 の確定した結果の残り（月次が書く）"}


def _回す(tmp_path, 会社=None, 指示=None):
    tabs引数 = {"会社": 会社} if 会社 else {}
    if 指示 is not None:
        tabs引数["その月だけの指示"] = 指示
    return 元._回す(tmp_path, **tabs引数)


def _額(o, NO) -> dict:
    return {r.項目: r.値 for r in o["関所を通った"].行たち if r.NO == NO}


def _次の月の行(o) -> dict:
    h, *rows = o["台帳"]["その月だけの指示"]
    assert h == 月次.台帳の形.見出し("その月だけの指示")
    return {r[h.index("NO")]: dict(zip(h, r)) for r in rows}


# ---- 1. 前の月の残りが返しで引かれ、残りが次の月の行になる ----
def test_前の月に残りがある人の次の月で返しが引かれる(tmp_path):
    _, _, 無 = _回す(tmp_path / "無", 立て替え, [_行(n, "0") for n in 人たち])
    _, _, o = _回す(tmp_path / "有", 立て替え, [_行("0001", "50,000"), _行("0002", "0"), _行("0003", "0")])
    assert set(元._出た人(o)["取り込み"]) == set(人たち)
    一 = _額(o, "0001")
    assert 一["社保の立て替えの返し"] == 50000 and 一[名] == 0
    assert 一["差引支給額"] == _額(無, "0001")["差引支給額"] - 50000
    次 = _次の月の行(o)
    assert set(次) == set(人たち)                                         # 立て替える式の人は 0 でも書く（行が無い＝結果が無い と分ける）
    assert {r["支給月"] for r in 次.values()} == {"2027.03支給"} and 次["0001"]["値"] == "0"
    assert 次["0001"]["氏名"] == "作り物 いちろう"
    # 残りは出す物に載らない
    assert all(名 not in row for x in o["支給控除一覧"] for row in x.表)


def test_給与で返し切れない残りは次の月の行に残る(tmp_path):
    _, _, o = _回す(tmp_path, 立て替え, [_行("0001", "10000000"), _行("0002", "0"), _行("0003", "0")])
    一 = _額(o, "0001")
    assert 0 < 一["社保の立て替えの返し"] < 10000000 and 一["差引支給額"] == 0
    assert Decimal(_次の月の行(o)["0001"]["値"]) == 10000000 - 一["社保の立て替えの返し"] > 0


def test_返った行を次の月の段の解決へ渡すと入力になる(tmp_path):
    tabs, _, o = _回す(tmp_path, 立て替え, [_行("0001", "10000000"), _行("0002", "0"), _行("0003", "0")])
    表 = o["台帳"]["その月だけの指示"]
    r = 段.解く("2027.03支給", **月次._台帳のタブを段へ({**tabs, "その月だけの指示": 表}))
    残り = Decimal(_次の月の行(o)["0001"]["値"])
    assert Decimal(r["入力"][(C, "0001")][名]) == 残り > 0
    assert r["入力"][(C, "0002")][名] == "0"
    assert not [q for q in r["仮の値"] if q["項目"] == "台帳.月の変動"]


# ---- 2. 前の月の結果が無いのに残りの要る人は止まる ----
def test_前の月の結果が無い立て替えの人は仮で出口へ出ない(tmp_path):
    _, _, o = _回す(tmp_path, 立て替え, [_行("0001", "0"), _行("0002", "0")])   # 0003 の行が無い
    出た = 元._出た人(o)
    assert "0003" not in 出た["関所を通った"] | 出た["取り込み"] | 出た["支給控除一覧"]
    assert {"0001", "0002"} <= 出た["取り込み"]
    問い = o["問い"]["立て替えの残り"]
    assert [q["NO"] for q in 問い] == ["0003"] and 名 in 問い[0]["何が無いか"]
    assert 問い[0]["反映先"] == "台帳/その月だけの指示"
    assert "0003" not in _次の月の行(o)                                   # 仮の人の残りは次の月へ書かない（次の月も止まる）


def test_その月だけの指示が無い月は立て替えの人が全員止まる(tmp_path):
    _, _, o = _回す(tmp_path, 立て替え)
    assert not 元._出た人(o)["取り込み"]
    assert sorted(q["NO"] for q in o["問い"]["立て替えの残り"]) == sorted(人たち)


# ---- 3. 回帰の見張り ----
def test_立て替えでない会社は行が無くても今のまま(tmp_path):
    _, _, o = _回す(tmp_path)
    assert set(元._出た人(o)["取り込み"]) == set(人たち)
    assert o["問い"]["立て替えの残り"] == [] and _次の月の行(o) == {}
