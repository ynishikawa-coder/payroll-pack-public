"""作り物の回帰の見張り: 清算期間が 1 か月を超えるフレックスの、前の月の実働を殻（月次）が年の台帳の確定した勤怠から数え直して芯へ渡す。

答えは厚生労働省「フレックスタイム制のわかりやすい解説＆導入の手引き」の 4〜6 月の例（実働 220・180・140 時間
→ 6 月の清算 857 分）。前の月の行は台帳の 支給月 の列で引く（作り物の会社・作り物の人だけ）。
年をまたぐ清算期間（11〜1 月）は前の年の台帳の行と締めの記録から引く。前の月はその月の決まりと法の線で数え直す。"""
import sys
from datetime import date, timedelta
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根))
sys.path.insert(0, str(根 / "tests" / "集計"))

import 月次  # noqa: E402
from 作る_集計 import 一つ, 人の鍵, 日, 区, 既定の決まり, 法の線  # noqa: E402
from 芯.集計 import 集計する  # noqa: E402

C, NO = 人の鍵["会社"], 人の鍵["NO"]
期 = {"起算日": "2026-04-01", "終わりの日": "2026-06-30", "総労働時間": "520"}


def _月(始め: date, 日数: int, 働く日: int, 時間: int):
    """支給月 = 始めの年月。平日の頭から 働く日 の日だけ 9:00 から 時間 働く（休憩 1 時間）。"""
    月 = 始め.isoformat()[:7]
    A, B, n = [], [], 0
    for i in range(日数):
        d = 始め + timedelta(days=i)
        s = d.isoformat()
        if d.weekday() < 5 and n < 働く日:
            n += 1
            A.append({**日(s), "支給月": 月})
            B += [{**区(s, 1, "9:00", f"{10 + 時間}:00"), "支給月": 月}, {**区(s, 2, "12:00", "13:00", "休憩"), "支給月": 月}]
        else:
            A.append({**日(s, "休日"), "支給月": 月})
    return A, B


四月, 五月, 六月 = _月(date(2026, 4, 1), 30, 22, 10), _月(date(2026, 5, 1), 31, 18, 10), _月(date(2026, 6, 1), 30, 20, 7)
三月 = _月(date(2026, 3, 1), 31, 20, 8)   # 前の清算期間の月


def _決(期=期):
    return {(C, NO): 既定の決まり(**{"時間.制度": "フレックス", "時間.フレックスの清算期間": 期})}


def _締め(*月たち, 状態="締まった"):
    return [["支給月", "会社", "NO", "状態"], *[[m, C, NO, 状態] for m in 月たち]]


締まった = _締め("2026-03", "2026-04", "2026-05")


def _前(全, 前の全=((), ()), 決=None, 月="2026-06", 始め="2026-06-01", 締め=締まった, 前の締め=(), 元=None):
    決 = 決 or _決()
    元 = 元 or (lambda 前の月: (決, 法の線))   # 既定: 前の月も今の月と同じ決まりと法の線
    return 月次._フレックスの前の月(全[0], 全[1], 前の全[0], 前の全[1], C, 月, 始め, 決, 法の線, 締め, 前の締め, 元)


def _足す(*月たち):
    return [a for m in 月たち for a in m[0]], [b for m in 月たち for b in m[1]]


def test_台帳の前の月から数え直して清算の終わりの月が出る():
    前 = _前(_足す(三月, 四月, 五月, 六月))
    assert sorted(前, key=lambda x: x["始め"]) == [{"会社": C, "NO": NO, "始め": "2026-04-01", "終わり": "2026-04-30", "実働": 13200},
                 {"会社": C, "NO": NO, "始め": "2026-05-01", "終わり": "2026-05-31", "実働": 10800}]   # 3 月は前の清算期間＝渡さない
    x = 集計する(*六月, 決まり=_決(), 法の線=法の線, フレックスの前の月=前)
    assert x["人"][0]["状態"] == "確認済" and 一つ(x, "法定外残業") == 857


期の冬 = {"起算日": "2025-11-01", "終わりの日": "2026-01-31", "総労働時間": "500"}
十一月, 十二月, 一月 = (_月(date(2025, 11, 1), 30, 20, 9), _月(date(2025, 12, 1), 31, 21, 8),
                    _月(date(2026, 1, 1), 31, 19, 8))


def test_年をまたぐ清算期間は前の年の台帳の締まった月を渡し終わりの月が出る():
    前の締め = _締め("2025-11", "2025-12")
    前 = _前(_足す(一月), 前の全=_足す(十一月, 十二月), 決=_決(期の冬), 月="2026-01", 始め="2026-01-01", 締め=_締め(), 前の締め=前の締め)
    assert sorted(x["始め"] for x in 前) == ["2025-11-01", "2025-12-01"]
    x = 集計する(*一月, 決まり=_決(期の冬), 法の線=法の線, フレックスの前の月=前)
    assert x["人"][0]["状態"] == "確認済"


def test_年をまたぐ清算期間で前の年の締めが無い月は渡さず終わりの月が仮():
    for 前の締め in ((), _締め(), _締め("2025-11"), _締め("2025-11", "2025-12", 状態="締めを外した")):
        前 = _前(_足す(一月), 前の全=_足す(十一月, 十二月), 決=_決(期の冬), 月="2026-01", 始め="2026-01-01", 締め=_締め(),
                前の締め=前の締め)
        assert "2025-12-01" not in [x["始め"] for x in 前]
        x = 集計する(*一月, 決まり=_決(期の冬), 法の線=法の線, フレックスの前の月=前)
        assert x["人"][0]["状態"] == "仮"
    # 今の年の締めの記録に前の年の月が 締まった と書いてあっても前の年の月は前の年の台帳の締めで決める
    前 = _前(_足す(一月), 前の全=_足す(十一月, 十二月), 決=_決(期の冬), 月="2026-01", 始め="2026-01-01",
            締め=_締め("2025-11", "2025-12"), 前の締め=())
    assert 前 == []


def test_前の年の月の行は前の年の台帳からだけ引く():
    # 前の年の月の行が今の年の台帳に紛れていても読まない（前の年の台帳に無ければ渡さない）
    前 = _前(_足す(十一月, 十二月, 一月), 決=_決(期の冬), 月="2026-01", 始め="2026-01-01", 締め=_締め("2025-11", "2025-12"),
            前の締め=_締め("2025-11", "2025-12"))
    assert 前 == []


def test_前の月はその月の決まりと法の線で数え直す(monkeypatch):
    呼ばれた, 渡した = [], []
    本物 = 月次.集計する

    def 見る(*a, **k):
        渡した.append((k["支給月"], k["決まり"], k["法の線"]))
        return 本物(*a, **k)
    monkeypatch.setattr(月次, "集計する", 見る)
    四月の線 = {**法の線, "出所": "四月の線"}
    五月の決 = {k: {**v, "備考": "五月の決まり"} for k, v in _決().items()}

    def 元(前の月):
        呼ばれた.append(前の月)
        return (五月の決, 法の線) if 前の月 == "2026-05" else (_決(), 四月の線)
    前 = _前(_足す(四月, 五月, 六月), 元=元)
    assert sorted(x["始め"] for x in 前) == ["2026-04-01", "2026-05-01"]
    assert 呼ばれた == ["2026-05", "2026-04"]
    assert {m: (決[(C, NO)].get("備考"), 線.get("出所")) for m, 決, 線 in 渡した} == {
        "2026-05": ("五月の決まり", None), "2026-04": (None, "四月の線")}


def test_前の月の決まりか法の線が揃わない月と前の月にフレックスでない人は渡さず終わりの月が仮():
    for 元 in (lambda m: None if m == "2026-05" else (_決(), 法の線),
               lambda m: ({(C, NO): 既定の決まり()}, 法の線) if m == "2026-05" else (_決(), 法の線),   # 5 月は通常の働き方
               lambda m: ({}, 法の線) if m == "2026-05" else (_決(), 法の線)):                        # 5 月はその人が仮
        前 = _前(_足す(四月, 五月, 六月), 元=元)
        assert [x["始め"] for x in 前] == ["2026-04-01"]
        x = 集計する(*六月, 決まり=_決(), 法の線=法の線, フレックスの前の月=前)
        assert x["人"][0]["状態"] == "仮"


def test_締まっていない月と仮の残る月は渡さず終わりの月が仮():
    前 = _前(_足す(四月, 五月, 六月), 締め=_締め("2026-04"))
    assert [x["始め"] for x in 前] == ["2026-04-01"]
    五月の区 = [dict(b) for b in 五月[1]]
    五月の区[0]["終わり"] = ""   # 5 月の 1 日の終わりの時刻が空＝5 月の数えが仮
    前 = _前(_足す(四月, (五月[0], 五月の区), 六月))
    assert [x["始め"] for x in 前] == ["2026-04-01"]
    x = 集計する(*六月, 決まり=_決(), 法の線=法の線, フレックスの前の月=前)
    assert x["人"][0]["状態"] == "仮"


def test_前の月が台帳に無ければ渡さず芯が仮にする():
    前 = _前(_足す(五月, 六月))
    x = 集計する(*六月, 決まり=_決(), 法の線=法の線, フレックスの前の月=前)
    assert x["人"][0]["状態"] == "仮"


def test_1か月の清算期間とフレックスでない人は数え直さない():
    assert _前(_足す(四月, 五月, 六月), 決=_決({"起算日": "2026-06-01", "終わりの日": "2026-06-30", "総労働時間": "160"})) == []
    assert _前(_足す(四月, 五月, 六月), 決={(C, NO): 既定の決まり()}) == []
