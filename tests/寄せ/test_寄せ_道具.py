def test_事務所の設定の置き場タブの型は_Drive_の型_8_と置き場の検査に合う():
    """置き場タブの 物 の名は 型.json の 木.置き場の物 を指し（文書 Drive の型.md も写さず指す）、
    会社 を空にしてよいと書かない（§1・置き場の検査の項目 6 は 会社 が空の行を赤にする）。
    根（2026-11-19）: 型.json だけが「組の物は 会社 が空・物=組の根」と書き、型どおりの表は検査で赤・
    型を読んだ殻は検査に合わせた実の表から根を引けなかった。"""
    import re
    型 = 当てる.型を開く(型の正本)
    tab = next(t for s in 型["シート"] if s["シート"] == "事務所の設定" for t in s["タブ"] if t["タブ"] == "置き場")
    意味 = {c["名"]: c["意味"] for c in tab["列"]}
    文書 = (ここ.parent.parent / "docs" / "設計" / "Drive の型.md").read_text(encoding="utf-8")
    # 物の名の正本は 型.json の 木.置き場の物 の 1 か所: 型の列の意味も文書もそこを指し、並びを写さない（写すと台帳の名がずれた）
    assert "木.置き場の物" in 意味["物"] and "木.置き場の物" in 文書
    assert not re.search(r"物＝会社の根・", 文書)
    assert "空" not in 意味["会社"].replace("空にしない", "")
    # 会社 が空の行は置き場の検査が赤にする（型の意味が 空 を許すと型どおりの表が赤になる）
    行 = [[c["名"] for c in tab["列"]], ["C0001", "作り物の会社", "作り物の組", "会社の根", "x"],
         ["C0001", "", "作り物の組", "2_マスタ", "y"]]
    一覧 = [["顧客ID", "会社", "組"], ["C0001", "作り物の会社", "作り物の組"]]
    r = 見回り.置き場の検査({"会社": "作り物の会社", "置き場": [],
                          "シート": {"00_事務所/事務所の設定": {"置き場": 行, "会社の一覧": 一覧}}}, dt.date(2026, 11, 11), 型)
    assert (6, "00_事務所/事務所の設定/置き場") in [(x["項目"], x["所"]) for x in r], r
    assert {x["項目"] for x in r} <= {6, 8}, r


