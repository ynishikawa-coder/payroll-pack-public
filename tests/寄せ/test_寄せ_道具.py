def test_口の記録だけはその置き場の決まった名で置ける_ほかの_json_は赤():
    """寄せの記録（会社の 9_履歴）と消す問いの答え（00_事務所/9_履歴）は口の記録＝Drive に置く物。
    名の形・置き場が 1 つでも違う .json は AI の作業の物のまま赤（注入: 置き場違い・名の形違い・ほかの .json）。"""
    def 五(置き場):
        r = 見回り.置き場の検査({"会社": "作り物の会社", "置き場": 置き場}, dt.date(2026, 11, 22))
        return [x["所"] for x in r if x["項目"] == 5]
    良い = ["9_履歴/寄せの記録_2026-11-22_093015.json", "00_事務所/9_履歴/消す問いの答え_2026-11-22_101500.json",
          "00_事務所/9_履歴/置き場の登録の写し_2026-11-22_103000.json"]
    assert 五(良い) == []
    悪い = ["8_確認事項/寄せの記録_2026-11-22_093015.json",          # 置き場違い
            "00_事務所/9_履歴/寄せの記録_2026-11-22_093015.json",   # 種類と置き場が合わない
            "9_履歴/消す問いの答え_2026-11-22_101500.json",          # 会社の 9_履歴 に答えは置かない
            "9_履歴/置き場の登録の写し_2026-11-22_103000.json",      # 登録の写しは事務所の 9_履歴 だけ
            "00_事務所/9_履歴/置き場の登録の写し_2026-11-22.json",   # 名の形違い（時刻が無い）
            "9_履歴/寄せの記録_2026-11-22.json",                     # 名の形違い（時刻が無い）
            "9_履歴/寄せの記録_2026-11-22_093015.json.bak.json",     # 尾が違う
            "9_履歴/計算の途中.json"]                                # ほかの .json
    assert 五(悪い) == 悪い
