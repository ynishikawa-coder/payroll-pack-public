def 管理表(*行):
    """管理表「会社」の今の値（作り物）。行＝(会社, 寄せ, 寄せの理由, 最後に配った日)。見出しは管理表の口の型から。"""
    h = 管理表の口.見出し("会社")
    out = [h]
    for 会社, 寄せ, 理由, 日 in 行:
        r = {**{k: "" for k in h}, "会社": 会社, "組": 会社, "型の版": "0", "寄せ": 寄せ, "寄せの理由": 理由, "最後に配った日": 日}
        out.append([r[k] for k in h])
    return out


