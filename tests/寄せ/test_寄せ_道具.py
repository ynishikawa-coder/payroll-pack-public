def test_見回りは消す日の過ぎた物と前の形の置き場を並べ_消さない():
    直し30 = {"版": 3, "前の版": 2, "なぜ": "作り物", "操作": [{"する": "前の置き場を止める", "前": "99_消してよい物/", "後": "9_履歴/"}]}
    会社 = {"会社": "作り物の会社", "型の版": 0, "置き場": [
        "9_履歴/", "9_履歴/消す_2026-11-01_作り物", "9_履歴/消す_2027-12-31_まだ", "9_履歴/名だけ",
        "99_消してよい物/前の木", "1_決まり/旧_作り物.md", "80_答え（照合用）/"]}
    r = 見回り.見回り([会社], [直し1, 直し2, 直し30], 3, dt.date(2026, 11, 11), "作り物の窓")
    物 = {x["物"]: x for x in r["消す問い"]}
    # 消す日の無い 9_履歴 の物（名だけ）は残す物・消す日の来ていない物（まだ）も並べない
    assert set(物) == {"消す_2026-11-01_作り物", "前の木", "旧_作り物.md", "80_答え（照合用）"}
    assert 物["消す_2026-11-01_作り物"]["消す手順"] == [{"する": "file を消す", "名": "9_履歴/消す_2026-11-01_作り物"}]
    # 前の形の置き場は消さずに作り直す（寄せも同じ名で止まる）
    assert 物["前の木"]["中身はどこに在るか"] == "前の形の置き場" and "作り直す" in 物["前の木"]["推奨"] and 物["前の木"]["消す手順"] == []
    assert r["前の版のままの会社"] == [{"会社": "作り物の会社", "型の版": 0}]
    assert r["消してよい直し"] == []
    r = 見回り.見回り([{**会社, "型の版": 3}], [直し1, 直し2, 直し30], 3, dt.date(2026, 11, 11),
                    前の答え={"作り物の会社/9_履歴/消す_2026-11-01_作り物": "残す:2027-01-31"})
    assert r["消してよい直し"] == [1, 2, 3]
    assert "消す_2026-11-01_作り物" not in {x["物"] for x in r["消す問い"]}


