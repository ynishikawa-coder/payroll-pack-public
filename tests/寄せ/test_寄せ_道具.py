@pytest.mark.parametrize("する", ["寄せる", "配る"])
def test_呼び口の寄せると配る(する, capsys, tmp_path):
    会社 = tmp_path / "会社.json"  # 殻が渡す形: 前の形の読み替えは人の答えの中（作り物の殻.py）
    会社.write_text(json.dumps(作り物の殻.前の形を渡す(json.loads((ここ / "作り物の前の形.json").read_text(encoding="utf-8"))),
                             ensure_ascii=False), encoding="utf-8")
    会社 = str(会社)
    args = [する, "--型", str(型の正本), "--今日", "2026-11-11"]
    args += ["--会社", 会社] if する == "寄せる" else ["--会社たち", 会社]
    assert 呼び口.main(args) == 0
    out = json.loads(capsys.readouterr().out)
    assert out["人が見る物"]


def test_寄せの型の列は型の口の見出しと同じ():
    """型を読む決まり（項目の列の広げ方）は 初期設定/型の口.py の 1 か所。寄せの読みと型の口の見出しが全部のタブで同じ。"""
    型 = json.loads(型の正本.read_text(encoding="utf-8"))
    K = 当てる.型を読む(当てる.型を開く(型の正本))
    for s in 型["シート"]:
        for t in s["タブ"]:
            寄せの = [c["名"] for c in K["ファイル"][当てる.組の根から(s.get("置き場", ""), s["シート"])][t["タブ"]]]
            assert 寄せの == 当てる.型の口.見出し(s["シート"], t["タブ"]), f'{s["シート"]}/{t["タブ"]}'
