def test_見回りは置き場の検査の6つを1つの口で当てる():
    型 = 当てる.型を開く(型の正本)
    会社の列 = ["会社", "項目", "今の値", "適用開始"]
    会社 = {"会社": "作り物の会社", "型の版": 3, "置き場": [
        "1_決まり/", "1_決まり/給与のルール.md", "1_決まり/質問と回答", "2_マスタ", "台帳_2027", "8_確認事項/",
        "3_月ごと/2027.01支給（12月分）/1_届いた物/勤怠_2027-01-05_作り物.pdf",
        "作業の場/",                                              # 1 木に無い名
        "3_月ごと/2027.01支給（12月分）/途中/",                    # 1 月のフォルダの外の名
        "1_決まり/前の決まり.html",                               # 2 1_決まり/ の 4 つの外
        "9_履歴/旧_作り物",                                       # 3 旧_
        "9_履歴/消す_2026-11-01_作り物",                          # 4 消す日が過ぎた（知らせ）
        "9_履歴/計算の途中.py", "8_確認事項/引き継ぎのメモ",       # 5 AI の作業の物
        "00_事務所/事務所の設定", "00_事務所/メモ"],               # 事務所の根の木（メモは木に無い名）
        "シート": {"2_マスタ": {"会社": [会社の列, ["作り物の会社", "支払.締め日", "末", ""], ["", "支払.支給日", "25", ""]],
                             "知らないタブ": [["会社", "何か"], ["作り物の会社", "1"]],
                             "社員": [["NO", "氏名"], ["0001", "作り物"]]}}}
    r = 見回り.見回り([会社], [直し1, 直し2], 3, dt.date(2026, 11, 11), "作り物の窓", 型=型)
    項目 = sorted({x["項目"] for x in r["置き場の検査"]})
    assert 項目 == [1, 2, 3, 4, 5, 6], r["置き場の検査"]
    assert (1, "00_事務所") not in {(x["項目"], x["所"]) for x in r["置き場の検査"]}
    所 = {(x["項目"], x["所"]) for x in r["置き場の検査"]}
    assert {(1, "作業の場"), (1, "3_月ごと/2027.01支給（12月分）/途中"), (2, "1_決まり/前の決まり.html"),
            (5, "9_履歴/計算の途中.py"), (5, "8_確認事項/引き継ぎのメモ"), (1, "00_事務所/メモ"),
            (6, "2_マスタ/会社"), (6, "2_マスタ/知らないタブ"), (6, "2_マスタ/社員")} <= 所
    assert r["赤"] and all(x["赤"] == (x["項目"] != 4) for x in r["置き場の検査"])
    assert "置き場の検査" in r["人が見る物"]
    # 木のとおりの置き場は赤 0（消す日の来ていない物・名だけの 9_履歴 の物も）
    きれい = {"会社": "作り物の会社", "型の版": 3, "置き場": [x for x in 会社["置き場"][:7]] + ["9_履歴/名だけ", "00_事務所/管理表"],
            "シート": {"2_マスタ": {"会社": [会社の列, ["作り物の会社", "支払.締め日", "末", ""]]}}}
    r = 見回り.見回り([きれい], [直し1, 直し2], 3, dt.date(2026, 11, 11), 型=型)
    assert r["置き場の検査"] == [] and not r["赤"]
