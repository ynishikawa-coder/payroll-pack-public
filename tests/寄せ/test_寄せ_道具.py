def test_見回りは期限の来た物と期限の無い物を並べ_消さない():
    会社 = {"会社": "作り物の会社", "型の版": 0, "置き場": [
        "99_消してよい物/", "99_消してよい物/20261031_作り物", "99_消してよい物/20271231_まだ", "99_消してよい物/名だけ",
        "90_履歴/消す_2026-11-01_作り物", "01_ルール/旧_作り物.md", "80_答え（照合用）/"]}
    r = 見回り.見回り([会社], [直し1, 直し2], 2, dt.date(2026, 11, 11), "作り物の窓")
    物 = {x["物"]: x for x in r["消す問い"]}
    assert set(物) == {"20261031_作り物", "名だけ", "消す_2026-11-01_作り物", "旧_作り物.md", "80_答え（照合用）"}
    assert 物["名だけ"]["推奨"].startswith("期限を付ける") and 物["名だけ"]["消す手順"] == []
    assert r["前の版のままの会社"] == [{"会社": "作り物の会社", "型の版": 0}]
    assert r["消してよい直し"] == []
    r = 見回り.見回り([{**会社, "型の版": 2}], [直し1, 直し2], 2, dt.date(2026, 11, 11),
                    前の答え={"作り物の会社/99_消してよい物/名だけ": "残す:2027-01-31"})
    assert r["消してよい直し"] == [1, 2]
    assert "名だけ" not in {x["物"] for x in r["消す問い"]}


