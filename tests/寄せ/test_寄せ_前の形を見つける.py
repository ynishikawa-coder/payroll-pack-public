"""見張り: 前の形を黙って「前と同じ」で通さない（段 10 寄せ）。作り物の値だけ。

1. 管理表の型の版が今の版でも、質問と回答の質問のタブが前の版の形なら、形から版を見て直しを当てる（知らせに出す）。
2. 型に無いシート（前の置き場の 質問と回答 など）に値が在れば寄せられない物に出す。人の答えで型の置き場へ移すと直しが当たる。
3. 管理表へ書く（型の版）は、書いた後の照らす回（書く手順 0・寄せられない物 0）にだけ出る。
4. 直し 11: 台帳「人ごと」の前の列は 欠勤日数→欠勤・実働計→総労働 へ名を変え、月の語に無い列の値は寄せられない物。
"""
import copy
import datetime as dt
import json
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根 / "道具" / "寄せ"))
sys.path.insert(0, str(ここ))
import 当てる  # noqa: E402
import 作り物の殻  # noqa: E402
import 直し as 直しの形  # noqa: E402

今日 = dt.date(2026, 11, 16)
Q, 帳 = "1_決まり/質問と回答", "台帳_2026"


def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(根 / "初期設定" / "型.json"), 直しの形.読む(), 今日)


def 殻なしで寄せる(会社):
    """前の形の読み替え（作り物の事務所の塊）を渡さない＝パックの直しだけ。"""
    return 当てる.見通す(会社, 当てる.型を開く(根 / "初期設定" / "型.json"), 直しの形.読む(), 今日)


def 今の形の会社():
    前 = json.loads((ここ / "作り物の前の形.json").read_text(encoding="utf-8"))
    r = 寄せる(前)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    会社 = 当てる.手順を当てる(前, r["書く手順"])
    会社["型の版"] = r["寄せた後の値"]["型の版"]
    return 会社


def _列を抜く(rows, *列たち):
    for c in 列たち:
        i = rows[0].index(c)
        for x in rows:
            del x[i]


def test_管理表の版が今でも質問のタブが前の形なら直しを当てる():
    会社 = 今の形の会社()
    今 = copy.deepcopy(会社["シート"][Q]["質問"])
    _列を抜く(会社["シート"][Q]["質問"], "対象", "理由", "分かっている事", "資料", "探した資料", "くわしく", "変わる事")  # 版 9 の形
    r = 寄せる(会社)
    assert r["寄せられない物"] == [] and r["前の版"] == 9 and r["管理表の型の版"] == 会社["型の版"]
    assert any("版 9 の形" in x for x in r["知らせ"])
    書いた = 当てる.手順を当てる(会社, r["書く手順"])
    assert 当てる.そろえる(書いた["シート"][Q]["質問"]) == 当てる.そろえる(今)
    assert r["管理表へ書く"] == []   # 書く手順がある回は書かない（照らす回に出す）


def test_型に無いシートの値は寄せられない物で_型の置き場へ移すと直しが当たる():
    会社 = 今の形の会社()
    会社["シート"]["01_前の置き場/質問と回答"] = 会社["シート"].pop(Q)
    会社["置き場"] = [x.replace(Q, "01_前の置き場/質問と回答") for x in 会社["置き場"]]
    r = 寄せる(会社)
    [x] = [x for x in r["寄せられない物"] if x["種類"] == "行き先の無いシート"]
    assert x["所"] == "01_前の置き場/質問と回答" and f"型の置き場へ移す:{Q}" in x["選べる答え"]
    assert r["書く手順"] == [] and r["値の保ち"]["合う"]

    会社["人の答え"] = {x["鍵"]: f"型の置き場へ移す:{Q}"}
    r = 寄せる(会社)
    assert r["寄せられない物"] == []
    assert {"する": "file を移す", "前": "01_前の置き場/質問と回答", "後": Q} in r["書く手順"]

    会社["人の答え"] = {x["鍵"]: "寄せの外に置く（型の外の file）"}
    r = 寄せる(会社)
    assert r["寄せられない物"] == [] and any("型に無いシート" in s for s in r["知らせ"])


def test_管理表へ書くは照らす回にだけ出る():
    会社 = 今の形の会社()
    会社["型の版"] = 10
    _列を抜く(会社["シート"][Q]["質問"], "対象", "理由", "分かっている事", "資料", "探した資料", "くわしく", "変わる事")  # 版 9 の形
    r = 寄せる(会社)
    assert r["書く手順"] and r["管理表へ書く"] == []
    書いた = 当てる.手順を当てる(会社, r["書く手順"])
    書いた["型の版"] = 10   # 管理表はまだ前の版のまま（殻が書いた後に読み直して照らす）
    r2 = 寄せる(書いた)
    版 = r2["今の版"]
    assert r2["書く手順"] == [] and r2["管理表へ書く"] == [{"会社": "作り物の会社", "型の版": str(版), "最後に配った日": "2026-11-16"}]
    書いた["型の版"] = 版
    assert 寄せる(書いた)["管理表へ書く"] == []   # 記録が今の版なら書かない


def test_版10の人ごとは畳んだタブのまま問いにせず値を変えない():
    """直し 11 は 人ごと の前の列の名を変えていたが、型の版 27 で 人ごと は畳んだ（月の数は 人ごとの月の数字 へ月を回すが書く）＝
    前の列（出勤時間 など）の行き先を問わず、値も列も変えずに消す問い（9_履歴 へ写して消す）へ。"""
    会社 = 今の形の会社()
    会社["型の版"] = 10
    rows = 会社["シート"][帳]["人ごと"]
    rows[0] = ["会社", "支給月", "NO", "氏名", "出勤日数", "有給日数", "欠勤日数", "実働計", "出勤時間", "残業時間", "深夜", "通勤 計"]
    rows[1:] = [["作り物の会社", "2026.10支給", "1", "作り物 一郎", "20", "", "1", "9600", "9000", "", "", ""]]
    前 = copy.deepcopy(rows)
    r = 殻なしで寄せる(会社)
    assert not [x for x in r["寄せられない物"] if x["所"].startswith(f"{帳}/人ごと")], r["寄せられない物"]
    assert any(x["置き場"] == 帳 and x["物"] == "タブ 人ごと" for x in r["消す問い"])
    後 = (r["見通しの値"] or r["寄せた後の値"])["シート"][帳]["人ごと"]
    assert 後 == 当てる.そろえる(前)
    assert r["値の保ち"]["合う"]


def test_事務所の質問と回答は会社の寄せの外で_会社の置き場へ移す答えを出さない():
    """00_事務所/質問と回答 は型（質問と回答「事務所」）に在る事務所のシート。会社の寄せに渡っても 1_決まり/質問と回答 へ移す
    答えを出さない（事務所全体の問いを会社の台帳へ混ぜない）＝知らせだけ（前の道具の形から寄せる呼び口は 2026-11-27 に畳んだ）。"""
    会社 = 今の形の会社()
    会社["シート"]["00_事務所/質問と回答"] = {"質問": [["問いの番号", "質問"], ["Q2099.11-01", "作り物の事務所の問い"]]}
    r = 寄せる(会社)
    assert not [x for x in r["寄せられない物"] if x["所"] == "00_事務所/質問と回答"]
    assert any(s.startswith("00_事務所/質問と回答: 事務所のシート") for s in r["知らせ"])
    assert r["値の保ち"]["合う"]
