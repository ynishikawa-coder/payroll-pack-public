def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(型の置き場), 直しの形.読む(), 今日)


def 委託にする(会社, 雇用も=False):
    """作り物の社員（1＝月給・2＝時給）を委託に。雇用も＝2 は雇用の人のまま。"""
    社 = 会社["シート"]["03_マスタ"]["社員"]
    for r in range(1, len(社) if not 雇用も else 2):
        置く(社, r, "区分", "委託")
    return 会社


def 丸め15の会社(答え=None, 値="15", 二つ目=None, 委託=True, 雇用も=False):
    会社 = 前の形()
    型 = 会社["シート"]["03_マスタ"]["勤務の型"]
    置く(型, 1, "勤務の長さの丸め（分）", 値)
    if 二つ目 is not None:
        型.append(list(型[1]))
        置く(型, 2, "型の名", "短時間")
        置く(型, 2, "勤務の長さの丸め（分）", 二つ目)
    if 委託:
        委託にする(会社, 雇用も)
    if 答え is not None:
        会社["人の答え"] = {鍵: 答え}
    return 会社


def 会社の値(r, 名):
    rows = r["寄せた後の値"]["シート"]["03_マスタ"]["会社"]
    return [x[rows[0].index("今の値")] for x in rows[1:] if x[rows[0].index("項目")] == 名]


def 次の回(r, 答え=None):
    """寄せた後の値を書いた後の Drive（型の版は今の版）をもう一度寄せる。"""
    会社 = copy.deepcopy(r["寄せた後の値"])
    if 答え is not None:
        会社["人の答え"] = 答え
    return 寄せる(会社)


def test_前の丸めは問わず委託の実働の丸めへ切捨てで移す():
    for 値, 後 in (("15", "15分切捨て"), ("15分", "15分切捨て"), ("１５", "15分切捨て"), ("30", "30分切捨て"), ("0", "丸めない")):
        r = 寄せる(丸め15の会社(値=値))
        assert r["寄せられない物"] == [], (値, r["寄せられない物"])
        assert 会社の値(r, "委託.実働の丸め") == [後], 値
        assert 列(r["寄せた後の値"]["シート"]["03_マスタ"]["勤務の型"], 打刻) == [""], 値   # 打刻の丸めへは移さない
        assert r["書く手順"] and r["値の保ち"]["合う"], 値
        assert any("委託.実働の丸め" in x and "休憩を引いた後" in x for x in r["知らせ"]), 値
        二 = 次の回(r)   # 何度当てても同じ
        assert 二["寄せられない物"] == [] and 二["書く手順"] == [], 値


