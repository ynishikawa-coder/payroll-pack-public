# ---- 寄せの後に 段の解決 → 集計 → 計算 → 関所 ----
C, NO = "作り物の会社", "1"


def _表(rows):
    return [dict(zip(rows[0], r)) for r in rows[1:]]


def _通す(tmp_path, 答え=None, 休憩=False):
    """寄せた後の 03_マスタ の 会社・勤務の型 に、委託だけの人 1 人（時給 2000・10:22〜13:59 の 1 日）を足して通す。"""
    import 作る_計算
    import 作る_集計
    from test_計算_役員と委託 import _報酬の表
    from 芯.集計 import 集計する
    from 芯.計算 import 計算する
    from 出口 import 関所

    r = 寄せる(丸め15の会社(答え))
    assert r["寄せられない物"] == [], r["寄せられない物"]
    シ = r["寄せた後の値"]["シート"]["03_マスタ"]
    会社 = _表(シ["会社"]) + [{"会社": C, "項目": k, "今の値": v, "適用開始": ""} for k, v in {
        "支払.締め日": "末", "支払.支給日": "25", "支払.支給の月": "翌月", "時間.日の所定": "8",
        "委託.式": "時給", "委託.丸め": "切捨て", "源泉.報酬": "対象でない"}.items()]
    社員 = [{"会社": C, "NO": NO, "氏名": "作り物 一郎", "人.区分": "委託", "勤務の型": "標準"}]
    人ごと = [{"会社": C, "NO": NO, "項目": "委託.時給", "額": "2000", "適用開始": ""}]
    段の結果 = 段.解く("2026.12支給", 会社=会社, 勤務の型=_表(シ["勤務の型"]), 社員=社員, 人ごとの支給控除=人ごと)
    決 = 段の結果["決まり"]
    A = [作る_集計.日("2026-11-02")]
    B = [作る_集計.区("2026-11-02", 1, "10:22", "13:59")]
    if 休憩:
        B.append(作る_集計.区("2026-11-02", 2, "12:00", "12:30", "休憩"))
    集 = 集計する(A, B, 決まり=決, 法の線=作る_集計.法の線)
    入力 = 繋.計算の入力(段の結果["入力"], 集)
    結果 = 計算する(集["行"], 決まり=決, 人=段の結果["人"], 入力=入力, 置き場=_報酬の表(作る_計算.置き場(tmp_path)),
                 支給月="2026-11")
    z = 繋.給与の関所へ(結果, 段の結果["仮の値"])
    return 入力[(C, NO)]["委託.日ごとの実働"], 結果, 関所.通す(z["行"], z["人の状態"])


def test_寄せの後に通して15分切捨ては前の道具と一致(tmp_path):
    # 前の道具: work＝打刻の和−休憩、それを 15 分で切り捨て（timecard_tally 375・376 行）
    for 休憩, 実働, 額 in ((False, 217, 7000), (True, 187, 6000)):   # 3:37 → 3:30・3:07 → 3:00（×2000）
        日ごと, 結果, 通 = _通す(tmp_path / str(休憩), 休憩=休憩)
        assert 日ごと == {"2026-11-02": 実働}, 休憩   # 打刻の丸めは空＝1 分・休憩を引いた後
        値 = {x["項目"]: x["値"] for x in 結果["行"]}
        assert 値["委託分の報酬"] == 額, 休憩
        assert 通.人たち() == [("2026-11", C, NO)], [q["何が無いか"] for q in 結果["問い"]]


