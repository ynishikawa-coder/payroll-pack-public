def test_前の勤怠の形は寄せず人が答える():
    前 = 読む("作り物の前の形.json")
    勤怠 = 前["シート"]["台帳_2026"]["打刻"]
    勤怠[1][勤怠[0].index("出勤")] = "9:00"
    r = 寄せる(前)
