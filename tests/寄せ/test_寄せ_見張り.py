"""寄せる道具の回帰の見張り（作り物の小さな前の形のシートだけ・会社の値は使わない）。

- 寄せた後の値が黙って変わらない（作り物の寄せた後.json と同じ）
- 2 度当てても同じ（2 度目は書く手順が空）
- 書く手順を当てると寄せた後になり、戻す手順で元に戻る
- 書く手順をどこで切っても、もう一度 寄せる で同じ寄せた後になる（途中で落ちてもやり直せる）
- 寄せられない物が 1 つでもあれば書かず、寄せた後の値は前の値のまま／人の答えで書けるようになり、消す物は消さず消す問いへ
型は 初期設定/ の型.json・項目.json・雛形/ をそのまま読む（写しを持たない。前の版の型が要る試験は試験の中で小さな型を作る）。
"""
import copy
import datetime as dt
import json
import sys
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
sys.path.insert(0, str(ここ.parent.parent / "道具" / "寄せ"))

sys.path.insert(0, str(ここ))
import 当てる  # noqa: E402
import 作り物の殻  # noqa: E402
import 直し as 直しの形  # noqa: E402

今日 = dt.date(2026, 11, 11)


def 読む(名):
    return json.loads((ここ / 名).read_text(encoding="utf-8"))


def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(ここ.parent.parent / "初期設定" / "型.json"), 直しの形.読む(), 今日)


def 形(d):
    """90_履歴/ の写し（md を移した元・寄せの写し）は寄せた後の値の外＝比べない。"""
    return {"シート": {f: {t: 当てる.そろえる(v) for t, v in tabs.items()} for f, tabs in d["シート"].items()},
            "md": {k: v for k, v in d["md"].items() if not k.startswith("90_履歴/")},
            "置き場": sorted(x for x in d["置き場"] if not x.startswith("90_履歴/"))}


def test_寄せた後の値が黙って変わらない():
    r = 寄せる(読む("作り物の前の形.json"))
    答え = 読む("作り物の寄せた後.json")
    assert r["寄せられない物"] == []
    assert r["寄せた後の値"] == 答え["寄せた後の値"]
    assert r["足りない値"] == 答え["足りない値"]
    assert r["値の保ち"] == 答え["値の保ち"] and r["値の保ち"]["合う"]
    assert [s["する"] for s in r["書く手順"]] == 答え["書く手順の並び"]


def test_二度当てても同じ():
    一 = 寄せる(読む("作り物の前の形.json"))
    再 = copy.deepcopy(一["寄せた後の値"])
    再["型の版"] = 0
    二 = 寄せる(再)
    assert 二["寄せた後の値"]["シート"] == 一["寄せた後の値"]["シート"]
    assert 二["寄せた後の値"]["md"] == 一["寄せた後の値"]["md"]
    assert 二["書く手順"] == [] and 二["寄せられない物"] == []


def test_書く手順で寄せた後になり戻す手順で元に戻る():
    前 = 読む("作り物の前の形.json")
    r = 寄せる(前)
    書いた = 当てる.手順を当てる(前, r["書く手順"])
    assert 形(書いた) == 形(r["寄せた後の値"])
    戻した = 当てる.手順を当てる(書いた, r["戻す手順"])
    assert 形(戻した) == 形(前)
    assert all(s["先"].startswith("90_履歴/消す_2027-01-31_") for s in r["書く手順"] if s["する"] == "file を写す")


def 渡すタブの数が増える形():
    """渡す側（社員）でも列「会社」で空でない数が増える形（NO・氏名だけの行を足す）。"""
    前 = 読む("作り物の前の形.json")
    社員 = 前["シート"]["03_マスタ"]["社員"]
    for n in range(3, 30):
        社員.append([str(n), f"作り物 {n}"] + [""] * (len(社員[0]) - 2))
    return 前


@pytest.mark.parametrize("どの形", ["そのまま", "渡すタブの数が増える"])
def test_書く手順をどこで切っても_もう一度寄せると同じになる(どの形):
    前 = 読む("作り物の前の形.json") if どの形 == "そのまま" else 渡すタブの数が増える形()
    r = 寄せる(前)
    並び = [(s["ファイル"], s["タブ"]) for s in r["書く手順"] if s["する"] == "値を書く"]
    assert 並び.index(("03_マスタ", "人ごとの支給控除")) < 並び.index(("03_マスタ", "社員"))
    答え = 形(r["寄せた後の値"])
    手順 = r["書く手順"]
    for k in range(len(手順) + 1):
        落ちた = 当てる.手順を当てる(前, 手順[:k])
        落ちた["型の版"] = 0
        再 = 寄せる(落ちた)
        assert 再["寄せられない物"] == [], (k, 再["寄せられない物"])
        assert 形(当てる.手順を当てる(落ちた, 再["書く手順"])) == 答え, k


def test_寄せられない物があれば書かず_人の答えで書ける():
    前 = 読む("作り物の前の形.json")
    社員 = 前["シート"]["03_マスタ"]["社員"]
    社員[0].append("作り物の謎の列")
    社員[1].append("謎の値")
    r = 寄せる(前)
    鍵 = "03_マスタ/社員/行き先の無い列:作り物の謎の列"
    assert [x["鍵"] for x in r["寄せられない物"]] == [鍵]
    assert r["書く手順"] == [] and r["戻す手順"] == []
    assert r["寄せた後の値"]["型の版"] == 0
    assert 形(r["寄せた後の値"]) == 形(前)  # 半ば寄った値は返さない（見通しの値で見るだけ）
    assert r["見通しの値"]["シート"]["03_マスタ"].get("つなぎ")

    前["人の答え"] = {鍵: "90_履歴 へ写して消す"}
    r = 寄せる(前)
    assert r["寄せられない物"] == [] and r["書く手順"]
    後の社員 = r["寄せた後の値"]["シート"]["03_マスタ"]["社員"]
    assert 後の社員[0][-1] == "作り物の謎の列" and 後の社員[1][-1] == "謎の値"  # 消さない
    assert {"する": "列を消す", "ファイル": "03_マスタ", "タブ": "社員", "見出し": "作り物の謎の列"} in [
        s for x in r["消す問い"] for s in x["消す手順"]]


def test_ぶつかりは人が選ぶまで書かない():
    前 = 読む("作り物の前の形.json")
    社員 = 前["シート"]["03_マスタ"]["社員"]
    社員[0].append("支払.賃金の形")
    社員[1].append("日給")  # 区分＝月給 と違う
    r = 寄せる(前)
    assert [x["種類"] for x in r["寄せられない物"]] == ["ぶつかり"]
    前["人の答え"] = {r["寄せられない物"][0]["鍵"]: "後を取る"}
    r = 寄せる(前)
    assert r["寄せられない物"] == []
    社員後 = r["寄せた後の値"]["シート"]["03_マスタ"]["社員"]
    assert 社員後[1][社員後[0].index("支払.賃金の形")] == "日給"
    assert r["値の保ち"]["合う"]


def test_前の勤怠の形は寄せず人が答える():
    前 = 読む("作り物の前の形.json")
