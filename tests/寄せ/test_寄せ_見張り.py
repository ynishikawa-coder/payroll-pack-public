@pytest.mark.parametrize("どの形", ["そのまま", "渡すタブの数が増える"])
def test_書く手順をどこで切っても_もう一度寄せると同じになる(どの形):
    前 = 読む("作り物の前の形.json") if どの形 == "そのまま" else 渡すタブの数が増える形()
    r = 寄せる(前)
    並び = [(s["ファイル"], s["タブ"]) for s in r["書く手順"] if s["する"] == "値を書く"]
    assert 並び.index(("2_マスタ", "人ごとの支給控除")) < 並び.index(("2_マスタ", "社員"))
    答え = 値(r["寄せた後の値"])
    手順 = r["書く手順"]
    通しで = 形(当てる.手順を当てる(前, 手順))   # 9_履歴 の写しまで（回し直しが写しを直す・移す・作るなら違う）
    for k in range(len(手順) + 1):
        落ちた = 当てる.手順を当てる(前, 手順[:k])
        落ちた["型の版"] = 0
        再 = 寄せる(落ちた)
        assert 再["寄せられない物"] == [], (k, 再["寄せられない物"])
        後 = 当てる.手順を当てる(落ちた, 再["書く手順"])
        assert 値(後) == 答え, k
        assert 形(後) == 通しで, k


def _置き場まで(d, 書いた手順):
    """値の上では中身の無い置き場は名を持たない＝移した先の名も在る物に数える（殻が Drive で読む置き場）。"""
    return {**d, "置き場": [*d["置き場"], *(s["後"] for s in 書いた手順 if s["する"] == "file を移す")]}


def test_書く手順のどこで切っても_寄せる道具の1_7の手順で前へ戻る():
    """docs/設計/寄せる道具.md §1.7: 書きかけで止めたら、回し直す → 元の戻す手順を照らして当てる → 前と同じか を見る。
    書く手順の各位置で切り、通しで流す。前（寄せの値）へ戻り、9_履歴 の写しまで切らずに書いて戻した時と同じになる。"""
    前 = 読む("作り物の前の形.json")
    r = 寄せる(copy.deepcopy(前))
    書く, 戻す = r["書く手順"], r["戻す手順"]
    通しで = 形(当てる.手順を当てる(当てる.手順を当てる(前, 書く), 戻す))
    for k in range(len(書く) + 1):
        落ちた = 当てる.手順を当てる(前, 書く[:k])
        落ちた["型の版"] = 0
        再 = 寄せる(copy.deepcopy(落ちた))
        assert 再["寄せられない物"] == [], (k, 再["寄せられない物"])
        後 = 当てる.手順を当てる(落ちた, 再["書く手順"])
        assert 当てる.履歴の名 + "/消す_2026-12-31_" + 当てる.履歴の名 not in "".join(後["置き場"]), k  # 写しを写しの中へ移さない
        assert 書.戻す手順を照らす(_置き場まで(後, 書く[:k] + 再["書く手順"]), 戻す) == [], k
        戻した = 当てる.手順を当てる(後, 戻す)
        assert 値(戻した) == 値(前), k
        assert 形(戻した) == 通しで, k


def test_寄せられない物があれば書かず_人の答えで書ける():
    前 = 読む("作り物の前の形.json")
    社員 = 前["シート"]["2_マスタ"]["社員"]
    社員[0].append("作り物の謎の列")
    社員[1].append("謎の値")
    r = 寄せる(前)
    鍵 = "2_マスタ/社員/行き先の無い列:作り物の謎の列"
    assert [x["鍵"] for x in r["寄せられない物"]] == [鍵]
    assert r["書く手順"] == [] and r["戻す手順"] == []
    assert r["寄せた後の値"]["型の版"] == 0
    assert 形(r["寄せた後の値"]) == 形(前)  # 半ば寄った値は返さない（見通しの値で見るだけ）
    assert r["見通しの値"]["シート"]["2_マスタ"].get("つなぎ")

    前["人の答え"] = {鍵: "9_履歴 へ写して消す"}
    r = 寄せる(前)
    assert r["寄せられない物"] == [] and r["書く手順"]
    後の社員 = r["寄せた後の値"]["シート"]["2_マスタ"]["社員"]
    assert 後の社員[0][-1] == "作り物の謎の列" and 後の社員[1][-1] == "謎の値"  # 消さない
    assert {"する": "列を消す", "ファイル": "2_マスタ", "タブ": "社員", "見出し": "作り物の謎の列"} in [
        s for x in r["消す問い"] for s in x["消す手順"]]


