def _当てる(今: dict, 手順: list[dict]) -> dict:
    """{"シート": {ファイル: {タブ: 値}}} の上で書く手順・戻す手順を当てる（殻が Drive に当てるのと同じ順）。形を照らす は飛ばす。"""
    d = copy.deepcopy(今)
    S = d.setdefault("シート", {})
    for s in 手順:
        k = s["する"]
        if k == "形を照らす":
            continue
        t = S.setdefault(s["ファイル"], {})
        if k == "タブを足す":
            t[s["タブ"]] = [list(s["見出し"])] if s.get("見出し") else []
        elif k == "タブを消す":
            t.pop(s["タブ"])
            if not t:   # タブの無いファイルは値の上で持たない（前にタブが無かった形と同じ）
                S.pop(s["ファイル"])
        elif k == "値を書く":
            t[s["タブ"]] = 当てる.そろえる(copy.deepcopy(s["値"]))
        elif k == "行を足す":
            v = s["値"]
            t[s["タブ"]] = 当てる.そろえる([*t[s["タブ"]], *(v if v and isinstance(v[0], list) else [v])])
        elif k == "行を消す":
            t[s["タブ"]].pop(s["行"] - 1)
        else:
            raise AssertionError(k)
    return d


def _書きかけ(前: dict, 書く: list[dict]) -> list[dict]:
    """書く手順の途中まで当てた形（触るタブの形が書き終えた後と違う物だけ）。"""
    return [_当てる(前, 書く[:i]) for i in range(len(書く))]


def _照らして戻る(前: dict, 書く: list[dict], 戻す: list[dict]):
    assert 戻す and 戻す[0]["する"] == "形を照らす"
    後 = _当てる(前, 書く)
    assert 書.戻す手順を照らす(後, 戻す) == []
    assert _当てる(後, 戻す) == 前
    for 半 in _書きかけ(前, 書く):
        if 半 != 後:
            assert 書.戻す手順を照らす(半, 戻す), "書きかけに戻す手順を当ててしまう"


