def test_寄せるの戻す手順は頭を持ち_書き終えた後なら照らしが通り前へ戻る():
    前 = 見張り.読む("作り物の前の形.json")
    r = 見張り.寄せる(copy.deepcopy(前))
    戻す = r["戻す手順"]
    assert 戻す[0]["する"] == "形を照らす"
    書いた = 当てる.手順を当てる(前, r["書く手順"])
    今 = {**書いた, "置き場": [*書いた["置き場"], *(s["後"] for s in r["書く手順"] if s["する"] == "file を移す")]}
    assert 書.戻す手順を照らす(今, 戻す) == []
    戻した = 当てる.手順を当てる(書いた, 戻す)
    assert 見張り.値(戻した) == 見張り.値(前)
    # 書きかけ（シートの値を書く手順の 1 つ目だけ当てた）は止める
    i = next(i for i, s in enumerate(r["書く手順"]) if s["する"] == "値を書く")
    assert 書.戻す手順を照らす(当てる.手順を当てる(前, r["書く手順"][:i + 1]), 戻す)


