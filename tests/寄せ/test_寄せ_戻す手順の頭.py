def test_頭の無い手順_頭の後ろの頭_頭の無い物を触る手順は止める():
    今 = {"シート": {"作り物の表": {"甲": [["列"], ["1"]], "乙": [["列"]]}}}
    本体 = [{"する": "値を書く", "ファイル": "作り物の表", "タブ": "甲", "範囲": "A1:A1", "値": [["列"]]}]
    組んだ = 書.戻す手順を組む(今, 本体)
    assert [s["する"] for s in 組んだ] == ["形を照らす", "値を書く"] and 書.戻す手順を照らす(今, 組んだ) == []
    assert 書.戻す手順を照らす(今, 本体)                       # 頭が無い
    assert 書.戻す手順を照らす(今, [*組んだ, 組んだ[0]])        # 頭の後ろの頭
    乙へ = {**本体[0], "タブ": "乙"}
    assert 書.戻す手順を照らす(今, [*組んだ, 乙へ])             # 頭の無い物を触る
    assert 書.戻す手順を照らす(今, [*組んだ, {"する": "作り物の知らない手"}])
    with pytest.raises(書.台帳へ書く誤り):
        書.戻す手順を組む(今, [{**本体[0], "タブ": "丙"}])      # 書いた後に無いタブ
    with pytest.raises(書.台帳へ書く誤り):
        書.戻す手順を組む(今, [{"する": "作り物の知らない手"}])
    書きかけ = {"シート": {"作り物の表": {"甲": [["列"]], "乙": [["列"]]}}}
    assert 書.戻す手順を照らす(書きかけ, 組んだ)                # 形が書き終えた後と違う


def test_一つの台帳の形はファイルを照らせず止め_別のファイルの同じタブでは通らない():
    """{タブ: 値} の形は頭の「ファイル」を見ずに通していた（2026-11-27）。今は 1 つの形だけ＝ファイルまで照らす。"""
    今 = {"シート": {"作り物の表": {"甲": [["列"], ["1"]]}}}
    組んだ = 書.戻す手順を組む(今, [{"する": "値を書く", "ファイル": "作り物の表", "タブ": "甲", "範囲": "A1:A1", "値": [["列"]]}])
    assert 書.戻す手順を照らす(今, 組んだ) == []
    assert 書.戻す手順を照らす(今["シート"]["作り物の表"], 組んだ)                  # {タブ: 値} の形
    assert 書.戻す手順を照らす({"シート": {"作り物の別の表": 今["シート"]["作り物の表"]}}, 組んだ)  # 同じ形のタブが別のファイル


def test_md_の物を在るの頭で名指すと指紋を見ずに通さず止める():
    """md の物に 在る だけの頭を置くと、本文が書き終えた後と違っても通っていた（2026-11-27）。md の頭は指紋だけ。"""
    今 = {"シート": {}, "md": {"作り物.md": "書き終えた後"}, "置き場": []}
    本体 = [{"する": "file を移す", "前": "作り物.md", "後": "作り物の先.md"}]
    組んだ = 書.戻す手順を組む(今, 本体)
    assert 組んだ[0] == {"する": "形を照らす", "md": "作り物.md", "指紋": 組んだ[0]["指紋"]} and 書.戻す手順を照らす(今, 組んだ) == []
    在るだけ = [{"する": "形を照らす", "在る": "作り物.md"}, *本体]
    assert 書.戻す手順を照らす(今, 在るだけ)
    assert 書.戻す手順を照らす({**今, "md": {"作り物.md": "ほかの手が入った"}}, 在るだけ)
    # md でない物（置き場の名）の 在る は通る
    置き場 = {"シート": {}, "md": {}, "置き場": ["作り物の置き場/"]}
    assert 書.戻す手順を照らす(置き場, 書.戻す手順を組む(置き場, [{"する": "file を移す", "前": "作り物の置き場/", "後": "作り物の先/"}])) == []


def test_戻す手順の本体は頭だけを除き_頭の無い手順はそのまま():
    本体 = [{"する": "値を書く", "ファイル": "F", "タブ": "T", "範囲": "A1:A1", "値": [["前"]]}]
    組んだ = 書.戻す手順を組む({"シート": {"F": {"T": [["後"]]}}}, 本体)
    assert 組んだ[0]["する"] == "形を照らす" and 書.戻す手順の本体(組んだ) == 本体
    assert 書.戻す手順の本体(本体) == 本体 and 書.戻す手順の本体([]) == [] and 書.戻す手順の本体(None) == []
