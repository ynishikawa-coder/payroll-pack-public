"""見張り: 時間の値の項目の `127.30` の形（作り物の値だけ）。

前の道具の時間は 60 進（127.30＝127 時間 30 分）のことがあり、段の解決は点の数を 10 進の時間で読む（127.30 → 127:18）。
寄せの 型の版を上げない読み（計算の形.py の 10）が、会社の 出口.時間の書き方（無ければ事務所の設定の既定）で読み分ける:
60進 → h:mm へ／10進 → そのまま／無い → 問い 1 つ（答え 60進・10進）。点の後ろが 00・h:mm の値は触らない。
60進 の会社の 60 以上・1 桁は問い（答え 10進・値:<h:mm>）。書き方の無い会社の 1 桁は時間の数。
"""
import sys
from pathlib import Path

根 = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(根 / "道具" / "寄せ"))
import 当てる  # noqa: E402
import 計算の形  # noqa: E402

マスタ = "03_マスタ"


def _物(会社の行, 型の行=None, 既定=None, 答え=None):
    シート = {マスタ: {"会社": [["会社", "項目", "今の値", "適用開始"], *会社の行]}}
    if 型の行:
        シート[マスタ]["勤務の型"] = 型の行
    if 既定:
        シート["00_事務所/事務所の設定"] = {"既定": [["項目", "今の値", "適用開始"], *既定]}
    return 当てる.物({"会社": "作り物", "シート": シート, "人の答え": 答え or {}})


def _回す(o):
    記 = 当てる.記録()
    計算の形.時間の60進(o, 記, 計算の形.読みを開く())
    return 記


def _値(o, 項目):
    rows = o.シート[マスタ]["会社"]
    return next(r[2] for r in rows[1:] if r[1] == 項目)


def test_60進の会社は_h_mm_へ():
    o = _物([["作り物", "出口.時間の書き方", "60進（h:mm）", ""], ["作り物", "委託.雇用分の出勤時間", "127.30", "2026.10支給"],
            ["作り物", "時間.月の所定時間", "161.20", ""], ["作り物", "委託.みなし残業時間", "10.00", ""]])
    記 = _回す(o)
    assert _値(o, "委託.雇用分の出勤時間") == "127:30"
    assert _値(o, "時間.月の所定時間") == "161:20"
    assert _値(o, "委託.みなし残業時間") == "10.00"          # 00 は 60 進も 10 進も同じ＝触らない
    assert 記.寄せられない == [] and len(記.知らせ) == 2
    assert _回す(o).当てた == []                              # 2 回目は何もしない


def test_10進の会社は触らない():
    o = _物([["作り物", "出口.時間の書き方", "10進（h.hh）", ""], ["作り物", "委託.雇用分の出勤時間", "127.30", ""]])
    記 = _回す(o)
    assert _値(o, "委託.雇用分の出勤時間") == "127.30" and 記.寄せられない == [] and 記.当てた == []


def test_事務所の既定で読み分ける():
    o = _物([["作り物", "委託.所定時間", "7.45", ""]], 既定=[["出口.時間の書き方", "60進（h:mm）", ""]])
    _回す(o)
    assert _値(o, "委託.所定時間") == "7:45"


def test_書き方が無ければ問い_答えで直す():
    行 = [["作り物", "委託.雇用分の出勤時間", "127.30", ""]]
    記 = _回す(_物([list(x) for x in 行]))
    assert len(記.寄せられない) == 1
    q = 記.寄せられない[0]
    assert q["選べる答え"] == ["60進", "10進"] and "127 時間 30 分" in q["中身"]
    o = _物([list(x) for x in 行], 答え={q["鍵"]: "60進"})
    assert _回す(o).寄せられない == [] and _値(o, "委託.雇用分の出勤時間") == "127:30"
    o = _物([list(x) for x in 行], 答え={q["鍵"]: "10進"})
    assert _回す(o).寄せられない == [] and _値(o, "委託.雇用分の出勤時間") == "127.30"


def test_60進で読めない値は問い_答えで止む():
    行 = [["作り物", "出口.時間の書き方", "60進（h:mm）", ""], ["作り物", "委託.雇用分の出勤時間", "127.75", ""]]
    o = _物([list(x) for x in 行])
    記 = _回す(o)
    q = 記.寄せられない[0]
    assert _値(o, "委託.雇用分の出勤時間") == "127.75" and "60 以上" in q["中身"]
    assert q["選べる答え"] == ["10進", "値:<h:mm>"] and "127:75" not in q["手がかり"] and "値:127:45" in q["手がかり"]
    o = _物([list(x) for x in 行], 答え={q["鍵"]: "60進"})       # 選べる答えの外＝問いのまま（同じ問い 1 つ）
    assert len(_回す(o).寄せられない) == 1
    o = _物([list(x) for x in 行], 答え={q["鍵"]: "10進"})
    assert _回す(o).寄せられない == [] and _値(o, "委託.雇用分の出勤時間") == "127.75"
    o = _物([list(x) for x in 行], 答え={q["鍵"]: "値:128:15"})
    assert _回す(o).寄せられない == [] and _値(o, "委託.雇用分の出勤時間") == "128:15"


def test_60進の会社の1桁は問い_書き方の無い会社の1桁は時間の数():
    o = _物([["作り物", "出口.時間の書き方", "60進", ""], ["作り物", "委託.雇用分の出勤時間", "127.3", ""]])
    q = _回す(o).寄せられない[0]                              # 殻が数で読んで 127.30 の 0 が落ちたかもしれない
    assert "1 桁" in q["中身"] and "値:127:30" in q["手がかり"]
    for v in ("127.5", "127.75"):                              # 書き方の無い会社: 1 桁・60 以上は 60 進で読めない＝時間の数
        o = _物([["作り物", "委託.雇用分の出勤時間", v, ""]])
        記 = _回す(o)
        assert 記.寄せられない == [] and _値(o, "委託.雇用分の出勤時間") == v


def test_勤務の型の列も読む_ほかの形は触らない():
    型 = [["会社", "型の名", "時間.日の所定", "時間.月の所定時間"], ["作り物", "日勤", "7.30", "160:00"], ["作り物", "短時間", "8.00", "120"]]
    o = _物([["作り物", "出口.時間の書き方", "60進", ""]], 型の行=型)
    記 = _回す(o)
    rows = o.シート[マスタ]["勤務の型"]
    assert rows[1][2:] == ["7:30", "160:00"] and rows[2][2:] == ["8.00", "120"] and 記.寄せられない == []
