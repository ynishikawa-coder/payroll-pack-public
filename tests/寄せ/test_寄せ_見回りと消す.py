"""見回り・配る・消す問いの答え（docs/設計/寄せる道具.md §2.2・§2.3・§4.2・§4.4）。作り物の値だけ。

根（原因の台帳 2026-11-22）:
- 寄せ・配りの写しの期限が紙（突き合わせが緑の翌月末）と違い、道具は寄せた日の翌々月末で固定＝寄せ中で止まった会社・
  まだ緑になっていない会社の写しが消す候補に並びえた → 期限は 名の日 と 管理表の 最後に配った日 の翌月末 の遅い方・
  寄せ中と緑の前は並べない。
- 寄せの 消す問い を作る口が無く、殻は 寄せる が返す 消す問い を捨てた → 見回り が今の Drive から作り直し、答えを当てる口を足す。
"""
