# ---- 寄せの消す問いを今の Drive から作り直す（§4.4）

def 写して消すと答えた会社(写し=True):
    シート = {"2_マスタ": {"社員": [["会社", "NO", "今の名"], [社, "1", "作り物"]], "作り物のメモ": [["何か"], ["作り物の値"]]}}
    置き場 = ["9_履歴/消す_2026-12-31_2_マスタ"] if 写し else []
    return 会社(置き場, シート, {"2_マスタ/作り物のメモ/行き先の無いタブ": "9_履歴 へ写して消す"})


def test_寄せで写して消すと答えたタブは見回りの消す問いに並ぶ():
    x = 並ぶ物(回す(写して消すと答えた会社(), dt.date(2026, 12, 1), 管理表(日="2026-11-20")))["タブ 作り物のメモ"]
    assert x["推奨"] == "消す" and x["消す手順"] == [{"する": "タブを消す", "ファイル": "2_マスタ", "タブ": "作り物のメモ"}]
    assert x["鍵"] == f"{社}/2_マスタ/タブ 作り物のメモ"


def test_注入_写しだけに中身が在る行が並ぶ間は写しを消すと推さない():
    c = 写して消すと答えた会社()
    c["置き場"] = [p.replace("2026-12-31", "2026-11-30") for p in c["置き場"]]
    r = 回す(c, dt.date(2027, 1, 1), 管理表(日="2026-11-20"))
    写し = 並ぶ物(r)["消す_2026-11-30_2_マスタ"]
    assert 写し["消す手順"] == [] and "作り物のメモ" in 写し["推奨"]
    答え = 見回り.答えを当てる(r["消す問い"], {写し["鍵"]: "消す"}, dt.date(2027, 1, 1))
    assert 答え["誤り"] and 答え["手順"] == {}
    # タブを消した次の回は写しが 消す と並ぶ
    c["シート"]["2_マスタ"].pop("作り物のメモ")
    assert 並ぶ物(回す(c, dt.date(2027, 1, 1), 管理表(日="2026-11-20")))["消す_2026-11-30_2_マスタ"]["推奨"] == "消す"


def test_注入_写しの無いタブは消すと推さず消す手順を持たない():
    x = 並ぶ物(回す(写して消すと答えた会社(写し=False), dt.date(2026, 12, 1), 管理表(日="2026-11-20")))["タブ 作り物のメモ"]
    assert x["消す手順"] == [] and x["推奨"].startswith("残す") and "どこにも無い" in x["中身はどこに在るか"]


def test_前の版のままの会社は寄せの消す問いを作らない():
    c = {**写して消すと答えた会社(), "型の版": 1}
    assert "タブ 作り物のメモ" not in 並ぶ物(回す(c, dt.date(2026, 12, 1), 管理表(日="2026-11-20")))


# ---- 答えを当てる（§4.4）

def 今の問い():
    c = 写して消すと答えた会社()
    c["置き場"] += ["9_履歴/消す_2026-10-31_作り物の要らない物", "2_マスタ/旧_作り物"]
    return 回す(c, dt.date(2027, 1, 1), 管理表(日="2026-11-20"))["消す問い"]


def test_推奨どおり全部は推奨が消すの行だけを消し_ほかは次に並ぶ():
    行 = 今の問い()
    r = 見回り.答えを当てる(行, {"全部": "推奨どおり"}, dt.date(2027, 1, 1))
    assert r["誤り"] == []
    消す = r["手順"][社]
    assert {"する": "タブを消す", "ファイル": "2_マスタ", "タブ": "作り物のメモ"} in 消す
    assert {"する": "file を消す", "名": "9_履歴/消す_2026-10-31_作り物の要らない物"} in 消す
    assert f"{社}/2_マスタ/旧_作り物" in r["答えの無い行"]   # 推奨が 消す でない行は消さない・黙って残さない


@pytest.mark.parametrize("答え", [
    {f"{社}/2_マスタ/旧_作り物": "消す"},                                    # 消す手順の無い行
    {f"{社}/9_履歴/前の回の物": "消す"},                                     # 今の問いに無い鍵（前の回の答え）
    {f"{社}/2_マスタ/タブ 作り物のメモ": "残す:2026-12-31"},                  # 今日より前の期限
    {f"{社}/2_マスタ/タブ 作り物のメモ": "残す"},                             # 期限が無い
    {f"{社}/2_マスタ/タブ 作り物のメモ": "原本へ移す:3_月ごと"},              # file でない行
    {f"{社}/2_マスタ/タブ 作り物のメモ": "捨てる"},                           # 知らない答え
    {"全部": "全部消す"},                                                   # 全部 は 推奨どおり だけ
])
def test_注入_誤った答えは1つでも在れば何も消さない(答え):
    r = 見回り.答えを当てる(今の問い(), {**答え, f"{社}/9_履歴/消す_2026-10-31_作り物の要らない物": "消す"}, dt.date(2027, 1, 1))
    assert r["誤り"] and r["手順"] == {}


def test_原本へ移すはfileの行を移し_残すは新しい期限で次まで並ばない():
    鍵 = f"{社}/9_履歴/消す_2026-10-31_作り物の要らない物"
    r = 見回り.答えを当てる(今の問い(), {鍵: "原本へ移す:3_月ごと/2026.12支給（11月分）/1_届いた物"}, dt.date(2027, 1, 1))
    assert r["手順"][社] == [{"する": "file を移す", "前": "9_履歴/消す_2026-10-31_作り物の要らない物",
                            "後": "3_月ごと/2026.12支給（11月分）/1_届いた物/消す_2026-10-31_作り物の要らない物"}]
    メモ = f"{社}/2_マスタ/タブ 作り物のメモ"
    r = 見回り.答えを当てる(今の問い(), {メモ: "残す:2027-03-31"}, dt.date(2027, 1, 1))
    assert r["残す"] == {メモ: "残す:2027-03-31"} and r["手順"] == {}
    次 = 回す(写して消すと答えた会社(), dt.date(2027, 2, 1), 管理表(日="2026-11-20"), 前の答え=r["残す"])
    assert "タブ 作り物のメモ" not in 並ぶ物(次)
    後 = 回す(写して消すと答えた会社(), dt.date(2027, 4, 1), 管理表(日="2026-11-20"), 前の答え=r["残す"])
    assert "タブ 作り物のメモ" in 並ぶ物(後)


def test_呼び口の消すは見回りと同じ問いに答えを当てる(tmp_path, capsys):
    c = 写して消すと答えた会社()
    (tmp_path / "c.json").write_text(json.dumps(c, ensure_ascii=False), encoding="utf-8")
    (tmp_path / "表.json").write_text(json.dumps(管理表(日="2026-11-20"), ensure_ascii=False), encoding="utf-8")
    (tmp_path / "答え.json").write_text(json.dumps({"全部": "推奨どおり"}, ensure_ascii=False), encoding="utf-8")
    型 = tmp_path / "型.json"
    型.write_text(json.dumps(型2, ensure_ascii=False), encoding="utf-8")
    d = tmp_path / "直し"
    d.mkdir()
    for x in 直したち:
        (d / f"直し_{x['版']:04d}.json").write_text(json.dumps(x, ensure_ascii=False), encoding="utf-8")
    args = ["消す", "--型", str(型), "--直し", str(d), "--会社たち", str(tmp_path / "c.json"), "--管理表", str(tmp_path / "表.json"),
            "--答え", str(tmp_path / "答え.json"), "--今日", "2026-12-01"]
    assert 呼び口.main(args) == 0
    out = json.loads(capsys.readouterr().out)
    assert {"する": "タブを消す", "ファイル": "2_マスタ", "タブ": "作り物のメモ"} in out["手順"][社]
    (tmp_path / "答え.json").write_text(json.dumps({f"{社}/9_履歴/無い物": "消す"}, ensure_ascii=False), encoding="utf-8")
    assert 呼び口.main(args) == 1
    assert json.loads(capsys.readouterr().out)["手順"] == {}


# ---- 配る（§2.2・§2.3）

def test_注入_配るは寄せ中の会社を当てずに頭へ並べる():
    前 = {**会社(版=1), "シート": {"2_マスタ": {"社員": [["会社", "NO"], [社, "1"]]}}}
    r = 見回り.配る([前], 型2, 直したち, dt.date(2026, 12, 1), 管理表=管理表("寄せ中", "突き合わせが合わない"))
    assert r["見通し"][0]["当てるか"].startswith("寄せ中（突き合わせが合わない）")
    assert r["消してよい直し"] == [1]   # 寄せ中の会社は前の版 1 のまま数える
    r = 見回り.配る([前], 型2, 直したち, dt.date(2026, 12, 1), 管理表=管理表())
    assert r["見通し"][0]["当てるか"] == "当てる"
