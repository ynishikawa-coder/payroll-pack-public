def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(型の置き場), 直しの形.読む(), 今日)


def 置く(rows, r, 列, 値):
    rows[r][rows[0].index(列)] = 値


def 列(rows, 名):
    return [r[rows[0].index(名)] for r in rows[1:]]


def 項目たち():
    return {it["項目"]: it for it in json.loads((根 / "初期設定" / "項目.json").read_text(encoding="utf-8"))["項目"]}


def test_委託の分野は芯の名にそろい人の額は行の束():
    委託 = {k: v for k, v in 項目たち().items() if k.startswith("委託.")}
    assert len(委託) == 19 and {"委託.式", "委託.源泉率", "委託.丸め", "委託.日当の境", "委託.雇用分", "委託.雇用分の出勤時間"} <= set(委託)  # 直し 3 の 17 ＋ 会社の段の定数 ＋ 委託.実働の丸め
    人の額 = {"委託.月給", "委託.時給", "委託.日給", "委託.通勤日額"}
    for 名, it in 委託.items():
        if 名 in 人の額:  # 人ごとの支給控除 の行＝社員の列は増えない
            assert it["段"] == ["人"] and "人ごとの支給控除" in it["置く所"], 名
        elif 名 == "委託.式":
            assert it["段"] == ["会社", "人"], 名
        else:
            assert it["段"] == ["会社"], 名
        assert "委託.py" in it["注"] or "検査.py" in it["注"] or "まだ読まない" in it["注"], 名
        assert {"意味", "選べる値", "既定", "法の線"} <= set(it), 名
    assert "委託の併用" in 項目たち()["人.区分"]["選べる値"]
    assert "1 日の所定" in 委託["委託.日当の境"]["既定"]
    assert "残業 10円切上げ" in 委託["委託.丸め"]["選べる値"]


