def test_前の列は行き先へ移り値は失わない():
    会社 = 前の形()
    支 = 会社["シート"]["03_マスタ"]["支給控除の項目"]
    置く(支, 1, "作り物ソフトの欄", "作り物の欄")
    置く(支, 1, "計算の仕方", "作り物の時給×時間")
    置く(支, 1, "足す行", "作り物の行")
    型 = 会社["シート"]["03_マスタ"]["勤務の型"]
    置く(型, 1, "勤務の長さの丸め（分）", "15")
    問 = 会社["シート"]["01_決まり/質問と回答"]["質問"]
    置く(問, 1, "誰が聞いた", "AI")
    r = 寄せる(会社)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    シ = r["寄せた後の値"]["シート"]
    assert 列(シ["03_マスタ"]["支給控除の項目"], "給与ソフトの欄") == ["作り物の欄"]
    assert "計算の仕方" not in シ["03_マスタ"]["支給控除の項目"][0]
    assert 列(シ["03_マスタ"]["支給控除の項目"], "足す行") == ["作り物の行"]
    md = r["寄せた後の値"]["md"]["01_ルール/給与のルール.md"]
    assert "計算の仕方＝作り物の時給×時間" in md  # 文は md へ・読めた 単価の元 は列へ（md へ逃がすだけにしない）
    assert 列(シ["03_マスタ"]["支給控除の項目"], "単価の元") == ["時間単価"]
    # 勤務の長さの丸めは直し 3 が 打刻の丸めの単位 へ移し、毎回の読みが空にする（前の道具の切り捨て＝打刻の丸めと意味が違う。
    # 委託の人の居ない会社＝委託.実働の丸め へも書かない。test_寄せ_実働の丸め.py）
    assert 列(シ["03_マスタ"]["勤務の型"], "時間.打刻の丸めの単位") == [""]
    assert 列(シ["01_ルール/質問と回答"]["質問"], "誰が聞いた")[0] == "AI"
    assert r["値の保ち"]["合う"]


