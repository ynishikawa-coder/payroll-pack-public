def test_人の委託の雇用分が会社の値に勝ち前の行の名も読み替わる():
    _s = importlib.util.spec_from_file_location("初期設定_段の解決_委託3", 根 / "初期設定" / "段の解決.py")
    段 = importlib.util.module_from_spec(_s)
    _s.loader.exec_module(段)
    r = 段.解く("2026.11支給",
               会社=[{"会社": "作り物の会社", "項目": "委託.雇用分", "今の値": "250000", "適用開始": ""}],
               社員=[{"会社": "作り物の会社", "NO": "0001", "人.区分": "委託の併用", "委託.式": "月額"},
                    {"会社": "作り物の会社", "NO": "0002", "人.区分": "委託の併用", "委託.式": "月額"}],
               人ごとの支給控除=[{"会社": "作り物の会社", "NO": "0001", "項目": "委託.雇用分", "額": "200000", "適用開始": ""}])
