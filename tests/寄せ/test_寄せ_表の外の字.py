def test_休憩の表の外の形の答えは書かずに問い():
    会社 = 前の形()
    置く(会社["シート"]["2_マスタ"]["勤務の型"], 1, "休憩の表", '{"長い日": "多め"}')
    r = 寄せる(会社)
    鍵 = 鍵たち(r, "そろえる:時間.休憩の表")
    assert len(鍵) == 1
    会社["人の答え"] = {鍵[0]: "値:夕方に少し"}
    r = 寄せる(会社)
    assert len(表の外の問い(r)) == 1 and r["書く手順"] == []
    会社["人の答え"] = {鍵[0]: "値:退勤18:00超30分"}   # 退勤の境の形は選べる
    r = 寄せる(会社)
    assert 列(r["寄せた後の値"]["シート"]["2_マスタ"]["勤務の型"], "時間.休憩の表") == ["退勤18:00超30分"]


def test_直しの読み替えの今の語は表の選べる値の中():
    外 = []
    for p in sorted((根 / "道具" / "寄せ" / "直し").glob("直し_*.json")):
        for op in json.loads(p.read_text(encoding="utf-8")).get("操作", []):
            if op.get("する") != "値をそろえる" or op.get("形") != "読み":
                continue
            名 = op.get("行", {}).get("項目") if op["列"] in ("今の値", "値") else op["列"]
            if 名 not in 設定.表():
                continue
            外 += [(p.name, 名, w) for w in set(op["読み"].values()) if not 設定.選べる値の字か(名, w)]
    assert 外 == [], 外
