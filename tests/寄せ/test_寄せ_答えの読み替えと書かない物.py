"""見張り: 当てる順（版の直し → 照らす〔人の答え〕 → 記録.解けた）の穴 2 つ。作り物の値と一般の語だけ。

1. 人の答え `値:<項目>` で前の名の行を今の項目にした時も、直しの「値をそろえる」の読み替え（前の語→今の語）が当たる
   （答えは項目の意味を決めるだけ。値の語は直しの読み替えでそろえる）。読み替えに無い語は黙って通さず問い。
2. 入れた物のうち書く手順に出ない物（前と同じタブ・md、入口が書く台帳の 勤怠・勤怠の区間〔表 A・B〕）を
   `書かない物` に一覧で出し、入れた勤怠が書かれない時は知らせに出す（黙って捨てない）。形が変われば書く。
"""
import datetime as dt
import json
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根 / "道具" / "寄せ"))

sys.path.insert(0, str(ここ))
import 当てる  # noqa: E402
import 作り物の殻  # noqa: E402
import 直し as 直しの形  # noqa: E402

今日 = dt.date(2026, 11, 12)
型の置き場 = 根 / "初期設定" / "型.json"
台帳 = "04_台帳_2026"
答えの鍵 = "03_マスタ/会社/形:項目/項目=残業の数え方"
問いの鍵 = "03_マスタ/会社/そろえる:今の値/項目=割増.残業の数え方"


def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(型の置き場), 直しの形.読む(), 今日)


def 前の形():
    return json.loads((ここ / "作り物の前の形.json").read_text(encoding="utf-8"))


def 会社の行(r, 項目):
    rows = (r["寄せた後の値"] if not r["寄せられない物"] else r["見通しの値"])["シート"]["03_マスタ"]["会社"]
    return [dict(zip(rows[0], x)) for x in rows[1:] if x[rows[0].index("項目")] == 項目]


def 書いてもう一度(前, r):
    assert r["寄せられない物"] == [], r["寄せられない物"]
    assert r["値の保ち"]["合う"]
    書いた = 当てる.手順を当てる(前, r["書く手順"])
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    r2 = 寄せる(書いた)
    assert r2["書く手順"] == [] and r2["寄せられない物"] == [], (r2["書く手順"][:2], r2["寄せられない物"])
    return 書いた, r2


def 前の名の残業(語):
    会社 = 前の形()
    会社["シート"]["03_マスタ"]["会社"].append(["残業の数え方", 語, "", ""])
    return 会社


# ---- 1 答えの行にも直しの読み替え

def test_前の名の行は答えるまで問い():
    r = 寄せる(前の名の残業("1日の所定時間を超えた分"))
    assert [x["鍵"] for x in r["寄せられない物"]] == [答えの鍵]
    assert r["書く手順"] == []


def test_答えで今の項目にした行の前の語は今の語で書かれる():
    for 前の語, 今の語 in (("1日の所定時間を超えた分", "1日の所定超え"), ("１日の所定時間を超えた分", "1日の所定超え"),
                       ("法定通り", "法定どおり"), ("1日の所定超え", "1日の所定超え")):
        会社 = 前の名の残業(前の語)
        会社["人の答え"] = {答えの鍵: "値:割増.残業の数え方"}
        r = 寄せる(会社)
        assert 会社の行(r, "割増.残業の数え方")[0]["今の値"] == 今の語, 前の語
        if 前の語 != 今の語:
            assert any("割増.残業の数え方" in x and f"{前の語}→{今の語}" in x for x in r["知らせ"]), r["知らせ"]
        書いた, _ = 書いてもう一度(会社, r)
        行 = [x for x in 書いた["シート"]["03_マスタ"]["会社"] if x[1] == "割増.残業の数え方"]
        assert 行 and 行[0][2] == 今の語  # 書く手順を当てた後の Drive の値も今の語


def test_答えの行で読み替えに無い語は黙って通さず問い():
    会社 = 前の名の残業("週で数える")
    会社["人の答え"] = {答えの鍵: "値:割増.残業の数え方"}
    r = 寄せる(会社)
    assert [x["鍵"] for x in r["寄せられない物"]] == [問いの鍵], r["寄せられない物"]
    問い = r["寄せられない物"][0]
    assert 問い["種類"] == "形の合わない値" and "法定どおり" in 問い["手がかり"]
    assert r["書く手順"] == []
    # 人が今の語で答えれば書ける
    会社["人の答え"][問いの鍵] = "値:1日の所定超え"
    r = 寄せる(会社)
    assert 会社の行(r, "割増.残業の数え方")[0]["今の値"] == "1日の所定超え"
    書いてもう一度(会社, r)


def test_答えの行で空にすれば足りない値に出る():
    会社 = 前の名の残業("週で数える")
    会社["人の答え"] = {答えの鍵: "値:割増.残業の数え方", 問いの鍵: "空にする"}
    r = 寄せる(会社)
    assert r["寄せられない物"] == [] and r["値の保ち"]["合う"]
    assert 会社の行(r, "割増.残業の数え方")[0]["今の値"] == ""
    assert any(x["項目"] == "今の値" and "週で数える" in x["なぜ"] for x in r["足りない値"])


