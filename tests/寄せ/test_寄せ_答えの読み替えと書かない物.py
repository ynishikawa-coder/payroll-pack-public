# ---- 2 入れた物のうち書かない物

def 表AB(K, 行の数=300):
    tk = 当てる.型のファイル(K, 台帳)
    hA = [c["名"] for c in tk["勤怠"]]
    hB = [c["名"] for c in tk["勤怠の区間"]]
    def A行(i):
        v = {"会社": "作り物の会社", "支給月": "2026.11支給", "NO": str(i % 3 + 1), "日付": f"2026-10-{i % 28 + 1:02d}", "日の種類": "勤務"}
        return [v.get(c, "") for c in hA]
    def B行(i):
        v = {"会社": "作り物の会社", "支給月": "2026.11支給", "NO": str(i % 3 + 1), "日付": f"2026-10-{i % 28 + 1:02d}",
             "区間の番号": "1", "区間の種別": "労働", "始め": "9:00", "終わり": "18:00", "時刻の出所": "打刻"}
        return [v.get(c, "") for c in hB]
    return [hA] + [A行(i) for i in range(行の数)], [hB] + [B行(i) for i in range(行の数)]


def 今の版の会社():
    """前の形を寄せて書いた後（型の版＝今の版）。"""
    会社 = 前の形()
    r = 寄せる(会社)
    書いた, _ = 書いてもう一度(会社, r)
    return 書いた


def test_今の形の勤怠を入れても書かず_書かない物と知らせに出る():
    会社 = 今の版の会社()
    K = 当てる.型を読む(当てる.型を開く(型の置き場))
    会社["シート"][台帳]["勤怠"], 会社["シート"][台帳]["勤怠の区間"] = 表AB(K)
    r = 寄せる(会社)
    assert r["寄せられない物"] == [] and r["書く手順"] == []
    書かない = {x["所"]: x for x in r["書かない物"]}
    for t in ("勤怠", "勤怠の区間"):
        x = 書かない[f"{台帳}/{t}"]
        assert x["行"] == 300 and "入口が書く" in x["なぜ"]
        assert any(x["所"] in s and "300 行" in s for s in r["知らせ"]), r["知らせ"]
    assert "入れたが書かない物" in r["人が見る物"] and f"{台帳}/勤怠" in r["人が見る物"]
    # 入れたタブは全部、書く手順か書かない物のどちらかに出る（黙って落とさない）
    入れた = {f"{f}/{t}" for f, tabs in 会社["シート"].items() for t in tabs}
    出た = set(r["変わるタブ"]) | {k for k in 書かない if k not in 会社["md"]}
    assert 入れた == 出た, 入れた ^ 出た
    assert set(会社["md"]) <= set(書かない)  # 前と同じ md も一覧に出る


def test_形の違う勤怠は書く手順に出る():
    会社 = 今の版の会社()
    K = 当てる.型を読む(当てる.型を開く(型の置き場))
    A, _ = 表AB(K, 5)
    会社["シート"][台帳]["勤怠"] = [x[1:] for x in A]  # 列「会社」の無い勤怠
    会社["型の版"] = 0  # 版 0 から当て直す＝直し 1 が 列「会社」を足す（形が変わる）
    r = 寄せる(会社)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    assert f"{台帳}/勤怠" in r["変わるタブ"]
    assert any(x["する"] == "値を書く" and x["タブ"] == "勤怠" for x in r["書く手順"])
    assert f"{台帳}/勤怠" not in {x["所"] for x in r["書かない物"]}
    assert not any("勤怠: 入れた" in s for s in r["知らせ"])

