"""寄せの見出し・値の語・写しの名は、字のそろえ方の正本（芯/字.py）でそろえてから照らす（台帳の束 K3）。作り物の値だけ。

根（2026-11-20）: 列の番号 が見出しを字のそのままの一致で探した（尾に空白・全角・幅の無い字の見出しは「列が無い」＝操作を黙って飛ばす）。
値の語を読み替える も startswith か strip だけで照らした（揺れた前の語が読み替えられずに残る）。見回りの消す候補は全角の「（1）」と
「コピー」だけを見た（Drive が付ける半角の「(1)」・英語の「Copy of …」の写しが並ばない）。
"""
import datetime as dt
import sys
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
sys.path.insert(0, str(ここ.parent.parent / "道具" / "寄せ"))

import 当てる  # noqa: E402
import 見回り  # noqa: E402

M = "2_マスタ"
幅の無い字 = "​"


def _当てる(見出し, 行たち, op):
    o = 当てる.物({"会社": "作り物の会社", "シート": {M: {"社員": [list(見出し)] + [list(r) for r in 行たち]}}})
    記 = 当てる.記録()
    当てる.当てる操作(o, {"ファイル": M, "タブ": "社員", **op}, {}, 記, 2, 1, {})
    return o.シート[M]["社員"], 記


# ---- 列の番号（見出しの揺れ）

@pytest.mark.parametrize("揺れた見出し", ["区分 ", " 区分", "区" + 幅の無い字 + "分", "区分　"])
def test_揺れた見出しも同じ列として見つける(揺れた見出し):
    assert 当てる.列の番号([["NO", 揺れた見出し, "氏名"]], "区分") == 1


def test_そのままの一致を先に取り_そろえて2つに当たる時はどれと決めない():
    assert 当てる.列の番号([["区分 ", "区分"]], "区分") == 1
    assert 当てる.列の番号([["区分 ", " 区分"]], "区分") is None
    assert 当てる.列の番号([["NO", "氏名"]], "区分") is None


@pytest.mark.parametrize("揺れた見出し", ["人.区分 ", "人．区分", "人.区" + 幅の無い字 + "分"])
def test_見出しが揺れても値の語を読み替える(揺れた見出し):
    rows, 記 = _当てる(["NO", 揺れた見出し], [["1", "在籍"], ["2", "退職"]],
                    {"する": "値の語を読み替える", "列": "人.区分", "前": "在籍", "後": "雇用"})
    assert [r[1] for r in rows[1:]] == ["雇用", "退職"]
    assert len(記.当てた) == 1


def test_見出しが揺れても列の名を変える():
    rows, _ = _当てる(["NO", "前の名 "], [["1", "作り物の値"]], {"する": "列の名を変える", "前": "前の名", "後": "今の名"})
    assert rows == [["NO", "今の名"], ["1", "作り物の値"]]


def test_そろえると同じ名への名の変えは列を消さず見出しを書くだけ():
    rows, _ = _当てる(["NO", "今の名 "], [["1", "作り物の値"]], {"する": "列の名を変える", "前": "今の名 ", "後": "今の名"})
    assert rows == [["NO", "今の名"], ["1", "作り物の値"]]


# ---- 値の語を読み替える（値の揺れ）

@pytest.mark.parametrize("揺れた値", ["在籍", " 在籍", "在籍 ", "在" + 幅の無い字 + "籍", "在籍　"])
def test_全体の読み替えは揺れた前の語も読み替える(揺れた値):
    rows, _ = _当てる(["NO", "人.区分"], [["1", 揺れた値]], {"する": "値の語を読み替える", "列": "人.区分", "前": "在籍", "後": "雇用"})
    assert rows[1][1] == "雇用"


def test_全体の読み替えは前の語を含むだけの値を読み替えない():
    rows, _ = _当てる(["NO", "人.区分"], [["1", "在籍中"]], {"する": "値の語を読み替える", "列": "人.区分", "前": "在籍", "後": "雇用"})
    assert rows[1][1] == "在籍中"


@pytest.mark.parametrize("揺れた値, 残り", [
    ("［出所: 作り物ソフトのマスタ（版3）］", "（版3）］"),
    (" ［出所: 作り物ソフトのマスタ（版3）］", "（版3）］"),
    ("[出所:作り物ソフトのマスタ（版3）］", "（版3）］"),
    ("［出所: 作り" + 幅の無い字 + "物ソフトのマスタ（版3）］", "（版3）］"),
])
def test_頭の読み替えは揺れた頭も読み替え_残りの字は元のまま付ける(揺れた値, 残り):
    rows, _ = _当てる(["NO", "出所"], [["1", 揺れた値]],
                    {"する": "値の語を読み替える", "列": "出所", "前": "［出所: 作り物ソフトのマスタ", "後": "［出所: 作り物の今の名", "合わせ": "頭"})
    assert rows[1][1] == "［出所: 作り物の今の名" + 残り


@pytest.mark.parametrize("揺れた値", ["過去の支給と一致", " 過去の支給と一致（作り物の注）", "過去の支給と一致" + 幅の無い字])
def test_頭で全体の読み替えは揺れた頭も後の語だけにする(揺れた値):
    rows, _ = _当てる(["NO", "確かめ"], [["1", 揺れた値]],
                    {"する": "値の語を読み替える", "列": "確かめ", "前": "過去の支給と一致", "後": "仮", "合わせ": "頭で全体"})
    assert rows[1][1] == "仮"


# ---- 見回り（写しの名）

@pytest.mark.parametrize("名", ["作り物の表 (1)", "作り物の表（1）", "Copy of 作り物の表", "copy of 作り物の表", "作り物の表 のコピー",
                               "作り物の表 のｺﾋﾟｰ", "旧_作り物の表", " 旧_作り物の表"])
def test_写しの名は消す問いと置き場の検査の両方に並ぶ(名):
    会社 = {"会社": "作り物の会社", "置き場": [f"2_マスタ/{名}"]}
    問い = 見回り.置き場を見る(会社, dt.date(2026, 11, 20), "")
    assert [x["中身はどこに在るか"] for x in 問い] == ["旧_・写しの名"]
    assert 3 in [x["項目"] for x in 見回り.置き場の検査(会社, dt.date(2026, 11, 20))]


@pytest.mark.parametrize("名", ["作り物の表", "作り物の表 (10)", "2026.11支給（11月分）", "作り物の表 Copy"])
def test_写しでない名は並ばない(名):
    会社 = {"会社": "作り物の会社", "置き場": [f"2_マスタ/{名}"]}
    assert 見回り.置き場を見る(会社, dt.date(2026, 11, 20), "") == []
    assert 3 not in [x["項目"] for x in 見回り.置き場の検査(会社, dt.date(2026, 11, 20))]
