"""置き場の検査の項目 8（事務所の設定「置き場」の登録・docs/設計/Drive の型.md §8）。判定は 初期設定/型の口.py の
置き場の登録の赤 の 1 か所で、見回り.置き場の検査 がそれを当てる。作り物の値だけ（パ-4）。"""
import datetime as dt
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(根 / "道具" / "寄せ"))
import 当てる  # noqa: E402
import 見回り  # noqa: E402

型の口 = 当てる.型の口
見出し = ["顧客ID", "会社", "組", "物", "ID"]
一覧の見出し = 型の口.見出し("事務所の設定", "会社の一覧")


def _一覧(*行たち):
    """型の見出しの会社の一覧（顧客ID・会社・組だけ値を置く）。"""
    return [一覧の見出し] + [[dict(zip(("顧客ID", "会社", "組"), r)).get(c, "") for c in 一覧の見出し] for r in 行たち]


一覧 = _一覧(("C0001", "作り物A", "組X"), ("C0002", "作り物B", "組X"))
緑の行 = [["C0001", "作り物A", "組X", "会社の根", "id-根-X"], ["C0002", "作り物B", "組X", "会社の根", "id-根-X"],
        ["C0001", "作り物A", "組X", "台帳_2026", "id-台帳-2026"]]


def _赤(行たち):
    事務所 = {"会社": "作り物の事務所", "置き場": ["00_事務所/事務所の設定"],
            "シート": {"00_事務所/事務所の設定": {"置き場": [見出し, *行たち], "会社の一覧": 一覧}}}
    return [x["訳"] for x in 見回り.置き場の検査(事務所, dt.date(2099, 1, 1)) if x["項目"] == 8]


def test_緑の表は赤0():
    assert _赤(緑の行) == []
    assert 型の口.置き場の登録の赤([見出し, *緑の行], 一覧) == []


def test_パ4_前の字_顧客IDの空_同じ行の重なり_年でない台帳は赤():
    壊す = {
        "前の字": ["C0001", "作り物A", "組X", "組の根", "id-根-X"],
        "顧客ID の空": ["", "作り物A", "組X", "2_マスタ", "id-マスタ-X"],
        "同じ行の重なり": 緑の行[0],
        "年でない台帳": ["C0001", "作り物A", "組X", "台帳_26", "id-台帳-26"],
        "型の字の台帳": ["C0001", "作り物A", "組X", 型の口.台帳の名(), "id-台帳"],
        "一覧に無い顧客ID": ["C0009", "作り物A", "組X", "2_マスタ", "id-マスタ-X"],
        "組の違い": ["C0002", "作り物B", "組Y", "2_マスタ", "id-マスタ-Y"],
        "ID の空": ["C0002", "作り物B", "組X", "2_マスタ", ""],
        "組の空": ["C0002", "作り物B", "", "2_マスタ", "id-マスタ-Y"],
    }
    for 何, 行 in 壊す.items():
        assert _赤([*緑の行, 行]), 何


def test_一覧の顧客IDの空と重なりは赤():
    for 壊れた一覧 in (_一覧(("", "作り物A", "組X")), _一覧(("C0001", "作り物A", "組X"), ("C0001", "作り物B", "組X")),
                    _一覧(("C0001", "作り物A", ""))):
        assert 型の口.置き場の登録の赤([見出し], 壊れた一覧), 壊れた一覧
