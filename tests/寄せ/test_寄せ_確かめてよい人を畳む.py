"""型の版 32（直し 32）: 事務所の設定「確かめてよい人」の名簿のタブを畳む（2026-11-19 オーナーの決定）。
版 31 の事務所に残る名簿のタブは、値が無くても在っても消す問いになり、ほかは変わらない。作り物だけ。"""
import copy

import test_寄せ_見張り as 見張り
from test_寄せ_見張り import 当てる, 直しの形  # noqa: F401
import 自己検査  # noqa: E402  （test_寄せ_見張り が 道具/寄せ を path に足した後）

_型 = 当てる.型を開く(見張り.ここ.parent.parent / "初期設定" / "型.json")


def _型31():
    型 = copy.deepcopy(_型)
    s = next(s for s in 型["シート"] if s["シート"] == "事務所の設定")
    s["タブ"].append({"タブ": "確かめてよい人", "形": "表", "列": [{"名": "名", "意味": ""}, {"名": "役目", "意味": ""}]})
    型["版"] = 31
    return 型


def test_直し32は版31から32で名簿のタブを畳むだけ():
    d = [x for x in 直しの形.読む() if x["版"] == 32][0]
    assert (d["前の版"], d["当たる"]) == (31, "全ての事務所")
    assert d["操作"] == [{"する": "タブを畳む", "ファイル": "00_事務所/事務所の設定", "タブ": "確かめてよい人"}]
    assert all(t["タブ"] != "確かめてよい人" for s in _型["シート"] for t in s["タブ"])   # 型から消えた


def _見通す(名簿の行):
    v = 自己検査.雛形(_型31())
    f = next(f for f in v["シート"] if f.endswith("事務所の設定"))
    v["シート"][f]["確かめてよい人"] = [["名", "役目"], *名簿の行]
    return f, 当てる.見通す(v, _型, 直しの形.読む(), 自己検査.今日)


def test_版31の名簿のタブは空でも値が在っても消す問いになり_ほかは今の雛形になる():
    for 行 in ([], [["作り物 確かめる人", "作り物の担当"]]):
        f, r = _見通す(行)
        assert r["寄せられない物"] == [], r["寄せられない物"]
        assert [x for q in r["消す問い"] for x in q["消す手順"]] == [{"する": "タブを消す", "ファイル": f, "タブ": "確かめてよい人"}]
        assert 自己検査.消した後(r) == 自己検査.形だけ(自己検査.雛形(_型))
        assert not any(x.get("タブ") == "確かめてよい人" for x in r["書く手順"])   # 消すタブへ書かない
