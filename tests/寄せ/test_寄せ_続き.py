"""寄せの回の続きの判断の口（道具/寄せ/続き.py）。止まった回の続き・変わらない会社・足りない値の終わりを殻でなくパックが決める。

根（2026-11-24）: 前の回の写しから続けるか・寄せる物が無いか・足りない値だけ残った時の終わり方を殻（事務所の側の口）が
自分で決めていた＝パックの寄せが変わっても殻の判断は古いまま。判断をパックの口 1 つに寄せた。作り物の名だけ。
"""
import json
import subprocess
import sys
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根 / "道具" / "寄せ"))

import 続き  # noqa: E402

C = "作り物の会社"
H = "9_履歴"
写し = [f"{H}/消す_2_マスタ", f"{H}/消す_3_勤怠"]
写す = [{"する": "file を写す", "先": p} for p in 写し] + [{"する": "列を足す"}]


# ---- 渡し方
def test_両方渡せば何も読まずに止める():
    assert 続き.渡し方(C, {"会社": C}, "まだ出していない")["赤"] == [続き.渡す物]


def test_別の会社の入力で突き合わせない():
    assert "別の会社の出す物で突き合わせない" in 続き.渡し方(C, {"会社": "別の作り物の会社"}, "")["赤"][0]


def test_どちらも渡さないのは読む前には止めない():
    assert 続き.渡し方(C, None, "") == {"赤": [], "渡した": False}


# ---- 前の回
def test_一番新しい寄せの記録を選ぶ():
    名 = ["寄せの記録_2000-01-01_000000.json", "寄せの記録_2000-01-02_000000.json", "消す_2_マスタ", "寄せの記録_x.json"]
    assert 続き.前の記録の名(名) == "寄せの記録_2000-01-02_000000.json"
    assert 続き.前の記録の名(["消す_2_マスタ"]) is None


def test_別の会社の寄せの記録では続けない():
    got = 続き.前の回(C, "寄せの記録_2000-01-02_000000.json", json.dumps({"会社": "別の作り物の会社", "写した物": []}))
    assert "の寄せの記録でない" in got["赤"][0]


def test_記録が無ければ写しも無い():
    assert 続き.前の回(C, None, None)["前の回"] == {"記録": None, "写した物": []}


# ---- 見通しと突き合わせる月の後
def test_寄せられない物が在れば書かない():
    assert 続き.見通しの後({"寄せられない物": [1, 2]}) == {"通す": False, "書いた": 0, "寄せられない物": 2, "赤": []}
    assert 続き.見通しの後({}) is None


def test_変わらない会社は寄せる物が無いで終わる():
    # 口の約束: 変わらない会社は書く手順 0 で通す（入力なしでも）
    got = 続き.突き合わせる月の後(False, None, {}, {"変わらない": True, "月": ""}, None)
    assert got["終わる"]["通す"] is True and got["終わる"]["書いた"] == 0


def test_足りない値だけ残れば寄せ終わりと言わない():
    got = 続き.突き合わせる月の後(False, None, {"足りない値": [1]}, None, "作り物の訳")
    assert got["終わる"]["通す"] is False and "寄せ終わりと言わない" in got["終わる"]["赤"][0]


def test_前の回が止まっていれば突き合わせてから外す():
    got = 続き.突き合わせる月の後(False, {"記録": None, "写した物": []}, {"足りない値": [1]}, None, "作り物の訳")
    assert "前の回が寄せ中のまま止まっている" in got["止める"] and got["止める"].endswith("パック: 作り物の訳")


def test_渡した入力をパックが拒めばその訳で止める():
    assert 続き.突き合わせる月の後(True, None, {}, None, "作り物の訳") == {"止める": "作り物の訳"}


def test_変わる会社は入力なしで書かない():
    got = 続き.突き合わせる月の後(False, None, {}, {"変わらない": False, "残り": ["列"]}, None)
    assert "パックの残り: 列" in got["止める"]
    assert 続き.突き合わせる月の後(True, None, {}, {"変わらない": False}, None) == {"続ける": True}


# ---- 続き（写しの照らし）
def test_初めての回は全部写す():
    got = 続き.続き(写し, H, [], None, 写す)
    assert got == {"赤": [], "続きの写し": [], "書く手順": 写す}


def test_止まった回の写しから続ける():
    # 口の約束: 前の回の寄せの記録の 写した物 に在る写しは作り直さず続きから当てる
    got = 続き.続き(写し, H, [写し[0]], {"記録": "r", "写した物": [写し[0]]}, 写す)
    assert got["赤"] == [] and got["続きの写し"] == [写し[0]]
    assert [s.get("先") for s in got["書く手順"]] == [写し[1], None]


def test_記録に無い写しが在れば重ねて書かない():
    # 口の約束: 前の回の寄せの記録に無い写しが履歴に在れば止める
    got = 続き.続き(写し, H, [写し[0]], {"記録": "r", "写した物": []}, 写す)
    assert "前の回の寄せの記録に無い写し" in got["赤"][0]
    assert "前の回の寄せの記録に無い写し" in 続き.続き(写し, H, [写し[0]], None, 写す)["赤"][0]


def test_前の回の写しが重なれば続けない():
    got = 続き.続き(写し, H, [写し[0], 写し[0]], {"記録": "r", "写した物": [写し[0]]}, 写す)
    assert "1 つずつ揃わない" in got["赤"][0]


@pytest.mark.parametrize("写した物", ["作り物", [f"{H}/消す_a", f"{H}/消す_a"], ["他の所/消す_a"], [f"{H}/中/消す_a"]])
def test_写しの名の並びでなければ書かない(写した物):
    assert "履歴の写しの名の並びでない" in 続き.続き(写した物, H, [], None, [])["赤"][0]


def test_口から呼ぶ():
    r = subprocess.run([sys.executable, "-I", str(根 / "道具" / "寄せ" / "続き.py"), "見通しの後"],
                       input=json.dumps({"見通し": {}}), capture_output=True, text=True, cwd=根)
    assert r.returncode == 0 and json.loads(r.stdout) == {"続ける": True}


def test_渡したのにパックの訳が無ければ止める訳を空にしない():
    with pytest.raises(続き.拒む, match="パックの訳 が無い"):
        続き.突き合わせる月の後(True, None, {}, None, None)


@pytest.mark.parametrize("何, 入力, 訳", [
    ("続き", {"履歴": H, "書く手順": 写す}, "写した物"),                                   # 写した物が欠けた＝写す物は無い とみなさない
    ("続き", {"写した物": 写し, "履歴": H, "書く手順": [1]}, "読めない"),                    # 手順が表でない
    ("突き合わせる月の後", {"渡した": True}, "パックの訳 が無い"),                          # 止める訳が空
    ("知らない", {}, "知らない口"),
])
def test_形の崩れた入力は拒む(何, 入力, 訳):
    # 口の約束: 形の崩れた入力はどの崩れでも 拒む と終わりの値 2（traceback と終わりの値 1 で抜けない）
    r = subprocess.run([sys.executable, "-I", str(根 / "道具" / "寄せ" / "続き.py"), 何],
                       input=json.dumps(入力, ensure_ascii=False), capture_output=True, text=True, cwd=根)
    assert r.returncode == 2 and 訳 in json.loads(r.stdout)["拒む"]
