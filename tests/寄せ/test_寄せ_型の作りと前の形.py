"""寄せの作り物の 2 つ（docs/設計/入れてよい物.md ⟦鍵:給与計算/移行だけの物はパックに入れない⟧）。作り物の値と一般の語だけ。

1. 型の作り: 今の型の名で作った版 0 の会社（どの事務所の会社でもよい）は、前の形の読み替え無しで今の版になる（パックの直しは型の作りだけ）
2. 前の形: 事務所の前の道具の形の列・タブは、渡さなければ寄せられない物に出る。人の答え（答えの表）か、
   人の答えの `前の形の読み替え`（版ごとの操作の塊・事務所の Drive に置く物）で寄せられ、どちらも今の版になる
3. 前の形の読み替えの形の誤りは止まる（直しと同じ閉じた一覧・まだ無い版の塊・知らない鍵）
"""
import copy
import datetime as dt
import sys
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根 / "道具" / "寄せ"))

import 当てる  # noqa: E402
import 直し as 直しの形  # noqa: E402

今日 = dt.date(2026, 11, 11)
型の置き場 = 根 / "初期設定" / "型.json"
M = "03_マスタ"


def 寄せる(会社):
    return 当てる.見通す(会社, 当てる.型を開く(型の置き場), 直しの形.読む(), 今日)


def 今の版():
    return 当てる.型を読む(当てる.型を開く(型の置き場))["版"]


def 版0の会社(**前の形):
    """今の型の名で作った版 0 の会社（列「会社」も型の他の列も無い・タブも足りない）。"""
    社員 = [["NO", "氏名"], ["1", "作り物 一郎"], ["2", "作り物 花子"]]
    for 前, 値 in 前の形.items():
        社員[0].append(前)
        for row, v in zip(社員[1:], 値):
            row.append(v)
    return {"会社": "作り物の会社", "型の版": 0, "選んだ部品": [],
            "シート": {M: {"社員": 社員, "会社": [["項目", "今の値"], ["支払.締め日", "末"]]}},
            "md": {}, "置き場": [M]}


def 書いて読み直す(会社, r):
    書いた = 当てる.手順を当てる(会社, r["書く手順"])
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    return 書いた


def 列(r, タブ, 名):
    rows = r["寄せた後の値"]["シート"][M][タブ]
    i = rows[0].index(名)
    return [row[i] for row in rows[1:]]


# ---- 1. 型の作り

def test_今の型の名の版0の会社は前の形の読み替え無しで今の版になる():
    会社 = 版0の会社()
    r = 寄せる(会社)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    assert r["寄せた後の値"]["型の版"] == 今の版() and r["当てた直し"] == list(range(1, 今の版() + 1))
    K = 当てる.型を読む(当てる.型を開く(型の置き場))
    for タブ in ("社員", "人ごとの支給控除", "会社", "支給控除の項目", "勤務の型", "変更の記録", "つなぎ"):
        assert r["寄せた後の値"]["シート"][M][タブ][0] == [c["名"] for c in K["ファイル"][M][タブ]], タブ  # 型の列と並び
    assert 列(r, "社員", "会社") == ["作り物の会社"] * 2 and 列(r, "社員", "氏名") == ["作り物 一郎", "作り物 花子"]
    assert not any("前の形の読み替え" in x for x in r["知らせ"])
    assert r["値の保ち"]["合う"]
    assert 寄せる(書いて読み直す(会社, r))["書く手順"] == []  # 2 回目の当ては手順 0


def test_パックの直しは前の形の名を持たない():
    """直し 1・3 は型の作りの操作だけ（前の名を今の名へ読み替える操作が無い）＝印「全ての事務所」を持つ。"""
    型の作り = {"列を足す", "タブを足す", "列の並びをそろえる", "md の見出しを足す"}
    for d in 直しの形.読む():
        if d["版"] in (1, 3):
            assert d.get("当たる") == "全ての事務所" and "手がかり" not in d
            assert {op["する"] for op in d["操作"]} <= 型の作り, d["版"]


# ---- 2. 前の形

def test_前の形の列は渡さなければ寄せられない物に出て書かない():
    会社 = 版0の会社(作り物の前の在籍=["在籍", "退職"])
    r = 寄せる(会社)
    assert [x["種類"] for x in r["寄せられない物"]] == ["行き先の無い列"]
    assert r["書く手順"] == [] and r["寄せた後の値"]["型の版"] == 0


def test_前の形は答えの表でも前の形の読み替えでも同じ今の版になる():
    会社 = 版0の会社(作り物の前の在籍=["在籍", "退職"])
    鍵 = 寄せる(会社)["寄せられない物"][0]["鍵"]

    答え = copy.deepcopy(会社)  # 人の答え（答えの表の 1 行）
    答え["人の答え"] = {鍵: "今の列へ移す:人.区分|在籍=雇用|退職=退職"}
    r1 = 寄せる(答え)

    読み = copy.deepcopy(会社)  # 事務所の Drive の前の形の読み替え（版 1 の塊）
    読み["人の答え"] = {"前の形の読み替え": [{"版": 1, "なぜ": "作り物の事務所の前の道具の形", "操作": [
        {"する": "列の名を変える", "ファイル": M, "タブ": "社員", "前": "作り物の前の在籍", "後": "人.区分"},
        {"する": "値の語を読み替える", "ファイル": M, "タブ": "社員", "列": "人.区分", "前": "在籍", "後": "雇用"},
        {"する": "値の語を読み替える", "ファイル": M, "タブ": "社員", "列": "人.区分", "前": "退職", "後": "退職"}]}]}
    r2 = 寄せる(読み)

    for r in (r1, r2):
        assert r["寄せられない物"] == [], r["寄せられない物"]
        assert r["寄せた後の値"]["型の版"] == 今の版() and r["値の保ち"]["合う"]
        assert 列(r, "社員", "人.区分") == ["雇用", "退職"]
        assert "作り物の前の在籍" not in r["寄せた後の値"]["シート"][M]["社員"][0]
    assert r1["寄せた後の値"]["シート"] == r2["寄せた後の値"]["シート"]
    assert "前の形の読み替え（人の答え）の操作 3 を、直し 1 の前に当てた" in r2["知らせ"]
    assert 寄せる(書いて読み直す(読み, r2))["書く手順"] == []


def test_前の形のタブの名は前の形の読み替えで今のタブへ():
    """答えの語では渡せない前の形（タブの名）も、前の形の読み替えなら直しと同じ操作で渡せる。"""
    会社 = 版0の会社()
    会社["シート"][M]["作り物の前の記録"] = [["記録日", "適用支給月", "NO", "項目", "前の値"],
                                            ["2026-10-01", "2026.10支給", "1", "氏名", "作り物 一"]]
    r = 寄せる(会社)
    assert [x["種類"] for x in r["寄せられない物"]] == ["行き先の無いタブ"]
    会社["人の答え"] = {"前の形の読み替え": [{"版": 1, "操作": [
        {"する": "タブの名を変える", "ファイル": M, "前": "作り物の前の記録", "後": "変更の記録"}]}]}
    r = 寄せる(会社)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    assert "作り物の前の記録" not in r["寄せた後の値"]["シート"][M]
    assert 列(r, "変更の記録", "前の値") == ["作り物 一"]


def test_塊は型の作りより先に走るので頼る型の作りの操作も塊に入れる():
    """塊はパックの直しの前に当たる。鍵 会社 で別のタブへ畳む前の形の操作だけでは止まり（全部か無し）、
    頼る型の作りの操作（タブ・列「会社」を足す）も入れれば寄せられる（前の版の直しの全部の操作を塊にしてよい訳）。"""
    畳む = {"する": "列を畳む", "ファイル": M, "タブ": "社員", "列": "作り物の前の手当",
            "先": {"タブ": "人ごとの支給控除", "鍵": ["会社", "NO"], "足す行": {"項目": "作り物手当"}, "列": "額"}}
    会社 = 版0の会社(作り物の前の手当=["1000", ""])
    会社["人の答え"] = {"前の形の読み替え": [{"版": 1, "操作": [畳む]}]}
    r = 寄せる(会社)
    assert "直しの誤り" in [x["種類"] for x in r["寄せられない物"]] and r["書く手順"] == []
    型の作り = [{"する": "タブを足す", "ファイル": M, "タブ": "人ごとの支給控除"},
               {"する": "列を足す", "ファイル": M, "タブ": "社員", "見出し": "会社", "値": "<会社>"}]
    会社["人の答え"] = {"前の形の読み替え": [{"版": 1, "操作": [*型の作り, 畳む]}]}
    r = 寄せる(会社)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    rows = r["寄せた後の値"]["シート"][M]["人ごとの支給控除"]
    h = rows[0]
    assert [(x[h.index("NO")], x[h.index("項目")], x[h.index("額")]) for x in rows[1:]] == [("1", "作り物手当", "1000")]
    assert r["値の保ち"]["合う"] and r["寄せた後の値"]["型の版"] == 今の版()


def test_会社の版より前の塊は当てない():
    会社 = 版0の会社()
    会社["型の版"] = 1
    会社["人の答え"] = {"前の形の読み替え": [{"版": 1, "操作": [
        {"する": "列の名を変える", "ファイル": M, "タブ": "社員", "前": "無い列", "後": "人.区分"}]}]}
    r = 寄せる(会社)
    assert r["当てた直し"] == list(range(2, 今の版() + 1))
    assert not any("前の形の読み替え" in x for x in r["知らせ"])


# ---- 3. 形の誤り

@pytest.mark.parametrize("塊, 字", [
    ({"版": 1, "操作": [{"する": "作り物の操作"}]}, "閉じた一覧に無い"),
    ({"版": 1, "操作": [{"する": "列の名を変える", "ファイル": M, "タブ": "社員", "前": "a"}]}, "鍵が無い"),
    ({"版": 99, "操作": []}, "まだ無い"),
    ({"版": 1, "操作": [], "作り物の鍵": 1}, "知らない鍵"),
    ({"操作": []}, "版（1 以上の数）と 操作"),
    ({"版": True, "操作": []}, "版（1 以上の数）と 操作"),
    ({"版": 0, "操作": [{"する": "タブを足す", "ファイル": M, "タブ": "作り物"}]}, "版（1 以上の数）と 操作"),
    ({"版": -1, "操作": []}, "版（1 以上の数）と 操作"),
    ({"版": 1, "操作": [], "手がかり": "作り物"}, "手がかり は"),
    ({"版": 1, "操作": ["列の名を変える"]}, "操作 の 1 つ 1 つ"),
])
def test_前の形の読み替えの形の誤りは止まる(塊, 字):
    会社 = 版0の会社()
    会社["人の答え"] = {"前の形の読み替え": [塊]}
    with pytest.raises(直しの形.直しの誤り, match=字):
        寄せる(会社)
