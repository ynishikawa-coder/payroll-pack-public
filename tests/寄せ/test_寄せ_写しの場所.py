"""見張り: 管理表「会社」の 写しの場所 を寄せる道具の 管理表へ書く が組む（寄せる道具.md §2.2 の 7）。作り物の値だけ。

1. 書く回は 写した物（9_履歴/消す_<日>_<名>）を返し、殻がそれを照らす回の入力 写しの場所 へ渡し返すと 管理表へ書く に載る。
2. 写した物の無い回（写しの場所を渡さない）は 写しの場所 の列を書かない（前の記録を空で上書きしない）。
3. 注入: 写しの場所 に名の並びでない物・9_履歴/消す_ の外の名・照らす回の置き場に無い名・同じ元により新しい写しが在る名
   （直前の書く回の 写した物 でない）を渡すと落ちる（黙って別の物を管理表に書かない）。
4. 注入: 呼び口が落ちた時の終わりの値は 2（寄せられない物の 1 と分ける＝殻が落ちた回を寄せられない物の回と読まない）。
   結果を字に直す途中で落ちても標準出力は空（半端な JSON を残さない）。
"""
import json
import subprocess
import sys
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根 / "道具" / "寄せ"))
sys.path.insert(0, str(ここ))
import 当てる  # noqa: E402
import test_寄せ_前の形を見つける as 前  # noqa: E402

import importlib.util as 管理表  # noqa: E402


def _版9の会社():
    会社 = 前.今の形の会社()
    会社["型の版"] = 10
    前._列を抜く(会社["シート"][前.Q]["質問"], "対象", "理由", "分かっている事", "資料", "探した資料", "くわしく", "変わる事")
    return 会社


def test_書く回の写した物を照らす回へ渡し返すと管理表へ書くに写しの場所が載る():
    会社 = _版9の会社()
    r = 前.寄せる(会社)
    assert r["書く手順"] and r["管理表へ書く"] == []
    assert r["写した物"] and all(x.startswith("9_履歴/消す_") for x in r["写した物"])
    写した = {s.get("先") or s.get("後") for s in r["書く手順"] if s["する"] in ("file を写す", "file を移す")}
    assert set(r["写した物"]) <= 写した
    書いた = 当てる.手順を当てる(会社, r["書く手順"])
    書いた["型の版"] = 10
    assert set(r["写した物"]) <= set(書いた["置き場"])   # 写しは照らす回に読む置き場（9_履歴）に在る
    書いた["写しの場所"] = r["写した物"]
    r2 = 前.寄せる(書いた)
    assert r2["書く手順"] == [] and r2["写した物"] == []
    [行] = r2["管理表へ書く"]
    assert 行["写しの場所"].split("\n") == r["写した物"]
    assert 行["型の版"] == str(r2["今の版"]) and 行["会社"] == "作り物の会社"


def test_写した物の無い回は写しの場所の列を書かない():
    会社 = _版9の会社()
