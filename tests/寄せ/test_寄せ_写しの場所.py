def test_注入_同じ元により新しい写しが在る古い写しを渡すと落ちる():
    """前の寄せの古い写し（置き場に在る）を渡しても、同じ元の新しい写しが在れば直前の書く回の 写した物 でない＝拒む。"""
    r, 書いた = _書いた後()
    名 = r["写した物"][0][len("9_履歴/消す_") + 11:]
    古い = f"9_履歴/消す_2000-01-31_{名}"
    書いた["置き場"].append(古い)
    書いた["写しの場所"] = [古い]
    with pytest.raises(ValueError, match="より新しい"):
        前.寄せる(書いた)
    書いた["写しの場所"] = r["写した物"]   # 新しい方なら通る
    assert 前.寄せる(書いた)["管理表へ書く"][0]["写しの場所"].split("\n") == r["写した物"]


def test_注入_結果を字に直す途中で落ちても標準出力は空で終わりの値は2(tmp_path, monkeypatch, capsys):
    import importlib.util as u
    spec = u.spec_from_file_location("呼び口", 根 / "道具" / "寄せ" / "呼び口.py")
    呼び口 = u.module_from_spec(spec)
    spec.loader.exec_module(呼び口)
    元 = 呼び口.当てる.見通す

    def 半端(*a, **k):
        r = 元(*a, **k)
        r["zz_直せない値"] = object()   # 先の鍵は直せて、最後で落ちる
        return r
    monkeypatch.setattr(呼び口.当てる, "見通す", 半端)
    monkeypatch.setattr(呼び口.当てる, "人が見る物", lambda r: "")
    p = tmp_path / "会社.json"
    p.write_text(json.dumps(_版9の会社(), ensure_ascii=False), encoding="utf-8")
    rc = 呼び口.main(["寄せる", "--会社", str(p), "--型", str(根 / "初期設定" / "型.json"), "--今日", "2026-11-16"])
    out = capsys.readouterr()
    assert rc == 2 and out.out == "" and "呼び口が落ちた" in out.err
