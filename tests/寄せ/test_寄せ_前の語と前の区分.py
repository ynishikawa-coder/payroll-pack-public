"""見張り: 寄せの後に前の語・前の区分が黙って残る／消える所（docs/設計/寄せる道具.md §4.1・§4.5）。作り物の値と一般の語だけ。

- 型の形に合っても芯の選べる値の外の字（前の語）は問いにし、答えの値も選べる値の外なら書かず問いに残す
- 旧_ のタブの前の列「区分」は、同じ NO の今の行の 人.区分 が空なら、同じ字が選べる値の時だけ移し、外なら見当で読み替えず問う
- NO の在る 旧_ のタブは人ごとに照らす（ほかの人の行に同じ字が在るだけでは「今に在る」と数えない）
"""
import copy
import datetime as dt
import json
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根 / "道具" / "寄せ"))
sys.path.insert(0, str(ここ))
import 当てる  # noqa: E402
import 作り物の殻  # noqa: E402
import 直し as 直しの形  # noqa: E402

今日 = dt.date(2026, 11, 11)
M = "2_マスタ"


def 前の形():
    return json.loads((ここ / "作り物の前の形.json").read_text(encoding="utf-8"))


def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(根 / "初期設定" / "型.json"), 直しの形.読む(), 今日)


def 答えて(会社, 答え):
    c = copy.deepcopy(会社)
    c["人の答え"] = 答え
    return 寄せる(c)


def 人の区分(r):
    s = r["寄せた後の値"]["シート"][M]["社員"]
    i = s[0].index("人.区分")
    return [row[i] for row in s[1:]]


def test_選べる値の外の字は問いにし答えも外なら書かない():
    会社 = 前の形()
    会社["シート"][M]["会社"].append(["欠勤・遅刻早退の控除の式", "作り物の前の式", "", ""])
    r = 寄せる(会社)
    assert [x["種類"] for x in r["寄せられない物"]] == ["表の外の字"]
    鍵 = r["寄せられない物"][0]["鍵"]
    assert r["書く手順"] == []

    r = 答えて(会社, {鍵: "値:作り物の別の式"})
    assert [x["鍵"] for x in r["寄せられない物"]] == [鍵]
    assert any(n.startswith(鍵) and "選べる値の外" in n for n in r["知らせ"])

    r = 答えて(会社, {鍵: "値:引く方式"})
    assert r["寄せられない物"] == [] and r["値の保ち"]["合う"]
    後 = {row[1]: row[2] for row in r["寄せた後の値"]["シート"][M]["会社"][1:]}
    assert 後["欠勤.控除の式"] == "引く方式"


def test_前の区分は選べる値なら移し外なら問う():
    会社 = 前の形()
    会社["シート"][M]["旧_社員"] = [["NO", "氏名", "区分"], ["1", "作り物 一郎", "役員"], ["2", "作り物 二子", "作り物の前の区分"]]
    r = 寄せる(会社)
    外 = {x["鍵"]: x for x in r["寄せられない物"]}
    鍵 = f"{M}/社員/前の列:区分→人.区分/NO=2"
    assert 鍵 in 外 and 外[鍵]["種類"] == "前の列が移っていない"
    assert f"{M}/社員/前の列:区分→人.区分/NO=1" not in 外   # 同じ字が選べる値＝読み替えずに移す

    旧 = f"{M}/旧_社員/旧のタブ"
    r = 答えて(会社, {鍵: "値:作り物の区分", 旧: "9_履歴 へ写して消す"})
    assert 鍵 in {x["鍵"] for x in r["寄せられない物"]}   # 答えも選べる値の外＝書かない

    r = 答えて(会社, {鍵: "値:パート", 旧: "9_履歴 へ写して消す"})
    assert r["寄せられない物"] == [] and r["値の保ち"]["合う"], r["寄せられない物"]
    assert 人の区分(r) == ["役員", "パート"]

    r = 答えて(会社, {鍵: "後で埋める", 旧: "9_履歴 へ写して消す"})
    assert r["寄せられない物"] == [] and 人の区分(r) == ["役員", ""]


def test_旧のタブは人ごとに照らしほかの人の行の同じ字では在るとしない():
    会社 = 前の形()
    # NO 1 の前のメモの字は NO 2 の氏名と同じ＝ファイルには在るが、NO 1 の今の行には無い
    会社["シート"][M]["旧_社員"] = [["NO", "氏名", "作り物のメモ"], ["1", "作り物 一郎", "作り物 二子"]]
    r = 寄せる(会社)
    外 = [x for x in r["寄せられない物"] if x["鍵"] == f"{M}/旧_社員/旧のタブ"]
    assert 外 and "列 作り物のメモ: 1 個" in 外[0]["中身"], r["寄せられない物"]

    会社["シート"][M]["旧_社員"] = [["NO", "氏名"], ["1", "作り物 一郎"]]   # 同じ人の今の行に在る値だけ＝消してよい
    r = 寄せる(会社)
    assert all(x["鍵"] != f"{M}/旧_社員/旧のタブ" for x in r["寄せられない物"])


def 源泉の欄(r):
    s = r["寄せた後の値"]["シート"][M]["社員"]
    i = s[0].index("源泉.欄")
    return [row[i] for row in s[1:]]


def test_表の外の同じ字は列と値の鍵で1問にまとめ答えは全部の行へ当てる():
    会社 = 前の形()
    s = 会社["シート"][M]["社員"]
    i = s[0].index("源泉の欄")
    for row in s[1:]:
        row[i] = "作り物の前の欄"
    r = 寄せる(会社)
    外 = [x for x in r["寄せられない物"] if x["種類"] == "表の外の字"]
    鍵 = f"{M}/社員/表の外の字:源泉.欄/作り物の前の欄"
    assert [x["鍵"] for x in 外] == [鍵], 外   # 行ごとに問わない（鍵は <列>/<値>）
    assert "NO=1" in 外[0]["中身"] and "NO=2" in 外[0]["中身"]
    r = 答えて(会社, {鍵: "値:甲"})
    assert r["寄せられない物"] == [], r["寄せられない物"]
    assert 源泉の欄(r) == ["甲", "甲"]


def test_前の列が二つの旧のタブで違えば先の物を黙って取らず問う():
    会社 = 前の形()
    会社["シート"][M]["旧_社員"] = [["NO", "氏名", "区分"], ["1", "作り物 一郎", "役員"], ["2", "作り物 二子", "パート"]]
    会社["シート"][M]["旧_社員の写し"] = [["NO", "氏名", "区分"], ["1", "作り物 一郎", "役員"], ["2", "作り物 二子", "役員"]]
    r = 寄せる(会社)
    外 = {x["鍵"]: x for x in r["寄せられない物"]}
    鍵 = f"{M}/社員/前の列:区分→人.区分/NO=2"
    assert 鍵 in 外 and "違う" in 外[鍵]["中身"], r["寄せられない物"]
    assert f"{M}/社員/前の列:区分→人.区分/NO=1" not in 外   # 同じ字で選べる値＝移す
    旧 = {f"{M}/旧_社員/旧のタブ": "9_履歴 へ写して消す", f"{M}/旧_社員の写し/旧のタブ": "9_履歴 へ写して消す"}
    r = 答えて(会社, {鍵: "値:パート", **旧})
    assert all(not x["鍵"].startswith(f"{M}/社員/前の列") for x in r["寄せられない物"]), r["寄せられない物"]
    assert 人の区分(r) == ["役員", "パート"]
