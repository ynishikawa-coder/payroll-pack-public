"""作り物の事務所の殻: その事務所の前の道具の形の読み替えを、人の答え の「前の形の読み替え」で寄せる道具へ渡す。

前の形の読み替えはパックに置かない（docs/設計/入れてよい物.md「1 社の移行だけ」）。本物は各事務所の Drive の寄せの記録に在り、
殻が人の答えに入れて渡す。ここの `作り物の前の形の読み替え.json` は作り物の会社（`作り物の前の形.json`）の前の形に合わせた例で、
口（道具/寄せ/当てる.py の 前の形を足す）を試すためだけの物。
"""
import json
from pathlib import Path

ここ = Path(__file__).resolve().parent
鍵 = "前の形の読み替え"


def 読み替え() -> list:
    return json.loads((ここ / "作り物の前の形の読み替え.json").read_text(encoding="utf-8"))


def 前の形を渡す(会社: dict) -> dict:
    """会社の人の答えに前の形の読み替えを足した写しを返す（会社の人の答えに在ればそれが勝つ）。"""
    return {**会社, "人の答え": {鍵: 読み替え(), **会社.get("人の答え", {})}}
