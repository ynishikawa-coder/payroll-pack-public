def test_写した後に人が指示の値を直すとぶつかり_答えで閉じる():
    """A2: 一度写した後に人が その月だけの指示 の値を直した。寄せは直した値を書き替えず、今の値ごとの問いにする。"""
    書いた = 写して書く(月の変動の会社())
    指示の値を書く(書いた, "1600")
    r = 寄せる(書いた)
    鍵 = 鍵たち(r, 指示の問い)
    assert 鍵 == [f"{指示の問い}会社=作り物の会社/支給月=2026.10支給/NO=1/項目=作り物の調整/指示の値=1600"]
    問い = [x for x in r["寄せられない物"] if x["鍵"] == 鍵[0]][0]
    assert set(問い["選べる答え"]) == {"その月だけの指示を正とする", "持たない:<なぜ>"}
