"""見張り: 寄せは変更の記録の標準報酬の行（社保.標準報酬・社保.厚年の標準報酬）の 適用支給月 を保険料の月 `YYYY.MM分` で書き、
段の解決が古い書き方として止めずに通す。前の道具の支給月は 社保.徴収の月（人 → 会社 → 事務所の設定の既定）と
芯の 保険料の月（1 か所の正本）で直す。徴収の月が引けなければ黙って決めず問い（値:<YYYY.MM分>・行ごと外す）。
作り物の値と一般の語だけ。
"""
import copy
import datetime as dt
import importlib.util
import json
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根 / "道具" / "寄せ"))
if str(根) not in sys.path:
    sys.path.insert(0, str(根))
sys.path.insert(0, str(ここ))
import 当てる  # noqa: E402
import 作り物の殻  # noqa: E402
import 直し as 直しの形  # noqa: E402

今日 = dt.date(2026, 11, 12)
M = "2_マスタ"
NO列 = "NO（複数は・で区切る・会社は空）"


def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(根 / "初期設定" / "型.json"), 直しの形.読む(), 今日)


def 段():
    spec = importlib.util.spec_from_file_location("寄せ_保険料の月_段の解決", 根 / "初期設定" / "段の解決.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def 行(rows, **v):
    return [v.get(c, "") for c in rows[0]]


def 会社を作る(徴収="翌月", 適用支給月="2026-10", 項目="健保の標準報酬"):
    """前の道具の会社: NO 1 の標準報酬が 2026-10 支給から 180000 → 200000（確かめ＝確認済）。徴収 None なら徴収の月の行を置かない。"""
    会社 = json.loads((ここ / "作り物の前の形.json").read_text(encoding="utf-8"))
    S = 会社["シート"][M]
    S["会社"] = [x for x in S["会社"] if x[0] not in ("社保の徴収の月", "社保.徴収の月")]
    if 徴収 is not None:
        S["会社"].append(["社保の徴収の月", 徴収, "", ""])
    社員 = S["社員"]
    社員[1][社員[0].index("健保の標準報酬")] = "200000"
    記 = S["更新ログ"]
    記[1:] = [行(記, 記録日="2026-09-20", 適用支給月=適用支給月, **{NO列: "1"}, 項目=項目,
               前の値="180000", 新しい値="200000", 確かめ="確認済")]
    会社["人の答え"] = {}
    return 会社


def 記録(r):
    v = r["寄せた後の値"] if not r["寄せられない物"] else r["見通しの値"]
    rows = v["シート"][M]["変更の記録"]
    return [dict(zip(rows[0], x)) for x in rows[1:]]


def 書く(前, r):
    assert r["寄せられない物"] == [], r["寄せられない物"]
    書いた = 当てる.手順を当てる(前, r["書く手順"])
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    r2 = 寄せる(書いた)   # 何度当てても同じ（YYYY.MM分 の字はそのまま）
    assert r2["書く手順"] == [] and r2["寄せられない物"] == [], (r2["書く手順"][:2], r2["寄せられない物"])
    return 書いた


def 標準報酬(書いた, 支給月):
    S = 書いた["シート"][M]
    x = 段().解く(支給月, 会社=S["会社"], 勤務の型=S["勤務の型"], 社員=S["社員"], 人ごとの支給控除=S["人ごとの支給控除"],
               支給控除の項目=S["支給控除の項目"], 変更の記録=S["変更の記録"])
    c = 書いた["会社"]
    assert not any(v["項目"] == "変更の記録.適用支給月" for v in x["仮の値"]), x["仮の値"]   # 古い書き方として止まらない
    return x["人"][(c, "1")].get("社保.標準報酬")


def test_寄せた標準報酬の行は保険料の月で書かれ段の解決を通る():
    # 翌月徴収: 2026.10 支給から引く保険料＝2026.09 分
    前 = 会社を作る("翌月")
    r = 寄せる(前)
    assert [(x["項目"], x["適用支給月"]) for x in 記録(r)] == [("社保.標準報酬", "2026.09分")]
    書いた = 書く(前, r)
    assert 標準報酬(書いた, "2026.10支給") == "200000"
    assert 標準報酬(書いた, "2026.09支給") == "180000"   # 前の支給月は前の値へ戻る（保険料の月 2026.08 < 2026.09）


def test_当月徴収は同じ月の分():
    前 = 会社を作る("当月")
    r = 寄せる(前)
    assert [x["適用支給月"] for x in 記録(r)] == ["2026.10分"]
    書いた = 書く(前, r)
    assert 標準報酬(書いた, "2026.10支給") == "200000" and 標準報酬(書いた, "2026.09支給") == "180000"


def test_厚年の標準報酬の行も保険料の月で_外の行は支給月のまま():
    前 = 会社を作る("翌月", 項目="厚年の標準報酬")
    記 = 前["シート"][M]["更新ログ"]
    記.append(行(記, 記録日="2026-09-20", 適用支給月="2026-10", **{NO列: "1"}, 項目="委託の月給（総額）",
               前の値="280000", 新しい値="300000", 確かめ="確認済"))
    r = 寄せる(前)
    assert [(x["項目"], x["適用支給月"]) for x in 記録(r)] == [("社保.厚年の標準報酬", "2026.09分"), ("委託.月給", "2026.10支給")]


def test_既に保険料の月で書いた行はそのまま():
    前 = 会社を作る(None, 適用支給月="2026年9月分")   # 徴収の月が無くても、分の字は保険料の月＝直さずそろえるだけ
    r = 寄せる(前)
    assert [x["適用支給月"] for x in 記録(r)] == ["2026.09分"]
    書く(前, r)


def test_徴収の月が引けなければ黙って決めず問い():
    for 徴収 in (None, "毎月"):
        前 = 会社を作る(徴収)
        r = 寄せる(前)
        鍵 = [x["鍵"] for x in r["寄せられない物"] if "保険料の月:適用支給月" in x["鍵"]]
        assert 鍵 == [f"{M}/変更の記録/保険料の月:適用支給月/NO=1/項目=健保の標準報酬/記録日=2026-09-20"], r["寄せられない物"]
        assert r["書く手順"] == []
        x = next(x for x in r["寄せられない物"] if x["鍵"] == 鍵[0])
        assert x["選べる答え"] == ["値:<YYYY.MM分>", "行ごと外す"]
        # 支給月の字（YYYY.MM支給）へ黙ってそろえない
        assert [y["適用支給月"] for y in 記録(r)] == ["2026-10"]
        if 徴収 is not None:
            continue
        答えた = copy.deepcopy(前)
        答えた["人の答え"][鍵[0]] = "値:2026.09分"
        r2 = 寄せる(答えた)
        assert [y["適用支給月"] for y in 記録(r2)] == ["2026.09分"]
        書く(答えた, r2)
        外した = copy.deepcopy(前)
        外した["人の答え"][鍵[0]] = "行ごと外す"
        r3 = 寄せる(外した)
        assert 記録(r3) == []
        書く(外した, r3)


def test_事務所の設定の既定の徴収の月を引く():
    前 = 会社を作る(None)
    前["シート"]["00_事務所/事務所の設定"] = {"既定": [["項目", "今の値", "メモ"], ["社保.徴収の月", "当月徴収", ""]]}
    r = 寄せる(前)
    assert [x["適用支給月"] for x in 記録(r)] == ["2026.10分"], r["寄せられない物"]
