"""殻が Drive に置く物の名と置き場は Drive の型 §2「殻が Drive に置く物」と 道具/寄せ/見回り.py の 1 か所（束 E・2026-11-22）。作り物の値だけ。

根: 殻が置く物（確認事項の版・下書き_・前の版の移し・届いた物・月のフォルダ・見通しと消す問い）の名を窓が組み、
置き場の検査は 8_確認事項・3_月ごと の中・00_事務所 の中の名を照らさず黙って通した。ここは外れた名をわざと置いて
置き場の検査が赤にする事と、名を返す口が外れた値を拒む事を見る。
"""
import datetime as dt
import sys
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
sys.path.insert(0, str(ここ.parent.parent / "道具" / "寄せ"))

import 見回り  # noqa: E402

日 = dt.date(2099, 1, 1)
月 = "2099.04支給（3月分）"
組 = "作り物の組"


def _赤(置き場, **会社):
    return [(x["項目"], x["所"]) for x in 見回り.置き場の検査({"会社": "作り物の会社", "組": 組, "置き場": 置き場, **会社}, 日) if x["赤"]]


def test_正しい名だけなら赤は無い():
    置き場 = ["3_月ごと/", f"3_月ごと/{月}/", f"3_月ごと/{月}/1_届いた物/", f"3_月ごと/{月}/1_届いた物/勤怠_2099-04-01_原本.csv",
           "8_確認事項/", f"8_確認事項/確認事項_{組}_{月}_v2.html", f"8_確認事項/下書き_確認事項_{組}_{月}_v3.html",
           f"9_履歴/消す_2099-05-31_確認事項_{組}_{月}_v1.html",
           "00_事務所/管理表", f"00_事務所/確認事項_事務所_{月}_v1.html"]
    assert _赤(置き場) == []


@pytest.mark.parametrize("p,項目", [
    (f"8_確認事項/確認事項_{組}_{月}_v1.html", 7),                     # 前の版が残る（v2 と並ぶ）
    (f"8_確認事項/下書き_確認事項_{組}_{月}_v2.html", 7),               # 配った版と同じ版の下書きが残る
    (f"8_確認事項/確認事項_ほかの組_{月}_v1.html", 1),                  # ほかの組の名
    ("8_確認事項/確認事項_作り物の組_2099.04_v1.html", 1),              # 支給月の形が外れた名
    ("8_確認事項/メモ.html", 1),
    ("3_月ごと/2099.4支給/", 1),                                         # 月のフォルダの名が外れた
    ("3_月ごと/2099.13支給（12月分）/", 1),
    (f"3_月ごと/{月}/1_届いた物/原本.csv", 7),                           # 届いた物の名に頭と日が無い
    (f"3_月ごと/{月}/1_届いた物/勤怠_2099-4-1_原本.csv", 7),
    ("00_事務所/配り_見通し.md", 5),                                     # 作業場の物を Drive に置いた
    ("00_事務所/消す問い.md", 5),
    ("8_確認事項/寄せ_見通し.json", 5),
    (f"00_事務所/確認事項_事務所_2099.04_v1.html", 1),
])
def test_外れた名をわざと置くと赤(p, 項目):
    置き場 = [f"8_確認事項/確認事項_{組}_{月}_v2.html", p]
    assert (項目, p.rstrip("/")) in _赤(置き場), _赤(置き場)


def test_事務所の確認事項も前の版が残れば赤():
    a, b = f"00_事務所/確認事項_事務所_{月}_v1.html", f"00_事務所/確認事項_事務所_{月}_v2.html"
    assert (7, a) in _赤([a, b])


def test_組を渡さない1社の会社は会社の名を組に読む():
    p = f"8_確認事項/確認事項_作り物の会社_{月}_v1.html"
    assert 見回り.置き場の検査({"会社": "作り物の会社", "置き場": [p]}, 日) == []


def test_見回りは00_事務所の赤を会社ごとに重ねない():
    # 本物の 見回り.見回り に、00_事務所 の同じ外れた名を持つ 2 社を渡す（殻は会社ごとの置き場に同じ 00_事務所/<名> を並べる）。
    # 置き場の検査の行が 1 つでなければ、事務所に 1 つの物の赤を会社の数だけ人に見せている
    import json
    sys.path.insert(0, str(ここ.parent.parent))
    import 管理表.管理表 as 管理表の口
    根 = ここ.parent.parent
    型 = json.loads((根 / "初期設定" / "型.json").read_text(encoding="utf-8"))
    h = 管理表の口.見出し("会社")
    表 = [h] + [[{"会社": 社, "組": 社, "型の版": str(型["版"])}.get(k, "") for k in h] for 社 in ("作り物の会社", "作り物の会社2")]
    会社たち = [{"会社": 社, "組": 社, "型の版": int(型["版"]), "置き場": ["00_事務所/メモ.txt"], "シート": {}}
             for 社 in ("作り物の会社", "作り物の会社2")]
    r = 見回り.見回り(会社たち, [], int(型["版"]), 日, "作り物の窓", None, 型=型, 管理表=表)
    行 = [x for x in r["置き場の検査"] if x["所"] == "00_事務所/メモ.txt"]
    assert len(行) == 1 and 行[0]["赤"], r["置き場の検査"]
    assert r["赤"]


def test_名を返す口():
    assert 見回り.置く物の名("届いた物", 頭="勤怠", 日="2099-04-01", 元の名="原本.csv") == "勤怠_2099-04-01_原本.csv"
    assert 見回り.置く物の名("月のフォルダ", 支給月="2099.04支給", 支給の月="翌月") == 月
    assert 見回り.置く物の名("作業場", 物="配りの見通し", 拡張子=".md") == "配り_見通し.md"
    for 何, 値 in [("届いた物", {"頭": "勤怠_", "日": "2099-04-01", "元の名": "a"}), ("届いた物", {"頭": "勤怠", "日": "2099-4-1", "元の名": "a"}),
                 ("届いた物", {"頭": "勤怠", "日": "2099-04-01", "元の名": "a/b"}), ("月のフォルダ", {"支給月": "2099.13支給"}),
                 ("作業場", {"物": "見通し", "拡張子": ".md"}), ("確認事項", {})]:
        with pytest.raises(ValueError):
            見回り.置く物の名(何, **値)


def test_口の記録の名は口が組み外れた値を拒む():
    assert 見回り.口の記録の名を組む("寄せの記録", "2099-04-01", "093000") == "寄せの記録_2099-04-01_093000.json"
    assert 見回り.口の記録の名を組む("置き場の登録の写し", "2099-04-01", "093000") == "置き場の登録の写し_2099-04-01_093000.json"
    for a in [("寄せの記", "2099-04-01", "093000"), ("寄せの記録", "20990401", "093000"), ("寄せの記録", "2099-04-01", "9300"),
              ("寄せの記録", "2099-02-30", "093000"), ("寄せの記録", "2099-04-01", "256000")]:
        with pytest.raises(ValueError):
            見回り.口の記録の名を組む(*a)


def test_消す日を詰めた名は期限と読まない():
    assert 見回り.名の期限("9_履歴/消す_2099-01-31_a") == dt.date(2099, 1, 31)
    assert 見回り.名の期限("9_履歴/消す_20990131_a") is None
