"""9_履歴/ へ移す物の名 `消す_<消す日>_<元の名>` の形は 確認ページ.消す名・消す名を読む の 1 つの口（PR #301 レビュー red 2026-11-24）。作り物の値だけ。

根: 名の形が 当てる.py（写しの頭・写しの名・写しの先の f 字）・見回り.py（期限の名・寄せの写しか・写しが在るか）・確認ページ.py
（差し替え・配る手順）・続き.py（写した物の頭）に別々に書かれ、作る側の形だけを変えても試験が緑のままだった。
ここは、作る口（当てる.写しの先・確認ページ.差し替え・配る手順）が組んだ名を、読む口（当てる.写しを読む・写しの場所を読む・
見回り.名の期限・寄せの写しか・写しが在るか・確認ページ.履歴の名の形・続き.続き）が全部読み戻せる事を見る。
注入: 口の 消す名 の形を変える（消す- にする）と、作る側と読む側がそろわず赤（下の test_形をずらすと赤）。
"""
import datetime as dt
import sys
from pathlib import Path

import pytest

ここ = Path(__file__).resolve().parent
sys.path.insert(0, str(ここ.parent.parent / "道具" / "寄せ"))

import 当てる  # noqa: E402
import 見回り  # noqa: E402
import 続き  # noqa: E402

頁 = 見回り.確認の口
H = 当てる.履歴の名
日 = "2099-05-31"
組, 支 = "作り物の組", "2099.04支給"


def _そろわない() -> list[str]:
    """作る口が組んだ名を読む口が読み戻せない所の並び（空＝そろう）。"""
    out = []
    f = "1_月ごと/作り物の勤怠.md"
    先 = 当てる.写しの先(日, f)
    名 = 先.split("/", 1)[1]
    会社 = {"md": {f: ""}, "置き場": [先, f]}
    if 当てる.写しを読む(先) != (日, f.replace("/", "_")):
        out.append("当てる.写しを読む")
    if not 当てる.写しの名.fullmatch(先):
        out.append("当てる.写しの名")
    try:
        当てる.写しの場所を読む({"写しの場所": [先], "置き場": [先]})
    except ValueError:
        out.append("当てる.写しの場所を読む")
    if 見回り.名の期限(先) != dt.date.fromisoformat(日):
        out.append("見回り.名の期限")
    if not 見回り.寄せの写しか(名, 会社):
        out.append("見回り.寄せの写しか")
    if not 見回り.写しが在るか(会社, f):
        out.append("見回り.写しが在るか")
    if 続き.続き([先], H, [], None, [])["赤"]:
        out.append("続き.続き")
    前 = 頁.名(組, 支, 1)
    移し = 頁.差し替え(組, 支, 前, 日)["先"]
    底 = 移し.rsplit("/", 1)[-1]
    if 頁.消す名を読む(底) != (日, 前) or not 頁.履歴の名の形.fullmatch(底) or 見回り.名の期限(移し) != dt.date.fromisoformat(日):
        out.append("確認ページ.差し替え")
    if 当てる.写しの先(日, "x.md") != f"{H}/" + 頁.消す名(日, "x.md"):
        out.append("当てる と 確認ページ の組み方")
    return out


def test_作る口の名を読む口が全部読み戻す():
    assert _そろわない() == []


def test_配る手順の前の版の移しも同じ形():
    前 = 頁.名(組, 支, 1)
    今 = 頁.名(組, 支, 2)
    手 = 頁.配る手順(組, 支, [(今, "<!doctype html>\n" + 頁.枚の印(1, 1) + f'\n<input type="hidden" name="__版__" value="{頁.版の字(支, 2)}">')],
                 [前], [], "2099-04-10")
    先たち = [x["先"].rsplit("/", 1)[-1] for x in 手["移す"]]
    assert 先たち and all(頁.消す名を読む(x) and 頁.消す名を読む(x)[1] == 前 for x in 先たち)


@pytest.mark.parametrize("消す日, 元", [("2099-02-30", "a.md"), ("20990531", "a.md"), (日, "中/a.md"), (日, "")])
def test_形の外は組まない(消す日, 元):
    with pytest.raises(ValueError):
        頁.消す名(消す日, 元)


def test_形をずらすと赤(monkeypatch):
    # 注入: 作る側の口だけ形を変える（消す_ → 消す-）＝読む側とそろわない事を見張りが拾う
    口 = 当てる.確認ページの形()
    monkeypatch.setattr(口, "消す名", lambda d, n: f"消す-{d}_{n}")
    assert _そろわない()
