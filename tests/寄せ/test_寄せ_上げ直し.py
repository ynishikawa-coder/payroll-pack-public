# ---- 8_確認事項 の前の形

確認 = 当てる.型の口.名("確認事項") + "/"
消す日 = 当てる.期限の日(今日)
前のページ = 確認 + "確認ページ_作り物の組_2026.11支給（10月分）_v1.html"
前の下書き = 確認 + "下書き_確認ページ_作り物の組_2026.12支給（11月分）_v1.html"
月のフォルダ = 確認 + "2026.11支給（10月分）/"
月の中 = 月のフォルダ + "確認ページ_作り物の組_2026.11支給（10月分）_v2.html"
今のページ = 確認 + "確認事項_作り物の組_2026.12支給（11月分）_v1.html"
今の下書き = 確認 + "下書き_確認事項_作り物の組_2027.01支給（12月分）_v1.html"
人が見る物 = 確認 + "寄せ_人が見る物_2026-11-20_1200.md"   # 確認事項の形の外の物＝読めない物（移す）
前の月の字 = 確認 + "確認事項_作り物の組_2026.11支給_v4.html"   # 前の支給月の字（（M月分）が無い）＝前の名（移す・版に数える）
# ほかの組の名（前の名の形でも）＝置き違い。この会社の 9_履歴/ へ移さずに残す（次の版 が置き違いで止める）
ほかの組 = [確認 + "確認事項_別の組_2026.11支給_v9.html", 確認 + "確認ページ_別の組_2026.11支給（10月分）_v9.html",
          確認 + "確認事項_別の組_2026.12支給（11月分）_v9.html",
          月のフォルダ + "確認ページ_別の組_2026.11支給（10月分）_v9.html"]   # 月のフォルダの中でも同じ（組を見ずに移す枝を作らない）
残る物 = [月のフォルダ, *ほかの組]   # ほかの組の名を中に持つフォルダも残す（フォルダごと移すと中の名も移る）


def 前の形の箱の会社():
    v = 今の版の会社()
    v["組"] = "作り物の組"
    v["置き場"] += [確認, 前のページ, 前の下書き, 月のフォルダ, 月の中, 今のページ, 今の下書き, 人が見る物, 前の月の字, *ほかの組]
    return v


def test_確認事項の前の形は9_履歴へ移し_今の形は残す():
    v = 前の形の箱の会社()
    r = 寄せる(v)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    移す = {(s["前"], s["後"]) for s in r["書く手順"] if s["する"] == "file を移す"}
    頭 = f"{当てる.履歴の名}/消す_{消す日}_"
    assert 移す == {(前のページ, 頭 + 前のページ[len(確認):]), (前の下書き, 頭 + 前の下書き[len(確認):]),
                  (月の中, 頭 + 月の中[len(月のフォルダ):]),
                  (人が見る物, 頭 + 人が見る物[len(確認):]), (前の月の字, 頭 + 前の月の字[len(確認):])}, 移す
    後 = r["寄せた後の値"]["置き場"]
    assert {今のページ, 今の下書き, 確認} <= set(後)
    assert [x for x in 後 if x.startswith(確認) and x not in (確認, 今のページ, 今の下書き)] == 残る物, 後   # 今の形の外は全部移した（ほかの組の名は残す）
    assert 頭 + 月の中[len(月のフォルダ):] in 後   # 月のフォルダの中のページも 9_履歴/ の直下へ（中身を消さない）
    assert not [s for s in r["書く手順"] if "消す" in s["する"]]   # 消す手は出さない
    assert not [x for x in r["写した物"] if x.startswith(頭)]   # 寄せの前の写しでない
    書いた = 当てる.手順を当てる(v, r["書く手順"])
    assert len(書いた["置き場"]) == len(v["置き場"])   # 移しただけ（数が減らない）
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    assert 寄せる(書いた)["書く手順"] == []


