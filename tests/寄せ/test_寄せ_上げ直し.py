def test_移す先が既に在れば消さずに日をずらして両方残す():
    v = 前の形の箱の会社()
    先 = f"{当てる.履歴の名}/消す_{消す日}_{前のページ[len(確認):]}"
    v["置き場"].append(先)
    r = 寄せる(v)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    次の日 = (dt.date.fromisoformat(消す日) + dt.timedelta(days=1)).isoformat()
    移す = {s["前"]: s["後"] for s in r["書く手順"] if s["する"] == "file を移す"}
    assert 移す[前のページ] == f"{当てる.履歴の名}/消す_{次の日}_{前のページ[len(確認):]}", 移す   # 元の名のまま・在る方を消さない
    後 = r["寄せた後の値"]["置き場"]
    assert 先 in 後 and [x for x in 後 if x.startswith(確認) and x not in (確認, 今のページ, 今の下書き)] == 残る物, 後


def test_移した前の版は次の版が数える():
    # 移した名が 確認ページ.次の版 の読む形でないと、上げ直しの後の確認事項が v1 から付け直す＝配った版と番号がぶつかる
    r = 寄せる(前の形の箱の会社())
    履歴 = [s["後"][len(当てる.履歴の名) + 1:] for s in r["書く手順"] if s["する"] == "file を移す" and not s["後"].endswith("/")]
    頁 = 当てる.確認ページの形()
    今 = [x[len(確認):] for x in 前の形の箱の会社()["置き場"] if x.startswith(確認) and x != 確認]
    with pytest.raises(ValueError, match="寄せ"):   # 移す前は読めない物（月のフォルダ・人が見る物）が在る＝答えは 1 つ（寄せの移し）
        頁.次の版("作り物の組", "2026.11支給", 今, [])
    v = 頁.次の版("作り物の組", "2026.11支給", [], 履歴)
    assert v["版"] == 5, (v, 履歴)   # 前の支給月の字の v4・月のフォルダの中の v2・直下の v1 の次
    書いた = 当てる.手順を当てる(前の形の箱の会社(), r["書く手順"])
    残り = [x[len(確認):] for x in 書いた["置き場"] if x.startswith(確認) and x != 確認]
    履歴 = [x[len(当てる.履歴の名) + 1:] for x in 書いた["置き場"] if x.startswith(当てる.履歴の名 + "/")]
    with pytest.raises(ValueError, match="置き違い"):   # ほかの組の名は移さずに残る＝次の版 が置き違いで止める
        頁.次の版("作り物の組", "2026.11支給", 残り, 履歴)
    assert not [x for x in 履歴 if "別の組" in x], 履歴   # この会社の 9_履歴/ へ黙って移さない
    書いた["置き場"] = [x for x in 書いた["置き場"] if x not in ほかの組]   # その組の置き場へ移した後に寄せ直す（空いたフォルダを移す）
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    書いた = 当てる.手順を当てる(書いた, 寄せる(書いた)["書く手順"])
    残り = [x[len(確認):] for x in 書いた["置き場"] if x.startswith(確認) and x != 確認]
    履歴 = [x[len(当てる.履歴の名) + 1:] for x in 書いた["置き場"] if x.startswith(当てる.履歴の名 + "/")]
    v = 頁.次の版("作り物の組", "2026.11支給", 残り, 履歴)   # 移した後は止まらずに数える（移しが全部を片付けた）
    assert v["版"] == 5 and v["寄せで移す物"] == [], (v, 残り)
