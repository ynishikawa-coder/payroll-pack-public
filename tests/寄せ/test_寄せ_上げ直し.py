"""型の上げ直し（会社の型の版が既に今の版の会社へ、もう一度 寄せる）で、前の形を黙って残さない（作り物の値だけ）。

- 会社の 質問と回答 の問いの番号: 会社の版によらず、前の形の読み替え（人の答え）の番号を毎回当てる。読み替えが無く前の形の
  番号（Q2026.12-xx）が残れば寄せられない物に出して書かない。ぶつかりも止める。当てた後にもう一度寄せると書く手順 0。
- 8_確認事項 の前の形（名 確認ページ_… のページ・月ごとに切ったフォルダ）: 9_履歴/消す_<期限の日>_<ページの名> へ移す（消さない・月のフォルダは中のページを 1 つずつ移してからフォルダを）。
  移した名は 確認ページ.次の版 が前の版に数える形（置き場の名を挟むと番号が v1 へ戻る）。
  今の形の名は動かさない。ほかの組の名（今の形も前の名も・前の支給月の字も）は移さずに残す（次の版 が置き違いで止める）。移した物は寄せの前の写し（写した物）に入れない。もう一度寄せると書く手順 0。
"""
import copy
import datetime as dt
import sys
import pytest
from pathlib import Path

ここ = Path(__file__).resolve().parent
sys.path.insert(0, str(ここ.parent.parent / "道具" / "寄せ"))
sys.path.insert(0, str(ここ))
import 当てる  # noqa: E402
import 作り物の殻  # noqa: E402
import 直し as 直しの形  # noqa: E402
import test_寄せ_見張り as 見張り  # noqa: E402

今日 = dt.date(2026, 11, 24)
表 = "1_決まり/質問と回答"
読み替えの鍵 = 当てる.前の形の鍵


def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(ここ.parent.parent / "初期設定" / "型.json"), 直しの形.読む(), 今日)


def 今の版の会社():
    """今の型の版まで寄せ終えた作り物の会社（上げ直しの元）。"""
    return copy.deepcopy(見張り.読む("作り物の寄せた後.json")["寄せた後の値"])


def 列(rows, 名):
    i = rows[0].index(名)
    return [r[i] for r in rows[1:]]


def 前の番号の会社():
    """問いの番号を前の形にした今の版の会社（1 行目の答えは 2 行目へ出し直し・2 行目の理由は 1 行目の聞き直し）。"""
    v = 今の版の会社()
    rows = v["シート"][表]["質問"]
    番 = rows[0].index("問いの番号")
    rows[1][番], rows[2][番] = "Q2026.12-01", "Q2026.12-02"
    rows[1][rows[0].index("回答")] = "出し直し→Q2026.12-02"
    rows[2][rows[0].index("理由")] = "聞き直し: Q2026.12-01"
    return v


def 番号の読み替え(前="Q2026.12-", 後="Q202612-"):
    return [{"版": 1, "なぜ": "作り物の事務所の前の番号の形", "操作": [
        {"する": "値の語を読み替える", "ファイル": 表, "タブ": "質問", "列": "問いの番号", "前": 前, "後": 後, "合わせ": "頭"}]}]


def もう一度(会社, r):
    書いた = 当てる.手順を当てる(会社, r["書く手順"])
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    return 寄せる(書いた)


# ---- 会社の 質問と回答 の問いの番号

def test_今の版の会社でも前の形の番号は黙って残さず止める():
    v = 前の番号の会社()
    r = 寄せる(v)
    assert r["当てた直し"] == []   # 上げ直し＝当てる直しが無い（前は番号を照らす物も無く通った）
    鍵 = {x["鍵"] for x in r["寄せられない物"]}
    assert f"{表}/質問/問いの番号" in 鍵, r["寄せられない物"]
    assert r["書く手順"] == [] and r["寄せた後の値"] == v


def test_前の形の読み替えを渡せば今の版の会社でも今の番号になり_二度目は手順0():
    v = 前の番号の会社()
    v["人の答え"] = {読み替えの鍵: 番号の読み替え()}
    r = 寄せる(v)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    rows = r["寄せた後の値"]["シート"][表]["質問"]
    assert 列(rows, "問いの番号") == ["Q202612-01", "Q202612-02"]
    assert 列(rows, "回答")[0] == "出し直し→Q202612-02" and 列(rows, "理由")[1] == "聞き直し: Q202612-01"
    assert r["値の保ち"]["合う"] and r["書く手順"]
    assert もう一度(v, r)["書く手順"] == []


def test_読み替えた番号が前から在る今の番号とぶつかれば止める():
    v = 前の番号の会社()
    rows = v["シート"][表]["質問"]
    rows[2][rows[0].index("問いの番号")] = "Q202612-01"   # 2 行目は今の形・1 行目の前の番号を読み替えると同じ番号
    rows[2][rows[0].index("理由")] = ""
    v["人の答え"] = {読み替えの鍵: 番号の読み替え()}
    r = 寄せる(v)
    assert f"{表}/質問/問いの番号/ぶつかり" in {x["鍵"] for x in r["寄せられない物"]}, r["寄せられない物"]
    assert r["書く手順"] == []


def test_版の鎖が読み替えて作ったぶつかりも止める():
    # 型の版が前の版の会社: 前の形の読み替えは版の鎖（直し 1 の前）が当てる＝鎖の後の表と照らすとぶつかりが見えない
    v = 前の番号の会社()
    rows = v["シート"][表]["質問"]
    rows[2][rows[0].index("問いの番号")] = "Q202612-01"
    rows[2][rows[0].index("理由")] = ""
    v["人の答え"] = {読み替えの鍵: 番号の読み替え()}
    v["型の版"] = 0
    r = 寄せる(v)
    assert f"{表}/質問/問いの番号/ぶつかり" in {x["鍵"] for x in r["寄せられない物"]}, r["寄せられない物"]
    assert r["書く手順"] == []


def test_読み替えが合わない前の番号が残れば止める():
    v = 前の番号の会社()
