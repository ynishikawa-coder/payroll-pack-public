"""型の版 31（直し 31）: 年の台帳に 賞与の支給一覧 のタブを足す。版 30 の会社は直し 31 で見出しまでのタブが足され、ほかは変わらない。作り物だけ。"""
import copy

import test_寄せ_前の置き場の名で止める as 前の名
import test_寄せ_見張り as 見張り
from test_寄せ_見張り import 当てる, 直しの形  # noqa: F401


def test_直し31は版30から31でタブを足すだけ():
    d = [x for x in 直しの形.読む() if x["版"] == 31][0]
    assert (d["前の版"], d["当たる"]) == (30, "全ての事務所")
    assert d["操作"] == [{"する": "タブを足す", "ファイル": "台帳_<支給年>", "タブ": "賞与の支給一覧"}]


def test_自己検査は版30の雛形に直し31を当てて今の雛形になる():
    import 自己検査
    型30, _ = 前の名._型30()
    r = 自己検査.全部(当てる.型を開く(見張り.ここ.parent.parent / "初期設定" / "型.json"), 直しの形.読む(), 型30)
    assert all(v == [] for v in r.values()), r


def test_版30の会社は賞与の支給一覧のタブだけが足される():
    v = copy.deepcopy(見張り.読む("作り物の寄せた後.json")["寄せた後の値"])
    v["型の版"] = 30
    del v["シート"]["台帳_2026"]["賞与の支給一覧"]
    r = 見張り.寄せる(v)
    assert r["寄せられない物"] == []
    assert [(x["する"], x.get("タブ")) for x in r["書く手順"] if x["する"] == "タブを足す"] == [("タブを足す", "賞与の支給一覧")]
    assert r["寄せた後の値"] == 見張り.読む("作り物の寄せた後.json")["寄せた後の値"]
