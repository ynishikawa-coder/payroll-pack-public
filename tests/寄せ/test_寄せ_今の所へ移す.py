def test_今の列へ移すの値に等号を含む時は矢印か列の値で切る():
    """前の値に `=` を含む値（夜勤1回=2日）も今の列へ移せる: `前→後` で書くか、`=` が 2 つ以上なら列に在る値で切る。"""
    for 答え in ("今の列へ移す:時間.夜勤の出勤日数|夜勤1回=2日→1 勤務 = 2 日",
                 "今の列へ移す:時間.夜勤の出勤日数|夜勤1回=2日=1 勤務 = 2 日"):
        前 = 前の形()
        型 = 前["シート"]["2_マスタ"]["勤務の型"]
        型[0].append("作り物の夜勤の印")
        for r in 型[1:]:
            r.append("夜勤1回=2日")
        r = 寄せる(前)
        前["人の答え"] = {鍵(r, "行き先の無い列:作り物の夜勤の印"): 答え}
        r = 寄せる(前)
        assert not [x for x in r["寄せられない物"] if "作り物の夜勤の印" in x["鍵"]], (答え, r["寄せられない物"])
        後 = r["寄せた後の値"]["シート"]["2_マスタ"]["勤務の型"]
        assert set(列(後, "時間.夜勤の出勤日数")) == {"1 勤務 = 2 日"}


def test_md_へ移すは寄せの前のmdの名と見出しでも当たり_当たらなければ訳を出す():
    """人は寄せの前の Drive を見て答える（01_決まり/給与の決まり.md・前の見出し）。直しが置き場と見出しの名を変えた後でも当たる。"""
    前 = 前の形()
    型 = 前["シート"]["2_マスタ"]["勤務の型"]
    型[0].append("作り物のメモ")
    for r in 型[1:]:
        r.append("作り物の夜勤のメモ")
    md = 前["md"]["01_決まり/給与の決まり.md"]
    見出したち = [l for l in md.split("\n") if l.startswith("## ")]
    r = 寄せる(前)
    k = 鍵(r, "行き先の無い列:作り物のメモ")
    for 見出し in 見出したち:   # 前の見出しのどれでも（名が変わった見出しも）今の見出しへ読む
        前["人の答え"] = {k: f"md へ移す:01_決まり/給与の決まり.md#{見出し}"}
        r = 寄せる(前)
        assert not [x for x in r["寄せられない物"] if "作り物のメモ" in x["鍵"]], (見出し, r["寄せられない物"])
    前["人の答え"] = {k: "md へ移す:01_決まり/給与の決まり.md### 作り物の無い見出し"}
    r = 寄せる(前)
    (x,) = [x for x in r["寄せられない物"] if "作り物のメモ" in x["鍵"]]
    assert "md へ移せない" in x["中身"] and "今の md と見出し" in x["中身"]
