def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(型の置き場), 直しの形.読む(), 今日)


def 前の形(**足す列):
    d = json.loads((ここ / "作り物の前の形.json").read_text(encoding="utf-8"))
    社員 = d["シート"]["2_マスタ"]["社員"]
    for 名, 値たち in 足す列.items():
        社員[0].append(名)
        for r, v in zip(社員[1:], 値たち):
            r.append(v)
    return d


def 列(シート, 名):
    return [r[シート[0].index(名)] for r in シート[1:]]


def 書いてもう一度(前, r):
    """書く手順を当てた後の値へ、もう一度当てる（2 回目の当て）。"""
    書いた = 当てる.手順を当てる(前, r["書く手順"])
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    return 寄せる(書いた)


def 鍵(r, 頭):
    return next(x["鍵"] for x in r["寄せられない物"] if x["鍵"].endswith(頭))


