def test_今の列へ移すは値を読み替えて移し_2回目は手順0():
    前 = 前の形(健保の加入の印=["有", "無"], 役員の印=["", "○"])
    r = 寄せる(前)
    前["人の答え"] = {鍵(r, "行き先の無い列:健保の加入の印"): "今の列へ移す:社保.加入|有=加入|無=加入しない",
                    鍵(r, "行き先の無い列:役員の印"): "今の列へ移す:人.区分|○=役員"}
    r = 寄せる(前)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    後 = r["寄せた後の値"]["シート"]["2_マスタ"]["社員"]
    assert "健保の加入の印" not in 後[0] and "役員の印" not in 後[0]
    assert 列(後, "社保.加入") == ["加入", "加入しない"]
    assert 列(後, "人.区分")[1] == "役員"
    assert r["値の保ち"]["合う"]
    再 = 書いてもう一度(前, r)
    assert 再["寄せられない物"] == [] and 再["書く手順"] == []


def test_読み替えに無い値は黙って捨てず問いに残す():
    前 = 前の形(健保の加入の印=["有", "不明"])
    r = 寄せる(前)
    k = 鍵(r, "行き先の無い列:健保の加入の印")
    前["人の答え"] = {k: "今の列へ移す:社保.加入|有=加入"}
    r = 寄せる(前)
    x = next(x for x in r["寄せられない物"] if x["鍵"] == k)
    assert "不明" in x["中身"] and r["書く手順"] == []
    assert r["値の保ち"]["合う"]
    # 人が「不明=」（空の読み替え＝捨てる）と答えれば、捨てた数に出て書ける
    前["人の答え"] = {k: "今の列へ移す:社保.加入|有=加入|不明="}
    r = 寄せる(前)
    assert not any(x["鍵"] == k for x in r["寄せられない物"])
    assert r["値の保ち"]["内訳"]["捨てた（人の答え）"] >= 1 and r["値の保ち"]["合う"]


