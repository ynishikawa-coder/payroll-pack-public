def 行を足す(d, ファイル, タブ, 行):
    d["シート"][ファイル][タブ].append(行)
    return d


def _畳んだタブは値を変えず消す問いへ(前, r, タブたち):
    台帳 = r["寄せた後の値"]["シート"]["台帳_2026"]
    for t in タブたち:
        assert not [x for x in r["寄せられない物"] if x["所"].startswith(f"台帳_2026/{t}")], r["寄せられない物"]
        assert any(x["置き場"] == "台帳_2026" and x["物"] == f"タブ {t}" for x in r["消す問い"]), t
        assert 台帳[t] == [list(x) for x in 当てる.そろえる(前["シート"]["台帳_2026"][t])], t   # 行を読み替えず移さない
        assert not any(s.get("タブ") == t for s in r["書く手順"]), t


def test_月の前提の語が合わない行は畳んだタブのまま問いにせず_2回目は手順0():
    """型の版 27 で 月の前提 は畳んだ（その月の値は その月だけの指示・確定した勤怠 から読み直す）＝前の語の行を
    今の所へ読み替える問いを出さず、値を変えずに消す問い（9_履歴 へ写して消す）へ。書いた後にもう一度寄せると手順 0。"""
    前 = 前の形()
    for 項目, 値 in [("前借", "5000"), ("対象期間", "2026-09-21〜2026-10-20"), ("日ごと", "作り物の日ごとの数"), ("原本", "作り物の原本")]:
        行を足す(前, "台帳_2026", "月の前提", ["2026.10支給", 項目, 値])
    r = 寄せる(前)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    _畳んだタブは値を変えず消す問いへ(前, r, ("月の前提",))
    assert r["値の保ち"]["合う"]
    再 = 書いてもう一度(前, r)
    assert 再["寄せられない物"] == [] and 再["書く手順"] == []


def test_行の答えは今の型のタブにだけ在り行き先も今の型に在る():
    """行ごと移す答え（当てる.行の答えの形）の鍵のタブと、答えが書く先のタブは、今の型に在る。畳んだタブ
    （型の版 27 の 月の前提・月の変動）を鍵や行き先に持つ答えは、照らす（今の型のタブにだけ当てる）から届かないか、
    計算の読まないタブへ値を置く（行き先の表〔Drive の型.md〕では 月の変動 → その月だけの指示）。"""
    今のタブ = {t["タブ"] for f in 当てる.型を開く(型の置き場)["シート"] for t in f["タブ"]}
    for t, 答えたち in 当てる.行の答えの形.items():
        assert t in 今のタブ, f"行の答えの形 の鍵「{t}」は今の型に無いタブ"
        for a in 答えたち:
            頭 = a.split(":")[0]
            if 頭.endswith("へ") and 頭 != "人の列へ":
                assert 頭[:-1] in 今のタブ, f"答え「{頭}」の行き先は今の型に無いタブ"
    # 前の答え 月の変動へ を書いても、畳んだタブへ行を足さない（消す問いのまま値を変えない）
    前 = 前の形()
    行を足す(前, "台帳_2026", "月の前提", ["2026.10支給", "前借", "5000"])
    前["人の答え"] = {"台帳_2026/月の前提/形:項目/前借": "月の変動へ:前借|2=5000"}
    r = 寄せる(前)
    _畳んだタブは値を変えず消す問いへ(前, r, ("月の前提", "月の変動"))


