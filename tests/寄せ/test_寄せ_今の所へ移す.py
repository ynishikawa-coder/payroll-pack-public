# ---- 項目の語が合わない行（月の前提・会社）

def 行を足す(d, ファイル, タブ, 行):
    d["シート"][ファイル][タブ].append(行)
    return d


def test_月の前提の語が合わない行は答えで今の所へ移り_2回目は手順0():
    前 = 前の形()
    for 項目, 値 in [("前借", "5000"), ("対象期間", "2026-09-21〜2026-10-20"), ("日ごと", "作り物の日ごとの数"), ("原本", "作り物の原本")]:
        行を足す(前, "04_台帳_2026", "月の前提", ["2026.10支給", 項目, 値])
    r = 寄せる(前)
    x = next(x for x in r["寄せられない物"] if x["鍵"].endswith("形:項目/項目=前借"))
    assert any(a.startswith("月の変動へ:") for a in x["選べる答え"]) and "月の変動" in x["手がかり"]
    前["人の答え"] = {
        鍵(r, "形:項目/項目=前借"): "月の変動へ:前借|2",
        鍵(r, "形:項目/項目=対象期間"): "月の前提の語へ:締めの始め=2026-09-21|締めの終わり=2026-10-20",
        鍵(r, "形:項目/項目=日ごと"): "入口が読み直す",
        鍵(r, "形:項目/項目=原本"): "持たない:作業の記録 の 原本の名前 に在る",
    }
    r = 寄せる(前)
    assert r["寄せられない物"] == [], r["寄せられない物"]
    台帳 = r["寄せた後の値"]["シート"]["04_台帳_2026"]
    月の前提 = {(row[台帳["月の前提"][0].index("項目")], row[台帳["月の前提"][0].index("今月の値")]) for row in 台帳["月の前提"][1:]}
    assert {("締めの始め", "2026-09-21"), ("締めの終わり", "2026-10-20")} <= 月の前提
    assert not {"前借", "対象期間", "日ごと", "原本"} & {a for a, _ in 月の前提}
    変動 = [dict(zip(台帳["月の変動"][0], row)) for row in 台帳["月の変動"][1:]]
    assert any(v["NO"] == "2" and v["項目"] == "前借" and v["値"] == "5000" and v["支給月"] == "2026.10支給" and v["会社"] for v in 変動)
    assert any(a["なぜ"].startswith("入口が原本から") for a in r["足りない値"])  # 読み直しは黙って消さず 1 問へ
    assert any("原本" in a[0] for a in r["持たない"])
    assert r["値の保ち"]["合う"]
    # 受け取る側（月の変動）を先に、渡す側（月の前提）を後に書く
    書く = [(s.get("タブ")) for s in r["書く手順"] if s["する"] == "値を書く"]
    assert 書く.index("月の変動") < 書く.index("月の前提")
    再 = 書いてもう一度(前, r)
    assert 再["寄せられない物"] == [] and 再["書く手順"] == []


