"""寄せ（直し 29）: 芯が読まない会社の決まりの項目を消した型の版 29 へ、前の版の会社の値を寄せる（作り物の会社の値だけ）。

- 社員の列 支払.組・支払.方法・手当.通勤の形 を畳む（値は持たない）
- 2_マスタ「会社」の消した項目の行・人ごとの支給控除の 控除.差押・現物.行 の行を消す
  （残ると段の解決が知らない名として知らせ＋その人を仮にする）
- 消した項目でない行・列は変えない。寄せられない物（人に聞く物）は出ない
"""
import copy
import json
from pathlib import Path

import test_寄せ_見張り as 見張り

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent


def _直し29():
    return json.loads((根 / "道具" / "寄せ" / "直し" / "直し_0029.json").read_text(encoding="utf-8"))


def _版28の会社():
    """今の寄せた後（版 29）を版 28 の形へ戻し、消した項目の値を置いた作り物の会社。"""
    v = copy.deepcopy(見張り.読む("作り物の寄せた後.json")["寄せた後の値"])
    v["型の版"] = 28
    m = v["シート"]["2_マスタ"]
    社員 = m["社員"]
    # 版 28 では 3 列は項目の列の中に在った。並びは直しの 列の並びをそろえる が直すので後ろへ足す
    社員[0] += ["支払.組", "支払.方法", "手当.通勤の形"]
    社員[1] += ["作り物の組", "口座振込", "定額"]
    for r in 社員[2:]:
        r += ["", "", ""]
    m["会社"] += [["作り物の会社", "休日.代休の日の控除", "引かない", "", ""],
                 ["作り物の会社", "有給.1日の賃金", "通常の賃金", "", ""]]
    m["人ごとの支給控除"] += [["作り物の会社", "1", "作り物 一郎", "控除.差押", "10000", ""],
                         ["作り物の会社", "1", "作り物 一郎", "現物.行", "3000", ""]]
    return v


def test_直し29は版28から29():
    d = _直し29()
    assert (d["前の版"], d["版"]) == (28, 29)


def test_消した項目の列と行を畳み_ほかは変えない():
    前 = _版28の会社()
    r = 見張り.寄せる(前)
    assert r["寄せられない物"] == []
    後 = r["寄せた後の値"]
    assert 後["型の版"] == 30
    m = 後["シート"]["2_マスタ"]
    assert not {"支払.組", "支払.方法", "手当.通勤の形"} & set(m["社員"][0])
    assert [x[1] for x in m["会社"][1:]] == [x[1] for x in 前["シート"]["2_マスタ"]["会社"][1:-2]]
    assert [x[3] for x in m["人ごとの支給控除"][1:]] == [x[3] for x in 前["シート"]["2_マスタ"]["人ごとの支給控除"][1:-2]]
    # 消した項目の外は、版 29 の寄せた後と同じ
    assert m == 見張り.読む("作り物の寄せた後.json")["寄せた後の値"]["シート"]["2_マスタ"]
