"""寄せ（直し 30）: 会社の Drive の置き場の名を新しい形にそろえた（docs/設計/Drive の型.md §2・§10）。

- 前の形の置き場の名（直し 30 の「前の置き場を止める」の 前）のシート・md・フォルダは、型の版によらず寄せが今の名（後）へ移す
  （後が空の名は 9_履歴 へ移す・消さない）＝前の形の Drive も作り直さずに値と来歴を持ったまま今の形になる
- 移せない名（後が月で決まる <…>・移す先が既に在る）が 1 つでも残る会社は、何も当てずに止まる
  （答えは 作り直す だけ＝人の答えで通す道は無い・前の名を黙って読み続けない）
- 前の直し（版 29 まで）の置き場の名は今の名で読む（出した直しの file は替えない）
前の名は直し 30 の file から読む（試験に写さない）。
"""
import copy
