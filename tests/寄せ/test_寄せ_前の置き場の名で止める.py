# 版 31 より後の直しが畳んだタブの、版 30 の型での列（型.json からは消えた＝ここで戻す）
_畳んだタブの前の列 = {("事務所の設定", "確かめてよい人"): ("名", "役目")}   # 直し 32


def _型30():
    """版 30 の型（今の型から 31 より後の直しが足したタブを除き、畳んだタブを戻す）と、版 30 までの直し（試験の中で作る）。"""
    型 = copy.deepcopy(当てる.型を開く(見張り.ここ.parent.parent / "初期設定" / "型.json"))
    後の直し = [d for d in 直しの形.読む() if d["版"] > 30]
    足した = {(op["ファイル"], op["タブ"]) for d in 後の直し for op in d["操作"] if op["する"] == "タブを足す"}
    畳んだ = {(op["ファイル"].split("/")[-1], op["タブ"]) for d in 後の直し for op in d["操作"] if op["する"] == "タブを畳む"}
    足した列 = {(re.sub(r"^\d+_", "", op["ファイル"].split("/")[-1]), op["タブ"], op["見出し"])
              for d in 後の直し for op in d["操作"] if op["する"] == "列を足す"}   # 直し 33（締めの記録 の パックの版）
    assert all(op["する"] in ("タブを足す", "タブを畳む", "列を足す", "列の並びをそろえる", "月の変動を写す") for d in 後の直し for op in d["操作"]), \
        "版 31 より後の直しがタブを足す・畳む・列を足す・型の形を変えない写す（直し 37）の外の操作を持つ＝この試験の版 30 の型を作り直す"
    assert 畳んだ <= set(_畳んだタブの前の列), f"畳んだタブの版 30 の列が無い: {畳んだ - set(_畳んだタブの前の列)}"
    for s in 型["シート"]:
        s["タブ"] = [t for t in s["タブ"] if (s["シート"], t["タブ"]) not in 足した]
        for t in s["タブ"]:
            t["列"] = [c for c in t["列"] if (s["シート"], t["タブ"], c["名"]) not in 足した列]
        s["タブ"] += [{"タブ": t, "形": "表", "列": [{"名": c, "意味": ""} for c in _畳んだタブの前の列[(f, t)]]}
                     for f, t in sorted(畳んだ) if f == s["シート"]]
    型["版"] = 30
    return 型, [d for d in 直しの形.読む() if d["版"] <= 30]


def _前の名の型():
    """版 30 の型の置き場の名を前の名へ戻した版 29 の型（作り物・試験の中で作る。名の対は直し 30 から読む）。"""
    型 = copy.deepcopy(_型30()[0])
    対 = {後: 前 for 前, 後 in 前の名たち if 後 and "<" not in 後}
    def 戻す(名):
        for 後, 前 in 対.items():
            if 名 == 後.rstrip("/") or 名.startswith(後):
                return 前.rstrip("/") + 名[len(後.rstrip("/")):]
        return 名
    型["版"] = 29
    for s in 型["シート"]:
        s["シート"] = 戻す(s["シート"])
        s["置き場"] = "/".join(戻す(x) for x in s.get("置き場", "").split("/"))
    for m in 型["md の雛形"]:
        m["置き場"] = "/".join(戻す(x) for x in m.get("置き場", "").split("/"))
    return 型


def test_自己検査は前の名の版の雛形を今の名へ移し_今の雛形になる():
    import 自己検査
