import pytest

import test_寄せ_見張り as 見張り
from test_寄せ_見張り import 当てる, 直しの形

直し30 = 見張り.読む("../../道具/寄せ/直し/直し_0030.json")
前の名たち = [(op["前"], op["後"]) for op in 直し30["操作"] if op["する"] == "前の置き場を止める"]


def _今の会社():
    # 殻は置き場の行（事務所の設定「置き場」のこの会社の行）を渡す＝置き場の物を移せる
    return {**copy.deepcopy(見張り.読む("作り物の寄せた後.json")["寄せた後の値"]), "置き場の行": {}}


def test_直し30は前の置き場の名を全部持つ():
    assert (直し30["前の版"], 直し30["版"]) == (29, 30)
    assert len(前の名たち) == 10
    # 今の形の会社（作り物の寄せた後）の置き場はどれも前の名に当たらない
    v = _今の会社()
    for 名 in [*v["シート"], *v["md"], *v["置き場"]]:
        assert not any(直しの形.前の名か(名, 前) for 前, _ in 前の名たち), 名


def test_今の形の会社は止まらず二度目の書く手順は0():
    r = 見張り.寄せる(_今の会社())
    assert not [x for x in r["寄せられない物"] if x["種類"] == 当てる.前の形の置き場], r["寄せられない物"]
    assert r["書く手順"] == []


def _置き場の名(v):
    return {*v["シート"], *v["md"], *v["置き場"]}


def _移す先(v, 前, 後):
    """試験で足す前の名の置き場（名）と、寄せが移す先（後が空なら None＝9_履歴 の写しの先）・移す先が既に在るか。"""
    名 = 前 + "作り物" if 前.endswith("/") or 前.endswith("_") else 前
    if 前.endswith("/"):
        先 = 後 or None
    else:
        先 = (後 + 名[len(前):]) if 後 else None
    在る = 先 is not None and any(x == 先 or x.startswith(先) for x in _置き場の名(v))
    return 名, 先, 在る


@pytest.mark.parametrize("前, 後", 前の名たち)
def test_前の名の置き場は今の名へ移し_移せない名だけ止める(前, 後):
    v = _今の会社()
    名, 先, 在る = _移す先(v, 前, 後)
    v["置き場"] = [*v["置き場"], 名]
    r = 見張り.寄せる(v)
    止め = [x for x in r["寄せられない物"] if x["種類"] == 当てる.前の形の置き場]
    if "<" in 後 or 在る:
        assert [x["所"] for x in 止め] == [名], r["寄せられない物"]
        assert 止め[0]["選べる答え"] == [当てる.作り直す] and 前 in 止め[0]["中身"]
        assert r["書く手順"] == [] and r["戻す手順"] == [] and r["当てた直し"] == [] and r["管理表へ書く"] == []
        assert r["寄せた後の値"]["置き場"] == v["置き場"]   # 何も書かない（前の値のまま）
        return
    assert 止め == [], r["寄せられない物"]
    後の名 = _置き場の名(r["寄せた後の値"])
    assert not any(直しの形.前の名か(x, 前) for x in 後の名), sorted(後の名)
    移す = [op for op in r["書く手順"] if op["する"] == "file を移す"]
    # 移した先に型に無い物が在れば、その後は普段の寄せ（8_確認事項 の型に無い物は 9_履歴 へ）
    assert any(直しの形.前の名か(op["前"], 前) for op in 移す), r["書く手順"]
    if 先 is not None:   # 移した先に在る（先の型に無い物は普段の寄せで 9_履歴 へ）
        assert any(x == 先 or x.startswith(先) or x.startswith("9_履歴/") for x in 後の名), sorted(後の名)
    else:
        assert any(x.startswith("9_履歴/") and x.endswith(名.rstrip("/")) for x in 後の名), sorted(後の名)


