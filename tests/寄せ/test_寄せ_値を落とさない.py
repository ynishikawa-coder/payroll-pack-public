"""見張り: 前の形 → 今の形の寄せで、支給控除の項目の行の値（条件＝皆勤 など）を黙って落とさない。作り物の値と一般の語だけ。

1. 額の出所の無い行（前の道具の給与ソフトの欄だけの行）でも、条件・課税 などの値を持つ行は外さず問い（値:人の額 で残す／持たない:<なぜ> で外す）
2. 残った行の値が寄せで空になったら止める（落ちた値の網）
"""
import datetime as dt
import json
import sys
from pathlib import Path

ここ = Path(__file__).resolve().parent
根 = ここ.parent.parent
sys.path.insert(0, str(根 / "道具" / "寄せ"))
sys.path.insert(0, str(ここ))
import 当てる  # noqa: E402
import 作り物の殻  # noqa: E402
import 直し as 直しの形  # noqa: E402

今日 = dt.date(2026, 11, 16)
鍵 = "03_マスタ/支給控除の項目/額の出所/項目=皆勤手当"


def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(根 / "初期設定" / "型.json"), 直しの形.読む(), 今日)


def 皆勤の会社():
    # 前の形の支給控除の項目に 条件 の列と、額の出所の無い 皆勤手当 の行（給与ソフトの欄だけ＋条件＝皆勤）を足す
    c = json.loads((ここ / "作り物の前の形.json").read_text(encoding="utf-8"))
    t = c["シート"]["03_マスタ"]["支給控除の項目"]
    t[0] = t[0] + ["条件"]
    for r in t[1:]:
        r.append("")
    行 = dict.fromkeys(t[0], "")
    行.update({"項目": "皆勤手当", "支給か控除か": "支給", "課税": "課税", "作り物ソフトの欄": "欄7", "条件": "皆勤"})
    t.append([行[k] for k in t[0]])
    return c


def _皆勤の行(r):
    out = r["寄せた後の値"]["シート"]["03_マスタ"]["支給控除の項目"]
    return [dict(zip(out[0], x)) for x in out[1:] if dict(zip(out[0], x)).get("項目") == "皆勤手当"]


def test_条件を持つ額の出所の無い行は黙って外さず問う():
    r = 寄せる(皆勤の会社())
    (q,) = [x for x in r["寄せられない物"] if x["鍵"] == 鍵]
    assert "条件＝皆勤" in q["中身"] and q["選べる答え"] == ["値:人の額", "持たない:<なぜ>"]
    assert _皆勤の行(r) and _皆勤の行(r)[0]["条件"] == "皆勤"     # 寄せられない物が在る回は前の値のまま（書かない）
    assert r["値の保ち"]["合う"]


def test_人の額と答えれば条件ごと残す():
    会社 = 皆勤の会社()
    会社["人の答え"] = {鍵: "値:人の額"}
    r = 寄せる(会社)
    assert not [x for x in r["寄せられない物"] if "皆勤" in x["鍵"]]
    (行,) = _皆勤の行(r)
    assert 行["条件"] == "皆勤" and 行["単価の元"] == "人の額" and r["値の保ち"]["合う"]


def test_持たないと答えれば外す():
    会社 = 皆勤の会社()
    会社["人の答え"] = {鍵: "持たない:前の道具の欄だけの行で要らない"}
    r = 寄せる(会社)
    assert not _皆勤の行(r) and r["値の保ち"]["合う"]
    assert any("皆勤手当" in x[0] and "人の答え" in x[2] for x in r["持たない"])


def test_残った行の値が空になれば落ちた値で止める():
    # 網: 寄せた後に残った行の値だけが消えた所を作る（寄せの直しの誤りを真似て、見通しの中で値を消す）
    会社 = 皆勤の会社()
    会社["人の答え"] = {鍵: "値:人の額"}
    元 = 当てる.落ちた値を照らす

    def 消してから照らす(前, o, 記):
        rows = o.シート["03_マスタ"]["支給控除の項目"]
        i, j = rows[0].index("項目"), rows[0].index("条件")
        for x in rows[1:]:
            if x[i] == "皆勤手当":
                x[j] = ""
        元(前, o, 記)
    当てる.落ちた値を照らす = 消してから照らす
    try:
        r = 寄せる(会社)
    finally:
        当てる.落ちた値を照らす = 元
    assert any(x["種類"] == "落ちた値" and "条件" in x["鍵"] and "皆勤手当" in x["鍵"] for x in r["寄せられない物"]), r["寄せられない物"]
