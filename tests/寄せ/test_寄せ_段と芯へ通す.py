def test_寄せた後を段の解決と芯へ通しても止まらず黙って確定しない(tmp_path):
    from 作る_計算 import 置き場, 勤怠
    from 芯.計算 import 計算する
    前 = 穴のある会社()
    書いた, _ = 書いてもう一度(前, 寄せる(前))
    x = 段の解決へ(書いた["シート"])   # 段の誤りで止まらない（適用支給月が読める形）
    c = 書いた["会社"]
    決 = x["決まり"][(c, "1")]
    芯の名 = set(計算の形.読みを開く()["芯が作る項目"])
    assert not {r["名"] for r in 決["項目.行"]} & 芯の名
    for r in 決["項目.行"]:
        assert r.get("雇保の対象", "入る") in ("入る", "入らない") and r.get("社保の報酬", "入る") in ("入る", "入らない")
    # 変更の記録 確かめ＝仮 が今の名で効く（前の名のままなら黙って確定）。標準報酬の行は寄せが保険料の月（YYYY.MM分）で書く＝
    # 段の解決は古い書き方として止めず、その行の 確かめ＝仮 でその人を仮にする（黙って確定しない）
    assert any(v["NO"] == "1" and v["項目"] == "社保.標準報酬" for v in x["仮の値"]), x["仮の値"]
    assert not any(v["項目"] == "変更の記録.適用支給月" for v in x["仮の値"]), x["仮の値"]
    assert x["人"][(c, "2")]["住民税.額"] == "8000"
    # 芯/計算 が ValueError（決まった項目の名とぶつかる）で止まらない
    月 = [{"支給月": "2026-08", "会社": c, "NO": no, "項目": k, "値": v, "単位": "", "状態": "確定", "問い": ""}
         for no in ("1", "2") for k, v in 勤怠.items()]
    # 必ず埋める欄（空ならその人を計算しない）は前の道具の作り物に無い＝寄せの後に事務所が埋める値を置いて通す
    必ず = {"人.区分": "社員", "源泉.欄": "甲", "源泉.扶養の数": "0", "社保.加入": "加入", "雇保.加入": "加入",
          "時間.制度": "通常", "社保.徴収の月": "翌月徴収"}
    人 = {k: {**{n: v for n, v in 必ず.items() if not x["決まり"].get(k, {}).get(n) and not x["人"].get(k, {}).get(n)}, **x["人"].get(k, {})}
         for k in {*x["決まり"], *x["人"]}}
    結果 = 計算する(月, 決まり=x["決まり"], 人=人, 入力=x["入力"], 置き場=置き場(tmp_path))
    assert 結果["止めた"] == []
    値 = {(r["NO"], r["項目"]): r["値"] for r in 結果["行"]}
    assert 値[("1", "基本給")] == 200000          # 単価の元＝人の額 で人の額を引く（固定の額のままなら額が無い）
    assert 値[("2", "住宅手当")] == 5000
    assert 値[("1", "雇用保険")] > 0                # 雇保の対象＝入る（はい のままなら 0 で黙って確定）


