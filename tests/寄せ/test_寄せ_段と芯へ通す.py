def test_寄せた後を段の解決と芯へ通しても止まらず黙って確定しない(tmp_path):
    from 作る_計算 import 置き場, 勤怠
    from 芯.計算 import 計算する
    前 = 穴のある会社()
    書いた, _ = 書いてもう一度(前, 寄せる(前))
    x = 段の解決へ(書いた["シート"])   # 段の誤りで止まらない（適用支給月が読める形）
