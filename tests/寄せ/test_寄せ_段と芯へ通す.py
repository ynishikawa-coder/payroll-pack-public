def test_穴のある会社が寄せで今の形になる():
    r = 寄せる(穴のある会社())
    assert r["寄せられない物"] == [], r["寄せられない物"]
    # 1 適用支給月
    assert {x["適用支給月"] for x in タブ(r, "変更の記録")} == {"2026.07支給"}
    assert {x["記録日"] for x in タブ(r, "変更の記録")} == {"2026-07-20"}
    # 6 前の項目名
    assert [x["項目"] for x in タブ(r, "変更の記録")] == ["社保.標準報酬", "委託.月給"]
    # 2 芯が作る項目の行は無い・率と丸めは会社の決まりへ
    支 = {x["項目"]: x for x in タブ(r, "支給控除の項目")}
    assert set(支) == {"基本給", "時給", "住宅手当"}
    会 = {x["項目"]: x["今の値"] for x in タブ(r, "会社")}
    assert 会["欠勤.控除の端数"] == "切捨て" and 会["割増.時間外の率"] == "1.25"
    assert any("作り物の住民税の欄" in x["なぜ"] for x in r["書かない物"])
    assert any("作り物の欠勤の欄" in x["なぜ"] for x in r["書かない物"])
    # 3 前の語 → 今の語
    assert (支["基本給"]["雇保の対象"], 支["基本給"]["社保の報酬"], 支["基本給"]["割増の基礎"]) == ("入る", "入る", "入る")
    assert (支["住宅手当"]["雇保の対象"], 支["住宅手当"]["社保の報酬"], 支["住宅手当"]["割増の基礎"]) == ("入らない", "入らない", "入らない")
    # 4 固定の額 → 人の額・額の出所の無い行は書かない物
    assert 支["基本給"]["単価の元"] == "人の額" and 支["住宅手当"]["単価の元"] == "人の額" and 支["時給"]["単価の元"] == "時間単価"
    assert any(x["所"].endswith("項目=作り物の欄だけ") for x in r["書かない物"])
    # 5 人の額の住民税 → 住民税.額・残業手当（前の単価）は答えで外す
    人 = [(x["NO"], x["項目"], x["額"]) for x in タブ(r, "人ごとの支給控除")]
    assert ("2", "住民税.額", "8000") in 人 and not any(x[1] == "残業手当" for x in 人)
    # 5 支払日 → 支給の月＋支給日
    assert 会["支払.支給日"] == "25" and 会["支払.支給の月"] == "翌月" and 会["支払.締め日"] == "末日"
    assert 会["会社.事業場の都道府県"] == "東京都"
    無い = {(x["項目"], x["段"]) for x in r["無い値"]}
    assert ("時間.暦", "会社") in 無い and ("休日.人の休日", "人") in 無い
    assert ("支払.締め日", "会社") not in 無い and ("支払.支給日", "会社") not in 無い
    assert any("週休形態「土日」" in x["なぜ"] for x in r["無い値"])
    assert "寄せた後に無い値" in r["人が見る物"]
    書いてもう一度(穴のある会社(), r)


