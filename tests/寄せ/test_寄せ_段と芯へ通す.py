def 寄せる(会社):
    return 当てる.見通す(作り物の殻.前の形を渡す(会社), 当てる.型を開く(型の置き場), 直しの形.読む(), 今日)


def 段():
    spec = importlib.util.spec_from_file_location("寄せ_段と芯_段の解決", 根 / "初期設定" / "段の解決.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def 前の形():
    return json.loads((ここ / "作り物の前の形.json").read_text(encoding="utf-8"))


def 行(rows, **v):
    return [v.get(c, "") for c in rows[0]]


def 置く(rows, r, 名, 値):
    rows[r][rows[0].index(名)] = 値


def 後(r):
    return r["寄せた後の値"] if not r["寄せられない物"] else r["見通しの値"]


def タブ(r, t):
    rows = 後(r)["シート"][M][t]
    return [dict(zip(rows[0], x)) for x in rows[1:]]


def 鍵たち(r, 頭=""):
    return [x["鍵"] for x in r["寄せられない物"] if 頭 in x["鍵"]]


def 書いてもう一度(前, r):
    assert r["寄せられない物"] == [], r["寄せられない物"]
    assert r["値の保ち"]["合う"]
    書いた = 当てる.手順を当てる(前, r["書く手順"])
    書いた["型の版"] = r["寄せた後の値"]["型の版"]
    r2 = 寄せる(書いた)
    assert r2["書く手順"] == [] and r2["寄せられない物"] == [], (r2["書く手順"][:2], r2["寄せられない物"])
    return 書いた, r2


