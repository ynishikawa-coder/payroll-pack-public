"""寄せ: 置き場の物（事務所の設定「置き場」の列「物」に書ける名）を移した時は、置き場の行も同じ書く手順で書き、
戻す手順で寄せの前の行へ戻す（docs/設計/Drive の型.md §8・§10）。

- 書く手順: file を移す の直後に「置き場の行を書く」（顧客ID・会社・組・物・名。ID は殻が移した後のその名から読む）
- 戻す手順: 移し戻しの直後に、前の ID へ書き戻す（入力の 置き場の行 にその物の行が無ければ「置き場の行を消す」）
- 入力に 置き場の行 の鍵が無い会社は、置き場の物を移す寄せを拒む（寄せられない物 置き場の行が無い・書く手順は空）。
  鍵が無いと前の行が分からず、戻す手順が元から在る行を消してしまう
- 置き場の物でない名（9_履歴 の写しの名・深い名・md）は行を書かない
前の名は直し 30 の file から読む（試験に写さない）。値は作り物だけ。
"""
import copy

import test_寄せ_見張り as 見張り
from test_寄せ_見張り import 当てる

直し30 = 見張り.読む("../../道具/寄せ/直し/直し_0030.json")
マスタの名 = 当てる.マスタの名
前のマスタ = next(op["前"] for op in 直し30["操作"] if op["する"] == "前の置き場を止める" and op["後"] == マスタの名)


def _前のマスタの会社(置き場の行=None):
    """今の形の作り物の会社のマスタを、前の形の名へ置き直した物（パ-6）。"""
    v = copy.deepcopy(見張り.読む("作り物の寄せた後.json")["寄せた後の値"])
    def 戻す名(x):
        return 前のマスタ + x[len(マスタの名):] if x == マスタの名 or x.startswith(マスタの名 + "/") else x
    v["シート"] = {戻す名(k): t for k, t in v["シート"].items()}
    v["md"] = {戻す名(k): t for k, t in v["md"].items()}
    v["置き場"] = [戻す名(x) for x in v["置き場"]]
    v["顧客ID"] = "C0001"
    if 置き場の行 is not None:
        v["置き場の行"] = 置き場の行
    return v


def test_前のマスタを移すと置き場の行を書き_戻すと行を消す():
    v = _前のマスタの会社({})   # 置き場の行の鍵は在り、この会社の行は 1 つも無い
    r = 見張り.寄せる(v)
    assert r["寄せられない物"] == [] or all(x["種類"] != 当てる.前の形の置き場 for x in r["寄せられない物"]), r["寄せられない物"]
    書く = r["書く手順"]
    i = next(i for i, s in enumerate(書く) if s["する"] == "file を移す" and s["前"] == 前のマスタ)
    assert 書く[i]["後"] == マスタの名
    assert 書く[i + 1] == {"する": "置き場の行を書く", "顧客ID": "C0001", "会社": v["会社"], "組": v.get("組") or v["会社"],
                         "物": マスタの名, "名": マスタの名}
    # 置き場の行を書くのは置き場の物の移しだけ（1 手）
    assert [s for s in 書く if s["する"] == "置き場の行を書く"] == [書く[i + 1]]
    戻す = r["戻す手順"]
    j = next(j for j, s in enumerate(戻す) if s["する"] == "file を移す" and s["前"] == マスタの名 and s["後"] == 前のマスタ)
    assert 戻す[j + 1]["する"] == "置き場の行を消す" and 戻す[j + 1]["物"] == マスタの名
    # 値の上で当てて戻すと、置き場の行は前（行が無い）へ戻り、file の名も前へ戻る
    後 = 当てる.手順を当てる(v, 書く)
    assert 後["置き場の行"] == {マスタの名: f"<{マスタの名} の ID>"}
    assert マスタの名 in 後["シート"] and 前のマスタ not in 後["シート"]
    元 = 当てる.手順を当てる(後, 戻す)
    assert 元.get("置き場の行") == {}
    assert set(元["シート"]) == set(v["シート"])


def test_前に行が在れば戻す手順は前の_ID_へ書き戻す():
    v = _前のマスタの会社({マスタの名: "id-マスタ-X"})
    r = 見張り.寄せる(v)
    戻す = r["戻す手順"]
    j = next(j for j, s in enumerate(戻す) if s["する"] == "file を移す" and s["前"] == マスタの名)
    assert 戻す[j + 1] == {"する": "置き場の行を書く", "顧客ID": "C0001", "会社": v["会社"], "組": v.get("組") or v["会社"],
                         "物": マスタの名, "ID": "id-マスタ-X"}
    元 = 当てる.手順を当てる(当てる.手順を当てる(v, r["書く手順"]), 戻す)
    assert 元["置き場の行"] == {マスタの名: "id-マスタ-X"}


def test_置き場の物でない名へ移しても行を書かない():
    o = 当てる.物({"会社": "作り物A", "型の版": 35, "顧客ID": "C0001"})
    assert 当てる.置き場の行の手(o, マスタの名) == {"顧客ID": "C0001", "会社": "作り物A", "組": "作り物A", "物": マスタの名}
    assert 当てる.置き場の行の手(o, "台帳_2026/") == {"顧客ID": "C0001", "会社": "作り物A", "組": "作り物A", "物": "台帳_2026"}
    for 名 in ("9_履歴/消す_2027-01-31_作り物", f"{マスタの名}/作り物", "台帳_<支給年>", "作り物.md"):
        assert 当てる.置き場の行の手(o, 名) is None, 名


def test_今の形の会社は置き場の行を書かない():
    v = copy.deepcopy(見張り.読む("作り物の寄せた後.json")["寄せた後の値"])
    v["顧客ID"] = "C0001"
    r = 見張り.寄せる(v)
    assert not [s for s in r["書く手順"] + r["戻す手順"] if s["する"].startswith("置き場の行")]


def test_置き場の行の鍵が無ければ置き場の物を移す寄せを拒む():
    v = _前のマスタの会社()   # 鍵 置き場の行 が無い＝事務所の設定「置き場」に元から行が在るか分からない
    r = 見張り.寄せる(v)
    拒み = [x for x in r["寄せられない物"] if x["種類"] == 当てる.置き場の行が無い]
    assert len(拒み) == 1 and 拒み[0]["所"] == 前のマスタ, r["寄せられない物"]
    assert r["書く手順"] == []
    assert not [s for s in r["戻す手順"] if s["する"] == "置き場の行を消す"]
    # 鍵を渡せば（行が在れば）移し、戻す手順はその行へ書き戻す＝消さない
    r = 見張り.寄せる(_前のマスタの会社({マスタの名: "id-元から在る"}))
    assert not [x for x in r["寄せられない物"] if x["種類"] == 当てる.置き場の行が無い]
    assert not [s for s in r["戻す手順"] if s["する"] == "置き場の行を消す"]
    assert [s["ID"] for s in r["戻す手順"] if s["する"] == "置き場の行を書く"] == ["id-元から在る"]
