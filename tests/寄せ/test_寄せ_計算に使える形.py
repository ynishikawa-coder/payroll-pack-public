"""見張り: 寄せた後の値が段の解決・芯の計算に使える形になる（C13 の穴のうち 道具/寄せ の分）。作り物の値と一般の語だけ。

1. 委託.ソフトの出勤時間の欄 は欄の名。時間の値が入った行は会社の段の定数 委託.雇用分の出勤時間 へ移す（欄の名と値を取り違えない・定数の行が既に在れば問い）
2. 適用開始 を YYYY.MM支給（型.json の列の意味・段の解決の 月()）へそろえる。読めない形は問い
3. 勤務の型の時間（h:mm・202:30 の 3 桁）は形を変えず残す（黙って捨てない）
4. 割増の基礎 はい→入る・社保.徴収の月 翌月→翌月徴収・社保.丸めの順／割増.残業の数え方 前の語→芯の語・健保の支部 → 法の表の 都道府県 の名。読み替えに無い語は問い
7. 会社の 給与の形＝委託 → 社員の 人.区分＝委託（人の値の在る人は人が勝つ）・社員の 給与の形＝委託 も 人.区分 へ。休憩の表の前の JSON → 長さの形
8. 前の「計算の仕方」から 単価の元 を読む（文は md へ・読めない文は問い）
どれも値の保ちが合い、書いた後にもう一度当てると書く手順が 0（2 回目の当て）。
"""
