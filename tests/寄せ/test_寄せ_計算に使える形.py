# ---- 直し 4（v0.1.2 のまま）→ 直し 5: 版 3 の会社は 4→5 と通って、0 から寄せた会社と同じ物になる

def test_版3の会社は直し4と5を通って同じ物になる():
    前の行 = [["委託の作り物ソフトの出勤時間", "160:00", "", ""], ["社保の丸めの順", "健保と支援金を先に", "", ""],
            ["割増.残業の数え方", "1日の所定時間を超えた分", "", ""]]
    会社 = 前の形()
    会社["シート"]["03_マスタ"]["会社"] += 前の行
    r0 = 寄せる(会社)
    書いた = 当てる.手順を当てる(会社, r0["書く手順"])
    書いた["型の版"] = r0["寄せた後の値"]["型の版"]
    assert 書いた["型の版"] == 5

    # 版 3 の形: 版 4・5 で足した列が無く、会社の行は版 3 の名と語のまま（直し 4 の前）
    版3 = json.loads(json.dumps(書いた))
    版3["型の版"] = 3
    for t, 列たち in (("社員", ("住民税.6月分", "住民税.7月以降", "休日.人の休日", "手当.通勤の非課税の限度")),
                    ("支給控除の項目", ("割増の基礎から除く訳",))):
        rows = 版3["シート"]["03_マスタ"][t]
        for c in 列たち:
            i = rows[0].index(c)
            for x in rows:
                del x[i]
    c = 版3["シート"]["03_マスタ"]["会社"]
    k, v = c[0].index("項目"), c[0].index("今の値")
    for x in c[1:]:
        if x[k] == "委託.雇用分の出勤時間":
            x[k] = "委託.ソフトの出勤時間の欄"  # 版 3 では欄の名の行に時間の値（直し 4 は問いにする）
        if x[k] == "社保.丸めの順":
            x[v] = "健保と支援金を先に"         # 直し 4 の読みに無い語（直し 5 が読む）
        if x[k] == "割増.残業の数え方":
            x[v] = "1日の所定時間を超えた分"

    r3 = 寄せる(版3)
    assert r3["寄せられない物"] == [], r3["寄せられない物"]  # 直し 4 の問いを直し 5 が解く
    後 = 当てる.手順を当てる(版3, r3["書く手順"])
    for t in ("会社", "社員", "支給控除の項目"):
        assert 当てる.そろえる(後["シート"]["03_マスタ"][t]) == 当てる.そろえる(書いた["シート"]["03_マスタ"][t]), t
    後["型の版"] = r3["寄せた後の値"]["型の版"]
    assert 後["型の版"] == 5 and 寄せる(後)["書く手順"] == []
