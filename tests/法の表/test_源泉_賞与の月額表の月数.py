"""法の表/源泉_賞与の月額表の月数.json を引いた値が、国が決めている答えと合うか。と、表の行が黙って変わらない見張り。

答えの出所:
- 所得税法 第186条第1項第1号ロ・第2号ロ・第2項（賞与の金額の六分の一〔計算の基礎の期間が六月を超える時は十二分の一〕・×六〔同じく十二〕）
- 国税庁 タックスアンサー No.2523 の設例（令和 8 年分の月額表・計算期間 6 か月）:
  前月の 10 倍を超える賞与: 前月 166,531 円・賞与 1,668,062 円・扶養 1 人 → 87,540 円
  前月に給与の支払がない: 賞与 769,300 円・扶養 0 人 → 7,800 円
引く口は 芯/計算/引く口.py の 1 つを使う。
"""
import json
import sys
from decimal import ROUND_FLOOR, Decimal
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
if str(根) not in sys.path:
    sys.path.insert(0, str(根))

from 芯.計算 import 月額表の税額  # noqa: E402
from 芯.計算.引く口 import 引く  # noqa: E402

表 = json.loads((根 / "法の表" / "源泉_賞与の月額表の月数.json").read_text(encoding="utf-8"), parse_float=Decimal)


def _月数(期間の月: int, 日: str) -> int:
    v = 引く("源泉_賞与の月額表の月数", 日).値
    return v["境を超える"] if 期間の月 > v["境の月数"] else v["境まで"]


def _割る(額: int, 月数: int) -> Decimal:
    return (Decimal(額) / 月数).to_integral_value(rounding=ROUND_FLOOR)


# ---- ① 国が答えを決めている例

def test_条文の月数():
    assert 引く("源泉_賞与の月額表の月数", "2027-06-30").値 == {"境の月数": 6, "境まで": 6, "境を超える": 12, "割った額の端数": "1円未満切り捨て"}
    assert _月数(6, "2026-12-10") == 6 and _月数(7, "2026-12-10") == 12


def test_国税庁No2523の設例_前月の10倍を超える賞与は87540円():
    月額表 = 引く("源泉_月額表", "2026-07-10").値
    m = _月数(6, "2026-07-10")
    x = _割る(1668062, m)
    assert x == 278010
    assert 月額表の税額(月額表, x + 166531, "甲", 1) == 16100 and 月額表の税額(月額表, Decimal(166531), "甲", 1) == 1510
    assert (月額表の税額(月額表, x + 166531, "甲", 1) - 月額表の税額(月額表, Decimal(166531), "甲", 1)) * m == 87540


def test_国税庁No2523の設例_前月に給与の支払がない賞与は7800円():
    月額表 = 引く("源泉_月額表", "2026-07-10").値
    m = _月数(6, "2026-07-10")
    x = _割る(769300, m)
    assert x == 128216
    assert 月額表の税額(月額表, x, "甲", 0) * m == 7800


# ---- ② 見張り（行の数と範囲と出典が黙って変わらない）

def test_行の見張り():
    assert 表["基準"] == "支払日" and 表["欠けた時"] == "止める" and 表["引く鍵"] == []
    assert len(表["行"]) == 1
    r = 表["行"][0]
    assert (r["効く始め"], r["効く終わり"], r["状態"]) == (None, None, "出た")
    assert r["出典"]["URL"].startswith("https://laws.e-gov.go.jp/") and "nta.go.jp" in r["出典"]["照らした元"]
