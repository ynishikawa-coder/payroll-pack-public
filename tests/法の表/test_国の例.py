def test_同じ鍵の行の範囲が重ならない():
    """引く口が 欠け を返すべき所で「行が重なっている」で落ちないための見張り（docs/設計/法の表.md §1.2）。"""
    重なり = []
    for f in sorted(法の表.glob("*.json")):
        行たち = json.loads(f.read_text(encoding="utf-8"))["行"]
        for i, a in enumerate(行たち):
            for b in 行たち[i + 1:]:
                ka, kb = a.get("鍵", {}), b.get("鍵", {})
                if any(ka[k] != kb[k] for k in ka.keys() & kb.keys()):
                    continue
                a前 = a["効く終わり"] is not None and b["効く始め"] is not None and a["効く終わり"] < b["効く始め"]
                b前 = b["効く終わり"] is not None and a["効く始め"] is not None and b["効く終わり"] < a["効く始め"]
                if not (a前 or b前):
                    重なり.append(f"{f.stem}: {ka} {a['効く始め']}〜{a['効く終わり']} と {kb} {b['効く始め']}〜{b['効く終わり']}")
    assert 重なり == []
