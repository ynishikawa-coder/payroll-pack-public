"""法の表/ から引いた値が、国が出している例の答えと合うか。

答えは全部、国が出している資料に書いてある数字（出典は各試験の doc に書く）。
引く口は 芯/計算/引く口.py の 1 つ（docs/設計/法の表.md §1.2）を使う。ここに引く口の写しを持たない。
"""
import json
import sys
from decimal import Decimal, ROUND_FLOOR
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
if str(根) not in sys.path:
    sys.path.insert(0, str(根))

from 芯.計算.引く口 import 引く as _引く  # noqa: E402

法の表 = 根 / "法の表"


def 引く(名: str, 基準: str, **鍵):
    """表の名・基準の日・鍵 → 値（芯の引く口の値だけを見る）。"""
    return _引く(名, 基準, **鍵).値


def 円未満切り捨て(x: Decimal) -> int:
    return int(x.to_integral_value(rounding=ROUND_FLOOR))


# ---- 国税庁「源泉徴収税額表 令和9年分」19〜22 頁の「税額表の使い方」の設例
# https://www.nta.go.jp/publication/pamph/gensen/zeigakuhyo2027/data/19-22.pdf

def test_月額表_甲欄の使用例():
    """支給 420,000 円・社会保険料等 63,400 円・扶養親族等 2 人 → 6,860 円。"""
    v = 引く("源泉_月額表", "2027-01-25")
    金額 = 420000 - 63400
    行 = next(r for r in v["表"]["行"] if r[0] <= 金額 < r[1])
    assert (行[0], 行[1]) == (356000, 359000)
    assert 行[2][2] == 6860


def test_月額表_乙欄の使用例():
    """支給 80,750 円・社会保険料等なし・申告書なし → 80,750 × 3.063％（1 円未満切り捨て）＝ 2,473 円。"""
    v = 引く("源泉_月額表", "2027-01-25")
    assert 80750 < v["下の端"]["未満"]
    assert 円未満切り捨て(Decimal(80750) * v["下の端"]["乙の率%"] / 100) == 2473


def test_賞与の算出率_使用例():
    """賞与 554,000 円・社会保険料 85,593 円・前月 196,616 円・2 人 → 率 2.042％・税額 9,564 円。"""
    v = 引く("源泉_賞与の算出率", "2027-06-30")
    前月 = 196616
    当たり = [b for b in v["甲"] if (b["甲"][2][0] or 0) <= 前月 < (b["甲"][2][1] or 10**12)]
    assert len(当たり) == 1
    率 = 当たり[0]["率%"]
    assert 率 == Decimal("2.042")
    assert 当たり[0]["甲"][2] == [147000, 279000]
    assert 円未満切り捨て(Decimal(554000 - 85593) * 率 / 100) == 9564


# ---- 協会けんぽ「令和8年3月分（4月納付分）からの健康保険・厚生年金保険の保険料額表（東京支部）」
# https://www.kyoukaikenpo.or.jp/assets/R8_13tokyo.pdf の 30（27）等級の行

def 等級(制度: str, 基準: str, 報酬: int):
    v = 引く("標準報酬月額", 基準, 制度=制度)
    当たり = [g for g in v["等級"] if (g[2] or 0) <= 報酬 < (g[3] or 10**12)]
    assert len(当たり) == 1
    return 当たり[0]


def test_保険料額表_東京_30等級():
    基準 = "2027-02"
    g = 等級("健保", 基準, 500000)
    assert g[:2] == [30, 500000]
    標準 = Decimal(g[1])
    健保 = 引く("健保_協会けんぽ", 基準, 都道府県="東京都")["率%"]
    介護 = 引く("介護_協会けんぽ", 基準)["率%"]
    支援 = 引く("子ども子育て支援金", 基準)["率%"]
    assert 標準 * 健保 / 100 == Decimal("49250.0")
    assert 標準 * 健保 / 100 / 2 == Decimal("24625.0")
    assert 標準 * (健保 + 介護) / 100 == Decimal("57350.0")
    assert 標準 * 支援 / 100 == Decimal("1150.0")

    k = 等級("厚年", 基準, 500000)
    assert k[:2] == [27, 500000]
    厚年 = 引く("厚年の率", 基準)["率%"]
    assert Decimal(k[1]) * 厚年 / 100 == Decimal("91500")
    assert Decimal(k[1]) * 厚年 / 100 / 2 == Decimal("45750")


def test_保険料額表_等級の端():
    """同じ額表の 1 等級（健保 58,000 円）・50 等級（1,390,000 円）・厚年 1 等級 88,000 円・32 等級 650,000 円。"""
    assert 等級("健保", "2026-11", 10000)[:2] == [1, 58000]
    assert 等級("健保", "2026-11", 5000000)[:2] == [50, 1390000]
    assert 等級("厚年", "2026-11", 10000)[:2] == [1, 88000]
    assert 等級("厚年", "2026-11", 5000000)[:2] == [32, 650000]


