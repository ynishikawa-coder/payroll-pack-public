"""法の表の改定の前に版を出す見張り（道具/法の表の見張り.py・docs/設計/法の表.md §3.4）。

日はいつも決まった日を渡す（今日の日で照らすと、日が進んだだけで他の PR が赤になる）。
誤りをわざと入れた作り物の表で、見張りが挙げることを見る。
"""
import json
import sys
from datetime import date
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
if str(根) not in sys.path:
    sys.path.insert(0, str(根))
from 道具 import 法の表の見張り as 見張り  # noqa: E402


def _表(次の改定, 行, 基準="月分", 引く鍵=()):
    t = {"表の名": "作り物", "基準": 基準, "単位": "%", "引く鍵": list(引く鍵), "欠けた時": "仮で計算し問う", "行": 行}
    if 次の改定 is not None:
        t["次の改定"] = 次の改定
    return t


def _行(始め, 終わり, 状態="出た", 鍵=None):
    return {"鍵": 鍵 or {}, "効く始め": 始め, "効く終わり": 終わり, "状態": 状態,
            "値": None if 状態 != "出た" else {"率%": 1}, "出典": None}


def _種類(挙げ):
    return [(x.種類, x.改定の日, x.鍵) for x in 挙げ]


# --- 今の法の表 ---

def test_今の法の表の全部が次の改定の欄を正しい形で持つ():
    for p in sorted((根 / "法の表").glob("*.json")):
        t = json.loads(p.read_text(encoding="utf-8"))
        assert "次の改定" in t, p.name
        見張り.改定の日たち(t["次の改定"], date(2026, 11, 18))  # 形が違えば 欄の誤り で落ちる
        assert [x for x in 見張り.見る_表(t, date(2026, 11, 18), 90) if x.種類 == "欄"] == [], p.name


def test_今の法の表は_2026_11_18_に挙げる物が無い():
    assert [x.行() for x in 見張り.見る(date(2026, 11, 18), 90)] == []


# --- わざと入れた誤り ---

def test_次の改定の欄が無い表を挙げる():
    挙げ = 見張り.見る_表(_表(None, [_行("2026-03", None)]), date(2026, 11, 18), 90)
    assert _種類(挙げ) == [("欄", None, {})]


@pytest.mark.parametrize("欄", [
    {},
    {"毎年": "3 月"},
    {"毎年": "02-30"},
    {"毎年": "03-01", "日": ["2027-03-01"]},
    {"毎年": "03-01", "いつ": "春"},
    {"日": []},
    {"日": ["2027-13-01"]},
    {"無し": "  "},
    {"毎年": "03-01", "おき": 0},
])
def test_次の改定の形が違う表を挙げる(欄):
    挙げ = 見張り.見る_表(_表(欄, [_行("2026-03", None)]), date(2026, 11, 18), 90)
    assert [x.種類 for x in 挙げ] == ["欄"]


def test_改定の月を過ぎても次の行が無い表を挙げる():
    # 2026-03 分の改定の後も、前の行（終わり null）が覆うだけ＝前の値のまま
    t = _表({"毎年": "03-01"}, [_行("2025-03", None)])
    assert _種類(見張り.見る_表(t, date(2026, 11, 18), 90)) == [("過ぎた", "2026-03", {})]


def test_N日以内に改定が来るのにその月からの行が無い表を挙げ_出た行を足すと消える():
    行 = [_行("2026-03", "2027-02"), _行("2027-03", None, "まだ")]
    t = _表({"毎年": "03-01"}, 行)
    assert _種類(見張り.見る_表(t, date(2027, 1, 10), 90)) == [("近い", "2027-03", {})]
    assert 見張り.見る_表(t, date(2026, 11, 1), 90) == []  # 90 日より先は挙げない
    t["行"] = [_行("2026-03", "2027-02"), _行("2027-03", None)]
    assert 見張り.見る_表(t, date(2027, 1, 10), 90) == []


def test_次の改定より後に始まる行はその改定の行と数えない():
    # 2027-03 の改定の行が無く 2028-03 の行だけ在る
    t = _表({"毎年": "03-01"}, [_行("2026-03", "2028-02"), _行("2028-03", None)])
    assert _種類(見張り.見る_表(t, date(2027, 3, 10), 30)) == [("過ぎた", "2027-03", {})]


def test_鍵ごとに欠けた鍵だけを挙げ_空の鍵のまだの行は数えない():
    行 = [_行("2026-04-01", None, 鍵={"県": "甲"}), _行("2026-04-01", None, 鍵={"県": "乙"}),
         _行("2027-04-01", None, 鍵={"県": "甲"}), _行("2027-04-01", None, "まだ")]
    t = _表({"毎年": "04-01"}, 行, 基準="締め日", 引く鍵=["県"])
    行の甲 = 行[0] | {"効く終わり": "2027-03-31"}
    t["行"] = [行の甲] + 行[1:]
    assert _種類(見張り.見る_表(t, date(2027, 4, 2), 30)) == [("過ぎた", "2027-04-01", {"県": "乙"})]


def test_空の鍵の出た行は全部の鍵を覆う():
    行 = [_行("2026-04-01", "2027-03-31", 鍵={"県": "甲"}), _行("2027-04-01", None)]
    t = _表({"毎年": "04-01"}, 行, 基準="締め日", 引く鍵=["県"])
    assert 見張り.見る_表(t, date(2027, 4, 2), 30) == []


def test_鍵で絞った改定はその鍵だけを見る():
    行 = [_行("2026-03", None, 鍵={"制度": "健保"}), _行("2026-03", "2027-08", 鍵={"制度": "厚年"}),
         _行("2027-09", None, "まだ", 鍵={"制度": "厚年"})]
    t = _表({"日": ["2027-09-01"], "鍵": {"制度": "厚年"}}, 行, 引く鍵=["制度"])
    assert _種類(見張り.見る_表(t, date(2027, 8, 1), 90)) == [("近い", "2027-09", {"制度": "厚年"})]
    t["次の改定"]["鍵"] = {"制度": "介護"}
    assert [x.種類 for x in 見張り.見る_表(t, date(2027, 8, 1), 90)] == ["欄"]


def test_おきの年は改定の無い年を挙げない():
    t = _表({"毎年": "04-01", "から": 2027, "おき": 3}, [_行("2027-04-01", None)], 基準="締め日")
    assert 見張り.見る_表(t, date(2029, 3, 1), 90) == []  # 2028・2029 は改定の年でない
    assert _種類(見張り.見る_表(t, date(2030, 3, 1), 90)) == [("近い", "2030-04-01", {})]


def test_年分の表は年の粒で比べる():
    t = _表({"日": ["2028-01-01"]}, [_行("2026", "2027"), _行("2028", None, "まだ")], 基準="年分")
    assert _種類(見張り.見る_表(t, date(2027, 11, 1), 90)) == [("近い", "2028", {})]


def test_無しの表は挙げない():
    t = _表({"無し": "法の改正の時だけ"}, [_行("2017-09", None)])
    assert 見張り.見る_表(t, date(2026, 11, 18), 3650) == []


def test_呼び口は挙げた時に_1_無い時に_0_を返す(tmp_path, capsys):
    (tmp_path / "作り物.json").write_text(
        json.dumps(_表({"毎年": "03-01"}, [_行("2025-03", None)]), ensure_ascii=False), encoding="utf-8")
    assert 見張り.main(["--日", "2026-11-18", "--置き場", str(tmp_path)]) == 1
    出 = capsys.readouterr().out
    assert "過ぎた: 法の表「作り物」 2026-03" in 出 and 出.rstrip().splitlines()[-1].startswith("知らせ:")
    空 = tmp_path / "空"
    空.mkdir()
    assert 見張り.main(["--日", "2026-11-18", "--置き場", str(空)]) == 0



def test_日の並びを使い切った表を挙げ続ける():
    t = _表({"日": ["2027-09-01"]}, [_行("2026-03", "2027-08"), _行("2027-09", None)])
    assert [x.種類 for x in 見張り.見る_表(t, date(2027, 8, 31), 90)] == []  # 改定の前で行も在る
    挙げ = 見張り.見る_表(t, date(2027, 9, 1), 90)
    assert [x.種類 for x in 挙げ] == ["欄"] and "書き足す" in 挙げ[0].訳
    assert [x.種類 for x in 見張り.見る_表(t, date(2031, 1, 1), 90)] == ["欄"]  # 何年たっても黙らない
    t["次の改定"] = {"日": ["2027-09-01", "2028-09-01"]}
    assert _種類(見張り.見る_表(t, date(2028, 9, 2), 30)) == [("欄", None, {}), ("過ぎた", "2028-09", {})]


def test_毎年と4月の改定を_2月に照らすと挙げる():
    # 今の表の中身に頼らない（行を足す PR を止めない）作り物で、月分の 3 月改定と締め日の 4 月改定を同じ日に照らす
    t3 = _表({"毎年": "03-01"}, [_行("2026-03", "2027-02"), _行("2027-03", None, "まだ")])
    t4 = _表({"毎年": "04-01"}, [_行("2026-04-01", "2027-03-31"), _行("2027-04-01", None, "まだ")], 基準="締め日")
    assert _種類(見張り.見る_表(t3, date(2027, 2, 15), 90)) == [("近い", "2027-03", {})]
    assert _種類(見張り.見る_表(t4, date(2027, 2, 15), 90)) == [("近い", "2027-04-01", {})]
