"""法の表/源泉_報酬.json を引いた値が、国が決めている答えと合うか。と、表の行が黙って変わらない見張り。

答えの出所:
- 所得税法 第204条第1項・第205条第1号（10%・100 万円を超えた分は 20%）
- 復興財確法 第28条（2013〜2037 年の徴収に 2.1%・2027 年からは 1.1%）・防衛財確法 第5条の26（2027 年からの徴収に 1%）
- 国税庁 タックスアンサー No.2795 の設例（150 万円の原稿料 → 204,200 円）
引く口は 芯/計算/引く口.py の 1 つを使う。
"""
import json
import sys
from decimal import ROUND_FLOOR, Decimal
from pathlib import Path

import pytest

根 = Path(__file__).resolve().parents[2]
if str(根) not in sys.path:
    sys.path.insert(0, str(根))

from 芯.計算.引く口 import 欠け, 引く  # noqa: E402

表 = json.loads((根 / "法の表" / "源泉_報酬.json").read_text(encoding="utf-8"), parse_float=Decimal)


def _税(額: int, 支払日: str) -> int:
    v = 引く("源泉_報酬", 支払日).値
    低, 境, 高 = Decimal(v["率%"]) / 100, Decimal(v["境の額"]), Decimal(v["境を超えた分の率%"]) / 100
    税 = min(額, 境) * 低 + max(Decimal(0), 額 - 境) * 高
    return int(税.to_integral_value(rounding=ROUND_FLOOR))


# ---- ① 国が答えを決めている例

def test_2026年11月の支払日で引ける():
    v = 引く("源泉_報酬", "2026-11-25").値
    assert v == {"率%": Decimal("10.21"), "境の額": 1000000, "境を超えた分の率%": Decimal("20.42")}


def test_国税庁No2795の設例_150万円の原稿料は204200円():
    """（150 万円−100 万円）×20.42%＋102,100 円＝204,200 円。"""
    assert _税(1500000, "2026-11-25") == 204200
    assert _税(1000000, "2026-11-25") == 102100


def test_2027年からも合わせた率は同じ():
    """防衛特別所得税 1%＋復興特別所得税 1.1%＝2.1%（10%×1.021＝10.21%）。"""
    assert 引く("源泉_報酬", "2027-01-01").値 == 引く("源泉_報酬", "2026-12-31").値
    assert _税(1500000, "2037-12-31") == 204200


def test_効く期間の外は欠け():
    """2012 年までは復興特別所得税が無い・2038 年からは表が閉じている＝止める表なので欠け（率を作らない）。"""
    for 日 in ("2012-12-31", "2038-01-01"):
        with pytest.raises(欠け):
            引く("源泉_報酬", 日)


# ---- ② 見張り（行の数と範囲と出典が黙って変わらない）

def test_行の見張り():
    assert (表["表の名"], 表["基準"], 表["引く鍵"], 表["欠けた時"]) == ("源泉_報酬", "支払日", [], "止める")
    assert [(r["効く始め"], r["効く終わり"], r["状態"]) for r in 表["行"]] == [
        ("2013-01-01", "2026-12-31", "出た"), ("2027-01-01", "2037-12-31", "出た")]
    for r in 表["行"]:
        assert r["鍵"] == {}
        for x in [r["出典"]] + r["出典"]["ほかの出典"]:
            assert {"URL", "ファイル", "sha256", "条文", "照らした元", "取った日"} <= x.keys()
            assert len(x["sha256"]) == 64
    assert [r["出典"]["条文"].split(" ")[0] for r in 表["行"]] == [
        "所得税法", "我が国の防衛力の抜本的な強化等のために必要な財源の確保に関する特別措置法"]
