"""子ども子育て支援金（2026-03 月分まで率 0）と標準賞与額の上限（2026-04-01 より前）の行。

原本は e-Gov 法令 API の健康保険法・厚生年金保険法の版（出典は各行に書く）。
"""
import sys
from pathlib import Path

根 = Path(__file__).resolve().parents[2]
if str(根) not in sys.path:
    sys.path.insert(0, str(根))

from 芯.計算.引く口 import 引く  # noqa: E402


def test_支援金は2026年4月分から():
    assert 引く("子ども子育て支援金", "2025-12").値["率%"] == 0
    assert 引く("子ども子育て支援金", "2026-03").値["率%"] == 0
    assert str(引く("子ども子育て支援金", "2026-04").値["率%"]) == "0.23"


def test_標準賞与額の上限_2026年3月までも引ける():
    """健康保険法 第45条（年度の累計 573 万円）・厚生年金保険法 第24条の4（150 万円）。"""
    assert 引く("標準賞与額の上限", "2025-12-10", 制度="健保").値["上限"] == 5730000
    assert 引く("標準賞与額の上限", "2026-03-31", 制度="厚年").値["上限"] == 1500000
    assert 引く("標準賞与額の上限", "2026-04-01", 制度="健保").値["上限"] == 5730000
