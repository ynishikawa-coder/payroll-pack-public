"""法の表/祝日.json・法の表/法の線.json を引いた値が、国が決めている答えと合うか。と、表の行が黙って変わらない見張り。

答えの出所:
- 祝日: 内閣府「国民の祝日について」の CSV（https://www8.cao.go.jp/chosei/shukujitsu/syukujitsu.csv）・国民の祝日に関する法律 第3条
- 法の線: 労働基準法 第32条・第34条・第35条・第36条・第37条・労働基準法施行規則 第25条の2・割増賃金令（平成6年政令第5号）・
  介護保険法 第9条・厚生年金保険法 第9条・高齢者の医療の確保に関する法律 第50条
引く口は docs/設計/法の表.md §1.2 の形を、この試験だけで使う小さな形で書いた（芯/計算/ の引く口ができたらそれに替える）。
"""
import json
from decimal import Decimal
from pathlib import Path

import pytest

法の表 = Path(__file__).resolve().parents[2] / "法の表"


class 欠け(Exception):
    pass


def 読む(名: str) -> dict:
    return json.loads((法の表 / f"{名}.json").read_text(encoding="utf-8"), parse_float=Decimal)


def 引く(名: str, 基準: str, **鍵):
    当たり = []
    for 行 in 読む(名)["行"]:
        if any(鍵.get(k) != v for k, v in 行["鍵"].items()):
            continue
        始め, 終わり = 行["効く始め"], 行["効く終わり"]
        if 始め is not None and 基準[: len(始め)] < 始め:
            continue
        if 終わり is not None and 基準[: len(終わり)] > 終わり:
            continue
        当たり.append(行)
    assert len(当たり) <= 1, f"{名} {基準} {鍵}: 行が重なっている"
    if not 当たり or 当たり[0]["状態"] != "出た":
        raise 欠け(f"{名} {基準} {鍵}")
    return 当たり[0]["値"]


# ---- ① 国が答えを決めている例

def test_2026年の祝日と休日は18日():
    """内閣府の CSV の 2026 年の行は 18（国民の祝日 16・振替休日 1・国民の休日 1）。"""
    日 = 引く("祝日", "2026-06-15")["日"]
    assert len(日) == 18
    assert sum(1 for 名 in 日.values() if 名 == "休日") == 2


def test_振替休日_2026年5月6日():
    """2026-05-03（憲法記念日）は日曜。祝日法 第3条第2項で、その後の祝日でない最も近い日 05-06 が休日。"""
    日 = 引く("祝日", "2026-05-06")["日"]
    assert 日["2026-05-03"] == "憲法記念日"
    assert 日["2026-05-06"] == "休日"


def test_国民の休日_2026年9月22日():
    """敬老の日（09-21）と秋分の日（09-23）に挟まれた 09-22 は祝日法 第3条第3項で休日。"""
    日 = 引く("祝日", "2026-09-22")["日"]
    assert (日["2026-09-21"], 日["2026-09-22"], 日["2026-09-23"]) == ("敬老の日", "休日", "秋分の日")


def test_振替休日_2027年3月22日():
    """2027-03-21（春分の日）は日曜 → 03-22 が休日。"""
    日 = 引く("祝日", "2027-03-22")["日"]
    assert 日["2027-03-21"] == "春分の日"
    assert 日["2027-03-22"] == "休日"


def test_2028年の祝日はまだ():
    """2028 年の春分・秋分の日は 2027 年 2 月の官報で決まる＝今は欠け。"""
    with pytest.raises(欠け):
        引く("祝日", "2028-01-01")


def test_深夜の割増は25パーセントで22時から5時():
    """労働基準法 第37条第4項。"""
    assert 引く("法の線", "2027-01-15", 線="深夜の割増")["率%"] == 25
    assert 引く("法の線", "2027-01-15", 線="深夜帯") == {"始め": "22:00", "終わり": "05:00"}


def test_割増の率():
    """割増賃金令 本則（時間外 2 割 5 分・休日 3 割 5 分）・第37条第1項ただし書（月 60 時間超 5 割）。"""
    assert 引く("法の線", "2027-01-15", 線="時間外の割増")["率%"] == 25
    assert 引く("法の線", "2027-01-15", 線="休日の割増")["率%"] == 35
    assert 引く("法の線", "2027-01-15", 線="月60時間超の時間外の割増") == {"境の時間": 60, "率%": 50}


def test_月60時間超の割増は2023年4月から():
    """平成30年法律第71号 附則第1条第3号: 中小事業主の猶予（第138条）の改正は 2023-04-01 施行。それより前は表に持たない＝欠け。"""
    with pytest.raises(欠け):
        引く("法の線", "2023-03-31", 線="月60時間超の時間外の割増")
    assert 引く("法の線", "2023-04-01", 線="月60時間超の時間外の割増")["率%"] == 50


def test_法定労働時間と特例と休憩と法定休日():
    """労働基準法 第32条・第34条・第35条・労働基準法施行規則 第25条の2。"""
    assert 引く("法の線", "2027-01-15", 線="法定労働時間") == {"日の時間": 8, "週の時間": 40}
    assert 引く("法の線", "2027-01-15", 線="特例の週の時間")["週の時間"] == 44
    assert 引く("法の線", "2027-01-15", 線="休憩")["段"] == [
        {"労働時間の超え": 6, "休憩の分": 45}, {"労働時間の超え": 8, "休憩の分": 60}]
    assert 引く("法の線", "2027-01-15", 線="法定休日") == {"週の日数": 1, "4週の日数": 4}


def test_36協定の上限():
    """労働基準法 第36条第4項・第5項。"""
    assert 引く("法の線", "2027-01-15", 線="36協定の上限")["月の時間"] == 45
    assert 引く("法の線", "2027-01-15", 線="36協定の上限")["年の時間"] == 360
    特 = 引く("法の線", "2027-01-15", 線="36協定の特別条項の上限")
    assert (特["月の時間外と休日の未満"], 特["年の時間外"], 特["2〜6か月平均の時間外と休日"], 特["月45時間を超える月の数の上限"]) == (100, 720, 80, 6)


def test_社保の年齢():
    """介護保険法 第9条第2号（40 歳以上 65 歳未満）・厚生年金保険法 第9条（70 歳未満）・高確法 第50条第1号（75 歳以上は後期高齢者医療）。"""
    assert 引く("法の線", "2027-01-15", 線="社保の年齢") == {
        "介護の始め": 40, "介護の終わり": 65, "厚年の終わり": 70, "健保の終わり": 75}


def test_社保の年齢の出典は3つの法():
    出典 = 読む("法の線")["行"][-1]["出典"]
    条文 = [出典["条文"]] + [x["条文"] for x in 出典["ほかの出典"]]
    assert [c.split(" ")[0] for c in 条文] == ["介護保険法", "厚生年金保険法", "高齢者の医療の確保に関する法律"]
    for x in [出典] + 出典["ほかの出典"]:
        assert {"URL", "ファイル", "sha256", "照らした元", "取った日"} <= x.keys()


# ---- ② 見張り（行の数と鍵が黙って変わらない）

def test_祝日の行の見張り():
    行たち = 読む("祝日")["行"]
    assert [(r["効く始め"], r["効く終わり"], r["状態"]) for r in 行たち] == [
        ("2026-01-01", "2026-12-31", "出た"), ("2027-01-01", "2027-12-31", "出た"), ("2028-01-01", None, "まだ")]
    assert [len(r["値"]["日"]) for r in 行たち if r["状態"] == "出た"] == [18, 17]
    for r in 行たち:
        if r["状態"] == "出た":
            assert all(d[:4] == r["効く始め"][:4] for d in r["値"]["日"])


def test_法の線の鍵の見張り():
    assert [r["鍵"]["線"] for r in 読む("法の線")["行"]] == [
        "法定労働時間", "特例の週の時間", "休憩", "法定休日", "深夜帯", "時間外の割増", "月60時間超の時間外の割増",
        "休日の割増", "深夜の割増", "36協定の上限", "36協定の特別条項の上限", "社保の年齢"]


@pytest.mark.parametrize("名", ["祝日", "法の線"])
def test_出た行は出典を持つ(名):
    表 = 読む(名)
    assert 表["表の名"] == 名 and 表["基準"] == "労働した日"
    for r in 表["行"]:
        if r["状態"] == "出た":
            assert {"URL", "ファイル", "sha256", "照らした元", "取った日"} <= r["出典"].keys(), r["鍵"]
        else:
            assert r["値"] is None and r["例年の時期"]
