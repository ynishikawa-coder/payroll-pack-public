"""作り物の Drive（型 39 の形）を通しで歩く: 置き場 → マスタ（顧客ID で絞る）→ 台帳 → 管理表。
実の Drive と同じ形（根の直下に事務所の物・00_事務所 を挟まない・マスタは事務所に 1 冊）を作り物の値だけで組む。"""
import importlib.util
from pathlib import Path

from drive口 import 置き場 as 置
from drive口.作り物 import 作り物のDrive
from 初期設定 import 型の口

_spec = importlib.util.spec_from_file_location("管理表_試験_通し", Path(__file__).resolve().parents[2] / "管理表" / "管理表.py")
管理表 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(管理表)

設 = "事務所の設定"
マ = 型の口.名("マスタ")
台 = "台帳_<支給年>"
台のタブ = [t["タブ"] for s in 型の口.型()["シート"] if s["シート"] == 台 for t in s["タブ"]]


def _行(頭, **値):
    return [値.get(c, "") for c in 頭]


def _実の形のDrive():
    d = 作り物のDrive()
    根 = d.根を作る("給与計算")
    設定 = d.シートを作る(根, 型の口.Driveの名(設), [型の口.タブの名(設, t) for t in ("既定", "会社の一覧", "置き場")])
    マスタ = d.シートを作る(根, 型の口.Driveの名("マスタ"))
    管理 = d.シートを作る(根, 型の口.Driveの名("管理表"))
    会社たち = d.フォルダを作る(根, 型の口.名("会社たち"))
    箱 = d.フォルダを作る(会社たち, "作り物の箱")
    月ごと = d.フォルダを作る(箱, 型の口.名("月ごと"))
    台帳 = d.シートを作る(箱, "台帳_2099", [型の口.タブの名(台, t) for t in 台のタブ])
    一頭, 置頭 = 型の口.見出し(設, "会社の一覧"), 型の口.見出し(設, "置き場")
    一覧 = [_行(一頭, 顧客ID="C9001", 会社="作り物A", 組="作り物の組"), _行(一頭, 顧客ID="C9002", 会社="作り物B", 組="作り物の組")]
    置き場 = []
    for cid, 名 in (("C9001", "作り物A"), ("C9002", "作り物B")):
        置き場 += [_行(置頭, 顧客ID=cid, 会社=名, 組="作り物の組", 物="会社の根", ID=箱),
                 _行(置頭, 顧客ID=cid, 会社=名, 組="作り物の組", 物=型の口.名("月ごと"), ID=月ごと),
                 _行(置頭, 顧客ID=cid, 会社=名, 組="作り物の組", 物="台帳_2099", ID=台帳)]
    タ = lambda t: 型の口.タブの名(設, t)  # noqa: E731
    d.物[設定]["タブ"] = {タ("既定"): [], タ("会社の一覧"): [一頭, *一覧], タ("置き場"): [置頭, *置き場]}
    社員の頭 = 型の口.Driveの見出し(マ, "社員")
    社員 = [社員の頭] + [_行(社員の頭, 顧客ID=c, 社員ID=n, 氏名=f"作り物の人{n}") for c, n in
                       (("C9001", "1"), ("C9002", "1"), ("C9001", "2"))]
    d.物[マスタ]["タブ"] = {型の口.タブの名(マ, "社員"): 社員}
    return d, 根, {"台帳": 台帳, "管理表": 管理}


def test_置き場からマスタ_台帳_管理表まで通しで歩ける():
    d, 根, ids = _実の形のDrive()
    # 置き場: 根の直下の事務所の物と会社の物を 1 つの辞書で引く（00_事務所 を挟まない）
    p = 置.会社の置き場(d, 根, "作り物A")
    assert p["顧客ID"] == "C9001" and p["台帳_2099"] == ids["台帳"]
    assert p[型の口.Driveの名("管理表")] == ids["管理表"]
    # マスタ: 事務所に 1 冊・顧客ID で絞り、Drive の列（顧客ID・社員ID）を道具の内の列（会社・NO）へ読み替える
    人 = 置.マスタを読む(d, p, "社員")
    assert [(r["会社"], r["NO"]) for r in 人] == [("作り物A", "1"), ("作り物A", "2")]
    assert all("顧客ID" not in r and "社員ID" not in r for r in 人)
    # 台帳: 会社の箱の 台帳_<年> は 1_ からのタブを持ち、型の見出しで書いて読める
    勤 = 型の口.タブの名(台, "確定した勤怠")
    assert 勤 in d.タブを並べる(p["台帳_2099"])
    頭 = 型の口.見出し(台, "確定した勤怠")
    d.表へ書く(p["台帳_2099"], f"'{勤}'!A1", [頭, _行(頭, 会社="作り物A", 支給月="2099.04支給（3月分）", NO="1")])
    assert d.表を読む(p["台帳_2099"], f"'{勤}'!A1:ZZ")[1][:3] == ["作り物A", "2099.04支給（3月分）", "1"]
    # 管理表: 根の直下の管理表に型のタブ（Drive の名）を足し、2 度目は何もしない
    管 = p[型の口.Driveの名("管理表")]
    手順 = 管理表.立ち上げ({"今のタブ": {t: d.表を読む(管, f"'{t}'!A1:ZZ") for t in d.タブを並べる(管)}})
    for s in 手順:
        assert s["する"] == "タブを足す"
        d.物[管]["タブ"].setdefault(s["タブ"], [])   # タブを足す（作り物の口は無いタブへ書くと止まる＝本物と同じ）
        d.表へ書く(管, f"'{s['タブ']}'!A1", [s["見出し"]])
    assert {管理表.Driveのタブ(n) for n in 管理表.全部の見出し()} <= set(d.タブを並べる(管))
    assert 管理表.立ち上げ({"今のタブ": {t: d.表を読む(管, f"'{t}'!A1:ZZ") for t in d.タブを並べる(管)}}) == []
