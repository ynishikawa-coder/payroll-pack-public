"""作り物のDrive の上で、事務所の根から 置き場を引く・会社の置き場・月の置き場 が引けること、決まりに外れた表で止まること。
値は全部作り物（実の id・会社の名を持たない）。"""
import pytest

from drive口 import Drive口
from drive口.作り物 import 作り物のDrive
from drive口 import 置き場 as 置
from 初期設定 import 型の口

一覧の頭 = 型の口.見出し("事務所の設定", "会社の一覧")
置き場の頭 = 型の口.見出し("事務所の設定", "置き場")


def _行(頭, **値):
    return [値.get(c, "") for c in 頭]


def _事務所(一覧=None, 置き場=None):
    d = 作り物のDrive()
    根 = d.根を作る("給与計算")
    設定 = d.シートを作る(根, 型の口.Driveの名("事務所の設定"),
                     [型の口.タブの名("事務所の設定", t) for t in ("既定", "会社の一覧", "置き場")])
    管理 = d.シートを作る(根, 型の口.Driveの名("管理表"))
    会社たち = d.フォルダを作る(根, 型の口.名("会社たち"))
    組 = d.フォルダを作る(会社たち, "作り物の組")
    出 = {x: d.フォルダを作る(組, 型の口.名(x)) for x in ("月ごと", "履歴")}
    台帳 = d.シートを作る(組, "台帳_2099")
    if 一覧 is None:
        一覧 = [_行(一覧の頭, 顧客ID="C9001", 会社="作り物A", 組="作り物の組"),
                _行(一覧の頭, 顧客ID="C9002", 会社="作り物B", 組="作り物の組")]
    if 置き場 is None:
        置き場 = []
        for cid, 名 in (("C9001", "作り物A"), ("C9002", "作り物B")):
            置き場 += [_行(置き場の頭, 顧客ID=cid, 会社=名, 組="作り物の組", 物="会社の根", ID=組),
                     _行(置き場の頭, 顧客ID=cid, 会社=名, 組="作り物の組", 物=型の口.名("月ごと"), ID=出["月ごと"]),
                     _行(置き場の頭, 顧客ID=cid, 会社=名, 組="作り物の組", 物=型の口.名("履歴"), ID=出["履歴"]),
                     _行(置き場の頭, 顧客ID=cid, 会社=名, 組="作り物の組", 物="台帳_2099", ID=台帳)]
    タ = lambda t: 型の口.タブの名("事務所の設定", t)  # noqa: E731
    d.物[設定]["タブ"] = {タ("既定"): [], タ("会社の一覧"): [一覧の頭, *一覧], タ("置き場"): [置き場の頭, *置き場]}
    return d, 根, {"設定": 設定, "管理表": 管理, "組": 組, "台帳": 台帳, **出}


def test_作り物のDriveは口の形を満たす():
    assert isinstance(作り物のDrive(), Drive口)


def test_置き場を引くは表の全部を顧客IDと物で返す():
    d, 根, ids = _事務所()
    引いた = 置.置き場を引く(d, 根)
    assert 引いた["C9001/会社の根"] == ids["組"]
    assert 引いた[f"C9002/{型の口.名('月ごと')}"] == ids["月ごと"]
    assert 引いた["C9001/台帳_2099"] == ids["台帳"]
    assert len(引いた) == 8


@pytest.mark.parametrize("会社", ["C9001", "作り物A"])
def test_会社の置き場は顧客IDでも呼び名でも引ける(会社):
    d, 根, ids = _事務所()
    p = 置.会社の置き場(d, 根, 会社)
    assert p["顧客ID"] == "C9001" and p["組"] == "作り物の組"
    assert p["会社の根"] == ids["組"] and p["台帳_2099"] == ids["台帳"]
    assert p[型の口.名("履歴")] == ids["履歴"]          # 9_履歴 は会社の物（事務所の 9_履歴 ではない）
    assert p[型の口.Driveの名("管理表")] == ids["管理表"]       # 管理表 は事務所の物＝根の直下から名で引く
    assert p[型の口.Driveの名("事務所の設定")] == ids["設定"]


def test_月の置き場は在れば引き_作るなら作る():
    d, 根, ids = _事務所()
    p = 置.会社の置き場(d, 根, "C9001")
    月 = "2099.04支給（3月分）"
    with pytest.raises(置.引けない, match="無い"):
        置.月の置き場(d, p[型の口.名("月ごと")], 月)
    作った = 置.月の置き場(d, p[型の口.名("月ごと")], 月, 作る=True)
    assert 置.月の置き場(d, p[型の口.名("月ごと")], 月) == 作った
    assert set(作った) == {月, *型の口.物たち("月の物")}


def test_一覧に無い会社は止める():
    d, 根, _ = _事務所()
    with pytest.raises(置.引けない, match="「会社の一覧」に無い"):
        置.会社の置き場(d, 根, "作り物Z")


def test_表が決まりに外れたら止める():
    d, 根, ids = _事務所(置き場=[
        _行(置き場の頭, 顧客ID="C9001", 会社="作り物A", 組="作り物の組", 物="会社の根", ID="作り物-1"),
        _行(置き場の頭, 顧客ID="C9001", 会社="作り物A", 組="作り物の組", 物="会社の根", ID="作り物-2")])  # 壊す: 重なり
    with pytest.raises(置.引けない, match="重なる"):
        置.置き場を引く(d, 根)


def test_同じ名の事務所の設定が2つ在れば止める():
    d, 根, _ = _事務所()
    d.シートを作る(根, 型の口.Driveの名("事務所の設定"))  # 壊す: 同じ名
    with pytest.raises(置.引けない, match="2 つ在る"):
        置.置き場を引く(d, 根)


def test_事務所の根に事務所の設定が無ければ止める():
    d = 作り物のDrive()
    with pytest.raises(置.引けない, match="無い"):
        置.置き場を引く(d, d.根を作る())


def test_根は引数か環境の変数から受け取り_無ければ止める(monkeypatch):
    monkeypatch.delenv("PAYROLL_OFFICE_ROOT_ID", raising=False)
    assert 置.根を受け取る("作り物-根") == "作り物-根"
    with pytest.raises(置.引けない, match="PAYROLL_OFFICE_ROOT_ID"):
        置.根を受け取る()
    monkeypatch.setenv("作り物の根の変数", "作り物-根2")
    assert 置.根を受け取る(根の変数名="作り物の根の変数") == "作り物-根2"
