"""読み口: Excel 出勤簿（先方の Excel・スプレッドシートの、1 人 1 日の出退の時刻がある表）。

殻が渡す物: {原本の名前, 見出し, 行, 勤怠の表記?, 読み替え?}。行は get_values の値のまま
（時刻は `8:00`・`8:00:00`・Excel の小数のどれでもよい）。
1 枚に何人も並ぶ表は 見出しに「氏名」（→ 役 表記）を置く。1 人 1 枚の表は 勤怠の表記 を渡す。
セルの色・コメントで書かれた事は、殻が字にして 備考 の欄で渡す。
「実働」「労働時間」の欄は 原本の時間 の 総労働 へ写す（照らす用。時間数＝印字の 退−出 とは別に持つ）。
"""
from . import _日の表, 口

種別 = "Excel出勤簿"
読み替え = {
    "日付": "日", "日": "日", "出勤": "出", "退勤": "退", "出勤時刻": "出", "退勤時刻": "退", "始業": "出", "終業": "退",
    "外出": "外出", "戻り": "戻", "休憩": "休憩", "休憩時間": "休憩", "区分": "区分", "勤怠区分": "区分", "勤怠コード": "区分",
    "備考": "備考", "氏名": "表記", "名前": "表記", "時間数": "時間数",
}
# 原本に書かれた実働（休憩を引いた時間）は 時間数（印字の 退−出）と分けて 原本の時間（照らす用）へ写す。
# 退−出 と合わなくても要確認にしない（休憩を引いた値なので合わないのが普通）。
原本の時間の語 = {"実働": "総労働", "労働時間": "総労働", "実働時間": "総労働", "総労働": "総労働"}


def 読む(表: dict, 文脈) -> 口.結果:
    rw = dict(読み替え)
    rw.update(表.get("読み替え", {}))
    役 = 口.欄の役(表["見出し"], rw)
    if "表記" not in 役:
        return _日の表.人ごとに読む([dict(表, 読み替え=rw)], 文脈, 種別, rw, 原本の時間の語=原本の時間の語)
    i = 役.index("表記")
    見出し = [h for j, h in enumerate(表["見出し"]) if j != i]
    人, 順 = {}, []
    for 行 in 表["行"]:
        name = str(行[i] if i < len(行) else "").strip()
        if not name:
            continue
        if name not in 人:
            人[name] = []
            順.append(name)
        人[name].append([v for j, v in enumerate(行) if j != i])
    表たち = [{"勤怠の表記": n, "原本の名前": 表["原本の名前"], "見出し": 見出し, "行": 人[n]} for n in 順]
    return _日の表.人ごとに読む(表たち, 文脈, 種別, rw, 原本の時間の語=原本の時間の語)
