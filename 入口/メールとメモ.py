"""読み口: メールとメモ（先方のメール本文・手書きのメモ・電話の聞き取り）。

殻が渡す物: 連絡たち。1 つの連絡に何件もあれば 1 件 1 つに分けて渡す。メールは先に 01_原本 に写しを置き、その名を 原本の名前 に。
  勤怠の連絡   {種類: 勤怠, 勤怠の表記, 日付, 区分?, 出?, 退?, 休憩?, 振替の相手の日?, 代休の相手の日?, 原本の名前, 曖昧?}
  手当控除の連絡 {種類: 手当控除, 勤怠の表記, 項目, 額 か 個数, 適用開始?, 原本の名前}（手当控除の一覧と同じ読み方）
勤怠の連絡は書かれた日だけの表 A・B を返す（全日は置かない）。他の原本の結果へ 口.重ねる で上から重ねる。
誰の事か・いつの事かが曖昧なら 曖昧 を真にして渡す（要確認）。入退社・数え方の決まりの変更はこの口で読まない
（マスタ「変更の記録」と質問と回答の道。入口の外）。
"""
from . import 口, 手当控除の一覧


def 読む(連絡たち: list[dict], 文脈, 項目の辞書: dict | None = None, 単価: dict | None = None) -> 口.結果:
    材料たち, 手当, 日の無い問い = [], [], []
    for c in 連絡たち:
        if c.get("種類") == "手当控除":
            手当.append(c)
            continue
        if c.get("種類") != "勤怠":
            raise ValueError(f"連絡の種類「{c.get('種類')}」はこの口で読まない")
        表記 = str(c.get("勤怠の表記", "")).strip()
        d = 口.日付を決める(c.get("日付", ""), 文脈)
        if d is None:  # どの日かが決まらない連絡は表 A に置かず、その人の要確認だけにする（他の日を上書きしない）
            no = 口.NOを引く(口.日の材料(表記, "", c["原本の名前"]), 文脈)
            日の無い問い.append({"NO": no, "勤怠の表記": 表記, "日付": "",
                            "理由": f"日付「{c.get('日付', '')}」が期間の中の日付に読めない（{c.get('区分', '')}）"})
            continue
        m = 口.日の材料(表記, d, c["原本の名前"])
        if c.get("曖昧"):
            m.理由.append("誰の事か・いつの事かが曖昧")
        if str(c.get("区分", "")).strip():
            m.区分を足す(c["区分"], 文脈)
        m.労働(c.get("出"), c.get("退"), "手書き")
        if str(c.get("休憩", "")).strip():
            v = 口.長さの分(c["休憩"])
            if v is None:
                m.理由.append(f"休憩「{c['休憩']}」が読めない")
            else:
                m.事実["時刻の無い休憩"] = str(v)
        for k in ("振替の相手の日", "代休の相手の日"):
            if c.get(k):
                x = 口.日付を決める(c[k], 文脈) or str(c[k]).strip()
                m.事実[k] = x
        if c.get("備考"):
            m.備考.append(str(c["備考"]))
        材料たち.append(m)
    out = 口.仕上げる(材料たち, 文脈, "メールとメモ", 全日を置く=False)
    out.要確認 += 日の無い問い
    if 手当:
        原本 = {c["原本の名前"] for c in 手当}
        for name in sorted(原本):
            t = 手当控除の一覧.読む([c for c in 手当 if c["原本の名前"] == name], 文脈, name, 項目の辞書 or {}, 単価)
            out.月の変動 += t.月の変動
            out.人ごとの支給控除 += t.人ごとの支給控除
            out.要確認 += t.要確認
    return out
