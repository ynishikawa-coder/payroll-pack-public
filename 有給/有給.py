def _時間を分に(x) -> Decimal | None:
    """時間の数（`40`・`29.5`・`"30"`）か h:mm（`38:31`＝段の解決が割り切れない週の所定を字のまま渡す）→ 分（Decimal）。
    None は None。読めない・負は None。分に直すのは有給.py の中だけ。"""
    if x is None or isinstance(x, bool):
        return None
    m = re.fullmatch(r"(\d+):([0-5]\d)", str(x).strip())
    if m:
        return Decimal(int(m.group(1)) * 60 + int(m.group(2)))
    try:
        h = Decimal(str(x).strip())
    except Exception:
        return None
    if not h.is_finite() or h < 0:
        return None
    return h * 60


def 法の日数(勤続の月: int, 週の所定日数=None, 週の所定時間=None, 表=None):
    """勤続の月と週の所定で引く法の付与日数 → (日数, 区分)。決められない時は (None, 理由)。

    週の所定時間は芯と同じ「時間の数」（`40`・`29.5`。段の解決が渡す `時間.週の所定` のまま）。中で分に直して表の上限（分）と比べる。
    週の所定時間が上限以上か、週の所定日数が上限を超えれば通常。どちらも上限より少なければ比例。"""
    表 = 表 or 法の表()
    段 = sum(1 for m in 表["勤続の月"] if 勤続の月 >= m) - 1
    if 段 < 0:
        return 0, "勤続 6 か月まで"
    時間の上限 = int(表["比例の週の所定時間の上限（分）"])
    日数の上限 = int(表["比例の週の所定日数の上限"])
    週の分 = _時間を分に(週の所定時間)
    if 週の所定時間 is not None and 週の分 is None:
        return None, f"時間.週の所定 {週の所定時間} を時間の数として読めない"
    if 週の分 is not None and 週の分 > 週の分の上限:
        return None, f"時間.週の所定 {週の所定時間} が週 168 時間を超える（分で渡したか。時間の数で渡す）"
    週の所定時間 = 週の分
    if 週の所定時間 is not None and 週の所定時間 >= 時間の上限:
        return 表["通常"][段], "通常"
    if 週の所定日数 is not None and int(週の所定日数) > 日数の上限:
        return 表["通常"][段], "通常"
    if 週の所定日数 is None:
        return None, "時間.週の所定日数 が無い"
    if 週の所定時間 is None:
        return None, "時間.週の所定 が無い（30 時間以上かで通常か比例かが決まる）"
    if int(週の所定日数) < 1:
        return 0, "週の所定日数 0"
    return 表["比例"][str(int(週の所定日数))][段], f"比例・週 {int(週の所定日数)} 日"


揃える値 = ("会社で揃えた日（斉一的付与）", "初回は入社日から（2 回目から揃えた日）")   # 有給.付与の基準日 のうち 有給.揃えた日 を読む値


def 揃えた日の形か(揃えた日) -> bool:
    """有給.揃えた日 が MM-DD（実在の月日・2 月 29 日も可）か。月だけ（`10`・`10月`）は付与の日（時効・基準日の起点）が決まらない＝読まない。"""
    m = re.fullmatch(r"(\d{1,2})-(\d{1,2})", str(揃えた日 or "").strip())
    if not m:
        return False
    try:
        dt.date(2000, int(m.group(1)), int(m.group(2)))   # 2000 年はうるう年＝02-29 も通す（無い年は 28 日）
    except ValueError:
        return False
    return True


def 付与の日たち(入社日: dt.date, 終わり: dt.date, 揃えた日: str | None = None, 表=None, 初回は法の日: bool = False):
    """終わりの日までの付与 → [(付与日, 段, 法の付与日)]。

    揃えた日（MM-DD）が有る時は、法の付与日ごとに (前の付与日〔初回は入社日〕, 法の付与日] の中で一番後の揃えた日へ前倒しする
    （無ければ法の付与日）。初回は法の日＝True（`有給.付与の基準日`＝初回は入社日から（2 回目から揃えた日））は初回だけ法の付与日のまま。
    前倒しだけ（法の付与日より後にしない＝39 条）の線はどちらも同じ。"""
    表 = 表 or 法の表()
    out, 段 = [], 0
    while True:
        月 = 表["勤続の月"][段] if 段 < len(表["勤続の月"]) else 表["勤続の月"][-1] + 12 * (段 - len(表["勤続の月"]) + 1)
        法の日 = 月を足す(入社日, 月)
        付与日 = 法の日
        if 揃えた日 and not (初回は法の日 and not out):
            mm, dd = (int(x) for x in str(揃えた日).strip().split("-"))
            for y in range(法の日.year, 入社日.year - 1, -1):
                try:
                    候補 = dt.date(y, mm, dd)
                except ValueError:
                    候補 = dt.date(y, mm, 28)
                if 入社日 < 候補 <= 法の日 and (not out or 候補 > out[-1][0]):
                    付与日 = 候補
                    break
        if 付与日 > 終わり:
            return out
        out.append((付与日, min(段, len(表["通常"]) - 1), 法の日))
        段 += 1


def 付与日数(段: int, 法の数, 区分: str, 会社の値: dict):
    """法の数と会社の選択から付与日数 → (日数, 仮の理由 or None)。会社の表が法を下回る段は法の数で仮。"""
    if 会社の値.get("有給.付与の表", "法の表") != "会社の表（法以上）" or not 区分.startswith("通常"):
        return 法の数, None
    表 = [x.strip() for x in str(会社の値.get("有給.会社の表") or "").replace("、", ",").split(",") if x.strip()]
    if len(表) != 7:
        return 法の数, "有給.会社の表 が無いか 7 つでない"
    数 = Decimal(表[段])
    if 数 < 法の数:
        return 法の数, "有給.会社の表 が法の表を下回る"
    return 数, None


