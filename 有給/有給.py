def _取得の日数(r: dict, 一日の分) -> tuple[Decimal | None, str | None]:
    単位 = r.get("休暇の単位") or "全日"
    if 単位 == "全日":
        return Decimal(1), None
    if 単位 in ("午前半休", "午後半休"):
        return Decimal("0.5"), None
    if 単位 == "時間":
        if not 一日の分:
            return None, "有給.1日の時間 が無い（時間単位の有給を日に直せない）"
        return Decimal(int(r.get("休暇の時間") or 0)) / Decimal(int(一日の分)), None
    return None, f"休暇の単位 {単位} を読めない"


def 一人(p: dict, 入力: dict, 表: dict, 置き場=None, 台帳: dict | None = None) -> tuple[dict, list[dict]]:
    """表は基準の日に効く行（付与の日の並び）。各付与の日数・時効・年 5 日はその付与日に効く行で引き直す。
    台帳（`台帳を読む` の返り）が有る時は、取得と出勤率 8 割を確定した勤怠から数える。要る期間の行が無い・数えられない日は 止める。"""
    会社, 支給月, 基準 = 入力["会社"], 入力["支給月"], 日(入力["基準の日"])
    会社の値 = 入力.get("会社の値", {})
    問い, 仮 = [], []

    def 聞く(何, 質問, 見当, 拠り所, 例):
        問い.append({"会社": 会社, "支給月": 支給月, "誰に": "先方", "何が無いか": 何, "質問": 質問,
                    "見当": 見当, "見当の拠り所": 拠り所, "答えで変わる項目と人": f"有給の残り、NO {p['NO']}", "答え方の例": 例})
        仮.append(何)

    入社日 = 日(p.get("入社日"))
    if not 入社日:
        聞く("入社日", f"NO {p['NO']} の方の入社日を教えてください。", "", "無し", "YYYY-MM-DD")
        return {"会社": 会社, "支給月": 支給月, "NO": p["NO"], "氏名": p.get("氏名", ""), "状態": "仮"}, 問い
    基準日の値 = 会社の値.get("有給.付与の基準日")
    揃えた日 = 会社の値.get("有給.揃えた日") if 基準日の値 in 揃える値 else None
    初回は法の日 = 基準日の値 == 揃える値[1]
    if 基準日の値 in 揃える値 and not 揃えた日の形か(揃えた日):
        # 月だけ（日の無い）揃えた日は付与の日（時効・基準日の起点）が決まらない＝パックが日を作らず聞く（法の付与日で見当）
        何 = "有給.揃えた日" if not 揃えた日 else f"有給.揃えた日（「{揃えた日}」は月日 MM-DD でない）"
        聞く(何, "有給を揃えて与える日（毎年の月と日）を教えてください。", "入社日から数えた日", "有給.付与の基準日 の既定", "見当のとおり／MM-DD")
        揃えた日 = None
    足りない付与 = {日(x) for x in p.get("出勤率が足りない付与日", [])}
    始め = 日(p.get("有給の始めの日"))
    # 承知の印 有給.付与（人の段）: 会社が法の付与をしない人＝付与 0・出勤率を数えない・仮にしない（法なら何日は 知らせ）
    付与の承知 = 承知の印.読む(p.get(承知の印.項目))[0].get(付与の線)
    始めに残りが無い = not Decimal(str(p.get("有給の始めの残り") or 0)) and not Decimal(str(p.get("有給の始めの繰越") or 0))
    if 台帳 is not None:
        if p.get("出勤率が足りない付与日"):
            raise ValueError("確定した勤怠を渡す時は 出勤率が足りない付与日 を渡さない（出勤率はパックが数える）")
        if p["NO"] and str(p["NO"]).strip() in 台帳["重なり"]:
            raise 止める(f"確定した勤怠に同じ日の行が 2 つある（{台帳['重なり'][str(p['NO']).strip()][0]}）")
        日たち = 台帳["日"].get(str(p["NO"]).strip(), {})
        数え始め = 始め + dt.timedelta(days=1) if 始め else 入社日
        # 付与しない承知で始めの残りも無い人は取れる日が無い＝勤怠の行が揃うのを待たない（年休の行があれば 残りを超えた で問う）
        if not (付与の承知 and 始めに残りが無い):
            _揃っているか(日たち, max(数え始め, 入社日), 基準,
                       f"取得を数える（{'有給の始めの日 ' + str(始め) + ' の翌日から' if 始め else '有給の始めの日が無いので入社日から'}）の")

    付与たち = []
    for 付与日, 段, 法の日 in 付与の日たち(入社日, 基準, 揃えた日, 表, 初回は法の日):
        勤続 = (法の日.year - 入社日.year) * 12 + 法の日.month - 入社日.month
        その表 = 法の表(付与日, 置き場)  # 付与日に効く行（日数・時効・年 5 日）
        法の数, 区分 = 法の日数(勤続, p.get("時間.週の所定日数"), p.get("時間.週の所定"), その表)
        if 法の数 is None:
            聞く(区分.split(" ")[0], f"NO {p['NO']} の方の週の所定（日数と時間）を教えてください。", "週 5 日", "時間.週の所定日数 の既定",
                 "見当のとおり／週 N 日・N 時間")
            法の数, 区分 = 法の日数(勤続, 5, None, その表)
        数, 理由 = 付与日数(段, 法の数, 区分, 会社の値)
        if 理由:
            聞く("有給.会社の表", f"会社の有給の付与日数の表を教えてください（{理由}）。", f"法の表（{法の数} 日）", "法の表", "見当のとおり／7 つの日数")
        if 付与日 in 足りない付与:
            数 = Decimal(0)
        if 付与の承知:
            数 = Decimal(0)   # 付与しない承知＝出勤率は数えない（法の数は 知らせ に残す）
        elif 台帳 is not None and (not 始め or 付与日 > 始め):
            # 出勤率の期間: 初回は入社日から、2 回目からは前の付与日から、付与日の前の日まで（39 条 1・2 項）
            期間の始め = 付与たち[-1]["付与日"] if 付与たち else 入社日
            短い = (付与日 < 法の日) if not 付与たち else (月を足す(期間の始め, 12) > 付与日)
            期間の終わり = 付与日 - dt.timedelta(days=1)
            try:
                _揃っているか(日たち, 期間の始め, 期間の終わり, f"付与日 {付与日} の出勤率 8 割を数える")
            except 止める as e:
                if 始め and 期間の始め <= 始め:
                    # 始めの日の後すぐに付与日が来て、出勤率の期間が始めの日より前にかかる＝始めの日か揃えた日が事務所の付与日とずれている事が多い
                    raise 止める(f"{e}。出勤率の期間が 有給の始めの日 {始め} より前にかかる＝有給の始めの日 と "
                              f"有給.揃えた日（{揃えた日 or '無し＝入社日から'}）を事務所の有給管理表の付与日で照らす"
                              f"（始めの日が付与日なら、その後の付与は 1 年後）") from e
                raise
            if not 出勤率は足りるか(日たち, 期間の始め, 期間の終わり, 短い):
                数 = Decimal(0)
        付与たち.append({"付与日": 付与日, "日数": Decimal(数), "法の数": Decimal(法の数), "残り": Decimal(数), "時効": 時効の日(付与日, int(その表["時効の年"])), "使った": [],
                      "表": その表})

    # 数え始め: 有給の始めの日の残り。無ければ入社日から（勤怠が入社日から揃っている時だけ）
    勤怠の始め = 日(入力.get("勤怠の始め"))
    if 始め:
        生き = [g for g in 付与たち if g["付与日"] <= 始め <= g["時効"]]
        for g in 付与たち:
            if g["付与日"] <= 始め:
                g["残り"] = Decimal(0)
        if 生き:
            生き[-1]["残り"] = Decimal(str(p.get("有給の始めの残り") or 0))
        if len(生き) > 1:
            生き[-2]["残り"] = Decimal(str(p.get("有給の始めの繰越") or 0))
    else:
        始め = 入社日 - dt.timedelta(days=1)
        if 台帳 is None and 勤怠の始め and 勤怠の始め > 入社日 and any(g["付与日"] < 勤怠の始め for g in 付与たち):
            聞く("有給の始めの残り", f"NO {p['NO']} の方の、今の有給の残りの日数（前の年からの繰越を分けて）を教えてください。",
                 "0 日", "無し（入社日からの勤怠が無い）", "N 日（うち繰越 M 日）")

    for g in 付与たち:
        g["初め"] = g["残り"]
    取得 = []
    for r in (日たち.values() if 台帳 is not None else 入力.get("勤怠", [])):
        if str(r.get("NO")).strip() != str(p["NO"]).strip() or r.get("休暇の種類") != "年休":
            continue
        d = 日(r.get("日付"))
        if not d or d <= 始め or d > 基準:
            continue
        n, 理由 = _取得の日数(r, p.get("有給.1日の時間"))
        if 理由:
            聞く(理由.split(" ")[0], f"NO {p['NO']} の方の {d} の有給の時間を日に直せません（{理由}）。", "1 日", "全日とみなした", "見当のとおり／N 時間")
            n = Decimal(1)
        取得.append((d, n, r.get("支給月")))
    取得.sort(key=lambda x: x[0])

    超えた = Decimal(0)
    for d, n, _ in 取得:
        残す = n
        for g in 付与たち:
            if g["付与日"] <= d <= g["時効"] and g["残り"] > 0 and 残す > 0:
                使う = min(g["残り"], 残す)
                g["残り"] -= 使う
                g["使った"].append((d, 使う))
                残す -= 使う
        超えた += 残す
    if 超えた > 0:
        聞く("有給の残り", f"NO {p['NO']} の方の有給の取得が残りを {超えた} 日超えています。残りの日数か取得の日を教えてください。",
             "", "勤怠の年休と付与の数が合わない", "N 日／取得の日の直し")

    生き = [g for g in 付与たち if g["付与日"] <= 基準 <= g["時効"]]
    今 = 生き[-1] if 生き else None
    前 = 生き[-2] if len(生き) > 1 else None
    今月 = [(d, n) for d, n, pm in 取得 if _月(pm, f"台帳 {d} の行") == _月(支給月, "管理表")]
    行 = {"会社": 会社, "支給月": 支給月, "NO": p["NO"], "氏名": p.get("氏名", "")}
    if 今:
        年の終わり = 月を足す(今["付与日"], 12) - dt.timedelta(days=1)
        年の取得 = sum((n for d, n, _ in 取得 if 今["付与日"] <= d <= 年の終わり), Decimal(0))
        五日 = 今["日数"] >= int(今["表"]["年5日の付与日数の下限"])
        行.update({
            "付与日": 今["付与日"].isoformat(),
            "付与日数": _数(今["日数"]),
            "繰越日数": _数(前["初め"] - sum((n for d, n in 前["使った"] if d < 今["付与日"]), Decimal(0))) if 前 else "0",
            "付与日からの取得日数": _数(sum((n for d, n, _ in 取得 if d >= 今["付与日"]), Decimal(0))),
            "年5日の期限": 年の終わり.isoformat() if 五日 else "",
            "年5日の残り": _数(max(Decimal(0), Decimal(int(今["表"]["年5日の日数"])) - 年の取得)) if 五日 else "",
            "時効の日": (前 or 今)["時効"].isoformat(),
        })
    else:
        行.update({"付与日": "", "付与日数": "0", "繰越日数": "0", "付与日からの取得日数": "0", "年5日の期限": "", "年5日の残り": "", "時効の日": ""})
    行["今月の取得日数"] = _数(sum((n for _, n in 今月), Decimal(0)))
    行["今月の取得日"] = "、".join(d.isoformat() for d, _ in 今月)
    行["残日数"] = _数(sum((g["残り"] for g in 生き), Decimal(0)))
    次 = 付与の日たち(入社日, 月を足す(基準, 13), 揃えた日, 表, 初回は法の日)
    次 = [x for x in 次 if x[0] > 基準]
    if 次:
        付与日, 段, 法の日 = 次[0]
        勤続 = (法の日.year - 入社日.year) * 12 + 法の日.month - 入社日.month
        try:
            次の表 = 法の表(付与日, 置き場)  # 次の付与日に効く行。まだ無ければ次の付与日数は空（前の行で代えない）
        except 引く口.欠け:
            次の表 = None
        法の数, 区分 = 法の日数(勤続, p.get("時間.週の所定日数"), p.get("時間.週の所定"), 次の表) if 次の表 else (None, "")
        数 = 付与日数(段, 法の数, 区分, 会社の値)[0] if 法の数 is not None else None
        次の法の数 = 数
        if 付与の承知:
            数 = Decimal(0)
        行["次の付与日"], 行["次の付与日数"] = 付与日.isoformat(), (_数(数) if 数 is not None else "")
    else:
        行["次の付与日"], 行["次の付与日数"] = "", ""
        次の法の数 = None
    行["状態"] = "仮" if 仮 else "確定"
    if 付与の承知:
        行["知らせ"] = _付与しない知らせ(p, 付与の承知, 今, 行, 次の法の数)
    return 行, 問い


def _付与しない知らせ(p: dict, 問い: str, 今: dict | None, 行: dict, 次の法の数) -> str:
    """承知した食い違い 有給.付与 の知らせ（線・人・問いの番号・法なら何日）。法の日数は出勤率 8 割を満たす時の物。"""
    法 = []
    if 今:
        法.append(f"{今['付与日']} に {_数(今['法の数'])} 日")
    if 行.get("次の付与日") and 次の法の数 is not None:
        法.append(f"次の {行['次の付与日']} に {_数(次の法の数)} 日")
    return (f"承知した食い違い: {付与の線}（{問い}）＝NO {p['NO']} {p.get('氏名', '')} に有給を付与しない（会社の今のまま・付与 0 で確定）。"
            + (f"法の線なら {'、'.join(法)}（出勤率 8 割を満たす時）" if 法 else "法の線でもまだ付与日が来ていない"))


def _数(x) -> str:
    x = Decimal(x)
    return str(x.quantize(Decimal(1))) if x == x.to_integral() else str(x.normalize())


def 管理表(入力: dict, 置き場=None) -> dict:
    """入力（README の形）→ {"見出し", "行", "問い", "止めた人", "知らせ"}。役員・委託の人は出さない。退職日が基準の日より前の人も出さない。
    `確定した勤怠`（今年と前の年の年の台帳の行）が有れば取得と出勤率をそこから数え、数えられない人は 行 に入れず 止めた人 に理由を返す。
    置き場は法の表の置き場（試験だけ渡す・既定は repo の 法の表/）。"""
    基準 = 日(入力["基準の日"])
    表 = 法の表(基準, 置き場)
    台帳 = None
    if "確定した勤怠" in 入力:
        混ざる = [k for k in ("勤怠", "勤怠の始め") if k in 入力]
        if 混ざる:
            raise ValueError(f"確定した勤怠を渡す時は {'・'.join(混ざる)} を渡さない（勤怠は年の台帳の確定した勤怠だけを読む）")
        台帳 = 台帳を読む(入力["確定した勤怠"])
    行たち, 問いたち, 止めた, 知らせ = [], [], [], []
    for p in 入力.get("人", []):
        if _有給の外か(p.get("人.区分")):
            continue
        退職 = 日(p.get("退職日"))
        if 退職 and 退職 < 基準:
            continue
        try:
            行, 問い = 一人(p, 入力, 表, 置き場, 台帳)
        except 止める as e:
            止めた.append({"会社": 入力["会社"], "支給月": 入力["支給月"], "NO": p.get("NO", ""), "氏名": p.get("氏名", ""), "理由": str(e)})
            continue
        行たち.append({k: 行.get(k, "") for k in 見出し()})
        問いたち += 問い
        if 行.get("知らせ"):
            知らせ.append(行["知らせ"])
    return {"見出し": 見出し(), "行": 行たち, "問い": 問いたち, "止めた人": 止めた, "知らせ": 知らせ}


