def _月(s, どこ: str) -> str:
    """支給月の字（`YYYY.MM支給`・`YYYY-MM` など）→ `YYYY-MM`（比べるためだけ・正本 芯/支給月の字.py）。
    読めない字は止める（黙ってその月の取得から外さない）。"""
    x = 支給月の字.そろえる(s, "中")
    if x is None:
        raise ValueError(f"{どこ}の支給月「{'' if s is None else str(s).strip()}」が読めない（YYYY.MM支給 か YYYY-MM）")
    return x


def 台帳を読む(行たち) -> dict:
    """確定した勤怠の行（列名→値の dict の並び。今年と前の年の台帳を合わせた物）→ {NO: {日付: 行}}。
    要る列が無い行・読めない日付・会社が幾つも混ざる束は ValueError（殻の渡し方の誤り）。同じ人の同じ日が 2 行なら その人を止める印を置く。"""
    会社たち, out, 重なり = set(), {}, {}
    for i, r in enumerate(行たち):
        欠け = [c for c in 台帳の要る列 if str(r.get(c) or "").strip() == ""]
        if 欠け:
            raise ValueError(f"確定した勤怠の {i + 1} 行目に {'・'.join(欠け)} が無い")
        try:
            d = dt.date.fromisoformat(str(r["日付"]).strip()[:10])
        except ValueError:
            raise ValueError(f"確定した勤怠の {i + 1} 行目の日付「{r['日付']}」を読めない（YYYY-MM-DD）") from None
        会社たち.add(str(r["会社"]).strip())
        NO = str(r["NO"]).strip()
        日たち = out.setdefault(NO, {})
        if d in 日たち:
            重なり.setdefault(NO, []).append(d)
        日たち[d] = r
    if len(会社たち) > 1:
        raise ValueError(f"確定した勤怠に会社が幾つも混ざっている（{'・'.join(sorted(会社たち))}）。1 社の行だけ渡す")
    return {"日": out, "重なり": 重なり}


def _日の出勤(r: dict) -> str:
    """1 日 → 出勤／欠勤／除く／分かれる（会社の決まりで変わる）。知らない値は止める。"""
    種 = str(r.get("日の種類") or "").strip()
    休 = str(r.get("休暇の種類") or "").strip()
    if 種 == "勤務":
        return "出勤"
    if 種 in ("休日", "休日勤務"):
        return "除く"
    if 種 == "欠勤":
        return "欠勤"
    if 種 == "休暇":
        if 休 in 出勤とみなす休暇:
            return "出勤"
        if 休 in 決まりで分かれる休暇:
            return "分かれる"
    if 種 == "休職・休業":
        if 休 in 出勤とみなす休業:
            return "出勤"
        if 休 in 除く休業:
            return "除く"
        if 休 in 決まりで分かれる休業:
            return "分かれる"
    raise 止める(f"{r.get('日付')} の日の種類「{種}」・休暇の種類「{休}」を出勤率に数えられない")


def 出勤率は足りるか(日たち: dict, 始め: dt.date, 終わり: dt.date, 短い: bool) -> bool:
    """[始め, 終わり] の確定した勤怠で 出勤 ÷ 全労働日 が 8 割以上か。会社の決まりで分かれる日を 欠勤／出勤 の両方で数え、
    答えが割れる時・前倒しで短くなった期間（短い＝真。短くなった分は出勤とみなす＝平 6.1.4 基発 1 号）で 8 割を割る時・全労働日が 0 の時は止める。"""
    出, 欠, 分, 訳 = 0, 0, 0, set()
    d = 始め
    while d <= 終わり:
        r = 日たち[d]
        k = _日の出勤(r)
        if k == "出勤":
            出 += 1
        elif k == "欠勤":
            欠 += 1
        elif k == "分かれる":
            分 += 1
            訳.add(str(r.get("休暇の種類") or ""))
        d += dt.timedelta(days=1)
    全 = 出 + 欠 + 分
    if 全 == 0:
        raise 止める(f"出勤率の期間 {始め}〜{終わり} に全労働日が無い（8 割を数えられない）")
    低い, 高い = 出 * 10 >= 全 * 8, (出 + 分) * 10 >= 全 * 8
    if 低い != 高い:
        raise 止める(f"出勤率の期間 {始め}〜{終わり} の {'・'.join(sorted(訳))} の日を出勤とみなすかで 8 割の境が変わる（会社の決まりが要る）")
    if not 低い and 短い:
        raise 止める(f"出勤率の期間 {始め}〜{終わり} は前倒しで短く、短くなった分を出勤とみなす数え方を表せない（8 割を割る）")
    return 低い


def _揃っているか(日たち: dict, 始め: dt.date, 終わり: dt.date, 何のため: str):
    """[始め, 終わり] の全部の日に確定した勤怠の行があるか（表 A は期間の全部の日に 1 行）。無ければ止める（黙って 0 にしない）。"""
    無い = []
    d = 始め
    while d <= 終わり:
        if d not in 日たち:
            無い.append(d)
        d += dt.timedelta(days=1)
    if 無い:
        raise 止める(f"{何のため}に {始め}〜{終わり} の確定した勤怠が要るが、{無い[0]} から {len(無い)} 日の行が無い"
                  f"（その年の台帳か前の年の台帳を渡す）")


